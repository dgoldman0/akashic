    _SLRGM-BODY-A @ _SLRGM-BODY-U @ _SLRGM-BUILDER @ RMSGB-BODY!
        RMSGB-S-OK <> IF 0 EXIT THEN
    _SLRGM-BUILDER @ RMSGB-SEAL RMSGB-S-OK <> IF 0 EXIT THEN
    _SLRGM-BUILDER @ RMSGB-MEASURE
    _SLRGM-RS ! _SLRGM-N !
    _SLRGM-RS @ RMSGB-S-OK <> IF 0 EXIT THEN
