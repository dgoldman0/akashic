: _SLRGP-FINALIZE-PROFILE  ( -- provider-status )
    _SLRGF-ROUTER _SLRGLC-LEASE @ _SLRGP-FLAG? IF
        _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGS.ROUTER @
            RROUTER-FINI RROUTER-S-OK <> IF SRBPROV-S-FAULT EXIT THEN
        _SLRGF-ROUTER _SLRGLC-LEASE @ _SLRGP-FLAG-
    THEN
    _SLRGF-PROFILE _SLRGLC-LEASE @ _SLRGP-FLAG? IF
        _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGS.PROFILE @
            STREAMS-RABBIT-LIBRARY-PROFILE-FINI DUP
        STREAMS-RABBIT-LIBRARY-PROFILE-S-OK <> IF
            STREAMS-RABBIT-LIBRARY-PROFILE-S-BUSY = IF
                SRBPROV-S-PENDING ELSE SRBPROV-S-FAULT THEN EXIT
        THEN DROP
        _SLRGF-PROFILE _SLRGLC-LEASE @ _SLRGP-FLAG-
    THEN
    SRBPROV-S-NONE ;

: _SLRGP-FINALIZE-CB  ( lease context -- status detail )
    2DUP _SLRGP-LEASE-MATCH? 0= IF
        2DROP SRBPROV-S-INVALID SRBPROV-D-BURROW-FINALIZE EXIT
    THEN
    _SLRGLC-CONTEXT ! _SLRGLC-LEASE !
    _SLRGLC-LEASE @ SLRGL.PHASE @ DUP SLRGP-PHASE-FINALIZED = IF
        DROP SRBPROV-S-NONE SRBPROV-D-NONE EXIT
    THEN
    DUP SLRGP-PHASE-CANCELLED =
    SWAP SLRGP-PHASE-FINALIZING = OR 0= IF
        SRBPROV-S-STATE SRBPROV-D-BURROW-FINALIZE EXIT
    THEN
    SLRGP-PHASE-FINALIZING _SLRGLC-LEASE @ SLRGL.PHASE !
    _SLRGP-FINALIZE-SERVER DUP IF
        DUP SRBPROV-S-PENDING = IF DROP
            SRBPROV-S-PENDING SRBPROV-D-BURROW-FINALIZE
        ELSE DROP SRBPROV-S-FAULT SRBPROV-D-BURROW-FINALIZE THEN EXIT
    THEN DROP
    _SLRGP-FINALIZE-CLIENT DUP IF
        DUP SRBPROV-S-PENDING = IF DROP
            SRBPROV-S-PENDING SRBPROV-D-BURROW-FINALIZE
        ELSE DROP SRBPROV-S-FAULT SRBPROV-D-BURROW-FINALIZE THEN EXIT
    THEN DROP
    _SLRGP-FINALIZE-PROFILE DUP IF
        DUP SRBPROV-S-PENDING = IF DROP
            SRBPROV-S-PENDING SRBPROV-D-BURROW-FINALIZE
        ELSE DROP SRBPROV-S-FAULT SRBPROV-D-BURROW-FINALIZE THEN EXIT
    THEN DROP
    _SLRGP-FINALIZE-TRANSPORT ?DUP IF
        DROP SRBPROV-S-FAULT SRBPROV-D-BURROW-FINALIZE EXIT
    THEN
    _SLRGLC-LEASE @ SLRGL.FLAGS @ IF
        SRBPROV-S-FAULT SRBPROV-D-INVARIANT EXIT
    THEN
    _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGP-GRAPH-BASELINE? 0= IF
        SRBPROV-S-FAULT SRBPROV-D-INVARIANT EXIT
    THEN
    SLRGP-PHASE-FINALIZED _SLRGLC-LEASE @ SLRGL.PHASE !
    SRBPROV-S-NONE SRBPROV-D-NONE ;

: _SLRGP-RELEASE-CB  ( lease context -- status detail )
    2DUP _SLRGP-LEASE-MATCH? 0= IF
        2DROP SRBPROV-S-INVALID SRBPROV-D-PROVIDER-RELEASE EXIT
    THEN
    _SLRGLC-CONTEXT ! _SLRGLC-LEASE !
    _SLRGLC-LEASE @ SLRGL.PHASE @ SLRGP-PHASE-FINALIZED <> IF
        SRBPROV-S-STATE SRBPROV-D-PROVIDER-RELEASE EXIT
    THEN
    _SLRGLC-LEASE @ SLRGL.FLAGS @ IF
        SRBPROV-S-FAULT SRBPROV-D-INVARIANT EXIT
    THEN
    _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGP-GRAPH-BASELINE? 0= IF
        SRBPROV-S-FAULT SRBPROV-D-INVARIANT EXIT
    THEN
    0 _SLRGLC-LEASE @ SLRGL.ACTIVE !
    SLRGP-PHASE-EMPTY _SLRGLC-LEASE @ SLRGL.PHASE !
    0 _SLRGLC-LEASE @ SLRGL.GRAPH-COUNT !
    0 _SLRGLC-LEASE @ SLRGL.SERVICE-COUNT !
    0 _SLRGLC-LEASE @ SLRGL.CLIENT-CONTROL-WIRE !
    0 _SLRGLC-LEASE @ SLRGL.CLIENT-DATA-WIRE !
    0 _SLRGLC-LEASE @ SLRGL.SERVER-CONTROL-WIRE !
    0 _SLRGLC-LEASE @ SLRGL.SERVER-DATA-WIRE !
    0 _SLRGLC-LEASE @ SLRGL.WIRE-BYTES !
    0 _SLRGLC-LEASE @ SLRGL.RESULT-BYTES !
    0 _SLRGLC-LEASE @ SLRGL.LAST-ITEM !
    0 _SLRGLC-LEASE @ SLRGL.LAST-SUBJECT !
    0 _SLRGLC-LEASE @ SLRGL.LAST-GENERATION !
    STREAMS-RABBIT-CONNECTOR-S-OK _SLRGLC-LEASE @ SLRGL.LAST-STATUS !
    SRBPROV-S-NONE SRBPROV-D-NONE ;

