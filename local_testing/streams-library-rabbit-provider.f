: _SLRGP-OPEN-CB  ( lease context -- status detail )
    2DUP _SLRGP-LEASE-MATCH? 0= IF
        2DROP SRBPROV-S-INVALID SRBPROV-D-BURROW-OPEN EXIT
    THEN
    _SLRGLC-CONTEXT ! _SLRGLC-LEASE !
    _SLRGLC-LEASE @ SLRGL.PHASE @ SLRGP-PHASE-READY <> IF
        SRBPROV-S-STATE SRBPROV-D-BURROW-OPEN EXIT
    THEN
    _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGS.BURROW @
        STREAMS-RABBIT-BURROW-OPEN
        STREAMS-RABBIT-BURROW-S-OK <> IF
        SRBPROV-S-FAULT SRBPROV-D-BURROW-OPEN EXIT
    THEN
    _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGS.CLIENT-BUILDER @
        DUP RMSGB-RESET RMSGB-S-OK <> IF
        DROP SRBPROV-S-FAULT SRBPROV-D-TRANSPORT EXIT
    THEN
    RABBIT-CAPS-LANES-ASYNC OVER RMSGB-BEGIN-HELLO RMSGB-S-OK <> IF
        DROP SRBPROV-S-FAULT SRBPROV-D-TRANSPORT EXIT
    THEN
    DUP RMSGB-SEAL RMSGB-S-OK <> IF
        DROP SRBPROV-S-FAULT SRBPROV-D-TRANSPORT EXIT
    THEN
    _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGS.CONNECTOR @
        STREAMS-RABBIT-CONNECTOR-HELLO
    _SLRGLC-STATUS !
    _SLRGLC-STATUS @ STREAMS-RABBIT-CONNECTOR-S-OK <> IF
        DROP SRBPROV-S-FAULT SRBPROV-D-TRANSPORT EXIT
    THEN
    0= IF SRBPROV-S-FAULT SRBPROV-D-TRANSPORT EXIT THEN
    _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGS.CLIENT-BUILDER @
        RMSGB-RESET RMSGB-S-OK <> IF
        SRBPROV-S-FAULT SRBPROV-D-TRANSPORT EXIT
    THEN
    \ TX precedes RX in one connection pump.  Exactly three physical
    \ memory-duplex rounds send HELLO, receive/queue HELLO-OK, then send and
    \ commit HELLO-OK.  This is protocol geometry, not a retry budget.
    _SLRGLC-CONTEXT @ _SLRGP-DUPLEX-ROUND 0= IF
        SRBPROV-S-FAULT SRBPROV-D-BURROW-OPEN EXIT
    THEN
    _SLRGLC-CONTEXT @ _SLRGP-DUPLEX-ROUND 0= IF
        SRBPROV-S-FAULT SRBPROV-D-BURROW-OPEN EXIT
    THEN
    _SLRGLC-CONTEXT @ _SLRGP-DUPLEX-ROUND 0= IF
        SRBPROV-S-FAULT SRBPROV-D-BURROW-OPEN EXIT
    THEN
    _SLRGLC-CONTEXT @ SLRGP.STORAGE @ DUP
        SLRGS.SESSION-CLIENT @ RABBIT-SESSION-ESTABLISHED? 0= IF
        DROP SRBPROV-S-FAULT SRBPROV-D-BURROW-OPEN EXIT
    THEN
    SLRGS.SESSION-SERVER @ RABBIT-SESSION-ESTABLISHED? 0= IF
        SRBPROV-S-FAULT SRBPROV-D-BURROW-OPEN EXIT
    THEN
    1 _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGS.CONNECTOR @
        STREAMS-RABBIT-CONNECTOR-LANE-ENSURE
        STREAMS-RABBIT-CONNECTOR-S-OK <> IF
        SRBPROV-S-FAULT SRBPROV-D-TRANSPORT EXIT
    THEN
    RSUB-ITEM-NONE _SLRGLC-LEASE @ SLRGL.LAST-ITEM !
    0 _SLRGLC-LEASE @ SLRGL.LAST-SUBJECT !
    0 _SLRGLC-LEASE @ SLRGL.LAST-GENERATION !
    STREAMS-RABBIT-CONNECTOR-S-OK
        _SLRGLC-LEASE @ SLRGL.LAST-STATUS !
    SLRGP-PHASE-OPEN _SLRGLC-LEASE @ SLRGL.PHASE !
    SRBPROV-S-NONE SRBPROV-D-NONE ;

: _SLRGP-SERVICE-CB  ( lease context -- status detail )
    2DUP _SLRGP-LEASE-MATCH? 0= IF
        2DROP SRBPROV-S-INVALID SRBPROV-D-BURROW-PUMP EXIT
    THEN
    _SLRGLC-CONTEXT ! _SLRGLC-LEASE !
    _SLRGLC-LEASE @ SLRGL.PHASE @ SLRGP-PHASE-OPEN <> IF
        SRBPROV-S-STATE SRBPROV-D-BURROW-PUMP EXIT
    THEN
    _SLRGLC-CONTEXT @ _SLRGP-BURROW-STEP
        _SLRGP-BURROW-PROGRESS? 0= IF
        SRBPROV-S-FAULT SRBPROV-D-BURROW-PUMP EXIT
    THEN
    _SLRGLC-CONTEXT @ _SLRGP-CLIENT-STEP
        _SLRGP-CLIENT-PROGRESS? 0= IF
        SRBPROV-S-FAULT SRBPROV-D-BURROW-PUMP EXIT
    THEN
    SRBPROV-S-NONE SRBPROV-D-NONE ;

