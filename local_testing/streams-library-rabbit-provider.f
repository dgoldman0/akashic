: _SLRGP-CANCEL-CB  ( lease context -- status detail )
    2DUP _SLRGP-LEASE-MATCH? 0= IF
        2DROP SRBPROV-S-INVALID SRBPROV-D-BURROW-FINALIZE EXIT
    THEN
    _SLRGLC-CONTEXT ! _SLRGLC-LEASE !
    _SLRGLC-LEASE @ SLRGL.PHASE @ DUP SLRGP-PHASE-CANCELLED = IF
        DROP SRBPROV-S-NONE SRBPROV-D-NONE EXIT
    THEN
    DUP SLRGP-PHASE-ACQUIRING = OVER SLRGP-PHASE-READY = OR
    OVER SLRGP-PHASE-OPEN = OR
    SWAP SLRGP-PHASE-CANCELLING = OR 0= IF
        SRBPROV-S-STATE SRBPROV-D-BURROW-FINALIZE EXIT
    THEN
    SLRGP-PHASE-CANCELLING _SLRGLC-LEASE @ SLRGL.PHASE !
    0 _SLRGLC-PENDING ! 0 _SLRGLC-FAILED !
    _SLRGP-CANCEL-SERVER _SLRGP-CANCEL-CLIENT _SLRGP-CANCEL-PORTS
    _SLRGLC-FAILED @ IF
        SRBPROV-S-FAULT SRBPROV-D-BURROW-FINALIZE EXIT
    THEN
    _SLRGLC-PENDING @ IF
        SRBPROV-S-PENDING SRBPROV-D-BURROW-FINALIZE EXIT
    THEN
    SLRGP-PHASE-CANCELLED _SLRGLC-LEASE @ SLRGL.PHASE !
    SRBPROV-S-NONE SRBPROV-D-NONE ;

\ Each successful lower FINI clears its ownership bit immediately.  A later
\ pending owner therefore resumes at the next live descriptor rather than
\ invoking FINI twice on storage the lower owner already zeroed.
: _SLRGP-FINALIZE-SERVER  ( -- provider-status )
    _SLRGF-ADOPTED _SLRGLC-LEASE @ _SLRGP-FLAG? IF
        _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGS.BURROW @
            STREAMS-RABBIT-BURROW-FINI DUP
        STREAMS-RABBIT-BURROW-S-OK <> IF
            DUP STREAMS-RABBIT-BURROW-S-PENDING =
            OVER STREAMS-RABBIT-BURROW-S-CLEANUP = OR
            SWAP STREAMS-RABBIT-BURROW-S-BUSY = OR IF
                SRBPROV-S-PENDING ELSE SRBPROV-S-FAULT THEN EXIT
        THEN DROP
        _SLRGF-ADOPTED _SLRGLC-LEASE @ _SLRGP-FLAG-
        _SLRGF-SERVER-SUBSCRIPTIONS _SLRGLC-LEASE @ _SLRGP-FLAG-
        _SLRGF-SERVER _SLRGLC-LEASE @ _SLRGP-FLAG-
        _SLRGF-CONNECTION-SERVER _SLRGLC-LEASE @ _SLRGP-FLAG-
        _SLRGF-BUILDER _SLRGLC-LEASE @ _SLRGP-FLAG-
        _SLRGF-BURROW _SLRGLC-LEASE @ _SLRGP-FLAG-
        SRBPROV-S-NONE EXIT
    THEN
    _SLRGF-SERVER-SUBSCRIPTIONS _SLRGLC-LEASE @ _SLRGP-FLAG? IF
        _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGS.SERVER-SUBSCRIPTIONS @
            RABBIT-SERVER-SUBSCRIPTIONS-FINI DUP RSERVER-S-OK <> IF
            RSERVER-S-PENDING = IF SRBPROV-S-PENDING
            ELSE SRBPROV-S-FAULT THEN EXIT
        THEN DROP
        _SLRGF-SERVER-SUBSCRIPTIONS _SLRGLC-LEASE @ _SLRGP-FLAG-
        _SLRGF-SERVER _SLRGLC-LEASE @ _SLRGP-FLAG-
        _SLRGF-CONNECTION-SERVER _SLRGLC-LEASE @ _SLRGP-FLAG-
        _SLRGF-BUILDER _SLRGLC-LEASE @ _SLRGP-FLAG-
    THEN
    _SLRGF-SERVER _SLRGLC-LEASE @ _SLRGP-FLAG? IF
        _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGS.SERVER @
            RABBIT-SERVER-FINI DUP RSERVER-S-OK <> IF
            RSERVER-S-PENDING = IF SRBPROV-S-PENDING
            ELSE SRBPROV-S-FAULT THEN EXIT
        THEN DROP
        _SLRGF-SERVER _SLRGLC-LEASE @ _SLRGP-FLAG-
        _SLRGF-CONNECTION-SERVER _SLRGLC-LEASE @ _SLRGP-FLAG-
        _SLRGF-BUILDER _SLRGLC-LEASE @ _SLRGP-FLAG-
