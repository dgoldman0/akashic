    _SLRGM-BODY-A @ _SLRGM-BODY-U @ [CHAR] a FILL
    _SLRGM-KIND @ LIBRARY-READ-V1-RABBIT-SELECTOR$ RABBIT-LANE-MAX
        SLRGP-TXN$ _SLRGM-BUILDER @
