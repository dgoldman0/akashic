            ELSE SRBPROV-S-FAULT THEN EXIT
        THEN DROP
        _SLRGF-CONNECTION-SERVER _SLRGLC-LEASE @ _SLRGP-FLAG-
    THEN
    _SLRGF-BUILDER _SLRGLC-LEASE @ _SLRGP-FLAG? IF
        _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGS.SERVER-BUILDER @
            RMSGB-FINI RMSGB-S-OK <> IF SRBPROV-S-FAULT EXIT THEN
        _SLRGF-BUILDER _SLRGLC-LEASE @ _SLRGP-FLAG-
    THEN
    _SLRGF-BURROW _SLRGLC-LEASE @ _SLRGP-FLAG? IF
        _SLRGLC-CONTEXT @ SLRGP.STORAGE @ SLRGS.BURROW @
            STREAMS-RABBIT-BURROW-FINI DUP
        STREAMS-RABBIT-BURROW-S-OK <> IF
            DUP STREAMS-RABBIT-BURROW-S-PENDING =
            OVER STREAMS-RABBIT-BURROW-S-CLEANUP = OR
            SWAP STREAMS-RABBIT-BURROW-S-BUSY = OR IF
                SRBPROV-S-PENDING ELSE SRBPROV-S-FAULT THEN EXIT
        THEN DROP
        _SLRGF-BURROW _SLRGLC-LEASE @ _SLRGP-FLAG-
    THEN
    SRBPROV-S-NONE ;

