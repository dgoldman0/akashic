\ =====================================================================
\ streams-library-rabbit-provider.f - deterministic Library Rabbit graph
\ =====================================================================
\ This qualification-only provider owns one retained graph lease at a time.
\ The graph is a real memory-duplex Rabbit client/server pair: the server is
\ hosted by one Streams Burrow row and the independent client is published
\ through a zero-capacity subscription owner and Streams Rabbit connector.
\
\ Fixed descriptor records and every variable-sized arena remain explicit,
\ caller-owned storage.  The local fixture cardinality of one retained lease
\ is not a hidden peer or product capacity.  The Burrow row capacity, session
\ arrays, operation table, queues, and byte backing spans are all supplied by
\ the composition and checked before the first lower owner is constructed.
\
\ The finalized production Library profile is intentionally required by the
\ graph-construction section below rather than reproduced here.  In
\ particular, this provider does not import Library service, controller, or
\ VFS internals and does not synthesize capability authority.
\ =====================================================================

