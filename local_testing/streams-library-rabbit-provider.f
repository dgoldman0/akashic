: _SLRGPI-INSTANCE?  ( instance -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP COMP-INST MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP CINST.DESC @ COMP-DESC-VALID? 0= IF DROP 0 EXIT THEN
    DUP CINST.ID @ 0> 0= IF DROP 0 EXIT THEN
    CINST.GENERATION @ 0> ;

: _SLRGPI-PREFLIGHT  ( -- flag )
    _SLRGPI-CONTEXT @ DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP SLRGP-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP SLRGP-SIZE _SLRGP-ZERO? 0= IF DROP 0 EXIT THEN
    DROP
    _SLRGPI-STORAGE @ DUP SLRGP-STORAGE-BOUND? 0= IF DROP 0 EXIT THEN
    DUP SLRGS.CONTEXT @ IF DROP 0 EXIT THEN
    DUP SLRGP-GRAPH-BASELINE? 0= IF DROP 0 EXIT THEN
    DUP SLRGP-STORAGE-SIZE _SLRGPI-CONTEXT @ SLRGP-SIZE
        MSPAN-OVERLAP? IF DROP 0 EXIT THEN
    DUP SLRGS.SLAB SLRGP-BINDING@
        _SLRGPI-CONTEXT @ SLRGP-SIZE MSPAN-OVERLAP? IF
        DROP 0 EXIT
    THEN
    DROP
    _SLRGPI-CALLER @ _SLRGPI-INSTANCE? 0= IF 0 EXIT THEN
    _SLRGPI-TARGET @ _SLRGPI-INSTANCE? 0= IF 0 EXIT THEN
    _SLRGPI-CONTEXT @ SLRGP-SIZE _SLRGPI-CALLER @ COMP-INST
        MSPAN-OVERLAP? IF 0 EXIT THEN
    _SLRGPI-CONTEXT @ SLRGP-SIZE _SLRGPI-TARGET @ COMP-INST
        MSPAN-OVERLAP? IF 0 EXIT THEN
    _SLRGPI-STORAGE @ SLRGP-STORAGE-SIZE _SLRGPI-CALLER @ COMP-INST
        MSPAN-OVERLAP? IF 0 EXIT THEN
    _SLRGPI-STORAGE @ SLRGP-STORAGE-SIZE _SLRGPI-TARGET @ COMP-INST
        MSPAN-OVERLAP? IF 0 EXIT THEN
    _SLRGPI-STORAGE @ SLRGS.SLAB SLRGP-BINDING@
        _SLRGPI-CALLER @ COMP-INST MSPAN-OVERLAP? IF 0 EXIT THEN
    _SLRGPI-STORAGE @ SLRGS.SLAB SLRGP-BINDING@
        _SLRGPI-TARGET @ COMP-INST MSPAN-OVERLAP? IF 0 EXIT THEN
    _SLRGPI-BUS @ 0<>
    _SLRGPI-QUERY-CAP @ 0<> AND
    _SLRGPI-READ-CAP @ 0<> AND
    _SLRGPI-FACET-ID @ RID-PRESENT? AND
    _SLRGPI-PRACTICE-ID @ RID-PRESENT? AND
    _SLRGPI-EPOCH @ 0> AND
    _SLRGPI-CONTEXT-ID @ 0> AND
    _SLRGPI-CONTEXT-GEN @ 0> AND
    _SLRGPI-AUTH-XT @ 0<> AND
    _SLRGPI-ROUTE-TOKEN @ 0<> AND
    _SLRGPI-PEER-TOKEN @ 0<> AND
    _SLRGPI-PEER-EVIDENCE @ 0<> AND ;

