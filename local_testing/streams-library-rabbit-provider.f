    >R _SLRGM-BUILDER @ RMSGB-MEASURE
    _SLRGM-RS ! _SLRGM-N !
    _SLRGM-RS @ RMSGB-S-OK <> IF R> DROP 0 EXIT THEN
    _SLRGM-N @ 0> 0= IF R> DROP 0 EXIT THEN
    _SLRGM-N @ R> ! -1 ;

: _SLRGM-PREFLIGHT  ( -- flag )
    _SLRGM-STORAGE @ SLRGS.CLIENT-OPS SLRGP-BINDING@
    DUP 0> 0= IF 2DROP 0 EXIT THEN
    NIP DUP _SLRGM-OPS ! DROP
    _SLRGM-STORAGE @ SLRGS.CLIENT-TXNS SLRGP-BINDING@
    _SLRGM-TXN-BYTES ! _SLRGM-TXN-A !
    _SLRGM-TXN-BYTES @ _SLRGM-OPS @ MOD IF 0 EXIT THEN
    _SLRGM-TXN-BYTES @ _SLRGM-OPS @ /
        DUP _SLRGM-TXN-U ! DROP
    _SLRGM-TXN-U @ SLRGP-TXN-SLOT-BYTES-MIN U< IF 0 EXIT THEN
    _SLRGM-STORAGE @ SLRGS.CLIENT-RESULTS SLRGB.U @
        SLRGP-REQUEST-BODY-BYTES-MAX U< IF 0 EXIT THEN
    _SLRGM-STORAGE @ SLRGS.CLIENT-RESULTS SLRGB.U @
        SLRGP-RESULT-SLOT-BYTES-MIN U< IF 0 EXIT THEN
    _SLRGM-STORAGE @ SLRGS.SERVER-BUILDER-HEADERS @
        SLRGP-BUILDER-HEADER-CAPACITY-MIN U< IF 0 EXIT THEN
    _SLRGM-STORAGE @ SLRGS.SERVER-BUILDER-ARENA SLRGB.U @
        SLRGP-MEASURE-BUILDER-ARENA-BYTES-MIN U< IF 0 EXIT THEN
    -1 ;

