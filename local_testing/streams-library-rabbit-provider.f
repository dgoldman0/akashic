  ( epoch context-id context-gen auth-xt auth-context route-token )
  ( peer-token peer-evidence context -- status )
    _SLRGPI-CONTEXT ! _SLRGPI-PEER-EVIDENCE ! _SLRGPI-PEER-TOKEN !
    _SLRGPI-ROUTE-TOKEN ! _SLRGPI-AUTH-CONTEXT ! _SLRGPI-AUTH-XT !
    _SLRGPI-CONTEXT-GEN ! _SLRGPI-CONTEXT-ID ! _SLRGPI-EPOCH !
    _SLRGPI-PRACTICE-ID ! _SLRGPI-FACET-ID ! _SLRGPI-READ-CAP !
    _SLRGPI-QUERY-CAP ! _SLRGPI-BUS ! _SLRGPI-TARGET !
    _SLRGPI-CALLER ! _SLRGPI-STORAGE !
    _SLRGPI-PREFLIGHT 0= IF SRBPROV-S-INVALID EXIT THEN
    _SLRGPI-STORAGE @ _SLRGPI-CONTEXT @ SLRGP.STORAGE !
    _SLRGPI-CALLER @ _SLRGPI-CONTEXT @ SLRGP.CALLER !
    _SLRGPI-TARGET @ _SLRGPI-CONTEXT @ SLRGP.TARGET !
    _SLRGPI-CALLER @ CINST.ID @
        _SLRGPI-CONTEXT @ SLRGP.CALLER-ID !
    _SLRGPI-CALLER @ CINST.GENERATION @
        _SLRGPI-CONTEXT @ SLRGP.CALLER-GEN !
    _SLRGPI-TARGET @ CINST.ID @
        _SLRGPI-CONTEXT @ SLRGP.TARGET-ID !
    _SLRGPI-TARGET @ CINST.GENERATION @
        _SLRGPI-CONTEXT @ SLRGP.TARGET-GEN !
    _SLRGPI-BUS @ _SLRGPI-CONTEXT @ SLRGP.BUS !
    _SLRGPI-QUERY-CAP @ _SLRGPI-CONTEXT @ SLRGP.QUERY-CAP !
    _SLRGPI-READ-CAP @ _SLRGPI-CONTEXT @ SLRGP.READ-CAP !
    _SLRGPI-FACET-ID @ _SLRGPI-CONTEXT @ SLRGP.FACET-ID RID-COPY
    _SLRGPI-PRACTICE-ID @
        _SLRGPI-CONTEXT @ SLRGP.PRACTICE-ID RID-COPY
    _SLRGPI-EPOCH @ _SLRGPI-CONTEXT @ SLRGP.EPOCH !
    _SLRGPI-CONTEXT-ID @ _SLRGPI-CONTEXT @ SLRGP.CONTEXT-ID !
    _SLRGPI-CONTEXT-GEN @ _SLRGPI-CONTEXT @ SLRGP.CONTEXT-GEN !
    _SLRGPI-AUTH-XT @ _SLRGPI-CONTEXT @ SLRGP.AUTH-XT !
    _SLRGPI-AUTH-CONTEXT @ _SLRGPI-CONTEXT @ SLRGP.AUTH-CONTEXT !
    _SLRGPI-ROUTE-TOKEN @ _SLRGPI-CONTEXT @ SLRGP.ROUTE-TOKEN !
    _SLRGPI-PEER-TOKEN @ _SLRGPI-CONTEXT @ SLRGP.PEER-TOKEN !
    _SLRGPI-PEER-EVIDENCE @
        _SLRGPI-CONTEXT @ SLRGP.PEER-EVIDENCE !
    SLRGP-REQUEST-BODY-BYTES-MAX
        _SLRGPI-CONTEXT @ SLRGP.REQUEST-BODY-MAX !
    _SLRGPI-CONTEXT @ SLRGP-LEASE DUP SLRGP-LEASE-SIZE 0 FILL
    _SLRGP-LEASE-MAGIC OVER SLRGL.MAGIC !
    _SLRGPI-CONTEXT @ OVER SLRGL.CONTEXT !
    SLRGP-PHASE-EMPTY OVER SLRGL.PHASE !
    STREAMS-RABBIT-CONNECTOR-S-OK SWAP SLRGL.LAST-STATUS !
    _SLRGPI-CONTEXT @ _SLRGPI-STORAGE @ SLRGS.CONTEXT !
    _SLRGPI-PROVIDER! SRBPROV-S-NONE <> IF
        0 _SLRGPI-STORAGE @ SLRGS.CONTEXT !
        _SLRGPI-CONTEXT @ SLRGP-SIZE 0 FILL
        SRBPROV-S-INVALID EXIT
    THEN
    _SLRGP-MAGIC-VALUE _SLRGPI-CONTEXT @ SLRGP.MAGIC !
    _SLRGPI-CONTEXT @ DUP SLRGP.SELF !
    SLRGP-SIZE _SLRGPI-CONTEXT @ SLRGP.BYTES !
