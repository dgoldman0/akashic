        0 _SLRGPI-STORAGE @ SLRGS.CONTEXT !
        _SLRGPI-CONTEXT @ SLRGP-SIZE 0 FILL
        SRBPROV-S-FAULT EXIT
    THEN
    SRBPROV-S-NONE ;

: SLRGP-VALID?  ( context -- flag ) _SLRGP-CONTEXT-READY? ;

\ RELEASE invalidates the retained lease but deliberately leaves the graph
\ descriptor and its zero baseline inspectable.  The composition witnesses
\ SLRGP-GRAPH-BASELINE? first, then finalizes this context, then finalizes the
\ storage descriptor, and only then frees the caller's slab.
: SLRGP-FINI  ( context -- status )
    DUP _SLRGP-CONTEXT-READY? 0= IF DROP SRBPROV-S-INVALID EXIT THEN
    DUP SLRGP-LEASE SLRGL.ACTIVE @ IF DROP SRBPROV-S-STATE EXIT THEN
    DUP SLRGP.STORAGE @ SLRGP-GRAPH-BASELINE? 0= IF
        DROP SRBPROV-S-STATE EXIT
    THEN
    DUP SLRGP.STORAGE @ 0 SWAP SLRGS.CONTEXT !
    SLRGP-SIZE 0 FILL SRBPROV-S-NONE ;

: SLRGP-STORAGE-FINI  ( storage -- status )
    DUP SLRGP-STORAGE-BOUND? 0= IF DROP SRBPROV-S-INVALID EXIT THEN
    DUP SLRGS.CONTEXT @ IF DROP SRBPROV-S-STATE EXIT THEN
    DUP SLRGP-GRAPH-BASELINE? 0= IF DROP SRBPROV-S-STATE EXIT THEN
    DUP SLRGS.SLAB SLRGP-BINDING@ 0 FILL
    SLRGP-STORAGE-SIZE 0 FILL SRBPROV-S-NONE ;
