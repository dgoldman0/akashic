        SRBPROV-S-STATE EXIT
    THEN
    _SLRSL-NEED @ _SLRSL-CAP ! 0 _SLRSL-OFF !
    _SLRSL-BIND-ALL 0= IF
        _SLRSL-STORAGE @ SLRGP-STORAGE-INIT
        SRBPROV-S-FAULT EXIT
    THEN
    _SLRSL-OFF @ _SLRSL-NEED @ <> IF
        _SLRSL-STORAGE @ SLRGP-STORAGE-INIT
        SRBPROV-S-FAULT EXIT
    THEN
    _SLRSL-BASE @ _SLRSL-NEED @
        _SLRSL-STORAGE @ SLRGS.SLAB SLRGP-BINDING!
    _SLRSL-STORAGE @ SLRGP-STORAGE-BOUND? 0= IF
        _SLRSL-STORAGE @ SLRGP-STORAGE-INIT
        SRBPROV-S-FAULT EXIT
    THEN
    _SLRSL-STORAGE @ SLRGP-GRAPH-BASELINE? 0= IF
        _SLRSL-STORAGE @ SLRGP-STORAGE-INIT
        SRBPROV-S-FAULT EXIT
    THEN
    SRBPROV-S-NONE ;

