    _SLRGM-BUILDER @ RMSGB-SEAL RMSGB-S-OK <> IF 0 EXIT THEN
    _SLRGM-LEASE @ SLRGL.SERVER-CONTROL-WIRE _SLRGM-MEASURE ;

