    _PBCT-WORK SBOX-DIGEST-WORKSPACE-SIZE
        _PBCT-ZERO? _PBCT-ASSERT

    _PBCT-VIEW SBOX-PBIND-SOURCE@
        SBOX-PBIND-S-OK = >R
        _PBCT-BINDING-TOTAL = SWAP
        _PBCT-BINDING = AND R> AND _PBCT-ASSERT
    _PBCT-VIEW SBOX-PBIND-PRACTICE-RID@
        SBOX-PBIND-S-OK = SWAP
        _PBCT-BINDING _PBI-H-PRACTICE-RID + RID= AND
        _PBCT-ASSERT
    _PBCT-VIEW SBOX-PBIND-RECORD-COUNT@
        SBOX-PBIND-S-OK = SWAP 2 = AND _PBCT-ASSERT

    0 _PBCT-VIEW SBOX-PBIND-RECORD@
        DUP SBOX-PBIND-S-OK = _PBCT-ASSERT
    DROP _PBCT-RECORD !
    _PBCT-RECORD @ _PBCT-VIEW SBOX-PBIND-RECORD-ROLE@
        SBOX-PBIND-S-OK = >R
        S" primary" COMPARE 0= R> AND _PBCT-ASSERT
    _PBCT-RECORD @ _PBCT-VIEW SBOX-PBIND-RECORD-ENTRY@
        SBOX-PBIND-S-OK = >R
        SBOX-DECL-SIGNATURE-PURE-VALUE = >R
        S" alpha" COMPARE 0=
        R> AND R> AND _PBCT-ASSERT

    _PBCT-RECORD @ _PBCT-VIEW
        SBOX-PBIND-RECORD-DECLARATION-DIGEST@
        SBOX-PBIND-S-OK = >R
        _PBCT-DECL-DIGEST _PBIND-32= R> AND _PBCT-ASSERT
    _PBCT-RECORD @ _PBCT-VIEW
        SBOX-PBIND-RECORD-MODULE-REVISION@
        SBOX-PBIND-S-OK = SWAP 7 = AND _PBCT-ASSERT

    SBOX-BUDGET-LIMIT-INSTRUCTION-UNITS
        _PBCT-RECORD @ _PBCT-VIEW SBOX-PBIND-RECORD-BUDGET@
        SBOX-PBIND-S-OK = >R
        0<> >R 5000 = R> AND R> AND _PBCT-ASSERT
    SBOX-BUDGET-LIMIT-CALL-FRAMES
        _PBCT-RECORD @ _PBCT-VIEW SBOX-PBIND-RECORD-BUDGET@
        SBOX-PBIND-S-OK = >R
        0= >R 0= R> AND R> AND _PBCT-ASSERT

    S" summary" _PBCT-VIEW SBOX-PBIND-ROLE-FIND-EXACT
        SBOX-PBIND-S-OK = SWAP _PBCT-RECORD1 = AND _PBCT-ASSERT
    S" absent" _PBCT-VIEW SBOX-PBIND-ROLE-FIND-EXACT
        SBOX-PBIND-S-NOT-FOUND = SWAP 0= AND _PBCT-ASSERT
    S" Summary" _PBCT-VIEW SBOX-PBIND-ROLE-FIND-EXACT
        SBOX-PBIND-S-ROLE = SWAP 0= AND _PBCT-ASSERT

    _PBCT-VIEW _PBCT-VIEW-COPY SBOX-PBIND-VIEW-SIZE MOVE
    _PBCT-VIEW-COPY SBOX-PBIND-VIEW-VALID? 0= _PBCT-ASSERT
    _PBCT-STACK ;

