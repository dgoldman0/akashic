        DUP 20 = SWAP 23 <= AND NIP _PBCT-ASSERT
    SBOX-PBIND-HEADER-SIZE 128 = _PBCT-ASSERT
    SBOX-PBIND-RECORD-SIZE 544 = _PBCT-ASSERT
    SBOX-PBIND-VIEW-SIZE 112 = _PBCT-ASSERT
    SBOX-PBIND-BYTES-MAX 34944 = _PBCT-ASSERT

