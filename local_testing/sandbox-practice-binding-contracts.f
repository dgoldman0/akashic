: _PBCT-ASSERT  ( flag -- )
    1 _PBCT-CHECKS +!
    0= IF
        1 _PBCT-FAILS +!
        ." SBOX PBIND ASSERT " _PBCT-CHECKS @ . CR
    THEN ;

: _PBCT-STACK  ( -- )
    DEPTH DUP _PBCT-DEPTH @ <> IF
        ." SBOX PBIND STACK " _PBCT-DEPTH @ . ." -> " DUP . CR
        .S CR
    THEN
    _PBCT-DEPTH @ = _PBCT-ASSERT ;

: _PBCT-ZERO?  ( address length -- flag )
    BEGIN DUP 0> WHILE
        OVER C@ IF 2DROP 0 EXIT THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP -1 ;

: _PBCT-U16!  ( value address -- )
    >R
    DUP 0xFF AND R@ C!
    8 RSHIFT 0xFF AND R> 1+ C! ;

: _PBCT-U32!  ( value address -- )
    >R
    DUP 0xFFFF AND R@ _PBCT-U16!
    16 RSHIFT 0xFFFF AND R> 2 + _PBCT-U16! ;

: _PBCT-U64!  ( value address -- )
    >R
    DUP 0xFFFFFFFF AND R@ _PBCT-U32!
    32 RSHIFT R> 4 + _PBCT-U32! ;

: _PBCT-FILL32  ( byte address -- )
    SWAP SBOX-DIGEST-SIZE SWAP FILL ;

: _PBCT-ACCEPT  ( status -- )
    0<> IF 0 _PBCT-BUILD-OK ! THEN ;

