\ Focused contracts for the inert Practice sandbox role-binding boundary.
\ The harness must load sandbox-practice-binding.f first.
\
\ Static companion check:
\   rg -n '^PROVIDED akashic-rt-sbx-pbind$' akashic
\ must report exactly this production module.  The contract below also
\ asserts that the key is exactly 20 bytes and within the loader's 23-byte
\ comparison width.  No production word in the module compiles, resolves,
\ invokes, dispatches, installs, or updates a PHEAD.

