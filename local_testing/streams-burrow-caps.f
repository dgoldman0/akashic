    _SBC-MANAGER SRBMGR-FINI SRBPROV-S-NONE = _SBC-ASSERT
    _SBC-MANAGER SRBMGR-SIZE _SBC-ZERO? _SBC-ASSERT
    _SBC-REQUEST @ ?DUP IF CBR-FREE 0 _SBC-REQUEST ! THEN
    _SBC-BUS @ ?DUP IF CBUS-FREE 0 _SBC-BUS ! THEN
    _SBC-REGISTRY @ ?DUP IF CREG-FREE 0 _SBC-REGISTRY ! THEN
    _SBC-INSTANCE @ ?DUP IF CINST-FREE 0 _SBC-INSTANCE ! THEN
    0 0 STREAMS-BURROW-CAPABILITY-BIND
    _SBC-BOUND-FREE
