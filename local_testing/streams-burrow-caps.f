: _SBC-ASSERT  ( flag -- )
    1 _SBC-CHECKS +!
    0= IF
        1 _SBC-FAILS +!
        ." STREAMS BURROW CAPS ASSERT " _SBC-CHECKS @ . CR
    THEN ;

: _SBC-STACK  ( -- )
    DEPTH DUP _SBC-DEPTH @ <> IF
        ." STREAMS BURROW CAPS STACK " _SBC-DEPTH @ . ."  -> " DUP . CR
        .S CR
    THEN
    _SBC-DEPTH @ = _SBC-ASSERT ;

: _SBC-OK  ( status -- ) 0= _SBC-ASSERT ;

: _SBC-ALIGN8  ( address -- aligned-address ) 7 + -8 AND ;

: _SBC-ZERO?  ( address bytes -- flag )
    BEGIN DUP WHILE
        OVER C@ IF 2DROP 0 EXIT THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP -1 ;

: _SBC-ID!  ( byte rid -- )
    RID-SIZE ROT FILL ;

: _SBC-LOWER-HEX?  ( c -- flag )
    DUP [CHAR] 0 >= OVER [CHAR] 9 <= AND IF DROP -1 EXIT THEN
    DUP [CHAR] a >= SWAP [CHAR] f <= AND ;

: _SBC-H64?  ( value -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP CV-TYPE@ CV-T-STRING <> IF DROP 0 EXIT THEN
    DUP CV-LEN@ SHA3-256-HEX-LEN <> IF DROP 0 EXIT THEN
    CV-DATA@
    0
    BEGIN DUP SHA3-256-HEX-LEN < WHILE
        2DUP + C@ _SBC-LOWER-HEX? 0= IF 2DROP 0 EXIT THEN
        1+
    REPEAT
    2DROP -1 ;

