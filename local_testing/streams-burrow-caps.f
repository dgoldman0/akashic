        ." STREAMS BURROW CAPS PASS " _SBC-CHECKS @ .
    ELSE
        ." STREAMS BURROW CAPS FAIL " _SBC-FAILS @ .
        ."  / " _SBC-CHECKS @ .
    THEN CR ;

