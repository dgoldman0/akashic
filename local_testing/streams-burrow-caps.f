: _SBC-PHASE-LIFECYCLE-STATUS  ( -- )
    _SBC-BURROW 1 _SBC-MUTATE-ARGS
    _SBC-INV-START _SBC-INVOCATION!
    STREAMS-BURROW-CAP-START _SBC-CALL _SBC-EXPECT-FRESH
    S" starting" _SBC-CHECK-MUTATION-RESULT
    S" domain_revision" _SBC-RESULT-INT 2 = _SBC-ASSERT
    _SBC-START-RECEIPT _SBC-COPY-RECEIPT

    _SBC-BURROW 1 _SBC-MUTATE-ARGS
    _SBC-INV-START _SBC-INVOCATION!
    STREAMS-BURROW-CAP-START _SBC-CALL _SBC-EXPECT-NO-EFFECT
    _SBC-START-RECEIPT _SBC-RECEIPT= _SBC-ASSERT
    S" starting" _SBC-CHECK-MUTATION-RESULT

    \ A new invocation with the old domain revision remains a domain
    \ conflict; CBR stale-instance/revision statuses are not repurposed.
    _SBC-BURROW 1 _SBC-MUTATE-ARGS
    _SBC-INV-START-STALE _SBC-INVOCATION!
    STREAMS-BURROW-CAP-START _SBC-CALL
        CBUS-S-FAILED SRBPROV-S-CONFLICT _SBC-EXPECT-ERROR

    _SBC-TICK
    _SBC-DECL SRBMGR-DECL.STATE @ SRBMGR-STATE-STARTING = _SBC-ASSERT
    _SBC-TICK
    _SBC-DECL SRBMGR-DECL.STATE @ SRBMGR-STATE-RUNNING = _SBC-ASSERT
    _SBC-DECL SRBMGR-DECL.DOMAIN-REVISION @ 3 = _SBC-ASSERT

    _SBC-BURROW _SBC-STATUS-ARGS
    _SBC-INV-CREATE-BAD _SBC-INVOCATION!
    STREAMS-BURROW-CAP-STATUS _SBC-CALL DUP CBUS-S-OK = _SBC-ASSERT
    DROP
    _SBC-INSTANCE @ CINST.REVISION @
        _SBC-BEFORE-REVISION @ = _SBC-ASSERT
    _SBC-INVALIDATIONS @
        _SBC-BEFORE-INVALIDATIONS @ = _SBC-ASSERT
    S" running" S" state" 2SWAP _SBC-RESULT-STRING= _SBC-ASSERT
    S" domain_revision" _SBC-RESULT-INT 3 = _SBC-ASSERT
    S" operation_receipt" _SBC-RESULT-FIELD
        CV-TYPE@ CV-T-NULL = _SBC-ASSERT
    _SBC-REQUEST @ CBR.RESULT
        STREAMS-BURROW-CAP-STATUS CAP.OUT-SCHEMA @ CS-VALIDATE-DEEP
        0= _SBC-ASSERT

    \ A presentation invalidator is post-commit best effort.  Throwing here
    \ cannot turn a committed mutation into a reported failure/retry trap.
    ['] _SBC-RESOLVE ['] _SBC-INVALIDATE-THROW
        STREAMS-BURROW-CAPABILITY-BIND
    _SBC-BURROW 3 _SBC-MUTATE-ARGS
    _SBC-INV-STOP _SBC-INVOCATION!
    STREAMS-BURROW-CAP-STOP _SBC-CALL _SBC-EXPECT-FRESH
    S" stopping" _SBC-CHECK-MUTATION-RESULT
    S" domain_revision" _SBC-RESULT-INT 4 = _SBC-ASSERT
    _SBC-STOP-RECEIPT _SBC-COPY-RECEIPT
    _SBC-DECL SRBMGR-DECL.STATE @ SRBMGR-STATE-STOPPING = _SBC-ASSERT
    ['] _SBC-RESOLVE ['] _SBC-INVALIDATE
        STREAMS-BURROW-CAPABILITY-BIND

    \ Close/quiesce performs only one retained cleanup step per call.
    _SBC-QUIESCE _SBC-CLEAN @ 0= _SBC-ASSERT
    _SBC-QUIESCE
    _SBC-QUIESCE
    _SBC-CLEAN @ -1 = _SBC-ASSERT
    _SBC-MANAGER SRBMGR-RELEASABLE? _SBC-ASSERT
    _SBC-DECL SRBMGR-DECL.STATE @ SRBMGR-STATE-STOPPED = _SBC-ASSERT
    _SBC-DECL SRBMGR-DECL.DOMAIN-REVISION @ 5 = _SBC-ASSERT

    \ Replay stays typed/result-bearing after later lifecycle progress and
    \ carries the historical receipt with a truthful current declaration.
    _SBC-BURROW 3 _SBC-MUTATE-ARGS
    _SBC-INV-STOP _SBC-INVOCATION!
    STREAMS-BURROW-CAP-STOP _SBC-CALL _SBC-EXPECT-NO-EFFECT
    _SBC-STOP-RECEIPT _SBC-RECEIPT= _SBC-ASSERT
    S" stopped" _SBC-CHECK-MUTATION-RESULT
    S" domain_revision" _SBC-RESULT-INT 5 = _SBC-ASSERT

    _SBC-BURROW _SBC-STATUS-ARGS
    STREAMS-BURROW-CAP-STATUS _SBC-CALL CBUS-S-OK = _SBC-ASSERT
    S" stopped" S" state" 2SWAP _SBC-RESULT-STRING= _SBC-ASSERT
    S" operation_receipt" _SBC-RESULT-FIELD
        CV-TYPE@ CV-T-NULL = _SBC-ASSERT
    _SBC-STACK ;

