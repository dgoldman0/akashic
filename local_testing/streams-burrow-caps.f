    _SBC-REQUEST @ CBR-ARGS-SEAL! CBUS-S-OK = _SBC-ASSERT
    _SBC-INSTANCE @ CINST.REVISION @ _SBC-BEFORE-REVISION !
    _SBC-INVALIDATIONS @ _SBC-BEFORE-INVALIDATIONS !
    _SBC-REQUEST @ _SBC-BUS @ CBUS-DISPATCH ;

: _SBC-RESULT-FIELD  ( key-a key-u -- value|0 )
    _SBC-REQUEST @ CBR.RESULT CV-MAP-FIND ;

: _SBC-RESULT-INT  ( key-a key-u -- n )
    _SBC-RESULT-FIELD DUP 0= IF
        DROP 0 _SBC-ASSERT 0 EXIT
    THEN
    DUP CV-TYPE@ CV-T-INT = _SBC-ASSERT
    CV-DATA@ ;

: _SBC-RESULT-STRING=  ( key-a key-u expected-a expected-u -- flag )
    2>R _SBC-RESULT-FIELD DUP 0= IF
        DROP 2R> 2DROP 0 EXIT
    THEN
    DUP CV-TYPE@ CV-T-STRING <> IF
        DROP 2R> 2DROP 0 EXIT
    THEN
    DUP CV-DATA@ SWAP CV-LEN@ 2R> STR-STR= ;

: _SBC-COPY-RECEIPT  ( destination -- )
    >R S" operation_receipt" _SBC-RESULT-FIELD
    DUP _SBC-H64? _SBC-ASSERT
    DUP CV-DATA@ R@ SHA3-256-HEX-LEN MOVE
    CV-LEN@ SHA3-256-HEX-LEN = _SBC-ASSERT
    R> DROP ;

: _SBC-RECEIPT=  ( expected -- flag )
    >R S" operation_receipt" _SBC-RESULT-FIELD
    DUP _SBC-H64? 0= IF DROP R> DROP 0 EXIT THEN
    DUP CV-DATA@ SWAP CV-LEN@ R> SHA3-256-HEX-LEN STR-STR= ;

: _SBC-RESULT-R0  ( key-a key-u destination -- flag )
    >R _SBC-RESULT-FIELD DUP 0= IF DROP R> DROP 0 EXIT THEN
    R@ IRES-RREF@ IRES-S-OK <> IF R> DROP 0 EXIT THEN
    R@ RREF.REVISION @ 0=
    R> RREF.ID RID-PRESENT? AND ;

