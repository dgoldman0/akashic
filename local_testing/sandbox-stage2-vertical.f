_S2V-HOST-A-RAW _S2V-ALIGN8 CONSTANT _S2V-HOST-A
CREATE _S2V-HOST-B-RAW SBOX-HOST-INVOCATION-SIZE 7 + ALLOT
_S2V-HOST-B-RAW _S2V-ALIGN8 CONSTANT _S2V-HOST-B
