: _S2V-ASSERT  ( flag -- )
    1 _S2V-CHECKS +!
    0= IF
        1 _S2V-FAILS +!
        ." SBOX STAGE2 ASSERT " _S2V-CHECKS @ . CR TX-FLUSH
    THEN ;

: _S2V-STACK  ( -- )
    DEPTH DUP _S2V-DEPTH @ <> IF
        ." SBOX STAGE2 STACK "
        _S2V-DEPTH @ . ." -> " DUP . CR .S CR TX-FLUSH
    THEN
    _S2V-DEPTH @ = _S2V-ASSERT ;

: _S2V-ZERO?  ( address length -- flag )
    0 ?DO
        DUP I + C@ IF DROP 0 UNLOOP EXIT THEN
    LOOP
    DROP -1 ;

: _S2V-RESULT=?  ( expected expected-u result -- flag )
    SBOX-VM-RESULT-CANDIDATE@
    0= IF 2DROP 2DROP 0 EXIT THEN
    2 PICK OVER <> IF 2DROP 2DROP 0 EXIT THEN
    COMPARE 0= ;

: _S2V-SOURCE-ECHO  ( -- address length )
    S" FUNCTION echo PARAMS 1 RESULTS 1 LOCALS 0 DUP V.TYPE DROP RETURN END ENTRY SIGNATURE 1 main echo" ;

: _S2V-SOURCE-INCREMENT  ( -- address length )
    S" FUNCTION increment PARAMS 1 RESULTS 1 LOCALS 0 V.I64.GET 1 I64.ADD V.NEW.I64 RETURN END ENTRY SIGNATURE 1 main increment" ;

: _S2V-LIMIT!  ( value field -- )
    _S2V-LIMITS SBOX-VALUE-LIMIT!
    SBOX-VALUE-S-OK = _S2V-ASSERT ;

: _S2V-LIMITS-INIT  ( -- )
    _S2V-LIMITS SBOX-VALUE-LIMITS-BEGIN
        SBOX-VALUE-S-OK = _S2V-ASSERT
       8 SBOX-VALUE-LIMIT-DEPTH _S2V-LIMIT!
      64 SBOX-VALUE-LIMIT-BLOB-BYTES _S2V-LIMIT!
       8 SBOX-VALUE-LIMIT-LIST-COUNT _S2V-LIMIT!
       4 SBOX-VALUE-LIMIT-MAP-COUNT _S2V-LIMIT!
      32 SBOX-VALUE-LIMIT-INPUT-NODES _S2V-LIMIT!
    4096 SBOX-VALUE-LIMIT-INPUT-BYTES _S2V-LIMIT!
      32 SBOX-VALUE-LIMIT-OUTPUT-ARENA-NODES _S2V-LIMIT!
    4096 SBOX-VALUE-LIMIT-OUTPUT-ARENA-BYTES _S2V-LIMIT!
      64 SBOX-VALUE-LIMIT-OUTPUT-RESULT-NODES _S2V-LIMIT!
    8192 SBOX-VALUE-LIMIT-OUTPUT-RESULT-BYTES _S2V-LIMIT!
    _S2V-LIMITS SBOX-VALUE-LIMITS-SEAL
        SBOX-VALUE-S-OK = _S2V-ASSERT ;

: _S2V-VM-LIMIT!  ( value field -- ) 8 * _S2V-VM-LIMITS + ! ;

\ Each invocation's activation: tight budgets and room for small modules.
: _S2V-VM-LIMITS-INIT  ( -- )
        100 SBOX-VM-LIMIT-INSTRUCTIONS _S2V-VM-LIMIT!
        100 SBOX-VM-LIMIT-VALUE-OPS _S2V-VM-LIMIT!
       1024 SBOX-VM-LIMIT-COPY-BYTES _S2V-VM-LIMIT!
        256 SBOX-VM-LIMIT-DATA-STACK _S2V-VM-LIMIT!
         64 SBOX-VM-LIMIT-CALL-FRAMES _S2V-VM-LIMIT!
         64 SBOX-VM-LIMIT-LOOP-FRAMES _S2V-VM-LIMIT!
      65536 SBOX-VM-LIMIT-MEMORY-BYTES _S2V-VM-LIMIT!
    _S2V-VM-LIMITS SBOX-VM-LIMITS-VALID? _S2V-ASSERT ;

: _S2V-BOOL!  ( flag address -- )
    >R
    R@ 24 0 FILL
    SBOX-VALUE-T-BOOL R@ C!
    8 R@ 8 + SBOX-BYTE-U64-LE!
    R> 16 + SBOX-BYTE-U64-LE! ;

: _S2V-I64!  ( value address -- )
    >R
    R@ 24 0 FILL
    SBOX-VALUE-T-I64 R@ C!
    8 R@ 8 + SBOX-BYTE-U64-LE!
    R> 16 + SBOX-BYTE-U64-LE! ;

: _S2V-VALUES-INIT  ( -- )
    0 _S2V-INPUT-A _S2V-BOOL!
    41 _S2V-INPUT-B _S2V-I64!
    0 _S2V-EXPECTED-A _S2V-BOOL!
    42 _S2V-EXPECTED-B _S2V-I64! ;

\ Each module builds into its own record, which keeps its plan.
: _S2V-PLANS-INIT  ( -- )
    _S2V-PROFILE _S2V-LOAD SBOX-PROFILE-PURE-INIT
        SBOX-PROFILE-S-OK = _S2V-ASSERT
    _S2V-BUILD-A SBOX-BUILD-SIZE 0 FILL
    _S2V-BUILD-B SBOX-BUILD-SIZE 0 FILL
    _S2V-BUILD-A SBOX-BUILD-INIT SBOX-BUILD-S-OK = _S2V-ASSERT
    _S2V-BUILD-B SBOX-BUILD-INIT SBOX-BUILD-S-OK = _S2V-ASSERT
    _S2V-SOURCE-ECHO _S2V-PROFILE 0 _S2V-BUILD-A SBOX-BUILD
        SBOX-BUILD-S-OK = _S2V-ASSERT
    _S2V-SOURCE-INCREMENT _S2V-PROFILE 0 _S2V-BUILD-B SBOX-BUILD
        SBOX-BUILD-S-OK = _S2V-ASSERT
    \ Building the second module cannot disturb the first one's plan.
    _S2V-BUILD-A SBOX-BUILD-PLAN@ SBOX-BUILD-S-OK = _S2V-ASSERT
        SBOX-PLAN-VALID? _S2V-ASSERT ;

\ A declaration of module NAME for the module BUILD holds: one entry,
\ main, taking and returning a value.
: _S2V-DECLARE  ( name name-u revision build -- declaration declaration-u )
    SBOX-BUILD-PLAN@ SBOX-BUILD-S-OK = _S2V-ASSERT
    SBOX-PLAN-ARTIFACT-DIGEST@ _S2V-PROFILE SBOX-PROFILE-DIGEST@
    1 0 24 SBOX-DECL-MEASURE SBOX-DECL-S-OK = _S2V-ASSERT
    DUP _S2V-DECL-U ! >R 1 0 24 _S2V-DECL R>
    SBOX-DECL-START SBOX-DECL-S-OK = _S2V-ASSERT
    _S2V-DECL-WS _S2V-DECL SBOX-DECL-MODULE! SBOX-DECL-S-OK = _S2V-ASSERT
    0 S" main" SBOX-ABI-SIGNATURE-VALUE-TO-VALUE _S2V-DECL
        SBOX-DECL-ENTRY! SBOX-DECL-S-OK = _S2V-ASSERT
    0 _S2V-SCHEMA 12 _S2V-SCHEMA 12 _S2V-DECL-WS _S2V-DECL
        SBOX-DECL-SCHEMAS! SBOX-DECL-S-OK = _S2V-ASSERT
    _S2V-DECL _S2V-DECL-U @ ;

: _S2V-OWNER-INIT  ( -- )
    S" AKSCHEMA" _S2V-SCHEMA SWAP MOVE
    _S2V-SCHEMA 8 + 4 0 FILL
    4 _S2V-SCHEMA 8 + C!
    S" echo" _S2V-RID-A _S2V-DECL-WS SBOX-DECL-MODULE-RID
        SBOX-DECL-S-OK = _S2V-ASSERT
    S" increment" _S2V-RID-B _S2V-DECL-WS SBOX-DECL-MODULE-RID
        SBOX-DECL-S-OK = _S2V-ASSERT

    _S2V-OWNER SBOX-MODULE-OWNER-SIZE 0 FILL
    _S2V-PROFILE _S2V-OWNER SBOX-MODULE-OWNER-INIT
        SBOX-MODULE-S-OK = _S2V-ASSERT
    S" echo" 11 _S2V-BUILD-A _S2V-DECLARE _S2V-BUILD-A _S2V-OWNER
        SBOX-MODULE-ADD SBOX-MODULE-S-OK = _S2V-ASSERT _S2V-MODULE-A !
    S" increment" 22 _S2V-BUILD-B _S2V-DECLARE _S2V-BUILD-B _S2V-OWNER
        SBOX-MODULE-ADD SBOX-MODULE-S-OK = _S2V-ASSERT _S2V-MODULE-B !
    _S2V-OWNER SBOX-MODULE-COUNT@ 2 = _S2V-ASSERT

    \ Only the exact revision resolves.
    _S2V-RID-A 12 _S2V-OWNER SBOX-MODULE-FIND 0= _S2V-ASSERT
    _S2V-RID-A 11 _S2V-OWNER SBOX-MODULE-FIND
        _S2V-MODULE-A @ = _S2V-ASSERT
    _S2V-RID-B 22 _S2V-OWNER SBOX-MODULE-FIND
        _S2V-MODULE-B @ = _S2V-ASSERT

    _S2V-MODULE-A @ SBOX-MODULE-PIN SBOX-MODULE-S-OK = >R
    DUP SBOX-PLAN-PROFILE@ DUP _S2V-PROFILE = _S2V-ASSERT
    _S2V-PROFILE-A-RESOLVED !
    _S2V-PLAN-A-RESOLVED !
    R> _S2V-ASSERT
    _S2V-MODULE-B @ SBOX-MODULE-PIN SBOX-MODULE-S-OK = >R
    DUP SBOX-PLAN-PROFILE@ DUP _S2V-PROFILE = _S2V-ASSERT
    _S2V-PROFILE-B-RESOLVED !
    _S2V-PLAN-B-RESOLVED !
    R> _S2V-ASSERT
    _S2V-PLAN-A-RESOLVED @ _S2V-PLAN-B-RESOLVED @ <> _S2V-ASSERT

    S" main" _S2V-PLAN-A-RESOLVED @
        SBOX-HOST-ENTRY-RESOLVE-EXACT
    SBOX-HOST-S-OK = >R _S2V-ENTRY-A ! R> _S2V-ASSERT
    S" main" _S2V-PLAN-B-RESOLVED @
        SBOX-HOST-ENTRY-RESOLVE-EXACT
    SBOX-HOST-S-OK = >R _S2V-ENTRY-B ! R> _S2V-ASSERT ;

: _S2V-PARENT-INIT  ( -- )
    1 CTX-NEW ?DUP IF THROW THEN _S2V-PARENT !
    \ Trusted host metadata may remain on the private child Context, but
    \ capability/service fields must stay absent and unreachable to the VM.
    0x1111 _S2V-PARENT @ CTX.PRACTICE !
    0x2222 _S2V-PARENT @ CTX.OWNER-CORE !
    0x3333 _S2V-PARENT @ CTX.OWNER-TOKEN !
    0x4444 _S2V-PARENT @ CTX.POLICY !
    _S2V-PARENT @ DUP CTX.FLAGS @ CTX-F-ACTIVE OR
        OVER CTX.FLAGS !
    CTX-TOUCH
    _S2V-PARENT @ CTX-VALID? _S2V-ASSERT ;

: _S2V-CAPTURE-CHILD-IDENTITIES  ( -- )
    _S2V-HOST-A SBOX-HOST-CONTEXT-IDENTITY@
    SBOX-HOST-S-OK = >R
    _S2V-CHILD-A-EPOCH !
    _S2V-CHILD-A-GENERATION !
    _S2V-CHILD-A-ID !
    R> _S2V-ASSERT

    _S2V-HOST-B SBOX-HOST-CONTEXT-IDENTITY@
    SBOX-HOST-S-OK = >R
    _S2V-CHILD-B-EPOCH !
    _S2V-CHILD-B-GENERATION !
    _S2V-CHILD-B-ID !
    R> _S2V-ASSERT

    _S2V-CHILD-A-ID @ _S2V-CHILD-B-ID @ <> _S2V-ASSERT
    _S2V-CHILD-A-GENERATION @ 0> _S2V-ASSERT
    _S2V-CHILD-B-GENERATION @ 0> _S2V-ASSERT
    _S2V-CHILD-A-EPOCH @ _S2V-CHILD-B-EPOCH @ =
        _S2V-ASSERT ;

: _S2V-HOSTS-INIT  ( -- )
    _S2V-HOST-A SBOX-HOST-INVOCATION-SIZE 0 FILL
    _S2V-HOST-B SBOX-HOST-INVOCATION-SIZE 0 FILL

    _S2V-PARENT @
    _S2V-PLAN-A-RESOLVED @ _S2V-ENTRY-A @
    _S2V-INPUT-A 24 _S2V-LIMITS
    _S2V-VM-LIMITS _S2V-HOST-A SBOX-HOST-INIT
        SBOX-HOST-S-OK = _S2V-ASSERT

    _S2V-PARENT @
    _S2V-PLAN-B-RESOLVED @ _S2V-ENTRY-B @
    _S2V-INPUT-B 24 _S2V-LIMITS
    _S2V-VM-LIMITS _S2V-HOST-B SBOX-HOST-INIT
        SBOX-HOST-S-OK = _S2V-ASSERT

    _S2V-HOST-A SBOX-HOST-VALID? _S2V-ASSERT
    _S2V-HOST-B SBOX-HOST-VALID? _S2V-ASSERT
    _S2V-CAPTURE-CHILD-IDENTITIES

    \ The caller input ceases to be canonical after both INIT calls.  Results
    \ must still come from each invocation's private decoded copy.
    _S2V-INPUT-A 24 0xA5 FILL
    _S2V-INPUT-B 24 0xA5 FILL ;

: _S2V-EXECUTE  ( -- )
    1 _S2V-HOST-A SBOX-HOST-RUN-SLICE
        SBOX-VM-RUN-RUNNABLE = _S2V-ASSERT
    _S2V-HOST-B SBOX-HOST-RUN-STATE@
        SBOX-VM-RUN-RUNNABLE = _S2V-ASSERT
    1 _S2V-HOST-B SBOX-HOST-RUN-SLICE
        SBOX-VM-RUN-RUNNABLE = _S2V-ASSERT
    _S2V-HOST-A SBOX-HOST-RUN-STATE@
        SBOX-VM-RUN-RUNNABLE = _S2V-ASSERT
    100 _S2V-HOST-A SBOX-HOST-RUN-SLICE
        SBOX-VM-RUN-COMPLETE = _S2V-ASSERT
    100 _S2V-HOST-B SBOX-HOST-RUN-SLICE
        SBOX-VM-RUN-COMPLETE = _S2V-ASSERT

    _S2V-HOST-A SBOX-HOST-RESULT-MEASURE
        SBOX-HOST-S-OK = SWAP 120 = AND _S2V-ASSERT
    _S2V-HOST-B SBOX-HOST-RESULT-MEASURE
        SBOX-HOST-S-OK = SWAP 120 = AND _S2V-ASSERT

    _S2V-RESULT-A _S2V-RESULT-CAP 0xA5 FILL
    _S2V-RESULT-B _S2V-RESULT-CAP 0xA5 FILL
    _S2V-RESULT-A _S2V-RESULT-CAP _S2V-HOST-A SBOX-HOST-FINISH
        SBOX-HOST-S-OK = _S2V-ASSERT
    _S2V-HOST-B SBOX-HOST-VALID? _S2V-ASSERT
    _S2V-RESULT-B _S2V-RESULT-CAP _S2V-HOST-B SBOX-HOST-FINISH
        SBOX-HOST-S-OK = _S2V-ASSERT

    _S2V-HOST-A SBOX-HOST-INVOCATION-SIZE _S2V-ZERO?
        _S2V-ASSERT
    _S2V-HOST-B SBOX-HOST-INVOCATION-SIZE _S2V-ZERO?
        _S2V-ASSERT
    _S2V-HOST-A SBOX-HOST-RELEASE SBOX-HOST-S-OK = _S2V-ASSERT
    _S2V-HOST-B SBOX-HOST-RELEASE SBOX-HOST-S-OK = _S2V-ASSERT ;

: _S2V-RELEASE-BORROWS  ( -- )
    \ The owner holds both plans until their runs unpin them.
    _S2V-OWNER SBOX-MODULE-OWNER-RELEASE
        SBOX-MODULE-S-BUSY = _S2V-ASSERT
    _S2V-MODULE-A @ SBOX-MODULE-UNPIN SBOX-MODULE-S-OK = _S2V-ASSERT
    _S2V-MODULE-B @ SBOX-MODULE-UNPIN SBOX-MODULE-S-OK = _S2V-ASSERT
    _S2V-OWNER SBOX-MODULE-OWNER-RELEASE
        SBOX-MODULE-S-OK = _S2V-ASSERT
    _S2V-BUILD-A SBOX-BUILD-RELEASE SBOX-BUILD-S-OK = _S2V-ASSERT
    _S2V-BUILD-B SBOX-BUILD-RELEASE SBOX-BUILD-S-OK = _S2V-ASSERT
    0 _S2V-PARENT @ CTX.FLAGS !
    _S2V-PARENT @ CTX-FREE
    0 _S2V-PARENT !
    _S2V-PARENT @ 0= _S2V-ASSERT ;

: _S2V-RESULTS  ( -- )
    _S2V-RESULT-A SBOX-VM-RESULT-VALID? _S2V-ASSERT
    _S2V-RESULT-B SBOX-VM-RESULT-VALID? _S2V-ASSERT
    _S2V-RESULT-A SBOX-VM-RESULT-CLASS@
        SBOX-VM-CLASS-OK = _S2V-ASSERT
    _S2V-RESULT-B SBOX-VM-RESULT-CLASS@
        SBOX-VM-CLASS-OK = _S2V-ASSERT
    _S2V-RESULT-A SBOX-VM-RESULT-USAGE@ 0> _S2V-ASSERT
    _S2V-RESULT-B SBOX-VM-RESULT-USAGE@ 0> _S2V-ASSERT
    _S2V-EXPECTED-A 24 _S2V-RESULT-A
        _S2V-RESULT=? _S2V-ASSERT
    _S2V-EXPECTED-B 24 _S2V-RESULT-B
        _S2V-RESULT=? _S2V-ASSERT

    _S2V-RESULT-A _S2V-RESULT-CAP SBOX-VM-RESULT-RELEASE
        SBOX-VM-S-OK = _S2V-ASSERT
    _S2V-RESULT-B _S2V-RESULT-CAP SBOX-VM-RESULT-RELEASE
        SBOX-VM-S-OK = _S2V-ASSERT
    _S2V-PROFILE SBOX-PROFILE-SIZE 0 FILL ;

: _S2V-RUN  ( -- )
    0 _S2V-FAILS !
    0 _S2V-CHECKS !
    DEPTH _S2V-DEPTH !
    ." SBOX STAGE2 VERTICAL START" CR TX-FLUSH

    _S2V-LIMITS-INIT
    _S2V-VM-LIMITS-INIT
    _S2V-VALUES-INIT
    _S2V-PLANS-INIT
    _S2V-OWNER-INIT
    _S2V-PARENT-INIT
    _S2V-HOSTS-INIT
    _S2V-EXECUTE
    _S2V-RELEASE-BORROWS
    _S2V-RESULTS
    _S2V-STACK

    _S2V-FAILS @ IF
        ." SBOX STAGE2 VERTICAL FAIL "
        _S2V-FAILS @ . ." / " _S2V-CHECKS @ . CR TX-FLUSH
    ELSE
        ." SBOX STAGE2 VERTICAL PASS "
        _S2V-CHECKS @ . CR TX-FLUSH
    THEN ;

_S2V-RUN
