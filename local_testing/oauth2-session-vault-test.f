\ =====================================================================

VARIABLE _O2SVT-RESOLVER-CALLS
VARIABLE _O2SVT-R-KEY-A
VARIABLE _O2SVT-R-KEY-U
VARIABLE _O2SVT-R-CONSUMER-XT
VARIABLE _O2SVT-R-CONSUMER-CONTEXT
VARIABLE _O2SVT-R-RESOLVER-CONTEXT

: _O2SVT-RESOLVER
  \ ( key-id key-id-u consumer-xt consumer-context resolver-context
  \   -- status )
    _O2SVT-R-RESOLVER-CONTEXT !
    _O2SVT-R-CONSUMER-CONTEXT !
    _O2SVT-R-CONSUMER-XT !
    _O2SVT-R-KEY-U !
    _O2SVT-R-KEY-A !
    _O2SVT-R-RESOLVER-CONTEXT @
        _O2SVT-RESOLVER-TOKEN = _O2SVT-ASSERT
    _O2SVT-R-KEY-U @ RID-SIZE = _O2SVT-ASSERT
    _O2SVT-R-KEY-A @ RID-SIZE
        _O2SVT-KEY-ID RID-SIZE COMPARE 0= _O2SVT-ASSERT
    1 _O2SVT-RESOLVER-CALLS +!
    _O2SVT-ROOT-KEY SEALED-RECORD-ROOT-KEY-SIZE
    _O2SVT-R-CONSUMER-CONTEXT @
    _O2SVT-R-CONSUMER-XT @ EXECUTE ;

