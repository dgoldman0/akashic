\ Exact credential-vault and durable OAuth-session composition lifecycle.
\
\ Load cv-deps.f, then runner-packaged exact production bodies for
\ credential-vault.f, oauth2/token-set.f, and oauth2/session.f, then this
\ fixture.  Invoke _O2SVT-RUN from autoexec.  The fixture is provider-neutral
\ and deliberately configures no rollback-floor provider.

PROVIDED oauth2-session-cv-test

VARIABLE _O2SVT-FAILS
VARIABLE _O2SVT-CHECKS
VARIABLE _O2SVT-DEPTH
VARIABLE _O2SVT-GENERATION
VARIABLE _O2SVT-EXPECTED-A
VARIABLE _O2SVT-EXPECTED-U
VARIABLE _O2SVT-RESOLVER-BEFORE

VARIABLE _O2SVT-VAULT-CONFIG
VARIABLE _O2SVT-VAULT
VARIABLE _O2SVT-BACKING
VARIABLE _O2SVT-SESSION

CREATE _O2SVT-SESSION-CONFIG O2SESSION-CONFIG-SIZE ALLOT
CREATE _O2SVT-GRANT O2SESSION-GRANT-SIZE ALLOT
CREATE _O2SVT-VFS VFS-DESC-SIZE ALLOT
CREATE _O2SVT-VAULT-ID RID-SIZE ALLOT
CREATE _O2SVT-KEY-ID RID-SIZE ALLOT
CREATE _O2SVT-RID RID-SIZE ALLOT
CREATE _O2SVT-ROOT-KEY SEALED-RECORD-ROOT-KEY-SIZE ALLOT

O2SESSION-RECORD-SIZE CVAULT-BACKING-SIZE
    CONSTANT _O2SVT-BACKING-U

0x4F32535654525331 CONSTANT _O2SVT-RESOLVER-TOKEN
0x4F32535654434231 CONSTANT _O2SVT-CALLBACK-TOKEN

: _O2SVT-ASSERT  ( flag -- )
    1 _O2SVT-CHECKS +!
    0= IF
        1 _O2SVT-FAILS +!
        ." OAUTH2 SESSION VAULT ASSERT " _O2SVT-CHECKS @ . CR
    THEN ;

: _O2SVT-STACK  ( -- )
    DEPTH DUP _O2SVT-DEPTH @ <> IF
        ." OAUTH2 SESSION VAULT STACK "
        _O2SVT-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _O2SVT-DEPTH @ = _O2SVT-ASSERT ;

: _O2SVT-ZERO?  ( address length -- flag )
    BEGIN
        DUP
    WHILE
        OVER C@ IF 2DROP 0 EXIT THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP -1 ;

: _O2SVT-ALLOCATE  ( size variable -- )
    >R ALLOCATE ABORT" OAUTH2 SESSION VAULT FAIL allocation"
    R> ! ;

: _O2SVT-FREE  ( variable -- )
    DUP @ ?DUP IF FREE 0 SWAP ! ELSE DROP THEN ;

\ =====================================================================
