\ =====================================================================
\  Session checks and owner-restart boundary
\ =====================================================================

: _O2SVT-EXPECT  ( address length -- )
    _O2SVT-EXPECTED-U !
    _O2SVT-EXPECTED-A ! ;

: _O2SVT-EXPECT-CALLBACK
  ( address length callback-context -- callback-result )
    >R
    _O2SVT-EXPECTED-A @ _O2SVT-EXPECTED-U @
        COMPARE 0= _O2SVT-ASSERT
    R@ _O2SVT-CALLBACK-TOKEN = _O2SVT-ASSERT
    R> ;

: _O2SVT-ADVANCE  ( generation status -- )
    DUP O2SESSION-S-OK = _O2SVT-ASSERT
    DROP
    DUP _O2SVT-GENERATION @ 1+ = _O2SVT-ASSERT
    _O2SVT-GENERATION ! ;

: _O2SVT-CHECK-STATE  ( expected-phase -- )
    >R
    _O2SVT-SESSION @ O2SESSION-STATE@
    DUP O2SESSION-S-OK = _O2SVT-ASSERT
    DROP
    R> = _O2SVT-ASSERT
    _O2SVT-GENERATION @ = _O2SVT-ASSERT ;

: _O2SVT-CHECK-OPEN  ( expected-phase -- )
    >R
    _O2SVT-SESSION @ O2SESSION-OPEN
    DUP O2SESSION-S-OK = _O2SVT-ASSERT
    DROP
    R> = _O2SVT-ASSERT
    _O2SVT-GENERATION @ = _O2SVT-ASSERT ;

: _O2SVT-CHECK-ACCESS  ( expected-a expected-u -- )
    _O2SVT-EXPECT
    ['] _O2SVT-EXPECT-CALLBACK _O2SVT-CALLBACK-TOKEN
        _O2SVT-SESSION @ O2SESSION-WITH-ACCESS
    DUP O2SESSION-S-OK = _O2SVT-ASSERT
    DROP
    _O2SVT-CALLBACK-TOKEN = _O2SVT-ASSERT ;

: _O2SVT-FINI-OWNERS  ( -- )
    _O2SVT-SESSION @ O2SESSION-CLOSE
        O2SESSION-S-OK = _O2SVT-ASSERT
    _O2SVT-SESSION @ O2SESSION-FINI
        O2SESSION-S-OK = _O2SVT-ASSERT
    _O2SVT-SESSION @ OAUTH2-SESSION-SIZE
        _O2SVT-ZERO? _O2SVT-ASSERT
    _O2SVT-VAULT @ CVAULT-FINI
        CVAULT-S-OK = _O2SVT-ASSERT
    _O2SVT-VAULT @ CVAULT-SIZE
        _O2SVT-ZERO? _O2SVT-ASSERT
    _O2SVT-BACKING @ _O2SVT-BACKING-U
        _O2SVT-ZERO? _O2SVT-ASSERT ;

: _O2SVT-RESTART-OWNERS  ( -- )
    _O2SVT-FINI-OWNERS
    _O2SVT-CONFIGURE-VAULT
    _O2SVT-CONFIGURE-SESSION ;

: _O2SVT-CHECK-TOMBSTONE  ( -- )
    _O2SVT-RID _O2SVT-VAULT @ CVAULT-METADATA
    DUP CVAULT-S-REVOKED = _O2SVT-ASSERT
    DROP
    0= _O2SVT-ASSERT
    O2SESSION-CREDENTIAL-KIND = _O2SVT-ASSERT
    CVAULT-STATE-TOMBSTONE = _O2SVT-ASSERT
    _O2SVT-GENERATION @ = _O2SVT-ASSERT ;

\ =====================================================================
\  Exact-composition lifecycle
\ =====================================================================

: _O2SVT-SETUP  ( -- )
    CVAULT-CONFIG-SIZE
        _O2SVT-VAULT-CONFIG _O2SVT-ALLOCATE
    CVAULT-SIZE _O2SVT-VAULT _O2SVT-ALLOCATE
    _O2SVT-BACKING-U _O2SVT-BACKING _O2SVT-ALLOCATE
    OAUTH2-SESSION-SIZE _O2SVT-SESSION _O2SVT-ALLOCATE

    _O2SVT-VAULT-CONFIG @ CVAULT-CONFIG-SIZE 0 FILL
    _O2SVT-VAULT @ CVAULT-SIZE 0 FILL
    _O2SVT-BACKING @ _O2SVT-BACKING-U 0 FILL
    _O2SVT-SESSION @ OAUTH2-SESSION-SIZE 0 FILL
    _O2SVT-SESSION-CONFIG O2SESSION-CONFIG-SIZE 0 FILL
    _O2SVT-GRANT O2SESSION-GRANT-SIZE 0 FILL
    _O2SVT-VFS VFS-DESC-SIZE 0 FILL

    _CVTD-RESET
    _CVTD-ROOT-INODE _O2SVT-VFS V.CWD !
    _O2SVT-VFS VFS-USE
    _O2SVT-VAULT-ID RID-SIZE 0x11 FILL
    _O2SVT-KEY-ID RID-SIZE 0x22 FILL
    _O2SVT-RID RID-SIZE 0x33 FILL
    _O2SVT-ROOT-KEY SEALED-RECORD-ROOT-KEY-SIZE 0x44 FILL
    _O2SVT-RID RID-PRESENT? _O2SVT-ASSERT
    _O2SVT-RID _O2SVT-VAULT-ID RID= 0= _O2SVT-ASSERT
    0 _O2SVT-RESOLVER-CALLS !
    _O2SVT-CONFIGURE-VAULT
    _O2SVT-CONFIGURE-SESSION ;

: _O2SVT-INSTALL  ( -- )
    _O2SVT-GRANT-ONE
    _O2SVT-GRANT _O2SVT-SESSION @ O2SESSION-INSTALL
        _O2SVT-ADVANCE
    O2SESSION-PHASE-ACTIVE _O2SVT-CHECK-STATE
    _O2SVT-RESOLVER-CALLS @ 0> _O2SVT-ASSERT
    S" access-one" _O2SVT-CHECK-ACCESS ;

: _O2SVT-RESTART-OPEN  ( -- )
    _O2SVT-RESTART-OWNERS
    _O2SVT-RESOLVER-CALLS @ _O2SVT-RESOLVER-BEFORE !
    O2SESSION-PHASE-ACTIVE _O2SVT-CHECK-OPEN
    _O2SVT-RESOLVER-CALLS @
        _O2SVT-RESOLVER-BEFORE @ > _O2SVT-ASSERT
    S" access-one" _O2SVT-CHECK-ACCESS ;

: _O2SVT-REFRESH  ( -- )
    _O2SVT-GENERATION @ _O2SVT-SESSION @
        O2SESSION-REFRESH-CLAIM _O2SVT-ADVANCE
    O2SESSION-PHASE-REFRESH-CLAIMED _O2SVT-CHECK-STATE

    S" refresh-one" _O2SVT-EXPECT
    ['] _O2SVT-EXPECT-CALLBACK _O2SVT-CALLBACK-TOKEN
    _O2SVT-GENERATION @ _O2SVT-SESSION @
        O2SESSION-REFRESH-EXPOSE
    DUP O2SESSION-S-OK = _O2SVT-ASSERT
    DROP
    _O2SVT-CALLBACK-TOKEN = _O2SVT-ASSERT
    DUP _O2SVT-GENERATION @ 1+ = _O2SVT-ASSERT
    _O2SVT-GENERATION !
    O2SESSION-PHASE-REFRESH-EXPOSED _O2SVT-CHECK-STATE

    _O2SVT-GRANT-TWO
    _O2SVT-GRANT _O2SVT-GENERATION @ _O2SVT-SESSION @
        O2SESSION-REFRESH-COMMIT _O2SVT-ADVANCE
    O2SESSION-PHASE-ACTIVE _O2SVT-CHECK-STATE
    S" access-two" _O2SVT-CHECK-ACCESS

    _O2SVT-SESSION @ O2SESSION-CLOSE
        O2SESSION-S-OK = _O2SVT-ASSERT
    O2SESSION-PHASE-ACTIVE _O2SVT-CHECK-OPEN
    S" access-two" _O2SVT-CHECK-ACCESS ;

: _O2SVT-LOGOUT  ( -- )
    _O2SVT-GENERATION @ _O2SVT-SESSION @
        O2SESSION-LOGOUT _O2SVT-ADVANCE
    ['] _O2SVT-EXPECT-CALLBACK _O2SVT-CALLBACK-TOKEN
        _O2SVT-SESSION @ O2SESSION-WITH-ACCESS
    DUP O2SESSION-S-REVOKED = _O2SVT-ASSERT
    DROP
    0= _O2SVT-ASSERT
    _O2SVT-CHECK-TOMBSTONE ;

: _O2SVT-NON-RESURRECTION  ( -- )
    _O2SVT-RESTART-OWNERS
    _O2SVT-SESSION @ O2SESSION-OPEN
    DUP O2SESSION-S-REVOKED = _O2SVT-ASSERT
    DROP
    0= _O2SVT-ASSERT
    0= _O2SVT-ASSERT
    _O2SVT-CHECK-TOMBSTONE

    _O2SVT-GRANT-TWO
    _O2SVT-GRANT _O2SVT-GENERATION @ _O2SVT-SESSION @
        O2SESSION-REAUTHORIZE
    DUP O2SESSION-S-REVOKED = _O2SVT-ASSERT
    DROP
    0= _O2SVT-ASSERT
    _O2SVT-CHECK-TOMBSTONE ;

: _O2SVT-CLEANUP  ( -- )
    _O2SVT-FINI-OWNERS
    _O2SVT-SESSION-CONFIG O2SESSION-CONFIG-CLEAR
        O2SESSION-S-OK = _O2SVT-ASSERT
    _O2SVT-SESSION-CONFIG O2SESSION-CONFIG-SIZE
        _O2SVT-ZERO? _O2SVT-ASSERT
    _O2SVT-GRANT O2SESSION-GRANT-CLEAR
        O2SESSION-S-OK = _O2SVT-ASSERT
    _O2SVT-GRANT O2SESSION-GRANT-SIZE
        _O2SVT-ZERO? _O2SVT-ASSERT
    _O2SVT-VAULT-CONFIG @ CVAULT-CONFIG-CLEAR
        CVAULT-S-OK = _O2SVT-ASSERT
    _O2SVT-VAULT-CONFIG @ CVAULT-CONFIG-SIZE
        _O2SVT-ZERO? _O2SVT-ASSERT

    0 VFS-USE
    _CVTD-RESET
    _O2SVT-VAULT-ID RID-CLEAR
    _O2SVT-KEY-ID RID-CLEAR
    _O2SVT-RID RID-CLEAR
    _O2SVT-ROOT-KEY SEALED-RECORD-ROOT-KEY-SIZE 0 FILL
    _O2SVT-VFS VFS-DESC-SIZE 0 FILL
    0 _O2SVT-EXPECTED-A !
    0 _O2SVT-EXPECTED-U !
    _O2SVT-VAULT-ID RID-SIZE _O2SVT-ZERO? _O2SVT-ASSERT
    _O2SVT-KEY-ID RID-SIZE _O2SVT-ZERO? _O2SVT-ASSERT
    _O2SVT-RID RID-SIZE _O2SVT-ZERO? _O2SVT-ASSERT
    _O2SVT-ROOT-KEY SEALED-RECORD-ROOT-KEY-SIZE
        _O2SVT-ZERO? _O2SVT-ASSERT
    _O2SVT-VFS VFS-DESC-SIZE _O2SVT-ZERO? _O2SVT-ASSERT

    _O2SVT-SESSION _O2SVT-FREE
    _O2SVT-BACKING _O2SVT-FREE
    _O2SVT-VAULT _O2SVT-FREE
    _O2SVT-VAULT-CONFIG _O2SVT-FREE ;

: _O2SVT-RUN  ( -- )
    ." OAUTH2 SESSION VAULT START" CR TX-FLUSH
    0 _O2SVT-FAILS !
    0 _O2SVT-CHECKS !
    0 _O2SVT-GENERATION !
    DEPTH _O2SVT-DEPTH !

    _O2SVT-SETUP _O2SVT-STACK
    _O2SVT-INSTALL _O2SVT-STACK
    ." OAUTH2 SESSION VAULT INSTALLED" CR TX-FLUSH
    _O2SVT-RESTART-OPEN _O2SVT-STACK
    ." OAUTH2 SESSION VAULT RESTARTED" CR TX-FLUSH
    _O2SVT-REFRESH _O2SVT-STACK
    ." OAUTH2 SESSION VAULT REFRESHED" CR TX-FLUSH
    _O2SVT-LOGOUT _O2SVT-STACK
    _O2SVT-NON-RESURRECTION _O2SVT-STACK
    ." OAUTH2 SESSION VAULT TOMBSTONED" CR TX-FLUSH
    _O2SVT-CLEANUP _O2SVT-STACK

    _O2SVT-FAILS @ 0= IF
        ." OAUTH2 SESSION VAULT PASS " _O2SVT-CHECKS @ . CR
    ELSE
        ." OAUTH2 SESSION VAULT FAIL " _O2SVT-FAILS @ .
        ." / " _O2SVT-CHECKS @ . CR
    THEN ;
