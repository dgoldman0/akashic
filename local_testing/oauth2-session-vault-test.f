    _O2SVT-BACKING @
        _O2SVT-VAULT-CONFIG @ CVAULT-C.BACKING !
    _O2SVT-BACKING-U
        _O2SVT-VAULT-CONFIG @ CVAULT-C.BACKING-U !
    _O2SVT-VFS
        _O2SVT-VAULT-CONFIG @ CVAULT-C.VFS !
    _O2SVT-VAULT-ID
        _O2SVT-VAULT-CONFIG @ CVAULT-C.VAULT-ID !
    _O2SVT-KEY-ID
