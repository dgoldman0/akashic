    DUP C@ 1 XOR OVER C!
    _SBC-ARTIFACT _SBC-ARTIFACT-U _SBC-INSPECT-LAYOUT SBOX-ARTIFACT-INSPECT
        SBOX-ARTIFACT-S-INVALID = _SBC-ASSERT
