: _SBC-RUN  ( -- )
    0 _SBC-FAILS !
    0 _SBC-CHECKS !
    DEPTH _SBC-DEPTH !
    ." SBOX CORE CONTRACTS START" CR
    _SBC-MACHINE-CONTRACTS
    _SBC-PROFILE-CONTRACTS
    _SBC-CANDIDATE-CONTRACTS
    _SBC-PLAN-CONTRACTS
    _SBC-BINDING-CONTRACTS
    _SBC-STACK
    _SBC-FAILS @ 0= IF
        ." SBOX CORE CONTRACTS PASS " _SBC-CHECKS @ . CR
    ELSE
        ." SBOX CORE CONTRACTS FAIL " _SBC-FAILS @ . CR
    THEN ;

_SBC-RUN
