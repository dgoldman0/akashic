\ The offset of TEXT within ADDRESS LENGTH, or -1.
: _SBC-FIND  ( address length text-a text-u -- offset|-1 )
    _SBC-TU ! _SBC-TA !
    _SBC-TU @ - 1+ 0 MAX 0 ?DO
        DUP I + _SBC-TU @ _SBC-TA @ _SBC-TU @ COMPARE 0= IF
            DROP I UNLOOP EXIT
        THEN
    LOOP
    DROP -1 ;

: _SBC-ASSERT  ( flag -- )
    1 _SBC-CHECKS +!
    0= IF
        1 _SBC-FAILS +!
        ." SBOX CORE ASSERT " _SBC-CHECKS @ . CR
    THEN ;

: _SBC-STACK  ( -- )
    DEPTH DUP _SBC-DEPTH @ <> IF
        ." SBOX CORE STACK " _SBC-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _SBC-DEPTH @ = _SBC-ASSERT ;

: _SBC-FILLED?  ( address length byte -- flag )
    _SBC-BYTE !
    0 ?DO
        DUP I + C@ _SBC-BYTE @ <> IF DROP 0 UNLOOP EXIT THEN
    LOOP
    DROP -1 ;

