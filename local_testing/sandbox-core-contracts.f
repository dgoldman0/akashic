: _SBC-PLAN-CONTRACTS  ( -- )
    136 SBOX-PLAN-MEASURE
        SBOX-PLAN-S-OK = SWAP 392 = AND _SBC-ASSERT
    _SBC-CANDIDATE 136 _SBC-LAYOUT _SBC-PROFILE
        _SBC-PLAN 512 SBOX-PLAN-PUBLISH-VERIFIED
        SBOX-PLAN-S-OK = _SBC-ASSERT
    _SBC-PLAN SBOX-PLAN-VALID? _SBC-ASSERT
    _SBC-PLAN SBOX-PLAN-TOTAL@ 392 = _SBC-ASSERT
    _SBC-PLAN SBOX-PLAN-PROFILE@ _SBC-PROFILE = _SBC-ASSERT
    _SBC-PLAN SBOX-PLAN-MEMORY-U@ 64 = _SBC-ASSERT
    1 _SBC-PLAN SBOX-PLAN-INSTRUCTION@
        SBOX-CANDIDATE-U16-LE@
        SBOX-MACHINE-OP-RETURN = _SBC-ASSERT

    \ The sealed plan owns the accepted bytes.
    SBOX-MACHINE-OP-ABORT
    _SBC-CANDIDATE
    _SBC-LAYOUT SBOX-CANDIDATE-LAYOUT-INSTRUCTIONS@ +
    SBOX-CANDIDATE-INSTRUCTION-SIZE +
    SBOX-CANDIDATE-U16-LE!
    1 _SBC-PLAN SBOX-PLAN-INSTRUCTION@
        SBOX-CANDIDATE-U16-LE@
        SBOX-MACHINE-OP-RETURN = _SBC-ASSERT

    _SBC-PLAN _SBC-PLAN-COPY 392 MOVE
    _SBC-PLAN-COPY SBOX-PLAN-VALID? 0= _SBC-ASSERT

    \ Direct plan publication must reject overlap with any byte of the
    \ complete fixed profile, not merely with its first byte.
    _SBC-PROFILE-PLAN-OVERLAP SBOX-PROFILE-PURE-INIT
        SBOX-PROFILE-S-OK = _SBC-ASSERT
    _SBC-CANDIDATE 136 _SBC-LAYOUT
        _SBC-PROFILE-PLAN-OVERLAP
        _SBC-PROFILE-PLAN-OVERLAP 8 + 392
        SBOX-PLAN-PUBLISH-VERIFIED
        SBOX-PLAN-S-ALIAS = _SBC-ASSERT
    _SBC-PROFILE-PLAN-OVERLAP SBOX-PROFILE-VALID? _SBC-ASSERT
    _SBC-STACK ;

