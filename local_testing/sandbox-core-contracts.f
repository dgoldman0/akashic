        SBOX-CANDIDATE-S-OK = _SBC-ASSERT
    _SBC-LAYOUT SBOX-CANDIDATE-LAYOUT-VALID? _SBC-ASSERT
    _SBC-LAYOUT SBOX-CANDIDATE-LAYOUT-TOTAL@ 136 = _SBC-ASSERT ;

: _SBC-WRITE-ANCHOR-RECORDS  ( -- )
    _SBC-CANDIDATE
    _SBC-LAYOUT SBOX-CANDIDATE-LAYOUT-FUNCTIONS@ + >R
    2 R@ SBOX-CANDIDATE-U32-LE!
    1 R@ SBOX-CANDIDATE-FUNCTION-PARAMS-OFFSET +
        SBOX-CANDIDATE-U16-LE!
    1 R@ SBOX-CANDIDATE-FUNCTION-RESULTS-OFFSET +
        SBOX-CANDIDATE-U16-LE!
    R> DROP

    _SBC-CANDIDATE
    _SBC-LAYOUT SBOX-CANDIDATE-LAYOUT-ENTRIES@ + >R
    4 R@ SBOX-CANDIDATE-ENTRY-NAME-U-OFFSET +
        SBOX-CANDIDATE-U16-LE!
    0 R@ SBOX-CANDIDATE-ENTRY-FUNCTION-INDEX-OFFSET +
        SBOX-CANDIDATE-U32-LE!
    R> DROP

    _SBC-CANDIDATE
    _SBC-LAYOUT SBOX-CANDIDATE-LAYOUT-NAMES@ +
    DUP [CHAR] m SWAP C!
    DUP 1+ [CHAR] a SWAP C!
    DUP 2 + [CHAR] i SWAP C!
    3 + [CHAR] n SWAP C!

    SBOX-MACHINE-OP-RETURN
    _SBC-CANDIDATE
    _SBC-LAYOUT SBOX-CANDIDATE-LAYOUT-INSTRUCTIONS@ +
    SBOX-CANDIDATE-INSTRUCTION-SIZE +
    SBOX-CANDIDATE-U16-LE! ;

