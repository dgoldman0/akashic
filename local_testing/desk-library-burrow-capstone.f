: _C5-PHASE-HELLO  ( -- )
    _C5-NONMEMBER-IDENTITY
    _C5-ENDPOINTS? _C5-HANDSHAKE-READY? AND DUP _C4-ASSERT 0= IF
        _C5-DATA-FAIL EXIT
    THEN
