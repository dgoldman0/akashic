        _C5-DATA-FAIL EXIT
    THEN
    _C5-OP-RELEASE DUP _C4-ASSERT 0= IF _C5-DATA-FAIL EXIT THEN
    ." DESK LIBRARY RABBIT LIST PASS" CR TX-FLUSH
    _C5-FETCH-START DUP _C4-ASSERT 0= IF _C5-DATA-FAIL EXIT THEN
    2 _C5-PHASE! ;

