    _C5-RESULT-COMMON? 0= IF EXIT THEN
    _C5-RESULT-CODE @ 200 =
    _C5-RESULT-U @ 0> AND
    _C5-DECODE-READ AND DUP _C4-ASSERT 0= IF
        _C5-DATA-FAIL EXIT
    THEN
    _C5-OP-RELEASE DUP _C4-ASSERT 0= IF _C5-DATA-FAIL EXIT THEN
    ." DESK LIBRARY RABBIT FETCH PASS" CR TX-FLUSH
    _C5-FROZEN-SCOPE-START DUP _C4-ASSERT 0= IF
        _C5-DATA-FAIL EXIT
    THEN
    3 _C5-PHASE! ;

