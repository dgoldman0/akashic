    _C5-LIST-START DUP _C4-ASSERT 0= IF _C5-DATA-FAIL EXIT THEN
    1 _C5-PHASE! ;

: _C5-PHASE-LIST  ( -- )
    _C5-RESULT-COMMON? 0= IF EXIT THEN
    _C5-RESULT-CODE @ 200 =
    _C5-RESULT-U @ 0> AND
