: _C5-RESULT-OBSERVE  ( -- )
    \ The document create result is still borrowed at this point.  Retain
    \ only the digest needed to verify the later independent FETCH.
    _C4-CALL @ 1 <> IF EXIT THEN
    S" content_digest" _C4-FIELD
    DUP 0<> DUP _C4-ASSERT 0= IF DROP EXIT THEN
    DUP CV-TYPE@ CV-T-STRING = DUP _C4-ASSERT 0= IF DROP EXIT THEN
    DUP CV-LEN@ SHA3-256-HEX-LEN = DUP _C4-ASSERT 0= IF DROP EXIT THEN
