    404 _C5-BODYLESS-CODE? DUP _C4-ASSERT 0= IF
        _C5-DATA-FAIL EXIT
    THEN
    _C5-OP-RELEASE DUP _C4-ASSERT 0= IF _C5-DATA-FAIL EXIT THEN
    ." DESK LIBRARY RABBIT NONMEMBER PASS" CR TX-FLUSH
    _C5-STALE-START DUP _C4-ASSERT 0= IF _C5-DATA-FAIL EXIT THEN
    5 _C5-PHASE! ;

: _C5-PHASE-STALE  ( -- )
    _C5-RESULT-COMMON? 0= IF EXIT THEN
    500 _C5-BODYLESS-CODE? DUP _C4-ASSERT 0= IF
        _C5-DATA-FAIL EXIT
    THEN
    _C5-OP-RELEASE DUP _C4-ASSERT 0= IF _C5-DATA-FAIL EXIT THEN
    _C5-PROVIDER SLRGP-GRAPH-COUNT@ 1 = _C4-ASSERT
    _C5-PROVIDER SLRGP-SERVICE-COUNT@ 0> _C4-ASSERT
    _C5-PROVIDER SLRGP-CLIENT-CONTROL-WIRE-BYTES@ 0> _C4-ASSERT
    _C5-PROVIDER SLRGP-CLIENT-DATA-WIRE-BYTES@ 0> _C4-ASSERT
    _C5-PROVIDER SLRGP-SERVER-CONTROL-WIRE-BYTES@ 0> _C4-ASSERT
    _C5-PROVIDER SLRGP-SERVER-DATA-WIRE-BYTES@ 0> _C4-ASSERT
    _C5-PROVIDER SLRGP-MEASURED-WIRE-BYTES@ 0> _C4-ASSERT
    _C5-PROVIDER SLRGP-MEASURED-RESULT-BYTES@
        STREAMS-RABBIT-LIBRARY-PROFILE-READ-JSON-MIN = _C4-ASSERT
    _C5-PROVIDER SLRGP-PROFILE@ DUP
        STREAMS-RABBIT-LIBRARY-PROFILE-VALID? _C4-ASSERT
    DUP STREAMS-RABBIT-LIBRARY-PROFILE-FACET@
        DUP _C4-FACET @ <> _C4-ASSERT
        CFACET.COUNT @ 2 = _C4-ASSERT
    _C5-ROWS SRBMGR-DECL.SPEC SWAP
        STREAMS-RABBIT-LIBRARY-PROFILE-GRAPH-SPEC-MATCH? _C4-ASSERT
    _C5-VALUE CV-FREE
    -1 _C5-RUNTIME-WITNESS !
    ." DESK LIBRARY RABBIT STALE REVISION PASS" CR
    ." DESK LIBRARY RABBIT DATA PLANE PASS" CR TX-FLUSH
    -1 _C5-DATA-DONE ! 6 _C5-PHASE! ;

: _C5-DATA-TICK  ( -- )
    _C5-DATA-DONE @ IF EXIT THEN
    _C5-PHASE @ CASE
        0 OF _C5-PHASE-HELLO ENDOF
        1 OF _C5-PHASE-LIST ENDOF
        2 OF _C5-PHASE-FETCH ENDOF
        3 OF _C5-PHASE-FROZEN-SCOPE ENDOF
        4 OF _C5-PHASE-NONMEMBER ENDOF
        5 OF _C5-PHASE-STALE ENDOF
        _C5-DATA-FAIL
    ENDCASE ;

