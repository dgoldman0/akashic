\ =====================================================================
\ desk-library-burrow-capstone.f - Checkpoint-5 product capstone
\ =====================================================================
\ Loaded after the Checkpoint-4 product fixture and the deterministic
\ Library Rabbit provider.  This file installs only the later composition
\ hooks: the ordinary Desk/Agent eight-logical-call journey remains owned by
\ desk-library-burrow.f.  Checkpoint 5 adds one physical replay of start and
\ progresses an independent framed client before the following status call.
\
\ The graph has one declaration because that is this fixture's cardinality,
\ not a product capacity.  Variable-sized transport memory is obtained as
\ one caller-owned slab and bound through the provider's checked geometry.
\ Keeping the source as its own image resource makes the Checkpoint-4 fixture
\ independently runnable and auditable.
\ =====================================================================

