        SBOX-BYTE-S-OK = _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READ-U8
        SBOX-BYTE-S-OK = SWAP 0x01 = AND _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READ-U16-LE
        SBOX-BYTE-S-OK = SWAP 0x1234 = AND _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READ-U32-LE
        SBOX-BYTE-S-OK = SWAP 0x12345678 = AND _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READ-U64-LE
        SBOX-BYTE-S-OK = SWAP 0x0123456789ABCDEF = AND _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-OFFSET@ 15 = _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-REMAINING@ 0= _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-AT-END? _SBF-ASSERT

    _SBF-READER-A SBOX-BYTE-READ-U8
        SBOX-BYTE-S-CAPACITY = SWAP 0= AND _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-OFFSET@ 15 = _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-STATUS@
        SBOX-BYTE-S-CAPACITY = _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-AT-END? 0= _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READ-U32-LE
        SBOX-BYTE-S-CAPACITY = SWAP 0= AND _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-OFFSET@ 15 = _SBF-ASSERT

    _SBF-READER-A SBOX-BYTE-READER-RESET
        SBOX-BYTE-S-OK = _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-STATUS@
        SBOX-BYTE-S-OK = _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-OFFSET@ 0= _SBF-ASSERT

    3 _SBF-READER-A SBOX-BYTE-READ-SPAN
        SBOX-BYTE-S-OK = >R
        3 = SWAP _SBF-SOURCE-A 1+ = AND R> AND _SBF-ASSERT
    4 _SBF-READER-A SBOX-BYTE-SKIP
        SBOX-BYTE-S-OK = _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-OFFSET@ 7 = _SBF-ASSERT

    -1 _SBF-READER-A SBOX-BYTE-READ-SPAN
        SBOX-BYTE-S-INVALID = >R OR 0= R> AND _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-OFFSET@ 7 = _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-STATUS@
        SBOX-BYTE-S-INVALID = _SBF-ASSERT
    _SBF-STACK ;

: _SBF-READER-INTEGRITY-CONTRACTS  ( -- )
    _SBF-SOURCE-A 16 _SBF-READER-A SBOX-BYTE-READER-INIT
        SBOX-BYTE-S-OK = _SBF-ASSERT
    _SBF-READER-A _SBF-READER-COPY SBOX-BYTE-READER-SIZE MOVE
    _SBF-READER-COPY SBOX-BYTE-READER-VALID? 0= _SBF-ASSERT
    _SBF-READER-COPY SBOX-BYTE-READER-STATUS@
        SBOX-BYTE-S-INVALID = _SBF-ASSERT

    1 _SBF-READER-A 48 + !
    _SBF-READER-A SBOX-BYTE-READER-VALID? 0= _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READ-U8
        SBOX-BYTE-S-INVALID = SWAP 0= AND _SBF-ASSERT

    _SBF-SOURCE-A 16 _SBF-READER-A SBOX-BYTE-READER-INIT
        SBOX-BYTE-S-OK = _SBF-ASSERT
    _SBF-SOURCE-B 16 _SBF-READER-B SBOX-BYTE-READER-INIT
        SBOX-BYTE-S-OK = _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READ-U8
        SBOX-BYTE-S-OK = SWAP 0xAA = AND _SBF-ASSERT
    3 _SBF-READER-B SBOX-BYTE-SKIP
        SBOX-BYTE-S-OK = _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READ-U16-LE
        SBOX-BYTE-S-OK = SWAP 0x3401 = AND _SBF-ASSERT
    _SBF-READER-B SBOX-BYTE-READ-U8
        SBOX-BYTE-S-OK = SWAP 0x43 = AND _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-OFFSET@ 3 = _SBF-ASSERT
    _SBF-READER-B SBOX-BYTE-READER-OFFSET@ 4 = _SBF-ASSERT
    _SBF-STACK ;

: _SBF-RUN  ( -- )
    0 _SBF-FAILS !
    0 _SBF-CHECKS !
    DEPTH _SBF-DEPTH !
    ." SBOX FORMAT CONTRACTS START" CR
    _SBF-INIT-SOURCES
    _SBF-ARITHMETIC-CONTRACTS
    _SBF-SLICE-CONTRACTS
    _SBF-READER-INIT-CONTRACTS
    _SBF-READER-SCALAR-CONTRACTS
    _SBF-READER-INTEGRITY-CONTRACTS
    _SBF-STACK
    _SBF-FAILS @ 0= IF
        ." SBOX FORMAT CONTRACTS PASS " _SBF-CHECKS @ . CR
    ELSE
        ." SBOX FORMAT CONTRACTS FAIL " _SBF-FAILS @ . CR
    THEN ;

_SBF-RUN
