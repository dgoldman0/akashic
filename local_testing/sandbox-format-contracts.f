\ Deterministic contracts for the neutral sandbox byte/geometry substrate.

PROVIDED sbox-format-contracts

VARIABLE _SBF-FAILS
VARIABLE _SBF-CHECKS
VARIABLE _SBF-DEPTH
VARIABLE _SBF-BYTE
VARIABLE _SBF-EXPECTED-A
VARIABLE _SBF-EXPECTED-U

CREATE _SBF-SOURCE-A 32 ALLOT
CREATE _SBF-SOURCE-B 32 ALLOT
CREATE _SBF-READER-A SBOX-BYTE-READER-SIZE ALLOT
CREATE _SBF-READER-B SBOX-BYTE-READER-SIZE ALLOT
CREATE _SBF-READER-PROBE SBOX-BYTE-READER-SIZE ALLOT
CREATE _SBF-READER-COPY SBOX-BYTE-READER-SIZE ALLOT

: _SBF-ASSERT  ( flag -- )
    1 _SBF-CHECKS +!
    0= IF
        1 _SBF-FAILS +!
        ." SBOX FORMAT ASSERT " _SBF-CHECKS @ . CR
    THEN ;

: _SBF-STACK  ( -- )
    DEPTH DUP _SBF-DEPTH @ <> IF
        ." SBOX FORMAT STACK " _SBF-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _SBF-DEPTH @ = _SBF-ASSERT ;

: _SBF-FILLED?  ( address length byte -- flag )
    _SBF-BYTE !
    0 ?DO
        DUP I + C@ _SBF-BYTE @ <> IF DROP 0 UNLOOP EXIT THEN
    LOOP
    DROP -1 ;

: _SBF-INIT-SOURCES  ( -- )
    _SBF-SOURCE-A 32 0 FILL
    0xAA _SBF-SOURCE-A      C!
    0x01 _SBF-SOURCE-A  1 + C!
    0x34 _SBF-SOURCE-A  2 + C!
    0x12 _SBF-SOURCE-A  3 + C!
    0x78 _SBF-SOURCE-A  4 + C!
    0x56 _SBF-SOURCE-A  5 + C!
    0x34 _SBF-SOURCE-A  6 + C!
    0x12 _SBF-SOURCE-A  7 + C!
    0xEF _SBF-SOURCE-A  8 + C!
    0xCD _SBF-SOURCE-A  9 + C!
    0xAB _SBF-SOURCE-A 10 + C!
    0x89 _SBF-SOURCE-A 11 + C!
    0x67 _SBF-SOURCE-A 12 + C!
    0x45 _SBF-SOURCE-A 13 + C!
    0x23 _SBF-SOURCE-A 14 + C!
    0x01 _SBF-SOURCE-A 15 + C!
    32 0 ?DO I 0x40 + _SBF-SOURCE-B I + C! LOOP ;

: _SBF-ARITHMETIC-CONTRACTS  ( -- )
    SBOX-BYTE-S-OK SBOX-BYTE-STATUS-VALID? _SBF-ASSERT
    SBOX-BYTE-S-ALIAS SBOX-BYTE-STATUS-VALID? _SBF-ASSERT
    -1 SBOX-BYTE-STATUS-VALID? 0= _SBF-ASSERT
    4 SBOX-BYTE-STATUS-VALID? 0= _SBF-ASSERT
    SBOX-BYTE-LENGTH-MAX 0> _SBF-ASSERT

    0 0 SBOX-BYTE-LENGTH+
        SBOX-BYTE-S-OK = SWAP 0= AND _SBF-ASSERT
    SBOX-BYTE-LENGTH-MAX 0 SBOX-BYTE-LENGTH+
        SBOX-BYTE-S-OK = SWAP SBOX-BYTE-LENGTH-MAX = AND _SBF-ASSERT
    SBOX-BYTE-LENGTH-MAX 1- 1 SBOX-BYTE-LENGTH+
        SBOX-BYTE-S-OK = SWAP SBOX-BYTE-LENGTH-MAX = AND _SBF-ASSERT
    SBOX-BYTE-LENGTH-MAX 1 SBOX-BYTE-LENGTH+
        SBOX-BYTE-S-CAPACITY = SWAP 0= AND _SBF-ASSERT
    -1 0 SBOX-BYTE-LENGTH+
        SBOX-BYTE-S-INVALID = SWAP 0= AND _SBF-ASSERT
    0 -1 SBOX-BYTE-LENGTH+
        SBOX-BYTE-S-INVALID = SWAP 0= AND _SBF-ASSERT

    0 SBOX-BYTE-LENGTH-MAX SBOX-BYTE-LENGTH*
        SBOX-BYTE-S-OK = SWAP 0= AND _SBF-ASSERT
    3 4 SBOX-BYTE-LENGTH*
        SBOX-BYTE-S-OK = SWAP 12 = AND _SBF-ASSERT
    SBOX-BYTE-LENGTH-MAX 1 SBOX-BYTE-LENGTH*
        SBOX-BYTE-S-OK = SWAP SBOX-BYTE-LENGTH-MAX = AND _SBF-ASSERT
    SBOX-BYTE-LENGTH-MAX 2 / 1+ 2 SBOX-BYTE-LENGTH*
        SBOX-BYTE-S-CAPACITY = SWAP 0= AND _SBF-ASSERT
    2 -1 SBOX-BYTE-LENGTH*
        SBOX-BYTE-S-INVALID = SWAP 0= AND _SBF-ASSERT

    -1 SBOX-BYTE-PAD8
        SBOX-BYTE-S-INVALID = SWAP 0= AND _SBF-ASSERT
    0 SBOX-BYTE-PAD8
        SBOX-BYTE-S-OK = SWAP 0= AND _SBF-ASSERT
    1 SBOX-BYTE-PAD8
        SBOX-BYTE-S-OK = SWAP 8 = AND _SBF-ASSERT
    8 SBOX-BYTE-PAD8
        SBOX-BYTE-S-OK = SWAP 8 = AND _SBF-ASSERT
    SBOX-BYTE-LENGTH-MAX 7 - SBOX-BYTE-PAD8
        SBOX-BYTE-S-OK = SWAP SBOX-BYTE-LENGTH-MAX 7 - = AND _SBF-ASSERT
    SBOX-BYTE-LENGTH-MAX 6 - SBOX-BYTE-PAD8
        SBOX-BYTE-S-CAPACITY = SWAP 0= AND _SBF-ASSERT
    9 SBOX-BYTE-CEIL8
        SBOX-BYTE-S-OK = SWAP 2 = AND _SBF-ASSERT
    15 16 SBOX-BYTE-ALIGN
        SBOX-BYTE-S-OK = SWAP 16 = AND _SBF-ASSERT
    16 SBOX-BYTE-PAD16
        SBOX-BYTE-S-OK = SWAP 16 = AND _SBF-ASSERT
    17 SBOX-BYTE-PAD16
        SBOX-BYTE-S-OK = SWAP 32 = AND _SBF-ASSERT
    SBOX-BYTE-LENGTH-MAX 15 - SBOX-BYTE-PAD16
        SBOX-BYTE-S-OK =
        SWAP SBOX-BYTE-LENGTH-MAX 15 - = AND _SBF-ASSERT
    SBOX-BYTE-LENGTH-MAX 14 - SBOX-BYTE-PAD16
        SBOX-BYTE-S-CAPACITY = SWAP 0= AND _SBF-ASSERT
    7 0 SBOX-BYTE-ALIGN
        SBOX-BYTE-S-INVALID = SWAP 0= AND _SBF-ASSERT
    7 3 SBOX-BYTE-ALIGN
        SBOX-BYTE-S-INVALID = SWAP 0= AND _SBF-ASSERT
    7 -8 SBOX-BYTE-ALIGN
        SBOX-BYTE-S-INVALID = SWAP 0= AND _SBF-ASSERT
    _SBF-STACK ;

: _SBF-SLICE-OK?  ( source source-u offset length expected -- flag )
    _SBF-EXPECTED-A !
    DUP _SBF-EXPECTED-U !
    SBOX-BYTE-SLICE
    SBOX-BYTE-S-OK = >R
    _SBF-EXPECTED-U @ =
    SWAP _SBF-EXPECTED-A @ = AND
    R> AND ;

: _SBF-SLICE-FAIL?  ( source source-u offset length expected-status -- flag )
    >R SBOX-BYTE-SLICE
    R> = >R
    OR 0= R> AND ;

: _SBF-SLICE-CONTRACTS  ( -- )
    _SBF-SOURCE-A 32 4 8 _SBF-SOURCE-A 4 +
        _SBF-SLICE-OK? _SBF-ASSERT
    _SBF-SOURCE-A 32 32 0 _SBF-SOURCE-A 32 +
        _SBF-SLICE-OK? _SBF-ASSERT
    0 0 0 0 0 _SBF-SLICE-OK? _SBF-ASSERT

    _SBF-SOURCE-A 32 33 0 SBOX-BYTE-S-CAPACITY
        _SBF-SLICE-FAIL? _SBF-ASSERT
    _SBF-SOURCE-A 32 31 2 SBOX-BYTE-S-CAPACITY
        _SBF-SLICE-FAIL? _SBF-ASSERT
    _SBF-SOURCE-A 32 -1 0 SBOX-BYTE-S-INVALID
        _SBF-SLICE-FAIL? _SBF-ASSERT
    _SBF-SOURCE-A 32 0 -1 SBOX-BYTE-S-INVALID
        _SBF-SLICE-FAIL? _SBF-ASSERT
    0 1 0 0 SBOX-BYTE-S-INVALID
        _SBF-SLICE-FAIL? _SBF-ASSERT
    -8 16 0 0 SBOX-BYTE-S-INVALID
        _SBF-SLICE-FAIL? _SBF-ASSERT
    _SBF-SOURCE-A -1 0 0 SBOX-BYTE-S-INVALID
        _SBF-SLICE-FAIL? _SBF-ASSERT
    _SBF-STACK ;

: _SBF-READER-INIT-CONTRACTS  ( -- )
    SBOX-BYTE-READER-SIZE 56 = _SBF-ASSERT

    _SBF-READER-PROBE SBOX-BYTE-READER-SIZE 0xA5 FILL
    0 1 _SBF-READER-PROBE SBOX-BYTE-READER-INIT
        SBOX-BYTE-S-INVALID = _SBF-ASSERT
    _SBF-READER-PROBE SBOX-BYTE-READER-SIZE 0xA5
        _SBF-FILLED? _SBF-ASSERT

    _SBF-READER-PROBE SBOX-BYTE-READER-SIZE 0xA5 FILL
    _SBF-READER-PROBE 1 _SBF-READER-PROBE SBOX-BYTE-READER-INIT
        SBOX-BYTE-S-ALIAS = _SBF-ASSERT
    _SBF-READER-PROBE SBOX-BYTE-READER-SIZE 0xA5
        _SBF-FILLED? _SBF-ASSERT

    _SBF-SOURCE-A 15 _SBF-READER-A SBOX-BYTE-READER-INIT
        SBOX-BYTE-S-OK = _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-VALID? _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-OFFSET@ 0= _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-REMAINING@ 15 = _SBF-ASSERT
    _SBF-READER-A SBOX-BYTE-READER-AT-END? 0= _SBF-ASSERT

    0 0 _SBF-READER-B SBOX-BYTE-READER-INIT
        SBOX-BYTE-S-OK = _SBF-ASSERT
    _SBF-READER-B SBOX-BYTE-READER-VALID? _SBF-ASSERT
    _SBF-READER-B SBOX-BYTE-READER-AT-END? _SBF-ASSERT
    _SBF-READER-B SBOX-BYTE-READ-U8
        SBOX-BYTE-S-CAPACITY = SWAP 0= AND _SBF-ASSERT
    _SBF-READER-B SBOX-BYTE-READER-OFFSET@ 0= _SBF-ASSERT

    0 SBOX-BYTE-READER-VALID? 0= _SBF-ASSERT
    0 SBOX-BYTE-READER-RESET
        SBOX-BYTE-S-INVALID = _SBF-ASSERT
    0 SBOX-BYTE-READER-STATUS@
        SBOX-BYTE-S-INVALID = _SBF-ASSERT
    _SBF-STACK ;

