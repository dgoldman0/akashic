: _GC-STATE  ( run-state instance -- )
    >R
    _GC-MIX
    R@ _SVI.USAGE @ _GC-MIX
    R@ _SVI.IP @ _GC-MIX
    R@ _SVI.CURRENT-FUNCTION @ _GC-MIX
    R@ _SVI.OPERAND-N @ DUP _GC-MIX
    0> IF 0 R@ _SVM-TOP@ _GC-MIX THEN
    R@ _SVI.CALL-N @ _GC-MIX
    R@ _SVI.LOOP-N @ _GC-MIX
    R@ _SVI.VALUE-OPS-USAGE @ _GC-MIX
    R@ _SVI.COPY-USAGE @ _GC-MIX
    R> DROP ;

