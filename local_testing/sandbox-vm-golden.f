\ ---------------------------------------------------------------------
\ Group bracketing
\ ---------------------------------------------------------------------

: _GC-GROUP-BEGIN  ( -- )
    _GC-BUFFERS
    100000 _GC-FULL !
    0 _GC-FAILS !
    0 _GC-CASES !
    0 _GC-RECORDED !
    DEPTH _GC-DEPTH !
    _GC-QUAL _GC-LOAD SBOX-QUALIFICATION-INIT
        SBOX-PROFILE-S-OK <> IF 1 _GC-FAILS +! THEN
    _GC-PURE _GC-LOAD SBOX-PROFILE-PURE-INIT
        SBOX-PROFILE-S-OK <> IF 1 _GC-FAILS +! THEN ;

: _GC-GROUP-END  ( name name-u -- )
    DEPTH 2 - _GC-DEPTH @ <> IF
        ." SBOX GOLDEN STACK " .S CR 1 _GC-FAILS +!
    THEN
    ." SBOX GOLDEN " TYPE SPACE
    _GC-FAILS @ IF
        ." FAIL " _GC-FAILS @ .
    ELSE
        _GC-RECORDED @ IF
            ." RECORDED " _GC-RECORDED @ .
        ELSE
            ." PASS " _GC-CASES @ .
        THEN
    THEN
    CR TX-FLUSH ;

