\ Frozen golden corpus for the sandbox VM.
\
\ Each case builds one module and runs it many ways, folding every
\ observable step into one FNV-1a 64 digest: a single-step trace, slices of
\ seven and unbounded, an instruction-budget sweep, and stack, call-frame,
\ loop-frame, value-operation, copy and output limit sweeps.  A step folds
\ the run state, the instruction units used, the instruction pointer and
\ function, the operand, call and loop depths and the top operand; a
\ finished run folds every status and the complete result record.
\
\ The expected digests were recorded from the VM as it stood before its
\ performance pass.  They are fixed: the VM must reproduce them exactly.

PROVIDED sbox-vm-golden

