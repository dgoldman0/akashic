: _GC-VALUE-BUILD  ( -- ok? )
    _GC-BUILD SBOX-BUILD-SIZE 0 FILL
    _GC-BUILD SBOX-BUILD-INIT _GC-MIX
    _GC-SRC @ _GC-SRC-U @ _GC-PURE _GC-MEM @ _GC-BUILD SBOX-BUILD
    DUP _GC-MIX IF 0 EXIT THEN
    _GC-BUILD SBOX-BUILD-PLAN@
    DUP _GC-MIX IF DROP 0 EXIT THEN
    _GC-VPLAN !
