VARIABLE _GC-H

: _GC-RESET  ( -- )
    0x4BF29CE484222325 1 63 LSHIFT OR _GC-H ! ;

: _GC-BYTE  ( byte -- )
    _GC-H @ XOR 0x100000001B3 * _GC-H ! ;

: _GC-MIX  ( u -- )
    8 0 DO DUP 0xFF AND _GC-BYTE 8 RSHIFT LOOP DROP ;

: _GC-MIX-BYTES  ( address length -- )
    0 ?DO DUP I + C@ _GC-BYTE LOOP DROP ;

\ An unrecorded case (expected 0) prints its digest for recording.
: _GC-CHECK  ( expected name name-u -- )
    DEPTH 3 - _GC-CASE-DEPTH @ - >R
    ." SBOX GOLDEN " TYPE SPACE _GC-H @ .
    _GC-BUILT @ 0= IF ." BUILD-FAILED " THEN
    R@ IF ." STACK-LEAK " R@ . 1 _GC-FAILS +! THEN
    R> DROP
    1 _GC-CASES +!
    DUP 0= IF
        DROP ." RECORD" 1 _GC-RECORDED +!
    ELSE
        _GC-H @ = IF
            ." ok"
        ELSE
            ." MISMATCH" 1 _GC-FAILS +!
        THEN
    THEN
    CR TX-FLUSH ;

