: _GC-INPUTS!  ( x1 .. xn n -- )
    DUP _GC-INPUT-N !
    0 ?DO
        _GC-INPUT-N @ 1- I - CELLS _GC-INPUT + !
    LOOP ;

\ Compile, verify and bind the current source; every status is folded.
: _GC-SCALAR-BUILD  ( -- ok? )
    _GC-SRC @ _GC-SRC-U @ SBOX-COMPILER-WORKSPACE-MEASURE
    DUP _GC-MIX IF DROP 0 EXIT THEN
    _GC-COMPILER-CAP > IF 0 EXIT THEN
    _GC-SRC @ _GC-SRC-U @ _GC-QUAL _GC-MEM @
    _GC-ARTIFACT _GC-ARTIFACT-CAP _GC-COMPILER-WORK SBOX-COMPILE
    DUP _GC-MIX
    SWAP _GC-ARTIFACT-U !
    IF 0 EXIT THEN
    _GC-ARTIFACT-U @ SBOX-PLAN-MEASURE
    DUP _GC-MIX IF DROP 0 EXIT THEN
    DUP _GC-PLAN-CAP > IF DROP 0 EXIT THEN
    _GC-PLAN-U !
    _GC-ARTIFACT _GC-ARTIFACT-U @ SBOX-VERIFIER-WORKSPACE-MEASURE
    DUP _GC-MIX IF DROP 0 EXIT THEN
    _GC-VERIFIER-CAP > IF 0 EXIT THEN
    _GC-ARTIFACT _GC-ARTIFACT-U @ _GC-QUAL
    _GC-PLAN _GC-PLAN-U @ _GC-VERIFIER-WORK SBOX-VERIFY
    DUP _GC-MIX IF 0 EXIT THEN
    _GC-PLAN _GC-BINDING SBOX-BINDING-PURE-INIT
    DUP _GC-MIX 0= ;

: _GC-SCALAR-RELEASE  ( -- )
    _GC-BINDING SBOX-BINDING-RELEASE DROP
    _GC-PLAN SBOX-PLAN-RELEASE DROP ;

: _GC-SCALAR-INIT  ( budget -- status )
    _GC-LIMITS!
    _GC-PLAN _GC-LIMITS SBOX-VM-INSTANCE-MEASURE
    ?DUP IF NIP EXIT THEN
    DUP _GC-INSTANCE-CAP > IF DROP SBOX-VM-S-CAPACITY EXIT THEN
    _GC-INSTANCE-U !
    _GC-INSTANCE _GC-INSTANCE-U @ 0xA5 FILL
    _GC-PLAN _GC-BINDING 0 _GC-INPUT _GC-INPUT-N @
    _GC-LIMITS _GC-INSTANCE _GC-INSTANCE-U @
    _SVM-SCALAR-INIT ;

: _GC-SCALAR-FINISH  ( -- )
    _GC-RESULT _SVM-SCALAR-RESULT-SIZE 0xA5 FILL
    _GC-RESULT _GC-INSTANCE _SVM-SCALAR-FINISH _GC-MIX
    _GC-RESULT _SVM-SCALAR-RESULT-CLASS@ _GC-MIX
    _GC-RESULT _SVM-SCALAR-RESULT-DETAIL@ _GC-MIX
    _GC-RESULT _SVM-SCALAR-RESULT-AUX@ _GC-MIX
    _GC-RESULT _SVM-SCALAR-RESULT-USAGE@ DUP _GC-USAGE ! _GC-MIX
    _GC-RESULT _SVM-SCALAR-RESULT-COUNT@ DUP _GC-MIX
    0 ?DO
        I _GC-RESULT _SVM-SCALAR-RESULT-CELL@ _GC-MIX _GC-MIX
    LOOP
    _GC-RESULT _SVM-SCALAR-RESULT-RELEASE _GC-MIX
    _GC-INSTANCE SBOX-VM-RELEASE _GC-MIX ;

: _GC-SCALAR-TRACE  ( budget -- )
    _GC-SCALAR-INIT DUP _GC-MIX IF EXIT THEN
    0 _GC-STEPS !
    BEGIN
        _GC-INSTANCE SBOX-VM-STEP
        DUP _GC-INSTANCE _GC-STATE
        1 _GC-STEPS +!
        SBOX-VM-RUN-RUNNABLE <>
    UNTIL
    _GC-STEPS @ _GC-MIX
    _GC-SCALAR-FINISH ;

: _GC-SCALAR-SLICED  ( slice budget -- )
    _GC-SCALAR-INIT DUP _GC-MIX IF DROP EXIT THEN
    BEGIN
        DUP _GC-INSTANCE SBOX-VM-RUN-SLICE
        DUP _GC-INSTANCE _GC-STATE
        SBOX-VM-RUN-RUNNABLE <>
    UNTIL
    DROP
    _GC-SCALAR-FINISH ;

: _GC-SCALAR-RUN  ( budget -- ) _GC-UNBOUNDED SWAP _GC-SCALAR-SLICED ;

\ Every budget from 1 to just past the full run's usage, up to 48, then
\ the budgets around the usage of a longer run.
: _GC-SCALAR-BUDGETS  ( usage -- )
    DUP 1+ 48 MIN 1+ 1 ?DO I _GC-SCALAR-RUN LOOP
    DUP 48 > IF
        DUP 1- _GC-SCALAR-RUN
        DUP _GC-SCALAR-RUN
        DUP 1+ _GC-SCALAR-RUN
    THEN
    DROP ;

: _GC-SCALAR-LIMITS  ( budget -- )
    7 1 DO I _GC-STACK-LIMIT ! DUP _GC-SCALAR-RUN LOOP
    _GC-LIMITS-DEFAULT
    5 1 DO I _GC-CALL-LIMIT ! DUP _GC-SCALAR-RUN LOOP
    _GC-LIMITS-DEFAULT
    4 0 DO I _GC-LOOP-LIMIT ! DUP _GC-SCALAR-RUN LOOP
    _GC-LIMITS-DEFAULT
    DROP ;

\ CASE: build the module, then run every variant.
: _GC-SCALAR-CASE  ( source source-u memory-u expected name name-u -- )
    DEPTH 6 - _GC-CASE-DEPTH !
    2>R >R
    _GC-MEM ! _GC-SRC-U ! _GC-SRC !
    _GC-RESET
    _GC-LIMITS-DEFAULT
    _GC-SCALAR-BUILD DUP _GC-BUILT ! IF
        _GC-FULL @ _GC-SCALAR-TRACE
        _GC-USAGE @
        7 _GC-FULL @ _GC-SCALAR-SLICED
        _GC-FULL @ _GC-SCALAR-RUN
        _GC-SCALAR-BUDGETS
        _GC-FULL @ _GC-SCALAR-LIMITS
        _GC-SCALAR-RELEASE
    THEN
    100000 _GC-FULL !
    R> 2R> _GC-CHECK ;

