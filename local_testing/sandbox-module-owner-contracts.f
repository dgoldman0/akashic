        _SMOC-ENTRY1 _SDCL-E-INPUT-STORAGE + C!
    SBOX-DECL-SCHEMA-REFERENCED
        _SMOC-ENTRY1 _SDCL-E-OUTPUT-STORAGE + C!
    S" shared" _SMOC-ENTRY1 _SDCL-E-NAME + SWAP MOVE
    64 _SMOC-ENTRY1 _SDCL-E-INPUT-U + _SMOC-U64!
    64 _SMOC-ENTRY1 _SDCL-E-OUTPUT-U + _SMOC-U64!
    _SMOC-SCHEMA-DIGEST
        _SMOC-ENTRY1 _SDCL-E-INPUT-DIGEST +
