: _SMOC-ASSERT  ( flag -- )
    1 _SMOC-CHECKS +!
    0= IF
        1 _SMOC-FAILS +!
        ." SBOX MODULE OWNER ASSERT " _SMOC-CHECKS @ . CR
    THEN ;

: _SMOC-IS  ( status expected -- ) = _SMOC-ASSERT ;

: _SMOC-STACK  ( -- )
    DEPTH DUP _SMOC-DEPTH @ <> IF
        ." SBOX MODULE OWNER STACK "
        _SMOC-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _SMOC-DEPTH @ = _SMOC-ASSERT ;

\ Module N's name: "m" and three digits.
: _SMOC-NAME  ( n -- name name-u )
    [CHAR] m _SMOC-NAME-BUF C!
    DUP 100 / 10 MOD [CHAR] 0 + _SMOC-NAME-BUF 1+ C!
    DUP 10 / 10 MOD [CHAR] 0 + _SMOC-NAME-BUF 2 + C!
    10 MOD [CHAR] 0 + _SMOC-NAME-BUF 3 + C!
    _SMOC-NAME-BUF 4 ;

\ Module N's RID, the digest of its name.
: _SMOC-RID!  ( n -- rid )
    _SMOC-NAME _SMOC-RID _SMOC-DECL-WS SBOX-DECL-MODULE-RID
        SBOX-DECL-S-OK _SMOC-IS
    _SMOC-RID ;

: _SMOC-SOURCE  ( -- address length )
    S" FUNCTION echo PARAMS 1 RESULTS 1 LOCALS 0 DUP V.TYPE DROP RETURN END ENTRY SIGNATURE 1 main echo" ;

\ Builds the echo module into the build record, and keeps a copy of its
\ artifact and the artifact's digest.
: _SMOC-BUILD!  ( -- )
    _SMOC-SOURCE _SMOC-PROFILE 0 _SMOC-BUILD SBOX-BUILD
        SBOX-BUILD-S-OK _SMOC-IS
    _SMOC-BUILD SBOX-BUILD-PLAN@ SBOX-BUILD-S-OK _SMOC-IS
    DUP SBOX-PLAN-ARTIFACT-DIGEST@ _SMOC-ARTIFACT-DIGEST 32 MOVE
    SBOX-PLAN-ARTIFACT$ DUP _SMOC-ARTIFACT-U !
    _SMOC-ARTIFACT SWAP MOVE ;

\ A declaration naming one entry, _SMOC-ENTRY-A with _SMOC-SIG, the
\ artifact digest in _SMOC-ARTIFACT-DIGEST and the profile digest in
\ _SMOC-PDIGEST.
: _SMOC-DECLARE  ( n revision -- declaration declaration-u )
    1 0 24 SBOX-DECL-MEASURE SBOX-DECL-S-OK _SMOC-IS _SMOC-DECL-U !
    _SMOC-ARTIFACT-DIGEST _SMOC-PDIGEST @ 1 0 24
        _SMOC-DECL _SMOC-DECL-U @ SBOX-DECL-START SBOX-DECL-S-OK _SMOC-IS
    _SMOC-NAME _SMOC-DECL-WS _SMOC-DECL SBOX-DECL-MODULE! SBOX-DECL-S-OK _SMOC-IS
    0 _SMOC-ENTRY-A @ _SMOC-ENTRY-U @ _SMOC-SIG @ _SMOC-DECL
        SBOX-DECL-ENTRY! SBOX-DECL-S-OK _SMOC-IS
    0 _SMOC-SCHEMA 12 _SMOC-SCHEMA 12 _SMOC-DECL-WS _SMOC-DECL
        SBOX-DECL-SCHEMAS! SBOX-DECL-S-OK _SMOC-IS
    _SMOC-DECL _SMOC-DECL-U @ ;

\ The same with a second entry, "other".
: _SMOC-DECLARE2  ( n revision -- declaration declaration-u )
    2 0 48 SBOX-DECL-MEASURE SBOX-DECL-S-OK _SMOC-IS _SMOC-DECL-U !
    _SMOC-ARTIFACT-DIGEST _SMOC-PDIGEST @ 2 0 48
        _SMOC-DECL _SMOC-DECL-U @ SBOX-DECL-START SBOX-DECL-S-OK _SMOC-IS
    _SMOC-NAME _SMOC-DECL-WS _SMOC-DECL SBOX-DECL-MODULE! SBOX-DECL-S-OK _SMOC-IS
    0 S" main" 1 _SMOC-DECL SBOX-DECL-ENTRY! SBOX-DECL-S-OK _SMOC-IS
    1 S" other" 1 _SMOC-DECL SBOX-DECL-ENTRY! SBOX-DECL-S-OK _SMOC-IS
    0 _SMOC-SCHEMA 12 _SMOC-SCHEMA 12 _SMOC-DECL-WS _SMOC-DECL
        SBOX-DECL-SCHEMAS! SBOX-DECL-S-OK _SMOC-IS
    1 _SMOC-SCHEMA 12 _SMOC-SCHEMA 12 _SMOC-DECL-WS _SMOC-DECL
        SBOX-DECL-SCHEMAS! SBOX-DECL-S-OK _SMOC-IS
    _SMOC-DECL _SMOC-DECL-U @ ;

: _SMOC-ENTRY!  ( name name-u signature -- )
    _SMOC-SIG ! _SMOC-ENTRY-U ! _SMOC-ENTRY-A ! ;

\ The key at INDEX comes before the next one: RID bytes, then revision.
: _SMOC-KEY<  ( index owner -- flag )
    2DUP SBOX-MODULE-NTH SBOX-MODULE-KEY@ _SMOC-V1 ! _SMOC-K1 !
    SWAP 1+ SWAP SBOX-MODULE-NTH SBOX-MODULE-KEY@
    SWAP _SMOC-K1 @ 32 ROT 32 COMPARE
    ?DUP IF NIP 0< EXIT THEN
    _SMOC-V1 @ > ;

: _SMOC-SETUP  ( -- )
    S" AKSCHEMA" _SMOC-SCHEMA SWAP MOVE
    _SMOC-SCHEMA 8 + 4 0 FILL
    4 _SMOC-SCHEMA 8 + C!
    _SMOC-PROFILE _SMOC-LOAD SBOX-PROFILE-PURE-INIT
        SBOX-PROFILE-S-OK _SMOC-IS
    _SMOC-PROFILE SBOX-PROFILE-DIGEST@ _SMOC-PDIGEST !
    _SMOC-BUILD SBOX-BUILD-SIZE 0 FILL
    _SMOC-BUILD SBOX-BUILD-INIT SBOX-BUILD-S-OK _SMOC-IS
    S" main" 1 _SMOC-ENTRY!
    _SMOC-OWNER SBOX-MODULE-OWNER-SIZE 0 FILL
    _SMOC-OWNER2 SBOX-MODULE-OWNER-SIZE 0 FILL ;

