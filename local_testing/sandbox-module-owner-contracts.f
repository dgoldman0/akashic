\ Focused structural/lifecycle contracts for the installed sandbox module
\ owner.  Exact plan registration is exercised with the host vertical after
\ that layer exists; these checks keep the owner measurement and cleanup
\ boundary independently buildable.

PROVIDED sbox-mod-owner-tests

VARIABLE _SMOC-FAILS
VARIABLE _SMOC-CHECKS
VARIABLE _SMOC-DEPTH
VARIABLE _SMOC-BYTE

: _SMOC-ALIGN8  ( address -- aligned-address ) 7 + -8 AND ;

2 SBOX-MODULE-OWNER-MEASURE
DROP CONSTANT _SMOC-OWNER-U

CREATE _SMOC-OWNER-RAW _SMOC-OWNER-U 7 + ALLOT
_SMOC-OWNER-RAW _SMOC-ALIGN8 CONSTANT _SMOC-OWNER

: _SMOC-ASSERT  ( flag -- )
    1 _SMOC-CHECKS +!
    0= IF
        1 _SMOC-FAILS +!
        ." SBOX MODULE OWNER ASSERT " _SMOC-CHECKS @ . CR
    THEN ;

: _SMOC-STACK  ( -- )
    DEPTH DUP _SMOC-DEPTH @ <> IF
        ." SBOX MODULE OWNER STACK "
        _SMOC-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _SMOC-DEPTH @ = _SMOC-ASSERT ;

: _SMOC-FILLED?  ( address length byte -- flag )
    _SMOC-BYTE !
    0 ?DO
        DUP I + C@ _SMOC-BYTE @ <> IF
            DROP 0 UNLOOP EXIT
        THEN
    LOOP
    DROP -1 ;

: _SMOC-RUN  ( -- )
    DEPTH _SMOC-DEPTH !
    0 _SMOC-FAILS !
    0 _SMOC-CHECKS !

    2 SBOX-MODULE-OWNER-MEASURE
        SBOX-MODULE-OWNER-S-OK =
        SWAP _SMOC-OWNER-U = AND _SMOC-ASSERT
    0 SBOX-MODULE-OWNER-MEASURE
        SBOX-MODULE-OWNER-S-INVALID =
        SWAP 0= AND _SMOC-ASSERT
    SBOX-MODULE-OWNER-CAPACITY-MAX 1+
        SBOX-MODULE-OWNER-MEASURE
        SBOX-MODULE-OWNER-S-CAPACITY =
        SWAP 0= AND _SMOC-ASSERT

    _SMOC-OWNER _SMOC-OWNER-U 0xA5 FILL
    2 _SMOC-OWNER _SMOC-OWNER-U 8 -
        SBOX-MODULE-OWNER-INIT
        SBOX-MODULE-OWNER-S-CAPACITY = _SMOC-ASSERT
    _SMOC-OWNER _SMOC-OWNER-U 0xA5
        _SMOC-FILLED? _SMOC-ASSERT

    2 _SMOC-OWNER _SMOC-OWNER-U SBOX-MODULE-OWNER-INIT
        SBOX-MODULE-OWNER-S-OK = _SMOC-ASSERT
    _SMOC-OWNER SBOX-MODULE-OWNER-VALID? _SMOC-ASSERT
    _SMOC-OWNER SBOX-MODULE-OWNER-COUNT@ 0= _SMOC-ASSERT

    _SMOC-OWNER SBOX-MODULE-OWNER-SEAL
        SBOX-MODULE-OWNER-S-INVALID = _SMOC-ASSERT
    _SMOC-OWNER SBOX-MODULE-OWNER-VALID? _SMOC-ASSERT

    _SMOC-OWNER SBOX-MODULE-OWNER-RELEASE
        SBOX-MODULE-OWNER-S-OK = _SMOC-ASSERT
    _SMOC-OWNER _SMOC-OWNER-U 0 _SMOC-FILLED? _SMOC-ASSERT
    _SMOC-OWNER SBOX-MODULE-OWNER-RELEASE
        SBOX-MODULE-OWNER-S-OK = _SMOC-ASSERT

    _SMOC-STACK
    _SMOC-FAILS @ IF
        ." SBOX MODULE OWNER CONTRACTS FAIL "
        _SMOC-FAILS @ . ." / " _SMOC-CHECKS @ . CR
    ELSE
        ." SBOX MODULE OWNER CONTRACTS PASS "
        _SMOC-CHECKS @ . CR
    THEN ;

_SMOC-RUN
