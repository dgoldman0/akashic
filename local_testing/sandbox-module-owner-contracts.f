: _SMOC-PROFILE-ID$  ( -- address length )
    S" org.akashic.sandbox.pure-compute" ;

: _SMOC-PROFILE-DESCRIPTOR$  ( -- address length )
    S" exact owner contract profile descriptor" ;

: _SMOC-SOURCE$  ( -- address length )
    S" FUNCTION pass PARAMS 1 RESULTS 1 LOCALS 0 RETURN END ENTRY alpha pass ENTRY shared pass" ;

: _SMOC-ASSERT  ( flag -- )
    1 _SMOC-CHECKS +!
    0= IF
        1 _SMOC-FAILS +!
        ." SBOX MODULE OWNER ASSERT " _SMOC-CHECKS @ . CR
    THEN ;

: _SMOC-STACK  ( -- )
    DEPTH DUP _SMOC-DEPTH @ <> IF
        ." SBOX MODULE OWNER STACK "
        _SMOC-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _SMOC-DEPTH @ = _SMOC-ASSERT ;

: _SMOC-U16!  ( value address -- )
    >R
    DUP R@ C!
    8 RSHIFT R> 1+ C! ;

: _SMOC-U32!  ( value address -- )
    >R
    DUP R@ _SMOC-U16!
    16 RSHIFT R> 2 + _SMOC-U16! ;

: _SMOC-U64!  ( value address -- )
    >R
    DUP R@ _SMOC-U32!
    32 RSHIFT R> 4 + _SMOC-U32! ;

: _SMOC-FILL32  ( byte address -- )
    SWAP RID-SIZE SWAP FILL ;

: _SMOC-ID$  ( -- address length )
    S" akashic-rt-sbx-owner" ;

: _SMOC-LOADER-ID-CONTRACT  ( -- )
    _SMOC-ID$ NIP DUP 1 >= SWAP 23 <= AND _SMOC-ASSERT
    _SMOC-ID$ S" akashic-rt-sbx-decl" COMPARE 0<> _SMOC-ASSERT
    _SMOC-ID$ S" akashic-rt-sbx-schema" COMPARE 0<> _SMOC-ASSERT
    _SMOC-ID$ S" akashic-rt-sbx-pbind" COMPARE 0<> _SMOC-ASSERT ;

: _SMOC-BUILD-SCHEMA  ( -- )
    _SMOC-SCHEMA 64 0 FILL
    SBOX-SCHEMA-DOCUMENT-MAGIC _SMOC-SCHEMA _SMOC-U64!
    SBOX-SCHEMA-DOCUMENT-VERSION _SMOC-SCHEMA 8 + _SMOC-U16!
    1 _SMOC-SCHEMA 12 + _SMOC-U32!
    1 _SMOC-SCHEMA 16 + _SMOC-U32!
    64 _SMOC-SCHEMA 24 + _SMOC-U64!
    SBOX-SCHEMA-T-NULL _SMOC-SCHEMA 32 + C!
    _SMOC-SCHEMA 64
    _SMOC-SCHEMA-DIGEST _SMOC-DIGEST-WORK
    SBOX-DIGEST-SCHEMA SBOX-DIGEST-S-OK = _SMOC-ASSERT ;

: _SMOC-BUILD-PROFILE  ( -- )
    _SMOC-PROFILE SBOX-PROFILE-PURE-INIT
        SBOX-PROFILE-S-OK = _SMOC-ASSERT
    _SMOC-PROFILE-DESCRIPTOR$
    _SMOC-PROFILE-DIGEST _SMOC-DIGEST-WORK
    SBOX-DIGEST-PROFILE SBOX-DIGEST-S-OK = _SMOC-ASSERT ;

: _SMOC-BUILD-ARTIFACT  ( -- )
    _SMOC-SOURCE$
    _SMOC-PROFILE
    64
    _SMOC-ARTIFACT _SMOC-ARTIFACT-CAP
    _SMOC-COMPILER-WORK
    SBOX-COMPILE
    SBOX-COMPILER-S-OK = _SMOC-ASSERT
    DUP 0> _SMOC-ASSERT
    _SMOC-ARTIFACT-U !
    _SMOC-ARTIFACT _SMOC-ARTIFACT-U @
    _SMOC-ARTIFACT-DIGEST _SMOC-DIGEST-WORK
    SBOX-DIGEST-ARTIFACT SBOX-DIGEST-S-OK = _SMOC-ASSERT ;

: _SMOC-ENTRY0  ( -- entry )
    _SMOC-ENTRIES @ ;

: _SMOC-ENTRY1  ( -- entry )
    _SMOC-ENTRIES @ SBOX-DECL-ENTRY-SIZE + ;

: _SMOC-WRITE-HEADER  ( -- )
    _SDECL-WIRE-MAGIC
        _SMOC-CURRENT-DECL @ _SDCL-H-MAGIC + _SMOC-U64!
    SBOX-DECL-FORMAT-V1
        _SMOC-CURRENT-DECL @ _SDCL-H-FORMAT + _SMOC-U16!
    SBOX-DECL-HEADER-SIZE
        _SMOC-CURRENT-DECL @ _SDCL-H-HEADER-U + _SMOC-U16!
    _SMOC-DECL-U @
        _SMOC-CURRENT-DECL @ _SDCL-H-TOTAL-U + _SMOC-U64!
    2 _SMOC-CURRENT-DECL @ _SDCL-H-ENTRY-N + _SMOC-U32!
    0 _SMOC-CURRENT-DECL @ _SDCL-H-CEILING-N + _SMOC-U16!
    _SMOC-PROFILE-ID$ NIP
        _SMOC-CURRENT-DECL @ _SDCL-H-PROFILE-ID-U + _SMOC-U16!
    SBOX-DECL-PROVENANCE-NONE
        _SMOC-CURRENT-DECL @ _SDCL-H-PROVENANCE-KIND + _SMOC-U16!
    128 _SMOC-CURRENT-DECL @ _SDCL-H-SCHEMA-U + _SMOC-U64!
    _SMOC-OWNER-RID
        _SMOC-CURRENT-DECL @ _SDCL-H-OWNER-RID + RID-COPY
    _SMOC-CURRENT-MODULE @
        _SMOC-CURRENT-DECL @ _SDCL-H-MODULE-RID + RID-COPY
    _SMOC-CURRENT-REVISION @
        _SMOC-CURRENT-DECL @ _SDCL-H-MODULE-REVISION + _SMOC-U64!
    _SMOC-ARTIFACT-DIGEST
        _SMOC-CURRENT-DECL @ _SDCL-H-ARTIFACT-DIGEST +
        SBOX-DIGEST-SIZE MOVE
    _SMOC-PROFILE-DIGEST
        _SMOC-CURRENT-DECL @ _SDCL-H-PROFILE-DIGEST +
        SBOX-DIGEST-SIZE MOVE ;

: _SMOC-WRITE-ENTRY0  ( -- )
    5 _SMOC-ENTRY0 _SDCL-E-NAME-U + _SMOC-U16!
    SBOX-DECL-SIGNATURE-PURE-VALUE
        _SMOC-ENTRY0 _SDCL-E-SIGNATURE + _SMOC-U16!
    SBOX-DECL-SCHEMA-EMBEDDED
        _SMOC-ENTRY0 _SDCL-E-INPUT-STORAGE + C!
    SBOX-DECL-SCHEMA-EMBEDDED
        _SMOC-ENTRY0 _SDCL-E-OUTPUT-STORAGE + C!
    S" alpha" _SMOC-ENTRY0 _SDCL-E-NAME + SWAP MOVE
    64 _SMOC-ENTRY0 _SDCL-E-INPUT-U + _SMOC-U64!
    0 _SMOC-ENTRY0 _SDCL-E-INPUT-OFFSET + _SMOC-U64!
    64 _SMOC-ENTRY0 _SDCL-E-OUTPUT-U + _SMOC-U64!
    64 _SMOC-ENTRY0 _SDCL-E-OUTPUT-OFFSET + _SMOC-U64!
    _SMOC-SCHEMA-DIGEST
        _SMOC-ENTRY0 _SDCL-E-INPUT-DIGEST +
