: _SMOC-INIT  ( -- )
    _SMOC-PROFILE 0 SBOX-MODULE-OWNER-INIT SBOX-MODULE-S-INVALID _SMOC-IS
    _SMOC-PROFILE _SMOC-OWNER 1+ SBOX-MODULE-OWNER-INIT
        SBOX-MODULE-S-INVALID _SMOC-IS
