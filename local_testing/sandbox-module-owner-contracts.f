    0x22 _SMOC-MODULE-A-RID _SMOC-FILL32
    0x23 _SMOC-MODULE-B-RID _SMOC-FILL32
    _SMOC-BUILD-SCHEMA
    _SMOC-BUILD-PROFILE
    _SMOC-BUILD-ARTIFACT
    _SMOC-DECL-A _SMOC-MODULE-A-RID 7 _SMOC-DECL-A-DIGEST
        _SMOC-BUILD-DECLARATION
    _SMOC-DECL-B _SMOC-MODULE-B-RID 9 _SMOC-DECL-B-DIGEST
