: _SMOC-PINS  ( -- )
    _SMOC-MOD @ SBOX-MODULE-PIN SBOX-MODULE-S-OK _SMOC-IS
    DUP _SMOC-PLAN !
    DUP SBOX-PLAN-VALID? _SMOC-ASSERT
    DUP SBOX-PLAN-PROFILE@ _SMOC-PROFILE = _SMOC-ASSERT
    SBOX-PLAN-ARTIFACT-DIGEST@ 32 _SMOC-ARTIFACT-DIGEST 32 COMPARE
        0= _SMOC-ASSERT
    _SMOC-MOD @ SBOX-MODULE-PIN SBOX-MODULE-S-OK _SMOC-IS
        _SMOC-PLAN @ = _SMOC-ASSERT
    _SMOC-MOD @ SBOX-MODULE-PINS@ 2 = _SMOC-ASSERT
    \ A pinned module stays.
    _SMOC-MOD @ _SMOC-OWNER SBOX-MODULE-REMOVE SBOX-MODULE-S-BUSY _SMOC-IS
    _SMOC-OWNER SBOX-MODULE-OWNER-RELEASE SBOX-MODULE-S-BUSY _SMOC-IS
    _SMOC-OWNER SBOX-MODULE-OWNER-VALID? _SMOC-ASSERT
    _SMOC-MOD @ SBOX-MODULE-UNPIN SBOX-MODULE-S-OK _SMOC-IS
    _SMOC-MOD @ SBOX-MODULE-UNPIN SBOX-MODULE-S-OK _SMOC-IS
    _SMOC-MOD @ SBOX-MODULE-UNPIN SBOX-MODULE-S-STATE _SMOC-IS
    _SMOC-MOD @ SBOX-MODULE-PINS@ 0= _SMOC-ASSERT
    0 SBOX-MODULE-PIN SBOX-MODULE-S-INVALID _SMOC-IS 0= _SMOC-ASSERT
    _SMOC-OWNER SBOX-MODULE-PIN SBOX-MODULE-S-INVALID _SMOC-IS 0= _SMOC-ASSERT ;

