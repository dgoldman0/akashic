: _SMOC-DECLARED  ( -- )
    _SMOC-BUILD!
    _SMOC-BUILD SBOX-BUILD-RELEASE SBOX-BUILD-S-OK _SMOC-IS
    S" main" 1 _SMOC-ENTRY!

    \ The good module: it verifies on first use.
    20 1 _SMOC-DECLARE 0 _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-OK _SMOC-IS _SMOC-MOD2 !
    _SMOC-MOD2 @ SBOX-MODULE-STATE@ SBOX-MODULE-DECLARED _SMOC-IS
    _SMOC-MOD2 @ SBOX-MODULE-PIN SBOX-MODULE-S-STATE _SMOC-IS 0= _SMOC-ASSERT
    \ Only the owner that holds it verifies it.
    _SMOC-ARTIFACT _SMOC-ARTIFACT-U @ _SMOC-MOD2 @ _SMOC-OWNER2
        SBOX-MODULE-VERIFY SBOX-MODULE-S-INVALID _SMOC-IS
    _SMOC-MOD2 @ _SMOC-OWNER2 SBOX-MODULE-REMOVE SBOX-MODULE-S-INVALID _SMOC-IS
    0 _SMOC-ARTIFACT-U @ _SMOC-MOD2 @ _SMOC-OWNER
        SBOX-MODULE-VERIFY SBOX-MODULE-S-INVALID _SMOC-IS
    _SMOC-MOD2 @ SBOX-MODULE-STATE@ SBOX-MODULE-DECLARED _SMOC-IS
    _SMOC-ARTIFACT _SMOC-ARTIFACT-U @ _SMOC-MOD2 @ _SMOC-OWNER
        SBOX-MODULE-VERIFY SBOX-MODULE-S-OK _SMOC-IS
    _SMOC-MOD2 @ SBOX-MODULE-STATE@ SBOX-MODULE-VERIFIED _SMOC-IS
    _SMOC-ARTIFACT _SMOC-ARTIFACT-U @ _SMOC-MOD2 @ _SMOC-OWNER
        SBOX-MODULE-VERIFY SBOX-MODULE-S-STATE _SMOC-IS
    _SMOC-MOD2 @ SBOX-MODULE-PIN SBOX-MODULE-S-OK _SMOC-IS
        SBOX-PLAN-VALID? _SMOC-ASSERT
    _SMOC-MOD2 @ SBOX-MODULE-UNPIN SBOX-MODULE-S-OK _SMOC-IS
    \ The owner's build record is free again.
    _SMOC-OWNER SBOX-MODULE-COUNT@ 2 = _SMOC-ASSERT

    \ Not the declared artifact.
    21 1 _SMOC-DECLARE 0 _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-OK _SMOC-IS _SMOC-MOD2 !
    _SMOC-ARTIFACT 40 + DUP C@ 1 XOR SWAP C!
    _SMOC-ARTIFACT _SMOC-ARTIFACT-U @ _SMOC-MOD2 @ _SMOC-OWNER
        SBOX-MODULE-VERIFY SBOX-MODULE-S-MISMATCH _SMOC-IS
    _SMOC-MOD2 @ SBOX-MODULE-STATE@ SBOX-MODULE-QUARANTINED _SMOC-IS
    _SMOC-MOD2 @ SBOX-MODULE-REASON@ 0= _SMOC-ASSERT
        SBOX-MODULE-Q-ARTIFACT _SMOC-IS
    _SMOC-MOD2 @ SBOX-MODULE-PIN SBOX-MODULE-S-STATE _SMOC-IS 0= _SMOC-ASSERT
    _SMOC-ARTIFACT _SMOC-ARTIFACT-U @ _SMOC-MOD2 @ _SMOC-OWNER
        SBOX-MODULE-VERIFY SBOX-MODULE-S-STATE _SMOC-IS

    \ The declared artifact, which the verifier refuses: it names another
    \ profile.
    _SMOC-ARTIFACT _SMOC-ARTIFACT-U @ _SMOC-ARTIFACT-DIGEST _SMOC-DIGEST-WS
        SBOX-DIGEST-ARTIFACT SBOX-DIGEST-S-OK _SMOC-IS
    22 1 _SMOC-DECLARE 0 _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-OK _SMOC-IS _SMOC-MOD2 !
    _SMOC-ARTIFACT _SMOC-ARTIFACT-U @ _SMOC-MOD2 @ _SMOC-OWNER
        SBOX-MODULE-VERIFY SBOX-MODULE-S-VERIFY _SMOC-IS
    _SMOC-MOD2 @ SBOX-MODULE-STATE@ SBOX-MODULE-QUARANTINED _SMOC-IS
    _SMOC-MOD2 @ SBOX-MODULE-REASON@ 0<> _SMOC-ASSERT
        SBOX-MODULE-Q-VERIFY _SMOC-IS
    _SMOC-ARTIFACT 40 + DUP C@ 1 XOR SWAP C!
    _SMOC-REAL-DIGEST _SMOC-ARTIFACT-DIGEST 32 MOVE

    \ The declared artifact, whose entries are not the declared ones.
    S" mine" 1 _SMOC-ENTRY!
    23 1 _SMOC-DECLARE 0 _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-OK _SMOC-IS _SMOC-MOD2 !
    _SMOC-ARTIFACT _SMOC-ARTIFACT-U @ _SMOC-MOD2 @ _SMOC-OWNER
        SBOX-MODULE-VERIFY SBOX-MODULE-S-MISMATCH _SMOC-IS
    _SMOC-MOD2 @ SBOX-MODULE-REASON@ 0= _SMOC-ASSERT
        SBOX-MODULE-Q-MISMATCH _SMOC-IS
    S" main" 1 _SMOC-ENTRY!
    _SMOC-OWNER SBOX-MODULE-COUNT@ 5 = _SMOC-ASSERT

    \ A module the store can only name.
    24 _SMOC-RID! 1 SBOX-MODULE-Q-NONE _SMOC-OWNER
        SBOX-MODULE-ADD-QUARANTINED SBOX-MODULE-S-INVALID _SMOC-IS
        0= _SMOC-ASSERT
    24 _SMOC-RID! 1 SBOX-MODULE-Q-PROFILE 1+ _SMOC-OWNER
        SBOX-MODULE-ADD-QUARANTINED SBOX-MODULE-S-INVALID _SMOC-IS
        0= _SMOC-ASSERT
    24 _SMOC-RID! 0 SBOX-MODULE-Q-STORE _SMOC-OWNER
        SBOX-MODULE-ADD-QUARANTINED SBOX-MODULE-S-INVALID _SMOC-IS
        0= _SMOC-ASSERT
    20 _SMOC-RID! 1 SBOX-MODULE-Q-STORE _SMOC-OWNER
        SBOX-MODULE-ADD-QUARANTINED SBOX-MODULE-S-DUPLICATE _SMOC-IS
        0= _SMOC-ASSERT
    24 _SMOC-RID! 1 SBOX-MODULE-Q-STORE _SMOC-OWNER
        SBOX-MODULE-ADD-QUARANTINED SBOX-MODULE-S-OK _SMOC-IS
    DUP SBOX-MODULE-STATE@ SBOX-MODULE-QUARANTINED _SMOC-IS
    DUP SBOX-MODULE-REASON@ 0= _SMOC-ASSERT SBOX-MODULE-Q-STORE _SMOC-IS
    DUP SBOX-MODULE-DECLARATION$ 0= _SMOC-ASSERT 0= _SMOC-ASSERT
    DUP SBOX-MODULE-DECLARATION-DIGEST@ 0= _SMOC-ASSERT
    24 _SMOC-RID! 1 _SMOC-OWNER SBOX-MODULE-FIND = _SMOC-ASSERT
    \ Its key is taken: a declaration for it is a duplicate.
    24 1 _SMOC-DECLARE 0 _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-DUPLICATE _SMOC-IS 0= _SMOC-ASSERT
    _SMOC-OWNER SBOX-MODULE-COUNT@ 6 = _SMOC-ASSERT
    \ The host quarantines a declared module whose stored artifact is gone.
    25 1 _SMOC-DECLARE 0 _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-OK _SMOC-IS _SMOC-MOD2 !
    SBOX-MODULE-Q-NONE 0 _SMOC-MOD2 @ SBOX-MODULE-QUARANTINE
        SBOX-MODULE-S-INVALID _SMOC-IS
    SBOX-MODULE-Q-STORE 0 _SMOC-MOD2 @ SBOX-MODULE-QUARANTINE
        SBOX-MODULE-S-OK _SMOC-IS
    _SMOC-MOD2 @ SBOX-MODULE-STATE@ SBOX-MODULE-QUARANTINED _SMOC-IS
    _SMOC-MOD2 @ SBOX-MODULE-REASON@ 0= _SMOC-ASSERT
        SBOX-MODULE-Q-STORE _SMOC-IS
    SBOX-MODULE-Q-STORE 0 _SMOC-MOD2 @ SBOX-MODULE-QUARANTINE
        SBOX-MODULE-S-STATE _SMOC-IS
    SBOX-MODULE-Q-STORE 0 20 _SMOC-RID! 1 _SMOC-OWNER SBOX-MODULE-FIND
        SBOX-MODULE-QUARANTINE SBOX-MODULE-S-STATE _SMOC-IS
    _SMOC-MOD2 @ _SMOC-OWNER SBOX-MODULE-REMOVE SBOX-MODULE-S-OK _SMOC-IS
    _SMOC-OWNER SBOX-MODULE-COUNT@ 6 = _SMOC-ASSERT ;

\ =====================================================================
\  Retiring and removing
\ =====================================================================

: _SMOC-RETIRE  ( -- )
    _SMOC-MOD @ SBOX-MODULE-PIN SBOX-MODULE-S-OK _SMOC-IS DROP
    _SMOC-MOD @ SBOX-MODULE-RETIRE SBOX-MODULE-S-OK _SMOC-IS
    _SMOC-MOD @ SBOX-MODULE-STATE@ SBOX-MODULE-RETIRED _SMOC-IS
    _SMOC-MOD @ SBOX-MODULE-PIN SBOX-MODULE-S-STATE _SMOC-IS 0= _SMOC-ASSERT
    \ The run that holds the plan still finishes with it.
    _SMOC-PLAN @ SBOX-PLAN-VALID? _SMOC-ASSERT
    _SMOC-MOD @ _SMOC-OWNER SBOX-MODULE-REMOVE SBOX-MODULE-S-BUSY _SMOC-IS
    _SMOC-MOD @ SBOX-MODULE-UNPIN SBOX-MODULE-S-OK _SMOC-IS
    _SMOC-MOD @ SBOX-MODULE-RETIRE SBOX-MODULE-S-OK _SMOC-IS
    _SMOC-MOD @ SBOX-MODULE-STATE@ SBOX-MODULE-RETIRED _SMOC-IS
    \ A retired revision is still known, and refused.
    10 _SMOC-RID! 1 _SMOC-OWNER SBOX-MODULE-FIND _SMOC-MOD @ = _SMOC-ASSERT

    _SMOC-MOD @ _SMOC-OWNER SBOX-MODULE-REMOVE SBOX-MODULE-S-OK _SMOC-IS
    10 _SMOC-RID! 1 _SMOC-OWNER SBOX-MODULE-FIND 0= _SMOC-ASSERT
    _SMOC-OWNER SBOX-MODULE-COUNT@ 5 = _SMOC-ASSERT
    0 _SMOC-OWNER SBOX-MODULE-NTH 0<> _SMOC-ASSERT
    3 0 DO I _SMOC-OWNER _SMOC-KEY< _SMOC-ASSERT LOOP
    \ A quarantined module is removed the same way.
    21 _SMOC-RID! 1 _SMOC-OWNER SBOX-MODULE-FIND _SMOC-OWNER
        SBOX-MODULE-REMOVE SBOX-MODULE-S-OK _SMOC-IS
    _SMOC-OWNER SBOX-MODULE-COUNT@ 4 = _SMOC-ASSERT ;

\ =====================================================================
\  Growth and key order
\ =====================================================================


\ Forty-one declared modules, added from the highest RID down, then
\ three revisions of one more out of order.
: _SMOC-GROWTH  ( -- )
    0 _SMOC-OWNER2 SBOX-MODULE-COUNT@ = _SMOC-ASSERT
    41 0 DO
        140 I - 1 _SMOC-DECLARE 0 _SMOC-OWNER2 SBOX-MODULE-ADD
            SBOX-MODULE-S-OK _SMOC-IS DROP
    LOOP
    _SMOC-OWNER2 SBOX-MODULE-COUNT@ 41 = _SMOC-ASSERT
    2 1 3 3 0 DO
        50 SWAP _SMOC-DECLARE 0 _SMOC-OWNER2 SBOX-MODULE-ADD
            SBOX-MODULE-S-OK _SMOC-IS DROP
    LOOP
    _SMOC-OWNER2 SBOX-MODULE-COUNT@ 44 = _SMOC-ASSERT
    \ The table is in key order, and every module is found by its key.
    43 0 DO I _SMOC-OWNER2 _SMOC-KEY< _SMOC-ASSERT LOOP
    41 0 DO
        140 I - _SMOC-RID! 1 _SMOC-OWNER2 SBOX-MODULE-FIND
        DUP 0<> _SMOC-ASSERT
        SBOX-MODULE-KEY@ 1 = _SMOC-ASSERT 32 _SMOC-RID 32 COMPARE 0= _SMOC-ASSERT
    LOOP
    3 0 DO
        50 _SMOC-RID! I 1+ _SMOC-OWNER2 SBOX-MODULE-FIND
        SBOX-MODULE-KEY@ I 1+ = _SMOC-ASSERT DROP
    LOOP
    50 _SMOC-RID! 4 _SMOC-OWNER2 SBOX-MODULE-FIND 0= _SMOC-ASSERT
    99 _SMOC-RID! 1 _SMOC-OWNER2 SBOX-MODULE-FIND 0= _SMOC-ASSERT
    \ Removing one keeps the order.
    120 _SMOC-RID! 1 _SMOC-OWNER2 SBOX-MODULE-FIND _SMOC-OWNER2
        SBOX-MODULE-REMOVE SBOX-MODULE-S-OK _SMOC-IS
    _SMOC-OWNER2 SBOX-MODULE-COUNT@ 43 = _SMOC-ASSERT
    42 0 DO I _SMOC-OWNER2 _SMOC-KEY< _SMOC-ASSERT LOOP
    121 _SMOC-RID! 1 _SMOC-OWNER2 SBOX-MODULE-FIND 0<> _SMOC-ASSERT
    120 _SMOC-RID! 1 _SMOC-OWNER2 SBOX-MODULE-FIND 0= _SMOC-ASSERT ;

