: _SMOC-BUILD-DECLARATION
  ( declaration module-rid revision digest -- )
    _SMOC-CURRENT-DIGEST !
    _SMOC-CURRENT-REVISION !
    _SMOC-CURRENT-MODULE !
    _SMOC-CURRENT-DECL !
    _SMOC-CURRENT-DECL @ _SMOC-DECL-CAP 0 FILL

    _SMOC-PROFILE-ID$ DUP SBOX-BYTE-PAD8
    SBOX-BYTE-S-OK = _SMOC-ASSERT
    _SMOC-PROFILE-PAD !
    _SMOC-CURRENT-DECL @ SBOX-DECL-HEADER-SIZE + SWAP MOVE

    _SMOC-CURRENT-DECL @ SBOX-DECL-HEADER-SIZE +
        _SMOC-PROFILE-PAD @ +
        DUP _SMOC-ENTRIES !
    2 SBOX-DECL-ENTRY-SIZE * +
        DUP _SMOC-SCHEMAS !
    128 + _SMOC-CURRENT-DECL @ - _SMOC-DECL-U !

    _SMOC-WRITE-HEADER
    _SMOC-WRITE-ENTRY0
    _SMOC-WRITE-ENTRY1
    _SMOC-SCHEMA _SMOC-SCHEMAS @ 64 MOVE
    _SMOC-SCHEMA _SMOC-SCHEMAS @ 64 + 64 MOVE
    _SMOC-CURRENT-DECL @ _SMOC-DECL-U @
    _SMOC-CURRENT-DIGEST @ _SMOC-DIGEST-WORK
    SBOX-DECL-DIGEST SBOX-DECL-S-OK = _SMOC-ASSERT ;

