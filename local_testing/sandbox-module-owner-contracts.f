        SBOX-MODULE-S-OK _SMOC-IS
    _SMOC-OWNER SBOX-MODULE-OWNER-VALID? _SMOC-ASSERT
    _SMOC-OWNER SBOX-MODULE-COUNT@ 0= _SMOC-ASSERT
