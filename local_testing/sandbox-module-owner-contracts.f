: _SMOC-ADD-BUILT  ( -- )
    _SMOC-BUILD!
    \ Whatever a refusal says, the build keeps its plan.
    S" main" 1 _SMOC-ENTRY!
    _SMOC-REAL-DIGEST 32 17 FILL
    _SMOC-REAL-DIGEST _SMOC-PDIGEST !
    10 1 _SMOC-DECLARE _SMOC-BUILD _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-PROFILE _SMOC-IS 0= _SMOC-ASSERT
    _SMOC-PROFILE SBOX-PROFILE-DIGEST@ _SMOC-PDIGEST !
    S" mine" 1 _SMOC-ENTRY!
    10 1 _SMOC-DECLARE _SMOC-BUILD _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-MISMATCH _SMOC-IS 0= _SMOC-ASSERT
    S" main" 2 _SMOC-ENTRY!
    10 1 _SMOC-DECLARE _SMOC-BUILD _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-MISMATCH _SMOC-IS 0= _SMOC-ASSERT
    10 1 _SMOC-DECLARE2 _SMOC-BUILD _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-MISMATCH _SMOC-IS 0= _SMOC-ASSERT
    S" main" 1 _SMOC-ENTRY!
    _SMOC-ARTIFACT-DIGEST _SMOC-REAL-DIGEST 32 MOVE
    _SMOC-ARTIFACT-DIGEST 32 0x5A FILL
    10 1 _SMOC-DECLARE _SMOC-BUILD _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-MISMATCH _SMOC-IS 0= _SMOC-ASSERT
    _SMOC-REAL-DIGEST _SMOC-ARTIFACT-DIGEST 32 MOVE
    \ A declaration that does not validate.
    10 1 _SMOC-DECLARE 2DUP + 1- DUP C@ 1 XOR SWAP C!
        _SMOC-BUILD _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-INVALID _SMOC-IS 0= _SMOC-ASSERT
    _SMOC-BUILD SBOX-BUILD-PLAN@ SBOX-BUILD-S-OK _SMOC-IS
        SBOX-PLAN-VALID? _SMOC-ASSERT
    _SMOC-OWNER SBOX-MODULE-COUNT@ 0= _SMOC-ASSERT

    10 1 _SMOC-DECLARE _SMOC-BUILD _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-OK _SMOC-IS
    DUP _SMOC-MOD !
    SBOX-MODULE-STATE@ SBOX-MODULE-VERIFIED _SMOC-IS
    \ The module took the build's plan.
    _SMOC-BUILD SBOX-BUILD-PLAN@ SBOX-BUILD-S-STATE _SMOC-IS 0= _SMOC-ASSERT
    _SMOC-OWNER SBOX-MODULE-COUNT@ 1 = _SMOC-ASSERT
    10 _SMOC-RID! 1 _SMOC-OWNER SBOX-MODULE-FIND _SMOC-MOD @ = _SMOC-ASSERT
    10 _SMOC-RID! 2 _SMOC-OWNER SBOX-MODULE-FIND 0= _SMOC-ASSERT
    11 _SMOC-RID! 1 _SMOC-OWNER SBOX-MODULE-FIND 0= _SMOC-ASSERT
    10 _SMOC-RID! 0 _SMOC-OWNER SBOX-MODULE-FIND 0= _SMOC-ASSERT
    _SMOC-RID 32 0 FILL _SMOC-RID 1 _SMOC-OWNER SBOX-MODULE-FIND 0= _SMOC-ASSERT
    0 _SMOC-OWNER SBOX-MODULE-NTH _SMOC-MOD @ = _SMOC-ASSERT
    1 _SMOC-OWNER SBOX-MODULE-NTH 0= _SMOC-ASSERT
    -1 _SMOC-OWNER SBOX-MODULE-NTH 0= _SMOC-ASSERT

    _SMOC-MOD @ SBOX-MODULE-KEY@ 1 = _SMOC-ASSERT
        32 10 _SMOC-RID! 32 COMPARE 0= _SMOC-ASSERT
    \ The declaration is a copy, with its digest.
    10 1 _SMOC-DECLARE 2DROP
    _SMOC-MOD @ SBOX-MODULE-DECLARATION$
        DUP _SMOC-DECL-U @ = _SMOC-ASSERT
        OVER _SMOC-DECL <> _SMOC-ASSERT
        _SMOC-DECL _SMOC-DECL-U @ COMPARE 0= _SMOC-ASSERT
    _SMOC-DECL _SMOC-DECL-U @ _SMOC-DIGEST _SMOC-DECL-WS SBOX-DECL-DIGEST
        SBOX-DECL-S-OK _SMOC-IS
    _SMOC-MOD @ SBOX-MODULE-DECLARATION-DIGEST@ 32 _SMOC-DIGEST 32 COMPARE
        0= _SMOC-ASSERT
    _SMOC-MOD @ SBOX-MODULE-REASON@ 0= _SMOC-ASSERT 0= _SMOC-ASSERT
    \ The same key again.
    _SMOC-BUILD!
    10 1 _SMOC-DECLARE _SMOC-BUILD _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-DUPLICATE _SMOC-IS 0= _SMOC-ASSERT
    _SMOC-BUILD SBOX-BUILD-RELEASE SBOX-BUILD-S-OK _SMOC-IS
    \ A build without a plan.
    10 2 _SMOC-DECLARE _SMOC-BUILD _SMOC-OWNER SBOX-MODULE-ADD
        SBOX-MODULE-S-STATE _SMOC-IS 0= _SMOC-ASSERT ;

