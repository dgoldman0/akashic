: _SMOC-RUN  ( -- )
    0 _SMOC-FAILS !
    0 _SMOC-CHECKS !
    DEPTH _SMOC-DEPTH !
    ." SBOX MODULE OWNER CONTRACTS START" CR
    _SMOC-LOADER-ID-CONTRACT
    _SMOC-BUILD-FIXTURES
    _SMOC-OWNER-CONTRACTS
    _SMOC-STACK
    _SMOC-FAILS @ 0= IF
        ." SBOX MODULE OWNER CONTRACTS PASS "
        _SMOC-CHECKS @ . CR
    ELSE
        ." SBOX MODULE OWNER CONTRACTS FAIL "
        _SMOC-FAILS @ . ." / " _SMOC-CHECKS @ . CR
        ABORT
    THEN ;

_SMOC-RUN
