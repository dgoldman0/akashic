    _SMOC-PROFILE _SMOC-OWNER SBOX-MODULE-OWNER-INIT
        SBOX-MODULE-S-STATE _SMOC-IS
    _SMOC-PROFILE _SMOC-OWNER2 SBOX-MODULE-OWNER-INIT
        SBOX-MODULE-S-OK _SMOC-IS ;

