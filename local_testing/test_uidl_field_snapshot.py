def test_mounted_field_copy_slots_all_kinds_frozen_validation_and_lifecycle():
    output = run_status_forth(_field_snapshot_program())
    summary = re.search(r"FIELD SNAP PASS\s+(\d+)\s+0", output)
    assert summary, output[-18000:]
    assert int(summary.group(1)) >= 90
