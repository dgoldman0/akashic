\ Focused contracts for the caller-owned JSON string writer.

PROVIDED json-writer-test

VARIABLE _JWT-FAILS
VARIABLE _JWT-CHECKS
VARIABLE _JWT-DEPTH

CREATE _JWT-BUFFER-A 128 ALLOT
CREATE _JWT-BUFFER-B 128 ALLOT
CREATE _JWT-WRITER-A CBW-SIZE ALLOT
CREATE _JWT-WRITER-B CBW-SIZE ALLOT

CREATE _JWT-EXPECTED-A
    34 C, 108 C, 101 C, 102 C, 116 C, 34 C, 44 C,
    34 C, 114 C, 105 C, 103 C, 104 C, 116 C, 34 C,

CREATE _JWT-EXPECTED-B
    91 C, 34 C, 98 C, 101 C, 116 C, 97 C, 34 C, 93 C,

CREATE _JWT-ESCAPE-SOURCE
    0 C, 1 C, 8 C, 9 C, 10 C, 12 C, 13 C, 31 C, 34 C, 92 C, 47 C,

CREATE _JWT-ESCAPE-ORIGINAL
    0 C, 1 C, 8 C, 9 C, 10 C, 12 C, 13 C, 31 C, 34 C, 92 C, 47 C,

CREATE _JWT-ESCAPE-EXPECTED
    34 C,
    92 C, 117 C, 48 C, 48 C, 48 C, 48 C,
    92 C, 117 C, 48 C, 48 C, 48 C, 49 C,
    92 C, 98 C, 92 C, 116 C, 92 C, 110 C,
    92 C, 102 C, 92 C, 114 C,
    92 C, 117 C, 48 C, 48 C, 49 C, 70 C,
    92 C, 34 C, 92 C, 92 C, 47 C, 34 C,

CREATE _JWT-UTF8-SOURCE
    0xC3 C, 0xA9 C, 0xF0 C, 0x9F C, 0x98 C, 0x80 C,

CREATE _JWT-UTF8-EXPECTED
    34 C, 0xC3 C, 0xA9 C, 0xF0 C, 0x9F C, 0x98 C, 0x80 C, 34 C,

CREATE _JWT-BAD-UTF8 0xC0 C, 0xAF C,
CREATE _JWT-BAD-SURROGATE 0xED C, 0xA0 C, 0x80 C,
CREATE _JWT-BAD-RANGE 0xF4 C, 0x90 C, 0x80 C, 0x80 C,
CREATE _JWT-BAD-TRUNCATED 0xE2 C, 0x82 C,
CREATE _JWT-EMPTY-EXPECTED 34 C, 34 C,
CREATE _JWT-OK-EXPECTED 34 C, 111 C, 107 C, 34 C,
CREATE _JWT-PREFIX-EXPECTED
    97 C, 98 C, 99 C, 34 C, 97 C, 98 C, 99 C, 34 C,

: _JWT-ASSERT  ( flag -- )
    1 _JWT-CHECKS +!
    0= IF
        1 _JWT-FAILS +!
        ." JSON WRITER ASSERT " _JWT-CHECKS @ . CR
    THEN ;

: _JWT-STACK  ( -- )
    DEPTH DUP _JWT-DEPTH @ <> IF
        ." JSON WRITER STACK " _JWT-DEPTH @ . ." -> " DUP . CR
        .S CR
    THEN
    _JWT-DEPTH @ = _JWT-ASSERT ;

: _JWT-FILLED?  ( address length byte -- flag )
    >R
    BEGIN DUP WHILE
        OVER C@ R@ <> IF
            2DROP R> DROP 0 EXIT
        THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP R> DROP -1 ;

: _JWT-EXPECT  ( expected-a expected-u writer -- )
    CBW-RESULT
    CBW-S-OK = _JWT-ASSERT
    COMPARE 0= _JWT-ASSERT ;

: _JWT-TEST-MEASURE  ( -- )
    0 0 JSONW-STRING-MEASURE
        CBW-S-OK = _JWT-ASSERT
        2 = _JWT-ASSERT
    S" alpha" JSONW-STRING-MEASURE
        CBW-S-OK = _JWT-ASSERT
        7 = _JWT-ASSERT
    _JWT-ESCAPE-SOURCE 11 JSONW-STRING-MEASURE
        CBW-S-OK = _JWT-ASSERT
        35 = _JWT-ASSERT
    _JWT-UTF8-SOURCE 6 JSONW-STRING-MEASURE
        CBW-S-OK = _JWT-ASSERT
        8 = _JWT-ASSERT
    _JWT-BAD-UTF8 2 JSONW-STRING-MEASURE
        CBW-S-INVALID = _JWT-ASSERT
        0= _JWT-ASSERT
    _JWT-BAD-SURROGATE 3 JSONW-STRING-MEASURE
        CBW-S-INVALID = _JWT-ASSERT
        0= _JWT-ASSERT
    _JWT-BAD-RANGE 4 JSONW-STRING-MEASURE
        CBW-S-INVALID = _JWT-ASSERT
        0= _JWT-ASSERT
    _JWT-BAD-TRUNCATED 2 JSONW-STRING-MEASURE
        CBW-S-INVALID = _JWT-ASSERT
        0= _JWT-ASSERT
    0 1 JSONW-STRING-MEASURE
        CBW-S-INVALID = _JWT-ASSERT
        0= _JWT-ASSERT
    _JWT-STACK ;

: _JWT-TEST-INTERLEAVED  ( -- )
    _JWT-BUFFER-A 128 _JWT-WRITER-A CBW-INIT
        CBW-S-OK = _JWT-ASSERT
    _JWT-BUFFER-B 128 _JWT-WRITER-B CBW-INIT
        CBW-S-OK = _JWT-ASSERT

    [CHAR] [ _JWT-WRITER-B CBW-CHAR CBW-S-OK = _JWT-ASSERT
    S" left" _JWT-WRITER-A JSONW-STRING CBW-S-OK = _JWT-ASSERT
    S" beta" _JWT-WRITER-B JSONW-STRING CBW-S-OK = _JWT-ASSERT
    [CHAR] , _JWT-WRITER-A CBW-CHAR CBW-S-OK = _JWT-ASSERT
    [CHAR] ] _JWT-WRITER-B CBW-CHAR CBW-S-OK = _JWT-ASSERT
    S" right" _JWT-WRITER-A JSONW-STRING CBW-S-OK = _JWT-ASSERT

    _JWT-EXPECTED-A 14 _JWT-WRITER-A _JWT-EXPECT
    _JWT-EXPECTED-B 8 _JWT-WRITER-B _JWT-EXPECT
    _JWT-STACK ;

: _JWT-TEST-ESCAPES-AND-UTF8  ( -- )
    _JWT-BUFFER-A 128 _JWT-WRITER-A CBW-INIT DROP
    0 0 _JWT-WRITER-A JSONW-STRING CBW-S-OK = _JWT-ASSERT
    _JWT-EMPTY-EXPECTED 2 _JWT-WRITER-A _JWT-EXPECT

    _JWT-BUFFER-A 128 _JWT-WRITER-A CBW-INIT DROP
    _JWT-ESCAPE-SOURCE 11 _JWT-WRITER-A JSONW-STRING
        CBW-S-OK = _JWT-ASSERT
    _JWT-ESCAPE-EXPECTED 35 _JWT-WRITER-A _JWT-EXPECT
    _JWT-ESCAPE-SOURCE 11 _JWT-ESCAPE-ORIGINAL 11 COMPARE
        0= _JWT-ASSERT

    _JWT-BUFFER-B 128 _JWT-WRITER-B CBW-INIT DROP
    _JWT-UTF8-SOURCE 6 _JWT-WRITER-B JSONW-STRING
        CBW-S-OK = _JWT-ASSERT
    _JWT-UTF8-EXPECTED 8 _JWT-WRITER-B _JWT-EXPECT
    _JWT-STACK ;

: _JWT-TEST-ATOMIC-CAPACITY  ( -- )
    _JWT-BUFFER-A 128 0xA5 FILL
    _JWT-BUFFER-A 34 _JWT-WRITER-A CBW-INIT DROP
    _JWT-ESCAPE-SOURCE 11 _JWT-WRITER-A JSONW-STRING
        CBW-S-CAPACITY = _JWT-ASSERT
    _JWT-WRITER-A CBW-LENGTH@ 0= _JWT-ASSERT
    _JWT-WRITER-A CBW-STATUS@ CBW-S-CAPACITY = _JWT-ASSERT
    _JWT-BUFFER-A 128 0xA5 _JWT-FILLED? _JWT-ASSERT
    0 0 _JWT-WRITER-A JSONW-STRING
        CBW-S-CAPACITY = _JWT-ASSERT
    _JWT-WRITER-A CBW-LENGTH@ 0= _JWT-ASSERT

    _JWT-BUFFER-A 35 _JWT-WRITER-A CBW-INIT DROP
    _JWT-ESCAPE-SOURCE 11 _JWT-WRITER-A JSONW-STRING
        CBW-S-OK = _JWT-ASSERT
    _JWT-ESCAPE-EXPECTED 35 _JWT-WRITER-A _JWT-EXPECT
    _JWT-STACK ;

: _JWT-TEST-INVALID-AND-STICKY  ( -- )
    _JWT-BUFFER-A 128 0xA5 FILL
    _JWT-BUFFER-B 128 0x5A FILL
    _JWT-BUFFER-A 128 _JWT-WRITER-A CBW-INIT DROP
    _JWT-BUFFER-B 128 _JWT-WRITER-B CBW-INIT DROP

    _JWT-BAD-UTF8 2 _JWT-WRITER-A JSONW-STRING
        CBW-S-INVALID = _JWT-ASSERT
    _JWT-WRITER-A CBW-LENGTH@ 0= _JWT-ASSERT
    _JWT-WRITER-A CBW-STATUS@ CBW-S-INVALID = _JWT-ASSERT
    _JWT-BUFFER-A 128 0xA5 _JWT-FILLED? _JWT-ASSERT
    0 0 _JWT-WRITER-A JSONW-STRING
        CBW-S-INVALID = _JWT-ASSERT
    S" ok" _JWT-WRITER-B JSONW-STRING CBW-S-OK = _JWT-ASSERT
    _JWT-OK-EXPECTED 4 _JWT-WRITER-B _JWT-EXPECT
    _JWT-WRITER-B CBW-STATUS@ CBW-S-OK = _JWT-ASSERT
    _JWT-STACK ;

: _JWT-TEST-ALIAS-POLICY  ( -- )
    _JWT-BUFFER-A 128 _JWT-WRITER-A CBW-INIT DROP
    _JWT-WRITER-A 1 _JWT-WRITER-A JSONW-STRING
        CBW-S-INVALID = _JWT-ASSERT
    _JWT-WRITER-A CBW-LENGTH@ 0= _JWT-ASSERT

    [CHAR] a _JWT-BUFFER-A C!
    _JWT-BUFFER-A 128 _JWT-WRITER-A CBW-INIT DROP
    _JWT-BUFFER-A 1 _JWT-WRITER-A JSONW-STRING
        CBW-S-INVALID = _JWT-ASSERT
    _JWT-WRITER-A CBW-LENGTH@ 0= _JWT-ASSERT
    _JWT-WRITER-A CBW-STATUS@ CBW-S-INVALID = _JWT-ASSERT
    _JWT-BUFFER-A C@ [CHAR] a = _JWT-ASSERT

    _JWT-BUFFER-A 128 _JWT-WRITER-A CBW-INIT DROP
    S" abc" _JWT-WRITER-A CBW-APPEND CBW-S-OK = _JWT-ASSERT
    _JWT-BUFFER-A 3 _JWT-WRITER-A JSONW-STRING
        CBW-S-OK = _JWT-ASSERT
    _JWT-PREFIX-EXPECTED 8 _JWT-WRITER-A _JWT-EXPECT
    _JWT-STACK ;

: _JWT-RUN  ( -- )
    0 _JWT-FAILS !
    0 _JWT-CHECKS !
    DEPTH _JWT-DEPTH !
    _JWT-TEST-MEASURE
    _JWT-TEST-INTERLEAVED
    _JWT-TEST-ESCAPES-AND-UTF8
    _JWT-TEST-ATOMIC-CAPACITY
    _JWT-TEST-INVALID-AND-STICKY
    _JWT-TEST-ALIAS-POLICY
    _JWT-FAILS @ 0= IF
        ." JSON WRITER PASS " _JWT-CHECKS @ . CR
    ELSE
        ." JSON WRITER FAIL " _JWT-FAILS @ .
        ." / " _JWT-CHECKS @ . CR
    THEN ;
