: VFSNAP-SAVE  ( encode-context expected-generation store -- status )
    _CVTD-VSS-STORE ! _CVTD-VSS-EXPECTED ! _CVTD-VSS-CONTEXT !
    _CVTD-VSS-STORE @ VFSNAP-VALID? 0= IF
        VFSNAP-S-INVALID EXIT
    THEN
    _CVTD-VSS-EXPECTED @ 0< IF VFSNAP-S-INVALID EXIT THEN
    _CVTD-PERSIST-PRESENT @ IF
        _CVTD-VSS-STORE @ _CVTD-PATH-MATCH? 0= IF
            VFSNAP-S-CONFLICT EXIT
        THEN
        _CVTD-VSS-EXPECTED @ _CVTD-PERSIST-GENERATION @ <> IF
            VFSNAP-S-CONFLICT EXIT
        THEN
    ELSE
        _CVTD-VSS-EXPECTED @ IF VFSNAP-S-CONFLICT EXIT THEN
    THEN
    _CVTD-VSS-EXPECTED @ 1+ DUP 0> 0= IF
        DROP VFSNAP-S-CAPACITY EXIT
    THEN
    _CVTD-VSS-NEXT !
    _CVTD-VSS-STORE @ VFSNAP.SCRATCH-A @ VFSNAP-HEADER-SIZE +
        _CVTD-VSS-PAYLOAD !
    _CVTD-VSS-STORE @ VFSNAP.SPEC @
        VFSNAP-SPEC.PAYLOAD-U @ _CVTD-VSS-PAYLOAD-U !
    _CVTD-VSS-PAYLOAD @ _CVTD-VSS-PAYLOAD-U @ 0 FILL
    _CVTD-VSS-CONTEXT @
        _CVTD-VSS-PAYLOAD @ _CVTD-VSS-PAYLOAD-U @
        _CVTD-VSS-NEXT @
        _CVTD-VSS-STORE @ VFSNAP.SPEC @
        VFSNAP-SPEC.ENCODE-XT @ EXECUTE
    DUP IF
        _CVTD-VSS-STORE @ VFSNAP.SCRATCH-A @
            _CVTD-VSS-STORE @ VFSNAP.SCRATCH-U @ 0 FILL
        EXIT
    THEN
    DROP
    _CVTD-VSS-PAYLOAD @ _CVTD-PERSIST-DATA
        _CVTD-VSS-PAYLOAD-U @ MOVE
    _CVTD-VSS-PAYLOAD-U @ _CVTD-PERSIST-U !
    _CVTD-VSS-NEXT @ _CVTD-PERSIST-GENERATION !
    -1 _CVTD-PERSIST-PRESENT !
    _CVTD-VSS-STORE @ _CVTD-CAPTURE-PATH
    _CVTD-VSS-STORE @ VFSNAP.SCRATCH-A @
        _CVTD-VSS-STORE @ VFSNAP.SCRATCH-U @ 0 FILL
    VFSNAP-S-OK ;

