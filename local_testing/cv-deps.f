\
\ Load this file before the runner-packaged cv-source.f.  That source is the
\ exact production credential-vault body with only its statically qualified
\ REQUIRE directives elided; these doubles supply those dependency contracts.
\
\ The doubles retain the production status values, public geometry, field
\ offsets, and callback ABIs used by credential-vault.f.  They deliberately
\ own one deterministic directory tree and one persistent snapshot record;
\ they qualify vault composition, not cryptography or crash durability.

