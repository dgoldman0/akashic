\ Pending-first RemoteSub consumption and cumulative EVENT ACK composition.

PROVIDED rabbit-landing3-mux-test

VARIABLE _RBT-L3-MUX-BUILDER
VARIABLE _RBT-L3-MUX-CONNECTOR
VARIABLE _RBT-L3-MUX-SUB
VARIABLE _RBT-L3-MUX-PENDING-ACTION
VARIABLE _RBT-L3-MUX-PENDING-STAGE
VARIABLE _RBT-L3-MUX-PENDING-STATUS
VARIABLE _RBT-L3-MUX-RETRY-STATUS

: _RBT-L3-MUX-PENDING? ( remote-sub -- flag )
    STREAMS-RABBIT-REMOTE-SUB-PENDING@
        _RBT-L3-MUX-PENDING-STATUS ! _RBT-L3-MUX-PENDING-STAGE !
        _RBT-L3-MUX-PENDING-ACTION !
    _RBT-L3-MUX-PENDING-STATUS @ STREAMS-RABBIT-REMOTE-SUB-S-OK =
        _RBT-ASSERT
    _RBT-L3-MUX-PENDING-ACTION @
        STREAMS-RABBIT-REMOTE-SUB-ACTION-NONE <> ;

: _RBT-L3-MUX-LAST-LANE-SEQ@ ( remote-sub -- lane-seq )
    STREAMS-RABBIT-REMOTE-SUB-LAST-EVENT@
        STREAMS-RABBIT-REMOTE-SUB-S-OK = _RBT-ASSERT
    2DROP 2DROP 2DROP 2DROP
    >R 2DROP DROP R> ;

: _RBT-L3-MUX-ACK-LATEST ( builder connector remote-sub -- )
    _RBT-L3-MUX-SUB ! _RBT-L3-MUX-CONNECTOR ! _RBT-L3-MUX-BUILDER !
    _RBT-L3-MUX-SUB @ _RBT-L3-MUX-LAST-LANE-SEQ@
        DUP 0> _RBT-ASSERT
    _RBT-L3-MUX-BUILDER @ RMSGB-RESET RMSGB-S-OK = _RBT-ASSERT
    1 SWAP _RBT-L3-MUX-BUILDER @ RMSGB-BEGIN-ACK
        RMSGB-S-OK = _RBT-ASSERT
    _RBT-L3-MUX-BUILDER @ RMSGB-SEAL RMSGB-S-OK = _RBT-ASSERT
    _RBT-L3-MUX-BUILDER @ _RBT-L3-MUX-CONNECTOR @
        STREAMS-RABBIT-CONNECTOR-CONTROL
        STREAMS-RABBIT-CONNECTOR-S-OK = _RBT-ASSERT
        0<> _RBT-ASSERT
    _RBT-L3-MUX-BUILDER @ RMSGB-RESET RMSGB-S-OK = _RBT-ASSERT ;

: _RBT-L3-MUX-RETRY-PENDING ( builder connector remote-sub -- handled? )
    _RBT-L3-MUX-SUB ! _RBT-L3-MUX-CONNECTOR ! _RBT-L3-MUX-BUILDER !
    _RBT-L3-MUX-SUB @ _RBT-L3-MUX-PENDING? 0= IF 0 EXIT THEN
    _RBT-L3-MUX-SUB @ STREAMS-RABBIT-REMOTE-SUB-EVENT-RETRY
        _RBT-L3-MUX-RETRY-STATUS ! DROP
    _RBT-L3-MUX-RETRY-STATUS @
        STREAMS-RABBIT-REMOTE-SUB-STATUS-VALID? _RBT-ASSERT
    _RBT-L3-MUX-SUB @ _RBT-L3-MUX-PENDING? IF -1 EXIT THEN
    _RBT-L3-MUX-BUILDER @ _RBT-L3-MUX-CONNECTOR @
        _RBT-L3-MUX-SUB @ _RBT-L3-MUX-ACK-LATEST
    -1 ;
