: _S3A-ASSERT  ( flag -- )
    1 _S3A-CHECKS +!
    0= IF
        1 _S3A-FAILS +!
        ." SBOX STAGE3 AGENT ASSERT " _S3A-CHECKS @ . CR TX-FLUSH
    THEN ;

: _S3A-STACK  ( -- )
    DEPTH DUP _S3A-DEPTH @ <> IF
        ." SBOX STAGE3 AGENT STACK "
        _S3A-DEPTH @ . ." -> " DUP . CR .S CR TX-FLUSH
    THEN
    _S3A-DEPTH @ = _S3A-ASSERT ;

: _S3A-SOURCE-ECHO  ( -- address length )
    S" FUNCTION echo PARAMS 1 RESULTS 1 LOCALS 0 DUP V.TYPE DROP RETURN END ENTRY SIGNATURE 1 main echo" ;

: _S3A-SOURCE-INCREMENT  ( -- address length )
    S" FUNCTION increment PARAMS 1 RESULTS 1 LOCALS 0 V.I64.GET 1 I64.ADD V.NEW.I64 RETURN END ENTRY SIGNATURE 1 main increment" ;

: _S3A-SOURCE-HOSTILE  ( -- address length )
    S" FUNCTION bad PARAMS 1 RESULTS 1 LOCALS 0 EVALUATE RETURN END ENTRY SIGNATURE 1 main bad" ;

: _S3A-BOOL!  ( flag address -- )
    >R
    R@ 24 0 FILL
    SBOX-VALUE-T-BOOL R@ C!
    8 R@ 8 + SBOX-CANDIDATE-U64-LE!
    R> 16 + SBOX-CANDIDATE-U64-LE! ;

: _S3A-I64!  ( value address -- )
    >R
    R@ 24 0 FILL
    SBOX-VALUE-T-I64 R@ C!
    8 R@ 8 + SBOX-CANDIDATE-U64-LE!
    R> 16 + SBOX-CANDIDATE-U64-LE! ;

: _S3A-RESULT-VALUE=?
  ( expected expected-u result-envelope -- flag )
    AGENT-SBOX-RESULT-PAYLOAD@
    0= IF 2DROP 2DROP 0 EXIT THEN
    DROP
    SBOX-VM-RESULT-CANDIDATE@
    0= IF 2DROP 2DROP 0 EXIT THEN
    2 PICK OVER <> IF 2DROP 2DROP 0 EXIT THEN
    COMPARE 0= ;

