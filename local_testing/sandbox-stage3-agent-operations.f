: _S3A-PARENT-INIT  ( -- )
    HEAP-FREE-BYTES _S3A-HEAP-BEFORE !
    1 CTX-NEW DUP IF THROW THEN DROP _S3A-PARENT !
    _S3A-PARENT @ DUP CTX.FLAGS @ CTX-F-ACTIVE OR
        OVER CTX.FLAGS !
    CTX-TOUCH
    _S3A-PARENT @ CTX-VALID? _S3A-ASSERT ;

