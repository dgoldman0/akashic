: _SSC-ASSERT  ( flag -- )
    1 _SSC-CHECKS +!
    0= IF
        1 _SSC-FAILS +!
        ." SBOX SCHEMA ASSERT " _SSC-CHECKS @ . CR
    THEN ;

: _SSC-STACK  ( -- )
    DEPTH DUP _SSC-DEPTH @ <> IF
        ." SBOX SCHEMA STACK " _SSC-DEPTH @ . ." -> " DUP . CR
        .S CR
    THEN
    _SSC-DEPTH @ = _SSC-ASSERT ;

: _SSC-U16!  ( value address -- )
    >R
    DUP R@ C!
    8 RSHIFT R@ 1+ C!
    R> DROP ;

: _SSC-U32!  ( value address -- )
    >R
    DUP R@ C!
    DUP 8 RSHIFT R@ 1+ C!
    DUP 16 RSHIFT R@ 2 + C!
    24 RSHIFT R@ 3 + C!
    R> DROP ;

: _SSC-U64!  ( value address -- )
    >R
    DUP R@ C!
    DUP 8 RSHIFT R@ 1+ C!
    DUP 16 RSHIFT R@ 2 + C!
    DUP 24 RSHIFT R@ 3 + C!
    DUP 32 RSHIFT R@ 4 + C!
    DUP 40 RSHIFT R@ 5 + C!
    DUP 48 RSHIFT R@ 6 + C!
    56 RSHIFT R@ 7 + C!
    R> DROP ;

: _SSC-DOCUMENT!
  ( node-count max-depth total-bytes address -- )
    >R
    R@ SBOX-SCHEMA-DOCUMENT-HEADER-SIZE 0 FILL
    SBOX-SCHEMA-DOCUMENT-MAGIC R@ _SSC-U64!
    SBOX-SCHEMA-DOCUMENT-VERSION R@ 8 + _SSC-U16!
    2 PICK R@ 12 + _SSC-U32!
    OVER R@ 16 + _SSC-U32!
    DUP R@ 24 + _SSC-U64!
    2DROP DROP R> DROP ;

: _SSC-SCHEMA-NODE!
  ( tag count lower upper payload-u address -- )
    >R
    R@ SBOX-SCHEMA-NODE-HEADER-SIZE 0 FILL
    4 PICK R@ C!
    3 PICK R@ 4 + _SSC-U32!
    2 PICK R@ 8 + _SSC-U64!
    OVER R@ 16 + _SSC-U64!
    DUP R@ 24 + _SSC-U64!
    2DROP 2DROP DROP R> DROP ;

: _SSC-FIELD!
  ( key-u flags child-schema-u address -- )
    >R
    R@ SBOX-SCHEMA-FIELD-HEADER-SIZE 0 FILL
    2 PICK R@ _SSC-U32!
    OVER R@ 4 + C!
    DUP R@ 8 + _SSC-U64!
    2DROP DROP R> DROP ;

: _SSC-VALUE-HEADER!  ( tag count payload-u address -- )
    >R
    R@ 16 0 FILL
    2 PICK R@ C!
    OVER R@ 4 + _SSC-U32!
    DUP R@ 8 + _SSC-U64!
    2DROP DROP R> DROP ;

: _SSC-BYTES!  ( source source-u target -- )
    SWAP CMOVE ;

: _SSC-BUILD-SCHEMA  ( -- )
    _SSC-SCHEMA 256 0 FILL
    4 3 202 _SSC-SCHEMA _SSC-DOCUMENT!

    \ Closed root MAP:
    \   required "name": UTF8[1,8]
    \   optional "scores": LIST[0,2] of I64
    SBOX-SCHEMA-T-MAP 2 0 0 138
        _SSC-SCHEMA 32 + _SSC-SCHEMA-NODE!

    4 SBOX-SCHEMA-FIELD-F-REQUIRED 32
        _SSC-SCHEMA 64 + _SSC-FIELD!
    S" name" _SSC-SCHEMA 80 + _SSC-BYTES!
    SBOX-SCHEMA-T-UTF8 0 1 8 0
        _SSC-SCHEMA 84 + _SSC-SCHEMA-NODE!

    6 SBOX-SCHEMA-FIELD-F-OPTIONAL 64
        _SSC-SCHEMA 116 + _SSC-FIELD!
    S" scores" _SSC-SCHEMA 132 + _SSC-BYTES!
    SBOX-SCHEMA-T-LIST 1 0 2 32
        _SSC-SCHEMA 138 + _SSC-SCHEMA-NODE!
    SBOX-SCHEMA-T-I64 0 0 0 0
        _SSC-SCHEMA 170 + _SSC-SCHEMA-NODE! ;

