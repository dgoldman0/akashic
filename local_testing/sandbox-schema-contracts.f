: _SSC-STATUS-CONTRACTS  ( -- )
    SBOX-SCHEMA-S-OK SBOX-SCHEMA-STATUS-VALID? _SSC-ASSERT
    SBOX-SCHEMA-S-MALFORMED-SCHEMA
        SBOX-SCHEMA-STATUS-VALID? _SSC-ASSERT
    SBOX-SCHEMA-S-MALFORMED-VALUE
        SBOX-SCHEMA-STATUS-VALID? _SSC-ASSERT
    SBOX-SCHEMA-S-VALUE-MISMATCH
        SBOX-SCHEMA-STATUS-VALID? _SSC-ASSERT
    -1 SBOX-SCHEMA-STATUS-VALID? 0= _SSC-ASSERT
    10 SBOX-SCHEMA-STATUS-VALID? 0= _SSC-ASSERT
    _SSC-STACK ;

: _SSC-RUN  ( -- )
    0 _SSC-FAILS !
    0 _SSC-CHECKS !
    DEPTH _SSC-DEPTH !
    ." SBOX SCHEMA CONTRACTS START" CR
    _SSC-BUILD-FIXTURES
    _SSC-WORKSPACE-CONTRACTS
    _SSC-SCHEMA-CONTRACTS
    _SSC-VALUE-CONTRACTS
    _SSC-STATUS-CONTRACTS
    _SSC-STACK
    _SSC-FAILS @ 0= IF
        ." SBOX SCHEMA CONTRACTS PASS " _SSC-CHECKS @ . CR
    ELSE
        ." SBOX SCHEMA CONTRACTS FAIL " _SSC-FAILS @ . CR
    THEN ;

[DEFINED] SBOX-SCHEMA-DEFER-AUTORUN [IF]
[ELSE]
    _SSC-RUN
[THEN]
