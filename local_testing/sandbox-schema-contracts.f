: _SSC-WORKSPACE-CONTRACTS  ( -- )
    _SSC-WORK-DEPTH SBOX-SCHEMA-WORKSPACE-MEASURE
        SBOX-SCHEMA-S-OK =
        SWAP _SSC-WORK-BYTES = AND _SSC-ASSERT
    0 SBOX-SCHEMA-WORKSPACE-MEASURE
        SBOX-SCHEMA-S-INVALID = SWAP 0= AND _SSC-ASSERT

    _SSC-WORK-DEPTH _SSC-WORK _SSC-WORK-BYTES
        SBOX-SCHEMA-WORKSPACE-INIT
        SBOX-SCHEMA-S-OK = _SSC-ASSERT
    _SSC-WORK SBOX-SCHEMA-WORKSPACE-VALID?
        _SSC-ASSERT
    _SSC-WORK SBOX-SCHEMA-WORKSPACE-MAX-DEPTH@
        _SSC-WORK-DEPTH = _SSC-ASSERT

    _SSC-SHALLOW-DEPTH _SSC-SHALLOW-WORK
        _SSC-SHALLOW-WORK-BYTES SBOX-SCHEMA-WORKSPACE-INIT
        SBOX-SCHEMA-S-OK = _SSC-ASSERT
    _SSC-SHALLOW-WORK SBOX-SCHEMA-WORKSPACE-VALID?
        _SSC-ASSERT
    _SSC-STACK ;

: _SSC-SCHEMA-CONTRACTS  ( -- )
    _SSC-SCHEMA 202 _SSC-WORK SBOX-SCHEMA-VALIDATE
        SBOX-SCHEMA-S-OK = _SSC-ASSERT
    _SSC-WORK SBOX-SCHEMA-WORKSPACE-SCHEMA-NODES@
        4 = _SSC-ASSERT
    _SSC-WORK SBOX-SCHEMA-WORKSPACE-SCHEMA-DEPTH@
        3 = _SSC-ASSERT

    \ Canonical bytes are relocatable data, not a self-bound native object.
    _SSC-SCHEMA _SSC-SCHEMA-COPY 202 MOVE
    _SSC-SCHEMA-COPY 202 _SSC-WORK SBOX-SCHEMA-VALIDATE
        SBOX-SCHEMA-S-OK = _SSC-ASSERT

    \ Complete-span validation rejects a trailing byte.
    _SSC-SCHEMA 203 _SSC-WORK SBOX-SCHEMA-VALIDATE
        SBOX-SCHEMA-S-MALFORMED-SCHEMA = _SSC-ASSERT

    \ Required/optional is a closed exact flag, not an extensible bitmap.
    _SSC-SCHEMA _SSC-SCHEMA-COPY 202 MOVE
    3 _SSC-SCHEMA-COPY 120 + C!
    _SSC-SCHEMA-COPY 202 _SSC-WORK SBOX-SCHEMA-VALIDATE
        SBOX-SCHEMA-S-MALFORMED-SCHEMA = _SSC-ASSERT

    \ Field keys must be strictly sorted by raw UTF-8 bytes.
    _SSC-SCHEMA _SSC-SCHEMA-COPY 202 MOVE
    [CHAR] z _SSC-SCHEMA-COPY 80 + C!
    _SSC-SCHEMA-COPY 202 _SSC-WORK SBOX-SCHEMA-VALIDATE
        SBOX-SCHEMA-S-MALFORMED-SCHEMA = _SSC-ASSERT

    \ Declared depth above caller workspace is a capacity result.
    _SSC-SCHEMA 202 _SSC-SHALLOW-WORK SBOX-SCHEMA-VALIDATE
        SBOX-SCHEMA-S-CAPACITY = _SSC-ASSERT
    _SSC-STACK ;

