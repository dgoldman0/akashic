8    CONSTANT _SSC-WORK-DEPTH
1776 CONSTANT _SSC-WORK-BYTES
2    CONSTANT _SSC-SHALLOW-DEPTH
528  CONSTANT _SSC-SHALLOW-WORK-BYTES

: _SSC-ALIGN8  ( address -- aligned-address ) 7 + -8 AND ;

CREATE _SSC-WORK-RAW _SSC-WORK-BYTES 7 + ALLOT
_SSC-WORK-RAW _SSC-ALIGN8 CONSTANT _SSC-WORK
CREATE _SSC-SHALLOW-WORK-RAW _SSC-SHALLOW-WORK-BYTES 7 + ALLOT
_SSC-SHALLOW-WORK-RAW _SSC-ALIGN8 CONSTANT _SSC-SHALLOW-WORK

CREATE _SSC-SCHEMA 256 ALLOT
CREATE _SSC-SCHEMA-COPY 256 ALLOT
