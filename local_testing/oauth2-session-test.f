: _O2ST-ASSERT  ( flag -- )
    1 _O2ST-CHECKS +!
    0= IF
        1 _O2ST-FAILS +!
        ." OAUTH2 SESSION ASSERT " _O2ST-CHECKS @ . CR
    THEN ;

: _O2ST-STACK  ( -- )
    DEPTH DUP _O2ST-DEPTH @ <> IF
        ." OAUTH2 SESSION STACK "
        _O2ST-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _O2ST-DEPTH @ = _O2ST-ASSERT ;

: _O2ST-ZERO?  ( address length -- flag )
    BEGIN
        DUP
    WHILE
        OVER C@ IF 2DROP 0 EXIT THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP -1 ;

: _O2ST-ALLOCATE  ( size variable -- )
    >R ALLOCATE ABORT" OAUTH2 SESSION FAIL allocation"
    R> ! ;

: _O2ST-FREE  ( variable -- )
    DUP @ ?DUP IF FREE 0 SWAP ! ELSE DROP THEN ;

: _O2ST-EXPECT  ( address length -- )
