    _O2ST-EXPECTED-A ! ;

: _O2ST-EXPECT-CALLBACK
  ( address length callback-context -- callback-result )
    >R
    _O2ST-EXPECTED-A @ _O2ST-EXPECTED-U @
    COMPARE 0= _O2ST-ASSERT
    R> ;

: _O2ST-REENTER-CALLBACK
  ( address length session -- callback-result )
    >R 2DROP
    R@ O2SESSION-STATE@
    DUP _O2ST-REENTRY-STATUS !
    O2SESSION-S-BUSY = _O2ST-ASSERT
    2DROP
    R> DROP 91 ;

: _O2ST-THROW-CALLBACK
  ( address length callback-context -- callback-result )
    2DROP DROP -3391 THROW ;

: _O2ST-BAD-STACK-CALLBACK
  ( address length callback-context -- malformed-results )
    2DROP DROP 17 18 ;

: _O2ST-GEN-OK  ( generation status -- )
    DUP O2SESSION-S-OK = _O2ST-ASSERT
    DROP
