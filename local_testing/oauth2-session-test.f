    ." OAUTH2 SESSION CALLBACK READY" CR TX-FLUSH
    KEY DROP
    _O2ST-RECOVERY-AND-LOGOUT _O2ST-STACK
    ." OAUTH2 SESSION RECOVERY" CR TX-FLUSH
    _O2ST-CLEANUP _O2ST-STACK

    _O2ST-FAILS @ 0= IF
        ." OAUTH2 SESSION PASS " _O2ST-CHECKS @ . CR
    ELSE
        ." OAUTH2 SESSION FAIL " _O2ST-FAILS @ . CR
    THEN ;
