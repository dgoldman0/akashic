: _O2ST-CHECK-STATE  ( generation phase session -- )
    O2SESSION-STATE@
    DUP O2SESSION-S-OK = _O2ST-ASSERT
    DROP
    2 PICK = _O2ST-ASSERT
    SWAP DROP
    = _O2ST-ASSERT ;

: _O2ST-CHECK-BORROW
  ( expected-a expected-u selector session -- )
    >R >R
    2DUP _O2ST-EXPECT
    2DROP
    R> 1 = IF
        ['] _O2ST-EXPECT-CALLBACK 77 R@
        O2SESSION-WITH-ACCESS
    ELSE
        ['] _O2ST-EXPECT-CALLBACK 77 R@
        O2SESSION-WITH-ID
    THEN
    DUP O2SESSION-S-OK = _O2ST-ASSERT
    DROP 77 = _O2ST-ASSERT
    R> DROP ;

