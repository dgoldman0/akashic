: _O2ST-RUN  ( -- )
    ." OAUTH2 SESSION START" CR TX-FLUSH
    0 _O2ST-FAILS !
    0 _O2ST-CHECKS !
    0 _O2ST-GENERATION !
    DEPTH _O2ST-DEPTH !
    OAUTH2-SESSION-SIZE _O2ST-SESSION-A _O2ST-ALLOCATE
    ." OAUTH2 SESSION ALLOC A" CR TX-FLUSH
    OAUTH2-SESSION-SIZE _O2ST-SESSION-B _O2ST-ALLOCATE
    ." OAUTH2 SESSION ALLOC B" CR TX-FLUSH
    CVAULT-SIZE _O2ST-VAULT _O2ST-ALLOCATE
    ." OAUTH2 SESSION ALLOC V" CR TX-FLUSH
    _O2ST-SESSION-A @ OAUTH2-SESSION-SIZE 0 FILL
    ." OAUTH2 SESSION FILL A" CR TX-FLUSH
    _O2ST-SESSION-B @ OAUTH2-SESSION-SIZE 0 FILL
    ." OAUTH2 SESSION FILL B" CR TX-FLUSH
    _O2ST-VAULT @ CVAULT-SIZE 0 FILL
    ." OAUTH2 SESSION FILL V" CR TX-FLUSH
    _O2ST-RID RID-SIZE 0x5A FILL
    _O2ST-OTHER-RID RID-SIZE 0xA5 FILL
    ." OAUTH2 SESSION RID" CR TX-FLUSH

    _O2ST-INITIAL-INSTALL _O2ST-STACK
    ." OAUTH2 SESSION INSTALL" CR TX-FLUSH
    _O2ST-REBOOT-AND-BINDING _O2ST-STACK
    ." OAUTH2 SESSION BINDING" CR TX-FLUSH
