: _RBT-L3-FETCH-HANDLER ( request instance -- status )
    _RBT-L3-HANDLER-INSTANCE ! _RBT-L3-REQUEST !
    _RBT-L3-HANDLER-INSTANCE @ _RBT-L3-TARGET @ <> IF
        CBUS-S-FAILED EXIT
    THEN
    _RBT-L3-REQUEST @ CBR.ARGS _RBT-L3-STATE-VALUE? 0= IF
        CBUS-S-FAILED EXIT
    THEN
    _RBT-L3-REQUEST @ _RBT-L3-WORLD _RBT-L3-SNAPSHOT! IF
        CBUS-S-OK
    ELSE
        CBUS-S-FAILED
    THEN ;

