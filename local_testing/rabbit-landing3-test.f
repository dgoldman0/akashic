: _RBT-L3-RETAIN-RESULT ( request world -- flag )
    _RBT-L3-HANDLER-WORLD ! DUP _RBT-L3-REQUEST !
    _RBT-L3-RESULT-ENCODE DUP IF 2DROP DROP 0 EXIT THEN DROP
    _RBT-L3-REQUEST @ -ROT
        _RBT-L3-HANDLER-WORLD @ _RBT-L3-LEDGER-ADD ;

: _RBT-L3-ACTION-HANDLER ( request instance -- status )
    _RBT-L3-HANDLER-INSTANCE ! _RBT-L3-REQUEST !
    _RBT-L3-HANDLER-INSTANCE @ _RBT-L3-TARGET @ <> IF
        CBUS-S-FAILED EXIT
    THEN
    _RBT-L3-REQUEST @ CBR.ARGS _RBT-L3-ACTION-VALUE? 0= IF
        CBUS-S-FAILED EXIT
    THEN
    _RBT-L3-REQUEST @ CBR.PRINCIPAL @ CPRINC-COMPONENT <> IF
        CBUS-S-DENIED EXIT
    THEN
    _RBT-L3-REQUEST @ CBR.FLAGS @ CBR-F-APPROVED AND 0= IF
        CBUS-S-DENIED EXIT
    THEN
    _RBT-L3-REQUEST @ CBR.ARGS-SEAL-FLAGS @
        CBR-ASF-TYPED-IVJSON-SHA3 AND 0= IF
        CBUS-S-DENIED EXIT
    THEN
    _RBT-L3-REQUEST @ CBR-ARGS-SEAL-MATCH? 0= IF CBUS-S-DENIED EXIT THEN
    _RBT-L3-REQUEST @ CBR.INVOCATION-ID RID-PRESENT? 0= IF
        CBUS-S-INVALID EXIT
    THEN

    _RBT-L3-REQUEST @ _RBT-L3-WORLD _RBT-L3-LEDGER-FIND ?DUP IF
        DUP _RBT-L3-REQUEST @ _RBT-L3-SAME-ARGS? IF
            _RBT-L3-REQUEST @ _RBT-L3-LEDGER-RECEIPT! 0= IF
                CBUS-S-FAILED EXIT
            THEN
        ELSE
            DROP 2 _RBT-L3-REQUEST @ _RBT-L3-WORLD
                _RBT-L3-RECEIPT! 0= IF CBUS-S-FAILED EXIT THEN
        THEN
        CBUS-S-NO-EFFECT EXIT
    THEN

    1 _RBT-L3-WORLD L3W.EXPECTED-CHECKS +!
    1 _RBT-L3-REQUEST @ CBR.ARGS CV-LIST-NTH CV-DATA@
        _RBT-L3-EXPECTED !
    2 _RBT-L3-REQUEST @ CBR.ARGS CV-LIST-NTH CV-DATA@
        _RBT-L3-NEW-VALUE !
    _RBT-L3-REQUEST @ CBR.CONTEXT-ID @ _RBT-L3-ACTOR !
    _RBT-L3-ACTOR @ DUP 1 = SWAP 2 = OR 0= IF CBUS-S-DENIED EXIT THEN
    _RBT-L3-WORLD _RBT-L3-LEDGER-ROOM? 0= IF
        3 _RBT-L3-REQUEST @ _RBT-L3-WORLD _RBT-L3-RECEIPT! DROP
        CBUS-S-NO-EFFECT EXIT
    THEN
    _RBT-L3-EXPECTED @ _RBT-L3-WORLD L3W.REVISION @ <> IF
        1 _RBT-L3-REQUEST @ _RBT-L3-WORLD _RBT-L3-RECEIPT! 0= IF
            CBUS-S-FAILED EXIT
        THEN
        _RBT-L3-REQUEST @ _RBT-L3-WORLD _RBT-L3-RETAIN-RESULT 0= IF
            CBUS-S-FAILED EXIT
        THEN
        CBUS-S-NO-EFFECT EXIT
    THEN

    _RBT-L3-WORLD L3W.REVISION @ 1+
    _RBT-L3-WORLD L3W.EVENT-SEQ @ 1+
    _RBT-L3-NEW-VALUE @ _RBT-L3-ACTOR @ _RBT-L3-EVENT-BUILD 0= IF
        CBUS-S-FAILED EXIT
    THEN
    0 _RBT-L3-REQUEST @ _RBT-L3-WORLD _RBT-L3-RECEIPT! 0= IF
        CBUS-S-FAILED EXIT
    THEN
    \ Patch the accepted receipt with the preflighted next state.
    _RBT-L3-REQUEST @ CBR.RESULT _RBT-L3-LIST !
    _RBT-L3-WORLD L3W.REVISION @ 1+ 2 _RBT-L3-LIST-INT!
    _RBT-L3-WORLD L3W.EVENT-SEQ @ 1+ 3 _RBT-L3-LIST-INT!
    _RBT-L3-NEW-VALUE @ 4 _RBT-L3-LIST-INT!
    _RBT-L3-REQUEST @ _RBT-L3-WORLD _RBT-L3-RETAIN-RESULT 0= IF
