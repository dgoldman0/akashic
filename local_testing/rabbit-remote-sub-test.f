    _RBT-RRSUB-EV-LANE @ 1 <> IF 72 EXIT THEN
    _RBT-RRSUB-EV-LANE-SEQ @ 0= IF 79 EXIT THEN
    _RBT-RRSUB-EV-EVENT-SEQ @ 0= IF 80 EXIT THEN
    _RBT-RRSUB-EV-DELIVERY @ DUP RSUB-DELIVERY-NEW =
    SWAP RSUB-DELIVERY-DUPLICATE = OR 0= IF 73 EXIT THEN
    _RBT-RRSUB-EV-V @ 0= IF 74 EXIT THEN
    _RBT-RRSUB-EV-U @ 0= IF 81 EXIT THEN
    _RBT-RRSUB-EV-A @ C@ [CHAR] [ = IF
        _RBT-RRSUB-EV-V @ CV-TYPE@ CV-T-LIST <> IF 82 EXIT THEN
    ELSE
        _RBT-RRSUB-EV-V @ CV-TYPE@ CV-T-INT <> IF 83 EXIT THEN
    THEN
    _RBT-RRSUB-EV-MODE @ 87 = IF 87 EXIT THEN
    _RBT-RRSUB-EV-MODE @ -1 = IF -701 THROW THEN
    _RBT-RRSUB-EV-MODE @ 2 = IF 0 0 EXIT THEN
    _RBT-RRSUB-EV-U @ _RBT-RRSUB-EV-SLOT-BYTES U> IF 75 EXIT THEN
    _RBT-RRSUB-EV-EVENT-SEQ @ _RBT-RRSUB-EV-FIND IF
        _RBT-RRSUB-EV-I !
        _RBT-RRSUB-EV-I @ _RBT-RRSUB-EV-LEN @
            _RBT-RRSUB-EV-U @ <> IF 76 EXIT THEN
        _RBT-RRSUB-EV-A @ _RBT-RRSUB-EV-U @
            _RBT-RRSUB-EV-I @ _RBT-RRSUB-EV-DATA
            _RBT-RRSUB-EV-U @ COMPARE 0= IF 0 ELSE 77 THEN EXIT
    THEN
    DROP
    _RBT-RRSUB-EV-N @ _RBT-RRSUB-EV-CAP >= IF 78 EXIT THEN
    _RBT-RRSUB-EV-N @ _RBT-RRSUB-EV-I !
    _RBT-RRSUB-EV-EVENT-SEQ @ _RBT-RRSUB-EV-I @ _RBT-RRSUB-EV-SEQ !
    _RBT-RRSUB-EV-U @ _RBT-RRSUB-EV-I @ _RBT-RRSUB-EV-LEN !
