: _SVC-ASSERT  ( flag -- )
    1 _SVC-CHECKS +!
    0= IF
        1 _SVC-FAILS +!
        ." SBOX VALUE ASSERT " _SVC-CHECKS @ . CR
    THEN ;

: _SVC-STACK  ( -- )
    DEPTH DUP _SVC-DEPTH @ <> IF
        ." SBOX VALUE STACK " _SVC-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _SVC-DEPTH @ = _SVC-ASSERT ;

: _SVC-FILLED?  ( address length byte -- flag )
    _SVC-BYTE !
    0 ?DO
        DUP I + C@ _SVC-BYTE @ <> IF
            DROP 0 UNLOOP EXIT
        THEN
    LOOP
    DROP -1 ;

: _SVC-BYTES=?  ( a b u -- flag )
    0 ?DO
        2DUP I + C@ SWAP I + C@ <> IF
            2DROP 0 UNLOOP EXIT
        THEN
    LOOP
    2DROP -1 ;

: _SVC-WIRE-HEADER!  ( tag count payload address -- )
    DUP SBOX-VALUE-WIRE-HEADER-SIZE 0 FILL
    3 PICK OVER C!
    2 PICK OVER 4 + _SVAL-U32!
    8 + _SVAL-U64!
    2DROP ;

: _SVC-LIMIT!  ( value field -- )
    _SVC-LIMITS SBOX-VALUE-LIMIT!
    SBOX-VALUE-S-OK = _SVC-ASSERT ;

: _SVC-LIMITS-INIT  ( -- )
    _SVC-LIMITS SBOX-VALUE-LIMITS-BEGIN
        SBOX-VALUE-S-OK = _SVC-ASSERT
       8 SBOX-VALUE-LIMIT-DEPTH _SVC-LIMIT!
      64 SBOX-VALUE-LIMIT-BLOB-BYTES _SVC-LIMIT!
       8 SBOX-VALUE-LIMIT-LIST-COUNT _SVC-LIMIT!
       4 SBOX-VALUE-LIMIT-MAP-COUNT _SVC-LIMIT!
      32 SBOX-VALUE-LIMIT-INPUT-NODES _SVC-LIMIT!
    4096 SBOX-VALUE-LIMIT-INPUT-BYTES _SVC-LIMIT!
      32 SBOX-VALUE-LIMIT-OUTPUT-ARENA-NODES _SVC-LIMIT!
    4096 SBOX-VALUE-LIMIT-OUTPUT-ARENA-BYTES _SVC-LIMIT!
      64 SBOX-VALUE-LIMIT-OUTPUT-RESULT-NODES _SVC-LIMIT!
    8192 SBOX-VALUE-LIMIT-OUTPUT-RESULT-BYTES _SVC-LIMIT!
    _SVC-LIMITS SBOX-VALUE-LIMITS-SEAL
        SBOX-VALUE-S-OK = _SVC-ASSERT
    _SVC-LIMITS SBOX-VALUE-LIMITS-VALID? _SVC-ASSERT
    SBOX-VALUE-LIMIT-DEPTH _SVC-LIMITS SBOX-VALUE-LIMIT@
        SBOX-VALUE-S-OK = SWAP 8 = AND _SVC-ASSERT
    _SVC-LIMITS SBOX-VALUE-WORK-MEASURE
        SBOX-VALUE-S-OK = SWAP _SVC-WORK-U = AND _SVC-ASSERT ;

: _SVC-FIXTURES  ( -- )
    _SVC-NULL 16 0 FILL

    SBOX-VALUE-T-BOOL 0 8 _SVC-BOOL-FALSE _SVC-WIRE-HEADER!
    0 _SVC-BOOL-FALSE 16 + _SVAL-U64!

    SBOX-VALUE-T-BOOL 0 8 _SVC-BAD-BOOL _SVC-WIRE-HEADER!
    1 _SVC-BAD-BOOL 16 + _SVAL-U64!

    SBOX-VALUE-T-UTF8 0 2 _SVC-BAD-UTF8 _SVC-WIRE-HEADER!
    0xC0 _SVC-BAD-UTF8 16 + C!
    0x80 _SVC-BAD-UTF8 17 + C!

    \ MAP { "a": NULL, "b": false }, already in strict raw-byte order.
    SBOX-VALUE-T-MAP 2 74 _SVC-MAP _SVC-WIRE-HEADER!
    SBOX-VALUE-T-UTF8 0 1 _SVC-MAP 16 + _SVC-WIRE-HEADER!
    [CHAR] a _SVC-MAP 32 + C!
    _SVC-NULL _SVC-MAP 33 + 16 MOVE
    SBOX-VALUE-T-UTF8 0 1 _SVC-MAP 49 + _SVC-WIRE-HEADER!
    [CHAR] b _SVC-MAP 65 + C!
    _SVC-BOOL-FALSE _SVC-MAP 66 + 24 MOVE

    _SVC-MAP _SVC-MAP-DUP 90 MOVE
    [CHAR] a _SVC-MAP-DUP 65 + C!

    _SVC-MAP _SVC-MAP-ORDER 90 MOVE
    [CHAR] b _SVC-MAP-ORDER 32 + C!
    [CHAR] a _SVC-MAP-ORDER 65 + C! ;

: _SVC-DECODE  ( source source-u -- status )
    _SVC-LIMITS _SVC-WORK _SVC-WORK-U
    _SVC-INPUT 2048 SBOX-VALUE-INPUT-DECODE NIP ;

