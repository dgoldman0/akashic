: _SVC-RUN  ( -- )
    0 _SVC-FAILS !
    0 _SVC-CHECKS !
    DEPTH _SVC-DEPTH !
    ." SBOX VALUE CONTRACTS START" CR TX-FLUSH
    _SVC-LIMITS-INIT
    _SVC-FIXTURES
    _SVC-CODEC-CONTRACTS
    _SVC-STATE-CONTRACTS
    _SVC-CONSTRUCTOR-CONTRACTS
    _SVC-ENCODE-CONTRACTS
    _SVC-RELEASE-CONTRACTS
    _SVC-STACK
    _SVC-FAILS @ 0= IF
        ." SBOX VALUE CONTRACTS PASS " _SVC-CHECKS @ . CR TX-FLUSH
    ELSE
        ." SBOX VALUE CONTRACTS FAIL " _SVC-FAILS @ . CR TX-FLUSH
    THEN ;

[DEFINED] SBOX-VALUE-CONTRACTS-DEFER-AUTORUN [IF]
[ELSE]
    _SVC-RUN
[THEN]
