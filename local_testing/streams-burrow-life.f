\ =====================================================================
\ streams-burrow-life.f - real Streams Burrow lifecycle callback witness
\ =====================================================================
\ The focused linked driver preloads rabbit-capabilities.f before streams.f,
\ then loads the allocation-free scripted provider before this fixture.
\ This contract crosses the real applet lifecycle callbacks; the narrower
\ manager and capability fixtures retain responsibility for their own seams.
\
\ One declaration and two replay rows are exact fixture cardinalities for one
\ CREATE plus one UI START.  They are caller-owned storage, not product caps.
\ =====================================================================

PROVIDED akashic-test-srblife

VARIABLE _SBL-FAILS
VARIABLE _SBL-CHECKS
VARIABLE _SBL-DEPTH
VARIABLE _SBL-INSTANCE
VARIABLE _SBL-STATE
VARIABLE _SBL-HEAP-BASELINE
VARIABLE _SBL-STATUS
VARIABLE _SBL-CHANGED
VARIABLE _SBL-REVISION

: _SBL-ASSERT  ( flag -- )
    1 _SBL-CHECKS +!
    0= IF
        1 _SBL-FAILS +!
        ." STREAMS BURROW LIFECYCLE ASSERT " _SBL-CHECKS @ . CR
    THEN ;

: _SBL-STACK  ( -- )
    DEPTH DUP _SBL-DEPTH @ <> IF
        ." STREAMS BURROW LIFECYCLE STACK "
        _SBL-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _SBL-DEPTH @ = _SBL-ASSERT ;

: _SBL-ZERO?  ( address bytes -- flag )
    BEGIN
        DUP
    WHILE
        OVER C@ IF 2DROP 0 EXIT THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP -1 ;

: _SBL-RID!  ( rid byte -- )
    SWAP RID-SIZE ROT FILL ;

1 CONSTANT _SBL-ROW-CAPACITY
2 CONSTANT _SBL-REPLAY-CAPACITY

SBSP-SIZE
_SBL-ROW-CAPACITY SRBMGR-DECLARATION-SIZE * +
_SBL-REPLAY-CAPACITY SRBMGR-REPLAY-SIZE * +
SRBMGR-PLAN-SIZE + SRBPROV-GRAPH-SPEC-SIZE +
5 RID-SIZE * + CONSTANT _SBL-STORAGE-SIZE

CREATE _SBL-STORAGE-RAW _SBL-STORAGE-SIZE 7 + ALLOT

: _SBL-STORAGE  ( -- address ) _SBL-STORAGE-RAW 7 + -8 AND ;
: _SBL-PROVIDER  ( -- context ) _SBL-STORAGE ;
: _SBL-ROWS  ( -- rows ) _SBL-PROVIDER SBSP-SIZE + ;
: _SBL-REPLAYS  ( -- replays )
    _SBL-ROWS _SBL-ROW-CAPACITY SRBMGR-DECLARATION-SIZE * + ;
: _SBL-PLAN  ( -- plan )
    _SBL-REPLAYS _SBL-REPLAY-CAPACITY SRBMGR-REPLAY-SIZE * + ;
: _SBL-SPEC  ( -- spec ) _SBL-PLAN SRBMGR-PLAN-SIZE + ;
: _SBL-COLLECTION  ( -- rid )
    _SBL-SPEC SRBPROV-GRAPH-SPEC-SIZE + ;
: _SBL-REQUEST-DIGEST  ( -- rid ) _SBL-COLLECTION RID-SIZE + ;
: _SBL-INVOCATION  ( -- rid ) _SBL-REQUEST-DIGEST RID-SIZE + ;
: _SBL-ARGS-DIGEST  ( -- rid ) _SBL-INVOCATION RID-SIZE + ;
: _SBL-BURROW  ( -- rid ) _SBL-ARGS-DIGEST RID-SIZE + ;

: _SBL-MANAGER  ( -- manager )
    _SBL-INSTANCE @ _STM-ACTIVATE _STM-BURROW-MANAGER ;

: _SBL-DECL  ( -- declaration )
    _SBL-MANAGER SRBMGR.ROWS @ ;

: _SBL-CLOSE  ( -- decision )
    APP-CLOSE-R-WINDOW _SBL-INSTANCE @ STREAMS-REQUEST-CLOSE-CB ;

: _SBL-SHUTDOWN  ( -- )
    _SBL-INSTANCE @ STREAMS-SHUTDOWN-CB ;

: _SBL-FREE-INSTANCE  ( -- )
    _SBL-INSTANCE @ CINST-FREE 0 _SBL-INSTANCE ! ;

: _SBL-EXTERNAL-STORAGE-INIT  ( -- )
    _SBL-STORAGE _SBL-STORAGE-SIZE 0 FILL
    _SBL-PROVIDER SBSP-INIT SRBPROV-S-NONE = _SBL-ASSERT
    1 0 _SBL-PROVIDER SBSP-COUNTS! _SBL-ASSERT
    _SBL-PROVIDER SBSP-VALID? _SBL-ASSERT ;

: _SBL-SPEC-INIT  ( -- )
    _SBL-COLLECTION 0x31 _SBL-RID!
    _SBL-REQUEST-DIGEST 0x32 _SBL-RID!
    _SBL-INVOCATION 0x33 _SBL-RID!
    _SBL-ARGS-DIGEST 0x34 _SBL-RID!
    _SBL-SPEC SRBPROV-GRAPH-SPEC-INIT
    _SBL-COLLECTION
        _SBL-SPEC SRBPROV-SPEC.COLLECTION RID-COPY
    1 _SBL-SPEC SRBPROV-SPEC.COLLECTION-REVISION !
    _SBL-REQUEST-DIGEST
        _SBL-SPEC SRBPROV-SPEC.REQUEST-DIGEST RID-COPY
    1 _SBL-SPEC SRBPROV-SPEC.PEER-CAPACITY !
    _SBL-SPEC SRBPROV-GRAPH-SPEC-VALID? _SBL-ASSERT ;

: _SBL-CREATE  ( -- )
    _SBL-SPEC _SBL-INVOCATION SRBPROV-GRAPH-SPEC-SIZE
        _SBL-ARGS-DIGEST _SBL-PLAN _SBL-MANAGER SRBMGR-PLAN-CREATE
        SRBPROV-S-NONE = _SBL-ASSERT
    _SBL-PLAN SRBMGR-PLAN-FRESH? _SBL-ASSERT
    _SBL-PLAN SRBMGR-PLAN.RESULT SRBMGR-RESULT.BURROW
        _SBL-BURROW RID-COPY
    _SBL-PLAN _SBL-MANAGER SRBMGR-COMMIT
        _SBL-STATUS ! _SBL-CHANGED !
    _SBL-STATUS @ SRBPROV-S-NONE = _SBL-ASSERT
    _SBL-CHANGED @ -1 = _SBL-ASSERT
    _SBL-MANAGER SRBMGR.ROW-COUNT @ 1 = _SBL-ASSERT
    _SBL-MANAGER SRBMGR.REPLAY-COUNT @ 1 = _SBL-ASSERT
    _SBL-DECL SRBMGR-DECL.STATE @
        SRBMGR-STATE-CONFIGURED = _SBL-ASSERT
    _SBL-DECL SRBMGR-DECL.DOMAIN-REVISION @ 1 = _SBL-ASSERT
    _SBL-DECL SRBMGR-DECL.BURROW _SBL-BURROW RID= _SBL-ASSERT ;

: _SBL-PREPARE  ( -- )
    0 _SBL-FAILS ! 0 _SBL-CHECKS ! DEPTH _SBL-DEPTH !
    _SBL-DEPTH @ 0= _SBL-ASSERT
    _STM-BURROW-BUILD? _SBL-ASSERT
    STREAMS-BURROW-CAPABILITY-COUNT 4 = _SBL-ASSERT
    _SBL-EXTERNAL-STORAGE-INIT
    _STREAMS-COMP-SETUP
    STREAMS-COMP-DESC COMP.CAPS-N @ 19 = _SBL-ASSERT
    HEAP-FREE-BYTES _SBL-HEAP-BASELINE !
    STREAMS-COMP-DESC CINST-NEW _SBL-STATUS ! _SBL-INSTANCE !
    _SBL-STATUS @ 0= _SBL-ASSERT
    _SBL-INSTANCE @ 0<> _SBL-ASSERT
    _SBL-INSTANCE @ CINST-STATE _SBL-STATE !
    _SBL-ROWS _SBL-ROW-CAPACITY
        _SBL-REPLAYS _SBL-REPLAY-CAPACITY
        _SBL-PROVIDER SBSP-PROVIDER _SBL-STATE @
        STREAMS-BURROW-COMPOSITION-STATE!
        SRBPROV-S-NONE = _SBL-ASSERT
    _SBL-INSTANCE @ STREAMS-INIT-CB
    _SBL-INSTANCE @ _STM-ACTIVATE
    _STM-BURROW-READY? _SBL-ASSERT
    _STM-BURROW-INIT-STATUS @ SRBPROV-S-NONE = _SBL-ASSERT
    _SBL-MANAGER SRBMGR.ROWS @ _SBL-ROWS = _SBL-ASSERT
    _SBL-MANAGER SRBMGR.REPLAYS @ _SBL-REPLAYS = _SBL-ASSERT
    _SBL-MANAGER SRBMGR.PROVIDER @
        _SBL-PROVIDER SBSP-PROVIDER = _SBL-ASSERT
    _SBL-SPEC-INIT _SBL-CREATE
    _SBL-INSTANCE @ CINST.REVISION @ _SBL-REVISION !
    SRBMGR-OP-START _STM-BURROW-UI-MUTATE
        SRBPROV-S-NONE = _SBL-ASSERT
    _SBL-MANAGER SRBMGR.REPLAY-COUNT @ 2 = _SBL-ASSERT
    _SBL-DECL SRBMGR-DECL.STATE @ SRBMGR-STATE-STARTING = _SBL-ASSERT
    _SBL-DECL SRBMGR-DECL.DOMAIN-REVISION @ 2 = _SBL-ASSERT
    _SBL-INSTANCE @ CINST.REVISION @
        _SBL-REVISION @ 1+ = _SBL-ASSERT
    _SBL-MANAGER SRBMGR-VALID? _SBL-ASSERT
    _SBL-STACK ;

