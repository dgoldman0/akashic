CREATE _STC-BYTE 8 ALLOT

: _STC-ASSERT  ( flag -- )
    1 _STC-CHECKS +!
    0= IF
        1 _STC-FAILS +!
        ." SBOX MODULE STORE ASSERT " _STC-CHECKS @ . CR
    THEN ;

: _STC-IS  ( status expected -- ) = _STC-ASSERT ;

: _STC-STACK  ( -- )
    DEPTH DUP _STC-DEPTH @ <> IF
        ." SBOX MODULE STORE STACK "
        _STC-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _STC-DEPTH @ = _STC-ASSERT ;

: _STC-CAT$  ( -- address length ) S" /sbx-catalog.bin" ;
: _STC-PACK$  ( -- address length ) S" /sbx-pack.bin" ;

\ The RID whose first byte is N and whose other bytes are 7.
: _STC-RID!  ( n -- rid ) _STC-RID 32 7 FILL _STC-RID C! _STC-RID ;
\ The operation key whose every byte is N.
: _STC-KEY!  ( n -- key ) _STC-KEY 32 ROT FILL _STC-KEY ;

: _STC-ECHO  ( -- address length )
    S" FUNCTION echo PARAMS 1 RESULTS 1 LOCALS 0 DUP V.TYPE DROP RETURN END ENTRY SIGNATURE 1 main echo" ;

: _STC-INC  ( -- address length )
    S" FUNCTION increment PARAMS 1 RESULTS 1 LOCALS 0 V.I64.GET 1 I64.ADD V.NEW.I64 RETURN END ENTRY SIGNATURE 1 main increment" ;

\ Builds SOURCE into the empty build record and notes its artifact digest.
: _STC-BUILD!  ( source source-u -- )
    _STC-PROFILE 0 _STC-BUILD SBOX-BUILD SBOX-BUILD-S-OK _STC-IS
    _STC-BUILD SBOX-BUILD-PLAN@ SBOX-BUILD-S-OK _STC-IS
    SBOX-PLAN-ARTIFACT-DIGEST@ _STC-ART-DIGEST 32 MOVE ;

\ The declaration of module N at REVISION for the artifact digest noted,
\ with one entry named by _STC-ENTRY-A and _STC-ENTRY-U.
: _STC-DECLARE  ( n revision -- declaration declaration-u )
    1 0 24 SBOX-DECL-MEASURE SBOX-DECL-S-OK _STC-IS _STC-DECL-U !
    >R _STC-RID! R> _STC-ART-DIGEST _STC-PROFILE SBOX-PROFILE-DIGEST@
    1 0 24 _STC-DECL _STC-DECL-U @ SBOX-DECL-START SBOX-DECL-S-OK _STC-IS
    0 _STC-ENTRY-A @ _STC-ENTRY-U @ 1 _STC-DECL SBOX-DECL-ENTRY!
        SBOX-DECL-S-OK _STC-IS
    0 _STC-SCHEMA 12 _STC-SCHEMA 12 _STC-DECL-WS _STC-DECL
        SBOX-DECL-SCHEMAS! SBOX-DECL-S-OK _STC-IS
    _STC-DECL _STC-DECL-U @ ;

\ Builds SOURCE and installs module N at REVISION as operation KEY-N.
\ The build record is empty again afterward.
: _STC-INSTALL  ( key-n n revision source source-u -- module status )
    _STC-BUILD!
    _STC-DECLARE ROT _STC-KEY! -ROT _STC-BUILD _STC-STORE SBOX-STORE-INSTALL
    _STC-BUILD SBOX-BUILD-RELEASE SBOX-BUILD-S-OK _STC-IS ;

: _STC-FIND  ( n revision -- module|0 )
    >R _STC-RID! R> _STC-OWNER SBOX-MODULE-FIND ;

: _STC-STATE  ( n revision -- state|0 )
    _STC-FIND DUP IF SBOX-MODULE-STATE@ THEN ;

: _STC-REASON  ( n revision -- reason ) _STC-FIND SBOX-MODULE-REASON@ DROP ;

: _STC-FLAGS  ( n revision -- flags|-1 )
    >R _STC-RID! R> _STC-STORE SBOX-STORE-RECORD-FLAGS@ ;

: _STC-GENERATION  ( -- n ) _STC-STORE SBOX-STORE-GENERATION@ ;

\ Closes the store, forgets every module, and opens it again over the
\ same files for an owner bound to PROFILE.
: _STC-REBOOT-FOR  ( profile -- )
    _STC-STORE SBOX-STORE-CLOSE SBOX-STORE-S-OK _STC-IS
    _STC-OWNER SBOX-MODULE-OWNER-RELEASE SBOX-MODULE-S-OK _STC-IS
    _STC-OWNER SBOX-MODULE-OWNER-INIT SBOX-MODULE-S-OK _STC-IS
    _STC-STORE SBOX-STORE-OPEN SBOX-STORE-S-OK _STC-IS ;

: _STC-REBOOT  ( -- ) _STC-PROFILE _STC-REBOOT-FOR ;

\ =====================================================================
\  Files
\ =====================================================================

: _STC-OPEN  ( path path-u flags -- fd )
    _STC-VFS @ VFS-OPEN? 0= _STC-ASSERT ;

: _STC-READ-FILE  ( path path-u -- )
    VFS-FF-READ _STC-OPEN >R
    R@ VFS-SIZE DUP _STC-FILE-U ! 65536 <= _STC-ASSERT
    _STC-FILE _STC-FILE-U @ R@ VFS-READ-EXACT 0= _STC-ASSERT
    R> VFS-CLOSE? DROP ;

\ Flips the low bit of the byte at OFFSET.
: _STC-FLIP  ( offset path path-u -- )
    VFS-FF-READ VFS-FF-WRITE OR _STC-OPEN >R
    DUP R@ VFS-SEEK? 0= _STC-ASSERT
    _STC-BYTE 1 R@ VFS-READ-EXACT 0= _STC-ASSERT
    _STC-BYTE C@ 1 XOR _STC-BYTE C!
    R@ VFS-SEEK? 0= _STC-ASSERT
    _STC-BYTE 1 R@ VFS-WRITE-EXACT 0= _STC-ASSERT
    R> VFS-CLOSE? DROP ;

: _STC-TRUNCATE  ( size path path-u -- )
    VFS-FF-READ VFS-FF-WRITE OR _STC-OPEN >R
    R@ VFS-TRUNCATE 0= _STC-ASSERT
    R> VFS-CLOSE? DROP ;

\ Where the pack read into _STC-FILE holds the object (KIND, DIGEST):
\ the offset of its bytes and their length, or 0 0.
: _STC-OBJECT  ( kind digest -- offset length )
    64 BEGIN DUP _STC-FILE-U @ < WHILE
        _STC-FILE OVER + DUP SBOX-BYTE-U32-LE@ 4 PICK =
        OVER 16 + 32 5 PICK 32 COMPARE 0= AND IF
            8 + SBOX-BYTE-U64-LE@ >R 48 + NIP NIP R> EXIT
        THEN
        8 + SBOX-BYTE-U64-LE@ 7 + -8 AND 48 + +
    REPEAT
    DROP 2DROP 0 0 ;

