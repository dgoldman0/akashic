: _STC-ALIGN8  ( address -- aligned-address ) 7 + -8 AND ;

CREATE _STC-PROFILE-RAW SBOX-PROFILE-SIZE 7 + ALLOT
_STC-PROFILE-RAW _STC-ALIGN8 CONSTANT _STC-PROFILE
CREATE _STC-QUAL-RAW SBOX-PROFILE-SIZE 7 + ALLOT
_STC-QUAL-RAW _STC-ALIGN8 CONSTANT _STC-QUAL
CREATE _STC-LOAD-RAW SBOX-PROFILE-LOAD-WORKSPACE-SIZE 7 + ALLOT
_STC-LOAD-RAW _STC-ALIGN8 CONSTANT _STC-LOAD
CREATE _STC-OWNER-RAW SBOX-MODULE-OWNER-SIZE 7 + ALLOT
_STC-OWNER-RAW _STC-ALIGN8 CONSTANT _STC-OWNER
CREATE _STC-STORE-RAW SBOX-STORE-SIZE 7 + ALLOT
_STC-STORE-RAW _STC-ALIGN8 CONSTANT _STC-STORE
CREATE _STC-BUILD-RAW SBOX-BUILD-SIZE 7 + ALLOT
_STC-BUILD-RAW _STC-ALIGN8 CONSTANT _STC-BUILD
CREATE _STC-DECL-RAW 1024 7 + ALLOT
_STC-DECL-RAW _STC-ALIGN8 CONSTANT _STC-DECL
