: _STC-SETUP  ( -- )
    S" AKSCHEMA" _STC-SCHEMA SWAP MOVE
    _STC-SCHEMA 8 + 4 0 FILL
    4 _STC-SCHEMA 8 + C!
    S" main" _STC-ENTRY-U ! _STC-ENTRY-A !
    _STC-PROFILE _STC-LOAD SBOX-PROFILE-PURE-INIT SBOX-PROFILE-S-OK _STC-IS
    _STC-QUAL _STC-LOAD SBOX-QUALIFICATION-INIT SBOX-PROFILE-S-OK _STC-IS
    _STC-BUILD SBOX-BUILD-SIZE 0 FILL
    _STC-BUILD SBOX-BUILD-INIT SBOX-BUILD-S-OK _STC-IS
    _STC-OWNER SBOX-MODULE-OWNER-SIZE 0 FILL
    _STC-PROFILE _STC-OWNER SBOX-MODULE-OWNER-INIT SBOX-MODULE-S-OK _STC-IS
    _STC-STORE SBOX-STORE-SIZE 0 FILL
    \ The two artifacts.
    _STC-ECHO _STC-BUILD! _STC-ART-DIGEST _STC-ECHO-DIGEST 32 MOVE
    _STC-BUILD SBOX-BUILD-RELEASE SBOX-BUILD-S-OK _STC-IS
    _STC-INC _STC-BUILD! _STC-ART-DIGEST _STC-INC-DIGEST 32 MOVE
    _STC-BUILD SBOX-BUILD-RELEASE SBOX-BUILD-S-OK _STC-IS
    _STC-ECHO-DIGEST 32 _STC-INC-DIGEST 32 COMPARE 0<> _STC-ASSERT
    VFS-CUR _STC-OLD-VFS !
    2097152 A-XMEM ARENA-NEW DUP 0= _STC-ASSERT DROP
    VFS-RAM-BINDING 0 VFS-NEW ?DUP IF THROW THEN
        DUP _STC-VFS ! 0<> _STC-ASSERT
    _STC-VFS @ VFS-USE ;

: _STC-FRESH  ( -- )
    0 _STC-CAT$ _STC-PACK$ _STC-OWNER _STC-STORE SBOX-STORE-INIT
        SBOX-STORE-S-INVALID _STC-IS
    _STC-VFS @ _STC-CAT$ _STC-PACK$ _STC-PROFILE _STC-STORE SBOX-STORE-INIT
        SBOX-STORE-S-INVALID _STC-IS
    _STC-VFS @ _STC-CAT$ _STC-PACK$ _STC-OWNER _STC-STORE 1+ SBOX-STORE-INIT
        SBOX-STORE-S-INVALID _STC-IS
    _STC-VFS @ S" relative.bin" _STC-PACK$ _STC-OWNER _STC-STORE
        SBOX-STORE-INIT SBOX-STORE-S-INVALID _STC-IS
    _STC-STORE SBOX-STORE-VALID? 0= _STC-ASSERT
    _STC-VFS @ _STC-CAT$ _STC-PACK$ _STC-OWNER _STC-STORE SBOX-STORE-INIT
        SBOX-STORE-S-OK _STC-IS
    _STC-VFS @ _STC-CAT$ _STC-PACK$ _STC-OWNER _STC-STORE SBOX-STORE-INIT
        SBOX-STORE-S-STATE _STC-IS
    \ Nothing works before OPEN.
    1 16 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-STATE _STC-IS 0= _STC-ASSERT
    _STC-STORE SBOX-STORE-OPEN SBOX-STORE-S-OK _STC-IS
    _STC-STORE SBOX-STORE-OPEN SBOX-STORE-S-STATE _STC-IS
    _STC-STORE SBOX-STORE-RECOVERY? 0= _STC-ASSERT
    _STC-GENERATION 0= _STC-ASSERT
    _STC-OWNER SBOX-MODULE-COUNT@ 0= _STC-ASSERT ;

: _STC-INSTALLS  ( -- )
    \ A, from the first operation.
    1 16 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-OK _STC-IS DUP _STC-A !
    SBOX-MODULE-STATE@ SBOX-MODULE-VERIFIED _STC-IS
    _STC-GENERATION 1 = _STC-ASSERT
    16 1 _STC-FLAGS 0= _STC-ASSERT
    \ The same operation again names the same module and writes nothing.
    _STC-ECHO _STC-BUILD! 16 1 _STC-DECLARE 1 _STC-KEY! -ROT _STC-BUILD
        _STC-STORE SBOX-STORE-INSTALL SBOX-STORE-S-OK _STC-IS
        _STC-A @ = _STC-ASSERT
    \ It did not take the build's plan.
    _STC-BUILD SBOX-BUILD-PLAN@ SBOX-BUILD-S-OK _STC-IS SBOX-PLAN-VALID? _STC-ASSERT
    _STC-BUILD SBOX-BUILD-RELEASE SBOX-BUILD-S-OK _STC-IS
    _STC-GENERATION 1 = _STC-ASSERT
    \ The operation for another module.
    1 32 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-CONFLICT _STC-IS 0= _STC-ASSERT
    \ The module from another operation.
    2 16 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-DUPLICATE _STC-IS 0= _STC-ASSERT
    \ B and C share A's artifact; E has its own.
    3 32 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-OK _STC-IS DROP
    4 48 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-OK _STC-IS DROP
    5 80 1 _STC-INC _STC-INSTALL SBOX-STORE-S-OK _STC-IS DROP
    _STC-GENERATION 4 = _STC-ASSERT
    _STC-OWNER SBOX-MODULE-COUNT@ 4 = _STC-ASSERT
    \ The owner refuses an entry the artifact lacks, and nothing is kept.
    S" mine" _STC-ENTRY-U ! _STC-ENTRY-A !
    6 96 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-MODULE _STC-IS 0= _STC-ASSERT
    _STC-STORE SBOX-STORE-MODULE-STATUS@ SBOX-MODULE-S-MISMATCH _STC-IS
    S" main" _STC-ENTRY-U ! _STC-ENTRY-A !
    _STC-GENERATION 4 = _STC-ASSERT
    96 1 _STC-FLAGS -1 = _STC-ASSERT
    _STC-OWNER SBOX-MODULE-COUNT@ 4 = _STC-ASSERT
    \ An operation needs a key.
    _STC-ECHO _STC-BUILD! 96 1 _STC-DECLARE 0 _STC-KEY! -ROT _STC-BUILD
        _STC-STORE SBOX-STORE-INSTALL SBOX-STORE-S-INVALID _STC-IS
        0= _STC-ASSERT
    _STC-BUILD SBOX-BUILD-RELEASE SBOX-BUILD-S-OK _STC-IS
    \ A pinned module stays.
    _STC-A @ SBOX-MODULE-PIN SBOX-MODULE-S-OK _STC-IS DROP
    _STC-A @ _STC-STORE SBOX-STORE-REMOVE SBOX-STORE-S-BUSY _STC-IS
    _STC-A @ SBOX-MODULE-UNPIN SBOX-MODULE-S-OK _STC-IS
    \ Revoking, durably and once.
    _STC-A @ _STC-STORE SBOX-STORE-REVOKE SBOX-STORE-S-OK _STC-IS
    _STC-A @ SBOX-MODULE-STATE@ SBOX-MODULE-RETIRED _STC-IS
    16 1 _STC-FLAGS SBOX-STORE-F-REVOKED = _STC-ASSERT
    _STC-GENERATION 5 = _STC-ASSERT
    _STC-A @ _STC-STORE SBOX-STORE-REVOKE SBOX-STORE-S-OK _STC-IS
    _STC-GENERATION 5 = _STC-ASSERT
    \ A revoked revision never returns.
    7 16 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-REVOKED _STC-IS 0= _STC-ASSERT ;

: _STC-SECOND-BOOT  ( -- )
    _STC-REBOOT
    _STC-STORE SBOX-STORE-RECOVERY? 0= _STC-ASSERT
    _STC-GENERATION 5 = _STC-ASSERT
    _STC-OWNER SBOX-MODULE-COUNT@ 4 = _STC-ASSERT
    16 1 _STC-STATE SBOX-MODULE-RETIRED _STC-IS
    32 1 _STC-STATE SBOX-MODULE-DECLARED _STC-IS
    48 1 _STC-STATE SBOX-MODULE-DECLARED _STC-IS
    80 1 _STC-STATE SBOX-MODULE-DECLARED _STC-IS
    \ B verifies on first use, from its stored artifact.
    32 1 _STC-FIND _STC-MOD !
    _STC-MOD @ SBOX-MODULE-PIN SBOX-MODULE-S-STATE _STC-IS DROP
    _STC-MOD @ _STC-STORE SBOX-STORE-VERIFY SBOX-STORE-S-OK _STC-IS
    _STC-MOD @ SBOX-MODULE-STATE@ SBOX-MODULE-VERIFIED _STC-IS
    _STC-MOD @ SBOX-MODULE-PIN SBOX-MODULE-S-OK _STC-IS SBOX-PLAN-VALID? _STC-ASSERT
    _STC-MOD @ SBOX-MODULE-UNPIN SBOX-MODULE-S-OK _STC-IS
    _STC-MOD @ _STC-STORE SBOX-STORE-VERIFY SBOX-STORE-S-STATE _STC-IS
    16 1 _STC-FIND _STC-STORE SBOX-STORE-VERIFY SBOX-STORE-S-STATE _STC-IS
    \ The first operation still names A, now retired.
    1 16 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-OK _STC-IS
        SBOX-MODULE-STATE@ SBOX-MODULE-RETIRED _STC-IS
    \ Removing B.
    _STC-MOD @ _STC-STORE SBOX-STORE-REMOVE SBOX-STORE-S-OK _STC-IS
    32 1 _STC-FIND 0= _STC-ASSERT
    32 1 _STC-FLAGS SBOX-STORE-F-REMOVED = _STC-ASSERT
    _STC-GENERATION 6 = _STC-ASSERT
    3 32 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-REMOVED _STC-IS 0= _STC-ASSERT
    8 32 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-REVOKED _STC-IS 0= _STC-ASSERT
    \ The artifact B shared stays for A and C.
    _STC-PACK$ _STC-READ-FILE
    2 _STC-ECHO-DIGEST _STC-OBJECT NIP 0<> _STC-ASSERT ;

: _STC-DAMAGED-DECLARATION  ( -- )
    \ C's declaration and its digest.
    _STC-ECHO-DIGEST _STC-ART-DIGEST 32 MOVE
    48 1 _STC-DECLARE _STC-C-DIGEST _STC-DECL-WS SBOX-DECL-DIGEST
        SBOX-DECL-S-OK _STC-IS
    _STC-PACK$ _STC-READ-FILE
    1 _STC-C-DIGEST _STC-OBJECT DUP 0<> _STC-ASSERT _STC-LEN ! _STC-OFF !
    _STC-OFF @ 120 + _STC-PACK$ _STC-FLIP
    _STC-REBOOT
    _STC-STORE SBOX-STORE-RECOVERY? 0= _STC-ASSERT
    48 1 _STC-STATE SBOX-MODULE-QUARANTINED _STC-IS
    48 1 _STC-REASON SBOX-MODULE-Q-STORE _STC-IS
    48 1 _STC-FIND SBOX-MODULE-DECLARATION$ NIP 0= _STC-ASSERT
    16 1 _STC-STATE SBOX-MODULE-RETIRED _STC-IS
    80 1 _STC-STATE SBOX-MODULE-DECLARED _STC-IS
    \ F's install rewrites the pack and keeps C's damaged bytes.
    9 96 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-OK _STC-IS DROP
    48 1 _STC-DECLARE 2DROP
    _STC-PACK$ _STC-READ-FILE
    1 _STC-C-DIGEST _STC-OBJECT _STC-LEN @ = _STC-ASSERT _STC-OFF !
    _STC-FILE _STC-OFF @ + 120 + C@ _STC-DECL 120 + C@ 1 XOR = _STC-ASSERT
    _STC-REBOOT
    48 1 _STC-STATE SBOX-MODULE-QUARANTINED _STC-IS
    96 1 _STC-STATE SBOX-MODULE-DECLARED _STC-IS
    \ Removing C drops them.
    48 1 _STC-FIND _STC-STORE SBOX-STORE-REMOVE SBOX-STORE-S-OK _STC-IS
    _STC-PACK$ _STC-READ-FILE
    1 _STC-C-DIGEST _STC-OBJECT NIP 0= _STC-ASSERT
    2 _STC-ECHO-DIGEST _STC-OBJECT NIP 0<> _STC-ASSERT ;

: _STC-DAMAGED-ARTIFACT  ( -- )
    _STC-PACK$ _STC-READ-FILE
    2 _STC-INC-DIGEST _STC-OBJECT DUP 70 > _STC-ASSERT DROP _STC-OFF !
    _STC-OFF @ 70 + _STC-PACK$ _STC-FLIP
    _STC-REBOOT
    _STC-STORE SBOX-STORE-RECOVERY? 0= _STC-ASSERT
    80 1 _STC-STATE SBOX-MODULE-DECLARED _STC-IS
    80 1 _STC-FIND DUP _STC-MOD ! _STC-STORE SBOX-STORE-VERIFY
        SBOX-STORE-S-MODULE _STC-IS
    _STC-MOD @ SBOX-MODULE-STATE@ SBOX-MODULE-QUARANTINED _STC-IS
    80 1 _STC-REASON SBOX-MODULE-Q-ARTIFACT _STC-IS
    _STC-STORE SBOX-STORE-MODULE-STATUS@ SBOX-MODULE-S-MISMATCH _STC-IS
    \ The other artifact still verifies.
    96 1 _STC-FIND _STC-STORE SBOX-STORE-VERIFY SBOX-STORE-S-OK _STC-IS ;

: _STC-DAMAGED-CATALOG  ( -- )
    _STC-CAT$ _STC-READ-FILE
    _STC-FILE-U @ 96 > _STC-ASSERT
    80 _STC-CAT$ _STC-FLIP
    _STC-REBOOT
    _STC-STORE SBOX-STORE-RECOVERY? _STC-ASSERT
    _STC-OWNER SBOX-MODULE-COUNT@ 0= _STC-ASSERT
    10 112 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-RECOVERY _STC-IS 0= _STC-ASSERT
    \ Repaired, it loads again.
    80 _STC-CAT$ _STC-FLIP
    _STC-REBOOT
    _STC-STORE SBOX-STORE-RECOVERY? 0= _STC-ASSERT
    _STC-OWNER SBOX-MODULE-COUNT@ 3 = _STC-ASSERT
    _STC-GENERATION 8 = _STC-ASSERT ;

: _STC-TRUNCATED-PACK  ( -- )
    _STC-PACK$ _STC-READ-FILE
    \ The last object is the artifact whose digest is larger.
    _STC-FILE-U @ 8 - _STC-PACK$ _STC-TRUNCATE
    _STC-REBOOT
    _STC-STORE SBOX-STORE-RECOVERY? _STC-ASSERT
    \ Every declaration comes before the artifacts, so all still load.
    _STC-OWNER SBOX-MODULE-COUNT@ 3 = _STC-ASSERT
    96 1 _STC-FIND DUP _STC-MOD ! _STC-STORE SBOX-STORE-VERIFY
    _STC-ECHO-DIGEST 32 _STC-INC-DIGEST 32 COMPARE 0> IF
        SBOX-STORE-S-MODULE _STC-IS
        96 1 _STC-REASON SBOX-MODULE-Q-STORE _STC-IS
    ELSE
        SBOX-STORE-S-OK _STC-IS
    THEN
    10 112 1 _STC-ECHO _STC-INSTALL SBOX-STORE-S-RECOVERY _STC-IS 0= _STC-ASSERT
    16 1 _STC-FIND _STC-STORE SBOX-STORE-REVOKE SBOX-STORE-S-RECOVERY _STC-IS ;

: _STC-OTHER-PROFILE  ( -- )
    _STC-QUAL _STC-REBOOT-FOR
    _STC-OWNER SBOX-MODULE-COUNT@ 3 = _STC-ASSERT
    16 1 _STC-STATE SBOX-MODULE-QUARANTINED _STC-IS
    16 1 _STC-REASON SBOX-MODULE-Q-PROFILE _STC-IS
    96 1 _STC-REASON SBOX-MODULE-Q-PROFILE _STC-IS ;

: _STC-TEARDOWN  ( -- )
    _STC-STORE SBOX-STORE-CLOSE SBOX-STORE-S-OK _STC-IS
    _STC-OWNER SBOX-MODULE-OWNER-RELEASE SBOX-MODULE-S-OK _STC-IS
    _STC-BUILD SBOX-BUILD-RELEASE SBOX-BUILD-S-OK _STC-IS
    _STC-OLD-VFS @ VFS-USE
    _STC-VFS @ VFS-DESTROY ;

: _STC-RUN  ( -- )
    DEPTH _STC-DEPTH !
    0 _STC-FAILS !
    0 _STC-CHECKS !
    ." SBOX MODULE STORE SETUP" CR _STC-SETUP _STC-STACK
    ." SBOX MODULE STORE FRESH" CR _STC-FRESH _STC-STACK
    ." SBOX MODULE STORE INSTALLS" CR _STC-INSTALLS _STC-STACK
    ." SBOX MODULE STORE SECOND BOOT" CR _STC-SECOND-BOOT _STC-STACK
    ." SBOX MODULE STORE DAMAGED DECLARATION" CR
        _STC-DAMAGED-DECLARATION _STC-STACK
    ." SBOX MODULE STORE DAMAGED ARTIFACT" CR _STC-DAMAGED-ARTIFACT _STC-STACK
    ." SBOX MODULE STORE DAMAGED CATALOG" CR _STC-DAMAGED-CATALOG _STC-STACK
    ." SBOX MODULE STORE TRUNCATED PACK" CR _STC-TRUNCATED-PACK _STC-STACK
    ." SBOX MODULE STORE OTHER PROFILE" CR _STC-OTHER-PROFILE _STC-STACK
    ." SBOX MODULE STORE TEARDOWN" CR _STC-TEARDOWN _STC-STACK
    _STC-FAILS @ IF
        ." SBOX MODULE STORE CONTRACTS FAIL "
        _STC-FAILS @ . ." / " _STC-CHECKS @ . CR
