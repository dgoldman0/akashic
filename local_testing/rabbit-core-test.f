: _RBT-ASSERT  ( flag -- )
    1 _RBT-CHECKS +!
    0= IF
        1 _RBT-FAILS +!
        ." RABBIT CORE ASSERT " _RBT-CHECKS @ . CR
    THEN ;

: _RBT-STACK  ( -- )
    DEPTH DUP _RBT-DEPTH @ <> IF
        ." RABBIT CORE STACK " _RBT-DEPTH @ . ." -> " DUP . CR
        .S CR
    THEN
    _RBT-DEPTH @ = _RBT-ASSERT ;

: _RBT-FILLED?  ( address length byte -- flag )
    >R
    BEGIN DUP WHILE
        OVER C@ R@ <> IF 2DROP R> DROP 0 EXIT THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP R> DROP -1 ;

