"""Ordinary UIDL status slots freeze into one native status snapshot."""

from __future__ import annotations

import re
from pathlib import Path

from test_uidl_collection_snapshot import _load_forth_lines
from status_snapshot_runtime import run_status_forth as _run_forth


ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "akashic/tui/uidl-status-field-snapshot.f"


def _status_snapshot_program() -> list[str]:
    source = r'''
VARIABLE _SX-FAILS VARIABLE _SX-CHECKS VARIABLE _SX-DEPTH
VARIABLE _SX-DOC VARIABLE _SX-LEFT VARIABLE _SX-RIGHT VARIABLE _SX-NEXT
VARIABLE _SX-STATUS VARIABLE _SX-COUNT VARIABLE _SX-USED
VARIABLE _SX-SC VARIABLE _SX-INDEX VARIABLE _SX-MORE
CREATE _SX-DESCRIPTORS-S 512 7 + ALLOT
CREATE _SX-NATIVE-S 1024 7 + ALLOT
CREATE _SX-WORK-S 32 7 + ALLOT
_SX-DESCRIPTORS-S 7 + -8 AND CONSTANT _SX-DESCRIPTORS
_SX-NATIVE-S 7 + -8 AND CONSTANT _SX-NATIVE
_SX-WORK-S 7 + -8 AND CONSTANT _SX-WORK
: _SX-D0 _SX-DESCRIPTORS ;
: _SX-D1 _SX-DESCRIPTORS USFSN-DESCRIPTOR-SIZE + ;
: _SX-ASSERT 1 _SX-CHECKS +! 0= IF 1 _SX-FAILS +! ." STATUS SNAP ASSERT " _SX-CHECKS @ . CR THEN ;
: _SX-OK 0= _SX-ASSERT ;
: _SX-STACK DEPTH _SX-DEPTH @ = _SX-ASSERT ;
: _SX-GEOM ( row col height width elem -- )
    _UTUI-SIDECAR _SX-SC ! _SX-SC @ _UTUI-SC-W!
    _SX-SC @ _UTUI-SC-H! _SX-SC @ _UTUI-SC-COL! _SX-SC @ _UTUI-SC-ROW! ;
: _SX-ALIGN ( align elem -- )
    _UTUI-SIDECAR DUP _UTUI-SC-STYLE@ 0x300000000 INVERT AND
    ROT 32 LSHIFT OR SWAP _UTUI-SC-STYLE! ;
: _SX-CAPTURE
    _SX-DESCRIPTORS 512 _SX-NATIVE 1024 USFSN-CAPTURE
    _SX-STATUS ! _SX-USED ! _SX-COUNT ! ;
: _SX-VALIDATE
    _SX-WORK 32 _SX-DESCRIPTORS _SX-COUNT @ USFSN-DESCRIPTOR-SIZE *
    _SX-NATIVE _SX-USED @ USFSN-FROZEN-VALIDATE ;
: _SX-REFUSED ( count used status -- )
    USFSN-S-INVALID = _SX-ASSERT 0= _SX-ASSERT 0= _SX-ASSERT ;
: _SX-PAINT UTUI-PAINT ;
: _SX-FULL _SX-LEFT @ UIDL-DIRTY! ['] _SX-PAINT UTUI-DRAW-OBSERVE _SX-OK ;
0 _SX-FAILS ! 0 _SX-CHECKS ! DEPTH _SX-DEPTH !
40 10 SCR-NEW SCR-USE
0 0 10 40 RGN-NEW _SX-DOC !
S" <uidl><status id=bar><label id=left text=hello/><label id=right text=bye/></status><status id=more><label id=next text=ready/></status></uidl>" _SX-DOC @ UTUI-LOAD _SX-ASSERT
S" left" UTUI-BY-ID _SX-LEFT !
S" right" UTUI-BY-ID _SX-RIGHT !
S" next" UTUI-BY-ID _SX-NEXT !
S" more" UTUI-BY-ID _SX-MORE !
1 2 1 12 _SX-LEFT @ _SX-GEOM
1 20 1 10 _SX-RIGHT @ _SX-GEOM
3 0 1 20 _SX-MORE @ _SX-GEOM
3 1 1 8 _SX-NEXT @ _SX-GEOM
0 _SX-LEFT @ _SX-ALIGN 2 _SX-RIGHT @ _SX-ALIGN 0 _SX-NEXT @ _SX-ALIGN
-1 _UTUI-PROJ-ATTACHED ! _SX-FULL
_SX-LEFT @ _UTUI-STATUS-LABEL-CANONICAL? _SX-ASSERT
_SX-RIGHT @ _UTUI-STATUS-LABEL-CANONICAL? 0= _SX-ASSERT
_SX-NEXT @ _UTUI-STATUS-LABEL-CANONICAL? _SX-ASSERT
_SX-CAPTURE _SX-STATUS @ _SX-OK
_SX-COUNT @ 2 = _SX-ASSERT _SX-USED @ 160 = _SX-ASSERT
_SX-D0 USFSN-DESCRIPTOR-SOURCE-GENERATION@ 0= _SX-ASSERT
_SX-D0 USFSN-DESCRIPTOR-ROOT-KEY@ 1 = _SX-ASSERT
_SX-D0 USFSN-DESCRIPTOR-ROW@ 1 = _SX-ASSERT
_SX-D0 USFSN-DESCRIPTOR-COLUMN@ 2 = _SX-ASSERT
_SX-D0 USFSN-DESCRIPTOR-WIDTH@ 12 = _SX-ASSERT
_SX-D0 _SX-NATIVE USFSN-DESCRIPTOR-NATIVE USF-VALIDATE _SX-OK
_SX-D0 _SX-NATIVE USFSN-DESCRIPTOR-NATIVE DROP USF-VALUE@ S" hello" STR-STR= _SX-ASSERT
_SX-D1 USFSN-DESCRIPTOR-SOURCE-GENERATION@ 0= _SX-ASSERT
_SX-D1 USFSN-DESCRIPTOR-ROOT-KEY@ 1 = _SX-ASSERT
_SX-D1 USFSN-DESCRIPTOR-SOURCE-INDEX@ _SX-D0 USFSN-DESCRIPTOR-SOURCE-INDEX@ U> _SX-ASSERT
_SX-D1 USFSN-DESCRIPTOR-ROW@ 3 = _SX-ASSERT
_SX-D1 USFSN-DESCRIPTOR-COLUMN@ 1 = _SX-ASSERT
_SX-D1 USFSN-DESCRIPTOR-WIDTH@ 8 = _SX-ASSERT
_SX-D1 _SX-NATIVE USFSN-DESCRIPTOR-NATIVE DROP USF-VALUE@ S" ready" STR-STR= _SX-ASSERT
_SX-VALIDATE _SX-OK _SX-STACK
\ Ordinary paint draws the same projected text.
1 2 SCR-GET CELL-CP@ 104 = _SX-ASSERT
3 1 SCR-GET CELL-CP@ 114 = _SX-ASSERT
\ Native metadata, exact clip, canonical identity, and coverage are checked.
1 _SX-D0 _USFSN-D.UTF8-U +!
_SX-VALIDATE USFSN-S-INVALID = _SX-ASSERT
-1 _SX-D0 _USFSN-D.UTF8-U +!
11 _SX-D0 _USFSN-D.CLIP-WIDTH !
_SX-VALIDATE USFSN-S-INVALID = _SX-ASSERT
12 _SX-D0 _USFSN-D.CLIP-WIDTH !
0 _SX-D1 _USFSN-D.NATIVE-O !
_SX-VALIDATE USFSN-S-INVALID = _SX-ASSERT
80 _SX-D1 _USFSN-D.NATIVE-O !
_SX-VALIDATE _SX-OK
\ Every record is one ordinary slot: generation zero, root key one, and a
\ strictly increasing source index.
5 _SX-D1 _USFSN-D.GENERATION !
_SX-VALIDATE USFSN-S-INVALID = _SX-ASSERT
0 _SX-D1 _USFSN-D.GENERATION !
2 _SX-D1 _USFSN-D.ROOT-KEY !
_SX-VALIDATE USFSN-S-INVALID = _SX-ASSERT
1 _SX-D1 _USFSN-D.ROOT-KEY !
_SX-D1 USFSN-DESCRIPTOR-SOURCE-INDEX@ _SX-INDEX !
_SX-D0 USFSN-DESCRIPTOR-SOURCE-INDEX@ _SX-D1 _USFSN-D.INDEX !
_SX-VALIDATE USFSN-S-INVALID = _SX-ASSERT
_SX-INDEX @ _SX-D1 _USFSN-D.INDEX !
_SX-VALIDATE _SX-OK _SX-STACK
\ Any bank overlapping status-model scratch, UIDL-TUI authority, or module
\ scratch is refused before a byte is written.
: _SX-USF-SCRATCH _USF-I-DST 7 + -8 AND ;
_SX-DESCRIPTORS 512 _SX-USF-SCRATCH 8 USFSN-CAPTURE _SX-REFUSED
_SX-DESCRIPTORS 512 _SX-DOC @ RGN-SIZE USFSN-CAPTURE _SX-REFUSED
_SX-DESCRIPTORS 512 _USFSN-NATIVE-U 8 USFSN-CAPTURE _SX-REFUSED
_USFSN-NATIVE-U @ 0= _SX-ASSERT
_SX-USF-SCRATCH 8 UTUI-COLLECTION-STORAGE-DISJOINT?
USCOL-S-INVALID = _SX-ASSERT 0= _SX-ASSERT
\ A partial root cannot be claimed; the other slot survives.
1 35 1 12 _SX-LEFT @ _SX-GEOM
_SX-CAPTURE _SX-STATUS @ _SX-OK _SX-COUNT @ 1 = _SX-ASSERT
_SX-D0 _SX-NATIVE USFSN-DESCRIPTOR-NATIVE DROP USF-VALUE@ S" ready" STR-STR= _SX-ASSERT
1 2 1 12 _SX-LEFT @ _SX-GEOM
\ Controls project through the shared display rules; ordinary source remains.
CREATE _SX-CONTROL 65 C, 10 C, 66 C,
_SX-LEFT @ S" text" _SX-CONTROL 3 UIDL-SET-ATTR
_SX-CAPTURE _SX-STATUS @ _SX-OK _SX-COUNT @ 2 = _SX-ASSERT
_SX-D0 _SX-NATIVE USFSN-DESCRIPTOR-NATIVE DROP USF-VALUE@
DUP 5 = _SX-ASSERT DROP DUP C@ 65 = _SX-ASSERT
DUP 1+ C@ 239 = _SX-ASSERT 4 + C@ 66 = _SX-ASSERT
_SX-LEFT @ UIDL-TEXT@ _SX-CONTROL 3 STR-STR= _SX-ASSERT
\ A short bank fails transactionally after the first native field was copied.
_SX-DESCRIPTORS 512 _SX-NATIVE 80 USFSN-CAPTURE
USFSN-S-CAPACITY = _SX-ASSERT 0= _SX-ASSERT 0= _SX-ASSERT
_SX-NATIVE @ 0= _SX-ASSERT _SX-DESCRIPTORS @ 0= _SX-ASSERT
\ A short descriptor bank is a capacity failure too.
_SX-DESCRIPTORS USFSN-DESCRIPTOR-SIZE _SX-NATIVE 1024 USFSN-CAPTURE
USFSN-S-CAPACITY = _SX-ASSERT 0= _SX-ASSERT 0= _SX-ASSERT
_SX-CAPTURE _SX-STATUS @ _SX-OK _SX-COUNT @ 2 = _SX-ASSERT
_SX-VALIDATE _SX-OK _SX-STACK
_SX-FAILS @ 0= IF ." STATUS SNAP PASS " ELSE ." STATUS SNAP FAIL " THEN _SX-CHECKS @ . _SX-FAILS @ . CR
'''
    return _load_forth_lines(SNAPSHOT) + [
        line for line in source.splitlines() if not line.lstrip().startswith("\\")
    ]


def test_status_snapshot_projection_identity_and_frozen_authority() -> None:
    output = _run_forth(_status_snapshot_program(), max_steps=20_000_000)
    summary = re.search(r"STATUS SNAP PASS\s+(\d+)\s+0", output)
    assert summary, output[-18000:]
    assert int(summary.group(1)) >= 69
