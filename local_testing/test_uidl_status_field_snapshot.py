def test_status_snapshot_direct_mounted_projection_and_frozen_authority() -> None:
    output = _run_forth(_status_snapshot_program(), max_steps=20_000_000)
    summary = re.search(r"STATUS SNAP PASS\s+(\d+)\s+0", output)
    assert summary, output[-18000:]
    assert int(summary.group(1)) >= 50
