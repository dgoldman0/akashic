: _RBT-CLI-CONNECTION-STEP  ( connection -- )
    RABBIT-CONNECTION-PUMP
    DUP RCONN-S-OK =
    OVER RCONN-S-PENDING = OR
    SWAP RCONN-S-RX-READY = OR 0= IF
        -1 _RBT-CLI-PUMP-BAD !
    THEN ;

