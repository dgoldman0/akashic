        _RBT-CLI-EXPECT @ 1 = _RBT-ASSERT
        _RBT-CLI-DISPOSITION @ RABBIT-INBOUND-NEW = _RBT-ASSERT
        _RBT-CLI-FRAME @ RMSG-BODY$
            RMSG-S-OK = _RBT-ASSERT
            S" early-event" STR-STR= _RBT-ASSERT
        0 0 _RBT-CLI-CLIENT RABBIT-CLIENT-DISPATCH
            RCLIENT-S-STATE = _RBT-ASSERT
            0= _RBT-ASSERT 0= _RBT-ASSERT
            RCLIENT-ITEM-NONE = _RBT-ASSERT
        1 _RBT-CLI-EVENTS +!
    ELSE
        _RBT-CLI-KIND @ RMSG-KIND-RESPONSE = _RBT-ASSERT
        _RBT-CLI-SEQ @ 0= _RBT-ASSERT
