  ( frame kind lane seq expected disposition context -- decision )
    _RBT-CLI-CB-CONTEXT ! _RBT-CLI-DISPOSITION ! _RBT-CLI-EXPECT !
    _RBT-CLI-SEQ ! _RBT-CLI-LANE ! _RBT-CLI-KIND ! _RBT-CLI-FRAME !
    _RBT-CLI-CB-CONTEXT @ 0xC11E = _RBT-ASSERT
    _RBT-CLI-KIND @ RMSG-KIND-EVENT = IF
        _RBT-CLI-LANE @ 1 = _RBT-ASSERT
