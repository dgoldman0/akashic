    _AIT-POLICY
    _AIT-REDIRECT-BOUND
    _AIT-FAILS @ 0= IF
        ." ATPROTO IDENTITY PASS " _AIT-CHECKS @ . CR
    ELSE
        ." ATPROTO IDENTITY FAIL " _AIT-FAILS @ .
        ." / " _AIT-CHECKS @ . CR
    THEN ;
