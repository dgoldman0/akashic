VARIABLE _AIT-FAILS
VARIABLE _AIT-CHECKS
VARIABLE _AIT-DEPTH
VARIABLE _AIT-BODY-U
VARIABLE _AIT-COPY-U
VARIABLE _AIT-DNS-U

CREATE _AIT-RESULT-STORAGE ATID-RESULT-SIZE 7 + ALLOT
CREATE _AIT-RESOLVER-STORAGE ATID-RESOLVER-SIZE 7 + ALLOT
CREATE _AIT-BODY 4096 ALLOT
CREATE _AIT-DNS 4096 ALLOT

: _AIT-RESULT  ( -- address )
    _AIT-RESULT-STORAGE 7 + -8 AND ;

: _AIT-RESOLVER  ( -- address )
    _AIT-RESOLVER-STORAGE 7 + -8 AND ;

: _AIT-ASSERT  ( flag -- )
    1 _AIT-CHECKS +!
    0= IF
        1 _AIT-FAILS +!
        ." ATPROTO IDENTITY ASSERT " _AIT-CHECKS @ . CR
    THEN ;

: _AIT-STACK  ( -- )
    DEPTH DUP _AIT-DEPTH @ <> IF
        ." ATPROTO IDENTITY STACK "
        _AIT-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _AIT-DEPTH @ = _AIT-ASSERT ;

: _AIT-CHAR  ( byte -- )
    _AIT-BODY _AIT-BODY-U @ + C!
    1 _AIT-BODY-U +! ;

: _AIT-TEXT  ( address length -- )
    DUP _AIT-COPY-U !
    _AIT-BODY _AIT-BODY-U @ + SWAP MOVE
    _AIT-COPY-U @ _AIT-BODY-U +! ;

: _AIT-U16!  ( value address -- )
    >R
    DUP 8 RSHIFT R@ C!
    0xFF AND R> 1+ C! ;

: _AIT-DNS-BYTE  ( byte -- )
    _AIT-DNS _AIT-DNS-U @ + C!
    1 _AIT-DNS-U +! ;

: _AIT-DNS-U16  ( value -- )
    DUP 8 RSHIFT _AIT-DNS-BYTE
    0xFF AND _AIT-DNS-BYTE ;

: _AIT-DNS-U32  ( value -- )
    DUP 24 RSHIFT _AIT-DNS-BYTE
    DUP 16 RSHIFT 0xFF AND _AIT-DNS-BYTE
    DUP 8 RSHIFT 0xFF AND _AIT-DNS-BYTE
    0xFF AND _AIT-DNS-BYTE ;

: _AIT-DNS-POINTER  ( offset -- )
    DUP 8 RSHIFT 0x3F AND 0xC0 OR _AIT-DNS-BYTE
    0xFF AND _AIT-DNS-BYTE ;

: _AIT-DNS-BYTES  ( address length -- )
    BEGIN
        DUP
    WHILE
        OVER C@ _AIT-DNS-BYTE
        1 /STRING
    REPEAT
    2DROP ;

: _AIT-DNS-ANSWER-COUNT!  ( count -- )
    _AIT-DNS 6 + _AIT-U16! ;

: _AIT-DNS-AUTHORITY-COUNT!  ( count -- )
    _AIT-DNS 8 + _AIT-U16! ;

: _AIT-DNS-ADDITIONAL-COUNT!  ( count -- )
    _AIT-DNS 10 + _AIT-U16! ;

: _AIT-DNS-RESPONSE-BASE  ( -- )
    _AIT-RESOLVER ATID-DNS-QUERY$
    DUP ATID-S-OK = _AIT-ASSERT
    DROP
    DUP _AIT-DNS-U !
    _AIT-DNS SWAP CMOVE
    0x8180 _AIT-DNS 2 + _AIT-U16!
    0 _AIT-DNS-ANSWER-COUNT!
    0 _AIT-DNS-AUTHORITY-COUNT!
    0 _AIT-DNS-ADDITIONAL-COUNT! ;

: _AIT-DNS-APPEND-FIXED  ( type ttl rdlength -- )
    >R >R
    12 _AIT-DNS-POINTER
    _AIT-DNS-U16
    1 _AIT-DNS-U16
    R> _AIT-DNS-U32
    R> _AIT-DNS-U16 ;

: _AIT-DNS-APPEND-TXT  ( text-a text-u ttl -- )
    >R
    DUP 1+ 16 R> ROT _AIT-DNS-APPEND-FIXED
    DUP _AIT-DNS-BYTE
    _AIT-DNS-BYTES ;

: _AIT-DNS-APPEND-CNAME-LABEL
  ( label-a label-u suffix-offset ttl -- )
    >R
    12 _AIT-DNS-POINTER
    5 _AIT-DNS-U16
    1 _AIT-DNS-U16
    R> _AIT-DNS-U32
    1 PICK 3 + _AIT-DNS-U16
    1 PICK _AIT-DNS-BYTE
    2 PICK 2 PICK _AIT-DNS-BYTES
    _AIT-DNS-POINTER
    2DROP ;

: _AIT-DNS-APPEND-CNAME-POINTER  ( target-offset ttl -- )
    >R
    12 _AIT-DNS-POINTER
    5 _AIT-DNS-U16
    1 _AIT-DNS-U16
    R> _AIT-DNS-U32
    2 _AIT-DNS-U16
    _AIT-DNS-POINTER ;

: _AIT-DNS-SUBMIT  ( -- status )
    _AIT-DNS _AIT-DNS-U @ _AIT-RESOLVER
    ATID-DNS-RESPONSE! ;

: _AIT-QTEXT  ( address length -- )
    34 _AIT-CHAR
    _AIT-TEXT
    34 _AIT-CHAR ;

: _AIT-RESET  ( -- )
    _AIT-RESULT ATID-RESULT-INIT ATID-S-OK = _AIT-ASSERT
    _AIT-RESOLVER ATID-RESOLVER-CLEAR ATID-S-OK = _AIT-ASSERT
    0 _AIT-BODY-U ! ;

: _AIT-BUILD-IDENTITY-ONLY  ( -- )
    0 _AIT-BODY-U !
    S" {" _AIT-TEXT
    S" id" _AIT-QTEXT
    S" :" _AIT-TEXT
    S" did:plc:abcdefghijklmnopqrstuvwx" _AIT-QTEXT
    S" }" _AIT-TEXT ;

: _AIT-BUILD-WITH-HANDLE  ( -- )
    0 _AIT-BODY-U !
    S" {" _AIT-TEXT
    S" id" _AIT-QTEXT
    S" :" _AIT-TEXT
    S" did:plc:abcdefghijklmnopqrstuvwx" _AIT-QTEXT
    S" ," _AIT-TEXT
    S" alsoKnownAs" _AIT-QTEXT
    S" :[" _AIT-TEXT
    S" at://alice.example.com" _AIT-QTEXT
    S" ]}" _AIT-TEXT ;

: _AIT-EVIDENCE?  ( bit -- flag )
    >R
    _AIT-RESULT ATID-EVIDENCE@
    ATID-S-OK = _AIT-ASSERT
    R> AND 0<> ;

: _AIT-CURRENT-TARGET  ( -- target )
    _AIT-RESOLVER ATID-HTTP-TARGET@
    ATID-S-OK = _AIT-ASSERT ;

: _AIT-CORRUPT-DERIVED-PARTICIPATION  ( -- )
    _AIT-RESULT _ATIDR.DOCUMENT >R
    S" z123" 2DUP R@ _ATDD.KEY SWAP MOVE
    DUP R@ _ATDD.KEY-U !
    2DROP
    S" https://pds.example/"
    R@ _ATDD.TARGET HTARGET-PARSE
    HTARGET-S-OK = _AIT-ASSERT
    R@ _ATDD.FLAGS @ _ATDD-F-KEY OR _ATDD-F-PDS OR
    R@ _ATDD.FLAGS !
    R> DROP
    _AIT-RESULT _ATIDR.EVIDENCE DUP @
    ATID-E-KEY OR ATID-E-PDS OR SWAP !
    _AIT-RESULT ATID-RESULT-VALID? 0= _AIT-ASSERT ;

