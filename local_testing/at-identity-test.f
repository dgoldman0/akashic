: _AIT-RUN  ( -- )
    0 _AIT-FAILS !
    0 _AIT-CHECKS !
    DEPTH _AIT-DEPTH !
    _AIT-DID-ONLY
    _AIT-CNAME-HOP
    _AIT-CNAME-LOOP
