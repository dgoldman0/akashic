    ATID-A-DID-DOCUMENT = _AIT-ASSERT
    _AIT-RESOLVER ATID-HTTP-TARGET@
    ATID-S-OK = _AIT-ASSERT
    HTARGET-URI$
    S" https://plc.directory/did:plc:abcdefghijklmnopqrstuvwx"
    COMPARE 0= _AIT-ASSERT

    _AIT-BUILD-IDENTITY-ONLY
    _AIT-BODY _AIT-BODY-U @ 200 0
    _AIT-CURRENT-TARGET _AIT-RESOLVER
    ATID-HTTP-RESPONSE! ATID-S-OK = _AIT-ASSERT
    _AIT-RESULT ATID-RESULT-READY? _AIT-ASSERT
    _AIT-RESOLVER ATID-ACTION@
    ATID-S-OK = _AIT-ASSERT
    ATID-A-DONE = _AIT-ASSERT
    _AIT-RESULT ATID-DID@
    ATID-S-OK = _AIT-ASSERT
    S" did:plc:abcdefghijklmnopqrstuvwx" COMPARE 0= _AIT-ASSERT
    _AIT-RESULT ATID-HANDLE@
    ATID-S-MISSING = _AIT-ASSERT
    2DROP
    ATID-E-INPUT-DID _AIT-EVIDENCE? _AIT-ASSERT
    ATID-E-HANDLE-MISSING _AIT-EVIDENCE? _AIT-ASSERT
    ATID-E-DOCUMENT-ID _AIT-EVIDENCE? _AIT-ASSERT
    _AIT-RESULT ATID-PARTICIPATION-STATUS
    ATID-S-KEY = _AIT-ASSERT
    _AIT-RESULT ATID-PARTICIPATION-READY? 0= _AIT-ASSERT
    _AIT-CORRUPT-DERIVED-PARTICIPATION
