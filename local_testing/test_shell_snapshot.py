def _run(program, minimum=1):
    runtime = MegaForthRuntime(
        memory=create_one_core_address_space(external_size=128 << 20, hbw_size=1 << 20),
        execution_backend="native",
    )
    runtime.evaluate((MEGAPAD_ROOT / "kdos.f").read_bytes(), source_name="kdos.f")
    runtime.evaluate(b"ENTER-USERLAND", source_name="shell-snapshot-init")
    for module in dependency_order(ROOT / "akashic", ("tui/shell-snapshot.f",)):
        source = (ROOT / "akashic" / module).read_text()
        source = "\n".join(line for line in source.splitlines()
                           if not line.strip().startswith(("REQUIRE ", "PROVIDED ")))
        runtime.evaluate(source.encode(), source_name=module, step_budget=30_000_000)
    runtime.drain_uart_output()
    try:
        runtime.evaluate(program.encode(), source_name="shell-snapshot-proof", step_budget=40_000_000)
    except Exception as error:
        raise AssertionError(runtime.uart_output.decode(errors="replace")[-16000:]) from error
    output = runtime.drain_uart_output().decode(errors="replace")
    summary = re.search(r"SHELL SNAP PASS\s+(\d+)\s+0", output)
    assert summary, (output[:3000], runtime.main_context.data.snapshot())
    assert int(summary.group(1)) >= minimum
    assert runtime.main_context.data.snapshot() == ()
    assert runtime.main_context.returns.snapshot() == ()


