: AT-CREATE-RECORD-XIO-START  ( operation owner -- step-status )
    DUP AT-CREATE-RECORD-VALID? 0= IF
        DROP AT-CREATE-RECORD-XERR-INVALID SWAP XIOO.ERROR !
        XIO-STEP-FAILED EXIT
    THEN
    DUP ATPCS.STARTS 1 SWAP +!
    DUP ATPCS.MODE @ ATPCS-MODE-NO-EFFECT = IF
        DUP _ATPCS-RESULT-NO-EFFECT
        AT-CREATE-RECORD-XERR-XRPC 2 PICK XIOO.ERROR !
        2DROP XIO-STEP-FAILED EXIT
    THEN
    AT-CREATE-RECORD-STATE-ACTIVE OVER ATPCS.STATE !
    2DROP XIO-STEP-PENDING ;

: AT-CREATE-RECORD-XIO-POLL  ( operation owner -- step-status )
    DUP AT-CREATE-RECORD-VALID? 0= IF
        DROP AT-CREATE-RECORD-XERR-INVALID SWAP XIOO.ERROR !
        XIO-STEP-FAILED EXIT
    THEN
    DUP ATPCS.POLLS 1 SWAP +!
    DUP ATPCS.MODE @ ATPCS-MODE-UNCERTAIN = IF
        DUP _ATPCS-RESULT-UNCERTAIN
        AT-CREATE-RECORD-XERR-XRPC 2 PICK XIOO.ERROR !
        2DROP XIO-STEP-FAILED EXIT
    THEN
    DUP _ATPCS-RESULT-CREATED
    DUP 2 PICK XIOO.RESULT !
    2DROP XIO-STEP-SUCCEEDED ;

: AT-CREATE-RECORD-XIO-CANCEL  ( operation owner -- )
    DUP AT-CREATE-RECORD-VALID? 0= IF 2DROP EXIT THEN
    DUP ATPCS.CANCELS 1 SWAP +!
    DUP ATPCS.MODE @ ATPCS-MODE-CANCEL-UNCERTAIN = IF
        _ATPCS-RESULT-UNCERTAIN DROP EXIT
    THEN
    DUP _ATPCS-RESULT-NO-EFFECT
    AT-CREATE-RECORD-STATE-CANCELLED SWAP ATPCS.STATE !
    DROP ;

: AT-CREATE-RECORD-XIO-WIPE  ( operation owner -- )
    DUP AT-CREATE-RECORD-VALID? 0= IF 2DROP EXIT THEN
    DUP ATPCS.WIPES 1 SWAP +!
    DUP ATPCS.WIPE-IOR @ ?DUP IF
        DUP 2 PICK ATPCS.CLEANUP-ERROR !
        >R 2DROP R> THROW
    THEN
    AT-CREATE-RECORD-STATE-IDLE OVER ATPCS.STATE !
    0 OVER ATPCS.CLEANUP-ERROR !
    2DROP ;

