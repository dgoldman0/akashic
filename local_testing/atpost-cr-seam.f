: AT-CREATE-RECORD-OUTCOME-VALID?  ( outcome -- flag )
    DUP AT-CREATE-RECORD-OUTCOME-PENDING >=
    SWAP AT-CREATE-RECORD-OUTCOME-CREATED <= AND ;

: AT-CREATE-RECORD-STATE-VALID?  ( state -- flag )
    DUP AT-CREATE-RECORD-STATE-IDLE >=
    SWAP AT-CREATE-RECORD-STATE-CANCELLED <= AND ;

: AT-CREATE-RECORD-STATUS-VALID?  ( status -- flag )
    DUP AT-CREATE-RECORD-S-OK >=
    SWAP AT-CREATE-RECORD-S-INTERNAL <= AND ;

: AT-CREATE-RECORD-TARGET?  ( target -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    @ _ATPCS-TARGET-MAGIC = ;

: AT-CREATE-RECORD-VALID?  ( owner -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP ATPCS.MAGIC @ _ATPCS-OWNER-MAGIC =
    OVER ATPCS.TAG @ DUP 1 >= SWAP 2 <= AND AND
    OVER ATPCS.MODE @ DUP ATPCS-MODE-CREATED >=
        SWAP ATPCS-MODE-PREPARE-FAIL <= AND AND
    OVER ATPCS.STATE @ AT-CREATE-RECORD-STATE-VALID? AND
    OVER ATPCS.OUTCOME @ AT-CREATE-RECORD-OUTCOME-VALID? AND
    SWAP ATPCS.LAST-STATUS @ AT-CREATE-RECORD-STATUS-VALID? AND ;

: ATPCS-INIT  ( tag target owner -- status )
    >R
    DUP 0= IF 2DROP R> DROP AT-CREATE-RECORD-S-INVALID EXIT THEN
    OVER DUP 1 < SWAP 2 > OR IF
        2DROP R> DROP AT-CREATE-RECORD-S-RANGE EXIT
    THEN
    R@ 7 AND IF 2DROP R> DROP AT-CREATE-RECORD-S-INVALID EXIT THEN
    R@ ATPCS-OWNER-SIZE 0 FILL
    _ATPCS-TARGET-MAGIC OVER !
    SWAP R@ ATPCS.TAG !
    DROP
    ATPCS-MODE-CREATED R@ ATPCS.MODE !
    AT-CREATE-RECORD-STATE-IDLE R@ ATPCS.STATE !
    AT-CREATE-RECORD-OUTCOME-NO-EFFECT R@ ATPCS.OUTCOME !
    AT-CREATE-RECORD-S-OK R@ ATPCS.LAST-STATUS !
    _ATPCS-OWNER-MAGIC R@ ATPCS.MAGIC !
    R> DROP AT-CREATE-RECORD-S-OK ;

