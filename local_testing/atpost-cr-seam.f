: AT-CREATE-RECORD-PREPARE
  \ ( iat target collection-a collection-u rkey-a rkey-u
  \   record-a record-u owner -- status )
    _ATPCSP-OWNER ! _ATPCSP-RECORD-U ! _ATPCSP-RECORD-A !
    _ATPCSP-RKEY-U ! _ATPCSP-RKEY-A !
    _ATPCSP-COLLECTION-U ! _ATPCSP-COLLECTION-A !
    _ATPCSP-TARGET ! _ATPCSP-IAT !
    _ATPCSP-OWNER @ AT-CREATE-RECORD-VALID? 0= IF
        AT-CREATE-RECORD-S-INVALID _ATPCSP-RETURN EXIT
    THEN
    _ATPCSP-OWNER @ ATPCS.STATE @
    AT-CREATE-RECORD-STATE-IDLE <> IF
        AT-CREATE-RECORD-S-BUSY _ATPCSP-REPORT EXIT
    THEN
    _ATPCSP-TARGET @ AT-CREATE-RECORD-TARGET? 0= IF
        AT-CREATE-RECORD-S-TARGET _ATPCSP-REPORT EXIT
    THEN
    _ATPCSP-OWNER @ ATPCS.MODE @ ATPCS-MODE-PREPARE-FAIL = IF
        AT-CREATE-RECORD-S-CAPACITY _ATPCSP-REPORT EXIT
    THEN
    _ATPCSP-COLLECTION-U @ DUP 0> 0= SWAP
    _ATPCS-COLLECTION-CAP > OR IF
        AT-CREATE-RECORD-S-COLLECTION _ATPCSP-REPORT EXIT
    THEN
    _ATPCSP-RKEY-U @ DUP 0> 0= SWAP _ATPCS-RKEY-CAP > OR IF
        AT-CREATE-RECORD-S-RKEY _ATPCSP-REPORT EXIT
    THEN
    _ATPCSP-RECORD-U @ DUP 0> 0= SWAP
    BSKY-TEXT-RECORD-BODY-MAX > OR IF
        AT-CREATE-RECORD-S-RECORD _ATPCSP-REPORT EXIT
    THEN
    _ATPCSP-IAT @ _ATPCSP-OWNER @ ATPCS.IAT !
    _ATPCSP-COLLECTION-U @ _ATPCSP-OWNER @ ATPCS.COLLECTION-U !
    _ATPCSP-RKEY-U @ _ATPCSP-OWNER @ ATPCS.RKEY-U !
    _ATPCSP-RECORD-U @ _ATPCSP-OWNER @ ATPCS.RECORD-U !
    _ATPCSP-COLLECTION-A @ _ATPCSP-OWNER @ ATPCS.COLLECTION
        _ATPCSP-COLLECTION-U @ MOVE
    _ATPCSP-RKEY-A @ _ATPCSP-OWNER @ ATPCS.RKEY
        _ATPCSP-RKEY-U @ MOVE
    _ATPCSP-RECORD-A @ _ATPCSP-OWNER @ ATPCS.RECORD
        _ATPCSP-RECORD-U @ MOVE
    AT-CREATE-RECORD-OUTCOME-PENDING
        _ATPCSP-OWNER @ ATPCS.OUTCOME !
    AT-CREATE-RECORD-STATE-PREPARED _ATPCSP-OWNER @ ATPCS.STATE !
    AT-CREATE-RECORD-S-OK _ATPCSP-REPORT ;

