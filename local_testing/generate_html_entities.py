#!/usr/bin/env python3
"""Generate Akashic's table of HTML named character references.

The WHATWG HTML standard lists the named character references, such as
``&amp;`` and ``&NotEqualTilde;``, and says the list will not change.
Python's ``html.entities.html5`` is that list.  Markdown decodes every
reference whose name ends with a semicolon, so the table holds those 2,125.

    python3 local_testing/generate_html_entities.py [--check]

``--check`` exits nonzero when the checked-in file differs from what the list
produces, so a test can prove the table is current.  The file is never edited
by hand.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from html.entities import html5
from pathlib import Path


AKASHIC_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = AKASHIC_ROOT / "akashic" / "markup" / "html-entities.f"

# The list is frozen, so its size and contents are pinned: a Python whose
# list differs cannot produce a different table unnoticed.
EXPECTED_COUNT = 2125
EXPECTED_SHA256 = "d62c29d4264e9a4b39cdcba06ea0b976888df93ded3e9eddf005d8459742d9a5"

# Room left on each source line for the text between S" and the closing
# quote, below the 255-byte line the guest's interpreter accepts.
LINE_TEXT = 200


class EntityError(RuntimeError):
    pass


def references() -> list[tuple[str, tuple[int, ...]]]:
    """Each reference ending in a semicolon, by name, and its scalars."""

    entries = []
    for key, value in html5.items():
        if not key.endswith(";"):
            continue
        entries.append((key[:-1], tuple(ord(character) for character in value)))
    entries.sort()
    return entries


def entry_text(name: str, scalars: tuple[int, ...]) -> str:
    return f"{name}={','.join(f'{scalar:X}' for scalar in scalars)} "


def render() -> str:
    entries = references()
    if len(entries) != EXPECTED_COUNT:
        raise EntityError(f"expected {EXPECTED_COUNT} references, found {len(entries)}")
    text = "".join(entry_text(name, scalars) for name, scalars in entries)
    digest = hashlib.sha256(text.encode("ascii")).hexdigest()
    if digest != EXPECTED_SHA256:
        raise EntityError(f"the reference list changed (SHA-256 {digest})")
    if any(len(scalars) not in (1, 2) for _name, scalars in entries):
        raise EntityError("html-entities.f keeps one or two scalars a reference")
    if '"' in text:
        raise EntityError("a quote would end an S\" string")

    lines = []
    line = ""
    for name, scalars in entries:
        piece = entry_text(name, scalars)
        if len(line) + len(piece) > LINE_TEXT:
            lines.append(line)
            line = ""
        line += piece
    lines.append(line)

    out = [
        "\\ =================================================================",
        "\\  html-entities.f — the HTML named character references",
        "\\ =================================================================",
        "\\  GENERATED by local_testing/generate_html_entities.py from the",
        "\\  WHATWG list of named character references, which will not",
        "\\  change.  Do not edit.",
        "\\",
        "\\  Prefix: HENT- (public), _HENT- (private)",
        "\\",
        "\\  Public API:",
        "\\    HENT-LOOKUP  ( name-a name-u -- cp1 cp2 n )",
        "\\      The scalars the reference &name; stands for: N is 1 or 2, or",
        "\\      0 when no reference has the name, and CP2 is 0 unless N is 2.",
        "\\      Names are case-sensitive and given without & and ;.",
        "\\",
        "\\  The references are one text, each an entry \"name=hex\" or",
        "\\  \"name=hex,hex\" and a space, sorted by name.  At load time an",
        "\\  index of where each entry starts is built once, so a lookup",
        "\\  searches the names in halves.  Every word only reads the text and",
        "\\  the index, so it is reentrant and needs no guard.",
        "\\ =================================================================",
        "",
        "PROVIDED akashic-html-entities",
        "",
        f"{len(entries)} CONSTANT HENT-COUNT",
        f"{len(text)} CONSTANT _HENT-BYTES",
        "",
        "CREATE _HENT-TEXT _HENT-BYTES ALLOT",
        "VARIABLE _HENT-AT  0 _HENT-AT !",
        ": _HENT+  ( a u -- )",
        "    DUP >R _HENT-TEXT _HENT-AT @ + SWAP MOVE R> _HENT-AT +! ;",
        "",
        *(f'S" {chunk}" _HENT+' for chunk in lines),
        "",
        "\\ Where each entry starts, four bytes an entry.",
        "CREATE _HENT-INDEX HENT-COUNT 4 * ALLOT",
        "",
        "VARIABLE _HENT-I",
        ": _HENT-INDEX!  ( -- )",
        "    0 _HENT-I !",
        "    0 BEGIN DUP _HENT-BYTES < WHILE",
        "        DUP _HENT-I @ 4 * _HENT-INDEX + L!  1 _HENT-I +!",
        "        BEGIN DUP _HENT-TEXT + C@ 32 <> WHILE 1+ REPEAT 1+",
        "    REPEAT DROP ;",
        "_HENT-INDEX!",
        "",
        "\\ The name of entry I.",
        ": _HENT-NAME  ( i -- a u )",
        "    4 * _HENT-INDEX + L@ _HENT-TEXT +",
        "    0 BEGIN 2DUP + C@ 61 <> WHILE 1+ REPEAT ;",
        "",
        "\\ One hexadecimal scalar at A, and the byte after it.",
        ": _HENT-HEX  ( a -- cp a' )",
        "    0 SWAP",
        "    BEGIN DUP C@ DUP 44 <> SWAP 32 <> AND WHILE",
        "        DUP C@ DUP 65 < IF 48 - ELSE 55 - THEN",
        "        ROT 4 LSHIFT + SWAP 1+",
        "    REPEAT ;",
        "",
        "\\ The scalars of entry I.",
        ": _HENT-VALUE  ( i -- cp1 cp2 n )",
        "    _HENT-NAME + 1+ _HENT-HEX",
        "    DUP C@ 44 = IF 1+ _HENT-HEX DROP 2 EXIT THEN",
        "    DROP 0 1 ;",
        "",
        "VARIABLE _HENT-A",
        "VARIABLE _HENT-U",
        "VARIABLE _HENT-LO",
        "VARIABLE _HENT-HI",
        "",
        ": HENT-LOOKUP  ( name-a name-u -- cp1 cp2 n )",
        "    _HENT-U ! _HENT-A !",
        "    0 _HENT-LO !  HENT-COUNT _HENT-HI !",
        "    BEGIN _HENT-LO @ _HENT-HI @ < WHILE",
        "        _HENT-LO @ _HENT-HI @ + 2/",
        "        _HENT-A @ _HENT-U @ 2 PICK _HENT-NAME COMPARE",
        "        DUP 0= IF DROP _HENT-VALUE EXIT THEN",
        "        0< IF _HENT-HI ! ELSE 1+ _HENT-LO ! THEN",
        "    REPEAT",
        "    0 0 0 ;",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != text:
            print(f"{args.output} is stale; rerun the generator", file=sys.stderr)
            return 1
        print(f"{args.output} matches the WHATWG list")
        return 0
    args.output.write_text(text, encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
