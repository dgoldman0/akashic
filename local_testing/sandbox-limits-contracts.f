\ Contracts for the sandbox limit record: building one source, narrowing
\ by other sources, and materializing the value limits and activation
\ limits of one invocation.

PROVIDED sbox-limits-tests

VARIABLE _SLC-FAILS
VARIABLE _SLC-CHECKS
VARIABLE _SLC-DEPTH
VARIABLE _SLC-BYTE

: _SLC-ALIGN8  ( address -- aligned-address ) 7 + -8 AND ;

CREATE _SLC-A-RAW SBOX-LIMITS-SIZE 7 + ALLOT
_SLC-A-RAW _SLC-ALIGN8 CONSTANT _SLC-A
CREATE _SLC-B-RAW SBOX-LIMITS-SIZE 7 + ALLOT
_SLC-B-RAW _SLC-ALIGN8 CONSTANT _SLC-B
\ Eight spare bytes hold a copy that overlaps C.
CREATE _SLC-C-RAW SBOX-LIMITS-SIZE 15 + ALLOT
_SLC-C-RAW _SLC-ALIGN8 CONSTANT _SLC-C
CREATE _SLC-V-RAW SBOX-VALUE-LIMITS-SIZE 7 + ALLOT
_SLC-V-RAW _SLC-ALIGN8 CONSTANT _SLC-V
\ Eight spare bytes let a misaligned record be named.
CREATE _SLC-M-RAW SBOX-VM-LIMITS-SIZE 15 + ALLOT
_SLC-M-RAW _SLC-ALIGN8 CONSTANT _SLC-M

: _SLC-ASSERT  ( flag -- )
    1 _SLC-CHECKS +!
    0= IF
        1 _SLC-FAILS +!
        ." SBOX LIMITS ASSERT " _SLC-CHECKS @ . CR
    THEN ;

: _SLC-STACK  ( -- )
    DEPTH DUP _SLC-DEPTH @ <> IF
        ." SBOX LIMITS STACK "
        _SLC-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _SLC-DEPTH @ = _SLC-ASSERT ;

: _SLC-FILLED?  ( address length byte -- flag )
    _SLC-BYTE !
    0 ?DO
        DUP I + C@ _SLC-BYTE @ <> IF
            DROP 0 UNLOOP EXIT
        THEN
    LOOP
    DROP -1 ;

: _SLC-CAP  ( value field limits -- )
    SBOX-LIMIT-CAP SBOX-LIMITS-S-OK = _SLC-ASSERT ;

: _SLC-FIELD=  ( expected field limits -- )
    SBOX-LIMIT@ SBOX-LIMITS-S-OK = -ROT = AND _SLC-ASSERT ;

: _SLC-VM=  ( expected field -- )
    _SLC-M SBOX-VM-LIMIT@ = _SLC-ASSERT ;

\ A complete host policy, as a host's caller supplies it.
: _SLC-POLICY  ( depth limits -- )
    DUP SBOX-LIMITS-BEGIN SBOX-LIMITS-S-OK = _SLC-ASSERT
    >R
    2000000 SBOX-LIMIT-INSTRUCTION-BUDGET R@ _SLC-CAP
    20000 SBOX-LIMIT-VALUE-OP-BUDGET R@ _SLC-CAP
    4096 SBOX-LIMIT-COPY-BUDGET R@ _SLC-CAP
    30000 SBOX-LIMIT-WALL-MS R@ _SLC-CAP
    SBOX-LIMIT-DEPTH R@ _SLC-CAP
    65536 SBOX-LIMIT-BLOB-BYTES R@ _SLC-CAP
    64 SBOX-LIMIT-LIST-COUNT R@ _SLC-CAP
    32 SBOX-LIMIT-MAP-COUNT R@ _SLC-CAP
    256 SBOX-LIMIT-INPUT-NODES R@ _SLC-CAP
    65536 SBOX-LIMIT-INPUT-BYTES R@ _SLC-CAP
    256 SBOX-LIMIT-OUTPUT-ARENA-NODES R@ _SLC-CAP
    65536 SBOX-LIMIT-OUTPUT-ARENA-BYTES R@ _SLC-CAP
    256 SBOX-LIMIT-OUTPUT-RESULT-NODES R@ _SLC-CAP
    131072 SBOX-LIMIT-OUTPUT-RESULT-BYTES R@ _SLC-CAP
    1024 SBOX-LIMIT-DATA-STACK R@ _SLC-CAP
    128 SBOX-LIMIT-CALL-FRAMES R@ _SLC-CAP
    32 SBOX-LIMIT-LOOP-FRAMES R@ _SLC-CAP
    524288 SBOX-LIMIT-MEMORY-BYTES R@ _SLC-CAP
    R> SBOX-LIMITS-SEAL SBOX-LIMITS-S-OK = _SLC-ASSERT ;

\ One partial source bounds only the fields it constrains.
: _SLC-BUILD  ( -- )
    0 SBOX-LIMITS-BEGIN SBOX-LIMITS-S-INVALID = _SLC-ASSERT
    _SLC-A 1+ SBOX-LIMITS-BEGIN SBOX-LIMITS-S-INVALID = _SLC-ASSERT

    _SLC-A SBOX-LIMITS-BEGIN SBOX-LIMITS-S-OK = _SLC-ASSERT
    _SLC-A SBOX-LIMITS-VALID? 0= _SLC-ASSERT
    SBOX-LIMIT-DEPTH _SLC-A SBOX-LIMIT@
        SBOX-LIMITS-S-INVALID = SWAP 0= AND _SLC-ASSERT
    0 SBOX-LIMIT-DEPTH _SLC-A SBOX-LIMIT-CAP
        SBOX-LIMITS-S-RANGE = _SLC-ASSERT
    5 -1 _SLC-A SBOX-LIMIT-CAP SBOX-LIMITS-S-RANGE = _SLC-ASSERT
    5 SBOX-LIMIT-COUNT _SLC-A SBOX-LIMIT-CAP
        SBOX-LIMITS-S-RANGE = _SLC-ASSERT
    500 SBOX-LIMIT-INSTRUCTION-BUDGET _SLC-A _SLC-CAP
    \ A later, larger cap never raises a field.
    900 SBOX-LIMIT-INSTRUCTION-BUDGET _SLC-A _SLC-CAP
    4 SBOX-LIMIT-DEPTH _SLC-A _SLC-CAP
    250 SBOX-LIMIT-WALL-MS _SLC-A _SLC-CAP
    64 SBOX-LIMIT-CALL-FRAMES _SLC-A _SLC-CAP

    _SLC-A SBOX-LIMITS-SEAL SBOX-LIMITS-S-OK = _SLC-ASSERT
    _SLC-A SBOX-LIMITS-VALID? _SLC-ASSERT
    _SLC-A SBOX-LIMITS-BOUNDED? 0= _SLC-ASSERT
    500 SBOX-LIMIT-INSTRUCTION-BUDGET _SLC-A _SLC-FIELD=
    4 SBOX-LIMIT-DEPTH _SLC-A _SLC-FIELD=
    SBOX-LIMIT-UNBOUNDED SBOX-LIMIT-COPY-BUDGET _SLC-A _SLC-FIELD=
    SBOX-LIMIT-COUNT _SLC-A SBOX-LIMIT@
        SBOX-LIMITS-S-RANGE = SWAP 0= AND _SLC-ASSERT
    1 SBOX-LIMIT-DEPTH _SLC-A SBOX-LIMIT-CAP
        SBOX-LIMITS-S-STATE = _SLC-ASSERT
    _SLC-A SBOX-LIMITS-SEAL SBOX-LIMITS-S-STATE = _SLC-ASSERT
    4 SBOX-LIMIT-DEPTH _SLC-A _SLC-FIELD=

    8 _SLC-B _SLC-POLICY
    _SLC-B SBOX-LIMITS-BOUNDED? _SLC-ASSERT ;

\ Copies are exact and relocated; sources only ever narrow a target.
: _SLC-COMBINE  ( -- )
    _SLC-B _SLC-C SBOX-LIMITS-COPY SBOX-LIMITS-S-OK = _SLC-ASSERT
    _SLC-C SBOX-LIMITS-VALID? _SLC-ASSERT
    _SLC-C SBOX-LIMITS-BOUNDED? _SLC-ASSERT
    2000000 SBOX-LIMIT-INSTRUCTION-BUDGET _SLC-C _SLC-FIELD=
    _SLC-C _SLC-C SBOX-LIMITS-COPY SBOX-LIMITS-S-OK = _SLC-ASSERT
    _SLC-C _SLC-C 8 + SBOX-LIMITS-COPY
        SBOX-LIMITS-S-ALIAS = _SLC-ASSERT
    _SLC-C SBOX-LIMITS-VALID? _SLC-ASSERT
    _SLC-V _SLC-C SBOX-LIMITS-COPY SBOX-LIMITS-S-INVALID = _SLC-ASSERT

    _SLC-A _SLC-C SBOX-LIMITS-MEET SBOX-LIMITS-S-OK = _SLC-ASSERT
    500 SBOX-LIMIT-INSTRUCTION-BUDGET _SLC-C _SLC-FIELD=
    4 SBOX-LIMIT-DEPTH _SLC-C _SLC-FIELD=
    20000 SBOX-LIMIT-VALUE-OP-BUDGET _SLC-C _SLC-FIELD=
    250 SBOX-LIMIT-WALL-MS _SLC-C _SLC-FIELD=
    64 SBOX-LIMIT-CALL-FRAMES _SLC-C _SLC-FIELD=
    1024 SBOX-LIMIT-DATA-STACK _SLC-C _SLC-FIELD=
    _SLC-C SBOX-LIMITS-BOUNDED? _SLC-ASSERT
    _SLC-B _SLC-C SBOX-LIMITS-MEET SBOX-LIMITS-S-OK = _SLC-ASSERT
    500 SBOX-LIMIT-INSTRUCTION-BUDGET _SLC-C _SLC-FIELD=
    _SLC-C _SLC-C SBOX-LIMITS-MEET SBOX-LIMITS-S-OK = _SLC-ASSERT
    4 SBOX-LIMIT-DEPTH _SLC-C _SLC-FIELD=
    2000000 SBOX-LIMIT-INSTRUCTION-BUDGET _SLC-B _SLC-FIELD=
    8 SBOX-LIMIT-DEPTH _SLC-B _SLC-FIELD=
    0 _SLC-C SBOX-LIMITS-MEET SBOX-LIMITS-S-INVALID = _SLC-ASSERT
    _SLC-C 8 + _SLC-C SBOX-LIMITS-MEET
        SBOX-LIMITS-S-INVALID = _SLC-ASSERT ;

\ Only a fully bounded record becomes the limits of one invocation.
: _SLC-MATERIALIZE  ( -- )
    _SLC-C _SLC-V _SLC-M SBOX-LIMITS-MATERIALIZE
        SBOX-LIMITS-S-OK = _SLC-ASSERT
    500 SBOX-VM-LIMIT-INSTRUCTIONS _SLC-VM=
    20000 SBOX-VM-LIMIT-VALUE-OPS _SLC-VM=
    4096 SBOX-VM-LIMIT-COPY-BYTES _SLC-VM=
    1024 SBOX-VM-LIMIT-DATA-STACK _SLC-VM=
    64 SBOX-VM-LIMIT-CALL-FRAMES _SLC-VM=
    32 SBOX-VM-LIMIT-LOOP-FRAMES _SLC-VM=
    524288 SBOX-VM-LIMIT-MEMORY-BYTES _SLC-VM=
    _SLC-M SBOX-VM-LIMITS-VALID? _SLC-ASSERT
    _SLC-V SBOX-VALUE-LIMITS-VALID? _SLC-ASSERT
    SBOX-VALUE-LIMIT-DEPTH _SLC-V SBOX-VALUE-LIMIT@
        SBOX-VALUE-S-OK = SWAP 4 = AND _SLC-ASSERT
    SBOX-VALUE-LIMIT-MAP-COUNT _SLC-V SBOX-VALUE-LIMIT@
        SBOX-VALUE-S-OK = SWAP 32 = AND _SLC-ASSERT
    SBOX-VALUE-LIMIT-OUTPUT-RESULT-BYTES _SLC-V SBOX-VALUE-LIMIT@
        SBOX-VALUE-S-OK = SWAP 131072 = AND _SLC-ASSERT

    _SLC-A _SLC-V _SLC-M SBOX-LIMITS-MATERIALIZE
        SBOX-LIMITS-S-UNBOUNDED = _SLC-ASSERT
    _SLC-B _SLC-B 8 + _SLC-M SBOX-LIMITS-MATERIALIZE
        SBOX-LIMITS-S-ALIAS = _SLC-ASSERT
    _SLC-B _SLC-V _SLC-B 8 + SBOX-LIMITS-MATERIALIZE
        SBOX-LIMITS-S-ALIAS = _SLC-ASSERT
    _SLC-B _SLC-V _SLC-V 8 + SBOX-LIMITS-MATERIALIZE
        SBOX-LIMITS-S-ALIAS = _SLC-ASSERT
    _SLC-B SBOX-LIMITS-VALID? _SLC-ASSERT
    0 _SLC-V _SLC-M SBOX-LIMITS-MATERIALIZE
        SBOX-LIMITS-S-INVALID = _SLC-ASSERT
    _SLC-B _SLC-V 0 SBOX-LIMITS-MATERIALIZE
        SBOX-LIMITS-S-INVALID = _SLC-ASSERT
    _SLC-B _SLC-V _SLC-M 1+ SBOX-LIMITS-MATERIALIZE
        SBOX-LIMITS-S-INVALID = _SLC-ASSERT

    \ Value limits beyond the implementation's ceilings never materialize,
    \ and a failure leaves neither output usable.
    SBOX-VALUE-IMPLEMENTATION-DEPTH-MAX 1+ _SLC-C _SLC-POLICY
    _SLC-C _SLC-V _SLC-M SBOX-LIMITS-MATERIALIZE
        SBOX-LIMITS-S-VALUE = _SLC-ASSERT
    _SLC-V SBOX-VALUE-LIMITS-SIZE 0 _SLC-FILLED? _SLC-ASSERT
    _SLC-M SBOX-VM-LIMITS-SIZE 0 _SLC-FILLED? _SLC-ASSERT ;

: _SLC-RUN  ( -- )
    DEPTH _SLC-DEPTH !
    0 _SLC-FAILS !
    0 _SLC-CHECKS !
    _SLC-BUILD _SLC-STACK
    _SLC-COMBINE _SLC-STACK
    _SLC-MATERIALIZE _SLC-STACK
    _SLC-FAILS @ IF
        ." SBOX LIMITS CONTRACTS FAIL "
        _SLC-FAILS @ . ." / " _SLC-CHECKS @ . CR
    ELSE
        ." SBOX LIMITS CONTRACTS PASS "
        _SLC-CHECKS @ . CR
    THEN ;

_SLC-RUN
