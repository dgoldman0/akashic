: _S1-VM-PREPARE  ( source source-u memory-u -- )
    _S1-COMPILE-VERIFY-ONE
    _S1-PLAN _S1-BINDING SBOX-BINDING-PURE-INIT
        SBOX-BINDING-S-OK = _S1-ASSERT
    _S1-PLAN _S1-BINDING SBOX-BINDING-VALID-FOR?
        _S1-ASSERT
    _S1-PLAN SBOX-VM-INSTANCE-MEASURE
    SBOX-VM-S-OK = _S1-ASSERT
    DUP 0> _S1-ASSERT
    DUP _S1-INSTANCE-CAP <= _S1-ASSERT
    _S1-INSTANCE-U ! ;

: _S1-VM-INIT-ONE
  ( input input-n budget instance -- status )
    DUP _S1-INSTANCE-U @ 0xA5 FILL
    >R >R >R >R
    _S1-PLAN _S1-BINDING 0
    R> R> R> R>
    _S1-INSTANCE-U @
    _SVM-SCALAR-INIT ;

: _S1-INSTANCE-RELEASE-ONE  ( instance -- )
    DUP SBOX-VM-RELEASE SBOX-VM-S-OK = _S1-ASSERT
    DUP _S1-INSTANCE-U @ _S1-ZERO-CELLS? _S1-ASSERT
    SBOX-VM-RELEASE SBOX-VM-S-OK = _S1-ASSERT ;

: _S1-RESULT-RELEASE-ONE  ( result -- )
    DUP SBOX-VM-RESULT-RELEASE SBOX-VM-S-OK = _S1-ASSERT
    DUP SBOX-VM-RESULT-SIZE _S1-ZERO-CELLS? _S1-ASSERT
    SBOX-VM-RESULT-RELEASE SBOX-VM-S-OK = _S1-ASSERT ;

: _S1-VM-PREPARED-RELEASE  ( -- )
    _S1-BINDING SBOX-BINDING-RELEASE
        SBOX-BINDING-S-OK = _S1-ASSERT
    _S1-BINDING SBOX-BINDING-SIZE
        _S1-ZERO-CELLS? _S1-ASSERT
    _S1-PLAN SBOX-PLAN-RELEASE
        SBOX-PLAN-S-OK = _S1-ASSERT
    _S1-PLAN _S1-PLAN-U @
        _S1-ZERO-CELLS? _S1-ASSERT ;

: _S1-RESULT-ONE  ( expected result -- )
    >R
    R@ SBOX-VM-RESULT-VALID? _S1-ASSERT
    R@ SBOX-VM-RESULT-CLASS@
        SBOX-VM-CLASS-OK = _S1-ASSERT
    R@ SBOX-VM-RESULT-DETAIL@ 0= _S1-ASSERT
    R@ SBOX-VM-RESULT-AUX@ 0= _S1-ASSERT
    R@ SBOX-VM-RESULT-USAGE@ 0> _S1-ASSERT
    R@ SBOX-VM-RESULT-COUNT@ 1 = _S1-ASSERT
    0 R@ SBOX-VM-RESULT-CELL@
    _S1-ASSERT
    = _S1-ASSERT
    R> DROP ;

: _S1-RESULT-ERROR  ( class detail result -- )
    >R
    R@ SBOX-VM-RESULT-VALID? _S1-ASSERT
    R@ SBOX-VM-RESULT-CLASS@
    2 PICK = _S1-ASSERT
    R@ SBOX-VM-RESULT-DETAIL@
    1 PICK = _S1-ASSERT
    R@ SBOX-VM-RESULT-AUX@ 0= _S1-ASSERT
    R@ SBOX-VM-RESULT-COUNT@ 0= _S1-ASSERT
    2DROP R> DROP ;

: _S1-VM-SUCCESS-A  ( input input-n expected -- )
    >R
    1000 _S1-INSTANCE-A _S1-VM-INIT-ONE
        SBOX-VM-S-OK = _S1-ASSERT
    _S1-INSTANCE-A SBOX-VM-INSTANCE-VALID? _S1-ASSERT
    _S1-INSTANCE-A SBOX-VM-RUN-STATE@
        SBOX-VM-RUN-RUNNABLE = _S1-ASSERT
    1000 _S1-INSTANCE-A SBOX-VM-RUN-SLICE
        SBOX-VM-RUN-COMPLETE = _S1-ASSERT
    _S1-INSTANCE-A SBOX-VM-USAGE@ 0> _S1-ASSERT
    _S1-RESULT-A _S1-INSTANCE-A SBOX-VM-FINISH
        SBOX-VM-S-OK = _S1-ASSERT
    _S1-INSTANCE-A SBOX-VM-INSTANCE-VALID? _S1-ASSERT
    _S1-INSTANCE-A SBOX-VM-RUN-STATE@
        SBOX-VM-RUN-FINISHED = _S1-ASSERT
    _S1-INSTANCE-A SBOX-VM-USAGE@ 0= _S1-ASSERT
    _S1-INSTANCE-A _S1-INSTANCE-RELEASE-ONE
    R> _S1-RESULT-A _S1-RESULT-ONE
    _S1-RESULT-A _S1-RESULT-RELEASE-ONE
    _S1-STACK ;

: _S1-VM-SUCCESS-SCALAR-CONTRACTS  ( -- )
    _S1-SOURCE-ADD 64 _S1-VM-PREPARE
    20 _S1-INPUT-A !
    22 _S1-INPUT-A 8 + !
    _S1-INPUT-A 2 42 _S1-VM-SUCCESS-A
    _S1-VM-PREPARED-RELEASE

    _S1-SOURCE-FORWARD-CALL 64 _S1-VM-PREPARE
    21 _S1-INPUT-A !
    _S1-INPUT-A 1 42 _S1-VM-SUCCESS-A
    _S1-VM-PREPARED-RELEASE

    \ One verified plan takes both conditional paths in separate invocations.
    _S1-SOURCE-CONTROL 64 _S1-VM-PREPARE
    0 _S1-INPUT-A !
    _S1-INPUT-A 1 20 _S1-VM-SUCCESS-A
    1 _S1-INPUT-A !
    _S1-INPUT-A 1 11 _S1-VM-SUCCESS-A
    _S1-VM-PREPARED-RELEASE
    _S1-STACK ;

: _S1-VM-SUCCESS-STATE-CONTRACTS  ( -- )
    _S1-SOURCE-WHILE 64 _S1-VM-PREPARE
    0 0 3 _S1-VM-SUCCESS-A
    _S1-VM-PREPARED-RELEASE

    \ R is the innermost counted-loop index; the nested sum is six.
    _S1-SOURCE-LOOPS 64 _S1-VM-PREPARE
    0 0 6 _S1-VM-SUCCESS-A
    _S1-VM-PREPARED-RELEASE

    _S1-SOURCE-MEMORY 64 _S1-VM-PREPARE
    0 0 42 _S1-VM-SUCCESS-A
    _S1-VM-PREPARED-RELEASE
    _S1-STACK ;

