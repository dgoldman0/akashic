: _S1-COMPILE  ( source source-u memory-u -- status )
    >R
    _S1-CANDIDATE _S1-CANDIDATE-CAP 0xA5 FILL
    _S1-PROFILE
    R>
    _S1-CANDIDATE _S1-CANDIDATE-CAP
    _S1-COMPILER-WORK
    SBOX-COMPILE
    SWAP _S1-CANDIDATE-U ! ;

: _S1-VERIFY  ( -- status )
    _S1-CANDIDATE-U @ SBOX-PLAN-MEASURE
    DUP IF
        >R DROP 0 _S1-PLAN-U ! R> EXIT
    THEN
    DROP
    DUP _S1-PLAN-U !
    >R
    _S1-CANDIDATE _S1-CANDIDATE-U @
    _S1-PROFILE
    _S1-PLAN R>
    _S1-VERIFIER-WORK
    SBOX-VERIFY ;

