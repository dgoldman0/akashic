    >R >R
    _S1-PLAN _S1-PLAN-CAP 0xA5 FILL
    _S1-VERIFY R> = _S1-ASSERT
    _S1-PLAN _S1-PLAN-U @ 0 _S1-FILLED? _S1-ASSERT
    _S1-VERIFIER-WORK SBOX-VERIFIER-ERROR-DETAIL@
        SBOX-VERIFIER-S-OK =
        SWAP R> = AND _S1-ASSERT ;

: _S1-VERIFIER-RECORD-REJECTIONS  ( -- )
    \ Exact source truncation is rejected as candidate geometry.
    _S1-SOURCE-ADD 64 _S1-COMPILE
        SBOX-COMPILER-S-OK = _S1-ASSERT
    -1 _S1-CANDIDATE-U +!
    SBOX-VERIFIER-S-CANDIDATE
        SBOX-VERIFIER-D-CANDIDATE-GEOMETRY
        _S1-VERIFY-EXPECT

    \ A reserved function flag is a record error, not executable metadata.
    _S1-SOURCE-ADD 64 _S1-COMPILE
        SBOX-COMPILER-S-OK = _S1-ASSERT
    _S1-INSPECT
    1 0 _S1-FUNCTION@
        SBOX-CANDIDATE-FUNCTION-FLAGS-OFFSET +
        SBOX-CANDIDATE-U16-LE!
    SBOX-VERIFIER-S-FUNCTION
        SBOX-VERIFIER-D-FUNCTION-FLAGS
        _S1-VERIFY-EXPECT

    \ Unknown instructions never reach plan publication.
    _S1-SOURCE-ADD 64 _S1-COMPILE
        SBOX-COMPILER-S-OK = _S1-ASSERT
    _S1-INSPECT
    0x0F 0 _S1-INSTRUCTION@
        SBOX-CANDIDATE-INSTRUCTION-OPCODE-OFFSET +
        SBOX-CANDIDATE-U16-LE!
    SBOX-VERIFIER-S-OPCODE
        SBOX-VERIFIER-D-INSTRUCTION-OPCODE
        _S1-VERIFY-EXPECT

    \ A function-local branch target cannot escape its instruction range.
    _S1-SOURCE-CONTROL 64 _S1-COMPILE
        SBOX-COMPILER-S-OK = _S1-ASSERT
    _S1-INSPECT
    999 1 _S1-INSTRUCTION@
        SBOX-CANDIDATE-INSTRUCTION-A-OFFSET +
        SBOX-CANDIDATE-U32-LE!
    SBOX-VERIFIER-S-TARGET
        SBOX-VERIFIER-D-INSTRUCTION-TARGET
        _S1-VERIFY-EXPECT ;

: _S1-VERIFIER-CFG-REJECTIONS  ( -- )
    \ Removing a DO opener while leaving its canonical closer is a typed
    \ loop-structure failure.
    _S1-SOURCE-LOOPS 64 _S1-COMPILE
        SBOX-COMPILER-S-OK = _S1-ASSERT
    _S1-INSPECT
    SBOX-MACHINE-OP-LOOP-ENTER _S1-FIND-OPCODE
    DUP 0<> _S1-ASSERT
    _S1-RECORD !
    SBOX-MACHINE-OP-NOP
        _S1-RECORD @ SBOX-CANDIDATE-U16-LE!
    0 _S1-RECORD @ SBOX-CANDIDATE-INSTRUCTION-A-OFFSET +
        SBOX-CANDIDATE-U32-LE!
    0 _S1-RECORD @ SBOX-CANDIDATE-INSTRUCTION-B-OFFSET +
        SBOX-CANDIDATE-U64-LE!
    SBOX-VERIFIER-S-LOOP
        SBOX-VERIFIER-D-LOOP-INDEX
        _S1-VERIFY-EXPECT

    \ Valid branch geometry can still make an instruction unreachable.
    _S1-SOURCE-DEAD-CODE 64 _S1-COMPILE
        SBOX-COMPILER-S-OK = _S1-ASSERT
    _S1-INSPECT
    SBOX-MACHINE-OP-BR 0 _S1-INSTRUCTION@
        SBOX-CANDIDATE-U16-LE!
    2 0 _S1-INSTRUCTION@
        SBOX-CANDIDATE-INSTRUCTION-A-OFFSET +
        SBOX-CANDIDATE-U32-LE!
    SBOX-VERIFIER-S-UNREACHABLE
        SBOX-VERIFIER-D-UNREACHABLE
        _S1-VERIFY-EXPECT

    \ A structurally valid function must still return its declared height.
    _S1-SOURCE-WRONG-RETURN 64 _S1-COMPILE
        SBOX-COMPILER-S-OK = _S1-ASSERT
    _S1-INSPECT
    SBOX-MACHINE-OP-NOP 0 _S1-INSTRUCTION@
        SBOX-CANDIDATE-U16-LE!
    0 0 _S1-INSTRUCTION@
        SBOX-CANDIDATE-INSTRUCTION-B-OFFSET +
        SBOX-CANDIDATE-U64-LE!
    SBOX-VERIFIER-S-STACK
        SBOX-VERIFIER-D-STACK-RETURN
        _S1-VERIFY-EXPECT ;

