: _S1-VM-BUDGET-CANCEL-CONTRACTS  ( -- )
    _S1-SOURCE-SPIN 64 _S1-VM-PREPARE

    \ The first unit is admitted exactly; the next instruction cannot
    \ reserve another unit and must not increase reported usage.
    0 0 1 _S1-INSTANCE-A _S1-VM-INIT-ONE
        SBOX-VM-S-OK = _S1-ASSERT
    _S1-INSTANCE-A SBOX-VM-STEP
        SBOX-VM-RUN-RUNNABLE = _S1-ASSERT
    _S1-INSTANCE-A SBOX-VM-USAGE@ 1 = _S1-ASSERT
    _S1-INSTANCE-A SBOX-VM-STEP
        SBOX-VM-RUN-EXHAUSTED = _S1-ASSERT
    _S1-INSTANCE-A SBOX-VM-USAGE@ 1 = _S1-ASSERT
    _S1-RESULT-A _S1-INSTANCE-A SBOX-VM-FINISH
        SBOX-VM-S-OK = _S1-ASSERT
    _S1-RESULT-A SBOX-VM-RESULT-USAGE@ 1 = _S1-ASSERT
    SBOX-VM-CLASS-RESOURCE-EXHAUSTED
        SBOX-VM-EXHAUST-INSTRUCTION-UNITS
        _S1-RESULT-A _S1-RESULT-ERROR
    _S1-INSTANCE-A _S1-INSTANCE-RELEASE-ONE
    _S1-RESULT-A _S1-RESULT-RELEASE-ONE

    \ Cancellation is per instance, retains usage, and is stable when
    \ repeated before FINISH transfers the terminal result.
    0 0 100 _S1-INSTANCE-A _S1-VM-INIT-ONE
        SBOX-VM-S-OK = _S1-ASSERT
    _S1-INSTANCE-A SBOX-VM-STEP
        SBOX-VM-RUN-RUNNABLE = _S1-ASSERT
    _S1-INSTANCE-A SBOX-VM-USAGE@ 1 = _S1-ASSERT
    SBOX-VM-CANCEL-CALLER _S1-INSTANCE-A SBOX-VM-CANCEL
        SBOX-VM-S-OK = _S1-ASSERT
    _S1-INSTANCE-A SBOX-VM-RUN-STATE@
        SBOX-VM-RUN-CANCELLED = _S1-ASSERT
    SBOX-VM-CANCEL-CALLER _S1-INSTANCE-A SBOX-VM-CANCEL
        SBOX-VM-S-OK = _S1-ASSERT
