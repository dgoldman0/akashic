: _S1-FIND-OPCODE  ( opcode -- record|0 )
    _S1-CANDIDATE SBOX-CANDIDATE-INSTRUCTION-N@ 0 ?DO
        DUP
        I _S1-INSTRUCTION@
        SBOX-CANDIDATE-U16-LE@ = IF
            DROP I _S1-INSTRUCTION@ UNLOOP EXIT
        THEN
    LOOP
    DROP 0 ;

