: _S1-ASSERT  ( flag -- )
    1 _S1-CHECKS +!
    0= IF
        1 _S1-FAILS +!
        ." SBOX STAGE1 ASSERT " _S1-CHECKS @ . CR TX-FLUSH
    THEN ;

: _S1-STACK  ( -- )
    DEPTH DUP _S1-DEPTH @ <> IF
        ." SBOX STAGE1 STACK " _S1-DEPTH @ . ." -> " DUP . CR
        .S CR
        TX-FLUSH
    THEN
    _S1-DEPTH @ = _S1-ASSERT ;

: _S1-FILLED?  ( address length byte -- flag )
    _S1-BYTE !
    0 ?DO
        DUP I + C@ _S1-BYTE @ <> IF
            DROP 0 UNLOOP EXIT
        THEN
    LOOP
    DROP -1 ;

: _S1-ZERO-CELLS?  ( address length -- flag )
    DUP 7 AND IF 2DROP 0 EXIT THEN
    8 / 0 ?DO
        DUP @ IF DROP 0 UNLOOP EXIT THEN
        8 +
    LOOP
    DROP -1 ;

