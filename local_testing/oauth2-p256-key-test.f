: _O2PKT-ASSERT  ( flag -- )
    1 _O2PKT-CHECKS +!
    0= IF
        1 _O2PKT-FAILS +!
        ." OAUTH2 P256 KEY ASSERT " _O2PKT-CHECKS @ . CR
    THEN ;

: _O2PKT-STACK  ( -- )
    DEPTH DUP _O2PKT-DEPTH @ <> IF
        ." OAUTH2 P256 KEY STACK "
        _O2PKT-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _O2PKT-DEPTH @ = _O2PKT-ASSERT ;

: _O2PKT-FILLED?  ( address length byte -- flag )
    >R
    BEGIN
        DUP
    WHILE
        OVER C@ R@ <> IF
            2DROP R> DROP 0 EXIT
        THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP R> DROP -1 ;

: _O2PKT-ZERO?  ( address length -- flag )
    0 _O2PKT-FILLED? ;

: _O2PKT-BE64!  ( value destination -- )
    >R
    DUP 56 RSHIFT 255 AND R@      C!
    DUP 48 RSHIFT 255 AND R@ 1+   C!
    DUP 40 RSHIFT 255 AND R@ 2 +  C!
    DUP 32 RSHIFT 255 AND R@ 3 +  C!
    DUP 24 RSHIFT 255 AND R@ 4 +  C!
    DUP 16 RSHIFT 255 AND R@ 5 +  C!
    DUP  8 RSHIFT 255 AND R@ 6 +  C!
        255 AND R@ 7 + C!
    R> DROP ;

: _O2PKT-ALLOCATE  ( size variable -- )
    >R ALLOCATE ABORT" OAUTH2 P256 KEY FAIL allocation"
    R> ! ;

: _O2PKT-FREE  ( variable -- )
    DUP @ ?DUP IF FREE 0 SWAP ! ELSE DROP THEN ;

