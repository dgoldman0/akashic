    _SDCT-TOTAL @ _SDCT-VALIDATE
        SBOX-DECL-S-CEILING = _SDCT-ASSERT

    _SDCT-BUILD _SDCT-ASSERT
    [CHAR] a _SDCT-ENTRY1 _SDCL-E-NAME + C!
