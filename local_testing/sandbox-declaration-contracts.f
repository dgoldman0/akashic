: _SDCT-ALIGN8  ( address -- aligned-address )
    7 + -8 AND ;

1024 CONSTANT _SDCT-BUFFER-SIZE

CREATE _SDCT-DECL-RAW _SDCT-BUFFER-SIZE 7 + ALLOT
_SDCT-DECL-RAW _SDCT-ALIGN8 CONSTANT _SDCT-DECL

CREATE _SDCT-VIEW-RAW SBOX-DECL-VIEW-SIZE 7 + ALLOT
_SDCT-VIEW-RAW _SDCT-ALIGN8 CONSTANT _SDCT-VIEW

CREATE _SDCT-WORK-RAW SBOX-DIGEST-WORKSPACE-SIZE 7 + ALLOT
_SDCT-WORK-RAW _SDCT-ALIGN8 CONSTANT _SDCT-WORK

CREATE _SDCT-DIGEST-A 32 ALLOT
CREATE _SDCT-DIGEST-B 32 ALLOT

CREATE _SDCT-REF-INPUT
    0xB1 C, 0x01 C, 0x00 C,
CREATE _SDCT-REF-OUTPUT
    0xB2 C, 0x01 C, 0x00 C,

: _SDCT-PROFILE$  ( -- address length )
    S" org.akashic.sandbox.pure.v1" ;

: _SDCT-ASSERT  ( flag -- )
    1 _SDCT-CHECKS +!
    0= IF
        1 _SDCT-FAILS +!
        ." SBOX DECL ASSERT " _SDCT-CHECKS @ . CR
    THEN ;

: _SDCT-STACK  ( -- )
    DEPTH DUP _SDCT-DEPTH @ <> IF
        ." SBOX DECL STACK " _SDCT-DEPTH @ . ." -> " DUP . CR .S CR
    THEN
    _SDCT-DEPTH @ = _SDCT-ASSERT ;

: _SDCT-ZERO?  ( address length -- flag )
    BEGIN DUP 0> WHILE
        OVER C@ IF 2DROP 0 EXIT THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP -1 ;

: _SDCT-U16!  ( value address -- )
    >R
    DUP 0xFF AND R@ C!
    8 RSHIFT 0xFF AND R> 1+ C! ;

: _SDCT-U32!  ( value address -- )
    >R
    DUP 0xFFFF AND R@ _SDCT-U16!
    16 RSHIFT 0xFFFF AND R> 2 + _SDCT-U16! ;

: _SDCT-U64!  ( value address -- )
    >R
    DUP 0xFFFFFFFF AND R@ _SDCT-U32!
    32 RSHIFT R> 4 + _SDCT-U32! ;

: _SDCT-FILL32  ( byte address -- )
    SWAP 32 SWAP FILL ;

: _SDCT-ACCEPT  ( status -- )
    0<> IF 0 _SDCT-BUILD-OK ! THEN ;

: _SDCT-ENTRY0  ( -- entry )
    _SDCT-ENTRIES @ ;

: _SDCT-ENTRY1  ( -- entry )
    _SDCT-ENTRIES @ SBOX-DECL-ENTRY-SIZE + ;

: _SDCT-WRITE-HEADER  ( -- )
    _SDECL-WIRE-MAGIC
        _SDCT-DECL _SDCL-H-MAGIC + _SDCT-U64!
    SBOX-DECL-FORMAT-V1
        _SDCT-DECL _SDCL-H-FORMAT + _SDCT-U16!
    SBOX-DECL-HEADER-SIZE
        _SDCT-DECL _SDCL-H-HEADER-U + _SDCT-U16!
    _SDCT-TOTAL @
        _SDCT-DECL _SDCL-H-TOTAL-U + _SDCT-U64!
    2 _SDCT-DECL _SDCL-H-ENTRY-N + _SDCT-U32!
    2 _SDCT-DECL _SDCL-H-CEILING-N + _SDCT-U16!
    _SDCT-PROFILE-U @
        _SDCT-DECL _SDCL-H-PROFILE-ID-U + _SDCT-U16!
    SBOX-DECL-PROVENANCE-NONE
        _SDCT-DECL _SDCL-H-PROVENANCE-KIND + _SDCT-U16!
    4 _SDCT-DECL _SDCL-H-SCHEMA-U + _SDCT-U64!
    0x11 _SDCT-DECL _SDCL-H-OWNER-RID + _SDCT-FILL32
    0x22 _SDCT-DECL _SDCL-H-MODULE-RID + _SDCT-FILL32
    7 _SDCT-DECL _SDCL-H-MODULE-REVISION + _SDCT-U64!

    S" artifact-fixture"
    _SDCT-DECL _SDCL-H-ARTIFACT-DIGEST +
    _SDCT-WORK SBOX-DIGEST-ARTIFACT _SDCT-ACCEPT

    _SDCT-PROFILE$
    _SDCT-DECL _SDCL-H-PROFILE-DIGEST +
    _SDCT-WORK SBOX-DIGEST-PROFILE _SDCT-ACCEPT ;

: _SDCT-WRITE-CEILINGS  ( -- )
    SBOX-BUDGET-LIMIT-INSTRUCTION-UNITS
        _SDCT-CEILINGS @ _SDCL-C-FIELD + _SDCT-U16!
    100000
        _SDCT-CEILINGS @ _SDCL-C-VALUE + _SDCT-U64!

    SBOX-BUDGET-LIMIT-OUTPUT-RESULT-BYTES
        _SDCT-CEILINGS @ SBOX-DECL-CEILING-SIZE +
        _SDCL-C-FIELD + _SDCT-U16!
    4096
        _SDCT-CEILINGS @ SBOX-DECL-CEILING-SIZE +
        _SDCL-C-VALUE + _SDCT-U64! ;

: _SDCT-WRITE-ENTRY0  ( -- )
    5 _SDCT-ENTRY0 _SDCL-E-NAME-U + _SDCT-U16!
    SBOX-DECL-SIGNATURE-PURE-VALUE
        _SDCT-ENTRY0 _SDCL-E-SIGNATURE + _SDCT-U16!
    SBOX-DECL-SCHEMA-EMBEDDED
        _SDCT-ENTRY0 _SDCL-E-INPUT-STORAGE + C!
    SBOX-DECL-SCHEMA-EMBEDDED
        _SDCT-ENTRY0 _SDCL-E-OUTPUT-STORAGE + C!
    S" alpha" _SDCT-ENTRY0 _SDCL-E-NAME + SWAP MOVE

    2 _SDCT-ENTRY0 _SDCL-E-INPUT-U + _SDCT-U64!
    0 _SDCT-ENTRY0 _SDCL-E-INPUT-OFFSET + _SDCT-U64!
    2 _SDCT-ENTRY0 _SDCL-E-OUTPUT-U + _SDCT-U64!
    2 _SDCT-ENTRY0 _SDCL-E-OUTPUT-OFFSET + _SDCT-U64!

    0xA1 _SDCT-SCHEMAS @ C!
    0x01 _SDCT-SCHEMAS @ 1+ C!
    0xA2 _SDCT-SCHEMAS @ 2 + C!
    0x01 _SDCT-SCHEMAS @ 3 + C!

    _SDCT-SCHEMAS @ 2
    _SDCT-ENTRY0 _SDCL-E-INPUT-DIGEST +
    _SDCT-WORK SBOX-DIGEST-SCHEMA _SDCT-ACCEPT

    _SDCT-SCHEMAS @ 2 + 2
    _SDCT-ENTRY0 _SDCL-E-OUTPUT-DIGEST +
    _SDCT-WORK SBOX-DIGEST-SCHEMA _SDCT-ACCEPT ;

: _SDCT-WRITE-ENTRY1  ( -- )
    4 _SDCT-ENTRY1 _SDCL-E-NAME-U + _SDCT-U16!
    SBOX-DECL-SIGNATURE-PURE-VALUE
        _SDCT-ENTRY1 _SDCL-E-SIGNATURE + _SDCT-U16!
    SBOX-DECL-SCHEMA-REFERENCED
        _SDCT-ENTRY1 _SDCL-E-INPUT-STORAGE + C!
    SBOX-DECL-SCHEMA-REFERENCED
        _SDCT-ENTRY1 _SDCL-E-OUTPUT-STORAGE + C!
    S" beta" _SDCT-ENTRY1 _SDCL-E-NAME + SWAP MOVE

    3 _SDCT-ENTRY1 _SDCL-E-INPUT-U + _SDCT-U64!
    3 _SDCT-ENTRY1 _SDCL-E-OUTPUT-U + _SDCT-U64!

    _SDCT-REF-INPUT 3
    _SDCT-ENTRY1 _SDCL-E-INPUT-DIGEST +
    _SDCT-WORK SBOX-DIGEST-SCHEMA _SDCT-ACCEPT

    _SDCT-REF-OUTPUT 3
    _SDCT-ENTRY1 _SDCL-E-OUTPUT-DIGEST +
    _SDCT-WORK SBOX-DIGEST-SCHEMA _SDCT-ACCEPT ;

: _SDCT-BUILD  ( -- flag )
    -1 _SDCT-BUILD-OK !
    _SDCT-DECL _SDCT-BUFFER-SIZE 0 FILL
    _SDCT-VIEW SBOX-DECL-VIEW-SIZE 0 FILL
    _SDCT-WORK SBOX-DIGEST-WORKSPACE-SIZE 0 FILL

    _SDCT-PROFILE$ DUP _SDCT-PROFILE-U !
    SBOX-DECL-HEADER-SIZE _SDCT-DECL + SWAP MOVE
    _SDCT-PROFILE-U @ SBOX-BYTE-PAD8
        DUP _SDCT-ACCEPT DROP
    _SDCT-PROFILE-PAD !

    _SDCT-DECL SBOX-DECL-HEADER-SIZE +
        _SDCT-PROFILE-PAD @ +
        DUP _SDCT-CEILINGS !
    2 SBOX-DECL-CEILING-SIZE * +
        DUP _SDCT-ENTRIES !
    2 SBOX-DECL-ENTRY-SIZE * +
        DUP _SDCT-SCHEMAS !
    4 + _SDCT-DECL - _SDCT-TOTAL !

    _SDCT-WRITE-HEADER
    _SDCT-WRITE-CEILINGS
    _SDCT-WRITE-ENTRY0
    _SDCT-WRITE-ENTRY1
    _SDCT-BUILD-OK @ ;

: _SDCT-VALIDATE  ( source-u -- status )
    _SDCT-DECL SWAP _SDCT-VIEW _SDCT-WORK
    SBOX-DECL-VALIDATE ;

: _SDCT-SAVE-SCHEMA
  ( bytes schema-u digest storage status -- )
    _SDCT-STATUS !
    _SDCT-MODE !
    _SDCT-D !
    _SDCT-U !
    _SDCT-A ! ;

: _SDCT-FORMAT-AND-ACCESS-CONTRACTS  ( -- )
    SBOX-DECL-HEADER-SIZE 256 = _SDCT-ASSERT
    SBOX-DECL-CEILING-SIZE 16 = _SDCT-ASSERT
    SBOX-DECL-ENTRY-SIZE 192 = _SDCT-ASSERT
    SBOX-DECL-VIEW-SIZE 176 = _SDCT-ASSERT
    SBOX-DECL-S-OK SBOX-DECL-STATUS-VALID? _SDCT-ASSERT
    SBOX-DECL-S-FAULT SBOX-DECL-STATUS-VALID? _SDCT-ASSERT
    -1 SBOX-DECL-STATUS-VALID? 0= _SDCT-ASSERT

    _SDCT-BUILD _SDCT-ASSERT
    _SDCT-TOTAL @ _SDCT-VALIDATE
        SBOX-DECL-S-OK = _SDCT-ASSERT
    _SDCT-VIEW SBOX-DECL-VIEW-VALID? _SDCT-ASSERT
    _SDCT-WORK SBOX-DIGEST-WORKSPACE-SIZE
        _SDCT-ZERO? _SDCT-ASSERT

    _SDCT-VIEW SBOX-DECL-MODULE-REVISION@
        SBOX-DECL-S-OK = SWAP 7 = AND _SDCT-ASSERT
    _SDCT-VIEW SBOX-DECL-ENTRY-COUNT@
        SBOX-DECL-S-OK = SWAP 2 = AND _SDCT-ASSERT
    _SDCT-VIEW SBOX-DECL-CEILING-COUNT@
        SBOX-DECL-S-OK = SWAP 2 = AND _SDCT-ASSERT

    SBOX-BUDGET-LIMIT-INSTRUCTION-UNITS _SDCT-VIEW
        SBOX-DECL-CEILING@
        SBOX-DECL-S-OK = >R
        0<> SWAP 100000 = AND R> AND _SDCT-ASSERT
    SBOX-BUDGET-LIMIT-CALL-FRAMES _SDCT-VIEW
        SBOX-DECL-CEILING@
        SBOX-DECL-S-OK = >R
        0= SWAP 0= AND R> AND _SDCT-ASSERT

    0 _SDCT-VIEW SBOX-DECL-ENTRY@
        DUP SBOX-DECL-S-OK = _SDCT-ASSERT
    DROP _SDCT-ENTRY !
    _SDCT-ENTRY @ _SDCT-VIEW SBOX-DECL-ENTRY-NAME@
        SBOX-DECL-S-OK = >R
        S" alpha" COMPARE 0= R> AND _SDCT-ASSERT
    _SDCT-ENTRY @ _SDCT-VIEW SBOX-DECL-ENTRY-SIGNATURE@
        SBOX-DECL-S-OK = SWAP
        SBOX-DECL-SIGNATURE-PURE-VALUE = AND _SDCT-ASSERT

    S" beta" _SDCT-VIEW SBOX-DECL-ENTRY-FIND-EXACT
        DUP SBOX-DECL-S-OK = _SDCT-ASSERT
    DROP _SDCT-ENTRY !
    _SDCT-ENTRY @ _SDCT-VIEW SBOX-DECL-ENTRY-NAME@
        SBOX-DECL-S-OK = >R
        S" beta" COMPARE 0= R> AND _SDCT-ASSERT
    S" gamma" _SDCT-VIEW SBOX-DECL-ENTRY-FIND-EXACT
        SBOX-DECL-S-NOT-FOUND = SWAP 0= AND _SDCT-ASSERT

    0 _SDCT-VIEW SBOX-DECL-ENTRY@ DROP _SDCT-ENTRY !
    _SDCT-ENTRY @ _SDCT-VIEW SBOX-DECL-ENTRY-INPUT-SCHEMA@
        _SDCT-SAVE-SCHEMA
    _SDCT-STATUS @ SBOX-DECL-S-OK = _SDCT-ASSERT
    _SDCT-MODE @ SBOX-DECL-SCHEMA-EMBEDDED = _SDCT-ASSERT
    _SDCT-A @ _SDCT-SCHEMAS @ = _SDCT-ASSERT
    _SDCT-U @ 2 = _SDCT-ASSERT

    1 _SDCT-VIEW SBOX-DECL-ENTRY@ DROP _SDCT-ENTRY !
    _SDCT-ENTRY @ _SDCT-VIEW SBOX-DECL-ENTRY-INPUT-SCHEMA@
        _SDCT-SAVE-SCHEMA
    _SDCT-STATUS @ SBOX-DECL-S-OK = _SDCT-ASSERT
    _SDCT-MODE @ SBOX-DECL-SCHEMA-REFERENCED = _SDCT-ASSERT
    _SDCT-A @ 0= _SDCT-ASSERT
    _SDCT-U @ 3 = _SDCT-ASSERT
    _SDCT-D @ _SDCT-ENTRY1 _SDCL-E-INPUT-DIGEST + =
        _SDCT-ASSERT
    _SDCT-STACK ;

