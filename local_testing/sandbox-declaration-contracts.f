    _SDCT-STACK ;

: _SDCT-RUN  ( -- )
    0 _SDCT-FAILS !
    0 _SDCT-CHECKS !
    DEPTH _SDCT-DEPTH !
    ." SBOX DECL CONTRACTS START" CR
    _SDCT-FORMAT-AND-ACCESS-CONTRACTS
    _SDCT-DIGEST-CONTRACTS
    _SDCT-DOMAIN-CONTRACTS
    _SDCT-EXTENT-AND-RESERVED-CONTRACTS
    _SDCT-CEILING-AND-ENTRY-CONTRACTS
    _SDCT-STACK
    _SDCT-FAILS @ 0= IF
        ." SBOX DECL CONTRACTS PASS " _SDCT-CHECKS @ . CR
    ELSE
        ." SBOX DECL CONTRACTS FAIL " _SDCT-FAILS @ . CR
    THEN ;

_SDCT-RUN
