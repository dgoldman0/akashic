        SBOX-DECL-S-OK = _SDCT-ASSERT

    _SDCT-DECL _SDCT-TOTAL @
        _SDCT-DIGEST-A _SDCT-WORK SBOX-DECL-DIGEST
        SBOX-DECL-S-OK = _SDCT-ASSERT
    _SDCT-DECL _SDCT-TOTAL @
        _SDCT-DIGEST-B _SDCT-WORK SBOX-DIGEST-RAW
        SBOX-DIGEST-S-OK = _SDCT-ASSERT
    _SDCT-DIGEST-A 32 _SDCT-DIGEST-B 32 COMPARE 0<>
        _SDCT-ASSERT

    _SDCT-DECL _SDCT-TOTAL @
        _SDCT-DIGEST-B _SDCT-WORK SBOX-DECL-DIGEST
        SBOX-DECL-S-OK = _SDCT-ASSERT
    _SDCT-DIGEST-A 32 _SDCT-DIGEST-B 32 COMPARE 0=
        _SDCT-ASSERT
    _SDCT-WORK SBOX-DIGEST-WORKSPACE-SIZE
        _SDCT-ZERO? _SDCT-ASSERT
    _SDCT-STACK ;

