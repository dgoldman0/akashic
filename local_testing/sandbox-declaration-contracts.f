    _SDCT-TOTAL @ _SDCT-VALIDATE
        SBOX-DECL-S-RESERVED = _SDCT-ASSERT

    _SDCT-BUILD _SDCT-ASSERT
    0x01 _SDCT-SCHEMAS @ C!
    _SDCT-TOTAL @ _SDCT-VALIDATE
        SBOX-DECL-S-DIGEST = _SDCT-ASSERT

    _SDCT-BUILD _SDCT-ASSERT
    1 _SDCT-ENTRY1 _SDCL-E-INPUT-OFFSET + _SDCT-U64!
