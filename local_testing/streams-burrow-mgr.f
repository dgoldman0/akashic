: _SBM-ASSERT  ( flag -- )
    1 _SBM-CHECKS +!
    0= IF
        1 _SBM-FAILS +!
        ." STREAMS BURROW MANAGER ASSERT " _SBM-CHECKS @ . CR
    THEN ;

: _SBM-STACK  ( -- )
    DEPTH DUP IF
        ." STREAMS BURROW MANAGER STACK " DUP . CR .S CR
    THEN
    0= _SBM-ASSERT ;

: _SBM-ZERO?  ( address bytes -- flag )
    BEGIN
        DUP
    WHILE
        OVER C@ IF 2DROP 0 EXIT THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP -1 ;

: _SBM-RID!  ( rid byte -- )
    SWAP RID-SIZE ROT FILL ;

: _SBM-FLIP-FIRST  ( address -- )
    DUP C@ 1 XOR SWAP C! ;

