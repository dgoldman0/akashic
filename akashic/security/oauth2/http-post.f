: _O2HP-CALLER>STATUS  ( caller-status -- status )
    DUP CALLER-SPAN-S-OK = IF
        DROP OAUTH2-HTTP-POST-S-OK EXIT
    THEN
    DUP CALLER-SPAN-S-RANGE = IF
        DROP OAUTH2-HTTP-POST-S-RANGE EXIT
    THEN
    DUP CALLER-SPAN-S-PROTECTED = IF
        DROP OAUTH2-HTTP-POST-S-PROTECTED EXIT
    THEN
    DUP CALLER-SPAN-S-PLATFORM = IF
        DROP OAUTH2-HTTP-POST-S-PLATFORM EXIT
    THEN
    DROP OAUTH2-HTTP-POST-S-PLATFORM ;

: _O2HP-SPAN-STATUS  ( address length -- status )
    DUP 0< IF 2DROP OAUTH2-HTTP-POST-S-INVALID EXIT THEN
    DUP 0= IF 2DROP OAUTH2-HTTP-POST-S-OK EXIT THEN
    OVER 0= IF 2DROP OAUTH2-HTTP-POST-S-INVALID EXIT THEN
    CALLER-SPAN-STATUS _O2HP-CALLER>STATUS ;

: _O2HP-FUEW>STATUS  ( fuew-status -- status )
    DUP FUEW-S-OK = IF DROP OAUTH2-HTTP-POST-S-OK EXIT THEN
    DUP FUEW-S-INVALID = IF
        DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    DUP FUEW-S-STATE = IF
        DROP OAUTH2-HTTP-POST-S-STATE EXIT
    THEN
    DUP FUEW-S-CAPACITY = IF
        DROP OAUTH2-HTTP-POST-S-CAPACITY EXIT
    THEN
    DUP FUEW-S-ALIAS = IF
        DROP OAUTH2-HTTP-POST-S-ALIAS EXIT
    THEN
    DUP FUEW-S-RANGE = IF
        DROP OAUTH2-HTTP-POST-S-RANGE EXIT
    THEN
    DUP FUEW-S-PROTECTED = IF
        DROP OAUTH2-HTTP-POST-S-PROTECTED EXIT
    THEN
    DUP FUEW-S-PLATFORM = IF
        DROP OAUTH2-HTTP-POST-S-PLATFORM EXIT
    THEN
    DROP OAUTH2-HTTP-POST-S-INTERNAL ;

