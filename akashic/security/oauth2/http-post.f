    R> DROP -1 ;

: _O2HP-HREQ-COUNTERS?  ( request -- flag )
    DUP HREQ.LENGTH @ DUP 0< IF 2DROP 0 EXIT THEN
    OVER HREQ.CAPACITY @ U> IF DROP 0 EXIT THEN
    DUP HREQ.SENT @ DUP 0< IF 2DROP 0 EXIT THEN
    OVER HREQ.LENGTH @ U> IF DROP 0 EXIT THEN
    DROP -1 ;

: _O2HP-HREQ-STATE-COUNTERS?  ( request -- flag )
    DUP HREQ.STATE @ CASE
        HREQ-STATE-EMPTY OF
            DUP HREQ.LENGTH @ 0=
            SWAP HREQ.SENT @ 0= AND
        ENDOF
        HREQ-STATE-BUILDING OF
            DUP HREQ.LENGTH @ 0>
            SWAP HREQ.SENT @ 0= AND
        ENDOF
        HREQ-STATE-SEALED OF
            DUP HREQ.LENGTH @ 0>
            SWAP HREQ.SENT @ 0= AND
        ENDOF
        HREQ-STATE-SENDING OF
            DUP HREQ.SENT @ SWAP HREQ.LENGTH @ U<
        ENDOF
        HREQ-STATE-SENT OF
            DUP HREQ.SENT @ SWAP HREQ.LENGTH @ =
        ENDOF
        HREQ-STATE-ERROR OF
            HREQ.LENGTH @ 0>
        ENDOF
        2DROP 0 EXIT
    ENDCASE ;

