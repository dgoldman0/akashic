\ =====================================================================
\  http-post.f - Generic bounded OAuth 2 form POST exchange
\ =====================================================================
\  This module owns one caller-managed OAuth 2 HTTP transaction.  It copies
\  an admitted HTTPS target, builds one application/x-www-form-urlencoded
\  POST, drives a caller-bound cooperative NIO port, and retains a hardened
\  semantic response result.  It performs no endpoint discovery, redirect,
\  retry, success-body decoding, AT Protocol, Streams, or provider policy.
\
\  The caller supplies complete, mutually disjoint request, form, and
\  response arenas.  The operation descriptor contains every other mutable
\  byte; this module has no mutable dictionary-global operation state.
\ =====================================================================

