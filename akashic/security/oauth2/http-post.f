    ?DUP IF _O2HP-RETURN8 EXIT THEN
    DUP OAUTH2-HTTP-POST-SIZE 0 FILL
    _O2HP-CONFIG-STORE
    DUP _O2HP-ARENA-GEOMETRY ?DUP IF
        SWAP _O2HP-ARENA-ONLY-FAIL EXIT
    THEN
    _O2HP-CONFIG-MATERIAL ;

