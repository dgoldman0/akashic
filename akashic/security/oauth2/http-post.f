    R@ _O2HP.REQUEST-A @ R@ _O2HP.REQUEST-CAP @
        MSPAN-OVERLAP? IF
        R> DROP OAUTH2-HTTP-POST-S-ALIAS EXIT
    THEN
    R@ _O2HP.T0 @ HTARGET-SIZE
    R@ _O2HP.FORM-A @ R@ _O2HP.FORM-CAP @
        MSPAN-OVERLAP? IF
        R> DROP OAUTH2-HTTP-POST-S-ALIAS EXIT
