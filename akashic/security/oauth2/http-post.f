: _O2HP-CLEAR-NONCE  ( post -- )
    DUP _O2HP.NONCE OAUTH2-HTTP-POST-NONCE-CAPACITY 0 FILL
    0 SWAP _O2HP.NONCE-U ! ;

: _O2HP-CLEAR-CORRELATION  ( post -- )
    DUP _O2HP.CORRELATION
    OAUTH2-HTTP-POST-CORRELATION-CAPACITY 0 FILL
    0 SWAP _O2HP.CORRELATION-U ! ;

: _O2HP-RESET-DIAGNOSTICS  ( post -- )
    DUP OAUTH2-HTTP-POST-O-NONE SWAP _O2HP.OUTCOME !
    DUP OAUTH2-HTTP-POST-D-NONE SWAP _O2HP.DETAIL !
    DUP OAUTH2-HTTP-POST-CLEANUP-CERTAIN SWAP _O2HP.CLEANUP !
    DUP 0 SWAP _O2HP.HTTP-STATUS !
    DUP 0 SWAP _O2HP.FLAGS !
    DUP 0 SWAP _O2HP.RESPONSE-U !
    DUP 0 SWAP _O2HP.PORT !
    DUP FUEW-S-OK SWAP _O2HP.FORM-STATUS !
    DUP HREQ-S-OK SWAP _O2HP.REQUEST-STATUS !
    DUP HBUF-S-OK SWAP _O2HP.EXCHANGE-STATUS !
    DUP HSTR-S-OK SWAP _O2HP.PARSER-STATUS !
    DUP NIO-S-OK SWAP _O2HP.NIO-OPEN-STATUS !
    DUP NIO-S-OK SWAP _O2HP.NIO-CLOSE-STATUS !
    DUP 0 SWAP _O2HP.NIO-CANCEL-ERROR !
    DUP 0 SWAP _O2HP.NIO-CLOSE-ERROR !
    DUP MTYPE-S-OK SWAP _O2HP.MEDIA-STATUS !
    DUP 0 SWAP _O2HP.T0 !
    DUP 0 SWAP _O2HP.T1 !
    DUP 0 SWAP _O2HP.T2 !
    0 SWAP _O2HP.T3 ! ;

: _O2HP-RESET-OPERATION  ( post -- status )
    >R
    R@ _O2HP-CLEAR-CORRELATION
    R@ _O2HP.REQUEST-A @ R@ _O2HP.REQUEST-CAP @ R@ _O2HP.REQUEST
        HREQ-INIT
    DUP R@ _O2HP.REQUEST-STATUS !
    DUP HREQ-S-OK <> IF
        _O2HP-HREQ>STATUS R> DROP EXIT
    THEN
    DROP
    R@ _O2HP.FORM-A @ R@ _O2HP.FORM-CAP @ R@ _O2HP.WRITER
        FUEW-INIT
    DUP R@ _O2HP.FORM-STATUS !
    DUP FUEW-S-OK <> IF
        _O2HP-FUEW>STATUS R> DROP EXIT
    THEN
    DROP
    R@ _O2HP.RESPONSE-A @ R@ _O2HP.RESPONSE-CAP @ 0 FILL
    R@ _O2HP.RESPONSE-A @ R@ _O2HP.RESPONSE-CAP @ R@ _O2HP.EXCHANGE
        HBUF-INIT
    DUP R@ _O2HP.EXCHANGE-STATUS !
    HBUF-S-OK <> IF
        R> DROP OAUTH2-HTTP-POST-S-INTERNAL EXIT
    THEN
    R@ _O2HP.RESPONSE-CAP @
        R@ _O2HP.EXCHANGE HBUF.PARSER HSTR-BODY-LIMIT!
    R@ _O2HP.MEDIA MTYPE-INIT
    R@ _O2HP-CLEAR-NONCE
    R@ _O2HP-RESET-DIAGNOSTICS
    R> DROP OAUTH2-HTTP-POST-S-OK ;

: OAUTH2-HTTP-POST-BEGIN  ( kind post -- status )
    DUP OAUTH2-HTTP-POST-VALID? 0= IF
        2DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    DUP _O2HP.CLEANUP @ OAUTH2-HTTP-POST-CLEANUP-UNCERTAIN = IF
        2DROP OAUTH2-HTTP-POST-S-CLEANUP EXIT
    THEN
    DUP _O2HP.STATE @
    DUP OAUTH2-HTTP-POST-STATE-CONFIGURED =
    SWAP OAUTH2-HTTP-POST-STATE-RESULT = OR 0= IF
        2DROP OAUTH2-HTTP-POST-S-BUSY EXIT
    THEN
    DUP _O2HP.EXCHANGE HBUF.PORT @ IF
        DUP OAUTH2-HTTP-POST-CLEANUP-UNCERTAIN SWAP _O2HP.CLEANUP !
        DUP OAUTH2-HTTP-POST-STATE-CLEANUP SWAP _O2HP.STATE !
        2DROP OAUTH2-HTTP-POST-S-CLEANUP EXIT
    THEN
    OVER OAUTH2-HTTP-POST-KIND-PAR <>
    2 PICK OAUTH2-HTTP-POST-KIND-TOKEN <> AND IF
        2DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    DUP _O2HP-RESET-OPERATION ?DUP IF
        DUP 2 PICK _O2HP.LAST-STATUS !
        >R 2DROP R> EXIT
    THEN
    OVER OVER _O2HP.KIND !
    OVER OAUTH2-HTTP-POST-KIND-PAR = IF 201 ELSE 200 THEN
        OVER _O2HP.EXPECTED !
    OAUTH2-HTTP-POST-STATE-BUILDING OVER _O2HP.STATE !
    OAUTH2-HTTP-POST-S-OK OVER _O2HP.LAST-STATUS !
    2DROP OAUTH2-HTTP-POST-S-OK ;

: _O2HP-CORRELATION-RETURN
  ( token-a token-u status post -- status )
    >R >R
    2DROP
    R>
    DUP R@ _O2HP.LAST-STATUS !
    R> DROP ;

: OAUTH2-HTTP-POST-CORRELATION!
  ( token-a token-u post -- status )
    DUP OAUTH2-HTTP-POST-VALID? 0= IF
        2DROP DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    >R
    R@ _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-BUILDING <> IF
        2DROP R> DROP
        OAUTH2-HTTP-POST-S-STATE EXIT
    THEN
    DUP 0< IF
        OAUTH2-HTTP-POST-S-INVALID R>
        _O2HP-CORRELATION-RETURN EXIT
    THEN
    DUP 0= IF
        OAUTH2-HTTP-POST-S-INVALID R>
        _O2HP-CORRELATION-RETURN EXIT
    THEN
    OVER 0= IF
        OAUTH2-HTTP-POST-S-INVALID R>
        _O2HP-CORRELATION-RETURN EXIT
    THEN
    DUP OAUTH2-HTTP-POST-CORRELATION-CAPACITY U> IF
        OAUTH2-HTTP-POST-S-CAPACITY R>
        _O2HP-CORRELATION-RETURN EXIT
    THEN
    2DUP _O2HP-SPAN-STATUS ?DUP IF
        R> _O2HP-CORRELATION-RETURN EXIT
    THEN
    2DUP R@ OAUTH2-HTTP-POST-SIZE MSPAN-OVERLAP? IF
        OAUTH2-HTTP-POST-S-ALIAS R>
        _O2HP-CORRELATION-RETURN EXIT
    THEN
    R@ _O2HP-CLEAR-CORRELATION
    DUP R@ _O2HP.CORRELATION-U !
    R@ _O2HP.CORRELATION SWAP MOVE
    OAUTH2-HTTP-POST-S-OK DUP R@ _O2HP.LAST-STATUS !
    R> DROP ;

: OAUTH2-HTTP-POST-FIELD
  ( name-a name-u value-a value-u post -- status )
    DUP OAUTH2-HTTP-POST-VALID? 0= IF
        2DROP 2DROP DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    DUP _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-BUILDING <> IF
        2DROP 2DROP DROP OAUTH2-HTTP-POST-S-STATE EXIT
    THEN
    DUP >R _O2HP.WRITER FUEW-FIELD
    DUP R@ _O2HP.FORM-STATUS !
    _O2HP-FUEW>STATUS
    DUP R@ _O2HP.LAST-STATUS !
    R> DROP ;

