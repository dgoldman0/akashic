: _O2HP-KIND-EXPECTED?  ( post -- flag )
    DUP _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-CONFIGURED = IF
        DUP _O2HP.KIND @ 0=
        SWAP _O2HP.EXPECTED @ 0= AND EXIT
    THEN
    DUP _O2HP.KIND @ OAUTH2-HTTP-POST-KIND-PAR = IF
        _O2HP.EXPECTED @ 201 = EXIT
    THEN
    DUP _O2HP.KIND @ OAUTH2-HTTP-POST-KIND-TOKEN = IF
        _O2HP.EXPECTED @ 200 = EXIT
    THEN
    DROP 0 ;

