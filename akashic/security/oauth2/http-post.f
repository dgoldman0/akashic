: _O2HP-RECONFIG-STATUS  ( post -- status )
    DUP _O2HP.MAGIC @ _O2HP-MAGIC-VALUE <> IF
        DROP OAUTH2-HTTP-POST-S-OK EXIT
    THEN
    8 + OAUTH2-HTTP-POST-SIZE 8 - _O2HP-ZERO? IF
        OAUTH2-HTTP-POST-S-OK
    ELSE
        OAUTH2-HTTP-POST-S-BUSY
    THEN ;

: _O2HP-CONFIG-PREFLIGHT
  ( target req-a req-cap form-a form-cap rsp-a rsp-cap post -- same status )
    DUP 0= IF OAUTH2-HTTP-POST-S-INVALID EXIT THEN
    DUP 7 AND IF OAUTH2-HTTP-POST-S-INVALID EXIT THEN
    DUP OAUTH2-HTTP-POST-SIZE _O2HP-SPAN-STATUS ?DUP IF EXIT THEN
    DUP _O2HP-RECONFIG-STATUS ?DUP IF EXIT THEN
    >R

    6 PICK HTARGET-SIZE _O2HP-SPAN-STATUS ?DUP IF R> SWAP EXIT THEN
    6 PICK HTARGET-VALID? 0= IF
        OAUTH2-HTTP-POST-S-INVALID R> SWAP EXIT
    THEN

    5 PICK 5 PICK _O2HP-SPAN-STATUS ?DUP IF R> SWAP EXIT THEN
    4 PICK 64 < IF OAUTH2-HTTP-POST-S-INVALID R> SWAP EXIT THEN
    3 PICK 3 PICK _O2HP-SPAN-STATUS ?DUP IF R> SWAP EXIT THEN
    1 PICK 1 PICK _O2HP-SPAN-STATUS ?DUP IF R> SWAP EXIT THEN
    DUP 0= IF OAUTH2-HTTP-POST-S-INVALID R> SWAP EXIT THEN

    6 PICK HTARGET-SIZE R@ OAUTH2-HTTP-POST-SIZE
        MSPAN-OVERLAP? IF
        OAUTH2-HTTP-POST-S-ALIAS R> SWAP EXIT
    THEN
    5 PICK 5 PICK R@ OAUTH2-HTTP-POST-SIZE MSPAN-OVERLAP? IF
        OAUTH2-HTTP-POST-S-ALIAS R> SWAP EXIT
    THEN
    3 PICK 3 PICK R@ OAUTH2-HTTP-POST-SIZE MSPAN-OVERLAP? IF
        OAUTH2-HTTP-POST-S-ALIAS R> SWAP EXIT
    THEN
    1 PICK 1 PICK R@ OAUTH2-HTTP-POST-SIZE MSPAN-OVERLAP? IF
        OAUTH2-HTTP-POST-S-ALIAS R> SWAP EXIT
    THEN

    R> OAUTH2-HTTP-POST-S-OK ;

