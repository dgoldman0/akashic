    R@ HSTR.BODY-TOTAL @ DUP 0< IF DROP R> DROP 0 EXIT THEN
    R@ HSTR.BODY-LIMIT @ U> IF R> DROP 0 EXIT THEN
    R@ HSTR.HEADER-U @ DUP 0< IF DROP R> DROP 0 EXIT THEN
    HSTR-HEADER-CAPACITY U> IF R> DROP 0 EXIT THEN
    R@ HSTR.LINE-U @ DUP 0< IF DROP R> DROP 0 EXIT THEN
    HSTR-LINE-CAPACITY U> IF R> DROP 0 EXIT THEN
    R@ HSTR.TRAILER-U @ DUP 0< IF DROP R> DROP 0 EXIT THEN
    HSTR-TRAILER-CAPACITY U> IF R> DROP 0 EXIT THEN
    R@ HSTR.CONTENT-LENGTH @ DUP 0< IF DROP R> DROP 0 EXIT THEN
    R@ HSTR.BODY-LIMIT @ U> IF R> DROP 0 EXIT THEN
    R@ HSTR.FRAMING @
        _HSTR-FR-CL _HSTR-FR-TE OR INVERT AND IF
        R> DROP 0 EXIT
    THEN
    R@ HSTR.INTERIMS @ DUP 0< IF DROP R> DROP 0 EXIT THEN
    8 > IF R> DROP 0 EXIT THEN
    R@ HSTR.BODY-A @ IF R> DROP 0 EXIT THEN
    R@ HSTR.BODY-U @ IF R> DROP 0 EXIT THEN
