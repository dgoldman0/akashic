: _O2HP-FLAGS-CONSISTENT?  ( post -- flag )
    >R
    R@ _O2HP.FLAGS @
    DUP OAUTH2-HTTP-POST-F-DPOP-SENT AND IF
        DUP OAUTH2-HTTP-POST-F-DPOP-INCLUDED AND 0= IF
            DROP R> DROP 0 EXIT
        THEN
    THEN
    DUP OAUTH2-HTTP-POST-F-AUTHORIZATION-SENT AND IF
        DUP OAUTH2-HTTP-POST-F-AUTHORIZATION-INCLUDED AND 0= IF
            DROP R> DROP 0 EXIT
        THEN
    THEN
    R@ _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-SEALED < IF
        0= R> DROP EXIT
    THEN
    R@ _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-SEALED = IF
        _O2HP-FLAGS-SENT AND 0= R> DROP EXIT
    THEN
    DROP R> DROP -1 ;

: _O2HP-SUBORDINATE-BINDINGS?  ( post -- flag )
    DUP _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-RESULT = IF
        DUP _O2HP.REQUEST HTTP-REQUEST-SIZE _O2HP-ZERO?
        OVER _O2HP.WRITER FUEW-SIZE _O2HP-ZERO? AND
        SWAP _O2HP.EXCHANGE HTTP-BUFFERED-SIZE _O2HP-ZERO? AND
        EXIT
    THEN
    >R
    R@ _O2HP-HREQ-BINDING? 0= IF R> DROP 0 EXIT THEN
    R@ _O2HP-FUEW-BINDING? 0= IF R> DROP 0 EXIT THEN
    R@ _O2HP-HBUF-BINDING? 0= IF R> DROP 0 EXIT THEN

    R@ _O2HP.STATE @ DUP OAUTH2-HTTP-POST-STATE-CONFIGURED =
    SWAP OAUTH2-HTTP-POST-STATE-BUILDING = OR IF
        R@ _O2HP.REQUEST HREQ.STATE @ HREQ-STATE-EMPTY =
        R@ _O2HP.WRITER FUEW.STATE @ FUEW-STATE-BUILDING = AND
        R@ _O2HP.EXCHANGE HBUF.REQUEST @ 0= AND
        R@ _O2HP.EXCHANGE HBUF.PORT @ 0= AND
        R@ _O2HP.EXCHANGE HBUF.STATE @ HBUF-STATE-IDLE = AND
        R@ _O2HP.PORT @ 0= AND
        R> DROP EXIT
    THEN
    R@ _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-SEALED = IF
        R@ _O2HP.REQUEST HREQ.STATE @ HREQ-STATE-SEALED =
        R@ _O2HP.WRITER FUEW.STATE @ FUEW-STATE-SEALED = AND
        R@ _O2HP.EXCHANGE HBUF.REQUEST @ 0= AND
        R@ _O2HP.EXCHANGE HBUF.PORT @ 0= AND
        R@ _O2HP.EXCHANGE HBUF.STATE @ HBUF-STATE-IDLE = AND
        R@ _O2HP.PORT @ 0= AND
        R> DROP EXIT
    THEN
    R@ _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-ACTIVE = IF
        R@ _O2HP.REQUEST HREQ.STATE @ _O2HP-HREQ-ACTIVE-STATE?
        R@ _O2HP.EXCHANGE HBUF.STATE @
            _O2HP-HBUF-ACTIVE-STATE? AND
        R@ _O2HP.WRITER FUEW.STATE @ FUEW-STATE-SEALED = AND
        R@ _O2HP.EXCHANGE HBUF.REQUEST @ R@ _O2HP.REQUEST = AND
        R@ _O2HP-RETAINED-PORT-GEOMETRY? AND
        R> DROP EXIT
    THEN
    R@ _O2HP.REQUEST HREQ.STATE @ _O2HP-HREQ-ACTIVE-STATE?
    R@ _O2HP.EXCHANGE HBUF.STATE @
        _O2HP-HBUF-CLEANUP-STATE? AND
    R@ _O2HP.WRITER FUEW.STATE @ FUEW-STATE-SEALED = AND
    R@ _O2HP.EXCHANGE HBUF.REQUEST @ R@ _O2HP.REQUEST = AND
    R@ _O2HP-RETAINED-PORT-GEOMETRY? AND
    R> DROP ;

: _O2HP-CORRELATION-CANONICAL?  ( post -- flag )
    >R
    R@ _O2HP.CORRELATION-U @
    DUP 0< IF DROP R> DROP 0 EXIT THEN
    DUP OAUTH2-HTTP-POST-CORRELATION-CAPACITY U> IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-CONFIGURED =
    OVER 0<> AND IF
        DROP R> DROP 0 EXIT
    THEN
    DUP R@ _O2HP.CORRELATION +
    SWAP OAUTH2-HTTP-POST-CORRELATION-CAPACITY SWAP -
    _O2HP-ZERO?
    R> DROP ;

: OAUTH2-HTTP-POST-VALID?  ( post -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP OAUTH2-HTTP-POST-SIZE _O2HP-SPAN-STATUS
        OAUTH2-HTTP-POST-S-OK <> IF
        DROP 0 EXIT
    THEN
    DUP _O2HP.MAGIC @ _O2HP-MAGIC-VALUE <> IF DROP 0 EXIT THEN
    DUP _O2HP.STATE @
    DUP OAUTH2-HTTP-POST-STATE-EMPTY <
    SWAP OAUTH2-HTTP-POST-STATE-CLEANUP > OR IF
        DROP 0 EXIT
    THEN
    DUP _O2HP.CLEANUP @
    DUP OAUTH2-HTTP-POST-CLEANUP-CERTAIN <>
    SWAP OAUTH2-HTTP-POST-CLEANUP-UNCERTAIN <> AND IF
        DROP 0 EXIT
    THEN
    DUP _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-EMPTY = IF
        DUP _O2HP.CLEANUP @ OAUTH2-HTTP-POST-CLEANUP-CERTAIN =
        OVER 8 + OAUTH2-HTTP-POST-SIZE 8 - _O2HP-ZERO? AND
        SWAP DROP EXIT
    THEN
    DUP _O2HP.TARGET HTARGET-VALID? 0= IF DROP 0 EXIT THEN
    DUP _O2HP.REQUEST-CAP @ 64 < IF DROP 0 EXIT THEN
    DUP _O2HP.RESPONSE-CAP @ 0= IF DROP 0 EXIT THEN
    DUP _O2HP.REQUEST-A @ OVER _O2HP.REQUEST-CAP @
        _O2HP-SPAN-STATUS OAUTH2-HTTP-POST-S-OK <> IF
        DROP 0 EXIT
    THEN
    DUP _O2HP.FORM-A @ OVER _O2HP.FORM-CAP @
        _O2HP-SPAN-STATUS OAUTH2-HTTP-POST-S-OK <> IF
        DROP 0 EXIT
    THEN
    DUP _O2HP.RESPONSE-A @ OVER _O2HP.RESPONSE-CAP @
        _O2HP-SPAN-STATUS OAUTH2-HTTP-POST-S-OK <> IF
        DROP 0 EXIT
    THEN
    DUP _O2HP-PERSISTENT-ARENAS-DISJOINT? 0= IF
        DROP 0 EXIT
    THEN
    DUP _O2HP-SUBORDINATE-BINDINGS? 0= IF
        DROP 0 EXIT
    THEN
    DUP _O2HP.RESPONSE-U @
    DUP 0< IF 2DROP 0 EXIT THEN
    OVER _O2HP.RESPONSE-CAP @ U> IF DROP 0 EXIT THEN
    DUP _O2HP.NONCE-U @
    DUP 0< IF 2DROP 0 EXIT THEN
    OAUTH2-HTTP-POST-NONCE-CAPACITY U> IF DROP 0 EXIT THEN
    DUP _O2HP-CORRELATION-CANONICAL? 0= IF DROP 0 EXIT THEN
    DUP _O2HP.FLAGS @ _O2HP-FLAGS-KNOWN INVERT AND IF
        DROP 0 EXIT
    THEN
    DUP _O2HP-FLAGS-CONSISTENT? 0= IF DROP 0 EXIT THEN
    DUP _O2HP-KIND-EXPECTED? 0= IF DROP 0 EXIT THEN
    DUP _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-CLEANUP =
    OVER _O2HP.CLEANUP @ OAUTH2-HTTP-POST-CLEANUP-UNCERTAIN = <> IF
        DROP 0 EXIT
    THEN
    DROP -1 ;

: OAUTH2-HTTP-POST-EXTERNAL-SPAN-STATUS
  ( address length post -- status )
    >R
    R@ OAUTH2-HTTP-POST-VALID? 0= IF
        2DROP R> DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    DUP 0< IF
        2DROP R> DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    DUP 0= IF
        2DROP R> DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    OVER 0= IF
        2DROP R> DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    2DUP _O2HP-SPAN-STATUS ?DUP IF
        >R 2DROP R> R> DROP EXIT
    THEN
    2DUP R@ OAUTH2-HTTP-POST-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP OAUTH2-HTTP-POST-S-ALIAS EXIT
    THEN
    2DUP R@ _O2HP.REQUEST-A @ R@ _O2HP.REQUEST-CAP @
        MSPAN-OVERLAP? IF
        2DROP R> DROP OAUTH2-HTTP-POST-S-ALIAS EXIT
    THEN
    2DUP R@ _O2HP.FORM-A @ R@ _O2HP.FORM-CAP @
        MSPAN-OVERLAP? IF
        2DROP R> DROP OAUTH2-HTTP-POST-S-ALIAS EXIT
    THEN
    R@ _O2HP.RESPONSE-A @ R@ _O2HP.RESPONSE-CAP @
        MSPAN-OVERLAP? IF
        R> DROP OAUTH2-HTTP-POST-S-ALIAS EXIT
    THEN
    R> DROP OAUTH2-HTTP-POST-S-OK ;

