    >R
    R@ _O2HP.T0 @ 0= IF
        R@ _O2HP.T0 !
    ELSE
        DROP
    THEN
    R> DROP ;

: _O2HP-NQCHAR?  ( byte -- flag )
    DUP 33 = IF DROP -1 EXIT THEN
    DUP 35 92 WITHIN IF DROP -1 EXIT THEN
    93 127 WITHIN ;

: _O2HP-NONCE-VALUE-DETAIL  ( address length -- detail | 0 )
    DUP 0= IF 2DROP OAUTH2-HTTP-POST-D-DPOP-NONCE-EMPTY EXIT THEN
    DUP OAUTH2-HTTP-POST-NONCE-CAPACITY U> IF
        2DROP OAUTH2-HTTP-POST-D-DPOP-NONCE-CAPACITY EXIT
    THEN
    BEGIN DUP WHILE
        OVER C@ _O2HP-NQCHAR? 0= IF
            2DROP OAUTH2-HTTP-POST-D-DPOP-NONCE-CHARACTER EXIT
        THEN
        1 /STRING
    REPEAT
    2DROP OAUTH2-HTTP-POST-D-NONE ;

: _O2HP-CAPTURE-NONCE  ( post -- detail | 0 )
    >R
    R@ _O2HP-CLEAR-NONCE
    S" dpop-nonce" R@ _O2HP-HEADER-COUNT
    DUP 0= IF DROP R> DROP OAUTH2-HTTP-POST-D-NONE EXIT THEN
    1 <> IF R> DROP OAUTH2-HTTP-POST-D-DPOP-NONCE-DUPLICATE EXIT THEN
    S" dpop-nonce" R@ _O2HP-HEADER 0= IF
        2DROP R> DROP OAUTH2-HTTP-POST-D-DPOP-NONCE-EMPTY EXIT
    THEN
    2DUP _O2HP-NONCE-VALUE-DETAIL ?DUP IF
        >R 2DROP R> R> DROP EXIT
    THEN
    2DUP
    R@ _O2HP.NONCE SWAP CMOVE
    NIP R@ _O2HP.NONCE-U !
    R> DROP OAUTH2-HTTP-POST-D-NONE ;

: _O2HP-HEADER-HARDEN  ( post -- detail | 0 )
    >R 0 R@ _O2HP.T0 !
    S" content-length" R@ _O2HP-HEADER-COUNT 1 > IF
        OAUTH2-HTTP-POST-D-CONTENT-LENGTH-DUPLICATE
            R@ _O2HP-FIRST-DETAIL!
    THEN
    S" content-type" R@ _O2HP-HEADER-COUNT 1 > IF
        OAUTH2-HTTP-POST-D-CONTENT-TYPE-DUPLICATE
            R@ _O2HP-FIRST-DETAIL!
    THEN
    S" content-encoding" R@ _O2HP-HEADER-COUNT 1 > IF
        OAUTH2-HTTP-POST-D-CONTENT-ENCODING-DUPLICATE
            R@ _O2HP-FIRST-DETAIL!
    THEN
    S" dpop-nonce" R@ _O2HP-HEADER-COUNT 1 > IF
        OAUTH2-HTTP-POST-D-DPOP-NONCE-DUPLICATE
            R@ _O2HP-FIRST-DETAIL!
    THEN
    S" trailer" R@ _O2HP-HEADER-COUNT IF
        OAUTH2-HTTP-POST-D-TRAILER-DECLARED
            R@ _O2HP-FIRST-DETAIL!
    THEN
    R@ _O2HP.EXCHANGE HBUF.PARSER HSTR.BODY-MODE @
        HSTR-BODY-CHUNKED = IF
        R@ _O2HP.EXCHANGE HBUF.PARSER HSTR.TRAILER-U @ 2 <> IF
            OAUTH2-HTTP-POST-D-TRAILER-PRESENT
                R@ _O2HP-FIRST-DETAIL!
        THEN
    THEN
    R@ _O2HP-CAPTURE-NONCE ?DUP IF
        R@ _O2HP-FIRST-DETAIL!
    THEN
    R@ _O2HP.T0 @
    R> DROP ;

: _O2HP-CONTENT-ENCODING-OK?  ( post -- flag )
    >R
    S" content-encoding" R@ _O2HP-HEADER-COUNT
    DUP 0= IF DROP R> DROP -1 EXIT THEN
    1 <> IF R> DROP 0 EXIT THEN
    S" content-encoding" R@ _O2HP-HEADER 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    S" identity" STR-STRI=
    R> DROP ;

: _O2HP-PARAM-NAME$  ( index post -- address length )
    _O2HP.MEDIA MTYPE-PARAM-NTH
    IF 2DROP ELSE 2DROP THEN ;

: _O2HP-MEDIA-PARAMS-UNIQUE?  ( post -- flag )
    >R
    R@ _O2HP.MEDIA MTYPE-PARAM-COUNT@ R@ _O2HP.T0 !
    0 R@ _O2HP.T1 !
    BEGIN
        R@ _O2HP.T1 @ R@ _O2HP.T0 @ 1- <
    WHILE
        R@ _O2HP.T1 @ 1+ R@ _O2HP.T2 !
        BEGIN
            R@ _O2HP.T2 @ R@ _O2HP.T0 @ <
        WHILE
            R@ _O2HP.T1 @ R@ _O2HP-PARAM-NAME$
            R@ _O2HP.T2 @ R@ _O2HP-PARAM-NAME$
            STR-STRI= IF
                R> DROP 0 EXIT
            THEN
            1 R@ _O2HP.T2 +!
        REPEAT
        1 R@ _O2HP.T1 +!
    REPEAT
    R> DROP -1 ;

: _O2HP-MEDIA-DETAIL  ( post -- detail | 0 )
    >R
    R@ _O2HP.MEDIA MTYPE-INIT
    S" content-type" R@ _O2HP-HEADER-COUNT 0= IF
        R> DROP OAUTH2-HTTP-POST-D-CONTENT-TYPE-MISSING EXIT
    THEN
    S" content-type" R@ _O2HP-HEADER 0= IF
        2DROP R> DROP OAUTH2-HTTP-POST-D-CONTENT-TYPE-MISSING EXIT
    THEN
    R@ _O2HP.MEDIA MTYPE-PARSE
    DUP R@ _O2HP.MEDIA-STATUS !
    MTYPE-S-OK <> IF
        R> DROP OAUTH2-HTTP-POST-D-CONTENT-TYPE-MALFORMED EXIT
    THEN
    R@ _O2HP.MEDIA MTYPE-TYPE$
        S" application" STR-STRI= 0= IF
        R> DROP OAUTH2-HTTP-POST-D-CONTENT-TYPE-NOT-JSON EXIT
    THEN
    R@ _O2HP.MEDIA MTYPE-SUBTYPE$
        S" json" STR-STRI= 0= IF
        R> DROP OAUTH2-HTTP-POST-D-CONTENT-TYPE-NOT-JSON EXIT
    THEN
    R@ _O2HP-MEDIA-PARAMS-UNIQUE? 0= IF
        R> DROP OAUTH2-HTTP-POST-D-MEDIA-PARAM-DUPLICATE EXIT
    THEN
    R> DROP OAUTH2-HTTP-POST-D-NONE ;

: _O2HP-OAUTH-CANDIDATE?  ( http-status post -- flag )
    >R
    DUP R@ _O2HP.EXPECTED @ =
    OVER 400 = OR
    SWAP 401 = OR
    R> DROP ;

: _O2HP-ADMIT-RESPONSE  ( post -- )
    >R
    R@ _O2HP.EXCHANGE HBUF.HTTP-CODE @
        R@ _O2HP.HTTP-STATUS !
    R@ _O2HP.EXCHANGE HBUF.BODY-U @
        R@ _O2HP.RESPONSE-U !

    R@ _O2HP-HEADER-HARDEN ?DUP IF
        OAUTH2-HTTP-POST-O-HEADER SWAP R@ _O2HP-SET-PRIMARY
        R> DROP EXIT
    THEN
    R@ _O2HP-CONTENT-ENCODING-OK? 0= IF
        OAUTH2-HTTP-POST-O-CONTENT-ENCODING
        OAUTH2-HTTP-POST-D-CONTENT-ENCODING-MISMATCH
            R@ _O2HP-SET-PRIMARY
        R> DROP EXIT
    THEN

    R@ _O2HP.HTTP-STATUS @ R@ _O2HP-OAUTH-CANDIDATE? IF
        R@ _O2HP.RESPONSE-U @ 0= IF
            OAUTH2-HTTP-POST-O-BODY OAUTH2-HTTP-POST-D-BODY-EMPTY
                R@ _O2HP-SET-PRIMARY
            R> DROP EXIT
        THEN
        R@ _O2HP-MEDIA-DETAIL ?DUP IF
            OAUTH2-HTTP-POST-O-MEDIA SWAP R@ _O2HP-SET-PRIMARY
            R> DROP EXIT
        THEN
        R@ _O2HP.HTTP-STATUS @ R@ _O2HP.EXPECTED @ = IF
            OAUTH2-HTTP-POST-O-SUCCESS
        ELSE
            OAUTH2-HTTP-POST-O-OAUTH-ERROR
        THEN
        OAUTH2-HTTP-POST-D-NONE R@ _O2HP-SET-PRIMARY
        R> DROP EXIT
    THEN

    R@ _O2HP.HTTP-STATUS @ 300 400 WITHIN IF
        OAUTH2-HTTP-POST-D-REDIRECT
    ELSE
        OAUTH2-HTTP-POST-D-UNEXPECTED-HTTP
    THEN
    OAUTH2-HTTP-POST-O-HTTP SWAP R@ _O2HP-SET-PRIMARY
    R> DROP ;

\ =====================================================================
\  Cooperative START/POLL and terminal cleanup
\ =====================================================================

: _O2HP-CLEAR-RESPONSE  ( post -- )
    DUP _O2HP.RESPONSE-A @ OVER _O2HP.RESPONSE-CAP @ 0 FILL
    DUP 0 SWAP _O2HP.RESPONSE-U !
    DUP _O2HP-CLEAR-NONCE
    _O2HP.MEDIA MTYPE-INIT ;

: _O2HP-FINISH-CERTAIN  ( retain-response? post -- status )
    >R
    0= IF R@ _O2HP-CLEAR-RESPONSE THEN
    R@ _O2HP-SCRUB-EGRESS
    R@ _O2HP.EXCHANGE HTTP-BUFFERED-SIZE 0 FILL
    0 R@ _O2HP.PORT !
    OAUTH2-HTTP-POST-CLEANUP-CERTAIN R@ _O2HP.CLEANUP !
    OAUTH2-HTTP-POST-STATE-RESULT R@ _O2HP.STATE !
    OAUTH2-HTTP-POST-S-OK R@ _O2HP.LAST-STATUS !
    R> DROP OAUTH2-HTTP-POST-S-OK ;

: _O2HP-FINISH-CLEAN  ( retain-response? post -- status )
    DUP >R _O2HP-CAPTURE-LOWER
    R> _O2HP-FINISH-CERTAIN ;

: _O2HP-POISON-CLEANUP  ( post -- status )
    DUP _O2HP-CAPTURE-LOWER
    DUP _O2HP.OUTCOME @ OAUTH2-HTTP-POST-O-NONE = IF
        DUP OAUTH2-HTTP-POST-O-CLEANUP SWAP _O2HP.OUTCOME !
        DUP OAUTH2-HTTP-POST-D-LOWER SWAP _O2HP.DETAIL !
    THEN
    DUP OAUTH2-HTTP-POST-CLEANUP-UNCERTAIN SWAP _O2HP.CLEANUP !
    DUP OAUTH2-HTTP-POST-STATE-CLEANUP SWAP _O2HP.STATE !
    OAUTH2-HTTP-POST-S-CLEANUP DUP ROT _O2HP.LAST-STATUS ! ;

: _O2HP-HANDLE-HBUF-TERMINAL  ( hbuf-status post -- status )
    >R
    DUP R@ _O2HP.EXCHANGE-STATUS !
    R@ _O2HP.EXCHANGE HBUF.PARSER HSTR.STATE @
        HSTR-STATE-DONE = R@ _O2HP.T3 !

    R@ _O2HP.T3 @ IF
        R@ _O2HP-ADMIT-RESPONSE
    ELSE
        DUP HBUF-S-CANCELLED = IF
            OAUTH2-HTTP-POST-O-CANCELLED OAUTH2-HTTP-POST-D-NONE
                R@ _O2HP-SET-PRIMARY
        ELSE
            DUP HBUF-S-PROTOCOL = IF
                OAUTH2-HTTP-POST-O-PROTOCOL
                R@ _O2HP.EXCHANGE HBUF.PARSER HSTR.STATUS @
                    R@ _O2HP-SET-PRIMARY
            ELSE
                DUP HBUF-S-TRANSPORT = IF
                    OAUTH2-HTTP-POST-O-TRANSPORT
                    OAUTH2-HTTP-POST-D-LOWER R@ _O2HP-SET-PRIMARY
                ELSE
                    OAUTH2-HTTP-POST-O-FAULT
                    OAUTH2-HTTP-POST-D-INTERNAL R@ _O2HP-SET-PRIMARY
                THEN
            THEN
        THEN
    THEN
    DROP

    R@ _O2HP.EXCHANGE HBUF.PORT @ IF
        R> _O2HP-POISON-CLEANUP EXIT
    THEN
    R@ _O2HP.T3 @
    R> _O2HP-FINISH-CLEAN ;

: _O2HP-MARK-SEND-ATTEMPT  ( post -- )
    >R
    R@ _O2HP.FLAGS @
    DUP OAUTH2-HTTP-POST-F-DPOP-INCLUDED AND IF
        OAUTH2-HTTP-POST-F-DPOP-SENT OR
    THEN
    DUP OAUTH2-HTTP-POST-F-AUTHORIZATION-INCLUDED AND IF
        OAUTH2-HTTP-POST-F-AUTHORIZATION-SENT OR
    THEN
    R@ _O2HP.FLAGS !
    R> DROP ;

: _O2HP-PORT-STATUS  ( port -- status )
    DUP 0= IF DROP OAUTH2-HTTP-POST-S-INVALID EXIT THEN
    DUP 7 AND IF DROP OAUTH2-HTTP-POST-S-INVALID EXIT THEN
    NET-IO-PORT-SIZE _O2HP-SPAN-STATUS ;

: _O2HP-COOPERATIVE-PORT?  ( port -- flag )
    DUP NIO.RECV-XT @ 0<>
    OVER NIO.SEND-XT @ 0<> AND
    OVER NIO.OPEN-START-XT @ 0<> AND
    OVER NIO.OPEN-POLL-XT @ 0<> AND
    OVER NIO.CLOSE-START-XT @ 0<> AND
    OVER NIO.CLOSE-POLL-XT @ 0<> AND
    SWAP NIO.CANCEL-XT @ 0<> AND ;

: _O2HP-DETACHED-PORT?  ( port -- flag )
    DUP NIO.OPEN-STATE @ NIO-OPEN-STATE-CLOSED =
    OVER NIO.CLOSE-STATE @ DUP NIO-CLOSE-STATE-IDLE =
        SWAP NIO-CLOSE-STATE-CLOSED = OR AND
    OVER NIO.CANCEL-ERROR @ 0= AND
    SWAP NIO.CLOSE-ERROR @ 0= AND ;

: _O2HP-PORT-ALIASES?  ( port post -- flag )
    >R
    DUP NET-IO-PORT-SIZE R@ OAUTH2-HTTP-POST-SIZE
        MSPAN-OVERLAP? IF
        DROP R> DROP -1 EXIT
    THEN
    DUP NET-IO-PORT-SIZE
    R@ _O2HP.REQUEST-A @ R@ _O2HP.REQUEST-CAP @
        MSPAN-OVERLAP? IF
        DROP R> DROP -1 EXIT
    THEN
    DUP NET-IO-PORT-SIZE
    R@ _O2HP.FORM-A @ R@ _O2HP.FORM-CAP @
        MSPAN-OVERLAP? IF
        DROP R> DROP -1 EXIT
    THEN
    DUP NET-IO-PORT-SIZE
    R@ _O2HP.RESPONSE-A @ R@ _O2HP.RESPONSE-CAP @
        MSPAN-OVERLAP? IF
        DROP R> DROP -1 EXIT
    THEN
    DROP R> DROP 0 ;

: _O2HP-PORT-PREFLIGHT  ( port post -- status )
    >R
    DUP _O2HP-PORT-STATUS ?DUP IF
        NIP R> DROP EXIT
    THEN
    DUP _O2HP-COOPERATIVE-PORT? 0= IF
        DROP R> DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    DUP R@ _O2HP-PORT-ALIASES? IF
        DROP R> DROP OAUTH2-HTTP-POST-S-ALIAS EXIT
    THEN
    _O2HP-DETACHED-PORT? 0= IF
        R> DROP OAUTH2-HTTP-POST-S-BUSY EXIT
    THEN
    R> DROP OAUTH2-HTTP-POST-S-OK ;

: OAUTH2-HTTP-POST-CLEANUP-FINALIZE  ( post -- status )
    DUP OAUTH2-HTTP-POST-VALID? 0= IF
        DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    DUP _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-CLEANUP <> IF
        DROP OAUTH2-HTTP-POST-S-STATE EXIT
    THEN
    DUP >R _O2HP.PORT @
    DUP 0= IF
        DROP
        R@ _O2HP.EXCHANGE HBUF.PORT @ IF
            R> DROP OAUTH2-HTTP-POST-S-CLEANUP EXIT
        THEN
    ELSE
        DUP R@ _O2HP.EXCHANGE HBUF.PORT @ <> IF
            DROP R> DROP OAUTH2-HTTP-POST-S-CLEANUP EXIT
        THEN
        R@ _O2HP-RETAINED-PORT-GEOMETRY? 0= IF
            DROP R> DROP OAUTH2-HTTP-POST-S-CLEANUP EXIT
        THEN
        DUP _O2HP-DETACHED-PORT? 0= IF
            DROP R> DROP OAUTH2-HTTP-POST-S-CLEANUP EXIT
        THEN
        DROP
    THEN
    R@ _O2HP.EXCHANGE HBUF.PARSER HSTR.STATE @
        HSTR-STATE-DONE =
    DUP IF R@ _O2HP-ADMIT-RESPONSE THEN
    R> _O2HP-FINISH-CERTAIN ;

: OAUTH2-HTTP-POST-START  ( port post -- status )
    DUP OAUTH2-HTTP-POST-VALID? 0= IF
        2DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    DUP _O2HP.CLEANUP @ OAUTH2-HTTP-POST-CLEANUP-UNCERTAIN = IF
        2DROP OAUTH2-HTTP-POST-S-CLEANUP EXIT
    THEN
    DUP _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-SEALED <> IF
        2DROP OAUTH2-HTTP-POST-S-STATE EXIT
    THEN
    2DUP _O2HP-PORT-PREFLIGHT ?DUP IF
        >R 2DROP R> EXIT
    THEN
    OVER OVER _O2HP.PORT !
    >R
    R@ _O2HP.REQUEST SWAP R@ _O2HP.EXCHANGE HBUF-START
    DUP R@ _O2HP.EXCHANGE-STATUS !
    DUP HBUF-S-PENDING = IF
        DROP OAUTH2-HTTP-POST-STATE-ACTIVE R@ _O2HP.STATE !
        OAUTH2-HTTP-POST-S-PENDING DUP R@ _O2HP.LAST-STATUS !
        R> DROP EXIT
    THEN
    R> _O2HP-HANDLE-HBUF-TERMINAL ;

: OAUTH2-HTTP-POST-POLL  ( post -- status )
    DUP OAUTH2-HTTP-POST-VALID? 0= IF
        DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    DUP _O2HP.CLEANUP @ OAUTH2-HTTP-POST-CLEANUP-UNCERTAIN = IF
        DROP OAUTH2-HTTP-POST-S-CLEANUP EXIT
    THEN
    DUP _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-RESULT = IF
        DROP OAUTH2-HTTP-POST-S-OK EXIT
    THEN
    DUP _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-ACTIVE <> IF
        DROP OAUTH2-HTTP-POST-S-STATE EXIT
    THEN
    DUP >R
    R@ _O2HP.EXCHANGE HBUF.STATE @ HBUF-STATE-SENDING = IF
        R@ _O2HP-MARK-SEND-ATTEMPT
    THEN
    _O2HP.EXCHANGE HBUF-POLL
    DUP R@ _O2HP.EXCHANGE-STATUS !
    DUP HBUF-S-PENDING = IF
        DROP OAUTH2-HTTP-POST-S-PENDING DUP R@ _O2HP.LAST-STATUS !
        R> DROP EXIT
    THEN
    R> _O2HP-HANDLE-HBUF-TERMINAL ;

\ =====================================================================
\  Cancellation and wipe
\ =====================================================================

: OAUTH2-HTTP-POST-CANCEL  ( post -- status )
    DUP OAUTH2-HTTP-POST-VALID? 0= IF
        DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    DUP _O2HP.CLEANUP @ OAUTH2-HTTP-POST-CLEANUP-UNCERTAIN = IF
        DROP OAUTH2-HTTP-POST-S-CLEANUP EXIT
    THEN
    DUP _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-ACTIVE <> IF
        DUP _O2HP.EXCHANGE HBUF.PORT @ IF
            OAUTH2-HTTP-POST-O-CLEANUP
            OAUTH2-HTTP-POST-D-LOWER 2 PICK _O2HP-SET-PRIMARY
            _O2HP-POISON-CLEANUP EXIT
        THEN
        DROP OAUTH2-HTTP-POST-S-OK EXIT
    THEN
    DUP >R _O2HP.EXCHANGE HBUF-CANCEL
    DUP HBUF-S-OK = IF
        DROP HBUF-S-CANCELLED R> _O2HP-HANDLE-HBUF-TERMINAL EXIT
    THEN
    R> _O2HP-HANDLE-HBUF-TERMINAL ;

: OAUTH2-HTTP-POST-WIPE  ( post -- status )
    DUP OAUTH2-HTTP-POST-VALID? 0= IF
        DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    DUP _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-EMPTY = IF
        DROP OAUTH2-HTTP-POST-S-OK EXIT
    THEN
    DUP _O2HP.CLEANUP @ OAUTH2-HTTP-POST-CLEANUP-UNCERTAIN = IF
        DROP OAUTH2-HTTP-POST-S-CLEANUP EXIT
    THEN
    DUP _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-ACTIVE = IF
        DROP OAUTH2-HTTP-POST-S-BUSY EXIT
    THEN
    DUP _O2HP.EXCHANGE HBUF.PORT @ IF
        OAUTH2-HTTP-POST-O-CLEANUP
        OAUTH2-HTTP-POST-D-LOWER 2 PICK _O2HP-SET-PRIMARY
        _O2HP-POISON-CLEANUP EXIT
    THEN
    DUP >R _O2HP-ZERO-ARENAS
    R@ OAUTH2-HTTP-POST-SIZE 0 FILL
    _O2HP-MAGIC-VALUE R@ _O2HP.MAGIC !
    OAUTH2-HTTP-POST-STATE-EMPTY R@ _O2HP.STATE !
    OAUTH2-HTTP-POST-CLEANUP-CERTAIN R@ _O2HP.CLEANUP !
    OAUTH2-HTTP-POST-S-OK R@ _O2HP.LAST-STATUS !
    R> DROP OAUTH2-HTTP-POST-S-OK ;

