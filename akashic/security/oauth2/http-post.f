    SWAP HSTR-S-UNSUPPORTED > OR IF R> DROP 0 EXIT THEN
    R@ HSTR.BODY-MODE @ DUP HSTR-BODY-NONE <
    SWAP HSTR-BODY-CLOSE > OR IF R> DROP 0 EXIT THEN
