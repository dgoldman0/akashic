: _O2HP-CONFIG-MATERIAL  ( post -- status )
    >R
    R@ _O2HP.REQUEST-A @ R@ _O2HP.REQUEST-CAP @ R@ _O2HP.REQUEST
        HREQ-INIT
    DUP R@ _O2HP.REQUEST-STATUS !
    DUP HREQ-S-OK <> IF
        _O2HP-HREQ>STATUS R> _O2HP-CONFIG-FAIL EXIT
    THEN
    DROP

    R@ _O2HP.FORM-A @ R@ _O2HP.FORM-CAP @ R@ _O2HP.WRITER
        FUEW-INIT
    DUP R@ _O2HP.FORM-STATUS !
    DUP FUEW-S-OK <> IF
        _O2HP-FUEW>STATUS R> _O2HP-CONFIG-FAIL EXIT
    THEN
    DROP

    R@ _O2HP.RESPONSE-A @ R@ _O2HP.RESPONSE-CAP @ 0 FILL
    R@ _O2HP.RESPONSE-A @ R@ _O2HP.RESPONSE-CAP @ R@ _O2HP.EXCHANGE
        HBUF-INIT
    DUP R@ _O2HP.EXCHANGE-STATUS !
    HBUF-S-OK <> IF
        OAUTH2-HTTP-POST-S-INTERNAL R> _O2HP-CONFIG-FAIL EXIT
    THEN
    R@ _O2HP.RESPONSE-CAP @
        R@ _O2HP.EXCHANGE HBUF.PARSER HSTR-BODY-LIMIT!
    R@ _O2HP.MEDIA MTYPE-INIT

    0 R@ _O2HP.T0 !
    _O2HP-MAGIC-VALUE R@ _O2HP.MAGIC !
    OAUTH2-HTTP-POST-STATE-CONFIGURED R@ _O2HP.STATE !
    OAUTH2-HTTP-POST-CLEANUP-CERTAIN R@ _O2HP.CLEANUP !
    OAUTH2-HTTP-POST-S-OK R@ _O2HP.LAST-STATUS !
    R> DROP OAUTH2-HTTP-POST-S-OK ;

