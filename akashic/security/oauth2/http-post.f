: _O2HP-OPTIONAL-HEADER-STATUS  ( address length -- status )
    DUP 0= IF
        DROP 0= IF
            OAUTH2-HTTP-POST-S-OK
        ELSE
            OAUTH2-HTTP-POST-S-INVALID
        THEN
        EXIT
    THEN
    DUP 0< IF 2DROP OAUTH2-HTTP-POST-S-INVALID EXIT THEN
    _O2HP-SPAN-STATUS ;

: _O2HP-OPTIONAL-REQUEST-ALIAS?  ( address length post -- flag )
    >R
    DUP 0= IF 2DROP R> DROP 0 EXIT THEN
    2DUP R@ _O2HP.REQUEST-A @ R@ _O2HP.REQUEST-CAP @
        MSPAN-OVERLAP? IF
        2DROP R> DROP -1 EXIT
    THEN
    R@ OAUTH2-HTTP-POST-SIZE MSPAN-OVERLAP?
    R> DROP ;

: _O2HP-HOST$  ( post -- address length )
    _O2HP.TARGET DUP >R HTARGET-URI$
    8 /STRING
    R> HTARGET.REQUEST-U @ - ;

: _O2HP-HREQ-RESULT  ( request-status post -- status )
    >R
    DUP R@ _O2HP.REQUEST-STATUS !
    _O2HP-HREQ>STATUS
    R> DROP ;

: _O2HP-BUILD-CORE  ( post -- status )
    >R
    S" POST" R@ _O2HP.TARGET HTARGET-REQUEST-TARGET$
        R@ _O2HP.REQUEST HREQ-BEGIN
        R@ _O2HP-HREQ-RESULT ?DUP IF R> DROP EXIT THEN
    R@ _O2HP-HOST$ R@ _O2HP.REQUEST HREQ-HOST
        R@ _O2HP-HREQ-RESULT ?DUP IF R> DROP EXIT THEN
    S" application/json" R@ _O2HP.REQUEST HREQ-ACCEPT
        R@ _O2HP-HREQ-RESULT ?DUP IF R> DROP EXIT THEN
    S" application/x-www-form-urlencoded"
        R@ _O2HP.REQUEST HREQ-CONTENT-TYPE
        R@ _O2HP-HREQ-RESULT
    R> DROP ;

: _O2HP-SCRUB-EGRESS  ( post -- )
    DUP _O2HP.WRITER FUEW-VALID? IF
        DUP _O2HP.WRITER FUEW-WIPE DROP
    ELSE
        DUP _O2HP.FORM-A @ OVER _O2HP.FORM-CAP @ 0 FILL
        DUP _O2HP.WRITER FUEW-SIZE 0 FILL
    THEN
    DUP _O2HP.REQUEST-A @ OVER _O2HP.REQUEST-CAP @ 0 FILL
    DUP _O2HP.REQUEST HTTP-REQUEST-SIZE 0 FILL
    DUP _O2HP.EXCHANGE 0 SWAP HBUF.REQUEST !
    DROP ;

: _O2HP-CAPTURE-LOWER  ( post -- )
    DUP _O2HP.REQUEST HREQ.STATUS @
        OVER _O2HP.REQUEST-STATUS !
    DUP _O2HP.EXCHANGE HBUF.LAST-STATUS @
        OVER _O2HP.EXCHANGE-STATUS !
    DUP _O2HP.EXCHANGE HBUF.PARSER HSTR.STATUS @
        OVER _O2HP.PARSER-STATUS !
    DUP _O2HP.PORT @ ?DUP IF
        DUP NIO.OPEN-STATUS @ 2 PICK _O2HP.NIO-OPEN-STATUS !
        DUP NIO.CLOSE-STATUS @ 2 PICK _O2HP.NIO-CLOSE-STATUS !
        DUP NIO.CANCEL-ERROR @ 2 PICK _O2HP.NIO-CANCEL-ERROR !
        NIO.CLOSE-ERROR @ OVER _O2HP.NIO-CLOSE-ERROR !
    THEN
    DROP ;

: _O2HP-SET-PRIMARY  ( outcome detail post -- )
    >R
    R@ _O2HP.DETAIL !
    R@ _O2HP.OUTCOME !
    R> DROP ;

: _O2HP-BUILD-FAIL  ( status detail post -- status )
    >R
    R@ _O2HP.DETAIL !
    OAUTH2-HTTP-POST-O-FAULT R@ _O2HP.OUTCOME !
    OAUTH2-HTTP-POST-STATE-RESULT R@ _O2HP.STATE !
    0 R@ _O2HP.FLAGS !
    DUP R@ _O2HP.LAST-STATUS !
    R@ _O2HP-CAPTURE-LOWER
    R@ _O2HP-SCRUB-EGRESS
    R@ _O2HP.EXCHANGE HTTP-BUFFERED-SIZE 0 FILL
    R> DROP ;

: _O2HP-SEAL-FAIL-RETURN
  ( dpop-a dpop-u authorization-a authorization-u status -- status )
    _O2HP-RETURN4 ;

: OAUTH2-HTTP-POST-SEAL
  ( dpop-a dpop-u authorization-a authorization-u post -- status )
    DUP OAUTH2-HTTP-POST-VALID? 0= IF
        2DROP 2DROP DROP OAUTH2-HTTP-POST-S-INVALID EXIT
    THEN
    DUP _O2HP.STATE @ OAUTH2-HTTP-POST-STATE-BUILDING <> IF
        2DROP 2DROP DROP OAUTH2-HTTP-POST-S-STATE EXIT
    THEN
    >R
    3 PICK 3 PICK _O2HP-OPTIONAL-HEADER-STATUS ?DUP IF
        DUP R@ _O2HP.LAST-STATUS !
        R> DROP _O2HP-SEAL-FAIL-RETURN EXIT
    THEN
    1 PICK 1 PICK _O2HP-OPTIONAL-HEADER-STATUS ?DUP IF
        DUP R@ _O2HP.LAST-STATUS !
        R> DROP _O2HP-SEAL-FAIL-RETURN EXIT
    THEN
    3 PICK 3 PICK R@ _O2HP-OPTIONAL-REQUEST-ALIAS? IF
        OAUTH2-HTTP-POST-S-ALIAS
        DUP R@ _O2HP.LAST-STATUS ! R> DROP
        _O2HP-SEAL-FAIL-RETURN EXIT
    THEN
    1 PICK 1 PICK R@ _O2HP-OPTIONAL-REQUEST-ALIAS? IF
        OAUTH2-HTTP-POST-S-ALIAS
        DUP R@ _O2HP.LAST-STATUS ! R> DROP
        _O2HP-SEAL-FAIL-RETURN EXIT
    THEN

    R@ _O2HP.WRITER FUEW-SEAL
    DUP R@ _O2HP.FORM-STATUS !
    DUP FUEW-S-OK <> IF
        _O2HP-FUEW>STATUS
        OAUTH2-HTTP-POST-D-FORM R> _O2HP-BUILD-FAIL
        _O2HP-SEAL-FAIL-RETURN EXIT
    THEN
    DROP
    R@ _O2HP.WRITER FUEW-BODY@
    DUP R@ _O2HP.FORM-STATUS !
    DUP FUEW-S-OK <> IF
        _O2HP-FUEW>STATUS
        >R 2DROP R>
        OAUTH2-HTTP-POST-D-FORM R> _O2HP-BUILD-FAIL
        _O2HP-SEAL-FAIL-RETURN EXIT
    THEN
    DROP
    R@ _O2HP.T1 !
    R@ _O2HP.T0 !

    R@ _O2HP-BUILD-CORE ?DUP IF
        OAUTH2-HTTP-POST-D-REQUEST R> _O2HP-BUILD-FAIL
        _O2HP-SEAL-FAIL-RETURN EXIT
    THEN

    2 PICK IF
        3 PICK 3 PICK S" DPoP" 2SWAP R@ _O2HP.REQUEST HREQ-HEADER
            R@ _O2HP-HREQ-RESULT ?DUP IF
            OAUTH2-HTTP-POST-D-REQUEST R> _O2HP-BUILD-FAIL
            _O2HP-SEAL-FAIL-RETURN EXIT
        THEN
        R@ _O2HP.FLAGS DUP @
            OAUTH2-HTTP-POST-F-DPOP-INCLUDED OR SWAP !
    THEN
    DUP IF
        1 PICK 1 PICK S" Authorization" 2SWAP
            R@ _O2HP.REQUEST HREQ-HEADER
            R@ _O2HP-HREQ-RESULT ?DUP IF
            OAUTH2-HTTP-POST-D-REQUEST R> _O2HP-BUILD-FAIL
            _O2HP-SEAL-FAIL-RETURN EXIT
        THEN
        R@ _O2HP.FLAGS DUP @
            OAUTH2-HTTP-POST-F-AUTHORIZATION-INCLUDED OR SWAP !
    THEN

    R@ _O2HP.REQUEST HREQ-CONNECTION-CLOSE
        R@ _O2HP-HREQ-RESULT ?DUP IF
        OAUTH2-HTTP-POST-D-REQUEST R> _O2HP-BUILD-FAIL
        _O2HP-SEAL-FAIL-RETURN EXIT
    THEN
    R@ _O2HP.T0 @ R@ _O2HP.T1 @ R@ _O2HP.REQUEST HREQ-BODY
        R@ _O2HP-HREQ-RESULT ?DUP IF
        OAUTH2-HTTP-POST-D-REQUEST R> _O2HP-BUILD-FAIL
        _O2HP-SEAL-FAIL-RETURN EXIT
    THEN

    OAUTH2-HTTP-POST-STATE-SEALED R@ _O2HP.STATE !
    OAUTH2-HTTP-POST-S-OK R@ _O2HP.LAST-STATUS !
    R> DROP
    _O2HP-DROP4
    OAUTH2-HTTP-POST-S-OK ;

