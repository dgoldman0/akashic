        DROP 0 EXIT
    THEN
    DUP _O2PKB.VERSION _O2PK-BE64-NONNEGATIVE? 0= IF
        DROP 0 EXIT
    THEN
    DUP _O2PKB.TOTAL-U _O2PK-BE64-NONNEGATIVE? 0= IF
        DROP 0 EXIT
    THEN
    DUP _O2PKB.FLAGS _O2PK-BE64-NONNEGATIVE? 0= IF
        DROP 0 EXIT
    THEN
    DUP _O2PKB.MAGIC _O2PK-BE64@
        _O2PK-BINDING-MAGIC <> IF DROP 0 EXIT THEN
    DUP _O2PKB.VERSION _O2PK-BE64@
        _O2PK-FORMAT-VERSION <> IF DROP 0 EXIT THEN
    DUP _O2PKB.TOTAL-U _O2PK-BE64@
        OAUTH2-P256-KEY-BINDING-SIZE <> IF DROP 0 EXIT THEN
    _O2PKB.FLAGS _O2PK-BE64@
    DUP 0= IF DROP 0 EXIT THEN
    DUP _O2PK-BINDING-F-KNOWN INVERT AND IF DROP 0 EXIT THEN
    DROP -1 ;

: _O2PK-BINDING-BODY?  ( binding -- flag )
    DUP _O2PKB.FLAGS _O2PK-BE64@ >R
    R@ OAUTH2-P256-KEY-BINDING-F-CLIENT AND IF
        DUP _O2PKB.CLIENT-SLOT
        OAUTH2-P256-KEY-ROLE-CLIENT _O2PK-SLOT-VALID? 0= IF
            DROP R> DROP 0 EXIT
        THEN
    ELSE
        DUP _O2PKB.CLIENT-SLOT OAUTH2-P256-KEY-SLOT-SIZE
        _O2PK-ZERO? 0= IF
            DROP R> DROP 0 EXIT
        THEN
    THEN
    R@ OAUTH2-P256-KEY-BINDING-F-DPOP AND IF
        DUP _O2PKB.DPOP-SLOT
        OAUTH2-P256-KEY-ROLE-DPOP _O2PK-SLOT-VALID? 0= IF
            DROP R> DROP 0 EXIT
        THEN
    ELSE
        DUP _O2PKB.DPOP-SLOT OAUTH2-P256-KEY-SLOT-SIZE
        _O2PK-ZERO? 0= IF
            DROP R> DROP 0 EXIT
        THEN
    THEN
    R@ _O2PK-BINDING-F-KNOWN = IF
        DUP _O2PKB.CLIENT-SLOT
        OVER _O2PKB.DPOP-SLOT
        _O2PK-SLOTS-DISTINCT? 0= IF
            DROP R> DROP 0 EXIT
        THEN
    THEN
    DROP R> DROP -1 ;

