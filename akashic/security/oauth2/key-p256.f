: _O2PK-BE64!  ( nonnegative-u destination -- )
    >R
    DUP 56 RSHIFT 255 AND R@      C!
    DUP 48 RSHIFT 255 AND R@ 1+   C!
    DUP 40 RSHIFT 255 AND R@ 2 +  C!
    DUP 32 RSHIFT 255 AND R@ 3 +  C!
    DUP 24 RSHIFT 255 AND R@ 4 +  C!
    DUP 16 RSHIFT 255 AND R@ 5 +  C!
    DUP  8 RSHIFT 255 AND R@ 6 +  C!
        255 AND R@ 7 + C!
    R> DROP ;

: _O2PK-BE64@  ( source -- nonnegative-u )
    >R
    R@     C@ 56 LSHIFT
    R@ 1+  C@ 48 LSHIFT OR
    R@ 2 + C@ 40 LSHIFT OR
    R@ 3 + C@ 32 LSHIFT OR
    R@ 4 + C@ 24 LSHIFT OR
    R@ 5 + C@ 16 LSHIFT OR
    R@ 6 + C@  8 LSHIFT OR
    R> 7 + C@ OR ;

: _O2PK-BE64-NONNEGATIVE?  ( source -- flag )
    C@ 0x80 AND 0= ;

: _O2PK-ZERO?  ( address length -- flag )
    BEGIN DUP WHILE
        OVER C@ IF 2DROP 0 EXIT THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP -1 ;

: _O2PK-ROLE?  ( role -- flag )
