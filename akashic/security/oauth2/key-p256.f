  ( client-slot|0 dpop-slot|0 binding -- status )
    DUP OAUTH2-P256-KEY-BINDING-SIZE _O2PK-ALIGNED-FIXED-STATUS
    ?DUP IF _O2PK-RETURN3 EXIT THEN
    DUP OAUTH2-P256-KEY-BINDING-SIZE _O2PK-ZERO? 0= IF
        _O2PK-DROP3 OAUTH2-P256-KEY-S-STATE EXIT
    THEN
    2 PICK OAUTH2-P256-KEY-ROLE-CLIENT
    _O2PK-OPTIONAL-SLOT-STATUS
    ?DUP IF _O2PK-RETURN3 EXIT THEN
    1 PICK OAUTH2-P256-KEY-ROLE-DPOP
    _O2PK-OPTIONAL-SLOT-STATUS
    ?DUP IF _O2PK-RETURN3 EXIT THEN
    2 PICK 0= 2 PICK 0= AND IF
        _O2PK-DROP3 OAUTH2-P256-KEY-S-INVALID EXIT
    THEN
    2 PICK ?DUP IF
        OAUTH2-P256-KEY-SLOT-SIZE
        2 PICK OAUTH2-P256-KEY-BINDING-SIZE
        MSPAN-OVERLAP? IF
            _O2PK-DROP3 OAUTH2-P256-KEY-S-ALIAS EXIT
        THEN
    THEN
    1 PICK ?DUP IF
        OAUTH2-P256-KEY-SLOT-SIZE
        2 PICK OAUTH2-P256-KEY-BINDING-SIZE
        MSPAN-OVERLAP? IF
            _O2PK-DROP3 OAUTH2-P256-KEY-S-ALIAS EXIT
        THEN
    THEN
    2 PICK 0<> 2 PICK 0<> AND IF
        2 PICK 2 PICK _O2PK-SLOTS-DISTINCT? 0= IF
            _O2PK-DROP3 OAUTH2-P256-KEY-S-INVALID EXIT
        THEN
    THEN
    _O2PK-DROP3 OAUTH2-P256-KEY-S-OK ;

