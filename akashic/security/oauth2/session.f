: O2SESSION-CONFIG-CLEAR  ( config -- status )
    DUP O2SESSION-CONFIG-SIZE _O2S-ADMIT-SPAN
    ?DUP IF NIP EXIT THEN
    O2SESSION-CONFIG-SIZE 0 FILL
    O2SESSION-S-OK ;

: O2SESSION-GRANT-CLEAR  ( grant -- status )
    DUP O2SESSION-GRANT-SIZE _O2S-ADMIT-SPAN
    ?DUP IF NIP EXIT THEN
    O2SESSION-GRANT-SIZE 0 FILL
    O2SESSION-S-OK ;

: _O2S-GRANT-SPAN-STATUS
  ( address length capacity required? grant session -- status )
    >R
    4 PICK 4 PICK _O2S-ADMIT-SPAN ?DUP IF
        >R 2DROP 2DROP DROP R> R> DROP EXIT
    THEN
    1 PICK IF
        3 PICK 0= IF
            2DROP 2DROP DROP R> DROP
            O2SESSION-S-ABSENT EXIT
        THEN
    THEN
    3 PICK 3 PICK U> IF
        2DROP 2DROP DROP R> DROP
        O2SESSION-S-CAPACITY EXIT
    THEN
    >R 2DROP R>
    2 PICK 2 PICK 2 PICK O2SESSION-GRANT-SIZE
    MSPAN-OVERLAP? IF
        2DROP DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    2 PICK 2 PICK R@ OAUTH2-SESSION-SIZE MSPAN-OVERLAP? IF
        2DROP DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    2DROP DROP R> DROP O2SESSION-S-OK ;

: _O2S-GRANT-STATUS  ( grant session -- status )
    >R
    DUP O2SESSION-GRANT-SIZE _O2S-ADMIT-SPAN
    ?DUP IF NIP R> DROP EXIT THEN
    DUP O2SESSION-GRANT-SIZE
    R@ OAUTH2-SESSION-SIZE MSPAN-OVERLAP? IF
        DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    DUP O2SESSION-G.FLAGS @
    DUP 0< IF
        2DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    DUP _O2S-GRANT-F-KNOWN INVERT AND IF
        2DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    DROP

    DUP O2SESSION-G.ACCESS-A @
    OVER O2SESSION-G.ACCESS-U @
    O2TOK-ACCESS-CAPACITY -1 4 PICK R@
    _O2S-GRANT-SPAN-STATUS ?DUP IF
        >R DROP R> R> DROP EXIT
    THEN

    DUP O2SESSION-G.TOKEN-TYPE-A @
    OVER O2SESSION-G.TOKEN-TYPE-U @
    O2SESSION-TOKEN-TYPE-CAPACITY -1 4 PICK R@
    _O2S-GRANT-SPAN-STATUS ?DUP IF
        >R DROP R> R> DROP EXIT
    THEN

    DUP O2SESSION-G.REFRESH-A @
    OVER O2SESSION-G.REFRESH-U @
    O2TOK-REFRESH-CAPACITY 0 4 PICK R@
    _O2S-GRANT-SPAN-STATUS ?DUP IF
        >R DROP R> R> DROP EXIT
    THEN
    DUP O2SESSION-G.REFRESH-A @
    OVER O2SESSION-G.REFRESH-U @
    O2SESSION-GRANT-F-REFRESH
    3 PICK O2SESSION-G.FLAGS @
    _O2S-FLAG-CONSISTENT? 0= IF
        DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN

    DUP O2SESSION-G.SCOPE-A @
    OVER O2SESSION-G.SCOPE-U @
    O2SESSION-SCOPE-CAPACITY 0 4 PICK R@
    _O2S-GRANT-SPAN-STATUS ?DUP IF
        >R DROP R> R> DROP EXIT
    THEN
    DUP O2SESSION-G.SCOPE-A @
    OVER O2SESSION-G.SCOPE-U @
    O2SESSION-GRANT-F-SCOPE
    3 PICK O2SESSION-G.FLAGS @
    _O2S-FLAG-CONSISTENT? 0= IF
        DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN

    DUP O2SESSION-G.ID-A @
    OVER O2SESSION-G.ID-U @
    O2TOK-ID-CAPACITY 0 4 PICK R@
    _O2S-GRANT-SPAN-STATUS ?DUP IF
        >R DROP R> R> DROP EXIT
    THEN
    DUP O2SESSION-G.ID-A @
    OVER O2SESSION-G.ID-U @
    O2SESSION-GRANT-F-ID
    3 PICK O2SESSION-G.FLAGS @
    _O2S-FLAG-CONSISTENT? 0= IF
        DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN

    DUP O2SESSION-G.EXPIRES-AT-MS @
    DUP 0< IF
        2DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    OVER O2SESSION-G.FLAGS @
    O2SESSION-GRANT-F-EXPIRY AND IF
        DROP
    ELSE
        IF
            DROP R> DROP O2SESSION-S-INVALID EXIT
        THEN
    THEN

    DROP R> DROP O2SESSION-S-OK ;

