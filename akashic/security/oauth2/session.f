    THEN
    _O2SR-H-TYPE-U R@ _O2S-R-H@
    O2SESSION-TOKEN-TYPE-CAPACITY _O2S-REQUIRED-LENGTH? 0= IF
        R> DROP 0 EXIT
    THEN
    _O2SR-H-SCOPE-U R@ _O2S-R-H@
    O2SESSION-SCOPE-CAPACITY _O2S-OPTIONAL-LENGTH? 0= IF
        R> DROP 0 EXIT
    THEN
    _O2SR-H-ACCESS-U R@ _O2S-R-H@
    O2TOK-ACCESS-CAPACITY _O2S-REQUIRED-LENGTH? 0= IF
        R> DROP 0 EXIT
    THEN
    _O2SR-H-REFRESH-U R@ _O2S-R-H@
    O2TOK-REFRESH-CAPACITY _O2S-OPTIONAL-LENGTH? 0= IF
        R> DROP 0 EXIT
    THEN
    _O2SR-H-ID-U R@ _O2S-R-H@
    O2TOK-ID-CAPACITY _O2S-OPTIONAL-LENGTH?
    R> DROP ;

: _O2S-RECORD-FLAGS-VALID?  ( session -- flag )
    >R
    _O2SR-H-FLAGS R@ _O2S-R-H@
    O2SESSION-GRANT-F-REFRESH AND 0<>
    _O2SR-H-REFRESH-U R@ _O2S-R-H@ 0<> = 0= IF
        R> DROP 0 EXIT
    THEN
    _O2SR-H-FLAGS R@ _O2S-R-H@
    O2SESSION-GRANT-F-SCOPE AND 0<>
    _O2SR-H-SCOPE-U R@ _O2S-R-H@ 0<> = 0= IF
        R> DROP 0 EXIT
    THEN
    _O2SR-H-FLAGS R@ _O2S-R-H@
    O2SESSION-GRANT-F-ID AND 0<>
    _O2SR-H-ID-U R@ _O2S-R-H@ 0<> = 0= IF
        R> DROP 0 EXIT
    THEN
    _O2SR-H-FLAGS R@ _O2S-R-H@
    O2SESSION-GRANT-F-EXPIRY AND 0= IF
        _O2SR-H-EXPIRES R@ _O2S-R-H@ IF
            R> DROP 0 EXIT
        THEN
    THEN
    _O2SR-H-PHASE R@ _O2S-R-H@
    O2SESSION-PHASE-ACTIVE <> IF
        _O2SR-H-FLAGS R@ _O2S-R-H@
        O2SESSION-GRANT-F-REFRESH AND 0= IF
            R> DROP 0 EXIT
        THEN
    THEN
    R> DROP -1 ;

: _O2S-RECORD-BINDING-VALID?  ( session -- flag )
    >R
    R@ _O2S-R.BINDING
    _O2SR-H-BINDING-U R@ _O2S-R-H@
    R@ _O2S.BINDING R@ _O2S.BINDING-U @
    COMPARE 0= IF
        R@ _O2S-R.ISSUER
        _O2SR-H-ISSUER-U R@ _O2S-R-H@
        R@ _O2S.ISSUER R@ _O2S.ISSUER-U @
        COMPARE 0=
    ELSE
        0
    THEN
    R> DROP ;

: _O2S-RECORD-PADDING-VALID?  ( session -- flag )
    >R
    R@ _O2S-R.BINDING
    _O2SR-H-BINDING-U R@ _O2S-R-H@
    O2SESSION-BINDING-CAPACITY _O2S-CANONICAL-ARENA? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _O2S-R.ISSUER
    _O2SR-H-ISSUER-U R@ _O2S-R-H@
    O2SESSION-ISSUER-CAPACITY _O2S-CANONICAL-ARENA? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _O2S-R.TYPE
    _O2SR-H-TYPE-U R@ _O2S-R-H@
    O2SESSION-TOKEN-TYPE-CAPACITY _O2S-CANONICAL-ARENA? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _O2S-R.SCOPE
    _O2SR-H-SCOPE-U R@ _O2S-R-H@
    O2SESSION-SCOPE-CAPACITY _O2S-CANONICAL-ARENA? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _O2S-R.ACCESS
    _O2SR-H-ACCESS-U R@ _O2S-R-H@
    O2TOK-ACCESS-CAPACITY _O2S-CANONICAL-ARENA? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _O2S-R.REFRESH
    _O2SR-H-REFRESH-U R@ _O2S-R-H@
    O2TOK-REFRESH-CAPACITY _O2S-CANONICAL-ARENA? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _O2S-R.ID
    _O2SR-H-ID-U R@ _O2S-R-H@
    O2TOK-ID-CAPACITY _O2S-CANONICAL-ARENA?
    R> DROP ;

: _O2S-RECORD-VALID?  ( session -- flag )
    DUP _O2S-RECORD-HEADER-VALID? 0= IF DROP 0 EXIT THEN
    DUP _O2S-RECORD-LENGTHS-VALID? 0= IF DROP 0 EXIT THEN
    DUP _O2S-RECORD-FLAGS-VALID? 0= IF DROP 0 EXIT THEN
    DUP _O2S-RECORD-BINDING-VALID? 0= IF DROP 0 EXIT THEN
    _O2S-RECORD-PADDING-VALID? ;

: _O2S-RECORD-HEADER-BUILD  ( grant phase session -- )
    >R
    DUP R@ _O2S.OP-RESULT !
    DROP
    _O2SR-MAGIC _O2SR-H-MAGIC R@ _O2S-R-H!
    _O2SR-VERSION _O2SR-H-VERSION R@ _O2S-R-H!
    O2SESSION-RECORD-HEADER-SIZE
        _O2SR-H-HEADER-U R@ _O2S-R-H!
    O2SESSION-RECORD-SIZE _O2SR-H-TOTAL-U R@ _O2S-R-H!
    R@ _O2S.OP-RESULT @ _O2SR-H-PHASE R@ _O2S-R-H!
    DUP O2SESSION-G.FLAGS @
        _O2SR-H-FLAGS R@ _O2S-R-H!
    R@ _O2S.BINDING-U @
        _O2SR-H-BINDING-U R@ _O2S-R-H!
    R@ _O2S.ISSUER-U @
        _O2SR-H-ISSUER-U R@ _O2S-R-H!
    DUP O2SESSION-G.TOKEN-TYPE-U @
        _O2SR-H-TYPE-U R@ _O2S-R-H!
    DUP O2SESSION-G.SCOPE-U @
        _O2SR-H-SCOPE-U R@ _O2S-R-H!
    DUP O2SESSION-G.ACCESS-U @
        _O2SR-H-ACCESS-U R@ _O2S-R-H!
    DUP O2SESSION-G.REFRESH-U @
        _O2SR-H-REFRESH-U R@ _O2S-R-H!
    DUP O2SESSION-G.ID-U @
        _O2SR-H-ID-U R@ _O2S-R-H!
    DUP O2SESSION-G.EXPIRES-AT-MS @
        _O2SR-H-EXPIRES R@ _O2S-R-H!
    0 _O2SR-H-RESERVED0 R@ _O2S-R-H!
    0 _O2SR-H-RESERVED1 R@ _O2S-R-H!
    DROP R> DROP ;

: _O2S-RECORD-BUILD  ( grant phase session -- )
    >R
    R@ _O2S.RECORD O2SESSION-RECORD-SIZE 0 FILL
    2DUP R@ _O2S-RECORD-HEADER-BUILD

    R@ _O2S.BINDING R@ _O2S-R.BINDING
    R@ _O2S.BINDING-U @ MOVE
    R@ _O2S.ISSUER R@ _O2S-R.ISSUER
    R@ _O2S.ISSUER-U @ MOVE

    DROP
    DUP O2SESSION-G.TOKEN-TYPE-A @ R@ _O2S-R.TYPE
    2 PICK O2SESSION-G.TOKEN-TYPE-U @ MOVE
    DUP O2SESSION-G.ACCESS-A @ R@ _O2S-R.ACCESS
    2 PICK O2SESSION-G.ACCESS-U @ MOVE
    DUP O2SESSION-G.FLAGS @ O2SESSION-GRANT-F-REFRESH AND IF
        DUP O2SESSION-G.REFRESH-A @ R@ _O2S-R.REFRESH
        2 PICK O2SESSION-G.REFRESH-U @ MOVE
    THEN
    DUP O2SESSION-G.FLAGS @ O2SESSION-GRANT-F-SCOPE AND IF
        DUP O2SESSION-G.SCOPE-A @ R@ _O2S-R.SCOPE
        2 PICK O2SESSION-G.SCOPE-U @ MOVE
    THEN
    DUP O2SESSION-G.FLAGS @ O2SESSION-GRANT-F-ID AND IF
        DUP O2SESSION-G.ID-A @ R@ _O2S-R.ID
        2 PICK O2SESSION-G.ID-U @ MOVE
    THEN
    DROP R> DROP ;

\ =====================================================================
\  Session shape, initialization, locking, and cleanup
\ =====================================================================

: _O2S-INITIALIZED?  ( session -- flag )
    DUP _O2S.MAGIC @ _O2S-MAGIC-VALUE =
    SWAP _O2S.GUARD GUARD-SPIN? AND ;

: _O2S-IMMUTABLE-SHAPE?  ( session -- flag )
    DUP _O2S.BINDING-U @
    O2SESSION-BINDING-CAPACITY _O2S-REQUIRED-LENGTH? 0= IF
        DROP 0 EXIT
    THEN
    DUP _O2S.ISSUER-U @
    O2SESSION-ISSUER-CAPACITY _O2S-REQUIRED-LENGTH? 0= IF
        DROP 0 EXIT
    THEN
    DUP _O2S.RID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP _O2S.BINDING OVER _O2S.BINDING-U @
    O2SESSION-BINDING-CAPACITY _O2S-CANONICAL-ARENA? 0= IF
        DROP 0 EXIT
    THEN
    DUP _O2S.ISSUER SWAP _O2S.ISSUER-U @
    O2SESSION-ISSUER-CAPACITY _O2S-CANONICAL-ARENA? ;

: _O2S-PUBLISHED-SHAPE?  ( session -- flag )
    >R
    R@ _O2S.FLAGS @
    _O2S-F-VAULT-BLOCKED _O2S-F-CACHE-ERROR OR AND IF
        R@ _O2S.PHASE @ O2SESSION-PHASE-EMPTY =
        R@ _O2S.TYPE-U @ 0= AND
        R@ _O2S.SCOPE-U @ 0= AND
        R> DROP EXIT
    THEN
    R@ _O2S.FLAGS @ _O2S-F-REVOKED AND IF
        R@ _O2S.PHASE @ O2SESSION-PHASE-EMPTY =
        R@ _O2S.TYPE-U @ 0= AND
        R@ _O2S.SCOPE-U @ 0= AND
        R> DROP EXIT
    THEN
    R@ _O2S.GENERATION @ 0= IF
        R@ _O2S.PHASE @ O2SESSION-PHASE-EMPTY =
        R@ _O2S.TYPE-U @ 0= AND
        R@ _O2S.SCOPE-U @ 0= AND
        R> DROP EXIT
    THEN
    R@ _O2S.PHASE @ _O2S-PHASE-VALID? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _O2S.TYPE-U @
    O2SESSION-TOKEN-TYPE-CAPACITY _O2S-REQUIRED-LENGTH? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _O2S.SCOPE-U @
    O2SESSION-SCOPE-CAPACITY _O2S-OPTIONAL-LENGTH? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _O2S.RECORD-FLAGS @
    DUP 0< IF DROP R> DROP 0 EXIT THEN
    DUP _O2S-GRANT-F-KNOWN INVERT AND IF
        DROP R> DROP 0 EXIT
    THEN
    DUP O2SESSION-GRANT-F-SCOPE AND 0<>
    R@ _O2S.SCOPE-U @ 0<> = 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP O2SESSION-GRANT-F-EXPIRY AND 0= IF
        R@ _O2S.EXPIRES @ IF
            DROP R> DROP 0 EXIT
        THEN
    THEN
    R@ _O2S.PHASE @ O2SESSION-PHASE-ACTIVE <> IF
        O2SESSION-GRANT-F-REFRESH AND 0= IF
            R> DROP 0 EXIT
        THEN
    ELSE
        DROP
    THEN
    R@ _O2S.TYPE R@ _O2S.TYPE-U @
    O2SESSION-TOKEN-TYPE-CAPACITY _O2S-CANONICAL-ARENA? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _O2S.SCOPE R@ _O2S.SCOPE-U @
    O2SESSION-SCOPE-CAPACITY _O2S-CANONICAL-ARENA?
    R> DROP ;

: _O2S-OBJECT-STATUS  ( session -- status )
    DUP OAUTH2-SESSION-SIZE _O2S-ADMIT-SPAN
    ?DUP IF NIP EXIT THEN
    DUP _O2S-INITIALIZED? 0= IF
        DROP O2SESSION-S-INVALID EXIT
    THEN
    DUP _O2S.FLAGS @
    DUP _O2S-F-CONFIGURED AND 0= IF
        2DROP O2SESSION-S-INVALID EXIT
    THEN
    DUP _O2S-F-KNOWN INVERT AND IF
        2DROP O2SESSION-S-INVALID EXIT
    THEN
    DROP
    DUP _O2S.VAULT @ 0= IF DROP O2SESSION-S-INVALID EXIT THEN
    DUP _O2S-IMMUTABLE-SHAPE? 0= IF
        DROP O2SESSION-S-INVALID EXIT
    THEN
    _O2S-PUBLISHED-SHAPE? IF
        O2SESSION-S-OK
    ELSE
        O2SESSION-S-INVALID
    THEN ;

: _O2S-CLEAR-TRANSIENT  ( session -- )
    DUP _O2S-CALLBACK-XT + 96 0 FILL
    _O2S.RECORD O2SESSION-RECORD-SIZE 0 FILL ;

: _O2S-CLEAR-PUBLISHED  ( session -- )
    >R
    R@ _O2S.TOKENS O2TOK-CLEAR? DROP
    R@ _O2S.TYPE O2SESSION-TOKEN-TYPE-CAPACITY 0 FILL
    R@ _O2S.SCOPE O2SESSION-SCOPE-CAPACITY 0 FILL
    0 R@ _O2S.TYPE-U !
    0 R@ _O2S.SCOPE-U !
    0 R@ _O2S.PHASE !
    0 R@ _O2S.RECORD-FLAGS !
    0 R@ _O2S.EXPIRES !
    R> DROP ;

: _O2S-OP-BEGIN  ( session -- status )
    DUP _O2S-OBJECT-STATUS ?DUP IF NIP EXIT THEN
    DUP _O2S.GUARD GUARD-TRY-ACQUIRE 0= IF
        DROP O2SESSION-S-BUSY EXIT
    THEN
    DUP _O2S.FLAGS @ _O2S-F-BUSY AND IF
        DUP _O2S.GUARD GUARD-RELEASE
        DROP O2SESSION-S-BUSY EXIT
    THEN
    DUP _O2S.FLAGS DUP @ _O2S-F-BUSY OR SWAP !
    DROP O2SESSION-S-OK ;

: _O2S-FINISH  ( status session -- status )
    >R
    DUP O2SESSION-STATUS-VALID? 0= IF
        DROP O2SESSION-S-INTERNAL
    THEN
    DUP R@ _O2S.LAST-STATUS !
    R@ _O2S-CLEAR-TRANSIENT
    R@ _O2S.FLAGS DUP @ _O2S-F-BUSY INVERT AND SWAP !
    R@ _O2S.GUARD GUARD-RELEASE
    R> DROP ;

: _O2S-CONFIG-SOURCE-STATUS
  ( address length capacity config session -- status )
    >R
    3 PICK 3 PICK _O2S-ADMIT-SPAN ?DUP IF
        >R 2DROP 2DROP R> R> DROP EXIT
    THEN
    2 PICK 0= IF
        2DROP 2DROP R> DROP O2SESSION-S-ABSENT EXIT
    THEN
    2 PICK 2 PICK U> IF
        2DROP 2DROP R> DROP O2SESSION-S-CAPACITY EXIT
    THEN
    >R DROP R>
    2 PICK 2 PICK 2 PICK O2SESSION-CONFIG-SIZE
    MSPAN-OVERLAP? IF
        2DROP DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    2 PICK 2 PICK R@ OAUTH2-SESSION-SIZE MSPAN-OVERLAP? IF
        2DROP DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    2 PICK 2 PICK 2 PICK O2SESSION-C.VAULT @ CVAULT-SIZE
    MSPAN-OVERLAP? IF
        2DROP DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    2DROP DROP R> DROP O2SESSION-S-OK ;

: _O2S-CONFIG-STATUS  ( config session -- status )
    >R
    DUP O2SESSION-CONFIG-SIZE _O2S-ADMIT-SPAN
    ?DUP IF NIP R> DROP EXIT THEN
    R@ OAUTH2-SESSION-SIZE _O2S-ADMIT-SPAN
    ?DUP IF NIP R> DROP EXIT THEN
    DUP O2SESSION-CONFIG-SIZE
    R@ OAUTH2-SESSION-SIZE MSPAN-OVERLAP? IF
        DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    DUP O2SESSION-C.VAULT @ ?DUP 0= IF
        DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    DUP CVAULT-VALID? 0= IF
        2DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    DUP CVAULT-SECRET-CAPACITY@
    DUP IF
        >R 2DROP DROP R>
        CVAULT-S-BUSY = IF
            R> DROP O2SESSION-S-BUSY
        ELSE
            R> DROP O2SESSION-S-INVALID
        THEN
        EXIT
    THEN
    DROP
    DUP O2SESSION-RECORD-SIZE U< IF
        2DROP DROP R> DROP O2SESSION-S-CAPACITY EXIT
    THEN
    DROP
    DUP CVAULT-SIZE
    R@ OAUTH2-SESSION-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    DUP CVAULT-SIZE 3 PICK O2SESSION-CONFIG-SIZE
    MSPAN-OVERLAP? IF
        2DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    DROP

    DUP O2SESSION-C.RID @ ?DUP 0= IF
        DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    DUP RID-SIZE _O2S-ADMIT-SPAN ?DUP IF
        >R 2DROP R> R> DROP EXIT
    THEN
    DUP RID-PRESENT? 0= IF
        2DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    DUP RID-SIZE R@ OAUTH2-SESSION-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    DUP RID-SIZE 3 PICK O2SESSION-CONFIG-SIZE
    MSPAN-OVERLAP? IF
        2DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    DUP RID-SIZE 3 PICK O2SESSION-C.VAULT @ CVAULT-SIZE
    MSPAN-OVERLAP? IF
        2DROP R> DROP O2SESSION-S-INVALID EXIT
    THEN
    DROP

    DUP O2SESSION-C.BINDING-A @
    OVER O2SESSION-C.BINDING-U @
    O2SESSION-BINDING-CAPACITY 3 PICK R@
    _O2S-CONFIG-SOURCE-STATUS ?DUP IF
        >R DROP R> R> DROP EXIT
    THEN
    DUP O2SESSION-C.ISSUER-A @
    OVER O2SESSION-C.ISSUER-U @
    O2SESSION-ISSUER-CAPACITY 3 PICK R@
    _O2S-CONFIG-SOURCE-STATUS ?DUP IF
        >R DROP R> R> DROP EXIT
    THEN
    DROP R> DROP O2SESSION-S-OK ;

: O2SESSION-INIT  ( config session -- status )
    2DUP _O2S-CONFIG-STATUS ?DUP IF
        >R 2DROP R> EXIT
    THEN
    DUP _O2S-INITIALIZED? IF
        2DROP O2SESSION-S-INVALID EXIT
    THEN
    >R
    R@ OAUTH2-SESSION-SIZE 0 FILL
    _O2S-MAGIC-VALUE R@ _O2S.MAGIC !
    _O2S-F-CONFIGURED R@ _O2S.FLAGS !
    O2SESSION-S-OK R@ _O2S.LAST-STATUS !
    DUP O2SESSION-C.VAULT @ R@ _O2S.VAULT !
    DUP O2SESSION-C.RID @ R@ _O2S.RID RID-SIZE MOVE
    DUP O2SESSION-C.BINDING-A @ R@ _O2S.BINDING
    2 PICK O2SESSION-C.BINDING-U @ MOVE
    DUP O2SESSION-C.BINDING-U @ R@ _O2S.BINDING-U !
    DUP O2SESSION-C.ISSUER-A @ R@ _O2S.ISSUER
    2 PICK O2SESSION-C.ISSUER-U @ MOVE
    O2SESSION-C.ISSUER-U @ R@ _O2S.ISSUER-U !
    R@ _O2S.TOKENS O2TOK-INIT?
    DUP O2TOK-S-OK <> IF
        DROP R@ OAUTH2-SESSION-SIZE 0 FILL
        R> DROP O2SESSION-S-INTERNAL EXIT
    THEN
    DROP R> DROP O2SESSION-S-OK ;

