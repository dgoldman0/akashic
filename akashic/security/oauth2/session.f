: _O2S-VAULT-CONSUMER
  \ ( secret-a secret-u kind generation session -- consumer-result )
    >R
    DUP R@ _O2S.OP-GENERATION ! DROP
    DUP R@ _O2S.OP-KIND ! DROP
    DUP O2SESSION-RECORD-SIZE <> IF
        2DROP R> DROP O2SESSION-S-FORMAT EXIT
    THEN
