    DROP
    R@ _O2S-CLEAR-PUBLISHED
    0 R@ _O2S.GENERATION !
    R@ _O2S.FLAGS DUP @
    _O2S-F-REVOKED _O2S-F-CACHE-ERROR OR INVERT AND SWAP !
