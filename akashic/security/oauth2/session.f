    THEN
    R@ _O2S.VAULT @ CVAULT-BLOCKED? IF
        R@ _O2S-CLEAR-PUBLISHED
        R@ _O2S.FLAGS DUP @
        _O2S-F-REVOKED _O2S-F-CACHE-ERROR OR INVERT AND
        _O2S-F-VAULT-BLOCKED OR SWAP !
    THEN
    _O2S-CVAULT>STATUS
    R> DROP ;

