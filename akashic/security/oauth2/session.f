: O2SESSION-VALID?  ( session -- flag )
    _O2S-OBJECT-STATUS O2SESSION-S-OK = ;

: O2SESSION-STATE@
  ( session -- generation phase status )
    DUP >R
    R@ _O2S-OP-BEGIN ?DUP IF
        R> DROP NIP _O2S-ZERO-OPEN EXIT
    THEN
    DROP
    R@ _O2S-PUBLISHED-STATUS
    R@ _O2S-COMPLETE-OPEN
    R> DROP ;

: _O2S-COMPLETE-EXPIRY
  ( status session -- expires-at-ms known? status )
    >R
    DUP O2SESSION-S-OK = IF
        R@ _O2S.EXPIRES @
        R@ _O2S.RECORD-FLAGS @
        O2SESSION-GRANT-F-EXPIRY AND 0<>
    ELSE
        0 0
    THEN
    2 PICK R@ _O2S-FINISH
    >R >R >R DROP R> R> R>
    R> DROP ;

: O2SESSION-EXPIRY@
  ( session -- expires-at-ms known? status )
    DUP >R
    R@ _O2S-OP-BEGIN ?DUP IF
        R> DROP NIP
        >R 0 0 R> EXIT
    THEN
    DROP
    R@ _O2S-PUBLISHED-STATUS
    R@ _O2S-COMPLETE-EXPIRY
    R> DROP ;

: O2SESSION-EXPIRED?
  ( now-ms session -- expired? known? status )
    >R
    DUP 0< IF
        DROP R> DROP 0 0 O2SESSION-S-INVALID EXIT
    THEN
    R@ O2SESSION-EXPIRY@
    DUP IF
        >R 2DROP DROP
        0 0 R> R> DROP EXIT
    THEN
    DROP
    DUP 0= IF
        DROP 2DROP
        R> DROP 0 0 O2SESSION-S-OK EXIT
    THEN
    DROP
    U< 0=
    -1 O2SESSION-S-OK
    R> DROP ;

: _O2S-WITH-METADATA
  \ ( callback callback-context selector session
  \   -- callback-result status )
    >R
    2 PICK 0= IF
        2DROP DROP R> DROP
        0 O2SESSION-S-INVALID EXIT
    THEN
    R@ _O2S-OP-BEGIN ?DUP IF
        >R 2DROP DROP R> R> DROP
        0 SWAP EXIT
    THEN
    2 PICK R@ _O2S.CALLBACK-XT !
    1 PICK R@ _O2S.CALLBACK-CONTEXT !
    DUP R@ _O2S.OP-RESULT !
    2DROP DROP
    0 R@ _O2S.CALLBACK-RESULT !

    R@ _O2S.OP-RESULT @
    CASE
        0 OF
            R@ _O2S.RID R@ _O2S.OP-GRANT !
            RID-SIZE R@ _O2S.OP-EXPECTED !
            O2SESSION-S-OK
        ENDOF
        1 OF
            R@ _O2S.BINDING R@ _O2S.OP-GRANT !
            R@ _O2S.BINDING-U @ R@ _O2S.OP-EXPECTED !
            O2SESSION-S-OK
        ENDOF
        2 OF
            R@ _O2S.ISSUER R@ _O2S.OP-GRANT !
            R@ _O2S.ISSUER-U @ R@ _O2S.OP-EXPECTED !
            O2SESSION-S-OK
        ENDOF
        3 OF
            R@ _O2S-PUBLISHED-STATUS DUP IF
            ELSE
                DROP
                R@ _O2S.TYPE R@ _O2S.OP-GRANT !
                R@ _O2S.TYPE-U @ R@ _O2S.OP-EXPECTED !
                O2SESSION-S-OK
            THEN
        ENDOF
        4 OF
            R@ _O2S-PUBLISHED-STATUS DUP IF
            ELSE
                DROP
                R@ _O2S.SCOPE-U @ 0= IF
                    O2SESSION-S-ABSENT
                ELSE
                    R@ _O2S.SCOPE R@ _O2S.OP-GRANT !
                    R@ _O2S.SCOPE-U @ R@ _O2S.OP-EXPECTED !
                    O2SESSION-S-OK
                THEN
            THEN
        ENDOF
        O2SESSION-S-INVALID SWAP
    ENDCASE
    DUP IF
        R@ _O2S-COMPLETE-CALLBACK R> DROP EXIT
    THEN
    DROP
    R@ _O2S-CALLBACK-SAFE
    R@ _O2S.CALLBACK-STATUS !
    R@ _O2S.CALLBACK-RESULT !
    R@ _O2S.CALLBACK-STATUS @
    R@ _O2S-COMPLETE-CALLBACK
    R> DROP ;

: O2SESSION-WITH-RID
  ( callback callback-context session -- callback-result status )
    0 SWAP _O2S-WITH-METADATA ;

: O2SESSION-WITH-BINDING
  ( callback callback-context session -- callback-result status )
    1 SWAP _O2S-WITH-METADATA ;

: O2SESSION-WITH-ISSUER
  ( callback callback-context session -- callback-result status )
    2 SWAP _O2S-WITH-METADATA ;

: O2SESSION-WITH-TOKEN-TYPE
  ( callback callback-context session -- callback-result status )
    3 SWAP _O2S-WITH-METADATA ;

: O2SESSION-WITH-SCOPE
  ( callback callback-context session -- callback-result status )
    4 SWAP _O2S-WITH-METADATA ;

