        R@ _O2S-MARK-VAULT-RESULT
        R@ _O2S-COMPLETE-GENERATION
        R> DROP EXIT
    THEN
    DROP
    R@ _O2S-HYDRATE
    R@ _O2S-COMPLETE-GENERATION
    R> DROP ;

: O2SESSION-CLOSE  ( session -- status )
    DUP >R
    R@ _O2S-OP-BEGIN ?DUP IF
        R> DROP NIP EXIT
    THEN
    DROP
    R@ _O2S-CLEAR-PUBLISHED
    0 R@ _O2S.GENERATION !
    R@ _O2S.FLAGS DUP @
    _O2S-F-VAULT-BLOCKED _O2S-F-REVOKED OR
    _O2S-F-CACHE-ERROR OR INVERT AND SWAP !
    O2SESSION-S-OK R@ _O2S-FINISH
    R> DROP ;

: O2SESSION-FINI  ( session -- status )
    DUP _O2S-OBJECT-STATUS ?DUP IF NIP EXIT THEN
    DUP _O2S.GUARD GUARD-TRY-ACQUIRE 0= IF
        DROP O2SESSION-S-BUSY EXIT
    THEN
    DUP _O2S.FLAGS @ _O2S-F-BUSY AND IF
        DUP _O2S.GUARD GUARD-RELEASE
        DROP O2SESSION-S-BUSY EXIT
    THEN
    DUP >R
    DROP
    R@ _O2S.TOKENS O2TOK-CLEAR?
    O2TOK-S-OK <> IF
        R@ _O2S.GUARD GUARD-RELEASE
        R> DROP O2SESSION-S-BUSY EXIT
    THEN
    0 R@ _O2S.MAGIC !
    0 R@ _O2S.FLAGS !
    R@ _O2S.GUARD GUARD-RELEASE
    R@ OAUTH2-SESSION-SIZE 0 FILL
    R> DROP O2SESSION-S-OK ;

