: _O2S-RECORD-HEADER-VALID?  ( session -- flag )
    DUP _O2S-RECORD-NUMERIC-SHAPE? 0= IF DROP 0 EXIT THEN
    DUP _O2SR-H-MAGIC SWAP _O2S-R-H@ _O2SR-MAGIC <> IF
        DROP 0 EXIT
    THEN
    DUP _O2SR-H-VERSION SWAP _O2S-R-H@ _O2SR-VERSION <> IF
        DROP 0 EXIT
    THEN
    DUP _O2SR-H-HEADER-U SWAP _O2S-R-H@
    O2SESSION-RECORD-HEADER-SIZE <> IF DROP 0 EXIT THEN
    DUP _O2SR-H-TOTAL-U SWAP _O2S-R-H@
    O2SESSION-RECORD-SIZE <> IF DROP 0 EXIT THEN
    DUP _O2SR-H-PHASE SWAP _O2S-R-H@
    _O2S-PHASE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _O2SR-H-FLAGS SWAP _O2S-R-H@
    DUP _O2S-GRANT-F-KNOWN INVERT AND IF
        2DROP 0 EXIT
    THEN
    DROP
    DUP _O2SR-H-RESERVED0 SWAP _O2S-R-H@ IF DROP 0 EXIT THEN
    DUP _O2SR-H-RESERVED1 SWAP _O2S-R-H@ IF DROP 0 EXIT THEN
    DROP -1 ;

