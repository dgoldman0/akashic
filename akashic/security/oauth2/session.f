        R> DROP EXIT
    THEN
    R@ _O2S.OP-GRANT @ O2SESSION-PHASE-ACTIVE
    R@ _O2S-RECORD-BUILD
    R@ _O2S-RECORD-VALID? 0= IF
        O2SESSION-S-INTERNAL R@ _O2S-COMPLETE-GENERATION
        R> DROP EXIT
    THEN

    R@ _O2S.RID R@ _O2S.OP-EXPECTED @
    R@ _O2S.RECORD O2SESSION-RECORD-SIZE
    R@ _O2S.VAULT @ CVAULT-REPLACE
    R@ _O2S.OP-STATUS !
    R@ _O2S.OP-GENERATION !
