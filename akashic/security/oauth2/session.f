    DUP O2SESSION-PHASE-ACTIVE R@ _O2S-RECORD-BUILD
    DROP
    R@ _O2S-RECORD-VALID? 0= IF
        O2SESSION-S-INTERNAL R@ _O2S-COMPLETE-GENERATION
        R> DROP EXIT
    THEN

    R@ _O2S.RID O2SESSION-CREDENTIAL-KIND
    R@ _O2S.RECORD O2SESSION-RECORD-SIZE
    R@ _O2S.VAULT @ CVAULT-CREATE
    R@ _O2S.OP-STATUS !
    R@ _O2S.OP-GENERATION !
    R@ _O2S.OP-STATUS @ DUP CVAULT-S-OK <> IF
        R@ _O2S-MARK-VAULT-RESULT
        R@ _O2S-COMPLETE-GENERATION
