\ =====================================================================
\  session.f - Durable provider-neutral OAuth 2 session ownership
\ =====================================================================
\  One caller-owned object binds an immutable OAuth client/profile identity
\  and issuer to one RID-addressed credential-vault record.  Access and
\  optional identity tokens are hydrated into the embedded token owner.
\  Refresh credentials remain only in the sealed record and the operation
\  buffer used by the durable refresh protocol.
\
\  Refresh use has three durable phases:
\    ACTIVE -> REFRESH-CLAIMED -> REFRESH-EXPOSED -> ACTIVE
\  CLAIMED may be aborted before exposure.  EXPOSED cannot return to ACTIVE
\  with the old credential: only committing a replacement grant,
\  reauthorizing, or revoking resolves it.  Every transition is persisted
\  before it is published in memory or exposed to an external callback.
\
\  This module owns no provider discovery, browser, HTTP, DPoP algorithm,
\  DPoP key, nonce, clock, AT Protocol, Streams, UI, or root key.
\ =====================================================================

