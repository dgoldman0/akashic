: _O2S-CALLER>STATUS  ( caller-status -- status )
    DUP CALLER-SPAN-S-OK = IF DROP O2SESSION-S-OK EXIT THEN
    DUP CALLER-SPAN-S-RANGE = IF DROP O2SESSION-S-RANGE EXIT THEN
    DUP CALLER-SPAN-S-PROTECTED = IF
        DROP O2SESSION-S-PROTECTED EXIT
    THEN
    DROP O2SESSION-S-PLATFORM ;

: _O2S-ADMIT-SPAN  ( address length -- status )
    CALLER-SPAN-STATUS _O2S-CALLER>STATUS ;

: _O2S-REQUIRED-LENGTH?  ( length capacity -- flag )
    OVER 0> IF U> 0= ELSE 2DROP 0 THEN ;

: _O2S-OPTIONAL-LENGTH?  ( length capacity -- flag )
    OVER 0< IF 2DROP 0 EXIT THEN
    U> 0= ;

: _O2S-PHASE-VALID?  ( phase -- flag )
    DUP O2SESSION-PHASE-ACTIVE =
    OVER O2SESSION-PHASE-REFRESH-CLAIMED = OR
    SWAP O2SESSION-PHASE-REFRESH-EXPOSED = OR ;

: _O2S-BE64!  ( nonnegative-u destination -- )
    >R
    DUP 56 RSHIFT 255 AND R@      C!
    DUP 48 RSHIFT 255 AND R@ 1+   C!
    DUP 40 RSHIFT 255 AND R@ 2 +  C!
    DUP 32 RSHIFT 255 AND R@ 3 +  C!
    DUP 24 RSHIFT 255 AND R@ 4 +  C!
    DUP 16 RSHIFT 255 AND R@ 5 +  C!
    DUP  8 RSHIFT 255 AND R@ 6 +  C!
        255 AND R@ 7 + C!
    R> DROP ;

: _O2S-BE64@  ( source -- nonnegative-u )
    >R
    R@     C@ 56 LSHIFT
    R@ 1+  C@ 48 LSHIFT OR
    R@ 2 + C@ 40 LSHIFT OR
    R@ 3 + C@ 32 LSHIFT OR
    R@ 4 + C@ 24 LSHIFT OR
    R@ 5 + C@ 16 LSHIFT OR
    R@ 6 + C@  8 LSHIFT OR
    R> 7 + C@ OR ;

: _O2S-BE64-NONNEGATIVE?  ( source -- flag )
    C@ 0x80 AND 0= ;

: _O2S-ZERO-SPAN?  ( address length -- flag )
    BEGIN
        DUP
    WHILE
        OVER C@ IF 2DROP 0 EXIT THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP -1 ;

: _O2S-CANONICAL-ARENA?  ( address used capacity -- flag )
    >R
    DUP >R
    +
    R> R> SWAP -
    _O2S-ZERO-SPAN? ;

: _O2S-FLAG-CONSISTENT?
  ( address length bit flags -- flag )
    AND IF
        NIP 0> EXIT
    THEN
    SWAP 0= SWAP 0= AND ;

