    THEN
    _O2SR-H-PHASE R@ _O2S-R-H@
    O2SESSION-PHASE-REFRESH-EXPOSED <> IF
        R> DROP O2SESSION-S-STATE EXIT
    THEN
    R@ _O2S.OP-GRANT @ R@ _O2S-REFRESH-APPLY
    ?DUP IF R> DROP EXIT THEN

    R@ _O2S.RID R@ _O2S.OP-EXPECTED @
    R@ _O2S.RECORD O2SESSION-RECORD-SIZE
    R@ _O2S.VAULT @ CVAULT-REPLACE
    R@ _O2S.OP-STATUS !
    R@ _O2S.OP-GENERATION !
    R@ _O2S.OP-STATUS @ DUP CVAULT-S-OK <> IF
        R@ _O2S-MARK-VAULT-RESULT R> DROP EXIT
    THEN
    DROP
    R@ _O2S-HYDRATE
    R> DROP ;

: O2SESSION-REFRESH-COMMIT
  ( grant expected-generation session -- generation status )
    2 PICK OVER _O2S-GRANT-STATUS ?DUP IF
        >R 2DROP DROP R> _O2S-ZERO-GENERATION EXIT
    THEN
    OVER 0> 0= IF
        2DROP DROP
        O2SESSION-S-INVALID _O2S-ZERO-GENERATION EXIT
    THEN
    DUP >R
    R@ _O2S-OP-BEGIN ?DUP IF
        >R 2DROP DROP R> R> DROP
        _O2S-ZERO-GENERATION EXIT
    THEN
    2 PICK R@ _O2S.OP-GRANT !
    OVER R@ _O2S.OP-EXPECTED !
    2DROP DROP
    R@ _O2S-REFRESH-COMMIT-BODY
    R@ _O2S-COMPLETE-GENERATION
    R> DROP ;

: O2SESSION-LOGOUT
  ( expected-generation session -- generation status )
    OVER 0> 0= IF
        2DROP O2SESSION-S-INVALID _O2S-ZERO-GENERATION EXIT
    THEN
    DUP >R
    R@ _O2S-OP-BEGIN ?DUP IF
        >R 2DROP R> R> DROP _O2S-ZERO-GENERATION EXIT
    THEN
    OVER R@ _O2S.OP-EXPECTED !
    2DROP
    R@ _O2S.OP-EXPECTED @ R@ _O2S-LOAD-EXPECTED
    ?DUP IF
        R@ _O2S-COMPLETE-GENERATION
        R> DROP EXIT
    THEN
    R@ _O2S.RID R@ _O2S.OP-EXPECTED @
    R@ _O2S.VAULT @ CVAULT-REVOKE
    R@ _O2S.OP-STATUS !
    R@ _O2S.OP-GENERATION !
    R@ _O2S.OP-STATUS @ DUP CVAULT-S-OK <> IF
        R@ _O2S-MARK-VAULT-RESULT
        R@ _O2S-COMPLETE-GENERATION
        R> DROP EXIT
    THEN
    DROP
    R@ _O2S-CLEAR-PUBLISHED
    R@ _O2S.OP-GENERATION @ R@ _O2S.GENERATION !
    R@ _O2S.FLAGS DUP @
    _O2S-F-VAULT-BLOCKED _O2S-F-CACHE-ERROR OR INVERT AND
    _O2S-F-REVOKED OR SWAP !
    O2SESSION-S-OK R@ _O2S-COMPLETE-GENERATION
    R> DROP ;

: O2SESSION-RECOVER  ( session -- generation phase status )
    DUP >R
    R@ _O2S-OP-BEGIN ?DUP IF
        R> DROP NIP _O2S-ZERO-OPEN EXIT
    THEN
    DROP
    R@ _O2S.RID R@ _O2S.VAULT @ CVAULT-RECOVER
    R@ _O2S.OP-STATUS !
    R@ _O2S.OP-RESULT !
    R@ _O2S.OP-GENERATION !

    R@ _O2S.OP-STATUS @ DUP CVAULT-S-OK = IF
        DROP
        R@ _O2S.OP-RESULT @ CVAULT-STATE-PRESENT <> IF
            O2SESSION-S-INTERNAL
            R@ _O2S-COMPLETE-OPEN R> DROP EXIT
        THEN
        R@ _O2S-LOAD
        DUP IF
            R@ _O2S-COMPLETE-OPEN R> DROP EXIT
        THEN
        DROP
        R@ _O2S-HYDRATE
        R@ _O2S-COMPLETE-OPEN R> DROP EXIT
    THEN
    R@ _O2S-MARK-VAULT-RESULT
    R@ _O2S-COMPLETE-OPEN
    R> DROP ;

