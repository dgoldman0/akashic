: OAUTH2-RESOURCE-METADATA-VALID?  ( metadata -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP OAUTH2-RESOURCE-METADATA-SIZE CALLER-SPAN-STATUS
        CALLER-SPAN-S-OK <> IF DROP 0 EXIT THEN
    DUP _O2RM.MAGIC @ _O2RM-MAGIC-VALUE <> IF DROP 0 EXIT THEN
    DUP _O2RM.PRESENCE @ DUP 0< IF 2DROP 0 EXIT THEN
    DUP OAUTH2-RESOURCE-METADATA-P-ALL > IF 2DROP 0 EXIT THEN
    OAUTH2-RESOURCE-METADATA-P-RESOURCE AND 0= IF
        DROP 0 EXIT
    THEN
    DUP _O2RM.RESOURCE-U @ _O2RM-TEXT-U? 0= IF DROP 0 EXIT THEN

    DUP _O2RM.AUTHORIZATION-SERVER-COUNT @
        DUP 0< IF 2DROP 0 EXIT THEN
    OAUTH2-RESOURCE-METADATA-MAX-AUTHORIZATION-SERVERS >
        IF DROP 0 EXIT THEN
    DUP _O2RM.AUTHORIZATION-SERVER-BYTES-U @
        DUP 0< IF 2DROP 0 EXIT THEN
    OAUTH2-RESOURCE-METADATA-AUTHORIZATION-SERVER-BYTES >
        IF DROP 0 EXIT THEN
    DUP _O2RM.PRESENCE @
        OAUTH2-RESOURCE-METADATA-P-AUTHORIZATION-SERVERS AND IF
        DUP _O2RM.AUTHORIZATION-SERVER-COUNT @ 0= IF
            DROP 0 EXIT
        THEN
        DUP _O2RM.AUTHORIZATION-SERVER-BYTES-U @ 0= IF
            DROP 0 EXIT
        THEN
    ELSE
        DUP _O2RM.AUTHORIZATION-SERVER-COUNT @ IF
            DROP 0 EXIT
        THEN
        DUP _O2RM.AUTHORIZATION-SERVER-BYTES-U @ IF
            DROP 0 EXIT
        THEN
    THEN
    DUP _O2RM-AUTHORIZATION-ENTRIES-VALID? 0= IF
        DROP 0 EXIT
    THEN
    DROP -1 ;

: OAUTH2-RESOURCE-METADATA-PRESENCE@
  ( metadata -- presence status )
    DUP OAUTH2-RESOURCE-METADATA-VALID? 0= IF
        DROP 0 OAUTH2-RESOURCE-METADATA-S-INVALID EXIT
    THEN
    _O2RM.PRESENCE @ OAUTH2-RESOURCE-METADATA-S-OK ;

: OAUTH2-RESOURCE-METADATA-RESOURCE@
  ( metadata -- address length status )
    DUP OAUTH2-RESOURCE-METADATA-VALID? 0= IF
        DROP 0 0 OAUTH2-RESOURCE-METADATA-S-INVALID EXIT
    THEN
    DUP _O2RM.RESOURCE
    SWAP _O2RM.RESOURCE-U @
    OAUTH2-RESOURCE-METADATA-S-OK ;

: OAUTH2-RESOURCE-METADATA-AUTHORIZATION-SERVER-COUNT@
  ( metadata -- count status )
    DUP OAUTH2-RESOURCE-METADATA-VALID? 0= IF
        DROP 0 OAUTH2-RESOURCE-METADATA-S-INVALID EXIT
    THEN
    DUP _O2RM.PRESENCE @
        OAUTH2-RESOURCE-METADATA-P-AUTHORIZATION-SERVERS AND 0= IF
        DROP 0 OAUTH2-RESOURCE-METADATA-S-MISSING EXIT
    THEN
    _O2RM.AUTHORIZATION-SERVER-COUNT @
    OAUTH2-RESOURCE-METADATA-S-OK ;

: OAUTH2-RESOURCE-METADATA-AUTHORIZATION-SERVER@
  ( index metadata -- address length status )
    DUP OAUTH2-RESOURCE-METADATA-VALID? 0= IF
        2DROP 0 0 OAUTH2-RESOURCE-METADATA-S-INVALID EXIT
    THEN
    DUP _O2RM.PRESENCE @
        OAUTH2-RESOURCE-METADATA-P-AUTHORIZATION-SERVERS AND 0= IF
        2DROP 0 0 OAUTH2-RESOURCE-METADATA-S-MISSING EXIT
    THEN
    OVER 0< IF
        2DROP 0 0 OAUTH2-RESOURCE-METADATA-S-INVALID EXIT
    THEN
    OVER OVER _O2RM.AUTHORIZATION-SERVER-COUNT @ >= IF
        2DROP 0 0 OAUTH2-RESOURCE-METADATA-S-INVALID EXIT
    THEN
    _O2RM-AUTHORIZATION-SERVER@
    OAUTH2-RESOURCE-METADATA-S-OK ;

