: _O2RM-JSON-WS?  ( byte -- flag )
    DUP 32 = IF DROP -1 EXIT THEN
    DUP 9 = IF DROP -1 EXIT THEN
    DUP 10 = IF DROP -1 EXIT THEN
    13 = ;

: _O2RM-ARRAY-C@  ( position workspace -- byte )
    DUP _O2RMW.VALUE-A @ ROT + C@ SWAP DROP ;

: _O2RM-ARRAY-SKIP-WS  ( workspace -- workspace )
    BEGIN
        DUP _O2RMW.ARRAY-POS @
        OVER _O2RMW.VALUE-U @ U<
    WHILE
        DUP _O2RMW.ARRAY-POS @
        OVER _O2RM-ARRAY-C@
        _O2RM-JSON-WS? 0= IF EXIT THEN
        1 OVER _O2RMW.ARRAY-POS +!
    REPEAT ;

: _O2RM-ARRAY-RESET  ( workspace -- )
    0 OVER _O2RMW.ARRAY-COUNT !
    0 SWAP _O2RMW.ARRAY-BYTES-U ! ;

: _O2RM-FIND-STRING-END  ( workspace -- status )
    BEGIN
        DUP _O2RMW.ARRAY-POS @
        OVER _O2RMW.VALUE-U @ U<
    WHILE
        DUP _O2RMW.ARRAY-POS @
        OVER _O2RM-ARRAY-C@
        DUP 34 = IF
            DROP
            1 OVER _O2RMW.ARRAY-POS +!
            DUP _O2RMW.ARRAY-POS @
            OVER _O2RMW.TOKEN-START @ -
            OVER _O2RMW.TOKEN-U !
            DROP OAUTH2-RESOURCE-METADATA-S-OK EXIT
        THEN
        92 = IF
            1 OVER _O2RMW.ARRAY-POS +!
            DUP _O2RMW.ARRAY-POS @
            OVER _O2RMW.VALUE-U @ U< 0= IF
                DROP OAUTH2-RESOURCE-METADATA-S-INTERNAL EXIT
            THEN
        THEN
        1 OVER _O2RMW.ARRAY-POS +!
    REPEAT
    DROP OAUTH2-RESOURCE-METADATA-S-INTERNAL ;

: _O2RM-DECODE-ARRAY-TOKEN  ( workspace -- status )
    >R
    R@ _O2RMW.VALUE-A @ R@ _O2RMW.TOKEN-START @ +
    R@ _O2RMW.TOKEN-U @
    R@ _O2RMW.SCRATCH OAUTH2-RESOURCE-METADATA-TEXT-CAPACITY
    R@ _O2RMW.JSON
    JOSE-JSON-STRING-DECODE
    DUP JOSE-JSON-S-OK <> IF
        DUP JOSE-JSON-S-CAPACITY = IF
            2DROP R> DROP
            OAUTH2-RESOURCE-METADATA-S-CAPACITY EXIT
        THEN
        2DROP R> DROP
        OAUTH2-RESOURCE-METADATA-S-INTERNAL EXIT
    THEN
    DROP
    DUP 0= IF
        DROP R> DROP OAUTH2-RESOURCE-METADATA-S-VALUE EXIT
    THEN
    R@ _O2RMW.DECODED-U !
    R> DROP OAUTH2-RESOURCE-METADATA-S-OK ;

