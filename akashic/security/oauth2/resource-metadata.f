: _O2RM-OFFSET-SPAN?  ( offset length bound -- flag )
    >R
    DUP 0< IF 2DROP R> DROP 0 EXIT THEN
    OVER 0< IF 2DROP R> DROP 0 EXIT THEN
    OVER R@ U> IF 2DROP R> DROP 0 EXIT THEN
    R@ ROT - U> 0=
    R> DROP ;

: _O2RM-TEXT-U?  ( length -- flag )
    DUP 0> SWAP OAUTH2-RESOURCE-METADATA-TEXT-CAPACITY <= AND ;

: _O2RM-AUTHORIZATION-ENTRIES-VALID?  ( metadata -- flag )
    DUP _O2RM.AUTHORIZATION-SERVER-COUNT @ 0 ?DO
        I OVER _O2RM-AUTHORIZATION-SERVER-ENTRY
        DUP _O2RME-OFFSET + @
        OVER _O2RME-U + @
        3 PICK _O2RM.AUTHORIZATION-SERVER-BYTES-U @
        _O2RM-OFFSET-SPAN? 0= IF
            2DROP 0 UNLOOP EXIT
        THEN
        _O2RME-U + @ _O2RM-TEXT-U? 0= IF
            DROP 0 UNLOOP EXIT
        THEN
        I 0= IF
            0 OVER _O2RM-AUTHORIZATION-SERVER-ENTRY
            _O2RME-OFFSET + @ IF
                DROP 0 UNLOOP EXIT
            THEN
        ELSE
            I OVER _O2RM-AUTHORIZATION-SERVER-ENTRY
            _O2RME-OFFSET + @
            I 1- 2 PICK _O2RM-AUTHORIZATION-SERVER-ENTRY
            DUP _O2RME-OFFSET + @
            SWAP _O2RME-U + @ + <> IF
                DROP 0 UNLOOP EXIT
            THEN
        THEN
    LOOP
    DUP _O2RM.AUTHORIZATION-SERVER-COUNT @ 0= IF
        DROP -1 EXIT
    THEN
    DUP _O2RM.AUTHORIZATION-SERVER-COUNT @ 1-
    OVER _O2RM-AUTHORIZATION-SERVER-ENTRY
    DUP _O2RME-OFFSET + @
    SWAP _O2RME-U + @ +
    OVER _O2RM.AUTHORIZATION-SERVER-BYTES-U @ =
    NIP ;

