: _O2RM-PARSE-ADMITTED
  ( source source-u metadata workspace -- status )
    DUP _O2RM-WIPE
    3 PICK OVER _O2RMW.SOURCE !
    2 PICK OVER _O2RMW.SOURCE-U !
    OVER OVER _O2RMW.OUTPUT !
    NIP NIP NIP
    _O2RM-PARSE-STAGE ;

: _O2RM-PUBLISH  ( workspace -- )
    0 OVER _O2RMW.OUTPUT @ _O2RM.MAGIC !
    DUP _O2RMW.STAGE 8 +
    OVER _O2RMW.OUTPUT @ 8 +
    OAUTH2-RESOURCE-METADATA-SIZE 8 - MOVE
    _O2RM-MAGIC-VALUE
    OVER _O2RMW.OUTPUT @ _O2RM.MAGIC !
    DROP ;

: _O2RM-PARSE-CALL
  ( source source-u metadata workspace xt -- status )
    1 PICK >R
    CATCH
    DUP IF
        DROP
        R@ _O2RM-WIPE
        _O2RM-DROP4
        R> DROP OAUTH2-RESOURCE-METADATA-S-INTERNAL EXIT
    THEN
    DROP
    DUP IF
        R@ _O2RM-WIPE
        R> DROP EXIT
    THEN
    DROP
    R@ ['] _O2RM-PUBLISH ['] _O2RM-WIPE
        _O2RM-CALL-FINALLY
    R> DROP
    OAUTH2-RESOURCE-METADATA-S-OK ;

: OAUTH2-RESOURCE-METADATA-PARSE
  ( source source-u metadata workspace -- status )
    3 PICK 3 PICK 3 PICK 3 PICK _O2RM-PARSE-GEOMETRY
    DUP IF
        >R _O2RM-DROP4 R> EXIT
    THEN
    DROP
    ['] _O2RM-PARSE-ADMITTED _O2RM-PARSE-CALL ;

