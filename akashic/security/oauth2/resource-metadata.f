\ =====================================================================
\  resource-metadata.f
\  Strict OAuth 2 protected-resource metadata parsing
\ =====================================================================
\  This module parses a caller-supplied RFC 9728 JSON object into a
\  fixed caller-owned result.  It retains the required `resource`
\  identifier and the optional bounded `authorization_servers` list.
\  Unknown members are accepted only after complete strict JSON
\  validation.
\
\  URI syntax, discovery URL construction, HTTP status and media policy,
\  redirect policy, resource-identifier binding, authorization-server
\  selection, AT Protocol, and application policy belong to higher
\  composition layers.
\
\  Public API:
\    OAUTH2-RESOURCE-METADATA-SIZE
\    OAUTH2-RESOURCE-METADATA-WORKSPACE-SIZE
\    OAUTH2-RESOURCE-METADATA-STATUS-VALID?
\    OAUTH2-RESOURCE-METADATA-VALID?
\    OAUTH2-RESOURCE-METADATA-WORKSPACE-CLEAR
\    OAUTH2-RESOURCE-METADATA-PARSE
\    OAUTH2-RESOURCE-METADATA-PRESENCE@
\    OAUTH2-RESOURCE-METADATA-RESOURCE@
\    OAUTH2-RESOURCE-METADATA-AUTHORIZATION-SERVER-COUNT@
\    OAUTH2-RESOURCE-METADATA-AUTHORIZATION-SERVER@
\ =====================================================================

