    DUP _O2RME-OFFSET + @
    SWAP _O2RME-U + @
    SWAP ROT + ROT DROP SWAP ;

: _O2RM-ARRAY-CONTAINS?  ( string-a string-u workspace -- flag )
    DUP _O2RMW.ARRAY-COUNT @ 0 ?DO
        2 PICK 2 PICK
        I 3 PICK _O2RM-ARRAY-ENTRY@
        COMPARE 0= IF
            2DROP DROP -1 UNLOOP EXIT
        THEN
    LOOP
    2DROP DROP 0 ;

: _O2RM-ARRAY-APPEND  ( workspace -- status )
    >R
    R@ _O2RMW.ARRAY-COUNT @
    OAUTH2-RESOURCE-METADATA-MAX-AUTHORIZATION-SERVERS >= IF
        R> DROP OAUTH2-RESOURCE-METADATA-S-CAPACITY EXIT
    THEN
    R@ _O2RMW.ARRAY-BYTES-U @
    R@ _O2RMW.DECODED-U @ +
    OAUTH2-RESOURCE-METADATA-AUTHORIZATION-SERVER-BYTES > IF
        R> DROP OAUTH2-RESOURCE-METADATA-S-CAPACITY EXIT
    THEN
    R@ _O2RMW.SCRATCH R@ _O2RMW.DECODED-U @ R@
    _O2RM-ARRAY-CONTAINS? IF
        R> DROP OAUTH2-RESOURCE-METADATA-S-DUPLICATE EXIT
    THEN

    R@ _O2RMW.ARRAY-COUNT @ R@ _O2RMW-ARRAY-ENTRY
    R@ _O2RMW.ARRAY-BYTES-U @ OVER _O2RME-OFFSET + !
    R@ _O2RMW.DECODED-U @ SWAP _O2RME-U + !

    R@ _O2RMW.SCRATCH
    R@ _O2RMW.ARRAY-BYTES
    R@ _O2RMW.ARRAY-BYTES-U @ +
    R@ _O2RMW.DECODED-U @ MOVE
    R@ _O2RMW.DECODED-U @ R@ _O2RMW.ARRAY-BYTES-U +!
    1 R@ _O2RMW.ARRAY-COUNT +!
    R> DROP OAUTH2-RESOURCE-METADATA-S-OK ;

: _O2RM-ARRAY-PARSE  ( workspace -- status )
    >R
    R@ _O2RM-ARRAY-RESET
    R@ _O2RMW.VALUE-U @ 2 U< IF
        R> DROP OAUTH2-RESOURCE-METADATA-S-INTERNAL EXIT
    THEN
    0 R@ _O2RM-ARRAY-C@ 91 <> IF
        R> DROP OAUTH2-RESOURCE-METADATA-S-INTERNAL EXIT
    THEN
    R@ _O2RMW.VALUE-U @ 1-
    R@ _O2RM-ARRAY-C@ 93 <> IF
        R> DROP OAUTH2-RESOURCE-METADATA-S-INTERNAL EXIT
    THEN
    1 R@ _O2RMW.ARRAY-POS !
    R@ _O2RM-ARRAY-SKIP-WS DROP
    R@ _O2RMW.ARRAY-POS @
    R@ _O2RMW.VALUE-U @ 1- = IF
        R> DROP OAUTH2-RESOURCE-METADATA-S-VALUE EXIT
    THEN

    BEGIN
        R@ _O2RMW.ARRAY-POS @
        R@ _O2RM-ARRAY-C@ 34 <> IF
            R> DROP OAUTH2-RESOURCE-METADATA-S-TYPE EXIT
        THEN
        R@ _O2RMW.ARRAY-POS @ R@ _O2RMW.TOKEN-START !
        1 R@ _O2RMW.ARRAY-POS +!
        R@ _O2RM-FIND-STRING-END
        DUP IF R> DROP EXIT THEN DROP
        R@ _O2RM-DECODE-ARRAY-TOKEN
        DUP IF R> DROP EXIT THEN DROP
        R@ _O2RM-ARRAY-APPEND
        DUP IF R> DROP EXIT THEN DROP

        R@ _O2RM-ARRAY-SKIP-WS DROP
        R@ _O2RMW.ARRAY-POS @
        R@ _O2RMW.VALUE-U @ U< 0= IF
            R> DROP OAUTH2-RESOURCE-METADATA-S-INTERNAL EXIT
        THEN
        R@ _O2RMW.ARRAY-POS @
        R@ _O2RM-ARRAY-C@
        DUP 93 = IF
            DROP
            1 R@ _O2RMW.ARRAY-POS +!
            R@ _O2RMW.ARRAY-POS @
            R@ _O2RMW.VALUE-U @ <> IF
                R> DROP OAUTH2-RESOURCE-METADATA-S-INTERNAL EXIT
            THEN
            R> DROP OAUTH2-RESOURCE-METADATA-S-OK EXIT
        THEN
        44 <> IF
            R> DROP OAUTH2-RESOURCE-METADATA-S-INTERNAL EXIT
        THEN
        1 R@ _O2RMW.ARRAY-POS +!
        R@ _O2RM-ARRAY-SKIP-WS DROP
        R@ _O2RMW.ARRAY-POS @
        R@ _O2RMW.VALUE-U @ 1- U< 0= IF
            R> DROP OAUTH2-RESOURCE-METADATA-S-INTERNAL EXIT
        THEN
    AGAIN ;

