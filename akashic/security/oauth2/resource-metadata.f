\ An operation/publication THROW is rethrown after successful cleanup.
\ Cleanup THROW propagates directly and therefore has precedence.
: _O2RM-CALL-FINALLY
  ( workspace operation-xt cleanup-xt -- results... )
    >R
    OVER >R
    CATCH
    DUP IF
        >R DROP
        R> R> R> EXECUTE
        THROW
    THEN
    DROP
    R> R> EXECUTE ;

