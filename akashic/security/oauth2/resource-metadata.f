: _O2RM-JSON>STATUS  ( json-status -- status )
    DUP JOSE-JSON-S-OK = IF
        DROP OAUTH2-RESOURCE-METADATA-S-OK EXIT
    THEN
    DUP JOSE-JSON-S-DUPLICATE = IF
        DROP OAUTH2-RESOURCE-METADATA-S-DUPLICATE EXIT
    THEN
    DUP JOSE-JSON-S-CAPACITY = IF
        DROP OAUTH2-RESOURCE-METADATA-S-CAPACITY EXIT
    THEN
    DUP JOSE-JSON-S-MEMBERS = IF
        DROP OAUTH2-RESOURCE-METADATA-S-CAPACITY EXIT
    THEN
    DUP JOSE-JSON-S-STRING = IF
        DROP OAUTH2-RESOURCE-METADATA-S-CAPACITY EXIT
    THEN
    DUP JOSE-JSON-S-DOCUMENT = IF
        DROP OAUTH2-RESOURCE-METADATA-S-CAPACITY EXIT
    THEN
    DUP JOSE-JSON-S-SYNTAX = IF
        DROP OAUTH2-RESOURCE-METADATA-S-JSON EXIT
    THEN
    DUP JOSE-JSON-S-UTF8 = IF
        DROP OAUTH2-RESOURCE-METADATA-S-JSON EXIT
    THEN
    DUP JOSE-JSON-S-DEPTH = IF
        DROP OAUTH2-RESOURCE-METADATA-S-JSON EXIT
    THEN
    DROP OAUTH2-RESOURCE-METADATA-S-INTERNAL ;

: _O2RM-MEMBER-LOAD  ( index workspace -- status )
    >R
    R@ _O2RMW.DESCRIPTOR JOSE-JSON-OBJECT-MEMBER@
    DUP JOSE-JSON-S-OK <> IF
        2DROP 2DROP 2DROP
        R> DROP OAUTH2-RESOURCE-METADATA-S-INTERNAL EXIT
    THEN
    DROP
    R@ _O2RMW.VALUE-TYPE !
    R@ _O2RMW.VALUE-U !
    R@ _O2RMW.SOURCE @ + R@ _O2RMW.VALUE-A !
    R@ _O2RMW.NAME-U !
    R@ _O2RMW.NAMES + R@ _O2RMW.NAME-A !
    R> DROP OAUTH2-RESOURCE-METADATA-S-OK ;

: _O2RM-NAME=  ( expected-a expected-u workspace -- flag )
    >R
    R@ _O2RMW.NAME-A @ R@ _O2RMW.NAME-U @
    2SWAP COMPARE 0=
    R> DROP ;

: _O2RM-COPY-MEMBER-STRING
  ( destination length-cell workspace -- status )
    >R
    R@ _O2RMW.VALUE-TYPE @ JOSE-JSON-T-STRING <> IF
        2DROP R> DROP OAUTH2-RESOURCE-METADATA-S-TYPE EXIT
    THEN
    R@ _O2RMW.VALUE-A @ R@ _O2RMW.VALUE-U @
    3 PICK OAUTH2-RESOURCE-METADATA-TEXT-CAPACITY
    R@ _O2RMW.JSON
    JOSE-JSON-STRING-DECODE
    DUP JOSE-JSON-S-OK <> IF
        DUP JOSE-JSON-S-CAPACITY = IF
            DROP _O2RM-DROP3 R> DROP
            OAUTH2-RESOURCE-METADATA-S-CAPACITY EXIT
        THEN
        DROP _O2RM-DROP3 R> DROP
        OAUTH2-RESOURCE-METADATA-S-INTERNAL EXIT
    THEN
    DROP
    DUP 0= IF
        _O2RM-DROP3 R> DROP
        OAUTH2-RESOURCE-METADATA-S-VALUE EXIT
    THEN
    SWAP ! DROP
    R> DROP OAUTH2-RESOURCE-METADATA-S-OK ;

: _O2RM-MARK-PRESENT  ( mask workspace -- status )
    >R
    DUP R@ _O2RMW.PRESENT @ AND IF
        DROP R> DROP OAUTH2-RESOURCE-METADATA-S-DUPLICATE EXIT
    THEN
    R@ _O2RMW.PRESENT @ OR R@ _O2RMW.PRESENT !
    R> DROP OAUTH2-RESOURCE-METADATA-S-OK ;

: _O2RM-COPY-AUTHORIZATION-SERVERS  ( workspace -- )
    >R
    R@ _O2RMW.ARRAY-COUNT @
        R@ _O2RMW.STAGE _O2RM.AUTHORIZATION-SERVER-COUNT !
    R@ _O2RMW.ARRAY-BYTES-U @
        R@ _O2RMW.STAGE _O2RM.AUTHORIZATION-SERVER-BYTES-U !
    R@ _O2RMW.ARRAY-ENTRIES
    R@ _O2RMW.STAGE _O2RM-AUTHORIZATION-SERVER-ENTRIES-OFF +
    R@ _O2RMW.ARRAY-COUNT @ _O2RM-ENTRY-SIZE * MOVE
    R@ _O2RMW.ARRAY-BYTES
    R@ _O2RMW.STAGE _O2RM.AUTHORIZATION-SERVERS
    R@ _O2RMW.ARRAY-BYTES-U @ MOVE
    R> DROP ;

: _O2RM-PROCESS-MEMBER  ( index workspace -- status )
    >R
    DUP R@ _O2RM-MEMBER-LOAD
    DUP IF NIP R> DROP EXIT THEN
    2DROP

    S" resource" R@ _O2RM-NAME= IF
        R@ _O2RMW.STAGE _O2RM.RESOURCE
        R@ _O2RMW.STAGE _O2RM.RESOURCE-U
        R@ _O2RM-COPY-MEMBER-STRING
        DUP IF R> DROP EXIT THEN DROP
        OAUTH2-RESOURCE-METADATA-P-RESOURCE
        R@ _O2RM-MARK-PRESENT R> DROP EXIT
    THEN

    S" authorization_servers" R@ _O2RM-NAME= IF
        R@ _O2RMW.VALUE-TYPE @ JOSE-JSON-T-ARRAY <> IF
            R> DROP OAUTH2-RESOURCE-METADATA-S-TYPE EXIT
        THEN
        R@ _O2RM-ARRAY-PARSE
        DUP IF R> DROP EXIT THEN DROP
        R@ _O2RM-COPY-AUTHORIZATION-SERVERS
        OAUTH2-RESOURCE-METADATA-P-AUTHORIZATION-SERVERS
        R@ _O2RM-MARK-PRESENT R> DROP EXIT
    THEN

    \ Unknown metadata has already been completely checked by the strict
    \ JSON dependency and is intentionally ignored.
    R> DROP OAUTH2-RESOURCE-METADATA-S-OK ;

: _O2RM-PROCESS-ALL  ( count workspace -- status )
    SWAP 0 ?DO
        I OVER _O2RM-PROCESS-MEMBER
        DUP IF
            NIP UNLOOP EXIT
        THEN
        DROP
    LOOP
    DROP OAUTH2-RESOURCE-METADATA-S-OK ;

: _O2RM-PARSE-STAGE  ( workspace -- status )
    >R
    R@ _O2RMW.SOURCE @ R@ _O2RMW.SOURCE-U @
    R@ _O2RMW.DESCRIPTOR OAUTH2-RESOURCE-METADATA-MAX-MEMBERS
    R@ _O2RMW.NAMES JOSE-JSON-MAX-NAME-BYTES
    R@ _O2RMW.JSON
    JOSE-JSON-OBJECT-PARSE
    _O2RM-JSON>STATUS
    DUP IF R> DROP EXIT THEN DROP

    R@ _O2RMW.DESCRIPTOR JOSE-JSON-OBJECT-COUNT@
    DUP JOSE-JSON-S-OK <> IF
        2DROP R> DROP OAUTH2-RESOURCE-METADATA-S-INTERNAL EXIT
    THEN
    DROP
    0 R@ _O2RMW.PRESENT !
    R@ _O2RM-PROCESS-ALL
    DUP IF R> DROP EXIT THEN DROP

    R@ _O2RMW.PRESENT @
        OAUTH2-RESOURCE-METADATA-P-RESOURCE AND 0= IF
        R> DROP OAUTH2-RESOURCE-METADATA-S-MISSING EXIT
    THEN
    R@ _O2RMW.PRESENT @
        R@ _O2RMW.STAGE _O2RM.PRESENCE !
    _O2RM-MAGIC-VALUE R@ _O2RMW.STAGE _O2RM.MAGIC !
    R> DROP OAUTH2-RESOURCE-METADATA-S-OK ;

