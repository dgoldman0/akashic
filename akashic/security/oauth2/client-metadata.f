\ =====================================================================
\  client-metadata.f - Structural OAuth Client ID Metadata parsing
\ =====================================================================
\  One bounded Client ID Metadata Document is decoded into an ephemeral
\  callback view inside caller-owned storage.  The view and all decoded
\  strings are valid only while the callback runs.  The complete workspace
\  is wiped after every admitted parse result, callback return, or caught
\  THROW.
\
\  Recognized members:
\
\    client_id                       required nonempty string
\    application_type                optional nonempty string
\    grant_types                     optional array of nonempty strings
\    response_types                  optional array of nonempty strings
\    redirect_uris                   optional array of nonempty strings
\    scope                           optional RFC 6749 scope string
\    token_endpoint_auth_method      optional nonempty string
\    token_endpoint_auth_signing_alg optional nonempty string except `none`
\    dpop_bound_access_tokens        optional boolean
\    jwks                            optional strict JSON object
\    jwks_uri                        optional nonempty string
\
\  Decoded duplicate object names and decoded duplicate array values are
\  rejected.  `jwks` and `jwks_uri` may not coexist.  Unknown members pass
\  complete strict JSON validation and are ignored.
\
\  This is a structural parser, not a complete deployment qualifier.  It
\  performs no HTTP, fetch-URL comparison, URI policy, default assignment,
\  JWK Set validation, key ownership, AT Protocol, session, or persistence.
\  A `jwks` accessor borrows the exact strict-validated object token from
\  the source document; a later checked JWKS layer must qualify its keys.
\
\  Public API:
\
\    OAUTH2-CLIENT-METADATA-WORKSPACE-SIZE
\    OAUTH2-CLIENT-METADATA-WORKSPACE-CLEAR
\    OAUTH2-CLIENT-METADATA-STATUS-VALID?
\    OAUTH2-CLIENT-METADATA-WITH
\    OAUTH2-CLIENT-METADATA-VIEW-PRESENCE@
\    OAUTH2-CLIENT-METADATA-VIEW-CLIENT-ID@
\    OAUTH2-CLIENT-METADATA-VIEW-APPLICATION-TYPE@
\    OAUTH2-CLIENT-METADATA-VIEW-GRANT-TYPE-COUNT@
\    OAUTH2-CLIENT-METADATA-VIEW-GRANT-TYPE@
\    OAUTH2-CLIENT-METADATA-VIEW-GRANT-TYPE?
\    OAUTH2-CLIENT-METADATA-VIEW-RESPONSE-TYPE-COUNT@
\    OAUTH2-CLIENT-METADATA-VIEW-RESPONSE-TYPE@
\    OAUTH2-CLIENT-METADATA-VIEW-RESPONSE-TYPE?
\    OAUTH2-CLIENT-METADATA-VIEW-REDIRECT-URI-COUNT@
\    OAUTH2-CLIENT-METADATA-VIEW-REDIRECT-URI@
\    OAUTH2-CLIENT-METADATA-VIEW-REDIRECT-URI?
\    OAUTH2-CLIENT-METADATA-VIEW-SCOPE@
\    OAUTH2-CLIENT-METADATA-VIEW-TOKEN-AUTH-METHOD@
\    OAUTH2-CLIENT-METADATA-VIEW-TOKEN-AUTH-SIGNING-ALG@
\    OAUTH2-CLIENT-METADATA-VIEW-DPOP-BOUND?
\    OAUTH2-CLIENT-METADATA-VIEW-JWKS@
\    OAUTH2-CLIENT-METADATA-VIEW-JWKS-URI@
\ =====================================================================

