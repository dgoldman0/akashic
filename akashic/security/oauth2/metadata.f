  ( source source-u metadata workspace -- status )
    3 PICK 3 PICK 3 PICK 3 PICK _O2MD-PARSE-GEOMETRY
    DUP IF
        >R _O2MD-DROP4 R> EXIT
    THEN
    DROP
    ['] _O2MD-PARSE-ADMITTED _O2MD-PARSE-CALL ;

