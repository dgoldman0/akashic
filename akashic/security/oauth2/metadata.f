: _O2MD-ARRAY-PARSE  ( workspace -- status )
    >R
    R@ _O2MD-ARRAY-RESET
    R@ _O2MDW.VALUE-U @ 2 U< IF
        R> DROP OAUTH2-METADATA-S-INTERNAL EXIT
    THEN
    0 R@ _O2MD-ARRAY-C@ 91 <> IF
        R> DROP OAUTH2-METADATA-S-INTERNAL EXIT
    THEN
    R@ _O2MDW.VALUE-U @ 1-
    R@ _O2MD-ARRAY-C@ 93 <> IF
        R> DROP OAUTH2-METADATA-S-INTERNAL EXIT
    THEN
    1 R@ _O2MDW.ARRAY-POS !
    R@ _O2MD-ARRAY-SKIP-WS DROP
    R@ _O2MDW.ARRAY-POS @
    R@ _O2MDW.VALUE-U @ 1- = IF
        R> DROP OAUTH2-METADATA-S-OK EXIT
    THEN

    BEGIN
        R@ _O2MDW.ARRAY-POS @
        R@ _O2MD-ARRAY-C@ 34 <> IF
            R> DROP OAUTH2-METADATA-S-TYPE EXIT
        THEN
        R@ _O2MDW.ARRAY-POS @ R@ _O2MDW.TOKEN-START !
        1 R@ _O2MDW.ARRAY-POS +!
        R@ _O2MD-FIND-STRING-END
        DUP IF R> DROP EXIT THEN DROP
        R@ _O2MD-DECODE-ARRAY-TOKEN
        DUP IF R> DROP EXIT THEN DROP
        R@ _O2MD-ARRAY-APPEND
        DUP IF R> DROP EXIT THEN DROP

        R@ _O2MD-ARRAY-SKIP-WS DROP
        R@ _O2MDW.ARRAY-POS @
        R@ _O2MDW.VALUE-U @ U< 0= IF
            R> DROP OAUTH2-METADATA-S-INTERNAL EXIT
        THEN
        R@ _O2MDW.ARRAY-POS @
        R@ _O2MD-ARRAY-C@
        DUP 93 = IF
            DROP
            1 R@ _O2MDW.ARRAY-POS +!
            R@ _O2MDW.ARRAY-POS @
            R@ _O2MDW.VALUE-U @ <> IF
                R> DROP OAUTH2-METADATA-S-INTERNAL EXIT
            THEN
            R> DROP OAUTH2-METADATA-S-OK EXIT
        THEN
        44 <> IF
            R> DROP OAUTH2-METADATA-S-INTERNAL EXIT
        THEN
        1 R@ _O2MDW.ARRAY-POS +!
        R@ _O2MD-ARRAY-SKIP-WS DROP
        R@ _O2MDW.ARRAY-POS @
        R@ _O2MDW.VALUE-U @ 1- U< 0= IF
            R> DROP OAUTH2-METADATA-S-INTERNAL EXIT
        THEN
    AGAIN ;

