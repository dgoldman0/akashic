: _O2MD-PARSE-ADMITTED
  ( source source-u metadata workspace -- status )
    DUP _O2MD-WIPE
    3 PICK OVER _O2MDW.SOURCE !
    2 PICK OVER _O2MDW.SOURCE-U !
    OVER OVER _O2MDW.OUTPUT !
    NIP NIP NIP
    _O2MD-PARSE-STAGE ;

: _O2MD-PUBLISH  ( workspace -- )
    0 OVER _O2MDW.OUTPUT @ _O2MD.MAGIC !
    DUP _O2MDW.STAGE 8 +
    OVER _O2MDW.OUTPUT @ 8 +
    OAUTH2-METADATA-SIZE 8 - MOVE
    _O2MD-MAGIC-VALUE
    OVER _O2MDW.OUTPUT @ _O2MD.MAGIC !
    DROP ;

: _O2MD-PARSE-CALL
  ( source source-u metadata workspace xt -- status )
    1 PICK >R
    CATCH
    DUP IF
        DROP
        R@ _O2MD-WIPE
        _O2MD-DROP4
        R> DROP OAUTH2-METADATA-S-INTERNAL EXIT
    THEN
    DROP
    DUP IF
        R@ _O2MD-WIPE
        R> DROP EXIT
    THEN
    DROP
    R@ ['] _O2MD-PUBLISH ['] _O2MD-WIPE
        _O2MD-CALL-FINALLY
    R> DROP
    OAUTH2-METADATA-S-OK ;

