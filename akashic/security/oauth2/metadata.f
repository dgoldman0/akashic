: _O2MD-COPY-MEMBER-STRING
  ( destination length-cell workspace -- status )
    >R
    R@ _O2MDW.VALUE-TYPE @ JOSE-JSON-T-STRING <> IF
        2DROP R> DROP OAUTH2-METADATA-S-TYPE EXIT
    THEN
    R@ _O2MDW.VALUE-A @ R@ _O2MDW.VALUE-U @
    3 PICK OAUTH2-METADATA-TEXT-CAPACITY
    R@ _O2MDW.JSON
    JOSE-JSON-STRING-DECODE
    DUP JOSE-JSON-S-OK <> IF
        DUP JOSE-JSON-S-CAPACITY = IF
            DROP _O2MD-DROP3 R> DROP
            OAUTH2-METADATA-S-CAPACITY EXIT
        THEN
        DROP _O2MD-DROP3 R> DROP
        OAUTH2-METADATA-S-INTERNAL EXIT
    THEN
    DROP
    DUP 0= IF
        _O2MD-DROP3 R> DROP OAUTH2-METADATA-S-VALUE EXIT
    THEN
    SWAP ! DROP
    R> DROP OAUTH2-METADATA-S-OK ;

