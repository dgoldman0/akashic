: _O2MD-PROCESS-MEMBER  ( index workspace -- status )
    >R
    DUP R@ _O2MD-MEMBER-LOAD
    DUP IF NIP R> DROP EXIT THEN
    2DROP

    S" issuer" R@ _O2MD-NAME= IF
        R@ _O2MDW.STAGE _O2MD.ISSUER
        R@ _O2MDW.STAGE _O2MD.ISSUER-U
        R@ _O2MD-COPY-MEMBER-STRING
        DUP IF R> DROP EXIT THEN DROP
        _O2MD-P-ISSUER R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" authorization_endpoint" R@ _O2MD-NAME= IF
        R@ _O2MDW.STAGE _O2MD.AUTHORIZATION
        R@ _O2MDW.STAGE _O2MD.AUTHORIZATION-U
        R@ _O2MD-COPY-MEMBER-STRING
        DUP IF R> DROP EXIT THEN DROP
        _O2MD-P-AUTHORIZATION R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" token_endpoint" R@ _O2MD-NAME= IF
        R@ _O2MDW.STAGE _O2MD.TOKEN
        R@ _O2MDW.STAGE _O2MD.TOKEN-U
        R@ _O2MD-COPY-MEMBER-STRING
        DUP IF R> DROP EXIT THEN DROP
        _O2MD-P-TOKEN R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" pushed_authorization_request_endpoint" R@ _O2MD-NAME= IF
        R@ _O2MDW.STAGE _O2MD.PAR
        R@ _O2MDW.STAGE _O2MD.PAR-U
        R@ _O2MD-COPY-MEMBER-STRING
        DUP IF R> DROP EXIT THEN DROP
        _O2MD-P-PAR R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" require_pushed_authorization_requests" R@ _O2MD-NAME= IF
        R@ _O2MDW.VALUE-TYPE @ JOSE-JSON-T-BOOL <> IF
            R> DROP OAUTH2-METADATA-S-TYPE EXIT
        THEN
        R@ _O2MDW.VALUE-A @ R@ _O2MDW.VALUE-U @
        S" true" COMPARE 0= IF
            OAUTH2-METADATA-F-PAR-REQUIRED R@ _O2MD-CAP!
        THEN
        _O2MD-P-REQUIRE-PAR R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" response_types_supported" R@ _O2MD-NAME= IF
        R@ _O2MD-CAPTURE-ARRAY
        DUP IF R> DROP EXIT THEN DROP
        S" code" R@ _O2MD-ARRAY-CONTAINS? IF
            OAUTH2-METADATA-F-RESPONSE-CODE R@ _O2MD-CAP!
        THEN
        _O2MD-P-RESPONSES R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" grant_types_supported" R@ _O2MD-NAME= IF
        R@ _O2MD-CAPTURE-ARRAY
        DUP IF R> DROP EXIT THEN DROP
        S" authorization_code" R@ _O2MD-ARRAY-CONTAINS? IF
            OAUTH2-METADATA-F-GRANT-AUTHORIZATION-CODE
                R@ _O2MD-CAP!
        THEN
        S" refresh_token" R@ _O2MD-ARRAY-CONTAINS? IF
            OAUTH2-METADATA-F-GRANT-REFRESH-TOKEN R@ _O2MD-CAP!
        THEN
        _O2MD-P-GRANTS R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" code_challenge_methods_supported" R@ _O2MD-NAME= IF
        R@ _O2MD-CAPTURE-ARRAY
        DUP IF R> DROP EXIT THEN DROP
        S" S256" R@ _O2MD-ARRAY-CONTAINS? IF
            OAUTH2-METADATA-F-PKCE-S256 R@ _O2MD-CAP!
        THEN
        _O2MD-P-CHALLENGES R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" dpop_signing_alg_values_supported" R@ _O2MD-NAME= IF
        R@ _O2MD-CAPTURE-ARRAY
        DUP IF R> DROP EXIT THEN DROP
        S" ES256" R@ _O2MD-ARRAY-CONTAINS? IF
            OAUTH2-METADATA-F-DPOP-ES256 R@ _O2MD-CAP!
        THEN
        _O2MD-P-DPOP R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" token_endpoint_auth_methods_supported" R@ _O2MD-NAME= IF
        R@ _O2MD-CAPTURE-ARRAY
        DUP IF R> DROP EXIT THEN DROP
        S" none" R@ _O2MD-ARRAY-CONTAINS? IF
            OAUTH2-METADATA-F-TOKEN-AUTH-NONE R@ _O2MD-CAP!
        THEN
        S" private_key_jwt" R@ _O2MD-ARRAY-CONTAINS? IF
            OAUTH2-METADATA-F-TOKEN-AUTH-PRIVATE-KEY-JWT
                R@ _O2MD-CAP!
        THEN
        R@ _O2MD-COPY-AUTH-METHODS
        _O2MD-P-TOKEN-AUTH R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" scopes_supported" R@ _O2MD-NAME= IF
        R@ _O2MD-CAPTURE-ARRAY
        DUP IF R> DROP EXIT THEN DROP
        R@ _O2MD-COPY-SCOPES
        _O2MD-P-SCOPES R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" token_endpoint_auth_signing_alg_values_supported"
        R@ _O2MD-NAME= IF
        R@ _O2MD-CAPTURE-ARRAY
        DUP IF R> DROP EXIT THEN DROP
        S" ES256" R@ _O2MD-ARRAY-CONTAINS? IF
            OAUTH2-METADATA-F-TOKEN-AUTH-SIGNING-ES256
                R@ _O2MD-CAP!
        THEN
        R@ _O2MD-COPY-TOKEN-AUTH-SIGNING-ALGS
        _O2MD-P-TOKEN-AUTH-SIGNING-ALGS R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" authorization_response_iss_parameter_supported"
        R@ _O2MD-NAME= IF
        R@ _O2MDW.VALUE-TYPE @ JOSE-JSON-T-BOOL <> IF
            R> DROP OAUTH2-METADATA-S-TYPE EXIT
        THEN
        R@ _O2MDW.VALUE-A @ R@ _O2MDW.VALUE-U @
        S" true" COMPARE 0= IF
            OAUTH2-METADATA-F-AUTHORIZATION-RESPONSE-ISS
                R@ _O2MD-CAP!
        THEN
        _O2MD-P-AUTHORIZATION-RESPONSE-ISS
            R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" require_request_uri_registration" R@ _O2MD-NAME= IF
        R@ _O2MDW.VALUE-TYPE @ JOSE-JSON-T-BOOL <> IF
            R> DROP OAUTH2-METADATA-S-TYPE EXIT
        THEN
        R@ _O2MDW.VALUE-A @ R@ _O2MDW.VALUE-U @
        S" true" COMPARE 0= IF
            OAUTH2-METADATA-F-REQUIRE-REQUEST-URI-REGISTRATION
                R@ _O2MD-CAP!
        THEN
        _O2MD-P-REQUIRE-REQUEST-URI-REGISTRATION
            R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    S" client_id_metadata_document_supported" R@ _O2MD-NAME= IF
        R@ _O2MDW.VALUE-TYPE @ JOSE-JSON-T-BOOL <> IF
            R> DROP OAUTH2-METADATA-S-TYPE EXIT
        THEN
        R@ _O2MDW.VALUE-A @ R@ _O2MDW.VALUE-U @
        S" true" COMPARE 0= IF
            OAUTH2-METADATA-F-CLIENT-ID-METADATA-DOCUMENT
                R@ _O2MD-CAP!
        THEN
        _O2MD-P-CLIENT-ID-METADATA-DOCUMENT
            R@ _O2MD-MARK-PRESENT
        R> DROP EXIT
    THEN

    \ Unknown metadata has already been validated completely by the strict
    \ JSON object parser and is intentionally ignored here.
    R> DROP OAUTH2-METADATA-S-OK ;

: _O2MD-PROCESS-ALL  ( count workspace -- status )
    SWAP 0 ?DO
        I OVER _O2MD-PROCESS-MEMBER
        DUP IF
            NIP UNLOOP EXIT
        THEN
        DROP
    LOOP
    DROP OAUTH2-METADATA-S-OK ;

: _O2MD-PARSE-STAGE  ( workspace -- status )
    >R
    R@ _O2MDW.SOURCE @ R@ _O2MDW.SOURCE-U @
    R@ _O2MDW.DESCRIPTOR OAUTH2-METADATA-MAX-MEMBERS
    R@ _O2MDW.NAMES JOSE-JSON-MAX-NAME-BYTES
    R@ _O2MDW.JSON
    JOSE-JSON-OBJECT-PARSE
    _O2MD-JSON>STATUS
    DUP IF R> DROP EXIT THEN DROP

    R@ _O2MDW.DESCRIPTOR JOSE-JSON-OBJECT-COUNT@
    DUP JOSE-JSON-S-OK <> IF
        2DROP R> DROP OAUTH2-METADATA-S-INTERNAL EXIT
    THEN
    DROP
    0 R@ _O2MDW.PRESENT !
    R@ _O2MD-PROCESS-ALL
    DUP IF R> DROP EXIT THEN DROP

    R@ _O2MDW.PRESENT @ _O2MD-P-ISSUER AND 0= IF
        R> DROP OAUTH2-METADATA-S-MISSING EXIT
    THEN
    R@ _O2MDW.PRESENT @
        R@ _O2MDW.STAGE _O2MD.PRESENCE !
    _O2MD-MAGIC-VALUE R@ _O2MDW.STAGE _O2MD.MAGIC !
    R> DROP OAUTH2-METADATA-S-OK ;

