\ =====================================================================
\  metadata.f - Strict OAuth 2 authorization-server metadata parsing
\ =====================================================================
\  This module parses only a caller-supplied RFC 8414-style JSON object.
\  It performs no HTTP, discovery, redirect, issuer-origin, identity, or
\  client-profile policy.  Exact decoded issuer and endpoint strings are
\  copied into a caller-owned result.  Boolean and registered-value-list
\  capabilities are validated and exposed without deciding whether a
\  particular client may proceed.
\
\  `issuer` is required.  The remaining named fields in this module's
\  bounded contract are optional, but are validated exactly when present:
\
\    issuer
\    authorization_endpoint
\    token_endpoint
\    pushed_authorization_request_endpoint
\    require_pushed_authorization_requests
\    response_types_supported
\    grant_types_supported
\    code_challenge_methods_supported
\    dpop_signing_alg_values_supported
\    token_endpoint_auth_methods_supported
\    scopes_supported
\    token_endpoint_auth_signing_alg_values_supported
\    authorization_response_iss_parameter_supported
\    require_request_uri_registration
\    client_id_metadata_document_supported
\
\  A present endpoint is a nonempty JSON string.  The PAR requirement is a
\  JSON boolean.  Each present supported-values field is an array of
\  nonempty JSON strings with no duplicate decoded value.  Unknown object
\  members are accepted only after the strict JSON dependency has validated
\  their complete value, including nested values.
\
\  A successful parse publishes a fixed-size, self-contained result.  It
\  reports whether `code`, `authorization_code`, `refresh_token`, `S256`,
\  DPoP `ES256`, `none`, `private_key_jwt`, and token-authentication `ES256`
\  occur in the corresponding lists, plus the true value of each recognized
\  boolean.
\  It also retains the complete bounded scope, token-endpoint authentication
\  method, and token-endpoint authentication signing-algorithm sets for exact
\  enumeration and membership queries.  Missing capabilities are not parse
\  errors; profile policy belongs to the caller.
\
\  Public API:
\    OAUTH2-METADATA-SIZE
\    OAUTH2-METADATA-WORKSPACE-SIZE
\    OAUTH2-METADATA-STATUS-VALID?       ( status -- flag )
\    OAUTH2-METADATA-VALID?              ( metadata -- flag )
\    OAUTH2-METADATA-WORKSPACE-CLEAR     ( workspace -- status )
\    OAUTH2-METADATA-PARSE
\      ( source source-u metadata workspace -- status )
\    OAUTH2-METADATA-PRESENCE@           ( metadata -- presence status )
\    OAUTH2-METADATA-FLAGS@              ( metadata -- flags status )
\    OAUTH2-METADATA-ISSUER@             ( metadata -- a u status )
\    OAUTH2-METADATA-AUTHORIZATION-ENDPOINT@
\      ( metadata -- a u status )
\    OAUTH2-METADATA-TOKEN-ENDPOINT@     ( metadata -- a u status )
\    OAUTH2-METADATA-PAR-ENDPOINT@       ( metadata -- a u status )
\    OAUTH2-METADATA-TOKEN-AUTH-COUNT@   ( metadata -- count status )
\    OAUTH2-METADATA-TOKEN-AUTH@         ( index metadata -- a u status )
\    OAUTH2-METADATA-TOKEN-AUTH-METHOD?
\      ( method-a method-u metadata -- supported status )
\    OAUTH2-METADATA-SCOPE-COUNT@        ( metadata -- count status )
\    OAUTH2-METADATA-SCOPE@              ( index metadata -- a u status )
\    OAUTH2-METADATA-SCOPE?
\      ( scope-a scope-u metadata -- supported status )
\    OAUTH2-METADATA-TOKEN-AUTH-SIGNING-ALG-COUNT@
\      ( metadata -- count status )
\    OAUTH2-METADATA-TOKEN-AUTH-SIGNING-ALG@
\      ( index metadata -- a u status )
\    OAUTH2-METADATA-TOKEN-AUTH-SIGNING-ALG?
\      ( alg-a alg-u metadata -- supported status )
\ =====================================================================

