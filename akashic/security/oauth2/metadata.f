    >R
    R@ _O2MDW.DESCRIPTOR JOSE-JSON-OBJECT-MEMBER@
    DUP JOSE-JSON-S-OK <> IF
        2DROP 2DROP 2DROP
        R> DROP OAUTH2-METADATA-S-INTERNAL EXIT
