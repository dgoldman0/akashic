\ =====================================================================
\  client-config.f - Immutable provider-neutral OAuth client selection
\ =====================================================================
\  This caller-owned record resolves one opaque durable binding to the
\  exact client values selected for an authorization-code flow.  It copies
\  every retained byte and contains no private key, token, endpoint, HTTP,
\  browser, provider, AT Protocol, or Streams state.
\
\  A higher owner resolves the binding to any client-authentication and
\  DPoP key material used with this selection.  The binding is deliberately
\  opaque here: it is an identity, not a private key container.
\ =====================================================================

