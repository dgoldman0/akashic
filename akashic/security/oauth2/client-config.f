    OVER OAUTH2-CLIENT-CONFIG-I.CLIENT-ID-U @
    OAUTH2-CLIENT-CONFIG-CLIENT-ID-CAPACITY
        _O2CC-REQUIRED-SOURCE-STATUS ?DUP IF NIP EXIT THEN
    DUP OAUTH2-CLIENT-CONFIG-I.REDIRECT-URI-A @
    OVER OAUTH2-CLIENT-CONFIG-I.REDIRECT-URI-U @
    OAUTH2-CLIENT-CONFIG-REDIRECT-URI-CAPACITY
        _O2CC-REQUIRED-SOURCE-STATUS ?DUP IF NIP EXIT THEN
