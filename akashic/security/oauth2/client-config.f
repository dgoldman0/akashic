: _O2CC-CALLER>STATUS  ( caller-status -- status )
    DUP CALLER-SPAN-S-OK = IF
        DROP OAUTH2-CLIENT-CONFIG-S-OK EXIT
    THEN
    DUP CALLER-SPAN-S-RANGE = IF
        DROP OAUTH2-CLIENT-CONFIG-S-RANGE EXIT
    THEN
    DUP CALLER-SPAN-S-PROTECTED = IF
        DROP OAUTH2-CLIENT-CONFIG-S-PROTECTED EXIT
    THEN
    DUP CALLER-SPAN-S-PLATFORM = IF
        DROP OAUTH2-CLIENT-CONFIG-S-PLATFORM EXIT
    THEN
    DROP OAUTH2-CLIENT-CONFIG-S-PLATFORM ;

: _O2CC-ADMIT-SPAN  ( address length -- status )
    CALLER-SPAN-STATUS _O2CC-CALLER>STATUS ;

: _O2CC-FIXED-STATUS  ( address length -- status )
    OVER 0= IF 2DROP OAUTH2-CLIENT-CONFIG-S-INVALID EXIT THEN
    OVER 7 AND IF 2DROP OAUTH2-CLIENT-CONFIG-S-INVALID EXIT THEN
    _O2CC-ADMIT-SPAN ;

: _O2CC-REQUIRED-LENGTH-STATUS
  ( length capacity -- status )
    OVER 1 < IF
        2DROP OAUTH2-CLIENT-CONFIG-S-INVALID EXIT
    THEN
    U> IF
        OAUTH2-CLIENT-CONFIG-S-CAPACITY
    ELSE
        OAUTH2-CLIENT-CONFIG-S-OK
    THEN ;

: _O2CC-OPTIONAL-LENGTH-STATUS
  ( length capacity -- status )
    OVER 0< IF
        2DROP OAUTH2-CLIENT-CONFIG-S-INVALID EXIT
    THEN
    U> IF
        OAUTH2-CLIENT-CONFIG-S-CAPACITY
    ELSE
        OAUTH2-CLIENT-CONFIG-S-OK
    THEN ;

: _O2CC-OPTIONAL-PAIR?  ( address length -- flag )
    DUP 0= IF
        SWAP 0= SWAP DROP EXIT
    THEN
    DROP 0<> ;

\ =====================================================================
\  Exact-value syntax
\ =====================================================================

: _O2CC-VSCHAR?  ( address length -- flag )
    BEGIN DUP WHILE
        OVER C@ 32 127 WITHIN 0= IF
            2DROP 0 EXIT
        THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP -1 ;

: _O2CC-URI-CHAR?  ( address length -- flag )
    BEGIN DUP WHILE
        OVER C@ 33 127 WITHIN 0= IF
            2DROP 0 EXIT
        THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP -1 ;

: _O2CC-SCOPE-TOKEN-CHAR?  ( character -- flag )
    DUP 33 = IF DROP -1 EXIT THEN
    DUP 35 92 WITHIN IF DROP -1 EXIT THEN
    93 127 WITHIN ;

: _O2CC-SCOPE?  ( address length -- flag )
    DUP 0= IF 2DROP -1 EXIT THEN
    OVER C@ BL = IF 2DROP 0 EXIT THEN
    2DUP + 1- C@ BL = IF 2DROP 0 EXIT THEN
    BEGIN DUP WHILE
        OVER C@ DUP BL = IF
            DROP
            DUP 1 <= IF 2DROP 0 EXIT THEN
            OVER 1+ C@ BL = IF 2DROP 0 EXIT THEN
        ELSE
            _O2CC-SCOPE-TOKEN-CHAR? 0= IF
                2DROP 0 EXIT
            THEN
        THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP -1 ;

: _O2CC-BYTES=  ( first-a first-u second-a second-u -- flag )
    2SWAP COMPARE 0= ;

\ =====================================================================
\  Canonical record validation
\ =====================================================================

: _O2CC-ZERO?  ( address length -- flag )
    BEGIN DUP WHILE
        OVER C@ IF 2DROP 0 EXIT THEN
        1- SWAP 1+ SWAP
    REPEAT
    2DROP -1 ;

: _O2CC-CANONICAL-ARENA?  ( address used capacity -- flag )
    >R
    DUP >R
    +
    R> R> SWAP -
    _O2CC-ZERO? ;

: _O2CC-FLAGS?  ( flags -- flag )
    DUP 0< IF DROP 0 EXIT THEN
    _O2CC-FLAGS-KNOWN INVERT AND 0= ;

: _O2CC-LENGTHS?  ( config -- flag )
    DUP _O2CC.BINDING-U @
    OAUTH2-CLIENT-CONFIG-BINDING-CAPACITY
        _O2CC-REQUIRED-LENGTH-STATUS
        OAUTH2-CLIENT-CONFIG-S-OK <> IF DROP 0 EXIT THEN
    DUP _O2CC.CLIENT-ID-U @
    OAUTH2-CLIENT-CONFIG-CLIENT-ID-CAPACITY
        _O2CC-REQUIRED-LENGTH-STATUS
        OAUTH2-CLIENT-CONFIG-S-OK <> IF DROP 0 EXIT THEN
    DUP _O2CC.REDIRECT-U @
    OAUTH2-CLIENT-CONFIG-REDIRECT-URI-CAPACITY
        _O2CC-REQUIRED-LENGTH-STATUS
        OAUTH2-CLIENT-CONFIG-S-OK <> IF DROP 0 EXIT THEN
    DUP _O2CC.SCOPE-U @
    OAUTH2-CLIENT-CONFIG-SCOPE-CAPACITY
        _O2CC-OPTIONAL-LENGTH-STATUS
        OAUTH2-CLIENT-CONFIG-S-OK <> IF DROP 0 EXIT THEN
    DUP _O2CC.AUTH-METHOD-U @
    OAUTH2-CLIENT-CONFIG-AUTH-METHOD-CAPACITY
        _O2CC-REQUIRED-LENGTH-STATUS
        OAUTH2-CLIENT-CONFIG-S-OK <> IF DROP 0 EXIT THEN
    _O2CC.AUTH-ALGORITHM-U @
    OAUTH2-CLIENT-CONFIG-AUTH-ALGORITHM-CAPACITY
        _O2CC-OPTIONAL-LENGTH-STATUS
        OAUTH2-CLIENT-CONFIG-S-OK = ;

: _O2CC-CONTENT?  ( config -- flag )
    DUP _O2CC.CLIENT-ID OVER _O2CC.CLIENT-ID-U @
        _O2CC-VSCHAR? 0= IF DROP 0 EXIT THEN
    DUP _O2CC.REDIRECT OVER _O2CC.REDIRECT-U @
        _O2CC-URI-CHAR? 0= IF DROP 0 EXIT THEN
    DUP _O2CC.SCOPE OVER _O2CC.SCOPE-U @
        _O2CC-SCOPE? 0= IF DROP 0 EXIT THEN
    DUP _O2CC.AUTH-METHOD OVER _O2CC.AUTH-METHOD-U @
        _O2CC-URI-CHAR? 0= IF DROP 0 EXIT THEN
    DUP _O2CC.AUTH-ALGORITHM OVER _O2CC.AUTH-ALGORITHM-U @
        _O2CC-URI-CHAR? 0= IF DROP 0 EXIT THEN
    DUP _O2CC.AUTH-METHOD OVER _O2CC.AUTH-METHOD-U @
    S" none" _O2CC-BYTES= IF
        _O2CC.AUTH-ALGORITHM-U @ 0=
    ELSE
        DROP -1
    THEN ;

: _O2CC-PADDING?  ( config -- flag )
    DUP _O2CC.BINDING OVER _O2CC.BINDING-U @
    OAUTH2-CLIENT-CONFIG-BINDING-CAPACITY
        _O2CC-CANONICAL-ARENA? 0= IF DROP 0 EXIT THEN
    DUP _O2CC.CLIENT-ID OVER _O2CC.CLIENT-ID-U @
    OAUTH2-CLIENT-CONFIG-CLIENT-ID-CAPACITY
        _O2CC-CANONICAL-ARENA? 0= IF DROP 0 EXIT THEN
    DUP _O2CC.REDIRECT OVER _O2CC.REDIRECT-U @
    OAUTH2-CLIENT-CONFIG-REDIRECT-URI-CAPACITY
        _O2CC-CANONICAL-ARENA? 0= IF DROP 0 EXIT THEN
    DUP _O2CC.SCOPE OVER _O2CC.SCOPE-U @
    OAUTH2-CLIENT-CONFIG-SCOPE-CAPACITY
        _O2CC-CANONICAL-ARENA? 0= IF DROP 0 EXIT THEN
    DUP _O2CC.AUTH-METHOD OVER _O2CC.AUTH-METHOD-U @
    OAUTH2-CLIENT-CONFIG-AUTH-METHOD-CAPACITY
        _O2CC-CANONICAL-ARENA? 0= IF DROP 0 EXIT THEN
    DUP _O2CC.AUTH-ALGORITHM SWAP _O2CC.AUTH-ALGORITHM-U @
    OAUTH2-CLIENT-CONFIG-AUTH-ALGORITHM-CAPACITY
        _O2CC-CANONICAL-ARENA? ;

: _O2CC-SHAPE?  ( config -- flag )
    DUP _O2CC.MAGIC @ _O2CC-MAGIC-VALUE <> IF DROP 0 EXIT THEN
    DUP _O2CC.FLAGS @ _O2CC-FLAGS? 0= IF DROP 0 EXIT THEN
    DUP _O2CC-LENGTHS? 0= IF DROP 0 EXIT THEN
    DUP _O2CC-CONTENT? 0= IF DROP 0 EXIT THEN
    _O2CC-PADDING? ;

: _O2CC-OBJECT-STATUS  ( config -- status )
    DUP OAUTH2-CLIENT-CONFIG-SIZE _O2CC-FIXED-STATUS
    ?DUP IF NIP EXIT THEN
    _O2CC-SHAPE? IF
        OAUTH2-CLIENT-CONFIG-S-OK
    ELSE
        OAUTH2-CLIENT-CONFIG-S-INVALID
    THEN ;

: OAUTH2-CLIENT-CONFIG-VALID?  ( config -- flag )
    _O2CC-OBJECT-STATUS OAUTH2-CLIENT-CONFIG-S-OK = ;

