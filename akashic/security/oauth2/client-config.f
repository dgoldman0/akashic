: _O2CC-INIT-STATUS  ( input config -- status )
    DUP OAUTH2-CLIENT-CONFIG-SIZE _O2CC-FIXED-STATUS
    ?DUP IF >R 2DROP R> EXIT THEN
    OVER _O2CC-INPUT-STATUS ?DUP IF
        >R 2DROP R> EXIT
    THEN
    2DUP _O2CC-INPUT-ALIASES-CONFIG? IF
        2DROP OAUTH2-CLIENT-CONFIG-S-ALIAS EXIT
    THEN
    DUP OAUTH2-CLIENT-CONFIG-SIZE _O2CC-ZERO? 0= IF
        2DROP OAUTH2-CLIENT-CONFIG-S-STATE EXIT
    THEN
    OVER _O2CC-INPUT-CONTENT-STATUS ?DUP IF
        >R 2DROP R> EXIT
    THEN
    2DROP OAUTH2-CLIENT-CONFIG-S-OK ;

: _O2CC-COPY-REQUIRED
  ( source-address source-length destination length-field -- )
    >R
    OVER R@ !
    SWAP MOVE
    R> DROP ;

: _O2CC-COPY-OPTIONAL
  ( source-address source-length destination length-field -- )
    >R
    OVER R@ !
    OVER IF SWAP MOVE ELSE 2DROP DROP THEN
    R> DROP ;

: _O2CC-PUBLISH  ( input config -- )
    >R
    R@ OAUTH2-CLIENT-CONFIG-SIZE 0 FILL

    DUP OAUTH2-CLIENT-CONFIG-I.BINDING-A @
    OVER OAUTH2-CLIENT-CONFIG-I.BINDING-U @
    R@ _O2CC.BINDING R@ _O2CC.BINDING-U
        _O2CC-COPY-REQUIRED
    DUP OAUTH2-CLIENT-CONFIG-I.CLIENT-ID-A @
    OVER OAUTH2-CLIENT-CONFIG-I.CLIENT-ID-U @
    R@ _O2CC.CLIENT-ID R@ _O2CC.CLIENT-ID-U
        _O2CC-COPY-REQUIRED
    DUP OAUTH2-CLIENT-CONFIG-I.REDIRECT-URI-A @
    OVER OAUTH2-CLIENT-CONFIG-I.REDIRECT-URI-U @
