    THEN
    DUP OAUTH2-CLIENT-CONFIG-I.CLIENT-ID-A @
    OVER OAUTH2-CLIENT-CONFIG-I.CLIENT-ID-U @
        _O2CC-VSCHAR? 0= IF
        DROP OAUTH2-CLIENT-CONFIG-S-INVALID EXIT
    THEN
    DUP OAUTH2-CLIENT-CONFIG-I.REDIRECT-URI-A @
    OVER OAUTH2-CLIENT-CONFIG-I.REDIRECT-URI-U @
        _O2CC-URI-CHAR? 0= IF
        DROP OAUTH2-CLIENT-CONFIG-S-INVALID EXIT
    THEN
    DUP OAUTH2-CLIENT-CONFIG-I.SCOPE-A @
    OVER OAUTH2-CLIENT-CONFIG-I.SCOPE-U @
        _O2CC-SCOPE? 0= IF
        DROP OAUTH2-CLIENT-CONFIG-S-INVALID EXIT
    THEN
    DUP OAUTH2-CLIENT-CONFIG-I.AUTH-METHOD-A @
    OVER OAUTH2-CLIENT-CONFIG-I.AUTH-METHOD-U @
