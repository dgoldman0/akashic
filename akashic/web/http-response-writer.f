: HRESP.SEND-CAPACITY   ( writer -- a ) _HRESP-SEND-CAPACITY-O + ;
: HRESP.BODY-U          ( writer -- a ) _HRESP-BODY-U-O + ;
: HRESP.BODY-SENT       ( writer -- a ) _HRESP-BODY-SENT-O + ;
