        DROP R> DROP AT-OAUTH-PAR-S-INTERNAL EXIT
    THEN
    DUP OAUTH2-DPOP-ES256-MAX-PROOF-BYTES U> IF
        DROP R> DROP AT-OAUTH-PAR-S-INTERNAL EXIT
