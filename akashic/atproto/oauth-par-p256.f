    1 PICK >R
    CATCH
    DUP IF
        DROP
        R@ _ATPP-WIPE
        _ATPP-DROP2
        R> DROP
        AT-OAUTH-PAR-S-INTERNAL EXIT
    THEN
    DROP R> DROP ;

