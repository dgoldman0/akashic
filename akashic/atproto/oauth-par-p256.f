    2DUP _ATPP-SOURCES-WORKSPACE-DISJOINT? 0= IF
        _ATPP-DROP2 AT-OAUTH-PAR-S-ALIAS EXIT
    THEN
    OVER _ATPP-MUTABLES-DISJOINT? 0= IF
        _ATPP-DROP2 AT-OAUTH-PAR-S-ALIAS EXIT
    THEN
    _ATPP-DROP2 AT-OAUTH-PAR-S-OK ;

