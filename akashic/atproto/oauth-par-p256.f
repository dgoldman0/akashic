    R@
    OAUTH2-CLIENT-CONFIG-WITH
    DUP OAUTH2-CLIENT-CONFIG-S-OK <> IF
        _ATPP-CONFIG>STATUS >R
        DROP R> R> DROP EXIT
    THEN
    DROP
    DUP AT-OAUTH-PAR-STATUS-VALID? 0= IF
        DROP AT-OAUTH-PAR-S-INTERNAL
    THEN
    R> DROP ;

