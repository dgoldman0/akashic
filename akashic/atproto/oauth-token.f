: _ATOT-PREPARE-GEOMETRY
  ( config profile authorization request workspace -- status )
    DUP AT-OAUTH-TOKEN-WORKSPACE-SIZE _ATOT-FIXED-STATUS
    ?DUP IF _ATOT-RETURN5 EXIT THEN
