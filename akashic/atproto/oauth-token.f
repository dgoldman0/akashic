\ =====================================================================
\  oauth-token.f - AT public authorization-code token exchange
\ =====================================================================
\  This thin AT-specific adapter joins one immutable public-client
\  selection and ready profile to the generic protected token-request,
\  OAuth form POST, issuer-bound DPoP nonce, OAuth error, and AT grant
\  owners.  It performs no transport, proof construction, clock sampling,
\  persistence, refresh, confidential-client authentication, XRPC, or
\  Streams work.
\
\  Public API:
\    AT-OAUTH-TOKEN-WORKSPACE-SIZE
\    AT-OAUTH-TOKEN-WORKSPACE-CLEAR
\    AT-OAUTH-TOKEN-STATUS-VALID?
\    AT-OAUTH-TOKEN-PREPARE
\    AT-OAUTH-TOKEN-BUILD
\    AT-OAUTH-TOKEN-ACCEPT-NONCE-CHALLENGE
\    AT-OAUTH-TOKEN-ACCEPT-SUCCESS
\ =====================================================================

