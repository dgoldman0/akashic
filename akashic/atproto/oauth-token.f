    DUP 0< IF 2DROP AT-OAUTH-TOKEN-S-INVALID EXIT THEN
    DUP 0= IF 2DROP AT-OAUTH-TOKEN-S-OK EXIT THEN
    OVER 0= IF 2DROP AT-OAUTH-TOKEN-S-INVALID EXIT THEN
