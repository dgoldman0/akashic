    ?DUP IF _ATOT-RETURN5 EXIT THEN
    2 PICK O2CODE-TRANSACTION-SIZE _ATOT-FIXED-STATUS
    ?DUP IF _ATOT-RETURN5 EXIT THEN
    1 PICK O2TREQ-SIZE _ATOT-FIXED-STATUS
    ?DUP IF _ATOT-RETURN5 EXIT THEN

    4 PICK OAUTH2-CLIENT-CONFIG-SIZE
    2 PICK AT-OAUTH-TOKEN-WORKSPACE-SIZE MSPAN-OVERLAP? IF
        AT-OAUTH-TOKEN-S-ALIAS _ATOT-RETURN5 EXIT
