\ This is the consume threshold.  Failures before it can describe a
\ cross-wired current selection or retained result, so they leave O2TREQ
\ awaiting.  Once it succeeds, this exact attempt owns the response and any
\ non-retryable response-policy failure must terminally destroy its secrets.
