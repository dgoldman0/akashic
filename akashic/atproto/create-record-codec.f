    [CHAR] : R@ _ATCRC-CHAR ?DUP IF R> DROP 0 SWAP EXIT THEN
    R@ _ATCRW.RKEY-A @ R@ _ATCRW.RKEY-U @
    R@ _ATCRC-STRING ?DUP IF R> DROP 0 SWAP EXIT THEN
    [CHAR] , R@ _ATCRC-CHAR ?DUP IF R> DROP 0 SWAP EXIT THEN
    S" record" R@ _ATCRC-STRING ?DUP IF R> DROP 0 SWAP EXIT THEN
    [CHAR] : R@ _ATCRC-CHAR ?DUP IF R> DROP 0 SWAP EXIT THEN
    R@ _ATCRW.RECORD-A @ R@ _ATCRW.RECORD-U @
    R@ _ATCRC-APPEND ?DUP IF R> DROP 0 SWAP EXIT THEN
    [CHAR] } R@ _ATCRC-CHAR ?DUP IF R> DROP 0 SWAP EXIT THEN
    R@ _ATCRW.WRITER CBW-RESULT
    _ATCRC-CBW>STATUS
    ROT DROP
    DUP IF
        >R DROP R> R> DROP 0 SWAP EXIT
    THEN
    DROP
    DUP R@ _ATCRW.STAGED-U1 !
    DUP R@ _ATCRW.STAGED-U2 @ <> IF
        DROP R> DROP 0 AT-CREATE-RECORD-S-INTERNAL EXIT
    THEN
    R@ _ATCRW.STAGING R@ _ATCRW.DESTINATION @
    R@ _ATCRW.STAGED-U1 @ MOVE
    AT-CREATE-RECORD-S-OK
    R> DROP ;

: _ATCRC-ADMIT-BODY  ( workspace -- status )
    >R
    R@ _ATCRW.REPO-A @ R@ _ATCRW.REPO-U @ DID-VALIDATE
    DID-S-OK <> IF R> DROP AT-CREATE-RECORD-S-REPOSITORY EXIT THEN
    R@ _ATCRW.COLLECTION-A @ R@ _ATCRW.COLLECTION-U @ NSID-CHECK
    NSID-S-OK <> IF R> DROP AT-CREATE-RECORD-S-COLLECTION EXIT THEN
    R@ _ATCRC-CANONICAL-COLLECTION? 0= IF
        R> DROP AT-CREATE-RECORD-S-COLLECTION EXIT
    THEN
    R@ _ATCRW.RKEY-A @ R@ _ATCRW.RKEY-U @ AT-RKEY-VALIDATE
    AT-RKEY-S-OK <> IF R> DROP AT-CREATE-RECORD-S-RKEY EXIT THEN
    R@ _ATCRC-ADMIT-RECORD
    R> DROP ;

