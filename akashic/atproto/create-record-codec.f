    R@ _ATCRW.RECORD-U @ R@ _ATCRW.SOURCE-U !
    0 R@ _ATCRW.PRESENT !
    R@ _ATCRC-PARSE-OBJECT
    ?DUP IF NIP R> DROP EXIT THEN
    R@ _ATCRC-PROCESS-RECORD
    R> DROP ;

