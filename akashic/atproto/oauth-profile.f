: _ATOP-BUILD-RESOURCE-METADATA-TARGET  ( profile -- status )
    DUP _ATOP.SCRATCH HTARGET-URI-CAPACITY 0 FILL
    DUP _ATOP.PDS HTARGET-URI$
    DUP S" .well-known/oauth-protected-resource" NIP +
    HTARGET-URI-CAPACITY U> IF
        2DROP
        DUP _ATOP.SCRATCH HTARGET-URI-CAPACITY 0 FILL
        DROP AT-OAUTH-PROFILE-S-CAPACITY EXIT
    THEN
    2 PICK _ATOP.SCRATCH SWAP MOVE

    S" .well-known/oauth-protected-resource"
    2 PICK _ATOP.PDS HTARGET-URI$ NIP
    3 PICK _ATOP.SCRATCH + SWAP MOVE

    DUP _ATOP.SCRATCH
    OVER _ATOP.PDS HTARGET-URI$ NIP
    S" .well-known/oauth-protected-resource" NIP +
    2 PICK _ATOP.RESOURCE-METADATA
    HTARGET-PARSE
    HTARGET-S-OK <> IF
        DUP _ATOP.SCRATCH HTARGET-URI-CAPACITY 0 FILL
        DROP AT-OAUTH-PROFILE-S-INTERNAL EXIT
    THEN
    DUP _ATOP.RESOURCE-METADATA
    OVER _ATOP.RESOURCE-METADATA-CHECK
    _ATOP-TARGET-CHECK!
    DUP _ATOP.SCRATCH HTARGET-URI-CAPACITY 0 FILL
    DROP AT-OAUTH-PROFILE-S-OK ;

: _ATOP-BUILD-AS-METADATA-TARGET  ( profile -- status )
    DUP _ATOP.SCRATCH HTARGET-URI-CAPACITY 0 FILL
    DUP _ATOP.AUTHORIZATION-SERVER HTARGET-URI$
    DUP S" .well-known/oauth-authorization-server" NIP +
    HTARGET-URI-CAPACITY U> IF
        2DROP
        DUP _ATOP.SCRATCH HTARGET-URI-CAPACITY 0 FILL
        DROP AT-OAUTH-PROFILE-S-CAPACITY EXIT
    THEN
    2 PICK _ATOP.SCRATCH SWAP MOVE

    S" .well-known/oauth-authorization-server"
    2 PICK _ATOP.AUTHORIZATION-SERVER HTARGET-URI$ NIP
    3 PICK _ATOP.SCRATCH + SWAP MOVE

    DUP _ATOP.SCRATCH
    OVER _ATOP.AUTHORIZATION-SERVER HTARGET-URI$ NIP
    S" .well-known/oauth-authorization-server" NIP +
    2 PICK _ATOP.AUTHORIZATION-SERVER-METADATA
    HTARGET-PARSE
    HTARGET-S-OK <> IF
        DUP _ATOP.SCRATCH HTARGET-URI-CAPACITY 0 FILL
        DROP AT-OAUTH-PROFILE-S-INTERNAL EXIT
    THEN
    DUP _ATOP.AUTHORIZATION-SERVER-METADATA
    OVER _ATOP.AUTHORIZATION-SERVER-METADATA-CHECK
    _ATOP-TARGET-CHECK!
    DUP _ATOP.SCRATCH HTARGET-URI-CAPACITY 0 FILL
    DROP AT-OAUTH-PROFILE-S-OK ;

