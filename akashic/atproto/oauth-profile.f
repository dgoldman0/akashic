: _ATOP-IDENTITY-ACCESS-STATUS  ( profile -- status )
    DUP AT-OAUTH-PROFILE-VALID? 0= IF
        DROP AT-OAUTH-PROFILE-S-INVALID EXIT
    THEN
    DUP _ATOP.PHASE @ AT-OAUTH-PROFILE-PHASE-FAILED = IF
        _ATOP.STATUS @ EXIT
    THEN
    _ATOP.PHASE @
    DUP AT-OAUTH-PROFILE-PHASE-RESOURCE-METADATA >=
    SWAP AT-OAUTH-PROFILE-PHASE-READY <= AND IF
        AT-OAUTH-PROFILE-S-OK
    ELSE
        AT-OAUTH-PROFILE-S-STATE
    THEN ;

: _ATOP-AUTHORITY-ACCESS-STATUS  ( profile -- status )
    DUP AT-OAUTH-PROFILE-VALID? 0= IF
        DROP AT-OAUTH-PROFILE-S-INVALID EXIT
    THEN
    DUP _ATOP.PHASE @ AT-OAUTH-PROFILE-PHASE-FAILED = IF
        _ATOP.STATUS @ EXIT
    THEN
    _ATOP.PHASE @
    DUP AT-OAUTH-PROFILE-PHASE-AUTHORIZATION-SERVER-METADATA >=
    SWAP AT-OAUTH-PROFILE-PHASE-READY <= AND IF
        AT-OAUTH-PROFILE-S-OK
    ELSE
        AT-OAUTH-PROFILE-S-STATE
    THEN ;

: _ATOP-READY-ACCESS-STATUS  ( profile -- status )
    DUP AT-OAUTH-PROFILE-VALID? 0= IF
        DROP AT-OAUTH-PROFILE-S-INVALID EXIT
    THEN
    DUP _ATOP.PHASE @ AT-OAUTH-PROFILE-PHASE-FAILED = IF
        _ATOP.STATUS @ EXIT
    THEN
    _ATOP.PHASE @ AT-OAUTH-PROFILE-PHASE-READY = IF
        AT-OAUTH-PROFILE-S-OK
    ELSE
        AT-OAUTH-PROFILE-S-STATE
    THEN ;

