    R@ _ATOP-BUILD-AS-METADATA-TARGET
    DUP AT-OAUTH-PROFILE-S-OK <> IF
        R@ _ATOP-FAIL R> DROP EXIT
    THEN
    DROP
    AT-OAUTH-PROFILE-PHASE-AUTHORIZATION-SERVER-METADATA
    R@ _ATOP.PHASE !
    R> DROP
    AT-OAUTH-PROFILE-S-OK ;

