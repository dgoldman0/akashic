\ =====================================================================
\  oauth-profile.f - AT Protocol OAuth discovery-profile composition
\ =====================================================================
\  This module binds a resolved AT Protocol identity to the OAuth
\  authorization server selected by its PDS.  It performs no HTTP, DNS,
\  browser, token, DPoP, session, vault, XRPC, or application work.
\
\  The caller supplies already-validated generic metadata objects:
\    1. BEGIN copies a resolved DID and canonical PDS origin.
\    2. RESOURCE! binds RFC 9728 protected-resource metadata exactly to
\       that PDS and selects its one canonical authorization-server origin.
\    3. AUTHORIZATION-SERVER! binds RFC 8414 metadata exactly to that
\       selected issuer and enforces the AT Protocol OAuth profile.
\
\  All retained bytes and parsed HTTPS targets live in one caller-owned
\  object.  Semantic trust-chain failures wipe partial results and publish
\  a terminal FAILED phase.  Caller geometry and state errors do not alter
\  the object.  Reinitialization is the only transition out of FAILED.
\
\  Public API:
\    AT-OAUTH-PROFILE-SIZE
\    AT-OAUTH-PROFILE-STATUS-VALID?
\    AT-OAUTH-PROFILE-INIT
\    AT-OAUTH-PROFILE-WIPE
\    AT-OAUTH-PROFILE-VALID?
\    AT-OAUTH-PROFILE-READY?
\    AT-OAUTH-PROFILE-BEGIN
\    AT-OAUTH-PROFILE-RESOURCE!
\    AT-OAUTH-PROFILE-AUTHORIZATION-SERVER!
\    AT-OAUTH-PROFILE-PHASE@
\    AT-OAUTH-PROFILE-STATUS@
\    AT-OAUTH-PROFILE-DID@
\    AT-OAUTH-PROFILE-RESOURCE@
\    AT-OAUTH-PROFILE-PDS-TARGET@
\    AT-OAUTH-PROFILE-RESOURCE-METADATA-TARGET@
\    AT-OAUTH-PROFILE-ISSUER@
\    AT-OAUTH-PROFILE-AUTHORIZATION-SERVER-TARGET@
\    AT-OAUTH-PROFILE-AUTHORIZATION-SERVER-METADATA-TARGET@
\    AT-OAUTH-PROFILE-AUTHORIZATION-TARGET@
\    AT-OAUTH-PROFILE-TOKEN-TARGET@
\    AT-OAUTH-PROFILE-PAR-TARGET@
\ =====================================================================

\ KDOS module identities are bounded to 23 bytes.
