    1 <> IF
        DROP
        AT-OAUTH-PROFILE-S-AUTHORIZATION-SERVER R@ _ATOP-FAIL
        R> DROP EXIT
    THEN

    0 OVER OAUTH2-RESOURCE-METADATA-AUTHORIZATION-SERVER@
    DUP OAUTH2-RESOURCE-METADATA-S-OK <> IF
        >R 2DROP DROP R> DROP
        AT-OAUTH-PROFILE-S-AUTHORIZATION-SERVER R@ _ATOP-FAIL
        R> DROP EXIT
    THEN
    DROP
    2DUP R@ _ATOP.AUTHORIZATION-SERVER HTARGET-PARSE
    HTARGET-S-OK <> IF
        2DROP DROP
        AT-OAUTH-PROFILE-S-AUTHORIZATION-SERVER R@ _ATOP-FAIL
        R> DROP EXIT
    THEN
    R@ _ATOP.AUTHORIZATION-SERVER
    R@ _ATOP.AUTHORIZATION-SERVER-CHECK
    _ATOP-TARGET-CHECK!
    2DUP R@ _ATOP.AUTHORIZATION-SERVER
    _ATOP-CANONICAL-ORIGIN? 0= IF
