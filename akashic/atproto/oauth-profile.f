: _ATOP-BEGIN-ADMITTED  ( identity-result profile -- status )
    >R
    DUP ATID-DID@
    DUP ATID-S-OK <> IF
        >R 2DROP DROP R> DROP
        AT-OAUTH-PROFILE-S-IDENTITY R@ _ATOP-FAIL
        R> DROP EXIT
    THEN
    DROP
    DUP AT-OAUTH-PROFILE-DID-CAPACITY U> IF
        2DROP DROP
        AT-OAUTH-PROFILE-S-CAPACITY R@ _ATOP-FAIL
        R> DROP EXIT
    THEN

    2 PICK ATID-PDS-TARGET@
    DUP ATID-S-OK <> IF
        >R DROP 2DROP DROP R> DROP
        AT-OAUTH-PROFILE-S-IDENTITY R@ _ATOP-FAIL
        R> DROP EXIT
    THEN
    DROP
    DUP _ATOP-ORIGIN-TARGET? 0= IF
        DROP 2DROP DROP
        AT-OAUTH-PROFILE-S-IDENTITY R@ _ATOP-FAIL
        R> DROP EXIT
    THEN

    DUP HTARGET-URI$ R@ _ATOP.PDS HTARGET-PARSE
    HTARGET-S-OK <> IF
        DROP 2DROP DROP
        AT-OAUTH-PROFILE-S-INTERNAL R@ _ATOP-FAIL
        R> DROP EXIT
    THEN
    DROP

    R@ _ATOP.PDS R@ _ATOP.PDS-CHECK
    _ATOP-TARGET-CHECK!
    DUP R@ _ATOP.DID-U !
    2DUP R@ _ATOP.DID SWAP MOVE
    2DROP DROP

    R@ _ATOP-BUILD-RESOURCE-METADATA-TARGET
    DUP AT-OAUTH-PROFILE-S-OK <> IF
        R@ _ATOP-FAIL R> DROP EXIT
    THEN
    DROP
    AT-OAUTH-PROFILE-PHASE-RESOURCE-METADATA
    R@ _ATOP.PHASE !
    R> DROP
    AT-OAUTH-PROFILE-S-OK ;

: AT-OAUTH-PROFILE-BEGIN  ( identity-result profile -- status )
    DUP _ATOP-OBJECT-STATUS ?DUP IF
        >R 2DROP R> EXIT
    THEN
    DUP AT-OAUTH-PROFILE-VALID? 0= IF
        2DROP AT-OAUTH-PROFILE-S-INVALID EXIT
    THEN
    DUP _ATOP.PHASE @ AT-OAUTH-PROFILE-PHASE-EMPTY <> IF
        2DROP AT-OAUTH-PROFILE-S-STATE EXIT
    THEN
    >R

    DUP ATID-RESULT-SIZE _ATOP-FIXED-STATUS ?DUP IF
        SWAP DROP R> DROP EXIT
    THEN
    DUP ATID-RESULT-SIZE
    R@ AT-OAUTH-PROFILE-SIZE MSPAN-OVERLAP? IF
        DROP R> DROP AT-OAUTH-PROFILE-S-ALIAS EXIT
    THEN
    DUP ATID-RESULT-READY? 0= IF
        DROP
        AT-OAUTH-PROFILE-S-IDENTITY R@ _ATOP-FAIL
        R> DROP EXIT
    THEN
    R> _ATOP-BEGIN-ADMITTED ;

: _ATOP-RESOURCE-ADMITTED
  ( resource-metadata profile -- status )
    >R
    DUP OAUTH2-RESOURCE-METADATA-RESOURCE@
    DUP OAUTH2-RESOURCE-METADATA-S-OK <> IF
        >R 2DROP DROP R> DROP
        AT-OAUTH-PROFILE-S-RESOURCE-METADATA R@ _ATOP-FAIL
        R> DROP EXIT
    THEN
    DROP
    2DUP R@ _ATOP.PDS _ATOP-CANONICAL-ORIGIN? 0= IF
