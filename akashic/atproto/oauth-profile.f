: _ATOP-CALLER>STATUS  ( caller-status -- status )
    DUP CALLER-SPAN-S-OK = IF
        DROP AT-OAUTH-PROFILE-S-OK EXIT
    THEN
    DUP CALLER-SPAN-S-RANGE = IF
        DROP AT-OAUTH-PROFILE-S-RANGE EXIT
    THEN
    DUP CALLER-SPAN-S-PROTECTED = IF
        DROP AT-OAUTH-PROFILE-S-PROTECTED EXIT
    THEN
    DUP CALLER-SPAN-S-PLATFORM = IF
        DROP AT-OAUTH-PROFILE-S-PLATFORM EXIT
    THEN
    DROP AT-OAUTH-PROFILE-S-PLATFORM ;

: _ATOP-SPAN-STATUS  ( address length -- status )
    DUP 0< IF 2DROP AT-OAUTH-PROFILE-S-INVALID EXIT THEN
    DUP 0= IF 2DROP AT-OAUTH-PROFILE-S-OK EXIT THEN
    OVER 0= IF 2DROP AT-OAUTH-PROFILE-S-INVALID EXIT THEN
    CALLER-SPAN-STATUS _ATOP-CALLER>STATUS ;

: _ATOP-FIXED-STATUS  ( address size -- status )
    OVER 0= IF 2DROP AT-OAUTH-PROFILE-S-INVALID EXIT THEN
    OVER 7 AND IF 2DROP AT-OAUTH-PROFILE-S-INVALID EXIT THEN
    _ATOP-SPAN-STATUS ;

: _ATOP-OBJECT-STATUS  ( profile -- status )
    AT-OAUTH-PROFILE-SIZE _ATOP-FIXED-STATUS ;

: _ATOP-ZERO?  ( address length -- flag )
    BEGIN
        DUP
    WHILE
        OVER C@ IF 2DROP 0 EXIT THEN
        1 /STRING
    REPEAT
    2DROP -1 ;

: _ATOP-PAD-ZERO?  ( base used capacity -- flag )
    >R
    2DUP +
    R> ROT -
    _ATOP-ZERO?
    NIP ;

: _ATOP-BITS-CONTAIN?  ( actual required -- flag )
    TUCK AND = ;

: _ATOP-TARGET-HASH  ( target -- hash )
    0xCBF29CE484222325
    HTARGET-SIZE 0 ?DO
        OVER I + C@ XOR
        0x100000001B3 *
    LOOP
    NIP ;

: _ATOP-TARGET-CHECK!  ( target check-field -- )
    SWAP _ATOP-TARGET-HASH SWAP ! ;

: _ATOP-TARGET-CHECKED?  ( target check-field -- flag )
    @ SWAP _ATOP-TARGET-HASH = ;

: _ATOP-ORIGIN-TARGET?  ( target -- flag )
    DUP HTARGET-VALID? 0= IF DROP 0 EXIT THEN
    DUP HTARGET-REDIRECT-COUNT@ IF DROP 0 EXIT THEN
    DUP HTARGET-URI$
    DUP 0= IF 2DROP DROP 0 EXIT THEN
    2DUP + 1- C@ [CHAR] / <> IF 2DROP DROP 0 EXIT THEN
    2DROP
    HTARGET-REQUEST-TARGET$ S" /" COMPARE 0= ;

\ Return the canonical OAuth resource/issuer serialization.  HTARGET keeps
\ an origin target as ".../"; AT OAuth and RFC exact binding use the same
\ canonical origin without that sole root slash.
: _ATOP-ORIGIN$  ( target -- address length )
    HTARGET-URI$ 1- ;

: _ATOP-CANONICAL-ORIGIN?  ( address length target -- flag )
    >R
    R@ _ATOP-ORIGIN-TARGET? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    R@ _ATOP-ORIGIN$
    2SWAP COMPARE 0=
    R> DROP ;

: _ATOP-RESOURCE-TARGET?  ( profile -- flag )
    DUP _ATOP.PDS
    OVER _ATOP.RESOURCE-METADATA
    HTARGET-SAME-ORIGIN? 0= IF DROP 0 EXIT THEN
    _ATOP.RESOURCE-METADATA HTARGET-REQUEST-TARGET$
    S" /.well-known/oauth-protected-resource"
    COMPARE 0= ;

: _ATOP-AS-METADATA-TARGET?  ( profile -- flag )
    DUP _ATOP.AUTHORIZATION-SERVER
    OVER _ATOP.AUTHORIZATION-SERVER-METADATA
    HTARGET-SAME-ORIGIN? 0= IF DROP 0 EXIT THEN
    _ATOP.AUTHORIZATION-SERVER-METADATA HTARGET-REQUEST-TARGET$
    S" /.well-known/oauth-authorization-server"
    COMPARE 0= ;

