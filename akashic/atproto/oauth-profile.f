: _ATOP-PAYLOAD-ZERO?  ( profile -- flag )
    _ATOP-DID-U +
    AT-OAUTH-PROFILE-SIZE _ATOP-DID-U -
    _ATOP-ZERO? ;

: _ATOP-EMPTY-SHAPE?  ( profile -- flag )
    DUP _ATOP.STATUS @ AT-OAUTH-PROFILE-S-OK <> IF
        DROP 0 EXIT
    THEN
    _ATOP-PAYLOAD-ZERO? ;

: _ATOP-IDENTITY-SHAPE?  ( profile -- flag )
    DUP _ATOP.STATUS @ AT-OAUTH-PROFILE-S-OK <> IF
        DROP 0 EXIT
    THEN
    DUP _ATOP.RESERVED @ IF DROP 0 EXIT THEN
    DUP _ATOP.DID-U @
    DUP 0> 0= SWAP AT-OAUTH-PROFILE-DID-CAPACITY > OR IF
        DROP 0 EXIT
    THEN
    DUP _ATOP.DID OVER _ATOP.DID-U @
    DID-VALID? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.DID OVER _ATOP.DID-U @
    AT-OAUTH-PROFILE-DID-CAPACITY
    _ATOP-PAD-ZERO? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.PDS OVER _ATOP.PDS-CHECK
    _ATOP-TARGET-CHECKED? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.RESOURCE-METADATA
    OVER _ATOP.RESOURCE-METADATA-CHECK
    _ATOP-TARGET-CHECKED? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.PDS _ATOP-ORIGIN-TARGET? 0= IF DROP 0 EXIT THEN
    DUP _ATOP-RESOURCE-TARGET? 0= IF DROP 0 EXIT THEN
    DROP -1 ;

: _ATOP-AUTHORITY-SHAPE?  ( profile -- flag )
    DUP _ATOP-IDENTITY-SHAPE? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.AUTHORIZATION-SERVER
    OVER _ATOP.AUTHORIZATION-SERVER-CHECK
    _ATOP-TARGET-CHECKED? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.AUTHORIZATION-SERVER-METADATA
    OVER _ATOP.AUTHORIZATION-SERVER-METADATA-CHECK
    _ATOP-TARGET-CHECKED? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.AUTHORIZATION-SERVER
    _ATOP-ORIGIN-TARGET? 0= IF DROP 0 EXIT THEN
    DUP _ATOP-AS-METADATA-TARGET? 0= IF DROP 0 EXIT THEN
    DROP -1 ;

: _ATOP-RESOURCE-PHASE-SHAPE?  ( profile -- flag )
    DUP _ATOP-IDENTITY-SHAPE? 0= IF DROP 0 EXIT THEN
    _ATOP.AUTHORIZATION-SERVER
    AT-OAUTH-PROFILE-SIZE
    _ATOP-AUTHORIZATION-SERVER-OFF -
    _ATOP-ZERO? ;

: _ATOP-AS-PHASE-SHAPE?  ( profile -- flag )
    DUP _ATOP-AUTHORITY-SHAPE? 0= IF DROP 0 EXIT THEN
    _ATOP.AUTHORIZATION
    AT-OAUTH-PROFILE-SIZE _ATOP-AUTHORIZATION-OFF -
    _ATOP-ZERO? ;

: _ATOP-READY-SHAPE?  ( profile -- flag )
    DUP _ATOP-AUTHORITY-SHAPE? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.AUTHORIZATION OVER _ATOP.AUTHORIZATION-CHECK
    _ATOP-TARGET-CHECKED? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.TOKEN OVER _ATOP.TOKEN-CHECK
    _ATOP-TARGET-CHECKED? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.PAR OVER _ATOP.PAR-CHECK
    _ATOP-TARGET-CHECKED? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.AUTHORIZATION HTARGET-VALID? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.AUTHORIZATION HTARGET-REDIRECT-COUNT@ IF
        DROP 0 EXIT
    THEN
    DUP _ATOP.TOKEN HTARGET-VALID? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.TOKEN HTARGET-REDIRECT-COUNT@ IF DROP 0 EXIT THEN
    DUP _ATOP.PAR HTARGET-VALID? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.PAR HTARGET-REDIRECT-COUNT@ IF DROP 0 EXIT THEN
    _ATOP.SCRATCH HTARGET-URI-CAPACITY _ATOP-ZERO? ;

: _ATOP-FAILED-SHAPE?  ( profile -- flag )
    DUP _ATOP.STATUS @
    DUP AT-OAUTH-PROFILE-STATUS-VALID? 0= IF
        2DROP 0 EXIT
    THEN
    AT-OAUTH-PROFILE-S-OK = IF DROP 0 EXIT THEN
    _ATOP-PAYLOAD-ZERO? ;

: AT-OAUTH-PROFILE-VALID?  ( profile -- flag )
    DUP _ATOP-OBJECT-STATUS ?DUP IF 2DROP 0 EXIT THEN
    DUP _ATOP.MAGIC @ _ATOP-MAGIC-VALUE <> IF DROP 0 EXIT THEN
    DUP _ATOP.PHASE @
    AT-OAUTH-PROFILE-PHASE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.STATUS @
    AT-OAUTH-PROFILE-STATUS-VALID? 0= IF DROP 0 EXIT THEN
    DUP _ATOP.PHASE @
    DUP AT-OAUTH-PROFILE-PHASE-EMPTY = IF
        DROP _ATOP-EMPTY-SHAPE? EXIT
    THEN
    DUP AT-OAUTH-PROFILE-PHASE-RESOURCE-METADATA = IF
        DROP _ATOP-RESOURCE-PHASE-SHAPE? EXIT
    THEN
    DUP AT-OAUTH-PROFILE-PHASE-AUTHORIZATION-SERVER-METADATA = IF
        DROP _ATOP-AS-PHASE-SHAPE? EXIT
    THEN
    DUP AT-OAUTH-PROFILE-PHASE-READY = IF
        DROP _ATOP-READY-SHAPE? EXIT
    THEN
    AT-OAUTH-PROFILE-PHASE-FAILED = IF
        _ATOP-FAILED-SHAPE? EXIT
    THEN
    DROP 0 ;

: AT-OAUTH-PROFILE-READY?  ( profile -- flag )
    DUP AT-OAUTH-PROFILE-VALID? IF
        _ATOP.PHASE @ AT-OAUTH-PROFILE-PHASE-READY =
    ELSE
        DROP 0
    THEN ;

: AT-OAUTH-PROFILE-INIT  ( profile -- status )
    DUP _ATOP-OBJECT-STATUS ?DUP IF NIP EXIT THEN
    DUP AT-OAUTH-PROFILE-SIZE 0 FILL
    _ATOP-MAGIC-VALUE OVER _ATOP.MAGIC !
    DROP AT-OAUTH-PROFILE-S-OK ;

: AT-OAUTH-PROFILE-WIPE  ( profile -- status )
    DUP _ATOP-OBJECT-STATUS ?DUP IF NIP EXIT THEN
    AT-OAUTH-PROFILE-SIZE 0 FILL
    AT-OAUTH-PROFILE-S-OK ;

: _ATOP-FAIL  ( status profile -- status )
    >R
    DUP AT-OAUTH-PROFILE-STATUS-VALID? 0=
    OVER AT-OAUTH-PROFILE-S-OK = OR IF
        DROP AT-OAUTH-PROFILE-S-INTERNAL
    THEN
    R@ AT-OAUTH-PROFILE-SIZE 0 FILL
    _ATOP-MAGIC-VALUE R@ _ATOP.MAGIC !
    AT-OAUTH-PROFILE-PHASE-FAILED R@ _ATOP.PHASE !
    DUP R@ _ATOP.STATUS !
    R> DROP ;

