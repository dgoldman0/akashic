: _ATX-SCOPE-HAS-ATPROTO?  ( scope-a scope-u -- flag )
    BEGIN
        DUP 0> IF OVER C@ BL = ELSE 0 THEN
    WHILE
        1 /STRING
    REPEAT
    DUP 0= IF 2DROP 0 EXIT THEN
    2DUP BL STR-INDEX
    DUP 0< IF
        DROP S" atproto" STR-STR= EXIT
    THEN
    >R
    OVER R@ S" atproto" STR-STR= IF
        2DROP R> DROP -1 EXIT
    THEN
    R> 1+ /STRING
    RECURSE ;

