    >R
    R@ _ATXW.INPUT AT-XRPC-AUTH-REQUEST-I.PROFILE @
    AT-OAUTH-PROFILE-PDS-TARGET@
    DUP AT-OAUTH-PROFILE-S-OK <> IF
        _ATX-PROFILE>STATUS >R
        DROP R> R> DROP EXIT
    THEN
    DROP
    R@ _ATXW.INPUT AT-XRPC-AUTH-REQUEST-I.TARGET @
    HTARGET-SAME-ORIGIN? 0= IF
        R> DROP AT-XRPC-S-TARGET EXIT
    THEN
    R@ _ATXW.INPUT AT-XRPC-AUTH-REQUEST-I.TARGET @
    _ATX-XRPC-TARGET? 0= IF
        R> DROP AT-XRPC-S-TARGET EXIT
    THEN
    R@ _ATXW.INPUT AT-XRPC-AUTH-REQUEST-I.METHOD @
    AT-XRPC-METHOD-POST = IF
        R@ _ATXW.INPUT AT-XRPC-AUTH-REQUEST-I.TARGET @
        HTARGET-REQUEST-TARGET$ [CHAR] ? STR-INDEX 0>= IF
            R> DROP AT-XRPC-S-TARGET EXIT
        THEN
    THEN

    R@ _ATXW.INPUT AT-XRPC-AUTH-REQUEST-I.PROFILE @
    AT-OAUTH-PROFILE-ISSUER@
    DUP AT-OAUTH-PROFILE-S-OK <> IF
        _ATX-PROFILE>STATUS >R
        2DROP
        R> R> DROP EXIT
    THEN
    DROP
    DUP R@ _ATXW.EXPECTED-U !
    SWAP R@ _ATXW.EXPECTED-A !
    DROP
    R> DROP AT-XRPC-S-OK ;

