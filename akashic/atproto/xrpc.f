    ?DUP IF NIP R> DROP EXIT THEN
    R@ AT-XRPC-AUTH-REQUEST-WORKSPACE-SIZE
    2 PICK _ATX-VAULT-SPAN-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.CONFIG @ OAUTH2-CLIENT-CONFIG-SIZE
    2 PICK _ATX-VAULT-SPAN-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.PROFILE @ AT-OAUTH-PROFILE-SIZE
    2 PICK _ATX-VAULT-SPAN-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.SESSION @ OAUTH2-SESSION-SIZE
    2 PICK _ATX-VAULT-SPAN-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.TARGET @ HTARGET-SIZE
    2 PICK _ATX-VAULT-SPAN-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.REQUEST @ HTTP-REQUEST-SIZE
    2 PICK _ATX-VAULT-SPAN-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.REQUEST-A @
    OVER AT-XRPC-AUTH-REQUEST-I.REQUEST-CAP @
    2 PICK _ATX-VAULT-SPAN-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.NONCE-A @
    OVER AT-XRPC-AUTH-REQUEST-I.NONCE-U @
    2 PICK _ATX-VAULT-SPAN-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.PROXY-A @
    OVER AT-XRPC-AUTH-REQUEST-I.PROXY-U @
    2 PICK _ATX-VAULT-SPAN-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.BODY-A @
    OVER AT-XRPC-AUTH-REQUEST-I.BODY-U @
    2 PICK _ATX-VAULT-SPAN-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DROP R> DROP AT-XRPC-S-OK ;

