: _ATX-FIELD-GEOMETRY  ( input workspace -- status )
    >R
    DUP AT-XRPC-AUTH-REQUEST-INPUT-SIZE _ATX-FIXED-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    R@ AT-XRPC-AUTH-REQUEST-WORKSPACE-SIZE _ATX-FIXED-STATUS
    ?DUP IF NIP R> DROP EXIT THEN

    DUP AT-XRPC-AUTH-REQUEST-I.IAT @ 0< IF
        DROP R> DROP AT-XRPC-S-INVALID EXIT
    THEN
    DUP AT-XRPC-AUTH-REQUEST-I.METHOD @
        AT-XRPC-METHOD-VALID? 0= IF
        DROP R> DROP AT-XRPC-S-INVALID EXIT
    THEN
    DUP AT-XRPC-AUTH-REQUEST-I.VAULT @
        CVAULT-SIZE _ATX-FIXED-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.CONFIG @
        OAUTH2-CLIENT-CONFIG-SIZE _ATX-FIXED-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.PROFILE @
        AT-OAUTH-PROFILE-SIZE _ATX-FIXED-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.SESSION @
        OAUTH2-SESSION-SIZE _ATX-FIXED-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.TARGET @
        HTARGET-SIZE _ATX-FIXED-STATUS
    ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.REQUEST @
        HTTP-REQUEST-SIZE _ATX-FIXED-STATUS
    ?DUP IF NIP R> DROP EXIT THEN

    DUP AT-XRPC-AUTH-REQUEST-I.NONCE-A @
    OVER AT-XRPC-AUTH-REQUEST-I.NONCE-U @
    _ATX-SPAN-STATUS ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.PROXY-A @
    OVER AT-XRPC-AUTH-REQUEST-I.PROXY-U @
    _ATX-SPAN-STATUS ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.BODY-A @
    OVER AT-XRPC-AUTH-REQUEST-I.BODY-U @
    _ATX-SPAN-STATUS ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.METHOD @
        AT-XRPC-METHOD-GET =
    OVER AT-XRPC-AUTH-REQUEST-I.BODY-U @ 0<> AND IF
        DROP R> DROP AT-XRPC-S-INVALID EXIT
    THEN
    DUP AT-XRPC-AUTH-REQUEST-I.REQUEST-A @
    OVER AT-XRPC-AUTH-REQUEST-I.REQUEST-CAP @
    _ATX-REQUIRED-SPAN-STATUS ?DUP IF NIP R> DROP EXIT THEN
    DUP AT-XRPC-AUTH-REQUEST-I.REQUEST-CAP @ 64 < IF
        DROP R> DROP AT-XRPC-S-CAPACITY EXIT
    THEN

    DUP AT-XRPC-AUTH-REQUEST-I.VAULT @ CVAULT-VALID? 0= IF
        DROP R> DROP AT-XRPC-S-INVALID EXIT
    THEN
    DUP AT-XRPC-AUTH-REQUEST-I.CONFIG @
        OAUTH2-CLIENT-CONFIG-VALID? 0= IF
        DROP R> DROP AT-XRPC-S-CONFIG EXIT
    THEN
    DUP AT-XRPC-AUTH-REQUEST-I.PROFILE @
        AT-OAUTH-PROFILE-VALID? 0= IF
        DROP R> DROP AT-XRPC-S-PROFILE EXIT
    THEN
    DUP AT-XRPC-AUTH-REQUEST-I.SESSION @ O2SESSION-VALID? 0= IF
        DROP R> DROP AT-XRPC-S-SESSION EXIT
    THEN
    DUP AT-XRPC-AUTH-REQUEST-I.TARGET @ HTARGET-VALID? 0= IF
        DROP R> DROP AT-XRPC-S-TARGET EXIT
    THEN
    DUP AT-XRPC-AUTH-REQUEST-I.REQUEST @ HTTP-REQUEST-SIZE
        _ATX-ZERO? 0= IF
        DROP R> DROP AT-XRPC-S-REQUEST EXIT
    THEN
    DROP R> DROP AT-XRPC-S-OK ;

\ A source may be borrowed while request publication and workspace wiping
\ occur.  Reject its overlap with either mutable, with the input descriptor,
\ and with the workspace.
: _ATX-SOURCE-DISJOINT?
  ( source-a source-u input workspace -- flag )
    >R
    2 PICK 2 PICK 2 PICK AT-XRPC-AUTH-REQUEST-INPUT-SIZE
    MSPAN-OVERLAP? IF
        2DROP DROP R> DROP 0 EXIT
    THEN
    2 PICK 2 PICK R@ AT-XRPC-AUTH-REQUEST-WORKSPACE-SIZE
    MSPAN-OVERLAP? IF
        2DROP DROP R> DROP 0 EXIT
    THEN
    2 PICK 2 PICK 2 PICK AT-XRPC-AUTH-REQUEST-I.REQUEST @
        HTTP-REQUEST-SIZE MSPAN-OVERLAP? IF
        2DROP DROP R> DROP 0 EXIT
    THEN
    2 PICK 2 PICK 2 PICK AT-XRPC-AUTH-REQUEST-I.REQUEST-A @
        3 PICK AT-XRPC-AUTH-REQUEST-I.REQUEST-CAP @
        MSPAN-OVERLAP? IF
        2DROP DROP R> DROP 0 EXIT
    THEN
    2DROP DROP R> DROP -1 ;

