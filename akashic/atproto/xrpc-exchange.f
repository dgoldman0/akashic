\ =====================================================================
\  xrpc-exchange.f - Cooperative authenticated AT XRPC GET exchange
\ =====================================================================
\  One caller-owned owner binds a durable OAuth session to caller-provided
\  request and response arenas, copies one exact PDS XRPC target, builds the
\  sealed request through xrpc.f, and drives it over KDOS TLS with HBUF.
\
\  The target copied here is the single authority for the TLS host, HTTP
\  Host header, request target, and DPoP htu.  Redirects are deliberately
\  unsupported.  The token-bearing request arena is wiped as soon as a
\  detached terminal response has been proven, while the bounded response
\  body remains available until the surrounding XIO operation is reset.
\
\  A distinct embedded nonce owner is keyed to the canonical PDS resource.
\  Every clean DPoP response must carry exactly one valid DPoP-Nonce.  Only
\  the first 400 or 401 response whose strict JSON error is use_dpop_nonce
\  may rebuild and retry; the second response is always terminal.
\
\  This module owns no endpoint schema, feed model, cursor, clock, Streams
\  state, UI, credential vault, OAuth session, or response arena.
\ =====================================================================

