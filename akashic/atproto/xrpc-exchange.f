    R@ ATXE.INPUT AT-XRPC-AUTH-GET-INPUT-SIZE 0 FILL
    R@ ATXE.IAT @ R@ ATXE.INPUT AT-XRPC-AUTH-GET-I.IAT !
    R@ ATXE.VAULT @ R@ ATXE.INPUT AT-XRPC-AUTH-GET-I.VAULT !
    R@ ATXE.CONFIG @ R@ ATXE.INPUT AT-XRPC-AUTH-GET-I.CONFIG !
    R@ ATXE.PROFILE @ R@ ATXE.INPUT AT-XRPC-AUTH-GET-I.PROFILE !
    R@ ATXE.SESSION @ R@ ATXE.INPUT AT-XRPC-AUTH-GET-I.SESSION !
    R@ ATXE.TARGET R@ ATXE.INPUT AT-XRPC-AUTH-GET-I.TARGET !
    R@ ATXE.PROXY-U @ IF
        R@ ATXE.PROXY R@ ATXE.INPUT AT-XRPC-AUTH-GET-I.PROXY-A !
        R@ ATXE.PROXY-U @
            R@ ATXE.INPUT AT-XRPC-AUTH-GET-I.PROXY-U !
    THEN
    R@ ATXE.REQUEST-A @
        R@ ATXE.INPUT AT-XRPC-AUTH-GET-I.REQUEST-A !
    R@ ATXE.REQUEST-CAP @
        R@ ATXE.INPUT AT-XRPC-AUTH-GET-I.REQUEST-CAP !
    R@ ATXE.REQUEST R@ ATXE.INPUT AT-XRPC-AUTH-GET-I.REQUEST !
    R> DROP ;

: _ATXE-BUILD-DIRECT  ( owner -- status )
    DUP ATXE.INPUT SWAP ATXE.CHILD
    AT-XRPC-AUTH-GET-BUILD _ATXE-XRPC>STATUS ;

: _ATXE-BUILD-WITH-NONCE-CALLBACK
  ( nonce-a nonce-u generation owner -- status )
    >R DROP
    DUP R@ ATXE.INPUT AT-XRPC-AUTH-GET-I.NONCE-U !
    SWAP R@ ATXE.INPUT AT-XRPC-AUTH-GET-I.NONCE-A !
    DROP
    R@ _ATXE-BUILD-DIRECT
    R> DROP ;

: _ATXE-BUILD-REQUEST  ( owner -- status )
    >R
    R@ _ATXE-CLEAR-REQUEST
    R@ _ATXE-FILL-INPUT
    R@ ATXE.NONCE OAUTH2-DPOP-NONCE-VALID? IF
        ['] _ATXE-BUILD-WITH-NONCE-CALLBACK
        R@
        R@ ATXE.PDS R@ ATXE.PDS-U @
        R@ ATXE.NONCE OAUTH2-DPOP-NONCE-WITH
        DUP OAUTH2-DPOP-NONCE-S-OK <> IF
            _ATXE-NONCE>STATUS >R
            DROP R> R> DROP EXIT
        THEN
        DROP
    ELSE
        R@ _ATXE-BUILD-DIRECT
    THEN
    DUP AT-XRPC-EXCHANGE-S-OK <> IF
        R@ _ATXE-CLEAR-REQUEST
        R> DROP EXIT
    THEN
    1 R@ ATXE.ATTEMPTS +!
    R> DROP ;

