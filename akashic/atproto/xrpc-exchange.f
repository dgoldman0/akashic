        DROP AT-XRPC-EXCHANGE-S-INVALID EXIT
    THEN
    DUP ATXE.STATE @ AT-XRPC-EXCHANGE-STATE-BOUND <> IF
        DROP AT-XRPC-EXCHANGE-S-BUSY EXIT
    THEN
    DUP _ATXE-CLEAR-REQUEST
    DUP ATXE.NONCE OAUTH2-DPOP-NONCE-WIPE
    _ATXE-NONCE>STATUS ?DUP IF NIP EXIT THEN
    DUP 0 SWAP ATXE.VAULT !
