VARIABLE _ATXES-OP
VARIABLE _ATXES-X
VARIABLE _ATXES-STATUS

: _ATXE-STEP-FAIL  ( status xerr operation owner -- step-status )
    _ATXES-X ! _ATXES-OP !
    _ATXES-OP @ XIOO.ERROR !
    DUP AT-XRPC-EXCHANGE-STATUS-VALID? 0= IF
        DROP AT-XRPC-EXCHANGE-S-INTERNAL
    THEN
    DUP _ATXES-X @ ATXE.LAST-STATUS !
    AT-XRPC-EXCHANGE-STATE-FAILED _ATXES-X @ ATXE.STATE !
    DROP XIO-STEP-FAILED ;

: _ATXE-COOPERATIVE-PORT?  ( owner -- flag )
    ATXE.PORT
    DUP NIO.OPEN-START-XT @ 0<>
    OVER NIO.OPEN-POLL-XT @ 0<> AND
    SWAP NIO.CANCEL-XT @ 0<> AND ;

: _ATXE-START-HBUF  ( owner -- status )
    >R
    R@ ATXE.REQUEST R@ ATXE.PORT R@ ATXE.EXCHANGE
    HBUF-START
    DUP HBUF-S-PENDING = IF
        DROP AT-XRPC-EXCHANGE-S-OK
    ELSE
        DROP AT-XRPC-EXCHANGE-S-TRANSPORT
    THEN
    R> DROP ;

: _ATXE-RETRY  ( owner -- status )
    >R
    R@ ATXE.EXCHANGE HBUF-RESET
    R@ ATXE.EXCHANGE HBUF.PORT @ IF
        R> DROP AT-XRPC-EXCHANGE-S-CLEANUP EXIT
    THEN
    R@ _ATXE-BUILD-REQUEST ?DUP IF R> DROP EXIT THEN
    _ATXE-F-RETRIED R@ ATXE.FLAGS DUP @ ROT OR SWAP !
    R@ _ATXE-START-HBUF
    R> DROP ;

: _ATXE-RESPONSE-PROVENANCE  ( owner -- status )
    >R
    R@ ATXE.EXCHANGE HBUF.STATE @ HBUF-STATE-DONE <> IF
        R@ _ATXE-CLEAR-REQUEST
        R> DROP AT-XRPC-EXCHANGE-S-PROTOCOL EXIT
    THEN
    R@ ATXE.EXCHANGE HBUF.PORT @ IF
        R@ _ATXE-CLEAR-REQUEST
        R> DROP AT-XRPC-EXCHANGE-S-PROTOCOL EXIT
    THEN
    R@ ATXE.REQUEST HREQ.STATE @ HREQ-STATE-SENT <> IF
        R@ _ATXE-CLEAR-REQUEST
        R> DROP AT-XRPC-EXCHANGE-S-PROTOCOL EXIT
    THEN
    _ATXE-F-REQUEST-SENT R@ ATXE.FLAGS DUP @ ROT OR SWAP !
    R@ _ATXE-CLEAR-REQUEST
    R> DROP AT-XRPC-EXCHANGE-S-OK ;

: _ATXE-ADMIT-RESPONSE  ( operation owner -- step-status )
    _ATXES-X ! _ATXES-OP !
    _ATXES-X @ ATXE.EXCHANGE HBUF.HTTP-CODE @
    _ATXES-X @ ATXE.HTTP-CODE !
    _ATXES-X @ ATXE.EXCHANGE HBUF.BODY-U @
    _ATXES-X @ ATXE.BODY-U !

    _ATXES-X @ _ATXE-RESPONSE-PROVENANCE ?DUP IF
        AT-XRPC-EXCHANGE-XERR-PROTOCOL
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN
    _ATXES-X @ _ATXE-ROTATE-NONCE ?DUP IF
        AT-XRPC-EXCHANGE-XERR-NONCE
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN
    _ATXES-X @ _ATXE-CONTENT-TYPE-STATUS ?DUP IF
        AT-XRPC-EXCHANGE-XERR-PROTOCOL
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN
    _ATXES-X @ _ATXE-CONTENT-ENCODING-STATUS ?DUP IF
        AT-XRPC-EXCHANGE-XERR-PROTOCOL
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN
    _ATXES-X @ ATXE.BODY-U @ 0= IF
        AT-XRPC-EXCHANGE-S-PROTOCOL
        AT-XRPC-EXCHANGE-XERR-PROTOCOL
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN

    _ATXES-X @ ATXE.HTTP-CODE @ 200 = IF
        AT-XRPC-EXCHANGE-S-OK _ATXES-X @ ATXE.LAST-STATUS !
        AT-XRPC-EXCHANGE-STATE-READY _ATXES-X @ ATXE.STATE !
        _ATXES-X @ _ATXES-OP @ XIOO.RESULT !
        XIO-STEP-SUCCEEDED EXIT
    THEN
    _ATXES-X @ _ATXE-DPOP-NONCE-CHALLENGE?
    _ATXES-X @ ATXE.ATTEMPTS @ 1 = AND
    IF
        _ATXES-X @ _ATXE-RETRY DUP _ATXES-STATUS !
        AT-XRPC-EXCHANGE-S-OK = IF
            XIO-STEP-PENDING EXIT
        THEN
        _ATXES-STATUS @
        DUP AT-XRPC-EXCHANGE-S-NONCE = IF
            AT-XRPC-EXCHANGE-XERR-NONCE
        ELSE
            AT-XRPC-EXCHANGE-XERR-BUILD
        THEN
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN
    _ATXES-X @ _ATXE-DPOP-NONCE-CHALLENGE? IF
        AT-XRPC-EXCHANGE-S-RETRY
    ELSE
        AT-XRPC-EXCHANGE-S-HTTP
    THEN
    AT-XRPC-EXCHANGE-XERR-HTTP
    _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL ;

