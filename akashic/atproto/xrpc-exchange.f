        >R 2DROP
        0 _ATXEB-X @ ATXE.VAULT !
        0 _ATXEB-X @ ATXE.CONFIG !
        0 _ATXEB-X @ ATXE.PROFILE !
        0 _ATXEB-X @ ATXE.SESSION !
        R> DROP AT-XRPC-EXCHANGE-S-CONFIG EXIT
    THEN
    DROP
    DUP HTARGET-URI-CAPACITY U> IF
        2DROP AT-XRPC-EXCHANGE-S-CAPACITY EXIT
    THEN
    _ATXEB-PDS-U ! _ATXEB-PDS-A !
    _ATXEB-X @ ATXE.PDS HTARGET-URI-CAPACITY 0 FILL
    _ATXEB-PDS-A @ _ATXEB-X @ ATXE.PDS _ATXEB-PDS-U @ MOVE
    _ATXEB-PDS-U @ _ATXEB-X @ ATXE.PDS-U !
    _ATXEB-X @ ATXE.NONCE OAUTH2-DPOP-NONCE-SIZE 0 FILL
    AT-XRPC-EXCHANGE-S-OK _ATXEB-X @ ATXE.LAST-STATUS !
    AT-XRPC-EXCHANGE-STATE-BOUND _ATXEB-X @ ATXE.STATE !
    AT-XRPC-EXCHANGE-S-OK ;

