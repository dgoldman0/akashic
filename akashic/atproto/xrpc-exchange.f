: AT-XRPC-EXCHANGE-XIO-START  ( operation owner -- step-status )
    _ATXES-X ! _ATXES-OP !
    _ATXES-X @ AT-XRPC-EXCHANGE-VALID? 0= IF
        AT-XRPC-EXCHANGE-S-INVALID
        AT-XRPC-EXCHANGE-XERR-INVALID
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN
    _ATXES-X @ ATXE.CLEANUP-ERROR @ IF
        AT-XRPC-EXCHANGE-S-CLEANUP
        AT-XRPC-EXCHANGE-XERR-CLEANUP
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN
    _ATXES-X @ ATXE.STATE @
    AT-XRPC-EXCHANGE-STATE-PREPARED <> IF
        AT-XRPC-EXCHANGE-S-BUSY
        AT-XRPC-EXCHANGE-XERR-INVALID
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN
    _ATXES-X @ _ATXE-COOPERATIVE-PORT? 0= IF
        AT-XRPC-EXCHANGE-S-TRANSPORT
        AT-XRPC-EXCHANGE-XERR-TRANSPORT
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN

    0 _ATXES-X @ ATXE.BODY-U !
    0 _ATXES-X @ ATXE.HTTP-CODE !
    0 _ATXES-X @ ATXE.ATTEMPTS !
    0 _ATXES-X @ ATXE.FLAGS !
    _ATXES-X @ ATXE.BODY-A @ _ATXES-X @ ATXE.BODY-CAP @
    _ATXES-X @ ATXE.EXCHANGE HBUF-INIT
    HBUF-S-OK <> IF
        AT-XRPC-EXCHANGE-S-CAPACITY
        AT-XRPC-EXCHANGE-XERR-INVALID
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN
    _ATXES-X @ ATXE.BODY-CAP @
    _ATXES-X @ ATXE.EXCHANGE HBUF.PARSER HSTR-BODY-LIMIT!
    _ATXES-X @ _ATXE-BUILD-REQUEST DUP _ATXES-STATUS !
    AT-XRPC-EXCHANGE-S-OK <> IF
        _ATXES-STATUS @
        AT-XRPC-EXCHANGE-XERR-BUILD
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN
    _ATXES-X @ _ATXE-START-HBUF DUP _ATXES-STATUS !
    AT-XRPC-EXCHANGE-S-OK <> IF
        _ATXES-X @ _ATXE-CLEAR-REQUEST
        _ATXES-STATUS @
        AT-XRPC-EXCHANGE-XERR-TRANSPORT
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN
    AT-XRPC-EXCHANGE-STATE-ACTIVE _ATXES-X @ ATXE.STATE !
    XIO-STEP-PENDING ;

: AT-XRPC-EXCHANGE-XIO-POLL  ( operation owner -- step-status )
    _ATXES-X ! _ATXES-OP !
    _ATXES-X @ AT-XRPC-EXCHANGE-VALID? 0= IF
        AT-XRPC-EXCHANGE-S-INVALID
        AT-XRPC-EXCHANGE-XERR-INVALID
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN
    _ATXES-X @ ATXE.STATE @
    AT-XRPC-EXCHANGE-STATE-ACTIVE <> IF
        AT-XRPC-EXCHANGE-S-BUSY
        AT-XRPC-EXCHANGE-XERR-INVALID
        _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL EXIT
    THEN
    _ATXES-X @ ATXE.EXCHANGE HBUF-POLL DUP _ATXES-STATUS !
    DUP HBUF-S-PENDING = IF DROP XIO-STEP-PENDING EXIT THEN
    HBUF-S-OK = IF
        _ATXES-OP @ _ATXES-X @ _ATXE-ADMIT-RESPONSE EXIT
    THEN
    _ATXES-X @ _ATXE-CLEAR-REQUEST
    _ATXES-STATUS @ HBUF-S-CANCELLED = IF
        AT-XRPC-EXCHANGE-S-CANCELLED
        AT-XRPC-EXCHANGE-XERR-CANCELLED
    ELSE
        AT-XRPC-EXCHANGE-S-TRANSPORT
        AT-XRPC-EXCHANGE-XERR-TRANSPORT
    THEN
    _ATXES-OP @ _ATXES-X @ _ATXE-STEP-FAIL ;

