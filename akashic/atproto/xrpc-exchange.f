: _ATXE-CLEAR-PREPARED  ( owner -- )
    DUP ATXE.TARGET HTARGET-SIZE 0 FILL
    DUP ATXE.TARGET HTARGET-INIT
    DUP ATXE.PROXY AT-XRPC-EXCHANGE-PROXY-CAPACITY 0 FILL
    DUP 0 SWAP ATXE.PROXY-U !
    DUP 0 SWAP ATXE.IAT !
    DROP ;

: AT-XRPC-EXCHANGE-PREPARE
  ( iat target proxy-a proxy-u owner -- status )
    _ATXEP-X ! _ATXEP-PROXY-U ! _ATXEP-PROXY-A !
    _ATXEP-TARGET ! _ATXEP-IAT !
    _ATXEP-X @ AT-XRPC-EXCHANGE-VALID? 0= IF
        AT-XRPC-EXCHANGE-S-INVALID EXIT
    THEN
    _ATXEP-X @ ATXE.STATE @
    AT-XRPC-EXCHANGE-STATE-BOUND <> IF
        AT-XRPC-EXCHANGE-S-BUSY EXIT
    THEN
    _ATXEP-IAT @ 0< IF AT-XRPC-EXCHANGE-S-INVALID EXIT THEN
    _ATXEP-TARGET @ HTARGET-VALID? 0= IF
        AT-XRPC-EXCHANGE-S-TARGET EXIT
    THEN
    _ATXEP-PROXY-A @ _ATXEP-PROXY-U @ _ATXE-SPAN-STATUS
    ?DUP IF EXIT THEN
    _ATXEP-PROXY-U @
    AT-XRPC-EXCHANGE-PROXY-CAPACITY U> IF
        AT-XRPC-EXCHANGE-S-CAPACITY EXIT
    THEN
    _ATXEP-TARGET @ HTARGET-SIZE _ATXEP-X @
    _ATXE-SPAN-DISJOINT-OWNER? 0= IF
        AT-XRPC-EXCHANGE-S-ALIAS EXIT
    THEN
    _ATXEP-PROXY-U @ IF
        _ATXEP-PROXY-A @ _ATXEP-PROXY-U @
        _ATXEP-X @ AT-XRPC-EXCHANGE-SIZE
        MSPAN-OVERLAP? IF AT-XRPC-EXCHANGE-S-ALIAS EXIT THEN
    THEN

    _ATXEP-X @ _ATXE-CLEAR-PREPARED
    _ATXEP-TARGET @ HTARGET-URI$
    _ATXEP-X @ ATXE.TARGET HTARGET-PARSE
    HTARGET-S-OK <> IF
        _ATXEP-X @ _ATXE-CLEAR-PREPARED
        AT-XRPC-EXCHANGE-S-TARGET EXIT
    THEN
    _ATXEP-PROXY-U @ IF
        _ATXEP-PROXY-A @ _ATXEP-X @ ATXE.PROXY
        _ATXEP-PROXY-U @ MOVE
    THEN
    _ATXEP-PROXY-U @ _ATXEP-X @ ATXE.PROXY-U !
    _ATXEP-IAT @ _ATXEP-X @ ATXE.IAT !

    _ATXEP-X @ ATXE.TARGET HTARGET-HOST$
    _ATXEP-X @ ATXE.TARGET HTARGET-PORT@
    _ATXEP-X @ ATXE.TRANSPORT KDOSTLS-CONFIGURE
    KDOSTLS-E-OK <> IF
        _ATXEP-X @ _ATXE-CLEAR-PREPARED
        AT-XRPC-EXCHANGE-S-TLS EXIT
    THEN
    0 _ATXEP-X @ ATXE.BODY-U !
    0 _ATXEP-X @ ATXE.HTTP-CODE !
    0 _ATXEP-X @ ATXE.ATTEMPTS !
    0 _ATXEP-X @ ATXE.FLAGS !
    AT-XRPC-EXCHANGE-S-OK _ATXEP-X @ ATXE.LAST-STATUS !
    AT-XRPC-EXCHANGE-STATE-PREPARED _ATXEP-X @ ATXE.STATE !
    AT-XRPC-EXCHANGE-S-OK ;

