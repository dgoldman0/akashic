\ =====================================================================
\  create-record.f - Exact authenticated createRecord operation owner
\ =====================================================================
\  One owner composes the caller-owned createRecord codec with one already
\  bound authenticated XRPC exchange.  Request bytes, codec scratch, result
\  bytes, the exchange, and the owner itself are all supplied by the caller.
\  Consequently this module sets no instance count and no request/result
\  payload capacity.
\
\  PREPARE derives the repository DID from the bound exchange, copies the
\  complete request, and builds the exact expected record URI before any
\  caller input may be released.  A successful operation publishes a copied
\  URI/CID receipt.  Every failure after a possible send is conservatively
\  UNCERTAIN; only failures with wire state NONE publish NO-EFFECT.
\ =====================================================================

