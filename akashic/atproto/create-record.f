: _ATCR-CALLER>STATUS  ( caller-status -- status )
    CASE
        CALLER-SPAN-S-OK OF AT-CREATE-RECORD-S-OK ENDOF
        CALLER-SPAN-S-RANGE OF AT-CREATE-RECORD-S-RANGE ENDOF
        CALLER-SPAN-S-PROTECTED OF
            AT-CREATE-RECORD-S-PROTECTED
        ENDOF
        CALLER-SPAN-S-PLATFORM OF
            AT-CREATE-RECORD-S-PLATFORM
        ENDOF
        AT-CREATE-RECORD-S-PLATFORM SWAP
    ENDCASE ;

: _ATCR-REQUIRED-SPAN-STATUS  ( address length -- status )
    DUP 0> 0= IF 2DROP AT-CREATE-RECORD-S-INVALID EXIT THEN
    OVER 0= IF 2DROP AT-CREATE-RECORD-S-INVALID EXIT THEN
    CALLER-SPAN-STATUS _ATCR-CALLER>STATUS ;

: _ATCR-FIXED-STATUS  ( address length -- status )
    OVER 0= IF 2DROP AT-CREATE-RECORD-S-INVALID EXIT THEN
    OVER 7 AND IF 2DROP AT-CREATE-RECORD-S-INVALID EXIT THEN
    _ATCR-REQUIRED-SPAN-STATUS ;

: _ATCR-XRPC>STATUS  ( xrpc-status -- status )
    DUP AT-XRPC-EXCHANGE-S-OK = IF DROP AT-CREATE-RECORD-S-OK EXIT THEN
    DUP AT-XRPC-EXCHANGE-S-BUSY = IF
        DROP AT-CREATE-RECORD-S-BUSY EXIT
    THEN
    DUP AT-XRPC-EXCHANGE-S-CAPACITY = IF
        DROP AT-CREATE-RECORD-S-CAPACITY EXIT
    THEN
    DUP AT-XRPC-EXCHANGE-S-ALIAS = IF
        DROP AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    DUP AT-XRPC-EXCHANGE-S-RANGE = IF
        DROP AT-CREATE-RECORD-S-RANGE EXIT
    THEN
    DUP AT-XRPC-EXCHANGE-S-PROTECTED = IF
        DROP AT-CREATE-RECORD-S-PROTECTED EXIT
    THEN
    DUP AT-XRPC-EXCHANGE-S-PLATFORM = IF
        DROP AT-CREATE-RECORD-S-PLATFORM EXIT
    THEN
    DUP AT-XRPC-EXCHANGE-S-TARGET = IF
        DROP AT-CREATE-RECORD-S-TARGET EXIT
    THEN
    DUP AT-XRPC-EXCHANGE-S-CLEANUP = IF
        DROP AT-CREATE-RECORD-S-CLEANUP EXIT
    THEN
    DROP AT-CREATE-RECORD-S-XRPC ;

: _ATCRR-NO-RECEIPT?  ( result -- flag )
    DUP ATCRR.URI-U @ SWAP ATCRR.CID-U @ OR 0= ;

: _ATCRR-PENDING-SHAPE?  ( result -- flag )
    DUP ATCRR.STATUS @ AT-CREATE-RECORD-S-OK =
    OVER ATCRR.EXPECTED-U @ 0> AND
    OVER ATCRR.BYTES-CAP @ 2 PICK ATCRR.EXPECTED-U @ -
    AT-CID-TEXT-LENGTH U< 0= AND
    OVER ATCRR.WIRE-STATE @ AT-XRPC-EXCHANGE-WIRE-NONE = AND
    OVER ATCRR.HTTP-CODE @ 0= AND
    SWAP _ATCRR-NO-RECEIPT? AND ;

: _ATCRR-NO-EFFECT-SHAPE?  ( result -- flag )
    DUP ATCRR.EXPECTED-U @ 0=
    OVER ATCRR.WIRE-STATE @ AT-XRPC-EXCHANGE-WIRE-NONE = AND
    SWAP _ATCRR-NO-RECEIPT? AND ;

: _ATCRR-UNCERTAIN-SHAPE?  ( result -- flag )
    DUP ATCRR.STATUS @ AT-CREATE-RECORD-S-OK <>
    OVER ATCRR.EXPECTED-U @ 0= AND
    OVER ATCRR.WIRE-STATE @ AT-XRPC-EXCHANGE-WIRE-NONE <> AND
    SWAP _ATCRR-NO-RECEIPT? AND ;

: _ATCRR-CREATED-SHAPE?  ( result -- flag )
    DUP ATCRR.STATUS @ AT-CREATE-RECORD-S-OK =
    OVER ATCRR.EXPECTED-U @ 0> AND
    OVER ATCRR.URI-U @ 2 PICK ATCRR.EXPECTED-U @ = AND
    OVER ATCRR.CID-U @ AT-CID-TEXT-LENGTH = AND
    OVER ATCRR.WIRE-STATE @ AT-XRPC-EXCHANGE-WIRE-RESPONSE = AND
    OVER ATCRR.HTTP-CODE @ 200 = AND
    NIP ;

: _ATCRR-OUTCOME-SHAPE?  ( result -- flag )
    DUP ATCRR.OUTCOME @
    CASE
        AT-CREATE-RECORD-OUTCOME-PENDING OF
            _ATCRR-PENDING-SHAPE?
        ENDOF
        AT-CREATE-RECORD-OUTCOME-NO-EFFECT OF
            _ATCRR-NO-EFFECT-SHAPE?
        ENDOF
        AT-CREATE-RECORD-OUTCOME-UNCERTAIN OF
            _ATCRR-UNCERTAIN-SHAPE?
        ENDOF
        AT-CREATE-RECORD-OUTCOME-CREATED OF
            _ATCRR-CREATED-SHAPE?
        ENDOF
        DROP 0 SWAP
    ENDCASE ;

: _ATCRR-SHAPE?  ( result -- flag )
    DUP ATCRR.MAGIC @ _ATCRR-MAGIC-VALUE <> IF DROP 0 EXIT THEN
    DUP ATCRR.OUTCOME @ AT-CREATE-RECORD-OUTCOME-VALID? 0= IF
        DROP 0 EXIT
    THEN
    DUP ATCRR.STATUS @ AT-CREATE-RECORD-STATUS-VALID? 0= IF
        DROP 0 EXIT
    THEN
    DUP ATCRR.WIRE-STATE @ AT-XRPC-EXCHANGE-WIRE-VALID? 0= IF
        DROP 0 EXIT
    THEN
    DUP ATCRR.BYTES-A @ 0= IF DROP 0 EXIT THEN
    DUP ATCRR.BYTES-CAP @ 0> 0= IF DROP 0 EXIT THEN
    DUP ATCRR.EXPECTED-U @ DUP 0< IF 2DROP 0 EXIT THEN
    OVER ATCRR.BYTES-CAP @ U> IF DROP 0 EXIT THEN
    DUP ATCRR.URI-U @ DUP 0< IF 2DROP 0 EXIT THEN
    OVER ATCRR.EXPECTED-U @ U> IF DROP 0 EXIT THEN
    DUP ATCRR.CID-U @ DUP 0< IF 2DROP 0 EXIT THEN
    OVER ATCRR.BYTES-CAP @ 2 PICK ATCRR.URI-U @ - U> IF
        DROP 0 EXIT
    THEN
    _ATCRR-OUTCOME-SHAPE? ;

: AT-CREATE-RECORD-RESULT-VALID?  ( result -- flag )
    DUP AT-CREATE-RECORD-RESULT-SIZE _ATCR-FIXED-STATUS
    AT-CREATE-RECORD-S-OK <> IF DROP 0 EXIT THEN
    DUP _ATCRR-SHAPE? 0= IF DROP 0 EXIT THEN
    DUP ATCRR.BYTES-A @ OVER ATCRR.BYTES-CAP @
    2 PICK AT-CREATE-RECORD-RESULT-SIZE MSPAN-OVERLAP? IF
        DROP 0 EXIT
    THEN
    DUP ATCRR.BYTES-A @ OVER ATCRR.BYTES-CAP @
    CALLER-SPAN-STATUS CALLER-SPAN-S-OK =
    SWAP DROP ;

: _ATCRR-CLEAR-BYTES  ( result -- )
    DUP ATCRR.BYTES-A @ SWAP ATCRR.BYTES-CAP @ 0 FILL ;

: _ATCRR-BYTES@  ( result -- bytes-a bytes-cap )
    DUP ATCRR.BYTES-A @ SWAP ATCRR.BYTES-CAP @ ;

: _ATCRR-RESET  ( result -- )
    DUP _ATCRR-CLEAR-BYTES
    DUP AT-CREATE-RECORD-OUTCOME-NO-EFFECT SWAP ATCRR.OUTCOME !
    DUP AT-CREATE-RECORD-S-OK SWAP ATCRR.STATUS !
    DUP 0 SWAP ATCRR.HTTP-CODE !
    DUP AT-XRPC-EXCHANGE-WIRE-NONE SWAP ATCRR.WIRE-STATE !
    DUP 0 SWAP ATCRR.EXPECTED-U !
    DUP 0 SWAP ATCRR.URI-U !
    0 SWAP ATCRR.CID-U ! ;

: AT-CREATE-RECORD-RESULT-INIT
  ( bytes-a bytes-cap result -- status )
    DUP AT-CREATE-RECORD-RESULT-SIZE _ATCR-FIXED-STATUS
    ?DUP IF >R 2DROP DROP R> EXIT THEN
    2 PICK 2 PICK _ATCR-REQUIRED-SPAN-STATUS
    ?DUP IF >R 2DROP DROP R> EXIT THEN
    2 PICK 2 PICK 2 PICK AT-CREATE-RECORD-RESULT-SIZE
    MSPAN-OVERLAP? IF
        2DROP DROP AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    >R
    R@ AT-CREATE-RECORD-RESULT-SIZE 0 FILL
    OVER R@ ATCRR.BYTES-A !
    DUP R@ ATCRR.BYTES-CAP !
    2DROP
    _ATCRR-MAGIC-VALUE R@ ATCRR.MAGIC !
    R@ _ATCRR-RESET
    R> DROP AT-CREATE-RECORD-S-OK ;

: AT-CREATE-RECORD-RESULT-OUTCOME@
  ( result -- outcome status )
    DUP AT-CREATE-RECORD-RESULT-VALID? 0= IF
        DROP 0 AT-CREATE-RECORD-S-INVALID EXIT
    THEN
    ATCRR.OUTCOME @ AT-CREATE-RECORD-S-OK ;

: AT-CREATE-RECORD-RESULT-STATUS@  ( result -- status )
