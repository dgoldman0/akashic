        DROP AT-CREATE-RECORD-S-INVALID EXIT
    THEN
    ATCRR.STATUS @ ;

: AT-CREATE-RECORD-RESULT-HTTP@  ( result -- code status )
    DUP AT-CREATE-RECORD-RESULT-VALID? 0= IF
        DROP 0 AT-CREATE-RECORD-S-INVALID EXIT
    THEN
    ATCRR.HTTP-CODE @ AT-CREATE-RECORD-S-OK ;

: AT-CREATE-RECORD-RESULT-WIRE@  ( result -- wire-state status )
    DUP AT-CREATE-RECORD-RESULT-VALID? 0= IF
        DROP 0 AT-CREATE-RECORD-S-INVALID EXIT
    THEN
    ATCRR.WIRE-STATE @ AT-CREATE-RECORD-S-OK ;

: AT-CREATE-RECORD-RESULT-URI@  ( result -- uri-a uri-u status )
    DUP AT-CREATE-RECORD-RESULT-VALID? 0= IF
        DROP 0 0 AT-CREATE-RECORD-S-INVALID EXIT
    THEN
    DUP ATCRR.OUTCOME @ AT-CREATE-RECORD-OUTCOME-CREATED <> IF
        DROP 0 0 AT-CREATE-RECORD-S-STATE EXIT
    THEN
    DUP ATCRR.BYTES-A @ SWAP ATCRR.URI-U @
    AT-CREATE-RECORD-S-OK ;

: AT-CREATE-RECORD-RESULT-CID@  ( result -- cid-a cid-u status )
    DUP AT-CREATE-RECORD-RESULT-VALID? 0= IF
        DROP 0 0 AT-CREATE-RECORD-S-INVALID EXIT
    THEN
    DUP ATCRR.OUTCOME @ AT-CREATE-RECORD-OUTCOME-CREATED <> IF
        DROP 0 0 AT-CREATE-RECORD-S-STATE EXIT
    THEN
    DUP ATCRR.BYTES-A @ OVER ATCRR.URI-U @ +
    SWAP ATCRR.CID-U @
    AT-CREATE-RECORD-S-OK ;

