: _ATCR-RETURN6  ( six-values status -- status )
    >R _ATCR-DROP6 R> ;

: _ATCR-XRPC-EXTERNAL-STATUS
  ( address length exchange -- status )
    AT-XRPC-EXCHANGE-EXTERNAL-SPAN-STATUS _ATCR-XRPC>STATUS ;

: _ATCR-INIT-GEOMETRY
  ( exchange body-a body-cap workspace result owner -- status )
    DUP AT-CREATE-RECORD-SIZE _ATCR-FIXED-STATUS
    ?DUP IF _ATCR-RETURN6 EXIT THEN
    4 PICK 4 PICK _ATCR-REQUIRED-SPAN-STATUS
    ?DUP IF _ATCR-RETURN6 EXIT THEN
    2 PICK AT-CREATE-RECORD-CODEC-WORKSPACE-SIZE _ATCR-FIXED-STATUS
    ?DUP IF _ATCR-RETURN6 EXIT THEN
    1 PICK AT-CREATE-RECORD-RESULT-VALID? 0= IF
        _ATCR-DROP6 AT-CREATE-RECORD-S-INVALID EXIT
    THEN
    5 PICK AT-XRPC-EXCHANGE-VALID? 0= IF
        _ATCR-DROP6 AT-CREATE-RECORD-S-XRPC EXIT
    THEN
    5 PICK AT-XRPC-EXCHANGE-STATE@
    DUP AT-XRPC-EXCHANGE-S-OK <> IF
        2DROP _ATCR-DROP6 AT-CREATE-RECORD-S-XRPC EXIT
    THEN
    DROP AT-XRPC-EXCHANGE-STATE-BOUND <> IF
        _ATCR-DROP6 AT-CREATE-RECORD-S-STATE EXIT
    THEN

    4 PICK 4 PICK 7 PICK _ATCR-XRPC-EXTERNAL-STATUS
    ?DUP IF _ATCR-RETURN6 EXIT THEN
    2 PICK AT-CREATE-RECORD-CODEC-WORKSPACE-SIZE
    7 PICK _ATCR-XRPC-EXTERNAL-STATUS
    ?DUP IF _ATCR-RETURN6 EXIT THEN
    1 PICK AT-CREATE-RECORD-RESULT-SIZE
    7 PICK _ATCR-XRPC-EXTERNAL-STATUS
    ?DUP IF _ATCR-RETURN6 EXIT THEN
    1 PICK _ATCRR-BYTES@
    7 PICK _ATCR-XRPC-EXTERNAL-STATUS
    ?DUP IF _ATCR-RETURN6 EXIT THEN
    DUP AT-CREATE-RECORD-SIZE
    7 PICK _ATCR-XRPC-EXTERNAL-STATUS
    ?DUP IF _ATCR-RETURN6 EXIT THEN

    4 PICK 4 PICK 2 PICK AT-CREATE-RECORD-SIZE MSPAN-OVERLAP? IF
        _ATCR-DROP6 AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    2 PICK AT-CREATE-RECORD-CODEC-WORKSPACE-SIZE
    2 PICK AT-CREATE-RECORD-SIZE MSPAN-OVERLAP? IF
        _ATCR-DROP6 AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    1 PICK AT-CREATE-RECORD-RESULT-SIZE
    2 PICK AT-CREATE-RECORD-SIZE MSPAN-OVERLAP? IF
        _ATCR-DROP6 AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    5 PICK AT-XRPC-EXCHANGE-SIZE
    2 PICK AT-CREATE-RECORD-SIZE MSPAN-OVERLAP? IF
        _ATCR-DROP6 AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    4 PICK 4 PICK 4 PICK
    AT-CREATE-RECORD-CODEC-WORKSPACE-SIZE MSPAN-OVERLAP? IF
        _ATCR-DROP6 AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    4 PICK 4 PICK 3 PICK AT-CREATE-RECORD-RESULT-SIZE
    MSPAN-OVERLAP? IF
        _ATCR-DROP6 AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    2 PICK AT-CREATE-RECORD-CODEC-WORKSPACE-SIZE
    3 PICK AT-CREATE-RECORD-RESULT-SIZE MSPAN-OVERLAP? IF
        _ATCR-DROP6 AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    4 PICK 4 PICK 3 PICK _ATCRR-BYTES@ MSPAN-OVERLAP? IF
        _ATCR-DROP6 AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    2 PICK AT-CREATE-RECORD-CODEC-WORKSPACE-SIZE
    3 PICK _ATCRR-BYTES@ MSPAN-OVERLAP? IF
        _ATCR-DROP6 AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    1 PICK _ATCRR-BYTES@
    2 PICK AT-CREATE-RECORD-SIZE MSPAN-OVERLAP? IF
        _ATCR-DROP6 AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    _ATCR-DROP6 AT-CREATE-RECORD-S-OK ;

: AT-CREATE-RECORD-INIT
  ( exchange body-a body-cap workspace result owner -- status )
    5 PICK 5 PICK 5 PICK 5 PICK 5 PICK 5 PICK
    _ATCR-INIT-GEOMETRY
    ?DUP IF >R _ATCR-DROP6 R> EXIT THEN
    >R
    R@ AT-CREATE-RECORD-SIZE 0 FILL
    3 PICK 3 PICK 0 FILL
    1 PICK AT-CREATE-RECORD-CODEC-WORKSPACE-SIZE 0 FILL
    DUP _ATCRR-RESET
    R@ ATCR.RESULT !
    R@ ATCR.WORKSPACE !
    R@ ATCR.BODY-CAP !
    R@ ATCR.BODY-A !
    R@ ATCR.EXCHANGE !
    AT-CREATE-RECORD-S-OK R@ ATCR.LAST-STATUS !
    AT-CREATE-RECORD-STATE-IDLE R@ ATCR.STATE !
    _ATCR-MAGIC-VALUE R@ ATCR.MAGIC !
    R> DROP AT-CREATE-RECORD-S-OK ;

: _ATCR-ATURI>STATUS  ( aturi-status -- status )
    DUP ATURI-S-OK = IF DROP AT-CREATE-RECORD-S-OK EXIT THEN
    DUP ATURI-S-CAPACITY = IF
        DROP AT-CREATE-RECORD-S-CAPACITY EXIT
    THEN
    DUP ATURI-S-ALIAS = IF DROP AT-CREATE-RECORD-S-ALIAS EXIT THEN
    DUP ATURI-S-RANGE = IF DROP AT-CREATE-RECORD-S-RANGE EXIT THEN
    DUP ATURI-S-PROTECTED = IF
        DROP AT-CREATE-RECORD-S-PROTECTED EXIT
    THEN
    DUP ATURI-S-PLATFORM = IF
        DROP AT-CREATE-RECORD-S-PLATFORM EXIT
    THEN
    DROP AT-CREATE-RECORD-S-URI ;

