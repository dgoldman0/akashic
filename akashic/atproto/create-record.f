: _ATCR-CAPTURE-EVIDENCE  ( owner -- )
    >R
    R@ ATCR.EXCHANGE @ AT-XRPC-EXCHANGE-WIRE-STATE@
    DUP AT-XRPC-EXCHANGE-S-OK = IF
        DROP R@ ATCR.RESULT @ ATCRR.WIRE-STATE !
    ELSE
        2DROP
        AT-XRPC-EXCHANGE-WIRE-UNCERTAIN
        R@ ATCR.RESULT @ ATCRR.WIRE-STATE !
    THEN
    R@ ATCR.EXCHANGE @ AT-XRPC-EXCHANGE-HTTP-CODE@
    DUP AT-XRPC-EXCHANGE-S-OK = IF
        DROP R@ ATCR.RESULT @ ATCRR.HTTP-CODE !
    ELSE
        2DROP
    THEN
    R> DROP ;

: _ATCR-TERMINAL-FAIL  ( status owner -- )
    >R
    DUP R@ ATCR.LAST-STATUS !
    DUP R@ ATCR.RESULT @ ATCRR.STATUS !
    R@ _ATCR-CAPTURE-EVIDENCE
    R@ ATCR.RESULT @ DUP _ATCRR-CLEAR-BYTES
    DUP 0 SWAP ATCRR.EXPECTED-U !
    DUP 0 SWAP ATCRR.URI-U !
    DUP 0 SWAP ATCRR.CID-U !
    DUP ATCRR.WIRE-STATE @ AT-XRPC-EXCHANGE-WIRE-NONE = IF
        AT-CREATE-RECORD-OUTCOME-NO-EFFECT
    ELSE
        AT-CREATE-RECORD-OUTCOME-UNCERTAIN
    THEN
    OVER ATCRR.OUTCOME !
    2DROP
    AT-CREATE-RECORD-STATE-FAILED R@ ATCR.STATE !
    R> DROP ;

: _ATCR-PUBLISH-RECEIPT
  ( uri-a uri-u cid-a cid-u owner -- status )
    >R
    DUP R@ ATCR.RESULT @ ATCRR.BYTES-CAP @
    R@ ATCR.RESULT @ ATCRR.EXPECTED-U @ - U> IF
        2DROP 2DROP R> DROP AT-CREATE-RECORD-S-CAPACITY EXIT
    THEN
    2 PICK R@ ATCR.RESULT @ ATCRR.EXPECTED-U @ <> IF
        2DROP 2DROP R> DROP AT-CREATE-RECORD-S-URI EXIT
    THEN
    2DUP
    R@ ATCR.RESULT @ ATCRR.BYTES-A @
    R@ ATCR.RESULT @ ATCRR.EXPECTED-U @ +
    SWAP MOVE
    DUP R@ ATCR.RESULT @ ATCRR.CID-U !
    2DROP 2DROP
    R@ ATCR.RESULT @ ATCRR.EXPECTED-U @
    R@ ATCR.RESULT @ ATCRR.URI-U !
    R@ _ATCR-CAPTURE-EVIDENCE
    AT-CREATE-RECORD-S-OK R@ ATCR.RESULT @ ATCRR.STATUS !
    AT-CREATE-RECORD-OUTCOME-CREATED
    R@ ATCR.RESULT @ ATCRR.OUTCOME !
    R> DROP AT-CREATE-RECORD-S-OK ;

: _ATCR-XIO-FAIL  ( status xerr operation owner -- step-status )
    >R >R
    DUP R@ XIOO.ERROR !
    DROP
    R> DROP R@ _ATCR-TERMINAL-FAIL
    R> DROP XIO-STEP-FAILED ;

: AT-CREATE-RECORD-XIO-START  ( operation owner -- step-status )
    DUP AT-CREATE-RECORD-VALID? 0= IF
        DROP AT-CREATE-RECORD-XERR-INVALID SWAP XIOO.ERROR !
        XIO-STEP-FAILED EXIT
    THEN
    DUP ATCR.CLEANUP-ERROR @ IF
        AT-CREATE-RECORD-XERR-CLEANUP 2 PICK XIOO.ERROR !
        2DROP XIO-STEP-FAILED EXIT
    THEN
    DUP ATCR.STATE @ AT-CREATE-RECORD-STATE-PREPARED <> IF
        AT-CREATE-RECORD-S-STATE
        AT-CREATE-RECORD-XERR-INVALID 2SWAP _ATCR-XIO-FAIL EXIT
    THEN
    2DUP ATCR.EXCHANGE @ AT-XRPC-EXCHANGE-XIO-START
    DUP XIO-STEP-PENDING = IF
        DROP
        AT-CREATE-RECORD-STATE-ACTIVE OVER ATCR.STATE !
        AT-CREATE-RECORD-S-OK OVER ATCR.LAST-STATUS !
        2DROP XIO-STEP-PENDING EXIT
    THEN
    DROP
    AT-CREATE-RECORD-S-XRPC AT-CREATE-RECORD-XERR-XRPC
    2SWAP _ATCR-XIO-FAIL ;

: AT-CREATE-RECORD-XIO-POLL  ( operation owner -- step-status )
    DUP AT-CREATE-RECORD-VALID? 0= IF
        DROP AT-CREATE-RECORD-XERR-INVALID SWAP XIOO.ERROR !
        XIO-STEP-FAILED EXIT
    THEN
    DUP ATCR.STATE @ AT-CREATE-RECORD-STATE-ACTIVE <> IF
        AT-CREATE-RECORD-S-STATE
        AT-CREATE-RECORD-XERR-INVALID 2SWAP _ATCR-XIO-FAIL EXIT
    THEN
    2DUP ATCR.EXCHANGE @ AT-XRPC-EXCHANGE-XIO-POLL
    DUP XIO-STEP-PENDING = IF
        DROP 2DROP XIO-STEP-PENDING EXIT
    THEN
    DUP XIO-STEP-SUCCEEDED <> IF
        DROP
        AT-CREATE-RECORD-S-XRPC AT-CREATE-RECORD-XERR-XRPC
        2SWAP _ATCR-XIO-FAIL EXIT
    THEN
    DROP
    0 2 PICK XIOO.RESULT !

    DUP ATCR.EXCHANGE @ AT-XRPC-EXCHANGE-BODY@
    DUP AT-XRPC-EXCHANGE-S-OK <> IF
        >R 2DROP R> DROP
        AT-CREATE-RECORD-S-XRPC AT-CREATE-RECORD-XERR-XRPC
        2SWAP _ATCR-XIO-FAIL EXIT
    THEN
    DROP
    2 PICK ATCR.RESULT @ DUP ATCRR.BYTES-A @ SWAP ATCRR.EXPECTED-U @
    4 PICK ATCR.WORKSPACE @
    AT-CREATE-RECORD-RECEIPT
    DUP AT-CREATE-RECORD-S-OK <> IF
        >R 2DROP 2DROP R>
        AT-CREATE-RECORD-XERR-RECEIPT 2SWAP _ATCR-XIO-FAIL EXIT
    THEN
    DROP
    4 PICK _ATCR-PUBLISH-RECEIPT
    DUP AT-CREATE-RECORD-S-OK <> IF
        AT-CREATE-RECORD-XERR-RECEIPT 2SWAP _ATCR-XIO-FAIL EXIT
    THEN
    DROP
    DUP ATCR.WORKSPACE @
    AT-CREATE-RECORD-CODEC-WORKSPACE-SIZE 0 FILL
    AT-CREATE-RECORD-STATE-CREATED OVER ATCR.STATE !
    AT-CREATE-RECORD-S-OK OVER ATCR.LAST-STATUS !
    DUP ATCR.RESULT @ 2 PICK XIOO.RESULT !
    2DROP XIO-STEP-SUCCEEDED ;

: _ATCR-CATCH-XRPC-CANCEL  ( operation exchange -- ior )
    ['] AT-XRPC-EXCHANGE-XIO-CANCEL CATCH
    DUP IF >R 2DROP R> THEN ;

: _ATCR-CATCH-XRPC-WIPE  ( operation exchange -- ior )
    ['] AT-XRPC-EXCHANGE-XIO-WIPE CATCH
    DUP IF >R 2DROP R> THEN ;

: AT-CREATE-RECORD-XIO-CANCEL  ( operation owner -- )
    DUP AT-CREATE-RECORD-VALID? 0= IF 2DROP EXIT THEN
    DUP ATCR.STATE @ DUP AT-CREATE-RECORD-STATE-PREPARED =
    SWAP AT-CREATE-RECORD-STATE-ACTIVE = OR IF
        AT-CREATE-RECORD-S-STATE OVER _ATCR-TERMINAL-FAIL
        AT-CREATE-RECORD-STATE-CANCELLED OVER ATCR.STATE !
    THEN
    >R
    R@ ATCR.EXCHANGE @ _ATCR-CATCH-XRPC-CANCEL
    ?DUP IF
        DUP R@ ATCR.CLEANUP-ERROR !
        AT-CREATE-RECORD-S-CLEANUP R@ ATCR.LAST-STATUS !
        AT-CREATE-RECORD-STATE-FAILED R@ ATCR.STATE !
        R> DROP THROW
    THEN
    R> DROP ;

: AT-CREATE-RECORD-XIO-WIPE  ( operation owner -- )
    DUP AT-CREATE-RECORD-VALID? 0= IF 2DROP EXIT THEN
    >R
    R@ ATCR.EXCHANGE @ _ATCR-CATCH-XRPC-WIPE
    R@ ATCR.BODY-A @ R@ ATCR.BODY-CAP @ 0 FILL
    0 R@ ATCR.BODY-U !
    R@ ATCR.WORKSPACE @
    AT-CREATE-RECORD-CODEC-WORKSPACE-SIZE 0 FILL
    R@ ATCR.WRITER CBW-SIZE 0 FILL
    R@ _ATCR-CLEAR-TEMPS
    DUP IF DUP R@ ATCR.CLEANUP-ERROR ! THEN
    DROP
    R@ ATCR.CLEANUP-ERROR @ ?DUP IF
        AT-CREATE-RECORD-S-CLEANUP R@ ATCR.LAST-STATUS !
        AT-CREATE-RECORD-STATE-FAILED R@ ATCR.STATE !
        R> DROP THROW
    THEN
    AT-CREATE-RECORD-STATE-IDLE R@ ATCR.STATE !
    R> DROP ;

