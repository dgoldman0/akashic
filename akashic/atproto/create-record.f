: _ATCR-INPUT-SPAN-STATUS  ( address length owner -- status )
    >R
    2DUP _ATCR-REQUIRED-SPAN-STATUS ?DUP IF
        >R 2DROP R> R> DROP EXIT
    THEN
    2DUP R@ AT-CREATE-RECORD-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    2DUP R@ ATCR.BODY-A @ R@ ATCR.BODY-CAP @
    MSPAN-OVERLAP? IF
        2DROP R> DROP AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    2DUP R@ ATCR.WORKSPACE @
    AT-CREATE-RECORD-CODEC-WORKSPACE-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    2DUP R@ ATCR.RESULT @ AT-CREATE-RECORD-RESULT-SIZE
    MSPAN-OVERLAP? IF
        2DROP R> DROP AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    R@ ATCR.RESULT @ _ATCRR-BYTES@ MSPAN-OVERLAP? IF
        R> DROP AT-CREATE-RECORD-S-ALIAS EXIT
    THEN
    R> DROP AT-CREATE-RECORD-S-OK ;

\ Qualify a composing owner's contiguous storage against this operation and
\ the complete bound exchange graph without claiming or retaining the span.
: AT-CREATE-RECORD-EXTERNAL-SPAN-STATUS
  ( address length owner -- status )
    >R
    R@ AT-CREATE-RECORD-VALID? 0= IF
        2DROP R> DROP AT-CREATE-RECORD-S-INVALID EXIT
    THEN
    2DUP R@ _ATCR-INPUT-SPAN-STATUS ?DUP IF
        >R 2DROP R> R> DROP EXIT
    THEN
    R@ ATCR.EXCHANGE @ _ATCR-XRPC-EXTERNAL-STATUS
    R> DROP ;

: _ATCR-PREPARE-GEOMETRY
  \ ( iat target collection-a collection-u rkey-a rkey-u
  \   record-a record-u owner -- status )
    7 PICK HTARGET-SIZE 2 PICK _ATCR-INPUT-SPAN-STATUS
    ?DUP IF >R _ATCR-DROP9 R> EXIT THEN
    6 PICK 6 PICK 2 PICK _ATCR-INPUT-SPAN-STATUS
    ?DUP IF >R _ATCR-DROP9 R> EXIT THEN
    4 PICK 4 PICK 2 PICK _ATCR-INPUT-SPAN-STATUS
    ?DUP IF >R _ATCR-DROP9 R> EXIT THEN
    2 PICK 2 PICK 2 PICK _ATCR-INPUT-SPAN-STATUS
    ?DUP IF >R _ATCR-DROP9 R> EXIT THEN
    _ATCR-DROP9 AT-CREATE-RECORD-S-OK ;

: _ATCR-PREPARE-FAIL  ( status owner -- status )
    >R
    DUP R@ ATCR.LAST-STATUS !
    R@ ATCR.RESULT @ _ATCRR-RESET
    DUP R@ ATCR.RESULT @ ATCRR.STATUS !
    R@ ATCR.BODY-A @ R@ ATCR.BODY-CAP @ 0 FILL
    0 R@ ATCR.BODY-U !
    R@ ATCR.WORKSPACE @
    AT-CREATE-RECORD-CODEC-WORKSPACE-SIZE 0 FILL
    R@ _ATCR-CLEAR-TEMPS
    AT-CREATE-RECORD-STATE-IDLE R@ ATCR.STATE !
    R> DROP ;

: _ATCR-BUILD-EXPECTED
  ( repo-a repo-u collection-a collection-u rkey-a rkey-u owner -- status )
    >R
    R@ ATCR.RESULT @ DUP _ATCRR-CLEAR-BYTES
    DUP ATCRR.BYTES-A @ SWAP ATCRR.BYTES-CAP @
    R@ ATCR.WRITER
    ATURI-BUILD
    DUP ATURI-S-OK <> IF
        >R DROP R> _ATCR-ATURI>STATUS
        R> DROP EXIT
    THEN
    DROP
    R@ ATCR.RESULT @ ATCRR.BYTES-CAP @ OVER -
    AT-CID-TEXT-LENGTH U< IF
        DROP R> DROP AT-CREATE-RECORD-S-CAPACITY EXIT
    THEN
    R@ ATCR.RESULT @ ATCRR.EXPECTED-U !
    AT-CREATE-RECORD-OUTCOME-PENDING
    R@ ATCR.RESULT @ ATCRR.OUTCOME !
    AT-CREATE-RECORD-S-OK R@ ATCR.RESULT @ ATCRR.STATUS !
    R> DROP AT-CREATE-RECORD-S-OK ;

\ PREPARE stores its arguments in the owner-owned destinations before
\ returning, so every caller input span can be overwritten immediately.
: AT-CREATE-RECORD-PREPARE
  \ ( iat target collection-a collection-u rkey-a rkey-u
  \   record-a record-u owner -- status )
    DUP AT-CREATE-RECORD-VALID? 0= IF
        2DROP 2DROP 2DROP 2DROP DROP
        AT-CREATE-RECORD-S-INVALID EXIT
    THEN
    DUP ATCR.STATE @ AT-CREATE-RECORD-STATE-IDLE <> IF
        2DROP 2DROP 2DROP 2DROP DROP
        AT-CREATE-RECORD-S-BUSY EXIT
    THEN
    DUP ATCR.CLEANUP-ERROR @ IF
        2DROP 2DROP 2DROP 2DROP DROP
        AT-CREATE-RECORD-S-CLEANUP EXIT
    THEN
    8 PICK 0< IF
        2DROP 2DROP 2DROP 2DROP DROP
        AT-CREATE-RECORD-S-INVALID EXIT
    THEN
    8 PICK 8 PICK 8 PICK 8 PICK 8 PICK
    8 PICK 8 PICK 8 PICK 8 PICK
    _ATCR-PREPARE-GEOMETRY
    ?DUP IF >R _ATCR-DROP9 R> EXIT THEN
    7 PICK AT-CREATE-RECORD-TARGET? 0= IF
        2DROP 2DROP 2DROP 2DROP DROP
        AT-CREATE-RECORD-S-TARGET EXIT
    THEN

    >R
    7 PICK R@ ATCR.TMP-IAT !
    6 PICK R@ ATCR.TMP-TARGET !
    R@ ATCR.RESULT @ _ATCRR-RESET
    R@ ATCR.BODY-A @ R@ ATCR.BODY-CAP @ 0 FILL
    R@ ATCR.WORKSPACE @
    AT-CREATE-RECORD-CODEC-WORKSPACE-SIZE 0 FILL

    R@ ATCR.EXCHANGE @ AT-XRPC-EXCHANGE-DID@
    DUP AT-XRPC-EXCHANGE-S-OK <> IF
        >R 2DROP R> _ATCR-XRPC>STATUS
        >R _ATCR-DROP8 R> R> _ATCR-PREPARE-FAIL EXIT
    THEN
    DROP
    R@ ATCR.TMP-DID-U !
    R@ ATCR.TMP-DID-A !

    R@ ATCR.TMP-DID-A @ R@ ATCR.TMP-DID-U @
    7 PICK 7 PICK 7 PICK 7 PICK 7 PICK 7 PICK
    R@ ATCR.BODY-A @ R@ ATCR.BODY-CAP @ R@ ATCR.WORKSPACE @
    AT-CREATE-RECORD-BODY
    DUP AT-CREATE-RECORD-S-OK <> IF
        NIP >R _ATCR-DROP8 R> R> _ATCR-PREPARE-FAIL EXIT
    THEN
    DROP R@ ATCR.BODY-U !

    R@ ATCR.TMP-DID-A @ R@ ATCR.TMP-DID-U @
    7 PICK 7 PICK 7 PICK 7 PICK R@
    _ATCR-BUILD-EXPECTED
    ?DUP IF
        >R _ATCR-DROP8 R> R> _ATCR-PREPARE-FAIL EXIT
    THEN

    R@ ATCR.TMP-IAT @ AT-XRPC-METHOD-POST
    R@ ATCR.TMP-TARGET @ 0 0
    R@ ATCR.BODY-A @ R@ ATCR.BODY-U @
    R@ ATCR.EXCHANGE @ AT-XRPC-EXCHANGE-PREPARE
    _ATCR-XRPC>STATUS
    DUP AT-CREATE-RECORD-S-OK <> IF
        >R _ATCR-DROP8 R> R> _ATCR-PREPARE-FAIL EXIT
    THEN
    DROP
    R@ _ATCR-CLEAR-TEMPS
    2DROP 2DROP 2DROP 2DROP
    AT-CREATE-RECORD-STATE-PREPARED R@ ATCR.STATE !
    AT-CREATE-RECORD-S-OK R@ ATCR.LAST-STATUS !
    R> DROP AT-CREATE-RECORD-S-OK ;

