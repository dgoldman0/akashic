\ =====================================================================
\  oauth-deployment-inline.f - Inline-JWKS AT OAuth key composition
\ =====================================================================
\  This state-free composition admits one confidential AT OAuth client
\  deployment, selects the deployed client-authentication public key from
\  its inline JWK Set, binds that identity to durable client and DPoP keys,
\  and only then lends copied public key material to one synchronous
\  application callback.
\
\  Private key records remain inside the credential vault.  The two key
\  owner operations are strictly sequential and each returns completely
\  before the application callback can run.  The module owns no HTTP,
\  jwks_uri acquisition, token, session, XRPC, or mutable operation state.
\
\  Public API:
\    AT-OAUTH-INLINE-WORKSPACE-SIZE
\    AT-OAUTH-INLINE-WORKSPACE-CLEAR  ( workspace -- status )
\    AT-OAUTH-INLINE-STATUS-VALID?  ( status -- flag )
\    AT-OAUTH-INLINE-WITH
\      ( document document-u config profile vault callback context workspace -- callback-result status )
\
\  Application callback ABI:
\      ( config-view metadata-view client-kid-a client-kid-u client-public-a client-thumbprint-a dpop-public-a dpop-thumbprint-a context -- callback-result )
\ =====================================================================

