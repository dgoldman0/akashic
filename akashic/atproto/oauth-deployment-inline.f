: _ATOI-DEPLOYMENT-PREP
  ( config-view metadata-view workspace -- status )
    >R
    DUP R@ _ATOIW.METADATA-VIEW !
    SWAP R@ _ATOIW.CONFIG-VIEW !
    DROP

    R@ _ATOIW.CONFIG-VIEW @
    OAUTH2-CLIENT-VIEW-AUTH-METHOD@
    S" private_key_jwt" _ATOI-BYTES= 0= IF
        R> DROP AT-OAUTH-INLINE-S-KEY-SOURCE EXIT
    THEN

    R@ _ATOIW.METADATA-VIEW @
    OAUTH2-CLIENT-METADATA-VIEW-PRESENCE@
    DUP OAUTH2-CLIENT-METADATA-S-OK <> IF
        2DROP R> DROP AT-OAUTH-INLINE-S-INTERNAL EXIT
    THEN
    DROP
    DUP OAUTH2-CLIENT-METADATA-P-JWKS AND 0= IF
        DROP R> DROP AT-OAUTH-INLINE-S-KEY-SOURCE EXIT
    THEN
    DUP OAUTH2-CLIENT-METADATA-P-JWKS-URI AND IF
        DROP R> DROP AT-OAUTH-INLINE-S-KEY-SOURCE EXIT
    THEN
    DROP

    R@ _ATOIW.METADATA-VIEW @
    OAUTH2-CLIENT-METADATA-VIEW-JWKS@
    DUP OAUTH2-CLIENT-METADATA-S-OK <> IF
        _ATOI-DROP3 R> DROP
        AT-OAUTH-INLINE-S-INTERNAL EXIT
    THEN
    DROP
    DUP 0> 0= IF
        2DROP R> DROP AT-OAUTH-INLINE-S-KEY-SOURCE EXIT
    THEN
    R@ _ATOIW.JWKS-U !
    R@ _ATOIW.JWKS-A !

    R@ _ATOIW.CONFIG-VIEW @ OAUTH2-CLIENT-VIEW-BINDING@
    DUP OAUTH2-P256-KEY-BINDING-SIZE <> IF
        2DROP R> DROP AT-OAUTH-INLINE-S-BINDING EXIT
    THEN
    R@ _ATOIW.BINDING-U !
    R@ _ATOIW.BINDING-A !

    R@ _ATOIW.BINDING-A @
    R@ _ATOIW.BINDING-U @
    OAUTH2-P256-KEY-BINDING-PRESENCE@
    DUP OAUTH2-P256-KEY-S-INVALID = IF
        2DROP R> DROP AT-OAUTH-INLINE-S-BINDING EXIT
    THEN
    DUP OAUTH2-P256-KEY-S-OK <> IF
        _ATOI-OWNER>STATUS
        SWAP DROP
        R> DROP EXIT
    THEN
    DROP
    OAUTH2-P256-KEY-BINDING-F-CLIENT
    OAUTH2-P256-KEY-BINDING-F-DPOP OR
    <> IF
        R> DROP AT-OAUTH-INLINE-S-BINDING EXIT
    THEN

    R> DROP AT-OAUTH-INLINE-S-OK ;

