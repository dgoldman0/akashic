: _ATOI-GEOMETRY
  ( document document-u config profile vault callback context workspace -- status )
    DUP 0= IF
        _ATOI-DROP8 AT-OAUTH-INLINE-S-INVALID EXIT
    THEN
    DUP 7 AND IF
        _ATOI-DROP8 AT-OAUTH-INLINE-S-INVALID EXIT
    THEN
    6 PICK 0> 0= IF
        _ATOI-DROP8 AT-OAUTH-INLINE-S-INVALID EXIT
    THEN
    6 PICK OAUTH2-CLIENT-METADATA-MAX-DOCUMENT-BYTES U> IF
        _ATOI-DROP8 AT-OAUTH-INLINE-S-CAPACITY EXIT
    THEN
    5 PICK DUP 0= SWAP 7 AND 0<> OR IF
        _ATOI-DROP8 AT-OAUTH-INLINE-S-INVALID EXIT
    THEN
    4 PICK DUP 0= SWAP 7 AND 0<> OR IF
        _ATOI-DROP8 AT-OAUTH-INLINE-S-INVALID EXIT
    THEN
    2 PICK 0= IF
        _ATOI-DROP8 AT-OAUTH-INLINE-S-INVALID EXIT
    THEN

    DUP AT-OAUTH-INLINE-WORKSPACE-SIZE _ATOI-SPAN-STATUS
    ?DUP IF _ATOI-RETURN8 EXIT THEN
    7 PICK 7 PICK _ATOI-SPAN-STATUS
    ?DUP IF _ATOI-RETURN8 EXIT THEN
    5 PICK OAUTH2-CLIENT-CONFIG-SIZE _ATOI-SPAN-STATUS
    ?DUP IF _ATOI-RETURN8 EXIT THEN
    4 PICK AT-OAUTH-PROFILE-SIZE _ATOI-SPAN-STATUS
    ?DUP IF _ATOI-RETURN8 EXIT THEN
    3 PICK CVAULT-SIZE _ATOI-SPAN-STATUS
    ?DUP IF _ATOI-RETURN8 EXIT THEN

    DUP AT-OAUTH-INLINE-WORKSPACE-SIZE 5 PICK
    _ATOI-EXTERNAL-STATUS
    ?DUP IF _ATOI-RETURN8 EXIT THEN
    7 PICK 7 PICK 5 PICK _ATOI-EXTERNAL-STATUS
    ?DUP IF _ATOI-RETURN8 EXIT THEN
    5 PICK OAUTH2-CLIENT-CONFIG-SIZE 5 PICK
    _ATOI-EXTERNAL-STATUS
    ?DUP IF _ATOI-RETURN8 EXIT THEN
    4 PICK AT-OAUTH-PROFILE-SIZE 5 PICK
    _ATOI-EXTERNAL-STATUS
    ?DUP IF _ATOI-RETURN8 EXIT THEN

    7 PICK 7 PICK 2 PICK AT-OAUTH-INLINE-WORKSPACE-SIZE
    MSPAN-OVERLAP? IF
        _ATOI-DROP8 AT-OAUTH-INLINE-S-ALIAS EXIT
    THEN
    5 PICK OAUTH2-CLIENT-CONFIG-SIZE
    2 PICK AT-OAUTH-INLINE-WORKSPACE-SIZE
