: _ATOR-SPAN-STATUS  ( address length -- status )
    DUP 0< IF
        2DROP AT-OAUTH-REMOTE-HRES-S-INVALID EXIT
    THEN
    DUP 0= IF
        2DROP AT-OAUTH-REMOTE-HRES-S-OK EXIT
    THEN
    OVER 0= IF
        2DROP AT-OAUTH-REMOTE-HRES-S-INVALID EXIT
    THEN
    CALLER-SPAN-STATUS _ATOR-CALLER>STATUS ;

: _ATOR-FIXED-STATUS  ( address length -- status )
    OVER 0= IF
        2DROP AT-OAUTH-REMOTE-HRES-S-INVALID EXIT
    THEN
    OVER 7 AND IF
        2DROP AT-OAUTH-REMOTE-HRES-S-INVALID EXIT
    THEN
    _ATOR-SPAN-STATUS ;

: _ATOR-EXTERNAL-STATUS  ( address length vault -- status )
    CVAULT-EXTERNAL-SPAN-STATUS _ATOR-CVAULT>STATUS ;

: AT-OAUTH-REMOTE-HRES-WORKSPACE-CLEAR  ( workspace -- status )
    DUP AT-OAUTH-REMOTE-HRES-WORKSPACE-SIZE
    _ATOR-FIXED-STATUS
    ?DUP IF NIP EXIT THEN
    _ATOR-WIPE
    AT-OAUTH-REMOTE-HRES-S-OK ;

\ Stack on entry is metadata-resource, config, profile, target, workspace.
: _ATOR-TARGET-GEOMETRY
  ( metadata-resource config profile target workspace -- status )
    4 PICK HTTP-RESOURCE-SIZE _ATOR-SPAN-STATUS
    ?DUP IF _ATOR-RETURN5 EXIT THEN
    3 PICK OAUTH2-CLIENT-CONFIG-SIZE _ATOR-FIXED-STATUS
    ?DUP IF _ATOR-RETURN5 EXIT THEN
    2 PICK AT-OAUTH-PROFILE-SIZE _ATOR-FIXED-STATUS
    ?DUP IF _ATOR-RETURN5 EXIT THEN
    1 PICK HTARGET-SIZE _ATOR-FIXED-STATUS
    ?DUP IF _ATOR-RETURN5 EXIT THEN
    DUP AT-OAUTH-REMOTE-HRES-WORKSPACE-SIZE
    _ATOR-FIXED-STATUS
    ?DUP IF _ATOR-RETURN5 EXIT THEN

    4 PICK HRES-VALID? 0= IF
        _ATOR-DROP5 AT-OAUTH-REMOTE-HRES-S-METADATA-HTTP EXIT
    THEN
    4 PICK HRES-BODY-STORAGE@ _ATOR-SPAN-STATUS
    ?DUP IF _ATOR-RETURN5 EXIT THEN

    4 PICK HTTP-RESOURCE-SIZE
    5 PICK OAUTH2-CLIENT-CONFIG-SIZE MSPAN-OVERLAP? IF
        _ATOR-DROP5 AT-OAUTH-REMOTE-HRES-S-ALIAS EXIT
    THEN
    4 PICK HTTP-RESOURCE-SIZE
    4 PICK AT-OAUTH-PROFILE-SIZE MSPAN-OVERLAP? IF
        _ATOR-DROP5 AT-OAUTH-REMOTE-HRES-S-ALIAS EXIT
    THEN
    4 PICK HTTP-RESOURCE-SIZE
    3 PICK HTARGET-SIZE MSPAN-OVERLAP? IF
        _ATOR-DROP5 AT-OAUTH-REMOTE-HRES-S-ALIAS EXIT
    THEN
    4 PICK HTTP-RESOURCE-SIZE
    2 PICK AT-OAUTH-REMOTE-HRES-WORKSPACE-SIZE
    MSPAN-OVERLAP? IF
        _ATOR-DROP5 AT-OAUTH-REMOTE-HRES-S-ALIAS EXIT
    THEN

    3 PICK OAUTH2-CLIENT-CONFIG-SIZE
    3 PICK HTARGET-SIZE MSPAN-OVERLAP? IF
        _ATOR-DROP5 AT-OAUTH-REMOTE-HRES-S-ALIAS EXIT
    THEN
    3 PICK OAUTH2-CLIENT-CONFIG-SIZE
    2 PICK AT-OAUTH-REMOTE-HRES-WORKSPACE-SIZE
    MSPAN-OVERLAP? IF
        _ATOR-DROP5 AT-OAUTH-REMOTE-HRES-S-ALIAS EXIT
    THEN
    2 PICK AT-OAUTH-PROFILE-SIZE
    3 PICK HTARGET-SIZE MSPAN-OVERLAP? IF
        _ATOR-DROP5 AT-OAUTH-REMOTE-HRES-S-ALIAS EXIT
    THEN
    2 PICK AT-OAUTH-PROFILE-SIZE
    2 PICK AT-OAUTH-REMOTE-HRES-WORKSPACE-SIZE
    MSPAN-OVERLAP? IF
        _ATOR-DROP5 AT-OAUTH-REMOTE-HRES-S-ALIAS EXIT
    THEN
    1 PICK HTARGET-SIZE
    2 PICK AT-OAUTH-REMOTE-HRES-WORKSPACE-SIZE
    MSPAN-OVERLAP? IF
        _ATOR-DROP5 AT-OAUTH-REMOTE-HRES-S-ALIAS EXIT
    THEN

    4 PICK 5 PICK HTTP-RESOURCE-SIZE
    _ATOR-BODY-OVERLAP? IF
        _ATOR-DROP5 AT-OAUTH-REMOTE-HRES-S-ALIAS EXIT
    THEN
    4 PICK 4 PICK OAUTH2-CLIENT-CONFIG-SIZE
    _ATOR-BODY-OVERLAP? IF
        _ATOR-DROP5 AT-OAUTH-REMOTE-HRES-S-ALIAS EXIT
    THEN
    4 PICK 3 PICK AT-OAUTH-PROFILE-SIZE
    _ATOR-BODY-OVERLAP? IF
        _ATOR-DROP5 AT-OAUTH-REMOTE-HRES-S-ALIAS EXIT
    THEN
    4 PICK 2 PICK HTARGET-SIZE
