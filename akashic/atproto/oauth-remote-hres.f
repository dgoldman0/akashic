\ =====================================================================
\  oauth-remote-hres.f - Retained remote-JWKS AT OAuth deployment
\ =====================================================================
\  This state-free adapter derives a bounded HTTPS jwks_uri target from one
\  retained Client Identifier Metadata HRES result, then composes that
\  metadata result and one separately retained JWK Set HRES result with the
\  provider-neutral published P-256 key owner.
\
\  The caller owns both HRES lifecycles, both complete response buffers, the
\  derived target, the credential vault, and all workspaces.  This module
\  performs no DNS, HTTP, TLS, deadlines, leases, redirects, PAR, browser,
\  token, session, XRPC, or Streams work.
\
\  Public API:
\    AT-OAUTH-REMOTE-HRES-WORKSPACE-SIZE
\    AT-OAUTH-REMOTE-HRES-WORKSPACE-CLEAR
\    AT-OAUTH-REMOTE-HRES-SPEC-POLICY!
\    AT-OAUTH-REMOTE-HRES-STATUS-VALID?
\    AT-OAUTH-REMOTE-HRES-JWKS-TARGET!
\    AT-OAUTH-REMOTE-HRES-WITH
\ =====================================================================

\ KDOS module identities are bounded to 23 bytes.
PROVIDED akashic-at-oauth-rhres

