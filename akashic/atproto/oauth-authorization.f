: _ATAU-FIXED-STATUS  ( address size -- status )
    OVER 0= IF
        2DROP AT-OAUTH-AUTHORIZATION-S-INVALID EXIT
    THEN
    OVER 7 AND IF
        2DROP AT-OAUTH-AUTHORIZATION-S-INVALID EXIT
    THEN
    _ATAU-SPAN-STATUS ;

