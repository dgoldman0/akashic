    DUP AT-OAUTH-AUTHORIZATION-WORKSPACE-SIZE
    _ATAU-FIXED-STATUS
    ?DUP IF NIP EXIT THEN
    _ATAU-WIPE
    AT-OAUTH-AUTHORIZATION-S-OK ;

