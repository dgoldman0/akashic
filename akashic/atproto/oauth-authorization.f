: _ATAU-SPAN-STATUS  ( address length -- status )
    DUP 0< IF
        2DROP AT-OAUTH-AUTHORIZATION-S-INVALID EXIT
    THEN
    DUP 0= IF
        2DROP AT-OAUTH-AUTHORIZATION-S-OK EXIT
    THEN
