: _SBP.MAGIC     ( profile -- address ) _SBP-MAGIC + ;
: _SBP.SELF      ( profile -- address ) _SBP-SELF + ;
: _SBP.STATE     ( profile -- address ) _SBP-STATE + ;
: _SBP.TAG       ( profile -- address ) _SBP-TAG + ;
: _SBP.OPCODES   ( profile -- address ) _SBP-OPCODES + ;
: _SBP.RESERVED  ( profile -- address ) _SBP-RESERVED + ;

: _SBP.LIMIT  ( field profile -- address )
    SWAP 8 * _SBP-LIMITS + + ;

: _SBOX-PROFILE-CALLER>STATUS  ( caller-status -- status )
    DUP CALLER-SPAN-S-OK = IF
        DROP SBOX-PROFILE-S-OK EXIT
    THEN
    DUP CALLER-SPAN-S-RANGE = IF
        DROP SBOX-PROFILE-S-RANGE EXIT
    THEN
    DUP CALLER-SPAN-S-PROTECTED = IF
        DROP SBOX-PROFILE-S-PROTECTED EXIT
    THEN
    DROP SBOX-PROFILE-S-PLATFORM ;

: _SBOX-PROFILE-SPAN-STATUS  ( profile -- status )
    SBOX-PROFILE-SIZE CALLER-SPAN-STATUS
    _SBOX-PROFILE-CALLER>STATUS ;

\ The complete fixed span has already passed _SBOX-PROFILE-SPAN-STATUS.
: _SBOX-PROFILE-BASE-VALID-ADMITTED?  ( profile -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP SBOX-PROFILE-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SBP.MAGIC @ _SBOX-PROFILE-MAGIC <> IF DROP 0 EXIT THEN
    DUP _SBP.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _SBP.STATE @ DUP SBOX-PROFILE-STATE-BUILDING =
        SWAP SBOX-PROFILE-STATE-SEALED = OR 0= IF DROP 0 EXIT THEN
    _SBP.RESERVED @ 0= ;

: _SBOX-PROFILE-BUILDING-STATUS  ( profile -- status )
    DUP _SBOX-PROFILE-SPAN-STATUS ?DUP IF NIP EXIT THEN
    DUP _SBOX-PROFILE-BASE-VALID-ADMITTED? 0= IF
        DROP SBOX-PROFILE-S-INVALID EXIT
    THEN
    DUP _SBP.STATE @ SBOX-PROFILE-STATE-BUILDING <> IF
        DROP SBOX-PROFILE-S-STATE EXIT
    THEN
    DROP SBOX-PROFILE-S-OK ;

\ =====================================================================
\  Initialization and build-only mutation
\ =====================================================================

: SBOX-PROFILE-INIT  ( profile -- status )
    DUP _SBOX-PROFILE-SPAN-STATUS ?DUP IF NIP EXIT THEN
    DUP 0= IF DROP SBOX-PROFILE-S-INVALID EXIT THEN
    DUP 7 AND IF DROP SBOX-PROFILE-S-INVALID EXIT THEN
    DUP SBOX-PROFILE-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP SBOX-PROFILE-S-INVALID EXIT THEN

    DUP SBOX-PROFILE-SIZE 0 FILL
    DUP DUP _SBP.SELF !
    SBOX-PROFILE-STATE-BUILDING OVER _SBP.STATE !

    -1 SBOX-PROFILE-LIMIT-MEMORY-BYTES
        2 PICK _SBP.LIMIT !
    -1 SBOX-PROFILE-LIMIT-OPERAND-CELLS
        2 PICK _SBP.LIMIT !
    -1 SBOX-PROFILE-LIMIT-CALL-FRAMES
        2 PICK _SBP.LIMIT !
    -1 SBOX-PROFILE-LIMIT-LOOP-FRAMES
        2 PICK _SBP.LIMIT !
    -1 SBOX-PROFILE-LIMIT-LOCALS-PER-FRAME
        2 PICK _SBP.LIMIT !
    -1 SBOX-PROFILE-LIMIT-RESULT-CELLS
        2 PICK _SBP.LIMIT !
    -1 SBOX-PROFILE-LIMIT-MAX-BUDGET
        2 PICK _SBP.LIMIT !
    -1 SBOX-PROFILE-LIMIT-FUNCTIONS
        2 PICK _SBP.LIMIT !
    -1 SBOX-PROFILE-LIMIT-IMPORTS
        2 PICK _SBP.LIMIT !
    -1 SBOX-PROFILE-LIMIT-ENTRIES
        2 PICK _SBP.LIMIT !
    -1 SBOX-PROFILE-LIMIT-INSTRUCTIONS
        2 PICK _SBP.LIMIT !

    _SBOX-PROFILE-MAGIC OVER _SBP.MAGIC !
    DROP SBOX-PROFILE-S-OK ;

: SBOX-PROFILE-TAG!  ( tag profile -- status )
    >R
    R@ _SBOX-PROFILE-BUILDING-STATUS DUP IF
        >R DROP R> R> DROP EXIT
    THEN
    DROP
    DUP 0= IF
        DROP R> DROP SBOX-PROFILE-S-LIMIT-VALUE EXIT
    THEN
    R@ _SBP.TAG !
    R> DROP SBOX-PROFILE-S-OK ;

: SBOX-PROFILE-LIMIT!  ( value field profile -- status )
    >R
    R@ _SBOX-PROFILE-BUILDING-STATUS DUP IF
        >R 2DROP R> R> DROP EXIT
    THEN
    DROP
    OVER 0< IF
        2DROP R> DROP SBOX-PROFILE-S-LIMIT-VALUE EXIT
    THEN
    DUP _SBOX-PROFILE-LIMIT-FIELD? 0= IF
        2DROP R> DROP SBOX-PROFILE-S-LIMIT-FIELD EXIT
    THEN
    R@ _SBP.LIMIT !
    R> DROP SBOX-PROFILE-S-OK ;

: _SBOX-PROFILE-OPCODE-CELL
    ( opcode profile -- cell-address mask )
    >R
    DUP 6 RSHIFT 8 * R@ _SBP.OPCODES +
    SWAP 63 AND 1 SWAP LSHIFT
    R> DROP ;

: _SBOX-PROFILE-RAW-OPCODE?  ( opcode profile -- flag )
    _SBOX-PROFILE-OPCODE-CELL
    SWAP @ AND 0<> ;

: SBOX-PROFILE-OPCODE-ENABLE  ( opcode profile -- status )
    >R
    R@ _SBOX-PROFILE-BUILDING-STATUS DUP IF
        >R DROP R> R> DROP EXIT
    THEN
    DROP
    DUP SBOX-MACHINE-OPCODE-STATUS SBOX-MACHINE-S-OK <> IF
        DROP R> DROP SBOX-PROFILE-S-OPCODE EXIT
    THEN
    DUP R@ _SBOX-PROFILE-OPCODE-CELL
    OVER @ OR SWAP !
    DROP R> DROP SBOX-PROFILE-S-OK ;

: SBOX-PROFILE-OPCODE-DISABLE  ( opcode profile -- status )
    >R
    R@ _SBOX-PROFILE-BUILDING-STATUS DUP IF
        >R DROP R> R> DROP EXIT
    THEN
    DROP
    DUP SBOX-MACHINE-OPCODE-STATUS SBOX-MACHINE-S-OK <> IF
        DROP R> DROP SBOX-PROFILE-S-OPCODE EXIT
    THEN
    DUP R@ _SBOX-PROFILE-OPCODE-CELL
    INVERT OVER @ AND SWAP !
    DROP R> DROP SBOX-PROFILE-S-OK ;

