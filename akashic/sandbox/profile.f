\ =====================================================================
\  profile.f - Caller-owned sealed scalar-machine policy
\ =====================================================================
\  A profile is one fixed native runtime object.  It owns only a nonzero
\  semantic tag, scalar resource ceilings, and a 256-opcode allow bitmap
\  over machine.f.  It owns no text identity, digest, package policy, import
\  signature, native handler, authority, compiler state, or VM state.
\
\  Construction is caller-scoped.  INIT self-binds an object in BUILDING
\  state; all policy mutation is refused after SEAL.  Public policy queries
\  require a complete SEALED object and always return an explicit status.
\  A byte-copy fails validation because its stored self address no longer
\  names the copy.
\
\  Callers must supply one writable, cell-aligned SBOX-PROFILE-SIZE-byte
\  object and keep it mapped and quiescent during each synchronous call.
\  Every public object operation qualifies that complete caller-owned span
\  before reading or writing any profile byte.
\ =====================================================================

PROVIDED akashic-sbx-profile

REQUIRE machine.f
REQUIRE ../utils/caller-span.f
REQUIRE ../utils/memory-span.f

