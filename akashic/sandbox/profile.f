0x53425850524F464C CONSTANT _SBOX-PROFILE-MAGIC  \ "SBXPROFL"

  0 CONSTANT _SBP-MAGIC
  8 CONSTANT _SBP-SELF
 16 CONSTANT _SBP-STATE
 24 CONSTANT _SBP-TAG
 32 CONSTANT _SBP-LIMITS
120 CONSTANT _SBP-OPCODES
