    SBOX-PROFILE-LIMIT-IMPORTS R@ _SBP.LIMIT @ 0>= AND
    SBOX-PROFILE-LIMIT-ENTRIES R@ _SBP.LIMIT @ 0>= AND
    SBOX-PROFILE-LIMIT-INSTRUCTIONS R@ _SBP.LIMIT @ 0>= AND
    R> DROP ;

: _SBOX-PROFILE-BITMAP-SUPPORTED?  ( profile -- flag )
    DUP _SBP.OPCODES @
        _SBP-MACHINE-MASK0 INVERT AND 0=
    OVER _SBP.OPCODES 8 + @
        _SBP-MACHINE-MASK1 INVERT AND 0= AND
    OVER _SBP.OPCODES 16 + @ 0= AND
    OVER _SBP.OPCODES 24 + @ 0= AND
    NIP ;

: _SBOX-PROFILE-BITMAP-NONEMPTY?  ( profile -- flag )
    DUP _SBP.OPCODES @
    OVER _SBP.OPCODES 8 + @ OR
    OVER _SBP.OPCODES 16 + @ OR
    OVER _SBP.OPCODES 24 + @ OR
    NIP 0<> ;

: _SBOX-PROFILE-RESULT-FITS?  ( profile -- flag )
    >R
    SBOX-PROFILE-LIMIT-RESULT-CELLS R@ _SBP.LIMIT @
    SBOX-PROFILE-LIMIT-OPERAND-CELLS R@ _SBP.LIMIT @
    <=
    R> DROP ;

: _SBOX-PROFILE-LIMITS-CONSISTENT?  ( profile -- flag )
    >R
    SBOX-PROFILE-LIMIT-MEMORY-BYTES R@ _SBP.LIMIT @ DUP 7 AND 0=
        SWAP SBOX-PROFILE-MAX-MEMORY-BYTES <= AND
    SBOX-PROFILE-LIMIT-OPERAND-CELLS R@ _SBP.LIMIT @
        SBOX-PROFILE-MAX-OPERAND-CELLS <= AND
    SBOX-PROFILE-LIMIT-CALL-FRAMES R@ _SBP.LIMIT @ DUP 0>
        SWAP SBOX-PROFILE-MAX-CALL-FRAMES <= AND AND
    SBOX-PROFILE-LIMIT-LOOP-FRAMES R@ _SBP.LIMIT @
        SBOX-PROFILE-MAX-LOOP-FRAMES <= AND
    SBOX-PROFILE-LIMIT-LOCALS-PER-FRAME R@ _SBP.LIMIT @
        SBOX-PROFILE-MAX-LOCALS-PER-FRAME <= AND
    SBOX-PROFILE-LIMIT-RESULT-CELLS R@ _SBP.LIMIT @
        SBOX-PROFILE-MAX-RESULT-CELLS <= AND
    SBOX-PROFILE-LIMIT-MAX-BUDGET R@ _SBP.LIMIT @ DUP 0>
        SWAP SBOX-PROFILE-MAX-BUDGET <= AND AND
    SBOX-PROFILE-LIMIT-FUNCTIONS R@ _SBP.LIMIT @ DUP 0>
        SWAP SBOX-PROFILE-MAX-FUNCTIONS <= AND AND
    SBOX-PROFILE-LIMIT-IMPORTS R@ _SBP.LIMIT @
        SBOX-PROFILE-MAX-IMPORTS <= AND
    SBOX-PROFILE-LIMIT-ENTRIES R@ _SBP.LIMIT @ DUP 0>
        SWAP SBOX-PROFILE-MAX-ENTRIES <= AND AND
    SBOX-PROFILE-LIMIT-INSTRUCTIONS R@ _SBP.LIMIT @ DUP 0>
        SWAP SBOX-PROFILE-MAX-INSTRUCTIONS <= AND AND
    R@ _SBOX-PROFILE-RESULT-FITS? AND
    R> DROP ;

: _SBOX-PROFILE-IMPORTS-CONSISTENT?  ( profile -- flag )
    >R
    SBOX-PROFILE-LIMIT-IMPORTS R@ _SBP.LIMIT @ 0>
    SBOX-MACHINE-OP-IMPORT-CALL R@
        _SBOX-PROFILE-RAW-OPCODE?
    =
    R> DROP ;

: _SBOX-PROFILE-LOOPS-CONSISTENT?  ( profile -- flag )
    >R
    SBOX-PROFILE-LIMIT-LOOP-FRAMES R@ _SBP.LIMIT @
        0> IF R> DROP -1 EXIT THEN
    R@ _SBP.OPCODES @ _SBP-LOOP-MASK0 AND 0=
    R> DROP ;

: _SBOX-PROFILE-POLICY-STATUS  ( profile -- status )
    DUP _SBP.TAG @ 0= IF
        DROP SBOX-PROFILE-S-INCOMPLETE EXIT
    THEN
    DUP _SBOX-PROFILE-LIMITS-SET? 0= IF
        DROP SBOX-PROFILE-S-INCOMPLETE EXIT
    THEN
    DUP _SBOX-PROFILE-BITMAP-SUPPORTED? 0= IF
        DROP SBOX-PROFILE-S-OPCODE EXIT
    THEN
    DUP _SBOX-PROFILE-BITMAP-NONEMPTY? 0= IF
        DROP SBOX-PROFILE-S-INCOMPLETE EXIT
    THEN
    DUP _SBOX-PROFILE-LIMITS-CONSISTENT? 0= IF
        DROP SBOX-PROFILE-S-LIMIT-VALUE EXIT
    THEN
    DUP _SBOX-PROFILE-IMPORTS-CONSISTENT? 0= IF
        DROP SBOX-PROFILE-S-LIMIT-VALUE EXIT
    THEN
    _SBOX-PROFILE-LOOPS-CONSISTENT? 0= IF
        SBOX-PROFILE-S-LIMIT-VALUE EXIT
    THEN
    SBOX-PROFILE-S-OK ;

: _SBOX-PROFILE-SEALED-STATUS  ( profile -- status )
    DUP _SBOX-PROFILE-SPAN-STATUS ?DUP IF NIP EXIT THEN
    DUP _SBOX-PROFILE-BASE-VALID-ADMITTED? 0= IF
        DROP SBOX-PROFILE-S-INVALID EXIT
    THEN
    DUP _SBP.STATE @ SBOX-PROFILE-STATE-SEALED <> IF
        DROP SBOX-PROFILE-S-STATE EXIT
    THEN
    _SBOX-PROFILE-POLICY-STATUS ;

: SBOX-PROFILE-VALID?  ( profile -- flag )
    _SBOX-PROFILE-SEALED-STATUS SBOX-PROFILE-S-OK = ;

: SBOX-PROFILE-SEALED?  ( profile -- flag )
    SBOX-PROFILE-VALID? ;

: SBOX-PROFILE-BUILDING?  ( profile -- flag )
    _SBOX-PROFILE-BUILDING-STATUS SBOX-PROFILE-S-OK = ;

: SBOX-PROFILE-SEAL  ( profile -- status )
    DUP _SBOX-PROFILE-BUILDING-STATUS DUP IF NIP EXIT THEN DROP
    DUP _SBOX-PROFILE-POLICY-STATUS DUP IF NIP EXIT THEN DROP
    SBOX-PROFILE-STATE-SEALED SWAP _SBP.STATE !
    SBOX-PROFILE-S-OK ;

\ =====================================================================
\  Exact status-returning queries
\ =====================================================================

: SBOX-PROFILE-STATE@  ( profile -- state status )
    DUP _SBOX-PROFILE-SPAN-STATUS ?DUP IF
        NIP SBOX-PROFILE-STATE-INVALID SWAP EXIT
    THEN
    DUP _SBOX-PROFILE-BASE-VALID-ADMITTED? 0= IF
        DROP SBOX-PROFILE-STATE-INVALID SBOX-PROFILE-S-INVALID EXIT
    THEN
    _SBP.STATE @ SBOX-PROFILE-S-OK ;

: SBOX-PROFILE-TAG@  ( profile -- tag status )
    >R
    R@ _SBOX-PROFILE-SEALED-STATUS DUP IF
        R> DROP 0 SWAP EXIT
    THEN
    DROP
    R@ _SBP.TAG @ SBOX-PROFILE-S-OK
    R> DROP ;

: SBOX-PROFILE-LIMIT@  ( field profile -- value status )
    >R
    R@ _SBOX-PROFILE-SEALED-STATUS DUP IF
        >R DROP R> R> DROP 0 SWAP EXIT
    THEN
    DROP
    DUP _SBOX-PROFILE-LIMIT-FIELD? 0= IF
        DROP R> DROP 0 SBOX-PROFILE-S-LIMIT-FIELD EXIT
    THEN
    R@ _SBP.LIMIT @ SBOX-PROFILE-S-OK
    R> DROP ;

: SBOX-PROFILE-OPCODE-ENABLED?
    ( opcode profile -- flag status )
    >R
    R@ _SBOX-PROFILE-SEALED-STATUS DUP IF
        >R DROP R> R> DROP 0 SWAP EXIT
    THEN
    DROP
    DUP SBOX-MACHINE-OPCODE-STATUS SBOX-MACHINE-S-OK <> IF
        DROP R> DROP 0 SBOX-PROFILE-S-OPCODE EXIT
    THEN
    R@ _SBOX-PROFILE-RAW-OPCODE?
    SBOX-PROFILE-S-OK
    R> DROP ;

