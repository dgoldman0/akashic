    SBOX-PROFILE-LIMIT-MEMORY-BYTES R@ _SBP.LIMIT @ 0>=
    SBOX-PROFILE-LIMIT-OPERAND-CELLS R@ _SBP.LIMIT @ 0>= AND
    SBOX-PROFILE-LIMIT-CALL-FRAMES R@ _SBP.LIMIT @ 0>= AND
    SBOX-PROFILE-LIMIT-LOOP-FRAMES R@ _SBP.LIMIT @ 0>= AND
    SBOX-PROFILE-LIMIT-LOCALS-PER-FRAME R@ _SBP.LIMIT @ 0>= AND
    SBOX-PROFILE-LIMIT-RESULT-CELLS R@ _SBP.LIMIT @ 0>= AND
    SBOX-PROFILE-LIMIT-MAX-BUDGET R@ _SBP.LIMIT @ 0>= AND
