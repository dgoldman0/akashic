    DUP _SVL-BUILDER? 0= IF
        2DROP DROP SBOX-VALUE-S-STATE EXIT
    THEN
    >R
    DUP 0< OVER SBOX-VALUE-LIMIT-COUNT >= OR IF
        2DROP R> DROP SBOX-VALUE-S-RANGE EXIT
    THEN
    OVER 0< IF
        2DROP R> DROP SBOX-VALUE-S-RANGE EXIT
