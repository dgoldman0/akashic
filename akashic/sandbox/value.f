    DUP SBOX-VALUE-LIMIT-DEPTH 3 PICK _SVW-LIMIT@ > IF
        2DROP SBOX-VALUE-S-DEPTH EXIT
    THEN
    OVER _SVW.MAX-DEPTH @ OVER < IF
        OVER _SVW.MAX-DEPTH !
    ELSE
        DROP
    THEN
    DROP SBOX-VALUE-S-OK ;

: _SVW-PARENT-EXPECTS-KEY?  ( work -- flag )
