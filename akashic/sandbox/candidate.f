\ =====================================================================
\  candidate.f - Address-free sandbox candidate module geometry
\ =====================================================================
\  The compiler publishes this bounded semantic candidate.  It is never
\  executable authority: the independent verifier must reconstruct an
\  owned sealed plan before the VM can start.
\
\  Candidate fields are little-endian and contain no native address, XT,
\  callback, allocator token, or borrowed span.  The representation keeps
\  the permanent function/import/entry/initial-memory/instruction model
\  while durable package envelopes and cryptographic identity remain above
\  the Stage 1 runtime boundary.
\ =====================================================================

