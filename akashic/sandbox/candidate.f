: _SCAND-MAGIC?  ( candidate -- flag )
    DUP C@ [CHAR] A =
    OVER 1+ C@ [CHAR] K = AND
    OVER 2 + C@ [CHAR] S = AND
    OVER 3 + C@ [CHAR] B = AND
    OVER 4 + C@ [CHAR] X = AND
    OVER 5 + C@ [CHAR] C = AND
    OVER 6 + C@ [CHAR] A = AND
    SWAP 7 + C@ [CHAR] N = AND ;

: _SCAND-WRITE-MAGIC  ( candidate -- )
    [CHAR] A OVER C!
    [CHAR] K OVER 1+ C!
    [CHAR] S OVER 2 + C!
    [CHAR] B OVER 3 + C!
    [CHAR] X OVER 4 + C!
    [CHAR] C OVER 5 + C!
    [CHAR] A OVER 6 + C!
    [CHAR] N SWAP 7 + C! ;

: _SCAND-CANDIDATE-LAYOUT-OVERLAP?  ( candidate layout -- flag )
    DUP >R _SCAND-L.TOTAL @
    R> SBOX-CANDIDATE-LAYOUT-SIZE MSPAN-OVERLAP? ;

\ HEADER! initializes the complete measured candidate, including zero padding,
\ before publishing the header.  Candidate and layout must be disjoint.
: SBOX-CANDIDATE-HEADER!
  ( profile-tag memory-u layout candidate -- status )
    >R
    R@ 0= IF
        2DROP DROP R> DROP SBOX-CANDIDATE-S-INVALID EXIT
    THEN
    DUP SBOX-CANDIDATE-LAYOUT-VALID? 0= IF
        2DROP DROP R> DROP SBOX-CANDIDATE-S-INVALID EXIT
    THEN
    DUP _SCAND-L.TOTAL @ R@ SWAP
        _SCAND-SPAN-STATUS IF
        2DROP DROP R> DROP SBOX-CANDIDATE-S-INVALID EXIT
    THEN
    R@ OVER _SCAND-CANDIDATE-LAYOUT-OVERLAP? IF
        2DROP DROP R> DROP SBOX-CANDIDATE-S-ALIAS EXIT
    THEN
    2 PICK 0= IF
        2DROP DROP R> DROP SBOX-CANDIDATE-S-INVALID EXIT
    THEN
    OVER 0< IF
        2DROP DROP R> DROP SBOX-CANDIDATE-S-INVALID EXIT
    THEN
    \ Initialization precedes section publication and canonicalizes padding.
    R@ OVER _SCAND-L.TOTAL @ 0 FILL
    DUP _SCAND-L.TOTAL @
        R@ _SCAND-H-TOTAL + SBOX-CANDIDATE-U64-LE!
    2 PICK
        R@ _SCAND-H-PROFILE-TAG + SBOX-CANDIDATE-U64-LE!
    OVER
        R@ _SCAND-H-MEMORY-U + SBOX-CANDIDATE-U64-LE!
    DUP _SCAND-L.FUNCTION-N @
        R@ _SCAND-H-FUNCTION-N + SBOX-CANDIDATE-U32-LE!
    DUP _SCAND-L.IMPORT-N @
        R@ _SCAND-H-IMPORT-N + SBOX-CANDIDATE-U32-LE!
    DUP _SCAND-L.ENTRY-N @
        R@ _SCAND-H-ENTRY-N + SBOX-CANDIDATE-U32-LE!
    DUP _SCAND-L.NAME-U @
        R@ _SCAND-H-NAME-U + SBOX-CANDIDATE-U32-LE!
    DUP _SCAND-L.INITIAL-U @
        R@ _SCAND-H-INITIAL-U + SBOX-CANDIDATE-U32-LE!
    DUP _SCAND-L.INSTRUCTION-N @
        R@ _SCAND-H-INSTRUCTION-N + SBOX-CANDIDATE-U32-LE!
    R@ _SCAND-WRITE-MAGIC
    2DROP DROP R> DROP SBOX-CANDIDATE-S-OK ;

: _SCAND-MEASURE-HEADER  ( candidate layout -- status )
    >R >R
    R@ _SCAND-H-FUNCTION-N + SBOX-CANDIDATE-U32-LE@
    R@ _SCAND-H-IMPORT-N + SBOX-CANDIDATE-U32-LE@
    R@ _SCAND-H-ENTRY-N + SBOX-CANDIDATE-U32-LE@
    R@ _SCAND-H-NAME-U + SBOX-CANDIDATE-U32-LE@
    R@ _SCAND-H-INITIAL-U + SBOX-CANDIDATE-U32-LE@
    R@ _SCAND-H-INSTRUCTION-N + SBOX-CANDIDATE-U32-LE@
    R> DROP
    R> SBOX-CANDIDATE-MEASURE ;

\ INSPECT treats the supplied candidate extent as exact and independently
\ reconstructs the measured layout.  It validates header/section geometry,
\ not record policy.  It does not touch the destination until both spans are
\ admitted and disjoint; subsequent format failures clear that destination.
: SBOX-CANDIDATE-INSPECT
  ( candidate candidate-u layout -- status )
    >R
    R@ _SCAND-LAYOUT-STATUS IF
        2DROP R> DROP SBOX-CANDIDATE-S-INVALID EXIT
    THEN
    DUP 0< IF
        2DROP R> DROP SBOX-CANDIDATE-S-INVALID EXIT
    THEN
    OVER 0= IF
        2DROP R> DROP SBOX-CANDIDATE-S-INVALID EXIT
    THEN
    2DUP MSPAN-NONWRAPPING? 0= IF
        2DROP R> DROP SBOX-CANDIDATE-S-INVALID EXIT
    THEN
    2DUP _SCAND-SPAN-STATUS IF
        2DROP R> DROP SBOX-CANDIDATE-S-INVALID EXIT
    THEN
    2DUP R@ SBOX-CANDIDATE-LAYOUT-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP SBOX-CANDIDATE-S-ALIAS EXIT
    THEN
    DUP SBOX-CANDIDATE-HEADER-SIZE < IF
        2DROP R> SBOX-CANDIDATE-S-CAPACITY _SCAND-MEASURE-FAIL EXIT
    THEN
    OVER _SCAND-MAGIC? 0= IF
        2DROP R> SBOX-CANDIDATE-S-INVALID _SCAND-MEASURE-FAIL EXIT
    THEN
    OVER _SCAND-H-TOTAL + SBOX-CANDIDATE-U64-LE@ OVER <> IF
        2DROP R> SBOX-CANDIDATE-S-INVALID _SCAND-MEASURE-FAIL EXIT
    THEN
    OVER _SCAND-H-FLAGS + SBOX-CANDIDATE-U64-LE@ IF
        2DROP R> SBOX-CANDIDATE-S-INVALID _SCAND-MEASURE-FAIL EXIT
    THEN
    OVER _SCAND-H-PROFILE-TAG + SBOX-CANDIDATE-U64-LE@ 0= IF
        2DROP R> SBOX-CANDIDATE-S-INVALID _SCAND-MEASURE-FAIL EXIT
    THEN
    OVER _SCAND-H-MEMORY-U + SBOX-CANDIDATE-U64-LE@ 0< IF
        2DROP R> SBOX-CANDIDATE-S-INVALID _SCAND-MEASURE-FAIL EXIT
    THEN
    OVER R@ _SCAND-MEASURE-HEADER
    DUP IF
        >R 2DROP R> R> DROP EXIT
    THEN
    DROP
    R@ _SCAND-L.TOTAL @ OVER <> IF
        2DROP R> SBOX-CANDIDATE-S-INVALID _SCAND-MEASURE-FAIL EXIT
    THEN
    2DROP R> DROP SBOX-CANDIDATE-S-OK ;

: _SCAND-HEADER-ADMIT?  ( candidate -- candidate flag )
    DUP SBOX-CANDIDATE-HEADER-SIZE _SCAND-SPAN-STATUS 0= ;

: SBOX-CANDIDATE-TOTAL@  ( candidate -- total|0 )
    _SCAND-HEADER-ADMIT? IF
