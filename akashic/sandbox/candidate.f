: _SCAND-LAYOUT-STATUS  ( layout -- status )
    DUP 0= IF DROP SBOX-CANDIDATE-S-INVALID EXIT THEN
    DUP 7 AND IF DROP SBOX-CANDIDATE-S-INVALID EXIT THEN
    SBOX-CANDIDATE-LAYOUT-SIZE _SCAND-SPAN-STATUS ;

\ Primitive wire access assumes that the owning operation has already
\ qualified a containing span of at least 2, 4, or 8 bytes respectively.
\ It is deliberately policy-neutral and works at any byte alignment.
: SBOX-CANDIDATE-U16-LE@  ( address -- value )
    DUP C@ SWAP 1+ C@ 8 LSHIFT OR ;

: SBOX-CANDIDATE-U32-LE@  ( address -- value )
    DUP SBOX-CANDIDATE-U16-LE@
    SWAP 2 + SBOX-CANDIDATE-U16-LE@ 16 LSHIFT OR ;

: SBOX-CANDIDATE-U64-LE@  ( address -- value )
    DUP SBOX-CANDIDATE-U32-LE@
    SWAP 4 + SBOX-CANDIDATE-U32-LE@ 32 LSHIFT OR ;

: SBOX-CANDIDATE-U16-LE!  ( value address -- )
    2DUP C!
    SWAP 8 RSHIFT SWAP 1+ C! ;

: SBOX-CANDIDATE-U32-LE!  ( value address -- )
    2DUP SBOX-CANDIDATE-U16-LE!
    SWAP 16 RSHIFT SWAP 2 + SBOX-CANDIDATE-U16-LE! ;

: SBOX-CANDIDATE-U64-LE!  ( value address -- )
    2DUP SBOX-CANDIDATE-U32-LE!
    SWAP 32 RSHIFT SWAP 4 + SBOX-CANDIDATE-U32-LE! ;

: _SCAND-AREA+  ( offset count element-u -- next status )
    SBOX-BYTE-LENGTH*
    DUP IF
        >R 2DROP 0 R> EXIT
    THEN
    DROP SBOX-BYTE-LENGTH+ ;

: _SCAND-PADDED+  ( offset logical-u -- next status )
    SBOX-BYTE-PAD8
    DUP IF
        >R 2DROP 0 R> EXIT
    THEN
    DROP SBOX-BYTE-LENGTH+ ;

: _SCAND-COUNT-VALID?  ( count maximum -- flag )
    >R DUP 0>= SWAP R> <= AND ;

: _SCAND-LIMIT-STATUS  ( value maximum -- status )
    >R
    DUP 0< IF
        DROP R> DROP SBOX-CANDIDATE-S-INVALID EXIT
    THEN
    R> U> IF
        SBOX-CANDIDATE-S-CAPACITY
    ELSE
        SBOX-CANDIDATE-S-OK
    THEN ;

: SBOX-CANDIDATE-LAYOUT-VALID?  ( layout -- flag )
    DUP _SCAND-LAYOUT-STATUS IF DROP 0 EXIT THEN
    DUP _SCAND-L.MAGIC @ _SCAND-LAYOUT-MAGIC <> IF DROP 0 EXIT THEN
    DUP _SCAND-L.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _SCAND-L.RESERVED @ IF DROP 0 EXIT THEN
    DUP _SCAND-L.FUNCTION-N @ SBOX-CANDIDATE-FUNCTION-MAX
        _SCAND-COUNT-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SCAND-L.IMPORT-N @ SBOX-CANDIDATE-IMPORT-MAX
        _SCAND-COUNT-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SCAND-L.ENTRY-N @ SBOX-CANDIDATE-ENTRY-MAX
        _SCAND-COUNT-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SCAND-L.NAME-U @ SBOX-CANDIDATE-NAME-BYTES-MAX
        _SCAND-COUNT-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SCAND-L.INITIAL-U @ SBOX-CANDIDATE-INITIAL-BYTES-MAX
        _SCAND-COUNT-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SCAND-L.INSTRUCTION-N @ SBOX-CANDIDATE-INSTRUCTION-MAX
        _SCAND-COUNT-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SCAND-L.FUNCTION-OFF @ SBOX-CANDIDATE-HEADER-SIZE <> IF
        DROP 0 EXIT
    THEN
    DUP _SCAND-L.FUNCTION-OFF @
    OVER _SCAND-L.FUNCTION-N @ SBOX-CANDIDATE-FUNCTION-SIZE
        _SCAND-AREA+ DUP IF 2DROP DROP 0 EXIT THEN DROP
    OVER _SCAND-L.IMPORT-OFF @ <> IF DROP 0 EXIT THEN
    DUP _SCAND-L.IMPORT-OFF @
    OVER _SCAND-L.IMPORT-N @ SBOX-CANDIDATE-IMPORT-SIZE
        _SCAND-AREA+ DUP IF 2DROP DROP 0 EXIT THEN DROP
    OVER _SCAND-L.ENTRY-OFF @ <> IF DROP 0 EXIT THEN
    DUP _SCAND-L.ENTRY-OFF @
    OVER _SCAND-L.ENTRY-N @ SBOX-CANDIDATE-ENTRY-SIZE
        _SCAND-AREA+ DUP IF 2DROP DROP 0 EXIT THEN DROP
    OVER _SCAND-L.NAME-OFF @ <> IF DROP 0 EXIT THEN
    DUP _SCAND-L.NAME-OFF @
    OVER _SCAND-L.NAME-U @ _SCAND-PADDED+
        DUP IF 2DROP DROP 0 EXIT THEN DROP
    OVER _SCAND-L.INITIAL-OFF @ <> IF DROP 0 EXIT THEN
    DUP _SCAND-L.INITIAL-OFF @
    OVER _SCAND-L.INITIAL-U @ _SCAND-PADDED+
        DUP IF 2DROP DROP 0 EXIT THEN DROP
    OVER _SCAND-L.INSTRUCTION-OFF @ <> IF DROP 0 EXIT THEN
    DUP _SCAND-L.INSTRUCTION-OFF @
    OVER _SCAND-L.INSTRUCTION-N @ SBOX-CANDIDATE-INSTRUCTION-SIZE
        _SCAND-AREA+ DUP IF 2DROP DROP 0 EXIT THEN DROP
    OVER _SCAND-L.TOTAL @ = NIP ;

: _SCAND-MEASURE-FAIL  ( layout status -- status )
    >R SBOX-CANDIDATE-LAYOUT-SIZE 0 FILL R> ;

\ Measure writes only the caller-owned layout.  Once that span is admitted,
\ every ordinary failure clears it; success writes the self-bound magic last.
\ Stack: function-n import-n entry-n name-u initial-u instruction-n layout
\     -- status
: SBOX-CANDIDATE-MEASURE
    >R
    R@ _SCAND-LAYOUT-STATUS IF
        2DROP 2DROP 2DROP R> DROP
        SBOX-CANDIDATE-S-INVALID EXIT
    THEN
    R@ SBOX-CANDIDATE-LAYOUT-SIZE 0 FILL
    R@ R@ _SCAND-L.SELF !
    R@ _SCAND-L.INSTRUCTION-N !
    R@ _SCAND-L.INITIAL-U !
    R@ _SCAND-L.NAME-U !
    R@ _SCAND-L.ENTRY-N !
    R@ _SCAND-L.IMPORT-N !
    R@ _SCAND-L.FUNCTION-N !

    R@ _SCAND-L.FUNCTION-N @ SBOX-CANDIDATE-FUNCTION-MAX
        _SCAND-LIMIT-STATUS
    DUP IF R> SWAP _SCAND-MEASURE-FAIL EXIT THEN DROP
    R@ _SCAND-L.IMPORT-N @ SBOX-CANDIDATE-IMPORT-MAX
        _SCAND-LIMIT-STATUS
    DUP IF R> SWAP _SCAND-MEASURE-FAIL EXIT THEN DROP
    R@ _SCAND-L.ENTRY-N @ SBOX-CANDIDATE-ENTRY-MAX
        _SCAND-LIMIT-STATUS
    DUP IF R> SWAP _SCAND-MEASURE-FAIL EXIT THEN DROP
    R@ _SCAND-L.NAME-U @ SBOX-CANDIDATE-NAME-BYTES-MAX
        _SCAND-LIMIT-STATUS
    DUP IF R> SWAP _SCAND-MEASURE-FAIL EXIT THEN DROP
    R@ _SCAND-L.INITIAL-U @ SBOX-CANDIDATE-INITIAL-BYTES-MAX
        _SCAND-LIMIT-STATUS
    DUP IF R> SWAP _SCAND-MEASURE-FAIL EXIT THEN DROP
    R@ _SCAND-L.INSTRUCTION-N @ SBOX-CANDIDATE-INSTRUCTION-MAX
        _SCAND-LIMIT-STATUS
    DUP IF R> SWAP _SCAND-MEASURE-FAIL EXIT THEN DROP

    SBOX-CANDIDATE-HEADER-SIZE
    DUP R@ _SCAND-L.FUNCTION-OFF !
    R@ _SCAND-L.FUNCTION-N @ SBOX-CANDIDATE-FUNCTION-SIZE
        _SCAND-AREA+ DUP IF
        >R DROP R> R> SWAP _SCAND-MEASURE-FAIL EXIT
    THEN DROP
    DUP R@ _SCAND-L.IMPORT-OFF !
    R@ _SCAND-L.IMPORT-N @ SBOX-CANDIDATE-IMPORT-SIZE
        _SCAND-AREA+ DUP IF
        >R DROP R> R> SWAP _SCAND-MEASURE-FAIL EXIT
    THEN DROP
    DUP R@ _SCAND-L.ENTRY-OFF !
    R@ _SCAND-L.ENTRY-N @ SBOX-CANDIDATE-ENTRY-SIZE
        _SCAND-AREA+ DUP IF
        >R DROP R> R> SWAP _SCAND-MEASURE-FAIL EXIT
    THEN DROP
    DUP R@ _SCAND-L.NAME-OFF !
    R@ _SCAND-L.NAME-U @ _SCAND-PADDED+ DUP IF
        >R DROP R> R> SWAP _SCAND-MEASURE-FAIL EXIT
    THEN DROP
    DUP R@ _SCAND-L.INITIAL-OFF !
    R@ _SCAND-L.INITIAL-U @ _SCAND-PADDED+ DUP IF
        >R DROP R> R> SWAP _SCAND-MEASURE-FAIL EXIT
    THEN DROP
    DUP R@ _SCAND-L.INSTRUCTION-OFF !
    R@ _SCAND-L.INSTRUCTION-N @ SBOX-CANDIDATE-INSTRUCTION-SIZE
        _SCAND-AREA+ DUP IF
        >R DROP R> R> SWAP _SCAND-MEASURE-FAIL EXIT
    THEN DROP
    DUP R@ _SCAND-L.TOTAL !
    DROP
    _SCAND-LAYOUT-MAGIC R@ _SCAND-L.MAGIC !
    R> DROP SBOX-CANDIDATE-S-OK ;

: SBOX-CANDIDATE-LAYOUT-TOTAL@  ( layout -- total|0 )
    DUP SBOX-CANDIDATE-LAYOUT-VALID? IF
        _SCAND-L.TOTAL @
    ELSE
        DROP 0
    THEN ;

