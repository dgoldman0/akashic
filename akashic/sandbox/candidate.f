\ All nonempty spans owned by a public candidate operation pass through the
\ architectural caller-memory boundary before any byte or native-cell access.
\ This small status vocabulary deliberately closes every boundary rejection
\ to INVALID.
: _SCAND-SPAN-STATUS  ( address length -- status )
    DUP 0< IF 2DROP SBOX-CANDIDATE-S-INVALID EXIT THEN
    DUP 0= IF 2DROP SBOX-CANDIDATE-S-OK EXIT THEN
    OVER 0= IF 2DROP SBOX-CANDIDATE-S-INVALID EXIT THEN
    2DUP MSPAN-NONWRAPPING? 0= IF
        2DROP SBOX-CANDIDATE-S-INVALID EXIT
    THEN
    CALLER-SPAN-STATUS IF
        SBOX-CANDIDATE-S-INVALID
    ELSE
        SBOX-CANDIDATE-S-OK
    THEN ;

