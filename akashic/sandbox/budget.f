: _SBOX-BUDGET-CALLER>STATUS  ( caller-status -- status )
    DUP CALLER-SPAN-S-OK = IF DROP SBOX-BUDGET-S-OK EXIT THEN
    DUP CALLER-SPAN-S-RANGE = IF DROP SBOX-BUDGET-S-RANGE EXIT THEN
    DUP CALLER-SPAN-S-PROTECTED = IF
        DROP SBOX-BUDGET-S-PROTECTED EXIT
    THEN
    DROP SBOX-BUDGET-S-PLATFORM ;

: _SBOX-BUDGET-SPAN-STATUS  ( budget -- status )
