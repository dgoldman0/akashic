\ =====================================================================
\  budget.f - Caller-owned sealed pure-invocation ceilings
\ =====================================================================
\  This object materializes the dynamic ceilings shared by declarations,
\  trusted host policy, Context policy, and one neutral VM invocation.
\  Required fields are always positive: zero in an outer policy means
\  "does not add another ceiling", never "unlimited".  MIN! therefore
\  ignores zero and folds positive values into an already materialized
\  baseline.
\
\  The object contains no Context, Practice, allocator, clock, handler,
\  authority, or mutable module scratch.  Higher layers decide which
\  semantically compatible policy fields may be folded into it.
\ =====================================================================

