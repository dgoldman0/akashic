: SBOX-BUDGET-LIMIT!  ( value field budget -- status )
    DUP _SBOX-BUDGET-BUILDING? 0= IF
        2DROP DROP SBOX-BUDGET-S-STATE EXIT
    THEN
    1 PICK _SBOX-BUDGET-FIELD? 0= IF
        2DROP DROP SBOX-BUDGET-S-FIELD EXIT
    THEN
    2 PICK DUP 0> 0= IF
        DROP 2DROP SBOX-BUDGET-S-LIMIT EXIT
    THEN
    2 PICK 2 PICK _SBOX-BUDGET-FIELD-MAX U> IF
        2DROP DROP SBOX-BUDGET-S-LIMIT EXIT
    THEN
    >R
    R@ _SBU.LIMIT !
    R> DROP SBOX-BUDGET-S-OK ;

: SBOX-BUDGET-MIN!  ( optional-positive field budget -- status )
    DUP _SBOX-BUDGET-BUILDING? 0= IF
        2DROP DROP SBOX-BUDGET-S-STATE EXIT
    THEN
    1 PICK _SBOX-BUDGET-FIELD? 0= IF
        2DROP DROP SBOX-BUDGET-S-FIELD EXIT
    THEN
    2 PICK 0= IF 2DROP DROP SBOX-BUDGET-S-OK EXIT THEN
    2 PICK 0< IF 2DROP DROP SBOX-BUDGET-S-LIMIT EXIT THEN
    >R
    DUP R@ _SBU.LIMIT @
    2 PICK U> IF
        R@ _SBU.LIMIT !
    ELSE
        2DROP
    THEN
    R> DROP SBOX-BUDGET-S-OK ;

: SBOX-BUDGET-SEAL  ( budget -- status )
    DUP _SBOX-BUDGET-BUILDING? 0= IF
        DROP SBOX-BUDGET-S-STATE EXIT
    THEN
    SBOX-BUDGET-STATE-SEALED OVER _SBU.STATE !
    DUP SBOX-BUDGET-VALID? IF
        DROP SBOX-BUDGET-S-OK
    ELSE
        SBOX-BUDGET-STATE-BUILDING SWAP _SBU.STATE !
        SBOX-BUDGET-S-INVALID
    THEN ;

: SBOX-BUDGET-LIMIT@  ( field budget -- value status )
    DUP SBOX-BUDGET-VALID? 0= IF
        2DROP 0 SBOX-BUDGET-S-INVALID EXIT
    THEN
    OVER _SBOX-BUDGET-FIELD? 0= IF
        2DROP 0 SBOX-BUDGET-S-FIELD EXIT
    THEN
    _SBU.LIMIT @ SBOX-BUDGET-S-OK ;

: SBOX-BUDGET-RELEASE  ( budget -- status )
    DUP _SBOX-BUDGET-SPAN-STATUS ?DUP IF NIP EXIT THEN
    DUP SBOX-BUDGET-VALID?
    OVER _SBOX-BUDGET-BUILDING? OR >R
    DUP SBOX-BUDGET-SIZE 0 FILL
    DROP R> IF SBOX-BUDGET-S-OK ELSE SBOX-BUDGET-S-INVALID THEN ;
