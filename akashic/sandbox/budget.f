: SBOX-BUDGET-LIMIT-MAX@  ( field -- maximum status )
    DUP _SBOX-BUDGET-FIELD? 0= IF
        DROP 0 SBOX-BUDGET-S-FIELD EXIT
    THEN
    _SBOX-BUDGET-FIELD-MAX SBOX-BUDGET-S-OK ;

: _SBOX-BUDGET-HEADER?  ( budget -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP _SBU.MAGIC @ _SBOX-BUDGET-MAGIC =
    OVER _SBU.SELF @ 2 PICK = AND
    OVER _SBU.STATE @ DUP SBOX-BUDGET-STATE-BUILDING =
    SWAP SBOX-BUDGET-STATE-SEALED = OR AND
    SWAP _SBU.RESERVED @ 0= AND ;

: _SBOX-BUDGET-LIMITS-VALID?  ( budget -- flag )
    SBOX-BUDGET-LIMIT-FIELD-COUNT 0 ?DO
        I OVER _SBU.LIMIT @
        DUP 0> SWAP
        I _SBOX-BUDGET-FIELD-MAX <= AND 0= IF
            DROP 0 UNLOOP EXIT
        THEN
    LOOP
    DROP -1 ;

: SBOX-BUDGET-VALID?  ( budget -- flag )
    DUP _SBOX-BUDGET-SPAN-STATUS IF DROP 0 EXIT THEN
    DUP _SBOX-BUDGET-HEADER? 0= IF DROP 0 EXIT THEN
    DUP _SBU.STATE @ SBOX-BUDGET-STATE-SEALED <> IF DROP 0 EXIT THEN
    _SBOX-BUDGET-LIMITS-VALID? ;

: _SBOX-BUDGET-BUILDING?  ( budget -- flag )
    DUP _SBOX-BUDGET-SPAN-STATUS IF DROP 0 EXIT THEN
    DUP _SBOX-BUDGET-HEADER? 0= IF DROP 0 EXIT THEN
    DUP _SBU.STATE @ SBOX-BUDGET-STATE-BUILDING =
    SWAP _SBOX-BUDGET-LIMITS-VALID? AND ;

