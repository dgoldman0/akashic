    2 R@ _SVM-TOP@ R@ _SVM-MEMORY-ADDRESS
    R@ _SVI.TMP-B @
    0 R@ _SVM-TOP@
    R@ _SVI.VALUE-STATE @ SBOX-VALUE-MAP-FIND
    R@ _SVM-MAP-FIND-STAGE? 0= IF
        R@ _SVI.RUN-STATE @ R> DROP EXIT
