: _SVM-LAYOUT!  ( instance -- status )
    >R
    R@ _SVI.PLAN @ SBOX-PLAN-FUNCTION-N@ R@ _SVI.FUNCTION-N !
    R@ _SVI.PLAN @ SBOX-PLAN-INSTRUCTION-N@
        R@ _SVI.INSTRUCTION-N !
