    CASE
        SBOX-VALUE-S-HANDLE OF
            SBOX-VM-TRAP-INVALID-VALUE-HANDLE R@ _SVM-TRAP0
        ENDOF
        SBOX-VALUE-S-TYPE OF
            SBOX-VM-TRAP-VALUE-TYPE-MISMATCH R@ _SVM-TRAP0
        ENDOF
        SBOX-VALUE-S-RANGE OF
            SBOX-VM-TRAP-VALUE-INDEX-RANGE R@ _SVM-TRAP0
        ENDOF
        SBOX-VALUE-S-UTF8 OF
            SBOX-VM-TRAP-INVALID-UTF8 R@ _SVM-TRAP0
        ENDOF
        SBOX-VALUE-S-MAP-ORDER OF
            SBOX-VM-TRAP-MAP-KEY-ORDER R@ _SVM-TRAP0
        ENDOF
        SBOX-VALUE-S-DUPLICATE-KEY OF
            SBOX-VM-TRAP-DUPLICATE-MAP-KEY R@ _SVM-TRAP0
        ENDOF
        SBOX-VALUE-S-INVALID-LENGTH OF
            SBOX-VM-TRAP-INVALID-LENGTH R@ _SVM-TRAP0
        ENDOF
        SBOX-VALUE-S-DEPTH OF
            SBOX-VM-TRAP-INVALID-RESULT-GRAPH R@ _SVM-TRAP0
        ENDOF
        SBOX-VALUE-S-CYCLE OF
            SBOX-VM-TRAP-INVALID-RESULT-GRAPH R@ _SVM-TRAP0
        ENDOF
        SBOX-VALUE-S-ARENA-NODES OF
            SBOX-VM-EXHAUST-OUTPUT-ARENA-NODES R@ _SVM-EXHAUST
        ENDOF
        SBOX-VALUE-S-ARENA-BYTES OF
            SBOX-VM-EXHAUST-OUTPUT-ARENA-BYTES R@ _SVM-EXHAUST
        ENDOF
        SBOX-VALUE-S-RESULT-NODES OF
            SBOX-VM-EXHAUST-OUTPUT-RESULT-NODES R@ _SVM-EXHAUST
        ENDOF
        SBOX-VALUE-S-RESULT-BYTES OF
            SBOX-VM-EXHAUST-OUTPUT-RESULT-BYTES R@ _SVM-EXHAUST
        ENDOF
        SBOX-VM-HOST-INTERNAL-INVARIANT R@ _SVM-HOST-FAIL
        SWAP
    ENDCASE
    R> DROP ;

: _SVM-TOP@  ( depth instance -- value )
    TUCK [ _SVI-OPERAND-N ] LITERAL + @ 1- SWAP - SWAP _SVM-OPERAND @ ;

: _SVM-TOP!  ( value depth instance -- )
    TUCK [ _SVI-OPERAND-N ] LITERAL + @ 1- SWAP - SWAP _SVM-OPERAND ! ;

\ Only steps push, and every slice's layout check placed the operand area
\ right after the descriptor.
: _SVM-PUSH!  ( value instance -- )
    [ _SVI-OPERAND-N ] LITERAL + DUP >R @
    DUP 1 + R@ !
    CELLS R> + [ SBOX-VM-INSTANCE-DESCRIPTOR-SIZE _SVI-OPERAND-N - ] LITERAL +
    ! ;

: _SVM-DROP-N  ( count instance -- )
    [ _SVI-OPERAND-N ] LITERAL + DUP >R @ SWAP - R> ! ;

\ Replaces the top two operands with VALUE.
: _SVM-BINARY!  ( value instance -- )
    DUP [ _SVI-OPERAND-N ] LITERAL + DUP @ 1- DUP ROT !
    1- SWAP _SVM-OPERAND ! ;

: _SVM-FRAME-DEPTH  ( instance -- depth )
    DUP [ _SVI-OPERAND-N ] LITERAL + @
    SWAP _SVM-CURRENT-CALL [ _SVC-STACK-BASE ] LITERAL + @ - ;

: _SVM-RESERVE?  ( charge instance -- flag )
    >R
    DUP 0> 0= IF
        DROP SBOX-VM-TRAP-BAD-OPCODE 0 R@ _SVM-TRAP DROP
        R> DROP 0 EXIT
    THEN
    R@ _SVI.BUDGET @ R@ _SVI.USAGE @ -
    OVER U< IF
        DROP
        SBOX-VM-EXHAUST-INSTRUCTION-UNITS R@ _SVM-EXHAUST DROP
        R> DROP 0 EXIT
    THEN
    R@ _SVI.TMP-CHARGE !
    R> DROP -1 ;

: _SVM-COMMIT-RESERVATION!  ( instance -- )
    >R
    R@ _SVI.TMP-CHARGE @ R@ _SVI.USAGE +!
    0 R@ _SVI.TMP-CHARGE !
    R> DROP ;

: _SVM-VALUE-RESERVATION-CLEAR  ( instance -- )
    0 OVER _SVI.TMP-CHARGE !
    0 SWAP _SVI.TMP-A ! ;

: _SVM-VALUE-STACK-CAPACITY?  ( instance -- flag )
    >R
    R@ _SVI.OPERAND-N @
    R@ _SVI.TMP-POP @ -
    R@ _SVI.TMP-PUSH @ +
    R@ _SVI.OPERAND-CAP @ U> IF
        SBOX-VM-EXHAUST-DATA-STACK R@ _SVM-EXHAUST DROP
        R> DROP 0 EXIT
    THEN
    -1 R> DROP ;

: _SVM-VALUE-RESERVE?  ( copy-bytes instruction-charge instance -- flag )
    >R
    R@ _SVI.ENTRY-SIGNATURE @
        SBOX-ABI-SIGNATURE-VALUE-TO-VALUE <> IF
        2DROP
        SBOX-VM-TRAP-INVALID-VALUE-HANDLE R@ _SVM-TRAP0 DROP
        R> DROP 0 EXIT
    THEN
    OVER 0< IF
        2DROP
        SBOX-VM-TRAP-INVALID-LENGTH R@ _SVM-TRAP0 DROP
        R> DROP 0 EXIT
    THEN
    DUP R@ _SVM-RESERVE? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    DROP
    1 R@ _SVI.VALUE-OPS-BUDGET @
        R@ _SVI.VALUE-OPS-USAGE @ - U> IF
        DROP R@ _SVM-VALUE-RESERVATION-CLEAR
        SBOX-VM-EXHAUST-VALUE-OPS R@ _SVM-EXHAUST DROP
        R> DROP 0 EXIT
    THEN
    DUP R@ _SVI.COPY-BUDGET @ R@ _SVI.COPY-USAGE @ - U> IF
        DROP R@ _SVM-VALUE-RESERVATION-CLEAR
        SBOX-VM-EXHAUST-COPY-BYTES R@ _SVM-EXHAUST DROP
        R> DROP 0 EXIT
    THEN
    DUP R@ _SVI.TMP-A !
    DROP
    R@ _SVM-VALUE-STACK-CAPACITY? 0= IF
        R@ _SVM-VALUE-RESERVATION-CLEAR
        R> DROP 0 EXIT
    THEN
    -1 R> DROP ;

: _SVM-VALUE-COMMIT!  ( instance -- )
    >R
    R@ _SVM-COMMIT-RESERVATION!
    1 R@ _SVI.VALUE-OPS-USAGE +!
    R@ _SVI.TMP-A @ R@ _SVI.COPY-USAGE +!
    0 R@ _SVI.TMP-A !
    R> DROP ;

: _SVM-CEIL8  ( nonnegative-u -- units )
    8 /MOD SWAP 0<> IF 1+ THEN ;

: _SVM-NEXT!  ( instance -- )
    [ _SVI-IP ] LITERAL + 1 SWAP +! ;

\ Signed addition with explicit overflow.  The sum is the wrapped cell and
\ the flag is true exactly when mathematical signed addition overflowed.
: _SVM-I64+OVERFLOW?  ( a b -- sum overflow? )
    2DUP + >R
    R@ XOR
    SWAP R@ XOR
    AND 0<
    R> SWAP ;

: _SVM-I64/MOD  ( a b -- remainder quotient )
    /MOD ;

\ =====================================================================
\  Read-only dynamic-state validation
\ =====================================================================

: _SVM-STARTS-VALID?  ( instance -- flag )
    0 OVER _SVI.TMP-X !
    0 OVER _SVI.TMP-Y !
    BEGIN
        DUP _SVI.TMP-Y @ OVER _SVI.FUNCTION-N @ <
    WHILE
        DUP _SVI.TMP-Y @ OVER _SVM-START-CELL @
        OVER _SVI.TMP-X @ <> IF
            DROP 0 EXIT
        THEN
        DUP _SVI.TMP-Y @ OVER _SVM-FUNCTION
        DUP 0= IF 2DROP 0 EXIT THEN
        DUP 2 PICK _SVM-FUNCTION-RECORD-VALID? 0= IF
            2DROP 0 EXIT
        THEN
        _SVM-FUNCTION-INSTRUCTION-N@
        OVER _SVI.TMP-X @ SWAP SBOX-BYTE-LENGTH+
        DUP IF 2DROP DROP 0 EXIT THEN
        DROP OVER _SVI.TMP-X !
        1 OVER _SVI.TMP-Y +!
    REPEAT
    DUP _SVI.TMP-X @ OVER _SVI.INSTRUCTION-N @ =
    >R
    0 OVER _SVI.TMP-X !
    0 OVER _SVI.TMP-Y !
    DROP R> ;

: _SVM-CURRENT-FUNCTION-RECORD  ( instance -- record|0 )
    DUP _SVI.CURRENT-FUNCTION @ SWAP _SVM-FUNCTION ;

: _SVM-CURRENT-START  ( instance -- index )
    DUP _SVI.CURRENT-FUNCTION @ SWAP _SVM-START-CELL @ ;

: _SVM-CURRENT-END  ( instance -- index )
    DUP _SVI.CURRENT-FUNCTION @ 1+
    OVER _SVI.FUNCTION-N @
    OVER SWAP U< IF
        SWAP _SVM-START-CELL @
    ELSE
        DROP _SVI.INSTRUCTION-N @
    THEN ;

: _SVM-CURRENT-CALL-VALID?  ( instance -- flag )
    >R
    R@ _SVI.CALL-N @ DUP 0> 0= SWAP R@ _SVI.CALL-CAP @ > OR IF
        R> DROP 0 EXIT
    THEN
    R@ _SVI.CURRENT-FUNCTION @ DUP 0<
    SWAP R@ _SVI.FUNCTION-N @ U< 0= OR IF R> DROP 0 EXIT THEN
    R@ _SVM-CURRENT-CALL DUP R@ _SVI.TMP-W !
    _SVM-CALL.RESERVED @ IF R> DROP 0 EXIT THEN
    R@ _SVI.TMP-W @ _SVM-CALL.FUNCTION @
        R@ _SVI.CURRENT-FUNCTION @ <> IF R> DROP 0 EXIT THEN
    R@ _SVM-CURRENT-FUNCTION-RECORD DUP R@ _SVI.TMP-Z !
    0= IF R> DROP 0 EXIT THEN
    R@ _SVI.TMP-Z @ _SVM-FUNCTION-PARAMS@
        R@ _SVI.TMP-W @ _SVM-CALL.PARAMS @ <> IF
        R> DROP 0 EXIT
    THEN
    R@ _SVI.TMP-Z @ _SVM-FUNCTION-RESULTS@
        R@ _SVI.TMP-W @ _SVM-CALL.RESULTS @ <> IF
        R> DROP 0 EXIT
    THEN
    R@ _SVI.TMP-Z @ _SVM-FUNCTION-LOCALS@
        R@ _SVI.TMP-W @ _SVM-CALL.LOCALS @ <> IF
        R> DROP 0 EXIT
    THEN
    R@ _SVI.TMP-W @ _SVM-CALL.STACK-BASE @ DUP 0<
    SWAP R@ _SVI.OPERAND-N @ U> OR IF R> DROP 0 EXIT THEN
    R@ _SVI.TMP-W @ _SVM-CALL.LOOP-BASE @ DUP 0<
    SWAP R@ _SVI.LOOP-N @ U> OR 0=
    R> DROP ;

: _SVM-RESUME-READY?  ( instance -- flag )
    DUP _SVI.RUN-STATE @ SBOX-VM-RUN-RUNNABLE <> IF
        DROP -1 EXIT
    THEN
    DUP _SVI.CANCEL-DETAIL @ IF DROP -1 EXIT THEN
    DUP _SVM-STARTS-VALID? 0= IF
        SBOX-VM-TRAP-BAD-CALL-TARGET 0 2 PICK _SVM-TRAP
        DROP DROP 0 EXIT
    THEN
    DUP _SVM-CURRENT-CALL-VALID? 0= IF
        SBOX-VM-TRAP-CALL-STACK-UNDERFLOW 0 2 PICK _SVM-TRAP
        DROP DROP 0 EXIT
    THEN
    DROP -1 ;

: _SVM-DYNAMIC-READY?  ( instance -- flag )
    DUP _SVI.IP @ DUP 0<
    SWAP 2 PICK _SVM-CURRENT-START U< OR IF
        SBOX-VM-TRAP-BAD-INSTRUCTION-POINTER 0 2 PICK _SVM-TRAP
        DROP DROP 0 EXIT
    THEN
    DUP _SVI.IP @ OVER _SVM-CURRENT-END U< 0= IF
        SBOX-VM-TRAP-BAD-INSTRUCTION-POINTER 0 2 PICK _SVM-TRAP
        DROP DROP 0 EXIT
    THEN
    DROP -1 ;

\ =====================================================================
\  Step completion and guest memory checks
\ =====================================================================

\ Ends a typed-value step that falls through.
: _SVM-FINISH-ORDINARY  ( instance -- run-state )
    DUP _SVM-NEXT! _SVI.RUN-STATE @ ;

\ OFFSET and LENGTH are nonnegative and the span ends inside guest memory.
\ Comparing OFFSET, unsigned, with what is left after LENGTH needs no sum
\ that could overflow, and a negative OFFSET is never small enough.
: _SVM-MEMORY-SPAN?  ( offset length instance -- flag )
    [ _SVI-MEMORY-U ] LITERAL + @ OVER -
    SWAP 0< IF 2DROP 0 EXIT THEN
    DUP 0< IF 2DROP 0 EXIT THEN
    U> 0= ;

\ The initial data at the start of memory is read-only, and an empty span
\ overlaps nothing.
: _SVM-MEMORY-WRITABLE?  ( offset length instance -- flag )
    >R
    2DUP R@ _SVM-MEMORY-SPAN? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    0= IF R> 2DROP -1 EXIT THEN
    R> [ _SVI-INITIAL-U ] LITERAL + @ U< 0= ;

: _SVM-MEMORY-ADDRESS  ( offset instance -- address )
    DUP [ _SVI-MEMORY-OFF ] LITERAL + @ + + ;

\ The decoded record's base cost waits in TMP-CHARGE until the reservation
\ replaces it with the whole charge (see _SVM-VALUE-ADAPT).
: _SVM-VALUE-BASE-COST  ( instance -- cost|0 flag )
    _SVI.TMP-CHARGE @ -1 ;

: _SVM-VALUE-CHARGE  ( dynamic-units instance -- charge flag )
    >R
    DUP 0< IF DROP R> DROP 0 0 EXIT THEN
    R@ _SVM-VALUE-BASE-COST 0= IF
        2DROP R> DROP 0 0 EXIT
    THEN
    SBOX-BYTE-LENGTH+ DUP IF
        2DROP R> DROP 0 0 EXIT
    THEN
    DROP -1 R> DROP ;

\ Typed values exist only in a signature-one activation.  The verifier
\ proved the operands and the fall-through.
: _SVM-VALUE-BEGIN?  ( instance -- flag )
    DUP _SVI.ENTRY-SIGNATURE @
        SBOX-ABI-SIGNATURE-VALUE-TO-VALUE = IF DROP -1 EXIT THEN
    SBOX-VM-TRAP-INVALID-VALUE-HANDLE SWAP _SVM-TRAP0 DROP 0 ;

: _SVM-VALUE-STAGE?  ( value value-status instance -- flag )
