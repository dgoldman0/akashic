        DROP R> DROP 0 SBOX-VM-S-ENTRY EXIT
    THEN
    SBOX-ABI-SIGNATURE-VALUE-TO-VALUE <> IF
        R> DROP 0 SBOX-VM-S-ENTRY EXIT
    THEN

    10 PICK 10 PICK 9 PICK 9 PICK 9 PICK 6 PICK 6 PICK
    _SVM-TYPED-DESTINATION-DISJOINT? 0= IF
