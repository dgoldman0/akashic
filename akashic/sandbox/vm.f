    DROP

    R@ _SVM-TYPED-RESOURCES-SCRUB!
    R@ _SVM-SCRUB-FINISHED

    \ This is the only seal write and the final operation that can affect the
    \ result.  Every fallible check and ownership transition is complete.
    _SVM-RESULT-MAGIC 2 PICK _SVT.MAGIC !
    2DROP R> DROP SBOX-VM-S-OK ;

: SBOX-VM-FINISH  ( result result-capacity instance -- status )
    DUP SBOX-VM-INSTANCE-VALID? 0= IF
        2DROP DROP SBOX-VM-S-INVALID EXIT
    THEN
    DUP _SVI.RUN-STATE @ _SVM-FINISHABLE? 0= IF
        2DROP DROP SBOX-VM-S-STATE EXIT
    THEN
    DUP _SVI.ENTRY-SIGNATURE @
        SBOX-ABI-SIGNATURE-VALUE-TO-VALUE <> IF
        2DROP DROP SBOX-VM-S-STATE EXIT
    THEN
    DUP _SVM-TERMINAL-COHERENT? 0= IF
        2DROP DROP SBOX-VM-S-RESULT EXIT
    THEN
    >R

    2DUP _SVM-RESULT-SPAN-STATUS ?DUP IF
        >R 2DROP R> R> DROP EXIT
    THEN
    2DUP R@ _SVM-RESULT-DISJOINT? 0= IF
        2DROP R> DROP SBOX-VM-S-ALIAS EXIT
    THEN

    R@ _SVM-RESULT-MEASURE-VALIDATED
    DUP IF
        >R DROP 2DROP R> R> DROP EXIT
    THEN
    DROP
    DUP 2 PICK U> IF
        2DROP DROP R> DROP SBOX-VM-S-CAPACITY EXIT
    THEN
    R> _SVM-FINISH-MEASURED-VALIDATED ;

\ FINISH has just scrubbed the mutable VM body, then established the
\ FINISHED+SCRUBBED causal-state cells.  The invocation host uses this private
\ release before any caller can observe or mutate the VM again.
: _SVM-RELEASE-FINISHED-VALIDATED  ( instance -- status )
    DUP _SVI.RUN-STATE @ SBOX-VM-RUN-FINISHED <> IF
        DROP SBOX-VM-S-INVALID EXIT
    THEN
    DUP _SVI.SCRUBBED @ 1 <> IF
        DROP SBOX-VM-S-INVALID EXIT
    THEN
    0 OVER _SVI.MAGIC !
    DUP SBOX-VM-INSTANCE-DESCRIPTOR-SIZE 0 FILL
    DROP SBOX-VM-S-OK ;

: SBOX-VM-RELEASE  ( instance -- status )
    DUP _SVM-INSTANCE-HEADER-STATUS ?DUP IF NIP EXIT THEN
    DUP _SVM-INSTANCE-ZERO? IF DROP SBOX-VM-S-OK EXIT THEN
    DUP SBOX-VM-INSTANCE-VALID? 0= IF
        0 OVER _SVI.MAGIC !
        DUP SBOX-VM-INSTANCE-DESCRIPTOR-SIZE 0 FILL
        DROP SBOX-VM-S-INVALID EXIT
    THEN
    DUP _SVI.RUN-STATE @ SBOX-VM-RUN-FINISHED = IF
        0 OVER _SVI.MAGIC !
        DUP SBOX-VM-INSTANCE-DESCRIPTOR-SIZE 0 FILL
        DROP SBOX-VM-S-OK EXIT
    THEN
    DUP _SVI.ENTRY-SIGNATURE @
        SBOX-ABI-SIGNATURE-VALUE-TO-VALUE = IF
        DUP _SVM-TYPED-RESOURCES-RELEASE >R
    ELSE
        SBOX-VM-S-OK >R
    THEN
    DUP _SVI.TOTAL @ >R
    0 OVER _SVI.MAGIC !
    DUP R@ 0 FILL
    R> DROP DROP R> ;
