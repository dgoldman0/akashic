    R@ _SVI.TMP-OPCODE @
    DUP SBOX-ABI-OP-V-LIST-GET =
    OVER SBOX-ABI-OP-V-MAP-KEY = OR
    SWAP SBOX-ABI-OP-V-MAP-VALUE = OR IF
        R@ _SVI.TMP-X @ R@ _SVM-BINARY!
    ELSE
        R@ _SVI.TMP-X @ 0 R@ _SVM-TOP!
    THEN
    R@ _SVM-FINISH-ORDINARY
    R> DROP ;

