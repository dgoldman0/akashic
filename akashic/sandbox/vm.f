                R@ _SVI.RUN-STATE @ R> DROP EXIT
            THEN
        ENDOF
        SBOX-ABI-OP-V-LIST-GET OF
            1 R@ _SVM-TOP@ 0 R@ _SVM-TOP@
            R@ _SVI.VALUE-STATE @ SBOX-VALUE-LIST@
            R@ _SVM-VALUE-STAGE? 0= IF
                R@ _SVI.RUN-STATE @ R> DROP EXIT
