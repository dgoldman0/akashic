        2DROP SBOX-VM-TRAP-BAD-OPCODE R@ _SVM-TRAP0 DROP
        R> DROP 0 EXIT
    THEN
    DROP R@ _SVI.TMP-POP !
    R@ _SVI.TMP-OPCODE @ SBOX-ABI-PUSH@
