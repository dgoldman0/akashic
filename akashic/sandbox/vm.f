    R@ _SVI.VALUE-STATE @ SBOX-VALUE-PREPARED-CAPACITY
    DUP IF
        R@ _SVM-VALUE-RESERVATION-CLEAR
        R@ _SVM-VALUE-DISCARD-PREPARED!
        R@ _SVI.RUN-STATE @ SBOX-VM-RUN-RUNNABLE <> IF
            DROP R> DROP 0 EXIT
        THEN
        R@ _SVM-VALUE-FAIL DROP
        R> DROP 0 EXIT
    THEN
    DROP -1 R> DROP ;

