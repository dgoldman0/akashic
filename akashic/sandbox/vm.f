        SWAP DROP R@ _SVM-VALUE-FAIL DROP
        R> DROP 0 EXIT
    THEN
    DROP R@ _SVI.TMP-W !
    -1 R> DROP ;

: _SVM-VALUE-DISCARD-PREPARED!  ( instance -- )
