\ =====================================================================
\  compaction.f - Bounded two-bank neutral store compaction coordinator
\ =====================================================================
\  This module coordinates an offline rebuild without knowing which records
\  are live or what an application-root page means.  A consumer-owned step
\  callback copies one bounded opaque unit into a private staging PSTORE.  A
\  separate finalizer receives the exact next generation of the shared
\  authority and writes the final application root after rebasing any
\  generation-bound consumer metadata.
\
\  Callback ABIs:
\    step
\      ( source-root builder-store builder-work byte-allowance context
\        -- done? bytes-used status )
\    finalize
\      ( exact-next-generation builder-store builder-work context -- status )
\
\  Staging commits may advance through any number of private generations.
\  Publication advances the shared root exactly once.  The selected snapshot
\  is then mirrored at that exact generation before the old physical bank may
\  be truncated.  PCOMPACT-RECOVER derives the same safe convergence solely
\  from validated root slots; no phase journal or alternate serialized layout
\  exists.
\ =====================================================================

PROVIDED akashic-persist-compaction

REQUIRE store.f

