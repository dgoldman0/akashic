: _PCOMPACT-TOPOLOGY?  ( compact -- flag )
    >R
    PERSIST-DATA-BANK-0 R@ _PCC.BUILDER @
        PSTORE-PAGE-FILE-FOR-BANK@
    PERSIST-DATA-BANK-0 R@ _PCC.ROOT @ PROOT-PAGE-FILE@
        _PCOMPACT-PAGE-FILE= 0= IF R> DROP 0 EXIT THEN
    PERSIST-DATA-BANK-0 R@ _PCC.BUILDER @
        PSTORE-SEGMENT-FILE-FOR-BANK@
    PERSIST-DATA-BANK-0 R@ _PCC.ROOT @ PROOT-SEGMENT-FILE@
        _PCOMPACT-SEGMENT-FILE= 0= IF R> DROP 0 EXIT THEN
    PERSIST-DATA-BANK-1 R@ _PCC.BUILDER @
        PSTORE-PAGE-FILE-FOR-BANK@
    PERSIST-DATA-BANK-1 R@ _PCC.ROOT @ PROOT-PAGE-FILE@
        _PCOMPACT-PAGE-FILE= 0= IF R> DROP 0 EXIT THEN
    PERSIST-DATA-BANK-1 R@ _PCC.BUILDER @
        PSTORE-SEGMENT-FILE-FOR-BANK@
    PERSIST-DATA-BANK-1 R@ _PCC.ROOT @ PROOT-SEGMENT-FILE@
        _PCOMPACT-SEGMENT-FILE= 0= IF R> DROP 0 EXIT THEN
    R@ _PCC.ROOT @
    R@ _PCC.BUILDER @ PSTORE-ROOT-FILE@
        _PCOMPACT-ROOT-PATHS-DISJOINT?
    R> DROP ;

: PCOMPACT-VALID?  ( compact -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP PCOMPACT-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    >R
    R@ _PCC.MAGIC @ _PCOMPACT-MAGIC <> IF R> DROP 0 EXIT THEN
    R@ _PCC.SELF @ R@ <> IF R> DROP 0 EXIT THEN
    R@ _PCC.ROOT @ DUP PROOT-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    PERSIST-DATA-BANK-0 OVER PROOT-BANK-CONFIGURED? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    PERSIST-DATA-BANK-1 SWAP PROOT-BANK-CONFIGURED? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _PCC.BUILDER @ PSTORE-VALID? 0= IF R> DROP 0 EXIT THEN
    R@ _PCC.BUILDER-WORK @ PSTORE-WORK-VALID? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _PCC.STEP-XT @ 0= IF R> DROP 0 EXIT THEN
    R@ _PCC.FINALIZE-XT @ 0= IF R> DROP 0 EXIT THEN
    R@ _PCC.BYTE-BUDGET @ 0> 0= IF R> DROP 0 EXIT THEN
    R@ _PCC.WORK-BUDGET @ 0> 0= IF R> DROP 0 EXIT THEN
    R@ _PCC.STEP-BYTES @ 0> 0= IF R> DROP 0 EXIT THEN
    R@ _PCC.STEP-BYTES @ R@ _PCC.BYTE-BUDGET @ > IF
        R> DROP 0 EXIT
    THEN
    R@ PCOMPACT-SIZE R@ _PCC.ROOT @
        _PCOMPACT-SPAN-DISJOINT-ROOT? 0= IF R> DROP 0 EXIT THEN
    R@ PCOMPACT-SIZE R@ _PCC.BUILDER @
        PSTORE-SPAN-DISJOINT? 0= IF R> DROP 0 EXIT THEN
    R@ PCOMPACT-SIZE R@ _PCC.BUILDER-WORK @
        PSTORE-WORK-SPAN-DISJOINT? 0= IF R> DROP 0 EXIT THEN
    R@ _PCC.ROOT @ PROOT-FILE-SIZE
        R@ _PCC.BUILDER @ PSTORE-SIZE MSPAN-OVERLAP? IF
        R> DROP 0 EXIT
    THEN
    R@ _PCC.ROOT @ PROOT-FILE-SIZE
        R@ _PCC.BUILDER-WORK @ PSTORE-WORK-SIZE MSPAN-OVERLAP? IF
        R> DROP 0 EXIT
    THEN
    R@ _PCC.BUILDER-WORK @ PSTORE-WORK-SIZE
        R@ _PCC.BUILDER @ PSTORE-SIZE MSPAN-OVERLAP? IF
        R> DROP 0 EXIT
    THEN
    R@ _PCOMPACT-TOPOLOGY? 0= IF R> DROP 0 EXIT THEN
    R> _PCC.STATUS @ _PCOMPACT-STATUS? ;

\ ( shared-root builder-store builder-work step-xt finalize-xt context
\   byte-budget work-budget step-byte-budget compact -- status )
: PCOMPACT-INIT  ( nine-arguments compact -- persist-status )
    >R
    R@ 0= IF _PCOMPACT-DROP9 R> DROP PERSIST-S-INVALID EXIT THEN
    R@ PCOMPACT-SIZE MSPAN-NONWRAPPING? 0= IF
        _PCOMPACT-DROP9 R> DROP PERSIST-S-INVALID EXIT
    THEN
    8 PICK PROOT-VALID? 0= IF
        _PCOMPACT-DROP9 R> DROP PERSIST-S-INVALID EXIT
    THEN
    8 PICK PERSIST-DATA-BANK-0 SWAP PROOT-BANK-CONFIGURED? 0= IF
        _PCOMPACT-DROP9 R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    8 PICK PERSIST-DATA-BANK-1 SWAP PROOT-BANK-CONFIGURED? 0= IF
        _PCOMPACT-DROP9 R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    7 PICK PSTORE-VALID? 0= IF
        _PCOMPACT-DROP9 R> DROP PERSIST-S-INVALID EXIT
    THEN
    6 PICK PSTORE-WORK-VALID? 0= IF
        _PCOMPACT-DROP9 R> DROP PERSIST-S-INVALID EXIT
    THEN
    5 PICK 0= 5 PICK 0= OR IF
        _PCOMPACT-DROP9 R> DROP PERSIST-S-INVALID EXIT
    THEN
    2 PICK 0> 2 PICK 0> AND 1 PICK 0> AND 0= IF
        _PCOMPACT-DROP9 R> DROP PERSIST-S-INVALID EXIT
    THEN
    DUP 3 PICK > IF
        _PCOMPACT-DROP9 R> DROP PERSIST-S-INVALID EXIT
    THEN
    8 PICK R@ PCOMPACT-SIZE ROT
        _PCOMPACT-SPAN-DISJOINT-ROOT? 0= IF
        _PCOMPACT-DROP9 R> DROP PERSIST-S-INVALID EXIT
    THEN
    7 PICK R@ PCOMPACT-SIZE ROT PSTORE-SPAN-DISJOINT? 0= IF
        _PCOMPACT-DROP9 R> DROP PERSIST-S-INVALID EXIT
    THEN
    6 PICK R@ PCOMPACT-SIZE ROT PSTORE-WORK-SPAN-DISJOINT? 0= IF
        _PCOMPACT-DROP9 R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ PCOMPACT-SIZE 0 FILL
    _PCOMPACT-MAGIC R@ _PCC.MAGIC !
    R@ R@ _PCC.SELF !
    8 PICK R@ _PCC.ROOT !
    7 PICK R@ _PCC.BUILDER !
    6 PICK R@ _PCC.BUILDER-WORK !
    5 PICK R@ _PCC.STEP-XT !
    4 PICK R@ _PCC.FINALIZE-XT !
    3 PICK R@ _PCC.CONTEXT !
    2 PICK R@ _PCC.BYTE-BUDGET !
    1 PICK R@ _PCC.WORK-BUDGET !
    DUP R@ _PCC.STEP-BYTES !
    PERSIST-S-OK R@ _PCC.STATUS !
    R@ PCOMPACT-VALID? 0= IF
        R@ PCOMPACT-SIZE 0 FILL
        _PCOMPACT-DROP9 R> DROP PERSIST-S-INVALID EXIT
    THEN
    _PCOMPACT-DROP9 R> DROP PERSIST-S-OK ;

