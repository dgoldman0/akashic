: _PCOMPACT-STATUS?  ( status -- flag )
    DUP PERSIST-S-OK >= SWAP PERSIST-S-FAULT <= AND ;

: _PCOMPACT-DROP3  ( x1 x2 x3 -- ) 2DROP DROP ;
: _PCOMPACT-DROP9  ( x1 x2 x3 x4 x5 x6 x7 x8 x9 -- )
    2DROP 2DROP 2DROP 2DROP DROP ;

: _PCOMPACT-BYTES=  ( a1 u1 a2 u2 -- flag )
    2 PICK OVER <> IF 2DROP 2DROP 0 EXIT THEN
    DUP 0 ?DO
        3 PICK I + C@ 2 PICK I + C@ <> IF
            2DROP 2DROP 0 UNLOOP EXIT
        THEN
    LOOP
    2DROP 2DROP -1 ;

: _PCOMPACT-ROOT=  ( root-a root-b -- flag )
    PERSIST-ROOT-VALUE-SIZE _PSTORE-BYTES= ;

: _PCOMPACT-PAGE-FILE=  ( file-a file-b -- flag )
    >R
    DUP PPAGE-FILE-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    R@ PPAGE-FILE-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    DUP PPAGE.VFS @ R@ PPAGE.VFS @ <> IF DROP R> DROP 0 EXIT THEN
    DUP PPAGE-FILE-PATH$ R@ PPAGE-FILE-PATH$
        _PCOMPACT-BYTES= NIP
    R> DROP ;

: _PCOMPACT-SEGMENT-FILE=  ( file-a file-b -- flag )
    >R
    DUP PSEG-FILE-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    R@ PSEG-FILE-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    DUP PSEG-FILE-VFS@ R@ PSEG-FILE-VFS@ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP PSEG-FILE-PATH$ R@ PSEG-FILE-PATH$
        _PCOMPACT-BYTES= NIP
    R> DROP ;

: _PCOMPACT-ROOT-PATHS-DISJOINT?  ( shared-root staging-root -- flag )
    >R
    DUP PROOT-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    R@ PROOT-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    DUP PROOT-PATH-A$ R@ PROOT-PATH-A$
        _PCOMPACT-BYTES= IF DROP R> DROP 0 EXIT THEN
    DUP PROOT-PATH-A$ R@ PROOT-PATH-B$
        _PCOMPACT-BYTES= IF DROP R> DROP 0 EXIT THEN
    DUP PROOT-PATH-B$ R@ PROOT-PATH-A$
        _PCOMPACT-BYTES= IF DROP R> DROP 0 EXIT THEN
    DUP PROOT-PATH-B$ R@ PROOT-PATH-B$
        _PCOMPACT-BYTES= IF DROP R> DROP 0 EXIT THEN
    DROP R> DROP -1 ;

\ Complete span check for a shared root descriptor, its optional statistics,
\ and both configured data banks.  The page helper also covers each cache
\ descriptor and backing span.
: _PCOMPACT-SPAN-DISJOINT-ROOT?  ( address length root -- flag )
    >R
    DUP IF OVER 0= IF 2DROP R> DROP 0 EXIT THEN THEN
    2DUP MSPAN-NONWRAPPING? 0= IF 2DROP R> DROP 0 EXIT THEN
    R@ PROOT-VALID? 0= IF 2DROP R> DROP 0 EXIT THEN
    2DUP R@ PROOT-FILE-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP 0 EXIT
    THEN
    2DUP R@ _PROOT-F.VFS @ VFS-DESC-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP 0 EXIT
    THEN
    R@ _PROOT-F.STATS @ ?DUP IF
        2 PICK 2 PICK ROT PERSIST-STATS-SIZE
            MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    THEN
    2DUP R@ _PROOT-F.PAGE-FILE @ PERSIST-PAGE-FILE-SIZE
        MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    2DUP R@ _PROOT-F.PAGE-FILE @
        _PROOT-PAGE-CACHE-DISJOINT? 0= IF 2DROP R> DROP 0 EXIT THEN
    2DUP R@ _PROOT-F.SEGMENT @ PSEG-FILE-SIZE
        MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    R@ _PROOT-F.BANK1-PAGE @ ?DUP IF
        2 PICK 2 PICK ROT PERSIST-PAGE-FILE-SIZE
            MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
        2DUP R@ _PROOT-F.BANK1-PAGE @
            _PROOT-PAGE-CACHE-DISJOINT? 0= IF
            2DROP R> DROP 0 EXIT
        THEN
        2DUP R@ _PROOT-F.BANK1-SEG @ PSEG-FILE-SIZE
            MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    THEN
    2DROP R> DROP -1 ;

