: PCOMPACT-STATE@  ( work -- state|-1 )
    DUP PCOMPACT-WORK-VALID? IF _PCW.STATE @ ELSE DROP -1 THEN ;

: PCOMPACT-STATUS@  ( work -- status )
    DUP PCOMPACT-WORK-VALID? IF _PCW.STATUS @ ELSE DROP PERSIST-S-INVALID THEN ;

: PCOMPACT-SOURCE-BANK@  ( work -- bank|-1 )
    DUP PCOMPACT-WORK-VALID? IF _PCW.SOURCE-BANK @ ELSE DROP -1 THEN ;

: PCOMPACT-TARGET-BANK@  ( work -- bank|-1 )
    DUP PCOMPACT-WORK-VALID? IF _PCW.TARGET-BANK @ ELSE DROP -1 THEN ;

: PCOMPACT-NEXT-GENERATION@  ( work -- generation|0 )
    DUP PCOMPACT-WORK-VALID? IF _PCW.GENERATION @ ELSE DROP 0 THEN ;

: PCOMPACT-BYTES-USED@  ( work -- bytes|-1 )
    DUP PCOMPACT-WORK-VALID? IF _PCW.BYTES-USED @ ELSE DROP -1 THEN ;

: PCOMPACT-WORK-USED@  ( work -- count|-1 )
    DUP PCOMPACT-WORK-VALID? IF _PCW.WORK-USED @ ELSE DROP -1 THEN ;

: PCOMPACT-SOURCE-ROOT@  ( work -- root|0 )
    DUP PCOMPACT-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _PCW.STATE @ PCOMPACT-STATE-IDLE = IF DROP 0 EXIT THEN
    _PCW.SOURCE-ROOT ;

: PCOMPACT-TARGET-ROOT@  ( work -- root|0 )
    DUP PCOMPACT-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _PCW.STATE @ PCOMPACT-STATE-FINALIZED < IF DROP 0 EXIT THEN
    _PCW.TARGET-ROOT ;

\ ---------------------------------------------------------------------
\  Physical-bank helpers
