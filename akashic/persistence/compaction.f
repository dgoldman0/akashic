: PCOMPACT-WORK-VALID?  ( work -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP PCOMPACT-WORK-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    >R
    R@ _PCW.MAGIC @ _PCOMPACT-WORK-MAGIC <> IF R> DROP 0 EXIT THEN
    R@ _PCW.SELF @ R@ <> IF R> DROP 0 EXIT THEN
    R@ _PCW.BUSY @ DUP 0= SWAP 1 = OR 0= IF R> DROP 0 EXIT THEN
    R@ _PCW.STATE @ DUP PCOMPACT-STATE-IDLE <
        SWAP PCOMPACT-STATE-UNCERTAIN > OR IF R> DROP 0 EXIT THEN
    R@ _PCW.STATUS @ _PCOMPACT-STATUS? 0= IF R> DROP 0 EXIT THEN
    R@ _PCW.SOURCE-BANK @ DUP -1 =
        SWAP PERSIST-DATA-BANK-VALID? OR 0= IF R> DROP 0 EXIT THEN
    R@ _PCW.TARGET-BANK @ DUP -1 =
        SWAP PERSIST-DATA-BANK-VALID? OR 0= IF R> DROP 0 EXIT THEN
    R@ _PCW.GENERATION @ 0< IF R> DROP 0 EXIT THEN
    R@ _PCW.BYTES-USED @ 0< IF R> DROP 0 EXIT THEN
    R@ _PCW.WORK-USED @ 0< IF R> DROP 0 EXIT THEN
    R@ _PCW.COMPACT @ ?DUP IF
        PCOMPACT-VALID? 0= IF R> DROP 0 EXIT THEN
    THEN
    R@ _PCW.ROOT-WORK PROOT-WORK-VALID? 0= IF R> DROP 0 EXIT THEN
    R@ _PCW.PAGE-WORK PPAGE-WORK-VALID? 0= IF R> DROP 0 EXIT THEN
    R@ _PCW.SEGMENT-WORK PSEG-WORK-VALID?
    R> DROP ;

: PCOMPACT-WORK-INIT  ( segment-buffer-a segment-buffer-u work -- status )
    >R
    R@ 0= IF 2DROP R> DROP PERSIST-S-INVALID EXIT THEN
    R@ PCOMPACT-WORK-SIZE MSPAN-NONWRAPPING? 0= IF
        2DROP R> DROP PERSIST-S-INVALID EXIT
    THEN
    2DUP _PSEG-BUFFER? 0= IF 2DROP R> DROP PERSIST-S-INVALID EXIT THEN
    2DUP R@ PCOMPACT-WORK-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ PCOMPACT-WORK-SIZE 0 FILL
    _PCOMPACT-WORK-MAGIC R@ _PCW.MAGIC !
    R@ R@ _PCW.SELF !
    PERSIST-S-INVALID R@ _PCW.STATUS !
    -1 R@ _PCW.SOURCE-BANK !
    -1 R@ _PCW.TARGET-BANK !
    R@ _PCW.ROOT-WORK PROOT-WORK-INIT
    DUP IF >R 2DROP R> R> DROP EXIT THEN DROP
    R@ _PCW.PAGE-WORK PPAGE-WORK-INIT
    DUP IF >R 2DROP R> R> DROP EXIT THEN DROP
    1 PICK 1 PICK R@ _PCW.SEGMENT-WORK PSEG-WORK-INIT
    DUP IF >R 2DROP R> R> DROP EXIT THEN DROP
    PERSIST-S-OK R@ _PCW.STATUS !
    2DROP
    R@ PCOMPACT-WORK-VALID? 0= IF
        R> DUP PCOMPACT-WORK-SIZE 0 FILL DROP PERSIST-S-INVALID EXIT
    THEN
    R> DROP PERSIST-S-OK ;

: _PCOMPACT-WORK-BUFFER$  ( work -- address length )
    _PCW.SEGMENT-WORK
    DUP _PSEG-W.BUFFER @ SWAP _PSEG-W.CAPACITY @ ;

: _PCOMPACT-DESC-WORK?  ( compact work -- flag )
    >R
    DUP PCOMPACT-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    R@ PCOMPACT-WORK-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    DUP PCOMPACT-SIZE R@ PCOMPACT-WORK-SIZE MSPAN-OVERLAP? IF
        DROP R> DROP 0 EXIT
    THEN
    R@ PCOMPACT-WORK-SIZE 2 PICK _PCC.ROOT @
        _PCOMPACT-SPAN-DISJOINT-ROOT? 0= IF DROP R> DROP 0 EXIT THEN
    R@ PCOMPACT-WORK-SIZE 2 PICK _PCC.BUILDER @
        PSTORE-SPAN-DISJOINT? 0= IF DROP R> DROP 0 EXIT THEN
    R@ PCOMPACT-WORK-SIZE 2 PICK _PCC.BUILDER-WORK @
        PSTORE-WORK-SPAN-DISJOINT? 0= IF DROP R> DROP 0 EXIT THEN
    R@ _PCOMPACT-WORK-BUFFER$ 2 PICK PCOMPACT-SIZE
        MSPAN-OVERLAP? IF DROP R> DROP 0 EXIT THEN
    R@ _PCOMPACT-WORK-BUFFER$ 2 PICK _PCC.ROOT @
        _PCOMPACT-SPAN-DISJOINT-ROOT? 0= IF DROP R> DROP 0 EXIT THEN
    R@ _PCOMPACT-WORK-BUFFER$ 2 PICK _PCC.BUILDER @
        PSTORE-SPAN-DISJOINT? 0= IF DROP R> DROP 0 EXIT THEN
    R@ _PCOMPACT-WORK-BUFFER$ 2 PICK _PCC.BUILDER-WORK @
        PSTORE-WORK-SPAN-DISJOINT? 0= IF DROP R> DROP 0 EXIT THEN
    DROP R> DROP -1 ;

: _PCOMPACT-WORK-END  ( status work -- status )
    >R
    DUP R@ _PCW.STATUS !
    0 R@ _PCW.BUSY !
    R> DROP ;

: _PCOMPACT-RUN-CATCH  ( work xt -- status )
    >R DUP R> CATCH
    DUP IF _PCOMPACT-DROP3 PERSIST-S-FAULT ELSE DROP NIP THEN ;

: _PCOMPACT-RESET-OPERATION  ( compact work -- )
    >R
    R@ _PCW.COMPACT !
    PCOMPACT-STATE-IDLE R@ _PCW.STATE !
    0 R@ _PCW.BYTES-USED !
    0 R@ _PCW.WORK-USED !
    0 R@ _PCW.ALLOWANCE !
    0 R@ _PCW.CALLBACK-BYTES !
    0 R@ _PCW.CALLBACK-DONE !
    0 R@ _PCW.GENERATION !
    -1 R@ _PCW.SOURCE-BANK !
    -1 R@ _PCW.TARGET-BANK !
    R@ _PCW.SOURCE-ROOT PERSIST-ROOT-VALUE-SIZE 0 FILL
    R@ _PCW.TARGET-ROOT PERSIST-ROOT-VALUE-SIZE 0 FILL
    R> DROP ;

