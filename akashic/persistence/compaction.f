: _PCOMPACT-CLEAR-PAGE  ( page-file work -- status )
    >R
    DUP R@ _PCW.PAGE-WORK PPAGE-ENSURE
    DUP IF NIP R> DROP EXIT THEN DROP
    0 OVER R@ _PCW.PAGE-WORK PPAGE-TRUNCATE
    DUP IF NIP R> DROP EXIT THEN DROP
    PPAGE-SYNC R> DROP ;

: _PCOMPACT-CLEAR-SEGMENT  ( segment-file work -- status )
    >R
    DUP R@ _PCW.SEGMENT-WORK PSEG-ENSURE
    DUP IF NIP R> DROP EXIT THEN DROP
    0 OVER R@ _PCW.SEGMENT-WORK PSEG-TRUNCATE
    DUP IF NIP R> DROP EXIT THEN DROP
    PSEG-SYNC R> DROP ;

\ The protected bank is the freshly loaded selected authority.  Keeping it
\ explicit makes every destructive call site prove that it is clearing the
\ other bank.
: _PCOMPACT-CLEAR-BANK  ( clear-bank protected-bank work -- status )
    >R
    2DUP = IF 2DROP R> DROP PERSIST-S-CONFLICT EXIT THEN
    OVER PERSIST-DATA-BANK-VALID? 0= IF
        2DROP R> DROP PERSIST-S-INVALID EXIT
    THEN
    DUP PERSIST-DATA-BANK-VALID? 0= IF
        2DROP R> DROP PERSIST-S-INVALID EXIT
    THEN
    OVER R@ _PCW.COMPACT @ _PCC.ROOT @ PROOT-PAGE-FILE@
    DUP 0= IF DROP 2DROP R> DROP PERSIST-S-CONFLICT EXIT THEN
    R@ _PCOMPACT-CLEAR-PAGE
    DUP IF >R 2DROP R> R> DROP EXIT THEN DROP
    OVER R@ _PCW.COMPACT @ _PCC.ROOT @ PROOT-SEGMENT-FILE@
    DUP 0= IF DROP 2DROP R> DROP PERSIST-S-CONFLICT EXIT THEN
    R@ _PCOMPACT-CLEAR-SEGMENT
    DUP IF >R 2DROP R> R> DROP EXIT THEN DROP
    2DROP R> DROP PERSIST-S-OK ;

: _PCOMPACT-SLOTS-EXACT?  ( generation bank root -- flag )
    >R
    OVER GPAIR-SLOT-A R@ PROOT-SLOT-GENERATION@ =
    2 PICK GPAIR-SLOT-B R@ PROOT-SLOT-GENERATION@ = AND
    OVER GPAIR-SLOT-A R@ PROOT-SLOT-DATA-BANK@ = AND
    SWAP GPAIR-SLOT-B R@ PROOT-SLOT-DATA-BANK@ = AND
    NIP R> DROP ;

\ ---------------------------------------------------------------------
\  Begin and bounded build
\ ---------------------------------------------------------------------

: _PCOMPACT-BEGIN-RUN  ( work -- status )
    >R
    R@ _PCW.SOURCE-ROOT
    R@ _PCW.COMPACT @ _PCC.ROOT @
    R@ _PCW.ROOT-WORK PROOT-LOAD
    DUP IF
        NIP DUP PERSIST-S-ABSENT = IF DROP PERSIST-S-CONFLICT THEN
        R> DROP EXIT
    THEN
    DROP
    DUP 0> 0= IF DROP R> DROP PERSIST-S-CORRUPT EXIT THEN
    1 _PSTORE-ADD? 0= IF
        DROP R> DROP PERSIST-S-CAPACITY EXIT
    THEN
    R@ _PCW.GENERATION !
    R@ _PCW.SOURCE-ROOT PROOTV.DATA-BANK @ DUP
        R@ _PCW.SOURCE-BANK !
    1 SWAP - DUP R@ _PCW.TARGET-BANK !
    R@ _PCW.COMPACT @ _PCC.ROOT @ PROOT-BANK-CONFIGURED? 0= IF
        R> DROP PERSIST-S-CONFLICT EXIT
    THEN

    \ Establish two exact source snapshots before reusing the inactive bank.
    R@ _PCW.COMPACT @ _PCC.ROOT @
        R@ _PCW.ROOT-WORK PROOT-MIRROR
    DUP IF R> DROP EXIT THEN DROP
    R@ _PCW.GENERATION @ 1-
    R@ _PCW.SOURCE-BANK @
    R@ _PCW.COMPACT @ _PCC.ROOT @
        _PCOMPACT-SLOTS-EXACT? 0= IF
        R> DROP PERSIST-S-CORRUPT EXIT
    THEN

    R@ _PCW.SOURCE-ROOT PROOTV.IDENTITY
    R@ _PCW.COMPACT @ _PCC.BUILDER @ PSTORE-CURRENT-ROOT@
        PROOTV.IDENTITY
    PERSIST-IDENTITY-SIZE _PSTORE-BYTES= 0= IF
        R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    R@ _PCW.COMPACT @ _PCC.BUILDER @
        R@ _PCW.COMPACT @ _PCC.BUILDER-WORK @ PSTORE-STAGING-RESET
    DUP IF R> DROP EXIT THEN DROP
    R@ _PCW.TARGET-BANK @
        R@ _PCW.COMPACT @ _PCC.BUILDER @
        PSTORE-EXPECTED-DATA-BANK!
    DUP IF R> DROP EXIT THEN DROP
    R@ _PCW.TARGET-BANK @ R@ _PCW.SOURCE-BANK @
        R@ _PCOMPACT-CLEAR-BANK
    DUP IF R> DROP EXIT THEN DROP
    R@ _PCW.COMPACT @ _PCC.BUILDER @
        R@ _PCW.COMPACT @ _PCC.BUILDER-WORK @ PSTORE-PROVISION
    DUP IF R> DROP EXIT THEN DROP
    R@ _PCW.COMPACT @ _PCC.BUILDER @
        R@ _PCW.COMPACT @ _PCC.BUILDER-WORK @ PSTORE-OPEN
    DUP PERSIST-S-ABSENT <> IF
        DUP PERSIST-S-OK = IF DROP PERSIST-S-CONFLICT THEN
        R> DROP EXIT
    THEN
    DROP
    PCOMPACT-STATE-BUILDING R@ _PCW.STATE !
    R> DROP PERSIST-S-OK ;

: PCOMPACT-BEGIN  ( compact work -- status )
    >R
    DUP R@ _PCOMPACT-DESC-WORK? 0= IF
        DROP R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ _PCW.BUSY @ IF DROP R> DROP PERSIST-S-BUSY EXIT THEN
    R@ _PCW.STATE @ DUP PCOMPACT-STATE-IDLE <>
        SWAP PCOMPACT-STATE-CLEANED <> AND IF
        DROP R> DROP PERSIST-S-BUSY EXIT
    THEN
    R@ _PCOMPACT-RESET-OPERATION
    1 R@ _PCW.BUSY !
    PERSIST-S-INVALID R@ _PCW.STATUS !
    R@ ['] _PCOMPACT-BEGIN-RUN _PCOMPACT-RUN-CATCH
    R> _PCOMPACT-WORK-END ;

: _PCOMPACT-STEP-RUN  ( work -- status )
    >R
    R@ _PCW.SOURCE-ROOT
    R@ _PCW.COMPACT @ _PCC.BUILDER @
    R@ _PCW.COMPACT @ _PCC.BUILDER-WORK @
    R@ _PCW.ALLOWANCE @
    R@ _PCW.COMPACT @ _PCC.CONTEXT @
    R@ _PCW.COMPACT @ _PCC.STEP-XT @ EXECUTE
    DUP _PCOMPACT-STATUS? 0= IF
        _PCOMPACT-DROP3 R> DROP PERSIST-S-FAULT EXIT
    THEN
    DUP IF >R 2DROP R> R> DROP EXIT THEN
    DROP
    OVER DUP 0= SWAP -1 = OR 0= IF
        2DROP R> DROP PERSIST-S-INVALID EXIT
    THEN
    DUP 0< IF 2DROP R> DROP PERSIST-S-INVALID EXIT THEN
    DUP R@ _PCW.ALLOWANCE @ > IF
        2DROP R> DROP PERSIST-S-CAPACITY EXIT
    THEN
    DUP R@ _PCW.CALLBACK-BYTES !
    SWAP R@ _PCW.CALLBACK-DONE !
    R@ _PCW.BYTES-USED @ SWAP _PSTORE-ADD? 0= IF
        DROP R> DROP PERSIST-S-CAPACITY EXIT
    THEN
    R@ _PCW.BYTES-USED !
    R@ _PCW.WORK-USED @ 1 _PSTORE-ADD? 0= IF
        DROP R> DROP PERSIST-S-CAPACITY EXIT
    THEN
    R@ _PCW.WORK-USED !
    R@ _PCW.CALLBACK-DONE @ IF
        PCOMPACT-STATE-READY R@ _PCW.STATE !
    THEN
    R> DROP PERSIST-S-OK ;

: PCOMPACT-STEP  ( work -- status )
    DUP PCOMPACT-WORK-VALID? 0= IF DROP PERSIST-S-INVALID EXIT THEN
    DUP _PCW.BUSY @ IF DROP PERSIST-S-BUSY EXIT THEN
    DUP _PCW.STATE @ PCOMPACT-STATE-BUILDING <> IF
        DROP PERSIST-S-CONFLICT EXIT
    THEN
    DUP _PCW.WORK-USED @
        OVER _PCW.COMPACT @ _PCC.WORK-BUDGET @ >= IF
        DROP PERSIST-S-CAPACITY EXIT
    THEN
    DUP _PCW.COMPACT @ _PCC.BYTE-BUDGET @
        OVER _PCW.BYTES-USED @ - DUP 0> 0= IF
        2DROP PERSIST-S-CAPACITY EXIT
    THEN
    OVER _PCW.COMPACT @ _PCC.STEP-BYTES @ MIN
        OVER _PCW.ALLOWANCE !
    1 OVER _PCW.BUSY !
    PERSIST-S-INVALID OVER _PCW.STATUS !
    DUP ['] _PCOMPACT-STEP-RUN _PCOMPACT-RUN-CATCH
    SWAP _PCOMPACT-WORK-END ;

\ ---------------------------------------------------------------------
\  Exact-generation finalization and shared publication
\ ---------------------------------------------------------------------

: _PCOMPACT-REFRESH-SOURCE  ( work -- status )
    >R
    R@ _PCW.TARGET-ROOT
    R@ _PCW.COMPACT @ _PCC.ROOT @
    R@ _PCW.ROOT-WORK PROOT-LOAD
    DUP IF NIP R> DROP EXIT THEN
    DROP
    R@ _PCW.GENERATION @ 1- <> IF
        R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    R@ _PCW.TARGET-ROOT R@ _PCW.SOURCE-ROOT
        _PCOMPACT-ROOT= 0= IF
        R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    R> DROP PERSIST-S-OK ;

: _PCOMPACT-FINALIZE-RUN  ( work -- status )
    >R
    R@ _PCW.GENERATION @
    R@ _PCW.COMPACT @ _PCC.BUILDER @
    R@ _PCW.COMPACT @ _PCC.BUILDER-WORK @
    R@ _PCW.COMPACT @ _PCC.CONTEXT @
    R@ _PCW.COMPACT @ _PCC.FINALIZE-XT @ EXECUTE
    DUP _PCOMPACT-STATUS? 0= IF
        DROP R> DROP PERSIST-S-FAULT EXIT
    THEN
    DUP IF R> DROP EXIT THEN DROP
    R@ _PCOMPACT-REFRESH-SOURCE
    DUP IF R> DROP EXIT THEN DROP
    R@ _PCW.COMPACT @ _PCC.BUILDER @ PSTORE-CURRENT-ROOT@
    DUP 0= IF DROP R> DROP PERSIST-S-CONFLICT EXIT THEN
    DUP PERSIST-ROOT-VALUE-VALID? 0= IF
        DROP R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    DUP PROOTV.DATA-BANK @ R@ _PCW.TARGET-BANK @ <> IF
        DROP R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    DUP PROOTV.IDENTITY R@ _PCW.SOURCE-ROOT PROOTV.IDENTITY
        PERSIST-IDENTITY-SIZE _PSTORE-BYTES= 0= IF
        DROP R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    R@ _PCW.TARGET-ROOT PERSIST-ROOT-VALUE-COPY
    PCOMPACT-STATE-FINALIZED R@ _PCW.STATE !
    R> DROP PERSIST-S-OK ;

: PCOMPACT-FINALIZE  ( work -- status )
    DUP PCOMPACT-WORK-VALID? 0= IF DROP PERSIST-S-INVALID EXIT THEN
    DUP _PCW.BUSY @ IF DROP PERSIST-S-BUSY EXIT THEN
    DUP _PCW.STATE @ PCOMPACT-STATE-READY <> IF
        DROP PERSIST-S-CONFLICT EXIT
    THEN
    1 OVER _PCW.BUSY !
    PERSIST-S-INVALID OVER _PCW.STATUS !
    DUP ['] _PCOMPACT-FINALIZE-RUN _PCOMPACT-RUN-CATCH
    SWAP _PCOMPACT-WORK-END ;

: _PCOMPACT-PUBLISH-RUN  ( work -- status )
    >R
    R@ _PCW.TARGET-ROOT
    R@ _PCW.COMPACT @ _PCC.ROOT @
    R@ _PCW.ROOT-WORK PROOT-PUBLISH
    R@ _PCW.ROOT-WORK PROOT-LAST-OUTCOME@
    DUP GPAIR-W-DURABLE = IF
        DROP
        R@ _PCW.ROOT-WORK PROOT-GENERATION@
            R@ _PCW.GENERATION @ <> IF
            DROP PCOMPACT-STATE-UNCERTAIN R@ _PCW.STATE !
            R> DROP PERSIST-S-CORRUPT EXIT
        THEN
        PCOMPACT-STATE-PUBLISHED R@ _PCW.STATE !
        R> DROP EXIT
    THEN
    GPAIR-W-MAYBE = IF
        PCOMPACT-STATE-UNCERTAIN R@ _PCW.STATE !
        DUP PERSIST-S-OK = IF DROP PERSIST-S-UNCERTAIN THEN
    THEN
    R> DROP ;

: PCOMPACT-PUBLISH  ( work -- status )
    DUP PCOMPACT-WORK-VALID? 0= IF DROP PERSIST-S-INVALID EXIT THEN
    DUP _PCW.BUSY @ IF DROP PERSIST-S-BUSY EXIT THEN
    DUP _PCW.STATE @ PCOMPACT-STATE-FINALIZED <> IF
        DROP PERSIST-S-CONFLICT EXIT
    THEN
    1 OVER _PCW.BUSY !
    PERSIST-S-INVALID OVER _PCW.STATUS !
    DUP ['] _PCOMPACT-PUBLISH-RUN _PCOMPACT-RUN-CATCH
    SWAP _PCOMPACT-WORK-END ;

: PCOMPACT-CLEANUP-ELIGIBLE?  ( work -- flag )
    DUP PCOMPACT-WORK-VALID? 0= IF DROP 0 EXIT THEN
    >R
    R@ _PCW.STATE @ DUP PCOMPACT-STATE-PUBLISHED <
        SWAP PCOMPACT-STATE-CLEANED > OR IF R> DROP 0 EXIT THEN
    R@ _PCW.GENERATION @ 0> 0= IF R> DROP 0 EXIT THEN
    R@ _PCW.TARGET-BANK @ PERSIST-DATA-BANK-VALID? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _PCW.GENERATION @
    R@ _PCW.TARGET-BANK @
    R@ _PCW.COMPACT @ _PCC.ROOT @
        _PCOMPACT-SLOTS-EXACT?
    R> DROP ;

: _PCOMPACT-MIRROR-RUN  ( work -- status )
    >R
    R@ _PCW.COMPACT @ _PCC.ROOT @
        R@ _PCW.ROOT-WORK PROOT-MIRROR
    DUP R@ _PCW.CALLBACK-BYTES ! DROP
    R@ _PCW.ROOT-WORK PROOT-LAST-OUTCOME@
    DUP GPAIR-W-MAYBE = IF
        DROP PCOMPACT-STATE-UNCERTAIN R@ _PCW.STATE !
        R@ _PCW.CALLBACK-BYTES @ DUP PERSIST-S-OK = IF
            DROP PERSIST-S-UNCERTAIN
        THEN
        R> DROP EXIT
    THEN
    GPAIR-W-DURABLE <> R@ _PCW.CALLBACK-BYTES @ PERSIST-S-OK <> AND IF
        R@ _PCW.CALLBACK-BYTES @ R> DROP EXIT
    THEN
    R@ PCOMPACT-CLEANUP-ELIGIBLE? 0= IF
        PCOMPACT-STATE-UNCERTAIN R@ _PCW.STATE !
        R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    PCOMPACT-STATE-MIRRORED R@ _PCW.STATE !
    R@ _PCW.CALLBACK-BYTES @
    R> DROP ;

: PCOMPACT-MIRROR  ( work -- status )
    DUP PCOMPACT-WORK-VALID? 0= IF DROP PERSIST-S-INVALID EXIT THEN
    DUP _PCW.BUSY @ IF DROP PERSIST-S-BUSY EXIT THEN
    DUP _PCW.STATE @ PCOMPACT-STATE-PUBLISHED <> IF
        DROP PERSIST-S-CONFLICT EXIT
    THEN
    1 OVER _PCW.BUSY !
    PERSIST-S-INVALID OVER _PCW.STATUS !
    DUP ['] _PCOMPACT-MIRROR-RUN _PCOMPACT-RUN-CATCH
    SWAP _PCOMPACT-WORK-END ;

: _PCOMPACT-REFRESH-TARGET  ( work -- status )
    >R
    R@ _PCW.SOURCE-ROOT
    R@ _PCW.COMPACT @ _PCC.ROOT @
    R@ _PCW.ROOT-WORK PROOT-LOAD
    DUP IF NIP R> DROP EXIT THEN
    DROP
    R@ _PCW.GENERATION @ <> IF R> DROP PERSIST-S-CONFLICT EXIT THEN
    R@ _PCW.SOURCE-ROOT R@ _PCW.TARGET-ROOT
        _PCOMPACT-ROOT= 0= IF R> DROP PERSIST-S-CONFLICT EXIT THEN
    R@ _PCW.SOURCE-ROOT PROOTV.DATA-BANK @
        R@ _PCW.TARGET-BANK @ <> IF
        R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    R@ _PCW.GENERATION @
    R@ _PCW.TARGET-BANK @
    R@ _PCW.COMPACT @ _PCC.ROOT @
        _PCOMPACT-SLOTS-EXACT? 0= IF
        R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    R> DROP PERSIST-S-OK ;

: _PCOMPACT-CLEANUP-RUN  ( work -- status )
    >R
    R@ _PCOMPACT-REFRESH-TARGET
    DUP IF R> DROP EXIT THEN DROP
    PCOMPACT-STATE-MIRRORED R@ _PCW.STATE !
    R@ _PCW.SOURCE-BANK @ R@ _PCW.TARGET-BANK @
        R@ _PCOMPACT-CLEAR-BANK
    DUP IF R> DROP EXIT THEN DROP
    PCOMPACT-STATE-CLEANED R@ _PCW.STATE !
    R> DROP PERSIST-S-OK ;

: PCOMPACT-CLEANUP  ( work -- status )
    DUP PCOMPACT-CLEANUP-ELIGIBLE? 0= IF
        DROP PERSIST-S-CONFLICT EXIT
    THEN
    DUP _PCW.BUSY @ IF DROP PERSIST-S-BUSY EXIT THEN
    1 OVER _PCW.BUSY !
    PERSIST-S-INVALID OVER _PCW.STATUS !
    DUP ['] _PCOMPACT-CLEANUP-RUN _PCOMPACT-RUN-CATCH
    SWAP _PCOMPACT-WORK-END ;

\ ---------------------------------------------------------------------
\  Abort and journal-free cold convergence
\ ---------------------------------------------------------------------

: _PCOMPACT-ABORT-RUN  ( work -- status )
    >R
    R@ _PCW.SOURCE-ROOT
    R@ _PCW.COMPACT @ _PCC.ROOT @
    R@ _PCW.ROOT-WORK PROOT-LOAD
    DUP IF NIP R> DROP EXIT THEN
    2DROP
    R@ _PCW.SOURCE-ROOT PROOTV.DATA-BANK @
        R@ _PCW.TARGET-BANK @ = IF
        R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    R@ _PCW.TARGET-BANK @
    R@ _PCW.SOURCE-ROOT PROOTV.DATA-BANK @
        R@ _PCOMPACT-CLEAR-BANK
    DUP IF R> DROP EXIT THEN DROP
    PCOMPACT-STATE-IDLE R@ _PCW.STATE !
    R> DROP PERSIST-S-OK ;

: PCOMPACT-ABORT  ( work -- status )
    DUP PCOMPACT-WORK-VALID? 0= IF DROP PERSIST-S-INVALID EXIT THEN
    DUP _PCW.BUSY @ IF DROP PERSIST-S-BUSY EXIT THEN
    DUP _PCW.STATE @ PCOMPACT-STATE-IDLE = IF
        DROP PERSIST-S-OK EXIT
    THEN
    DUP _PCW.STATE @ DUP PCOMPACT-STATE-BUILDING <
        SWAP PCOMPACT-STATE-FINALIZED > OR IF
        DROP PERSIST-S-CONFLICT EXIT
    THEN
    1 OVER _PCW.BUSY !
    PERSIST-S-INVALID OVER _PCW.STATUS !
    DUP ['] _PCOMPACT-ABORT-RUN _PCOMPACT-RUN-CATCH
    SWAP _PCOMPACT-WORK-END ;

: _PCOMPACT-RECOVER-RUN  ( work -- status )
    >R
    R@ _PCW.TARGET-ROOT
    R@ _PCW.COMPACT @ _PCC.ROOT @
    R@ _PCW.ROOT-WORK PROOT-LOAD
    DUP IF NIP R> DROP EXIT THEN
    DROP
    DUP 0> 0= IF DROP R> DROP PERSIST-S-CORRUPT EXIT THEN
    R@ _PCW.GENERATION !
    R@ _PCW.TARGET-ROOT PROOTV.DATA-BANK @ DUP
        R@ _PCW.TARGET-BANK !
    1 SWAP - R@ _PCW.SOURCE-BANK !
    PCOMPACT-STATE-PUBLISHED R@ _PCW.STATE !

    \ Repair the non-selected slot first.  Only a durable or already-complete
    \ mirror is allowed to approach the destructive old-bank operation.
    R@ _PCW.COMPACT @ _PCC.ROOT @
        R@ _PCW.ROOT-WORK PROOT-MIRROR
    DUP R@ _PCW.CALLBACK-BYTES ! DROP
    R@ _PCW.ROOT-WORK PROOT-LAST-OUTCOME@
    DUP GPAIR-W-MAYBE = IF
        DROP PCOMPACT-STATE-UNCERTAIN R@ _PCW.STATE !
        R@ _PCW.CALLBACK-BYTES @ DUP PERSIST-S-OK = IF
            DROP PERSIST-S-UNCERTAIN
        THEN
        R> DROP EXIT
    THEN
    GPAIR-W-DURABLE <> R@ _PCW.CALLBACK-BYTES @ PERSIST-S-OK <> AND IF
        R@ _PCW.CALLBACK-BYTES @ R> DROP EXIT
    THEN

    R@ _PCOMPACT-REFRESH-TARGET
    DUP IF R> DROP EXIT THEN DROP
    PCOMPACT-STATE-MIRRORED R@ _PCW.STATE !
    R@ _PCW.SOURCE-BANK @ R@ _PCW.TARGET-BANK @
        R@ _PCOMPACT-CLEAR-BANK
    DUP IF R> DROP EXIT THEN DROP
    PCOMPACT-STATE-CLEANED R@ _PCW.STATE !
    R@ _PCW.CALLBACK-BYTES @
    R> DROP ;

\ Reinitialize operation-local facts, load the selected checked root once,
\ mirror it exactly, and truncate only the opposite physical bank after both
\ slots validate.  This safely discards a pre-publication partial rebuild and
\ completes either publish/mirror or mirror/truncate crash windows.
: PCOMPACT-RECOVER  ( compact work -- status )
    >R
    DUP R@ _PCOMPACT-DESC-WORK? 0= IF
        DROP R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ _PCW.BUSY @ IF DROP R> DROP PERSIST-S-BUSY EXIT THEN
    R@ _PCOMPACT-RESET-OPERATION
    1 R@ _PCW.BUSY !
    PERSIST-S-INVALID R@ _PCW.STATUS !
    R@ ['] _PCOMPACT-RECOVER-RUN _PCOMPACT-RUN-CATCH
    R> _PCOMPACT-WORK-END ;
