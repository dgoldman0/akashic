    OVER _RCS.ROTATE-SOURCE @ -1 = AND
    OVER _RCS.ROTATE-BUILD @ -1 = AND
    OVER _RCS.READY-HEAD @ -1 = AND
    OVER _RCS.READY-INDEX @ 0= AND
    OVER _RCS.RETIRED-COUNT @ 0= AND
    OVER _RCS.REUSABLE-COUNT @ 0= AND
    OVER _RCS.ROTATING @ 0= AND
