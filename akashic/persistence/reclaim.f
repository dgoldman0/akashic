: RECLAIM-AUDIT-WORK-VALID?  ( work -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP RECLAIM-AUDIT-WORK-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP 0 EXIT
    THEN
    DUP _RCA.MAGIC @ _RECLAIM-AUDIT-MAGIC <> IF DROP 0 EXIT THEN
    DUP _RCA.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _RCA.BUSY @ DUP 0= SWAP -1 = OR 0= IF DROP 0 EXIT THEN
    DUP _RCA.STATUS @ _RECLAIM-STATUS? 0= IF DROP 0 EXIT THEN
    DUP _RCA.BUSY @ IF
        DUP _RCA.MAP-U @ 0< IF DROP 0 EXIT THEN
        DUP _RCA.MAP-U @ IF
            DUP _RCA.MAP @ 0= IF DROP 0 EXIT THEN
            DUP _RCA.MAP @ OVER _RCA.MAP-U @
                MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
        THEN
        DUP _RCA.ENUMERATOR-XT @ 0= IF DROP 0 EXIT THEN
        DUP _RCA.RECLAIM @ RECLAIM-VALID? 0= IF DROP 0 EXIT THEN
        DUP _RCA.STORE @ PSTORE-VALID? 0= IF DROP 0 EXIT THEN
        DUP _RCA.PSTORE-WORK @ PSTORE-WORK-VALID? 0= IF
            DROP 0 EXIT
        THEN
        DUP _RCA.PHASE @ DUP 0=
        SWAP DUP _RCA-PHASE-OLD =
        SWAP _RCA-PHASE-CURRENT = OR OR 0= IF DROP 0 EXIT THEN
        DUP _RCA.ARENA-START @ DUP -1 < IF 2DROP 0 EXIT THEN
        DUP -1 = IF
            DROP
            DUP _RCA.ARENA-COUNT @ IF DROP 0 EXIT THEN
        ELSE
            DROP
            DUP _RCA.ARENA-START @
            OVER _RCA.ARENA-COUNT @
            2 PICK _RCA-ARENA-BOUNDS? 0= IF DROP 0 EXIT THEN
        THEN
    THEN
    DROP -1 ;

