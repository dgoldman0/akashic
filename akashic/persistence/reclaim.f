    DUP _RCW.ACTIVE @ DUP 0= SWAP -1 = OR 0= IF DROP 0 EXIT THEN
    DUP _RCW.FINALIZED @ DUP 0= SWAP -1 = OR 0= IF DROP 0 EXIT THEN
