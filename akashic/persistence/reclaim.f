: _RCW-ACTIVE?  ( reclaim-work store pstore-work -- flag )
    >R
    OVER RECLAIM-WORK-VALID? 0= IF 2DROP R> DROP 0 EXIT THEN
    OVER _RCW.ACTIVE @ 0= IF 2DROP R> DROP 0 EXIT THEN
    OVER _RCW.FINALIZED @ IF 2DROP R> DROP 0 EXIT THEN
    OVER _RCW.STATUS @ PERSIST-S-OK <> IF 2DROP R> DROP 0 EXIT THEN
    OVER _RCW.RECLAIM @ _RCL.ACTIVE-WORK @ 2 PICK <> IF
        2DROP R> DROP 0 EXIT
    THEN
    OVER _RCW.STORE @ OVER <> IF 2DROP R> DROP 0 EXIT THEN
    OVER _RCW.PSTORE-WORK @ R@ <> IF 2DROP R> DROP 0 EXIT THEN
    DUP R@ PSTORE-TX-READY? >R 2DROP R> R> DROP ;

\ Once an operation has passed the active-owner gate, any local failure makes
\ the shared PSTORE proposal uncommittable as well as stopping reclaim work.
\ This is a memory-only handoff; callers retain the original layered status
\ and must abort PSTORE before releasing the reclaim owner.
: _RCW-SET-STATUS  ( status work -- status )
    >R
    DUP IF
        DUP R@ _RCW.STORE @ R@ _RCW.PSTORE-WORK @
            PSTORE-TX-POISON DROP
    THEN
    DUP R@ _RCW.STATUS !
    R> DROP ;

: _RCW-PROPOSED-PAGE-COUNT  ( work -- count|-1 )
    _RCW.PSTORE-WORK @ PSTORE-PROPOSED-ROOT@
    DUP IF PROOTV.PAGE-COUNT @ ELSE DROP -1 THEN ;

: _RCW-READ-BUCKET  ( page-id work -- status )
    >R
    DUP R@ _RCW.STORE @ R@ _RCW.PSTORE-WORK @ PSTORE-READ-PAGE-TX
    DUP IF NIP R> DROP EXIT THEN DROP
    R@ _RCW.PSTORE-WORK @ PSTORE-PAGE-PAYLOAD$
    DUP PERSIST-PAGE-PAYLOAD-SIZE <> IF
        2DROP DROP R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    DROP R@ _RCW.BUCKET PERSIST-PAGE-PAYLOAD-SIZE MOVE
    R@ _RCW.BUCKET R@ _RCW-PROPOSED-PAGE-COUNT
        _RECLAIM-BUCKET-VALID? 0= IF
        DROP R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    DROP R> DROP PERSIST-S-OK ;

: _RCW-WRITE-OUTPUT  ( page-id work -- status )
    >R
    R@ _RCW.OUTPUT PERSIST-PAGE-PAYLOAD-SIZE ROT
    R@ _RCW.STORE @ R@ _RCW.PSTORE-WORK @ PSTORE-WRITE-PAGE-TX
    R> DROP ;

: _RCW-STAGED-CONTAINS?  ( page-id work -- flag )
    DUP _RCW.STAGED-COUNT @ 0 ?DO
        OVER I 2 PICK _RCW.STAGED-ENTRY @ = IF
            2DROP -1 UNLOOP EXIT
        THEN
    LOOP
    2DROP 0 ;

: _RCW-ALLOCATED-CONTAINS?  ( page-id work -- flag )
    DUP _RCW.ALLOCATED-COUNT @ 0 ?DO
        OVER I 2 PICK _RCW.ALLOCATED-ENTRY @ = IF
            2DROP -1 UNLOOP EXIT
        THEN
    LOOP
    2DROP 0 ;

: _RCW-DISCARDED-CONTAINS?  ( page-id work -- flag )
    DUP _RCW.DISCARD-COUNT @ 0 ?DO
        OVER I 2 PICK _RCW.DISCARDED-ENTRY @ = IF
            2DROP -1 UNLOOP EXIT
        THEN
    LOOP
    2DROP 0 ;

: _RCW-STAGE-ID  ( page-id work -- status )
    >R
    DUP 0< IF DROP R> DROP PERSIST-S-INVALID EXIT THEN
    R@ _RCW.STAGED-COUNT @ RECLAIM-RETIRED-MAX >= IF
        DROP R> DROP PERSIST-S-CAPACITY EXIT
    THEN
    DUP R@ _RCW-STAGED-CONTAINS? IF
        DROP R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    DUP R@ _RCW.TEMP ! DROP
    R@ _RCW.STAGED-COUNT @ R@ _RCW.RESULT !
    R>                                      ( work )
    DUP _RCW.STAGED-COUNT @ 0 ?DO
        DUP _RCW.RESULT @ OVER _RCW.STAGED-COUNT @ = IF
            I OVER _RCW.STAGED-ENTRY @ OVER _RCW.TEMP @ > IF
                I OVER _RCW.RESULT !
            THEN
        THEN
    LOOP
    DUP _RCW.RESULT @ OVER _RCW.STAGED-ENTRY
    DUP CELL+
    2 PICK _RCW.STAGED-COUNT @ 3 PICK _RCW.RESULT @ - CELLS MOVE
    DUP _RCW.TEMP @ OVER _RCW.RESULT @ 2 PICK _RCW.STAGED-ENTRY !
    1 SWAP _RCW.STAGED-COUNT +!
    PERSIST-S-OK ;

: _RCW-RECORD-ALLOCATION  ( page-id work -- status )
    >R
    R@ _RCW.ALLOCATED-COUNT @ RECLAIM-ALLOCATED-MAX >= IF
        DROP R> DROP PERSIST-S-CAPACITY EXIT
    THEN
    DUP R@ _RCW-ALLOCATED-CONTAINS? IF
        DROP R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    R@ _RCW.ALLOCATED-COUNT @ R@ _RCW.ALLOCATED-ENTRY !
    1 R@ _RCW.ALLOCATED-COUNT +!
    R> DROP PERSIST-S-OK ;

: _RCW-CLAIM-END  ( page-id work status -- status )
    >R
    DUP R> SWAP _RCW-SET-STATUS
    >R 2DROP R> ;

\ Admit the current PSTORE high-water id into the consumer-issued allocation
\ ledger without choosing a reusable id.  This is the neutral bridge for
\ copy-on-write owners that must allocate hidden pages strictly above the
\ durable page range while still sharing the reclaimer's bounded transaction
\ accounting.  The caller must claim immediately before writing that id.
: RECLAIM-CLAIM-HIGH-WATER  ( page-id reclaim-work -- status )
    DUP RECLAIM-WORK-VALID? 0= IF
        2DROP PERSIST-S-INVALID EXIT
    THEN
    DUP DUP _RCW.STORE @ 2 PICK _RCW.PSTORE-WORK @
        _RCW-ACTIVE? 0= IF
        2DROP PERSIST-S-BUSY EXIT
    THEN
    OVER 0< IF PERSIST-S-INVALID _RCW-CLAIM-END EXIT THEN
    OVER OVER _RCW-PROPOSED-PAGE-COUNT <> IF
        PERSIST-S-CONFLICT _RCW-CLAIM-END EXIT
    THEN
    OVER OVER _RCW-RECORD-ALLOCATION
    _RCW-CLAIM-END ;

: _RCW-DISCARD-ID  ( page-id work -- status )
    >R
    R@ _RCW.DISCARD-COUNT @ RECLAIM-DISCARD-MAX >= IF
        DROP R> DROP PERSIST-S-CAPACITY EXIT
    THEN
    DUP R@ _RCW-DISCARDED-CONTAINS? IF
        DROP R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    DUP R@ _RCW.TEMP ! DROP
    R@ _RCW.DISCARD-COUNT @ R@ _RCW.RESULT !
    R>
    DUP _RCW.DISCARD-COUNT @ 0 ?DO
        DUP _RCW.RESULT @ OVER _RCW.DISCARD-COUNT @ = IF
            I OVER _RCW.DISCARDED-ENTRY @ OVER _RCW.TEMP @ > IF
                I OVER _RCW.RESULT !
            THEN
        THEN
    LOOP
    DUP _RCW.RESULT @ OVER _RCW.DISCARDED-ENTRY
    DUP CELL+
    2 PICK _RCW.DISCARD-COUNT @ 3 PICK _RCW.RESULT @ - CELLS MOVE
    DUP _RCW.TEMP @ OVER _RCW.RESULT @ 2 PICK _RCW.DISCARDED-ENTRY !
    1 SWAP _RCW.DISCARD-COUNT +!
    PERSIST-S-OK ;

: _RCW-OUTPUT-HEADER  ( kind generation count next work -- )
    >R
    R@ _RCW.OUTPUT PERSIST-PAGE-PAYLOAD-SIZE 0 FILL
