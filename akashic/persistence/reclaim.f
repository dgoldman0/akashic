: _RCA-AUDIT-CHAIN  ( work -- status )
    >R
    0 R@ _RCA.CHAIN-COUNT !
    0 R@ _RCA.CHAIN-FIRST !
    0 R@ _RCA.CHAIN-LAST !
    0 R@ _RCA.CHAIN-PREV !
    0 R@ _RCA.CHAIN-SEEN !
    BEGIN
        R@ _RCA.CHAIN-HEAD @ -1 <>
    WHILE
        R@ _RCA.CHAIN-HEAD @ R@ _RCA-PHASE-META-MARK R@
            _RCA-MARK-UNIQUE
        DUP IF R> DROP EXIT THEN DROP
        R@ _RCA.CHAIN-HEAD @ R@ _RCA-READ-BUCKET
        DUP IF R> DROP EXIT THEN DROP
        R@ _RCA.BUCKET _RCB.KIND @
            R@ _RCA.CHAIN-KIND @ <> IF
            R> DROP PERSIST-S-CORRUPT EXIT
        THEN
        R@ _RCA.BUCKET _RCB.GENERATION @ DUP
            R@ _RCA-CHAIN-GENERATION? 0= IF
            DROP R> DROP PERSIST-S-CORRUPT EXIT
        THEN
        DUP R@ _RCA-CHAIN-ORDER? 0= IF
            DROP R> DROP PERSIST-S-CORRUPT EXIT
        THEN
        R@ _RCA-CHAIN-NOTE-GENERATION
        R@ _RCA.CHAIN-INDEX @ DUP
            R@ _RCA.BUCKET _RCB.COUNT @ >= IF
            DROP R> DROP PERSIST-S-CORRUPT EXIT
        THEN
        R@ _RCA.BUCKET _RCB.COUNT @ SWAP -
            R@ _RCA-CHAIN-ADD-ACTIVE
        DUP IF R> DROP EXIT THEN DROP
        R@ _RCA-MARK-BUCKET-ACTIVE
        DUP IF R> DROP EXIT THEN DROP
        R@ _RCA.BUCKET _RCB.NEXT @
            R@ _RCA.CHAIN-HEAD !
        R@ _RCA.BUCKET _RCB.NEXT-INDEX @
            R@ _RCA.CHAIN-INDEX !
    REPEAT
    R@ _RCA.CHAIN-INDEX @ IF
        R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    R> DROP PERSIST-S-OK ;

: _RCA-RUN-CHAIN
  ( head index kind mark order work -- status )
    >R
    R@ _RCA.CHAIN-ORDER !
    R@ _RCA.CHAIN-MARK !
    R@ _RCA.CHAIN-KIND !
    R@ _RCA.CHAIN-INDEX !
    R@ _RCA.CHAIN-HEAD !
    R> _RCA-AUDIT-CHAIN ;

: _RCA-ACCUMULATE-RETIRED  ( work -- status )
    >R
    R@ _RCA.RETIRED-SUM @
    R@ _RCA.CHAIN-COUNT @ _RECLAIM-ADD? 0= IF
        DROP R> DROP PERSIST-S-CAPACITY EXIT
    THEN
    R@ _RCA.RETIRED-SUM !
    R> DROP PERSIST-S-OK ;

: _RCA-AUDIT-IN  ( work -- status )
    >R
    R@ _RCA.STATE _RCS.IN-HEAD @
    0
    _RECLAIM-BUCKET-PENDING
    R@ _RCA-PHASE-PENDING-MARK
    _RCA-ORDER-DESCENDING
    R@ _RCA-RUN-CHAIN
    DUP IF R> DROP EXIT THEN DROP
    R@ _RCA.CHAIN-SEEN @ R@ _RCA.BOUNDARY-A-SEEN !
    R@ _RCA.CHAIN-LAST @ R@ _RCA.BOUNDARY-A !
    R@ _RCA-ACCUMULATE-RETIRED
    R> DROP ;

: _RCA-AUDIT-NONROTATING-OUT  ( work -- status )
    >R
    R@ _RCA.STATE _RCS.OUT-HEAD @
    R@ _RCA.STATE _RCS.OUT-INDEX @
    _RECLAIM-BUCKET-PENDING
    R@ _RCA-PHASE-PENDING-MARK
    _RCA-ORDER-ASCENDING
    R@ _RCA-RUN-CHAIN
    DUP IF R> DROP EXIT THEN DROP
    R@ _RCA.CHAIN-SEEN @ IF
        R@ _RCA.BOUNDARY-A-SEEN @ IF
            R@ _RCA.CHAIN-LAST @
            R@ _RCA.BOUNDARY-A @ >= IF
                R> DROP PERSIST-S-CORRUPT EXIT
            THEN
        THEN
    THEN
    R@ _RCA-ACCUMULATE-RETIRED
    R> DROP ;

: _RCA-AUDIT-ROTATING  ( work -- status )
    >R
    R@ _RCA.STATE _RCS.OUT-HEAD @ -1 <>
    R@ _RCA.STATE _RCS.OUT-INDEX @ OR IF
        R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    R@ _RCA.STATE _RCS.ROTATE-SOURCE @
    0
    _RECLAIM-BUCKET-PENDING
    R@ _RCA-PHASE-PENDING-MARK
    _RCA-ORDER-DESCENDING
    R@ _RCA-RUN-CHAIN
    DUP IF R> DROP EXIT THEN DROP
    R@ _RCA.CHAIN-SEEN @ 0= IF
        R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    R@ _RCA.CHAIN-FIRST @ R@ _RCA.BOUNDARY-B !
    R@ _RCA-ACCUMULATE-RETIRED
    DUP IF R> DROP EXIT THEN DROP

    R@ _RCA.STATE _RCS.ROTATE-BUILD @
    0
    _RECLAIM-BUCKET-PENDING
    R@ _RCA-PHASE-PENDING-MARK
    _RCA-ORDER-ASCENDING
    R@ _RCA-RUN-CHAIN
    DUP IF R> DROP EXIT THEN DROP
    R@ _RCA.CHAIN-SEEN @ 0= IF
        R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    R@ _RCA.BOUNDARY-B @
        R@ _RCA.CHAIN-FIRST @ > IF
        R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    R@ _RCA.BOUNDARY-A-SEEN @ IF
        R@ _RCA.BOUNDARY-A @
            R@ _RCA.CHAIN-LAST @ <= IF
            R> DROP PERSIST-S-CORRUPT EXIT
        THEN
    THEN
    R@ _RCA-ACCUMULATE-RETIRED
    R> DROP ;

: _RCA-AUDIT-READY  ( work -- status )
    >R
    R@ _RCA.STATE _RCS.READY-HEAD @
    R@ _RCA.STATE _RCS.READY-INDEX @
    _RECLAIM-BUCKET-READY
    R@ _RCA-PHASE-READY-MARK
    _RCA-ORDER-NONE
    R@ _RCA-RUN-CHAIN
    DUP IF R> DROP EXIT THEN DROP
    R@ _RCA.CHAIN-COUNT @ R@ _RCA.REUSABLE-SUM !
    R> DROP PERSIST-S-OK ;

: _RCA-AUDIT-SUBMITTED-STATE  ( work -- status )
    >R
    0 R@ _RCA.RETIRED-SUM !
    0 R@ _RCA.REUSABLE-SUM !
    0 R@ _RCA.BOUNDARY-A-SEEN !
    0 R@ _RCA.BOUNDARY-B-SEEN !
    R@ _RCA-AUDIT-IN
    DUP IF R> DROP EXIT THEN DROP
    R@ _RCA.STATE _RCS.ROTATING @ IF
        R@ _RCA-AUDIT-ROTATING
    ELSE
        R@ _RCA-AUDIT-NONROTATING-OUT
    THEN
    DUP IF R> DROP EXIT THEN DROP
    R@ _RCA-AUDIT-READY
    DUP IF R> DROP EXIT THEN DROP
    R@ _RCA.RETIRED-SUM @
        R@ _RCA.STATE _RCS.RETIRED-COUNT @ <> IF
        R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    R@ _RCA.REUSABLE-SUM @
        R@ _RCA.STATE _RCS.REUSABLE-COUNT @ <> IF
        R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    R> DROP PERSIST-S-OK ;

: _RCA-ONE-BIT?  ( byte mask -- flag )
    AND DUP 0= IF DROP 0 EXIT THEN
    DUP 1- AND 0= ;

: _RCA-AUDIT-ARENA  ( work -- status )
    >R
    R@ _RCA.ARENA-START @ -1 = IF
        R> DROP PERSIST-S-OK EXIT
    THEN
    R@ _RCA.ARENA-START @
    R@ _RCA.ARENA-COUNT @
    R@ _RCA-ARENA-BOUNDS? 0= IF
        R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    0 R@ _RCA.CHAIN-INDEX !
    BEGIN
        R@ _RCA.CHAIN-INDEX @ R@ _RCA.ARENA-COUNT @ <
    WHILE
        R@ _RCA.ARENA-START @ R@ _RCA.CHAIN-INDEX @ + DUP
        R@ _RCA.MAP @ + C@ R@ _RCA-PHASE-MASK AND
        DUP IF
            R@ _RCA-PHASE-APP-MARK <> IF
                DROP R> DROP PERSIST-S-CORRUPT EXIT
            THEN
            DROP
        ELSE
            DROP
            R@ _RCA-PHASE-APP-MARK R@ _RCA-MARK-UNIQUE
            DUP IF R> DROP EXIT THEN DROP
        THEN
        1 R@ _RCA.CHAIN-INDEX +!
    REPEAT
    R> DROP PERSIST-S-OK ;

: _RCA-CLASSIFY-OLD  ( work -- status )
    DUP _RCA.SLOT-PAGE-COUNT @ 0 ?DO
        DUP _RCA.MAP @ I + C@ _RCA-M-OLD _RCA-ONE-BIT? 0= IF
            DROP PERSIST-S-CORRUPT UNLOOP EXIT
        THEN
    LOOP
    DROP PERSIST-S-OK ;

: _RCA-CURRENT-OVERLAP?  ( byte -- flag )
    DUP _RCA-M-OLD-LIVE AND 0= IF DROP -1 EXIT THEN
    DUP _RCA-M-CURRENT-PENDING AND IF DROP -1 EXIT THEN
    DUP _RCA-M-OLD-APP AND IF
        _RCA-M-CURRENT-APP AND 0<> EXIT
    THEN
    DUP _RCA-M-OLD-META AND IF
        _RCA-M-CURRENT-META AND 0<> EXIT
    THEN
    DROP 0 ;

: _RCA-CLASSIFY-CURRENT  ( work -- status )
    DUP _RCA.SLOT-PAGE-COUNT @ 0 ?DO
        DUP _RCA.MAP @ I + C@ DUP
        _RCA-M-CURRENT _RCA-ONE-BIT? 0= IF
            2DROP PERSIST-S-CORRUPT UNLOOP EXIT
        THEN
        _RCA-CURRENT-OVERLAP? 0= IF
            DROP PERSIST-S-CORRUPT UNLOOP EXIT
        THEN
    LOOP
    DROP PERSIST-S-OK ;

: _RCA-BYTES=  ( a b u -- flag )
    DUP 0< IF DROP 2DROP 0 EXIT THEN
    0 ?DO
        2DUP I + C@ SWAP I + C@ <> IF
            2DROP 0 UNLOOP EXIT
        THEN
    LOOP
    2DROP -1 ;

: _RCA-EXPECTED-ROOT  ( slot work -- root )
    SWAP GPAIR-SLOT-A = IF _RCA.ROOT-A ELSE _RCA.ROOT-B THEN ;

: _RCA-EXPECTED-GENERATION  ( slot work -- generation )
    SWAP GPAIR-SLOT-A = IF
        _RCA.GENERATION-A
    ELSE
        _RCA.GENERATION-B
    THEN @ ;

: _RCA-REBIND-SLOT  ( slot work -- status )
    >R
    DUP R@ _RCA.SLOT-ROOT
    R@ _RCA.STORE @ R@ _RCA.PSTORE-WORK @ PSTORE-ROOT-SLOT@
    DUP IF
        >R 2DROP R>
        DUP PERSIST-S-ABSENT =
        OVER PERSIST-S-CORRUPT = OR
        OVER PERSIST-S-BUSY = OR IF
            DROP PERSIST-S-CONFLICT
        THEN
        R> DROP EXIT
    THEN DROP
    OVER R@ _RCA-EXPECTED-GENERATION <> IF
        DROP R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    DUP R@ _RCA-EXPECTED-ROOT
    R@ _RCA.SLOT-ROOT PERSIST-ROOT-VALUE-SIZE
        _RCA-BYTES= 0= IF
        DROP R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    DROP R> DROP PERSIST-S-OK ;

: _RCA-ENUMERATOR-BODY  ( work -- )
    >R
    R@ _RCA.SLOT-ROOT
    R@ _RCA.SLOT-GENERATION @
    R@ _RCA.SLOT @
    R@
    R@ _RCA.ENUMERATOR-CTX @
    R@ _RCA.ENUMERATOR-XT @ EXECUTE
    R@ _RCA.CALLBACK-STATUS !
    R> DROP ;

: _RCA-CALL-ENUMERATOR  ( work -- status )
    >R
    PERSIST-S-FAULT R@ _RCA.CALLBACK-STATUS !
    R@ ['] _RCA-ENUMERATOR-BODY CATCH
    DUP IF
        2DROP R> DROP PERSIST-S-FAULT EXIT
    THEN DROP
    R@ _RCA.CALLBACK-STATUS @ DUP _RECLAIM-STATUS? 0= IF
        DROP R> DROP PERSIST-S-FAULT EXIT
    THEN
    DUP IF R> DROP EXIT THEN DROP
    R@ _RCA.ROOT-SUBMITTED @ -1 <>
    R@ _RCA.STATE-SUBMITTED @ -1 <> OR
    R@ _RCA.COMPLETE @ -1 <> OR IF
        R> DROP PERSIST-S-FAULT EXIT
    THEN
    R> DROP PERSIST-S-OK ;

: _RCA-AUDIT-SLOT  ( slot work -- status )
    >R
    DUP R@ _RCA.SLOT !
    DUP R@ _RCA-REBIND-SLOT
    DUP IF NIP R> DROP EXIT THEN DROP
    DUP R@ _RCA-EXPECTED-GENERATION
        R@ _RCA.SLOT-GENERATION !
    R@ _RCA.SLOT-ROOT PROOTV.PAGE-COUNT @
        R@ _RCA.SLOT-PAGE-COUNT !
    R@ _RCA.SLOT-ROOT PROOTV.DATA-BANK @
        R@ _RCA.SLOT-BANK !
    0 R@ _RCA.ROOT-SUBMITTED !
    0 R@ _RCA.STATE-SUBMITTED !
    0 R@ _RCA.COMPLETE !
    -1 R@ _RCA.ARENA-START !
    0 R@ _RCA.ARENA-COUNT !
    DROP
    R@ _RCA-CALL-ENUMERATOR
    DUP IF R> DROP EXIT THEN DROP
    R@ _RCA.SLOT @ R@ _RCA-REBIND-SLOT
    DUP IF R> DROP EXIT THEN DROP
    R@ _RCA.PHASE @ _RCA-PHASE-CURRENT = IF
        R@ _RCA.STATE
        R@ _RCA.RECLAIM @ _RCL.STATE
        RECLAIM-STATE-SIZE _RCA-BYTES= 0= IF
            R> DROP PERSIST-S-CORRUPT EXIT
        THEN
    THEN
    R@ _RCA-AUDIT-SUBMITTED-STATE
    DUP IF R> DROP EXIT THEN DROP
    R@ _RCA-AUDIT-ARENA
    DUP IF R> DROP EXIT THEN DROP
    R@ _RCA.PHASE @ _RCA-PHASE-OLD = IF
        R> _RCA-CLASSIFY-OLD
    ELSE
        R> _RCA-CLASSIFY-CURRENT
    THEN ;

: _RCA-COLLECT-A  ( work -- status )
    >R
    0 R@ _RCA.VALID-A !
    0 R@ _RCA.GENERATION-A !
    GPAIR-SLOT-A R@ _RCA.ROOT-A
    R@ _RCA.STORE @ R@ _RCA.PSTORE-WORK @ PSTORE-ROOT-SLOT@
    DUP PERSIST-S-OK = IF
        DROP R@ _RCA.GENERATION-A !
        -1 R@ _RCA.VALID-A !
        R> DROP PERSIST-S-OK EXIT
    THEN
    DUP PERSIST-S-ABSENT =
    OVER PERSIST-S-CORRUPT = OR IF
        2DROP R> DROP PERSIST-S-OK EXIT
    THEN
    DUP PERSIST-S-BUSY = IF
        2DROP R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    NIP R> DROP ;

: _RCA-COLLECT-B  ( work -- status )
    >R
    0 R@ _RCA.VALID-B !
    0 R@ _RCA.GENERATION-B !
    GPAIR-SLOT-B R@ _RCA.ROOT-B
    R@ _RCA.STORE @ R@ _RCA.PSTORE-WORK @ PSTORE-ROOT-SLOT@
    DUP PERSIST-S-OK = IF
        DROP R@ _RCA.GENERATION-B !
        -1 R@ _RCA.VALID-B !
        R> DROP PERSIST-S-OK EXIT
    THEN
    DUP PERSIST-S-ABSENT =
    OVER PERSIST-S-CORRUPT = OR IF
        2DROP R> DROP PERSIST-S-OK EXIT
    THEN
    DUP PERSIST-S-BUSY = IF
        2DROP R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    NIP R> DROP ;

: _RCA-SLOT-VALID?  ( slot work -- flag )
    SWAP GPAIR-SLOT-A = IF _RCA.VALID-A ELSE _RCA.VALID-B THEN @ ;

: _RCA-SLOT-CURRENT?  ( slot work -- flag )
    >R
    DUP R@ _RCA-SLOT-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    DUP R@ _RCA-EXPECTED-GENERATION
        R@ _RCA.STORE @ PSTORE-GENERATION@ <> IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _RCA-EXPECTED-ROOT
    R@ _RCA.STORE @ PSTORE-CURRENT-ROOT@
    PERSIST-ROOT-VALUE-SIZE _RCA-BYTES=
    R> DROP ;

: _RCA-SLOT-PAGE-COUNT@  ( slot work -- count )
    _RCA-EXPECTED-ROOT PROOTV.PAGE-COUNT @ ;

: _RCA-SLOT-BANK@  ( slot work -- bank )
    _RCA-EXPECTED-ROOT PROOTV.DATA-BANK @ ;

: _RCA-SELECT-SLOTS  ( work -- status )
    >R
    -1 R@ _RCA.CURRENT-SLOT !
    -1 R@ _RCA.OLD-SLOT !
    0 R@ _RCA.OLD-SAME-BANK !
    GPAIR-SLOT-A R@ _RCA-SLOT-CURRENT? IF
        GPAIR-SLOT-A R@ _RCA.CURRENT-SLOT !
    ELSE
        GPAIR-SLOT-B R@ _RCA-SLOT-CURRENT? IF
            GPAIR-SLOT-B R@ _RCA.CURRENT-SLOT !
        ELSE
            R> DROP PERSIST-S-CONFLICT EXIT
        THEN
    THEN
    R@ _RCA.CURRENT-SLOT @ GPAIR-SLOT-A = IF
        GPAIR-SLOT-B
    ELSE
        GPAIR-SLOT-A
    THEN
    DUP R@ _RCA-SLOT-VALID? IF
        DUP R@ _RCA-SLOT-CURRENT? 0= IF
            DUP R@ _RCA-EXPECTED-GENERATION
                R@ _RCA.STORE @ PSTORE-GENERATION@ >= IF
                DROP R> DROP PERSIST-S-CONFLICT EXIT
            THEN
            DUP R@ _RCA.OLD-SLOT !
        THEN
    THEN
    DROP
    R@ _RCA.STORE @ PSTORE-CURRENT-ROOT@ DUP
        PROOTV.PAGE-COUNT @ R@ _RCA.CURRENT-PAGE-COUNT !
    PROOTV.DATA-BANK @ R@ _RCA.CURRENT-BANK !
    0 R@ _RCA.MAX-PAGE-COUNT !
    R@ _RCA.VALID-A @ IF
        R@ _RCA.ROOT-A PROOTV.PAGE-COUNT @
        R@ _RCA.MAX-PAGE-COUNT @ MAX
        R@ _RCA.MAX-PAGE-COUNT !
    THEN
    R@ _RCA.VALID-B @ IF
        R@ _RCA.ROOT-B PROOTV.PAGE-COUNT @
        R@ _RCA.MAX-PAGE-COUNT @ MAX
        R@ _RCA.MAX-PAGE-COUNT !
    THEN
    R@ _RCA.OLD-SLOT @ -1 <> IF
        R@ _RCA.OLD-SLOT @ R@ _RCA-EXPECTED-GENERATION
            R@ _RCA.OLD-GENERATION !
        R@ _RCA.OLD-SLOT @ R@ _RCA-SLOT-BANK@
            R@ _RCA.CURRENT-BANK @ = IF
            -1 R@ _RCA.OLD-SAME-BANK !
            R@ _RCA.OLD-SLOT @ R@ _RCA-SLOT-PAGE-COUNT@
                R@ _RCA.CURRENT-PAGE-COUNT @ > IF
                R> DROP PERSIST-S-CORRUPT EXIT
            THEN
        THEN
    ELSE
        0 R@ _RCA.OLD-GENERATION !
    THEN
    R> DROP PERSIST-S-OK ;

: _RCA-DROP7  ( x1 x2 x3 x4 x5 x6 x7 -- )
    2DROP 2DROP 2DROP DROP ;

: _RCA-DROP8  ( x1 x2 x3 x4 x5 x6 x7 x8 -- )
    2DROP 2DROP 2DROP 2DROP ;

: _RCA-ARGS-PREFLIGHT
  ( map-a map-u xt ctx reclaim store pstore-work audit-work -- status )
    >R
    R@ RECLAIM-AUDIT-WORK-VALID? 0= IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ _RCA.BUSY @ IF
        _RCA-DROP7 R> DROP PERSIST-S-BUSY EXIT
    THEN
    4 PICK 0= IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    5 PICK 0< IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    5 PICK IF
        6 PICK DUP 0= IF
            DROP _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
        THEN
        6 PICK MSPAN-NONWRAPPING? 0= IF
            _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
        THEN
    THEN
    2 PICK RECLAIM-VALID? 0= IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    1 PICK PSTORE-VALID? 0= IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    DUP PSTORE-WORK-VALID? 0= IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    2 PICK _RCL.ACTIVE-WORK @ IF
        _RCA-DROP7 R> DROP PERSIST-S-BUSY EXIT
    THEN
    2 PICK _RCL.AUDIT-WORK @ IF
        _RCA-DROP7 R> DROP PERSIST-S-BUSY EXIT
    THEN
    2 PICK _RCL.STORE @ 2 PICK <> IF
        _RCA-DROP7 R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    2 PICK _RCL.GENERATION @ 2 PICK PSTORE-GENERATION@ <> IF
        _RCA-DROP7 R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    1 PICK 1 PICK PSTORE-TX-READY? 0= IF
        _RCA-DROP7 R> DROP PERSIST-S-BUSY EXIT
    THEN

    \ All five mutable authorities are pairwise disjoint before the audit
    \ work receives even its first argument binding.
    R@ RECLAIM-AUDIT-WORK-SIZE 4 PICK RECLAIM-SIZE
        MSPAN-OVERLAP? IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ RECLAIM-AUDIT-WORK-SIZE 3 PICK
        PSTORE-SPAN-DISJOINT? 0= IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ RECLAIM-AUDIT-WORK-SIZE 2 PICK
        PSTORE-WORK-SPAN-DISJOINT? 0= IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN

    6 PICK 6 PICK R@ RECLAIM-AUDIT-WORK-SIZE
        MSPAN-OVERLAP? IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    6 PICK 6 PICK 4 PICK RECLAIM-SIZE MSPAN-OVERLAP? IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    6 PICK 6 PICK 3 PICK PSTORE-SPAN-DISJOINT? 0= IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    6 PICK 6 PICK 2 PICK PSTORE-WORK-SPAN-DISJOINT? 0= IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN

    2 PICK RECLAIM-SIZE 3 PICK PSTORE-SPAN-DISJOINT? 0= IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    2 PICK RECLAIM-SIZE 2 PICK
        PSTORE-WORK-SPAN-DISJOINT? 0= IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    1 PICK PSTORE-SIZE 2 PICK PSTORE-WORK-SIZE
        MSPAN-OVERLAP? IF
        _RCA-DROP7 R> DROP PERSIST-S-INVALID EXIT
    THEN
    _RCA-DROP7 R> DROP PERSIST-S-OK ;

: _RCA-PREFLIGHT  ( work -- status )
    >R
    R@ _RCA.ENUMERATOR-XT @ 0= IF
        R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ _RCA.RECLAIM @ RECLAIM-VALID? 0= IF
        R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ _RCA.STORE @ PSTORE-VALID? 0= IF
        R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ _RCA.PSTORE-WORK @ PSTORE-WORK-VALID? 0= IF
        R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ _RCA.RECLAIM @ _RCL.ACTIVE-WORK @ IF
        R> DROP PERSIST-S-BUSY EXIT
    THEN
    R@ _RCA.RECLAIM @ _RCL.AUDIT-WORK @ IF
        R> DROP PERSIST-S-BUSY EXIT
    THEN
    R@ _RCA.RECLAIM @ _RCL.STORE @
        R@ _RCA.STORE @ <> IF
        R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    R@ _RCA.RECLAIM @ _RCL.GENERATION @
        R@ _RCA.STORE @ PSTORE-GENERATION@ <> IF
        R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    R@ _RCA.STORE @ R@ _RCA.PSTORE-WORK @
        PSTORE-TX-READY? 0= IF
        R> DROP PERSIST-S-BUSY EXIT
    THEN
    R@ _RCA.MAP-U @ 0< IF R> DROP PERSIST-S-INVALID EXIT THEN
    R@ _RCA.MAP-U @ IF
        R@ _RCA.MAP @ DUP 0= IF
            DROP R> DROP PERSIST-S-INVALID EXIT
        THEN
        R@ _RCA.MAP-U @ MSPAN-NONWRAPPING? 0= IF
            R> DROP PERSIST-S-INVALID EXIT
        THEN
    THEN
    R@ RECLAIM-AUDIT-WORK-SIZE
        R@ _RCA.RECLAIM @ RECLAIM-SIZE MSPAN-OVERLAP? IF
        R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ RECLAIM-AUDIT-WORK-SIZE R@ _RCA.STORE @
        PSTORE-SPAN-DISJOINT? 0= IF
        R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ RECLAIM-AUDIT-WORK-SIZE R@ _RCA.PSTORE-WORK @
        PSTORE-WORK-SPAN-DISJOINT? 0= IF
        R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ _RCA.MAP @ R@ _RCA.MAP-U @ R@
        RECLAIM-AUDIT-WORK-SIZE MSPAN-OVERLAP? IF
        R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ _RCA.MAP @ R@ _RCA.MAP-U @
        R@ _RCA.RECLAIM @ RECLAIM-SIZE MSPAN-OVERLAP? IF
        R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ _RCA.MAP @ R@ _RCA.MAP-U @ R@ _RCA.STORE @
        PSTORE-SPAN-DISJOINT? 0= IF
        R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ _RCA.MAP @ R@ _RCA.MAP-U @
        R@ _RCA.PSTORE-WORK @ PSTORE-WORK-SPAN-DISJOINT? 0= IF
        R> DROP PERSIST-S-INVALID EXIT
    THEN
    R> DROP PERSIST-S-OK ;

: _RCA-END  ( status work -- status )
    >R
    DUP _RECLAIM-STATUS? 0= IF DROP PERSIST-S-FAULT THEN
    DUP PERSIST-S-OK = IF
        R@ _RCA.STORE @ PSTORE-GENERATION@
        R@ _RCA.RECLAIM @ _RCL.AUDITED-GENERATION !
