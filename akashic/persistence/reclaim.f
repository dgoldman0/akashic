        R@ _RCA.OLD-SAME-BANK @ 0= IF R@ _RCA-CLEAR-MAP THEN
    THEN
    _RCA-PHASE-CURRENT R@ _RCA.PHASE !
    R@ _RCA.CURRENT-SLOT @ R@ _RCA-AUDIT-SLOT
    R> DROP ;

