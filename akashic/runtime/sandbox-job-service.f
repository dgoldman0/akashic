    SWAP SBOX-JOB-STATE-FAILED > OR IF 0 EXIT THEN
    _SBXJV-SLOT @ _SBXJS.RESERVED @ IF 0 EXIT THEN
    _SBXJV-SLOT @ _SBXJS.JOB-GENERATION @ DUP 0> 0= IF DROP 0 EXIT THEN
    _SBXJV-GENERATION !
