    OVER _SBXJS.ADMISSION SBOX-ADMISSION-STATE@
    SBOX-ADMISSION-STATE-DRAINED <> IF
        NIP R> DROP EXIT
    THEN
    OVER _SBXJS-SIZE 0 FILL
    -1 R> _SBXJ.LIVE-N +!
    NIP ;

