    THEN
    _SBXJL-ACTIVATION @ _SBXJL-SERVICE @ _SBXJ.ACTIVATION-ID @ <> IF
        0 SBOX-JOB-S-STALE-GENERATION EXIT
    THEN
    _SBXJL-GENERATION @ 0> 0= IF
        0 SBOX-JOB-S-STALE-GENERATION EXIT
    THEN
