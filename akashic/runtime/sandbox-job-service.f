    SWAP SBOX-VM-RUN-CANCELLED > OR IF 0 EXIT THEN
    _SBXJV-SLOT @ _SBXJS.STATUS @ DUP
        SBOX-JOB-STATUS-VALID? 0= IF DROP 0 EXIT THEN
    _SBXJV-STATUS !
    _SBXJV-SLOT @ _SBXJS.ADMISSION DUP _SBXJV-ADMISSION !
