    _SBXART-ADMISSION @ SBOX-ADMISSION-VALID? 0= IF
        SBOX-JOB-S-INVALID EXIT
    THEN
    _SBXART-RECEIPT @ SBOX-RECEIPT-SIZE
    _SBXART-ADMISSION @ _SBXA-EXTERNAL-SPAN? 0= IF
        SBOX-JOB-S-ALIAS EXIT
    THEN
    _SBXART-RECEIPT @
    _SBXART-GENERATION @
    _SBXART-ADMISSION @
    _SBXA-RESULT-SPAN-STATUS DUP IF EXIT THEN DROP
