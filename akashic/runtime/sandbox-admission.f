: _SBXRC-FIXED?  ( receipt -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    SBOX-RECEIPT-SIZE _SBXA-SPAN? ;

: _SBXRC-COPIED-ENTRY?  ( receipt -- flag )
    DUP _SBXRC.ENTRY
    OVER _SBXRC.ENTRY-U @
    _SBXA-ENTRY-NAME? 0= IF DROP 0 EXIT THEN
    DUP _SBXRC.ENTRY
    OVER _SBXRC.ENTRY-U @ +
    SWAP _SBXRC.ENTRY-U @ 64 SWAP -
    _SBXA-ZERO? ;

: SBOX-RECEIPT-VALID?  ( receipt -- flag )
    DUP _SBXRC-FIXED? 0= IF DROP 0 EXIT THEN
    DUP _SBXRC.MAGIC @ _SBXRC-MAGIC <> IF DROP 0 EXIT THEN
    DUP _SBXRC.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _SBXRC.SIZE @ SBOX-RECEIPT-SIZE <> IF DROP 0 EXIT THEN
    DUP _SBXRC.CLASS @ SBOX-CLASS-PURE <> IF DROP 0 EXIT THEN
    DUP _SBXRC.ACTIVATION-ID @ 0> 0= IF DROP 0 EXIT THEN
    DUP _SBXRC.ACTIVATION-GENERATION @ 0> 0= IF DROP 0 EXIT THEN
    DUP _SBXRC.INVOCATION-GENERATION @ 0> 0= IF DROP 0 EXIT THEN
    DUP _SBXRC.PRACTICE-REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP _SBXRC.CONTEXT-ID @ 0> 0= IF DROP 0 EXIT THEN
    DUP _SBXRC.CONTEXT-GENERATION @ 0> 0= IF DROP 0 EXIT THEN
    DUP _SBXRC.CONTEXT-EPOCH @ 0> 0= IF DROP 0 EXIT THEN
    DUP _SBXRC.MODULE-REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP _SBXRC.PRACTICE-RID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP _SBXRC.MODULE-RID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP _SBXRC-COPIED-ENTRY? 0= IF DROP 0 EXIT THEN
    DUP _SBXRC.RESERVED0 @
    OVER _SBXRC.RESERVED1 @ OR IF DROP 0 EXIT THEN
    DUP _SBXRC.RESULT SBOX-SLOT-RESULT-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SBXRC.INVOCATION-GENERATION @
    OVER _SBXRC.RESULT _SBXR-GENERATION-VALIDATED@ <> IF
        DROP 0 EXIT
