: _SBXA-RECEIPT-BOUNDARY  ( receipt -- status )
    DUP _SBXRC-FIXED? 0= IF
        DROP SBOX-JOB-S-INVALID EXIT
    THEN
    DUP SBOX-RECEIPT-SIZE _SBXA-ZERO? 0= IF
        DROP SBOX-JOB-S-STATE EXIT
    THEN
    DUP SBOX-RECEIPT-SIZE
        _SBXART-RECEIPT 8 MSPAN-OVERLAP? IF
        DROP SBOX-JOB-S-ALIAS EXIT
    THEN
    DUP SBOX-RECEIPT-SIZE
        _SBXART-GENERATION 8 MSPAN-OVERLAP? IF
        DROP SBOX-JOB-S-ALIAS EXIT
    THEN
    DUP SBOX-RECEIPT-SIZE
        _SBXART-ADMISSION 8 MSPAN-OVERLAP? IF
        DROP SBOX-JOB-S-ALIAS EXIT
    THEN
    DROP
    SBOX-JOB-S-OK ;

: _SBXART-RECEIPT-BOUNDARY  ( -- status )
    _SBXART-RECEIPT @ _SBXA-RECEIPT-BOUNDARY ;

: _SBXA-RESULT-SPAN-STATUS
  ( receipt invocation-generation admission -- status )
    2 PICK SBOX-RECEIPT-SIZE
    3 PICK 3 PICK _SBXA.SLOT
    _SBXS-TAKE-SPAN-STATUS
    >R 2DROP DROP R> ;

