: _SBXAI-BINDING-STATUS  ( -- status )
    _SBXAI-RID @ _SBXAI-REVISION @ _SBXAI-OWNER @
    SBOX-MODULE-OWNER-RESOLVE-EXACT
    DUP IF
        >R 2DROP R> _SBXA-OWNER>STATUS EXIT
    THEN
    DROP
    _SBXAI-PROFILE ! _SBXAI-PLAN !

    _SBXAI-PLAN @ SBOX-PLAN-VALID? 0= IF
        SBOX-JOB-S-PROFILE EXIT
    THEN
    _SBXAI-PROFILE @ SBOX-PROFILE-VALID? 0= IF
        SBOX-JOB-S-PROFILE EXIT
    THEN
    _SBXAI-PLAN @ SBOX-PLAN-PROFILE@
    _SBXAI-PROFILE @ <> IF SBOX-JOB-S-PROFILE EXIT THEN
    _SBXAI-PROFILE @ SBOX-PROFILE-TAG@
    DUP IF 2DROP SBOX-JOB-S-PROFILE EXIT THEN
    DROP
    SBOX-PROFILE-PURE-TAG <> IF SBOX-JOB-S-PROFILE EXIT THEN
    _SBXAI-PLAN @ SBOX-PLAN-IMPORT-N@ IF
        SBOX-JOB-S-PROFILE EXIT
    THEN
    _SBXAI-BUDGETS? 0= IF SBOX-JOB-S-BUDGET EXIT THEN

    _SBXAI-ENTRY-A @ _SBXAI-ENTRY-U @ _SBXAI-PLAN @
    SBOX-HOST-ENTRY-RESOLVE-EXACT
    DUP IF 2DROP SBOX-JOB-S-ENTRY EXIT THEN
    DROP
    DUP _SBXAI-ENTRY-INDEX !
    _SBXAI-PLAN @ SBOX-PLAN-ENTRY-SIGNATURE@
    0= IF DROP SBOX-JOB-S-ENTRY EXIT THEN
    SBOX-ABI-SIGNATURE-VALUE-TO-VALUE <> IF
        SBOX-JOB-S-ENTRY EXIT
    THEN
    SBOX-JOB-S-OK ;

