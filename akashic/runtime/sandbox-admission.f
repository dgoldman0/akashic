    OVER _SBXA.ENTRY-U @
    _SBXA-ENTRY-NAME? 0= IF DROP 0 EXIT THEN
    DUP _SBXA.ENTRY
    OVER _SBXA.ENTRY-U @ +
    SWAP _SBXA.ENTRY-U @ 64 SWAP -
    _SBXA-ZERO? ;

: _SBXA-HEADER?  ( admission -- flag )
