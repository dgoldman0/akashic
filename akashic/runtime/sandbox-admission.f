\ slot, admission, slot generation, host, and VM graph.  No callback,
\ yield, substitution, or mutation may intervene before this span check.
: _SBXA-SERVICE-RESULT-SPAN-STATUS
  ( receipt admission -- status )
    _SBXA.SLOT >R
    SBOX-RECEIPT-SIZE R>
    _SBXS-TAKE-SPAN-VALIDATED ;

: _SBXART-BOUNDARY  ( -- status )
