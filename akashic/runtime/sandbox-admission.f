: SBOX-ADMISSION-CLOSE  ( admission -- status )
    DUP _SBXA-HEADER? 0= IF DROP SBOX-JOB-S-INVALID EXIT THEN
    DUP _SBXA.STATE @ SBOX-ADMISSION-STATE-DRAINED = IF
        DROP SBOX-JOB-S-OK EXIT
    THEN
    DUP _SBXA.SLOT SBOX-SLOT-VALID? 0= IF
        DROP SBOX-JOB-S-INVALID EXIT
    THEN
    SBOX-ADMISSION-STATE-CLOSING OVER _SBXA.STATE !
    _SBXA.SLOT SBOX-SLOT-CLOSE ;

: _SBXA-DRAIN-CLEAR  ( admission -- )
    DUP _SBXA.OWNER
    SBOX-ADMISSION-SIZE _SBXA-OWNER -
    0 FILL
    SBOX-ADMISSION-STATE-DRAINED SWAP _SBXA.STATE ! ;

: SBOX-ADMISSION-DRAIN  ( admission -- status )
    DUP _SBXA-HEADER? 0= IF DROP SBOX-JOB-S-INVALID EXIT THEN
    DUP _SBXA.STATE @ SBOX-ADMISSION-STATE-DRAINED = IF
        DROP SBOX-JOB-S-OK EXIT
    THEN
    DUP SBOX-ADMISSION-CLOSE >R
    DUP _SBXA.SLOT SBOX-SLOT-DRAIN
    DUP IF
        R> DROP NIP EXIT
    THEN
    DROP
    _SBXA-DRAIN-CLEAR
    R> ;

: SBOX-ADMISSION-STATE@  ( admission -- state|0 )
    DUP SBOX-ADMISSION-VALID?
    IF _SBXA.STATE @ ELSE DROP 0 THEN ;

: SBOX-ADMISSION-RELEASE  ( admission -- status )
    DUP _SBXA-FIXED? 0= IF DROP SBOX-JOB-S-INVALID EXIT THEN
    DUP SBOX-ADMISSION-SIZE _SBXA-ZERO? IF
        DROP SBOX-JOB-S-OK EXIT
    THEN
    DUP _SBXA-HEADER? 0= IF DROP SBOX-JOB-S-INVALID EXIT THEN
    DUP SBOX-ADMISSION-DRAIN
    OVER _SBXA.STATE @ SBOX-ADMISSION-STATE-DRAINED = IF
        OVER SBOX-ADMISSION-SIZE 0 FILL
    THEN
    NIP ;
