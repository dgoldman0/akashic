: _SBXA-SPAN?  ( address length -- flag )
    2DUP MSPAN-NONWRAPPING? 0= IF 2DROP 0 EXIT THEN
    CALLER-SPAN-STATUS CALLER-SPAN-S-OK = ;

: _SBXA-ZERO?  ( address length -- flag )
    0 ?DO
        DUP I + C@ IF DROP 0 UNLOOP EXIT THEN
    LOOP
    DROP -1 ;

: _SBXA-FIXED?  ( admission -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    SBOX-ADMISSION-SIZE _SBXA-SPAN? ;

: _SBXA-LOWERCASE?  ( byte -- flag )
    DUP [CHAR] a >= SWAP [CHAR] z <= AND ;

: _SBXA-DIGIT?  ( byte -- flag )
    DUP [CHAR] 0 >= SWAP [CHAR] 9 <= AND ;

: _SBXA-ENTRY-REST-CHAR?  ( byte -- flag )
    DUP _SBXA-LOWERCASE? IF DROP -1 EXIT THEN
    DUP _SBXA-DIGIT? IF DROP -1 EXIT THEN
    DUP [CHAR] . = IF DROP -1 EXIT THEN
    DUP [CHAR] _ = IF DROP -1 EXIT THEN
    DUP [CHAR] - = IF DROP -1 EXIT THEN
    DROP 0 ;

: _SBXA-ENTRY-NAME?  ( address length -- flag )
    DUP 1 < OVER 63 > OR IF 2DROP 0 EXIT THEN
    OVER C@ _SBXA-LOWERCASE? 0= IF 2DROP 0 EXIT THEN
    1 ?DO
        DUP I + C@ _SBXA-ENTRY-REST-CHAR? 0= IF
            DROP 0 UNLOOP EXIT
        THEN
    LOOP
    DROP -1 ;

: _SBXA-COPIED-ENTRY?  ( admission -- flag )
