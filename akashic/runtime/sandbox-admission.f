        DROP SBOX-JOB-S-NOT-FOUND EXIT
    THEN
    SBOX-MODULE-OWNER-S-STALE-REVISION = IF
        SBOX-JOB-S-STALE-REVISION
    ELSE
        SBOX-JOB-S-OWNER
    THEN ;

