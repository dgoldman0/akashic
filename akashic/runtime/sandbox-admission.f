    _SBXART-ADMISSION @ _SBXA.ENTRY-U @ R@ _SBXRC.ENTRY-U !
    _SBXART-ADMISSION @ _SBXA.PRACTICE-RID
        R@ _SBXRC.PRACTICE-RID RID-COPY
    _SBXART-ADMISSION @ _SBXA.MODULE-RID
        R@ _SBXRC.MODULE-RID RID-COPY
    _SBXART-ADMISSION @ _SBXA.ENTRY
        R@ _SBXRC.ENTRY
        _SBXART-ADMISSION @ _SBXA.ENTRY-U @ CMOVE
    R> DROP ;

: _SBXART-COMMIT  ( -- status )
    _SBXART-RECEIPT @ _SBXRC.RESULT
    _SBXART-GENERATION @
    _SBXART-ADMISSION @ _SBXA.SLOT
    _SBXS-RESULT-TAKE-PRECHECKED
    DUP IF EXIT THEN
    DROP
    _SBXART-COPY-METADATA
    _SBXRC-MAGIC _SBXART-RECEIPT @ _SBXRC.MAGIC !
    _SBXART-RECEIPT @ SBOX-RECEIPT-VALID? 0= IF
        _SBXART-RECEIPT @ _SBXRC.RESULT
            SBOX-SLOT-RESULT-RELEASE DROP
        _SBXART-RECEIPT @ SBOX-RECEIPT-SIZE 0 FILL
        SBOX-JOB-S-RESULT EXIT
    THEN
    SBOX-JOB-S-OK ;

\ The serialized service has checked receipt shape/zero state, the complete
\ admission graph, and the whole destination span immediately before this
\ private commit.  No callback or yield separates that proof from publication.
: _SBXA-RESULT-TAKE-PRECHECKED
  ( receipt invocation-generation admission -- status )
    _SBXART-ADMISSION !
    _SBXART-GENERATION !
    _SBXART-RECEIPT !
    _SBXART-COMMIT ;

: SBOX-ADMISSION-RESULT-TAKE
