    _RSERVERI-ROUTER @ _RSERVERI-S @ RSERVER.ROUTER !
    _RSERVERI-BUILDER @ _RSERVERI-S @ RSERVER.BUILDER !
    _RSERVERI-BA @ _RSERVERI-S @ RSERVER.BURROW-A !
    _RSERVERI-BCAP @ _RSERVERI-S @ RSERVER.BURROW-CAP !
    _RSERVERI-SU @ _RSERVERI-S @ RSERVER.BURROW-U !
    _RSERVERI-EVIDENCE @ _RSERVERI-S @ RSERVER.PEER-EVIDENCE !
    _RSERVERI-AXT @ _RSERVERI-S @ RSERVER.ADMIT-XT !
    _RSERVERI-ACTX @ _RSERVERI-S @ RSERVER.ADMIT-CONTEXT !
