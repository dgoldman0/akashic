: _RSERVER-OUTPUT-AVAILABLE?  ( kind -- flag )
    DUP RMSG-KIND-ACK = OVER RMSG-KIND-CREDIT = OR IF DROP -1 EXIT THEN
    DUP RMSG-KIND-HELLO = OVER RMSG-KIND-PING = OR IF
        DROP _RSERVERP-C @ RCONN.CONTROL-Q @
            _RSERVER-QUEUE-AVAILABLE? EXIT
    THEN
    DUP RMSG-KIND-REQUEST? OVER RMSG-KIND-UNKNOWN = OR IF
        DROP _RSERVERP-C @ RCONN.HELD-LANE @ 0= IF
            _RSERVERP-C @ RCONN.CONTROL-Q @
        ELSE
            _RSERVERP-C @ RCONN.DATA-Q @
        THEN
        _RSERVER-QUEUE-AVAILABLE? EXIT
    THEN
    DROP _RSERVERP-C @ RCONN.DATA-Q @ _RSERVER-QUEUE-AVAILABLE? ;

: _RSERVER-HELLO-FLUSHED?  ( -- flag )
    _RSERVERP-S @ RSERVER.FLAGS @ _RSERVER-F-HELLO-QUEUED AND 0= IF
        -1 EXIT
    THEN
    _RSERVERP-C @ RABBIT-CONNECTION-TX-COUNTS@
    _RSERVERP-RS ! _RSERVERP-DATA-COUNT ! _RSERVERP-CONTROL-COUNT !
    _RSERVERP-RS @ IF 0 EXIT THEN
    _RSERVERP-CONTROL-COUNT @ IF 0 EXIT THEN
    _RSERVERP-S @ RSERVER.FLAGS DUP @
        _RSERVER-F-HELLO-QUEUED INVERT AND SWAP !
    -1 ;

: _RSERVER-DISPATCH-HELD  ( -- item status )
    _RSERVERP-C @ RCONN.HELD-KIND @
        _RSERVER-OUTPUT-AVAILABLE? 0= IF
        RSERVER-S-PENDING RSERVER-DETAIL-NONE 0 _RSERVERP-S @
            _RSERVER-STATUS! _RSERVER-NO-ITEM EXIT
    THEN
    _RSERVER-RX-LOAN DUP IF
        RSERVER-DETAIL-CONNECTION _RSERVERP-RS @
            _RSERVERP-S @ _RSERVER-STATUS! _RSERVER-NO-ITEM EXIT
    THEN DROP
    _RSERVERP-KIND @ RMSG-KIND-HELLO = IF
        _RSERVER-HANDSHAKE EXIT
    THEN
    _RSERVERP-S @ RSERVER.FLAGS @ _RSERVER-F-PEER-ADMITTED AND 0= IF
        RSERVER-S-PROTOCOL RSERVER-DETAIL-ADMISSION RABBIT-S-STATE
            _RSERVER-ABORT-LOAN EXIT
    THEN
    _RSERVERP-KIND @ RMSG-KIND-PING = IF _RSERVER-PING EXIT THEN
    _RSERVERP-KIND @ DUP RMSG-KIND-ACK =
    SWAP RMSG-KIND-CREDIT = OR IF _RSERVER-CONTROL-COMMIT EXIT THEN
    _RSERVERP-KIND @ RMSG-KIND-REQUEST? IF
        _RSERVER-ROUTE-REQUEST EXIT
    THEN
    _RSERVERP-KIND @ RMSG-KIND-UNKNOWN = IF
        _RSERVER-EXTENSION EXIT
    THEN
    RSERVER-S-PROTOCOL RSERVER-DETAIL-MESSAGE _RSERVERP-KIND @
        _RSERVER-ABORT-LOAN ;

: _RSERVER-DISPATCH-INNER  ( server -- item status )
    DUP _RSERVERP-S !
    DUP RABBIT-SERVER-VALID? 0= IF
        DROP RSERVER-ITEM-NONE RSERVER-S-INVALID EXIT
    THEN
    RSERVER.STATE @ RSERVER-ST-ACTIVE <> IF
        RSERVER-S-STATE RSERVER-DETAIL-NONE 0 _RSERVERP-S @
            _RSERVER-STATUS! _RSERVER-NO-ITEM EXIT
    THEN
    _RSERVERP-S @ RSERVER.CONNECTION @ _RSERVERP-C !
    _RSERVERP-S @ RSERVER.ROUTER @ _RSERVERP-R !
    _RSERVERP-S @ RSERVER.BUILDER @ _RSERVERP-B !
    _RSERVER-HELLO-FLUSHED? 0= IF
        RSERVER-S-PENDING RSERVER-DETAIL-NONE 0 _RSERVERP-S @
            _RSERVER-STATUS! _RSERVER-NO-ITEM EXIT
    THEN
    _RSERVERP-C @ RABBIT-CONNECTION-RX-READY? 0= IF
        RSERVER-S-PENDING RSERVER-DETAIL-NONE 0 _RSERVERP-S @
            _RSERVER-STATUS! _RSERVER-NO-ITEM EXIT
    THEN
    _RSERVER-DISPATCH-HELD ;

: _RSERVER-POLL-CONNECTION-ERROR  ( connection-status -- item status )
    DUP RCONN-S-CANCELLED = IF
        DROP RSERVER-ST-CANCELLED _RSERVERP-S @ RSERVER.STATE !
        RSERVER-S-CANCELLED RSERVER-DETAIL-CONNECTION RCONN-S-CANCELLED
            _RSERVERP-S @ _RSERVER-STATUS! _RSERVER-NO-ITEM EXIT
    THEN
    RCONN-S-EOF = IF
        RSERVER-ST-CLOSED _RSERVERP-S @ RSERVER.STATE !
        RSERVER-S-EOF RSERVER-DETAIL-CONNECTION RCONN-S-EOF
            _RSERVERP-S @ _RSERVER-STATUS! _RSERVER-NO-ITEM EXIT
    THEN
    RSERVER-S-CONNECTION RSERVER-DETAIL-CONNECTION _RSERVERP-RS @
        _RSERVER-FAIL-CONNECTION ;

: _RSERVER-POLL-INNER  ( server -- item status )
    DUP _RSERVERP-S !
    DUP RABBIT-SERVER-VALID? 0= IF
        DROP RSERVER-ITEM-NONE RSERVER-S-INVALID EXIT
    THEN
    RSERVER.STATE @ RSERVER-ST-ACTIVE <> IF
        RSERVER-S-STATE RSERVER-DETAIL-NONE 0 _RSERVERP-S @
            _RSERVER-STATUS! _RSERVER-NO-ITEM EXIT
    THEN
    _RSERVERP-S @ RSERVER.CONNECTION @ _RSERVERP-C !
    _RSERVERP-S @ RSERVER.ROUTER @ _RSERVERP-R !
    _RSERVERP-S @ RSERVER.BUILDER @ _RSERVERP-B !
    _RSERVERP-C @ RABBIT-CONNECTION-PUMP DUP _RSERVERP-RS !
    DUP RCONN-S-OK = OVER RCONN-S-PENDING = OR
    OVER RCONN-S-RX-READY = OR 0= IF
        DROP _RSERVERP-RS @ _RSERVER-POLL-CONNECTION-ERROR EXIT
    THEN DROP
    _RSERVER-HELLO-FLUSHED? 0= IF
        RSERVER-S-PENDING RSERVER-DETAIL-NONE 0 _RSERVERP-S @
            _RSERVER-STATUS! _RSERVER-NO-ITEM EXIT
    THEN
    _RSERVERP-C @ RABBIT-CONNECTION-RX-READY? IF
        _RSERVER-DISPATCH-HELD EXIT
    THEN
    RSERVER-S-PENDING RSERVER-DETAIL-NONE 0 _RSERVERP-S @
        _RSERVER-STATUS! _RSERVER-NO-ITEM ;

: RABBIT-SERVER-DISPATCH  ( server -- item status )
    _RSERVERP-BUSY @ IF
        DROP RSERVER-ITEM-NONE RSERVER-S-STATE EXIT
    THEN
    -1 _RSERVERP-BUSY !
    _RSERVER-DISPATCH-INNER
    0 _RSERVERP-BUSY ! ;

: RABBIT-SERVER-POLL  ( server -- item status )
    _RSERVERP-BUSY @ IF
        DROP RSERVER-ITEM-NONE RSERVER-S-STATE EXIT
    THEN
    -1 _RSERVERP-BUSY !
    _RSERVER-POLL-INNER
    0 _RSERVERP-BUSY ! ;

