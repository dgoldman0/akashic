: RABBIT-SERVER-OPEN  ( server -- status )
    _RSERVERP-BUSY @ IF DROP RSERVER-S-STATE EXIT THEN
    DUP RABBIT-SERVER-VALID? 0= IF DROP RSERVER-S-INVALID EXIT THEN
    DUP _RSERVERS-S ! RSERVER.STATE @ DUP RSERVER-ST-ACTIVE = IF
        DROP RSERVER-S-OK RSERVER-DETAIL-NONE 0 _RSERVERS-S @
            _RSERVER-STATUS! EXIT
    THEN
    RSERVER-ST-READY <> IF
        RSERVER-S-STATE RSERVER-DETAIL-NONE 0 _RSERVERS-S @
            _RSERVER-STATUS! EXIT
    THEN
    _RSERVERS-S @ RSERVER.CONNECTION @ RABBIT-CONNECTION-OPEN
    DUP RCONN-S-OK = IF
        DROP RSERVER-ST-ACTIVE _RSERVERS-S @ RSERVER.STATE !
        RSERVER-S-OK RSERVER-DETAIL-NONE 0 _RSERVERS-S @
            _RSERVER-STATUS! EXIT
    THEN
    DUP RCONN-S-PENDING = IF
        DROP RSERVER-S-PENDING RSERVER-DETAIL-NONE 0 _RSERVERS-S @
            _RSERVER-STATUS! EXIT
    THEN
    DUP RCONN-S-CANCELLED = IF
        RSERVER-ST-CANCELLED _RSERVERS-S @ RSERVER.STATE !
        RSERVER-S-CANCELLED RSERVER-DETAIL-CONNECTION ROT _RSERVERS-S @
            _RSERVER-STATUS! EXIT
    THEN
    RSERVER-ST-FAILED _RSERVERS-S @ RSERVER.STATE !
    RSERVER-S-CONNECTION RSERVER-DETAIL-CONNECTION ROT _RSERVERS-S @
        _RSERVER-STATUS! ;

VARIABLE _RSERVERL-RS

: _RSERVER-BUILDER-RESET  ( server -- builder-status )
    RSERVER.BUILDER @ DUP RMSGB-VALID? 0= IF
        DROP RMSGB-S-INVALID EXIT
    THEN
    RMSGB-RESET ;

: RABBIT-SERVER-CLOSE  ( server -- status )
    _RSERVERP-BUSY @ IF DROP RSERVER-S-STATE EXIT THEN
    DUP RABBIT-SERVER-VALID? 0= IF DROP RSERVER-S-INVALID EXIT THEN
    DUP _RSERVERS-S ! RSERVER.STATE @ DUP RSERVER-ST-CLOSED = IF
        DROP RSERVER-S-OK RSERVER-DETAIL-NONE 0 _RSERVERS-S @
            _RSERVER-STATUS! EXIT
    THEN
    RSERVER-ST-CANCELLED = IF
        RSERVER-S-CANCELLED RSERVER-DETAIL-NONE 0 _RSERVERS-S @
            _RSERVER-STATUS! EXIT
    THEN
    _RSERVERS-S @ _RSERVER-BUILDER-RESET DROP
    _RSERVERS-S @ RSERVER.CONNECTION @ RABBIT-CONNECTION-CLOSE
        DUP _RSERVERL-RS !
    DUP RCONN-S-OK = IF
        DROP RSERVER-ST-CLOSED _RSERVERS-S @ RSERVER.STATE !
        RSERVER-S-OK RSERVER-DETAIL-NONE 0 _RSERVERS-S @
            _RSERVER-STATUS! EXIT
    THEN
    DUP RCONN-S-PENDING = IF
        DROP RSERVER-ST-CLOSING _RSERVERS-S @ RSERVER.STATE !
        RSERVER-S-PENDING RSERVER-DETAIL-NONE 0 _RSERVERS-S @
            _RSERVER-STATUS! EXIT
    THEN
    RCONN-S-CANCELLED = IF
        RSERVER-ST-CANCELLED _RSERVERS-S @ RSERVER.STATE !
        RSERVER-S-CANCELLED RSERVER-DETAIL-CONNECTION _RSERVERL-RS @
            _RSERVERS-S @ _RSERVER-STATUS! EXIT
    THEN
    RSERVER-ST-FAILED _RSERVERS-S @ RSERVER.STATE !
    RSERVER-S-CONNECTION RSERVER-DETAIL-CONNECTION _RSERVERL-RS @
        _RSERVERS-S @ _RSERVER-STATUS! ;

: RABBIT-SERVER-CLOSE-POLL  ( server -- status )
    RABBIT-SERVER-CLOSE ;

: RABBIT-SERVER-CANCEL  ( server -- status )
    _RSERVERP-BUSY @ IF DROP RSERVER-S-STATE EXIT THEN
    DUP RABBIT-SERVER-VALID? 0= IF DROP RSERVER-S-INVALID EXIT THEN
    DUP _RSERVERS-S ! RSERVER.STATE @ RSERVER-ST-CANCELLED = IF
        RSERVER-S-CANCELLED EXIT
    THEN
    _RSERVERS-S @ _RSERVER-BUILDER-RESET DROP
    _RSERVERS-S @ RSERVER.CONNECTION @ RABBIT-CONNECTION-CANCEL
        DUP _RSERVERL-RS !
    DUP RCONN-S-CANCELLED = SWAP RCONN-S-OK = OR IF
        RSERVER-ST-CANCELLED _RSERVERS-S @ RSERVER.STATE !
        RSERVER-S-CANCELLED RSERVER-DETAIL-NONE 0 _RSERVERS-S @
            _RSERVER-STATUS! EXIT
    THEN
    RSERVER-ST-FAILED _RSERVERS-S @ RSERVER.STATE !
    RSERVER-S-CONNECTION RSERVER-DETAIL-CONNECTION _RSERVERL-RS @
        _RSERVERS-S @ _RSERVER-STATUS! ;

