\ Inputs are connection, sealed router, empty reply builder, Burrow source and
\ destination spans, peer evidence, admission XT/context, and the server.
: RABBIT-SERVER-INIT  ( eleven caller inputs -- status )
    _RSERVERI-S ! _RSERVERI-ACTX ! _RSERVERI-AXT !
    _RSERVERI-EVIDENCE ! _RSERVERI-BCAP ! _RSERVERI-BA !
    _RSERVERI-SU ! _RSERVERI-SA ! _RSERVERI-BUILDER !
    _RSERVERI-ROUTER ! _RSERVERI-CONN !
    _RSERVERI-S @ 0= IF RSERVER-S-INVALID EXIT THEN
    _RSERVERI-S @ _RSERVER-CELL-ALIGNED? 0= IF
        RSERVER-S-INVALID EXIT
    THEN
    _RSERVERI-S @ RABBIT-SERVER-SIZE MSPAN-NONWRAPPING? 0= IF
        RSERVER-S-INVALID EXIT
    THEN
    _RSERVERI-S @ RSERVER.MAGIC @ _RSERVER-MAGIC-VALUE = IF
        RSERVER-S-STATE EXIT
    THEN
    _RSERVERI-CONN @ RABBIT-CONNECTION-VALID? 0= IF
        RSERVER-S-CONNECTION EXIT
    THEN
    _RSERVERI-CONN @ RCONN.STATE @ DUP RCONN-ST-READY =
    SWAP RCONN-ST-OPEN = OR 0= IF
        RSERVER-S-STATE EXIT
    THEN
    _RSERVERI-CONN @ RCONN.SESSION @ DUP RABBIT-SESSION-VALID? 0= IF
        DROP RSERVER-S-CONNECTION EXIT
    THEN
    DUP RSESS.ROLE @ RABBIT-ROLE-SERVER <> IF
        DROP RSERVER-S-CONNECTION EXIT
    THEN
    RABBIT-SESSION-STATE@
    _RSERVERI-CONN @ RCONN.STATE @ RCONN-ST-READY = IF
        RABBIT-ST-READY
    ELSE
        RABBIT-ST-HELLO
    THEN <> IF
        RSERVER-S-STATE EXIT
    THEN
    _RSERVERI-CONN @ RCONN.CONTROL-Q @ RTXQ.CAP @ 0= IF
        RSERVER-S-CAPACITY EXIT
    THEN
    _RSERVERI-CONN @ RCONN.DATA-Q @ RTXQ.CAP @ 0= IF
        RSERVER-S-CAPACITY EXIT
    THEN
    _RSERVERI-CONN @ RABBIT-CONNECTION-TX-COUNTS@
    IF 2DROP RSERVER-S-CONNECTION EXIT THEN
    OR IF RSERVER-S-STATE EXIT THEN
    _RSERVERI-CONN @ RABBIT-CONNECTION-RX-READY? IF
        RSERVER-S-STATE EXIT
    THEN
    _RSERVERI-ROUTER @ RROUTER-SEALED? 0= IF
        RSERVER-S-ROUTER EXIT
    THEN
    _RSERVERI-BUILDER @ RMSGB-VALID? 0= IF
        RSERVER-S-BUILDER EXIT
    THEN
    _RSERVERI-BUILDER @ RMSGB-STATE@ RMSGB-STATE-EMPTY <> IF
        RSERVER-S-BUILDER EXIT
    THEN
    _RSERVERI-SU @ 0> 0= IF RSERVER-S-INVALID EXIT THEN
    _RSERVERI-SA @ _RSERVERI-SU @ _RSERVER-SPAN? 0= IF
        RSERVER-S-INVALID EXIT
    THEN
    _RSERVERI-SA @ _RSERVERI-SU @ UTF8-VALID? 0= IF
        RSERVER-S-MESSAGE EXIT
    THEN
    _RSERVERI-BA @ _RSERVERI-BCAP @ _RSERVER-SPAN? 0= IF
        RSERVER-S-INVALID EXIT
    THEN
    _RSERVERI-SU @ _RSERVERI-BCAP @ U> IF
        RSERVER-S-CAPACITY EXIT
    THEN
    _RSERVERI-AXT @ 0= IF RSERVER-S-INVALID EXIT THEN
    _RSERVER-INIT-GEOMETRY? 0= IF RSERVER-S-ALIAS EXIT THEN

    _RSERVERI-S @ RABBIT-SERVER-SIZE 0 FILL
    _RSERVERI-BA @ _RSERVERI-BCAP @ 0 FILL
