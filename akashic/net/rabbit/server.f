    _RSERVER-MAGIC-VALUE _RSERVERI-S @ RSERVER.MAGIC !
    _RSERVER-ABI-VERSION _RSERVERI-S @ RSERVER.ABI !
    RABBIT-SERVER-SIZE _RSERVERI-S @ RSERVER.BYTES !
