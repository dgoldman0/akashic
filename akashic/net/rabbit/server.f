VARIABLE _RSERVERF-S
VARIABLE _RSERVERF-BA
VARIABLE _RSERVERF-BCAP
VARIABLE _RSERVERF-B

: _RSERVER-CLEAR-SCRATCH  ( -- )
    0 _RSERVERG-A ! 0 _RSERVERG-U ! 0 _RSERVERG-R !
    0 _RSERVERG-B ! 0 _RSERVERG-C !
    0 _RSERVERV-S !
    0 _RSERVERI-CONN ! 0 _RSERVERI-ROUTER ! 0 _RSERVERI-BUILDER !
    0 _RSERVERI-SA ! 0 _RSERVERI-SU ! 0 _RSERVERI-BA !
    0 _RSERVERI-BCAP ! 0 _RSERVERI-EVIDENCE ! 0 _RSERVERI-AXT !
    0 _RSERVERI-ACTX ! 0 _RSERVERI-S ! 0 _RSERVERS-S !
    0 _RSERVERL-RS !
    0 _RSERVERP-BUSY !
    0 _RSERVERP-S ! 0 _RSERVERP-C ! 0 _RSERVERP-R ! 0 _RSERVERP-B !
    _RSERVER-CLEAR-LOAN-SCRATCH
    0 _RSERVERP-KIND ! 0 _RSERVERP-LANE ! 0 _RSERVERP-SEQ !
    0 _RSERVERP-EXPECTED ! 0 _RSERVERP-DISPOSITION ! 0 _RSERVERP-RS !
    0 _RSERVERP-MSGS ! 0 _RSERVERP-PRESENT ! 0 _RSERVERP-CAPS !
    0 _RSERVERP-HANDLER-XT ! 0 _RSERVERP-HANDLER-CONTEXT !
    0 _RSERVERP-OUTCOME ! 0 _RSERVERP-THROW !
    0 _RSERVERP-ADMIT-DECISION ! 0 _RSERVERP-PEER-TOKEN !
    0 _RSERVERP-CODE ! 0 _RSERVERP-SEMANTIC-STATUS !
    0 _RSERVERP-CONTROL-COUNT ! 0 _RSERVERP-DATA-COUNT !
    0 _RSERVERVC-F ! 0 _RSERVERVC-A ! 0 _RSERVERVC-U ! ;

: RABBIT-SERVER-FINI  ( server -- status )
    _RSERVERP-BUSY @ IF DROP RSERVER-S-STATE EXIT THEN
    DUP RABBIT-SERVER-VALID? 0= IF DROP RSERVER-S-INVALID EXIT THEN
    DUP _RSERVERF-S !
    DUP RSERVER.BURROW-A @ _RSERVERF-BA !
    DUP RSERVER.BURROW-CAP @ _RSERVERF-BCAP !
    DUP RSERVER.BUILDER @ _RSERVERF-B !
    RSERVER.CONNECTION @ RABBIT-CONNECTION-FINI DUP _RSERVERL-RS !
    DUP RCONN-S-PENDING = IF
        DROP RSERVER-ST-CLOSING _RSERVERF-S @ RSERVER.STATE !
        RSERVER-S-PENDING RSERVER-DETAIL-NONE 0 _RSERVERF-S @
            _RSERVER-STATUS! EXIT
    THEN
    IF
        RSERVER-ST-FAILED _RSERVERF-S @ RSERVER.STATE !
        RSERVER-S-CONNECTION RSERVER-DETAIL-CONNECTION _RSERVERL-RS @
            _RSERVERF-S @ _RSERVER-STATUS! EXIT
    THEN
    _RSERVERF-B @ RMSGB-FINI DUP IF
        RSERVER-ST-FAILED _RSERVERF-S @ RSERVER.STATE !
        RSERVER-S-BUILDER RSERVER-DETAIL-BUILDER ROT _RSERVERF-S @
            _RSERVER-STATUS! EXIT
    THEN DROP
    _RSERVERF-BA @ _RSERVERF-BCAP @ 0 FILL
    _RSERVERF-S @ RABBIT-SERVER-SIZE 0 FILL
    _RSERVER-CLEAR-SCRATCH
    0 _RSERVERF-S ! 0 _RSERVERF-BA ! 0 _RSERVERF-BCAP ! 0 _RSERVERF-B !
    RSERVER-S-OK ;
