\ =====================================================================
\  server.f - Caller-owned generic Rabbit server peer
\ =====================================================================
\  One server owner exclusively operates one server-role Rabbit connection,
\  one EMPTY reply builder, and one copied Burrow identifier.  It borrows one
\  immutable sealed router plus peer-admission evidence and callbacks.  It is
\  deliberately a per-peer protocol owner: listeners, peer pools, scheduling,
\  application state, journals, and product policy remain with its caller.
\
\  The admission callback is synchronous:
\
\    ( hello-frame peer-evidence context -- peer-token decision )
\
\  decision is RSERVER-ADMIT-ALLOW or RSERVER-ADMIT-DENY.  The HELLO frame
\  expires when the callback returns; peer-token is an opaque stable cell
\  retained until finalization.  This checkpoint implements only anonymous
\  fixture negotiation.  DENY or callback failure cancels the peer because
\  the lower minimal handshake cannot honestly transmit a refusal before it
\  establishes the session.
\
\  Exact router handlers are synchronous:
\
\    ( request-frame request-kind peer-token empty-reply-builder context
\      -- outcome )
\
\  RESPONSE means the handler sealed one correlated response.  DENY and
\  FAILED ask the server to synthesize 403 and 500 responses.  A thrown or
\  invalid callback and a malformed/wrong-correlation RESPONSE also become a
\  bounded 500 response when the preflighted builder remains recoverable.
\  Exact route misses become 404; correlated extension verbs become 501.
\
\  The request loan remains live until the encoded response is copied into a
\  connection queue slot.  Only then is the request committed.  The poller
\  pumps TX before dispatch and will not loan a request while its response
\  queue is full, so application code is never repeated merely because a peer
\  is backpressured.  Server-side EVENT/subscription delivery is intentionally
\  a later owner layered on this response boundary.
\
\  All persistent bytes are caller-owned.  Private VARIABLEs are synchronous
\  scratch and callbacks make this module globally non-reentrant; nested
\  POLL/DISPATCH is refused before the outer borrowed frame can be overwritten.
\  Callbacks must not retain slices or the builder, pump either connection,
\  mutate the router, or otherwise bypass the server's exclusive ownership.
\ =====================================================================

