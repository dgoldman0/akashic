: _RSERVER-HANDLER-500  ( -- item status )
    500 _RSERVERP-CODE !
    500 S" HANDLER FAILED" _RSERVER-SYNTHESIZE DUP IF
        RSERVER-DETAIL-BUILDER RMSGB-S-STATE _RSERVER-ABORT-LOAN EXIT
    THEN DROP
    RSERVER-S-CALLBACK _RSERVER-PUBLISH-RESPONSE ;

: _RSERVER-CALL-HANDLER  ( -- item status )
    RSERVER-HANDLER-NONE _RSERVERP-OUTCOME !
    0 _RSERVERP-THROW !
    ['] _RSERVER-HANDLER-INNER CATCH DUP _RSERVERP-THROW ! IF
        _RSERVERP-THROW @ _RSERVERP-S @ RSERVER.CALLBACK-THROW !
        RSERVER-HANDLER-FAILED
            _RSERVERP-S @ RSERVER.LAST-HANDLER-OUTCOME !
        _RSERVER-HANDLER-500 EXIT
    THEN
    _RSERVERP-OUTCOME @ _RSERVERP-S @ RSERVER.LAST-HANDLER-OUTCOME !
    _RSERVERP-OUTCOME @ RSERVER-HANDLER-VALID? 0= IF
        _RSERVERP-OUTCOME @ _RSERVERP-S @ RSERVER.CALLBACK-THROW !
        RSERVER-HANDLER-FAILED
            _RSERVERP-S @ RSERVER.LAST-HANDLER-OUTCOME !
        _RSERVER-HANDLER-500 EXIT
    THEN
    _RSERVERP-OUTCOME @ RSERVER-HANDLER-RESPONSE = IF
        _RSERVER-RESPONSE-CORRELATED? 0= IF
            _RSERVER-HANDLER-500 EXIT
        THEN
        RSERVER-S-OK _RSERVER-PUBLISH-RESPONSE EXIT
    THEN
    _RSERVERP-OUTCOME @ RSERVER-HANDLER-DENY = IF
        403 _RSERVERP-CODE !
        403 S" FORBIDDEN" _RSERVER-SYNTHESIZE DUP IF
            RSERVER-DETAIL-BUILDER RMSGB-S-STATE
                _RSERVER-ABORT-LOAN EXIT
        THEN DROP
        RSERVER-S-DENIED _RSERVER-PUBLISH-RESPONSE EXIT
    THEN
    _RSERVER-HANDLER-500 ;

: _RSERVER-ROUTE-REQUEST  ( -- item status )
    _RSERVER-REQUEST-FIELDS DUP IF
        RSERVER-S-MESSAGE RSERVER-DETAIL-MESSAGE ROT
            _RSERVER-ABORT-LOAN EXIT
    THEN DROP
    _RSERVER-PREFLIGHT-FAILURE DUP IF
        RSERVER-DETAIL-BUILDER RMSGB-S-CAPACITY
            _RSERVER-ABORT-LOAN EXIT
    THEN DROP
    _RSERVERP-VERB-A @ _RSERVERP-VERB-U @
    _RSERVERP-TARGET-A @ _RSERVERP-TARGET-U @ _RSERVERP-R @
        RROUTER-MATCH
    _RSERVERP-RS ! _RSERVERP-HANDLER-CONTEXT !
    _RSERVERP-HANDLER-XT !
    _RSERVERP-RS @ RROUTER-S-OK = IF
        _RSERVER-CALL-HANDLER EXIT
    THEN
    _RSERVERP-RS @ RROUTER-S-NOT-FOUND = IF
        404 _RSERVERP-CODE !
        404 S" NOT FOUND" _RSERVER-SYNTHESIZE DUP IF
            RSERVER-DETAIL-BUILDER RMSGB-S-STATE
                _RSERVER-ABORT-LOAN EXIT
        THEN DROP
        RSERVER-S-NOT-FOUND _RSERVER-PUBLISH-RESPONSE EXIT
    THEN
    _RSERVERP-RS @ DUP RROUTER-S-GRAMMAR =
    SWAP RROUTER-S-UTF8 = OR IF
        400 _RSERVERP-CODE !
        400 S" BAD REQUEST" _RSERVER-SYNTHESIZE DUP IF
            RSERVER-DETAIL-BUILDER RMSGB-S-STATE
                _RSERVER-ABORT-LOAN EXIT
        THEN DROP
        RSERVER-S-MESSAGE _RSERVER-PUBLISH-RESPONSE EXIT
    THEN
    RSERVER-S-ROUTER RSERVER-DETAIL-ROUTER _RSERVERP-RS @
        _RSERVER-ABORT-LOAN ;

: _RSERVER-EXTENSION  ( -- item status )
    _RSERVER-REQUEST-FIELDS DUP IF
        RSERVER-S-PROTOCOL RSERVER-DETAIL-MESSAGE ROT
            _RSERVER-ABORT-LOAN EXIT
    THEN DROP
    _RSERVERP-TARGET-U @ 0= IF
        RSERVER-S-PROTOCOL RSERVER-DETAIL-MESSAGE RMSG-S-REQUIRED
            _RSERVER-ABORT-LOAN EXIT
    THEN
    501 _RSERVERP-CODE !
    501 S" UNSUPPORTED" _RSERVER-SYNTHESIZE DUP IF
        RSERVER-DETAIL-BUILDER RMSGB-S-CAPACITY
            _RSERVER-ABORT-LOAN EXIT
    THEN DROP
    RSERVER-S-UNSUPPORTED _RSERVER-PUBLISH-RESPONSE ;

