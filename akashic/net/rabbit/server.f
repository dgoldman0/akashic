: _RSERVER-BUILD-HELLO  ( caps -- server-status )
    _RSERVER-RESET-BUILDER DUP IF NIP EXIT THEN DROP
    _RSERVERP-S @ RSERVER.BURROW-A @
    _RSERVERP-S @ RSERVER.BURROW-U @ _RSERVERP-B @
        RMSGB-BEGIN-HELLO-OK
    RMSGB-S-OK <> IF RSERVER-S-BUILDER EXIT THEN
    _RSERVERP-B @ RMSGB-SEAL
    RMSGB-S-OK <> IF RSERVER-S-BUILDER EXIT THEN
    _RSERVERP-B @ RMSGB-READY-FRAME@ DUP 0= IF
        DROP RSERVER-S-BUILDER EXIT
    THEN
    RMSG-HELLO-OK-STATUS
    RMSG-S-OK = IF RSERVER-S-OK ELSE RSERVER-S-BUILDER THEN ;

: _RSERVER-HANDSHAKE  ( -- item status )
    _RSERVERP-F @ RMSG-CAPS@
    _RSERVERP-MSGS ! _RSERVERP-PRESENT ! _RSERVERP-CAPS !
    _RSERVERP-MSGS @ IF
        RSERVER-S-MESSAGE RSERVER-DETAIL-MESSAGE _RSERVERP-MSGS @
            _RSERVER-ABORT-LOAN EXIT
    THEN
    _RSERVERP-PRESENT @ 0= IF 0 _RSERVERP-CAPS ! THEN
    _RSERVERP-CAPS @ _RSERVERP-C @ RCONN.SESSION @
        RSESS.LOCAL-CAPS @ AND _RSERVERP-CAPS !
    _RSERVERP-CAPS @ _RSERVER-BUILD-HELLO DUP IF
        RSERVER-DETAIL-BUILDER RMSGB-S-CAPACITY
            _RSERVER-ABORT-LOAN EXIT
    THEN DROP
    _RSERVER-RESET-BUILDER ?DUP IF
        RSERVER-DETAIL-BUILDER RMSGB-S-STATE _RSERVER-ABORT-LOAN EXIT
    THEN
    0 _RSERVERP-THROW !
    RSERVER-ADMIT-DENY _RSERVERP-ADMIT-DECISION !
    ['] _RSERVER-ADMIT-INNER CATCH DUP _RSERVERP-THROW ! IF
        _RSERVERP-THROW @ _RSERVERP-S @ RSERVER.CALLBACK-THROW !
        RSERVER-S-CALLBACK RSERVER-DETAIL-ADMISSION _RSERVERP-THROW @
            _RSERVER-REJECT-HELLO EXIT
    THEN
    _RSERVERP-ADMIT-DECISION @ RSERVER-ADMIT-VALID? 0= IF
        _RSERVERP-ADMIT-DECISION @
            _RSERVERP-S @ RSERVER.CALLBACK-THROW !
        RSERVER-S-CALLBACK RSERVER-DETAIL-ADMISSION
            _RSERVERP-ADMIT-DECISION @ _RSERVER-REJECT-HELLO EXIT
    THEN
    _RSERVERP-ADMIT-DECISION @ RSERVER-ADMIT-DENY = IF
        RSERVER-S-DENIED RSERVER-DETAIL-ADMISSION 0
            _RSERVER-REJECT-HELLO EXIT
    THEN
    _RSERVERP-CAPS @ _RSERVER-BUILD-HELLO DUP IF
        RSERVER-DETAIL-BUILDER RMSGB-S-CAPACITY
            _RSERVER-ABORT-LOAN EXIT
    THEN DROP
    _RSERVER-COMMIT-LOAN DUP IF
        RSERVER-S-CONNECTION RSERVER-DETAIL-CONNECTION ROT
            _RSERVER-FAIL-CONNECTION EXIT
    THEN DROP
    _RSERVERP-C @ RCONN.SESSION @ RABBIT-SESSION-AGREED-CAPS@
        _RSERVERP-CAPS @ <> IF
        RSERVER-S-PROTOCOL RSERVER-DETAIL-CONNECTION RABBIT-S-CAPABILITY
            _RSERVER-FAIL-CONNECTION EXIT
    THEN
    _RSERVERP-B @ _RSERVERP-C @ RABBIT-CONNECTION-ENQUEUE
    _RSERVERP-RS ! DROP
    _RSERVERP-RS @ IF
        RSERVER-S-CONNECTION RSERVER-DETAIL-CONNECTION _RSERVERP-RS @
            _RSERVER-FAIL-CONNECTION EXIT
    THEN
    _RSERVER-RESET-BUILDER DUP IF
        RSERVER-DETAIL-BUILDER RMSGB-S-STATE
            _RSERVER-FAIL-CONNECTION EXIT
    THEN DROP
    _RSERVERP-PEER-TOKEN @ _RSERVERP-S @ RSERVER.PEER-TOKEN !
    _RSERVERP-S @ RSERVER.FLAGS DUP @
        _RSERVER-F-PEER-ADMITTED _RSERVER-F-HELLO-QUEUED OR OR SWAP !
    RSERVER-S-OK RSERVER-DETAIL-NONE 0 _RSERVERP-S @ _RSERVER-STATUS!
    RSERVER-ITEM-HANDSHAKE SWAP ;

: _RSERVER-PING  ( -- item status )
    _RSERVER-RESET-BUILDER ?DUP IF
        RSERVER-DETAIL-BUILDER RMSGB-S-STATE _RSERVER-ABORT-LOAN EXIT
    THEN
    _RSERVERP-B @ RMSGB-BEGIN-PONG RMSGB-S-OK <> IF
        RSERVER-S-BUILDER RSERVER-DETAIL-BUILDER RMSGB-S-CAPACITY
            _RSERVER-ABORT-LOAN EXIT
    THEN
    _RSERVERP-B @ RMSGB-SEAL RMSGB-S-OK <> IF
        RSERVER-S-BUILDER RSERVER-DETAIL-BUILDER RMSGB-S-FRAME
            _RSERVER-ABORT-LOAN EXIT
    THEN
    _RSERVERP-B @ RMSGB-READY-FRAME@ DUP 0= IF
        DROP RSERVER-S-BUILDER RSERVER-DETAIL-BUILDER RMSGB-S-STATE
            _RSERVER-ABORT-LOAN EXIT
    THEN
    RMSG-PONG-STATUS DUP _RSERVERP-MSGS ! RMSG-S-OK <> IF
        RSERVER-S-BUILDER RSERVER-DETAIL-MESSAGE _RSERVERP-MSGS @
            _RSERVER-ABORT-LOAN EXIT
    THEN
    _RSERVERP-B @ _RSERVERP-C @ RABBIT-CONNECTION-ENQUEUE
    _RSERVERP-RS ! DROP
    _RSERVERP-RS @ IF
        RSERVER-S-CONNECTION RSERVER-DETAIL-CONNECTION _RSERVERP-RS @
            _RSERVER-ABORT-LOAN EXIT
    THEN
    _RSERVER-RESET-BUILDER DUP IF
        RSERVER-DETAIL-BUILDER RMSGB-S-STATE _RSERVER-ABORT-LOAN EXIT
    THEN DROP
    _RSERVER-COMMIT-LOAN DUP IF
        RSERVER-S-CONNECTION RSERVER-DETAIL-CONNECTION ROT
            _RSERVER-FAIL-CONNECTION EXIT
    THEN DROP
    RSERVER-S-OK RSERVER-DETAIL-NONE 0 _RSERVERP-S @ _RSERVER-STATUS!
    RSERVER-ITEM-CONTROL SWAP ;

