: _RSERVER-HANDLER-INNER  ( -- )
    _RSERVERP-F @ _RSERVERP-KIND @
    _RSERVERP-S @ RSERVER.PEER-TOKEN @ _RSERVERP-B @
    _RSERVERP-HANDLER-CONTEXT @ _RSERVERP-HANDLER-XT @ EXECUTE
