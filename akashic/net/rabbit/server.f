    _RSERVER-COMMIT-LOAN DUP IF
        RSERVER-S-CONNECTION RSERVER-DETAIL-CONNECTION ROT
            _RSERVER-FAIL-CONNECTION EXIT
    THEN DROP
    RSERVER-S-OK RSERVER-DETAIL-NONE 0 _RSERVERP-S @ _RSERVER-STATUS!
    RSERVER-ITEM-CONTROL SWAP ;

