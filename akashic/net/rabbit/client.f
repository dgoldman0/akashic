        _RCLI-V-OP @ RCOP.STATUS @ RCLIENT-S-OK <> IF 0 EXIT THEN
        _RCLI-V-OP @ RCOP.RESPONSE-CODE @ DUP 100 >=
        SWAP 599 <= AND 0= IF 0 EXIT THEN
        _RCLI-V-OP @ RCOP.RESULT-U @
        _RCLI-V-OP @ RCOP.RESULT-REQUIRED @ = EXIT
    THEN
    _RCLI-V-OP @ RCOP.STATE @ RCLIENT-OP-CANCELLED = IF
        _RCLI-V-OP @ RCOP.STATUS @ RCLIENT-S-CANCELLED <> IF 0 EXIT THEN
        _RCLI-V-OP @ RCOP.RESPONSE-CODE @ 0=
        _RCLI-V-OP @ RCOP.RESULT-U @ 0= AND
        _RCLI-V-OP @ RCOP.RESULT-REQUIRED @ 0= AND EXIT
