    DROP
    _RCLI-V-OP @ RCOP.LANE @ DUP 0< IF DROP 0 EXIT THEN
    RABBIT-LANE-MAX U> IF 0 EXIT THEN
    _RCLI-V-OP @ RCOP.KIND @ RMSG-KIND-REQUEST? 0= IF 0 EXIT THEN
