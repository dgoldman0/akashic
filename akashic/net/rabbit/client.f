: RABBIT-CLIENT-CANCEL  ( client -- status )
    DUP RABBIT-CLIENT-VALID? 0= IF DROP RCLIENT-S-INVALID EXIT THEN
    DUP _RCLIENTS-C ! RCLIENT.STATE @ RCLIENT-ST-CANCELLED = IF
        RCLIENT-S-CANCELLED RCLIENT-DETAIL-NONE 0 _RCLIENTS-C @
            _RCLIENT-STATUS! EXIT
