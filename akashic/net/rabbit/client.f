\ =====================================================================
\  client.f - Caller-owned correlated Rabbit client operations
\ =====================================================================
\  The client owns a caller-sized operation registry above one Rabbit
\  connection.  Each registry row has a dedicated caller-selected Txn byte
\  slot and result byte slot, while one separate caller span owns the HELLO
\  Burrow-ID.  REQUEST copies the builder's exact Txn before
\  lending that stable copy to the session transaction table; neither the
\  builder nor an inbound parser view is retained.
\
\  Request publication is transactional.  The client validates and copies
\  all fallible operation state, begins the exact session (Lane, Txn), and
\  then asks the connection to copy the encoded request into its own queue.
\  A refused connection publication rolls the session transaction back and
\  wipes the unpublished client candidate.  Success finishes with infallible
\  record stores only.
\
\  A locally abandoned operation remains a correlation tombstone until its
\  response arrives or the whole connection is cancelled.  This prevents a
\  late response from satisfying a reused Txn.  Completed response bytes are
\  copied from the response body into the operation's result slot before the
\  connection's held RX view is released.  REQUEST returns an operation plus
\  generation; generation-bearing CANCEL/RELEASE prevents stale-pointer ABA.
\
\  POLL and DISPATCH take an opaque callback with stack effect
\
\    ( frame kind lane seq expected disposition context -- decision )
\
\  where decision is RCLIENT-DISPATCH-COMMIT or RCLIENT-DISPATCH-DROP.
\  EVENT, extension, and optionally correlated-response views exist only
\  during that synchronous callback, which must copy anything it retains.
\  A callback may not recursively POLL/DISPATCH; nested entry is refused before
\  it can overwrite the outer loan.  Borrowed frame and slice scratch is cleared
\  before return; no connection parser pointer is retained.  ACK/CREDIT and strict typed
\  HELLO/PONG responses are committed internally.
\
\  After establishment, APP-LANE-ENSURE opens one exact nonzero application
\  Lane through the owning client.  An already-open Lane is successful and
\  does not allocate another session record.  Callers therefore need not
\  reach through the client into its nested session during reconnect/rebind.
\
\  Persistent state and all variable-size storage are caller-owned.  Private
\  VARIABLEs are synchronous operation scratch.  One cooperative owner must
\  serialize calls; this module makes no multicore/reentrancy claim while the
\  lower frame/message/connection layers retain the same limitation.
\ =====================================================================

