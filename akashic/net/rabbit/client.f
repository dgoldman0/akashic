        _RCLIENTR-LANE @ _RCLIENTR-TXN @ _RCLIENTR-TU @
            _RCLIENTR-C @ RCLIENT.SESSION @ RABBIT-SESSION-TXN-COMPLETE
            _RCLIENTR-ROLLBACK !
        _RCLIENTR-ROLLBACK @ _RCLIENTR-C @ RCLIENT.CLEANUP-STATUS !
        _RCLIENTR-ROLLBACK @ IF
            _RCLIENTR-LANE @ _RCLIENTR-TXN @ _RCLIENTR-TU @
                _RCLIENTR-C @ RCLIENT.SESSION @
                RABBIT-SESSION-TXN-PENDING? IF
                _RCLIENT-REQUEST-TOMBSTONE
            ELSE
                _RCLIENT-REQUEST-WIPE
            THEN
        ELSE
            _RCLIENT-REQUEST-WIPE
        THEN
        RCLIENT-S-CONNECTION RCLIENT-DETAIL-CONNECTION _RCLIENTR-RS @
            _RCLIENTR-C @ _RCLIENT-REFUSE EXIT
    THEN
