    _RCLIENTS-C @ RCLIENT.CONNECTION @ RABBIT-CONNECTION-CANCEL
        DUP _RCLIENTL-RS ! DROP
    _RCLIENTS-C @ RCLIENT.SESSION @ RSESS.STATE @
        RABBIT-ST-ESTABLISHED <> IF
        _RCLIENTS-C @ _RCLIENT-NORMALIZE-OUTSTANDING
