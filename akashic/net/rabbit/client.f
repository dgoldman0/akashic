    _RCLIENTS-C @ RCLIENT.CONNECTION @ RABBIT-CONNECTION-CLOSE
        DUP _RCLIENTL-RS ! DROP
    _RCLIENTS-C @ RCLIENT.SESSION @ RSESS.STATE @
        RABBIT-ST-ESTABLISHED <> IF
        _RCLIENTS-C @ _RCLIENT-NORMALIZE-OUTSTANDING
    THEN
    _RCLIENTL-RS @ RCONN-S-OK = IF
        RCLIENT-ST-CLOSED _RCLIENTS-C @ RCLIENT.STATE !
        RCLIENT-S-OK RCLIENT-DETAIL-NONE 0 _RCLIENTS-C @
            _RCLIENT-STATUS! EXIT
    THEN
    _RCLIENTL-RS @ RCONN-S-PENDING = IF
        RCLIENT-ST-CLOSING _RCLIENTS-C @ RCLIENT.STATE !
        RCLIENT-S-PENDING RCLIENT-DETAIL-NONE 0 _RCLIENTS-C @
            _RCLIENT-STATUS! EXIT
    THEN
    _RCLIENTL-RS @ RCONN-S-CANCELLED = IF
        RCLIENT-ST-CANCELLED _RCLIENTS-C @ RCLIENT.STATE !
        RCLIENT-S-CANCELLED RCLIENT-DETAIL-CONNECTION _RCLIENTL-RS @
            _RCLIENTS-C @ _RCLIENT-STATUS! EXIT
    THEN
    RCLIENT-ST-FAILED _RCLIENTS-C @ RCLIENT.STATE !
    RCLIENT-S-CONNECTION RCLIENT-DETAIL-CONNECTION _RCLIENTL-RS @
