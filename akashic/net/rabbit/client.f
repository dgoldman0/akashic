: RABBIT-CLIENT-INIT
  ( ops count txn-a txn-u result-a result-u burrow-a burrow-u conn client -- status )
    _RCLIENTI-C ! _RCLIENTI-CONN ! _RCLIENTI-BU ! _RCLIENTI-BA !
    _RCLIENTI-RU ! _RCLIENTI-RA !
    _RCLIENTI-TU ! _RCLIENTI-TA ! _RCLIENTI-CAP ! _RCLIENTI-OPS !
    _RCLIENTI-C @ 0= IF RCLIENT-S-INVALID EXIT THEN
    _RCLIENTI-C @ _RCLIENT-CELL-ALIGNED? 0= IF RCLIENT-S-INVALID EXIT THEN
    _RCLIENTI-C @ RABBIT-CLIENT-SIZE MSPAN-NONWRAPPING? 0= IF
        RCLIENT-S-INVALID EXIT
    THEN
    \ Matching magic is sufficient evidence that this storage is already an
    \ owned client object.  Do not overwrite a damaged live object merely
    \ because its full semantic validator can no longer walk it.
    _RCLIENTI-C @ RCLIENT.MAGIC @ _RCLIENT-MAGIC-VALUE = IF
        RCLIENT-S-STATE EXIT
    THEN
    _RCLIENTI-CONN @ RABBIT-CONNECTION-VALID? 0= IF
        RCLIENT-S-CONNECTION EXIT
    THEN
    _RCLIENTI-CONN @ RCONN.SESSION @ DUP _RCLIENTI-SESSION !
    RSESS.ROLE @ RABBIT-ROLE-CLIENT <> IF RCLIENT-S-SESSION EXIT THEN
    _RCLIENTI-SESSION @ _RCLIENT-SESSION-TXNS-EMPTY? 0= IF
        RCLIENT-S-STATE EXIT
    THEN
    _RCLIENTI-CAP @ 0< _RCLIENTI-TU @ 0< OR
    _RCLIENTI-RU @ 0< OR _RCLIENTI-BU @ 0< OR IF
        RCLIENT-S-INVALID EXIT
    THEN
    _RCLIENTI-OPS @ _RCLIENTI-CAP @ RABBIT-CLIENT-OP-SIZE
        _RCLIENT-ARRAY? 0= IF RCLIENT-S-INVALID EXIT THEN
    _RCLIENTI-TA @ _RCLIENTI-CAP @ _RCLIENTI-TU @
        _RCLIENT-BYTE-ARRAY? 0= IF RCLIENT-S-INVALID EXIT THEN
    _RCLIENTI-RA @ _RCLIENTI-CAP @ _RCLIENTI-RU @
        _RCLIENT-BYTE-ARRAY? 0= IF RCLIENT-S-INVALID EXIT THEN
    _RCLIENTI-BA @ _RCLIENTI-BU @
        _RCLIENT-OPTIONAL-SPAN? 0= IF RCLIENT-S-INVALID EXIT THEN
    _RCLIENTI-CAP @ IF
        _RCLIENTI-TU @ 0= _RCLIENTI-RU @ 0= OR IF
            RCLIENT-S-CAPACITY EXIT
        THEN
    THEN
    _RCLIENTI-CAP @ RABBIT-CLIENT-OP-SIZE _RCLIENT-MUL? 0= IF
        DROP RCLIENT-S-INVALID EXIT
    THEN _RCLIENTI-OPS-U !
    _RCLIENTI-CAP @ _RCLIENTI-TU @ _RCLIENT-MUL? 0= IF
        DROP RCLIENT-S-INVALID EXIT
    THEN _RCLIENTI-TOTAL-TU !
    _RCLIENTI-CAP @ _RCLIENTI-RU @ _RCLIENT-MUL? 0= IF
        DROP RCLIENT-S-INVALID EXIT
    THEN _RCLIENTI-TOTAL-RU !
    _RCLIENT-INIT-DISJOINT? 0= IF RCLIENT-S-ALIAS EXIT THEN
    _RCLIENTI-C @ RABBIT-CLIENT-SIZE 0 FILL
    _RCLIENTI-OPS @ _RCLIENTI-OPS-U @ 0 FILL
    _RCLIENTI-TA @ _RCLIENTI-TOTAL-TU @ 0 FILL
    _RCLIENTI-RA @ _RCLIENTI-TOTAL-RU @ 0 FILL
    _RCLIENTI-BA @ _RCLIENTI-BU @ 0 FILL
    _RCLIENT-MAGIC-VALUE _RCLIENTI-C @ RCLIENT.MAGIC !
    _RCLIENT-ABI-VERSION _RCLIENTI-C @ RCLIENT.ABI !
    RABBIT-CLIENT-SIZE _RCLIENTI-C @ RCLIENT.BYTES !
    RCLIENT-ST-READY _RCLIENTI-C @ RCLIENT.STATE !
    RCLIENT-S-OK _RCLIENTI-C @ RCLIENT.LAST-STATUS !
    _RCLIENTI-CONN @ _RCLIENTI-C @ RCLIENT.CONNECTION !
    _RCLIENTI-SESSION @ _RCLIENTI-C @ RCLIENT.SESSION !
    _RCLIENTI-OPS @ _RCLIENTI-C @ RCLIENT.OPS !
    _RCLIENTI-CAP @ _RCLIENTI-C @ RCLIENT.OP-CAP !
    _RCLIENTI-TA @ _RCLIENTI-C @ RCLIENT.TXN-A !
    _RCLIENTI-TU @ _RCLIENTI-C @ RCLIENT.TXN-SLOT-BYTES !
