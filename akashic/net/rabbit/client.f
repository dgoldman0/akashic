        RCLIENT-S-CANCELLED RCLIENT-DETAIL-NONE 0 _RCLIENTS-C @
            _RCLIENT-STATUS! EXIT
    THEN
    RCLIENT-ST-FAILED _RCLIENTS-C @ RCLIENT.STATE !
    RCLIENT-S-CONNECTION RCLIENT-DETAIL-CONNECTION _RCLIENTL-RS @
        _RCLIENTS-C @ _RCLIENT-STATUS! ;

