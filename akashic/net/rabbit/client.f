        2DROP RCLIENT-S-CAPACITY RCLIENT-DETAIL-NONE
        RCLIENT-S-CAPACITY _RCLIENTR-C @ _RCLIENT-REFUSE EXIT
    THEN
    _RCLIENTR-I ! _RCLIENTR-OP !
