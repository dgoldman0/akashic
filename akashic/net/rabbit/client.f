    _RCLIENTR-I @ _RCLIENTR-C @ _RCLIENT-RESULT@ _RCLIENTR-RESULT !
    _RCLIENTR-TA @ _RCLIENTR-TXN @ _RCLIENTR-TU @ MOVE
    _RCLIENTR-LANE @ _RCLIENTR-TXN @ _RCLIENTR-TU @
        _RCLIENTR-C @ RCLIENT.SESSION @ RABBIT-SESSION-TXN-BEGIN
    DUP _RCLIENTR-RS ! IF
        _RCLIENT-REQUEST-WIPE
        RCLIENT-S-SESSION RCLIENT-DETAIL-SESSION _RCLIENTR-RS @
            _RCLIENTR-C @ _RCLIENT-REFUSE EXIT
    THEN
