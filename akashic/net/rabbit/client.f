        RCLIENT-S-ALIAS RCLIENT-DETAIL-BUILDER RMSGB-S-ALIAS
            _RCLIENTR-C @ _RCLIENT-REFUSE EXIT
    THEN
    _RCLIENT-REQUEST-FIELDS DUP IF
        DUP RCLIENT-S-CAPACITY = IF RCLIENT-DETAIL-TXN ELSE
            RCLIENT-DETAIL-BUILDER
        THEN
        _RCLIENTR-DETAIL @ _RCLIENTR-C @ _RCLIENT-REFUSE EXIT
    THEN DROP
    _RCLIENTR-C @ RCLIENT.NEXT-GENERATION @ RABBIT-U64-MAX = IF
        RCLIENT-S-CAPACITY RCLIENT-DETAIL-NONE RABBIT-U64-MAX
            _RCLIENTR-C @ _RCLIENT-REFUSE EXIT
    THEN
