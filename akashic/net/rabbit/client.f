    OVER RCLIENT-OP-ABANDONED = OR IF
        _RCLI-V-OP @ RCOP.STATE @ RCLIENT-OP-PENDING = IF
            _RCLI-V-OP @ RCOP.STATUS @ RCLIENT-S-PENDING <> IF
                DROP 0 EXIT
            THEN
        ELSE
            _RCLI-V-OP @ RCOP.STATUS @ RCLIENT-S-CANCELLED <> IF
                DROP 0 EXIT
            THEN
        THEN
        DROP
        _RCLI-V-OP @ RCOP.RESULT-U @
        _RCLI-V-OP @ RCOP.RESULT-REQUIRED @ OR
        _RCLI-V-OP @ RCOP.RESPONSE-CODE @ OR IF 0 EXIT THEN
