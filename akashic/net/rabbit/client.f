    _RCLIENTI-RU @ _RCLIENTI-C @ RCLIENT.RESULT-SLOT-BYTES !
    _RCLIENTI-BA @ _RCLIENTI-C @ RCLIENT.BURROW-A !
    _RCLIENTI-BU @ _RCLIENTI-C @ RCLIENT.BURROW-CAP !
