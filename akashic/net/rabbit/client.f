    _RCLIENT-CLEAR-LOAN-SCRATCH _RCLIENTP-RS @ ;

\ This path is used only after RX-LOAN.  DROP expires the borrowed parser view
\ first; connection cancellation then releases every session transaction, so
\ stable Txn slots can be normalized without dangling session pointers.
: _RCLIENT-ABORT-LOAN
  ( client-status detail-domain exact-detail -- item operation generation status )
    _RCLIENTS-DETAIL ! _RCLIENTS-DOMAIN ! _RCLIENTP-ABORT-STATUS !
    _RCLIENT-DROP-LOAN _RCLIENTP-C @ RCLIENT.CLEANUP-STATUS !
    _RCLIENTP-CONN @ RABBIT-CONNECTION-CANCEL
        _RCLIENTP-C @ RCLIENT.CLEANUP-STATUS !
    _RCLIENTP-C @ _RCLIENT-NORMALIZE-OUTSTANDING
    RCLIENT-ST-FAILED _RCLIENTP-C @ RCLIENT.STATE !
    _RCLIENTP-ABORT-STATUS @ _RCLIENTS-DOMAIN @ _RCLIENTS-DETAIL @
        _RCLIENTP-C @ _RCLIENT-STATUS!
    _RCLIENT-NO-ITEM ;

: _RCLIENT-CONTROL-COMMIT
  ( -- item operation generation status )
    _RCLIENT-COMMIT-LOAN DUP IF
        RCLIENT-S-CONNECTION RCLIENT-DETAIL-CONNECTION ROT
            \ COMMIT may have failed before releasing its loan.  CANCEL owns
            \ exact cleanup; no parser pointer is inspected again.
            _RCLIENTP-CONN @ RABBIT-CONNECTION-CANCEL
                _RCLIENTP-C @ RCLIENT.CLEANUP-STATUS !
        _RCLIENTP-C @ _RCLIENT-NORMALIZE-OUTSTANDING
        RCLIENT-ST-FAILED _RCLIENTP-C @ RCLIENT.STATE !
        _RCLIENTP-C @ _RCLIENT-STATUS!
        _RCLIENT-NO-ITEM EXIT
    THEN
    DROP
    RCLIENT-S-OK _RCLIENTP-C @ _RCLIENT-PUBLISH-STATUS
    _RCLIENT-OTHER-ITEM ;

: _RCLIENT-BURROW-WIPE  ( client -- )
    DUP RCLIENT.BURROW-A @ OVER RCLIENT.BURROW-CAP @ 0 FILL
    0 SWAP RCLIENT.BURROW-U ! ;

: _RCLIENT-HELLO-COMMIT
  ( -- item operation generation status )
    _RCLIENTP-F @ RMSG-BURROW-ID$
    _RCLIENTP-MSGS ! _RCLIENTP-BURROW-PRESENT !
    _RCLIENTP-BURROW-U ! _RCLIENTP-BURROW-A !
    _RCLIENTP-MSGS @ IF
        RCLIENT-S-PROTOCOL RCLIENT-DETAIL-MESSAGE _RCLIENTP-MSGS @
            _RCLIENT-ABORT-LOAN EXIT
    THEN
    _RCLIENTP-BURROW-U @ _RCLIENTP-C @ RCLIENT.BURROW-CAP @ U> IF
        RCLIENT-S-CAPACITY RCLIENT-DETAIL-BURROW _RCLIENTP-BURROW-U @
            _RCLIENT-ABORT-LOAN EXIT
    THEN
    _RCLIENTP-C @ _RCLIENT-BURROW-WIPE
    _RCLIENTP-BURROW-PRESENT @ IF
        _RCLIENTP-BURROW-A @ _RCLIENTP-C @ RCLIENT.BURROW-A @
            _RCLIENTP-BURROW-U @ MOVE
    THEN
    _RCLIENT-COMMIT-LOAN DUP IF
        _RCLIENTP-C @ _RCLIENT-BURROW-WIPE
        RCLIENT-S-CONNECTION RCLIENT-DETAIL-CONNECTION ROT
        _RCLIENTP-CONN @ RABBIT-CONNECTION-CANCEL
            _RCLIENTP-C @ RCLIENT.CLEANUP-STATUS !
        _RCLIENTP-C @ _RCLIENT-NORMALIZE-OUTSTANDING
        RCLIENT-ST-FAILED _RCLIENTP-C @ RCLIENT.STATE !
        _RCLIENTP-C @ _RCLIENT-STATUS!
        _RCLIENT-NO-ITEM EXIT
    THEN DROP
    _RCLIENTP-BURROW-PRESENT @ IF _RCLIENTP-BURROW-U @ ELSE 0 THEN
        _RCLIENTP-C @ RCLIENT.BURROW-U !
    RCLIENT-S-OK _RCLIENTP-C @ _RCLIENT-PUBLISH-STATUS
    _RCLIENT-OTHER-ITEM ;

VARIABLE _RCLIENTCB-THROW

: _RCLIENT-CALLBACK-INNER  ( -- )
    _RCLIENTP-F @ _RCLIENTP-KIND @ _RCLIENTP-LANE @
    _RCLIENTP-SEQ @ _RCLIENTP-EXPECTED @ _RCLIENTP-DISPOSITION @
    _RCLIENTP-CONTEXT @ _RCLIENTP-XT @ EXECUTE
    _RCLIENTP-DECISION ! ;

: _RCLIENT-CALLBACK  ( -- status )
    0 _RCLIENTCB-THROW !
    0 _RCLIENTP-DECISION !
    _RCLIENTP-XT @ 0= IF RCLIENT-S-CALLBACK EXIT THEN
    ['] _RCLIENT-CALLBACK-INNER CATCH DUP _RCLIENTCB-THROW ! IF
        RCLIENT-S-CALLBACK EXIT
    THEN
    _RCLIENTP-DECISION @ RCLIENT-DISPATCH-VALID? 0= IF
        RCLIENT-S-CALLBACK EXIT
    THEN
    RCLIENT-S-OK ;

: _RCLIENT-CALLBACK-DISPATCH
  ( -- item operation generation status )
    _RCLIENT-CALLBACK DUP IF
        DROP _RCLIENTCB-THROW @ DUP 0= IF
            DROP _RCLIENTP-DECISION @
        THEN
        RCLIENT-S-CALLBACK RCLIENT-DETAIL-CALLBACK ROT
            _RCLIENT-ABORT-LOAN EXIT
    THEN DROP
    _RCLIENTP-DECISION @ RCLIENT-DISPATCH-COMMIT = IF
        _RCLIENT-COMMIT-LOAN
    ELSE
        _RCLIENT-DROP-LOAN
    THEN
    DUP IF
        RCLIENT-S-CONNECTION RCLIENT-DETAIL-CONNECTION ROT
        \ The release path itself failed; cancel without touching the expired
        \ or indeterminate parser view.
        _RCLIENTP-CONN @ RABBIT-CONNECTION-CANCEL
            _RCLIENTP-C @ RCLIENT.CLEANUP-STATUS !
        _RCLIENTP-C @ _RCLIENT-NORMALIZE-OUTSTANDING
        RCLIENT-ST-FAILED _RCLIENTP-C @ RCLIENT.STATE !
        _RCLIENTP-C @ _RCLIENT-STATUS!
        _RCLIENT-NO-ITEM EXIT
    THEN DROP
    _RCLIENTP-KIND @ RMSG-KIND-EVENT = IF
        RCLIENT-S-EVENT _RCLIENTP-C @ _RCLIENT-PUBLISH-STATUS
        _RCLIENT-EVENT-ITEM
    ELSE
        RCLIENT-S-OK _RCLIENTP-C @ _RCLIENT-PUBLISH-STATUS
        _RCLIENT-OTHER-ITEM
    THEN ;

: _RCLIENT-RESPONSE-FIELDS  ( -- message-status )
    _RCLIENTP-F @ RMSG-LANE@
    _RCLIENTP-MSGS ! _RCLIENTP-LANE-PRESENT ! _RCLIENTP-LANE !
    _RCLIENTP-MSGS @ IF _RCLIENTP-MSGS @ EXIT THEN
    _RCLIENTP-F @ RMSG-TXN$
    _RCLIENTP-MSGS ! _RCLIENTP-TXN-PRESENT !
    _RCLIENTP-TU ! _RCLIENTP-TA !
    _RCLIENTP-MSGS @ IF _RCLIENTP-MSGS @ EXIT THEN
    _RCLIENTP-F @ RMSG-STATUS@
    _RCLIENTP-MSGS ! _RCLIENTP-STATUS-PRESENT ! _RCLIENTP-CODE !
    _RCLIENTP-MSGS @ IF _RCLIENTP-MSGS @ EXIT THEN
    _RCLIENTP-STATUS-PRESENT @ 0= IF RMSG-S-REQUIRED EXIT THEN
    _RCLIENTP-F @ RMSG-LABEL$
    _RCLIENTP-MSGS ! _RCLIENTP-LABEL-U ! _RCLIENTP-LABEL-A !
    _RCLIENTP-MSGS @ IF _RCLIENTP-MSGS @ EXIT THEN
    _RCLIENTP-F @ RMSG-BODY$
    _RCLIENTP-MSGS ! _RCLIENTP-BU ! _RCLIENTP-BA !
    _RCLIENTP-MSGS @ IF _RCLIENTP-MSGS @ EXIT THEN
    RMSG-S-OK ;

: _RCLIENT-RESPONSE-PUBLISH
  ( -- item operation generation status )
    _RCLIENTP-OP @ RCOP.STATE @ RCLIENT-OP-ABANDONED = IF
        RCLIENT-OP-CANCELLED _RCLIENTP-OP @ RCOP.STATE !
        RCLIENT-S-CANCELLED _RCLIENTP-OP @ RCOP.STATUS !
        RCLIENT-S-CANCELLED _RCLIENTP-C @ _RCLIENT-PUBLISH-STATUS DROP
    ELSE
        _RCLIENTP-BU @ _RCLIENTP-C @ RCLIENT.RESULT-SLOT-BYTES @ U> IF
            RCLIENT-OP-FAILED _RCLIENTP-OP @ RCOP.STATE !
            0 _RCLIENTP-OP @ RCOP.RESULT-U !
            _RCLIENTP-BU @ _RCLIENTP-OP @ RCOP.RESULT-REQUIRED !
            _RCLIENTP-CODE @ _RCLIENTP-OP @ RCOP.RESPONSE-CODE !
            RCLIENT-S-RESULT _RCLIENTP-OP @ RCOP.STATUS !
            RCLIENT-S-RESULT RCLIENT-DETAIL-RESULT _RCLIENTP-BU @
                _RCLIENTP-C @ _RCLIENT-STATUS! DROP
        ELSE
            RCLIENT-OP-COMPLETE _RCLIENTP-OP @ RCOP.STATE !
            _RCLIENTP-BU @ _RCLIENTP-OP @ RCOP.RESULT-U !
            _RCLIENTP-BU @ _RCLIENTP-OP @ RCOP.RESULT-REQUIRED !
            _RCLIENTP-CODE @ _RCLIENTP-OP @ RCOP.RESPONSE-CODE !
            RCLIENT-S-OK _RCLIENTP-OP @ RCOP.STATUS !
            RCLIENT-S-OK _RCLIENTP-C @ _RCLIENT-PUBLISH-STATUS DROP
        THEN
    THEN
    -1 _RCLIENTP-C @ RCLIENT.PENDING +!
    1 _RCLIENTP-C @ RCLIENT.TERMINAL +!
    _RCLIENTP-C @ RCLIENT.PENDING @ 0= IF
        RCLIENT-ST-READY _RCLIENTP-C @ RCLIENT.STATE !
    THEN
    RCLIENT-ITEM-OPERATION _RCLIENTP-OP @
        _RCLIENTP-OP @ RCOP.GENERATION @
        _RCLIENTP-OP @ RCOP.STATUS @ ;

: _RCLIENT-CORRELATED-RESPONSE
  ( -- item operation generation status )
    _RCLIENTP-LANE @ _RCLIENTP-TA @ _RCLIENTP-TU @ _RCLIENTP-C @
        _RCLIENT-FIND-OP 0= IF
        2DROP RCLIENT-S-PROTOCOL RCLIENT-DETAIL-SESSION
            RABBIT-S-NOT-FOUND _RCLIENT-ABORT-LOAN EXIT
    THEN
    _RCLIENTP-I ! _RCLIENTP-OP !
    _RCLIENTP-LANE @ _RCLIENTP-TA @ _RCLIENTP-TU @
        _RCLIENTP-C @ RCLIENT.SESSION @
        RABBIT-SESSION-TXN-PENDING? 0= IF
        RCLIENT-S-PROTOCOL RCLIENT-DETAIL-SESSION RABBIT-S-NOT-FOUND
            _RCLIENT-ABORT-LOAN EXIT
    THEN
    \ A supplied callback sees the complete borrowed correlated response before
    \ any parser bytes expire.  This is the application-profile seam for exact
    \ labels, View headers, and extension metadata; the operation still owns
    \ the durable numeric code and copied body.  Rejecting a terminal response
    \ cannot leave the transaction pending, so DROP cancels the connection.
    _RCLIENTP-XT @ IF
        _RCLIENT-CALLBACK DUP IF
            DROP _RCLIENTCB-THROW @ DUP 0= IF
                DROP _RCLIENTP-DECISION @
            THEN
            RCLIENT-S-CALLBACK RCLIENT-DETAIL-CALLBACK ROT
                _RCLIENT-ABORT-LOAN EXIT
        THEN DROP
        _RCLIENTP-DECISION @ RCLIENT-DISPATCH-COMMIT <> IF
            RCLIENT-S-PROTOCOL RCLIENT-DETAIL-CALLBACK
                _RCLIENTP-DECISION @ _RCLIENT-ABORT-LOAN EXIT
        THEN
    THEN
    0 _RCLIENTP-COPIED !
    _RCLIENTP-OP @ RCOP.STATE @ RCLIENT-OP-PENDING =
    _RCLIENTP-BU @ _RCLIENTP-C @ RCLIENT.RESULT-SLOT-BYTES @ U> 0= AND IF
        _RCLIENTP-BA @ _RCLIENTP-I @ _RCLIENTP-C @ _RCLIENT-RESULT@
            _RCLIENTP-BU @ MOVE
        -1 _RCLIENTP-COPIED !
    THEN
    _RCLIENT-COMMIT-LOAN DUP IF
        _RCLIENTP-COPIED @ IF
            _RCLIENTP-I @ _RCLIENTP-C @ _RCLIENT-RESULT@
                _RCLIENTP-C @ RCLIENT.RESULT-SLOT-BYTES @ 0 FILL
        THEN
        RCLIENT-S-CONNECTION RCLIENT-DETAIL-CONNECTION ROT
        _RCLIENTP-CONN @ RABBIT-CONNECTION-CANCEL
            _RCLIENTP-C @ RCLIENT.CLEANUP-STATUS !
        _RCLIENTP-C @ _RCLIENT-NORMALIZE-OUTSTANDING
        RCLIENT-ST-FAILED _RCLIENTP-C @ RCLIENT.STATE !
        _RCLIENTP-C @ _RCLIENT-STATUS!
        _RCLIENT-NO-ITEM EXIT
    THEN DROP
    _RCLIENTP-OP @ RCOP.LANE @
    _RCLIENTP-I @ _RCLIENTP-C @ _RCLIENT-TXN@
    _RCLIENTP-OP @ RCOP.TXN-U @ _RCLIENTP-C @ RCLIENT.SESSION @
        RABBIT-SESSION-TXN-COMPLETE DUP _RCLIENTP-RS ! IF
        _RCLIENTP-COPIED @ IF
            _RCLIENTP-I @ _RCLIENTP-C @ _RCLIENT-RESULT@
                _RCLIENTP-C @ RCLIENT.RESULT-SLOT-BYTES @ 0 FILL
        THEN
        _RCLIENTP-CONN @ RABBIT-CONNECTION-CANCEL
            _RCLIENTP-C @ RCLIENT.CLEANUP-STATUS !
        _RCLIENTP-C @ _RCLIENT-NORMALIZE-OUTSTANDING
        RCLIENT-ST-FAILED _RCLIENTP-C @ RCLIENT.STATE !
        RCLIENT-S-SESSION RCLIENT-DETAIL-SESSION _RCLIENTP-RS @
            _RCLIENTP-C @ _RCLIENT-STATUS!
        _RCLIENT-NO-ITEM EXIT
    THEN
    _RCLIENT-RESPONSE-PUBLISH ;

: _RCLIENT-RESPONSE-DISPATCH
  ( -- item operation generation status )
    _RCLIENT-RESPONSE-FIELDS DUP IF
        RCLIENT-S-PROTOCOL RCLIENT-DETAIL-MESSAGE ROT
            _RCLIENT-ABORT-LOAN EXIT
    THEN DROP
    \ HELLO is the one no-Lane/no-Txn response committed internally, and only
    \ while the connection's state admission is completing client handshake.
    _RCLIENTP-LABEL-A @ _RCLIENTP-LABEL-U @ S" HELLO" STR-STR= IF
        _RCLIENTP-F @ RMSG-HELLO-OK-STATUS DUP IF
            RCLIENT-S-PROTOCOL RCLIENT-DETAIL-MESSAGE ROT
                _RCLIENT-ABORT-LOAN EXIT
        THEN
        DROP
        _RCLIENTP-C @ RCLIENT.SESSION @ RSESS.STATE @
            RABBIT-ST-HELLO-SENT <> IF
            RCLIENT-S-PROTOCOL RCLIENT-DETAIL-SESSION RABBIT-S-STATE
                _RCLIENT-ABORT-LOAN EXIT
        THEN
        _RCLIENT-HELLO-COMMIT EXIT
    THEN
    \ Typed PONG uses the same exact state-free control-response contract.
    _RCLIENTP-LABEL-A @ _RCLIENTP-LABEL-U @ S" PONG" STR-STR= IF
        _RCLIENTP-F @ RMSG-PONG-STATUS DUP IF
            RCLIENT-S-PROTOCOL RCLIENT-DETAIL-MESSAGE ROT
                _RCLIENT-ABORT-LOAN EXIT
        THEN
        DROP _RCLIENT-CONTROL-COMMIT EXIT
    THEN
    _RCLIENTP-LANE-PRESENT @ _RCLIENTP-TXN-PRESENT @ AND IF
        _RCLIENT-CORRELATED-RESPONSE EXIT
    THEN
    \ Any other one-sided correlation shape is ambiguous.  A fully
    \ uncorrelated, explicitly labelled extension response is offered to the
    \ synchronous opaque callback instead of being silently accepted.
    _RCLIENTP-LANE-PRESENT @ _RCLIENTP-TXN-PRESENT @ OR IF
        RCLIENT-S-PROTOCOL RCLIENT-DETAIL-MESSAGE RMSG-S-CONFLICT
            _RCLIENT-ABORT-LOAN EXIT
    THEN
    _RCLIENT-CALLBACK-DISPATCH ;

: _RCLIENT-DISPATCH-HELD
  ( -- item operation generation status )
    _RCLIENT-RX-LOAN DUP IF
        RCLIENT-DETAIL-CONNECTION _RCLIENTP-RS @ _RCLIENTP-C @
            _RCLIENT-STATUS! _RCLIENT-NO-ITEM EXIT
    THEN DROP
    _RCLIENTP-KIND @ RMSG-KIND-RESPONSE = IF
        _RCLIENT-RESPONSE-DISPATCH EXIT
    THEN
    _RCLIENTP-KIND @ DUP RMSG-KIND-ACK =
    SWAP RMSG-KIND-CREDIT = OR IF
        _RCLIENT-CONTROL-COMMIT EXIT
    THEN
    _RCLIENT-CALLBACK-DISPATCH ;

: _RCLIENT-DISPATCH-INNER
  ( dispatch-xt context client -- item operation generation status )
    _RCLIENTP-C ! _RCLIENTP-CONTEXT ! _RCLIENTP-XT !
    _RCLIENTP-C @ RABBIT-CLIENT-VALID? 0= IF
        RCLIENT-ITEM-NONE 0 0 RCLIENT-S-INVALID EXIT
    THEN
    _RCLIENTP-C @ RCLIENT.STATE @ DUP RCLIENT-ST-READY =
    SWAP RCLIENT-ST-ACTIVE = OR 0= IF
        RCLIENT-ITEM-NONE RCLIENT-S-STATE RCLIENT-DETAIL-NONE 0
            _RCLIENTP-C @ _RCLIENT-REFUSE EXIT
    THEN
    _RCLIENTP-C @ RCLIENT.CONNECTION @ DUP _RCLIENTP-CONN !
        RABBIT-CONNECTION-RX-READY? 0= IF
        RCLIENT-ITEM-NONE RCLIENT-S-PENDING RCLIENT-DETAIL-NONE 0
            _RCLIENTP-C @ _RCLIENT-REFUSE EXIT
    THEN
    _RCLIENT-DISPATCH-HELD ;

: _RCLIENT-POLL-INNER
  ( dispatch-xt context client -- item operation generation status )
    _RCLIENTP-C ! _RCLIENTP-CONTEXT ! _RCLIENTP-XT !
    _RCLIENTP-C @ RABBIT-CLIENT-VALID? 0= IF
        RCLIENT-ITEM-NONE 0 0 RCLIENT-S-INVALID EXIT
    THEN
    _RCLIENTP-C @ RCLIENT.STATE @ DUP RCLIENT-ST-READY =
    SWAP RCLIENT-ST-ACTIVE = OR 0= IF
        RCLIENT-ITEM-NONE RCLIENT-S-STATE RCLIENT-DETAIL-NONE 0
            _RCLIENTP-C @ _RCLIENT-REFUSE EXIT
    THEN
    _RCLIENTP-C @ RCLIENT.CONNECTION @ DUP _RCLIENTP-CONN !
    DUP RABBIT-CONNECTION-RX-READY? IF
        DROP _RCLIENT-DISPATCH-HELD EXIT
    THEN
    RABBIT-CONNECTION-PUMP DUP _RCLIENTP-RS !
    DUP RCONN-S-RX-READY = IF
        DROP _RCLIENT-DISPATCH-HELD EXIT
    THEN
    DUP RCONN-S-OK = OVER RCONN-S-PENDING = OR IF
        DROP RCLIENT-S-PENDING _RCLIENTP-C @ _RCLIENT-PUBLISH-STATUS
        _RCLIENT-NO-ITEM EXIT
    THEN
    DUP RCONN-S-CANCELLED = IF
        DROP _RCLIENTP-C @ _RCLIENT-NORMALIZE-OUTSTANDING
        RCLIENT-ST-CANCELLED _RCLIENTP-C @ RCLIENT.STATE !
        RCLIENT-S-CANCELLED RCLIENT-DETAIL-CONNECTION _RCLIENTP-RS @
            _RCLIENTP-C @ _RCLIENT-STATUS!
        _RCLIENT-NO-ITEM EXIT
    THEN
    \ EOF and all other non-progress statuses have already made the connection
    \ clear its queues/session or enter failure.  Preserve exact lower evidence.
    DROP
    _RCLIENTP-CONN @ RABBIT-CONNECTION-CANCEL
        _RCLIENTP-C @ RCLIENT.CLEANUP-STATUS !
    _RCLIENTP-C @ _RCLIENT-NORMALIZE-OUTSTANDING
    _RCLIENTP-RS @ RCONN-S-EOF = IF
        RCLIENT-ST-CLOSED
    ELSE
        RCLIENT-ST-FAILED
    THEN
        _RCLIENTP-C @ RCLIENT.STATE !
    RCLIENT-S-CONNECTION RCLIENT-DETAIL-CONNECTION _RCLIENTP-RS @
        _RCLIENTP-C @ _RCLIENT-STATUS!
    _RCLIENT-NO-ITEM ;

\ POLL/DISPATCH retain their live loan in module scratch while invoking the
\ opaque callback.  Refuse nested dispatch, including dispatch of a different
\ client, before any outer scratch can be overwritten.  Callbacks may inspect
\ and copy the supplied frame but must not recursively poll or dispatch.
: RABBIT-CLIENT-DISPATCH
  ( dispatch-xt context client -- item operation generation status )
    _RCLIENTP-BUSY @ IF
        2DROP DROP RCLIENT-ITEM-NONE 0 0 RCLIENT-S-STATE EXIT
    THEN
    -1 _RCLIENTP-BUSY !
    _RCLIENT-DISPATCH-INNER
    0 _RCLIENTP-BUSY ! ;

: RABBIT-CLIENT-POLL
  ( dispatch-xt context client -- item operation generation status )
    _RCLIENTP-BUSY @ IF
        2DROP DROP RCLIENT-ITEM-NONE 0 0 RCLIENT-S-STATE EXIT
    THEN
    -1 _RCLIENTP-BUSY !
    _RCLIENT-POLL-INNER
    0 _RCLIENTP-BUSY ! ;

