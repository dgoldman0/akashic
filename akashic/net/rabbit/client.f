\ The connection/session teardown must have released every transaction before
\ this helper is called.  Terminal results remain readable; only operations
\ which could no longer receive a response become CANCELLED.
: _RCLIENT-NORMALIZE-OUTSTANDING  ( client -- )
    DUP _RCLIENTN-C ! RCLIENT.OP-CAP @ 0 ?DO
        I _RCLIENTN-C @ _RCLIENT-OP@ DUP _RCLIENTN-OP !
        RCOP.STATE @ DUP RCLIENT-OP-PENDING =
        SWAP RCLIENT-OP-ABANDONED = OR IF
            I _RCLIENTN-C @ _RCLIENT-RESULT@
                _RCLIENTN-C @ RCLIENT.RESULT-SLOT-BYTES @ 0 FILL
            RCLIENT-OP-CANCELLED _RCLIENTN-OP @ RCOP.STATE !
            0 _RCLIENTN-OP @ RCOP.RESULT-U !
            0 _RCLIENTN-OP @ RCOP.RESULT-REQUIRED !
            0 _RCLIENTN-OP @ RCOP.RESPONSE-CODE !
            RCLIENT-S-CANCELLED _RCLIENTN-OP @ RCOP.STATUS !
            -1 _RCLIENTN-C @ RCLIENT.PENDING +!
            1 _RCLIENTN-C @ RCLIENT.TERMINAL +!
        THEN
    LOOP ;

: RABBIT-CLIENT-OPEN  ( client -- status )
    DUP RABBIT-CLIENT-VALID? 0= IF DROP RCLIENT-S-INVALID EXIT THEN
    DUP _RCLIENTS-C ! RCLIENT.STATE @ RCLIENT-ST-READY <> IF
        RCLIENT-S-STATE RCLIENT-DETAIL-NONE 0 _RCLIENTS-C @
            _RCLIENT-STATUS! EXIT
    THEN
    _RCLIENTS-C @ RCLIENT.CONNECTION @ RABBIT-CONNECTION-OPEN
    DUP RCONN-S-OK = IF
        DROP RCLIENT-S-OK RCLIENT-DETAIL-NONE 0 _RCLIENTS-C @
            _RCLIENT-STATUS! EXIT
    THEN
    DUP RCONN-S-PENDING = IF
        DROP RCLIENT-S-PENDING RCLIENT-DETAIL-NONE 0 _RCLIENTS-C @
            _RCLIENT-STATUS! EXIT
    THEN
    DUP RCONN-S-CANCELLED = IF
        RCLIENT-ST-CANCELLED _RCLIENTS-C @ RCLIENT.STATE !
        RCLIENT-S-CANCELLED RCLIENT-DETAIL-CONNECTION ROT _RCLIENTS-C @
            _RCLIENT-STATUS! EXIT
    THEN
    RCLIENT-ST-FAILED _RCLIENTS-C @ RCLIENT.STATE !
    RCLIENT-S-CONNECTION RCLIENT-DETAIL-CONNECTION ROT _RCLIENTS-C @
        _RCLIENT-STATUS! ;

