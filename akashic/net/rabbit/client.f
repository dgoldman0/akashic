: _RCLIENT-FIND-OP
  ( lane txn-a txn-u client -- operation index flag )
    _RCLIENTF-C ! _RCLIENTF-TU ! _RCLIENTF-TA ! _RCLIENTF-LANE !
    _RCLIENTF-C @ RCLIENT.OP-CAP @ 0 ?DO
        I _RCLIENTF-C @ _RCLIENT-OP@ DUP _RCLIENTF-OP !
        RCOP.STATE @ DUP RCLIENT-OP-PENDING =
        SWAP RCLIENT-OP-ABANDONED = OR IF
            _RCLIENTF-OP @ RCOP.LANE @ _RCLIENTF-LANE @ =
            _RCLIENTF-OP @ RCOP.TXN-U @ _RCLIENTF-TU @ = AND IF
                I _RCLIENTF-C @ _RCLIENT-TXN@ _RCLIENTF-TU @
                    _RCLIENTF-TA @ _RCLIENTF-TU @ COMPARE 0= IF
                    _RCLIENTF-OP @ I -1 UNLOOP EXIT
                THEN
            THEN
        THEN
    LOOP
    0 0 0 ;

