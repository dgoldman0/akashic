    _RCLI-V-OP @ RCOP.RESPONSE-CODE @ DUP 100 >=
    SWAP 599 <= AND
    _RCLI-V-OP @ RCOP.RESULT-U @ 0= AND
    _RCLI-V-OP @ RCOP.RESULT-REQUIRED @
        _RCLIOP-C @ RCLIENT.RESULT-SLOT-BYTES @ U> AND ;

