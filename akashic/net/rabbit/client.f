VARIABLE _RCLIENTFIN-BU

: RABBIT-CLIENT-FINI  ( client -- status )
    DUP RABBIT-CLIENT-VALID? 0= IF DROP RCLIENT-S-INVALID EXIT THEN
    DUP _RCLIENTFIN-C !
    DUP RCLIENT.OPS @ _RCLIENTFIN-OPS !
    DUP RCLIENT.OP-CAP @ RABBIT-CLIENT-OP-SIZE * _RCLIENTFIN-OPS-U !
    DUP RCLIENT.TXN-A @ _RCLIENTFIN-TA !
    DUP RCLIENT.OP-CAP @ OVER RCLIENT.TXN-SLOT-BYTES @ * _RCLIENTFIN-TU !
    DUP RCLIENT.RESULT-A @ _RCLIENTFIN-RA !
    DUP RCLIENT.OP-CAP @ OVER RCLIENT.RESULT-SLOT-BYTES @ * _RCLIENTFIN-RU !
    DUP RCLIENT.BURROW-A @ _RCLIENTFIN-BA !
    DUP RCLIENT.BURROW-CAP @ _RCLIENTFIN-BU !
    RCLIENT.CONNECTION @ RABBIT-CONNECTION-FINI DUP _RCLIENTL-RS !
    _RCLIENTFIN-C @ RCLIENT.SESSION @ RSESS.STATE @
        RABBIT-ST-ESTABLISHED <> IF
        _RCLIENTFIN-C @ _RCLIENT-NORMALIZE-OUTSTANDING
    THEN
    DUP RCONN-S-PENDING = IF
        DROP RCLIENT-ST-CLOSING _RCLIENTFIN-C @ RCLIENT.STATE !
        RCLIENT-S-PENDING RCLIENT-DETAIL-NONE 0 _RCLIENTFIN-C @
            _RCLIENT-STATUS! EXIT
    THEN
    IF
        RCLIENT-S-CONNECTION RCLIENT-DETAIL-CONNECTION _RCLIENTL-RS @
            _RCLIENTFIN-C @ _RCLIENT-STATUS! EXIT
    THEN
    _RCLIENTFIN-OPS @ _RCLIENTFIN-OPS-U @ 0 FILL
    _RCLIENTFIN-TA @ _RCLIENTFIN-TU @ 0 FILL
    _RCLIENTFIN-RA @ _RCLIENTFIN-RU @ 0 FILL
    _RCLIENTFIN-BA @ _RCLIENTFIN-BU @ 0 FILL
    _RCLIENTFIN-C @ RABBIT-CLIENT-SIZE 0 FILL
    RCLIENT-S-OK ;
