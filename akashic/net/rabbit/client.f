        0 0 RCLIENT-S-INVALID EXIT
    THEN
    _RCLIENTR-C @ RCLIENT.STATE @ DUP RCLIENT-ST-READY =
    SWAP RCLIENT-ST-ACTIVE = OR 0= IF
        RCLIENT-S-STATE RCLIENT-DETAIL-NONE 0 _RCLIENTR-C @
            _RCLIENT-REFUSE EXIT
    THEN
    _RCLIENTR-C @ RCLIENT.CONNECTION @ RCONN.STATE @
        RCONN-ST-OPEN <> IF
        RCLIENT-S-CONNECTION RCLIENT-DETAIL-CONNECTION RCONN-S-STATE
            _RCLIENTR-C @ _RCLIENT-REFUSE EXIT
    THEN
    _RCLIENTR-C @ RCLIENT.SESSION @ RABBIT-SESSION-ESTABLISHED? 0= IF
        RCLIENT-S-SESSION RCLIENT-DETAIL-SESSION RABBIT-S-STATE
            _RCLIENTR-C @ _RCLIENT-REFUSE EXIT
    THEN
    _RCLIENTR-B @ RMSGB-VALID? 0= IF
        RCLIENT-S-BUILDER RCLIENT-DETAIL-BUILDER RMSGB-S-INVALID
            _RCLIENTR-C @ _RCLIENT-REFUSE EXIT
    THEN
