: _RSERVSUB-WIPE-REGISTRATIONS  ( owner -- )
    >R
    R@ RSERVSUB.CAPACITY @ RABBIT-SERVER-SUBSCRIPTION-ENTRY-BYTES IF
        R@ RSERVSUB.ENTRIES @
        R@ RSERVSUB.CAPACITY @ RABBIT-SERVER-SUBSCRIPTION-ENTRY-BYTES
        0 FILL
    THEN
    R@ RSERVSUB.CAPACITY @ R@ RSERVSUB.TARGET-SLOT-BYTES @ * IF
        R@ RSERVSUB.TARGET-A @
        R@ RSERVSUB.CAPACITY @ R@ RSERVSUB.TARGET-SLOT-BYTES @ *
        0 FILL
    THEN
    0 R@ RSERVSUB.COUNT ! 0 R@ RSERVSUB.NEXT-INDEX !
    -1 R@ RSERVSUB.PENDING-INDEX !
    R> DROP ;

\ RESET controls future subscription publication only.  It wipes registration
\ metadata/selectors, but cannot retract already-enqueued EVENT bytes or close
\ transport Lanes owned by the nested server/session.
: RABBIT-SERVER-SUBSCRIPTIONS-RESET  ( owner -- status )
    _RSERVSUB-BUSY @ IF DROP RSERVSUB-S-STATE EXIT THEN
    DUP RABBIT-SERVER-SUBSCRIPTIONS-VALID? 0= IF
        DROP RSERVSUB-S-INVALID EXIT
    THEN
    DUP _RSERVSUB-WIPE-REGISTRATIONS
    RSERVSUB-S-OK 0 ROT _RSERVSUB-STATUS! ;

