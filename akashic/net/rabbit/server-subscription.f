    _RSERVSUBSG-U ! _RSERVSUBSG-A !
    _RSERVSUBSG-U @ 0> 0= IF 0 EXIT THEN
    _RSERVSUBSG-A @ 0= IF 0 EXIT THEN
    _RSERVSUBSG-A @ _RSERVSUBSG-U @ MSPAN-NONWRAPPING? 0= IF 0 EXIT THEN
