        _RSERVSUBV-O @ RSERVSUB.TARGET-A @ _RSERVSUBV-TU @
            _RSERVSUBV-O @ RSERVSUB.SERVER @
            RABBIT-SERVER-GRAPH-SPAN-OVERLAP? IF 0 EXIT THEN
