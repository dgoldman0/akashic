: _RSERVSUB-LIFECYCLE  ( owner mode -- server-status )
    \ Keep all public operation wrappers consistent: busy refusal is inert.
    _RSERVSUB-BUSY @ IF 2DROP RSERVER-S-STATE EXIT THEN
    _RSERVSUBL-MODE ! DUP _RSERVSUBL-O !
    DUP RABBIT-SERVER-SUBSCRIPTIONS-VALID? 0= IF
        DROP RSERVER-S-INVALID EXIT
    THEN
    DROP RSERVER-S-CALLBACK _RSERVSUBL-RS ! 0 _RSERVSUBL-THROW !
    -1 _RSERVSUB-BUSY !
    ['] _RSERVSUBL-INNER CATCH DUP _RSERVSUBL-THROW ! IF
        RSERVER-S-CALLBACK _RSERVSUBL-RS !
    THEN
    0 _RSERVSUB-BUSY !
    _RSERVSUBL-RS @ _RSERVSUBL-O @ _RSERVSUB-RECORD-SERVER
    _RSERVSUBL-RS @ ;

