\ =====================================================================
\  server-subscription.f - Generic Rabbit server subscription owner
\ =====================================================================
\  This neutral per-peer owner takes exclusive ownership of one initialized
\  RABBIT-SERVER plus a caller-sized table of copied SUBSCRIBE selectors.
\  After INIT succeeds, callers drive and finalize that server only through
\  this wrapper.  The sealed router remains borrowed by the owned server.
\
\  A router can be shared by many peers.  Its SUBSCRIBE entry therefore uses
\  one stable, shared route token as context:
\
\    ['] RABBIT-SERVER-SUBSCRIPTIONS-ROUTE  route-token
\
\  POLL/DISPATCH establish the exact active owner in synchronous dynamic
\  scope.  ROUTE accepts the fixed token only when it equals that owner's
\  expected token.  It never treats the immutable router context as a
\  per-peer owner pointer.
\  INIT cannot infer which application selector(s) should carry this handler;
\  the router owner must install the exact ROUTE/token pair before sealing.
\
\  Registration is commit-gated.  ROUTE copies a CANDIDATE, builds the 200
\  response, and ensures only the held request's application Lane.  The
\  wrapper publishes/counts it as ACTIVE only after the owned server reports
\  the exact successfully enqueued 200 response and commits the request.
\  Every other return path wipes the candidate.  The session Lane itself is
\  transport state and cannot be rolled back if failure happens after its
\  successful allocation.
\
\  Canonical events remain outside Rabbit.  SERVICE asks one injected,
\  deterministic exact-cursor source for at most one event:
\
\    ( target-a target-u expected-event-seq context
\      -- event-seq view-a view-u body-a body-u source-result )
\
\  EVENT must return the exact expected Event-Seq.  View/body slices expire
\  with the callback; RABBIT-SERVER-EVENT copies them synchronously.  Cursor
\  state advances only after enqueue succeeds.  This owner creates neither a
\  second journal nor a hidden fanout loop.
\
\  All persistent storage is caller-owned.  Private VARIABLE cells are
\  serialized synchronous scratch.  Source callbacks must not re-enter this
\  owner, and router handlers must be reached only through wrapper drive.
\ =====================================================================

