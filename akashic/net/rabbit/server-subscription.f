        _RSERVSUBV-PENDING @ 0< IF 0 EXIT THEN
        _RSERVSUBV-PENDING @ _RSERVSUBV-O @ RSERVSUB.CAPACITY @
            U< 0= IF 0 EXIT THEN
    THEN
