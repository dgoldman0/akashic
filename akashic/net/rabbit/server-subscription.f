: _RSERVSUB-DRIVE  ( owner mode -- item server-status )
    \ Refuse reentry before touching scratch used by an outer drive.
    _RSERVSUB-BUSY @ IF
        2DROP RSERVER-ITEM-NONE RSERVER-S-STATE EXIT
    THEN
    _RSERVSUBD-MODE ! DUP _RSERVSUBD-O !
    DUP RABBIT-SERVER-SUBSCRIPTIONS-VALID? 0= IF
        DROP RSERVER-ITEM-NONE RSERVER-S-INVALID EXIT
    THEN
    DROP
    RSERVER-ITEM-NONE _RSERVSUBD-ITEM !
    RSERVER-S-CALLBACK _RSERVSUBD-RS !
    0 _RSERVSUBD-THROW !
    _RSERVSUBD-O @ _RSERVSUB-ACTIVE ! -1 _RSERVSUB-BUSY !
    ['] _RSERVSUBD-INNER CATCH DUP _RSERVSUBD-THROW ! IF
        _RSERVSUBD-O @ _RSERVSUB-ROLLBACK-PENDING
        RSERVER-ITEM-NONE _RSERVSUBD-ITEM !
        RSERVER-S-CALLBACK _RSERVSUBD-RS !
    THEN
    0 _RSERVSUB-ACTIVE ! 0 _RSERVSUB-BUSY !
    _RSERVSUBD-RS @ _RSERVSUBD-O @ _RSERVSUB-RECORD-SERVER
    _RSERVSUBD-ITEM @ _RSERVSUBD-RS @ ;

