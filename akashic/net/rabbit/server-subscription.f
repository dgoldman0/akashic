    0 0 0 RSERVSUB-S-PENDING _RSERVSUBP-SET
    _RSERVSUBP-O @ RABBIT-SERVER-SUBSCRIPTIONS-VALID? 0= IF
        0 0 0 RSERVSUB-S-INVALID _RSERVSUBP-SET EXIT
    THEN
    _RSERVSUBP-O @ RSERVSUB.CAPACITY @ 0= IF EXIT THEN
    _RSERVSUBP-O @ RSERVSUB.NEXT-INDEX @ _RSERVSUBP-I !
    _RSERVSUBP-NEXT-INDEX
    _RSERVSUBP-I @ _RSERVSUBP-O @ _RSERVSUB-ENTRY@ _RSERVSUBP-E !
    _RSERVSUBP-E @ RSERVSUBE.STATE @ RSERVSUB-ENTRY-ACTIVE <> IF EXIT THEN
    _RSERVSUBP-E @ RSERVSUBE.CURSOR @ DUP RABBIT-U64-MAX = IF
        DROP RSERVSUB-ENTRY-TERMINAL _RSERVSUBP-E @ RSERVSUBE.STATE !
        _RSERVSUBP-E @ RABBIT-U64-MAX 0 RSERVSUB-S-OVERFLOW
            _RSERVSUBP-SET EXIT
    THEN
    1+ _RSERVSUBP-EXPECTED !
    \ Credit and Lane availability are protocol state, so refuse before the
    \ retryable journal callback.  Queue capacity remains an enqueue-time
    \ result and may legitimately cause the same exact suffix lookup again.
    _RSERVSUBP-E @ RSERVSUBE.LANE @
    _RSERVSUBP-O @ RSERVSUB.SERVER @
        RABBIT-SERVER-NEXT-EVENT-LANE-SEQ@
    _RSERVSUBP-SERVER-STATUS ! _RSERVSUBP-LANE-SEQ !
    _RSERVSUBP-SERVER-STATUS @ RSERVER-S-OK <> IF
        _RSERVSUBP-SERVER-STATUS @ _RSERVSUBP-E @ RSERVSUBE.DETAIL !
        _RSERVSUBP-SERVER-STATUS @ RSERVER-S-OVERFLOW = IF
            RSERVSUB-ENTRY-TERMINAL _RSERVSUBP-E @ RSERVSUBE.STATE !
        THEN
        _RSERVSUBP-O @ RSERVSUB.SERVER @ RSERVER.STATE @
            RSERVER-ST-ACTIVE <> IF
            _RSERVSUBP-E @ _RSERVSUBP-EXPECTED @ 0
                RSERVSUB-S-DISCONNECTED _RSERVSUBP-SET EXIT
        THEN
        _RSERVSUBP-E @ _RSERVSUBP-EXPECTED @ 0
        _RSERVSUBP-SERVER-STATUS @ _RSERVSUB-SERVER>STATUS
            _RSERVSUBP-SET EXIT
    THEN
    0 _RSERVSUBP-THROW !
    ['] _RSERVSUBP-SOURCE-INNER CATCH DUP _RSERVSUBP-THROW ! IF
        RSERVSUB-ENTRY-TERMINAL _RSERVSUBP-E @ RSERVSUBE.STATE !
        _RSERVSUBP-THROW @ _RSERVSUBP-E @ RSERVSUBE.DETAIL !
        _RSERVSUBP-E @ _RSERVSUBP-EXPECTED @ 0 RSERVSUB-S-CALLBACK
            _RSERVSUBP-SET EXIT
    THEN
    _RSERVSUBP-SOURCE @ RSERVSUB-SOURCE-VALID? 0= IF
        RSERVSUB-ENTRY-TERMINAL _RSERVSUBP-E @ RSERVSUBE.STATE !
        _RSERVSUBP-SOURCE @ _RSERVSUBP-E @ RSERVSUBE.DETAIL !
        _RSERVSUBP-E @ _RSERVSUBP-EXPECTED @ 0 RSERVSUB-S-CALLBACK
            _RSERVSUBP-SET EXIT
    THEN
    _RSERVSUBP-SOURCE @ _RSERVSUBP-E @ RSERVSUBE.LAST-SOURCE !
    _RSERVSUBP-SOURCE @ RSERVSUB-SOURCE-PENDING =
    _RSERVSUBP-SOURCE @ RSERVSUB-SOURCE-END = OR IF
        _RSERVSUBP-E @ _RSERVSUBP-EXPECTED @ 0 RSERVSUB-S-PENDING
            _RSERVSUBP-SET EXIT
    THEN
    _RSERVSUBP-SOURCE @ RSERVSUB-SOURCE-FAILED = IF
        RSERVSUB-ENTRY-TERMINAL _RSERVSUBP-E @ RSERVSUBE.STATE !
        _RSERVSUBP-E @ _RSERVSUBP-EXPECTED @ 0 RSERVSUB-S-CALLBACK
            _RSERVSUBP-SET EXIT
    THEN
    _RSERVSUBP-EVENT-SEQ @ _RSERVSUBP-EXPECTED @ <> IF
        RSERVSUB-ENTRY-TERMINAL _RSERVSUBP-E @ RSERVSUBE.STATE !
        _RSERVSUBP-EVENT-SEQ @ _RSERVSUBP-E @ RSERVSUBE.DETAIL !
        _RSERVSUBP-E @ _RSERVSUBP-EVENT-SEQ @ 0 RSERVSUB-S-GAP
            _RSERVSUBP-SET EXIT
    THEN
    _RSERVSUBP-VA @ _RSERVSUBP-VU @ _RSERVSUBP-SPAN? 0= IF
        RSERVSUB-ENTRY-TERMINAL _RSERVSUBP-E @ RSERVSUBE.STATE !
        _RSERVSUBP-E @ _RSERVSUBP-EVENT-SEQ @ 0 RSERVSUB-S-MESSAGE
            _RSERVSUBP-SET EXIT
    THEN
    _RSERVSUBP-BA @ _RSERVSUBP-BU @ _RSERVSUBP-SPAN? 0= IF
        RSERVSUB-ENTRY-TERMINAL _RSERVSUBP-E @ RSERVSUBE.STATE !
        _RSERVSUBP-E @ _RSERVSUBP-EVENT-SEQ @ 0 RSERVSUB-S-MESSAGE
            _RSERVSUBP-SET EXIT
    THEN
    _RSERVSUBP-I @ _RSERVSUBP-O @ _RSERVSUB-TARGET@
    _RSERVSUBP-E @ RSERVSUBE.TARGET-U @
    _RSERVSUBP-E @ RSERVSUBE.LANE @ _RSERVSUBP-EVENT-SEQ @
    _RSERVSUBP-VA @ _RSERVSUBP-VU @ _RSERVSUBP-BA @ _RSERVSUBP-BU @
    _RSERVSUBP-O @ RSERVSUB.SERVER @ RABBIT-SERVER-EVENT
    _RSERVSUBP-SERVER-STATUS ! _RSERVSUBP-LANE-SEQ !
    _RSERVSUBP-SERVER-STATUS @ RSERVER-S-OK = IF
        _RSERVSUBP-EVENT-SEQ @ _RSERVSUBP-E @ RSERVSUBE.CURSOR !
        _RSERVSUBP-LANE-SEQ @ _RSERVSUBP-E @ RSERVSUBE.LAST-LANE-SEQ !
        _RSERVSUBP-E @ _RSERVSUBP-EVENT-SEQ @
        _RSERVSUBP-LANE-SEQ @ RSERVSUB-S-EVENT _RSERVSUBP-SET EXIT
    THEN
    _RSERVSUBP-SERVER-STATUS @ _RSERVSUBP-E @ RSERVSUBE.DETAIL !
    _RSERVSUBP-SERVER-STATUS @ RSERVER-S-CREDIT = IF
        _RSERVSUBP-E @ _RSERVSUBP-EVENT-SEQ @ 0 RSERVSUB-S-CREDIT
            _RSERVSUBP-SET EXIT
    THEN
    _RSERVSUBP-SERVER-STATUS @ RSERVER-S-CAPACITY = IF
        _RSERVSUBP-E @ _RSERVSUBP-EVENT-SEQ @ 0 RSERVSUB-S-CAPACITY
            _RSERVSUBP-SET EXIT
    THEN
    _RSERVSUBP-SERVER-STATUS @ RSERVER-S-OVERFLOW = IF
        RSERVSUB-ENTRY-TERMINAL _RSERVSUBP-E @ RSERVSUBE.STATE !
        _RSERVSUBP-E @ _RSERVSUBP-EVENT-SEQ @ 0 RSERVSUB-S-OVERFLOW
            _RSERVSUBP-SET EXIT
    THEN
    _RSERVSUBP-O @ RSERVSUB.SERVER @ RSERVER.STATE @
        RSERVER-ST-ACTIVE <> IF
        _RSERVSUBP-E @ _RSERVSUBP-EVENT-SEQ @ 0
            RSERVSUB-S-DISCONNECTED _RSERVSUBP-SET EXIT
    THEN
    _RSERVSUBP-E @ _RSERVSUBP-EVENT-SEQ @ 0 RSERVSUB-S-SERVER
        _RSERVSUBP-SET ;

: _RSERVSUBP-CALL  ( -- ) _RSERVSUBP-INNER ;

: RABBIT-SERVER-SUBSCRIPTIONS-SERVICE
  ( owner -- entry|0 event-seq|0 lane-seq|0 status )
    \ A callback may attempt reentry with a foreign pointer.  Refuse it before
    \ replacing the outer service's live owner scratch.
    _RSERVSUB-BUSY @ IF DROP 0 0 0 RSERVSUB-S-STATE EXIT THEN
    DUP _RSERVSUBP-O !
    DROP -1 _RSERVSUB-BUSY !
    0 _RSERVSUBP-THROW !
    ['] _RSERVSUBP-CALL CATCH DUP _RSERVSUBP-THROW ! IF
        0 0 0 RSERVSUB-S-CALLBACK _RSERVSUBP-SET
    THEN
    0 _RSERVSUB-BUSY !
    _RSERVSUBP-O @ RABBIT-SERVER-SUBSCRIPTIONS-VALID? IF
        _RSERVSUBP-OUT-STATUS @ _RSERVSUBP-THROW @ _RSERVSUBP-O @
            _RSERVSUB-STATUS! DROP
    THEN
    _RSERVSUBP-OUT-E @ _RSERVSUBP-OUT-EVENT @
    _RSERVSUBP-OUT-LANE @ _RSERVSUBP-OUT-STATUS @ ;

