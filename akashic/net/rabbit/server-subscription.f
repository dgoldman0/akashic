: _RSERVSUB-RESOLVE-CANDIDATE  ( -- )
    _RSERVSUBD-O @ RSERVSUB.PENDING-INDEX @ DUP 0< IF DROP EXIT THEN
    0 _RSERVSUBD-COMMIT !
    _RSERVSUBD-RS @ RSERVER-S-OK =
    _RSERVSUBD-ITEM @ RSERVER-ITEM-RESPONSE = AND IF
        _RSERVSUBD-O @ RSERVSUB.SERVER @
            RABBIT-SERVER-LAST-RESPONSE-CODE@
        _RSERVSUBD-CODE-STATUS ! _RSERVSUBD-CODE !
        _RSERVSUBD-CODE-STATUS @ RSERVER-S-OK =
        _RSERVSUBD-CODE @ 200 = AND IF -1 _RSERVSUBD-COMMIT ! THEN
    THEN
    DUP _RSERVSUBD-O @ _RSERVSUB-ENTRY@ DUP RSERVSUBE.STATE @
        RSERVSUB-ENTRY-CANDIDATE <> IF
        2DROP _RSERVSUBD-O @ _RSERVSUB-ROLLBACK-PENDING EXIT
    THEN
    _RSERVSUBD-COMMIT @ IF
        RSERVSUB-ENTRY-ACTIVE SWAP RSERVSUBE.STATE !
        1 _RSERVSUBD-O @ RSERVSUB.COUNT +!
        DROP -1 _RSERVSUBD-O @ RSERVSUB.PENDING-INDEX ! EXIT
    THEN
    2DROP _RSERVSUBD-O @ _RSERVSUB-ROLLBACK-PENDING ;

