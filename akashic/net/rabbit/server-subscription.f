        DROP _RSERVSUBV-E @ _RSERVSUB-ENTRY-ZERO? EXIT
    THEN
    _RSERVSUBV-E @ RSERVSUBE.LANE @ DUP 0> 0= IF 2DROP 0 EXIT THEN
    RABBIT-LANE-MAX U> IF DROP 0 EXIT THEN
    _RSERVSUBV-E @ RSERVSUBE.TARGET-U @ DUP 0> 0= IF 2DROP 0 EXIT THEN
