: RABBIT-SERVER-SUBSCRIPTIONS-INIT
  ( entries capacity target-a target-slot-bytes server route-token source-xt source-context owner -- status )
    _RSERVSUB-BUSY @ IF
        2DROP 2DROP 2DROP 2DROP DROP RSERVSUB-S-STATE EXIT
    THEN
    _RSERVSUBI-O ! _RSERVSUBI-CONTEXT ! _RSERVSUBI-XT !
    _RSERVSUBI-TOKEN ! _RSERVSUBI-S ! _RSERVSUBI-TS !
    _RSERVSUBI-TA ! _RSERVSUBI-CAP ! _RSERVSUBI-ENTRIES !
    _RSERVSUBI-O @ 0= IF RSERVSUB-S-INVALID EXIT THEN
    _RSERVSUBI-O @ _RSERVSUB-CELL-ALIGNED? 0= IF
        RSERVSUB-S-INVALID EXIT
    THEN
    _RSERVSUBI-O @ RABBIT-SERVER-SUBSCRIPTIONS-SIZE
        MSPAN-NONWRAPPING? 0= IF RSERVSUB-S-INVALID EXIT THEN
    _RSERVSUBI-O @ RSERVSUB.MAGIC @ _RSERVSUB-MAGIC-VALUE = IF
        RSERVSUB-S-STATE EXIT
    THEN
    _RSERVSUBI-S @ RABBIT-SERVER-VALID? 0= IF RSERVSUB-S-SERVER EXIT THEN
    _RSERVSUBI-S @ RSERVER.STATE @ DUP RSERVER-ST-READY =
    SWAP RSERVER-ST-ACTIVE = OR 0= IF RSERVSUB-S-STATE EXIT THEN
    _RSERVSUBI-TOKEN @ 0= IF RSERVSUB-S-INVALID EXIT THEN
    _RSERVSUBI-XT @ 0= IF RSERVSUB-S-CALLBACK EXIT THEN
    _RSERVSUBI-CAP @ RABBIT-SERVER-SUBSCRIPTION-CAPACITY-VALID? 0= IF
        RSERVSUB-S-INVALID EXIT
    THEN
    _RSERVSUBI-TS @ 0< IF RSERVSUB-S-INVALID EXIT THEN
    _RSERVSUBI-CAP @ RABBIT-SERVER-SUBSCRIPTION-ENTRY-BYTES
        _RSERVSUBI-EU !
    _RSERVSUBI-CAP @ _RSERVSUBI-TS @ _RSERVSUB-MUL? 0= IF
        DROP RSERVSUB-S-INVALID EXIT
    THEN _RSERVSUBI-TU !
    _RSERVSUBI-CAP @ 0= IF
        _RSERVSUBI-ENTRIES @ _RSERVSUBI-TA @ OR
        _RSERVSUBI-TS @ OR IF RSERVSUB-S-INVALID EXIT THEN
    ELSE
        _RSERVSUBI-ENTRIES @ 0= IF RSERVSUB-S-INVALID EXIT THEN
        _RSERVSUBI-ENTRIES @ _RSERVSUB-CELL-ALIGNED? 0= IF
            RSERVSUB-S-INVALID EXIT
        THEN
        _RSERVSUBI-ENTRIES @ _RSERVSUBI-EU @
            MSPAN-NONWRAPPING? 0= IF RSERVSUB-S-INVALID EXIT THEN
        _RSERVSUBI-TS @ 0> 0= _RSERVSUBI-TA @ 0= OR IF
            RSERVSUB-S-INVALID EXIT
        THEN
        _RSERVSUBI-TA @ _RSERVSUBI-TU @
            MSPAN-NONWRAPPING? 0= IF RSERVSUB-S-INVALID EXIT THEN
    THEN
    _RSERVSUBI-O @ RABBIT-SERVER-SUBSCRIPTIONS-SIZE _RSERVSUBI-S @
        RABBIT-SERVER-GRAPH-SPAN-OVERLAP? IF RSERVSUB-S-ALIAS EXIT THEN
    _RSERVSUBI-EU @ IF
        _RSERVSUBI-O @ RABBIT-SERVER-SUBSCRIPTIONS-SIZE
            _RSERVSUBI-ENTRIES @ _RSERVSUBI-EU @
            MSPAN-OVERLAP? IF RSERVSUB-S-ALIAS EXIT THEN
        _RSERVSUBI-ENTRIES @ _RSERVSUBI-EU @ _RSERVSUBI-S @
            RABBIT-SERVER-GRAPH-SPAN-OVERLAP? IF
            RSERVSUB-S-ALIAS EXIT
        THEN
    THEN
    _RSERVSUBI-TU @ IF
        _RSERVSUBI-O @ RABBIT-SERVER-SUBSCRIPTIONS-SIZE
            _RSERVSUBI-TA @ _RSERVSUBI-TU @
            MSPAN-OVERLAP? IF RSERVSUB-S-ALIAS EXIT THEN
        _RSERVSUBI-TA @ _RSERVSUBI-TU @ _RSERVSUBI-S @
            RABBIT-SERVER-GRAPH-SPAN-OVERLAP? IF
            RSERVSUB-S-ALIAS EXIT
        THEN
    THEN
    _RSERVSUBI-CAP @ IF
        _RSERVSUBI-ENTRIES @ _RSERVSUBI-EU @
            _RSERVSUBI-TA @ _RSERVSUBI-TU @
            MSPAN-OVERLAP? IF RSERVSUB-S-ALIAS EXIT THEN
    THEN

    _RSERVSUBI-O @ RABBIT-SERVER-SUBSCRIPTIONS-SIZE 0 FILL
    _RSERVSUBI-EU @ IF _RSERVSUBI-ENTRIES @ _RSERVSUBI-EU @ 0 FILL THEN
    _RSERVSUBI-TU @ IF _RSERVSUBI-TA @ _RSERVSUBI-TU @ 0 FILL THEN
    _RSERVSUB-MAGIC-VALUE _RSERVSUBI-O @ RSERVSUB.MAGIC !
    _RSERVSUB-ABI-VERSION _RSERVSUBI-O @ RSERVSUB.ABI !
    RABBIT-SERVER-SUBSCRIPTIONS-SIZE _RSERVSUBI-O @ RSERVSUB.BYTES !
    RSERVSUB-S-OK _RSERVSUBI-O @ RSERVSUB.LAST-STATUS !
    _RSERVSUBI-S @ _RSERVSUBI-O @ RSERVSUB.SERVER !
    _RSERVSUBI-ENTRIES @ _RSERVSUBI-O @ RSERVSUB.ENTRIES !
    _RSERVSUBI-CAP @ _RSERVSUBI-O @ RSERVSUB.CAPACITY !
    _RSERVSUBI-TA @ _RSERVSUBI-O @ RSERVSUB.TARGET-A !
    _RSERVSUBI-TS @ _RSERVSUBI-O @ RSERVSUB.TARGET-SLOT-BYTES !
    _RSERVSUBI-XT @ _RSERVSUBI-O @ RSERVSUB.SOURCE-XT !
    _RSERVSUBI-CONTEXT @ _RSERVSUBI-O @ RSERVSUB.SOURCE-CONTEXT !
