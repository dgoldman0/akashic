: _RSERVSUBH-WIPE-CANDIDATE  ( -- )
    _RSERVSUBH-I @ 0< IF EXIT THEN
    _RSERVSUBH-I @ _RSERVSUBH-O @ _RSERVSUB-TARGET@
        _RSERVSUBH-O @ RSERVSUB.TARGET-SLOT-BYTES @ 0 FILL
    _RSERVSUBH-E @ IF
        _RSERVSUBH-E @ RABBIT-SERVER-SUBSCRIPTION-ENTRY-SIZE 0 FILL
    THEN
    -1 _RSERVSUBH-I ! 0 _RSERVSUBH-E ! ;

: _RSERVSUBH-BUILD  ( code label-a label-u -- flag )
    _RSERVSUBH-B @ RMSGB-RESET RMSGB-S-OK <> IF 2DROP DROP 0 EXIT THEN
    _RSERVSUBH-LANE @ _RSERVSUBH-XA @ _RSERVSUBH-XU @ _RSERVSUBH-B @
        RMSGB-BEGIN-RESPONSE RMSGB-S-OK <> IF 0 EXIT THEN
    _RSERVSUBH-B @ RMSGB-SEAL RMSGB-S-OK = ;

: _RSERVSUBH-RESPOND  ( code label-a label-u -- )
    _RSERVSUBH-BUILD IF
        RSERVER-HANDLER-RESPONSE
    ELSE
        RSERVER-HANDLER-FAILED
    THEN _RSERVSUBH-OUTCOME ! ;

: _RSERVSUBH-FIELDS?  ( -- flag )
    _RSERVSUBH-F @ RMSG-LANE@
        _RSERVSUBH-MS ! _RSERVSUBH-PRESENT ! _RSERVSUBH-LANE !
    _RSERVSUBH-MS @ IF 0 EXIT THEN
    _RSERVSUBH-PRESENT @ 0= IF 0 EXIT THEN
    _RSERVSUBH-F @ RMSG-TXN$
        _RSERVSUBH-MS ! _RSERVSUBH-PRESENT !
        _RSERVSUBH-XU ! _RSERVSUBH-XA !
    _RSERVSUBH-MS @ IF 0 EXIT THEN
    _RSERVSUBH-PRESENT @ 0= IF 0 EXIT THEN
    _RSERVSUBH-F @ RBF-ARGS$ _RSERVSUBH-TU ! _RSERVSUBH-TA !
    0 _RSERVSUBH-CURSOR !
    _RSERVSUBH-F @ RMSG-SINCE@
        _RSERVSUBH-MS ! _RSERVSUBH-PRESENT ! _RSERVSUBH-CURSOR !
    _RSERVSUBH-MS @ IF 0 EXIT THEN
    _RSERVSUBH-PRESENT @ 0= IF 0 _RSERVSUBH-CURSOR ! THEN
    -1 ;

: _RSERVSUBH-FIND-EMPTY  ( -- flag )
    -1 _RSERVSUBH-I ! 0 _RSERVSUBH-E !
    _RSERVSUBH-O @ RSERVSUB.CAPACITY @ 0 ?DO
        I _RSERVSUBH-O @ _RSERVSUB-ENTRY@ DUP RSERVSUBE.STATE @
            RSERVSUB-ENTRY-EMPTY = IF
            _RSERVSUBH-E ! I _RSERVSUBH-I ! -1 UNLOOP EXIT
        THEN
        DROP
    LOOP
    0 ;

: _RSERVSUBH-INNER  ( -- )
    RSERVER-HANDLER-FAILED _RSERVSUBH-OUTCOME !
    _RSERVSUB-ACTIVE @ DUP 0= IF DROP EXIT THEN _RSERVSUBH-O !
    _RSERVSUB-BUSY @ 0= IF EXIT THEN
    _RSERVSUBH-TOKEN @ _RSERVSUBH-O @ RSERVSUB.ROUTE-TOKEN @ <> IF
        EXIT
    THEN
    _RSERVSUBH-O @ RABBIT-SERVER-SUBSCRIPTIONS-VALID? 0= IF EXIT THEN
    _RSERVSUBH-KIND @ RMSG-KIND-SUBSCRIBE <> IF EXIT THEN
    _RSERVSUBH-FIELDS? 0= IF EXIT THEN
    _RSERVSUBH-LANE @ DUP 0> 0= SWAP RABBIT-LANE-MAX U> OR IF
        400 S" APPLICATION LANE REQUIRED" _RSERVSUBH-RESPOND EXIT
    THEN
    _RSERVSUBH-TA @ _RSERVSUBH-TU @ _RSERVSUB-SELECTOR? 0= IF
        400 S" INVALID SELECTOR" _RSERVSUBH-RESPOND EXIT
    THEN
    _RSERVSUBH-TU @ _RSERVSUBH-O @ RSERVSUB.TARGET-SLOT-BYTES @ U> IF
        413 S" SELECTOR TOO LARGE" _RSERVSUBH-RESPOND EXIT
    THEN
    _RSERVSUBH-TA @ _RSERVSUBH-TU @ _RSERVSUBH-LANE @ _RSERVSUBH-O @
        _RSERVSUB-FIND IF
        2DROP 409 S" ALREADY SUBSCRIBED" _RSERVSUBH-RESPOND EXIT
    THEN
    2DROP
    _RSERVSUBH-FIND-EMPTY 0= IF
        507 S" SUBSCRIPTION CAPACITY" _RSERVSUBH-RESPOND EXIT
    THEN
    _RSERVSUBH-I @ _RSERVSUBH-O @ _RSERVSUB-TARGET@
        _RSERVSUBH-O @ RSERVSUB.TARGET-SLOT-BYTES @ 0 FILL
    _RSERVSUBH-E @ RABBIT-SERVER-SUBSCRIPTION-ENTRY-SIZE 0 FILL
    _RSERVSUBH-TA @ _RSERVSUBH-I @ _RSERVSUBH-O @ _RSERVSUB-TARGET@
        _RSERVSUBH-TU @ MOVE
    200 S" SUBSCRIBED" _RSERVSUBH-BUILD 0= IF
        _RSERVSUBH-WIPE-CANDIDATE EXIT
    THEN
    _RSERVSUBH-O @ RSERVSUB.SERVER @
        RABBIT-SERVER-HELD-APP-LANE-ENSURE DUP _RSERVSUBH-RS !
    RSERVER-S-OK <> IF
        _RSERVSUBH-WIPE-CANDIDATE
        _RSERVSUBH-RS @ RSERVER-S-CAPACITY = IF
            507 S" LANE CAPACITY" _RSERVSUBH-RESPOND
        ELSE
            409 S" LANE UNAVAILABLE" _RSERVSUBH-RESPOND
        THEN
        EXIT
    THEN
    _RSERVSUBH-LANE @ _RSERVSUBH-E @ RSERVSUBE.LANE !
    _RSERVSUBH-TU @ _RSERVSUBH-E @ RSERVSUBE.TARGET-U !
    _RSERVSUBH-CURSOR @ _RSERVSUBH-E @ RSERVSUBE.CURSOR !
    RSERVSUB-SOURCE-PENDING _RSERVSUBH-E @ RSERVSUBE.LAST-SOURCE !
    RSERVSUB-ENTRY-CANDIDATE _RSERVSUBH-E @ RSERVSUBE.STATE !
    _RSERVSUBH-I @ _RSERVSUBH-O @ RSERVSUB.PENDING-INDEX !
    -1 _RSERVSUBH-I ! 0 _RSERVSUBH-E !
    RSERVER-HANDLER-RESPONSE _RSERVSUBH-OUTCOME ! ;

: _RSERVSUBH-CALL  ( -- ) _RSERVSUBH-INNER ;

: _RSERVSUBH-CLEAR  ( -- )
