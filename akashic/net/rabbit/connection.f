    _RTXQV-SLOT @ RTXS.KIND @ RMSG-KIND-INVALID = IF 0 EXIT THEN
    _RTXQV-SLOT @ RTXS.FLAGS @ DUP 0< IF DROP 0 EXIT THEN
    _RTXQ-SLOTF-KNOWN INVERT AND IF 0 EXIT THEN
    _RTXQV-SLOT @ RTXS.STATE @ RTXQ-SLOT-WAIT-ACK = IF
        _RTXQV-SLOT @ RTXS.FLAGS @ _RTXQ-SLOTF-EVENT AND 0<>
