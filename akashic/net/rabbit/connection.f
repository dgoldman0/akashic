            RCONN-S-PROTOCOL EXIT
        THEN
        _RCONNX-FRAME @ _RCONN-HANDSHAKE-FIELDS
        _RCONNX-RS ! _RCONNX-VALUE !
        _RCONNX-RS @ IF RCONN-S-MESSAGE EXIT THEN
        _RCONNX-C @ RCONN.FLAGS DUP @ _RCONN-F-RX-HANDSHAKE OR SWAP !
        RCONN-S-OK EXIT
    THEN
    RABBIT-ST-ESTABLISHED <> IF RCONN-S-SESSION EXIT THEN
    _RCONNX-KIND @ RMSG-KIND-HELLO = IF RCONN-S-PROTOCOL EXIT THEN
    RCONN-S-OK ;

: _RCONN-RX-KIND-FIELDS  ( -- connection-status )
    0 _RCONNX-LANE ! 0 _RCONNX-SEQ ! 0 _RCONNX-VALUE !
    0 _RCONNX-EXPECTED ! RABBIT-INBOUND-NONE _RCONNX-DISPOSITION !
    _RCONNX-FRAME @ RMSG-LANE@
    _RCONNX-RS ! _RCONNX-PRESENT ! _RCONNX-LANE !
    _RCONNX-RS @ IF RCONN-S-MESSAGE EXIT THEN
    _RCONNX-KIND @ RMSG-KIND-EVENT = IF
        _RCONNX-PRESENT @ 0= IF RCONN-S-MESSAGE EXIT THEN
        _RCONNX-FRAME @ RMSG-SEQ@
        _RCONNX-RS ! _RCONNX-PRESENT ! _RCONNX-SEQ !
        _RCONNX-RS @ IF RCONN-S-MESSAGE EXIT THEN
        _RCONNX-PRESENT @ 0= IF RCONN-S-MESSAGE EXIT THEN
        _RCONNX-LANE @ _RCONNX-SEQ @ _RCONNX-C @ RCONN.SESSION @
            RABBIT-SESSION-INBOUND-CLASSIFY
        _RCONNX-RS ! _RCONNX-DISPOSITION ! _RCONNX-EXPECTED !
        _RCONNX-RS @ RABBIT-S-CREDIT = IF RCONN-S-PROTOCOL EXIT THEN
        _RCONNX-RS @ IF RCONN-S-SESSION EXIT THEN
        RCONN-S-OK EXIT
    THEN
    _RCONNX-KIND @ RMSG-KIND-ACK = IF
        _RCONNX-FRAME @ RMSG-ACK@
        _RCONNX-RS ! _RCONNX-PRESENT ! _RCONNX-VALUE !
        _RCONNX-RS @ IF RCONN-S-MESSAGE EXIT THEN
        _RCONNX-PRESENT @ 0= IF RCONN-S-MESSAGE EXIT THEN
    THEN
    _RCONNX-KIND @ RMSG-KIND-CREDIT = IF
        _RCONNX-FRAME @ RMSG-CREDIT@
        _RCONNX-RS ! _RCONNX-PRESENT ! _RCONNX-VALUE !
        _RCONNX-RS @ IF RCONN-S-MESSAGE EXIT THEN
        _RCONNX-PRESENT @ 0= IF RCONN-S-MESSAGE EXIT THEN
    THEN
    RCONN-S-OK ;

: _RCONN-RX-HOLD  ( connection -- status )
    DUP _RCONNX-C ! RCONN.PARSER @ DUP _RCONNX-FRAME !
    RMSG-ADMIT _RCONNX-RS ! _RCONNX-KIND !
    _RCONNX-RS @ IF
        RCONN-S-MESSAGE RCONN-DETAIL-MESSAGE _RCONNX-RS @
            _RCONNX-C @ _RCONN-FAIL EXIT
    THEN
    _RCONN-RX-KIND-FIELDS DUP _RCONNX-RS ! IF
        _RCONNX-RS @ RCONN-S-MESSAGE = IF
            RCONN-S-MESSAGE RCONN-DETAIL-MESSAGE RMSG-S-VALUE
        ELSE
            RCONN-S-PROTOCOL RCONN-DETAIL-SESSION _RCONNX-RS @
        THEN _RCONNX-C @ _RCONN-FAIL EXIT
    THEN
    _RCONN-RX-STATE-ADMIT DUP _RCONNX-RS ! IF
        _RCONNX-RS @ RCONN-S-MESSAGE = IF
            RCONN-S-MESSAGE RCONN-DETAIL-MESSAGE RMSG-S-CONFLICT
        ELSE
            RCONN-S-PROTOCOL RCONN-DETAIL-SESSION RABBIT-S-STATE
        THEN _RCONNX-C @ _RCONN-FAIL EXIT
    THEN
    _RCONNX-KIND @ _RCONNX-C @ RCONN.HELD-KIND !
    _RCONNX-LANE @ _RCONNX-C @ RCONN.HELD-LANE !
    _RCONNX-SEQ @ _RCONNX-C @ RCONN.HELD-SEQ !
    _RCONNX-EXPECTED @ _RCONNX-C @ RCONN.HELD-EXPECTED !
    _RCONNX-DISPOSITION @ _RCONNX-C @ RCONN.HELD-DISPOSITION !
    _RCONNX-VALUE @ _RCONNX-C @ RCONN.HELD-VALUE !
    _RCONNX-C @ RCONN.FLAGS DUP @ _RCONN-F-RX-HELD OR SWAP !
    RCONN-S-RX-READY ;

: _RCONN-RX-FEED-CARRY  ( connection -- status )
    DUP _RCONNX-C !
    DUP RCONN.RX-USED @ OVER RCONN.RX-OFF @ = IF
        DUP 0 SWAP RCONN.RX-OFF !
        0 SWAP RCONN.RX-USED !
        RCONN-S-OK EXIT
    THEN
    DROP
    _RCONNX-C @ RCONN.RX-A @ _RCONNX-C @ RCONN.RX-OFF @ +
    _RCONNX-C @ RCONN.RX-USED @ _RCONNX-C @ RCONN.RX-OFF @ -
    _RCONNX-C @ RCONN.PARSER @ RBF-FEED
        _RCONNX-RS ! _RCONNX-N !
    _RCONNX-N @ _RCONNX-C @ RCONN.RX-OFF +!
    _RCONNX-RS @ RBF-S-READY = IF
        _RCONNX-C @ _RCONN-RX-HOLD EXIT
    THEN
    _RCONNX-RS @ RBF-S-NEED-MORE = IF
        _RCONNX-C @ RCONN.RX-OFF @ _RCONNX-C @ RCONN.RX-USED @ = IF
            0 _RCONNX-C @ RCONN.RX-OFF !
            0 _RCONNX-C @ RCONN.RX-USED !
        THEN
        RCONN-S-OK EXIT
    THEN
    RCONN-S-FRAME RCONN-DETAIL-FRAME _RCONNX-RS @
        _RCONNX-C @ _RCONN-FAIL ;

: _RCONN-RX-COMPACT  ( connection -- )
    DUP _RCONNX-C !
    RCONN.RX-USED @ _RCONNX-C @ RCONN.RX-OFF @ - _RCONNX-U !
    _RCONNX-U @ 0= IF
        0 _RCONNX-C @ RCONN.RX-OFF !
        0 _RCONNX-C @ RCONN.RX-USED ! EXIT
    THEN
    _RCONNX-C @ RCONN.RX-A @ _RCONNX-C @ RCONN.RX-OFF @ +
    _RCONNX-C @ RCONN.RX-A @ _RCONNX-U @ CMOVE
    0 _RCONNX-C @ RCONN.RX-OFF !
    _RCONNX-U @ _RCONNX-C @ RCONN.RX-USED ! ;

: _RCONN-RX-EOF  ( connection -- status )
    DUP _RCONNX-C ! RCONN.PARSER @ RBF-EOF DUP _RCONNX-RS !
    RBF-S-OK <> IF
        RCONN-S-FRAME RCONN-DETAIL-FRAME _RCONNX-RS @
            _RCONNX-C @ _RCONN-FAIL EXIT
    THEN
    _RCONNX-C @ RCONN.SESSION @ RABBIT-SESSION-CLOSE DUP _RCONNX-RS !
    DUP RABBIT-S-PENDING = IF
        DROP RCONN-ST-CLOSING _RCONNX-C @ RCONN.STATE !
    ELSE
        RABBIT-S-OK = IF
            RCONN-ST-CLOSED _RCONNX-C @ RCONN.STATE !
        ELSE
            RCONN-S-SESSION RCONN-DETAIL-SESSION _RCONNX-RS @
                _RCONNX-C @ _RCONN-FAIL EXIT
        THEN
    THEN
    RCONN-S-EOF _RCONNX-C @ _RCONN-PUBLISH-STATUS ;

: _RCONN-RX-PUMP  ( connection -- status )
    DUP _RCONNX-C ! RCONN.FLAGS @ _RCONN-F-RX-HELD AND IF
        RCONN-S-RX-READY EXIT
    THEN
    _RCONNX-C @ RCONN.RX-OFF @ _RCONNX-C @ RCONN.RX-USED @ U< IF
        _RCONNX-C @ _RCONN-RX-FEED-CARRY DUP RCONN-S-OK <> IF EXIT THEN
        DROP
    THEN
    _RCONNX-C @ _RCONN-RX-COMPACT
    _RCONNX-C @ RCONN.RX-A @ _RCONNX-C @ RCONN.RX-USED @ +
        _RCONNX-A !
    _RCONNX-C @ RCONN.RX-CAP @ _RCONNX-C @ RCONN.RX-USED @ -
        _RCONNX-U !
    _RCONNX-A @ _RCONNX-U @
        _RCONNX-C @ RCONN.SESSION @ RABBIT-SESSION-PORT@
        NIO-RECV _RCONNX-IOS ! _RCONNX-N !
    _RCONNX-IOS @ NIO-S-CANCELLED = IF
        _RCONNX-IOS @ _RCONNX-C @ _RCONN-CANCELLED EXIT
    THEN
    _RCONNX-IOS @ NIO-S-FAILED = IF
        RCONN-S-IO RCONN-DETAIL-IO _RCONNX-IOS @
            _RCONNX-C @ _RCONN-FAIL EXIT
    THEN
    _RCONNX-IOS @ NIO-S-EOF = IF _RCONNX-C @ _RCONN-RX-EOF EXIT THEN
    _RCONNX-N @ 0= IF RCONN-S-OK EXIT THEN
    _RCONNX-N @ _RCONNX-C @ RCONN.RX-USED +!
    _RCONNX-C @ _RCONN-RX-FEED-CARRY ;

\ =====================================================================
\  RX loan, exact session commit, cumulative ACK release, and drop
\ =====================================================================

VARIABLE _RCONNACK-C
VARIABLE _RCONNACK-Q
VARIABLE _RCONNACK-SLOT
VARIABLE _RCONNACK-LANE
VARIABLE _RCONNACK-ACK

: _RCONN-RELEASE-ACKED  ( lane ack connection -- )
    _RCONNACK-C ! _RCONNACK-ACK ! _RCONNACK-LANE !
    _RCONNACK-C @ RCONN.DATA-Q @ DUP _RCONNACK-Q ! RTXQ.CAP @ 0 ?DO
        I _RCONNACK-Q @ _RTXQ-SLOT@ DUP _RCONNACK-SLOT !
        RTXS.STATE @ RTXQ-SLOT-WAIT-ACK = IF
            _RCONNACK-SLOT @ RTXS.LANE @ _RCONNACK-LANE @ =
            _RCONNACK-SLOT @ RTXS.SEQ @ _RCONNACK-ACK @ U> 0= AND IF
                I _RCONNACK-Q @ _RTXQ-SLOT-WIPE
                -1 _RCONNACK-Q @ RTXQ.COUNT +!
            THEN
        THEN
    LOOP ;

: _RCONN-RX-RELEASE  ( connection -- status )
    DUP _RCONNX-C ! RCONN.PARSER @ DUP RBF.BUFFER @
        OVER RBF-PARSER-USED@ 0 FILL
    RBF-PARSER-RESET DUP _RCONNX-RS ! IF
        RCONN-S-FRAME RCONN-DETAIL-FRAME _RCONNX-RS @
            _RCONNX-C @ _RCONN-FAIL EXIT
    THEN
    _RCONNX-C @ RCONN.FLAGS DUP @
        _RCONN-F-RX-HELD _RCONN-F-RX-LOANED OR
        _RCONN-F-RX-HANDSHAKE OR INVERT AND SWAP !
    RMSG-KIND-INVALID _RCONNX-C @ RCONN.HELD-KIND !
    0 _RCONNX-C @ RCONN.HELD-LANE !
    0 _RCONNX-C @ RCONN.HELD-SEQ !
    0 _RCONNX-C @ RCONN.HELD-EXPECTED !
    RABBIT-INBOUND-NONE _RCONNX-C @ RCONN.HELD-DISPOSITION !
    0 _RCONNX-C @ RCONN.HELD-VALUE !
    RCONN-S-OK ;

: RABBIT-CONNECTION-RX-LOAN
  ( connection -- frame kind lane seq expected disposition status )
    DUP RABBIT-CONNECTION-VALID? 0= IF
        DROP 0 RMSG-KIND-INVALID 0 0 0 RABBIT-INBOUND-NONE
            RCONN-S-INVALID EXIT
    THEN
    DUP RCONN.STATE @ RCONN-ST-OPEN <> IF
        DROP 0 RMSG-KIND-INVALID 0 0 0 RABBIT-INBOUND-NONE
            RCONN-S-STATE EXIT
    THEN
    DUP RCONN.FLAGS @ _RCONN-F-RX-HELD AND 0= IF
        DROP 0 RMSG-KIND-INVALID 0 0 0 RABBIT-INBOUND-NONE
            RCONN-S-PENDING EXIT
    THEN
    DUP RCONN.FLAGS @ _RCONN-F-RX-LOANED AND IF
        DROP 0 RMSG-KIND-INVALID 0 0 0 RABBIT-INBOUND-NONE
            RCONN-S-STATE EXIT
    THEN
    DUP _RCONNX-C ! RCONN.FLAGS DUP @ _RCONN-F-RX-LOANED OR SWAP !
    _RCONNX-C @ RCONN.PARSER @
    _RCONNX-C @ RCONN.HELD-KIND @
    _RCONNX-C @ RCONN.HELD-LANE @
    _RCONNX-C @ RCONN.HELD-SEQ @
    _RCONNX-C @ RCONN.HELD-EXPECTED @
    _RCONNX-C @ RCONN.HELD-DISPOSITION @
    RCONN-S-OK ;

: _RCONN-RX-COMMIT-SESSION  ( connection -- rabbit-status )
    DUP _RCONNX-C ! RCONN.FLAGS @ _RCONN-F-RX-HANDSHAKE AND IF
        _RCONNX-C @ RCONN.HELD-VALUE @
            _RCONNX-C @ RCONN.SESSION @ RABBIT-SESSION-HELLO-ACCEPT
        NIP EXIT
    THEN
    _RCONNX-C @ RCONN.HELD-KIND @ RMSG-KIND-EVENT = IF
        _RCONNX-C @ RCONN.HELD-DISPOSITION @ RABBIT-INBOUND-GAP = IF
            RABBIT-S-SEQUENCE EXIT
        THEN
        _RCONNX-C @ RCONN.HELD-DISPOSITION @
            RABBIT-INBOUND-DUPLICATE = IF RABBIT-S-OK EXIT THEN
        _RCONNX-C @ RCONN.HELD-LANE @
            _RCONNX-C @ RCONN.HELD-SEQ @
            _RCONNX-C @ RCONN.SESSION @ RABBIT-SESSION-INBOUND-COMMIT
        EXIT
    THEN
    _RCONNX-C @ RCONN.HELD-KIND @ RMSG-KIND-ACK = IF
        _RCONNX-C @ RCONN.HELD-LANE @
            _RCONNX-C @ RCONN.HELD-VALUE @
            _RCONNX-C @ RCONN.SESSION @ RABBIT-SESSION-ACK
        DUP IF EXIT THEN DROP
        _RCONNX-C @ RCONN.HELD-LANE @
            _RCONNX-C @ RCONN.HELD-VALUE @ _RCONNX-C @
            _RCONN-RELEASE-ACKED
        RABBIT-S-OK EXIT
    THEN
    _RCONNX-C @ RCONN.HELD-KIND @ RMSG-KIND-CREDIT = IF
        _RCONNX-C @ RCONN.HELD-LANE @
            _RCONNX-C @ RCONN.HELD-VALUE @
            _RCONNX-C @ RCONN.SESSION @ RABBIT-SESSION-CREDIT+ EXIT
    THEN
    RABBIT-S-OK ;

: RABBIT-CONNECTION-RX-COMMIT  ( connection -- status )
    DUP RABBIT-CONNECTION-VALID? 0= IF DROP RCONN-S-INVALID EXIT THEN
    DUP _RCONNX-C ! RCONN.FLAGS @ _RCONN-F-RX-LOANED AND 0= IF
        RCONN-S-STATE EXIT
    THEN
    _RCONNX-C @ _RCONN-RX-COMMIT-SESSION DUP _RCONNX-RS ! IF
        _RCONNX-RS @ _RCONNX-C @ RCONN.DETAIL-STATUS !
        RCONN-DETAIL-SESSION _RCONNX-C @ RCONN.DETAIL-DOMAIN !
        RCONN-S-SESSION DUP _RCONNX-C @ RCONN.LAST-STATUS ! EXIT
    THEN
    _RCONNX-C @ _RCONN-RX-RELEASE DUP IF EXIT THEN DROP
    RCONN-S-OK _RCONNX-C @ _RCONN-PUBLISH-STATUS ;

: RABBIT-CONNECTION-RX-DROP  ( connection -- status )
    DUP RABBIT-CONNECTION-VALID? 0= IF DROP RCONN-S-INVALID EXIT THEN
    DUP _RCONNX-C ! RCONN.FLAGS @ _RCONN-F-RX-LOANED AND 0= IF
        RCONN-S-STATE EXIT
    THEN
    _RCONNX-C @ _RCONN-RX-RELEASE DUP IF EXIT THEN DROP
    RCONN-S-OK _RCONNX-C @ _RCONN-PUBLISH-STATUS ;

\ =====================================================================
\  Cooperative pump and exact teardown
\ =====================================================================

VARIABLE _RCONNC-C
VARIABLE _RCONNC-RS
VARIABLE _RCONNC-RESULT

: _RCONN-CLEAN-STORAGE  ( connection -- status )
    DUP _RCONNC-C ! RCONN.FLAGS @ _RCONN-F-CLEANED AND IF
        RCONN-S-OK EXIT
    THEN
    _RCONNC-C @ RCONN.PARSER @ DUP RBF-PARSER-USED@ DUP IF
        OVER RBF.BUFFER @ SWAP 0 FILL
    ELSE
        DROP
    THEN
    RBF-PARSER-RESET DUP _RCONNC-RS ! IF
        RCONN-S-FRAME EXIT
    THEN
    _RCONNC-C @ RCONN.RX-A @ _RCONNC-C @ RCONN.RX-CAP @ 0 FILL
    _RCONNC-C @ RCONN.CONTROL-Q @ _RTXQ-WIPE
    _RCONNC-C @ RCONN.DATA-Q @ _RTXQ-WIPE
    _RCONNC-C @ _RCONN-CLEAR-ACTIVE
    0 _RCONNC-C @ RCONN.RX-OFF !
    0 _RCONNC-C @ RCONN.RX-USED !
    RMSG-KIND-INVALID _RCONNC-C @ RCONN.HELD-KIND !
    0 _RCONNC-C @ RCONN.HELD-LANE !
    0 _RCONNC-C @ RCONN.HELD-SEQ !
    0 _RCONNC-C @ RCONN.HELD-EXPECTED !
    RABBIT-INBOUND-NONE _RCONNC-C @ RCONN.HELD-DISPOSITION !
    0 _RCONNC-C @ RCONN.HELD-VALUE !
    _RCONN-F-CLEANED _RCONNC-C @ RCONN.FLAGS !
    RCONN-S-OK ;

: RABBIT-CONNECTION-RX-READY?  ( connection -- flag )
    DUP RABBIT-CONNECTION-VALID? 0= IF DROP 0 EXIT THEN
    RCONN.FLAGS @ _RCONN-F-RX-HELD AND 0<> ;

: RABBIT-CONNECTION-PUMP  ( connection -- status )
    DUP RABBIT-CONNECTION-VALID? 0= IF DROP RCONN-S-INVALID EXIT THEN
    DUP _RCONNC-C ! RCONN.STATE @ RCONN-ST-OPEN <> IF
        RCONN-S-STATE _RCONNC-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN
    _RCONNC-C @ RCONN.SESSION @ RABBIT-SESSION-PORT@ NIO-POLL
    _RCONNC-C @ _RCONN-TX-PUMP DUP _RCONNC-RESULT !
    RCONN-S-OK <> IF
        _RCONNC-C @ _RCONN-CLEAN-STORAGE DROP
        _RCONNC-RESULT @ EXIT
    THEN
    _RCONNC-C @ _RCONN-RX-PUMP DUP _RCONNC-RESULT !
    DUP RCONN-S-OK = IF
        DROP RCONN-S-PENDING _RCONNC-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN
    DUP RCONN-S-RX-READY = IF
        _RCONNC-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN
    DUP RCONN-S-EOF = IF
        _RCONNC-C @ _RCONN-CLEAN-STORAGE DROP
        _RCONNC-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN
    DROP _RCONNC-C @ _RCONN-CLEAN-STORAGE DROP
    _RCONNC-RESULT @ ;

: RABBIT-CONNECTION-CLOSE  ( connection -- status )
    DUP RABBIT-CONNECTION-VALID? 0= IF DROP RCONN-S-INVALID EXIT THEN
    DUP _RCONNC-C ! RCONN.STATE @ DUP RCONN-ST-CLOSED = IF
        DROP RCONN-S-OK _RCONNC-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN
    DUP RCONN-ST-CANCELLED = IF
        DROP RCONN-S-CANCELLED _RCONNC-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN
    DROP
    _RCONNC-C @ _RCONN-CLEAN-STORAGE DUP IF
        RCONN-S-FRAME RCONN-DETAIL-FRAME ROT
            _RCONNC-C @ _RCONN-FAIL EXIT
    THEN DROP
    _RCONNC-C @ RCONN.SESSION @ RABBIT-SESSION-CLOSE DUP _RCONNC-RS !
    DUP RABBIT-S-PENDING = IF
        DROP RCONN-ST-CLOSING _RCONNC-C @ RCONN.STATE !
        RCONN-S-PENDING _RCONNC-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN
    DUP RABBIT-S-OK = IF
        DROP RCONN-ST-CLOSED _RCONNC-C @ RCONN.STATE !
        RCONN-S-OK _RCONNC-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN
    RABBIT-S-CANCELLED = IF
        RCONN-ST-CANCELLED _RCONNC-C @ RCONN.STATE !
        RCONN-S-CANCELLED _RCONNC-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN
    RCONN-S-SESSION RCONN-DETAIL-SESSION _RCONNC-RS @
        _RCONNC-C @ _RCONN-FAIL ;

: RABBIT-CONNECTION-CLOSE-POLL  ( connection -- status )
    RABBIT-CONNECTION-CLOSE ;

: RABBIT-CONNECTION-CANCEL  ( connection -- status )
    DUP RABBIT-CONNECTION-VALID? 0= IF DROP RCONN-S-INVALID EXIT THEN
    DUP _RCONNC-C ! RCONN.STATE @ RCONN-ST-CANCELLED = IF
        RCONN-S-CANCELLED EXIT
    THEN
    _RCONNC-C @ _RCONN-CLEAN-STORAGE DUP IF
        RCONN-S-FRAME RCONN-DETAIL-FRAME ROT
            _RCONNC-C @ _RCONN-FAIL EXIT
    THEN DROP
    _RCONNC-C @ RCONN.SESSION @ RABBIT-SESSION-CANCEL DUP _RCONNC-RS !
    DUP RABBIT-S-CANCELLED = OVER RABBIT-S-OK = OR IF
        DROP RCONN-ST-CANCELLED _RCONNC-C @ RCONN.STATE !
        RCONN-S-CANCELLED _RCONNC-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN DROP
    RCONN-S-SESSION RCONN-DETAIL-SESSION _RCONNC-RS @
        _RCONNC-C @ _RCONN-FAIL ;

: RABBIT-CONNECTION-FINI  ( connection -- status )
    DUP RABBIT-CONNECTION-VALID? 0= IF DROP RCONN-S-INVALID EXIT THEN
    DUP _RCONNC-C ! RCONN.STATE @ DUP RCONN-ST-CLOSED =
    OVER RCONN-ST-CANCELLED = OR OVER RCONN-ST-FAILED = OR IF
        DROP
    ELSE
        DROP _RCONNC-C @ RABBIT-CONNECTION-CLOSE DUP IF EXIT THEN DROP
    THEN
    _RCONNC-C @ _RCONN-CLEAN-STORAGE DUP IF EXIT THEN DROP
    _RCONNC-C @ RABBIT-CONNECTION-SIZE 0 FILL
    RCONN-S-OK ;
