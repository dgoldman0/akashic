: RABBIT-CONNECTION-ENQUEUE-RESERVED
  ( ready-builder minimum-free-after connection -- slot|0 status )
    _RCONNE-C ! _RCONNE-RESERVE ! _RCONNE-B !
    _RCONNE-C @ RABBIT-CONNECTION-VALID? 0= IF
        0 RCONN-S-INVALID EXIT
    THEN
    _RCONNE-RESERVE @ 0< IF
        RCONN-S-INVALID RCONN-DETAIL-NONE _RCONNE-RESERVE @
            _RCONNE-C @ _RCONN-REFUSE EXIT
    THEN
    _RCONNE-C @ RCONN.STATE @ RCONN-ST-OPEN <> IF
        RCONN-S-STATE RCONN-DETAIL-NONE 0 _RCONNE-C @ _RCONN-REFUSE EXIT
    THEN
    _RCONNE-B @ RMSGB-READY-FRAME@ DUP 0= IF
        DROP RCONN-S-BUILDER RCONN-DETAIL-BUILDER
        _RCONNE-B @ RMSGB-STATUS@ _RCONNE-C @ _RCONN-REFUSE EXIT
    THEN _RCONNE-FRAME !
    _RCONNE-C @ RABBIT-CONNECTION-SIZE _RCONNE-FRAME @
        _RCONN-SPAN-HITS-FRAME? IF
        RCONN-S-ALIAS RCONN-DETAIL-BUILDER RMSGB-S-ALIAS
            _RCONNE-C @ _RCONN-REFUSE EXIT
    THEN
    _RCONNE-B @ RMSGB-KIND@ DUP _RCONNE-KIND !
    RMSG-KIND-INVALID = IF
        RCONN-S-BUILDER RCONN-DETAIL-BUILDER RMSGB-S-STATE
            _RCONNE-C @ _RCONN-REFUSE EXIT
    THEN
    _RCONNE-MESSAGE-FIELDS DUP _RCONNE-RS ! IF
        RCONN-S-MESSAGE RCONN-DETAIL-MESSAGE _RCONNE-RS @
            _RCONNE-C @ _RCONN-REFUSE EXIT
    THEN
    _RCONNE-SESSION-PREFLIGHT DUP _RCONNE-RS ! IF
        RCONN-S-SESSION RCONN-DETAIL-SESSION _RCONNE-RS @
            _RCONNE-C @ _RCONN-REFUSE EXIT
    THEN
    _RCONNE-FRAME @ _RCONNE-KIND @ _RCONN-CONTROL-FRAME? IF
        _RCONNE-C @ RCONN.CONTROL-Q @
    ELSE
        _RCONNE-C @ RCONN.DATA-Q @
    THEN DUP _RCONNE-Q !
    DUP RTXQ.CAP @ OVER RTXQ.COUNT @ - _RCONNE-RESERVE @ U> 0= IF
        DROP RCONN-S-CAPACITY RCONN-DETAIL-QUEUE RCONN-S-CAPACITY
            _RCONNE-C @ _RCONN-REFUSE EXIT
    THEN
    _RTXQ-EMPTY@ 0= IF
        2DROP RCONN-S-CAPACITY RCONN-DETAIL-QUEUE RCONN-S-CAPACITY
            _RCONNE-C @ _RCONN-REFUSE EXIT
    THEN
    _RCONNE-INDEX ! _RCONNE-SLOT !
    _RCONNE-SLOT @ RCONN-TXSLOT-SIZE _RCONNE-FRAME @
        _RCONN-SPAN-HITS-FRAME? IF
        RCONN-S-ALIAS RCONN-DETAIL-BUILDER RMSGB-S-ALIAS
            _RCONNE-C @ _RCONN-REFUSE EXIT
    THEN
    _RCONNE-B @ RMSGB-MEASURE _RCONNE-RS ! _RCONNE-N !
    _RCONNE-RS @ IF
        RCONN-S-BUILDER RCONN-DETAIL-BUILDER _RCONNE-RS @
            _RCONNE-C @ _RCONN-REFUSE EXIT
    THEN
    _RCONNE-N @ _RCONNE-Q @ RTXQ.SLOT-BYTES @ U> IF
        RCONN-S-CAPACITY RCONN-DETAIL-QUEUE RCONN-S-CAPACITY
            _RCONNE-C @ _RCONN-REFUSE EXIT
    THEN
    _RCONNE-INDEX @ _RCONNE-Q @ _RTXQ-SLOT-BYTES@
        _RCONNE-Q @ RTXQ.SLOT-BYTES @ _RCONNE-B @ RMSGB-ENCODE
    _RCONNE-RS ! _RCONNE-BYTES !
    _RCONNE-RS @ IF
        _RCONNE-INDEX @ _RCONNE-Q @ _RTXQ-SLOT-BYTES@
            _RCONNE-Q @ RTXQ.SLOT-BYTES @ 0 FILL
        RCONN-S-BUILDER RCONN-DETAIL-BUILDER _RCONNE-RS @
            _RCONNE-C @ _RCONN-REFUSE EXIT
    THEN
    _RCONNE-BYTES @ _RCONNE-N @ <> IF
        _RCONNE-INDEX @ _RCONNE-Q @ _RTXQ-SLOT-BYTES@
            _RCONNE-Q @ RTXQ.SLOT-BYTES @ 0 FILL
        RCONN-S-PROTOCOL RCONN-DETAIL-BUILDER RMSGB-S-FRAME
            _RCONNE-C @ _RCONN-FAIL 0 SWAP EXIT
    THEN
    _RCONNE-POST-ENCODE-COMMIT DUP _RCONNE-RS ! IF
        _RCONNE-INDEX @ _RCONNE-Q @ _RTXQ-SLOT-BYTES@
            _RCONNE-Q @ RTXQ.SLOT-BYTES @ 0 FILL
        RCONN-S-PROTOCOL RCONN-DETAIL-SESSION _RCONNE-RS @
            _RCONNE-C @ _RCONN-FAIL 0 SWAP EXIT
    THEN
    _RCONNE-PUBLISH
    RCONN-S-OK _RCONNE-C @ _RCONN-PUBLISH-STATUS ;

