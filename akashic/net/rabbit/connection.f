    DUP 0 SWAP RCONN.ACTIVE-SLOT !
    0 SWAP RCONN.ACTIVE-INDEX ! ;

: _RCONN-TX-COMPLETE  ( connection -- )
    DUP _RCONNT-C ! RCONN-WIRE-COMPLETE SWAP _RCONN-WIRE-SNAPSHOT
    _RCONNT-C @ RCONN.ACTIVE-INDEX @ _RCONNT-C @ RCONN.ACTIVE-Q @
        _RTXQ-CURSOR-AFTER!
    _RCONNT-C @ RCONN.ACTIVE-SLOT @ RTXS.FLAGS @
        _RTXQ-SLOTF-EVENT AND IF
        _RCONNT-C @ RCONN.ACTIVE-SLOT @ RTXS.LANE @
            _RCONNT-C @ RCONN.SESSION @ RABBIT-SESSION-LANE@
        DUP IF
            RLANE.ACKED @
            _RCONNT-C @ RCONN.ACTIVE-SLOT @ RTXS.SEQ @ SWAP U> 0=
        ELSE
            DROP 0
        THEN IF
            _RCONNT-C @ RCONN.ACTIVE-INDEX @
                _RCONNT-C @ RCONN.ACTIVE-Q @ _RTXQ-SLOT-WIPE
            -1 _RCONNT-C @ RCONN.ACTIVE-Q @ RTXQ.COUNT +!
        ELSE
            RTXQ-SLOT-WAIT-ACK
                _RCONNT-C @ RCONN.ACTIVE-SLOT @ RTXS.STATE !
        THEN
    ELSE
        _RCONNT-C @ RCONN.ACTIVE-INDEX @
            _RCONNT-C @ RCONN.ACTIVE-Q @ _RTXQ-SLOT-WIPE
        -1 _RCONNT-C @ RCONN.ACTIVE-Q @ RTXQ.COUNT +!
    THEN
    _RCONNT-C @ _RCONN-CLEAR-ACTIVE ;

