    _RCONNE-FLAGS @ _RCONNE-F-EVENT AND IF
        _RCONNE-LANE @ _RCONNE-SEQ @ _RCONNE-C @ RCONN.SESSION @
            RABBIT-SESSION-RESERVE-SEND-EXACT ?DUP IF EXIT THEN
    THEN
    _RCONNE-FLAGS @ _RCONNE-F-CREDIT AND IF
        _RCONNE-LANE @ _RCONNE-VALUE @ _RCONNE-C @ RCONN.SESSION @
            RABBIT-SESSION-GRANT-CREDIT ?DUP IF EXIT THEN
    THEN
    _RCONNE-FLAGS @ _RCONNE-F-HELLO-BEGIN AND IF
        _RCONNE-C @ RCONN.SESSION @ RABBIT-SESSION-HELLO-BEGIN
        NIP ?DUP IF EXIT THEN
    THEN
    RABBIT-S-OK ;

