: RABBIT-CONNECTION-OPEN  ( connection -- status )
    DUP RABBIT-CONNECTION-VALID? 0= IF DROP RCONN-S-INVALID EXIT THEN
    DUP _RCONNO-C ! RCONN.STATE @ DUP RCONN-ST-OPEN = IF
        DROP RCONN-S-OK _RCONNO-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN
    DUP RCONN-ST-OPENING = SWAP RCONN-ST-READY = OR 0= IF
        RCONN-S-STATE _RCONNO-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN
    _RCONNO-C @ RCONN.SESSION @ RABBIT-SESSION-OPEN DUP _RCONNO-RS !
    DUP RABBIT-S-PENDING = IF
        DROP RCONN-ST-OPENING _RCONNO-C @ RCONN.STATE !
        RCONN-S-PENDING _RCONNO-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN
    RABBIT-S-OK = IF
        RCONN-ST-OPEN _RCONNO-C @ RCONN.STATE !
        RCONN-S-OK _RCONNO-C @ _RCONN-PUBLISH-STATUS EXIT
    THEN
    RCONN-S-SESSION RCONN-DETAIL-SESSION _RCONNO-RS @
        _RCONNO-C @ _RCONN-FAIL ;

\ =====================================================================
\  Queue scans and publication primitives
\ =====================================================================
\  Both scans are circular and bounded by the caller-selected capacity.
\  WAIT-ACK entries are skipped by the send scan and are not EMPTY, so they
\  neither block later queued frames nor become reusable before ACK release.

VARIABLE _RTXQS-Q
VARIABLE _RTXQS-I
VARIABLE _RTXQS-N
VARIABLE _RTXQS-SLOT

: _RTXQ-INDEX+  ( index queue -- next-index )
    >R 1+ DUP R> RTXQ.CAP @ = IF DROP 0 THEN ;

: _RTXQ-EMPTY@  ( queue -- slot index flag )
    DUP _RTXQS-Q ! RTXQ.CAP @ DUP 0= IF DROP 0 0 0 EXIT THEN
    _RTXQS-Q @ RTXQ.TAIL @ _RTXQS-I !
    0 ?DO
        _RTXQS-I @ _RTXQS-Q @ _RTXQ-SLOT@ DUP _RTXQS-SLOT !
        RTXS.STATE @ RTXQ-SLOT-EMPTY = IF
            _RTXQS-SLOT @ _RTXQS-I @ -1 UNLOOP EXIT
        THEN
        _RTXQS-I @ _RTXQS-Q @ _RTXQ-INDEX+ _RTXQS-I !
    LOOP
    0 0 0 ;

: _RTXQ-NEXT-QUEUED@  ( queue -- slot index flag )
    DUP _RTXQS-Q ! RTXQ.CAP @ DUP 0= IF DROP 0 0 0 EXIT THEN
    _RTXQS-Q @ RTXQ.SEND-CURSOR @ _RTXQS-I !
    0 ?DO
        _RTXQS-I @ _RTXQS-Q @ _RTXQ-SLOT@ DUP _RTXQS-SLOT !
