: _RCONN-TX-PUMP  ( connection -- status )
    DUP _RCONNT-C ! _RCONN-TX-SELECT 0= IF RCONN-S-OK EXIT THEN
    _RCONNT-C @ RCONN.ACTIVE-SLOT @ DUP _RCONNT-SLOT !
    RTXS.ATTEMPTS @ RABBIT-U64-MAX = IF
        RCONN-S-OVERFLOW RCONN-DETAIL-QUEUE RABBIT-S-OVERFLOW
            _RCONNT-C @ _RCONN-FAIL EXIT
    THEN
    _RCONNT-SLOT @ RTXS.ATTEMPTS DUP @ 1+ SWAP !
    _RCONNT-SLOT @ RTXS.OFFSET @ IF
        RCONN-WIRE-PARTIAL
    ELSE
        RCONN-WIRE-ATTEMPTED
    THEN _RCONNT-C @ _RCONN-WIRE-SNAPSHOT
    _RCONNT-C @ RCONN.ACTIVE-INDEX @
        _RCONNT-C @ RCONN.ACTIVE-Q @ _RTXQ-SLOT-BYTES@
    _RCONNT-SLOT @ RTXS.OFFSET @ + _RCONNT-A !
    _RCONNT-SLOT @ RTXS.USED @ _RCONNT-SLOT @ RTXS.OFFSET @ -
