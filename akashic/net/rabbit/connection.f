\ =====================================================================
\  connection.f - Caller-owned cooperative Rabbit connection owner
\ =====================================================================
\  A connection serializes one Rabbit session, one incremental RBF parser,
\  and two caller-sized outbound queues over the session's injected NIO port.
\  Control and data queues have separate caller-owned metadata arrays and
\  uniform caller-chosen byte slots.  There is no product queue depth or
\  frame-size constant in this module.
\
\  Outbound builders are encoded into an EMPTY queue slot before session
\  mutation or publication.  EVENT sequence reservation and CREDIT receive-
\  grant recording therefore happen only after encoding succeeds, followed
\  by an infallible slot-state store.  The pump never switches slots during a
\  short send: control traffic takes priority only at the next frame boundary.
\  Fully sent EVENT slots remain owned until a cumulative lane ACK releases
\  them; other slots are wiped as soon as their complete wire image is sent.
\  The pinned profile carries no Seq field on ACK/CREDIT/PING, so connection
\  queues do not invent or consume a non-wire control ordinal.
\
\  The parser owns one held READY view at a time.  Its slices remain stable
\  until explicit RX-COMMIT or RX-DROP, while unconsumed coalesced input stays
\  in the distinct receive carry buffer.  No parser pointer is queued.
\
\  Persistent state and all variable-size storage are caller-owned.  Private
\  VARIABLEs below are synchronous operation scratch only.  Calls do not
\  yield or call application code, but this implementation is non-reentrant;
\  one cooperative owner must serialize every operation on a connection.
\ =====================================================================

