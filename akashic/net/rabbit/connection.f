    _RTXQV-Q @ RTXQ.SLOT-BYTES @ U> IF 0 EXIT THEN
    _RTXQV-SLOT @ RTXS.OFFSET @ DUP 0< IF DROP 0 EXIT THEN
    _RTXQV-SLOT @ RTXS.USED @ U> IF 0 EXIT THEN
    _RTXQV-SLOT @ RTXS.LANE @ DUP 0< IF DROP 0 EXIT THEN
    RABBIT-LANE-MAX U> IF 0 EXIT THEN
