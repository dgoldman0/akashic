: RCONN-TXQ-VALID?  ( queue -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP _RCONN-CELL-ALIGNED? 0= IF DROP 0 EXIT THEN
    DUP RCONN-TXQ-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _RTXQV-Q !
    DUP RTXQ.MAGIC @ _RTXQ-MAGIC-VALUE <> IF DROP 0 EXIT THEN
    DUP RTXQ.ABI @ _RTXQ-ABI-VERSION <> IF DROP 0 EXIT THEN
    DUP RTXQ.BYTES @ RCONN-TXQ-SIZE <> IF DROP 0 EXIT THEN
    DUP RTXQ.CAP @ DUP _RTXQV-CAP ! 0< IF DROP 0 EXIT THEN
    DUP RTXQ.SLOT-BYTES @ DUP _RTXQV-SLOT-BYTES ! 0< IF DROP 0 EXIT THEN
    DUP RTXQ.META @ _RTXQV-CAP @ RCONN-TXSLOT-SIZE
        _RCONN-ARRAY? 0= IF DROP 0 EXIT THEN
    DUP RTXQ.ARENA @ _RTXQV-CAP @ _RTXQV-SLOT-BYTES @
        _RCONN-BYTE-ARRAY? 0= IF DROP 0 EXIT THEN
    _RTXQV-CAP @ IF
        DUP RTXQ.META @ _RTXQV-CAP @ RCONN-TXSLOT-SIZE *
        2 PICK RTXQ.ARENA @ _RTXQV-CAP @ _RTXQV-SLOT-BYTES @ *
        MSPAN-OVERLAP? IF DROP 0 EXIT THEN
    THEN
    DUP RTXQ.COUNT @ DUP 0< IF 2DROP 0 EXIT THEN
    _RTXQV-CAP @ U> IF DROP 0 EXIT THEN
