        NIO-SEND _RCONNT-IOS ! _RCONNT-N !
    _RCONNT-IOS @ NIO-S-CANCELLED = IF
        _RCONNT-IOS @ _RCONNT-C @ _RCONN-CANCELLED EXIT
    THEN
    _RCONNT-IOS @ NIO-S-OK <> IF
        RCONN-S-IO RCONN-DETAIL-IO _RCONNT-IOS @
            _RCONNT-C @ _RCONN-FAIL EXIT
    THEN
    _RCONNT-N @ 0= IF RCONN-S-OK EXIT THEN
    _RCONNT-N @ _RCONNT-SLOT @ RTXS.OFFSET +!
    _RCONNT-N @ _RCONNT-C @ _RCONN-WIRE-BYTES+
    _RCONNT-SLOT @ RTXS.OFFSET @ _RCONNT-SLOT @ RTXS.USED @ = IF
        _RCONNT-C @ _RCONN-TX-COMPLETE
    ELSE
        RCONN-WIRE-PARTIAL _RCONNT-C @ _RCONN-WIRE-SNAPSHOT
    THEN
    RCONN-S-OK ;

