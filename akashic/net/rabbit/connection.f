: _RCONNE-SESSION-PREFLIGHT  ( -- rabbit-status )
    _RCONNE-KIND @ RMSG-KIND-HELLO = IF
        _RCONNE-C @ RCONN.SESSION @ DUP RSESS.ROLE @
            RABBIT-ROLE-CLIENT <> IF DROP RABBIT-S-STATE EXIT THEN
        DUP RABBIT-SESSION-STATE@ RABBIT-ST-HELLO <> IF
            DROP
            RABBIT-S-STATE EXIT
        THEN
        RSESS.LOCAL-CAPS @ _RCONNE-VALUE @ <> IF
            RABBIT-S-CAPABILITY EXIT
        THEN
        _RCONNE-F-HELLO-BEGIN _RCONNE-FLAGS !
        RABBIT-S-OK EXIT
    THEN
    _RCONNE-C @ RCONN.SESSION @ RABBIT-SESSION-ESTABLISHED? 0= IF
        RABBIT-S-STATE EXIT
    THEN
    _RCONNE-FLAGS @ _RCONNE-F-EVENT AND IF
        _RCONNE-LANE @ _RCONNE-C @ RCONN.SESSION @
            RABBIT-SESSION-NEXT-SEND@
        _RCONNE-RS ! _RCONNE-CURRENT !
        _RCONNE-RS @ IF _RCONNE-RS @ EXIT THEN
        _RCONNE-CURRENT @ _RCONNE-SEQ @ <> IF
            RABBIT-S-SEQUENCE EXIT
        THEN
    THEN
    _RCONNE-FLAGS @ _RCONNE-F-CREDIT AND IF
        _RCONNE-LANE @ _RCONNE-C @ RCONN.SESSION @
            RABBIT-SESSION-RECV-CREDIT@
        _RCONNE-RS ! _RCONNE-CURRENT !
        _RCONNE-RS @ IF _RCONNE-RS @ EXIT THEN
        RABBIT-CREDIT-MAX _RCONNE-CURRENT @ -
            _RCONNE-VALUE @ U< IF RABBIT-S-OVERFLOW EXIT THEN
    THEN
    RABBIT-S-OK ;

