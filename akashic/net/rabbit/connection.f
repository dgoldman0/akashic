        _RCONN-BYTE-ARRAY? 0= IF RCONN-S-INVALID EXIT THEN
    _RTXQI-CAP @ RCONN-TXSLOT-SIZE _RCONN-MUL? 0= IF
        DROP RCONN-S-INVALID EXIT
    THEN _RTXQI-META-BYTES !
    _RTXQI-CAP @ _RTXQI-SLOT-BYTES @ _RCONN-MUL? 0= IF
        DROP RCONN-S-INVALID EXIT
    THEN _RTXQI-ARENA-BYTES !
    _RTXQI-Q @ RCONN-TXQ-SIZE
        _RTXQI-META @ _RTXQI-META-BYTES @ MSPAN-OVERLAP? IF
        RCONN-S-ALIAS EXIT
    THEN
    _RTXQI-Q @ RCONN-TXQ-SIZE
        _RTXQI-ARENA @ _RTXQI-ARENA-BYTES @ MSPAN-OVERLAP? IF
        RCONN-S-ALIAS EXIT
    THEN
    _RTXQI-META @ _RTXQI-META-BYTES @
        _RTXQI-ARENA @ _RTXQI-ARENA-BYTES @ MSPAN-OVERLAP? IF
        RCONN-S-ALIAS EXIT
    THEN
    \ Matching magic denotes a live or damaged owner.  Refuse before the
    \ full semantic validator can dereference caller-corrupted bindings.
    _RTXQI-Q @ RTXQ.MAGIC @ _RTXQ-MAGIC-VALUE = IF
        RCONN-S-STATE EXIT
    THEN
    _RTXQI-Q @ RCONN-TXQ-SIZE 0 FILL
    _RTXQI-META @ _RTXQI-META-BYTES @ 0 FILL
    _RTXQI-ARENA @ _RTXQI-ARENA-BYTES @ 0 FILL
    _RTXQ-MAGIC-VALUE _RTXQI-Q @ RTXQ.MAGIC !
    _RTXQ-ABI-VERSION _RTXQI-Q @ RTXQ.ABI !
    RCONN-TXQ-SIZE _RTXQI-Q @ RTXQ.BYTES !
    _RTXQI-META @ _RTXQI-Q @ RTXQ.META !
    _RTXQI-CAP @ _RTXQI-Q @ RTXQ.CAP !
    _RTXQI-ARENA @ _RTXQI-Q @ RTXQ.ARENA !
    _RTXQI-SLOT-BYTES @ _RTXQI-Q @ RTXQ.SLOT-BYTES !
    RCONN-S-OK ;

: RCONN-TXQ-CAPACITY@  ( queue -- slots status )
    DUP RCONN-TXQ-VALID? 0= IF DROP 0 RCONN-S-INVALID EXIT THEN
    RTXQ.CAP @ RCONN-S-OK ;

: RCONN-TXQ-COUNT@  ( queue -- used-slots status )
    DUP RCONN-TXQ-VALID? 0= IF DROP 0 RCONN-S-INVALID EXIT THEN
    RTXQ.COUNT @ RCONN-S-OK ;

: _RTXQ-WIPE  ( queue -- )
    DUP RTXQ.META @ OVER RTXQ.CAP @ RCONN-TXSLOT-SIZE * 0 FILL
    DUP RTXQ.ARENA @ OVER RTXQ.CAP @ 2 PICK RTXQ.SLOT-BYTES @ * 0 FILL
    DUP 0 SWAP RTXQ.COUNT !
    DUP 0 SWAP RTXQ.TAIL !
    0 SWAP RTXQ.SEND-CURSOR ! ;

: RCONN-TXQ-FINI  ( queue -- status )
    DUP RCONN-TXQ-VALID? 0= IF DROP RCONN-S-INVALID EXIT THEN
    DUP _RTXQ-WIPE
    RCONN-TXQ-SIZE 0 FILL
    RCONN-S-OK ;

