: KDOSTLS-PREP-CANCEL  ( adapter -- prep-status )
    COREID 0<> IF DROP KDOSTLS-PREP-S-FAILED EXIT THEN
    _KDPC-A !
    \ Once ACTIVATE has exposed the established port, its shared cancellation
    \ callback owns retirement.  This entry is only the outbound producer's
    \ pre-publication cancellation operation.
    _KDPC-A @ KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-OPEN =
    OVER KDOSTLSP-STATE-CLOSE-TRY = OR
    OVER KDOSTLSP-STATE-CLOSE-POLL = OR
    OVER KDOSTLSP-STATE-CLOSE-ABORT = OR
    OVER KDOSTLSP-STATE-CLOSED = OR
    SWAP KDOSTLSP-STATE-CANCELLED = OR IF
        KDOSTLS-E-INVALID _KDPC-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    KDOSTLS-E-CANCELLED _KDPC-A @ KDOSTLS.LAST-ERROR !
    KDOSTLS-PHASE-CANCELLED _KDPC-A @ KDOSTLS.PHASE !
    _KDPC-A @ _KDOSTLS-PREP-DETACH IF
        KDOSTLS-PREP-S-CANCELLED
    ELSE
        KDOSTLS-PREP-S-PENDING
    THEN ;

