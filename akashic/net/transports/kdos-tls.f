: _KDOSTLS-OPEN-VALID?  ( adapter -- flag )
    DUP KDOSTLSP.STATE @ KDOSTLSP-STATE-OPEN =
    OVER KDOSTLSP.SOCKET-SD @ 0<> AND
    OVER KDOSTLS.CONTEXT @ 0= AND
    OVER KDOSTLS.CTX-GENERATION @ 0= AND
    OVER KDOSTLS.TCB-GENERATION @ 0= AND
    OVER KDOSTLS.LOCAL-PORT @ 0= AND
    OVER KDOSTLS.STAGING-SOCKET @ 0= AND
    OVER KDOSTLS.STAGING-ORIGINAL-STATE @ 0= AND
    OVER KDOSTLS.STAGING-PUBLISHED @ 0= AND
    SWAP KDOSNET-OWNER? 0= AND ;

: _KDOSTLS-PUBLISH-FAIL  ( -- prep-status )
    TLS-CONNECT-E-AUTH _KDOP-A @ KDOSTLS.NATIVE-ERROR !
    KDOSTLS-E-AUTH _KDOP-A @ KDOSTLS.LAST-ERROR !
    KDOSTLS-PREP-S-FAILED ;

: _KDOSTLS-STAGE-PUBLISHED  ( -- prep-status )
    _KDOP-A @ KDOSTLS.STAGING-SOCKET @ _KDOP-A @ KDOSTLSP-PUBLISH
    DUP KDOSTLSP-S-OK <> IF
        DROP KDOSTLS-E-CLEANUP _KDOP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN DROP
    _KDOP-A @ _KDOSTLS-CLEAR-RAW-AUTHORITY
    _KDOP-A @ KDOSNET-RELEASE DUP
        _KDOP-A @ KDOSTLSP.OWNER-STATUS !
    KDOSNET-S-OK <> IF
        KDOSTLS-E-CLEANUP _KDOP-A @ KDOSTLS.CLEANUP-ERROR !
        KDOSTLS-E-CLEANUP _KDOP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    _KDOP-A @ KDOSTLSP-ACTIVATE DUP _KDOP-STATUS !
    KDOSTLSP-S-OK = IF KDOSTLS-PREP-S-READY EXIT THEN
    _KDOP-STATUS @ KDOSTLSP-S-PENDING = IF
        KDOSTLS-PREP-S-PENDING EXIT
    THEN
    KDOSTLS-E-CLEANUP _KDOP-A @ KDOSTLS.LAST-ERROR !
    KDOSTLS-PREP-S-FAILED ;

: _KDOSTLS-HANDSHAKE-PUBLISH-CALL  ( -- )
    _KDOP-CTX @ TLS-HANDSHAKE-PUBLISH _KDOP-STATUS ! ;

: _KDOSTLS-HANDSHAKE-PUBLISH-OWNED  ( -- ior )
    \ TLS-HANDSHAKE-PUBLISH takes one same-task nested owner depth.  If its
    \ body throws before its normal return helper, unwind that nested depth
    \ here and let the outer owner finally release only the depth it acquired.
    ['] _KDOSTLS-HANDSHAKE-PUBLISH-CALL CATCH ?DUP IF
        TLS-OWNER-RELEASE THROW
    THEN
    _KDOP-STATUS @ ;

: _KDOSTLS-STEP-OPEN-OWNED  ( -- prep-status )
    _KDOP-A @ _KDOSTLS-CTX-EXACT? 0= IF
        _KDOSTLS-PUBLISH-FAIL EXIT
    THEN
    _KDOP-A @ KDOSTLS.CONTEXT @ DUP _KDOP-CTX !
    TLS-CTX.STATE @ TLSS-HANDSHAKE = IF
        _KDOSTLS-HANDSHAKE-PUBLISH-OWNED DUP TLS-E-BUSY = IF
            DROP KDOSTLS-PREP-S-PENDING EXIT
        THEN
        ?DUP IF DROP _KDOSTLS-PUBLISH-FAIL EXIT THEN
    THEN
    _KDOP-A @ _KDOSTLS-CTX-EXACT? 0=
    _KDOP-CTX @ TLS-CTX.STATE @ TLSS-ESTABLISHED <> OR
    _KDOP-CTX @ TLS-CTX.HS-STATE @ TLSH-CONNECTED <> OR
    _KDOP-CTX @ TLS-CTX.PEER-AUTH @ 1 <> OR
    _KDOP-CTX @ TLS-CTX.ERROR @ TLS-E-OK <> OR IF
        _KDOSTLS-PUBLISH-FAIL EXIT
    THEN
    _KDOP-A @ KDOSTLS.STAGING-SOCKET @ DUP 0= IF
        DROP SOCK-TYPE-TLS SOCKET DUP -1 = IF
            DROP KDOSTLS-PREP-S-PENDING EXIT
        THEN
        DUP _KDOP-A @ KDOSTLS.STAGING-SOCKET !
    THEN _KDOP-SD !
    _KDOP-A @ KDOSTLS.STAGING-ORIGINAL-STATE @ 0= IF
        _KDOP-SD @ SOCK-CONNECT-CLAIM DUP -1 = IF
            DROP KDOSTLS-PREP-S-PENDING EXIT
        THEN
        DUP _KDOP-A @ KDOSTLS.STAGING-ORIGINAL-STATE !
        SOCKST-TLS <> IF _KDOSTLS-PUBLISH-FAIL EXIT THEN
    THEN
    _KDOP-SD @ _KDOP-CTX @ SOCK-TLS-PUBLISH-TRY
    DUP IF
        DUP TLS-E-BUSY =
        OVER TCP-ACCEPT-E-BUSY = OR
        OVER TLS-E-WOULD-BLOCK = OR IF
            2DROP KDOSTLS-PREP-S-PENDING EXIT
        THEN
        2DROP _KDOSTLS-PUBLISH-FAIL EXIT
    THEN
    DROP 0= IF
        _KDOSTLS-PUBLISH-FAIL EXIT
    THEN
    -1 _KDOP-A @ KDOSTLS.STAGING-PUBLISHED !
    KDOSTLS-PREP-S-PENDING ;

: _KDOSTLS-STEP-OPEN-OWNER-CALL  ( -- )
    _KDOSTLS-STEP-OPEN-OWNED _KDOP-RESULT ! ;

: _KDOSTLS-STEP-OPEN-WITH-OWNER  ( -- prep-status )
    KDOSTLS-PREP-S-FAILED _KDOP-RESULT !
    ['] _KDOSTLS-STEP-OPEN-OWNER-CALL CATCH _KDOP-THROW !
    \ This is the one release paired with _KDOSTLS-STEP-OPEN's successful
    \ TLS-OWNER-TRY, regardless of the owned body's result or exception.
    TLS-OWNER-RELEASE
    _KDOP-THROW @ IF
        TLS-CONNECT-E-AUTH _KDOP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-FAULT _KDOP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    _KDOP-A @ KDOSTLS.STAGING-PUBLISHED @ IF
        _KDOSTLS-STAGE-PUBLISHED
    ELSE
        _KDOP-RESULT @
    THEN ;

: _KDOSTLS-STEP-OPEN  ( -- prep-status )
    _KDCP-A @ _KDOP-A !
    _KDOP-A @ KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-OPEN = IF
        DROP _KDOP-A @ _KDOSTLS-OPEN-VALID? IF
            KDOSTLS-PREP-S-READY
        ELSE
            KDOSTLS-E-AUTH _KDOP-A @ KDOSTLS.LAST-ERROR !
            KDOSTLS-PREP-S-FAILED
        THEN EXIT
    THEN
    DUP KDOSTLSP-STATE-PUBLISHED = IF
        DROP _KDOP-A @ KDOSTLSP-ACTIVATE DUP _KDOP-STATUS !
        KDOSTLSP-S-OK = IF KDOSTLS-PREP-S-READY EXIT THEN
        _KDOP-STATUS @ KDOSTLSP-S-PENDING = IF
            KDOSTLS-PREP-S-PENDING EXIT
        THEN
        KDOSTLS-E-CLEANUP _KDOP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    KDOSTLSP-STATE-RESERVED <> IF
        KDOSTLS-E-INVALID _KDOP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    _KDOP-A @ KDOSTLS.STAGING-PUBLISHED @ IF
        _KDOSTLS-STAGE-PUBLISHED EXIT
    THEN
    _KDOP-A @ _KDOSTLS-CTX-EXACT? 0= IF
        KDOSTLS-E-AUTH _KDOP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    TLS-OWNER-TRY IF KDOSTLS-PREP-S-PENDING EXIT THEN
    _KDOSTLS-STEP-OPEN-WITH-OWNER ;

