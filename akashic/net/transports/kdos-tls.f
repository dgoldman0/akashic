: KDOSTLS-ADDRESS-POLICY!  ( context xt adapter -- status )
    COREID 0<> IF DROP 2DROP KDOSTLS-E-PLATFORM EXIT THEN
    _KDTAP-A ! _KDTAP-XT ! _KDTAP-CONTEXT !
    _KDTAP-A @ 0= _KDTAP-XT @ 0= OR IF KDOSTLS-E-INVALID EXIT THEN
    _KDTAP-A @ _KDOSTLS-INITIALIZED? 0= IF KDOSTLS-E-INVALID EXIT THEN
    _KDTAP-A @ KDOSTLSP.STATE @ KDOSTLSP-STATE-RESET <> IF
        KDOSTLS-E-BUSY EXIT
    THEN
    _KDTAP-CONTEXT @ _KDTAP-A @ KDOSTLS.ADDRESS-CONTEXT !
    _KDTAP-XT @ _KDTAP-A @ KDOSTLS.ADDRESS-XT !
    KDOSTLS-E-OK ;

: KDOSTLS-CONFIGURE  ( host-a host-u remote-port adapter -- status )
    COREID 0<> IF 2DROP 2DROP KDOSTLS-E-PLATFORM EXIT THEN
    _KDTCFG-T ! _KDTCFG-PORT ! _KDTCFG-U ! _KDTCFG-A !
    _KDTCFG-T @ 0= IF KDOSTLS-E-INVALID EXIT THEN
    _KDTCFG-T @ KDOSTLS-SIZE MSPAN-NONWRAPPING? 0= IF
        KDOSTLS-E-INVALID EXIT
    THEN
    _KDTCFG-T @ _KDOSTLS-INITIALIZED? 0= IF KDOSTLS-E-INVALID EXIT THEN
    _KDTCFG-T @ KDOSTLSP.STATE @ KDOSTLSP-STATE-RESET <> IF
        KDOSTLS-E-BUSY EXIT
    THEN
    _KDTCFG-U @ 0= _KDTCFG-U @ KDOSTLS-HOST-CAPACITY > OR
    _KDTCFG-A @ 0= OR IF KDOSTLS-E-INVALID EXIT THEN
    _KDTCFG-A @ _KDTCFG-U @ MSPAN-NONWRAPPING? 0= IF
        KDOSTLS-E-INVALID EXIT
    THEN
    _KDTCFG-A @ _KDTCFG-U @ FALSE DNS-NAME-VALID? 0= IF
        KDOSTLS-E-INVALID EXIT
    THEN
    _KDTCFG-PORT @ 1 < _KDTCFG-PORT @ 65535 > OR IF
        KDOSTLS-E-INVALID EXIT
    THEN
    _KDTCFG-A @ _KDTCFG-U @
    _KDTCFG-T @ KDOSTLS.HOST-BUF KDOSTLS-HOST-STORAGE
    MSPAN-OVERLAP? IF
        _KDTCFG-A @ _KDTCFG-T @ KDOSTLS.HOST-BUF <> IF
            KDOSTLS-E-INVALID EXIT
        THEN
        _KDTCFG-T @ KDOSTLS.HOST-BUF _KDTCFG-U @ +
        KDOSTLS-HOST-STORAGE _KDTCFG-U @ - 0 FILL
    ELSE
        _KDTCFG-T @ KDOSTLS.HOST-BUF KDOSTLS-HOST-STORAGE 0 FILL
        _KDTCFG-A @ _KDTCFG-T @ KDOSTLS.HOST-BUF
        _KDTCFG-U @ CMOVE
    THEN
    _KDTCFG-U @ _KDTCFG-T @ KDOSTLS.HOST-U !
    _KDTCFG-PORT @ _KDTCFG-T @ KDOSTLS.REMOTE-PORT !
    KDOSTLS-E-OK _KDTCFG-T @ KDOSTLS.LAST-ERROR !
    KDOSTLS-E-OK ;

