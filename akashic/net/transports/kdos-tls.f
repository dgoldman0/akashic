: KDOSTLS-INIT  ( adapter -- )
    COREID 0<> IF DROP KDOSTLS-E-PLATFORM NEGATE THROW THEN
    DUP KDOSNET-OWNER? IF
        DROP KDOSTLS-E-CLEANUP NEGATE THROW
    THEN
    DUP _KDOSTLS-INITIALIZED? IF
        DUP _KDOSTLS-REINIT-SAFE? 0= IF
            DROP KDOSTLS-E-CLEANUP NEGATE THROW
        THEN
    THEN
    DUP KDOSTLS-SIZE 0 FILL
    DUP KDOSTLSP-INIT DUP KDOSTLSP-S-OK <> IF
        2DROP KDOSTLS-E-CLEANUP NEGATE THROW
    THEN DROP
    DUP _KDOSTLS-BIND-OPENING
    ['] _KDOSTLS-ADDRESS-DEFAULT OVER KDOSTLS.ADDRESS-XT !
    0 OVER KDOSTLS.ADDRESS-CONTEXT !
    ['] _KDOSTLS-NOW-DEFAULT OVER KDOSTLS.NOW-XT !
    ['] _KDOSTLS-COOP-STEP-DEFAULT OVER KDOSTLS.COOP-STEP-XT !
    _KDOSTLS-MAGIC-VALUE SWAP _KDOSTLS.MAGIC ! ;

