: _KDOSTLS-RAW-ABORT-EXACT  ( adapter -- retired? )
    DUP _KDAD-A ! KDOSTLS.CONTEXT @ 0= IF -1 EXIT THEN
    _KDAD-A @ KDOSTLS.CONTEXT @
    _KDAD-A @ KDOSTLS.CTX-GENERATION @
    TLS-ABORT-EXACT _KDAD-IOR ! _KDAD-RETIRED !
    _KDAD-IOR @ DUP TLS-E-BUSY =
    SWAP TLS-E-WOULD-BLOCK = OR IF 0 EXIT THEN
    _KDAD-IOR @ ?DUP IF
        _KDAD-A @ KDOSTLS.CLEANUP-ERROR ! 0 EXIT
    THEN
    _KDAD-RETIRED @ 0= IF
        KDOSTLS-E-CLEANUP _KDAD-A @ KDOSTLS.CLEANUP-ERROR !
        0 EXIT
    THEN
    0 _KDAD-A @ KDOSTLS.CONTEXT !
    0 _KDAD-A @ KDOSTLS.CTX-GENERATION !
    0 _KDAD-A @ KDOSTLS.TCB-GENERATION !
    -1 ;

: _KDOSTLS-STAGING-RELEASE-INNER  ( -- )
    _KDAD-A @ KDOSTLS.STAGING-ORIGINAL-STATE @ IF
        _KDAD-A @ KDOSTLS.STAGING-SOCKET @
        _KDAD-A @ KDOSTLS.STAGING-ORIGINAL-STATE @
        SOCK-CONNECT-ROLLBACK-TRY _KDAD-IOR !
        _KDAD-IOR @ IF EXIT THEN
        0 _KDAD-A @ KDOSTLS.STAGING-ORIGINAL-STATE !
    THEN
    _KDAD-A @ KDOSTLS.STAGING-SOCKET @ SOCK-TLS-ABORT-EXACT-TRY
    _KDAD-IOR ! _KDAD-ABORT-STATUS ! ;

: _KDOSTLS-STAGING-RELEASE  ( adapter -- released? )
    DUP _KDAD-A ! KDOSTLS.STAGING-SOCKET @ 0= IF -1 EXIT THEN
    _KDAD-A @ KDOSTLS.STAGING-PUBLISHED @ IF 0 EXIT THEN
    0 _KDAD-IOR ! TLS-ABORT-S-NONE _KDAD-ABORT-STATUS !
    ['] _KDOSTLS-STAGING-RELEASE-INNER CATCH ?DUP IF
        _KDAD-A @ KDOSTLS.CLEANUP-ERROR ! 0 EXIT
    THEN
    _KDAD-IOR @ DUP TLS-E-BUSY =
    OVER TCP-ACCEPT-E-BUSY = OR
    SWAP TLS-E-WOULD-BLOCK = OR IF 0 EXIT THEN
    _KDAD-ABORT-STATUS @ TLS-ABORT-S-BUSY = IF 0 EXIT THEN
    _KDAD-IOR @ ?DUP IF
        _KDAD-A @ KDOSTLS.CLEANUP-ERROR ! 0 EXIT
    THEN
    0 _KDAD-A @ KDOSTLS.STAGING-SOCKET !
    -1 ;

: _KDOSTLS-OWNER-RELEASE  ( adapter -- released? )
    DUP KDOSNET-OWNER? IF
        DUP KDOSNET-RELEASE DUP 2 PICK KDOSTLSP.OWNER-STATUS !
        DUP KDOSNET-S-OK <> IF
            SWAP KDOSTLS.CLEANUP-ERROR ! 0 EXIT
        THEN
        2DROP -1 EXIT
    THEN
    \ A foreign transient owner is not authority retained by this adapter.
    \ Raw RESERVED cleanup proves the lifetime token separately before it
    \ reaches this helper; PUBLISHED cleanup may legitimately wait behind a
    \ different record in the shared port's per-operation gate.
    DROP -1 ;

: _KDOSTLS-STAGED-DISCARD  ( adapter -- discarded? )
    DUP _KDAD-A ! KDOSTLS.STAGING-PUBLISHED @ IF
        _KDAD-A @ KDOSTLS.STAGING-SOCKET @ _KDAD-A @ KDOSTLSP-PUBLISH
        KDOSTLSP-S-OK <> IF
            KDOSTLS-E-CLEANUP _KDAD-A @ KDOSTLS.CLEANUP-ERROR !
            0 EXIT
        THEN
    THEN
    _KDAD-A @ _KDOSTLS-CLEAR-RAW-AUTHORITY
    _KDAD-A @ _KDOSTLS-OWNER-RELEASE 0= IF 0 EXIT THEN
    _KDAD-A @ KDOSTLSP-DISCARD-STEP DUP KDOSTLSP-S-OK = IF
        DROP _KDAD-A @ _KDOSTLS-PREP-CLEAR-SCRATCH -1 EXIT
    THEN
    DUP KDOSTLSP-S-PENDING = IF DROP 0 EXIT THEN
    _KDAD-A @ KDOSTLS.CLEANUP-ERROR ! 0 ;

: _KDOSTLS-PREP-DETACH  ( adapter -- detached? )
    _KDAD-A !
    _KDAD-A @ KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-PUBLISHED =
    OVER KDOSTLSP-STATE-ERROR = OR
    SWAP KDOSTLSP-STATE-QUARANTINED = OR
    _KDAD-A @ KDOSTLS.STAGING-PUBLISHED @ OR IF
        _KDAD-A @ _KDOSTLS-STAGED-DISCARD EXIT
    THEN
    _KDAD-A @ KDOSTLS.CONTEXT @
    _KDAD-A @ KDOSTLS.STAGING-SOCKET @ OR
    _KDAD-A @ KDOSNET-OWNER? OR
    _KDAD-A @ KDOSTLSP.STATE @ KDOSTLSP-STATE-RESERVED = OR
    _KDAD-A @ KDOSNET-OPERATE? 0= AND IF
        _KDAD-A @ _KDOSTLS-QUARANTINE
        0 EXIT
    THEN
    _KDAD-A @ _KDOSTLS-RAW-ABORT-EXACT 0= IF 0 EXIT THEN
    _KDAD-A @ _KDOSTLS-STAGING-RELEASE 0= IF 0 EXIT THEN
    _KDAD-A @ _KDOSTLS-OWNER-RELEASE 0= IF 0 EXIT THEN
    _KDAD-A @ KDOSTLSP.STATE @ KDOSTLSP-STATE-RESERVED = IF
        _KDAD-A @ KDOSTLSP-UNRESERVE KDOSTLSP-S-OK <> IF
            KDOSTLS-E-CLEANUP _KDAD-A @ KDOSTLS.CLEANUP-ERROR !
            0 EXIT
        THEN
    THEN
    _KDAD-A @ _KDOSTLS-CLEAR-RAW-AUTHORITY
    _KDAD-A @ _KDOSTLS-PREP-CLEAR-SCRATCH
    -1 ;

