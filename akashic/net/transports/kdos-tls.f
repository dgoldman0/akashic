        TLS-CONNECT-E-HANDSHAKE-WAIT _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-CONNECT _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    _KDRL-U !
    TLS-RECV-REC C@ TLS-CT-CCS = IF
        TLS-RECV-REC _KDRL-U @ TLS-COMPAT-CCS? 0= IF
            TLS-CONNECT-E-HANDSHAKE-RECORD
                _KDCP-A @ KDOSTLS.NATIVE-ERROR !
            KDOSTLS-E-CONNECT _KDCP-A @ KDOSTLS.LAST-ERROR !
            KDOSTLS-PREP-S-FAILED EXIT
        THEN
        _KDRL-U @ TLS-RBUF-CONSUME
        KDOSTLS-PREP-S-PENDING EXIT
    THEN
    TLS-RECV-REC C@ TLS-CT-APP-DATA <> IF
        TLS-CONNECT-E-HANDSHAKE-RECORD _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-CONNECT _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    _KDCP-A @ KDOSTLS.CONTEXT @ TLS-RECV-REC _KDRL-U @ TLS-PLAIN-BUF
        TLS-DECRYPT-RECORD
    _KDRL-U @ TLS-RBUF-CONSUME
    _KDHD-PLEN ! _KDHD-CTYPE !
    _KDHD-PLEN @ 0= _KDHD-CTYPE @ TLS-CT-HANDSHAKE <> OR IF
        TLS-CONNECT-E-HANDSHAKE-PROCESS
            _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-CONNECT _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    TLS-PLAIN-BUF _KDHD-PLEN @ _KDOSTLS-HS-APPEND 0= IF
        TLS-CONNECT-E-HANDSHAKE-PROCESS
            _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-CONNECT _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    KDOSTLS-PHASE-HANDSHAKE-MESSAGE _KDOSTLS-PHASE!
    KDOSTLS-PREP-S-PENDING ;

: _KDOSTLS-STEP-HANDSHAKE-MESSAGE  ( -- prep-status )
    _KDCP-A @ KDOSTLS.CONTEXT @ _KDOSTLS-HS-PROCESS-ONE
    DUP _KDOSTLS-HS-S-FAILED = IF
        DROP TLS-CONNECT-E-HANDSHAKE-PROCESS
            _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-CONNECT _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    _KDOSTLS-HS-S-INCOMPLETE = IF
        KDOSTLS-PHASE-HANDSHAKE-RECORD _KDOSTLS-PHASE!
        KDOSTLS-PREP-S-PENDING EXIT
    THEN
    _KDCP-A @ KDOSTLS.CONTEXT @ TLS-CTX.HS-STATE @
        TLSH-SERVER-FINISHED = IF
        TLS-HS-RBUF-ERROR @ TLS-HS-RBUF-LEN @ 0<> OR IF
            TLS-CONNECT-E-HANDSHAKE-RECORD
                _KDCP-A @ KDOSTLS.NATIVE-ERROR !
            KDOSTLS-E-CONNECT _KDCP-A @ KDOSTLS.LAST-ERROR !
            KDOSTLS-PREP-S-FAILED EXIT
        THEN
        KDOSTLS-PHASE-CLIENT-FINISHED _KDOSTLS-PHASE!
    ELSE
        TLS-HS-RBUF-LEN @ IF
            KDOSTLS-PHASE-HANDSHAKE-MESSAGE
        ELSE
            KDOSTLS-PHASE-HANDSHAKE-RECORD
        THEN _KDOSTLS-PHASE!
    THEN
    KDOSTLS-PREP-S-PENDING ;

: _KDOSTLS-STEP-CLIENT-FINISHED  ( -- prep-status )
    _KDCP-A @ _KDOSTLS-CTX-EXACT? 0= IF
        TLS-CONNECT-E-AUTH _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-AUTH _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    _KDCP-A @ KDOSTLS.CONTEXT @ TLS-SEND-REC TLS-HANDSHAKE-COMPLETE
    DUP _KDCP-A @ KDOSTLS.FINISHED-U ! 0= IF
        TLS-CONNECT-E-FINISHED _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-CONNECT _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    _KDCP-A @ _KDOSTLS-CTX-EXACT? 0= IF
        TLS-CONNECT-E-AUTH _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-AUTH _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    _KDCP-A @ KDOSTLS.CONTEXT @
    DUP TLS-CTX.STATE @ TLSS-HANDSHAKE <>
    OVER TLS-CTX.HS-STATE @ TLSH-APPLICATION-READY <> OR
    OVER TLS-CTX.PEER-AUTH @ 1 <> OR
    SWAP TLS-CTX.ERROR @ TLS-E-OK <> OR IF
        TLS-CONNECT-E-AUTH _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-AUTH _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    KDOSTLS-PHASE-CLIENT-FINISHED-SEND _KDOSTLS-PHASE!
    KDOSTLS-PREP-S-PENDING ;

: _KDOSTLS-STEP-CLIENT-FINISHED-SEND  ( -- prep-status )
    _KDCP-A @ KDOSTLS.REMOTE-IP NEXT-HOP ARP-LOOKUP DUP 0= IF
        DROP KDOSTLS-PHASE-CLIENT-FINISHED-SEND
            _KDOSTLS-REMOTE-ARP-FOR EXIT
    THEN DROP
    _KDCP-A @ _KDOSTLS-TCB@ DUP 0= IF
        DROP TLS-CONNECT-E-FINISHED _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-CONNECT _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN DROP
    _KDCP-A @ _KDOSTLS-SEND-READY?
    DUP IF
        DUP TCP-ACCEPT-E-BUSY = IF
            2DROP KDOSTLS-PREP-S-PENDING EXIT
        THEN
        2DROP
        TLS-CONNECT-E-FINISHED _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-CONNECT _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN DROP 0= IF
        _KDCP-A @ _KDOSTLS-TCB@ DUP IF
            TCB.STATE @ TCPS-ESTABLISHED = IF
                _KDCP-A @ _KDOSTLS-TCP-RECEIVE-ONE
                KDOSTLS-PREP-S-PENDING EXIT
            THEN
        ELSE
            DROP
        THEN
        TLS-CONNECT-E-FINISHED _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-CONNECT _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    TLS-SEND-REC _KDCP-A @ KDOSTLS.FINISHED-U @ _KDCP-A @
    _KDOSTLS-SEND-EXACT
    DUP IF
        DUP TCP-ACCEPT-E-BUSY = IF
            2DROP KDOSTLS-PREP-S-PENDING EXIT
        THEN
        2DROP
        TLS-CONNECT-E-FINISHED _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-CONNECT _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN DROP
    _KDCP-A @ KDOSTLS.FINISHED-U @ <> IF
        TLS-CONNECT-E-FINISHED _KDCP-A @ KDOSTLS.NATIVE-ERROR !
        KDOSTLS-E-CONNECT _KDCP-A @ KDOSTLS.LAST-ERROR !
        KDOSTLS-PREP-S-FAILED EXIT
    THEN
    KDOSTLS-PHASE-OPEN _KDOSTLS-PHASE!
    KDOSTLS-PREP-S-PENDING ;

