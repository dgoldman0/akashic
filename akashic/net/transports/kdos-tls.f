    _KDPP-A @ _KDOSTLS-NOW@ _KDPP-NOW ! ;

: _KDOSTLS-PREP-STEP-RECORD  ( cycles adapter -- )
    >R DUP R@ KDOSTLS.LAST-STEP-CYCLES !
    DUP R@ KDOSTLS.MAX-STEP-CYCLES @ > IF
        R@ KDOSTLS.MAX-STEP-CYCLES !
    ELSE
        DROP
    THEN
    1 R> KDOSTLS.STEP-COUNT +! ;

: _KDOSTLS-PREP-POLL-BODY  ( adapter -- prep-status )
    _KDPP-A !
    \ A lower abort or shared discard may need more than one cooperative
    \ cleanup step.  Terminal publication waits until exact retirement has
    \ actually completed.
    _KDPP-A @ KDOSTLS.PHASE @ KDOSTLS-PHASE-FAILED = IF
        _KDPP-A @ _KDOSTLS-PREP-DETACH IF
            KDOSTLS-PREP-S-FAILED
        ELSE
            KDOSTLS-PREP-S-PENDING
        THEN EXIT
    THEN
    _KDPP-A @ KDOSTLS.PHASE @ KDOSTLS-PHASE-CANCELLED = IF
        _KDPP-A @ _KDOSTLS-PREP-DETACH IF
            KDOSTLS-PREP-S-CANCELLED
        ELSE
            KDOSTLS-PREP-S-PENDING
        THEN EXIT
    THEN
    \ OPEN is already beyond the opening lease and beyond its deadline.
    _KDPP-A @ KDOSTLSP.STATE @ KDOSTLSP-STATE-OPEN = IF
        _KDPP-A @ _KDOSTLS-OPEN-VALID? IF
            KDOSTLS-E-OK _KDPP-A @ KDOSTLS.LAST-ERROR !
            KDOSTLS-PREP-S-READY
        ELSE
            KDOSTLS-E-AUTH _KDPP-A @ _KDOSTLS-PREP-FAIL
        THEN EXIT
    THEN
    _KDPP-A @ KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-RESERVED =
    SWAP KDOSTLSP-STATE-PUBLISHED = OR 0= IF
        KDOSTLS-E-INVALID _KDPP-A @ _KDOSTLS-PREP-FAIL EXIT
    THEN
    \ Only RESERVED carries outbound's lifetime KDOSNET lease and still
    \ depends on the mutable global trust/scratch generation.
    _KDPP-A @ KDOSTLSP.STATE @ KDOSTLSP-STATE-RESERVED = IF
        _KDPP-A @ KDOSNET-OPERATE? 0= IF
            KDOSTLS-E-CLEANUP _KDPP-A @ _KDOSTLS-PREP-FAIL EXIT
        THEN
        TLS-TRUST-GENERATION @
        _KDPP-A @ KDOSTLS.TRUST-GENERATION @ <> IF
            KDOSTLS-E-TRUST-CHANGED _KDPP-A @ _KDOSTLS-PREP-FAIL EXIT
        THEN
    ELSE
        \ PUBLISHED has transferred lower authority and must not retain the
        \ opening lease while it waits for a transient ACTIVATE claim.
        _KDPP-A @ KDOSNET-OWNER? IF
            KDOSTLS-E-CLEANUP _KDPP-A @ _KDOSTLS-PREP-FAIL EXIT
        THEN
    THEN
    ['] _KDOSTLS-PREP-POLL-NOW CATCH IF
        KDOSTLS-E-FAULT _KDPP-A @ _KDOSTLS-PREP-FAIL EXIT
    THEN
    _KDPP-A @ KDOSTLSP.STATE @ KDOSTLSP-STATE-RESERVED = IF
        _KDPP-A @ KDOSNET-OPERATE? 0= IF
            KDOSTLS-E-CLEANUP _KDPP-A @ _KDOSTLS-PREP-FAIL EXIT
        THEN
    THEN
    _KDPP-NOW @
    _KDPP-A @ KDOSTLS.DEADLINE-MS @ _KDOSTLS-TIME-REACHED? IF
        KDOSTLS-E-TIMEOUT _KDPP-A @ _KDOSTLS-PREP-FAIL EXIT
    THEN
    PERF-CYCLES _KDCP-STEP-START !
    ['] _KDOSTLS-PREP-POLL-INNER CATCH
    PERF-CYCLES _KDCP-STEP-START @ - _KDPP-A @
        _KDOSTLS-PREP-STEP-RECORD
    ?DUP IF
        DROP
        \ ACTIVATE may have completed before a custom opening step threw.
        \ A fully valid shared port is already the safer terminal result.
        _KDPP-A @ KDOSTLSP.STATE @ KDOSTLSP-STATE-OPEN =
        _KDPP-A @ _KDOSTLS-OPEN-VALID? AND IF
            KDOSTLS-E-OK _KDPP-A @ KDOSTLS.LAST-ERROR !
            KDOSTLS-PREP-S-READY EXIT
        THEN
        KDOSTLS-E-FAULT _KDPP-A @ _KDOSTLS-PREP-FAIL EXIT
    THEN
    _KDCP-STEP-STATUS !
    _KDPP-A @ KDOSTLSP.STATE @ KDOSTLSP-STATE-RESERVED = IF
        _KDPP-A @ KDOSNET-OPERATE? 0= IF
            KDOSTLS-E-CLEANUP _KDPP-A @ _KDOSTLS-PREP-FAIL EXIT
        THEN
        TLS-TRUST-GENERATION @
        _KDPP-A @ KDOSTLS.TRUST-GENERATION @ <> IF
            KDOSTLS-E-TRUST-CHANGED _KDPP-A @ _KDOSTLS-PREP-FAIL EXIT
        THEN
    ELSE
        _KDPP-A @ KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-PUBLISHED =
        SWAP KDOSTLSP-STATE-OPEN = OR IF
            _KDPP-A @ KDOSNET-OWNER? IF
                KDOSTLS-E-CLEANUP _KDPP-A @ _KDOSTLS-PREP-FAIL EXIT
            THEN
        THEN
    THEN
    _KDCP-STEP-STATUS @ DUP KDOSTLS-PREP-S-PENDING = IF
        DROP
        _KDPP-A @ KDOSTLSP.STATE @ KDOSTLSP-STATE-OPEN =
        _KDPP-A @ _KDOSTLS-OPEN-VALID? AND IF
            KDOSTLS-E-OK _KDPP-A @ KDOSTLS.LAST-ERROR !
            KDOSTLS-PREP-S-READY
        ELSE
            KDOSTLS-PREP-S-PENDING
        THEN EXIT
    THEN
    DUP KDOSTLS-PREP-S-READY = IF
        _KDPP-A @ KDOSTLS.PHASE @ KDOSTLS-PHASE-OPEN =
        _KDPP-A @ _KDOSTLS-OPEN-VALID? AND IF
            KDOSTLS-E-OK _KDPP-A @ KDOSTLS.LAST-ERROR !
            EXIT
        THEN
        DROP KDOSTLS-E-INVALID _KDPP-A @ _KDOSTLS-PREP-FAIL EXIT
    THEN
    DUP KDOSTLS-PREP-S-CANCELLED = IF
        DROP _KDPP-A @ KDOSTLS-PREP-CANCEL EXIT
    THEN
    KDOSTLS-PREP-S-FAILED = IF
        _KDPP-A @ KDOSTLS.LAST-ERROR @ DUP KDOSTLS-E-OK = IF
            DROP KDOSTLS-E-FAULT
        THEN
        _KDPP-A @ _KDOSTLS-PREP-FAIL EXIT
    THEN
    KDOSTLS-E-INVALID _KDPP-A @ _KDOSTLS-PREP-FAIL ;

: KDOSTLS-PREP-POLL  ( adapter -- prep-status )
    COREID 0<> IF DROP KDOSTLS-PREP-S-FAILED EXIT THEN
    _KDPP-BUSY @ IF DROP KDOSTLS-PREP-S-FAILED EXIT THEN
    -1 _KDPP-BUSY !
    _KDOSTLS-PREP-POLL-BODY
    0 _KDPP-BUSY ! ;

: _KDOSTLS-NIO-OPEN-START  ( adapter -- nio-status )
    KDOSTLS-PREP-START
    DUP KDOSTLS-PREP-S-PENDING = IF DROP NIO-S-PENDING EXIT THEN
    DUP KDOSTLS-PREP-S-READY = IF DROP NIO-S-OK EXIT THEN
    DUP KDOSTLS-PREP-S-CANCELLED = IF DROP NIO-S-CANCELLED EXIT THEN
    DROP NIO-S-FAILED ;

: _KDOSTLS-NIO-OPEN-POLL  ( adapter -- nio-status )
    KDOSTLS-PREP-POLL
    DUP KDOSTLS-PREP-S-PENDING = IF DROP NIO-S-PENDING EXIT THEN
    DUP KDOSTLS-PREP-S-READY = IF DROP NIO-S-OK EXIT THEN
    DUP KDOSTLS-PREP-S-CANCELLED = IF DROP NIO-S-CANCELLED EXIT THEN
    DROP NIO-S-FAILED ;

: _KDOSTLS-NIO-CANCEL  ( adapter -- )
    COREID 0<> IF DROP KDOSTLS-E-PLATFORM NEGATE THROW THEN
    KDOSTLS-PREP-CANCEL KDOSTLS-PREP-S-CANCELLED <> IF
        KDOSTLS-E-CLEANUP NEGATE THROW
    THEN ;

VARIABLE _KDTO-A

: _KDOSTLS-NIO-OPEN  ( adapter -- nio-status )
    COREID 0<> IF DROP NIO-S-FAILED EXIT THEN
    DUP _KDTO-A ! _KDOSTLS-NIO-OPEN-START
    DUP NIO-S-PENDING <> IF EXIT THEN DROP
    4096 0 DO
        _KDTO-A @ _KDOSTLS-NIO-OPEN-POLL
        DUP NIO-S-PENDING <> IF UNLOOP EXIT THEN DROP
        NET-IDLE
    LOOP
    _KDTO-A @ KDOSTLS-PREP-CANCEL
    KDOSTLS-PREP-S-CANCELLED <> IF
        KDOSTLS-E-CLEANUP NEGATE THROW
    THEN
    NIO-S-FAILED ;

