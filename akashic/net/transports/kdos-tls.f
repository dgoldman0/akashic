    DUP KDOSNET-OPERATE? 0= IF DROP 0 EXIT THEN
    DUP _KDOSTLS-TCB-MATCH? 0= IF DROP 0 EXIT THEN
    KDOSTLS.CONTEXT @ TLS-CTX.TCB @ ;

