VARIABLE _KDOSTLSP-STAGE-R

: KDOSTLSP-PUBLISH  ( socket-sd record -- status )
    _KDOSTLSP-IN-CALL @ IF 2DROP KDOSTLSP-S-BUSY EXIT THEN
    _KDOSTLSP-STAGE-R ! _KDOSTLSP-STAGE-SD !
    COREID 0<> IF KDOSTLSP-S-PLATFORM EXIT THEN
    _KDOSTLSP-STAGE-R @ _KDOSTLSP-VALID? 0= IF
        KDOSTLSP-S-INVALID EXIT
    THEN
    _KDOSTLSP-STAGE-R @ KDOSTLSP.STATE @
    KDOSTLSP-STATE-RESERVED <> IF KDOSTLSP-S-STATE EXIT THEN
    _KDOSTLSP-STAGE-R @ KDOSTLSP.SOCKET-SD @ 0<> IF
        KDOSTLSP-S-STATE EXIT
    THEN
    _KDOSTLSP-STAGE-SD @ 0= IF KDOSTLSP-S-INVALID EXIT THEN
    \ Store the descriptor before any later interpretation.  If a malformed
    \ lower tuple contains both a socket and an error, the socket is still
    \ potentially transferred authority and must be retired through DISCARD.
    _KDOSTLSP-STAGE-SD @ _KDOSTLSP-STAGE-R @ KDOSTLSP.SOCKET-SD !
    KDOSTLSP-STATE-PUBLISHED _KDOSTLSP-STAGE-R @ KDOSTLSP.STATE !
    KDOSTLSP-S-OK ;

VARIABLE _KDOSTLSP-ACTIVATE-R

: KDOSTLSP-ACTIVATE  ( record -- status )
    _KDOSTLSP-IN-CALL @ IF DROP KDOSTLSP-S-PENDING EXIT THEN
    _KDOSTLSP-ACTIVATE-R !
    COREID 0<> IF KDOSTLSP-S-PLATFORM EXIT THEN
    _KDOSTLSP-ACTIVATE-R @ _KDOSTLSP-VALID? 0= IF
        KDOSTLSP-S-INVALID EXIT
    THEN
    _KDOSTLSP-ACTIVATE-R @ KDOSTLSP.STATE @
    KDOSTLSP-STATE-PUBLISHED <>
    _KDOSTLSP-ACTIVATE-R @ KDOSTLSP.SOCKET-SD @ 0= OR IF
        KDOSTLSP-S-STATE EXIT
    THEN
    _KDOSTLSP-ACTIVATE-R @ _KDOSTLSP-R !
    0 _KDOSTLSP-IOR !
    ['] _KDOSTLSP-ACTIVATE-OP _KDOSTLSP-WITH
    _KDOSTLSP-CLAIM-STATUS @ DUP IF
        DUP _KDOSTLSP-NET-CONTENDED? IF
            DROP KDOSTLSP-S-PENDING EXIT
        THEN
        _KDOSTLSP-NET-FAULT KDOSTLSP-S-LOWER EXIT
    THEN DROP
    _KDOSTLSP-LATCH-PRIMARY-THROW
    _KDOSTLSP-THROW @ 0= IF
        _KDOSTLSP-IOR @ _KDOSTLSP-LATCH-PRIMARY-IOR
    THEN
    _KDOSTLSP-RELEASED? 0= IF KDOSTLSP-S-LOWER EXIT THEN
    _KDOSTLSP-THROW @ ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-ACTIVATE-R @
        _KDOSTLSP-MARK-ERROR KDOSTLSP-S-LOWER EXIT
    THEN
    _KDOSTLSP-IOR @ DUP _KDOSTLSP-BUSY-IOR? IF
        DROP KDOSTLSP-S-PENDING EXIT
    THEN
    ?DUP IF
        _KDOSTLSP-ACTIVATE-R @ _KDOSTLSP-MARK-ERROR
        KDOSTLSP-S-LOWER EXIT
    THEN
    KDOSTLSP-STATE-OPEN _KDOSTLSP-ACTIVATE-R @ KDOSTLSP.STATE !
    \ Outbound may temporarily replace cleanup callbacks while its raw
    \ connector owns RESERVED.  Switch every established callback back here
    \ without touching NIO's open callbacks or in-progress publication state.
    _KDOSTLSP-ACTIVATE-R @ _KDOSTLSP-BIND-ESTABLISHED
    KDOSTLSP-S-OK ;

: KDOSTLSP-ADOPT-OPEN  ( record -- port|0 status )
    _KDOSTLSP-IN-CALL @ IF DROP 0 KDOSTLSP-S-PENDING EXIT THEN
    DUP _KDOSTLSP-ACTIVATE-R ! KDOSTLSP-ACTIVATE
    DUP KDOSTLSP-S-OK <> IF 0 SWAP EXIT THEN DROP
    \ Premature NIO calls may have changed only wrapper bookkeeping.  Reset
    \ it after the exact published authority has been validated, while
    \ preserving descriptor-local lower callbacks and diagnostics.
    _KDOSTLSP-ACTIVATE-R @ _KDOSTLSP-INSTALL
    _KDOSTLSP-ACTIVATE-R @ KDOSTLSP.PORT NIO-OPEN
    NIO-S-OK <> IF
        KDOSTLSP-E-STATE _KDOSTLSP-ACTIVATE-R @ _KDOSTLSP-MARK-ERROR
        0 KDOSTLSP-S-LOWER EXIT
    THEN
    _KDOSTLSP-ACTIVATE-R @ KDOSTLSP.PORT KDOSTLSP-S-OK ;

: KDOSTLSP-CLOSE-TIMEOUT!  ( timeout-ms record -- status )
    _KDOSTLSP-IN-CALL @ IF 2DROP KDOSTLSP-S-BUSY EXIT THEN
    COREID 0<> IF 2DROP KDOSTLSP-S-PLATFORM EXIT THEN
    DUP _KDOSTLSP-VALID? 0= IF 2DROP KDOSTLSP-S-INVALID EXIT THEN
    DUP KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-RESET =
    SWAP KDOSTLSP-STATE-RESERVED = OR 0= IF
        2DROP KDOSTLSP-S-STATE EXIT
    THEN
    OVER 0> 0= IF 2DROP KDOSTLSP-S-INVALID EXIT THEN
    KDOSTLSP.CLOSE-TIMEOUT ! KDOSTLSP-S-OK ;

