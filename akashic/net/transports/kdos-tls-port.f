\ =====================================================================
\  kdos-tls-port.f - Established KDOS TLS socket as an NIO byte stream
\ =====================================================================
\  This is the common post-authentication transport for both outbound and
\  inbound TLS composition.  Its only lower authority is a KDOS TLS socket
\  descriptor.  Handshake owners stage that descriptor here only after the
\  lower publication transaction has transferred authority; a separate
\  adoption step makes the embedded NIO port callable.
\
\  KDOSNET is acquired for one port operation, never for the lifetime of the
\  connection.  Ordinary contention is retryable.  A live socket remains in
\  this caller-owned record until graceful close or the exact TLS-socket
\  abort entry has proved retirement.  Uncertain retirement is quarantined
\  without pretending that the record or socket can be reused.
\
\  Producer lifecycle:
\    KDOSTLSP-INIT          ( record -- status )
\    KDOSTLSP-RESERVE       ( record -- status )
\    KDOSTLSP-PUBLISH       ( socket-sd record -- status )
\    KDOSTLSP-ACTIVATE      ( record -- status )
\    KDOSTLSP-ADOPT-OPEN    ( record -- port|0 status )
\
\  PUBLISH is the authority-transfer staging point.  It deliberately leaves
\  the embedded port inert.  Outbound's NIO open callback uses ACTIVATE so
\  NIO can publish its own successful open without losing connector fields.
\  An inbound XIO owner uses ADOPT-OPEN while success remains retained; only
\  after that transfer commits does it consume the same success with XIO-TAKE.
\  ADOPT-OPEN installs and opens the established-only NIO port itself.
\
\  Failed producers call DISCARD-STEP until it is terminal.  QUARANTINED
\  records retain any unresolved socket and are retryable only through
\  RECOVER-STEP.
\ =====================================================================

