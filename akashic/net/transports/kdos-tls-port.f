: KDOSTLSP-INIT  ( record -- status )
    _KDOSTLSP-IN-CALL @ IF DROP KDOSTLSP-S-BUSY EXIT THEN
    COREID 0<> IF DROP KDOSTLSP-S-PLATFORM EXIT THEN
    DUP 0= IF DROP KDOSTLSP-S-INVALID EXIT THEN
    DUP KDOSTLSP-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP KDOSTLSP-S-INVALID EXIT
    THEN
    DUP KDOSNET-OWNER? IF DROP KDOSTLSP-S-BUSY EXIT THEN
    DUP _KDOSTLSP-VALID? IF
        DUP _KDOSTLSP-REUSABLE? 0= IF DROP KDOSTLSP-S-STATE EXIT THEN
    THEN
    DUP KDOSTLSP-SIZE 0 FILL
    _KDOSTLSP-MAGIC-VALUE OVER _KDOSTLSP.MAGIC !
    KDOSTLSP-STATE-RESET OVER KDOSTLSP.STATE !
    KDOSTLSP-CLOSE-TIMEOUT-MS OVER KDOSTLSP.CLOSE-TIMEOUT !
    ['] _KDOSTLSP-NOW-DEFAULT OVER KDOSTLSP.NOW-XT !
    ['] _KDOSTLSP-SEND-DEFAULT OVER KDOSTLSP.SEND-XT !
    ['] _KDOSTLSP-RECV-DEFAULT OVER KDOSTLSP.RECV-XT !
    ['] _KDOSTLSP-STATUS-DEFAULT OVER KDOSTLSP.STATUS-XT !
    ['] _KDOSTLSP-READY-DEFAULT OVER KDOSTLSP.READY-XT !
    ['] _KDOSTLSP-POLL-DEFAULT OVER KDOSTLSP.POLL-XT !
    ['] _KDOSTLSP-CLOSE-TRY-DEFAULT OVER KDOSTLSP.CLOSE-TRY-XT !
    ['] _KDOSTLSP-ABORT-DEFAULT OVER KDOSTLSP.ABORT-XT !
    DUP _KDOSTLSP-INSTALL
    DROP KDOSTLSP-S-OK ;

: KDOSTLSP-RESET  ( record -- status )
    KDOSTLSP-INIT ;

: KDOSTLSP-RESERVE  ( record -- status )
    _KDOSTLSP-IN-CALL @ IF DROP KDOSTLSP-S-BUSY EXIT THEN
    COREID 0<> IF DROP KDOSTLSP-S-PLATFORM EXIT THEN
    DUP _KDOSTLSP-VALID? 0= IF DROP KDOSTLSP-S-INVALID EXIT THEN
    DUP KDOSTLSP.STATE @ KDOSTLSP-STATE-RESET <>
    OVER KDOSTLSP.SOCKET-SD @ 0<> OR IF
        DROP KDOSTLSP-S-STATE EXIT
    THEN
    DUP 0 SWAP KDOSTLSP.LAST-ERROR !
    DUP 0 SWAP KDOSTLSP.CLEANUP-ERROR !
    DUP 0 SWAP KDOSTLSP.OWNER-STATUS !
    DUP 0 SWAP KDOSTLSP.CLOSE-DEADLINE !
    DUP 0 SWAP KDOSTLSP.CLOSE-FALLBACKS !
    DUP 0 SWAP KDOSTLSP.ABORT-STATUS !
    KDOSTLSP-STATE-RESERVED SWAP KDOSTLSP.STATE !
    KDOSTLSP-S-OK ;

: KDOSTLSP-UNRESERVE  ( record -- status )
    _KDOSTLSP-IN-CALL @ IF DROP KDOSTLSP-S-BUSY EXIT THEN
    COREID 0<> IF DROP KDOSTLSP-S-PLATFORM EXIT THEN
    DUP _KDOSTLSP-VALID? 0= IF DROP KDOSTLSP-S-INVALID EXIT THEN
    DUP KDOSTLSP.STATE @ KDOSTLSP-STATE-RESERVED <>
    OVER KDOSTLSP.SOCKET-SD @ 0<> OR IF
        DROP KDOSTLSP-S-STATE EXIT
    THEN
    KDOSTLSP-STATE-RESET SWAP KDOSTLSP.STATE !
    KDOSTLSP-S-OK ;

