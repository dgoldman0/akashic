: _KDOSTLSP-NIO-SEND-IMPL  ( buffer length record -- count nio-status )
    _KDOSTLSP-IN-CALL @ IF 2DROP DROP 0 NIO-S-OK EXIT THEN
    _KDOSTLSP-R ! _KDOSTLSP-U ! _KDOSTLSP-B !
    COREID 0<> IF 0 NIO-S-FAILED EXIT THEN
    _KDOSTLSP-R @ _KDOSTLSP-VALID? 0= IF 0 NIO-S-FAILED EXIT THEN
    _KDOSTLSP-R @ KDOSTLSP.STATE @ KDOSTLSP-STATE-OPEN <> IF
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-U @ 0<
    _KDOSTLSP-B @ 0= _KDOSTLSP-U @ 0> AND OR IF
        KDOSTLSP-E-STATE _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-B @ _KDOSTLSP-U @ MSPAN-NONWRAPPING? 0=
    _KDOSTLSP-B @ _KDOSTLSP-U @
    _KDOSTLSP-R @ KDOSTLSP-SIZE MSPAN-OVERLAP? OR IF
        KDOSTLSP-E-STATE _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-U @ 0= IF 0 NIO-S-OK EXIT THEN
    0 _KDOSTLSP-N ! 0 _KDOSTLSP-IOR !
    ['] _KDOSTLSP-SEND-OP _KDOSTLSP-WITH
    _KDOSTLSP-CLAIM-STATUS @ DUP IF
        DUP _KDOSTLSP-NET-CONTENDED? IF
            DROP 0 NIO-S-OK EXIT
        THEN
        _KDOSTLSP-NET-FAULT 0 NIO-S-FAILED EXIT
    THEN DROP
    _KDOSTLSP-LATCH-PRIMARY-THROW
    _KDOSTLSP-THROW @ 0= _KDOSTLSP-N @ 0= AND IF
        _KDOSTLSP-IOR @ _KDOSTLSP-LATCH-PRIMARY-IOR
    THEN
    _KDOSTLSP-N @ DUP 0< SWAP _KDOSTLSP-U @ > OR IF
        KDOSTLSP-E-STATE _KDOSTLSP-R @ _KDOSTLSP-ERROR!
    THEN
    _KDOSTLSP-RELEASED? 0= IF 0 NIO-S-FAILED EXIT THEN
    _KDOSTLSP-THROW @ ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-N @ DUP 0< SWAP _KDOSTLSP-U @ > OR IF
        KDOSTLSP-E-STATE _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-N @ 0= IF
        _KDOSTLSP-IOR @ DUP _KDOSTLSP-BUSY-IOR? IF
            DROP 0 NIO-S-OK EXIT
        THEN
        ?DUP IF
            _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
            0 NIO-S-FAILED EXIT
        THEN
    THEN
    _KDOSTLSP-N @ NIO-S-OK ;

: _KDOSTLSP-NIO-RECV-IMPL  ( buffer capacity record -- count nio-status )
    _KDOSTLSP-IN-CALL @ IF 2DROP DROP 0 NIO-S-OK EXIT THEN
    _KDOSTLSP-R ! _KDOSTLSP-U ! _KDOSTLSP-B !
    COREID 0<> IF 0 NIO-S-FAILED EXIT THEN
    _KDOSTLSP-R @ _KDOSTLSP-VALID? 0= IF 0 NIO-S-FAILED EXIT THEN
    _KDOSTLSP-R @ KDOSTLSP.STATE @ KDOSTLSP-STATE-OPEN <> IF
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-U @ 0> 0= _KDOSTLSP-B @ 0= OR IF
        KDOSTLSP-E-STATE _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-B @ _KDOSTLSP-U @ MSPAN-NONWRAPPING? 0=
    _KDOSTLSP-B @ _KDOSTLSP-U @
    _KDOSTLSP-R @ KDOSTLSP-SIZE MSPAN-OVERLAP? OR IF
        KDOSTLSP-E-STATE _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    0 _KDOSTLSP-N ! 0 _KDOSTLSP-IOR ! 0 _KDOSTLSP-READY !
    ['] _KDOSTLSP-RECV-OP _KDOSTLSP-WITH
    _KDOSTLSP-CLAIM-STATUS @ DUP IF
        DUP _KDOSTLSP-NET-CONTENDED? IF
            DROP 0 NIO-S-OK EXIT
        THEN
        _KDOSTLSP-NET-FAULT 0 NIO-S-FAILED EXIT
    THEN DROP
    _KDOSTLSP-LATCH-PRIMARY-THROW
    _KDOSTLSP-THROW @ 0= _KDOSTLSP-N @ 1 < AND IF
        _KDOSTLSP-IOR @ _KDOSTLSP-LATCH-PRIMARY-IOR
    THEN
    _KDOSTLSP-N @ 0< IF
        _KDOSTLSP-IOR @ DUP 0= IF DROP TLS-E-TRANSPORT THEN
        _KDOSTLSP-R @ _KDOSTLSP-ERROR!
    ELSE
        _KDOSTLSP-N @ _KDOSTLSP-U @ > IF
            KDOSTLSP-E-STATE _KDOSTLSP-R @ _KDOSTLSP-ERROR!
        THEN
    THEN
    _KDOSTLSP-RELEASED? 0= IF 0 NIO-S-FAILED EXIT THEN
    _KDOSTLSP-THROW @ ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-N @ 0< IF
        _KDOSTLSP-IOR @ DUP 0= IF DROP TLS-E-TRANSPORT THEN
        _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-N @ _KDOSTLSP-U @ > IF
        KDOSTLSP-E-STATE _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-N @ IF _KDOSTLSP-N @ NIO-S-OK EXIT THEN
    _KDOSTLSP-IOR @ DUP _KDOSTLSP-BUSY-IOR? IF
        DROP 0 NIO-S-OK EXIT
    THEN
    ?DUP IF
        _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-READY @ IF 0 NIO-S-EOF ELSE 0 NIO-S-OK THEN ;

: _KDOSTLSP-NIO-POLL-IMPL  ( record -- )
    _KDOSTLSP-IN-CALL @ IF DROP EXIT THEN
    COREID 0<> IF DROP KDOSTLSP-E-STATE THROW THEN
    DUP _KDOSTLSP-VALID? 0= IF DROP KDOSTLSP-E-STATE THROW THEN
    DUP _KDOSTLSP-R ! KDOSTLSP.STATE @ KDOSTLSP-STATE-OPEN <> IF
        KDOSTLSP-E-STATE THROW
    THEN
    ['] _KDOSTLSP-POLL-OP _KDOSTLSP-WITH
    _KDOSTLSP-CLAIM-STATUS @ DUP IF
        DUP _KDOSTLSP-NET-CONTENDED? IF DROP EXIT THEN
        _KDOSTLSP-NET-FAULT KDOSTLSP-E-STATE THROW
    THEN DROP
    _KDOSTLSP-LATCH-PRIMARY-THROW
    _KDOSTLSP-RELEASED? 0= IF KDOSTLSP-E-QUARANTINED THROW THEN
    _KDOSTLSP-THROW @ ?DUP IF
        _KDOSTLSP-THROW>IOR DUP _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        THROW
    THEN ;

\ ---------------------------------------------------------------------
\ Cooperative close, abort fallback, cancellation, and recovery
\ ---------------------------------------------------------------------

: _KDOSTLSP-TIME-REACHED?  ( now deadline -- flag )
    - 0< 0= ;

: _KDOSTLSP-ARM-DEADLINE  ( record -- armed? )
    _KDOSTLSP-R !
    _KDOSTLSP-NOW-GUARDED ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-ERROR! 0 EXIT
    THEN
    _KDOSTLSP-NOW @ _KDOSTLSP-R @ KDOSTLSP.CLOSE-TIMEOUT @ +
    _KDOSTLSP-R @ KDOSTLSP.CLOSE-DEADLINE ! -1 ;

: _KDOSTLSP-DEADLINE?  ( record -- expired? )
    _KDOSTLSP-R !
    _KDOSTLSP-NOW-GUARDED ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-ERROR! -1 EXIT
    THEN
    _KDOSTLSP-NOW @ _KDOSTLSP-R @ KDOSTLSP.CLOSE-DEADLINE @
    _KDOSTLSP-TIME-REACHED? ;

: _KDOSTLSP-BEGIN-ABORT  ( ior record -- )
    DUP KDOSTLSP.STATE @ KDOSTLSP-STATE-CLOSE-ABORT <> IF
        1 OVER KDOSTLSP.CLOSE-FALLBACKS +!
    THEN
    2DUP _KDOSTLSP-ERROR!
    KDOSTLSP-STATE-CLOSE-ABORT SWAP KDOSTLSP.STATE ! DROP ;

VARIABLE _KDOSTLSP-RETIRE-FINAL

: _KDOSTLSP-RETIRE-STEP  ( final-state record -- status )
    _KDOSTLSP-R ! _KDOSTLSP-RETIRE-FINAL !
    _KDOSTLSP-SETTLE-OWN-OWNER? 0= IF KDOSTLSP-S-PENDING EXIT THEN
    _KDOSTLSP-R @ KDOSTLSP.SOCKET-SD @ 0= IF
        _KDOSTLSP-RETIRE-FINAL @ _KDOSTLSP-R @ KDOSTLSP.STATE !
        KDOSTLSP-S-OK EXIT
    THEN
    0 _KDOSTLSP-IOR ! 0 _KDOSTLSP-ABORTED ! 0 _KDOSTLSP-RETIRED !
    ['] _KDOSTLSP-ABORT-OP _KDOSTLSP-WITH
    _KDOSTLSP-CLAIM-STATUS @ DUP IF
        DUP _KDOSTLSP-NET-CONTENDED? IF
            DROP KDOSTLSP-S-PENDING EXIT
        THEN
        DROP KDOSTLSP-E-CLEANUP _KDOSTLSP-R @ _KDOSTLSP-QUARANTINE
        KDOSTLSP-S-PLATFORM EXIT
    THEN DROP
    _KDOSTLSP-LATCH-CLEANUP-THROW
    _KDOSTLSP-THROW @ 0= IF
        _KDOSTLSP-IOR @ _KDOSTLSP-LATCH-CLEANUP-IOR
    THEN
    _KDOSTLSP-RELEASED? 0= IF KDOSTLSP-S-LOWER EXIT THEN
    _KDOSTLSP-THROW @ ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-QUARANTINE
        KDOSTLSP-S-LOWER EXIT
    THEN
    _KDOSTLSP-RETIRED @ IF
        _KDOSTLSP-RETIRE-FINAL @ _KDOSTLSP-R @ KDOSTLSP.STATE !
        KDOSTLSP-S-OK EXIT
    THEN
    _KDOSTLSP-IOR @ _KDOSTLSP-BUSY-IOR? IF
        KDOSTLSP-S-PENDING EXIT
    THEN
    _KDOSTLSP-IOR @ _KDOSTLSP-R @ _KDOSTLSP-QUARANTINE
    KDOSTLSP-S-LOWER ;

: _KDOSTLSP-DETACHED  ( record -- nio-status )
    DUP 0 SWAP KDOSTLSP.SOCKET-SD !
    KDOSTLSP-STATE-CLOSED OVER KDOSTLSP.STATE !
    KDOSTLSP.LAST-ERROR @ IF NIO-S-FAILED ELSE NIO-S-OK THEN ;

: _KDOSTLSP-CLOSE-TRY-STEP  ( record -- nio-status )
    _KDOSTLSP-R !
    0 _KDOSTLSP-IOR ! 0 _KDOSTLSP-RETIRED !
    ['] _KDOSTLSP-CLOSE-TRY-OP _KDOSTLSP-WITH
    _KDOSTLSP-CLAIM-STATUS @ DUP IF
        DUP _KDOSTLSP-NET-CONTENDED? IF
            DROP NIO-S-PENDING EXIT
        THEN
        _KDOSTLSP-NET-FAULT NIO-S-FAILED EXIT
    THEN DROP
    _KDOSTLSP-LATCH-PRIMARY-THROW
    _KDOSTLSP-THROW @ 0= IF
        _KDOSTLSP-IOR @ DUP TLS-E-WOULD-BLOCK = IF
            DROP
        ELSE
            _KDOSTLSP-LATCH-PRIMARY-IOR
        THEN
    THEN
    _KDOSTLSP-RELEASED? 0= IF NIO-S-FAILED EXIT THEN
    _KDOSTLSP-THROW @ ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-BEGIN-ABORT
        NIO-S-PENDING EXIT
    THEN
    _KDOSTLSP-RETIRED @ IF _KDOSTLSP-R @ _KDOSTLSP-DETACHED EXIT THEN
    _KDOSTLSP-IOR @
    DUP _KDOSTLSP-BUSY-IOR? IF DROP NIO-S-PENDING EXIT THEN
    TLS-E-WOULD-BLOCK = IF
        KDOSTLSP-STATE-CLOSE-POLL _KDOSTLSP-R @ KDOSTLSP.STATE !
        NIO-S-PENDING EXIT
    THEN
    _KDOSTLSP-IOR @ _KDOSTLSP-R @ _KDOSTLSP-BEGIN-ABORT
    NIO-S-PENDING ;

: _KDOSTLSP-CLOSE-POLL-STEP  ( record -- nio-status )
    _KDOSTLSP-R !
    ['] _KDOSTLSP-POLL-OP _KDOSTLSP-WITH
    _KDOSTLSP-CLAIM-STATUS @ DUP IF
        DUP _KDOSTLSP-NET-CONTENDED? IF
            DROP NIO-S-PENDING EXIT
        THEN
        _KDOSTLSP-NET-FAULT NIO-S-FAILED EXIT
    THEN DROP
    _KDOSTLSP-LATCH-PRIMARY-THROW
    _KDOSTLSP-RELEASED? 0= IF NIO-S-FAILED EXIT THEN
    _KDOSTLSP-THROW @ ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-BEGIN-ABORT
        NIO-S-PENDING EXIT
    THEN
    KDOSTLSP-STATE-CLOSE-TRY _KDOSTLSP-R @ KDOSTLSP.STATE !
    NIO-S-PENDING ;

: _KDOSTLSP-CLOSE-ABORT-STEP  ( record -- nio-status )
    DUP _KDOSTLSP-R ! KDOSTLSP-STATE-CLOSED SWAP _KDOSTLSP-RETIRE-STEP
    DUP KDOSTLSP-S-PENDING = IF DROP NIO-S-PENDING EXIT THEN
    KDOSTLSP-S-OK = IF
        _KDOSTLSP-R @ KDOSTLSP.LAST-ERROR @ IF
            NIO-S-FAILED
        ELSE
            NIO-S-OK
        THEN
    ELSE
        NIO-S-FAILED
    THEN ;

: _KDOSTLSP-CLOSE-STEP  ( record -- nio-status )
    DUP _KDOSTLSP-R ! KDOSTLSP.STATE @ DUP
    KDOSTLSP-STATE-CLOSE-TRY = OVER
    KDOSTLSP-STATE-CLOSE-POLL = OR IF
        DROP _KDOSTLSP-R @ _KDOSTLSP-DEADLINE? IF
            _KDOSTLSP-R @ KDOSTLSP.LAST-ERROR @ DUP 0= IF
                DROP KDOSTLSP-E-TIMEOUT
            THEN
            _KDOSTLSP-R @ _KDOSTLSP-BEGIN-ABORT
            NIO-S-PENDING EXIT
        THEN
        _KDOSTLSP-R @ KDOSTLSP.STATE @
    THEN
    CASE
        KDOSTLSP-STATE-OPEN OF
            _KDOSTLSP-R @ _KDOSTLSP-ARM-DEADLINE 0= IF
                _KDOSTLSP-R @ KDOSTLSP.LAST-ERROR @
                _KDOSTLSP-R @ _KDOSTLSP-BEGIN-ABORT
                NIO-S-PENDING
            ELSE
                KDOSTLSP-STATE-CLOSE-TRY
                _KDOSTLSP-R @ KDOSTLSP.STATE !
                _KDOSTLSP-R @ _KDOSTLSP-CLOSE-TRY-STEP
            THEN
        ENDOF
        KDOSTLSP-STATE-ERROR OF
            _KDOSTLSP-R @ KDOSTLSP.LAST-ERROR @ DUP 0= IF
                DROP KDOSTLSP-E-STATE
            THEN
            _KDOSTLSP-R @ _KDOSTLSP-BEGIN-ABORT NIO-S-PENDING
        ENDOF
        KDOSTLSP-STATE-CLOSE-TRY OF
            _KDOSTLSP-R @ _KDOSTLSP-CLOSE-TRY-STEP
        ENDOF
        KDOSTLSP-STATE-CLOSE-POLL OF
            _KDOSTLSP-R @ _KDOSTLSP-CLOSE-POLL-STEP
        ENDOF
        KDOSTLSP-STATE-CLOSE-ABORT OF
            _KDOSTLSP-R @ _KDOSTLSP-CLOSE-ABORT-STEP
        ENDOF
        KDOSTLSP-STATE-CLOSED OF NIO-S-OK ENDOF
        KDOSTLSP-STATE-CANCELLED OF NIO-S-CANCELLED ENDOF
        KDOSTLSP-STATE-QUARANTINED OF NIO-S-FAILED ENDOF
        NIO-S-FAILED SWAP
    ENDCASE ;

: _KDOSTLSP-NIO-CLOSE-START-IMPL  ( record -- nio-status )
    _KDOSTLSP-IN-CALL @ IF DROP NIO-S-PENDING EXIT THEN
    COREID 0<> IF DROP NIO-S-FAILED EXIT THEN
    DUP _KDOSTLSP-VALID? 0= IF DROP NIO-S-FAILED EXIT THEN
    DUP KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-RESET =
    OVER KDOSTLSP-STATE-CLOSED = OR IF 2DROP NIO-S-OK EXIT THEN
    KDOSTLSP-STATE-CANCELLED = IF DROP NIO-S-CANCELLED EXIT THEN
    DUP _KDOSTLSP-NIO-ACTIVE? 0= IF DROP NIO-S-FAILED EXIT THEN
    _KDOSTLSP-CLOSE-STEP ;

: _KDOSTLSP-NIO-CLOSE-POLL-IMPL  ( record -- nio-status )
    _KDOSTLSP-IN-CALL @ IF DROP NIO-S-PENDING EXIT THEN
    COREID 0<> IF DROP NIO-S-FAILED EXIT THEN
    DUP _KDOSTLSP-VALID? 0= IF DROP NIO-S-FAILED EXIT THEN
    DUP KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-CLOSED = IF
        2DROP NIO-S-OK EXIT
    THEN
    KDOSTLSP-STATE-CANCELLED = IF DROP NIO-S-CANCELLED EXIT THEN
    DUP _KDOSTLSP-NIO-ACTIVE? 0= IF DROP NIO-S-FAILED EXIT THEN
    _KDOSTLSP-CLOSE-STEP ;

VARIABLE _KDOSTLSP-BC-R
VARIABLE _KDOSTLSP-BC-STATUS

: _KDOSTLSP-NIO-CLOSE-IMPL  ( record -- )
    _KDOSTLSP-IN-CALL @ IF DROP KDOSTLSP-E-CONTENTION THROW THEN
    COREID 0<> IF DROP KDOSTLSP-E-STATE THROW THEN
    DUP _KDOSTLSP-BC-R ! _KDOSTLSP-NIO-CLOSE-START
    DUP NIO-S-OK = IF DROP EXIT THEN
    DUP NIO-S-PENDING <> IF DROP KDOSTLSP-E-CLEANUP THROW THEN DROP
    KDOSTLSP-CLOSE-POLL-MAX 0 DO
        _KDOSTLSP-BC-R @ _KDOSTLSP-NIO-CLOSE-POLL
        DUP _KDOSTLSP-BC-STATUS ! NIO-S-PENDING <> IF LEAVE THEN
    LOOP
    _KDOSTLSP-BC-STATUS @ DUP NIO-S-OK = IF DROP EXIT THEN
    NIO-S-PENDING = IF
        KDOSTLSP-E-TIMEOUT _KDOSTLSP-BC-R @ _KDOSTLSP-BEGIN-ABORT
        KDOSTLSP-CLOSE-POLL-MAX 0 DO
            _KDOSTLSP-BC-R @ _KDOSTLSP-NIO-CLOSE-POLL
            DUP _KDOSTLSP-BC-STATUS ! NIO-S-PENDING <> IF LEAVE THEN
        LOOP
    THEN
    _KDOSTLSP-BC-STATUS @ NIO-S-PENDING = IF
        KDOSTLSP-E-CLEANUP _KDOSTLSP-BC-R @ _KDOSTLSP-QUARANTINE
        KDOSTLSP-E-QUARANTINED THROW
    THEN
    KDOSTLSP-E-CLEANUP THROW ;

: _KDOSTLSP-NIO-CANCEL-IMPL  ( record -- )
    _KDOSTLSP-IN-CALL @ IF DROP KDOSTLSP-E-CONTENTION THROW THEN
    COREID 0<> IF DROP KDOSTLSP-E-STATE THROW THEN
    DUP _KDOSTLSP-VALID? 0= IF DROP KDOSTLSP-E-STATE THROW THEN
    DUP _KDOSTLSP-R ! KDOSTLSP.STATE @
    DUP KDOSTLSP-STATE-CLOSED = SWAP KDOSTLSP-STATE-CANCELLED = OR IF
        EXIT
    THEN
    _KDOSTLSP-R @ _KDOSTLSP-NIO-ACTIVE? 0= IF
        KDOSTLSP-E-STATE THROW
    THEN
    KDOSTLSP-STATE-CANCELLED _KDOSTLSP-R @ _KDOSTLSP-RETIRE-STEP
    DUP KDOSTLSP-S-OK = IF DROP EXIT THEN
    DUP KDOSTLSP-S-PENDING = IF
        DROP KDOSTLSP-E-CONTENTION _KDOSTLSP-R @ _KDOSTLSP-QUARANTINE
        KDOSTLSP-E-QUARANTINED THROW
    THEN
    DROP KDOSTLSP-E-QUARANTINED THROW ;

: KDOSTLSP-RECOVER-STEP  ( record -- status )
    _KDOSTLSP-IN-CALL @ IF DROP KDOSTLSP-S-PENDING EXIT THEN
    COREID 0<> IF DROP KDOSTLSP-S-PLATFORM EXIT THEN
    DUP _KDOSTLSP-VALID? 0= IF DROP KDOSTLSP-S-INVALID EXIT THEN
    DUP KDOSTLSP.STATE @ KDOSTLSP-STATE-QUARANTINED <> IF
        DROP KDOSTLSP-S-STATE EXIT
    THEN
    KDOSTLSP-STATE-CLOSED SWAP _KDOSTLSP-RETIRE-STEP ;

: KDOSTLSP-DISCARD-STEP  ( record -- status )
    _KDOSTLSP-IN-CALL @ IF DROP KDOSTLSP-S-PENDING EXIT THEN
    COREID 0<> IF DROP KDOSTLSP-S-PLATFORM EXIT THEN
    DUP _KDOSTLSP-VALID? 0= IF DROP KDOSTLSP-S-INVALID EXIT THEN
    DUP KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-RESET = IF
        2DROP KDOSTLSP-S-OK EXIT
    THEN
    DUP KDOSTLSP-STATE-RESERVED = IF
        DROP KDOSTLSP-STATE-RESET SWAP KDOSTLSP.STATE !
        KDOSTLSP-S-OK EXIT
    THEN
    DUP KDOSTLSP-STATE-PUBLISHED =
    OVER KDOSTLSP-STATE-ERROR = OR 0= IF
        DUP KDOSTLSP-STATE-QUARANTINED = IF
            DROP
            KDOSTLSP-RECOVER-STEP
        ELSE
            2DROP KDOSTLSP-S-STATE
        THEN EXIT
    THEN DROP
    KDOSTLSP-STATE-RESET SWAP _KDOSTLSP-RETIRE-STEP ;

