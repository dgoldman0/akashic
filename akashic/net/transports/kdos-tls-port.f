: _KDOSTLSP-WITH  ( operation-xt -- )
    -1 _KDOSTLSP-IN-CALL !
    _KDOSTLSP-R @ SWAP KDOSNET-WITH
    0 _KDOSTLSP-IN-CALL !
    _KDOSTLSP-RELEASE-STATUS !
    _KDOSTLSP-THROW !
    _KDOSTLSP-CLAIM-STATUS !
