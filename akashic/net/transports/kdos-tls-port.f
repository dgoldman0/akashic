\ Each word below is one complete lower logical operation.  KDOSNET-WITH
\ catches across the whole sequence, so SEND/RECV and their status probes
\ cannot be split by another Akashic network owner.
: _KDOSTLSP-ACTIVATE-OP  ( -- )
    _KDOSTLSP-STATUS-INNER ;

: _KDOSTLSP-SEND-OP  ( -- )
    _KDOSTLSP-SEND-INNER
    _KDOSTLSP-R @ KDOSNET-OPERATE? _KDOSTLSP-N @ 0= AND IF
        _KDOSTLSP-STATUS-INNER
    THEN ;

: _KDOSTLSP-RECV-OP  ( -- )
    _KDOSTLSP-RECV-INNER
    _KDOSTLSP-R @ KDOSNET-OPERATE? _KDOSTLSP-N @ 1 < AND IF
        _KDOSTLSP-STATUS-INNER
    THEN
    _KDOSTLSP-R @ KDOSNET-OPERATE?
    _KDOSTLSP-N @ 0= AND _KDOSTLSP-IOR @ 0= AND IF
        _KDOSTLSP-READY-INNER
    THEN ;

: _KDOSTLSP-POLL-OP  ( -- )
    _KDOSTLSP-POLL-INNER ;

: _KDOSTLSP-CLOSE-TRY-OP  ( -- )
    _KDOSTLSP-CLOSE-TRY-INNER
    _KDOSTLSP-IOR @ 0= IF
        \ Retirement is lower authority, distinct from the Akashic owner
        \ token.  Clear it before KDOSNET-WITH performs the exact release.
        0 _KDOSTLSP-R @ KDOSTLSP.SOCKET-SD !
        -1 _KDOSTLSP-RETIRED !
    THEN ;

: _KDOSTLSP-ABORT-OP  ( -- )
    _KDOSTLSP-ABORT-INNER
    _KDOSTLSP-IOR @ 0= IF
        _KDOSTLSP-ABORTED @ _KDOSTLSP-R @ KDOSTLSP.ABORT-STATUS !
        \ Do not retain a reusable /SOCK address if the independent owner
        \ release later fails after KDOS has proved retirement.
        0 _KDOSTLSP-R @ KDOSTLSP.SOCKET-SD !
        -1 _KDOSTLSP-RETIRED !
    THEN ;

