    _KDOSTLSP-RELEASE-STATUS @
    _KDOSTLSP-R @ KDOSTLSP.OWNER-STATUS ! ;

: _KDOSTLSP-RELEASED?  ( -- flag )
    _KDOSTLSP-RELEASE-STATUS @ KDOSNET-S-OK = IF -1 EXIT THEN
    KDOSTLSP-E-CLEANUP _KDOSTLSP-R @ _KDOSTLSP-QUARANTINE 0 ;

\ A failed helper release is quarantined.  Recovery may settle only this
\ exact record's retained token; it never removes or waits behind a foreign
\ owner.  Even a release which reports failure must be observed on a later
\ step before the record can publish terminal state.
: _KDOSTLSP-SETTLE-OWN-OWNER?  ( -- settled? )
    _KDOSTLSP-R @ KDOSNET-OWNER? 0= IF -1 EXIT THEN
    _KDOSTLSP-R @ KDOSNET-RELEASE
    DUP _KDOSTLSP-R @ KDOSTLSP.OWNER-STATUS !
    KDOSNET-S-OK = IF -1 EXIT THEN
    KDOSTLSP-E-CLEANUP _KDOSTLSP-R @ _KDOSTLSP-QUARANTINE 0 ;

: _KDOSTLSP-NET-CONTENDED?  ( kdosnet-status -- flag )
    KDOSNET-S-BUSY = ;

: _KDOSTLSP-NET-FAULT  ( kdosnet-status -- )
    DUP _KDOSTLSP-R @ KDOSTLSP.OWNER-STATUS !
    DUP KDOSNET-S-PLATFORM = IF
        DROP KDOSTLSP-E-STATE _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
    ELSE
        DROP KDOSTLSP-E-CLEANUP _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
    THEN ;

