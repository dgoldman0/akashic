: _KDOSTLSL-ACCEPT-GEOMETRY?  ( -- flag )
    _KDOSTLSLA-PORT @ KDOSTLSP-SIZE MSPAN-NONWRAPPING?
    _KDOSTLSLA-OWNER @ KDOSTLSL-SIZE
    _KDOSTLSLA-PORT @ KDOSTLSP-SIZE MSPAN-OVERLAP? 0= AND
    _KDOSTLSLA-OWNER @ _KDOSTLSL.XIO-SERVICE @ XIO-SERVICE-SIZE
    _KDOSTLSLA-PORT @ KDOSTLSP-SIZE MSPAN-OVERLAP? 0= AND ;

: _KDOSTLSL-ROLLBACK-ACCEPT  ( status -- status )
    _KDOSTLSLA-XIO !
    _KDOSTLSLA-PORT @ KDOSTLSP-UNRESERVE
    DUP KDOSTLSP-S-OK <> IF
        _KDOSTLSL-PORT>STATUS EXIT
    THEN DROP
    0 _KDOSTLSLA-OWNER @ _KDOSTLSL.BORROWED-PORT !
    _KDOSTLSL-PHASE-IDLE _KDOSTLSLA-OWNER @ _KDOSTLSL.PHASE !
    _KDOSTLSLA-OWNER @ _KDOSTLSL.XIO-OP XIO-OP-INIT
    _KDOSTLSLA-XIO @ ;

: KDOSTLSL-ACCEPT  ( fresh-shared-port owner -- status )
    _KDOSTLSLA-OWNER ! _KDOSTLSLA-PORT !
    COREID 0<> IF KDOSTLSL-S-PLATFORM EXIT THEN
    _KDOSTLSLX-IN-CALL @ IF KDOSTLSL-S-BUSY EXIT THEN
    _KDOSTLSLA-OWNER @ _KDOSTLSL-VALID? 0= IF
        KDOSTLSL-S-INVALID EXIT
    THEN
    _KDOSTLSLA-OWNER @ _KDOSTLSL-SERVICE-READY? 0= IF
        KDOSTLSL-S-NOT-OWNER EXIT
    THEN
    _KDOSTLSLA-OWNER @ _KDOSTLSL-IDLE? 0= IF
        KDOSTLSL-S-BUSY EXIT
    THEN
    _KDOSTLSLA-PORT @ 0= IF KDOSTLSL-S-INVALID EXIT THEN
    _KDOSTLSL-ACCEPT-GEOMETRY? 0= IF KDOSTLSL-S-INVALID EXIT THEN
    _KDOSTLSLA-OWNER @ _KDOSTLSL.REQUEST-GEN @
    _KDOSTLSL-CELL-MAX >= IF KDOSTLSL-S-STATE EXIT THEN
    _KDOSTLSLA-PORT @ KDOSTLSP-RESERVE DUP _KDOSTLSLA-PORT-STATUS !
    KDOSTLSP-S-OK <> IF
        _KDOSTLSLA-PORT-STATUS @ _KDOSTLSL-PORT>STATUS EXIT
    THEN
    _KDOSTLSLA-OWNER @ _KDOSTLSL.REQUEST-GEN @ 1+
    _KDOSTLSLA-OWNER @ _KDOSTLSL.REQUEST-GEN !
    _KDOSTLSLA-PORT @ _KDOSTLSLA-OWNER @
    _KDOSTLSL.BORROWED-PORT !
    0 _KDOSTLSLA-OWNER @ _KDOSTLSL.TERMINAL !
    _KDOSTLSL-PHASE-LISTENER-POLL
    _KDOSTLSLA-OWNER @ _KDOSTLSL.PHASE !
    _KDOSTLSLA-OWNER @ _KDOSTLSL.XIO-SERVICE @
    _KDOSTLSLA-OWNER @
    _KDOSTLSLA-OWNER @ _KDOSTLSL.OWNER-GEN @
    _KDOSTLSLA-OWNER @ _KDOSTLSL.REQUEST-GEN @ 0
    _KDOSTLSLA-OWNER @
    ['] _KDOSTLSL-XIO-START ['] _KDOSTLSL-XIO-POLL
    ['] _KDOSTLSL-XIO-CANCEL ['] _KDOSTLSL-XIO-WIPE
    _KDOSTLSLA-OWNER @ _KDOSTLSL.XIO-OP XIO-OP-CONFIGURE
    DUP XIO-S-OK <> IF
        _KDOSTLSL-XIO>STATUS _KDOSTLSL-ROLLBACK-ACCEPT EXIT
    THEN DROP
    _KDOSTLSLA-OWNER @ _KDOSTLSL.XIO-SERVICE @
    _KDOSTLSLA-OWNER @
    _KDOSTLSLA-OWNER @ _KDOSTLSL.OWNER-GEN @
    _KDOSTLSLA-OWNER @ _KDOSTLSL.REQUEST-GEN @
    ['] _KDOSTLSL-XIO-CLEANUP-POLL
    _KDOSTLSLA-OWNER @ _KDOSTLSL.XIO-OP XIO-OP-CONFIGURE-CLEANUP
    DUP XIO-S-OK <> IF
        _KDOSTLSL-XIO>STATUS _KDOSTLSL-ROLLBACK-ACCEPT EXIT
    THEN DROP
    _KDOSTLSLA-OWNER @ _KDOSTLSL.XIO-SERVICE @
    _KDOSTLSLA-OWNER @ _KDOSTLSL.XIO-OP XIO-SUBMIT
    DUP XIO-S-OK <> IF
        _KDOSTLSL-XIO>STATUS _KDOSTLSL-ROLLBACK-ACCEPT EXIT
    THEN DROP
    KDOSTLSL-S-OK ;

: _KDOSTLSL-RETRY-ERROR?  ( ior -- flag )
    DUP TLS-E-WOULD-BLOCK =
    OVER TLS-E-BUSY = OR
    SWAP KDOSTLSL-E-CONTENTION = OR ;

: _KDOSTLSL-TERMINAL-STATUS  ( owner -- status )
    DUP _KDOSTLSL.XIO-OP XIOO.STATE @ CASE
        XIO-STATE-CANCELLED OF DROP KDOSTLSL-S-CANCELLED ENDOF
        XIO-STATE-TIMED-OUT OF DROP KDOSTLSL-S-TIMED-OUT ENDOF
        XIO-STATE-FAILED OF
            DUP _KDOSTLSL.XIO-OP XIOO.CLEANUP-ERROR @ IF
                DROP KDOSTLSL-S-LOWER EXIT
            THEN
            _KDOSTLSL.XIO-OP XIOO.ERROR @ DUP
            KDOSTLSL-E-PLATFORM = IF DROP KDOSTLSL-S-PLATFORM EXIT THEN
            DUP KDOSTLSL-E-STATE = IF DROP KDOSTLSL-S-STATE EXIT THEN
            _KDOSTLSL-RETRY-ERROR? IF
                KDOSTLSL-S-RETRY
            ELSE
                KDOSTLSL-S-LOWER
            THEN
        ENDOF
        DROP KDOSTLSL-S-STATE SWAP
    ENDCASE ;

VARIABLE _KDOSTLSLS-OWNER
VARIABLE _KDOSTLSLS-STATE
VARIABLE _KDOSTLSLS-STATUS
VARIABLE _KDOSTLSLS-PORT
VARIABLE _KDOSTLSLS-NIO
VARIABLE _KDOSTLSLS-TAKE-RESULT

: _KDOSTLSL-RETURN-TERMINAL  ( owner -- port|0 status )
    DUP _KDOSTLSL.TERMINAL @ DUP _KDOSTLSLS-STATUS !
    0= IF DROP 0 KDOSTLSL-S-STATE EXIT THEN
    0 SWAP _KDOSTLSL.TERMINAL !
    0 _KDOSTLSLS-STATUS @ ;

: _KDOSTLSL-CONSUME-TERMINAL  ( owner -- port|0 status )
    DUP _KDOSTLSLS-OWNER !
    DUP _KDOSTLSL-TERMINAL-STATUS
    OVER _KDOSTLSL.TERMINAL !
    DUP _KDOSTLSL.XIO-SERVICE @
    SWAP _KDOSTLSL.XIO-OP XIO-RESET
    DUP XIO-S-OK = IF
        DROP _KDOSTLSLS-OWNER @ _KDOSTLSL-RETURN-TERMINAL EXIT
    THEN
    DUP XIO-S-PENDING = IF DROP 0 KDOSTLSL-S-PENDING EXIT THEN
    _KDOSTLSL-XIO>STATUS 0 SWAP ;

: _KDOSTLSL-DISCARD-RETAINED  ( terminal-status owner -- port|0 status )
    DUP _KDOSTLSLS-OWNER ! _KDOSTLSL.TERMINAL !
    _KDOSTLSLS-OWNER @ _KDOSTLSL.XIO-SERVICE @
    _KDOSTLSLS-OWNER @ _KDOSTLSL.XIO-OP XIO-RESET
    DUP XIO-S-OK = IF
        DROP _KDOSTLSLS-OWNER @ _KDOSTLSL-RETURN-TERMINAL EXIT
    THEN
    DUP XIO-S-PENDING = IF DROP 0 KDOSTLSL-S-PENDING EXIT THEN
    _KDOSTLSL-XIO>STATUS 0 SWAP ;

: _KDOSTLSL-TAKE-ADOPTED  ( owner -- port|0 status )
    _KDOSTLSLS-OWNER !
    _KDOSTLSLS-OWNER @ _KDOSTLSL.BORROWED-PORT @
    DUP _KDOSTLSLS-PORT ! KDOSTLSP.PORT _KDOSTLSLS-NIO !
    _KDOSTLSLS-OWNER @ _KDOSTLSL.XIO-SERVICE @
    _KDOSTLSLS-OWNER @
    _KDOSTLSLS-OWNER @ _KDOSTLSL.OWNER-GEN @
    _KDOSTLSLS-OWNER @ _KDOSTLSL.REQUEST-GEN @
    _KDOSTLSLS-OWNER @ _KDOSTLSL.XIO-OP XIO-TAKE
    _KDOSTLSLS-STATUS ! _KDOSTLSLS-TAKE-RESULT !
    _KDOSTLSLS-STATUS @ XIO-S-OK <> IF
        0 _KDOSTLSLS-STATUS @ _KDOSTLSL-XIO>STATUS EXIT
    THEN
    \ Authority was committed by ADOPT-OPEN before TAKE.  Exact result and
    \ wipe invariants were validated before this point; never hide the open
    \ port merely because a corrupted XIO result cell disagrees afterward.
    _KDOSTLSLS-NIO @ KDOSTLSL-S-OK ;

: _KDOSTLSL-ADOPT-SUCCESS  ( owner -- port|0 status )
    DUP _KDOSTLSLS-OWNER !
    DUP _KDOSTLSL.PHASE @ _KDOSTLSL-PHASE-ADOPTED = IF
        DROP _KDOSTLSLS-OWNER @ _KDOSTLSL-TAKE-ADOPTED EXIT
    THEN
    DUP _KDOSTLSL.PHASE @ _KDOSTLSL-PHASE-PUBLISHED <>
    OVER _KDOSTLSL.BORROWED-PORT @ 0= OR IF
        DROP KDOSTLSL-S-STATE _KDOSTLSLS-OWNER @
        _KDOSTLSL-DISCARD-RETAINED EXIT
    THEN
    DUP _KDOSTLSL.CTX @
    OVER _KDOSTLSL.CTX-GEN @ OR
    OVER _KDOSTLSL.STAGING-SOCKET @ OR IF
        DROP KDOSTLSL-S-STATE _KDOSTLSLS-OWNER @
        _KDOSTLSL-DISCARD-RETAINED EXIT
    THEN
    DUP _KDOSTLSL.BORROWED-PORT @ DUP _KDOSTLSLS-PORT !
    OVER _KDOSTLSL.XIO-OP XIOO.RESULT @ <>
    _KDOSTLSLS-PORT @ KDOSTLSP.STATE @
        KDOSTLSP-STATE-PUBLISHED <> OR
    _KDOSTLSLS-PORT @ KDOSTLSP.SOCKET-SD @ 0= OR IF
        DROP KDOSTLSL-S-STATE _KDOSTLSLS-OWNER @
        _KDOSTLSL-DISCARD-RETAINED EXIT
    THEN DROP
    _KDOSTLSLS-PORT @ KDOSTLSP-ADOPT-OPEN
    _KDOSTLSLS-STATUS ! _KDOSTLSLS-NIO !
    _KDOSTLSLS-STATUS @ KDOSTLSP-S-OK <> IF
        _KDOSTLSLS-STATUS @ DUP KDOSTLSP-S-PENDING =
        SWAP KDOSTLSP-S-BUSY = OR IF
            0 KDOSTLSL-S-PENDING EXIT
        THEN
        _KDOSTLSLS-STATUS @ _KDOSTLSL-PORT>STATUS
        _KDOSTLSLS-OWNER @ _KDOSTLSL-DISCARD-RETAINED EXIT
    THEN
    _KDOSTLSL-PHASE-ADOPTED
    _KDOSTLSLS-OWNER @ _KDOSTLSL.PHASE !
    _KDOSTLSLS-OWNER @ _KDOSTLSL-TAKE-ADOPTED ;

: _KDOSTLSL-ACTIVE-TOPOLOGY?  ( owner -- flag )
    >R
    R@ _KDOSTLSL.XIO-SERVICE @ XIOS.ACTIVE @
    R@ _KDOSTLSL.XIO-OP =
    R@ _KDOSTLSL.XIO-SERVICE @ XIOS.RETAINED @ 0= AND
    R> _KDOSTLSL-XIO-EXACT? AND ;

: _KDOSTLSL-SUCCESS-TOPOLOGY?  ( owner -- flag )
    DUP _KDOSTLSL.XIO-SERVICE @ XIOS.ACTIVE @ 0=
    OVER _KDOSTLSL.XIO-SERVICE @ XIOS.RETAINED @
    2 PICK _KDOSTLSL.XIO-OP = AND
    SWAP _KDOSTLSL-XIO-EXACT? AND ;

: _KDOSTLSL-CLEANUP-TOPOLOGY?  ( owner -- flag )
    >R
    R@ _KDOSTLSL.XIO-SERVICE @ XIOS.ACTIVE @
    R@ _KDOSTLSL.XIO-OP =
    R@ _KDOSTLSL.XIO-SERVICE @ XIOS.RETAINED @ DUP 0=
    SWAP R@ _KDOSTLSL.XIO-OP = OR AND
    R> _KDOSTLSL-XIO-EXACT? AND ;

: KDOSTLSL-STEP  ( owner -- nio-port|0 status )
    _KDOSTLSLS-OWNER !
    COREID 0<> IF 0 KDOSTLSL-S-PLATFORM EXIT THEN
    _KDOSTLSLX-IN-CALL @ IF 0 KDOSTLSL-S-BUSY EXIT THEN
    _KDOSTLSLS-OWNER @ _KDOSTLSL-VALID? 0= IF
        0 KDOSTLSL-S-INVALID EXIT
    THEN
    _KDOSTLSLS-OWNER @ _KDOSTLSL-SERVICE-READY? 0= IF
        0 KDOSTLSL-S-NOT-OWNER EXIT
    THEN
    _KDOSTLSLS-OWNER @ _KDOSTLSL.XIO-OP XIO-CLEANUP-PENDING? IF
        _KDOSTLSLS-OWNER @ _KDOSTLSL-CLEANUP-TOPOLOGY? 0= IF
            0 KDOSTLSL-S-STATE EXIT
        THEN
        _KDOSTLSLS-OWNER @ _KDOSTLSL.XIO-SERVICE @ XIO-TICK
        0 KDOSTLSL-S-PENDING EXIT
    THEN
    _KDOSTLSLS-OWNER @ _KDOSTLSL.XIO-OP XIOO.STATE @
    DUP _KDOSTLSLS-STATE !
    XIO-STATE-RESET = IF
        _KDOSTLSLS-OWNER @ _KDOSTLSL.TERMINAL @ IF
            _KDOSTLSLS-OWNER @ _KDOSTLSL-RETURN-TERMINAL
        ELSE
            0 KDOSTLSL-S-STATE
        THEN EXIT
    THEN
    _KDOSTLSLS-STATE @ XIO-STATE-ACTIVE = IF
        _KDOSTLSLS-OWNER @ _KDOSTLSL-ACTIVE-TOPOLOGY? 0= IF
            0 KDOSTLSL-S-STATE EXIT
        THEN
        _KDOSTLSLS-OWNER @ _KDOSTLSL.XIO-SERVICE @ XIO-TICK
        \ One public STEP performs at most one lower handshake or cleanup
        \ operation.  Adoption/terminal consumption therefore begins on the
        \ following cooperative call even if this tick just completed XIO.
        0 KDOSTLSL-S-PENDING EXIT
    THEN
    _KDOSTLSLS-STATE @ XIO-STATE-SUCCEEDED = IF
        _KDOSTLSLS-OWNER @ _KDOSTLSL-SUCCESS-TOPOLOGY? 0= IF
            0 KDOSTLSL-S-STATE EXIT
        THEN
        _KDOSTLSLS-OWNER @ _KDOSTLSL-ADOPT-SUCCESS EXIT
    THEN
    _KDOSTLSLS-STATE @ DUP XIO-STATE-FAILED =
    OVER XIO-STATE-CANCELLED = OR
    SWAP XIO-STATE-TIMED-OUT = OR IF
        _KDOSTLSLS-OWNER @ _KDOSTLSL-CONSUME-TERMINAL EXIT
    THEN
    0 KDOSTLSL-S-STATE ;

VARIABLE _KDOSTLSLC-OWNER
VARIABLE _KDOSTLSLC-XIO

: KDOSTLSL-CANCEL  ( owner -- status )
    _KDOSTLSLC-OWNER !
    COREID 0<> IF KDOSTLSL-S-PLATFORM EXIT THEN
    _KDOSTLSLX-IN-CALL @ IF KDOSTLSL-S-BUSY EXIT THEN
    _KDOSTLSLC-OWNER @ _KDOSTLSL-VALID? 0= IF
        KDOSTLSL-S-INVALID EXIT
    THEN
    _KDOSTLSLC-OWNER @ _KDOSTLSL-SERVICE-READY? 0= IF
        KDOSTLSL-S-NOT-OWNER EXIT
    THEN
    _KDOSTLSLC-OWNER @ _KDOSTLSL.XIO-OP XIOO.STATE @
    DUP XIO-STATE-ACTIVE = IF
        DROP
        _KDOSTLSLC-OWNER @ _KDOSTLSL-ACTIVE-TOPOLOGY? 0= IF
            KDOSTLSL-S-STATE EXIT
        THEN
        _KDOSTLSLC-OWNER @ _KDOSTLSL.XIO-SERVICE @
        _KDOSTLSLC-OWNER @ _KDOSTLSL.XIO-OP XIO-CANCEL
        DUP _KDOSTLSLC-XIO !
        DUP XIO-S-OK = SWAP XIO-S-PENDING = OR IF
            KDOSTLSL-S-PENDING
        ELSE
            _KDOSTLSLC-XIO @ _KDOSTLSL-XIO>STATUS
        THEN EXIT
    THEN
    DUP XIO-STATE-CANCELLED = IF
        DROP KDOSTLSL-S-CANCELLED EXIT
    THEN
    XIO-STATE-SUCCEEDED = IF
        _KDOSTLSLC-OWNER @ _KDOSTLSL.PHASE @
        _KDOSTLSL-PHASE-ADOPTED = IF KDOSTLSL-S-STATE EXIT THEN
        KDOSTLSL-S-CANCELLED
        _KDOSTLSLC-OWNER @ _KDOSTLSL.TERMINAL !
        _KDOSTLSLC-OWNER @ _KDOSTLSL.XIO-SERVICE @
        _KDOSTLSLC-OWNER @ _KDOSTLSL.XIO-OP XIO-RESET
        DUP XIO-S-OK = IF DROP KDOSTLSL-S-CANCELLED EXIT THEN
        DUP XIO-S-PENDING = IF DROP KDOSTLSL-S-PENDING EXIT THEN
        _KDOSTLSL-XIO>STATUS EXIT
    THEN
    KDOSTLSL-S-STATE ;

: KDOSTLSL-FINI  ( owner -- status )
    COREID 0<> IF DROP KDOSTLSL-S-PLATFORM EXIT THEN
    _KDOSTLSLX-IN-CALL @ IF DROP KDOSTLSL-S-BUSY EXIT THEN
    DUP _KDOSTLSL-VALID? 0= IF DROP KDOSTLSL-S-INVALID EXIT THEN
    DUP _KDOSTLSL-IDLE? 0= IF DROP KDOSTLSL-S-BUSY EXIT THEN
    KDOSTLSL-SIZE 0 FILL KDOSTLSL-S-OK ;
