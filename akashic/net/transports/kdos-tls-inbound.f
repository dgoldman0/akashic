\ =====================================================================
\  kdos-tls-inbound.f - Persistent XIO-driven KDOS TLS listener owner
\ =====================================================================
\  KDOS owns the TLS server engine and every lower transport authority.
\  This module owns only the Akashic composition of one persistent secure
\  listener: one caller-pumped XIO accept request, its exact lower context,
\  and a borrowed shared KDOS TLS port used to stage authenticated success.
\
\  The listener owner never publishes a plaintext accepted child and never
\  retains an established connection after returning its already-open NIO
\  port.  KDOSNET is acquired for exactly one lower handshake or raw-context
\  cleanup operation.  Established-port cleanup and adoption use the shared
\  port's own per-call KDOSNET boundary.
\
\  Public lifecycle:
\    KDOSTLSL-INIT
\      ( xio-service listener-sd listener-h1 listener-generation
\        timeout-ms early-budget owner -- status )
\    KDOSTLSL-ACCEPT  ( fresh-shared-port owner -- status )
\    KDOSTLSL-STEP    ( owner -- nio-port|0 status )
\    KDOSTLSL-CANCEL  ( owner -- status )
\    KDOSTLSL-FINI    ( owner -- status )
\
\  STEP returning PENDING means the current request still owns work.  RETRY
\  means an empty backlog or pre-claim contention completed the request and
\  the owner is ready for another ACCEPT.  The shared port passed to ACCEPT
\  must already have been initialized and be in RESET.
\ =====================================================================

