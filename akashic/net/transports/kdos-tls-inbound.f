    _KDOSTLSAX-A @ KDOSTLSA.CTX-GEN @
    TLS-SERVER-INGRESS-DISPOSITION-STEP
    _KDOSTLSAX-IOR ! _KDOSTLSAX-PROGRESS !
    _KDOSTLSAX-IOR @ DUP TLS-E-BUSY = IF
        DROP _KDOSTLSAX-PROGRESS @ TLS-SERVER-DISPOSITION-NONE = IF
            XIO-STEP-PENDING
        ELSE
            TLS-E-TRANSPORT _KDOSTLSA-TERMINAL-FAIL
        THEN EXIT
    THEN
    DUP TLS-E-WOULD-BLOCK = IF
        DROP _KDOSTLSAX-PROGRESS @ TLS-SERVER-DISPOSITION-NONE = IF
            KDOSTLSA-PHASE-DISPOSITION-POLL
            _KDOSTLSAX-A @ KDOSTLSA.PHASE ! XIO-STEP-PENDING
        ELSE
            TLS-E-TRANSPORT _KDOSTLSA-TERMINAL-FAIL
        THEN EXIT
    THEN
    DUP IF
        _KDOSTLSA-TERMINAL-FAIL EXIT
    THEN DROP
    _KDOSTLSAX-PROGRESS @ TLS-SERVER-DISPOSITION-COMPLETE <> IF
        TLS-E-TRANSPORT _KDOSTLSA-TERMINAL-FAIL EXIT
    THEN
    KDOSTLSA-PHASE-TERMINAL-CLOSE _KDOSTLSAX-A @ KDOSTLSA.PHASE !
    XIO-STEP-PENDING ;

: _KDOSTLSA-TERMINAL-CLOSE-STEP  ( -- step-status )
    _KDOSTLSAX-A @ KDOSTLSA.CTX @
    _KDOSTLSAX-A @ KDOSTLSA.CTX-GEN @
    TLS-SERVER-CLOSE-EXACT-TRY
    _KDOSTLSAX-IOR ! _KDOSTLSAX-RETIRED !
    _KDOSTLSAX-RETIRED @ IF
        0 _KDOSTLSAX-A @ KDOSTLSA.CTX !
        0 _KDOSTLSAX-A @ KDOSTLSA.CTX-GEN !
        _KDOSTLSAX-IOR @ _KDOSTLSA-TERMINAL-FAIL EXIT
    THEN
    _KDOSTLSAX-IOR @ DUP TLS-E-BUSY = IF DROP XIO-STEP-PENDING EXIT THEN
    TLS-E-WOULD-BLOCK = IF
        KDOSTLSA-PHASE-TERMINAL-CLOSE-POLL
        _KDOSTLSAX-A @ KDOSTLSA.PHASE ! XIO-STEP-PENDING EXIT
    THEN
    _KDOSTLSAX-IOR @ DUP 0= IF DROP TLS-E-TRANSPORT THEN
    _KDOSTLSA-TERMINAL-FAIL ;

: _KDOSTLSA-PUBLISH-STEP  ( -- step-status )
    _KDOSTLSAX-A @ KDOSTLSA.CTX @
    _KDOSTLSAX-A @ KDOSTLSA.CTX-GEN @ TLS-SERVER-SOCKET-PUBLISH
    _KDOSTLSAX-IOR ! _KDOSTLSAX-SD !
    _KDOSTLSAX-SD @ IF
        _KDOSTLSAX-A @ KDOSTLSA.RESULT @ _KDOSTLSAX-RESULT !
        _KDOSTLSAX-SD @ _KDOSTLSAX-RESULT @ KDOSTLSP.SOCKET-SD !
        KDOSTLSP-STATE-PUBLISHED _KDOSTLSAX-RESULT @ KDOSTLSP.STATE !
        0 _KDOSTLSAX-A @ KDOSTLSA.CTX !
        0 _KDOSTLSAX-A @ KDOSTLSA.CTX-GEN !
        KDOSTLSA-PHASE-PUBLISHED _KDOSTLSAX-A @ KDOSTLSA.PHASE !
        \ A nonzero descriptor is potentially the post-publication authority
        \ even if a broken lower implementation also returns an error.  Retain
        \ it before failing so cooperative cleanup aborts the socket rather
        \ than trying to act on raw context authority that may have transferred.
        _KDOSTLSAX-IOR @ IF TLS-E-TRANSPORT _KDOSTLSA-FAIL EXIT THEN
        _KDOSTLSAX-RESULT @ _KDOSTLSAX-OP @ XIOO.RESULT !
        0 _KDOSTLSAX-OP @ XIOO.ERROR !
        XIO-STEP-SUCCEEDED EXIT
    THEN
    _KDOSTLSAX-IOR @ DUP TLS-E-BUSY = IF DROP XIO-STEP-PENDING EXIT THEN
    DUP IF
        DUP 0< IF _KDOSTLSA-FAIL
        ELSE DROP TLS-E-TRANSPORT _KDOSTLSA-FAIL THEN EXIT
    THEN DROP
    TLS-E-TRANSPORT _KDOSTLSA-FAIL ;

: _KDOSTLSA-POLL-TRANSPORT-STEP  ( resume-phase -- step-status )
    TCP-POLL _KDOSTLSAX-A @ KDOSTLSA.PHASE ! XIO-STEP-PENDING ;

: _KDOSTLSA-POLL  ( operation adapter -- step-status )
    _KDOSTLSA-CALLBACK-BEGIN 0= IF
        KDOSTLSA-E-STATE _KDOSTLSA-FAIL EXIT
    THEN
    _KDOSTLSAX-A @ KDOSTLSA.PHASE @ CASE
        KDOSTLSA-PHASE-CLAIM OF _KDOSTLSA-CLAIM-STEP ENDOF
        KDOSTLSA-PHASE-CLIENT-HELLO OF
            _KDOSTLSA-CLIENT-HELLO-STEP ENDOF
        KDOSTLSA-PHASE-CLIENT-HELLO-POLL OF
            KDOSTLSA-PHASE-CLIENT-HELLO _KDOSTLSA-POLL-TRANSPORT-STEP
        ENDOF
        KDOSTLSA-PHASE-PREPARE-HELLO OF
            _KDOSTLSA-PREPARE-HELLO-STEP ENDOF
        KDOSTLSA-PHASE-PREPARE-FLIGHT OF
            _KDOSTLSA-PREPARE-FLIGHT-STEP ENDOF
        KDOSTLSA-PHASE-FLIGHT OF _KDOSTLSA-FLIGHT-STEP ENDOF
        KDOSTLSA-PHASE-FLIGHT-POLL OF
            KDOSTLSA-PHASE-FLIGHT _KDOSTLSA-POLL-TRANSPORT-STEP
        ENDOF
        KDOSTLSA-PHASE-CLIENT-FLIGHT-BEGIN OF
            _KDOSTLSA-CLIENT-FLIGHT-BEGIN-STEP ENDOF
        KDOSTLSA-PHASE-CLIENT-FLIGHT OF
            _KDOSTLSA-CLIENT-FLIGHT-STEP ENDOF
        KDOSTLSA-PHASE-CLIENT-FLIGHT-POLL OF
            KDOSTLSA-PHASE-CLIENT-FLIGHT _KDOSTLSA-POLL-TRANSPORT-STEP
        ENDOF
        KDOSTLSA-PHASE-DISPOSITION OF
            _KDOSTLSA-DISPOSITION-STEP ENDOF
        KDOSTLSA-PHASE-DISPOSITION-POLL OF
            KDOSTLSA-PHASE-DISPOSITION _KDOSTLSA-POLL-TRANSPORT-STEP
        ENDOF
        KDOSTLSA-PHASE-TERMINAL-CLOSE OF
            _KDOSTLSA-TERMINAL-CLOSE-STEP ENDOF
        KDOSTLSA-PHASE-TERMINAL-CLOSE-POLL OF
            KDOSTLSA-PHASE-TERMINAL-CLOSE
            _KDOSTLSA-POLL-TRANSPORT-STEP
        ENDOF
        KDOSTLSA-PHASE-PUBLISH OF _KDOSTLSA-PUBLISH-STEP ENDOF
        KDOSTLSA-E-STATE _KDOSTLSA-FAIL SWAP
    ENDCASE ;

: _KDOSTLSA-CANCEL  ( operation adapter -- )
    _KDOSTLSA-CALLBACK-BEGIN 0= IF KDOSTLSA-E-STATE THROW THEN
    _KDOSTLSAX-A @ KDOSTLSA.PHASE @ KDOSTLSA-PHASE-TAKEN <> IF
        KDOSTLSA-PHASE-CLEANUP _KDOSTLSAX-A @ KDOSTLSA.PHASE !
    THEN ;

: _KDOSTLSA-CLEANUP-RELEASE  ( -- step-status )
    _KDOSTLSAX-A @ KDOSTLSA.RESULT @ DUP _KDOSTLSAX-RESULT !
    DUP KDOSNET-OWNER? IF
        KDOSNET-RELEASE DUP IF
            _KDOSTLSA-SECONDARY! XIO-STEP-PENDING EXIT
        THEN DROP
    ELSE
        KDOSTLSP.STATE @ KDOSTLSP-STATE-RESET <> IF
            KDOSTLSA-E-CLEANUP _KDOSTLSA-SECONDARY!
            XIO-STEP-PENDING EXIT
        THEN
    THEN
    KDOSTLSP-STATE-RESET _KDOSTLSAX-RESULT @ KDOSTLSP.STATE !
    XIO-STEP-SUCCEEDED ;

: _KDOSTLSA-CLEANUP-POLL  ( operation adapter -- step-status )
    _KDOSTLSA-CALLBACK-BEGIN 0= IF
        KDOSTLSA-E-STATE _KDOSTLSA-SECONDARY! XIO-STEP-PENDING EXIT
    THEN
    _KDOSTLSAX-A @ KDOSTLSA.PHASE @ KDOSTLSA-PHASE-TAKEN = IF
        XIO-STEP-SUCCEEDED EXIT
    THEN
    _KDOSTLSAX-A @ KDOSTLSA.RESULT @ DUP _KDOSTLSAX-RESULT !
    _KDOSTLSP-VALID? 0= IF
        KDOSTLSA-E-STATE _KDOSTLSA-SECONDARY! XIO-STEP-PENDING EXIT
    THEN
    _KDOSTLSAX-A @ KDOSTLSA.CTX @
    _KDOSTLSAX-A @ KDOSTLSA.CTX-GEN @ OR IF
        _KDOSTLSAX-A @ KDOSTLSA.CTX @
        _KDOSTLSAX-A @ KDOSTLSA.CTX-GEN @
        TLS-SERVER-ABORT-EXACT
        _KDOSTLSAX-IOR ! _KDOSTLSAX-RETIRED !
        _KDOSTLSAX-RETIRED @ IF
            0 _KDOSTLSAX-A @ KDOSTLSA.CTX !
            0 _KDOSTLSAX-A @ KDOSTLSA.CTX-GEN !
            _KDOSTLSAX-IOR @ _KDOSTLSA-SECONDARY!
            _KDOSTLSA-CLEANUP-RELEASE EXIT
        THEN
        _KDOSTLSAX-IOR @ DUP TLS-E-BUSY = IF
            DROP XIO-STEP-PENDING EXIT
        THEN
        DUP 0= IF DROP TLS-E-TRANSPORT THEN
        _KDOSTLSA-SECONDARY! XIO-STEP-PENDING EXIT
    THEN
    _KDOSTLSAX-RESULT @ KDOSTLSP.SOCKET-SD @ IF
        _KDOSTLSAX-RESULT @ KDOSTLSP.STATE @
        KDOSTLSP-STATE-PUBLISHED <> IF
            KDOSTLSA-E-CLEANUP _KDOSTLSA-SECONDARY!
            XIO-STEP-PENDING EXIT
        THEN
        _KDOSTLSAX-RESULT @ KDOSTLSP.SOCKET-SD @ SOCK-ABORT
        _KDOSTLSAX-IOR ! DROP
        _KDOSTLSAX-IOR @ 0= IF
            0 _KDOSTLSAX-RESULT @ KDOSTLSP.SOCKET-SD !
            KDOSTLSP-STATE-RESET _KDOSTLSAX-RESULT @ KDOSTLSP.STATE !
            _KDOSTLSA-CLEANUP-RELEASE EXIT
        THEN
        _KDOSTLSAX-IOR @ _KDOSTLSP-BUSY-IOR? IF
            XIO-STEP-PENDING EXIT
        THEN
        _KDOSTLSAX-IOR @ _KDOSTLSA-SECONDARY!
        XIO-STEP-PENDING EXIT
    THEN
    _KDOSTLSAX-RESULT @ KDOSTLSP.STATE @ DUP
    KDOSTLSP-STATE-RESET = SWAP KDOSTLSP-STATE-RESERVED = OR 0= IF
        KDOSTLSA-E-CLEANUP _KDOSTLSA-SECONDARY!
        XIO-STEP-PENDING EXIT
    THEN
    _KDOSTLSA-CLEANUP-RELEASE ;

: _KDOSTLSA-WIPE  ( operation adapter -- )
    _KDOSTLSA-CALLBACK-BEGIN 0= IF KDOSTLSA-E-STATE THROW THEN
    _KDOSTLSAX-A @ KDOSTLSA.CTX @
    _KDOSTLSAX-A @ KDOSTLSA.CTX-GEN @ OR IF
        KDOSTLSA-E-CLEANUP THROW
    THEN
    _KDOSTLSAX-A @ KDOSTLSA.RESULT @ DUP _KDOSTLSAX-RESULT !
    _KDOSTLSP-VALID? 0= IF KDOSTLSA-E-CLEANUP THROW THEN
    _KDOSTLSAX-A @ KDOSTLSA.PHASE @ KDOSTLSA-PHASE-TAKEN <> IF
        _KDOSTLSAX-RESULT @ KDOSNET-OWNER? IF
            KDOSTLSA-E-CLEANUP THROW
        THEN
        _KDOSTLSAX-RESULT @ KDOSTLSP.STATE @ KDOSTLSP-STATE-RESET <> IF
            KDOSTLSA-E-CLEANUP THROW
        THEN
    THEN
    0 _KDOSTLSAX-A @ KDOSTLSA.CTX !
    0 _KDOSTLSAX-A @ KDOSTLSA.CTX-GEN !
    KDOSTLSA-PHASE-CONFIGURED _KDOSTLSAX-A @ KDOSTLSA.PHASE ! ;

