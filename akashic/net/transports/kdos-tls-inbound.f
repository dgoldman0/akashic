    _KDOSTLSAX-OP @ XIO-OP-VALID? 0= IF 0 EXIT THEN
    _KDOSTLSAX-OP @ XIOO.CONTEXT @ _KDOSTLSAX-A @ = ;

: _KDOSTLSA-SECONDARY!  ( ior -- )
    ?DUP IF
        _KDOSTLSAX-OP @ XIOO.CLEANUP-ERROR @ 0= IF
            _KDOSTLSAX-OP @ XIOO.CLEANUP-ERROR !
        ELSE
            DROP
        THEN
    THEN ;

