            R> _KDOSTLSA-FAIL
        ELSE
            R> DROP TLS-E-TRANSPORT _KDOSTLSA-FAIL
        THEN EXIT
    THEN DROP
    _KDOSTLSAX-ALERT @ DUP IF
        DUP _KDOSTLSA-ALERT-VALID? IF _KDOSTLSA-EARLY-ALERT
        ELSE DROP TLS-E-TRANSPORT _KDOSTLSA-FAIL THEN EXIT
