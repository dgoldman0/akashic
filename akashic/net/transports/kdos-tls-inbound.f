    _KDOSTLSAX-OP @ XIOO.DEADLINE-MS ! ;

: _KDOSTLSA-START  ( operation adapter -- step-status )
    _KDOSTLSA-CALLBACK-BEGIN 0= IF
        KDOSTLSA-E-STATE _KDOSTLSA-FAIL EXIT
    THEN
    _KDOSTLSAX-A @ KDOSTLSA.PHASE @
    KDOSTLSA-PHASE-CONFIGURED <> IF
        KDOSTLSA-E-STATE _KDOSTLSA-FAIL EXIT
    THEN
    _KDOSTLSAX-A @ KDOSTLSA.RESULT @ DUP _KDOSTLSAX-RESULT !
    DUP _KDOSTLSP-VALID? 0= IF
        DROP KDOSTLSA-E-STATE _KDOSTLSA-FAIL EXIT
    THEN
    KDOSTLSP.STATE @ KDOSTLSP-STATE-RESET <> IF
        KDOSTLSA-E-STATE _KDOSTLSA-FAIL EXIT
    THEN
    _KDOSTLSAX-RESULT @ KDOSNET-CLAIM DUP IF
        DUP KDOSNET-S-BUSY = IF DROP KDOSTLSA-E-CONTENTION
        ELSE KDOSNET-S-PLATFORM = IF KDOSTLSA-E-PLATFORM
        ELSE KDOSTLSA-E-STATE THEN THEN
        _KDOSTLSA-FAIL EXIT
    THEN DROP
    0 _KDOSTLSAX-RESULT @ KDOSTLSP.LAST-ERROR !
    0 _KDOSTLSAX-RESULT @ KDOSTLSP.CLEANUP-ERROR !
    KDOSTLSP-STATE-RESERVED _KDOSTLSAX-RESULT @ KDOSTLSP.STATE !
    TCP-POLL
    KDOSTLSA-PHASE-CLAIM _KDOSTLSAX-A @ KDOSTLSA.PHASE !
    XIO-STEP-PENDING ;

: _KDOSTLSA-CLAIM-STEP  ( -- step-status )
    _KDOSTLSAX-A @ KDOSTLSA.LISTENER-SD @
    _KDOSTLSAX-A @ KDOSTLSA.LISTENER-H1 @
    _KDOSTLSAX-A @ KDOSTLSA.LISTENER-GEN @
    TLS-SERVER-ACCEPT-CLAIM
    _KDOSTLSAX-IOR ! _KDOSTLSAX-GEN ! _KDOSTLSAX-CTX !
    _KDOSTLSAX-IOR @ IF
        _KDOSTLSAX-CTX @ _KDOSTLSAX-GEN @ OR IF
            _KDOSTLSAX-CTX @ _KDOSTLSAX-A @ KDOSTLSA.CTX !
            _KDOSTLSAX-GEN @ _KDOSTLSAX-A @ KDOSTLSA.CTX-GEN !
            TLS-E-TRANSPORT _KDOSTLSA-FAIL EXIT
        THEN
        _KDOSTLSAX-IOR @ _KDOSTLSA-FAIL EXIT
    THEN
    _KDOSTLSAX-CTX @ 0= _KDOSTLSAX-GEN @ 0= OR IF
        TLS-E-TRANSPORT _KDOSTLSA-FAIL EXIT
