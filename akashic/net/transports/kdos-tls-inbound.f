\ =====================================================================
\  kdos-tls-inbound.f - XIO-driven inbound KDOS TLS transport
\ =====================================================================
\  KDOS owns the TLS server engine and every lower transport authority.
\  This module composes its bounded nonblocking server primitives under one
\  external-io operation, then publishes only an authenticated NIO port.
\  A queued TCP child is never exposed as a plaintext application socket.
\ =====================================================================

