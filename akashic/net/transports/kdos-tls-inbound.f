: _KDOSTLSA-CLIENT-HELLO-STEP  ( -- step-status )
    _KDOSTLSAX-A @ KDOSTLSA.CTX @
    _KDOSTLSAX-A @ KDOSTLSA.CTX-GEN @
    TLS-SERVER-CLIENT-HELLO-STEP
    _KDOSTLSAX-IOR ! _KDOSTLSAX-ALERT ! _KDOSTLSAX-PROGRESS !
    _KDOSTLSAX-IOR @ DUP TLS-E-WOULD-BLOCK = IF
        DROP _KDOSTLSAX-PROGRESS @ TLS-SERVER-CLIENT-HELLO-NONE =
        _KDOSTLSAX-ALERT @ 0= AND 0= IF
            TLS-E-TRANSPORT _KDOSTLSA-FAIL EXIT
        THEN
        KDOSTLSA-PHASE-CLIENT-HELLO-POLL
        _KDOSTLSAX-A @ KDOSTLSA.PHASE ! XIO-STEP-PENDING EXIT
    THEN
    DUP TLS-E-BUSY = IF
        DROP _KDOSTLSAX-PROGRESS @ TLS-SERVER-CLIENT-HELLO-NONE =
        _KDOSTLSAX-ALERT @ 0= AND 0= IF
            TLS-E-TRANSPORT _KDOSTLSA-FAIL EXIT
        THEN
        XIO-STEP-PENDING EXIT
    THEN
    DUP IF
        >R _KDOSTLSAX-PROGRESS @ TLS-SERVER-CLIENT-HELLO-NONE =
        _KDOSTLSAX-ALERT @ 0= AND R@ 0< AND IF
            R> _KDOSTLSA-FAIL
        ELSE
            R> DROP TLS-E-TRANSPORT _KDOSTLSA-FAIL
        THEN EXIT
    THEN DROP
    _KDOSTLSAX-ALERT @ DUP IF
        DUP _KDOSTLSA-ALERT-VALID?
        _KDOSTLSAX-PROGRESS @ TLS-SERVER-CLIENT-HELLO-NONE = AND IF
            _KDOSTLSA-EARLY-ALERT
        ELSE
            DROP TLS-E-TRANSPORT _KDOSTLSA-FAIL
        THEN EXIT
    THEN DROP
    _KDOSTLSAX-PROGRESS @ DUP TLS-SERVER-CLIENT-HELLO-RECORD = IF
        DROP XIO-STEP-PENDING EXIT
    THEN
    TLS-SERVER-CLIENT-HELLO-COMPLETE = IF
        KDOSTLSA-PHASE-PREPARE-HELLO _KDOSTLSAX-A @ KDOSTLSA.PHASE !
        XIO-STEP-PENDING EXIT
    THEN
    TLS-E-TRANSPORT _KDOSTLSA-FAIL ;

