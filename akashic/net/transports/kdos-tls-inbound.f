: KDOSTLSL-INIT
    \ ( xio-service listener-sd listener-h1 listener-generation
    \   timeout-ms early-budget owner -- status )
    _KDOSTLSLI-OWNER ! _KDOSTLSLI-EARLY ! _KDOSTLSLI-TIMEOUT !
    _KDOSTLSLI-GEN ! _KDOSTLSLI-H1 ! _KDOSTLSLI-SD !
    _KDOSTLSLI-SERVICE !
    COREID 0<> IF KDOSTLSL-S-PLATFORM EXIT THEN
    _KDOSTLSLI-OWNER @ 0=
    _KDOSTLSLI-SERVICE @ 0= OR IF KDOSTLSL-S-INVALID EXIT THEN
    _KDOSTLSLI-OWNER @ KDOSTLSL-SIZE MSPAN-NONWRAPPING? 0=
    _KDOSTLSLI-SERVICE @ XIO-SERVICE-SIZE MSPAN-NONWRAPPING? 0= OR IF
        KDOSTLSL-S-INVALID EXIT
    THEN
    _KDOSTLSLI-OWNER @ KDOSTLSL-SIZE
    _KDOSTLSLI-SERVICE @ XIO-SERVICE-SIZE MSPAN-OVERLAP? IF
        KDOSTLSL-S-INVALID EXIT
    THEN
    _KDOSTLSLI-SERVICE @ XIO-SERVICE-BOUND? 0= IF
        KDOSTLSL-S-INVALID EXIT
    THEN
    _KDOSTLSLI-SERVICE @ XIO-SERVICE-OWNER? 0= IF
        KDOSTLSL-S-NOT-OWNER EXIT
    THEN
    _KDOSTLSLI-SD @ 0=
    _KDOSTLSLI-H1 @ 0> 0= OR
    _KDOSTLSLI-GEN @ 0> 0= OR
    _KDOSTLSLI-TIMEOUT @ 0> 0= OR
    _KDOSTLSLI-EARLY @ 0< OR IF KDOSTLSL-S-INVALID EXIT THEN
    0 _KDOSTLSLI-OLD-GEN !
    _KDOSTLSLI-OWNER @ _KDOSTLSL.MAGIC @
    _KDOSTLSL-MAGIC-VALUE = IF
        _KDOSTLSLI-OWNER @ _KDOSTLSL-VALID? 0= IF
            KDOSTLSL-S-STATE EXIT
        THEN
        _KDOSTLSLI-OWNER @ _KDOSTLSL-IDLE? 0= IF
            KDOSTLSL-S-BUSY EXIT
        THEN
        _KDOSTLSLI-OWNER @ _KDOSTLSL.OWNER-GEN @
        _KDOSTLSLI-OLD-GEN !
    THEN
    _KDOSTLSLI-OLD-GEN @ DUP IF
        DUP _KDOSTLSL-CELL-MAX >= IF DROP KDOSTLSL-S-STATE EXIT THEN
        1+
    ELSE
        DROP 1
    THEN _KDOSTLSLI-NEW-GEN !
    _KDOSTLSLI-OWNER @ KDOSTLSL-SIZE 0 FILL
    _KDOSTLSL-MAGIC-VALUE _KDOSTLSLI-OWNER @ _KDOSTLSL.MAGIC !
    _KDOSTLSLI-SERVICE @ _KDOSTLSLI-OWNER @ _KDOSTLSL.XIO-SERVICE !
    _KDOSTLSLI-SD @ _KDOSTLSLI-OWNER @ _KDOSTLSL.LISTENER-SD !
    _KDOSTLSLI-H1 @ _KDOSTLSLI-OWNER @ _KDOSTLSL.LISTENER-H1 !
    _KDOSTLSLI-GEN @ _KDOSTLSLI-OWNER @ _KDOSTLSL.LISTENER-GEN !
    _KDOSTLSLI-TIMEOUT @ _KDOSTLSLI-OWNER @ _KDOSTLSL.TIMEOUT-MS !
    _KDOSTLSLI-EARLY @ _KDOSTLSLI-OWNER @ _KDOSTLSL.EARLY-BUDGET !
    _KDOSTLSLI-NEW-GEN @ _KDOSTLSLI-OWNER @ _KDOSTLSL.OWNER-GEN !
    _KDOSTLSL-PHASE-IDLE _KDOSTLSLI-OWNER @ _KDOSTLSL.PHASE !
    _KDOSTLSLI-OWNER @ _KDOSTLSL.XIO-OP XIO-OP-INIT
