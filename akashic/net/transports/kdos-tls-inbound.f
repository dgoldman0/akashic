: KDOSTLSP.PORT          ( result -- port ) _KDOSTLSP-PORT + ;
: KDOSTLSP.STATE         ( result -- a ) _KDOSTLSP-STATE + ;
: KDOSTLSP.SOCKET-SD     ( result -- a ) _KDOSTLSP-SOCKET-SD + ;
: KDOSTLSP.LAST-ERROR    ( result -- a ) _KDOSTLSP-LAST-ERROR + ;
: KDOSTLSP.CLEANUP-ERROR ( result -- a ) _KDOSTLSP-CLEANUP-ERROR + ;
: _KDOSTLSP.MAGIC        ( result -- a ) _KDOSTLSP-MAGIC + ;

: _KDOSTLSP-VALID?  ( result -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP KDOSTLSP-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _KDOSTLSP.MAGIC @ _KDOSTLSP-MAGIC-VALUE =
    OVER KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-RESET >=
    SWAP KDOSTLSP-STATE-QUARANTINED <= AND AND
    SWAP DROP ;

: _KDOSTLSP-PORT-ACTIVE?  ( result -- flag )
    KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-OPEN >=
    SWAP KDOSTLSP-STATE-CLOSE-ABORT <= AND ;

: _KDOSTLSP-BUSY-IOR?  ( ior -- flag )
    DUP TLS-E-BUSY = SWAP TCP-ACCEPT-E-BUSY = OR ;

VARIABLE _KDOSTLSP-R
VARIABLE _KDOSTLSP-B
VARIABLE _KDOSTLSP-U
VARIABLE _KDOSTLSP-N
VARIABLE _KDOSTLSP-IOR

\ io-port contains callback exceptions, so every throwable port-side lower
\ call must first publish a provider state from which exact teardown can
\ continue.  XIO callbacks do not need these wrappers: XIO retains their
\ descriptor and drives its cooperative cleanup after containment.
: _KDOSTLSP-THROW>IOR  ( throw -- ior )
    DUP 0> IF DROP TLS-E-TRANSPORT THEN ;

: _KDOSTLSP-SEND-INNER  ( -- )
    _KDOSTLSP-R @ KDOSTLSP.SOCKET-SD @
    _KDOSTLSP-B @ _KDOSTLSP-U @ SEND _KDOSTLSP-N ! ;
: _KDOSTLSP-SEND-GUARDED  ( -- throw )
    ['] _KDOSTLSP-SEND-INNER CATCH ;

: _KDOSTLSP-RECV-INNER  ( -- )
    _KDOSTLSP-R @ KDOSTLSP.SOCKET-SD @
    _KDOSTLSP-B @ _KDOSTLSP-U @ RECV _KDOSTLSP-N ! ;
: _KDOSTLSP-RECV-GUARDED  ( -- throw )
    ['] _KDOSTLSP-RECV-INNER CATCH ;

: _KDOSTLSP-IO-STATUS-INNER  ( -- )
    _KDOSTLSP-R @ KDOSTLSP.SOCKET-SD @
    SOCK-TLS-IO-STATUS _KDOSTLSP-IOR ! ;
: _KDOSTLSP-IO-STATUS-GUARDED  ( -- throw )
    ['] _KDOSTLSP-IO-STATUS-INNER CATCH ;

: _KDOSTLSP-READY-INNER  ( -- )
    _KDOSTLSP-R @ KDOSTLSP.SOCKET-SD @ SOCKET-READY?
    _KDOSTLSP-N ! ;
: _KDOSTLSP-READY-GUARDED  ( -- throw )
    ['] _KDOSTLSP-READY-INNER CATCH ;

: _KDOSTLSP-POLL-INNER  ( -- ) TCP-POLL ;
: _KDOSTLSP-POLL-GUARDED  ( -- throw )
    ['] _KDOSTLSP-POLL-INNER CATCH ;

: _KDOSTLSP-CLOSE-TRY-INNER  ( -- )
    _KDOSTLSP-R @ KDOSTLSP.SOCKET-SD @ CLOSE-TRY _KDOSTLSP-IOR ! ;
: _KDOSTLSP-CLOSE-TRY-GUARDED  ( -- throw )
    ['] _KDOSTLSP-CLOSE-TRY-INNER CATCH ;

: _KDOSTLSP-ABORT-INNER  ( -- )
    _KDOSTLSP-R @ KDOSTLSP.SOCKET-SD @ SOCK-ABORT
    _KDOSTLSP-IOR ! DROP ;
: _KDOSTLSP-ABORT-GUARDED  ( -- throw )
    ['] _KDOSTLSP-ABORT-INNER CATCH ;

: _KDOSTLSP-ERROR!  ( ior result -- )
    DUP KDOSTLSP.LAST-ERROR @ 0= IF
        KDOSTLSP.LAST-ERROR !
    ELSE
        2DROP
    THEN ;

: _KDOSTLSP-CLEANUP-ERROR!  ( ior result -- )
    DUP KDOSTLSP.CLEANUP-ERROR @ 0= IF
        KDOSTLSP.CLEANUP-ERROR !
    ELSE
        2DROP
    THEN ;

: _KDOSTLSP-MARK-ERROR  ( ior result -- )
    2DUP _KDOSTLSP-ERROR!
    KDOSTLSP-STATE-ERROR SWAP KDOSTLSP.STATE ! DROP ;

: _KDOSTLSP-OPERABLE?  ( result -- flag )
    DUP _KDOSTLSP-VALID? 0= IF DROP 0 EXIT THEN
    DUP KDOSNET-OPERATE? SWAP KDOSTLSP.SOCKET-SD @ 0<> AND ;

VARIABLE _KDOSTLSP-OWNER-R

: _KDOSTLSP-OWNER-RELEASE  ( result -- flag )
    DUP _KDOSTLSP-OWNER-R ! KDOSNET-RELEASE DUP IF
        _KDOSTLSP-OWNER-R @ _KDOSTLSP-CLEANUP-ERROR!
        0
    ELSE
        DROP -1
    THEN ;

: _KDOSTLSP-QUARANTINE  ( ior result -- )
    2DUP _KDOSTLSP-CLEANUP-ERROR!
    KDOSTLSP-STATE-QUARANTINED SWAP KDOSTLSP.STATE ! DROP ;

: _KDOSTLSP-NIO-SEND  ( buffer length result -- count nio-status )
    _KDOSTLSP-R ! _KDOSTLSP-U ! _KDOSTLSP-B !
    COREID 0<> IF 0 NIO-S-FAILED EXIT THEN
    _KDOSTLSP-R @ _KDOSTLSP-VALID? 0= IF 0 NIO-S-FAILED EXIT THEN
    _KDOSTLSP-R @ KDOSTLSP.STATE @ KDOSTLSP-STATE-OPEN <> IF
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-R @ _KDOSTLSP-OPERABLE? 0= IF
        KDOSTLSA-E-STATE _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-U @ 0<
    _KDOSTLSP-B @ 0= _KDOSTLSP-U @ 0> AND OR IF
        KDOSTLSA-E-STATE _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-B @ _KDOSTLSP-U @ MSPAN-NONWRAPPING? 0=
    _KDOSTLSP-B @ _KDOSTLSP-U @
    _KDOSTLSP-R @ KDOSTLSP-SIZE MSPAN-OVERLAP? OR IF
        KDOSTLSA-E-STATE _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-U @ 0= IF 0 NIO-S-OK EXIT THEN
    _KDOSTLSP-SEND-GUARDED ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-N @ DUP 0< SWAP _KDOSTLSP-U @ > OR IF
        TLS-E-TRANSPORT _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-N @ 0= IF
        _KDOSTLSP-IO-STATUS-GUARDED ?DUP IF
            _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
            0 NIO-S-FAILED EXIT
        THEN
        _KDOSTLSP-IOR @ DUP TLS-E-BUSY = IF DROP 0 NIO-S-OK EXIT THEN
        DUP IF
            _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
            0 NIO-S-FAILED EXIT
        THEN DROP
    THEN
    _KDOSTLSP-N @ NIO-S-OK ;

: _KDOSTLSP-NIO-RECV  ( buffer capacity result -- count nio-status )
    _KDOSTLSP-R ! _KDOSTLSP-U ! _KDOSTLSP-B !
    COREID 0<> IF 0 NIO-S-FAILED EXIT THEN
    _KDOSTLSP-R @ _KDOSTLSP-VALID? 0= IF 0 NIO-S-FAILED EXIT THEN
    _KDOSTLSP-R @ KDOSTLSP.STATE @ KDOSTLSP-STATE-OPEN <> IF
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-R @ _KDOSTLSP-OPERABLE? 0= IF
        KDOSTLSA-E-STATE _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-U @ 0> 0= _KDOSTLSP-B @ 0= OR IF
        KDOSTLSA-E-STATE _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-B @ _KDOSTLSP-U @ MSPAN-NONWRAPPING? 0=
    _KDOSTLSP-B @ _KDOSTLSP-U @
    _KDOSTLSP-R @ KDOSTLSP-SIZE MSPAN-OVERLAP? OR IF
        KDOSTLSA-E-STATE _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-RECV-GUARDED ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-N @ 0< IF
        _KDOSTLSP-IO-STATUS-GUARDED ?DUP IF
            _KDOSTLSP-THROW>IOR
        ELSE
            _KDOSTLSP-IOR @ DUP 0= IF DROP TLS-E-TRANSPORT THEN
        THEN
        _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-N @ _KDOSTLSP-U @ > IF
        TLS-E-TRANSPORT _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-N @ IF _KDOSTLSP-N @ NIO-S-OK EXIT THEN
    _KDOSTLSP-IO-STATUS-GUARDED ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-IOR @ DUP TLS-E-BUSY = IF DROP 0 NIO-S-OK EXIT THEN
    DUP IF
        _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN DROP
    _KDOSTLSP-READY-GUARDED ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR
        0 NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-N @ IF
        0 NIO-S-EOF
    ELSE
        0 NIO-S-OK
    THEN ;

: _KDOSTLSP-NIO-POLL  ( result -- )
    COREID 0<> IF DROP KDOSTLSA-E-PLATFORM THROW THEN
    DUP _KDOSTLSP-VALID? 0= IF DROP KDOSTLSA-E-STATE THROW THEN
    DUP _KDOSTLSP-R !
    DUP KDOSTLSP.STATE @ KDOSTLSP-STATE-OPEN <> IF
        DROP KDOSTLSA-E-STATE THROW
    THEN
    DUP KDOSNET-OPERATE? 0= IF
        KDOSTLSA-E-CLEANUP OVER _KDOSTLSP-QUARANTINE
        DROP KDOSTLSP-E-QUARANTINED THROW
    THEN
    DROP _KDOSTLSP-POLL-GUARDED ?DUP IF
        _KDOSTLSP-THROW>IOR DUP _KDOSTLSP-R @ _KDOSTLSP-MARK-ERROR THROW
    THEN ;

: _KDOSTLSP-DETACHED  ( result -- nio-status )
    DUP 0 SWAP KDOSTLSP.SOCKET-SD !
    DUP _KDOSTLSP-OWNER-RELEASE 0= IF
        KDOSTLSP-STATE-QUARANTINED OVER KDOSTLSP.STATE !
        DROP NIO-S-FAILED EXIT
    THEN
    DUP KDOSTLSP.LAST-ERROR @ >R
    KDOSTLSP-STATE-CLOSED SWAP KDOSTLSP.STATE !
    R> IF NIO-S-FAILED ELSE NIO-S-OK THEN ;

: _KDOSTLSP-CLOSE-TRY-STEP  ( result -- nio-status )
    _KDOSTLSP-R !
    _KDOSTLSP-CLOSE-TRY-GUARDED ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-ERROR!
        KDOSTLSP-STATE-CLOSE-ABORT _KDOSTLSP-R @ KDOSTLSP.STATE !
        NIO-S-PENDING EXIT
    THEN
    _KDOSTLSP-IOR @ DUP 0= IF
        DROP _KDOSTLSP-R @ _KDOSTLSP-DETACHED EXIT
    THEN
    DUP _KDOSTLSP-BUSY-IOR? IF DROP NIO-S-PENDING EXIT THEN
    TLS-E-WOULD-BLOCK = IF
        KDOSTLSP-STATE-CLOSE-POLL _KDOSTLSP-R @ KDOSTLSP.STATE !
        NIO-S-PENDING EXIT
    THEN
    _KDOSTLSP-IOR @ _KDOSTLSP-R @ _KDOSTLSP-ERROR!
    KDOSTLSP-STATE-CLOSE-ABORT _KDOSTLSP-R @ KDOSTLSP.STATE !
    NIO-S-PENDING ;

: _KDOSTLSP-ABORT-STEP  ( result -- nio-status )
    _KDOSTLSP-R !
    _KDOSTLSP-ABORT-GUARDED ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-QUARANTINE
        NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-IOR @ 0= IF
        _KDOSTLSP-R @ _KDOSTLSP-DETACHED EXIT
    THEN
    _KDOSTLSP-IOR @ _KDOSTLSP-BUSY-IOR? IF NIO-S-PENDING EXIT THEN
    _KDOSTLSP-IOR @ _KDOSTLSP-R @ _KDOSTLSP-QUARANTINE
    NIO-S-FAILED ;

: _KDOSTLSP-CLOSE-STEP  ( result -- nio-status )
    DUP _KDOSTLSP-R ! KDOSTLSP.STATE @ CASE
        KDOSTLSP-STATE-OPEN OF
            KDOSTLSP-STATE-CLOSE-TRY _KDOSTLSP-R @ KDOSTLSP.STATE !
            _KDOSTLSP-R @ _KDOSTLSP-CLOSE-TRY-STEP
        ENDOF
        KDOSTLSP-STATE-ERROR OF
            KDOSTLSP-STATE-CLOSE-ABORT _KDOSTLSP-R @ KDOSTLSP.STATE !
            NIO-S-PENDING
        ENDOF
        KDOSTLSP-STATE-CLOSE-TRY OF
            _KDOSTLSP-R @ _KDOSTLSP-CLOSE-TRY-STEP
        ENDOF
        KDOSTLSP-STATE-CLOSE-POLL OF
            _KDOSTLSP-POLL-GUARDED ?DUP IF
                _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-ERROR!
                KDOSTLSP-STATE-CLOSE-ABORT
                _KDOSTLSP-R @ KDOSTLSP.STATE !
                NIO-S-PENDING
            ELSE
                KDOSTLSP-STATE-CLOSE-TRY
                _KDOSTLSP-R @ KDOSTLSP.STATE !
                NIO-S-PENDING
            THEN
        ENDOF
        KDOSTLSP-STATE-CLOSE-ABORT OF
            _KDOSTLSP-R @ _KDOSTLSP-ABORT-STEP
        ENDOF
        KDOSTLSP-STATE-CLOSED OF NIO-S-OK ENDOF
        KDOSTLSP-STATE-CANCELLED OF NIO-S-CANCELLED ENDOF
        KDOSTLSP-STATE-QUARANTINED OF NIO-S-FAILED ENDOF
        NIO-S-FAILED SWAP
    ENDCASE ;

: _KDOSTLSP-NIO-CLOSE-START  ( result -- nio-status )
    COREID 0<> IF DROP NIO-S-FAILED EXIT THEN
    DUP _KDOSTLSP-VALID? 0= IF DROP NIO-S-FAILED EXIT THEN
    DUP KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-CLOSED = IF
        2DROP NIO-S-OK EXIT
    THEN
    KDOSTLSP-STATE-CANCELLED = IF DROP NIO-S-CANCELLED EXIT THEN
    DUP _KDOSTLSP-PORT-ACTIVE? 0= IF DROP NIO-S-FAILED EXIT THEN
    DUP KDOSNET-OPERATE? 0= IF
        KDOSTLSA-E-CLEANUP OVER _KDOSTLSP-QUARANTINE
        DROP NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-CLOSE-STEP ;

: _KDOSTLSP-NIO-CLOSE-POLL  ( result -- nio-status )
    COREID 0<> IF DROP NIO-S-FAILED EXIT THEN
    DUP _KDOSTLSP-VALID? 0= IF DROP NIO-S-FAILED EXIT THEN
    DUP KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-CLOSED = IF
        2DROP NIO-S-OK EXIT
    THEN
    KDOSTLSP-STATE-CANCELLED = IF DROP NIO-S-CANCELLED EXIT THEN
    DUP _KDOSTLSP-PORT-ACTIVE? 0= IF DROP NIO-S-FAILED EXIT THEN
    DUP KDOSNET-OPERATE? 0= IF
        KDOSTLSA-E-CLEANUP OVER _KDOSTLSP-QUARANTINE
        DROP NIO-S-FAILED EXIT
    THEN
    _KDOSTLSP-CLOSE-STEP ;

: _KDOSTLSP-NIO-CLOSE  ( result -- )
    DUP _KDOSTLSP-VALID? 0= IF DROP KDOSTLSA-E-STATE THROW THEN
    DUP KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-CLOSED =
    SWAP KDOSTLSP-STATE-CANCELLED = OR IF DROP EXIT THEN
    DUP _KDOSTLSP-PORT-ACTIVE? 0= IF
        DROP KDOSTLSA-E-STATE THROW
    THEN
    DUP _KDOSTLSP-R ! _KDOSTLSP-NIO-CLOSE-START
    NIO-S-OK <> IF
        KDOSTLSA-E-CLEANUP _KDOSTLSP-R @ _KDOSTLSP-QUARANTINE
        KDOSTLSP-E-QUARANTINED THROW
    THEN ;

: _KDOSTLSP-NIO-CANCEL  ( result -- )
    COREID 0<> IF DROP KDOSTLSA-E-PLATFORM THROW THEN
    DUP _KDOSTLSP-VALID? 0= IF DROP KDOSTLSA-E-STATE THROW THEN
    DUP _KDOSTLSP-R ! KDOSTLSP.STATE @
    DUP KDOSTLSP-STATE-CLOSED = SWAP KDOSTLSP-STATE-CANCELLED = OR IF
        EXIT
    THEN
    _KDOSTLSP-R @ _KDOSTLSP-PORT-ACTIVE? 0= IF
        KDOSTLSA-E-STATE THROW
    THEN
    _KDOSTLSP-R @ KDOSNET-OPERATE? 0= IF
        KDOSTLSA-E-CLEANUP _KDOSTLSP-R @ _KDOSTLSP-QUARANTINE
        KDOSTLSP-E-QUARANTINED THROW
    THEN
    _KDOSTLSP-ABORT-GUARDED ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-QUARANTINE
        KDOSTLSP-E-QUARANTINED THROW
    THEN
    _KDOSTLSP-IOR @ IF
        _KDOSTLSP-IOR @ _KDOSTLSP-R @ _KDOSTLSP-QUARANTINE
        KDOSTLSP-E-QUARANTINED THROW
    THEN
    0 _KDOSTLSP-R @ KDOSTLSP.SOCKET-SD !
    _KDOSTLSP-R @ _KDOSTLSP-OWNER-RELEASE 0= IF
        KDOSTLSP-STATE-QUARANTINED _KDOSTLSP-R @ KDOSTLSP.STATE !
        KDOSTLSP-E-QUARANTINED THROW
    THEN
    KDOSTLSP-STATE-CANCELLED _KDOSTLSP-R @ KDOSTLSP.STATE ! ;

: _KDOSTLSP-INSTALL  ( result -- )
    DUP KDOSTLSP.PORT NIO-INIT
    DUP OVER KDOSTLSP.PORT NIO.CONTEXT !
    ['] _KDOSTLSP-NIO-SEND OVER KDOSTLSP.PORT NIO.SEND-XT !
    ['] _KDOSTLSP-NIO-RECV OVER KDOSTLSP.PORT NIO.RECV-XT !
    ['] _KDOSTLSP-NIO-POLL OVER KDOSTLSP.PORT NIO.POLL-XT !
    ['] _KDOSTLSP-NIO-CLOSE OVER KDOSTLSP.PORT NIO.CLOSE-XT !
    ['] _KDOSTLSP-NIO-CLOSE-START OVER KDOSTLSP.PORT NIO.CLOSE-START-XT !
    ['] _KDOSTLSP-NIO-CLOSE-POLL OVER KDOSTLSP.PORT NIO.CLOSE-POLL-XT !
    ['] _KDOSTLSP-NIO-CANCEL OVER KDOSTLSP.PORT NIO.CANCEL-XT !
    DROP ;

: KDOSTLSP-INIT  ( result -- status )
    COREID 0<> IF DROP KDOSTLSA-S-PLATFORM EXIT THEN
    DUP 0= IF DROP KDOSTLSA-S-INVALID EXIT THEN
    DUP KDOSTLSP-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP KDOSTLSA-S-INVALID EXIT
    THEN
    DUP KDOSNET-OWNER? IF DROP KDOSTLSA-S-BUSY EXIT THEN
    DUP _KDOSTLSP-VALID? IF
        DUP KDOSTLSP.SOCKET-SD @ IF DROP KDOSTLSA-S-STATE EXIT THEN
        DUP KDOSTLSP.STATE @ DUP KDOSTLSP-STATE-RESET =
        OVER KDOSTLSP-STATE-CLOSED = OR
        SWAP KDOSTLSP-STATE-CANCELLED = OR 0= IF
            DROP KDOSTLSA-S-STATE EXIT
        THEN
    THEN
    DUP KDOSTLSP-SIZE 0 FILL
    _KDOSTLSP-MAGIC-VALUE OVER _KDOSTLSP.MAGIC !
    KDOSTLSP-STATE-RESET OVER KDOSTLSP.STATE !
    DUP _KDOSTLSP-INSTALL
    DROP KDOSTLSA-S-OK ;

: KDOSTLSP-RESET  ( result -- status )
    KDOSTLSP-INIT ;

\ Recovery exists only for post-TAKE NIO quarantine.  Normal accept
\ cancellation, timeout, failure, and retained-result discard are driven by
\ XIO's cooperative cleanup poll and never enter this path.
: KDOSTLSP-RECOVER-STEP  ( result -- status )
    COREID 0<> IF DROP KDOSTLSA-S-PLATFORM EXIT THEN
    DUP _KDOSTLSP-VALID? 0= IF DROP KDOSTLSA-S-INVALID EXIT THEN
    DUP KDOSTLSP.STATE @ KDOSTLSP-STATE-QUARANTINED <> IF
        DROP KDOSTLSA-S-STATE EXIT
    THEN
    DUP _KDOSTLSP-R ! KDOSNET-OPERATE? 0= IF
        KDOSTLSA-S-NOT-OWNER EXIT
    THEN
    _KDOSTLSP-R @ KDOSTLSP.SOCKET-SD @ 0= IF
        _KDOSTLSP-R @ _KDOSTLSP-OWNER-RELEASE IF
            KDOSTLSP-STATE-CLOSED _KDOSTLSP-R @ KDOSTLSP.STATE !
            KDOSTLSA-S-OK
        ELSE
            KDOSTLSA-S-PENDING
        THEN EXIT
    THEN
    _KDOSTLSP-ABORT-GUARDED ?DUP IF
        _KDOSTLSP-THROW>IOR _KDOSTLSP-R @ _KDOSTLSP-QUARANTINE
        KDOSTLSA-S-LOWER EXIT
    THEN
    _KDOSTLSP-IOR @ DUP 0= IF
        DROP 0 _KDOSTLSP-R @ KDOSTLSP.SOCKET-SD !
        _KDOSTLSP-R @ _KDOSTLSP-OWNER-RELEASE IF
            KDOSTLSP-STATE-CLOSED _KDOSTLSP-R @ KDOSTLSP.STATE !
            KDOSTLSA-S-OK
        ELSE
            KDOSTLSA-S-PENDING
        THEN EXIT
    THEN
    _KDOSTLSP-BUSY-IOR? IF KDOSTLSA-S-PENDING ELSE KDOSTLSA-S-LOWER THEN ;

