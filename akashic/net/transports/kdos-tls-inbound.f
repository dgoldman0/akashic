: _KDOSTLSA-SUBMIT-GEOMETRY?  ( -- flag )
    _KDOSTLSS-SERVICE @ XIO-SERVICE-SIZE MSPAN-NONWRAPPING?
    _KDOSTLSS-OP @ XIO-OP-SIZE MSPAN-NONWRAPPING? AND
    _KDOSTLSS-A @ KDOSTLSA-SIZE MSPAN-NONWRAPPING? AND
    _KDOSTLSS-A @ KDOSTLSA.RESULT @ KDOSTLSP-SIZE
        MSPAN-NONWRAPPING? AND 0= IF 0 EXIT THEN
    _KDOSTLSS-SERVICE @ XIO-SERVICE-SIZE
    _KDOSTLSS-OP @ XIO-OP-SIZE MSPAN-OVERLAP? IF 0 EXIT THEN
    _KDOSTLSS-SERVICE @ XIO-SERVICE-SIZE
    _KDOSTLSS-A @ KDOSTLSA-SIZE MSPAN-OVERLAP? IF 0 EXIT THEN
    _KDOSTLSS-SERVICE @ XIO-SERVICE-SIZE
    _KDOSTLSS-A @ KDOSTLSA.RESULT @ KDOSTLSP-SIZE
        MSPAN-OVERLAP? IF 0 EXIT THEN
    _KDOSTLSS-OP @ XIO-OP-SIZE
    _KDOSTLSS-A @ KDOSTLSA-SIZE MSPAN-OVERLAP? IF 0 EXIT THEN
    _KDOSTLSS-OP @ XIO-OP-SIZE
    _KDOSTLSS-A @ KDOSTLSA.RESULT @ KDOSTLSP-SIZE
        MSPAN-OVERLAP? IF 0 EXIT THEN
    _KDOSTLSS-A @ KDOSTLSA-SIZE
    _KDOSTLSS-A @ KDOSTLSA.RESULT @ KDOSTLSP-SIZE
        MSPAN-OVERLAP? 0= ;

: KDOSTLSA-SUBMIT
    ( service owner-id owner-gen request-gen operation adapter -- xio-status )
    _KDOSTLSS-A ! _KDOSTLSS-OP ! _KDOSTLSS-REQUEST-GEN !
    _KDOSTLSS-OWNER-GEN ! _KDOSTLSS-OWNER ! _KDOSTLSS-SERVICE !
    COREID 0<> IF XIO-S-NOT-OWNER EXIT THEN
    _KDOSTLSS-A @ _KDOSTLSA-VALID? 0= IF XIO-S-INVALID EXIT THEN
    _KDOSTLSS-A @ KDOSTLSA.PHASE @
    KDOSTLSA-PHASE-CONFIGURED <> IF XIO-S-STATE EXIT THEN
    _KDOSTLSS-A @ KDOSTLSA.RESULT @ DUP _KDOSTLSP-VALID? 0= IF
        DROP XIO-S-INVALID EXIT
    THEN
    KDOSTLSP.STATE @ KDOSTLSP-STATE-RESET <> IF XIO-S-STATE EXIT THEN
    _KDOSTLSA-SUBMIT-GEOMETRY? 0= IF XIO-S-INVALID EXIT THEN
    _KDOSTLSS-SERVICE @ _KDOSTLSS-OWNER @
    _KDOSTLSS-OWNER-GEN @ _KDOSTLSS-REQUEST-GEN @ 0
    _KDOSTLSS-A @
    ['] _KDOSTLSA-START ['] _KDOSTLSA-POLL
    ['] _KDOSTLSA-CANCEL ['] _KDOSTLSA-WIPE
    _KDOSTLSS-OP @ XIO-OP-CONFIGURE DUP XIO-S-OK <> IF EXIT THEN DROP
    _KDOSTLSS-SERVICE @ _KDOSTLSS-OWNER @ _KDOSTLSS-OWNER-GEN @
    _KDOSTLSS-REQUEST-GEN @ ['] _KDOSTLSA-CLEANUP-POLL
    _KDOSTLSS-OP @ XIO-OP-CONFIGURE-CLEANUP DUP XIO-S-OK <> IF
        _KDOSTLSS-OP @ XIO-OP-INIT EXIT
    THEN DROP
    _KDOSTLSS-SERVICE @ _KDOSTLSS-OP @ XIO-SUBMIT ;

: KDOSTLSA-RETRY?  ( operation -- flag )
    DUP XIO-OP-VALID? 0= IF DROP 0 EXIT THEN
    DUP XIOO.STATE @ XIO-STATE-FAILED <> IF DROP 0 EXIT THEN
    XIOO.ERROR @ DUP TLS-E-WOULD-BLOCK =
    OVER TLS-E-BUSY = OR
    SWAP KDOSTLSA-E-CONTENTION = OR ;

