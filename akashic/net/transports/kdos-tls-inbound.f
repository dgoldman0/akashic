: KDOSTLSA-TAKE
    \ ( service owner-id owner-gen request-gen operation adapter
    \   -- port|0 status )
    _KDOSTLST-A ! _KDOSTLST-OP ! _KDOSTLST-REQUEST-GEN !
    _KDOSTLST-OWNER-GEN ! _KDOSTLST-OWNER ! _KDOSTLST-SERVICE !
    COREID 0<> IF 0 KDOSTLSA-S-PLATFORM EXIT THEN
    _KDOSTLST-SERVICE @ XIO-SERVICE-BOUND? 0= IF
        0 KDOSTLSA-S-INVALID EXIT
    THEN
    _KDOSTLST-SERVICE @ XIO-SERVICE-OWNER? 0= IF
        0 KDOSTLSA-S-NOT-OWNER EXIT
    THEN
    _KDOSTLST-OP @ XIO-OP-VALID? 0=
    _KDOSTLST-A @ _KDOSTLSA-VALID? 0= OR IF
        0 KDOSTLSA-S-INVALID EXIT
    THEN
    _KDOSTLST-OP @ XIOO.CONTEXT @ _KDOSTLST-A @ <> IF
        0 KDOSTLSA-S-INVALID EXIT
    THEN
    _KDOSTLST-OWNER @ _KDOSTLST-OWNER-GEN @ _KDOSTLST-REQUEST-GEN @
    _KDOSTLST-OP @ XIO-OP-MATCH? 0= IF
        0 KDOSTLSA-S-NOT-OWNER EXIT
    THEN
    _KDOSTLST-OP @ XIO-CLEANUP-PENDING?
    _KDOSTLST-SERVICE @ XIO-ACTIVE? OR IF
        0 KDOSTLSA-S-PENDING EXIT
    THEN
    _KDOSTLST-SERVICE @ XIOS.RETAINED @ _KDOSTLST-OP @ <>
    _KDOSTLST-OP @ XIOO.STATE @ XIO-STATE-SUCCEEDED <> OR IF
        0 KDOSTLSA-S-PENDING EXIT
    THEN
    _KDOSTLST-A @ KDOSTLSA.PHASE @ KDOSTLSA-PHASE-PUBLISHED <> IF
        0 KDOSTLSA-S-STATE EXIT
    THEN
    _KDOSTLST-A @ KDOSTLSA.RESULT @ DUP _KDOSTLST-RESULT !
    DUP _KDOSTLSP-VALID? 0= IF DROP 0 KDOSTLSA-S-INVALID EXIT THEN
    DUP _KDOSTLST-OP @ XIOO.RESULT @ <>
    OVER KDOSTLSP.STATE @ KDOSTLSP-STATE-PUBLISHED <> OR
    SWAP KDOSTLSP.SOCKET-SD @ 0= OR IF 0 KDOSTLSA-S-STATE EXIT THEN
    _KDOSTLST-RESULT @ KDOSNET-OPERATE? 0= IF
        0 KDOSTLSA-S-NOT-OWNER EXIT
    THEN
    \ Clear any premature io-port wrapper diagnostics only after the exact
    \ retained authority and live generations have all been proven.
    _KDOSTLST-RESULT @ _KDOSTLSP-INSTALL
    _KDOSTLST-RESULT @ KDOSTLSP.PORT NIO-OPEN
    NIO-S-OK <> IF 0 KDOSTLSA-S-STATE EXIT THEN
    KDOSTLSP-STATE-OPEN _KDOSTLST-RESULT @ KDOSTLSP.STATE !
    KDOSTLSA-PHASE-TAKEN _KDOSTLST-A @ KDOSTLSA.PHASE !
    _KDOSTLST-RESULT @ KDOSTLSP.PORT KDOSTLSA-S-OK ;
