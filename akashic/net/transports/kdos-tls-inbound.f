: _KDOSTLSL-CALLBACK-BEGIN  ( operation owner -- flag )
    _KDOSTLSLX-OWNER ! _KDOSTLSLX-OP !
    _KDOSTLSLX-OWNER @ _KDOSTLSL-VALID? 0= IF 0 EXIT THEN
    _KDOSTLSLX-OP @ XIO-OP-VALID? 0= IF 0 EXIT THEN
    _KDOSTLSLX-OP @ XIOO.CONTEXT @ _KDOSTLSLX-OWNER @ =
    _KDOSTLSLX-OWNER @ _KDOSTLSL-XIO-EXACT? AND ;

: _KDOSTLSL-PRIMARY!  ( ior -- )
    ?DUP IF
        _KDOSTLSLX-OP @ XIOO.ERROR @ 0= IF
            _KDOSTLSLX-OP @ XIOO.ERROR !
        ELSE
            DROP
        THEN
    THEN ;

: _KDOSTLSL-SECONDARY!  ( ior -- )
    ?DUP IF
        _KDOSTLSLX-OP @ XIOO.CLEANUP-ERROR @ 0= IF
            _KDOSTLSLX-OP @ XIOO.CLEANUP-ERROR !
        ELSE
            DROP
        THEN
    THEN ;

: _KDOSTLSL-FAIL  ( ior -- step-status )
    DUP 0= IF DROP TLS-E-TRANSPORT THEN
    _KDOSTLSL-PRIMARY! XIO-STEP-FAILED ;

: _KDOSTLSL-TERMINAL-FAIL  ( secondary-ior -- step-status )
    _KDOSTLSL-SECONDARY!
    _KDOSTLSLX-OP @ XIOO.ERROR @ 0= IF
        TLS-E-TRANSPORT _KDOSTLSLX-OP @ XIOO.ERROR !
    THEN
    XIO-STEP-FAILED ;

: _KDOSTLSL-THROW>IOR  ( throw -- ior )
    DUP 0> IF DROP TLS-E-TRANSPORT THEN ;

: _KDOSTLSL-ALERT-VALID?  ( alert -- flag )
    DUP 0> SWAP 255 <= AND ;

: _KDOSTLSL-EARLY-ALERT  ( alert -- step-status )
    _KDOSTLSLX-OP @ XIOO.RESULT !
    KDOSTLSL-E-HANDSHAKE-ALERT _KDOSTLSLX-OP @ XIOO.ERROR !
    XIO-STEP-FAILED ;

: _KDOSTLSL-ARM-DEADLINE  ( -- )
    MS@ _KDOSTLSLX-OWNER @ _KDOSTLSL.TIMEOUT-MS @ +
    _KDOSTLSLX-OP @ XIOO.DEADLINE-MS ! ;

: _KDOSTLSL-LISTENER-POLL-STEP  ( -- step-status )
    TCP-POLL
    _KDOSTLSL-PHASE-CLAIM _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE !
    XIO-STEP-PENDING ;

: _KDOSTLSL-CLAIM-STEP  ( -- step-status )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.LISTENER-SD @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.LISTENER-H1 @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.LISTENER-GEN @
    TLS-SERVER-ACCEPT-CLAIM
    _KDOSTLSLX-IOR ! _KDOSTLSLX-GEN ! _KDOSTLSLX-CTX !
    _KDOSTLSLX-IOR @ IF
        _KDOSTLSLX-CTX @ _KDOSTLSLX-GEN @ OR IF
            _KDOSTLSLX-CTX @ _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX !
            _KDOSTLSLX-GEN @ _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN !
            TLS-E-TRANSPORT _KDOSTLSL-FAIL EXIT
        THEN
        _KDOSTLSLX-IOR @ _KDOSTLSL-FAIL EXIT
    THEN
    _KDOSTLSLX-CTX @ 0= _KDOSTLSLX-GEN @ 0= OR IF
        TLS-E-TRANSPORT _KDOSTLSL-FAIL EXIT
    THEN
    _KDOSTLSLX-CTX @ _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX !
    _KDOSTLSLX-GEN @ _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN !
    _KDOSTLSL-ARM-DEADLINE
    _KDOSTLSL-PHASE-CLIENT-HELLO
    _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE !
    XIO-STEP-PENDING ;

: _KDOSTLSL-CLIENT-HELLO-STEP  ( -- step-status )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @
    TLS-SERVER-CLIENT-HELLO-STEP
    _KDOSTLSLX-IOR ! _KDOSTLSLX-ALERT ! _KDOSTLSLX-PROGRESS !
    _KDOSTLSLX-IOR @ DUP TLS-E-WOULD-BLOCK = IF
        DROP _KDOSTLSLX-PROGRESS @ TLS-SERVER-CLIENT-HELLO-NONE =
        _KDOSTLSLX-ALERT @ 0= AND 0= IF
            TLS-E-TRANSPORT _KDOSTLSL-FAIL EXIT
        THEN
        _KDOSTLSL-PHASE-CLIENT-HELLO-POLL
        _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE ! XIO-STEP-PENDING EXIT
    THEN
    DUP TLS-E-BUSY = IF
        DROP _KDOSTLSLX-PROGRESS @ TLS-SERVER-CLIENT-HELLO-NONE =
        _KDOSTLSLX-ALERT @ 0= AND 0= IF
            TLS-E-TRANSPORT _KDOSTLSL-FAIL EXIT
        THEN
        XIO-STEP-PENDING EXIT
    THEN
    DUP IF
        >R _KDOSTLSLX-PROGRESS @ TLS-SERVER-CLIENT-HELLO-NONE =
        _KDOSTLSLX-ALERT @ 0= AND R@ 0< AND IF
            R> _KDOSTLSL-FAIL
        ELSE
            R> DROP TLS-E-TRANSPORT _KDOSTLSL-FAIL
        THEN EXIT
    THEN DROP
    _KDOSTLSLX-ALERT @ DUP IF
        DUP _KDOSTLSL-ALERT-VALID?
        _KDOSTLSLX-PROGRESS @ TLS-SERVER-CLIENT-HELLO-NONE = AND IF
            _KDOSTLSL-EARLY-ALERT
        ELSE
            DROP TLS-E-TRANSPORT _KDOSTLSL-FAIL
        THEN EXIT
    THEN DROP
    _KDOSTLSLX-PROGRESS @ DUP TLS-SERVER-CLIENT-HELLO-RECORD = IF
        DROP XIO-STEP-PENDING EXIT
    THEN
    TLS-SERVER-CLIENT-HELLO-COMPLETE = IF
        _KDOSTLSL-PHASE-PREPARE-HELLO
        _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE !
        XIO-STEP-PENDING EXIT
    THEN
    TLS-E-TRANSPORT _KDOSTLSL-FAIL ;

: _KDOSTLSL-PREPARE-HELLO-STEP  ( -- step-status )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @
    TLS-SERVER-PREPARE-HELLO-EXACT
    _KDOSTLSLX-IOR ! _KDOSTLSLX-ALERT !
    _KDOSTLSLX-IOR @ DUP TLS-E-BUSY = IF
        DROP _KDOSTLSLX-ALERT @ 0= IF XIO-STEP-PENDING
        ELSE TLS-E-TRANSPORT _KDOSTLSL-FAIL THEN EXIT
    THEN
    DUP IF
        >R _KDOSTLSLX-ALERT @ 0= R@ 0< AND IF
            R> _KDOSTLSL-FAIL
        ELSE
            R> DROP TLS-E-TRANSPORT _KDOSTLSL-FAIL
        THEN EXIT
    THEN DROP
    _KDOSTLSLX-ALERT @ DUP IF
        DUP _KDOSTLSL-ALERT-VALID? IF _KDOSTLSL-EARLY-ALERT
        ELSE DROP TLS-E-TRANSPORT _KDOSTLSL-FAIL THEN EXIT
    THEN DROP
    _KDOSTLSL-PHASE-PREPARE-FLIGHT
    _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE !
    XIO-STEP-PENDING ;

: _KDOSTLSL-PREPARE-FLIGHT-STEP  ( -- step-status )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @
    TLS-SERVER-PREPARE-FLIGHT-EXACT DUP _KDOSTLSLX-IOR !
    DUP TLS-E-BUSY = IF DROP XIO-STEP-PENDING EXIT THEN
    DUP IF
        DUP 0< IF _KDOSTLSL-FAIL
        ELSE DROP TLS-E-TRANSPORT _KDOSTLSL-FAIL THEN EXIT
    THEN DROP
    _KDOSTLSL-PHASE-FLIGHT _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE !
    XIO-STEP-PENDING ;

: _KDOSTLSL-FLIGHT-STEP  ( -- step-status )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @ TLS-SERVER-FLIGHT-STEP
    _KDOSTLSLX-IOR ! _KDOSTLSLX-PROGRESS !
    _KDOSTLSLX-IOR @ DUP TLS-E-BUSY = IF
        DROP _KDOSTLSLX-PROGRESS @ TLS-SERVER-EMIT-NONE = IF
            XIO-STEP-PENDING
        ELSE
            TLS-E-TRANSPORT _KDOSTLSL-FAIL
        THEN EXIT
    THEN
    DUP TLS-E-WOULD-BLOCK = IF
        DROP _KDOSTLSLX-PROGRESS @ TLS-SERVER-EMIT-NONE = IF
            _KDOSTLSL-PHASE-FLIGHT-POLL
            _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE ! XIO-STEP-PENDING
        ELSE
            TLS-E-TRANSPORT _KDOSTLSL-FAIL
        THEN EXIT
    THEN
    DUP IF
        >R _KDOSTLSLX-PROGRESS @ TLS-SERVER-EMIT-NONE = R@ 0< AND IF
            R> _KDOSTLSL-FAIL
        ELSE
            R> DROP TLS-E-TRANSPORT _KDOSTLSL-FAIL
        THEN EXIT
    THEN DROP
    _KDOSTLSLX-PROGRESS @ DUP TLS-SERVER-EMIT-RECORD = IF
        DROP XIO-STEP-PENDING EXIT
    THEN
    TLS-SERVER-EMIT-COMPLETE = IF
        _KDOSTLSL-PHASE-CLIENT-FLIGHT-BEGIN
        _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE ! XIO-STEP-PENDING EXIT
    THEN
    TLS-E-TRANSPORT _KDOSTLSL-FAIL ;

: _KDOSTLSL-CLIENT-FLIGHT-BEGIN-STEP  ( -- step-status )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.EARLY-BUDGET @
    TLS-SERVER-CLIENT-FLIGHT-BEGIN-ATTACHED DUP _KDOSTLSLX-IOR !
    DUP TLS-E-BUSY = IF DROP XIO-STEP-PENDING EXIT THEN
    DUP IF
        DUP 0< IF _KDOSTLSL-FAIL
        ELSE DROP TLS-E-TRANSPORT _KDOSTLSL-FAIL THEN EXIT
    THEN DROP
    _KDOSTLSL-PHASE-CLIENT-FLIGHT
    _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE !
    XIO-STEP-PENDING ;

: _KDOSTLSL-INGRESS-TERMINAL?  ( -- flag )
    _KDOSTLSLX-PROGRESS @
    DUP TLS-SERVER-INGRESS-SEND-FATAL = IF
        DROP _KDOSTLSLX-IOR @ DUP 0<
        SWAP TLS-E-PEER-ALERT <> AND
        _KDOSTLSLX-ALERT @ _KDOSTLSL-ALERT-VALID? AND EXIT
    THEN
    DUP TLS-SERVER-INGRESS-SEND-CLOSE = IF
        DROP _KDOSTLSLX-IOR @ TLS-E-PEER-ALERT =
        _KDOSTLSLX-ALERT @ 0= AND EXIT
    THEN
    TLS-SERVER-INGRESS-PEER-ALERT = IF
        _KDOSTLSLX-IOR @ TLS-E-PEER-ALERT =
        _KDOSTLSLX-ALERT @ _KDOSTLSL-ALERT-VALID? AND EXIT
    THEN
    0 ;

: _KDOSTLSL-CLIENT-FLIGHT-STEP  ( -- step-status )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @
    TLS-SERVER-CLIENT-FLIGHT-STEP
    _KDOSTLSLX-IOR ! _KDOSTLSLX-ALERT ! _KDOSTLSLX-PROGRESS !
    _KDOSTLSLX-IOR @ DUP TLS-E-BUSY = IF
        DROP _KDOSTLSLX-PROGRESS @ TLS-SERVER-INGRESS-NONE =
        _KDOSTLSLX-ALERT @ 0= AND IF XIO-STEP-PENDING
        ELSE TLS-E-TRANSPORT _KDOSTLSL-FAIL THEN EXIT
    THEN
    DUP TLS-E-WOULD-BLOCK = IF
        DROP _KDOSTLSLX-PROGRESS @ TLS-SERVER-INGRESS-NONE =
        _KDOSTLSLX-ALERT @ 0= AND IF
            _KDOSTLSL-PHASE-CLIENT-FLIGHT-POLL
            _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE ! XIO-STEP-PENDING
        ELSE
            TLS-E-TRANSPORT _KDOSTLSL-FAIL
        THEN EXIT
    THEN DROP
    _KDOSTLSLX-IOR @ IF
        _KDOSTLSL-INGRESS-TERMINAL? IF
            _KDOSTLSLX-IOR @ _KDOSTLSLX-OP @ XIOO.ERROR !
            _KDOSTLSLX-ALERT @ _KDOSTLSLX-OP @ XIOO.RESULT !
            _KDOSTLSL-PHASE-DISPOSITION
            _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE !
            XIO-STEP-PENDING EXIT
        THEN
        _KDOSTLSLX-PROGRESS @ TLS-SERVER-INGRESS-NONE =
        _KDOSTLSLX-ALERT @ 0= AND
        _KDOSTLSLX-IOR @ 0< AND IF
            _KDOSTLSLX-IOR @ _KDOSTLSL-FAIL
        ELSE
            TLS-E-TRANSPORT _KDOSTLSL-FAIL
        THEN EXIT
    THEN
    _KDOSTLSLX-ALERT @ IF TLS-E-TRANSPORT _KDOSTLSL-FAIL EXIT THEN
    _KDOSTLSLX-PROGRESS @ DUP TLS-SERVER-INGRESS-RECORD = IF
        DROP XIO-STEP-PENDING EXIT
    THEN
    TLS-SERVER-INGRESS-FINISHED = IF
        _KDOSTLSL-PHASE-PUBLISH
        _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE !
        XIO-STEP-PENDING EXIT
    THEN
    TLS-E-TRANSPORT _KDOSTLSL-FAIL ;

: _KDOSTLSL-DISPOSITION-STEP  ( -- step-status )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @
    TLS-SERVER-INGRESS-DISPOSITION-STEP
    _KDOSTLSLX-IOR ! _KDOSTLSLX-PROGRESS !
    _KDOSTLSLX-IOR @ DUP TLS-E-BUSY = IF
        DROP _KDOSTLSLX-PROGRESS @ TLS-SERVER-DISPOSITION-NONE = IF
            XIO-STEP-PENDING
        ELSE
            TLS-E-TRANSPORT _KDOSTLSL-TERMINAL-FAIL
        THEN EXIT
    THEN
    DUP TLS-E-WOULD-BLOCK = IF
        DROP _KDOSTLSLX-PROGRESS @ TLS-SERVER-DISPOSITION-NONE = IF
            _KDOSTLSL-PHASE-DISPOSITION-POLL
            _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE ! XIO-STEP-PENDING
        ELSE
            TLS-E-TRANSPORT _KDOSTLSL-TERMINAL-FAIL
        THEN EXIT
    THEN
    DUP IF _KDOSTLSL-TERMINAL-FAIL EXIT THEN DROP
    _KDOSTLSLX-PROGRESS @ TLS-SERVER-DISPOSITION-COMPLETE <> IF
        TLS-E-TRANSPORT _KDOSTLSL-TERMINAL-FAIL EXIT
    THEN
    _KDOSTLSL-PHASE-TERMINAL-CLOSE
    _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE !
    XIO-STEP-PENDING ;

: _KDOSTLSL-TERMINAL-CLOSE-STEP  ( -- step-status )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @
    TLS-SERVER-CLOSE-EXACT-TRY
    _KDOSTLSLX-IOR ! _KDOSTLSLX-RETIRED !
    _KDOSTLSLX-RETIRED @ IF
        0 _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX !
        0 _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN !
        _KDOSTLSLX-IOR @ _KDOSTLSL-TERMINAL-FAIL EXIT
    THEN
    _KDOSTLSLX-IOR @ DUP TLS-E-BUSY = IF DROP XIO-STEP-PENDING EXIT THEN
    TLS-E-WOULD-BLOCK = IF
        _KDOSTLSL-PHASE-TERMINAL-CLOSE-POLL
        _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE ! XIO-STEP-PENDING EXIT
    THEN
    _KDOSTLSLX-IOR @ DUP 0= IF DROP TLS-E-TRANSPORT THEN
    _KDOSTLSL-TERMINAL-FAIL ;

: _KDOSTLSL-STAGING-IN-PORT?  ( -- flag )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.BORROWED-PORT @ DUP 0= IF
        DROP 0 EXIT
    THEN
    DUP KDOSTLSP.STATE @ KDOSTLSP-STATE-PUBLISHED =
    SWAP KDOSTLSP.SOCKET-SD @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.STAGING-SOCKET @ = AND ;

: _KDOSTLSL-NORMALIZE-STAGING  ( -- )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.STAGING-SOCKET @ IF
        _KDOSTLSL-STAGING-IN-PORT? IF
            0 _KDOSTLSLX-OWNER @ _KDOSTLSL.STAGING-SOCKET !
        THEN
    THEN ;

: _KDOSTLSL-PUBLISH-STEP  ( -- step-status )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @
    TLS-SERVER-SOCKET-PUBLISH
    _KDOSTLSLX-IOR ! _KDOSTLSLX-SD !
    _KDOSTLSLX-SD @ IF
        \ The lower publication transaction has transferred authority as
        \ soon as it returns a descriptor.  Record that descriptor before
        \ staging it into the shared port so a contained throw or contract
        \ failure still has an exact cleanup path.
        _KDOSTLSLX-SD @
        _KDOSTLSLX-OWNER @ _KDOSTLSL.STAGING-SOCKET !
        0 _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX !
        0 _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN !
        _KDOSTLSLX-OWNER @ _KDOSTLSL.BORROWED-PORT @
        _KDOSTLSLX-PORT !
        _KDOSTLSLX-SD @ _KDOSTLSLX-PORT @ KDOSTLSP-PUBLISH
        DUP KDOSTLSP-S-OK <> IF
            _KDOSTLSL-NORMALIZE-STAGING
            DROP KDOSTLSL-E-STATE _KDOSTLSL-FAIL EXIT
        THEN DROP
        0 _KDOSTLSLX-OWNER @ _KDOSTLSL.STAGING-SOCKET !
        _KDOSTLSL-PHASE-PUBLISHED
        _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE !
        \ A nonzero descriptor is publication authority even if a malformed
        \ lower tuple also carries an error.  Stage it before failing so XIO
        \ cleanup retires the shared socket rather than stale raw authority.
        _KDOSTLSLX-IOR @ IF TLS-E-TRANSPORT _KDOSTLSL-FAIL EXIT THEN
        _KDOSTLSLX-PORT @ _KDOSTLSLX-OP @ XIOO.RESULT !
        0 _KDOSTLSLX-OP @ XIOO.ERROR !
        XIO-STEP-SUCCEEDED EXIT
    THEN
    _KDOSTLSLX-IOR @ DUP TLS-E-BUSY = IF DROP XIO-STEP-PENDING EXIT THEN
    DUP IF
        DUP 0< IF _KDOSTLSL-FAIL
        ELSE DROP TLS-E-TRANSPORT _KDOSTLSL-FAIL THEN EXIT
    THEN DROP
    TLS-E-TRANSPORT _KDOSTLSL-FAIL ;

: _KDOSTLSL-POLL-TRANSPORT-STEP  ( resume-phase -- step-status )
    TCP-POLL _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE !
    XIO-STEP-PENDING ;

: _KDOSTLSL-LOWER-DISPATCH  ( -- step-status )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE @ CASE
        _KDOSTLSL-PHASE-LISTENER-POLL OF
            _KDOSTLSL-LISTENER-POLL-STEP ENDOF
        _KDOSTLSL-PHASE-CLAIM OF _KDOSTLSL-CLAIM-STEP ENDOF
        _KDOSTLSL-PHASE-CLIENT-HELLO OF
            _KDOSTLSL-CLIENT-HELLO-STEP ENDOF
        _KDOSTLSL-PHASE-CLIENT-HELLO-POLL OF
            _KDOSTLSL-PHASE-CLIENT-HELLO
            _KDOSTLSL-POLL-TRANSPORT-STEP
        ENDOF
        _KDOSTLSL-PHASE-PREPARE-HELLO OF
            _KDOSTLSL-PREPARE-HELLO-STEP ENDOF
        _KDOSTLSL-PHASE-PREPARE-FLIGHT OF
            _KDOSTLSL-PREPARE-FLIGHT-STEP ENDOF
        _KDOSTLSL-PHASE-FLIGHT OF _KDOSTLSL-FLIGHT-STEP ENDOF
        _KDOSTLSL-PHASE-FLIGHT-POLL OF
            _KDOSTLSL-PHASE-FLIGHT _KDOSTLSL-POLL-TRANSPORT-STEP
        ENDOF
        _KDOSTLSL-PHASE-CLIENT-FLIGHT-BEGIN OF
            _KDOSTLSL-CLIENT-FLIGHT-BEGIN-STEP ENDOF
        _KDOSTLSL-PHASE-CLIENT-FLIGHT OF
            _KDOSTLSL-CLIENT-FLIGHT-STEP ENDOF
        _KDOSTLSL-PHASE-CLIENT-FLIGHT-POLL OF
            _KDOSTLSL-PHASE-CLIENT-FLIGHT
            _KDOSTLSL-POLL-TRANSPORT-STEP
        ENDOF
        _KDOSTLSL-PHASE-DISPOSITION OF
            _KDOSTLSL-DISPOSITION-STEP ENDOF
        _KDOSTLSL-PHASE-DISPOSITION-POLL OF
            _KDOSTLSL-PHASE-DISPOSITION
            _KDOSTLSL-POLL-TRANSPORT-STEP
        ENDOF
        _KDOSTLSL-PHASE-TERMINAL-CLOSE OF
            _KDOSTLSL-TERMINAL-CLOSE-STEP ENDOF
        _KDOSTLSL-PHASE-TERMINAL-CLOSE-POLL OF
            _KDOSTLSL-PHASE-TERMINAL-CLOSE
            _KDOSTLSL-POLL-TRANSPORT-STEP
        ENDOF
        _KDOSTLSL-PHASE-PUBLISH OF _KDOSTLSL-PUBLISH-STEP ENDOF
        KDOSTLSL-E-STATE _KDOSTLSL-FAIL SWAP
    ENDCASE ;

: _KDOSTLSL-LOWER-INNER  ( -- )
    _KDOSTLSL-LOWER-DISPATCH _KDOSTLSLX-STEP ! ;

: _KDOSTLSL-PRECLAIM?  ( -- flag )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @ OR 0=
    _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE @
    _KDOSTLSL-PHASE-CLAIM <= AND ;

: _KDOSTLSL-GUARDED-STEP  ( -- step-status )
    XIO-STEP-FAILED _KDOSTLSLX-STEP !
    -1 _KDOSTLSLX-IN-CALL !
    _KDOSTLSLX-OWNER @ ['] _KDOSTLSL-LOWER-INNER KDOSNET-WITH
    0 _KDOSTLSLX-IN-CALL !
    _KDOSTLSLX-RELEASE-STATUS !
    _KDOSTLSLX-THROW !
    _KDOSTLSLX-CLAIM-STATUS !
    _KDOSTLSLX-CLAIM-STATUS @ DUP IF
        DUP KDOSNET-S-BUSY = IF
            DROP _KDOSTLSL-PRECLAIM? IF
                KDOSTLSL-E-CONTENTION _KDOSTLSL-FAIL
            ELSE
                XIO-STEP-PENDING
            THEN EXIT
        THEN
        KDOSNET-S-PLATFORM = IF
            KDOSTLSL-E-PLATFORM _KDOSTLSL-FAIL
        ELSE
            KDOSTLSL-E-STATE _KDOSTLSL-FAIL
        THEN EXIT
    THEN DROP
    _KDOSTLSLX-THROW @ ?DUP IF
        _KDOSTLSL-THROW>IOR _KDOSTLSL-FAIL EXIT
    THEN
    _KDOSTLSLX-RELEASE-STATUS @ ?DUP IF
        _KDOSTLSL-SECONDARY!
        KDOSTLSL-E-CLEANUP _KDOSTLSL-FAIL EXIT
    THEN
    _KDOSTLSLX-STEP @ ;

: _KDOSTLSL-XIO-START  ( operation owner -- step-status )
    _KDOSTLSL-CALLBACK-BEGIN 0= IF
        KDOSTLSL-E-STATE _KDOSTLSL-FAIL EXIT
    THEN
    _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE @
    _KDOSTLSL-PHASE-LISTENER-POLL <> IF
        KDOSTLSL-E-STATE _KDOSTLSL-FAIL EXIT
    THEN
    _KDOSTLSL-GUARDED-STEP ;

: _KDOSTLSL-XIO-POLL  ( operation owner -- step-status )
    _KDOSTLSL-CALLBACK-BEGIN 0= IF
        KDOSTLSL-E-STATE _KDOSTLSL-FAIL EXIT
    THEN
    _KDOSTLSL-GUARDED-STEP ;

: _KDOSTLSL-XIO-CANCEL  ( operation owner -- )
    _KDOSTLSL-CALLBACK-BEGIN 0= IF KDOSTLSL-E-STATE THROW THEN
    _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE @
    _KDOSTLSL-PHASE-ADOPTED <> IF
        _KDOSTLSL-PHASE-CLEANUP
        _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE !
    THEN ;

