: _KDOSTLSL-ABORT-INNER  ( -- )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @ OR IF
        _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
        _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @ TLS-ABORT-EXACT
        _KDOSTLSLX-IOR ! _KDOSTLSLX-RETIRED !
        _KDOSTLSLX-RETIRED @ IF
            0 _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX !
            0 _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN !
        THEN
        EXIT
    THEN
    _KDOSTLSLX-OWNER @ _KDOSTLSL.STAGING-SOCKET @ ?DUP IF
        SOCK-TLS-ABORT-EXACT-TRY
        _KDOSTLSLX-IOR ! _KDOSTLSLX-ALERT !
        _KDOSTLSLX-ALERT @ TLS-ABORT-S-BUSY <>
        _KDOSTLSLX-IOR @ 0= AND _KDOSTLSLX-RETIRED !
        _KDOSTLSLX-RETIRED @ IF
            0 _KDOSTLSLX-OWNER @ _KDOSTLSL.STAGING-SOCKET !
        THEN
    THEN ;

: _KDOSTLSL-ABORT-CLEANUP-STEP  ( -- step-status )
    0 _KDOSTLSLX-IOR ! 0 _KDOSTLSLX-RETIRED !
    -1 _KDOSTLSLX-IN-CALL !
    _KDOSTLSLX-OWNER @ ['] _KDOSTLSL-ABORT-INNER KDOSNET-WITH
    0 _KDOSTLSLX-IN-CALL !
    _KDOSTLSLX-RELEASE-STATUS !
    _KDOSTLSLX-THROW !
    _KDOSTLSLX-CLAIM-STATUS !
    _KDOSTLSLX-CLAIM-STATUS @ DUP IF
        DUP KDOSNET-S-BUSY = IF DROP XIO-STEP-PENDING EXIT THEN
        DUP KDOSNET-S-PLATFORM = IF
            DROP KDOSTLSL-E-PLATFORM
        ELSE
            DROP KDOSTLSL-E-CLEANUP
        THEN _KDOSTLSL-SECONDARY! XIO-STEP-PENDING EXIT
    THEN DROP
    _KDOSTLSLX-THROW @ ?DUP IF
        _KDOSTLSL-THROW>IOR _KDOSTLSL-SECONDARY!
    THEN
    _KDOSTLSLX-RELEASE-STATUS @ ?DUP IF
        _KDOSTLSL-SECONDARY! XIO-STEP-PENDING EXIT
    THEN
    _KDOSTLSLX-RETIRED @ IF
        _KDOSTLSLX-IOR @ _KDOSTLSL-SECONDARY!
        \ The exact lower authority is gone, but the caller's borrowed port
        \ is still RESERVED.  A following cleanup tick returns that record
        \ to RESET before XIO invokes the ordinary wipe callback.
        XIO-STEP-PENDING EXIT
    THEN
    _KDOSTLSLX-THROW @ IF XIO-STEP-PENDING EXIT THEN
    _KDOSTLSLX-IOR @ DUP TLS-E-BUSY = IF
        DROP XIO-STEP-PENDING EXIT
    THEN
    DUP 0= IF DROP TLS-E-TRANSPORT THEN
    _KDOSTLSL-SECONDARY! XIO-STEP-PENDING ;

: _KDOSTLSL-PORT-CLEANUP-STEP  ( -- step-status )
    _KDOSTLSLX-OWNER @ _KDOSTLSL.BORROWED-PORT @ DUP IF
        KDOSTLSP-DISCARD-STEP
        DUP KDOSTLSP-S-OK = IF DROP XIO-STEP-SUCCEEDED EXIT THEN
        DUP KDOSTLSP-S-PENDING = OVER KDOSTLSP-S-BUSY = OR IF
            DROP XIO-STEP-PENDING EXIT
        THEN
        DROP KDOSTLSL-E-CLEANUP _KDOSTLSL-SECONDARY!
        XIO-STEP-PENDING
    ELSE
        DROP XIO-STEP-SUCCEEDED
    THEN ;

: _KDOSTLSL-XIO-CLEANUP-POLL  ( operation owner -- step-status )
    _KDOSTLSL-CALLBACK-BEGIN 0= IF
        KDOSTLSL-E-STATE _KDOSTLSL-SECONDARY!
        XIO-STEP-PENDING EXIT
    THEN
    _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE @
    _KDOSTLSL-PHASE-ADOPTED = IF
        KDOSTLSL-E-STATE _KDOSTLSL-SECONDARY!
        XIO-STEP-PENDING EXIT
    THEN
    _KDOSTLSLX-OWNER @ KDOSNET-OWNER? IF
        _KDOSTLSLX-OWNER @ KDOSNET-RELEASE DUP IF
            _KDOSTLSL-SECONDARY!
        ELSE
            DROP
        THEN
        XIO-STEP-PENDING EXIT
    THEN
    _KDOSTLSL-NORMALIZE-STAGING
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @ OR
    _KDOSTLSLX-OWNER @ _KDOSTLSL.STAGING-SOCKET @ OR IF
        _KDOSTLSL-ABORT-CLEANUP-STEP EXIT
    THEN
    _KDOSTLSL-PORT-CLEANUP-STEP ;

: _KDOSTLSL-XIO-WIPE  ( operation owner -- )
    \ Adoption commits the lower socket to the caller before XIO-TAKE invokes
    \ this callback.  Keep that post-commit branch nonthrowing: TAKE is then
    \ guaranteed not to hide an already-open NIO port behind a wipe failure.
    DUP _KDOSTLSL-VALID? IF
        DUP _KDOSTLSL.PHASE @ _KDOSTLSL-PHASE-ADOPTED = IF
            NIP
            0 OVER _KDOSTLSL.BORROWED-PORT !
            _KDOSTLSL-PHASE-IDLE SWAP _KDOSTLSL.PHASE !
            EXIT
        THEN
    THEN
    _KDOSTLSL-CALLBACK-BEGIN 0= IF KDOSTLSL-E-STATE THROW THEN
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX @
    _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN @ OR IF
        KDOSTLSL-E-CLEANUP THROW
    THEN
    _KDOSTLSLX-OWNER @ _KDOSTLSL.STAGING-SOCKET @ IF
        KDOSTLSL-E-CLEANUP THROW
    THEN
    _KDOSTLSLX-OWNER @ _KDOSTLSL.BORROWED-PORT @ ?DUP IF
        KDOSTLSP.STATE @ KDOSTLSP-STATE-RESET <> IF
            KDOSTLSL-E-CLEANUP THROW
        THEN
    THEN
    0 _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX !
    0 _KDOSTLSLX-OWNER @ _KDOSTLSL.CTX-GEN !
    0 _KDOSTLSLX-OWNER @ _KDOSTLSL.STAGING-SOCKET !
    0 _KDOSTLSLX-OWNER @ _KDOSTLSL.BORROWED-PORT !
    _KDOSTLSL-PHASE-IDLE _KDOSTLSLX-OWNER @ _KDOSTLSL.PHASE ! ;

