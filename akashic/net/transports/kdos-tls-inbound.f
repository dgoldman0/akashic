        DROP _KDOSTLSAX-PROGRESS @ TLS-SERVER-INGRESS-NONE =
        _KDOSTLSAX-ALERT @ 0= AND IF XIO-STEP-PENDING
        ELSE TLS-E-TRANSPORT _KDOSTLSA-FAIL THEN EXIT
    THEN
    DUP TLS-E-WOULD-BLOCK = IF
        DROP _KDOSTLSAX-PROGRESS @ TLS-SERVER-INGRESS-NONE =
        _KDOSTLSAX-ALERT @ 0= AND IF
            KDOSTLSA-PHASE-CLIENT-FLIGHT-POLL
            _KDOSTLSAX-A @ KDOSTLSA.PHASE ! XIO-STEP-PENDING
        ELSE
            TLS-E-TRANSPORT _KDOSTLSA-FAIL
        THEN EXIT
    THEN DROP
    _KDOSTLSAX-IOR @ IF
        _KDOSTLSA-INGRESS-TERMINAL? IF
            _KDOSTLSAX-IOR @ _KDOSTLSAX-A @ KDOSTLSA.RESULT @
            _KDOSTLSP-ERROR!
            _KDOSTLSAX-IOR @ _KDOSTLSAX-OP @ XIOO.ERROR !
            _KDOSTLSAX-ALERT @ _KDOSTLSAX-OP @ XIOO.RESULT !
            KDOSTLSA-PHASE-DISPOSITION _KDOSTLSAX-A @ KDOSTLSA.PHASE !
            XIO-STEP-PENDING EXIT
        THEN
        _KDOSTLSAX-PROGRESS @ TLS-SERVER-INGRESS-NONE =
        _KDOSTLSAX-ALERT @ 0= AND
        _KDOSTLSAX-IOR @ 0< AND IF
            _KDOSTLSAX-IOR @ _KDOSTLSA-FAIL
        ELSE
            TLS-E-TRANSPORT _KDOSTLSA-FAIL
        THEN EXIT
    THEN
    _KDOSTLSAX-ALERT @ IF TLS-E-TRANSPORT _KDOSTLSA-FAIL EXIT THEN
    _KDOSTLSAX-PROGRESS @ DUP TLS-SERVER-INGRESS-RECORD = IF
        DROP XIO-STEP-PENDING EXIT
    THEN
    TLS-SERVER-INGRESS-FINISHED = IF
        KDOSTLSA-PHASE-PUBLISH _KDOSTLSAX-A @ KDOSTLSA.PHASE !
        XIO-STEP-PENDING EXIT
    THEN
    TLS-E-TRANSPORT _KDOSTLSA-FAIL ;

