: _MTR-KDOS-MATCH?  ( -- flag )
    TLS-TRUST-VERSION @ TLS-TRUST-FORMAT =
    TLS-TRUST-COUNT @ _MTRUST-ANCHOR-N @ = AND
    TLS-TRUST-GENERATION @ _MTRUST-GENERATION @ = AND ;

: _MTR-FREEZE-BUILD  ( -- status )
    _MTRUST-BUFFER @ _MTRUST-FIRST-CAPACITY _MTRUST-BUILDER _MTB-INIT
    _MTRUST-CONTRIBUTOR-N @ 0 ?DO
        I _MTRUST-CONTRIBUTOR@ _MTR-CALL-EMITTER ?DUP IF UNLOOP EXIT THEN
        _MTRUST-ACTIVE-BUILDER? 0= IF
            MTRUST-D-EMITTER-BUILDER _MTRUST-LAST-DETAIL !
            MTRUST-S-CONTRIBUTOR UNLOOP EXIT
        THEN
    LOOP
    _MTR-BUILD-HEADER
    ['] _MTR-HASH-INNER CATCH ?DUP IF
        _MTRUST-LAST-DETAIL ! MTRUST-S-PLATFORM EXIT
    THEN
    _MTRUST-DIGEST _MTRUST-BUFFER @ 8 + 8 CMOVE
    _MTRUST-DIGEST _MTR-BE64@ _MTRUST-GENERATION !
    MTRUST-S-PLATFORM _MTR-LOAD-STATUS !
    ['] _MTR-LOAD-INNER CATCH ?DUP IF
        _MTRUST-LAST-DETAIL ! MTRUST-S-PLATFORM EXIT
    THEN
    _MTR-LOAD-STATUS @ ?DUP IF
        _MTRUST-LAST-DETAIL ! MTRUST-S-PLATFORM EXIT
    THEN
    _MTRUST-BUILDER _MTB.COUNT @ _MTRUST-ANCHOR-N !
    _MTR-KDOS-MATCH? 0= IF MTRUST-S-DIVERGED EXIT THEN
    MTRUST-STATE-FROZEN _MTRUST-STATE !
    MTRUST-S-OK ;

VARIABLE _MTR-FREEZE-RESULT

: _MTR-FREEZE-BUILD-INNER  ( -- )
    _MTR-FREEZE-BUILD _MTR-FREEZE-RESULT ! ;

\ Freeze is one-way for the machine boot.  A repeated call verifies the
\ already-loaded KDOS snapshot and never performs a replacement load.
: MTRUST-FREEZE  ( -- status )
    COREID IF MTRUST-S-INVALID EXIT THEN
    _MTRUST-STATE @ MTRUST-STATE-FROZEN = IF
        _MTR-KDOS-MATCH? IF MTRUST-S-OK ELSE MTRUST-S-DIVERGED THEN
        DUP _MTRUST-LAST-STATUS ! EXIT
    THEN
    _MTRUST-STATE @ MTRUST-STATE-OPEN <> IF
        MTRUST-S-STATE DUP _MTRUST-LAST-STATUS ! EXIT
    THEN
    MTRUST-STATE-BUILDING _MTRUST-STATE !
    0 _MTRUST-GENERATION ! 0 _MTRUST-ANCHOR-N ! 0 _MTRUST-LAST-DETAIL !
    0 _MTRUST-ROOTS-IN !
    _MTRUST-FIRST-CAPACITY ALLOCATE DUP IF
        2DROP
        TLS-TRUST-RESET
        MTRUST-STATE-FAILED _MTRUST-STATE !
        MTRUST-S-CAPACITY DUP _MTRUST-LAST-STATUS ! EXIT
    THEN
    DROP _MTRUST-BUFFER !
    MTRUST-S-PLATFORM _MTR-FREEZE-RESULT !
    ['] _MTR-FREEZE-BUILD-INNER CATCH ?DUP IF
        _MTRUST-LAST-DETAIL ! MTRUST-S-PLATFORM _MTR-FREEZE-RESULT !
    THEN
    _MTRUST-BUILDER _MTB-FINI
    _MTRUST-BUFFER @ FREE 0 _MTRUST-BUFFER !
    _MTR-FREEZE-RESULT @ DUP MTRUST-S-OK <> IF
        TLS-TRUST-RESET
        0 _MTRUST-GENERATION ! 0 _MTRUST-ANCHOR-N !
        MTRUST-STATE-FAILED _MTRUST-STATE !
    THEN
    DUP _MTRUST-LAST-STATUS ! ;
