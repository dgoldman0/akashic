: _MTR-CALL-EMITTER-INNER  ( -- )
    _MTRUST-BUILDER
    _MTRCE-CONTRIBUTOR @ _MTC.CONTEXT @
    _MTRCE-CONTRIBUTOR @ _MTC.EMIT-XT @ EXECUTE
    _MTRCE-STATUS ! ;

: _MTR-CALL-EMITTER  ( contributor -- status )
    _MTRCE-CONTRIBUTOR !
    DEPTH _MTRCE-DEPTH !
    MTRUST-S-CONTRIBUTOR _MTRCE-STATUS !
    ['] _MTR-CALL-EMITTER-INNER CATCH _MTRCE-IOR !
    DEPTH _MTRCE-DEPTH @ <> IF
        BEGIN DEPTH _MTRCE-DEPTH @ > WHILE DROP REPEAT
        MTRUST-D-EMITTER-STACK _MTRUST-LAST-DETAIL !
        MTRUST-S-CONTRIBUTOR EXIT
    THEN
    _MTRCE-IOR @ ?DUP IF
        _MTRUST-LAST-DETAIL ! MTRUST-S-CONTRIBUTOR EXIT
    THEN
    _MTRCE-STATUS @ DUP IF
        _MTRUST-LAST-DETAIL ! MTRUST-S-CONTRIBUTOR
    THEN ;

: _MTR-BUILD-HEADER  ( -- )
    _MTRUST-BUFFER @ >R
    77 R@ C! 80 R@ 1+ C! 84 R@ 2 + C! 65 R@ 3 + C!
    TLS-TRUST-FORMAT DUP 8 RSHIFT 255 AND R@ 4 + C! 255 AND R@ 5 + C!
    _MTRUST-BUILDER _MTB.COUNT @ DUP 8 RSHIFT 255 AND R@ 6 + C!
    255 AND R@ 7 + C!
    R@ 8 + 8 0 FILL
    R> DROP ;

: _MTR-HASH-INNER  ( -- )
    _MTRUST-BUFFER @ _MTRUST-BUILDER _MTB.POSITION @
    _MTRUST-DIGEST SHA3-256-HASH ;

VARIABLE _MTR-LOAD-STATUS
: _MTR-LOAD-INNER  ( -- )
    _MTRUST-BUFFER @ _MTRUST-BUILDER _MTB.POSITION @
