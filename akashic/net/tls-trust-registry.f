: _MTRUST-BUILDER-OK?  ( builder -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    _MTRUST-BUILDER <> IF 0 EXIT THEN
    _MTRUST-ACTIVE-BUILDER? ;

