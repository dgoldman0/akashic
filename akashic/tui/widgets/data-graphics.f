: _DGRAPH-AFTER-PREV?  ( record -- flag )
    DUP UDG-OBJECT-FLAGS@ UDG-OBJECT-VISIBLE AND 0= IF DROP 0 EXIT THEN
    _DGRAPH-O-PREV-HAVE @ 0= IF DROP -1 EXIT THEN
    DUP UDG-OBJECT-Z@ _DGRAPH-O-PREV-Z @ > IF DROP -1 EXIT THEN
    DUP UDG-OBJECT-Z@ _DGRAPH-O-PREV-Z @ < IF DROP 0 EXIT THEN
    UDG-RECORD-KEY@ _DGRAPH-O-PREV-KEY @ U> ;

: _DGRAPH-BEFORE-BEST?  ( record -- flag )
    _DGRAPH-O-BEST-HAVE @ 0= IF DROP -1 EXIT THEN
    DUP UDG-OBJECT-Z@ _DGRAPH-O-BEST @ UDG-OBJECT-Z@ < IF DROP -1 EXIT THEN
    DUP UDG-OBJECT-Z@ _DGRAPH-O-BEST @ UDG-OBJECT-Z@ > IF DROP 0 EXIT THEN
    UDG-RECORD-KEY@ _DGRAPH-O-BEST @ UDG-RECORD-KEY@ U< ;

: _DGRAPH-FIND-NEXT  ( -- record|0 )
    _DGRAPH-D-GRAPH @ UDG-FIRST-RECORD _DGRAPH-O-CURSOR !
    0 _DGRAPH-O-I ! 0 _DGRAPH-O-BEST ! 0 _DGRAPH-O-BEST-HAVE !
    BEGIN _DGRAPH-O-I @ _DGRAPH-D-GRAPH @ UDG-RECORD-COUNT@ U< WHILE
        _DGRAPH-O-CURSOR @ DUP _DGRAPH-O-SCAN !
        _DGRAPH-AFTER-PREV? IF
            _DGRAPH-O-SCAN @ _DGRAPH-BEFORE-BEST? IF
                _DGRAPH-O-SCAN @ _DGRAPH-O-BEST !
                -1 _DGRAPH-O-BEST-HAVE !
            THEN
        THEN
        _DGRAPH-O-CURSOR @ UDG-RECORD-NEXT _DGRAPH-O-CURSOR !
        1 _DGRAPH-O-I +!
    REPEAT
    _DGRAPH-O-BEST @ ;

: _DGRAPH-DRAW-OBJECT  ( record -- )
    DUP _DGRAPH-D-WIDGET @ _DGRAPH-OBJECT-INTERSECTS? 0= IF
        DROP EXIT
    THEN
    DUP UDG-RECORD-KIND@ CASE
        UDG-K-READOUT OF _DGRAPH-DRAW-READOUT ENDOF
        UDG-K-METER   OF _DGRAPH-DRAW-METER ENDOF
        UDG-K-STATUS  OF _DGRAPH-DRAW-STATUS ENDOF
        DROP
    ENDCASE ;

: _DGRAPH-DRAW-IMPL  ( widget -- )
    DUP _DGRAPH-D-WIDGET !
    DUP _DGRAPH-BOUND? 0= IF DROP EXIT THEN
    _DGRAPH-O-MODEL-A + @ DUP _DGRAPH-D-GRAPH !
    UDG-ROOT-STATE@ UDG-STATE-VISIBLE AND 0= IF EXIT THEN
    _DGRAPH-D-WIDGET @ WDG-DISABLED?
    _DGRAPH-D-GRAPH @ UDG-ROOT-STATE@ UDG-STATE-ENABLED AND 0= OR
        _DGRAPH-D-DISABLED !
    0 _DGRAPH-O-PREV-HAVE !
    BEGIN _DGRAPH-FIND-NEXT DUP WHILE
        DUP _DGRAPH-DRAW-OBJECT
        DUP UDG-OBJECT-Z@ _DGRAPH-O-PREV-Z !
        UDG-RECORD-KEY@ _DGRAPH-O-PREV-KEY !
        -1 _DGRAPH-O-PREV-HAVE !
    REPEAT
    DROP DRW-STYLE-RESTORE ;

: _DGRAPH-HANDLE-IMPL  ( event widget -- consumed? )
    2DROP 0 ;

