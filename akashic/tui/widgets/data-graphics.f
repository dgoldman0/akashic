: _DGRAPH-MAGNITUDE  ( n -- u )
    DUP 0< IF INVERT 1+ THEN ;

: _DGRAPH-U/10  ( u -- remainder quotient )
    _DGRAPH-N-SOURCE ! 0 _DGRAPH-N-REM ! 0 _DGRAPH-N-QUOT !
    64 0 DO
        _DGRAPH-N-QUOT @ 1 LSHIFT _DGRAPH-N-QUOT !
        _DGRAPH-N-REM @ 1 LSHIFT
        _DGRAPH-N-SOURCE @ 63 I - RSHIFT 1 AND OR
        DUP 10 U< IF
            _DGRAPH-N-REM !
        ELSE
            10 - _DGRAPH-N-REM !
            _DGRAPH-N-QUOT @ 1 OR _DGRAPH-N-QUOT !
        THEN
    LOOP
    _DGRAPH-N-REM @ _DGRAPH-N-QUOT @ ;

: _DGRAPH-SIGNED-LENGTH  ( n -- bytes )
    DUP _DGRAPH-N-VALUE ! _DGRAPH-MAGNITUDE _DGRAPH-N-MAG !
    1 _DGRAPH-N-DIGITS !
    BEGIN _DGRAPH-N-MAG @ 10 U< 0= WHILE
        _DGRAPH-N-MAG @ _DGRAPH-U/10 NIP _DGRAPH-N-MAG !
        1 _DGRAPH-N-DIGITS +!
    REPEAT
    _DGRAPH-N-DIGITS @
    _DGRAPH-N-VALUE @ 0< IF 1+ THEN ;

: _DGRAPH-SIGNED-FORMAT  ( value destination -- bytes )
    _DGRAPH-N-DST ! _DGRAPH-N-VALUE !
    _DGRAPH-N-VALUE @ _DGRAPH-SIGNED-LENGTH DUP _DGRAPH-N-CURSOR !
    _DGRAPH-N-DST @ + _DGRAPH-N-CURSOR !
    _DGRAPH-N-VALUE @ _DGRAPH-MAGNITUDE _DGRAPH-N-MAG !
    _DGRAPH-N-DIGITS @ 0 ?DO
        _DGRAPH-N-MAG @ _DGRAPH-U/10 _DGRAPH-N-MAG !
        [CHAR] 0 +
        -1 _DGRAPH-N-CURSOR +!
        _DGRAPH-N-CURSOR @ C!
    LOOP
    _DGRAPH-N-VALUE @ 0< IF
        [CHAR] - _DGRAPH-N-DST @ C!
    THEN
    _DGRAPH-N-DIGITS @
    _DGRAPH-N-VALUE @ 0< IF 1+ THEN ;

