: DGRAPH-DATA-GRAPHICS-STORAGE-DISJOINT?
    ( address bytes widget -- flag )
    >R
    2DUP DGRAPH-STORAGE-DISJOINT? 0= IF 2DROP R> DROP 0 EXIT THEN
    _DGRAPH-SD-U ! _DGRAPH-SD-A ! R> _DGRAPH-SD-W !
    _DGRAPH-SD-W @ _DGRAPH-GENUINE? 0= IF 0 EXIT THEN
    _DGRAPH-SD-A @ _DGRAPH-SD-U @
        _DGRAPH-SD-W @ _DGRAPH-DESC-SIZE MSPAN-OVERLAP? IF 0 EXIT THEN
    _DGRAPH-SD-W @ WDG-REGION ?DUP IF
        _DGRAPH-SD-A @ _DGRAPH-SD-U @ ROT RGN-SIZE
            MSPAN-OVERLAP? IF 0 EXIT THEN
    THEN
    _DGRAPH-SD-W @ _DGRAPH-O-MODEL-A + @ ?DUP IF
        _DGRAPH-SD-A @ _DGRAPH-SD-U @ ROT
        _DGRAPH-SD-W @ _DGRAPH-O-MODEL-U + @
            MSPAN-OVERLAP? IF 0 EXIT THEN
    THEN
    _DGRAPH-SD-W @ _DGRAPH-O-SCRATCH-A + @ ?DUP IF
        _DGRAPH-SD-A @ _DGRAPH-SD-U @ ROT
        _DGRAPH-SD-W @ _DGRAPH-O-SCRATCH-U + @
            MSPAN-OVERLAP? IF 0 EXIT THEN
    THEN
    -1 ;

: _DGRAPH-POS-U32?  ( value -- flag )
    DUP 0> SWAP 0x100000000 U< AND ;

: _DGRAPH-REGION-MATCHES?  ( widget -- flag )
    DUP WDG-REGION RGN-H DUP _DGRAPH-POS-U32? 0= IF
        2DROP 0 EXIT
    THEN
    OVER _DGRAPH-O-MODEL-A + @ UDG-ROOT-HEIGHT@ <> IF
        DROP 0 EXIT
    THEN
    DUP WDG-REGION RGN-W DUP _DGRAPH-POS-U32? 0= IF
        2DROP 0 EXIT
    THEN
    SWAP _DGRAPH-O-MODEL-A + @ UDG-ROOT-WIDTH@ = ;

: _DGRAPH-BOUND?  ( widget -- flag )
    DUP _DGRAPH-GENUINE? 0= IF DROP 0 EXIT THEN
    DUP _DGRAPH-O-MODEL-A + @ DUP 0= IF 2DROP 0 EXIT THEN
    OVER _DGRAPH-O-MODEL-U + @ _DGRAPH-SPAN? 0= IF DROP 0 EXIT THEN
    _DGRAPH-REGION-MATCHES? ;

