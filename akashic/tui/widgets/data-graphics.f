\ =====================================================================
\  data-graphics.f -- Canonical renderer-neutral instrument widget
\ =====================================================================
\
\  DATA_GRAPHICS is the ordinary widget consumer of one immutable UDG
\  INSTRUMENT graph.  Applets own and rebuild that graph; this widget owns
\  only the representation scratch needed by its selected CELL renderer.
\  Optional rich capture copies the same graph reached through WDG-DRAW.
\
\  Descriptor (80 bytes):
\    +0..+32  common widget header
\    +40      borrowed UDG graph, or 0
\    +48      exact graph bytes
\    +56      renderer-owned formatting scratch, or 0
\    +64      exact scratch capacity
\    +72      nonzero allocation-lifetime instance token
\
\  Prefix: DGRAPH- (public), _DGRAPH- (private)
\ =====================================================================

