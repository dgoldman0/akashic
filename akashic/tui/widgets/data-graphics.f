: _DGRAPH-METER-SCALE  ( value minimum maximum span -- filled )
    _DGRAPH-Q-SPAN ! _DGRAPH-Q-MAXIMUM !
    _DGRAPH-Q-MINIMUM ! _DGRAPH-Q-VALUE !
    _DGRAPH-Q-VALUE @ _DGRAPH-Q-MINIMUM @ <= IF 0 EXIT THEN
    _DGRAPH-Q-VALUE @ _DGRAPH-Q-MAXIMUM @ >= IF
        _DGRAPH-Q-SPAN @ EXIT
    THEN
    _DGRAPH-Q-MAXIMUM @ _DGRAPH-Q-MINIMUM @ - _DGRAPH-Q-D !
    _DGRAPH-Q-VALUE @ _DGRAPH-Q-MINIMUM @ - _DGRAPH-Q-N !
    _DGRAPH-Q-N @ _DGRAPH-Q-SPAN @ UM*
    _DGRAPH-Q-REM ! _DGRAPH-Q-SOURCE !
    0 _DGRAPH-Q-QUOT !
    64 0 DO
        _DGRAPH-Q-QUOT @ 1 LSHIFT _DGRAPH-Q-QUOT !
        _DGRAPH-Q-REM @ 63 RSHIFT _DGRAPH-Q-CARRY !
        _DGRAPH-Q-REM @ 1 LSHIFT
        _DGRAPH-Q-SOURCE @ 63 I - RSHIFT 1 AND OR
        _DGRAPH-Q-REM !
        _DGRAPH-Q-CARRY @
        _DGRAPH-Q-REM @ _DGRAPH-Q-D @ U< 0= OR IF
            _DGRAPH-Q-REM @ _DGRAPH-Q-D @ - _DGRAPH-Q-REM !
            _DGRAPH-Q-QUOT @ 1 OR _DGRAPH-Q-QUOT !
        THEN
    LOOP
    _DGRAPH-Q-QUOT @ ;

