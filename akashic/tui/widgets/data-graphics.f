: _DGRAPH-OBJECT-INTERSECTS?  ( record widget -- flag )
    >R
    DUP UDG-OBJECT-FLAGS@ UDG-OBJECT-VISIBLE AND 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP UDG-OBJECT-ROW@
        R@ WDG-REGION RGN-H < 0= IF DROP R> DROP 0 EXIT THEN
    DUP UDG-OBJECT-ROW@ OVER UDG-OBJECT-HEIGHT@ + 0> 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP UDG-OBJECT-COLUMN@
        R@ WDG-REGION RGN-W < 0= IF DROP R> DROP 0 EXIT THEN
    DUP UDG-OBJECT-COLUMN@ SWAP UDG-OBJECT-WIDTH@ + 0>
    R> DROP ;

: _DGRAPH-SCRATCH-MAX!  ( bytes -- )
    _DGRAPH-S-MAX @ MAX _DGRAPH-S-MAX ! ;

: _DGRAPH-SCAN-READOUT  ( record -- )
    DUP _DGRAPH-S-RECORD ! DGF-READOUT-MEASURE
    DUP DGF-S-OK <> IF
        DROP DROP DGRAPH-S-INVALID _DGRAPH-S-STATUS ! EXIT
    THEN
    DROP DUP _DGRAPH-S-BYTES !
    _DGRAPH-S-RECORD @ UDG-READOUT-UNIT-BYTES@ -
    _DGRAPH-S-RECORD @ UDG-READOUT-UNIT@ UTF8-LEN +
    DUP _DGRAPH-S-CELLS !
    _DGRAPH-S-RECORD @ UDG-OBJECT-WIDTH@ U> IF EXIT THEN
    _DGRAPH-S-BYTES @ _DGRAPH-SCRATCH-MAX! ;

: _DGRAPH-SCAN-METER  ( record -- )
    DUP UDG-METER-FLAGS@ UDG-METER-SHOW-VALUE AND 0= IF DROP EXIT THEN
    DUP _DGRAPH-S-RECORD ! UDG-METER-VALUE@ _DGRAPH-SIGNED-LENGTH
    DUP _DGRAPH-S-BYTES !
    _DGRAPH-S-RECORD @ UDG-OBJECT-WIDTH@ U> IF EXIT THEN
    _DGRAPH-S-BYTES @ _DGRAPH-SCRATCH-MAX! ;

: _DGRAPH-SCRATCH-SCAN  ( graph widget -- bytes status )
    _DGRAPH-S-WIDGET ! DUP _DGRAPH-S-GRAPH !
    UDG-FIRST-RECORD _DGRAPH-S-CURSOR !
    0 _DGRAPH-S-I ! 0 _DGRAPH-S-MAX ! DGRAPH-S-OK _DGRAPH-S-STATUS !
    BEGIN
        _DGRAPH-S-I @ _DGRAPH-S-GRAPH @ UDG-RECORD-COUNT@ U<
        _DGRAPH-S-STATUS @ DGRAPH-S-OK = AND
    WHILE
        _DGRAPH-S-CURSOR @ DUP _DGRAPH-S-RECORD !
        _DGRAPH-S-WIDGET @ _DGRAPH-OBJECT-INTERSECTS? IF
            _DGRAPH-S-RECORD @ UDG-RECORD-KIND@ CASE
                UDG-K-READOUT OF
                    _DGRAPH-S-RECORD @ _DGRAPH-SCAN-READOUT
                ENDOF
                UDG-K-METER OF
                    _DGRAPH-S-RECORD @ _DGRAPH-SCAN-METER
                ENDOF
            ENDCASE
        THEN
        _DGRAPH-S-CURSOR @ UDG-RECORD-NEXT _DGRAPH-S-CURSOR !
        1 _DGRAPH-S-I +!
    REPEAT
    _DGRAPH-S-MAX @ _DGRAPH-S-STATUS @ ;

