: _DGRAPH-BIND-PREFLIGHT?  ( graph bytes summary widget -- flag )
    3 PICK 3 PICK DGRAPH-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    1 PICK UDG-SUMMARY-SIZE DGRAPH-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    DUP _DGRAPH-DESC-SIZE DGRAPH-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    3 PICK 3 PICK UDG-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    1 PICK UDG-SUMMARY-SIZE UDG-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    3 PICK 3 PICK DGF-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    1 PICK UDG-SUMMARY-SIZE DGF-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    DUP _DGRAPH-DESC-SIZE DGF-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    DUP _DGRAPH-GENUINE? 0= IF 0 EXIT THEN
    DUP WDG-REGION RGN-SIZE DGF-STORAGE-DISJOINT? ;

: _DGRAPH-BIND-SPANS?  ( -- flag )
    _DGRAPH-B-GRAPH @ _DGRAPH-B-U @ _DGRAPH-SPAN? 0= IF 0 EXIT THEN
    _DGRAPH-B-GRAPH @ 7 AND IF 0 EXIT THEN
    _DGRAPH-B-SUMMARY @ DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    UDG-SUMMARY-SIZE MSPAN-NONWRAPPING? 0= IF 0 EXIT THEN
    _DGRAPH-B-GRAPH @ _DGRAPH-B-U @
        _DGRAPH-B-SUMMARY @ UDG-SUMMARY-SIZE MSPAN-OVERLAP? IF 0 EXIT THEN
    _DGRAPH-B-GRAPH @ _DGRAPH-B-U @
        _DGRAPH-B-WIDGET @ _DGRAPH-DESC-SIZE MSPAN-OVERLAP? IF 0 EXIT THEN
    _DGRAPH-B-GRAPH @ _DGRAPH-B-U @
        _DGRAPH-B-WIDGET @ WDG-REGION RGN-SIZE MSPAN-OVERLAP? IF 0 EXIT THEN
    _DGRAPH-B-WIDGET @ _DGRAPH-O-SCRATCH-A + @ ?DUP IF
        _DGRAPH-B-GRAPH @ _DGRAPH-B-U @ ROT
        _DGRAPH-B-WIDGET @ _DGRAPH-O-SCRATCH-U + @
            MSPAN-OVERLAP? IF 0 EXIT THEN
    THEN
    _DGRAPH-B-SUMMARY @ UDG-SUMMARY-SIZE
        _DGRAPH-B-WIDGET @ _DGRAPH-DESC-SIZE MSPAN-OVERLAP? IF 0 EXIT THEN
    _DGRAPH-B-SUMMARY @ UDG-SUMMARY-SIZE
        _DGRAPH-B-WIDGET @ WDG-REGION RGN-SIZE MSPAN-OVERLAP? IF 0 EXIT THEN
    _DGRAPH-B-WIDGET @ _DGRAPH-O-MODEL-A + @ ?DUP IF
        _DGRAPH-B-SUMMARY @ UDG-SUMMARY-SIZE ROT
        _DGRAPH-B-WIDGET @ _DGRAPH-O-MODEL-U + @
            MSPAN-OVERLAP? IF 0 EXIT THEN
    THEN
    _DGRAPH-B-WIDGET @ _DGRAPH-O-SCRATCH-A + @ ?DUP IF
        _DGRAPH-B-SUMMARY @ UDG-SUMMARY-SIZE ROT
        _DGRAPH-B-WIDGET @ _DGRAPH-O-SCRATCH-U + @
            MSPAN-OVERLAP? IF 0 EXIT THEN
    THEN
    -1 ;

: DGRAPH-NEW  ( region -- widget )
    DUP 0= ABORT" DGRAPH-NEW: region"
    DUP 7 AND ABORT" DGRAPH-NEW: region alignment"
    DUP RGN-SIZE MSPAN-NONWRAPPING? 0= ABORT" DGRAPH-NEW: region span"
    _DGRAPH-CLAIM-INSTANCE _DGRAPH-NEW-INSTANCE !
    _DGRAPH-DESC-SIZE ALLOCATE 0<> ABORT" DGRAPH-NEW: alloc"
    WDG-T-DATA-GRAPHICS OVER _WDG-O-TYPE + !
    SWAP OVER _WDG-O-REGION + !
    ['] _DGRAPH-DRAW OVER _WDG-O-DRAW-XT + !
    ['] _DGRAPH-HANDLE OVER _WDG-O-HANDLE-XT + !
    WDG-F-VISIBLE WDG-F-DIRTY OR OVER _WDG-O-FLAGS + !
    0 OVER _DGRAPH-O-MODEL-A + !
    0 OVER _DGRAPH-O-MODEL-U + !
    0 OVER _DGRAPH-O-SCRATCH-A + !
    0 OVER _DGRAPH-O-SCRATCH-U + !
    _DGRAPH-NEW-INSTANCE @ OVER _DGRAPH-O-INSTANCE + !
    0 _DGRAPH-NEW-INSTANCE ! ;

: DGRAPH-BIND  ( graph bytes summary widget -- status )
    _DGRAPH-BIND-PREFLIGHT? 0= IF
        2DROP 2DROP DGRAPH-S-INVALID EXIT
    THEN
    _DGRAPH-B-WIDGET ! _DGRAPH-B-SUMMARY !
    _DGRAPH-B-U ! _DGRAPH-B-GRAPH !
    _DGRAPH-BIND-SPANS? 0= IF DGRAPH-S-INVALID EXIT THEN
    _DGRAPH-B-GRAPH @ _DGRAPH-B-U @ _DGRAPH-B-SUMMARY @
        UDG-ENTRY-VALIDATE
    DUP UDG-S-OK <> IF EXIT THEN DROP
    _DGRAPH-B-GRAPH @ UDG-ROOT-ROW@ IF DGRAPH-S-INVALID EXIT THEN
    _DGRAPH-B-GRAPH @ UDG-ROOT-COLUMN@ IF DGRAPH-S-INVALID EXIT THEN
    _DGRAPH-B-GRAPH @ UDG-ROOT-HEIGHT@
        _DGRAPH-B-WIDGET @ WDG-REGION RGN-H <> IF
        DGRAPH-S-INVALID EXIT
    THEN
    _DGRAPH-B-GRAPH @ UDG-ROOT-WIDTH@
        _DGRAPH-B-WIDGET @ WDG-REGION RGN-W <> IF
        DGRAPH-S-INVALID EXIT
    THEN
    _DGRAPH-B-GRAPH @ _DGRAPH-B-WIDGET @ _DGRAPH-SCRATCH-SCAN
    DUP DGRAPH-S-OK <> IF NIP EXIT THEN DROP _DGRAPH-B-NEED !
    0 _DGRAPH-B-NEW-SCRATCH !
    _DGRAPH-B-NEED @ ?DUP IF
        ALLOCATE DUP IF
            2DROP DGRAPH-S-ALLOC EXIT
        THEN
        DROP _DGRAPH-B-NEW-SCRATCH !
    THEN
    _DGRAPH-B-WIDGET @ _DGRAPH-O-SCRATCH-A + @
        _DGRAPH-B-OLD-SCRATCH !
    _DGRAPH-B-GRAPH @ _DGRAPH-B-WIDGET @ _DGRAPH-O-MODEL-A + !
    _DGRAPH-B-U @ _DGRAPH-B-WIDGET @ _DGRAPH-O-MODEL-U + !
    _DGRAPH-B-NEW-SCRATCH @
        _DGRAPH-B-WIDGET @ _DGRAPH-O-SCRATCH-A + !
    _DGRAPH-B-NEED @ _DGRAPH-B-WIDGET @ _DGRAPH-O-SCRATCH-U + !
    _DGRAPH-B-WIDGET @ WDG-DIRTY
    _DGRAPH-B-OLD-SCRATCH @ ?DUP IF FREE THEN
    DGRAPH-S-OK ;

: DGRAPH-INSTANCE@  ( widget -- token )
    DUP _DGRAPH-GENUINE? 0= IF DROP 0 EXIT THEN
    _DGRAPH-O-INSTANCE + @ ;

: DGRAPH-FREE  ( widget -- )
    DUP _DGRAPH-O-SCRATCH-A + @ ?DUP IF FREE THEN
    FREE ;

