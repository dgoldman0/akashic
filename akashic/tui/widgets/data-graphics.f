    DUP UDG-METER-FG@ _DGRAPH-APPLY-FG
    UDG-METER-BG@ _DGRAPH-APPLY-BG
    _DGRAPH-APPLY-DIM ;

: _DGRAPH-DRAW-METER-VALUE  ( record -- )
    DUP _DGRAPH-D-RECORD ! _DGRAPH-METER-STYLE
    _DGRAPH-D-RECORD @ UDG-METER-VALUE@ _DGRAPH-SIGNED-LENGTH
    DUP _DGRAPH-M-LENGTH !
    _DGRAPH-D-RECORD @ UDG-OBJECT-WIDTH@ U> IF
        _DGRAPH-D-RECORD @ _DGRAPH-DRAW-MARKER EXIT
    THEN
    _DGRAPH-D-RECORD @ UDG-METER-VALUE@
        _DGRAPH-D-WIDGET @ _DGRAPH-O-SCRATCH-A + @
        _DGRAPH-SIGNED-FORMAT DROP
    _DGRAPH-D-RECORD @ UDG-OBJECT-ROW@
        _DGRAPH-D-RECORD @ UDG-OBJECT-HEIGHT@ 1- 2/ +
        _DGRAPH-D-ROW !
    _DGRAPH-D-RECORD @ UDG-OBJECT-COLUMN@
        _DGRAPH-D-RECORD @ UDG-OBJECT-WIDTH@
        _DGRAPH-M-LENGTH @ - 2/ + _DGRAPH-D-COL !
    _DGRAPH-D-WIDGET @ _DGRAPH-O-SCRATCH-A + @ _DGRAPH-M-LENGTH @
        _DGRAPH-D-ROW @ _DGRAPH-D-COL @ DRW-TEXT ;

: _DGRAPH-DRAW-METER  ( record -- )
    _DGRAPH-D-RECORD !
    _DGRAPH-D-RECORD @ UDG-METER-BG@
    _DGRAPH-D-RECORD @ UDG-OBJECT-ROW@
    _DGRAPH-D-RECORD @ UDG-OBJECT-COLUMN@
    _DGRAPH-D-RECORD @ UDG-OBJECT-HEIGHT@
    _DGRAPH-D-RECORD @ UDG-OBJECT-WIDTH@
    _DGRAPH-DRAW-COLOR-RECT
    _DGRAPH-D-RECORD @ UDG-METER-ORIENTATION@
        UDG-METER-HORIZONTAL = IF
        _DGRAPH-D-RECORD @ UDG-METER-VALUE@
        _DGRAPH-D-RECORD @ UDG-METER-MINIMUM@
        _DGRAPH-D-RECORD @ UDG-METER-MAXIMUM@
        _DGRAPH-D-RECORD @ UDG-OBJECT-WIDTH@
        _DGRAPH-METER-SCALE _DGRAPH-M-FILL !
        _DGRAPH-D-RECORD @ UDG-METER-FG@
        _DGRAPH-D-RECORD @ UDG-OBJECT-ROW@
        _DGRAPH-D-RECORD @ UDG-OBJECT-COLUMN@
        _DGRAPH-D-RECORD @ UDG-OBJECT-HEIGHT@
        _DGRAPH-M-FILL @ _DGRAPH-DRAW-COLOR-RECT
    ELSE
        _DGRAPH-D-RECORD @ UDG-METER-VALUE@
        _DGRAPH-D-RECORD @ UDG-METER-MINIMUM@
        _DGRAPH-D-RECORD @ UDG-METER-MAXIMUM@
        _DGRAPH-D-RECORD @ UDG-OBJECT-HEIGHT@
        _DGRAPH-METER-SCALE _DGRAPH-M-FILL !
        _DGRAPH-D-RECORD @ UDG-METER-FG@
        _DGRAPH-D-RECORD @ UDG-OBJECT-ROW@
            _DGRAPH-D-RECORD @ UDG-OBJECT-HEIGHT@ +
            _DGRAPH-M-FILL @ -
        _DGRAPH-D-RECORD @ UDG-OBJECT-COLUMN@
        _DGRAPH-M-FILL @
        _DGRAPH-D-RECORD @ UDG-OBJECT-WIDTH@
        _DGRAPH-DRAW-COLOR-RECT
    THEN
    _DGRAPH-D-RECORD @ UDG-METER-FLAGS@
        UDG-METER-SHOW-VALUE AND IF
        _DGRAPH-D-RECORD @ _DGRAPH-DRAW-METER-VALUE
    THEN ;

: _DGRAPH-STATUS-CP  ( record -- codepoint )
    DUP UDG-STATUS-VALUE@ 0<> IF
        UDG-STATUS-SHAPE@ CASE
            UDG-STATUS-CIRCLE  OF 0x25CF ENDOF
            UDG-STATUS-SQUARE  OF 0x25A0 ENDOF
            UDG-STATUS-DIAMOND OF 0x25C6 ENDOF
        ENDCASE
    ELSE
        UDG-STATUS-SHAPE@ CASE
            UDG-STATUS-CIRCLE  OF 0x25CB ENDOF
            UDG-STATUS-SQUARE  OF 0x25A1 ENDOF
            UDG-STATUS-DIAMOND OF 0x25C7 ENDOF
        ENDCASE
    THEN ;

: _DGRAPH-DRAW-STATUS  ( record -- )
    DUP _DGRAPH-D-RECORD !
    DUP UDG-STATUS-VALUE@ 0<> IF UDG-STATUS-ACTIVE@
        ELSE UDG-STATUS-INACTIVE@ THEN
    DUP UDG-RGBA-ALPHA@ 0= IF DROP EXIT THEN
    DRW-STYLE-RESTORE _DGRAPH-APPLY-FG _DGRAPH-APPLY-DIM
    _DGRAPH-D-RECORD @ _DGRAPH-STATUS-CP
    _DGRAPH-D-RECORD @ _DGRAPH-OBJECT-CENTER DRW-CHAR ;

