: _DGRAPH-CLAIM-INSTANCE  ( -- token )
    _DGRAPH-NEXT-INSTANCE @ DUP -1 =
        IF DROP 1 ELSE 1+ DUP 0= IF DROP 1 THEN THEN
    DUP _DGRAPH-NEXT-INSTANCE ! ;

: _DGRAPH-SPAN?  ( address bytes -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    DUP 0= IF DROP 0= EXIT THEN
    OVER 0= IF 2DROP 0 EXIT THEN
    MSPAN-NONWRAPPING? ;

: DGRAPH-STORAGE-DISJOINT?  ( address bytes -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    DUP 0= IF DROP 0= EXIT THEN
    OVER 0= IF 2DROP 0 EXIT THEN
    2DUP MSPAN-NONWRAPPING? 0= IF 2DROP 0 EXIT THEN
    _DGRAPH-OWNED-LIMIT @ DUP _DGRAPH-OWNED-START U< IF
        DROP 2DROP 0 EXIT
    THEN
    _DGRAPH-OWNED-START -
    _DGRAPH-OWNED-START SWAP
    MSPAN-OVERLAP? 0= ;

: _DGRAPH-GENUINE?  ( widget -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP _DGRAPH-DESC-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _WDG-O-TYPE + @ WDG-T-DATA-GRAPHICS <> IF DROP 0 EXIT THEN
    DUP _WDG-O-DRAW-XT + @ ['] _DGRAPH-DRAW <> IF DROP 0 EXIT THEN
    DUP _WDG-O-HANDLE-XT + @ ['] _DGRAPH-HANDLE <> IF DROP 0 EXIT THEN
    DUP _DGRAPH-O-INSTANCE + @ 0= IF DROP 0 EXIT THEN
    WDG-REGION DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    RGN-SIZE MSPAN-NONWRAPPING? ;

