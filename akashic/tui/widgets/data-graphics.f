: _DGRAPH-DRAW-MARKER  ( record -- )
    DUP UDG-OBJECT-ROW@ OVER UDG-OBJECT-HEIGHT@ 1- 2/ +
    SWAP DUP UDG-OBJECT-COLUMN@ SWAP UDG-OBJECT-WIDTH@ 1- +
    [CHAR] # -ROT DRW-CHAR ;

: _DGRAPH-READOUT-STYLE  ( record -- )
    DRW-STYLE-RESTORE
    DUP UDG-READOUT-FG@ _DGRAPH-APPLY-FG
    UDG-READOUT-BG@ _DGRAPH-APPLY-BG
    _DGRAPH-APPLY-DIM ;

: _DGRAPH-DRAW-READOUT  ( record -- )
    DUP _DGRAPH-D-RECORD ! _DGRAPH-READOUT-STYLE
    _DGRAPH-D-RECORD @ DGF-READOUT-MEASURE
    DUP DGF-S-OK <> IF
        2DROP _DGRAPH-D-RECORD @ _DGRAPH-DRAW-MARKER EXIT
    THEN
    DROP DUP _DGRAPH-D-BYTES !
    _DGRAPH-D-RECORD @ UDG-READOUT-UNIT-BYTES@ -
    _DGRAPH-D-RECORD @ UDG-READOUT-UNIT@ UTF8-LEN +
    DUP _DGRAPH-D-CELLS !
    _DGRAPH-D-RECORD @ UDG-OBJECT-WIDTH@ U> IF
        _DGRAPH-D-RECORD @ _DGRAPH-DRAW-MARKER EXIT
    THEN
    _DGRAPH-D-RECORD @
        _DGRAPH-D-WIDGET @ _DGRAPH-O-SCRATCH-A + @
        _DGRAPH-D-WIDGET @ _DGRAPH-O-SCRATCH-U + @
        DGF-READOUT-FORMAT
    DUP DGF-S-OK <> IF
        2DROP _DGRAPH-D-RECORD @ _DGRAPH-DRAW-MARKER EXIT
    THEN
    DROP DROP
    _DGRAPH-D-RECORD @ UDG-OBJECT-ROW@
        _DGRAPH-D-RECORD @ UDG-OBJECT-HEIGHT@ 1- 2/ +
        _DGRAPH-D-ROW !
    _DGRAPH-D-RECORD @ UDG-OBJECT-COLUMN@
        _DGRAPH-D-RECORD @ UDG-OBJECT-WIDTH@ +
        _DGRAPH-D-CELLS @ - _DGRAPH-D-COL !
    _DGRAPH-D-WIDGET @ _DGRAPH-O-SCRATCH-A + @ _DGRAPH-D-BYTES @
        _DGRAPH-D-ROW @ _DGRAPH-D-COL @ DRW-TEXT ;

