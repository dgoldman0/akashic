VARIABLE _TGRID-NAV-DIRECTION
VARIABLE _TGRID-NAV-CURRENT
VARIABLE _TGRID-NAV-CURRENT-ROW
VARIABLE _TGRID-NAV-CURRENT-COL
VARIABLE _TGRID-NAV-BEST
VARIABLE _TGRID-NAV-BEST-ROW
VARIABLE _TGRID-NAV-BEST-COL
VARIABLE _TGRID-NAV-BEST-DIST
VARIABLE _TGRID-NAV-HAVE

0 CONSTANT _TGRID-NAV-LEFT
1 CONSTANT _TGRID-NAV-RIGHT
2 CONSTANT _TGRID-NAV-UP
3 CONSTANT _TGRID-NAV-DOWN

: _TGRID-ABS  ( n -- u ) DUP 0< IF NEGATE THEN ;

: _TGRID-NAV-TAKE  ( item -- )
    DUP _TGRID-NAV-BEST !
    DUP USCOL-ITEM-ROW@ _TGRID-NAV-BEST-ROW !
    USCOL-ITEM-COLUMN@ _TGRID-NAV-BEST-COL !
    -1 _TGRID-NAV-HAVE ! ;

: _TGRID-NAV-LEFT-BETTER?  ( item -- flag )
    DUP USCOL-ITEM-ROW@ _TGRID-NAV-CURRENT-ROW @ U> IF DROP 0 EXIT THEN
    DUP USCOL-ITEM-ROW@ _TGRID-NAV-CURRENT-ROW @ = IF
        DUP USCOL-ITEM-COLUMN@ _TGRID-NAV-CURRENT-COL @ U< 0=
            IF DROP 0 EXIT THEN
    THEN
    _TGRID-NAV-HAVE @ 0= IF DROP -1 EXIT THEN
    DUP USCOL-ITEM-ROW@ _TGRID-NAV-BEST-ROW @ U> IF DROP -1 EXIT THEN
    DUP USCOL-ITEM-ROW@ _TGRID-NAV-BEST-ROW @ =
    SWAP USCOL-ITEM-COLUMN@ _TGRID-NAV-BEST-COL @ U> AND ;

: _TGRID-NAV-RIGHT-BETTER?  ( item -- flag )
    DUP USCOL-ITEM-ROW@ _TGRID-NAV-CURRENT-ROW @ U< IF DROP 0 EXIT THEN
    DUP USCOL-ITEM-ROW@ _TGRID-NAV-CURRENT-ROW @ = IF
        DUP USCOL-ITEM-COLUMN@ _TGRID-NAV-CURRENT-COL @ U> 0=
            IF DROP 0 EXIT THEN
    THEN
    _TGRID-NAV-HAVE @ 0= IF DROP -1 EXIT THEN
    DUP USCOL-ITEM-ROW@ _TGRID-NAV-BEST-ROW @ U< IF DROP -1 EXIT THEN
    DUP USCOL-ITEM-ROW@ _TGRID-NAV-BEST-ROW @ =
    SWAP USCOL-ITEM-COLUMN@ _TGRID-NAV-BEST-COL @ U< AND ;

: _TGRID-NAV-VERTICAL-BETTER?  ( item -- flag )
    DUP USCOL-ITEM-ROW@
    _TGRID-NAV-DIRECTION @ _TGRID-NAV-UP = IF
        DUP _TGRID-NAV-CURRENT-ROW @ U< 0= IF 2DROP 0 EXIT THEN
        _TGRID-NAV-HAVE @ IF
            DUP _TGRID-NAV-BEST-ROW @ U< IF 2DROP 0 EXIT THEN
        THEN
    ELSE
        DUP _TGRID-NAV-CURRENT-ROW @ U> 0= IF 2DROP 0 EXIT THEN
        _TGRID-NAV-HAVE @ IF
            DUP _TGRID-NAV-BEST-ROW @ U> IF 2DROP 0 EXIT THEN
        THEN
    THEN
    _TGRID-NAV-HAVE @ IF
        DUP _TGRID-NAV-BEST-ROW @ = IF
            DROP DUP USCOL-ITEM-COLUMN@ _TGRID-NAV-CURRENT-COL @ - _TGRID-ABS
            _TGRID-NAV-BEST-COL @ _TGRID-NAV-CURRENT-COL @ - _TGRID-ABS U<
            NIP EXIT
        THEN
    THEN
    2DROP -1 ;

: _TGRID-NAV-CANDIDATE?  ( item -- flag )
    DUP _TGRID-AVAILABLE-CONTENT? 0= IF DROP 0 EXIT THEN
    DUP USCOL-ITEM-KEY@ _TGRID-NAV-CURRENT @ = IF DROP 0 EXIT THEN
    _TGRID-NAV-DIRECTION @ CASE
        _TGRID-NAV-LEFT OF _TGRID-NAV-LEFT-BETTER? ENDOF
        _TGRID-NAV-RIGHT OF _TGRID-NAV-RIGHT-BETTER? ENDOF
        _TGRID-NAV-UP OF _TGRID-NAV-VERTICAL-BETTER? ENDOF
        _TGRID-NAV-DOWN OF _TGRID-NAV-VERTICAL-BETTER? ENDOF
        DROP 0
    ENDCASE ;

: _TGRID-NAV-TARGET  ( direction widget -- key|0 )
