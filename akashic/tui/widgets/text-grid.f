VARIABLE _TGRID-D-ATTR
CREATE _TGRID-D-DECODE UTF8-DECODE-STATE-SIZE ALLOT

: _TGRID-DRAW-TEXT  ( address bytes row column width -- )
    _TGRID-D-CELL-W ! _TGRID-D-TEXT-COL ! _TGRID-D-ROW !
    _TGRID-D-TEXT-U ! _TGRID-D-TEXT-A !
    _TGRID-D-DECODE UTF8-DECODE-STATE-SIZE 0 FILL
    0 _TGRID-D-TEXT-I !
    BEGIN
        _TGRID-D-TEXT-U @ 0>
        _TGRID-D-TEXT-I @ _TGRID-D-CELL-W @ < AND
    WHILE
        _TGRID-D-TEXT-A @ _TGRID-D-TEXT-U @ _TGRID-D-DECODE
            UTF8-DECODE-WITH
        _TGRID-D-TEXT-U ! _TGRID-D-TEXT-A ! _TGRID-D-TEXT-CP !
        _TGRID-D-TEXT-CP @ _TGRID-D-ROW @
            _TGRID-D-TEXT-COL @ _TGRID-D-TEXT-I @ + DRW-CHAR
        1 _TGRID-D-TEXT-I +!
    REPEAT ;

: _TGRID-DRAW-STYLE  ( item -- )
    DRW-STYLE-RESTORE
    0 _TGRID-D-ATTR !
    DUP USCOL-ITEM-ROLE@ USCOL-ROLE-CONTENT <> IF
        CELL-A-BOLD _TGRID-D-ATTR +!
    THEN
    DUP USCOL-ITEM-STATE@ USCOL-ITEM-CURRENT AND IF
        CELL-A-UNDERLINE _TGRID-D-ATTR +!
    THEN
    DUP USCOL-ITEM-STATE@ USCOL-ITEM-UNAVAILABLE AND IF
        CELL-A-DIM _TGRID-D-ATTR +!
    THEN
    DUP USCOL-ITEM-KEY@ _TGRID-D-M @ USCOL-TEXT-PRIMARY-KEY@ = IF
        CELL-A-REVERSE _TGRID-D-ATTR +!
    THEN
    DROP _TGRID-D-ATTR @ DRW-ATTR! ;

: _TGRID-DRAW-ITEM  ( item -- )
    _TGRID-ITEM !
    _TGRID-ITEM @ USCOL-ITEM-ROW@ _TGRID-D-VROW @ -
        DUP 0< IF DROP EXIT THEN
        DUP _TGRID-D-VROWS @ U< 0= IF DROP EXIT THEN
        _TGRID-D-ROW !
    _TGRID-ITEM @ USCOL-ITEM-COLUMN@ _TGRID-D-VCOL @ -
        DUP 0< IF DROP EXIT THEN
        DUP _TGRID-D-VCOLS @ U< 0= IF DROP EXIT THEN
        _TGRID-D-COL !
    _TGRID-D-ROW @ _TGRID-D-H @ * _TGRID-D-VROWS @ / _TGRID-D-ROW !
    _TGRID-ITEM @ USCOL-ITEM-ROW@ _TGRID-D-VROW @ -
        _TGRID-ITEM @ USCOL-ITEM-ROW-SPAN@ +
        _TGRID-D-H @ * _TGRID-D-VROWS @ / _TGRID-D-BOTTOM !
    _TGRID-D-COL @ _TGRID-D-WIDTH @ * _TGRID-D-VCOLS @ / _TGRID-D-COL !
    _TGRID-ITEM @ USCOL-ITEM-COLUMN@ _TGRID-D-VCOL @ -
        _TGRID-ITEM @ USCOL-ITEM-COLUMN-SPAN@ +
        _TGRID-D-WIDTH @ * _TGRID-D-VCOLS @ / _TGRID-D-RIGHT !
    _TGRID-D-BOTTOM @ _TGRID-D-ROW @ - 1 MAX _TGRID-D-CELL-H !
    _TGRID-D-RIGHT @ _TGRID-D-COL @ - 1 MAX _TGRID-D-CELL-W !
    _TGRID-ITEM @ _TGRID-DRAW-STYLE
    _TGRID-ITEM @ USCOL-ITEM-TEXT@
    _TGRID-D-ROW @
    _TGRID-D-COL @
    _TGRID-D-CELL-W @ _TGRID-DRAW-TEXT ;

: _TGRID-DRAW-IMPL  ( widget -- )
    DUP _TGRID-D-W !
    DUP WDG-REGION RGN-H _TGRID-D-H !
    WDG-REGION RGN-W _TGRID-D-WIDTH !
    DRW-STYLE-RESTORE
    32 0 0 _TGRID-D-H @ _TGRID-D-WIDTH @ DRW-FILL-RECT
    _TGRID-D-W @ _TGRID-BOUND? 0= IF EXIT THEN
    _TGRID-D-W @ _TGRID-O-MODEL-A + @ DUP _TGRID-D-M !
    DUP USCOL-TEXT-VIEWPORT-ROW@ _TGRID-D-VROW !
    DUP USCOL-TEXT-VIEWPORT-COLUMN@ _TGRID-D-VCOL !
    DUP USCOL-TEXT-VIEWPORT-ROWS@ _TGRID-D-VROWS !
    DUP USCOL-TEXT-VIEWPORT-COLUMNS@ _TGRID-D-VCOLS !
    USCOL-TEXT-FIRST _TGRID-CURSOR !
    0 _TGRID-I !
    BEGIN _TGRID-I @ _TGRID-D-M @ USCOL-TEXT-ITEM-COUNT@ U< WHILE
        _TGRID-CURSOR @ DUP _TGRID-DRAW-ITEM
        USCOL-ITEM-NEXT _TGRID-CURSOR !
        1 _TGRID-I +!
    REPEAT
    DRW-STYLE-RESTORE ;

