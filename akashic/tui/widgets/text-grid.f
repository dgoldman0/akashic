CREATE _TGRID-OWNED-START
VARIABLE _TGRID-OWNED-LIMIT
0 _TGRID-OWNED-LIMIT !

40 CONSTANT _TGRID-O-MODEL-A
48 CONSTANT _TGRID-O-MODEL-U
56 CONSTANT _TGRID-O-ON-SELECT
64 CONSTANT _TGRID-O-INSTANCE
72 CONSTANT _TGRID-DESC-SIZE

\ Stable execution tokens let exact canonical-widget checks exist before the
\ mutually recursive draw/state helpers are installed below.
DEFER _TGRID-DRAW
DEFER _TGRID-HANDLE

VARIABLE _TGRID-NEXT-INSTANCE
VARIABLE _TGRID-NEW-INSTANCE
0 _TGRID-NEXT-INSTANCE !
0 _TGRID-NEW-INSTANCE !

: _TGRID-CLAIM-INSTANCE  ( -- token )
    _TGRID-NEXT-INSTANCE @ DUP -1 =
        IF DROP 1 ELSE 1+ DUP 0= IF DROP 1 THEN THEN
    DUP _TGRID-NEXT-INSTANCE ! ;

: _TGRID-SPAN?  ( address bytes -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    DUP 0= IF DROP 0= EXIT THEN
    OVER 0= IF 2DROP 0 EXIT THEN
    MSPAN-NONWRAPPING? ;

: _TGRID-GENUINE?  ( widget -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP _TGRID-DESC-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _WDG-O-TYPE + @ WDG-T-TEXTGRID <> IF DROP 0 EXIT THEN
    DUP _WDG-O-DRAW-XT + @ ['] _TGRID-DRAW <> IF DROP 0 EXIT THEN
    DUP _WDG-O-HANDLE-XT + @ ['] _TGRID-HANDLE <> IF DROP 0 EXIT THEN
    DUP _TGRID-O-INSTANCE + @ 0= IF DROP 0 EXIT THEN
    WDG-REGION DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    RGN-SIZE MSPAN-NONWRAPPING? ;

\ =====================================================================
\  Module and live-widget storage authority
\ =====================================================================

\ Pure and deliberately unguarded.  Higher layers call this before allowing
\ a caller bank to alias any mutable TGRID scratch or the optional guard.
: TGRID-STORAGE-DISJOINT?  ( address bytes -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    DUP 0= IF DROP 0= EXIT THEN
    OVER 0= IF 2DROP 0 EXIT THEN
    2DUP MSPAN-NONWRAPPING? 0= IF 2DROP 0 EXIT THEN
    _TGRID-OWNED-LIMIT @ DUP _TGRID-OWNED-START U< IF
        DROP 2DROP 0 EXIT
    THEN
    _TGRID-OWNED-START - >R
    _TGRID-OWNED-START R> MSPAN-OVERLAP? 0= ;

VARIABLE _TGRID-SD-A
VARIABLE _TGRID-SD-U
VARIABLE _TGRID-SD-W

: TGRID-TEXT-GRID-STORAGE-DISJOINT?  ( address bytes widget -- flag )
    >R
    2DUP TGRID-STORAGE-DISJOINT? 0= IF 2DROP R> DROP 0 EXIT THEN
    _TGRID-SD-U ! _TGRID-SD-A ! R> _TGRID-SD-W !
    _TGRID-SD-W @ _TGRID-GENUINE? 0= IF 0 EXIT THEN
    _TGRID-SD-A @ _TGRID-SD-U @
        _TGRID-SD-W @ _TGRID-DESC-SIZE MSPAN-OVERLAP? IF 0 EXIT THEN
    _TGRID-SD-W @ WDG-REGION ?DUP IF
        _TGRID-SD-A @ _TGRID-SD-U @ ROT RGN-SIZE
            MSPAN-OVERLAP? IF 0 EXIT THEN
    THEN
    _TGRID-SD-W @ _TGRID-O-MODEL-A + @ ?DUP IF
        _TGRID-SD-A @ _TGRID-SD-U @ ROT
        _TGRID-SD-W @ _TGRID-O-MODEL-U + @
            MSPAN-OVERLAP? IF 0 EXIT THEN
    THEN
    -1 ;

