    DUP _TGRID-BOUND? 0= IF 0 EXIT THEN
    4 PICK 0= IF 0 EXIT THEN
    3 PICK 3 PICK 2 PICK TGRID-TEXT-GRID-STORAGE-DISJOINT? 0=
