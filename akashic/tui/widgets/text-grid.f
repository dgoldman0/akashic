        TGRID-TEXT-GRID-STORAGE-DISJOINT? 0=
        IF 0 EXIT THEN
    1 PICK USCOL-BUILDER-SIZE USCOL-STORAGE-DISJOINT? 0=
        IF 0 EXIT THEN
    -1 ;

: TGRID-TEXT-GRID-CAPTURE
    ( root-key destination capacity builder widget -- bytes status )
    _TGRID-CAPTURE-PREFLIGHT? 0= IF
        2DROP 2DROP DROP 0 USCOL-S-INVALID EXIT
    THEN
    _TGRID-C-WIDGET ! _TGRID-C-BUILDER ! _TGRID-C-CAP !
    _TGRID-C-DST ! _TGRID-C-ROOT !
    _TGRID-C-WIDGET @ _TGRID-O-MODEL-U + @ _TGRID-C-U !
    _TGRID-C-DST @ 0= IF
        _TGRID-C-CAP @ IF 0 USCOL-S-INVALID EXIT THEN
        _TGRID-C-U @ USCOL-S-OK EXIT
    THEN
    _TGRID-C-DST @ 7 AND IF 0 USCOL-S-INVALID EXIT THEN
    _TGRID-C-DST @ _TGRID-C-CAP @ _TGRID-SPAN? 0= IF
        0 USCOL-S-INVALID EXIT
    THEN
    _TGRID-C-DST @ _TGRID-C-CAP @
        _TGRID-C-BUILDER @ USCOL-BUILDER-SIZE MSPAN-OVERLAP? IF
        0 USCOL-S-INVALID EXIT
    THEN
    _TGRID-C-CAP @ _TGRID-C-U @ U< IF 0 USCOL-S-CAPACITY EXIT THEN
    _TGRID-C-WIDGET @ _TGRID-O-MODEL-A + @ _TGRID-C-DST @ _TGRID-C-U @ MOVE
    _TGRID-C-ROOT @ _TGRID-C-DST @ 24 + !
    0 _TGRID-C-DST @ USCOL-ROOT-ROW-OFFSET + !
    0 _TGRID-C-DST @ USCOL-ROOT-COLUMN-OFFSET + !
    _TGRID-C-WIDGET @ WDG-REGION RGN-H
        _TGRID-C-DST @ USCOL-ROOT-HEIGHT-OFFSET + !
    _TGRID-C-WIDGET @ WDG-REGION RGN-W
        _TGRID-C-DST @ USCOL-ROOT-WIDTH-OFFSET + !
    0 _TGRID-C-STATE !
    _TGRID-C-WIDGET @ WDG-VISIBLE? IF USCOL-STATE-VISIBLE _TGRID-C-STATE +! THEN
    _TGRID-C-WIDGET @ WDG-DISABLED? 0= IF USCOL-STATE-ENABLED _TGRID-C-STATE +! THEN
    _TGRID-C-WIDGET @ WDG-FOCUSED?
    _TGRID-C-WIDGET @ WDG-VISIBLE? AND
    _TGRID-C-WIDGET @ WDG-DISABLED? 0= AND IF
        USCOL-STATE-SELECTED _TGRID-C-STATE +!
    THEN
    _TGRID-C-STATE @ _TGRID-C-DST @ USCOL-ROOT-STATE-OFFSET + !
    _TGRID-C-U @ USCOL-S-OK ;

