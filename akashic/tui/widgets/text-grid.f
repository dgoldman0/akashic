: _TGRID-BIND-PREFLIGHT?  ( entry bytes work-a work-u summary widget -- flag )
    5 PICK 5 PICK TGRID-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    3 PICK 3 PICK TGRID-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    1 PICK USCOL-SUMMARY-SIZE TGRID-STORAGE-DISJOINT? 0=
        IF 0 EXIT THEN
    5 PICK 5 PICK USCOL-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    3 PICK 3 PICK USCOL-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    1 PICK USCOL-SUMMARY-SIZE USCOL-STORAGE-DISJOINT? 0=
        IF 0 EXIT THEN
    5 PICK 5 PICK 2 PICK TGRID-TEXT-GRID-STORAGE-DISJOINT? 0=
        IF 0 EXIT THEN
    3 PICK 3 PICK 2 PICK TGRID-TEXT-GRID-STORAGE-DISJOINT? 0=
        IF 0 EXIT THEN
    1 PICK USCOL-SUMMARY-SIZE 2 PICK
        TGRID-TEXT-GRID-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    -1 ;

: TGRID-NEW  ( rgn -- widget )
    DUP 0= ABORT" TGRID-NEW: region"
    DUP 7 AND ABORT" TGRID-NEW: region alignment"
    DUP RGN-SIZE MSPAN-NONWRAPPING? 0= ABORT" TGRID-NEW: region span"
    _TGRID-CLAIM-INSTANCE _TGRID-NEW-INSTANCE !
    _TGRID-DESC-SIZE ALLOCATE 0<> ABORT" TGRID-NEW: alloc"
    WDG-T-TEXTGRID OVER _WDG-O-TYPE + !
    SWAP OVER _WDG-O-REGION + !
    ['] _TGRID-DRAW OVER _WDG-O-DRAW-XT + !
    ['] _TGRID-HANDLE OVER _WDG-O-HANDLE-XT + !
    WDG-F-VISIBLE WDG-F-DIRTY OR OVER _WDG-O-FLAGS + !
    0 OVER _TGRID-O-MODEL-A + !
    0 OVER _TGRID-O-MODEL-U + !
    0 OVER _TGRID-O-ON-SELECT + !
    _TGRID-NEW-INSTANCE @ OVER _TGRID-O-INSTANCE + !
    0 _TGRID-NEW-INSTANCE ! ;

: TGRID-BIND  ( entry bytes work-a work-u summary widget -- status )
    _TGRID-BIND-PREFLIGHT? 0= IF
        2DROP 2DROP 2DROP USCOL-S-INVALID EXIT
    THEN
    _TGRID-B-WIDGET ! _TGRID-B-SUMMARY !
    _TGRID-B-WORK-U ! _TGRID-B-WORK ! _TGRID-B-U ! _TGRID-B-ENTRY !
    _TGRID-B-WIDGET @ _TGRID-GENUINE? 0= IF USCOL-S-INVALID EXIT THEN
    _TGRID-B-ENTRY @ _TGRID-B-U @ _TGRID-SPAN? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _TGRID-B-ENTRY @ 7 AND IF USCOL-S-INVALID EXIT THEN
    _TGRID-B-WORK @ _TGRID-B-WORK-U @ _TGRID-SPAN? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _TGRID-B-WORK-U @ IF
        _TGRID-B-WORK @ 7 AND IF USCOL-S-INVALID EXIT THEN
    THEN
    _TGRID-B-SUMMARY @ DUP 0= IF DROP USCOL-S-INVALID EXIT THEN
    DUP 7 AND IF DROP USCOL-S-INVALID EXIT THEN
    USCOL-SUMMARY-SIZE MSPAN-NONWRAPPING? 0= IF USCOL-S-INVALID EXIT THEN
    _TGRID-B-ENTRY @ _TGRID-B-U @
        _TGRID-B-WIDGET @ _TGRID-DESC-SIZE MSPAN-OVERLAP? IF
        USCOL-S-INVALID EXIT
    THEN
    _TGRID-B-ENTRY @ _TGRID-B-U @
        _TGRID-B-WIDGET @ WDG-REGION RGN-SIZE MSPAN-OVERLAP? IF
        USCOL-S-INVALID EXIT
    THEN
    _TGRID-B-ENTRY @ _TGRID-B-U @
        _TGRID-B-WORK @ _TGRID-B-WORK-U @ MSPAN-OVERLAP? IF
        USCOL-S-INVALID EXIT
    THEN
    _TGRID-B-ENTRY @ _TGRID-B-U @
        _TGRID-B-SUMMARY @ USCOL-SUMMARY-SIZE MSPAN-OVERLAP? IF
        USCOL-S-INVALID EXIT
    THEN
    _TGRID-B-WORK @ _TGRID-B-WORK-U @
        _TGRID-B-SUMMARY @ USCOL-SUMMARY-SIZE MSPAN-OVERLAP? IF
        USCOL-S-INVALID EXIT
    THEN
    _TGRID-B-ENTRY @ _TGRID-B-U @
        _TGRID-B-WORK @ _TGRID-B-WORK-U @ _TGRID-B-SUMMARY @
        USCOL-ENTRY-VALIDATE
    DUP USCOL-S-OK <> IF EXIT THEN DROP
    _TGRID-B-SUMMARY @ USCOL-SUMMARY-FAMILY@
        USCOL-F-TEXT-GRID <> IF USCOL-S-INVALID EXIT THEN
    _TGRID-B-ENTRY @ USCOL-TEXT-FLAGS@
        USCOL-CONTENT-READ-ONLY AND 0= IF USCOL-S-INVALID EXIT THEN
    _TGRID-B-ENTRY @ USCOL-ROOT-ROW@ IF USCOL-S-INVALID EXIT THEN
    _TGRID-B-ENTRY @ USCOL-ROOT-COLUMN@ IF USCOL-S-INVALID EXIT THEN
    _TGRID-B-ENTRY @ USCOL-ROOT-HEIGHT@
        _TGRID-B-WIDGET @ WDG-REGION RGN-H <> IF USCOL-S-INVALID EXIT THEN
    _TGRID-B-ENTRY @ USCOL-ROOT-WIDTH@
        _TGRID-B-WIDGET @ WDG-REGION RGN-W <> IF USCOL-S-INVALID EXIT THEN
    _TGRID-B-ENTRY @ _TGRID-MODEL-PRIMARY-AVAILABLE? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _TGRID-B-ENTRY @ _TGRID-B-WIDGET @ _TGRID-O-MODEL-A + !
    _TGRID-B-U @ _TGRID-B-WIDGET @ _TGRID-O-MODEL-U + !
    _TGRID-B-WIDGET @ WDG-DIRTY
    USCOL-S-OK ;

: TGRID-SELECTED@  ( widget -- item-key )
    DUP _TGRID-BOUND? 0= IF DROP 0 EXIT THEN
    _TGRID-O-MODEL-A + @ USCOL-TEXT-PRIMARY-KEY@ ;

VARIABLE _TGRID-S-KEY
VARIABLE _TGRID-S-WIDGET

: _TGRID-SELECT!  ( item-key widget -- status )
    _TGRID-S-WIDGET ! _TGRID-S-KEY !
    _TGRID-S-KEY @ 0= IF USCOL-S-INVALID EXIT THEN
    _TGRID-S-KEY @ _TGRID-S-WIDGET @ _TGRID-FIND-ITEM
    DUP 0= IF DROP USCOL-S-INVALID EXIT THEN
    _TGRID-AVAILABLE-CONTENT? 0= IF USCOL-S-INVALID EXIT THEN
    _TGRID-S-WIDGET @ TGRID-SELECTED@ _TGRID-S-KEY @ = IF
        USCOL-S-OK EXIT
    THEN
    _TGRID-S-KEY @ _TGRID-S-WIDGET @ _TGRID-O-MODEL-A + @
        USCOL-TEXT-PRIMARY-KEY-OFFSET + !
    _TGRID-S-WIDGET @ WDG-DIRTY
    _TGRID-S-WIDGET @ _TGRID-O-ON-SELECT + @ ?DUP IF
        _TGRID-S-KEY @ _TGRID-S-WIDGET @ ROT EXECUTE
    THEN
    USCOL-S-OK ;

: TGRID-SELECT!  ( item-key widget -- status )
    _TGRID-SELECT! ;

: TGRID-ON-SELECT  ( xt widget -- )
    _TGRID-O-ON-SELECT + ! ;

: TGRID-INSTANCE@  ( widget -- token )
    DUP _TGRID-GENUINE? 0= IF DROP 0 EXIT THEN
    _TGRID-O-INSTANCE + @ ;

: TGRID-FREE  ( widget -- )
    FREE ;

