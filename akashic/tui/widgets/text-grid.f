VARIABLE _TGRID-W
VARIABLE _TGRID-MODEL
VARIABLE _TGRID-CURSOR
VARIABLE _TGRID-ITEM
VARIABLE _TGRID-I

: _TGRID-BOUND?  ( widget -- flag )
    DUP _TGRID-GENUINE? 0= IF DROP 0 EXIT THEN
    DUP _TGRID-O-MODEL-A + @ DUP 0= IF 2DROP 0 EXIT THEN
    SWAP _TGRID-O-MODEL-U + @ _TGRID-SPAN? ;

: _TGRID-AVAILABLE-CONTENT?  ( item -- flag )
    DUP USCOL-ITEM-ROLE@ USCOL-ROLE-CONTENT =
    SWAP USCOL-ITEM-STATE@ USCOL-ITEM-UNAVAILABLE AND 0= AND ;

VARIABLE _TGRID-FIND-KEY

: _TGRID-FIND-IN-MODEL  ( key model -- item|0 )
    _TGRID-MODEL ! _TGRID-FIND-KEY !
    _TGRID-MODEL @ USCOL-TEXT-FIRST _TGRID-CURSOR !
    0 _TGRID-I !
    BEGIN _TGRID-I @ _TGRID-MODEL @ USCOL-TEXT-ITEM-COUNT@ U< WHILE
        _TGRID-CURSOR @ DUP USCOL-ITEM-KEY@ _TGRID-FIND-KEY @ = IF EXIT THEN
        USCOL-ITEM-NEXT _TGRID-CURSOR !
        1 _TGRID-I +!
    REPEAT
    0 ;

: _TGRID-FIND-ITEM  ( key widget -- item|0 )
    _TGRID-W !
    _TGRID-W @ _TGRID-BOUND? 0= IF DROP 0 EXIT THEN
    _TGRID-W @ _TGRID-O-MODEL-A + @ _TGRID-FIND-IN-MODEL ;

: _TGRID-MODEL-PRIMARY-AVAILABLE?  ( model -- flag )
    DUP USCOL-TEXT-PRIMARY-KEY@ DUP 0= IF
        2DROP -1 EXIT
    THEN
    SWAP _TGRID-FIND-IN-MODEL DUP 0= IF EXIT THEN
    _TGRID-AVAILABLE-CONTENT? ;

