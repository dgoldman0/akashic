\ =====================================================================
\ status-field.f -- Canonical, pointer-transparent structured status
\ =====================================================================
\ Borrows an immutable USF model.  CELL and optional capture consume that
\ same value.  Its region is exactly one row and the model width; changing
\ the region width requires binding a matching model.  Legacy SBAR remains
\ a separate widget with its original left/right string interface.

PROVIDED akashic-tui-status-field

REQUIRE ../widget.f
REQUIRE ../draw.f
REQUIRE ../status-field-model.f

USF-S-OK          CONSTANT SFIELD-S-OK
USF-S-UNSUPPORTED CONSTANT SFIELD-S-UNSUPPORTED
USF-S-CAPACITY    CONSTANT SFIELD-S-CAPACITY
USF-S-INVALID     CONSTANT SFIELD-S-INVALID

40 CONSTANT _SFIELD-O-MODEL-A
48 CONSTANT _SFIELD-O-MODEL-U
56 CONSTANT _SFIELD-O-INSTANCE
64 CONSTANT _SFIELD-DESC-SIZE

CREATE _SFIELD-OWNED-START
VARIABLE _SFIELD-OWNED-LIMIT
0 _SFIELD-OWNED-LIMIT !

DEFER _SFIELD-DRAW
DEFER _SFIELD-HANDLE
VARIABLE _SFIELD-NEXT-INSTANCE
0 _SFIELD-NEXT-INSTANCE !

: SFIELD-STORAGE-DISJOINT? ( address bytes -- flag )
    2DUP USF-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    _SFIELD-OWNED-LIMIT @ DUP _SFIELD-OWNED-START U< IF
        DROP 2DROP 0 EXIT
    THEN
    _SFIELD-OWNED-START - _SFIELD-OWNED-START SWAP MSPAN-OVERLAP? 0= ;

: _SFIELD-GENUINE? ( widget -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP _SFIELD-DESC-SIZE SFIELD-STORAGE-DISJOINT? 0= IF DROP 0 EXIT THEN
    DUP WDG-TYPE WDG-T-STATUS-FIELD <> IF DROP 0 EXIT THEN
    DUP _WDG-O-DRAW-XT + @ ['] _SFIELD-DRAW <> IF DROP 0 EXIT THEN
    DUP _WDG-O-HANDLE-XT + @ ['] _SFIELD-HANDLE <> IF DROP 0 EXIT THEN
    DUP _SFIELD-O-INSTANCE + @ 0= IF DROP 0 EXIT THEN
    WDG-REGION DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    RGN-SIZE SFIELD-STORAGE-DISJOINT? ;

: _SFIELD-REGION-MATCHES? ( model widget -- flag )
    WDG-REGION DUP RGN-H 1 <> IF 2DROP 0 EXIT THEN
    RGN-W SWAP USF-WIDTH@ = ;

: _SFIELD-BOUND? ( widget -- flag )
    DUP _SFIELD-GENUINE? 0= IF DROP 0 EXIT THEN
    DUP _SFIELD-O-MODEL-A + @ OVER _SFIELD-O-MODEL-U + @
        USF-VALIDATE USF-S-OK <> IF DROP 0 EXIT THEN
    DUP _SFIELD-O-MODEL-A + @ SWAP _SFIELD-REGION-MATCHES? ;

VARIABLE _SFIELD-SD-A
VARIABLE _SFIELD-SD-U
VARIABLE _SFIELD-SD-W

: SFIELD-STATUS-FIELD-STORAGE-DISJOINT?
    ( address bytes widget -- flag )
    >R 2DUP SFIELD-STORAGE-DISJOINT? 0= IF 2DROP R> DROP 0 EXIT THEN
    R@ _SFIELD-GENUINE? 0= IF 2DROP R> DROP 0 EXIT THEN
    _SFIELD-SD-U ! _SFIELD-SD-A ! R> _SFIELD-SD-W !
    _SFIELD-SD-A @ _SFIELD-SD-U @
        _SFIELD-SD-W @ _SFIELD-DESC-SIZE MSPAN-OVERLAP? IF 0 EXIT THEN
    _SFIELD-SD-A @ _SFIELD-SD-U @
        _SFIELD-SD-W @ WDG-REGION RGN-SIZE MSPAN-OVERLAP? IF 0 EXIT THEN
    _SFIELD-SD-W @ _SFIELD-O-MODEL-A + @ ?DUP IF
        _SFIELD-SD-A @ _SFIELD-SD-U @ ROT
        _SFIELD-SD-W @ _SFIELD-O-MODEL-U + @ MSPAN-OVERLAP? IF 0 EXIT THEN
    THEN -1 ;

: SFIELD-NEW ( region -- widget )
    DUP 0= ABORT" SFIELD-NEW: region"
    DUP 7 AND ABORT" SFIELD-NEW: region alignment"
    DUP RGN-SIZE SFIELD-STORAGE-DISJOINT? 0= ABORT" SFIELD-NEW: region span"
    _SFIELD-DESC-SIZE ALLOCATE 0<> ABORT" SFIELD-NEW: alloc"
    WDG-T-STATUS-FIELD OVER _WDG-O-TYPE + !
    SWAP OVER _WDG-O-REGION + !
    ['] _SFIELD-DRAW OVER _WDG-O-DRAW-XT + !
    ['] _SFIELD-HANDLE OVER _WDG-O-HANDLE-XT + !
    WDG-F-VISIBLE WDG-F-DIRTY OR OVER _WDG-O-FLAGS + !
    0 OVER _SFIELD-O-MODEL-A + !
    0 OVER _SFIELD-O-MODEL-U + !
    _SFIELD-NEXT-INSTANCE @ DUP -1 = IF DROP 1 ELSE 1+ THEN
    DUP _SFIELD-NEXT-INSTANCE ! OVER _SFIELD-O-INSTANCE + ! ;

VARIABLE _SFIELD-B-A
VARIABLE _SFIELD-B-U
VARIABLE _SFIELD-B-W

: SFIELD-BIND ( model bytes widget -- status )
    2 PICK 2 PICK SFIELD-STORAGE-DISJOINT? 0= IF
        2DROP DROP SFIELD-S-INVALID EXIT
    THEN
    DUP _SFIELD-GENUINE? 0= IF 2DROP DROP SFIELD-S-INVALID EXIT THEN
    _SFIELD-B-W ! _SFIELD-B-U ! _SFIELD-B-A !
    _SFIELD-B-A @ _SFIELD-B-U @ _SFIELD-B-W @ _SFIELD-DESC-SIZE
        MSPAN-OVERLAP? IF SFIELD-S-INVALID EXIT THEN
    _SFIELD-B-A @ _SFIELD-B-U @ _SFIELD-B-W @ WDG-REGION RGN-SIZE
        MSPAN-OVERLAP? IF SFIELD-S-INVALID EXIT THEN
    _SFIELD-B-A @ _SFIELD-B-U @ USF-VALIDATE DUP IF EXIT THEN DROP
    _SFIELD-B-A @ _SFIELD-B-W @ _SFIELD-REGION-MATCHES? 0= IF
        SFIELD-S-INVALID EXIT
    THEN
    _SFIELD-B-A @ _SFIELD-B-W @ _SFIELD-O-MODEL-A + !
    _SFIELD-B-U @ _SFIELD-B-W @ _SFIELD-O-MODEL-U + !
    _SFIELD-B-W @ WDG-DIRTY SFIELD-S-OK ;

: SFIELD-UNBIND ( widget -- )
    DUP _SFIELD-GENUINE? 0= IF DROP EXIT THEN
    0 OVER _SFIELD-O-MODEL-A + !
    0 OVER _SFIELD-O-MODEL-U + ! WDG-DIRTY ;

: SFIELD-INSTANCE@ ( widget -- token|0 )
    DUP _SFIELD-GENUINE? 0= IF DROP 0 EXIT THEN
    _SFIELD-O-INSTANCE + @ ;

: SFIELD-FREE ( widget -- )
    DUP _SFIELD-GENUINE? 0= IF DROP EXIT THEN
    0 OVER _SFIELD-O-INSTANCE + ! FREE ;

\ Each text slot is an ordinary one-row DRW-TEXT paragraph, independently
\ clipped before paint.  No padding or width transfer between the slots.
\ UIDL's direct status values can share this primitive with their resolved
\ row/column while mounted widgets use row zero in their active region.
: SFIELD-DRAW-SLOT ( address bytes row column width -- )
    DUP 0> 0= IF DROP 2DROP 2DROP EXIT THEN
    >R 2DUP ['] DRW-TEXT -ROT 1 R> DRW-WITH-CLIP ;

VARIABLE _SFIELD-D-MODEL

: _SFIELD-SEVERITY-STYLE ( severity -- )
    CASE
        1 OF 6 DRW-FG! ENDOF
        2 OF 2 DRW-FG! ENDOF
        3 OF 3 DRW-FG! ENDOF
        4 OF 1 DRW-FG! ENDOF
    ENDCASE ;

: _SFIELD-DRAW-IMPL ( widget -- )
    DUP _SFIELD-BOUND? 0= IF DROP EXIT THEN
    DUP WDG-VISIBLE? 0= IF DROP EXIT THEN
    _SFIELD-O-MODEL-A + @ DUP USF-FLAGS@ USF-F-VISIBLE AND 0= IF
        DROP EXIT
    THEN _SFIELD-D-MODEL !
    DRW-FG@ >R DRW-ATTR@ >R
    _SFIELD-D-MODEL @ USF-SEVERITY@ _SFIELD-SEVERITY-STYLE
    _SFIELD-D-MODEL @ USF-FLAGS@ USF-F-EMPHASIZED AND IF
        DRW-ATTR@ CELL-A-BOLD OR DRW-ATTR!
    THEN
    32 0 0 _SFIELD-D-MODEL @ USF-WIDTH@ DRW-HLINE
    _SFIELD-D-MODEL @ USF-LABEL@ 0 0
        _SFIELD-D-MODEL @ USF-LABEL-COLS@ SFIELD-DRAW-SLOT
    _SFIELD-D-MODEL @ USF-VALUE@ 0
        _SFIELD-D-MODEL @ USF-LABEL-COLS@
        _SFIELD-D-MODEL @ USF-WIDTH@ OVER - SFIELD-DRAW-SLOT
    R> DRW-ATTR! R> DRW-FG! ;

: _SFIELD-HANDLE-IMPL ( event widget -- consumed? ) 2DROP 0 ;
' _SFIELD-DRAW-IMPL IS _SFIELD-DRAW
' _SFIELD-HANDLE-IMPL IS _SFIELD-HANDLE

VARIABLE _SFIELD-C-DST
VARIABLE _SFIELD-C-CAP
VARIABLE _SFIELD-C-W
VARIABLE _SFIELD-C-U

: SFIELD-STATUS-FIELD-CAPTURE ( destination capacity widget -- bytes status )
    2 PICK 2 PICK SFIELD-STORAGE-DISJOINT? 0= IF
        2DROP DROP 0 SFIELD-S-INVALID EXIT
    THEN
    DUP _SFIELD-BOUND? 0= IF 2DROP DROP 0 SFIELD-S-INVALID EXIT THEN
    _SFIELD-C-W ! _SFIELD-C-CAP ! _SFIELD-C-DST !
    _SFIELD-C-W @ _SFIELD-O-MODEL-U + @ _SFIELD-C-U !
    _SFIELD-C-DST @ 0= IF
        _SFIELD-C-CAP @ IF 0 SFIELD-S-INVALID EXIT THEN
        _SFIELD-C-U @ SFIELD-S-OK EXIT
    THEN
    _SFIELD-C-DST @ 7 AND IF 0 SFIELD-S-INVALID EXIT THEN
    _SFIELD-C-DST @ _SFIELD-C-CAP @ _SFIELD-C-W @
        SFIELD-STATUS-FIELD-STORAGE-DISJOINT? 0= IF 0 SFIELD-S-INVALID EXIT THEN
    _SFIELD-C-CAP @ _SFIELD-C-U @ U< IF 0 SFIELD-S-CAPACITY EXIT THEN
    _SFIELD-C-W @ _SFIELD-O-MODEL-A + @
        _SFIELD-C-DST @ _SFIELD-C-U @ MOVE
    \ Widget visibility composes with model visibility; no enabled or
    \ interactive state is introduced into this static object.
    _SFIELD-C-W @ WDG-VISIBLE? 0= IF
        _SFIELD-C-DST @ USF-FLAGS@
        USF-F-VISIBLE INVERT AND _SFIELD-C-DST @ USF-FLAGS-OFFSET + !
    THEN
    _SFIELD-C-U @ SFIELD-S-OK ;

: SFIELD-STATUS-FIELD-MEASURE ( widget -- bytes status )
    0 0 ROT SFIELD-STATUS-FIELD-CAPTURE ;

