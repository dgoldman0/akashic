\ =====================================================================
\ field.f -- Ordinary typed field widget over an immutable UFLD value
\ =====================================================================
\ The widget paints and reports intents.  The application owns editing,
\ validation policy, selection and replacement of the authoritative value.
\ Descriptor96: header40, model-a40/u48, instance56, activate64, adjust72,
\ normal packed style80 and selected packed style88.

PROVIDED akashic-tui-field
REQUIRE ../widget.f
REQUIRE ../draw.f
REQUIRE ../keys.f
REQUIRE ../field-model.f

UFLD-S-OK CONSTANT FLD-S-OK
UFLD-S-UNSUPPORTED CONSTANT FLD-S-UNSUPPORTED
UFLD-S-CAPACITY CONSTANT FLD-S-CAPACITY
UFLD-S-INVALID CONSTANT FLD-S-INVALID
40 CONSTANT _FLD-O-MODEL-A
48 CONSTANT _FLD-O-MODEL-U
56 CONSTANT _FLD-O-INSTANCE
64 CONSTANT _FLD-O-ACTIVATE
72 CONSTANT _FLD-O-ADJUST
80 CONSTANT _FLD-O-NORMAL
88 CONSTANT _FLD-O-SELECTED
96 CONSTANT _FLD-DESC-SIZE

CREATE _FLD-OWNED-START
VARIABLE _FLD-OWNED-LIMIT
0 _FLD-OWNED-LIMIT !
DEFER _FLD-DRAW
DEFER _FLD-HANDLE
VARIABLE _FLD-NEXT-INSTANCE
0 _FLD-NEXT-INSTANCE !

: FLD-STORAGE-DISJOINT? ( address bytes -- flag )
    2DUP UFLD-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    _FLD-OWNED-LIMIT @ DUP _FLD-OWNED-START U< IF DROP 2DROP 0 EXIT THEN
    _FLD-OWNED-START - _FLD-OWNED-START SWAP MSPAN-OVERLAP? 0= ;

: _FLD-GENUINE? ( widget -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP _FLD-DESC-SIZE FLD-STORAGE-DISJOINT? 0= IF DROP 0 EXIT THEN
    DUP WDG-TYPE WDG-T-FIELD <> IF DROP 0 EXIT THEN
    DUP _WDG-O-DRAW-XT + @ ['] _FLD-DRAW <> IF DROP 0 EXIT THEN
    DUP _WDG-O-HANDLE-XT + @ ['] _FLD-HANDLE <> IF DROP 0 EXIT THEN
    DUP _FLD-O-INSTANCE + @ 0= IF DROP 0 EXIT THEN
    WDG-REGION DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    RGN-SIZE FLD-STORAGE-DISJOINT? ;

: _FLD-REGION-MATCHES? ( model widget -- flag )
    WDG-REGION >R
    DUP UFLD-WIDTH@ R@ RGN-W =
    SWAP UFLD-HEIGHT@ R> RGN-H = AND ;

: _FLD-BOUND? ( widget -- flag )
    DUP _FLD-GENUINE? 0= IF DROP 0 EXIT THEN
    DUP _FLD-O-MODEL-A + @ OVER _FLD-O-MODEL-U + @
        UFLD-VALIDATE UFLD-S-OK <> IF DROP 0 EXIT THEN
    DUP _FLD-O-MODEL-A + @ SWAP _FLD-REGION-MATCHES? ;

VARIABLE _FLD-SD-A VARIABLE _FLD-SD-U VARIABLE _FLD-SD-W
: FLD-FIELD-STORAGE-DISJOINT? ( address bytes widget -- flag )
    >R 2DUP FLD-STORAGE-DISJOINT? 0= IF 2DROP R> DROP 0 EXIT THEN
    R@ _FLD-GENUINE? 0= IF 2DROP R> DROP 0 EXIT THEN
    _FLD-SD-U ! _FLD-SD-A ! R> _FLD-SD-W !
    _FLD-SD-A @ _FLD-SD-U @ _FLD-SD-W @ _FLD-DESC-SIZE
        MSPAN-OVERLAP? IF 0 EXIT THEN
    _FLD-SD-A @ _FLD-SD-U @ _FLD-SD-W @ WDG-REGION RGN-SIZE
        MSPAN-OVERLAP? IF 0 EXIT THEN
    _FLD-SD-W @ _FLD-O-MODEL-A + @ ?DUP IF
        _FLD-SD-A @ _FLD-SD-U @ ROT _FLD-SD-W @ _FLD-O-MODEL-U + @
            MSPAN-OVERLAP? IF 0 EXIT THEN
    THEN -1 ;

: _FLD-PACK-STYLE ( fg bg attributes -- packed )
    16 LSHIFT >R 8 LSHIFT OR R> OR ;
: _FLD-USE-STYLE ( packed -- )
    DUP 255 AND OVER 8 RSHIFT 255 AND ROT 16 RSHIFT DRW-STYLE! ;

: FLD-NEW ( region -- widget )
    DUP 0= ABORT" FLD-NEW: region"
    DUP 7 AND ABORT" FLD-NEW: region alignment"
    DUP RGN-SIZE FLD-STORAGE-DISJOINT? 0= ABORT" FLD-NEW: region span"
    _FLD-DESC-SIZE ALLOCATE 0<> ABORT" FLD-NEW: alloc"
    WDG-T-FIELD OVER _WDG-O-TYPE + !
    SWAP OVER _WDG-O-REGION + !
    ['] _FLD-DRAW OVER _WDG-O-DRAW-XT + !
    ['] _FLD-HANDLE OVER _WDG-O-HANDLE-XT + !
    WDG-F-VISIBLE WDG-F-DIRTY OR OVER _WDG-O-FLAGS + !
    0 OVER _FLD-O-MODEL-A + ! 0 OVER _FLD-O-MODEL-U + !
    0 OVER _FLD-O-ACTIVATE + ! 0 OVER _FLD-O-ADJUST + !
    7 0 0 _FLD-PACK-STYLE OVER _FLD-O-NORMAL + !
    7 0 CELL-A-REVERSE _FLD-PACK-STYLE OVER _FLD-O-SELECTED + !
    _FLD-NEXT-INSTANCE @ DUP -1 = IF DROP 1 ELSE 1+ THEN
    DUP _FLD-NEXT-INSTANCE ! OVER _FLD-O-INSTANCE + ! ;

VARIABLE _FLD-B-A VARIABLE _FLD-B-U VARIABLE _FLD-B-W
: FLD-BIND ( model bytes widget -- status )
    2 PICK 2 PICK FLD-STORAGE-DISJOINT? 0= IF 2DROP DROP FLD-S-INVALID EXIT THEN
    DUP _FLD-GENUINE? 0= IF 2DROP DROP FLD-S-INVALID EXIT THEN
    _FLD-B-W ! _FLD-B-U ! _FLD-B-A !
    _FLD-B-A @ _FLD-B-U @ _FLD-B-W @ _FLD-DESC-SIZE
        MSPAN-OVERLAP? IF FLD-S-INVALID EXIT THEN
    _FLD-B-A @ _FLD-B-U @ _FLD-B-W @ WDG-REGION RGN-SIZE
        MSPAN-OVERLAP? IF FLD-S-INVALID EXIT THEN
    _FLD-B-A @ _FLD-B-U @ UFLD-VALIDATE DUP IF EXIT THEN DROP
    _FLD-B-A @ _FLD-B-W @ _FLD-REGION-MATCHES? 0= IF FLD-S-INVALID EXIT THEN
    _FLD-B-A @ _FLD-B-W @ _FLD-O-MODEL-A + !
    _FLD-B-U @ _FLD-B-W @ _FLD-O-MODEL-U + !
    _FLD-B-W @ WDG-DIRTY FLD-S-OK ;

: FLD-UNBIND ( widget -- )
    DUP _FLD-GENUINE? 0= IF DROP EXIT THEN
    0 OVER _FLD-O-MODEL-A + ! 0 OVER _FLD-O-MODEL-U + ! WDG-DIRTY ;
: FLD-INSTANCE@ ( widget -- token|0 )
    DUP _FLD-GENUINE? 0= IF DROP 0 EXIT THEN _FLD-O-INSTANCE + @ ;
: FLD-MODEL@ ( widget -- model bytes )
    DUP _FLD-BOUND? 0= IF DROP 0 0 EXIT THEN
    DUP _FLD-O-MODEL-A + @ SWAP _FLD-O-MODEL-U + @ ;
: FLD-FREE ( widget -- )
    DUP _FLD-GENUINE? 0= IF DROP EXIT THEN
    0 OVER _FLD-O-INSTANCE + ! FREE ;
: FLD-ON-ACTIVATE ( xt widget -- )
    DUP _FLD-GENUINE? 0= IF 2DROP EXIT THEN _FLD-O-ACTIVATE + ! ;
: FLD-ON-ADJUST ( xt widget -- )
    DUP _FLD-GENUINE? 0= IF 2DROP EXIT THEN _FLD-O-ADJUST + ! ;
: FLD-STYLE! ( fg bg attributes widget -- )
    DUP _FLD-GENUINE? 0= IF 2DROP 2DROP EXIT THEN
    >R _FLD-PACK-STYLE R@ _FLD-O-NORMAL + ! R> WDG-DIRTY ;
: FLD-SELECTED-STYLE! ( fg bg attributes widget -- )
    DUP _FLD-GENUINE? 0= IF 2DROP 2DROP EXIT THEN
    >R _FLD-PACK-STYLE R@ _FLD-O-SELECTED + ! R> WDG-DIRTY ;

\ Min-safe decimal: retain a negative magnitude and negate only digits.
CREATE _FLD-NUMBER 24 ALLOT
VARIABLE _FLD-N-CURSOR VARIABLE _FLD-N-NEGATIVE
: _FLD-NUMBER-TEXT ( signed -- address bytes )
    DUP 0< DUP _FLD-N-NEGATIVE ! 0= IF NEGATE THEN
    _FLD-NUMBER 24 + _FLD-N-CURSOR !
    BEGIN
        10 /MOD SWAP NEGATE [CHAR] 0 +
        -1 _FLD-N-CURSOR +! _FLD-N-CURSOR @ C!
        DUP 0=
    UNTIL DROP
    _FLD-N-NEGATIVE @ IF
        -1 _FLD-N-CURSOR +! [CHAR] - _FLD-N-CURSOR @ C!
    THEN
    _FLD-N-CURSOR @ _FLD-NUMBER 24 + OVER - ;

: _FLD-TEXT-SLOT ( address bytes row column width -- )
    DUP 0> 0= IF DROP 2DROP 2DROP EXIT THEN
    >R 2DUP ['] DRW-TEXT -ROT 1 R> DRW-WITH-CLIP ;
: _FLD-RIGHT-SLOT ( address bytes row column width -- )
    DUP 0> 0= IF DROP 2DROP 2DROP EXIT THEN
    >R 2DUP R@ -ROT ['] DRW-TEXT-RIGHT -ROT 1 R> DRW-WITH-CLIP ;

VARIABLE _FLD-D-W VARIABLE _FLD-D-M
: _FLD-DRAW-IMPL ( widget -- )
    DUP _FLD-BOUND? 0= IF DROP EXIT THEN
    DUP WDG-VISIBLE? 0= IF DROP EXIT THEN
    DUP _FLD-D-W ! _FLD-O-MODEL-A + @ DUP _FLD-D-M !
    UFLD-STATE@ UFLD-STATE-VISIBLE AND 0= IF EXIT THEN
    DRW-FG@ >R _DRW-BG @ >R DRW-ATTR@ >R
    _FLD-D-M @ UFLD-STATE@ UFLD-STATE-SELECTED AND
    _FLD-D-W @ WDG-DISABLED? 0= AND IF
        _FLD-D-W @ _FLD-O-SELECTED + @
    ELSE _FLD-D-W @ _FLD-O-NORMAL + @ THEN _FLD-USE-STYLE
    _FLD-D-W @ WDG-DISABLED?
    _FLD-D-M @ UFLD-STATE@ UFLD-STATE-ENABLED AND 0= OR IF
        DRW-ATTR@ CELL-A-DIM OR DRW-ATTR!
    THEN
    32 0 0 _FLD-D-M @ UFLD-HEIGHT@ _FLD-D-M @ UFLD-WIDTH@ DRW-FILL-RECT
    _FLD-D-M @ UFLD-LABEL@
        _FLD-D-M @ UFLD-LABEL-ROW@
        _FLD-D-M @ UFLD-LABEL-HEIGHT@ 1- 0 MAX 2/ +
        _FLD-D-M @ UFLD-LABEL-COLUMN@ _FLD-D-M @ UFLD-LABEL-WIDTH@
        _FLD-TEXT-SLOT
    _FLD-D-M @ UFLD-KIND@ CASE
        UFLD-K-INTEGER OF _FLD-D-M @ UFLD-VALUE@ _FLD-NUMBER-TEXT ENDOF
        UFLD-K-CHOICE OF _FLD-D-M @ UFLD-CHOICE-SELECTED@ UFLD-CHOICE-LABEL@ ENDOF
        UFLD-K-TEXT OF _FLD-D-M @ UFLD-TEXT@ ENDOF
    ENDCASE
    _FLD-D-M @ UFLD-VALUE-ROW@
        _FLD-D-M @ UFLD-VALUE-HEIGHT@ 1- 2/ +
        _FLD-D-M @ UFLD-VALUE-COLUMN@ _FLD-D-M @ UFLD-VALUE-WIDTH@
    _FLD-D-M @ UFLD-KIND@ UFLD-K-INTEGER = IF
        _FLD-RIGHT-SLOT
    ELSE _FLD-TEXT-SLOT THEN
    R> DRW-ATTR! R> DRW-BG! R> DRW-FG! ;

: _FLD-EDITABLE? ( widget -- flag )
    DUP _FLD-BOUND? 0= IF DROP 0 EXIT THEN
    DUP WDG-VISIBLE? 0= OVER WDG-DISABLED? OR IF DROP 0 EXIT THEN
    _FLD-O-MODEL-A + @ DUP UFLD-STATE@ 3 AND 3 <> IF DROP 0 EXIT THEN
    UFLD-FLAGS@ UFLD-F-READ-ONLY AND 0= ;
: FLD-ACTIVATE ( widget -- consumed? )
    DUP _FLD-EDITABLE? 0= IF DROP 0 EXIT THEN
    DUP _FLD-O-ACTIVATE + @ ?DUP 0= IF DROP 0 EXIT THEN EXECUTE -1 ;
: FLD-ADJUST ( signed-count widget -- consumed? )
    OVER 0= IF 2DROP 0 EXIT THEN
    DUP _FLD-EDITABLE? 0= IF 2DROP 0 EXIT THEN
    DUP _FLD-O-MODEL-A + @ UFLD-KIND@ UFLD-K-TEXT = IF 2DROP 0 EXIT THEN
    DUP _FLD-O-ADJUST + @ ?DUP 0= IF 2DROP 0 EXIT THEN EXECUTE -1 ;

VARIABLE _FLD-P-ROW VARIABLE _FLD-P-COL VARIABLE _FLD-P-M
: FLD-VALUE-CONTAINS? ( screen-row screen-column widget -- flag )
    DUP _FLD-BOUND? 0= IF 2DROP DROP 0 EXIT THEN
    DUP WDG-REGION RGN-COL ROT SWAP - _FLD-P-COL !
    DUP WDG-REGION RGN-ROW ROT SWAP - _FLD-P-ROW !
    _FLD-O-MODEL-A + @ _FLD-P-M !
    _FLD-P-ROW @ _FLD-P-M @ UFLD-VALUE-ROW@
        DUP _FLD-P-M @ UFLD-VALUE-HEIGHT@ + WITHIN
    _FLD-P-COL @ _FLD-P-M @ UFLD-VALUE-COLUMN@
        DUP _FLD-P-M @ UFLD-VALUE-WIDTH@ + WITHIN AND ;

: _FLD-POINTER ( event widget -- consumed? )
    >R DUP 16 + @ DUP 16 RSHIFT SWAP 0xFFFF AND
        R@ FLD-VALUE-CONTAINS? 0= IF DROP R> DROP 0 EXIT THEN
    8 + @ KEY-MOUSE-BUTTON CASE
        KEY-MOUSE-LEFT OF R> FLD-ACTIVATE EXIT ENDOF
        KEY-MOUSE-SCROLL-UP OF 1 R> FLD-ADJUST EXIT ENDOF
        KEY-MOUSE-SCROLL-DN OF -1 R> FLD-ADJUST EXIT ENDOF
        KEY-MOUSE-FIELD-ADJUST OF
            KEY-MOUSE-FIELD-REVISION @
            R@ _FLD-O-MODEL-A + @ UFLD-REVISION@ <> IF
                R> DROP 0 EXIT
            THEN
            KEY-MOUSE-FIELD-ADJUSTMENT @ R> FLD-ADJUST EXIT
        ENDOF
    ENDCASE R> DROP 0 ;
: _FLD-HANDLE-IMPL ( event widget -- consumed? )
    OVER @ KEY-T-MOUSE = IF _FLD-POINTER EXIT THEN
    >R DUP @ KEY-T-SPECIAL <> IF DROP R> DROP 0 EXIT THEN
    8 + @ CASE
        KEY-ENTER OF R> FLD-ACTIVATE EXIT ENDOF
        KEY-F2 OF R> FLD-ACTIVATE EXIT ENDOF
        KEY-LEFT OF -1 R> FLD-ADJUST EXIT ENDOF
        KEY-RIGHT OF 1 R> FLD-ADJUST EXIT ENDOF
    ENDCASE R> DROP 0 ;
' _FLD-DRAW-IMPL IS _FLD-DRAW
' _FLD-HANDLE-IMPL IS _FLD-HANDLE

VARIABLE _FLD-C-A VARIABLE _FLD-C-U VARIABLE _FLD-C-W VARIABLE _FLD-C-NEED
: FLD-FIELD-CAPTURE ( destination capacity widget -- bytes status )
    2 PICK 2 PICK FLD-STORAGE-DISJOINT? 0= IF 2DROP DROP 0 FLD-S-INVALID EXIT THEN
    DUP _FLD-BOUND? 0= IF 2DROP DROP 0 FLD-S-INVALID EXIT THEN
    _FLD-C-W ! _FLD-C-U ! _FLD-C-A !
    _FLD-C-W @ _FLD-O-MODEL-U + @ _FLD-C-NEED !
    _FLD-C-A @ 0= IF
        _FLD-C-U @ IF 0 FLD-S-INVALID EXIT THEN
        _FLD-C-NEED @ FLD-S-OK EXIT
    THEN
    _FLD-C-A @ 7 AND IF 0 FLD-S-INVALID EXIT THEN
    _FLD-C-A @ _FLD-C-U @ _FLD-C-W @ FLD-FIELD-STORAGE-DISJOINT? 0= IF
        0 FLD-S-INVALID EXIT
    THEN
    _FLD-C-U @ _FLD-C-NEED @ U< IF 0 FLD-S-CAPACITY EXIT THEN
    _FLD-C-W @ _FLD-O-MODEL-A + @ _FLD-C-A @ _FLD-C-NEED @ MOVE
    _FLD-C-A @ UFLD-STATE@
    _FLD-C-W @ WDG-VISIBLE? 0= IF UFLD-STATE-VISIBLE INVERT AND THEN
    _FLD-C-W @ WDG-DISABLED? IF UFLD-STATE-ENABLED INVERT AND THEN
    DUP 3 AND 3 <> IF UFLD-STATE-SELECTED INVERT AND THEN
    _FLD-C-A @ UFLD-STATE-OFFSET + !
    _FLD-C-NEED @ FLD-S-OK ;
: FLD-FIELD-MEASURE ( widget -- bytes status ) 0 0 ROT FLD-FIELD-CAPTURE ;

