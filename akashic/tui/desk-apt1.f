    OVER _A1D-U32-POSITIVE? 0= ABORT" desk-apt1: invalid capacity"
    DUP _A1D-U32-POSITIVE? 0= ABORT" desk-apt1: invalid item size"
    OVER + DUP ROT U< ABORT" desk-apt1: storage size overflow"
    DUP _A1D-U32-POSITIVE? 0=
