    DUP _UFLD-C-N @ >= IF _UFLD-C-N @ - THEN
    _UFLD-C-M @ UFLD-CHOICE-FIRST SWAP 0 ?DO UFLD-CHOICE-NEXT LOOP
    UFLD-CHOICE-VALUE@ UFLD-S-OK ;

