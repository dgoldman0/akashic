    _UFLD-I-STEP @ 0> 0= _UFLD-I-MIN @ _UFLD-I-V @ > OR
    _UFLD-I-V @ _UFLD-I-MAX @ > OR IF 0 UFLD-S-INVALID EXIT THEN
    _UFLD-I-ADJ @ DUP 0< IF NEGATE THEN _UFLD-I-STEP @ UM*
    SWAP _UFLD-I-LO ! IF
        _UFLD-I-ADJ @ 0< IF _UFLD-I-MIN @ ELSE _UFLD-I-MAX @ THEN UFLD-S-OK EXIT
    THEN
    _UFLD-I-ADJ @ 0< IF
        _UFLD-I-LO @ _UFLD-I-V @ _UFLD-I-MIN @ - U> IF _UFLD-I-MIN @
        ELSE _UFLD-I-V @ _UFLD-I-LO @ - THEN
    ELSE
        _UFLD-I-LO @ _UFLD-I-MAX @ _UFLD-I-V @ - U> IF _UFLD-I-MAX @
        ELSE _UFLD-I-V @ _UFLD-I-LO @ + THEN
    THEN UFLD-S-OK ;

