\ Accessors, including SELECTED@, require a previously validated model.
: UFLD-CHOICE-SELECTED@ ( model -- record|0 )
    DUP UFLD-KIND@ UFLD-K-CHOICE <> IF DROP 0 EXIT THEN
    DUP UFLD-VALUE@ SWAP DUP UFLD-CHOICE-COUNT@ SWAP UFLD-CHOICE-FIRST SWAP
    0 ?DO DUP UFLD-CHOICE-VALUE@ 2 PICK = IF NIP UNLOOP EXIT THEN
        UFLD-CHOICE-NEXT LOOP 2DROP 0 ;
: UFLD-UTF8-BYTES@ ( validated-model -- bytes )
    DUP UFLD-LABEL-BYTES@ OVER UFLD-TEXT-BYTES@ + SWAP
    DUP UFLD-CHOICE-COUNT@ SWAP UFLD-CHOICE-FIRST SWAP
    0 ?DO DUP 16 + @ ROT + SWAP UFLD-CHOICE-NEXT LOOP DROP ;

: UFLD-STORAGE-DISJOINT? ( address bytes -- flag )
    2DUP USF-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    _UFLD-OWNED-LIMIT @ DUP _UFLD-OWNED-START U< IF DROP 2DROP 0 EXIT THEN
    _UFLD-OWNED-START - _UFLD-OWNED-START SWAP MSPAN-OVERLAP? 0= ;
: _UFLD-U32? ( n -- flag ) 0x100000000 U< ;
: _UFLD-POS32? ( n -- flag ) DUP 0<> SWAP _UFLD-U32? AND ;
: _UFLD-COORD? ( n -- flag ) 0x80000000 U< ;
: _UFLD-ZERO? ( a u -- flag )
    0 ?DO DUP I + C@ IF DROP 0 UNLOOP EXIT THEN LOOP DROP -1 ;
: _UFLD-ALIGNED-SPAN? ( a u -- flag )
    OVER DUP 0= SWAP 7 AND OR IF 2DROP 0 EXIT THEN UFLD-STORAGE-DISJOINT? ;

