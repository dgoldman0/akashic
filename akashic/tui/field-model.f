: _UFLD-BASE? ( -- flag )
    _UFLD-V-M @ UFLD-BYTES@ _UFLD-V-U @ <> IF 0 EXIT THEN
    _UFLD-V-M @ UFLD-KEY@ 0= _UFLD-V-M @ UFLD-REVISION@ 0= OR IF 0 EXIT THEN
    _UFLD-V-M @ UFLD-WIDTH@ _UFLD-POS32? 0=
    _UFLD-V-M @ UFLD-HEIGHT@ _UFLD-POS32? 0= OR IF 0 EXIT THEN
    _UFLD-V-M @ UFLD-STATE@ DUP 7 INVERT AND IF DROP 0 EXIT THEN
    DUP UFLD-STATE-SELECTED AND IF 3 AND 3 <> IF 0 EXIT THEN ELSE DROP THEN
    _UFLD-V-M @ UFLD-FLAGS@ UFLD-F-READ-ONLY INVERT AND IF 0 EXIT THEN
    _UFLD-V-M @ UFLD-LABEL-BYTES@ _UFLD-U32? 0=
    _UFLD-V-M @ UFLD-TEXT-BYTES@ _UFLD-U32? 0= OR
    _UFLD-V-M @ UFLD-CHOICE-COUNT@ _UFLD-U32? 0= OR 0= ;

: _UFLD-RECTS? ( -- flag )
    _UFLD-V-M @ UFLD-LABEL-ROW@ DUP _UFLD-V-LR ! _UFLD-COORD? 0= IF 0 EXIT THEN
    _UFLD-V-M @ UFLD-LABEL-COLUMN@ DUP _UFLD-V-LC ! _UFLD-COORD? 0= IF 0 EXIT THEN
    _UFLD-V-M @ UFLD-LABEL-HEIGHT@ DUP _UFLD-V-LH ! _UFLD-U32? 0= IF 0 EXIT THEN
    _UFLD-V-M @ UFLD-LABEL-WIDTH@ DUP _UFLD-V-LW ! _UFLD-U32? 0= IF 0 EXIT THEN
    _UFLD-V-M @ UFLD-VALUE-ROW@ DUP _UFLD-V-VR ! _UFLD-COORD? 0= IF 0 EXIT THEN
    _UFLD-V-M @ UFLD-VALUE-COLUMN@ DUP _UFLD-V-VC ! _UFLD-COORD? 0= IF 0 EXIT THEN
    _UFLD-V-M @ UFLD-VALUE-HEIGHT@ DUP _UFLD-V-VH ! _UFLD-POS32? 0= IF 0 EXIT THEN
    _UFLD-V-M @ UFLD-VALUE-WIDTH@ DUP _UFLD-V-VW ! _UFLD-POS32? 0= IF 0 EXIT THEN
    _UFLD-V-VR @ _UFLD-V-VH @ + _UFLD-V-M @ UFLD-HEIGHT@ U>
    _UFLD-V-VC @ _UFLD-V-VW @ + _UFLD-V-M @ UFLD-WIDTH@ U> OR IF 0 EXIT THEN
    _UFLD-V-LH @ _UFLD-V-LW @ OR 0= IF
        _UFLD-V-LR @ _UFLD-V-LC @ OR 0= EXIT
    THEN
    _UFLD-V-LH @ 0= _UFLD-V-LW @ 0= OR IF 0 EXIT THEN
    _UFLD-V-LR @ _UFLD-V-LH @ + _UFLD-V-M @ UFLD-HEIGHT@ U>
    _UFLD-V-LC @ _UFLD-V-LW @ + _UFLD-V-M @ UFLD-WIDTH@ U> OR IF 0 EXIT THEN
    _UFLD-V-LR @ _UFLD-V-VR @ _UFLD-V-VH @ + U<
    _UFLD-V-VR @ _UFLD-V-LR @ _UFLD-V-LH @ + U< AND
    _UFLD-V-LC @ _UFLD-V-VC @ _UFLD-V-VW @ + U< AND
    _UFLD-V-VC @ _UFLD-V-LC @ _UFLD-V-LW @ + U< AND 0= ;

\ Validate one padded string, advancing the bounded byte offset.
: _UFLD-V-STRING? ( bytes -- flag )
    DUP _UFLD-U32? 0= IF DROP 0 EXIT THEN _UFLD-V-N !
    _UFLD-V-N @ _UFLD-ALIGN8 _UFLD-V-U @ _UFLD-V-O @ - U> IF 0 EXIT THEN
    _UFLD-V-M @ _UFLD-V-O @ + _UFLD-V-N @ USF-TEXT? 0= IF 0 EXIT THEN
    _UFLD-V-M @ _UFLD-V-O @ + _UFLD-V-N @ +
    _UFLD-V-N @ _UFLD-ALIGN8 _UFLD-V-N @ - _UFLD-ZERO? 0= IF 0 EXIT THEN
    _UFLD-V-N @ _UFLD-ALIGN8 _UFLD-V-O +! -1 ;

: _UFLD-CHOICES? ( -- flag )
    _UFLD-V-M @ UFLD-CHOICE-COUNT@
    _UFLD-V-U @ _UFLD-V-O @ - UFLD-CHOICE-HEADER-SIZE / U> IF 0 EXIT THEN
    0 _UFLD-V-MATCHES !
    _UFLD-V-M @ UFLD-CHOICE-COUNT@ 0 ?DO
        _UFLD-V-U @ _UFLD-V-O @ - UFLD-CHOICE-HEADER-SIZE U< IF 0 UNLOOP EXIT THEN
        _UFLD-V-M @ _UFLD-V-O @ + _UFLD-V-R !
        _UFLD-V-R @ @ _UFLD-V-RU !
        _UFLD-V-R @ 16 + @ DUP 0= IF DROP 0 UNLOOP EXIT THEN
        DUP _UFLD-U32? 0= IF DROP 0 UNLOOP EXIT THEN
        _UFLD-ALIGN8 UFLD-CHOICE-HEADER-SIZE + _UFLD-V-RU @ <> IF 0 UNLOOP EXIT THEN
        _UFLD-V-RU @ _UFLD-V-U @ _UFLD-V-O @ - U> IF 0 UNLOOP EXIT THEN
        _UFLD-V-M @ UFLD-CHOICE-FIRST _UFLD-V-PRIOR !
        I 0 ?DO
            _UFLD-V-PRIOR @ UFLD-CHOICE-VALUE@ _UFLD-V-R @ UFLD-CHOICE-VALUE@ = IF
                0 UNLOOP UNLOOP EXIT
            THEN
            _UFLD-V-PRIOR @ UFLD-CHOICE-NEXT _UFLD-V-PRIOR !
        LOOP
        _UFLD-V-R @ UFLD-CHOICE-VALUE@ _UFLD-V-M @ UFLD-VALUE@ = IF
            1 _UFLD-V-MATCHES +!
        THEN
        UFLD-CHOICE-HEADER-SIZE _UFLD-V-O +!
        _UFLD-V-R @ 16 + @ _UFLD-V-STRING? 0= IF 0 UNLOOP EXIT THEN
    LOOP
    _UFLD-V-PHASE @ 4 = IF _UFLD-V-MATCHES @ 1 = ELSE -1 THEN ;

: _UFLD-CONTENT? ( -- flag )
    _UFLD-V-M @ UFLD-KIND@ CASE
        UFLD-K-INTEGER OF
            _UFLD-V-M @ UFLD-TEXT-BYTES@ _UFLD-V-M @ UFLD-CHOICE-COUNT@ OR IF 0 EXIT THEN
            _UFLD-V-M @ UFLD-STEP@ 0> 0= IF 0 EXIT THEN
            _UFLD-V-M @ UFLD-MINIMUM@ _UFLD-V-M @ UFLD-VALUE@ >
            _UFLD-V-M @ UFLD-VALUE@ _UFLD-V-M @ UFLD-MAXIMUM@ > OR 0=
        ENDOF
        UFLD-K-CHOICE OF
            _UFLD-V-M @ UFLD-MINIMUM@ _UFLD-V-M @ UFLD-MAXIMUM@ OR
            _UFLD-V-M @ UFLD-STEP@ OR _UFLD-V-M @ UFLD-TEXT-BYTES@ OR IF 0 EXIT THEN
            _UFLD-CHOICES?
        ENDOF
        UFLD-K-TEXT OF
            _UFLD-V-M @ UFLD-VALUE@ _UFLD-V-M @ UFLD-MINIMUM@ OR
            _UFLD-V-M @ UFLD-MAXIMUM@ OR _UFLD-V-M @ UFLD-STEP@ OR
            _UFLD-V-M @ UFLD-CHOICE-COUNT@ OR IF 0 EXIT THEN
            _UFLD-V-M @ UFLD-TEXT-BYTES@ _UFLD-V-STRING?
        ENDOF
        0 SWAP
    ENDCASE ;

\ Phases 1/2/3 validate inactive builder prefixes; 4 requires a complete value.
: _UFLD-VALIDATE ( model bytes phase -- status )
    >R 2DUP _UFLD-ALIGNED-SPAN? 0= IF 2DROP R> DROP UFLD-S-INVALID EXIT THEN
    DUP UFLD-HEADER-SIZE U< IF 2DROP R> DROP UFLD-S-INVALID EXIT THEN
    R> _UFLD-V-PHASE ! _UFLD-V-U ! _UFLD-V-M !
    _UFLD-V-M @ UFLD-ABI@ UFLD-ABI <> IF UFLD-S-UNSUPPORTED EXIT THEN
    _UFLD-V-M @ UFLD-KIND@ DUP 1 < SWAP 3 > OR IF UFLD-S-UNSUPPORTED EXIT THEN
    _UFLD-BASE? 0= IF UFLD-S-INVALID EXIT THEN
    UFLD-HEADER-SIZE _UFLD-V-O !
    _UFLD-V-PHASE @ 1 = IF
        _UFLD-V-M @ UFLD-HEADER-SIZE 56 - + 56 _UFLD-ZERO? 0= IF UFLD-S-INVALID EXIT THEN
        _UFLD-V-U @ UFLD-HEADER-SIZE = IF UFLD-S-OK ELSE UFLD-S-INVALID THEN EXIT
    THEN
    _UFLD-RECTS? 0= IF UFLD-S-INVALID EXIT THEN
    _UFLD-V-M @ UFLD-LABEL-BYTES@ 0= _UFLD-V-LH @ 0= <> IF UFLD-S-INVALID EXIT THEN
    _UFLD-V-M @ UFLD-LABEL-BYTES@ _UFLD-V-STRING? 0= IF UFLD-S-INVALID EXIT THEN
    _UFLD-V-PHASE @ 2 = IF
        _UFLD-V-M @ UFLD-VALUE-OFFSET + 32 _UFLD-ZERO? 0= IF UFLD-S-INVALID EXIT THEN
        _UFLD-V-M @ UFLD-TEXT-BYTES@ _UFLD-V-M @ UFLD-CHOICE-COUNT@ OR IF UFLD-S-INVALID EXIT THEN
    ELSE
        _UFLD-CONTENT? 0= IF UFLD-S-INVALID EXIT THEN
    THEN
    _UFLD-V-O @ _UFLD-V-U @ = IF UFLD-S-OK ELSE UFLD-S-INVALID THEN ;

: UFLD-VALIDATE ( model bytes -- status ) 4 _UFLD-VALIDATE ;

\ Builder descriptor: destination, capacity, used, phase, reserved.
: _UFLD-B-DESC? ( builder -- flag )
    UFLD-BUILDER-SIZE _UFLD-ALIGNED-SPAN? ;
: _UFLD-B? ( builder -- flag )
    DUP _UFLD-B-DESC? 0= IF DROP 0 EXIT THEN
    DUP 32 + @ IF DROP 0 EXIT THEN
    DUP 24 + @ 3 U> IF DROP 0 EXIT THEN
    DUP @ OVER 8 + @ _UFLD-ALIGNED-SPAN? 0= IF DROP 0 EXIT THEN
    DUP UFLD-BUILDER-SIZE 2 PICK @ 3 PICK 8 + @ MSPAN-OVERLAP? IF DROP 0 EXIT THEN
    DUP 16 + @ OVER 8 + @ U> IF DROP 0 EXIT THEN
    DUP 24 + @ 0= IF 16 + @ 0= EXIT THEN
    DUP @ OVER 16 + @ ROT 24 + @ _UFLD-VALIDATE UFLD-S-OK = ;
: _UFLD-PHASE? ( builder phase -- flag )
    >R DUP _UFLD-B? 0= IF DROP R> DROP 0 EXIT THEN 24 + @ R> = ;

VARIABLE _UFLD-B
VARIABLE _UFLD-M
VARIABLE _UFLD-CAP
VARIABLE _UFLD-USED
VARIABLE _UFLD-A VARIABLE _UFLD-U VARIABLE _UFLD-NEED
VARIABLE _UFLD-KEY VARIABLE _UFLD-KIND VARIABLE _UFLD-REV
VARIABLE _UFLD-W VARIABLE _UFLD-H VARIABLE _UFLD-STATE VARIABLE _UFLD-FLAGS
VARIABLE _UFLD-VALUE VARIABLE _UFLD-MIN VARIABLE _UFLD-MAX VARIABLE _UFLD-STEP
CREATE _UFLD-SLOT-TEMP UFLD-HEADER-SIZE ALLOT

: _UFLD-B-LOAD ( builder -- )
    DUP _UFLD-B ! DUP @ _UFLD-M ! DUP 8 + @ _UFLD-CAP ! 16 + @ _UFLD-USED ! ;
: _UFLD-USED! ( used -- )
    DUP _UFLD-B @ 16 + ! _UFLD-M @ UFLD-BYTES-OFFSET + ! ;
: _UFLD-PHASE! ( phase -- ) _UFLD-B @ 24 + ! ;
: _UFLD-DROP8 ( eight-values -- ) 2DROP 2DROP 2DROP 2DROP ;
: _UFLD-DROP9 ( nine-values -- ) _UFLD-DROP8 DROP ;

: UFLD-BUILDER-INIT ( dst cap builder -- status )
    DUP _UFLD-B-DESC? 0= IF 2DROP DROP UFLD-S-INVALID EXIT THEN
    2 PICK 2 PICK _UFLD-ALIGNED-SPAN? 0= IF 2DROP DROP UFLD-S-INVALID EXIT THEN
    DUP UFLD-BUILDER-SIZE 4 PICK 4 PICK MSPAN-OVERLAP? IF 2DROP DROP UFLD-S-INVALID EXIT THEN
    DUP UFLD-BUILDER-SIZE 0 FILL >R R@ 8 + ! R> ! UFLD-S-OK ;

: UFLD-BEGIN ( key kind revision width height state flags builder -- status )
    DUP 0 _UFLD-PHASE? 0= IF _UFLD-DROP8 UFLD-S-INVALID EXIT THEN
    _UFLD-B-LOAD _UFLD-FLAGS ! _UFLD-STATE ! _UFLD-H ! _UFLD-W !
    _UFLD-REV ! _UFLD-KIND ! _UFLD-KEY !
    _UFLD-KIND @ DUP 1 < SWAP 3 > OR IF UFLD-S-UNSUPPORTED EXIT THEN
    _UFLD-KEY @ 0= _UFLD-REV @ 0= OR IF UFLD-S-INVALID EXIT THEN
    _UFLD-W @ _UFLD-POS32? 0= _UFLD-H @ _UFLD-POS32? 0= OR IF UFLD-S-INVALID EXIT THEN
    _UFLD-STATE @ 7 INVERT AND _UFLD-FLAGS @ 1 INVERT AND OR IF UFLD-S-INVALID EXIT THEN
    _UFLD-STATE @ 4 AND IF _UFLD-STATE @ 3 AND 3 <> IF UFLD-S-INVALID EXIT THEN THEN
    _UFLD-CAP @ UFLD-HEADER-SIZE U< IF UFLD-S-CAPACITY EXIT THEN
    _UFLD-M @ UFLD-HEADER-SIZE 0 FILL UFLD-HEADER-SIZE _UFLD-USED!
    UFLD-ABI _UFLD-M @ UFLD-ABI-OFFSET + !
    _UFLD-KEY @ _UFLD-M @ UFLD-KEY-OFFSET + !
    _UFLD-KIND @ _UFLD-M @ UFLD-KIND-OFFSET + !
    _UFLD-REV @ _UFLD-M @ UFLD-REVISION-OFFSET + !
    _UFLD-W @ _UFLD-M @ UFLD-WIDTH-OFFSET + !
    _UFLD-H @ _UFLD-M @ UFLD-HEIGHT-OFFSET + !
    _UFLD-STATE @ _UFLD-M @ UFLD-STATE-OFFSET + !
    _UFLD-FLAGS @ _UFLD-M @ UFLD-FLAGS-OFFSET + !
    1 _UFLD-PHASE! UFLD-S-OK ;

: UFLD-SLOTS ( lr lc lh lw vr vc vh vw builder -- status )
    DUP 1 _UFLD-PHASE? 0= IF _UFLD-DROP9 UFLD-S-INVALID EXIT THEN
    _UFLD-B-LOAD
    _UFLD-M @ _UFLD-SLOT-TEMP UFLD-HEADER-SIZE MOVE
    _UFLD-SLOT-TEMP UFLD-VALUE-WIDTH-OFFSET + !
    _UFLD-SLOT-TEMP UFLD-VALUE-HEIGHT-OFFSET + !
    _UFLD-SLOT-TEMP UFLD-VALUE-COLUMN-OFFSET + !
    _UFLD-SLOT-TEMP UFLD-VALUE-ROW-OFFSET + !
    _UFLD-SLOT-TEMP UFLD-LABEL-WIDTH-OFFSET + !
    _UFLD-SLOT-TEMP UFLD-LABEL-HEIGHT-OFFSET + !
    _UFLD-SLOT-TEMP UFLD-LABEL-COLUMN-OFFSET + !
    _UFLD-SLOT-TEMP UFLD-LABEL-ROW-OFFSET + !
    _UFLD-SLOT-TEMP _UFLD-V-M ! _UFLD-RECTS? 0= IF UFLD-S-INVALID EXIT THEN
    _UFLD-SLOT-TEMP UFLD-LABEL-ROW-OFFSET +
    _UFLD-M @ UFLD-LABEL-ROW-OFFSET + 64 MOVE UFLD-S-OK ;

: _UFLD-TEXT-INPUT? ( a u builder -- flag )
    >R 2DUP UFLD-STORAGE-DISJOINT? 0= IF 2DROP R> DROP 0 EXIT THEN
    DUP _UFLD-U32? 0= IF 2DROP R> DROP 0 EXIT THEN
    2DUP USF-TEXT? 0= IF 2DROP R> DROP 0 EXIT THEN
    R@ _UFLD-B? 0= IF 2DROP R> DROP 0 EXIT THEN
    2DUP R@ UFLD-BUILDER-SIZE MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    R@ @ R> 8 + @ MSPAN-OVERLAP? 0= ;
: _UFLD-APPEND-TEXT ( -- )
    _UFLD-M @ _UFLD-USED @ + _UFLD-U @ _UFLD-ALIGN8 0 FILL
    _UFLD-A @ _UFLD-M @ _UFLD-USED @ + _UFLD-U @ MOVE
    _UFLD-NEED @ _UFLD-USED! ;
: _UFLD-TEXT-FITS? ( -- flag )
    _UFLD-U @ _UFLD-ALIGN8 _UFLD-CAP @ _UFLD-USED @ - U> IF 0 EXIT THEN
    _UFLD-USED @ _UFLD-U @ _UFLD-ALIGN8 + _UFLD-NEED ! -1 ;

: UFLD-LABEL ( a u builder -- status )
    2 PICK 2 PICK 2 PICK _UFLD-TEXT-INPUT? 0= IF 2DROP DROP UFLD-S-INVALID EXIT THEN
    DUP 24 + @ 1 <> IF 2DROP DROP UFLD-S-INVALID EXIT THEN
    _UFLD-B-LOAD _UFLD-U ! _UFLD-A !
    _UFLD-M @ _UFLD-V-M ! _UFLD-RECTS? 0= IF UFLD-S-INVALID EXIT THEN
    _UFLD-U @ 0= _UFLD-V-LH @ 0= <> IF UFLD-S-INVALID EXIT THEN
    _UFLD-TEXT-FITS? 0= IF UFLD-S-CAPACITY EXIT THEN
    _UFLD-APPEND-TEXT _UFLD-U @ _UFLD-M @ UFLD-LABEL-BYTES-OFFSET + !
    2 _UFLD-PHASE! UFLD-S-OK ;

: UFLD-INTEGER ( value min max step builder -- status )
    DUP 2 _UFLD-PHASE? 0= IF 2DROP 2DROP DROP UFLD-S-INVALID EXIT THEN
    DUP @ UFLD-KIND@ UFLD-K-INTEGER <> IF 2DROP 2DROP DROP UFLD-S-INVALID EXIT THEN
    _UFLD-B-LOAD _UFLD-STEP ! _UFLD-MAX ! _UFLD-MIN ! _UFLD-VALUE !
    _UFLD-STEP @ 0> 0= _UFLD-MIN @ _UFLD-VALUE @ > OR
    _UFLD-VALUE @ _UFLD-MAX @ > OR IF UFLD-S-INVALID EXIT THEN
    _UFLD-VALUE @ _UFLD-M @ UFLD-VALUE-OFFSET + !
    _UFLD-MIN @ _UFLD-M @ UFLD-MINIMUM-OFFSET + !
    _UFLD-MAX @ _UFLD-M @ UFLD-MAXIMUM-OFFSET + !
    _UFLD-STEP @ _UFLD-M @ UFLD-STEP-OFFSET + ! 3 _UFLD-PHASE! UFLD-S-OK ;

: UFLD-TEXT ( a u builder -- status )
    2 PICK 2 PICK 2 PICK _UFLD-TEXT-INPUT? 0= IF 2DROP DROP UFLD-S-INVALID EXIT THEN
    DUP 24 + @ 2 <> OVER @ UFLD-KIND@ UFLD-K-TEXT <> OR IF 2DROP DROP UFLD-S-INVALID EXIT THEN
    _UFLD-B-LOAD _UFLD-U ! _UFLD-A !
    _UFLD-TEXT-FITS? 0= IF UFLD-S-CAPACITY EXIT THEN
    _UFLD-APPEND-TEXT _UFLD-U @ _UFLD-M @ UFLD-TEXT-BYTES-OFFSET + !
    3 _UFLD-PHASE! UFLD-S-OK ;

: UFLD-CHOICE-VALUE ( value builder -- status )
    DUP 2 _UFLD-PHASE? 0= IF 2DROP UFLD-S-INVALID EXIT THEN
    DUP @ UFLD-KIND@ UFLD-K-CHOICE <> IF 2DROP UFLD-S-INVALID EXIT THEN
    _UFLD-B-LOAD _UFLD-M @ UFLD-VALUE-OFFSET + ! 3 _UFLD-PHASE! UFLD-S-OK ;

: UFLD-CHOICE ( value label-a label-u builder -- status )
    2 PICK 2 PICK 2 PICK _UFLD-TEXT-INPUT? 0= IF 2DROP 2DROP UFLD-S-INVALID EXIT THEN
