VARIABLE _APTASI-SESSION

: _APTASI-STORAGE-VALID?  ( -- flag )
    _APTASI-OWNER @ 7 AND IF FALSE EXIT THEN
    _APTASI-OWNER @ APTAS-SIZE MSPAN-NONWRAPPING? 0= IF FALSE EXIT THEN
    _APTASI-OWNER @ APTAS-SIZE
    _APTASI-ADAPTER @ APTSCB-SIZE MSPAN-OVERLAP? IF FALSE EXIT THEN
    _APTASI-OWNER @ APTAS-SIZE _APTASI-SESSION @
        PT-STORAGE-DISJOINT? ;

\ APTAS-INIT ( adapter owner -- status )
\   Construct an inert optional owner.  PT-INIT and APTSCB-INIT must already
\   have succeeded.  Negotiation begins only when ASHELL-RUN reaches acquire.
: APTAS-INIT  ( adapter owner -- status )
    _APTASI-OWNER ! _APTASI-ADAPTER !
    _APTASI-ADAPTER @ APTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _APTASI-ADAPTER @ APTSCB-SESSION@ DUP 0= IF
        DROP SCB-S-INVALID EXIT
    THEN _APTASI-SESSION !
    _APTASI-SESSION @ PT-STATE@ PT-ST-ANSI <> IF
        SCB-S-INVALID EXIT
    THEN
    _APTASI-OWNER @ 0= IF SCB-S-INVALID EXIT THEN
    _APTASI-STORAGE-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _APTASI-OWNER @ APTAS-SIZE 0 FILL
    _APTASI-ADAPTER @ _APTASI-OWNER @ _APTAS.ADAPTER !
    _APTASI-SESSION @ _APTASI-OWNER @ _APTAS.SESSION !
    _APTASI-OWNER @
    ['] _APTAS-PREFLIGHT ['] _APTAS-ACQUIRE ['] _APTAS-SERVICE
    ['] _APTAS-POLL ['] _APTAS-CLOSE
    _APTASI-OWNER @ ASHELL-TERMINAL-INIT
    DUP SCB-S-OK <> IF EXIT THEN DROP
    _APTAS-MAGIC _APTASI-OWNER @ _APTAS.MAGIC !
    SCB-S-OK ;

VARIABLE _APTASCR-CONTEXT
VARIABLE _APTASCR-XT
VARIABLE _APTASCR-OWNER

\ APTAS-CONTROL-ROUTE! ( context resolver-xt owner -- status )
\   Bind an inert owner to a generic retained-control resolver.  The resolver
\   contract is ( owner generation control-id context -- row col found? ).
\   Binding is refused after this exact owner has entered the shell lifecycle.
: APTAS-CONTROL-ROUTE!  ( context resolver-xt owner -- status )
    _APTASCR-OWNER ! _APTASCR-XT ! _APTASCR-CONTEXT !
    _APTASCR-OWNER @ APTAS-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _APTASCR-CONTEXT @ 0= _APTASCR-XT @ 0= OR IF SCB-S-INVALID EXIT THEN
    _APTASCR-OWNER @ ASHELL-TERMINAL@ = IF SCB-S-INVALID EXIT THEN
    _APTASCR-CONTEXT @ _APTASCR-OWNER @ _APTAS.CONTROL-CONTEXT !
    _APTASCR-XT @ _APTASCR-OWNER @ _APTAS.CONTROL-XT !
    _APTASCR-OWNER @ APTAS-VALID? IF SCB-S-OK ELSE SCB-S-INVALID THEN ;

: APTAS-INSTALL  ( owner -- status )
    DUP APTAS-VALID? 0= IF DROP SCB-S-INVALID EXIT THEN
    ASHELL-TERMINAL! ;

: _APTAS-RELEASE-SOURCE  ( -- status )
    _APTAS-C @ _APTAS.SOURCE-LEASE @ DUP 0= IF
        DROP SCB-S-OK
    ELSE
        _APTAS-C @ SWAP KEY-SOURCE-RELEASE _APTAS-STATUS !
        _APTAS-STATUS @ KEY-SOURCE-S-OK = IF
            0 _APTAS-C @ _APTAS.SOURCE-LEASE !
            SCB-S-OK
        ELSE
            _APTAS-STATUS @ KEY-SOURCE-S-BUSY = IF
                SCB-S-WOULD-BLOCK
            ELSE
                SCB-S-INVALID
            THEN
        THEN
    THEN ;

: APTAS-UNINSTALL  ( owner -- status )
    DUP APTAS-VALID? 0= IF DROP SCB-S-INVALID EXIT THEN
    _APTAS-C !
    _APTAS-C @ ASHELL-TERMINAL@ <> IF SCB-S-INVALID EXIT THEN
    ASHELL-TERMINAL-OWNS? IF SCB-S-INVALID EXIT THEN
    _APTAS-C @ ASHELL-TERMINAL-RELEASE-CHECK
    DUP SCB-S-OK <> IF EXIT THEN DROP
    _APTAS-C @ _APTAS.SESSION @ PT-LEGACY-PENDING? IF
        SCB-S-WOULD-BLOCK EXIT
    THEN
    _APTAS-RELEASE-SOURCE _APTAS-STATUS !
    _APTAS-STATUS @ SCB-S-OK <> IF _APTAS-STATUS @ EXIT THEN
    _APTAS-C @ ASHELL-TERMINAL-RELEASE ;
