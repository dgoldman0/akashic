: _APTAS-MAP-STATUS  ( pt-status -- status )
    DUP PT-S-OK = IF DROP SCB-S-OK EXIT THEN
    DUP PT-S-WOULD-BLOCK = IF DROP SCB-S-WOULD-BLOCK EXIT THEN
    DUP PT-S-INVALID = IF DROP SCB-S-INVALID EXIT THEN
    DROP SCB-S-SESSION-LOST ;

: _APTAS-STATE-OWNS?  ( owner -- flag )
    _APTAS.SESSION @ PT-OWNS? ;

: _APTAS-RETURN-PT  ( pt-status -- status owns-stream )
    _APTAS-MAP-STATUS
    _APTAS-C @ _APTAS-STATE-OWNS? ;

: _APTAS-EVENT!  ( type code mods -- )
    _APTAS-MODS ! _APTAS-CODE ! _APTAS-TYPE !
    _APTAS-TYPE @ _APTAS-EV @ !
    _APTAS-CODE @ _APTAS-EV @ 8 + !
    _APTAS-MODS @ _APTAS-EV @ 16 + ! ;

: _APTAS-LOCAL-MODS  ( wire-mods -- local-mods )
