    _APTAS-MODS @ 1 AND IF KEY-MOD-SHIFT OR THEN
    _APTAS-MODS @ 2 AND IF KEY-MOD-CTRL OR THEN
    _APTAS-MODS @ 4 AND IF KEY-MOD-ALT OR THEN ;

