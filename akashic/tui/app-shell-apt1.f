: _APTAS-MAP-KEY  ( -- has-event )
    _APTAS-C @ _APTAS.EVENT PT-EVENT-VALUE1@ 3 = IF FALSE EXIT THEN
    _APTAS-C @ _APTAS.EVENT PT-EVENT-VALUE0@ DUP _APTAS-SYMBOL !
    _APTAS-NAMED-KEY? IF
        _APTAS-CODE ! KEY-T-SPECIAL _APTAS-TYPE !
    ELSE
        DROP _APTAS-SYMBOL @ _APTAS-CODE ! KEY-T-CHAR _APTAS-TYPE !
    THEN
    _APTAS-C @ _APTAS.EVENT PT-EVENT-VALUE3@
    _APTAS-LOCAL-MODS _APTAS-MODS !
    _APTAS-TYPE @ _APTAS-CODE @ _APTAS-MODS @ _APTAS-EVENT!
    TRUE ;

: _APTAS-TEXT-PENDING?  ( owner -- flag )
    _APTAS.TEXT-PHASE @ 0<> ;

: _APTAS-LOAD-TEXT  ( -- )
    _APTAS-C @ _APTAS.EVENT PT-EVENT-DATA@
    _APTAS-C @ _APTAS.TEXT-U !
    _APTAS-C @ _APTAS.TEXT-A !
    _APTAS-C @ _APTAS.EVENT PT-EVENT-VALUE0@ 1 AND 0<>
    DUP _APTAS-C @ _APTAS.TEXT-PASTE !
    IF 1 ELSE 2 THEN _APTAS-C @ _APTAS.TEXT-PHASE ! ;

: _APTAS-POLL-TEXT  ( -- has-event )
    _APTAS-C @ _APTAS.TEXT-PHASE @ 1 = IF
        2 _APTAS-C @ _APTAS.TEXT-PHASE !
        KEY-T-PASTE KEY-PASTE-START 0 _APTAS-EVENT!
        TRUE EXIT
    THEN
    _APTAS-C @ _APTAS.TEXT-PHASE @ 2 = IF
        _APTAS-C @ _APTAS.TEXT-A @ _APTAS-C @ _APTAS.TEXT-U @
        UTF8-DECODE
        _APTAS-U ! _APTAS-A ! _APTAS-CP !
        _APTAS-A @ _APTAS-C @ _APTAS.TEXT-A !
        _APTAS-U @ _APTAS-C @ _APTAS.TEXT-U !
        _APTAS-U @ 0= IF
            _APTAS-C @ _APTAS.TEXT-PASTE @ IF 3 ELSE 0 THEN
            _APTAS-C @ _APTAS.TEXT-PHASE !
        THEN
        KEY-T-CHAR _APTAS-CP @ 0 _APTAS-EVENT!
        TRUE EXIT
    THEN
    _APTAS-C @ _APTAS.TEXT-PHASE @ 3 = IF
        0 _APTAS-C @ _APTAS.TEXT-PHASE !
        FALSE _APTAS-C @ _APTAS.TEXT-PASTE !
        KEY-T-PASTE KEY-PASTE-END 0 _APTAS-EVENT!
        TRUE EXIT
    THEN
    FALSE ;

: _APTAS-I16  ( u -- n )
    0xFFFF AND DUP 0x8000 AND IF 0xFFFF INVERT OR THEN ;

: _APTAS-POINTER-COORDS?  ( -- flag )
    _APTAS-C @ _APTAS.PTR-X @ 0<
    _APTAS-C @ _APTAS.PTR-Y @ 0< OR IF FALSE EXIT THEN
    _APTAS-C @ _APTAS.PTR-X @ 0xFFFF U>
    _APTAS-C @ _APTAS.PTR-Y @ 0xFFFF U> OR IF FALSE EXIT THEN
    _APTAS-C @ _APTAS.PTR-X @ SCR-W U<
    _APTAS-C @ _APTAS.PTR-Y @ SCR-H U< AND ;

: _APTAS-POINTER-EVENT!  ( code -- )
    _APTAS-CODE !
    _APTAS-C @ _APTAS.PTR-X @ 1+ KEY-MOUSE-X !
    _APTAS-C @ _APTAS.PTR-Y @ 1+ KEY-MOUSE-Y !
    _APTAS-C @ _APTAS.PTR-Y @ 16 LSHIFT
    _APTAS-C @ _APTAS.PTR-X @ OR _APTAS-MODS !
    KEY-T-MOUSE _APTAS-CODE @ _APTAS-MODS @ _APTAS-EVENT! ;

: _APTAS-NEXT-BUTTON  ( -- button has-button )
    _APTAS-C @ _APTAS.PTR-CHANGED @ 1 AND IF
        _APTAS-C @ _APTAS.PTR-CHANGED DUP @ 1 INVERT AND SWAP !
        KEY-MOUSE-LEFT TRUE EXIT
    THEN
    _APTAS-C @ _APTAS.PTR-CHANGED @ 2 AND IF
        _APTAS-C @ _APTAS.PTR-CHANGED DUP @ 2 INVERT AND SWAP !
        KEY-MOUSE-MIDDLE TRUE EXIT
    THEN
    _APTAS-C @ _APTAS.PTR-CHANGED @ 4 AND IF
        _APTAS-C @ _APTAS.PTR-CHANGED DUP @ 4 INVERT AND SWAP !
        KEY-MOUSE-RIGHT TRUE EXIT
    THEN
    0 FALSE ;

: _APTAS-POLL-POINTER  ( -- has-event )
    _APTAS-POINTER-COORDS? 0= IF
        0 _APTAS-C @ _APTAS.PTR-CHANGED !
        0 _APTAS-C @ _APTAS.PTR-WHEEL-Y !
        FALSE EXIT
    THEN
    _APTAS-NEXT-BUTTON IF
        _APTAS-C @ _APTAS.PTR-KIND @ 3 = IF
            DROP KEY-MOUSE-RELEASE
        THEN
        _APTAS-POINTER-EVENT! TRUE EXIT
    THEN DROP
    _APTAS-C @ _APTAS.PTR-WHEEL-Y @ DUP IF
        DUP 0< IF
            1+ _APTAS-C @ _APTAS.PTR-WHEEL-Y !
            KEY-MOUSE-SCROLL-UP
        ELSE
            1- _APTAS-C @ _APTAS.PTR-WHEEL-Y !
            KEY-MOUSE-SCROLL-DN
        THEN
        _APTAS-POINTER-EVENT! TRUE EXIT
    THEN DROP
    FALSE ;

: _APTAS-LOAD-POINTER  ( -- )
    _APTAS-C @ _APTAS.EVENT PT-EVENT-VALUE0@
    _APTAS-C @ _APTAS.PTR-X !
    _APTAS-C @ _APTAS.EVENT PT-EVENT-VALUE1@
    _APTAS-C @ _APTAS.PTR-Y !
    _APTAS-C @ _APTAS.EVENT PT-EVENT-VALUE2@ 16 RSHIFT 7 AND
    _APTAS-C @ _APTAS.PTR-CHANGED !
    _APTAS-C @ _APTAS.EVENT PT-EVENT-VALUE3@ 16 RSHIFT 0xFFFF AND
    _APTAS-C @ _APTAS.PTR-KIND !
    _APTAS-C @ _APTAS.EVENT PT-EVENT-VALUE3@ 48 RSHIFT _APTAS-I16
    _APTAS-C @ _APTAS.PTR-WHEEL-Y ! ;

\ A native control resolver is composition-supplied and renderer-neutral.
\ It receives only the typed retained identity and its caller context, and
\ returns one absolute cell inside the exact acknowledged control target.
\ Mapping that point to the established mouse descriptor keeps application,
\ host, UCTX, UIDL, focus, and dirtying behavior on their ordinary path.
: _APTAS-MAP-CONTROL  ( -- has-event )
    _APTAS-C @ _APTAS.EVENT PT-CONTROL-EVENT-KIND@
        PT-CONTROL-ACTIVATE <> IF FALSE EXIT THEN
    _APTAS-C @ _APTAS.CONTROL-XT @ 0= IF FALSE EXIT THEN
    _APTAS-C @ _APTAS.EVENT PT-CONTROL-EVENT-OWNER@
    _APTAS-C @ _APTAS.EVENT PT-CONTROL-EVENT-GENERATION@
    _APTAS-C @ _APTAS.EVENT PT-CONTROL-EVENT-ID@
    _APTAS-C @ _APTAS.CONTROL-CONTEXT @
    _APTAS-C @ _APTAS.CONTROL-XT @ EXECUTE
    _APTAS-CONTROL-HAS ! _APTAS-CONTROL-COL ! _APTAS-CONTROL-ROW !
    _APTAS-CONTROL-HAS @ 0= IF FALSE EXIT THEN
    _APTAS-CONTROL-ROW @ 0< _APTAS-CONTROL-COL @ 0< OR IF FALSE EXIT THEN
    _APTAS-CONTROL-ROW @ 0xFFFF U>
    _APTAS-CONTROL-COL @ 0xFFFF U> OR IF FALSE EXIT THEN
    _APTAS-CONTROL-ROW @ SCR-H U<
    _APTAS-CONTROL-COL @ SCR-W U< AND 0= IF FALSE EXIT THEN
    _APTAS-CONTROL-COL @ _APTAS-C @ _APTAS.PTR-X !
    _APTAS-CONTROL-ROW @ _APTAS-C @ _APTAS.PTR-Y !
    KEY-MOUSE-LEFT _APTAS-POINTER-EVENT!
    TRUE ;

\ Raw input callback installed in keys.f.  It exposes only PT's retained
\ pre-switch bytes while enhanced ownership is live.  Once PT is ANSI again,
\ it falls through to the BIOS UART after draining that bounded retention.
: _APTAS-RAW-POLL  ( owner -- byte has-byte )
    DUP APTAS-VALID? 0= IF DROP 0 FALSE EXIT THEN
    DUP _APTAS.SESSION @ PT-LEGACY-POLL IF NIP TRUE EXIT THEN
    2DROP
    PT-STREAM-OWNED? 0= IF
        KEY? IF KEY TRUE ELSE 0 FALSE THEN
    ELSE
        0 FALSE
    THEN ;

: _APTAS-PREFLIGHT  ( owner -- status ansi-safe )
    DUP APTAS-VALID? 0= IF DROP SCB-S-INVALID FALSE EXIT THEN
    DUP _APTAS.SESSION @ PT-STATE@ PT-ST-ANSI <> IF
        DROP SCB-S-SESSION-LOST FALSE EXIT
    THEN DROP
    PT-STREAM-OWNED? IF SCB-S-WOULD-BLOCK TRUE EXIT THEN
    SCB-S-OK TRUE ;

DEFER _APTAS-KEY-POLL

: _APTAS-ACQUIRE  ( owner -- status owns-stream )
    DUP APTAS-VALID? 0= IF DROP SCB-S-INVALID FALSE EXIT THEN
    DUP _APTAS-C !
    DUP _APTAS.SOURCE-LEASE @ ?DUP IF
        OVER SWAP KEY-SOURCE-HELD? 0= IF
            DROP SCB-S-INVALID
            _APTAS-C @ _APTAS-STATE-OWNS? EXIT
        THEN
    ELSE
        DUP ['] _APTAS-RAW-POLL ['] _APTAS-KEY-POLL
        KEY-SOURCE-ACQUIRE
        _APTAS-STATUS !
        _APTAS-STATUS @ KEY-SOURCE-S-OK <> IF
            2DROP SCB-S-INVALID
            _APTAS-C @ _APTAS-STATE-OWNS? EXIT
        THEN
        OVER _APTAS.SOURCE-LEASE !
    THEN
    _APTAS.SESSION @ PT-START DUP PT-S-OK <> IF
        _APTAS-RETURN-PT EXIT
    THEN DROP
    BEGIN
        _APTAS-C @ _APTAS.SESSION @ PT-SERVICE _APTAS-STATUS !
        _APTAS-C @ _APTAS.SESSION @ PT-STATE@ _APTAS-STATE !
        _APTAS-STATE @ PT-ST-ANSI = IF
            SCR-FORCE SCB-S-OK FALSE EXIT
        THEN
        _APTAS-STATE @ PT-ST-LOST = IF
            SCB-S-SESSION-LOST TRUE EXIT
        THEN
        _APTAS-C @ _APTAS.SESSION @ PT-ACTIVE? IF
            _APTAS-C @ _APTAS.ADAPTER @ APTSCB-BIND TRUE EXIT
        THEN
        _APTAS-STATUS @ DUP PT-S-OK <>
        OVER PT-S-WOULD-BLOCK <> AND IF
            _APTAS-RETURN-PT EXIT
        THEN DROP
        YIELD?
    AGAIN ;

: _APTAS-SERVICE  ( owner -- status owns-stream )
    DUP APTAS-VALID? 0= IF DROP SCB-S-INVALID FALSE EXIT THEN
    DUP _APTAS-C !
    DUP _APTAS.SESSION @ PT-STATE@ PT-ST-LOST = IF
        DROP SCB-S-SESSION-LOST TRUE EXIT
    THEN
    DUP _APTAS-TEXT-PENDING? IF
        DUP _APTAS.SESSION @ PT-OWNS? IF
            DROP SCB-S-OK TRUE
        ELSE
            DROP SCB-S-SESSION-LOST TRUE
        THEN EXIT
    THEN
    _APTAS.ADAPTER @ APTSCB-SERVICE _APTAS-STATUS !
    _APTAS-C @ _APTAS.SESSION @ PT-STATE@ _APTAS-STATE !
    _APTAS-STATE @ PT-ST-ANSI = IF
        PT-STREAM-OWNED? IF SCB-S-SESSION-LOST TRUE EXIT THEN
        SCB-S-OK FALSE EXIT
    THEN
    _APTAS-STATE @ PT-ST-LOST = IF SCB-S-SESSION-LOST TRUE EXIT THEN
    _APTAS-STATUS @ TRUE ;

: _APTAS-POLL  ( event owner -- status has-event )
    DUP APTAS-VALID? 0= IF 2DROP SCB-S-INVALID FALSE EXIT THEN
    _APTAS-C ! _APTAS-EV !
    \ Bytes captured before the enhanced switch precede every framed event.
    \ The installed key source exposes only that retained prefix while PT owns
    \ the raw UART, so this preserves order without admitting binary frames.
    _APTAS-EV @ _APTAS-C @ DUP _APTAS.SOURCE-LEASE @
    KEY-SOURCE-RAW-POLL IF SCB-S-OK TRUE EXIT THEN
    _APTAS-C @ _APTAS-TEXT-PENDING? IF
        _APTAS-POLL-TEXT SCB-S-OK SWAP EXIT
    THEN
    _APTAS-C @ _APTAS.PTR-CHANGED @
    _APTAS-C @ _APTAS.PTR-WHEEL-Y @ OR IF
        _APTAS-POLL-POINTER SCB-S-OK SWAP EXIT
    THEN
    _APTAS-C @ _APTAS.EVENT
    _APTAS-C @ _APTAS.SESSION @ PT-EVENT-POLL
    _APTAS-HAS ! _APTAS-STATUS !
    _APTAS-STATUS @ PT-S-OK <> IF
        _APTAS-STATUS @ _APTAS-MAP-STATUS FALSE EXIT
    THEN
    _APTAS-HAS @ 0= IF SCB-S-OK FALSE EXIT THEN
    _APTAS-C @ _APTAS.EVENT PT-EVENT-TYPE@ DUP PT-EVENT-KEY = IF
        DROP _APTAS-MAP-KEY SCB-S-OK SWAP EXIT
    THEN
    DUP PT-EVENT-TEXT = IF
        DROP _APTAS-LOAD-TEXT _APTAS-POLL-TEXT SCB-S-OK SWAP EXIT
    THEN
    DUP PT-EVENT-POINTER = IF
        DROP _APTAS-LOAD-POINTER _APTAS-POLL-POINTER SCB-S-OK SWAP EXIT
    THEN
    DUP PT-EVENT-RESIZE = IF
        DROP
        KEY-T-RESIZE
        _APTAS-C @ _APTAS.EVENT PT-EVENT-VALUE0@
        _APTAS-C @ _APTAS.EVENT PT-EVENT-VALUE1@
        _APTAS-EVENT!
        SCB-S-OK TRUE EXIT
    THEN
    DUP PT-EVENT-CONTROL = IF
        DROP _APTAS-MAP-CONTROL SCB-S-OK SWAP EXIT
    THEN
    PT-EVENT-FOCUS = IF SCB-S-OK FALSE EXIT THEN
    SCB-S-INVALID FALSE ;

: _APTAS-STATUS-THROW  ( status -- )
    -3300 SWAP - THROW ;

: _APTAS-KEY-POLL-IMPL  ( event owner -- has-event )
    DUP _APTAS-C !
    DUP _APTAS-SERVICE
    _APTAS-HAS ! _APTAS-STATUS !
    _APTAS-STATUS @ DUP SCB-S-OK <>
    OVER SCB-S-WOULD-BLOCK <> AND IF
        >R 2DROP R> _APTAS-STATUS-THROW
    THEN DROP
    _APTAS-HAS @ IF
        _APTAS-POLL
        _APTAS-HAS ! _APTAS-STATUS !
        _APTAS-STATUS @ SCB-S-OK = IF _APTAS-HAS @ EXIT THEN
        _APTAS-STATUS @ SCB-S-WOULD-BLOCK = IF FALSE EXIT THEN
        _APTAS-STATUS @ _APTAS-STATUS-THROW
    THEN
    DUP _APTAS.SOURCE-LEASE @ KEY-SOURCE-RAW-POLL ;

' _APTAS-KEY-POLL-IMPL IS _APTAS-KEY-POLL

: _APTAS-CLOSE  ( reason owner -- status owns-stream )
    DUP APTAS-VALID? 0= IF 2DROP SCB-S-INVALID FALSE EXIT THEN
    _APTAS-C ! _APTAS-CLOSE-REASON !
    0 _APTAS-C @ _APTAS.TEXT-PHASE !
    0 _APTAS-C @ _APTAS.PTR-CHANGED !
    0 _APTAS-C @ _APTAS.PTR-WHEEL-Y !
    BEGIN
        _APTAS-C @ _APTAS.SESSION @ PT-STATE@ _APTAS-STATE !
        _APTAS-STATE @ PT-ST-ANSI = IF
            PT-STREAM-OWNED? IF SCB-S-SESSION-LOST TRUE EXIT THEN
            SCR-ANSI SCB-S-OK FALSE EXIT
        THEN
        _APTAS-STATE @ PT-ST-LOST = IF
            SCB-S-SESSION-LOST TRUE EXIT
        THEN
        _APTAS-C @ _APTAS.SESSION @ PT-OWNS? 0= IF
            SCB-S-SESSION-LOST TRUE EXIT
        THEN
        _APTAS-CLOSE-REASON @ _APTAS-C @ _APTAS.ADAPTER @
            APTSCB-CLOSE-STEP _APTAS-STATUS !
        _APTAS-C @ _APTAS.SESSION @ PT-STATE@ _APTAS-STATE !
        _APTAS-STATE @ PT-ST-ANSI = IF
            PT-STREAM-OWNED? IF SCB-S-SESSION-LOST TRUE EXIT THEN
            SCR-ANSI SCB-S-OK FALSE EXIT
        THEN
        _APTAS-STATE @ PT-ST-LOST = IF
            SCB-S-SESSION-LOST TRUE EXIT
        THEN
        _APTAS-STATUS @ DUP SCB-S-OK <>
        OVER SCB-S-WOULD-BLOCK <> AND IF
            _APTAS-C @ _APTAS-STATE-OWNS? EXIT
        THEN DROP
        YIELD?
    AGAIN ;

