: _APTSCBI-STORAGE-VALID?  ( -- flag )
    _APTSCBI-SESSION @ 7 AND _APTSCBI-ADAPTER @ 7 AND OR IF 0 EXIT THEN
    _APTSCBI-SESSION @ PT-SESSION-SIZE MSPAN-NONWRAPPING? 0= IF
        0 EXIT
    THEN
    _APTSCBI-ADAPTER @ APTSCB-SIZE MSPAN-NONWRAPPING? 0= IF
        0 EXIT
    THEN
    _APTSCBI-ADAPTER @ APTSCB-SIZE _APTSCBI-SESSION @
        PT-STORAGE-DISJOINT? ;

\ APTSCB-INIT ( session adapter -- status )
\   Construct from a caller-owned initialized PT session.  No session is
\   created or started implicitly, and loading this module alone emits no
\   bytes.  Binding remains illegal until the session is ACTIVE.
: APTSCB-INIT  ( session adapter -- status )
    _APTSCBI-ADAPTER ! _APTSCBI-SESSION !
    _APTSCBI-SESSION @ 0= _APTSCBI-ADAPTER @ 0= OR IF
        SCB-S-INVALID EXIT
    THEN
    _APTSCBI-STORAGE-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _APTSCBI-ADAPTER @ APTSCB-SIZE 0 FILL
    _APTSCBI-SESSION @ PT-STATE@ PT-ST-LOST = IF
        SCB-S-SESSION-LOST EXIT
    THEN
    _APTSCBI-ADAPTER @
    ['] _APTSCB-BEGIN ['] _APTSCB-SPAN ['] _APTSCB-CURSOR
    ['] _APTSCB-COMMIT ['] _APTSCB-ABORT
    _APTSCBI-ADAPTER @ SCB-INIT DUP SCB-S-OK <> IF EXIT THEN DROP
    _APTSCBI-SESSION @ _APTSCBI-ADAPTER @ APTSCB.SESSION !
    _APTSCB-MAGIC _APTSCBI-ADAPTER @ APTSCB.MAGIC !
    SCB-S-OK ;

\ APTSCB-BIND ( adapter -- status )
\   Bind only an already-live adapter.  SCR-BACKEND! forces the mandatory
\   initial replacement snapshot.
: APTSCB-BIND  ( adapter -- status )
    DUP APTSCB-VALID? 0= IF DROP SCB-S-INVALID EXIT THEN
    DUP APTSCB.SESSION @ PT-ACTIVE? 0= IF
        DROP SCB-S-SESSION-LOST EXIT
    THEN
    DUP APTSCB.SESSION @ PT-OWNS? 0= IF
        DROP SCB-S-SESSION-LOST EXIT
    THEN
    SCR-BACKEND! ;

: _APTSCB-FALLBACK  ( adapter -- )
    DUP SCR-BACKEND@ = IF DROP SCR-ANSI ELSE DROP THEN ;

: _APTSCB-PUBLISHER-STEP  ( adapter -- status )
    APTSCB.PUBLISHER @ DUP 0= IF DROP SCB-S-OK EXIT THEN
    DUP APTSCBP.CONTEXT @
    SWAP APTSCBP.STEP-XT @ EXECUTE _APTSCB-NORMALIZE-STATUS ;

VARIABLE _APTSCB-PENDING

: _APTSCB-PUBLISHER-SETTLE  ( adapter -- status pending? )
    APTSCB.PUBLISHER @ DUP 0= IF DROP SCB-S-OK 0 EXIT THEN
    DUP APTSCBP.CONTEXT @ SWAP APTSCBP.SETTLE-XT @ EXECUTE
    0<> _APTSCB-PENDING ! _APTSCB-NORMALIZE-STATUS
    _APTSCB-PENDING @ ;

\ Retained discovery deliberately follows the accepted initial CELL snapshot.
\ Remember only a handoff actually scheduled for this exact screen/backend,
\ not raw protocol availability.  Ineligibility therefore leaves the edge
\ pending, while reset or a CELL-only answer clears it for a later epoch.
: _APTSCB-RETAINED-HANDOFF  ( adapter -- )
    DUP APTSCB.SESSION @ PT-RETAINED-AVAILABLE? 0= IF
        0 SWAP _APTSCB.RETAINED-HANDOFF ! EXIT
    THEN
    DUP _APTSCB.RETAINED-HANDOFF @ IF DROP EXIT THEN
    DUP APTSCB.PUBLISHER @ 0= IF DROP EXIT THEN
    DUP SCR-BACKEND@ <> IF DROP EXIT THEN
    DUP _APTSCB.ROUTE @ _APTSCB-ROUTE-IDLE <> IF DROP EXIT THEN
    SCR-FORCE
    -1 SWAP _APTSCB.RETAINED-HANDOFF ! ;

\ Every observed ANSI transition is also the neutral publisher-retirement
\ boundary.  SETTLE is best-effort here: PT has already released its wire
\ authority, so the callback may only quarantine publisher-local state.
: _APTSCB-ANSI-RETIRE  ( adapter -- status )
    PT-STREAM-OWNED? IF DROP SCB-S-WOULD-BLOCK EXIT THEN
    DUP _APTSCB-PUBLISHER-SETTLE 2DROP
    0 OVER _APTSCB.RETAINED-HANDOFF !
    _APTSCB-ROUTE-IDLE OVER _APTSCB.ROUTE !
    _APTSCB-FALLBACK
    SCB-S-OK ;

\ APTSCB-SERVICE ( adapter -- status )
\   Advance the separate PT service outside paint.  Call this before input
\   dispatch and before SCR-FLUSH?.  A soft reset forces a snapshot.  ANSI is
\   rebound only after PT reports its synchronized ANSI state; structural
\   SESSION-LOST retains the binary backend and must await an external reset.
: APTSCB-SERVICE  ( adapter -- status )
    DUP APTSCB-VALID? 0= IF DROP SCB-S-INVALID EXIT THEN
    DUP _APTSCB-ADAPTER !
    APTSCB.SESSION @ DUP _APTSCB-SESSION !
    DUP PT-STATE@ PT-ST-ANSI = IF
        DROP
        _APTSCB-ADAPTER @ _APTSCB-ANSI-RETIRE EXIT
    THEN
    DUP PT-STATE@ PT-ST-LOST = IF DROP SCB-S-SESSION-LOST EXIT THEN
    DUP PT-OWNS? 0= IF DROP SCB-S-SESSION-LOST EXIT THEN
    PT-SERVICE _APTSCB-MAP-STATUS _APTSCB-STATUS !
    _APTSCB-SESSION @ PT-STATE@ PT-ST-ANSI = IF
        _APTSCB-ADAPTER @ _APTSCB-ANSI-RETIRE EXIT
    THEN
    _APTSCB-SESSION @ PT-STATE@ PT-ST-LOST = IF
        SCB-S-SESSION-LOST EXIT
    THEN
    _APTSCB-SESSION @ PT-STATE@ PT-ST-CLOSING = IF
        SCB-S-WOULD-BLOCK EXIT
    THEN
    _APTSCB-STATUS @ DUP SCB-S-SESSION-LOST =
    SWAP SCB-S-INVALID = OR IF _APTSCB-STATUS @ EXIT THEN
    \ PT-ACTIVE? includes the pre-CLOSING writer barrier.  Automatic sequence
    \ exhaustion may latch that barrier while the underlying state is still
    \ ACTIVE, and no ordinary publisher STEP is admitted past it.
    _APTSCB-SESSION @ PT-ACTIVE? 0= IF SCB-S-WOULD-BLOCK EXIT THEN
    _APTSCB-ADAPTER @ _APTSCB-RETAINED-HANDOFF
    _APTSCB-ADAPTER @ _APTSCB-PUBLISHER-STEP
    DUP SCB-S-OK <> IF EXIT THEN DROP
    _APTSCB-SESSION @ PT-SNAPSHOT-NEEDED? IF
        _APTSCB-ADAPTER @ SCR-BACKEND@ = IF SCR-FORCE THEN
    THEN
    _APTSCB-STATUS @ SCB-S-WOULD-BLOCK = IF SCB-S-WOULD-BLOCK EXIT THEN
    _APTSCB-STATUS @ SCB-S-OK = IF SCB-S-OK EXIT THEN
    _APTSCB-STATUS @ SCB-S-INVALID = IF SCB-S-INVALID EXIT THEN
    SCB-S-SESSION-LOST ;

VARIABLE _APTSCBC-REASON

\ APTSCB-CLOSE-STEP ( reason adapter -- status )
\   The single synchronized-close primitive: latch PT's finite close bound,
\ service its pending path, then settle only an already-admitted publisher
\ result.  A later service publishes CLOSE once that authority clears.  While
\ PT remains CLOSING this word pumps transport only; after service proves ANSI,
\ one final settlement retires engine-local state before fallback.
: APTSCB-CLOSE-STEP  ( reason adapter -- status )
    _APTSCB-ADAPTER ! _APTSCBC-REASON !
    _APTSCB-ADAPTER @ APTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _APTSCB-ADAPTER @ APTSCB.SESSION @ _APTSCB-SESSION !
    _APTSCB-SESSION @ PT-STATE@ PT-ST-ANSI = IF
        _APTSCB-ADAPTER @ _APTSCB-ANSI-RETIRE EXIT
    THEN
    _APTSCB-SESSION @ PT-STATE@ PT-ST-LOST = IF
        SCB-S-SESSION-LOST EXIT
    THEN
    _APTSCB-SESSION @ PT-OWNS? 0= IF SCB-S-SESSION-LOST EXIT THEN
    _APTSCB-SESSION @ PT-STATE@ PT-ST-CLOSING = IF
        _APTSCB-SESSION @ PT-SERVICE _APTSCB-MAP-STATUS _APTSCB-STATUS !
        _APTSCB-SESSION @ PT-STATE@ PT-ST-ANSI = IF
            _APTSCB-ADAPTER @ _APTSCB-ANSI-RETIRE EXIT
        THEN
        _APTSCB-SESSION @ PT-STATE@ PT-ST-LOST = IF
            SCB-S-SESSION-LOST EXIT
        THEN
        _APTSCB-STATUS @ DUP SCB-S-SESSION-LOST =
        SWAP SCB-S-INVALID = OR IF _APTSCB-STATUS @ EXIT THEN
        SCB-S-WOULD-BLOCK EXIT
    THEN
    \ Latch PT's immutable close reason and deadline before service can emit
    \ ordinary CREDIT/discovery work.  A published CLOSE moves directly to
    \ the transport-only branch; an outstanding result leaves PT ACTIVE with
    \ its internal close-pending admission barrier set.
    _APTSCBC-REASON @ _APTSCB-SESSION @ PT-CLOSE
        _APTSCB-MAP-STATUS _APTSCB-STATUS !
    _APTSCB-SESSION @ PT-STATE@ PT-ST-ANSI = IF
        _APTSCB-ADAPTER @ _APTSCB-ANSI-RETIRE EXIT
    THEN
    _APTSCB-SESSION @ PT-STATE@ PT-ST-LOST = IF
        SCB-S-SESSION-LOST EXIT
    THEN
    _APTSCB-SESSION @ PT-STATE@ PT-ST-CLOSING = IF
        _APTSCB-ROUTE-IDLE _APTSCB-ADAPTER @ _APTSCB.ROUTE !
        SCB-S-OK EXIT
    THEN
    _APTSCB-STATUS @ DUP SCB-S-SESSION-LOST =
    SWAP SCB-S-INVALID = OR IF _APTSCB-STATUS @ EXIT THEN

    _APTSCB-SESSION @ PT-SERVICE _APTSCB-MAP-STATUS _APTSCB-STATUS !
    _APTSCB-SESSION @ PT-STATE@ PT-ST-ANSI = IF
        _APTSCB-ADAPTER @ _APTSCB-ANSI-RETIRE EXIT
    THEN
    _APTSCB-SESSION @ PT-STATE@ PT-ST-LOST = IF
        SCB-S-SESSION-LOST EXIT
    THEN
    _APTSCB-SESSION @ PT-STATE@ PT-ST-CLOSING = IF
        _APTSCB-ROUTE-IDLE _APTSCB-ADAPTER @ _APTSCB.ROUTE !
        SCB-S-WOULD-BLOCK EXIT
    THEN
    _APTSCB-STATUS @ DUP SCB-S-SESSION-LOST =
    SWAP SCB-S-INVALID = OR IF _APTSCB-STATUS @ EXIT THEN
    _APTSCB-ADAPTER @ _APTSCB-PUBLISHER-SETTLE 2DROP
    SCB-S-WOULD-BLOCK ;
