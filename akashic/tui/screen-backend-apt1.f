    THEN
    SCB-M-SNAPSHOT = IF PT-CELL-REPLACE ELSE PT-CELL-DELTA THEN ;

: _APTSCB-BEGIN  ( mode cols rows span-count cell-count context -- status )
    _APTSCB-ADAPTER !
    _APTSCB-CELLS ! _APTSCB-SPANS !
    _APTSCB-ROWS ! _APTSCB-COLS ! _APTSCB-MODE !
    _APTSCB-ADAPTER @ _APTSCB-CONTEXT-VALID? 0= IF
        SCB-S-INVALID EXIT
    THEN
    _APTSCB-MODE @ _APTSCB-MODE? 0= IF SCB-S-INVALID EXIT THEN
    _APTSCB-ADAPTER @ _APTSCB.ROUTE @ _APTSCB-ROUTE-IDLE <> IF
        SCB-S-WOULD-BLOCK EXIT
    THEN
    _APTSCB-ADAPTER @ APTSCB.SESSION @ _APTSCB-SESSION !
    _APTSCB-ADAPTER @ APTSCB.PUBLISHER @ _APTSCB-PUBLISHER !
    _APTSCB-PUBLISHER @ 0<>
    _APTSCB-SESSION @ PT-RETAINED-AVAILABLE? AND IF
        _APTSCB-ROUTE-OUTPUT _APTSCB-ADAPTER @ _APTSCB.ROUTE !
        _APTSCB-COLS @ _APTSCB-ROWS @
        _APTSCB-SPANS @ _APTSCB-CELLS @
        _APTSCB-PUBLISHER-CELL-MODE
        _APTSCB-PUBLISHER @ APTSCBP.CONTEXT @
        _APTSCB-PUBLISHER @ APTSCBP.BEGIN-XT @ EXECUTE
        _APTSCB-NORMALIZE-STATUS
    ELSE
        \ A retained-only request has no direct PT transaction equivalent.
        \ Refuse before pinning a route so the screen can retry the same
        \ persistent request when retained publication becomes available.
        _APTSCB-MODE @ SCB-M-NONE = IF
            SCB-S-WOULD-BLOCK EXIT
        THEN
        _APTSCB-MODE @ SCB-M-DELTA = IF
            _APTSCB-SESSION @ PT-SNAPSHOT-NEEDED? IF
                SCB-S-WOULD-BLOCK EXIT
            THEN
        THEN
        _APTSCB-ROUTE-DIRECT _APTSCB-ADAPTER @ _APTSCB.ROUTE !
        _APTSCB-MODE @ SCB-M-SNAPSHOT = IF
            _APTSCB-COLS @ _APTSCB-ROWS @
            _APTSCB-SPANS @ _APTSCB-CELLS @ _APTSCB-SESSION @
            PT-SNAPSHOT-BEGIN
        ELSE
            _APTSCB-COLS @ _APTSCB-ROWS @
            _APTSCB-SPANS @ _APTSCB-CELLS @ _APTSCB-SESSION @
            PT-TX-BEGIN
        THEN _APTSCB-MAP-STATUS
    THEN
    DUP SCB-S-OK <> IF
        _APTSCB-ROUTE-IDLE _APTSCB-ADAPTER @ _APTSCB.ROUTE !
    THEN ;

: _APTSCB-SPAN-BEGIN  ( -- status )
    _APTSCB-ADAPTER @ _APTSCB.ROUTE @ _APTSCB-ROUTE-DIRECT = IF
        _APTSCB-ROW @ _APTSCB-COL @ _APTSCB-N @ _APTSCB-SESSION @
        PT-SPAN-BEGIN _APTSCB-MAP-STATUS EXIT
    THEN
    _APTSCB-ADAPTER @ _APTSCB.ROUTE @ _APTSCB-ROUTE-OUTPUT = IF
        _APTSCB-ROW @ _APTSCB-COL @ _APTSCB-N @
        _APTSCB-PUBLISHER @ APTSCBP.CONTEXT @
        _APTSCB-PUBLISHER @ APTSCBP.SPAN-XT @ EXECUTE
        _APTSCB-NORMALIZE-STATUS EXIT
    THEN
    SCB-S-INVALID ;

: _APTSCB-WRITE-CELL  ( cell -- status )
    _APTSCB-CELL !
    _APTSCB-CELL @ _APTSCB-CELL-CP
    _APTSCB-CELL @ CELL-FG@
    _APTSCB-CELL @ CELL-BG@
    _APTSCB-CELL @ _APTSCB-WIRE-ATTRS
    _APTSCB-ADAPTER @ _APTSCB.ROUTE @ _APTSCB-ROUTE-DIRECT = IF
        _APTSCB-SESSION @ PT-CELL _APTSCB-MAP-STATUS EXIT
    THEN
    _APTSCB-PUBLISHER @ APTSCBP.CONTEXT @
    _APTSCB-PUBLISHER @ APTSCBP.CELL-XT @ EXECUTE
    _APTSCB-NORMALIZE-STATUS ;

: _APTSCB-SPAN  ( cells count row col context -- status )
    _APTSCB-ADAPTER !
    _APTSCB-COL ! _APTSCB-ROW ! _APTSCB-N ! _APTSCB-A !
    _APTSCB-ADAPTER @ _APTSCB-CONTEXT-VALID? 0= IF
        SCB-S-INVALID EXIT
    THEN
    _APTSCB-ADAPTER @ APTSCB.SESSION @ _APTSCB-SESSION !
    _APTSCB-ADAPTER @ APTSCB.PUBLISHER @ _APTSCB-PUBLISHER !
    _APTSCB-SPAN-BEGIN DUP SCB-S-OK <> IF EXIT THEN DROP
    SCB-S-OK _APTSCB-STATUS !
    _APTSCB-N @ 0 ?DO
        _APTSCB-STATUS @ SCB-S-OK = IF
            _APTSCB-A @ I 8 * + @ _APTSCB-WRITE-CELL
            _APTSCB-STATUS !
        THEN
    LOOP
    _APTSCB-STATUS @ ;

: _APTSCB-CURSOR  ( row col visible context -- status )
    _APTSCB-ADAPTER ! _APTSCB-VISIBLE ! _APTSCB-COL ! _APTSCB-ROW !
    _APTSCB-ADAPTER @ _APTSCB-CONTEXT-VALID? 0= IF
        SCB-S-INVALID EXIT
    THEN
    _APTSCB-ADAPTER @ APTSCB.SESSION @ _APTSCB-SESSION !
    _APTSCB-ADAPTER @ APTSCB.PUBLISHER @ _APTSCB-PUBLISHER !
    _APTSCB-ADAPTER @ _APTSCB.ROUTE @ _APTSCB-ROUTE-DIRECT = IF
        _APTSCB-ROW @ _APTSCB-COL @ _APTSCB-VISIBLE @ _APTSCB-SESSION @
        PT-CURSOR _APTSCB-MAP-STATUS EXIT
    THEN
    _APTSCB-ADAPTER @ _APTSCB.ROUTE @ _APTSCB-ROUTE-OUTPUT = IF
        _APTSCB-ROW @ _APTSCB-COL @ _APTSCB-VISIBLE @
        _APTSCB-PUBLISHER @ APTSCBP.CONTEXT @
        _APTSCB-PUBLISHER @ APTSCBP.CURSOR-XT @ EXECUTE
        _APTSCB-NORMALIZE-STATUS EXIT
    THEN
    SCB-S-INVALID ;

: _APTSCB-COMMIT  ( context -- status )
    DUP _APTSCB-ADAPTER ! _APTSCB-CONTEXT-VALID? 0= IF
        SCB-S-INVALID EXIT
    THEN
    _APTSCB-ADAPTER @ APTSCB.SESSION @ _APTSCB-SESSION !
    _APTSCB-ADAPTER @ APTSCB.PUBLISHER @ _APTSCB-PUBLISHER !
    _APTSCB-ADAPTER @ _APTSCB.ROUTE @ _APTSCB-ROUTE-DIRECT = IF
        _APTSCB-SESSION @ PT-TX-COMMIT _APTSCB-MAP-STATUS _APTSCB-STATUS !
        _APTSCB-STATUS @ SCB-S-OK <> IF
            0 _APTSCB-SESSION @ PT-TX-ABORT DROP
        THEN
    ELSE
        _APTSCB-ADAPTER @ _APTSCB.ROUTE @ _APTSCB-ROUTE-OUTPUT <> IF
            SCB-S-INVALID EXIT
        THEN
        _APTSCB-PUBLISHER @ APTSCBP.CONTEXT @
        _APTSCB-PUBLISHER @ APTSCBP.COMMIT-XT @ EXECUTE
        _APTSCB-NORMALIZE-STATUS _APTSCB-STATUS !
    THEN
    _APTSCB-ROUTE-IDLE _APTSCB-ADAPTER @ _APTSCB.ROUTE !
    _APTSCB-STATUS @ ;

: _APTSCB-ABORT  ( context -- )
    DUP _APTSCB-ADAPTER ! _APTSCB-CONTEXT-VALID? 0= IF EXIT THEN
    _APTSCB-ADAPTER @ APTSCB.SESSION @ _APTSCB-SESSION !
    _APTSCB-ADAPTER @ APTSCB.PUBLISHER @ _APTSCB-PUBLISHER !
    _APTSCB-ADAPTER @ _APTSCB.ROUTE @ _APTSCB-ROUTE-DIRECT = IF
        0 _APTSCB-SESSION @ PT-TX-ABORT DROP
    ELSE
        _APTSCB-ADAPTER @ _APTSCB.ROUTE @ _APTSCB-ROUTE-OUTPUT = IF
            0 _APTSCB-PUBLISHER @ APTSCBP.CONTEXT @
            _APTSCB-PUBLISHER @ APTSCBP.ABORT-XT @ EXECUTE DROP
        THEN
    THEN
    _APTSCB-ROUTE-IDLE _APTSCB-ADAPTER @ _APTSCB.ROUTE ! ;

