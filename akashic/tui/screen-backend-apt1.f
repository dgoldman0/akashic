\ APTSCB-PUBLISHER-INIT
\   ( session context begin span cell cursor commit abort step settle
\     publisher -- status )
\ Construct a borrowed, engine-neutral publisher only after all fields and
\ its storage relationship to the exact PT session have been preflighted.
: APTSCB-PUBLISHER-INIT
    _APTSCBPI-PUBLISHER ! _APTSCBPI-SETTLE ! _APTSCBPI-STEP !
    _APTSCBPI-ABORT ! _APTSCBPI-COMMIT ! _APTSCBPI-CURSOR !
    _APTSCBPI-CELL ! _APTSCBPI-SPAN ! _APTSCBPI-BEGIN !
    _APTSCBPI-CONTEXT ! _APTSCBPI-SESSION !
    _APTSCBPI-SESSION @ 0= _APTSCBPI-CONTEXT @ 0= OR
    _APTSCBPI-BEGIN @ 0= OR _APTSCBPI-SPAN @ 0= OR
    _APTSCBPI-CELL @ 0= OR _APTSCBPI-CURSOR @ 0= OR
    _APTSCBPI-COMMIT @ 0= OR _APTSCBPI-ABORT @ 0= OR
    _APTSCBPI-STEP @ 0= OR _APTSCBPI-SETTLE @ 0= OR IF
        SCB-S-INVALID EXIT
    THEN
    _APTSCBPI-PUBLISHER @ 0= IF SCB-S-INVALID EXIT THEN
    _APTSCBPI-PUBLISHER @ 7 AND IF SCB-S-INVALID EXIT THEN
    _APTSCBPI-PUBLISHER @ APTSCB-PUBLISHER-SIZE
        MSPAN-NONWRAPPING? 0= IF SCB-S-INVALID EXIT THEN
    _APTSCBPI-PUBLISHER @ APTSCB-PUBLISHER-SIZE
        _APTSCBPI-SESSION @ PT-STORAGE-DISJOINT? 0= IF
        SCB-S-INVALID EXIT
    THEN
    _APTSCBPI-PUBLISHER @ APTSCB-PUBLISHER-SIZE 0 FILL
    _APTSCBPI-SESSION @ _APTSCBPI-PUBLISHER @ APTSCBP.SESSION !
    _APTSCBPI-CONTEXT @ _APTSCBPI-PUBLISHER @ APTSCBP.CONTEXT !
    _APTSCBPI-BEGIN @ _APTSCBPI-PUBLISHER @ APTSCBP.BEGIN-XT !
    _APTSCBPI-SPAN @ _APTSCBPI-PUBLISHER @ APTSCBP.SPAN-XT !
    _APTSCBPI-CELL @ _APTSCBPI-PUBLISHER @ APTSCBP.CELL-XT !
    _APTSCBPI-CURSOR @ _APTSCBPI-PUBLISHER @ APTSCBP.CURSOR-XT !
    _APTSCBPI-COMMIT @ _APTSCBPI-PUBLISHER @ APTSCBP.COMMIT-XT !
    _APTSCBPI-ABORT @ _APTSCBPI-PUBLISHER @ APTSCBP.ABORT-XT !
    _APTSCBPI-STEP @ _APTSCBPI-PUBLISHER @ APTSCBP.STEP-XT !
    _APTSCBPI-SETTLE @ _APTSCBPI-PUBLISHER @ APTSCBP.SETTLE-XT !
    _APTSCBP-MAGIC _APTSCBPI-PUBLISHER @ APTSCBP.MAGIC !
    SCB-S-OK ;

