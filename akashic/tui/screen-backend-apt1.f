\ Install once after complete validation.  Repeating the exact same binding
\ is idempotent; replacement and cross-session attachment are forbidden.
: APTSCB-PUBLISHER!  ( publisher adapter -- status )
    _APTSCBPA-ADAPTER ! _APTSCBPA-PUBLISHER !
    _APTSCBPA-ADAPTER @ APTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _APTSCBPA-PUBLISHER @ APTSCB-PUBLISHER-VALID? 0= IF
        SCB-S-INVALID EXIT
    THEN
    _APTSCBPA-ADAPTER @ _APTSCB.ROUTE @ _APTSCB-ROUTE-IDLE <> IF
        SCB-S-WOULD-BLOCK EXIT
    THEN
    _APTSCBPA-PUBLISHER @ APTSCBP.SESSION @
    _APTSCBPA-ADAPTER @ APTSCB.SESSION @ <> IF SCB-S-INVALID EXIT THEN
    _APTSCBPA-PUBLISHER @ APTSCB-PUBLISHER-SIZE _APTSCBPA-ADAPTER @
        APTSCB-STORAGE-DISJOINT? 0= IF SCB-S-INVALID EXIT THEN
    _APTSCBPA-ADAPTER @ APTSCB.PUBLISHER @ ?DUP IF
        _APTSCBPA-PUBLISHER @ = IF SCB-S-OK ELSE SCB-S-INVALID THEN EXIT
    THEN
    _APTSCBPA-PUBLISHER @ _APTSCBPA-ADAPTER @ APTSCB.PUBLISHER !
    SCB-S-OK ;

