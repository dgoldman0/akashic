\ =====================================================================
\ field-content.f -- Checked canonical UFLD to FDC1 content lowering
\ =====================================================================
\ The outer label remains separate CONTROL data.  This encoder allocates
\ nothing, copies no native padding, and accepts byte-aligned destinations.
PROVIDED akashic-tui-field-content
REQUIRE field-model.f

0 CONSTANT UFLDC-S-OK
1 CONSTANT UFLDC-S-CAPACITY
2 CONSTANT UFLDC-S-INVALID
96 CONSTANT UFLDC-HEADER-SIZE
0x31434446 CONSTANT UFLDC-TAG

CREATE _UFLDC-OWNED-START
VARIABLE _UFLDC-OWNED-LIMIT
0 _UFLDC-OWNED-LIMIT !

: UFLDC-STORAGE-DISJOINT? ( address bytes -- flag )
    2DUP UFLD-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    _UFLDC-OWNED-LIMIT @ DUP _UFLDC-OWNED-START U< IF DROP 2DROP 0 EXIT THEN
    _UFLDC-OWNED-START - _UFLDC-OWNED-START SWAP MSPAN-OVERLAP? 0= ;

VARIABLE _UFLDC-M
VARIABLE _UFLDC-NEED
VARIABLE _UFLDC-R
VARIABLE _UFLDC-DST
VARIABLE _UFLDC-CAP
VARIABLE _UFLDC-OUT

: _UFLDC-ADD? ( u -- flag )
    _UFLDC-NEED @ + DUP 0x100000000 U< 0= IF DROP 0 EXIT THEN
    _UFLDC-NEED ! -1 ;

: UFLDC-BYTES ( model bytes -- wire-bytes status )
    2DUP UFLDC-STORAGE-DISJOINT? 0= IF 2DROP 0 UFLDC-S-INVALID EXIT THEN
    2DUP UFLD-VALIDATE UFLD-S-OK <> IF 2DROP 0 UFLDC-S-INVALID EXIT THEN
    DROP _UFLDC-M ! UFLDC-HEADER-SIZE _UFLDC-NEED !
    _UFLDC-M @ UFLD-TEXT-BYTES@ _UFLDC-ADD? 0= IF 0 UFLDC-S-CAPACITY EXIT THEN
    _UFLDC-M @ UFLD-CHOICE-FIRST _UFLDC-R !
    _UFLDC-M @ UFLD-CHOICE-COUNT@ 0 ?DO
        _UFLDC-R @ UFLD-CHOICE-LABEL@ NIP 16 + _UFLDC-ADD? 0= IF
            0 UFLDC-S-CAPACITY UNLOOP EXIT
        THEN
        _UFLDC-R @ UFLD-CHOICE-NEXT _UFLDC-R !
    LOOP _UFLDC-NEED @ UFLDC-S-OK ;

: _UFLDC-LE! ( value address bytes -- )
    0 ?DO OVER 255 AND OVER I + C! SWAP 8 RSHIFT SWAP LOOP 2DROP ;
: _UFLDC-U16! ( value offset -- ) _UFLDC-DST @ + 2 _UFLDC-LE! ;
: _UFLDC-U32! ( value offset -- ) _UFLDC-DST @ + 4 _UFLDC-LE! ;
: _UFLDC-U64! ( value offset -- ) _UFLDC-DST @ + 8 _UFLDC-LE! ;

: _UFLDC-HEADER! ( -- )
    _UFLDC-DST @ UFLDC-HEADER-SIZE 0 FILL
    UFLDC-TAG 0 _UFLDC-U32! 1 4 _UFLDC-U16!
    _UFLDC-M @ UFLD-KIND@ 6 _UFLDC-U16!
    _UFLDC-M @ UFLD-REVISION@ 8 _UFLDC-U64!
    _UFLDC-M @ UFLD-FLAGS@ 16 _UFLDC-U32!
    _UFLDC-M @ UFLD-LABEL-COLUMN@ 24 _UFLDC-U32!
    _UFLDC-M @ UFLD-LABEL-ROW@ 28 _UFLDC-U32!
    _UFLDC-M @ UFLD-LABEL-WIDTH@ 32 _UFLDC-U32!
    _UFLDC-M @ UFLD-LABEL-HEIGHT@ 36 _UFLDC-U32!
    _UFLDC-M @ UFLD-VALUE-COLUMN@ 40 _UFLDC-U32!
    _UFLDC-M @ UFLD-VALUE-ROW@ 44 _UFLDC-U32!
    _UFLDC-M @ UFLD-VALUE-WIDTH@ 48 _UFLDC-U32!
    _UFLDC-M @ UFLD-VALUE-HEIGHT@ 52 _UFLDC-U32!
    _UFLDC-M @ UFLD-VALUE@ 56 _UFLDC-U64!
    _UFLDC-M @ UFLD-MINIMUM@ 64 _UFLDC-U64!
    _UFLDC-M @ UFLD-MAXIMUM@ 72 _UFLDC-U64!
    _UFLDC-M @ UFLD-STEP@ 80 _UFLDC-U64!
    _UFLDC-M @ UFLD-CHOICE-COUNT@ 88 _UFLDC-U32!
    _UFLDC-M @ UFLD-TEXT-BYTES@ 92 _UFLDC-U32! ;

: _UFLDC-CONTENT! ( -- )
    _UFLDC-DST @ UFLDC-HEADER-SIZE + _UFLDC-OUT !
    _UFLDC-M @ UFLD-KIND@ UFLD-K-TEXT = IF
        _UFLDC-M @ UFLD-TEXT@ _UFLDC-OUT @ SWAP MOVE EXIT
    THEN
    _UFLDC-M @ UFLD-CHOICE-FIRST _UFLDC-R !
    _UFLDC-M @ UFLD-CHOICE-COUNT@ 0 ?DO
        _UFLDC-OUT @ 16 0 FILL
        _UFLDC-R @ UFLD-CHOICE-VALUE@ _UFLDC-OUT @ 8 _UFLDC-LE!
        _UFLDC-R @ UFLD-CHOICE-LABEL@ NIP _UFLDC-OUT @ 8 + 4 _UFLDC-LE!
        16 _UFLDC-OUT +!
        _UFLDC-R @ UFLD-CHOICE-LABEL@ _UFLDC-OUT @ SWAP MOVE
        _UFLDC-R @ UFLD-CHOICE-LABEL@ NIP _UFLDC-OUT +!
        _UFLDC-R @ UFLD-CHOICE-NEXT _UFLDC-R !
    LOOP ;

: UFLDC-PACK ( model bytes output-address capacity -- used status )
    2DUP UFLDC-STORAGE-DISJOINT? 0= IF 2DROP 2DROP 0 UFLDC-S-INVALID EXIT THEN
    3 PICK 3 PICK UFLDC-STORAGE-DISJOINT? 0= IF 2DROP 2DROP 0 UFLDC-S-INVALID EXIT THEN
    OVER 0= IF 2DROP 2DROP 0 UFLDC-S-INVALID EXIT THEN
    3 PICK 3 PICK 3 PICK 3 PICK MSPAN-OVERLAP? IF 2DROP 2DROP 0 UFLDC-S-INVALID EXIT THEN
    _UFLDC-CAP ! _UFLDC-DST !
    UFLDC-BYTES DUP IF EXIT THEN DROP
    _UFLDC-CAP @ U> IF 0 UFLDC-S-CAPACITY EXIT THEN
    \ All fallible work precedes the first destination write.
    _UFLDC-HEADER! _UFLDC-CONTENT!
    _UFLDC-NEED @ UFLDC-S-OK ;

[DEFINED] GUARDED [IF] GUARDED [IF]
REQUIRE ../concurrency/guard.f
GUARD _ufldc-guard
' UFLDC-BYTES CONSTANT _ufldc-bytes-xt
' UFLDC-PACK CONSTANT _ufldc-pack-xt
: UFLDC-BYTES _ufldc-bytes-xt _ufldc-guard WITH-GUARD ;
: UFLDC-PACK _ufldc-pack-xt _ufldc-guard WITH-GUARD ;
[THEN] [THEN]

CREATE _UFLDC-OWNED-END
_UFLDC-OWNED-END _UFLDC-OWNED-LIMIT !
