    _RUCP-R.STATE @ DUP UMSN-F-OPEN AND IF
        _RUCP-OPEN-SEEN @ IF DROP 0 EXIT THEN
        -1 _RUCP-OPEN-SEEN !
    THEN
    UMSN-F-SELECTED AND IF
        _RUCP-SELECTED-SEEN @ IF 0 EXIT THEN
        -1 _RUCP-SELECTED-SEEN !
    THEN
    -1 ;

