: _RUCP-SCALARS?  ( -- flag )
    _RUCP-Q @ _RUCP-Q.RESERVED @ IF 0 EXIT THEN
    _RUCP-ATTACHMENT @ 0= _RUCP-OWNER @ 0= OR
    _RUCP-OWNER-GEN @ 0= OR _RUCP-SOURCE-GEN @ 0= OR IF 0 EXIT THEN
    _RUCP-SURFACE-W @ DUP 0= IF DROP 0 EXIT THEN
    _RUCP-U32? 0= IF 0 EXIT THEN
