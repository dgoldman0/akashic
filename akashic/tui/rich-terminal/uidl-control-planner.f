    _RUCP-RECORD @ _RUCP-R.SHORTCUT-U @ OVER _RTE-CONTROL.SHORTCUT-U !
    DROP
    _RUCP-NEXT-ID @ _RUCP-RECORD @ _RUCP-R.INDEX @ _RUCP-LOOKUP-AT
        _RUCP-L.CONTROL-ID !
    1 _RUCP-OUTPUT-COUNT +!
    _RUCP-OUTPUT-COUNT @ _RUCP-RECORD-COUNT @ < IF
        1 _RUCP-NEXT-ID +!
    THEN ;

: _RUCP-BUCKET-MENUS?  ( -- flag )
    _RUCP-CLEAR-ORDER-A
    _RUCP-RECORD-COUNT @ 0 ?DO
        I _RUCP-RECORD-AT DUP _RUCP-RECORD !
        _RUCP-R.KIND @ UMSN-K-MENU = IF
            _RUCP-RECORD @ _RUCP-R.ORDINAL @ DUP _RUCP-ORDER-CAP @
                U< 0= IF DROP _RUCP-SET-CAPACITY 0 UNLOOP EXIT THEN
            DUP _RUCP-HIGH-WATER @ U< 0= IF DROP 0 UNLOOP EXIT THEN
            _RUCP-ORDER-AT DUP @ IF DROP 0 UNLOOP EXIT THEN
            _RUCP-RECORD @ SWAP !
        THEN
    LOOP
    -1 ;

