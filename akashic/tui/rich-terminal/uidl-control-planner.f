    _RUCP-MENU-COUNT @ 0 ?DO
        I _RUCP-LOOKUP-AT DUP _RUCP-LOOKUP !
        _RUCP-TOTAL @ OVER _RUCP-L.CURSOR !
        _RUCP-TOTAL @ SWAP _RUCP-L.COUNT @ _RUCP-UADD? 0= IF
            DROP 0 UNLOOP EXIT
        THEN
        _RUCP-TOTAL !
    LOOP
