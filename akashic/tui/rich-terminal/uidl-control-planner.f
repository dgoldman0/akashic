    0 _RUCP-OUTPUT-COUNT !
    _RUCP-MENUBAR @ _RUCP-WRITE-CONTROL
    _RUCP-NEXT-ID @ _RUCP-MENU-FIRST-ID !
    0 _RUCP-TOTAL ! 0 _RUCP-OPEN-SEEN ! 0 _RUCP-SELECTED-SEEN !
    _RUCP-HIGH-WATER @ 0 ?DO
        I _RUCP-ORDER-AT @ ?DUP IF
            DUP _RUCP-MENU-STATE-UNIQUE? 0= IF
                DROP 0 UNLOOP EXIT
            THEN
            _RUCP-WRITE-CONTROL 1 _RUCP-TOTAL +!
        THEN
    LOOP
    _RUCP-TOTAL @ _RUCP-MENU-COUNT @ = ;

: _RUCP-COUNT-ROW-ORDINALS?  ( -- flag )
    _RUCP-CLEAR-ORDER-A
    _RUCP-RECORD-COUNT @ 0 ?DO
        I _RUCP-RECORD-AT DUP _RUCP-RECORD ! _RUCP-R.KIND @
        DUP UMSN-K-ITEM = SWAP UMSN-K-SEPARATOR = OR IF
            _RUCP-RECORD @ _RUCP-R.ORDINAL @ DUP _RUCP-ORDER-CAP @
                U< 0= IF DROP _RUCP-SET-CAPACITY 0 UNLOOP EXIT THEN
            DUP _RUCP-HIGH-WATER @ U< 0= IF DROP 0 UNLOOP EXIT THEN
            _RUCP-ORDER-AT DUP @ 1 _RUCP-UADD? 0= IF
                DROP DROP 0 UNLOOP EXIT
            THEN SWAP !
        THEN
    LOOP
    -1 ;

