            DROP 0 UNLOOP EXIT
        THEN DUP _RUCP-TOTAL ! I _RUCP-ORDER-AT !
    LOOP
    _RUCP-TOTAL @ _RUCP-ROW-COUNT @ = ;

: _RUCP-SORT-ROWS-BY-ORDINAL  ( -- )
    _RUCP-CLEAR-ORDER2
    _RUCP-RECORD-COUNT @ _RUCP-I !
    BEGIN _RUCP-I @ 0> WHILE
        -1 _RUCP-I +!
        _RUCP-I @ _RUCP-RECORD-AT DUP _RUCP-RECORD ! _RUCP-R.KIND @
        DUP UMSN-K-ITEM = SWAP UMSN-K-SEPARATOR = OR IF
            _RUCP-RECORD @ _RUCP-R.ORDINAL @ _RUCP-ORDER-AT
            DUP @ 1- DUP ROT ! _RUCP-ORDER2-AT
            _RUCP-RECORD @ SWAP !
        THEN
    REPEAT ;

