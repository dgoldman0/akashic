: _RUCP-SORT-ROWS-BY-PARENT  ( -- )
    _RUCP-CLEAR-ORDER-A
    _RUCP-ROW-COUNT @ 0 ?DO
        I _RUCP-ORDER2-AT @ DUP _RUCP-RECORD !
        _RUCP-ROW-PARENT-KEY? DROP _RUCP-LOOKUP-AT DUP _RUCP-LOOKUP !
        _RUCP-L.CURSOR @ DUP _RUCP-ORDER-AT
            _RUCP-RECORD @ SWAP !
        1+ _RUCP-LOOKUP @ _RUCP-L.CURSOR !
    LOOP ;

: _RUCP-ORDERED-ROWS?  ( -- flag )
    0 _RUCP-HAVE-PRIOR ! 0 _RUCP-PARENT-ID ! 0 _RUCP-ORDINAL !
    0 _RUCP-SELECTED-SEEN !
    _RUCP-ROW-COUNT @ 0 ?DO
        I _RUCP-ORDER-AT @ DUP 0= IF DROP 0 UNLOOP EXIT THEN
        DUP _RUCP-RECORD ! _RUCP-CONTROL-PARENT-ID
            DUP _RUCP-NEXT ! DROP
        _RUCP-RECORD @ _RUCP-R.ORDINAL @ _RUCP-J !
        _RUCP-HAVE-PRIOR @ IF
            _RUCP-NEXT @ _RUCP-PARENT-ID @ U< IF 0 UNLOOP EXIT THEN
            _RUCP-NEXT @ _RUCP-PARENT-ID @ = IF
                _RUCP-J @ _RUCP-ORDINAL @ U> 0= IF 0 UNLOOP EXIT THEN
            ELSE
                0 _RUCP-SELECTED-SEEN !
            THEN
        THEN
        _RUCP-RECORD @ _RUCP-R.STATE @ UMSN-F-SELECTED AND IF
            _RUCP-SELECTED-SEEN @ IF 0 UNLOOP EXIT THEN
            -1 _RUCP-SELECTED-SEEN !
        THEN
        _RUCP-NEXT @ _RUCP-PARENT-ID ! _RUCP-J @ _RUCP-ORDINAL !
        -1 _RUCP-HAVE-PRIOR !
    LOOP
    -1 ;

