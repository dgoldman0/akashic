\ =====================================================================
\  uidl-control-planner.f -- UMSN to neutral rich-control planning
\ =====================================================================
\
\  Builds one initial/all-new RTE CONTROL plan from a canonical UIDL menu
\  snapshot.  This module is a pure, synchronous, caller-bounded adapter:
\  it allocates nothing, calls no facade or transport, and knows no Desk,
\  host, UCTX, or application API.
\
\  Source keys remain in canonical UMSN order in the persistent correlation
\  output.  CONTROL records are independently emitted in the graph order the
\  neutral engine requires: MENUBAR, all MENU controls, then rows grouped by
\  parent and authored ordinal.  Caller lookup and two order banks avoid
\  repeated searches, including legal cases where a parent has a newer source
\  index than its child.  Total work is linear in records, source high-water,
\  validated UTF-8 bytes, and the supplied mutable spans cleared atomically.
\  The one shared neutral plan region retains its signed logical root and
\  independent physical clip; source control geometry is never cropped to
\  impersonate per-control clipping.
\
\  UMSN text remains caller-owned.  CONTROL text pointers borrow it only for
\  an immediate RTE-CONTROL-PREFLIGHT, RTE-HYBRID-PREFLIGHT, or definition
\  phase; the plan and CONTROL bank must not outlive or be used across mutation
\  of that text.  Correlation records are pointer-free and may persist.
\
\  Public build API:
\    RUCP-BUILD
\      ( request -- count text aligned-text max-item-text last-id status )
\
\  Prefix: RUCP- (contract), _RUCP- (implementation)

