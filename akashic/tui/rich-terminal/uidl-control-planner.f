    _RUCP-ROW-COUNT @ 0 ?DO
        I _RUCP-ORDER2-AT @ _RUCP-ROW-PARENT-KEY? 0= IF
            DROP 0 UNLOOP EXIT
        THEN
        _RUCP-LOOKUP-AT DUP _RUCP-L.COUNT @ 1 _RUCP-UADD? 0= IF
            DROP DROP 0 UNLOOP EXIT
