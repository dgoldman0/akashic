    _RTERM-MS-RESTART? IF
        _RTERM-MS-START-EPOCH
        RTERM-S-OK -1 0 _RTERM-MS-RESULT! EXIT
    THEN
    _RTERM-MS-MAT @ _RTERM-M.RECORD-INDEX @
        _RTERM-MS-BACKEND @ _RTERM-B.CAPACITY @ U< IF
        RTERM-S-OK -1 0
    ELSE
        _RTERM-MS-MAT @ _RTERM-M.FLAGS @
            _RTERM-MAT-F-STARTED AND IF
            RTERM-S-OK 0 -1
        ELSE RTERM-S-OK 0 0 THEN
    THEN
    _RTERM-MS-RESULT! ;

