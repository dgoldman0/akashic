    _RTERM-L-SLOT @ AHS-VISIBLE? 0= ;

: _RTERM-RELAYOUT-COMMIT  ( -- )
    _RTERM-RL-VISIBLE @ IF
        _RTERM-RL-REGION @ DUP _RTERM-REGION>GEOMETRY
        _RTERM-C-RECORD @ _RTERM-R.REGION !
        _RTERM-G-ROW @ _RTERM-C-RECORD @ _RTERM-R.ROW !
        _RTERM-G-COL @ _RTERM-C-RECORD @ _RTERM-R.COL !
        _RTERM-G-HEIGHT @ _RTERM-C-RECORD @ _RTERM-R.HEIGHT !
        _RTERM-G-WIDTH @ _RTERM-C-RECORD @ _RTERM-R.WIDTH !
        -1 _RTERM-C-RECORD @ _RTERM-R.VISIBLE !
    ELSE
        _RTERM-C-RECORD @ _RTERM-R.REGION 48 0 FILL
    THEN ;

: _RTERM-UCTX-RELAYOUT-BODY
    ( visible region binding-token backend -- status )
    _RTERM-RL-BACKEND ! _RTERM-RL-TOKEN !
    _RTERM-RL-REGION ! _RTERM-RL-VISIBLE !
    _RTERM-RL-VISIBLE @ _RTERM-BOOL? 0= IF RTERM-S-INVALID EXIT THEN
    _RTERM-RL-TOKEN @ _RTERM-RL-BACKEND @
        _RTERM-CALL-LOOKUP 0= IF
        _RTERM-C-STATUS @ _RTERM-CALL-FAIL EXIT
    THEN
    _RTERM-C-RECORD @ _RTERM-R.STATE @
        _RTERM-BINDING-ST-ATTACHED <> IF
        RTERM-S-STALE _RTERM-CALL-FAIL EXIT
    THEN
    _RTERM-CALL-LIVE? 0= IF RTERM-S-STALE _RTERM-CALL-FAIL EXIT THEN
    _RTERM-RL-VISIBLE @ IF
        _RTERM-RELAYOUT-VISIBLE? 0= IF
            RTERM-S-INVALID _RTERM-CALL-FAIL EXIT
        THEN
    ELSE
        _RTERM-RELAYOUT-HIDDEN? 0= IF
            RTERM-S-INVALID _RTERM-CALL-FAIL EXIT
        THEN
    THEN
    _RTERM-RELAYOUT-COMMIT
    RTERM-S-OK ;

: _RTERM-UCTX-QUIESCE-BODY  ( binding-token backend -- status )
    2DUP _RTERM-CALL-LOOKUP 0= IF
        2DROP _RTERM-C-STATUS @ _RTERM-CALL-FAIL EXIT
    THEN
    2DROP
    _RTERM-C-RECORD @ _RTERM-R.STATE @
        _RTERM-BINDING-ST-DETACHED = IF RTERM-S-OK EXIT THEN
    _RTERM-C-RECORD @ _RTERM-R.STATE @ DUP
        _RTERM-BINDING-ST-ATTACHED = SWAP
        _RTERM-BINDING-ST-QUIESCED = OR 0= IF
        RTERM-S-INVALID _RTERM-CALL-FAIL EXIT
    THEN
    _RTERM-CALL-LIVE? 0= IF RTERM-S-STALE _RTERM-CALL-FAIL EXIT THEN
    RTERM-S-OK _RTERM-C-RECORD @ _RTERM-R.LAST-STATUS !
    _RTERM-BINDING-ST-QUIESCED _RTERM-C-RECORD @ _RTERM-R.STATE !
    RTERM-S-OK ;

VARIABLE _RTERM-D-TOKEN

: _RTERM-UCTX-DETACH-BODY  ( binding-token backend -- status )
    2DUP _RTERM-CALL-LOOKUP 0= IF
        2DROP _RTERM-C-STATUS @ _RTERM-CALL-FAIL EXIT
    THEN
    2DROP
    _RTERM-C-RECORD @ _RTERM-R.STATE @
        _RTERM-BINDING-ST-DETACHED = IF RTERM-S-OK EXIT THEN
    _RTERM-C-RECORD @ _RTERM-R.STATE @
        _RTERM-BINDING-ST-QUIESCED <> IF
        RTERM-S-INVALID _RTERM-CALL-FAIL EXIT
    THEN
    _RTERM-CALL-LIVE? 0= IF RTERM-S-STALE _RTERM-CALL-FAIL EXIT THEN
    _RTERM-C-BACKEND @ _RTERM-B.ACTIVE @ 0= IF
        RTERM-S-INVALID _RTERM-CALL-FAIL EXIT
    THEN
    _RTERM-C-RECORD @ _RTERM-R.TOKEN @ _RTERM-D-TOKEN !
    _RTERM-C-RECORD @ RTERM-UIDL-BINDING-SIZE 0 FILL
    _RTERM-D-TOKEN @ _RTERM-C-RECORD @ _RTERM-R.TOKEN !
    _RTERM-C-BACKEND @ _RTERM-C-RECORD @ _RTERM-R.ISSUER !
    RTERM-S-OK _RTERM-C-RECORD @ _RTERM-R.LAST-STATUS !
    _RTERM-BINDING-ST-DETACHED _RTERM-C-RECORD @ _RTERM-R.STATE !
    -1 _RTERM-C-BACKEND @ _RTERM-B.ACTIVE +!
    RTERM-S-OK ;

