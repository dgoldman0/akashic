: _RTERM-RECORD-LIVE?  ( -- flag )
    _RTERM-RV-RECORD @ _RTERM-R.TOKEN @ 0<>
    _RTERM-RV-RECORD @ _RTERM-R.ISSUER @ _RTERM-RV-BACKEND @ = AND
    _RTERM-RV-RECORD @ _RTERM-R.HOST @
        _RTERM-RV-BACKEND @ _RTERM-B.HOST @ = AND
    _RTERM-RV-RECORD @ _RTERM-R.HOST @ AHOST-SIZE _RTERM-SPAN? AND
    _RTERM-RV-RECORD @ _RTERM-R.SLOT @ AHS-SIZE _RTERM-SPAN? AND
    _RTERM-RV-RECORD @ _RTERM-R.SLOT-ID @ 0<> AND
    _RTERM-RV-RECORD @ _RTERM-R.INST @ COMP-INST _RTERM-SPAN? AND
    _RTERM-RV-RECORD @ _RTERM-R.INST-ID @ 0<> AND
    _RTERM-RV-RECORD @ _RTERM-R.INST-GEN @ 0<> AND
    _RTERM-RV-RECORD @ _RTERM-R.UCTX @ UCTX-TOTAL _RTERM-SPAN? AND
    _RTERM-RV-RECORD @ _RTERM-R.VISIBLE @ _RTERM-BOOL? AND
    _RTERM-RV-RECORD @ _RTERM-R.LAST-STATUS @
        RTERM-STATUS-VALID? AND
    _RTERM-RV-RECORD @ _RTERM-R.RESERVED @ 0= AND
    0= IF 0 EXIT THEN
    _RTERM-RV-RECORD @ _RTERM-R.VISIBLE @ IF
        _RTERM-RV-RECORD @ _RTERM-R.REGION @ RGN-SIZE
            _RTERM-SPAN? 0= IF 0 EXIT THEN
        _RTERM-RV-RECORD @ _RTERM-R.ROW @
        _RTERM-RV-RECORD @ _RTERM-R.COL @
        _RTERM-RV-RECORD @ _RTERM-R.HEIGHT @
        _RTERM-RV-RECORD @ _RTERM-R.WIDTH @
        _RTERM-GEOMETRY?
    ELSE
        _RTERM-RV-RECORD @ _RTERM-R.REGION 48 _RTERM-ZERO?
    THEN ;

: _RTERM-RECORD-VALID?  ( record backend -- flag )
    _RTERM-RV-BACKEND ! _RTERM-RV-RECORD !
    _RTERM-RV-RECORD @ _RTERM-R.STATE @ DUP
    _RTERM-BINDING-ST-FREE = IF
        DROP _RTERM-RV-RECORD @ RTERM-UIDL-BINDING-SIZE _RTERM-ZERO? EXIT
    THEN
    DUP _RTERM-BINDING-ST-ATTACHED =
    SWAP _RTERM-BINDING-ST-QUIESCED = OR IF
        _RTERM-RECORD-LIVE? EXIT
    THEN
    _RTERM-RV-RECORD @ _RTERM-R.STATE @
        _RTERM-BINDING-ST-DETACHED = IF
        _RTERM-RECORD-DETACHED? EXIT
    THEN
    0 ;

VARIABLE _RTERM-V-BACKEND
VARIABLE _RTERM-V-ACTIVE

: _RTERM-UIDL-VALID-BODY?  ( backend -- flag )
    DUP RTERM-UIDL-BACKEND-SIZE _RTERM-SPAN? 0= IF DROP 0 EXIT THEN
    DUP _RTERM-B.MAGIC @ _RTERM-UIDL-MAGIC <> IF DROP 0 EXIT THEN
    DUP _RTERM-B.ABI @ _RTERM-UIDL-ABI <> IF DROP 0 EXIT THEN
    DUP _RTERM-B.SIZE @ RTERM-UIDL-BACKEND-SIZE <> IF DROP 0 EXIT THEN
    DUP _RTERM-B.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _RTERM-B.STATUS @ RTERM-STATUS-VALID? 0= IF DROP 0 EXIT THEN
    DUP _RTERM-B.INSTALLED @ _RTERM-BOOL? 0= IF DROP 0 EXIT THEN
    DUP _RTERM-B.RESERVED @ IF DROP 0 EXIT THEN
    DUP _RTERM-V-BACKEND !
    DUP _RTERM-B.HOST @ _RTERM-I-HOST !
    DUP _RTERM-B.RECORDS-A @ _RTERM-I-RECORDS-A !
    DUP _RTERM-B.RECORDS-U @ _RTERM-I-RECORDS-U !
    _RTERM-I-BACKEND !
    _RTERM-UIDL-RANGES? 0= IF 0 EXIT THEN
    _RTERM-I-RECORDS-U @ RTERM-UIDL-BINDING-SIZE /
        _RTERM-V-BACKEND @ _RTERM-B.CAPACITY @ <> IF 0 EXIT THEN
    _RTERM-V-BACKEND @ _RTERM-B.ACTIVE @ DUP 0< IF DROP 0 EXIT THEN
    _RTERM-V-BACKEND @ _RTERM-B.CAPACITY @ > IF 0 EXIT THEN
    0 _RTERM-V-ACTIVE !
    _RTERM-V-BACKEND @ _RTERM-B.CAPACITY @ 0 ?DO
        I _RTERM-V-BACKEND @ _RTERM-RECORD-AT
        DUP _RTERM-V-BACKEND @ _RTERM-RECORD-VALID? 0= IF
            DROP 0 UNLOOP EXIT
        THEN
        _RTERM-R.STATE @ DUP _RTERM-BINDING-ST-ATTACHED =
        SWAP _RTERM-BINDING-ST-QUIESCED = OR IF
            1 _RTERM-V-ACTIVE +!
        THEN
    LOOP
    _RTERM-V-ACTIVE @ _RTERM-V-BACKEND @ _RTERM-B.ACTIVE @ = ;

