\ Physical desired slots are record-major: A then B for each binding.  The
\ final physical slot is one backend-global frozen-attempt bank.  Addresses
\ are always re-derived from backend geometry; records never retain pointers
\ into caller-owned slabs.
: _RTERM-SLOT-LOAD  ( slot backend -- flag )
    _RTERM-BK-BACKEND ! _RTERM-BK-SLOT !
    _RTERM-BK-BACKEND @ _RTERM-B.CAPACITY @ 2
        _RTERM-UMUL? 0= IF DROP 0 EXIT THEN
    1 _RTERM-UADD? 0= IF DROP 0 EXIT THEN
        _RTERM-BK-SLOT @ U> 0= IF 0 EXIT THEN
    _RTERM-BK-BACKEND @ _RTERM-B.ITEMS-PER-BANK @ RUPJ-ITEM-BYTES
        _RTERM-UMUL? 0= IF DROP 0 EXIT THEN
    _RTERM-BK-ITEM-U !

    _RTERM-BK-SLOT @ 0= IF
        0
    ELSE
        _RTERM-BK-SLOT @ _RTERM-BK-ITEM-U @
            _RTERM-UMUL? 0= IF DROP 0 EXIT THEN
    THEN
    DUP _RTERM-BK-OFFSET !
    _RTERM-BK-ITEM-U @ _RTERM-UADD? 0= IF DROP 0 EXIT THEN
    _RTERM-BK-BACKEND @ _RTERM-B.ITEMS-U @ U> IF 0 EXIT THEN
    _RTERM-BK-BACKEND @ _RTERM-B.ITEMS-A @
        _RTERM-BK-OFFSET @ _RTERM-UADD? 0= IF DROP 0 EXIT THEN
    _RTERM-BK-ITEM-A !

    _RTERM-BK-BACKEND @ _RTERM-B.ITEMS-PER-BANK @
        _RTERM-IDENTITY-SIZE _RTERM-UMUL? 0= IF DROP 0 EXIT THEN
    _RTERM-BK-IDENTITY-U !
    _RTERM-BK-SLOT @ 0= IF
        0
    ELSE
        _RTERM-BK-SLOT @ _RTERM-BK-IDENTITY-U @
            _RTERM-UMUL? 0= IF DROP 0 EXIT THEN
    THEN
    DUP _RTERM-BK-OFFSET !
    _RTERM-BK-IDENTITY-U @ _RTERM-UADD? 0= IF DROP 0 EXIT THEN
    _RTERM-BK-BACKEND @ _RTERM-B.IDENTITIES-U @ U> IF 0 EXIT THEN
    _RTERM-BK-BACKEND @ _RTERM-B.IDENTITIES-A @
        _RTERM-BK-OFFSET @ _RTERM-UADD? 0= IF DROP 0 EXIT THEN
    _RTERM-BK-IDENTITY-A !

    _RTERM-BK-SLOT @ 0= IF
        0
    ELSE
        _RTERM-BK-SLOT @
        _RTERM-BK-BACKEND @ _RTERM-B.SNAPSHOT-BANK-U @
            _RTERM-UMUL? 0= IF DROP 0 EXIT THEN
    THEN
