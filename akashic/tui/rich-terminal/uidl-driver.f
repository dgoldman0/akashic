: _RTERM-NOTE  ( status backend -- status )
    OVER DUP RTERM-S-CAPACITY =
    OVER RTERM-S-INVALID = OR
    OVER RTERM-S-SESSION-LOST = OR
    SWAP RTERM-S-SOURCE = OR IF
        DUP _RTERM-B.STATUS @ RTERM-S-OK = IF
            OVER OVER _RTERM-B.STATUS !
        THEN
    THEN
    DROP ;

