    \ A terminal epoch reports its terminal cause, not an older sticky
    \ advisory failure.  Publish the normalized cause before the epoch marker.
    _RTERM-MS-CALL-STATUS @ _RTERM-MS-BACKEND @ _RTERM-B.STATUS !
    _RTERM-EPOCH-QUARANTINED _RTERM-MS-BACKEND @ _RTERM-B.EPOCH !
