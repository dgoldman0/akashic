    _RTERM-MS-CALL-STATUS !
    _RTERM-MS-CLEAN-ATTEMPT
    _RTERM-MS-BACKEND @ _RTERM-B.CAPACITY @ 0 ?DO
        I _RTERM-MS-BACKEND @ _RTERM-RECORD-AT DUP
            _RTERM-R.MAT-STATE @ IF
            \ Normalize the whole materialization suffix first.  This repairs
            \ a caught transition between generation stores as well as a
            \ provider-side uncertainty, then publishes QUARANTINED last.
            DUP _RTERM-R.MAT-STATE 40 0 FILL
            _RTERM-MS-CALL-STATUS @ OVER _RTERM-R.LAST-STATUS !
            _RTERM-MAT-ST-QUARANTINED SWAP _RTERM-R.MAT-STATE !
        ELSE
            _RTERM-R.MAT-STATE 40 0 FILL
