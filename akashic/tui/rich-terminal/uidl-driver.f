    _RTERM-PJ-BUILD-STATUS ! _RTERM-PJ-ROOT-W ! _RTERM-PJ-ROOT-H !
    _RTERM-PJ-UTF8 ! _RTERM-PJ-OBJECTS !
    _RTERM-PJ-REGIONS ! _RTERM-PJ-SNAPSHOT-USED ! _RTERM-PJ-ITEMS !
    _RTERM-PJ-BUILD-STATUS @ RUPJ-S-OK <> IF
        _RTERM-PJ-BUILD-STATUS @ RUPJ-S-CAPACITY = IF
            RTERM-S-CAPACITY
        ELSE
            RTERM-S-INVALID
        THEN
        _RTERM-PROJECT-FAIL EXIT
    THEN
    _RTERM-PROJECT-CANDIDATE-VALID? 0= IF
        _RTERM-PROJECT-CLEAR-INACTIVE
        RTERM-S-INVALID _RTERM-PROJECT-FAIL EXIT
    THEN

    \ Deep neutral validation precedes private identity mapping and the only
    \ facade read in this stage.  Mapping authority survives a temporary
    \ eligibility refusal, while retained owner admission and every mutation remain
