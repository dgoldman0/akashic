    DUP _RTERM-EPOCH-LIVE = IF
        DROP DUP _RTERM-B.MAT _RTERM-MAT-VALID? 0= IF DROP 0 EXIT THEN
        _RTERM-B.MAT _RTERM-M.PHASE @ _RTERM-MAT-PHASE-IDLE = EXIT
    THEN
    _RTERM-EPOCH-REBUILD <> IF DROP 0 EXIT THEN
    DUP _RTERM-B.MAT _RTERM-MAT-VALID? 0= IF DROP 0 EXIT THEN
    DUP _RTERM-B.MAT _RTERM-M.PHASE @ DUP
        _RTERM-MAT-PHASE-IDLE =
    SWAP _RTERM-MAT-PHASE-QUARANTINED = OR IF DROP 0 EXIT THEN
    DROP -1 ;

\ Exception recovery must not require the mutable lifecycle state to be
\ semantically valid: a caught callback may follow an uncertainty marker or a
\ partially published local transition.  This narrower proof admits writes
\ only after re-deriving the exact caller-owned storage envelope.
