                0 _RTERM-MS-CALL-STATUS !
            ELSE
                0 0 _RTERM-MS-RESULT! EXIT
            THEN
        THEN
        _RTERM-MS-INDEX @ 1+ _RTERM-MS-MAT @ _RTERM-M.RECORD-INDEX !
        -1 _RTERM-MS-BUDGET +!
        _RTERM-MS-CALL-STATUS @ ?DUP IF
            _RTERM-MS-MAT @ _RTERM-M.RECORD-INDEX @
                _RTERM-MS-BACKEND @ _RTERM-B.CAPACITY @ U<
            0 _RTERM-MS-RESULT! EXIT
        THEN
