    DUP _RTERM-UIDL-VALID-BODY? 0= IF DROP RTERM-S-INVALID EXIT THEN
    DUP _RTERM-B.ACTIVE @ IF DROP RTERM-S-WOULD-BLOCK EXIT THEN
