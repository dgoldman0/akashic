            _RTERM-MAT-ST-STAGED = IF
            DROP
            _RTERM-MS-STAGED-CURRENT? 0= IF
                _RTERM-MS-REQUEST-RESTART
            THEN
            _RTERM-MS-RESTART? IF
                _RTERM-MS-ASSOCIATE-DROP
