: _RTERM-UCTX-PROJECT-BODY  ( binding-token backend -- status )
    2DUP _RTERM-CALL-LOOKUP 0= IF
        2DROP _RTERM-C-STATUS @ _RTERM-CALL-FAIL EXIT
    THEN
    2DROP
    _RTERM-C-RECORD @ _RTERM-R.STATE @
        _RTERM-BINDING-ST-ATTACHED <> IF
        RTERM-S-STALE _RTERM-CALL-FAIL EXIT
    THEN
    _RTERM-CALL-LIVE? 0= IF RTERM-S-STALE _RTERM-CALL-FAIL EXIT THEN
    _RTERM-PROJECT-SELECT DUP RTERM-S-OK <> IF
        _RTERM-PROJECT-FAIL EXIT
    THEN
    DROP

    \ The inactive metadata loses authority before construction.  RUPJ owns
    \ complete clearing of its item/snapshot pair on every build outcome,
    \ the driver clears the positional identity pair independently.
    _RTERM-PJ-META @ _RTERM-CANDIDATE-META-SIZE 0 FILL
    _RTERM-PJ-IDENTITY-A @ _RTERM-PJ-IDENTITY-U @ 0 FILL
    _RTERM-PJ-ITEM-A @ _RTERM-PJ-ITEM-U @
    _RTERM-PJ-SNAPSHOT-A @ _RTERM-PJ-SNAPSHOT-U @ RUPJ-BUILD
    _RTERM-PJ-BUILD-STATUS ! _RTERM-PJ-ROOT-W ! _RTERM-PJ-ROOT-H !
    _RTERM-PJ-UTF8 ! _RTERM-PJ-OBJECTS !
    _RTERM-PJ-REGIONS ! _RTERM-PJ-SNAPSHOT-USED ! _RTERM-PJ-ITEMS !
    _RTERM-PJ-BUILD-STATUS @ RUPJ-S-OK <> IF
        _RTERM-PJ-BUILD-STATUS @ RUPJ-S-CAPACITY = IF
            RTERM-S-CAPACITY
        ELSE
            RTERM-S-INVALID
        THEN
        _RTERM-PROJECT-FAIL EXIT
    THEN
    _RTERM-PROJECT-CANDIDATE-VALID? 0= IF
        _RTERM-PROJECT-CLEAR-INACTIVE
        RTERM-S-INVALID _RTERM-PROJECT-FAIL EXIT
    THEN

    \ Deep neutral validation precedes private identity mapping and the only
    \ facade read in this stage.  Mapping authority survives a temporary
    \ eligibility refusal, while retained owner admission and every mutation remain
    \ the later materializer's responsibility.
    _RTERM-C-RECORD @ _RTERM-R.OBJECT-HIGH @ _RTERM-PJ-NEXT-HIGH !
    _RTERM-PJ-ITEMS @ IF
        _RTERM-PROJECT-MAP-IDENTITIES DUP RTERM-S-OK <> IF
            _RTERM-PROJECT-CLEAR-INACTIVE
            _RTERM-PROJECT-FAIL EXIT
        THEN
        DROP
    THEN
    _RTERM-PROJECT-ELIGIBILITY _RTERM-PJ-ELIGIBILITY-STATUS !

    \ Metadata, identity high-water, eligibility, LAST-STATUS, and any sticky
