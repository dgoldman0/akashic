: _RTERM-MAT-CORRELATION?  ( backend -- flag )
    DUP _RTERM-MV-BACKEND ! _RTERM-B.MAT DUP _RTERM-MV-MAT !
    _RTERM-M.PHASE @ DUP _RTERM-MAT-PHASE-QUARANTINED = IF
        DROP
        _RTERM-MV-BACKEND @ _RTERM-B.CAPACITY @ 0 ?DO
            I _RTERM-MV-BACKEND @ _RTERM-RECORD-AT _RTERM-R.MAT-STATE @
            DUP _RTERM-MAT-ST-NONE =
            SWAP _RTERM-MAT-ST-QUARANTINED = OR 0= IF
                0 UNLOOP EXIT
            THEN
        LOOP
        -1 EXIT
    THEN
    DUP _RTERM-MAT-PHASE-COHORT = IF
        DROP
        _RTERM-MV-MAT @ _RTERM-M.RECORD-INDEX @
            _RTERM-MV-BACKEND @ _RTERM-B.CAPACITY @ U> IF 0 EXIT THEN
        _RTERM-MV-BACKEND @ _RTERM-B.CAPACITY @ 0 ?DO
            I _RTERM-MV-BACKEND @ _RTERM-RECORD-AT _RTERM-R.MAT-STATE @
            _RTERM-MAT-REBUILD-REST-STATE? 0= IF 0 UNLOOP EXIT THEN
        LOOP
        -1 EXIT
    THEN
    DUP _RTERM-MAT-PHASE-REVEAL-SEALED =
    OVER _RTERM-MAT-PHASE-REVEAL-AWAITING = OR IF
        DROP _RTERM-MAT-REVEAL-RECORDS? EXIT
    THEN
    DUP _RTERM-MAT-PHASE-IDLE = IF
        DROP _RTERM-MAT-LIVE-RECORDS? EXIT
    THEN
    _RTERM-MAT-EXPECTED-STATE? 0= IF 0 EXIT THEN
    _RTERM-MV-MAT @ _RTERM-M.RECORD-INDEX @
        _RTERM-MV-BACKEND @ _RTERM-B.CAPACITY @ U< 0= IF 0 EXIT THEN
    _RTERM-MV-MAT @ _RTERM-M.RECORD-INDEX @ _RTERM-MV-BACKEND @
        _RTERM-RECORD-AT DUP _RTERM-MV-RECORD !
    _RTERM-R.TOKEN @ _RTERM-MV-MAT @ _RTERM-M.TOKEN @ =
    _RTERM-MV-RECORD @ _RTERM-R.OWNER @
        _RTERM-MV-MAT @ _RTERM-M.OWNER @ = AND
    _RTERM-MV-RECORD @ _RTERM-R.OWNER-GEN @
        _RTERM-MV-MAT @ _RTERM-M.OWNER-GEN @ = AND
    _RTERM-MV-RECORD @ _RTERM-R.ROOT-REGION @ 1 = AND 0= IF 0 EXIT THEN
    _RTERM-MV-GEOMETRY @ IF
        _RTERM-MV-RECORD @ _RTERM-R.COL @
            _RTERM-MV-MAT @ _RTERM-M.REGION-X @ =
        _RTERM-MV-RECORD @ _RTERM-R.ROW @
            _RTERM-MV-MAT @ _RTERM-M.REGION-Y @ = AND
        _RTERM-MV-RECORD @ _RTERM-R.HEIGHT @
            _RTERM-MV-MAT @ _RTERM-M.ROOT-H @ = AND
        _RTERM-MV-RECORD @ _RTERM-R.WIDTH @
            _RTERM-MV-MAT @ _RTERM-M.ROOT-W @ = AND 0= IF 0 EXIT THEN
    THEN
    _RTERM-MV-RECORD @ _RTERM-R.MAT-STATE @
        _RTERM-MV-EXPECTED-STATE @ <> IF 0 EXIT THEN
    0 _RTERM-MV-OPEN-COUNT !
    _RTERM-MV-BACKEND @ _RTERM-B.CAPACITY @ 0 ?DO
        I _RTERM-MV-BACKEND @ _RTERM-RECORD-AT DUP _RTERM-R.MAT-STATE @
        DUP _RTERM-MAT-ASSOCIATED-STATE? IF
            DROP
            DUP _RTERM-MV-RECORD @ <> IF DROP 0 UNLOOP EXIT THEN
            1 _RTERM-MV-OPEN-COUNT +!
            DROP
        ELSE
            _RTERM-MAT-REBUILD-REST-STATE? 0= IF
                DROP 0 UNLOOP EXIT
            THEN
            DROP
        THEN
    LOOP
    _RTERM-MV-OPEN-COUNT @ 1 = ;

