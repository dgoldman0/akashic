            _RTERM-MS-MAT @ _RTERM-M.PHASE @
                _RTERM-MAT-PHASE-OPENING = AND
            _RTERM-MS-RESTART? AND IF
                RTERM-S-WOULD-BLOCK -1 0 _RTERM-MS-RESULT! EXIT
            THEN
            _RTERM-MS-CALL-STATUS @ DUP RTERM-S-WOULD-BLOCK =
            SWAP RTERM-S-UNAVAILABLE = OR IF
                _RTERM-MS-CALL-STATUS @ -1 0 _RTERM-MS-RESULT! EXIT
            THEN
            _RTERM-MS-CALL-STATUS @ _RTERM-FATAL? IF
