    _RTERM-MV-MAT @ _RTERM-M.REGIONS @
    _RTERM-MV-MAT @ _RTERM-M.OBJECTS @
    _RTERM-MV-MAT @ _RTERM-M.UTF8 @
    _RTERM-MV-MAT @ _RTERM-M.ROOT-H @
    _RTERM-MV-MAT @ _RTERM-M.ROOT-W @
        RUPJ-CANDIDATE-VALID? 0= IF 0 EXIT THEN
    _RTERM-BK-ITEM-A @ _RTERM-BK-IDENTITY-A @
    _RTERM-BK-IDENTITY-U @ _RTERM-MV-MAT @ _RTERM-M.ITEMS @
    _RTERM-MV-MAT @ _RTERM-M.OBJECT-HIGH @
        _RTERM-IDENTITY-BANK-VALID? 0= IF 0 EXIT THEN
