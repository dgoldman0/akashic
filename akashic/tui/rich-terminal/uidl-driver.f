            _RTERM-MS-ASSOCIATE-DROP
            RTERM-S-OK -1 0 _RTERM-MS-RESULT! EXIT
        THEN THEN
        _RTERM-MS-RESTART? 0= _RTERM-MS-COHORT-CANDIDATE? AND IF
