    0 _RTERM-MV-OBJECT-MAX !
    _RTERM-MV-MAT @ _RTERM-M.ITEMS @ 0 ?DO
        I _RTERM-IDENTITY-SIZE * _RTERM-BK-IDENTITY-A @ +
            _RTERM-X.OBJECT @ DUP _RTERM-MV-OBJECT-MAX @ U> IF
            _RTERM-MV-OBJECT-MAX !
        ELSE DROP THEN
    LOOP
    _RTERM-MV-OBJECT-MAX @
        _RTERM-MV-MAT @ _RTERM-M.OBJECT-HIGH @ = ;

