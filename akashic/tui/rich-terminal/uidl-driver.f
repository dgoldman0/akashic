: _RTERM-MS-DISPATCH  ( -- )
    _RTERM-MS-MAT @ _RTERM-M.PHASE @ DUP
        _RTERM-MAT-PHASE-COHORT = IF
        DROP
        _RTERM-MS-SURFACE=? 0= IF _RTERM-MS-REQUEST-RESTART THEN
        _RTERM-MS-UPDATE-STATE @ RTE-UPDATE-IDLE <> IF
            RTERM-S-WOULD-BLOCK -1 0 _RTERM-MS-RESULT! EXIT
        THEN
        _RTERM-MS-COHORT-STEP EXIT
    THEN
    DUP _RTERM-MAT-PHASE-OPENING = IF
        DROP _RTERM-MS-OPENING-STEP EXIT
    THEN
    DUP _RTERM-MAT-PHASE-OPEN = IF
        DROP _RTERM-MS-OPEN-STEP EXIT
    THEN
    DUP _RTERM-MAT-PHASE-HIDDEN-SEALED =
    OVER _RTERM-MAT-PHASE-HIDDEN-AWAITING = OR IF
