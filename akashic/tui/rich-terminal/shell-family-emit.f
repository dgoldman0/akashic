\ =====================================================================
\ shell-family-emit.f -- emit one admitted immutable family batch
\ =====================================================================
\ Caller preflights this same frozen batch and begins a complete START.
\ This helper does not begin, seal, cancel, publish or reorder the candidate.
\ Any non-OK result requires cancelling the entire caller-owned capture.
PROVIDED akashic-tui-rte-shell-family-emit
REQUIRE family-batch.f

CREATE _RTE-FEM-OWNED-START
VARIABLE _RTE-FEM-OWNED-LIMIT 0 _RTE-FEM-OWNED-LIMIT !
VARIABLE _RTE-FEM-BATCH VARIABLE _RTE-FEM-SHELL VARIABLE _RTE-FEM-BASE
VARIABLE _RTE-FEM-CATALOG VARIABLE _RTE-FEM-REGION VARIABLE _RTE-FEM-ENTRY
VARIABLE _RTE-FEM-KIND VARIABLE _RTE-FEM-PLAN VARIABLE _RTE-FEM-ITEM
VARIABLE _RTE-FEM-STRIDE VARIABLE _RTE-FEM-REF VARIABLE _RTE-FEM-BYTES
VARIABLE _RTE-FEM-COUNT VARIABLE _RTE-FEM-TEXT-U
CREATE _RTE-FEM-RUN-MEM RTE-GLYPH-RUN-SIZE 7 + ALLOT
: _RTE-FEM-RUN ( -- run ) _RTE-FEM-RUN-MEM 7 + -8 AND ;

: RTE-FAMILY-EMIT-STORAGE-DISJOINT? ( a u -- flag )
    2DUP RTE-FAMILY-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    _RTE-FEM-OWNED-START _RTE-FEM-OWNED-LIMIT @ _RTE-FEM-OWNED-START -
        MSPAN-OVERLAP? 0= ;
: _RTE-FEM-EXTERNAL? ( a u shell -- flag )
    >R
    2DUP RTE-FAMILY-EMIT-STORAGE-DISJOINT? 0= IF 2DROP R> DROP 0 EXIT THEN
    DUP 0= IF 2DROP R> DROP -1 EXIT THEN
    2DUP R@ RTE-SHELL-FACADE-SIZE MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    R> _RTE-SH.BASE @ RTE-STORAGE-DISJOINT? ;
: _RTE-FEM-AUTHORITY? ( batch shell -- flag )
    DUP RTE-SHELL-FACADE-SIZE RTE-FAMILY-EMIT-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    DUP RTE-SHELL-VALID? 0= IF 2DROP 0 EXIT THEN
    DUP _RTE-SH.BASE @ RTE-FACADE-SIZE RTE-FAMILY-EMIT-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    OVER RTE-FAMILY-BATCH-SIZE 2 PICK _RTE-FEM-EXTERNAL? 0= IF 2DROP 0 EXIT THEN
    OVER RTE-FAMILY-BATCH-FIXED? 0= IF 2DROP 0 EXIT THEN
    _RTE-FEM-OWNED-START _RTE-FEM-OWNED-LIMIT @ _RTE-FEM-OWNED-START -
        2 PICK _RTE-SH.BASE @ RTE-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    OVER RTE-FAMILY-BATCH-SPAN-COUNT 0 ?DO
        I 2 PICK RTE-FAMILY-BATCH-SPAN@ 2 PICK _RTE-FEM-EXTERNAL? 0= IF
            2DROP 0 UNLOOP EXIT
        THEN
    LOOP 2DROP -1 ;

: _RTE-FEM-REGIONS ( -- status )
    _RTE-FEM-CATALOG @ _RTE-RC.REGIONS-A @ _RTE-FEM-REGION !
    _RTE-FEM-CATALOG @ _RTE-RC.REGIONS-U @ RTE-INSTRUMENT-REGION-SIZE / 0 ?DO
        _RTE-FEM-CATALOG @ _RTE-RC.OWNER @
        _RTE-FEM-CATALOG @ _RTE-RC.GENERATION @
        _RTE-FEM-REGION @ _RTE-IR.ID @
        _RTE-FEM-REGION @ _RTE-IR.X @ _RTE-FEM-REGION @ _RTE-IR.Y @
        _RTE-FEM-REGION @ _RTE-IR.COLS @ _RTE-FEM-REGION @ _RTE-IR.ROWS @
        _RTE-FEM-REGION @ _RTE-IR.CLIP-X @ _RTE-FEM-REGION @ _RTE-IR.CLIP-Y @
        _RTE-FEM-REGION @ _RTE-IR.CLIP-COLS @ _RTE-FEM-REGION @ _RTE-IR.CLIP-ROWS @
        _RTE-FEM-REGION @ _RTE-IR.Z @ _RTE-FEM-REGION @ _RTE-IR.FLAGS @
        _RTE-FEM-BASE @ RTE-REGION-DEFINE
        DUP RTE-S-OK <> IF UNLOOP EXIT THEN DROP
        RTE-INSTRUMENT-REGION-SIZE _RTE-FEM-REGION +!
    LOOP RTE-S-OK ;
: _RTE-FEM-GLYPH ( -- status )
    _RTE-FEM-RUN RTE-GLYPH-RUN-SIZE 0 FILL
    _RTE-FEM-CATALOG @ _RTE-RC.OWNER @ _RTE-FEM-RUN _RTE-GLYPH-RUN.OWNER !
    _RTE-FEM-CATALOG @ _RTE-RC.GENERATION @ _RTE-FEM-RUN _RTE-GLYPH-RUN.GENERATION !
    _RTE-FEM-ITEM @ _RTE-LPI.OBJECT @ _RTE-FEM-RUN _RTE-GLYPH-RUN.OBJECT !
    _RTE-FEM-PLAN @ _RTE-LP.REGION-ID @ _RTE-FEM-RUN _RTE-GLYPH-RUN.REGION !
    _RTE-FEM-ITEM @ 8 + _RTE-FEM-RUN 32 + 96 MOVE
    _RTE-FEM-REF @ 8 + @ DUP _RTE-FEM-TEXT-U !
        _RTE-FEM-RUN _RTE-GLYPH-RUN.TEXT-U !
    _RTE-FEM-TEXT-U @ IF
        _RTE-FEM-BYTES @ _RTE-FEM-REF @ @ +
    ELSE 0 THEN _RTE-FEM-RUN _RTE-GLYPH-RUN.TEXT-A !
    _RTE-FEM-RUN _RTE-FEM-BASE @ RTE-GLYPH-RUN-DEFINE ;
: _RTE-FEM-ITEM-EMIT ( -- status )
    _RTE-FEM-KIND @ RTE-FAMILY-GLYPH = IF _RTE-FEM-GLYPH EXIT THEN
    _RTE-FEM-KIND @ RTE-FAMILY-PANE = IF
        _RTE-FEM-ITEM @ _RTE-FEM-SHELL @ RTE-PANE-DEFINE EXIT
    THEN
    _RTE-FEM-ITEM @ _RTE-FEM-BASE @
    _RTE-FEM-KIND @ RTE-FAMILY-CONTROL = IF RTE-CONTROL-DEFINE EXIT THEN
    _RTE-FEM-KIND @ RTE-FAMILY-INSTRUMENT = IF RTE-INSTRUMENT-DEFINE EXIT THEN
    _RTE-FEM-KIND @ RTE-FAMILY-STATIC = IF RTE-STATIC-DEFINE EXIT THEN
    RTE-SERIES-DEFINE ;
: _RTE-FEM-FAMILY ( -- status )
    _RTE-FEM-ENTRY @ _RTE-FE.KIND @ DUP _RTE-FEM-KIND !
        RTE-FAMILY-ITEM-SIZE _RTE-FEM-STRIDE !
    _RTE-FEM-ENTRY @ _RTE-FE.PLAN-A @ _RTE-FEM-PLAN !
    _RTE-FEM-ENTRY @ _RTE-FE.BYTES-A @ _RTE-FEM-BYTES !
    _RTE-FEM-ENTRY @ _RTE-FE.REFS-A @ _RTE-FEM-REF !
    _RTE-FEM-ENTRY @ RTE-FAMILY-ITEMS@
        _RTE-FEM-STRIDE @ / _RTE-FEM-COUNT ! _RTE-FEM-ITEM !
    _RTE-FEM-COUNT @ 0 ?DO
        _RTE-FEM-ITEM-EMIT DUP RTE-S-OK <> IF UNLOOP EXIT THEN DROP
        _RTE-FEM-STRIDE @ _RTE-FEM-ITEM +!
        _RTE-FEM-KIND @ RTE-FAMILY-GLYPH = IF 16 _RTE-FEM-REF +! THEN
    LOOP RTE-S-OK ;
: _RTE-FEM-BODY ( -- status )
    _RTE-FEM-BATCH @ RTE-FAMILY-BATCH-VALID? 0= IF RTE-S-INVALID EXIT THEN
    _RTE-FEM-BATCH @ _RTE-FB.CATALOG-A @ _RTE-FEM-CATALOG !
    _RTE-FEM-REGIONS DUP RTE-S-OK <> IF EXIT THEN DROP
    _RTE-FEM-BATCH @ _RTE-FB.FAMILIES-A @ _RTE-FEM-ENTRY !
    _RTE-FEM-BATCH @ _RTE-FB.FAMILIES-U @ RTE-FAMILY-ENTRY-SIZE / 0 ?DO
        _RTE-FEM-FAMILY DUP RTE-S-OK <> IF UNLOOP EXIT THEN DROP
        RTE-FAMILY-ENTRY-SIZE _RTE-FEM-ENTRY +!
    LOOP RTE-S-OK ;
: _RTE-FEM-FINISH ( status -- status )
    _RTE-FEM-RUN RTE-GLYPH-RUN-SIZE 0 FILL
    0 _RTE-FEM-BATCH ! 0 _RTE-FEM-SHELL ! 0 _RTE-FEM-BASE !
    0 _RTE-FEM-CATALOG ! 0 _RTE-FEM-REGION ! 0 _RTE-FEM-ENTRY !
    0 _RTE-FEM-KIND ! 0 _RTE-FEM-PLAN ! 0 _RTE-FEM-ITEM !
    0 _RTE-FEM-STRIDE ! 0 _RTE-FEM-REF ! 0 _RTE-FEM-BYTES !
    0 _RTE-FEM-COUNT ! 0 _RTE-FEM-TEXT-U ! ;
: RTE-FAMILY-BATCH-EMIT ( admitted-immutable-batch shell -- status )
    2DUP _RTE-FEM-AUTHORITY? 0= IF 2DROP RTE-S-INVALID EXIT THEN
    DUP _RTE-SH.BASE @ _RTE-FEM-BASE ! _RTE-FEM-SHELL ! _RTE-FEM-BATCH !
    ['] _RTE-FEM-BODY CATCH ?DUP IF DROP RTE-S-INVALID THEN
    _RTE-FEM-FINISH ;
HERE _RTE-FEM-OWNED-LIMIT !
