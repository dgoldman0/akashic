: _RTHP-D-MAP-AT  ( slot -- a )
    8 * _RTHP-D-MAP-A @ + ;

: _RTHP-D-ID>MAP?  ( id -- entry-a flag )
    DUP _RTHP-D-GLYPH-BASE @ U< IF DROP 0 0 EXIT THEN
    _RTHP-D-GLYPH-BASE @ - DUP _RTHP-D-SLOTS @ U< 0= IF
        DROP 0 0 EXIT
    THEN
    _RTHP-D-MAP-AT -1 ;

