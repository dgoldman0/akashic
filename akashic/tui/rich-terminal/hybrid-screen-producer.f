        _RTHP-PK-P @ _RTHP.MAX-RECORDS @ U> IF 0 EXIT THEN
    _RTHP-PK-BANK @ _RTHP-TB.CONTROL-COUNT @
        _RTHP-PK-P @ _RTHP.MAX-RECORDS @ U> IF 0 EXIT THEN
