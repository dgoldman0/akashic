    DUP _RTHP-CT-ORDINAL !
    RUCP-CORRELATION-SIZE * _RTHP-CT-P @ _RTHP.CORR-A @ +
    DUP _RTHP-CT-CORRELATION !
    RUCP-CORRELATION-CONTROL-ID@ DUP _RTHP-CT-ID ! 0<> ;

