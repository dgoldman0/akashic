        _RTHP-PK-BANK @ _RTHP-TB.SOURCE-TEXT-USED @
        _RTHP-PK-P @ _RTHP.SOURCE-TEXT-U @ _RTHP-PK-BOUNDED-SOURCE?
        0= IF 0 EXIT THEN
    _RTHP-PK-P @ _RTHP.GLYPH-ITEMS-A @ _RTHP-PK-ITEM-U @
        _RTHP-PK-P @ _RTHP.GLYPH-ITEMS-U @ _RTHP-PK-BOUNDED-SOURCE?
