        0= IF DROP 0 EXIT THEN DUP _RTHP-RD-EVENTS-U !
    _RTHP-RD-P @ _RTHP.EVENTS-U @ U> IF 0 EXIT THEN
    _RTHP-RD-EVENTS-U @ IF
        _RTHP-RD-P @ _RTHP.EVENTS-A @ _RTHP-RD-EVENTS-U @
        _RTHP-RD-P @ _RTHP-ARENA-SPAN? 0= IF 0 EXIT THEN
