        _RTHP-PK-BANK-U @ _RTHP-PK-PREFIX @ - U> IF 0 EXIT THEN

    _RTHP-PK-BANK @ _RTHP-PK-PREFIX @ _RTHP-U+?
        0= IF DROP 0 EXIT THEN DUP _RTHP-PK-PACK-A ! _RTHP-PK-CURSOR !
