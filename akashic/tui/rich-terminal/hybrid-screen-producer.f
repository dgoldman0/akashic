        DUP _RTHP-PK-REF-U ! _RTHP-PK-ADD? 0= IF 0 EXIT THEN
    _RTHP-PK-BANK @ _RTHP-TB.GLYPH-TEXT-USED @ _RTHP-ALIGN8?
