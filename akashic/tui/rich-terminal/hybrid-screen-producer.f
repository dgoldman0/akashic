VARIABLE _RTHP-D-SLOTS
VARIABLE _RTHP-D-MAP-A
VARIABLE _RTHP-D-MAP-U
VARIABLE _RTHP-D-MAP-BYTES
VARIABLE _RTHP-D-BANK-BYTES
VARIABLE _RTHP-D-MAP-ID
