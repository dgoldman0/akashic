    _RUIP-LIMITS-A @ 0= IF 0 _RUIP-ADMISSIBLE ! -1 EXIT THEN
    _RUIP-LIMITS-A @ RTE-LIMITS-FEATURES@ RTE-F-SERIES AND 0= IF
        0 _RUIP-ADMISSIBLE ! -1 EXIT
