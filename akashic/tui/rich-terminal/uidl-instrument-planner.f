    _RUIP-S-CHUNKS @ 1+ _RUIP-S-OPS !
    1 _RUIP-SERIES-COUNT _RUIP-ACCUMULATE? 0= IF 0 EXIT THEN
    _RUIP-RECORD @ UDG-SERIES-CAPACITY@ _RUIP-SAMPLE-SLOTS
        _RUIP-ACCUMULATE? 0= IF 0 EXIT THEN
    _RUIP-S-BYTES @ _RUIP-SAMPLE-BYTES _RUIP-ACCUMULATE? 0= IF 0 EXIT THEN
    _RUIP-S-OPS @ _RUIP-SERIES-OPS _RUIP-ACCUMULATE? 0= IF 0 EXIT THEN
