        OVER _RUIP-C.INDEX !
    _RUIP-RECORD @ UDG-RECORD-KEY@ OVER _RUIP-C.SUBKEY !
    _RUIP-DESCRIPTOR @ UDGSN-DESCRIPTOR-Z@ OVER _RUIP-C.Z !
    _RUIP-CLAIM-ROW0 @ OVER _RUIP-C.ROW0 !
    _RUIP-CLAIM-COL0 @ OVER _RUIP-C.COL0 !
    _RUIP-CLAIM-ROW1 @ OVER _RUIP-C.ROW1 !
    _RUIP-CLAIM-COL1 @ SWAP _RUIP-C.COL1 !
    1 _RUIP-CLAIM-I +! ;

: _RUIP-MAYBE-WRITE-CLAIM  ( -- )
    _RUIP-ROOT-VISIBLE @ 0= IF EXIT THEN
    _RUIP-RECORD @ UDG-OBJECT-FLAGS@ UDG-OBJECT-VISIBLE AND 0= IF EXIT THEN
    _RUIP-RECORD @ _RUIP-OBJECT-CLIP? IF _RUIP-WRITE-CLAIM THEN ;

: _RUIP-EMIT-ONE?  ( -- flag )
    _RUIP-FIRST-ITEM @ _RUIP-ITEM-I @ _RUIP-UADD?
        0= IF DROP 0 EXIT THEN _RUIP-CURRENT-ITEM !
    _RUIP-WRITE-INSTRUMENT? 0= IF 0 EXIT THEN
    _RUIP-WRITE-CORRELATION
    _RUIP-MAYBE-WRITE-CLAIM
    1 _RUIP-ITEM-I +!
    -1 ;

: _RUIP-EMIT-GRAPH?  ( -- flag )
    _RUIP-GRAPH @ UDG-ROOT-STATE@ UDG-STATE-VISIBLE AND
        IF -1 ELSE 0 THEN _RUIP-ROOT-VISIBLE !
    _RUIP-GRAPH @ UDG-OBJECT-COUNT@ 0= IF -1 EXIT THEN
    _RUIP-FIRST-REGION @ _RUIP-REGION-I @ _RUIP-UADD?
        0= IF DROP 0 EXIT THEN _RUIP-CURRENT-REGION !
    _RUIP-WRITE-REGION
    _RUIP-GRAPH @ UDG-FIRST-RECORD _RUIP-CURSOR !
    _RUIP-GRAPH @ UDG-OBJECT-COUNT@ 0 ?DO
        _RUIP-CURSOR @ _RUIP-RECORD !
        _RUIP-EMIT-ONE? 0= IF 0 UNLOOP EXIT THEN
        _RUIP-RECORD @ UDG-RECORD-NEXT _RUIP-CURSOR !
    LOOP
    1 _RUIP-REGION-I +!
    -1 ;

: _RUIP-WRITE-PLAN  ( -- )
    _RUIP-OWNER @ _RUIP-PLAN-A @ _RTE-IP.OWNER !
    _RUIP-OWNER-GEN @ _RUIP-PLAN-A @ _RTE-IP.GENERATION !
    _RUIP-SURFACE-W @ _RUIP-PLAN-A @ _RTE-IP.SURFACE-COLS !
    _RUIP-SURFACE-H @ _RUIP-PLAN-A @ _RTE-IP.SURFACE-ROWS !
    _RUIP-REGIONS-A @ _RUIP-PLAN-A @ _RTE-IP.REGIONS-A !
    _RUIP-REGION-COUNT @ RTE-INSTRUMENT-REGION-SIZE *
        _RUIP-PLAN-A @ _RTE-IP.REGIONS-U !
    _RUIP-ITEMS-A @ _RUIP-PLAN-A @ _RTE-IP.ITEMS-A !
    _RUIP-ITEM-COUNT @ RTE-INSTRUMENT-SIZE *
        _RUIP-PLAN-A @ _RTE-IP.ITEMS-U ! ;

: _RUIP-EMIT?  ( -- flag )
    _RUIP-ITEM-COUNT @ 0= IF -1 EXIT THEN
    0 _RUIP-REGION-I ! 0 _RUIP-ITEM-I !
    0 _RUIP-UNIT-USED ! 0 _RUIP-CLAIM-I !
    _RUIP-DESCRIPTOR-COUNT @ 0 ?DO
        I _RUIP-DESCRIPTOR-AT _RUIP-DESCRIPTOR !
        _RUIP-DESCRIPTOR @ _RUIP-NATIVE-A @ UDGSN-DESCRIPTOR-NATIVE
            _RUIP-GRAPH-U ! _RUIP-GRAPH !
        _RUIP-DESCRIPTOR-ROOT-GEOMETRY? 0= IF 0 UNLOOP EXIT THEN
        _RUIP-DESCRIPTOR-CLIP? 0= IF 0 UNLOOP EXIT THEN
        _RUIP-EMIT-GRAPH? 0= IF 0 UNLOOP EXIT THEN
    LOOP
    _RUIP-REGION-I @ _RUIP-REGION-COUNT @ =
    _RUIP-ITEM-I @ _RUIP-ITEM-COUNT @ = AND
    _RUIP-UNIT-USED @ _RUIP-UNIT-BYTES @ = AND
    _RUIP-CLAIM-I @ _RUIP-CLAIM-COUNT @ = AND 0= IF 0 EXIT THEN
    _RUIP-WRITE-PLAN
    -1 ;

: _RUIP-FAIL-RESULT  ( -- 0 0 0 0 0 0 status )
    _RUIP-CLEAR-OUTPUT
    0 0 0 0 0 0 _RUIP-STATUS @ ;

: _RUIP-SUCCESS-RESULT
    ( -- region-count instrument-count unit-bytes claim-count last-region last-item status )
    _RUIP-REGION-COUNT @ _RUIP-ITEM-COUNT @ _RUIP-UNIT-BYTES @
    _RUIP-CLAIM-COUNT @ _RUIP-LAST-REGION @ _RUIP-LAST-ITEM @ RUIP-S-OK ;

: _RUIP-BUILD-BODY
    ( -- region-count instrument-count unit-bytes claim-count last-region last-item status )
    RUIP-S-OK _RUIP-STATUS !
    0 _RUIP-RANGES-VALID !
    _RUIP-LOAD-REQUEST
    _RUIP-RANGE-AUTHORITY? 0= IF
        _RUIP-SET-INVALID _RUIP-FAIL-RESULT EXIT
    THEN
    _RUIP-CLEAR-OUTPUT
    _RUIP-SCALARS? 0= IF _RUIP-SET-INVALID _RUIP-FAIL-RESULT EXIT THEN
    _RUIP-VALIDATE-AND-MEASURE? 0= IF
        _RUIP-SET-INVALID _RUIP-FAIL-RESULT EXIT
    THEN
    _RUIP-CAPACITIES? 0= IF
        _RUIP-STATUS @ RUIP-S-OK = IF _RUIP-SET-INVALID THEN
        _RUIP-FAIL-RESULT EXIT
    THEN
    _RUIP-EMIT? 0= IF _RUIP-SET-INVALID _RUIP-FAIL-RESULT EXIT THEN
    _RUIP-SUCCESS-RESULT ;

