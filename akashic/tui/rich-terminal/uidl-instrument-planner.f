        _RUIP-S-Q @ 0= IF 0 _RUIP-ADMISSIBLE ! -1 EXIT THEN
        _RUIP-S-COUNT @ 1- _RUIP-S-Q @ / 1+
    ELSE 0 THEN _RUIP-S-CHUNKS !
