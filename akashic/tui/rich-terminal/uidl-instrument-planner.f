\ Safe in DO loops: no return-stack scratch aliases the loop counter.
: _RUIP-SADD?  ( a b -- sum flag )
    _RUIP-SADD-B ! _RUIP-SADD-A !
    _RUIP-SADD-A @ _RUIP-SADD-B @ + _RUIP-SADD-SUM !
    _RUIP-SADD-A @ _RUIP-SADD-SUM @ XOR
