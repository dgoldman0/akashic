\ =====================================================================
\  uidl-instrument-planner.f -- frozen UIDL DGRAPH to RTE instruments
\ =====================================================================
\
\  This pure, synchronous leaf lowers one frozen UDGSN document slice into
\  one initial/all-new renderer-neutral INSTRUMENT plan.  It allocates
\  nothing, calls no provider, and knows no Desk, applet, UCTX, terminal, or
\  physical renderer API.  Every bank is independently caller-sized.
\
\  The mounted relation root key, the native UDG root/object keys, and the
\  newly assigned retained region/object IDs are deliberately separate.
\  Correlations preserve all three namespaces without treating any source
\  key as a globally unique retained identity.  Retained IDs are assigned in
\  canonical frozen descriptor/record order from caller-provided first IDs.
\
\  Full logical graph and object geometry is preserved.  Each graph region
\  carries the independent physical clip captured by UDGSN; each visible
\  object's tentative residual claim is its absolute intersection with that
\  clip.  Claims are output only after the complete source and every required
\  capacity have been proved.  They remain tentative: the aggregate producer
\  must use them only if whole-family hybrid admission succeeds.
\  Successful builds initialize only the exact extents reported by the
\  result and plan; unused caller-capacity tails remain outside the result.
\  A failed build still scrubs every validated mutable span.
\
\  SERIES is a non-object record. Complete histories are copied unchanged,
\  with WAVEFORM references translated through a separate identity bank.
\  Unsupported/unaffordable graphs are omitted whole and reported by source
\  descriptor ordinal; omissions never grant a residual claim.
\
\  Public build API:
\    RUIP-BUILD
\      ( request -- region-count instrument-count unit-bytes claim-count
\                    last-region-id last-instrument-id status )
\
\  Prefix: RUIP- (public), _RUIP- (private)

