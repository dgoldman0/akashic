        _RUHA-BYTE-SPAN? 0= IF DROP 0 EXIT THEN
    DUP _RUHA-A.SNAP-TEXT-U @ 2 MOD IF DROP 0 EXIT THEN
    DUP _RUHA-A.SNAP-TEXT-BANK-U @ 2 *
        OVER _RUHA-A.SNAP-TEXT-U @ <> IF DROP 0 EXIT THEN
