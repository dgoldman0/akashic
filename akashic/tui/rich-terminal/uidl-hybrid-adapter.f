    _RUHA-Q-RECORD @ _RUHA-R.STATE @
        _RUHA-RECORD-QUIESCED <> IF RUHA-S-STALE EXIT THEN
    _RUHA-Q-TOKEN @ _RUHA-Q-ADAPTER @ _RUHA-INVALIDATE-TOKEN
    _RUHA-Q-RECORD @ RUHA-RECORD-SIZE 0 FILL
    RUHA-S-OK ;

