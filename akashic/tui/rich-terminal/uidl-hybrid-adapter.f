: _RUHA-B-CAPTURE-RECORD ( record -- status )
    _RUHA-B-RECORD !
    _RUHA-B-RECORD @ _RUHA-B-ADAPTER @ _RUHA-RECORD-VISIBLE? 0= IF
        RUHA-S-OK EXIT
    THEN
