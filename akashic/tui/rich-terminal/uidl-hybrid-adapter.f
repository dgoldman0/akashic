    _RUHA-A-ADAPTER @ _RUHA-A.INSTALLED @ 0= IF
        0 RUHA-S-INVALID EXIT
    THEN
    _RUHA-A-ADAPTER @ _RUHA-A.HOST @ DUP 0= IF
        DROP 0 RUHA-S-INVALID EXIT
    THEN
    _RUHA-A-SLOT @ SWAP _RUHA-HOST-HAS-SLOT? 0= IF
        0 RUHA-S-STALE EXIT
