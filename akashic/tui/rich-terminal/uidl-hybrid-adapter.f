    _RUHA-A-SLOT @ AHS.ID @ _RUHA-A-FREE @ _RUHA-R.SLOT-ID !
    _RUHA-A-SLOT @ AHS.UCTX @ _RUHA-A-FREE @ _RUHA-R.UCTX !
