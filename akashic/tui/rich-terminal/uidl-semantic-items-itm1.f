\ =====================================================================
\  uidl-semantic-items-itm1.f -- frozen native item view to ITM1
\ =====================================================================
\
\  Translates one already-deep-validated, immutable USCOL item view entry
\  and its correlated summary into canonical little-endian ITM1
\  (SEMANTIC-CONTENT-1).  Like the STX1 packer, this module is not another
\  validation authority: it performs only constant-time correlation, span,
\  capacity, and revision checks before one bounded walk over the columns,
\  items, fields, and runs.  It does not decode UTF-8, sort keys, or repeat
\  the structure proofs.
\
\  The destination tag remains zero until the complete cursor accounting
\  succeeds, so an impossible post-freeze mismatch cannot leave a
\  valid-looking partial value.
\
\  Public API:
\    USITM-PACK
\      ( entry entry-bytes summary source-revision destination capacity
\        -- bytes status )
\
\  Prefix: USITM- (public), _USITM- (private)

PROVIDED akashic-tui-rterm-usitm

REQUIRE ../semantic-collections.f

0x314D5449 CONSTANT USITM-TAG
1 CONSTANT USITM-VERSION
40 CONSTANT USITM-HEADER-SIZE
8 CONSTANT USITM-COLUMN-SIZE
32 CONSTANT USITM-ITEM-HEADER-SIZE
8 CONSTANT USITM-FIELD-SIZE
12 CONSTANT USITM-RUN-SIZE

VARIABLE _USITM-ENTRY
VARIABLE _USITM-ENTRY-U
VARIABLE _USITM-SUMMARY
VARIABLE _USITM-REVISION
VARIABLE _USITM-DST
VARIABLE _USITM-CAP

VARIABLE _USITM-COLUMNS
VARIABLE _USITM-ITEM-COUNT
VARIABLE _USITM-UTF8-U
VARIABLE _USITM-RUN-COUNT
VARIABLE _USITM-FIELD-COUNT
VARIABLE _USITM-OUT-U

VARIABLE _USITM-NATIVE
VARIABLE _USITM-NATIVE-U
VARIABLE _USITM-WIRE
VARIABLE _USITM-WIRE-U
VARIABLE _USITM-TEXT-U
VARIABLE _USITM-RUNS
VARIABLE _USITM-NATIVE-STEP
VARIABLE _USITM-WIRE-STEP
VARIABLE _USITM-COPIED-UTF8
VARIABLE _USITM-COPIED-RUNS
VARIABLE _USITM-COPIED-FIELDS
VARIABLE _USITM-FIELDS          \ this item's fields
VARIABLE _USITM-RUN-A
VARIABLE _USITM-RUN-W

: _USITM-ALIGNED-SPAN?  ( address bytes -- flag )
    OVER 0<> OVER 0> AND 0= IF 2DROP 0 EXIT THEN
    OVER 7 AND IF 2DROP 0 EXIT THEN
    MSPAN-NONWRAPPING? ;

: _USITM-DISJOINT?  ( a u b v -- flag )  MSPAN-OVERLAP? 0= ;

: _USITM-U32?  ( value -- flag )
    DUP 0< IF DROP 0 EXIT THEN 0x100000000 U< ;

: _USITM-UADD?  ( a b -- sum flag )  OVER + DUP ROT U< 0= ;

: _USITM-LE16!  ( value address -- )  2DUP C! SWAP 8 RSHIFT SWAP 1+ C! ;
: _USITM-LE32!  ( value address -- )
    2DUP _USITM-LE16! SWAP 16 RSHIFT SWAP 2 + _USITM-LE16! ;
: _USITM-LE64!  ( value address -- )
    2DUP _USITM-LE32! SWAP 32 RSHIFT SWAP 4 + _USITM-LE32! ;

: _USITM-ARGS!  ( entry entry-u summary revision destination capacity -- )
    _USITM-CAP ! _USITM-DST ! _USITM-REVISION !
    _USITM-SUMMARY ! _USITM-ENTRY-U ! _USITM-ENTRY ! ;

\ Deliberately O(1): FAMILY, KEY, and ENTRY-BYTES bind the summary to the
\ exact frozen native slice whose deep validation produced it.
: _USITM-CORRELATE  ( -- status )
    _USITM-ENTRY @ _USITM-ENTRY-U @ _USITM-ALIGNED-SPAN? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USITM-SUMMARY @ USCOL-SUMMARY-SIZE _USITM-ALIGNED-SPAN? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USITM-ENTRY @ _USITM-ENTRY-U @
        _USITM-SUMMARY @ USCOL-SUMMARY-SIZE _USITM-DISJOINT? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USITM-REVISION @ 0= IF USCOL-S-INVALID EXIT THEN
    _USITM-ENTRY-U @ USCOL-ENTRY-HEADER-SIZE U< IF USCOL-S-INVALID EXIT THEN
    _USITM-ENTRY-U @ 7 AND IF USCOL-S-INVALID EXIT THEN
    _USITM-ENTRY @ USCOL-ENTRY-BYTES@ _USITM-ENTRY-U @ <> IF
        USCOL-S-INVALID EXIT
    THEN
    _USITM-ENTRY @ USCOL-ENTRY-FAMILY-ABI@ USCOL-FAMILY-ABI <> IF
        USCOL-S-INVALID EXIT
    THEN
    _USITM-SUMMARY @ USCOL-SUMMARY-ENTRY-BYTES@ _USITM-ENTRY-U @ <> IF
        USCOL-S-INVALID EXIT
    THEN
    _USITM-ENTRY @ USCOL-ENTRY-FAMILY@
        _USITM-SUMMARY @ USCOL-SUMMARY-FAMILY@ <> IF USCOL-S-INVALID EXIT THEN
    _USITM-ENTRY @ USCOL-ENTRY-KEY@ DUP 0= IF DROP USCOL-S-INVALID EXIT THEN
    _USITM-SUMMARY @ USCOL-SUMMARY-ROOT-KEY@ <> IF USCOL-S-INVALID EXIT THEN
    _USITM-ENTRY @ USCOL-ENTRY-FAMILY@ USCOL-F-ITEM-VIEW <> IF
        USCOL-S-UNSUPPORTED EXIT
    THEN
    _USITM-ENTRY-U @ USCOL-IV-FIXED-SIZE U< IF USCOL-S-INVALID EXIT THEN
    _USITM-ENTRY @ USCOL-IV-COLUMN-COUNT@
    _USITM-SUMMARY @ USCOL-SUMMARY-CHILD-COUNT@ DUP _USITM-COLUMNS !
        <> IF USCOL-S-INVALID EXIT THEN
    _USITM-ENTRY @ USCOL-IV-ITEM-COUNT@
    _USITM-SUMMARY @ USCOL-SUMMARY-ITEM-COUNT@ DUP _USITM-ITEM-COUNT !
        <> IF USCOL-S-INVALID EXIT THEN
    _USITM-SUMMARY @ USCOL-SUMMARY-UTF8-BYTES@ DUP _USITM-UTF8-U !
        _USITM-U32? 0= IF USCOL-S-INVALID EXIT THEN
    _USITM-SUMMARY @ USCOL-SUMMARY-RUN-COUNT@ DUP _USITM-RUN-COUNT !
        _USITM-U32? 0= IF USCOL-S-INVALID EXIT THEN
    _USITM-SUMMARY @ USCOL-SUMMARY-FIELD-COUNT@ DUP _USITM-FIELD-COUNT !
        _USITM-U32? 0= IF USCOL-S-INVALID EXIT THEN

    _USITM-SUMMARY @ USCOL-SUMMARY-ITM1-BYTES
    DUP USCOL-S-OK <> IF NIP EXIT THEN
    DROP _USITM-OUT-U !

    _USITM-CAP @ 0< IF USCOL-S-INVALID EXIT THEN
    _USITM-CAP @ _USITM-OUT-U @ U< IF USCOL-S-CAPACITY EXIT THEN
    _USITM-DST @ _USITM-CAP @ OVER 0<> OVER 0> AND 0= IF
        2DROP USCOL-S-INVALID EXIT
    THEN
    MSPAN-NONWRAPPING? 0= IF USCOL-S-INVALID EXIT THEN
    _USITM-ENTRY @ _USITM-ENTRY-U @
        _USITM-DST @ _USITM-CAP @ _USITM-DISJOINT? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USITM-SUMMARY @ USCOL-SUMMARY-SIZE
        _USITM-DST @ _USITM-CAP @ _USITM-DISJOINT? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    USCOL-S-OK ;

: _USITM-HEADER!  ( -- )
    \ Zero is the invalid publication tag until the complete walk succeeds.
    0 _USITM-DST @ _USITM-LE32!
    USITM-VERSION _USITM-DST @ 4 + _USITM-LE16!
    0 _USITM-DST @ 6 + _USITM-LE16!
    _USITM-REVISION @ _USITM-DST @ 8 + _USITM-LE64!
    _USITM-ENTRY @ USCOL-IV-ROLE@ _USITM-DST @ 16 + _USITM-LE16!
    _USITM-ENTRY @ USCOL-IV-FLAGS@ _USITM-DST @ 18 + _USITM-LE16!
    _USITM-COLUMNS @ _USITM-DST @ 20 + _USITM-LE32!
    _USITM-ENTRY @ USCOL-IV-TOTAL@ _USITM-DST @ 24 + _USITM-LE32!
    _USITM-ENTRY @ USCOL-IV-FIRST@ _USITM-DST @ 28 + _USITM-LE32!
    _USITM-ENTRY @ USCOL-IV-SHOWN@ _USITM-DST @ 32 + _USITM-LE32!
    _USITM-ITEM-COUNT @ _USITM-DST @ 36 + _USITM-LE32! ;

: _USITM-CURSORS!  ( -- )
    _USITM-ENTRY @ USCOL-IV-FIRST-COLUMN _USITM-NATIVE !
    _USITM-ENTRY-U @ USCOL-IV-FIXED-SIZE - _USITM-NATIVE-U !
    _USITM-DST @ USITM-HEADER-SIZE + _USITM-WIRE !
    _USITM-OUT-U @ USITM-HEADER-SIZE - _USITM-WIRE-U !
    0 _USITM-COPIED-UTF8 ! 0 _USITM-COPIED-RUNS ! 0 _USITM-COPIED-FIELDS ! ;

\ _USITM-STEP? ( native-step wire-step -- flag )
\   Both records fit what remains; they become the cursors' next steps.
: _USITM-STEP?  ( native-step wire-step -- flag )
    DUP _USITM-WIRE-STEP ! _USITM-WIRE-U @ U> IF DROP 0 EXIT THEN
    DUP _USITM-NATIVE-STEP ! _USITM-NATIVE-U @ U> 0= ;

: _USITM-ADVANCE  ( -- )
    _USITM-NATIVE-STEP @ _USITM-NATIVE +!
    _USITM-NATIVE-STEP @ NEGATE _USITM-NATIVE-U +!
    _USITM-WIRE-STEP @ _USITM-WIRE +!
    _USITM-WIRE-STEP @ NEGATE _USITM-WIRE-U +! ;

: _USITM-UTF8+?  ( bytes -- flag )
    _USITM-COPIED-UTF8 @ SWAP _USITM-UADD? 0= IF DROP 0 EXIT THEN
    DUP _USITM-UTF8-U @ U> IF DROP 0 EXIT THEN
    _USITM-COPIED-UTF8 ! -1 ;

\ Cursor checks are memory-safety accounting, not a second semantic proof.
: _USITM-COLUMN?  ( -- flag )
    _USITM-NATIVE-U @ USCOL-COLUMN-HEADER-SIZE U< IF 0 EXIT THEN
    _USITM-NATIVE @ USCOL-COLUMN-LABEL-BYTES@ DUP _USITM-TEXT-U !
        _USITM-U32? 0= IF 0 EXIT THEN
    _USITM-TEXT-U @ USCOL-COLUMN-BYTES DUP 0= IF DROP 0 EXIT THEN
    _USITM-TEXT-U @ USITM-COLUMN-SIZE + _USITM-STEP? 0= IF 0 EXIT THEN
    _USITM-TEXT-U @ _USITM-UTF8+? 0= IF 0 EXIT THEN
    _USITM-NATIVE @ USCOL-COLUMN-KIND@ _USITM-WIRE @ _USITM-LE16!
    0 _USITM-WIRE @ 2 + _USITM-LE16!
    _USITM-TEXT-U @ _USITM-WIRE @ 4 + _USITM-LE32!
    _USITM-NATIVE @ USCOL-COLUMN-LABEL-OFFSET +
        _USITM-WIRE @ USITM-COLUMN-SIZE + _USITM-TEXT-U @ MOVE
    _USITM-ADVANCE
    -1 ;

\ _USITM-RUNS! ( -- )
\   Copy the field's already-proved style runs after its text: u32 start,
\   u32 length, u16 meaning, and a zero u16.
: _USITM-RUNS!  ( -- )
    _USITM-NATIVE @ _USITM-TEXT-U @ USCOL-FIELD-BYTES + _USITM-RUN-A !
    _USITM-WIRE @ USITM-FIELD-SIZE + _USITM-TEXT-U @ + _USITM-RUN-W !
    _USITM-RUNS @ 0 ?DO
        _USITM-RUN-A @ USCOL-RUN-START@ _USITM-RUN-W @ _USITM-LE32!
        _USITM-RUN-A @ USCOL-RUN-LENGTH@ _USITM-RUN-W @ 4 + _USITM-LE32!
        _USITM-RUN-A @ USCOL-RUN-MEANING@ _USITM-RUN-W @ 8 + _USITM-LE16!
        0 _USITM-RUN-W @ 10 + _USITM-LE16!
        USCOL-RUN-SIZE _USITM-RUN-A +!
        USITM-RUN-SIZE _USITM-RUN-W +!
    LOOP ;

: _USITM-FIELD?  ( -- flag )
    _USITM-NATIVE-U @ USCOL-FIELD-HEADER-SIZE U< IF 0 EXIT THEN
    _USITM-NATIVE @ USCOL-FIELD-TEXT-BYTES@ DUP _USITM-TEXT-U !
        _USITM-U32? 0= IF 0 EXIT THEN
    _USITM-NATIVE @ USCOL-FIELD-RUN-COUNT@ DUP _USITM-RUNS !
        _USITM-U32? 0= IF 0 EXIT THEN
    _USITM-TEXT-U @ USCOL-FIELD-BYTES DUP 0= IF DROP 0 EXIT THEN
        _USITM-RUNS @ USCOL-RUN-SIZE * _USITM-UADD? 0= IF DROP 0 EXIT THEN
    _USITM-TEXT-U @ USITM-FIELD-SIZE +
        _USITM-RUNS @ USITM-RUN-SIZE * _USITM-UADD? 0= IF 2DROP 0 EXIT THEN
    _USITM-STEP? 0= IF 0 EXIT THEN
    _USITM-TEXT-U @ _USITM-UTF8+? 0= IF 0 EXIT THEN
    _USITM-COPIED-RUNS @ _USITM-RUNS @ _USITM-UADD? 0= IF DROP 0 EXIT THEN
    DUP _USITM-RUN-COUNT @ U> IF DROP 0 EXIT THEN _USITM-COPIED-RUNS !
    _USITM-COPIED-FIELDS @ 1+ DUP _USITM-FIELD-COUNT @ U> IF DROP 0 EXIT THEN
        _USITM-COPIED-FIELDS !
    _USITM-TEXT-U @ _USITM-WIRE @ _USITM-LE32!
    _USITM-RUNS @ _USITM-WIRE @ 4 + _USITM-LE32!
    _USITM-NATIVE @ USCOL-FIELD-TEXT-OFFSET +
        _USITM-WIRE @ USITM-FIELD-SIZE + _USITM-TEXT-U @ MOVE
    _USITM-RUNS!
    _USITM-ADVANCE
    -1 ;

: _USITM-ITEM?  ( -- flag )
    USCOL-VI-HEADER-SIZE USITM-ITEM-HEADER-SIZE _USITM-STEP? 0= IF 0 EXIT THEN
    _USITM-NATIVE @ USCOL-VI-FIELD-COUNT@ DUP _USITM-FIELDS !
        _USITM-U32? 0= IF 0 EXIT THEN
    _USITM-NATIVE @ USCOL-VI-KEY@ _USITM-WIRE @ _USITM-LE64!
    _USITM-NATIVE @ USCOL-VI-PARENT@ _USITM-WIRE @ 8 + _USITM-LE64!
    _USITM-NATIVE @ USCOL-VI-ORDINAL@ _USITM-WIRE @ 16 + _USITM-LE32!
    _USITM-NATIVE @ USCOL-VI-DEPTH@ _USITM-WIRE @ 20 + _USITM-LE16!
    _USITM-NATIVE @ USCOL-VI-STATE@ _USITM-WIRE @ 22 + _USITM-LE16!
    _USITM-NATIVE @ USCOL-VI-ROLE@ _USITM-WIRE @ 24 + _USITM-LE16!
    _USITM-FIELDS @ _USITM-WIRE @ 26 + _USITM-LE16!
    0 _USITM-WIRE @ 28 + _USITM-LE32!
    _USITM-ADVANCE
    _USITM-FIELDS @ 0 ?DO
        _USITM-FIELD? 0= IF 0 UNLOOP EXIT THEN
    LOOP
    -1 ;

: _USITM-WALK?  ( -- flag )
    _USITM-COLUMNS @ 0 ?DO
        _USITM-COLUMN? 0= IF 0 UNLOOP EXIT THEN
    LOOP
    _USITM-ITEM-COUNT @ 0 ?DO
        _USITM-ITEM? 0= IF 0 UNLOOP EXIT THEN
    LOOP
    _USITM-NATIVE-U @ 0=
    _USITM-WIRE-U @ 0= AND
    _USITM-COPIED-UTF8 @ _USITM-UTF8-U @ = AND
    _USITM-COPIED-RUNS @ _USITM-RUN-COUNT @ = AND
    _USITM-COPIED-FIELDS @ _USITM-FIELD-COUNT @ = AND ;

: _USITM-PACK-BODY  ( -- bytes status )
    _USITM-CORRELATE DUP USCOL-S-OK <> IF 0 SWAP EXIT THEN DROP
    _USITM-HEADER!
    _USITM-CURSORS!
    _USITM-WALK? 0= IF 0 USCOL-S-INVALID EXIT THEN
    \ The tag is the final write; no fallible operation follows it.
    USITM-TAG _USITM-DST @ _USITM-LE32!
    _USITM-OUT-U @ USCOL-S-OK ;

: _USITM-SCRUB  ( -- )
    0 _USITM-ENTRY ! 0 _USITM-ENTRY-U ! 0 _USITM-SUMMARY !
    0 _USITM-REVISION ! 0 _USITM-DST ! 0 _USITM-CAP !
    0 _USITM-COLUMNS ! 0 _USITM-ITEM-COUNT ! 0 _USITM-UTF8-U !
    0 _USITM-RUN-COUNT ! 0 _USITM-FIELD-COUNT ! 0 _USITM-OUT-U !
    0 _USITM-NATIVE ! 0 _USITM-NATIVE-U ! 0 _USITM-WIRE ! 0 _USITM-WIRE-U !
    0 _USITM-TEXT-U ! 0 _USITM-RUNS ! 0 _USITM-FIELDS !
    0 _USITM-NATIVE-STEP ! 0 _USITM-WIRE-STEP !
    0 _USITM-COPIED-UTF8 ! 0 _USITM-COPIED-RUNS ! 0 _USITM-COPIED-FIELDS !
    0 _USITM-RUN-A ! 0 _USITM-RUN-W ! ;

: USITM-PACK
    ( entry entry-u summary revision destination capacity -- bytes status )
    _USITM-ARGS!
    ['] _USITM-PACK-BODY CATCH ?DUP IF DROP 0 USCOL-S-INVALID THEN
    >R >R _USITM-SCRUB R> R> ;
