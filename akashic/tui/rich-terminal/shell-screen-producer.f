    7 _RSHSP-DSTAGE ! 0 _RSHSP-DIAG-FAMILY !
    -1 _RSHSP-REUSE ! _RSHSP-SOURCE-TARGET _RSHSP-BUILD-BATCH 0 _RSHSP-REUSE !
    0 _RSHSP-DTASK-N ! 0 _RSHSP-DPANE-N ! 0 _RSHSP-DSER-N !
