    _RSHSP-NEXT-OBJECT @ _RSHSP-BANK @ RSHSP-BANK.NEXT-OBJECT !
    _RSHSP-BANK-USED @ _RSHSP-BANK @ RSHSP-BANK.USED !
    _RSHSP-BANK @ _RSHSP-S @ _RSHSP-BANK-VALID? _RSHSP-CHECK ;
