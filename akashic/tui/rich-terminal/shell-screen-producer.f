        _RSHSP-S @ _RSHSP.EXTENSION <> IF RTE-S-UNAVAILABLE EXIT THEN
        0 _RSHSP-P @ _RTHP.EXTENSION !
    ELSE DROP THEN
    _RSHSP-S @ _RSHSP-RETIRE RTE-S-OK ;

