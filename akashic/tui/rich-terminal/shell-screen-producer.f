    _RTHP-EXTENSION-MAGIC OVER RTHPX.MAGIC ! RTHP-EXTENSION-SIZE OVER RTHPX.SIZE !
    DUP DUP RTHPX.SELF !
    _RSHSP-S @ OVER RTHPX.CONTEXT ! ['] _RSHSP-DISPATCH SWAP RTHPX.DISPATCH !
