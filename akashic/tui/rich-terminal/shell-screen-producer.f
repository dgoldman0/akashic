            RUIP-CORRELATION-ATTACHMENT@ _RSHSP-MEMBER@ _RSHSP-MEMBER !
        _RSHSP-ITEM @ _RTE-INSTRUMENT.REGION @ _RSHSP-REGION@ _RSHSP-REGION !
