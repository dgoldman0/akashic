    _RSHSP-ISHELL @ _RTE-SH.BASE @ _RSHSP-P @ _RTHP.FACADE @ <> IF RTE-S-INVALID EXIT THEN
    _RSHSP-ISOURCE @ SHSN-VALID? 0= IF RTE-S-INVALID EXIT THEN
    _RSHSP-S @ RSHSP-SIZE 0 _RSHSP-SPAN!
