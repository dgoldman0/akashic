    _RTSCREEN-P-ROWS ! _RTSCREEN-P-COLS !
    _RTSCREEN-P-P @ RTSCREEN-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _RTSCREEN-P-P @ _RTSCREEN.PHASE @ _RTSCREEN-PH-FAULT = IF
        _RTSCREEN-P-P @ _RTSCREEN.FAULT @ EXIT
    THEN
    _RTSCREEN-P-COLS @ _RTSCREEN-P-ROWS @ _RTSCREEN-P-GEN @
        _RTSCREEN-P-P @ _RTSCREEN-CALL-SURFACE? 0= IF
        SCB-S-INVALID EXIT
    THEN
    _RTSCREEN-P-P @ _RTSCREEN.PHASE @ DUP
        _RTSCREEN-PH-READY-START =
    OVER _RTSCREEN-PH-START-SEALED = OR IF
        DROP _RTSCREEN-P-P @ _RTSCREEN-PREPARE-START EXIT
    THEN
    DUP _RTSCREEN-PH-READY-REVEAL =
    OVER _RTSCREEN-PH-REVEAL-SEALED = OR IF
        DROP _RTSCREEN-P-P @ _RTSCREEN-PREPARE-REVEAL EXIT
    THEN
