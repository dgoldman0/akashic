        2DROP SCB-S-SESSION-LOST R> _RTSCREEN-FAULT-RESULT EXIT
    THEN
    _RTSCREEN-S-STATE @ RTE-UPDATE-SEALED = IF
        2DROP R> DROP SCB-S-OK 0 -1 EXIT
    THEN
    _RTSCREEN-S-STATE @ RTE-UPDATE-PUBLISHING =
    _RTSCREEN-S-STATE @ RTE-UPDATE-AWAITING = OR IF
        2DROP R> DROP SCB-S-OK -1 0 EXIT
    THEN
    _RTSCREEN-S-STATE @ RTE-UPDATE-IDLE =
    _RTSCREEN-S-STATUS @ RTE-S-OK = AND IF
        DROP R@ _RTSCREEN.PHASE !
        0 R@ _RTSCREEN.SCAN !
        R> DROP SCB-S-OK 0 0 EXIT
    THEN
    _RTSCREEN-S-STATE @ RTE-UPDATE-IDLE =
    _RTSCREEN-S-STATUS @ RTE-S-STALE = AND IF
        R@ _RTSCREEN.FACADE @ RTE-RETAINED-CANCEL
            _RTSCREEN-S-STATUS !
        _RTSCREEN-S-STATUS @ RTE-S-SESSION-LOST = IF
            2DROP SCB-S-SESSION-LOST R> _RTSCREEN-FAULT-RESULT EXIT
        THEN
        _RTSCREEN-S-STATUS @ RTE-S-OK <> IF
            2DROP SCB-S-INVALID R> _RTSCREEN-FAULT-RESULT EXIT
        THEN
        NIP R@ _RTSCREEN.PHASE !
        0 R@ _RTSCREEN.SCAN !
        R> DROP SCB-S-OK 0 -1 EXIT
    THEN
    2DROP SCB-S-INVALID R> _RTSCREEN-FAULT-RESULT ;

