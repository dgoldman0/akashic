\ RTSCREEN-STEP
\   ( cols rows generation budget producer
\     -- scb-status more? output-needed? )
: RTSCREEN-STEP  ( cols rows generation budget producer -- scb-status more? output-needed? )
    _RTSCREEN-S-P ! _RTSCREEN-S-BUDGET ! _RTSCREEN-S-GEN !
    _RTSCREEN-S-ROWS ! _RTSCREEN-S-COLS !
    _RTSCREEN-S-P @ RTSCREEN-VALID? 0= IF SCB-S-INVALID 0 0 EXIT THEN
    _RTSCREEN-S-P @ _RTSCREEN.PHASE @ _RTSCREEN-PH-FAULT = IF
        _RTSCREEN-S-P @ _RTSCREEN.FAULT @ 0 0 EXIT
    THEN
    _RTSCREEN-S-BUDGET @ 0> 0= IF
        SCB-S-INVALID _RTSCREEN-S-P @ _RTSCREEN-FAULT-RESULT EXIT
    THEN
    _RTSCREEN-S-COLS @ _RTSCREEN-S-ROWS @ _RTSCREEN-S-GEN @
        _RTSCREEN-S-P @ _RTSCREEN-CALL-SURFACE? 0= IF
        SCB-S-INVALID _RTSCREEN-S-P @ _RTSCREEN-FAULT-RESULT EXIT
    THEN
    _RTSCREEN-S-P @ _RTSCREEN.PHASE @ DUP _RTSCREEN-PH-COLD = IF
        DROP _RTSCREEN-S-P @ _RTSCREEN-STEP-COLD EXIT
    THEN
    DUP _RTSCREEN-PH-PLAN = IF
        DROP _RTSCREEN-S-P @ _RTSCREEN-STEP-PLAN EXIT
    THEN
    DUP _RTSCREEN-PH-PREFLIGHT = IF
        DROP _RTSCREEN-S-P @ _RTSCREEN-STEP-PREFLIGHT EXIT
    THEN
    DUP _RTSCREEN-PH-OWNER-OPEN = IF
        DROP _RTSCREEN-S-P @ _RTSCREEN-STEP-OWNER-OPEN EXIT
    THEN
    DUP _RTSCREEN-PH-OWNER-WAIT = IF
        DROP _RTSCREEN-S-P @ _RTSCREEN-STEP-OWNER-WAIT EXIT
    THEN
    DUP _RTSCREEN-PH-READY-START = IF
        DROP SCB-S-OK 0 -1 EXIT
    THEN
    DUP _RTSCREEN-PH-START-SEALED = IF
        DROP _RTSCREEN-PH-ACCEPT-START _RTSCREEN-PH-READY-START
            _RTSCREEN-S-P @
            _RTSCREEN-STEP-SEALED EXIT
    THEN
    DUP _RTSCREEN-PH-ACCEPT-START = IF
        DROP _RTSCREEN-PH-READY-REVEAL -1 _RTSCREEN-S-P @
            _RTSCREEN-STEP-ACCEPT EXIT
    THEN
    DUP _RTSCREEN-PH-READY-REVEAL = IF
        DROP SCB-S-OK 0 -1 EXIT
    THEN
    DUP _RTSCREEN-PH-REVEAL-SEALED = IF
        DROP _RTSCREEN-PH-ACCEPT-REVEAL _RTSCREEN-PH-READY-REVEAL
            _RTSCREEN-S-P @
            _RTSCREEN-STEP-SEALED EXIT
    THEN
    DUP _RTSCREEN-PH-ACCEPT-REVEAL = IF
        DROP _RTSCREEN-PH-LIVE 0 _RTSCREEN-S-P @
            _RTSCREEN-STEP-ACCEPT EXIT
    THEN
    DUP _RTSCREEN-PH-LIVE = IF
        DROP _RTSCREEN-S-P @ _RTSCREEN-STEP-LIVE EXIT
    THEN
    DUP _RTSCREEN-PH-READY-DELTA = IF
        DROP SCB-S-OK 0 -1 EXIT
    THEN
    _RTSCREEN-PH-DELTA-SEALED = IF
        _RTSCREEN-PH-ACCEPT-DELTA _RTSCREEN-PH-READY-DELTA
            _RTSCREEN-S-P @
            _RTSCREEN-STEP-SEALED EXIT
    THEN
    _RTSCREEN-S-P @ _RTSCREEN.PHASE @ _RTSCREEN-PH-ACCEPT-DELTA = IF
        _RTSCREEN-PH-LIVE 0 _RTSCREEN-S-P @
            _RTSCREEN-STEP-ACCEPT EXIT
    THEN
    SCB-S-INVALID _RTSCREEN-S-P @ _RTSCREEN-FAULT-RESULT ;

