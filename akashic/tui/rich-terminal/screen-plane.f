        SCB-S-INVALID SWAP _RTSCREEN-FAULT-RESULT EXIT
    THEN
    DUP _RTSCREEN-LIMITS-ADMIT? 0= IF
        SCB-S-INVALID SWAP _RTSCREEN-FAULT-RESULT EXIT
    THEN
    _RTSCREEN-S-COLS @ OVER _RTSCREEN.COLS !
    _RTSCREEN-S-ROWS @ OVER _RTSCREEN.ROWS !
    _RTSCREEN-S-GEN @ OVER _RTSCREEN.SURFACE-GEN !
    _RTSCREEN-S-CELLS @ OVER _RTSCREEN.CELLS !
    0 OVER _RTSCREEN.SCAN !
