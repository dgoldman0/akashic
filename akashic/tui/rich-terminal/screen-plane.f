        _RTSCREEN-C-CELL @ _RTSCREEN-P-INDEX @ _RTSCREEN-P-P @
            _RTSCREEN-PENDING!
        IF
            _RTSCREEN-P-INDEX @ OVER _RTSCREEN-RUN? 0= IF
                DROP RTE-S-INVALID _RTSCREEN-P-COUNT @ EXIT
            THEN
            DUP _RTSCREEN.RUN OVER _RTSCREEN.FACADE @
                RTE-GLYPH-RUN-REPLACE DUP RTE-S-OK <> IF
                NIP _RTSCREEN-P-COUNT @ EXIT
            THEN DROP
            1 _RTSCREEN-P-COUNT +!
        THEN
        1 _RTSCREEN-P-INDEX +!
    REPEAT
    DROP RTE-S-OK _RTSCREEN-P-COUNT @ ;

