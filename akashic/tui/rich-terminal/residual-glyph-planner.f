    _RGRP-STYLE-SAME? 0= IF 0 EXIT THEN
    _RGRP-RUN-TEXT-U @ _RGRP-CELL-U @ _RGRP-UADD? 0= IF
        DROP _RGRP-SET-INVALID 0 EXIT
