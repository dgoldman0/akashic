        _RGRP-CONTINUES? 0= IF
            _RGRP-STATUS @ RGRP-S-OK <> IF 0 EXIT THEN
            _RGRP-CLOSE-RUN? 0= IF 0 EXIT THEN
        THEN
    THEN
    _RGRP-RUN-OPEN @ 0= IF _RGRP-OPEN-RUN THEN
    _RGRP-APPEND-CELL? ;

