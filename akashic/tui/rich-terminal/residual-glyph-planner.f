: _RGRP-SADD?  ( a b -- sum flag )
    _RGRP-SADD-B ! _RGRP-SADD-A !
    _RGRP-SADD-A @ _RGRP-SADD-B @ + _RGRP-SADD-SUM !
    _RGRP-SADD-A @ _RGRP-SADD-SUM @ XOR
    _RGRP-SADD-B @ _RGRP-SADD-SUM @ XOR AND 0< IF
        0 0 EXIT
    THEN
    _RGRP-SADD-SUM @ -1 ;

: _RGRP-DIFF-ADD?  ( relative-column delta -- flag )
    _RGRP-DIFF-DELTA ! _RGRP-DIFF-I !
    _RGRP-DIFF-I @ _RGRP-REGION-W @ U> IF 0 EXIT THEN
    _RGRP-DIFF-I @ _RGRP-DIFF-AT DUP @
        _RGRP-DIFF-DELTA @ _RGRP-SADD? 0= IF
            DROP DROP 0 EXIT
        THEN
    SWAP !
    -1 ;

: _RGRP-APPLY-EVENT?  ( -- flag )
    _RGRP-EVENT @ _RGRP-E.CLAIM @ DUP 0= IF DROP 0 EXIT THEN
    1- DUP _RGRP-CLAIM-COUNT @ U< 0= IF DROP 0 EXIT THEN
    DUP _RGRP-EVENT-CLAIM-I ! _RGRP-CLAIM-AT _RGRP-CLAIM !
    _RGRP-EVENT @ _RGRP-E.DELTA @ DUP
    DUP 1 = SWAP -1 = OR 0= IF DROP 0 EXIT THEN
    _RGRP-EVENT-DELTA !
    _RGRP-CLAIM @ _RGRP-C.COL0 @ _RGRP-REGION-X @ MAX
        _RGRP-REGION-X @ - _RGRP-REL-COL0 !
    _RGRP-CLAIM @ _RGRP-C.COL1 @ _RGRP-REGION-COL-END @ MIN
        _RGRP-REGION-X @ - _RGRP-REL-COL1 !
    _RGRP-REL-COL0 @ _RGRP-REL-COL1 @ U< 0= IF 0 EXIT THEN
    _RGRP-REL-COL0 @ _RGRP-EVENT-DELTA @ _RGRP-DIFF-ADD? 0= IF
        0 EXIT
    THEN
    _RGRP-REL-COL1 @ 0 _RGRP-EVENT-DELTA @ -
        _RGRP-DIFF-ADD? ;

: _RGRP-APPLY-ROW-EVENTS?  ( relative-row -- flag )
    _RGRP-HEAD-AT @ _RGRP-EVENT-LINK !
    BEGIN _RGRP-EVENT-LINK @ WHILE
        _RGRP-EVENT-LINK @ 1- DUP _RGRP-EVENT-COUNT @ U< 0= IF
            DROP 0 EXIT
        THEN
        _RGRP-EVENT-AT DUP _RGRP-EVENT !
        _RGRP-E.NEXT @ _RGRP-EVENT-LINK !
        _RGRP-APPLY-EVENT? 0= IF 0 EXIT THEN
    REPEAT
    -1 ;

