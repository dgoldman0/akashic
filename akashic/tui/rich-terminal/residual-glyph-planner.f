    _RGRP-Q !
    _RGRP-PLANE-H ! _RGRP-PLANE-W ! _RGRP-PLANE-A !
    -1 _RGRP-SCREEN-AUTHORIZED !
    _RGRP-BUILD-FROM-SET-PLANE ;

