: _RGRP-CLAIM-VALID?  ( -- flag )
    _RGRP-CLAIM @ _RGRP-C.ATTACHMENT @ 0= IF 0 EXIT THEN
    _RGRP-CLAIM @ _RGRP-C.GENERATION @ 0= IF 0 EXIT THEN
    _RGRP-CLAIM @ _RGRP-C.SOURCE @ UMSN-SOURCE-UIDL <> IF 0 EXIT THEN
    _RGRP-CLAIM @ _RGRP-C.INDEX @ 0< IF 0 EXIT THEN
    _RGRP-CLAIM @ _RGRP-C.SUBKEY @ IF 0 EXIT THEN
    _RGRP-CLAIM @ _RGRP-C.Z @ 255 U> IF 0 EXIT THEN
    _RGRP-CLAIM @ _RGRP-C.ROW0 @ DUP 0< IF DROP 0 EXIT THEN
        _RGRP-CLAIM-ROW0 !
    _RGRP-CLAIM @ _RGRP-C.COL0 @ DUP 0< IF DROP 0 EXIT THEN
        _RGRP-CLAIM-COL0 !
    _RGRP-CLAIM @ _RGRP-C.ROW1 @ DUP 0< IF DROP 0 EXIT THEN
        _RGRP-CLAIM-ROW1 !
    _RGRP-CLAIM @ _RGRP-C.COL1 @ DUP 0< IF DROP 0 EXIT THEN
        _RGRP-CLAIM-COL1 !
    _RGRP-CLAIM-ROW0 @ _RGRP-CLAIM-ROW1 @ U< 0= IF 0 EXIT THEN
    _RGRP-CLAIM-COL0 @ _RGRP-CLAIM-COL1 @ U< 0= IF 0 EXIT THEN
    _RGRP-CLAIM-ROW1 @ _RGRP-SURFACE-H @ U> IF 0 EXIT THEN
    _RGRP-CLAIM-COL1 @ _RGRP-SURFACE-W @ U> IF 0 EXIT THEN
    -1 ;

: _RGRP-INTERSECT-CLAIM?  ( -- flag )
    _RGRP-CLAIM-ROW0 @ _RGRP-REGION-Y @ MAX _RGRP-IROW0 !
    _RGRP-CLAIM-COL0 @ _RGRP-REGION-X @ MAX _RGRP-ICOL0 !
    _RGRP-CLAIM-ROW1 @ _RGRP-REGION-ROW-END @ MIN _RGRP-IROW1 !
    _RGRP-CLAIM-COL1 @ _RGRP-REGION-COL-END @ MIN _RGRP-ICOL1 !
    _RGRP-IROW0 @ _RGRP-IROW1 @ U<
    _RGRP-ICOL0 @ _RGRP-ICOL1 @ U< AND ;

: _RGRP-ADD-EVENT  ( relative-row claim-index delta -- )
    _RGRP-EVENT-DELTA ! _RGRP-EVENT-CLAIM ! _RGRP-EVENT-ROW !
    _RGRP-EVENT-COUNT @ _RGRP-EVENT-AT _RGRP-EVENT !
    _RGRP-EVENT-ROW @ _RGRP-HEAD-AT _RGRP-HEAD !
    _RGRP-HEAD @ @ _RGRP-EVENT @ _RGRP-E.NEXT !
    _RGRP-EVENT-CLAIM @ 1+ _RGRP-EVENT @ _RGRP-E.CLAIM !
    _RGRP-EVENT-DELTA @ _RGRP-EVENT @ _RGRP-E.DELTA !
    1 _RGRP-EVENT-COUNT +!
    _RGRP-EVENT-COUNT @ _RGRP-HEAD @ ! ;

: _RGRP-EVENT-CLAIM?  ( -- flag )
    _RGRP-ACTIVATE-WORK? 0= IF 0 EXIT THEN
    _RGRP-EVENT-COUNT @ 2 _RGRP-UADD? 0= IF
        DROP _RGRP-SET-INVALID 0 EXIT
    THEN
    _RGRP-EVENT-CAP @ U> IF _RGRP-SET-CAPACITY 0 EXIT THEN
    _RGRP-IROW0 @ _RGRP-REGION-Y @ -
        _RGRP-CLAIM-I @ 1 _RGRP-ADD-EVENT
    _RGRP-IROW1 @ _RGRP-REGION-Y @ -
        _RGRP-CLAIM-I @ -1 _RGRP-ADD-EVENT
    -1 ;

\ This is the only traversal of the claim bank.  Each record is validated and
\ contributes at most its two actual events in the same pass.
: _RGRP-BUILD-EVENTS?  ( -- flag )
    0 _RGRP-WORK-ACTIVE ! 0 _RGRP-EVENT-COUNT !
    _RGRP-CLAIM-COUNT @ 0 ?DO
        I _RGRP-CLAIM-I !
        I _RGRP-CLAIM-AT _RGRP-CLAIM !
        _RGRP-CLAIM-VALID? 0= IF 0 UNLOOP EXIT THEN
        _RGRP-INTERSECT-CLAIM? IF
            _RGRP-EVENT-CLAIM? 0= IF 0 UNLOOP EXIT THEN
        THEN
    LOOP
    -1 ;

