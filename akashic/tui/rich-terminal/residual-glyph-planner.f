: _RGRP-ACTIVATE-WORK?  ( -- flag )
    _RGRP-WORK-ACTIVE @ IF -1 EXIT THEN
    _RGRP-REGION-H @ 1 _RGRP-UADD? 0= IF
        DROP _RGRP-SET-INVALID 0 EXIT
    THEN
    DUP _RGRP-HEAD-CAP @ U> IF
        DROP _RGRP-SET-CAPACITY 0 EXIT
