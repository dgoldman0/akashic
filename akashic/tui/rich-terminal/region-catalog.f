VARIABLE _RTE-RC-OWNED-LIMIT
: RTE-CATALOG-STORAGE-DISJOINT? ( a u -- flag )
    DUP 0= IF DROP 0= EXIT THEN
    OVER 0= OVER 0< OR IF 2DROP 0 EXIT THEN
    2DUP MSPAN-NONWRAPPING? 0= IF 2DROP 0 EXIT THEN
    2DUP RTE-ADMISSION-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    _RTE-RC-OWNED-START _RTE-RC-OWNED-LIMIT @ _RTE-RC-OWNED-START -
        MSPAN-OVERLAP? 0= ;
: _RTE-RC-SPAN? ( a u -- flag )
    OVER 7 AND IF 2DROP 0 EXIT THEN RTE-CATALOG-STORAGE-DISJOINT? ;
: _RTE-RC-POS-SPAN? ( a u -- flag )
    DUP 0= IF 2DROP 0 EXIT THEN _RTE-RC-SPAN? ;
: RTE-FAMILY-PLAN-SIZE ( kind -- bytes|0 )
    DUP 1 < OVER 6 > OR IF DROP 0 EXIT THEN
    DUP RTE-FAMILY-INSTRUMENT = IF DROP RTE-INSTRUMENT-PLAN-SIZE EXIT THEN
    RTE-FAMILY-SERIES = IF RTE-SERIES-PLAN-SIZE ELSE RTE-CONTROL-PLAN-SIZE THEN ;
: RTE-FAMILY-ITEM-SIZE ( kind -- bytes|0 )
    DUP RTE-FAMILY-CONTROL = IF DROP RTE-CONTROL-SIZE EXIT THEN
    DUP RTE-FAMILY-GLYPH = IF DROP RTE-GLYPH-RUN-PLAN-ITEM-SIZE EXIT THEN
    DUP RTE-FAMILY-INSTRUMENT = IF DROP RTE-INSTRUMENT-SIZE EXIT THEN
    DUP RTE-FAMILY-STATIC = IF DROP RTE-STATIC-SIZE EXIT THEN
    DUP RTE-FAMILY-SERIES = IF DROP RTE-SERIES-SIZE EXIT THEN
    RTE-FAMILY-PANE = IF RTE-PANE-SIZE ELSE 0 THEN ;
: RTE-FAMILY-ITEMS@ ( entry -- a u )
    DUP _RTE-FE.KIND @ RTE-FAMILY-INSTRUMENT = IF
        _RTE-FE.PLAN-A @ DUP _RTE-IP.ITEMS-A @ SWAP _RTE-IP.ITEMS-U @ EXIT
    THEN
    DUP _RTE-FE.KIND @ RTE-FAMILY-SERIES = IF
        _RTE-FE.PLAN-A @ DUP _RTE-SRP.ITEMS-A @ SWAP _RTE-SRP.ITEMS-U @ EXIT
    THEN _RTE-FE.PLAN-A @ DUP _RTE-CP.ITEMS-A @ SWAP _RTE-CP.ITEMS-U @ ;
: RTE-FAMILY-REGIONS@ ( entry -- a u )
    DUP _RTE-FE.KIND @ RTE-FAMILY-INSTRUMENT <> IF DROP 0 0 EXIT THEN
    _RTE-FE.PLAN-A @ DUP _RTE-IP.REGIONS-A @ SWAP _RTE-IP.REGIONS-U @ ;

\ These fixed-shape passes write no scratch. Every nested source range is
\ checked against this module and engine admission storage before any store.
: _RTE-RC-FIXED? ( catalog -- flag )
    DUP RTE-REGION-CATALOG-SIZE _RTE-RC-POS-SPAN? 0= IF DROP 0 EXIT THEN
    DUP _RTE-RC.OWNER @ 0= OVER _RTE-RC.GENERATION @ 0= OR IF DROP 0 EXIT THEN
    DUP _RTE-RC.SURFACE-COLS @ DUP 0= SWAP _RTE-U32? 0= OR IF DROP 0 EXIT THEN
    DUP _RTE-RC.SURFACE-ROWS @ DUP 0= SWAP _RTE-U32? 0= OR IF DROP 0 EXIT THEN
    DUP _RTE-RC.RESERVED @ IF DROP 0 EXIT THEN
    DUP _RTE-RC.REGIONS-U @ RTE-INSTRUMENT-REGION-SIZE MOD IF DROP 0 EXIT THEN
    DUP _RTE-RC.REGIONS-A @ OVER _RTE-RC.REGIONS-U @
        2DUP _RTE-RC-SPAN? 0= IF 2DROP DROP 0 EXIT THEN
    ROT RTE-REGION-CATALOG-SIZE MSPAN-OVERLAP? 0= ;
: _RTE-RC-FAMILY-FIXED? ( entry -- flag )
    DUP _RTE-FE.KIND @ RTE-FAMILY-PLAN-SIZE DUP 0= IF 2DROP 0 EXIT THEN
    OVER _RTE-FE.PLAN-U @ <> IF DROP 0 EXIT THEN
    DUP _RTE-FE.RESERVED @ IF DROP 0 EXIT THEN
    DUP _RTE-FE.PLAN-A @ OVER _RTE-FE.PLAN-U @
        _RTE-RC-POS-SPAN? 0= IF DROP 0 EXIT THEN
    DUP RTE-FAMILY-ITEMS@ _RTE-RC-POS-SPAN? 0= IF DROP 0 EXIT THEN
    DUP RTE-FAMILY-ITEMS@ NIP OVER _RTE-FE.KIND @ RTE-FAMILY-ITEM-SIZE MOD IF DROP 0 EXIT THEN
    DUP _RTE-FE.BYTES-A @ OVER _RTE-FE.BYTES-U @
        RTE-CATALOG-STORAGE-DISJOINT? 0= IF DROP 0 EXIT THEN
    DUP _RTE-FE.KIND @ RTE-FAMILY-SERIES = IF
        DUP _RTE-FE.BYTES-A @ 7 AND IF DROP 0 EXIT THEN
    THEN
    DUP _RTE-FE.KIND @ RTE-FAMILY-GLYPH = IF
        DUP _RTE-FE.REFS-A @ OVER _RTE-FE.REFS-U @
            _RTE-RC-POS-SPAN? 0= IF DROP 0 EXIT THEN
        DUP RTE-FAMILY-ITEMS@ NIP RTE-GLYPH-RUN-PLAN-ITEM-SIZE / 16 *
            OVER _RTE-FE.REFS-U @ <> IF DROP 0 EXIT THEN
    ELSE
        DUP _RTE-FE.REFS-A @ OVER _RTE-FE.REFS-U @ OR IF DROP 0 EXIT THEN
    THEN
    DUP _RTE-FE.KIND @ RTE-FAMILY-INSTRUMENT = IF
        DUP RTE-FAMILY-REGIONS@ _RTE-RC-POS-SPAN? 0= IF DROP 0 EXIT THEN
        DUP RTE-FAMILY-REGIONS@ NIP RTE-INSTRUMENT-REGION-SIZE MOD IF DROP 0 EXIT THEN
    THEN DROP -1 ;
: _RTE-RC-BATCH-FIXED? ( batch -- flag )
    DUP RTE-FAMILY-BATCH-SIZE _RTE-RC-POS-SPAN? 0= IF DROP 0 EXIT THEN
    DUP _RTE-FB.ABI @ 1 <> IF DROP 0 EXIT THEN
    DUP _RTE-FB.RESERVED @ IF DROP 0 EXIT THEN
    DUP _RTE-FB.ATTEMPT @ 0= OVER _RTE-FB.SOURCE-GENERATION @ 0= OR
        OVER _RTE-FB.SURFACE-GENERATION @ 0= OR IF DROP 0 EXIT THEN
    DUP _RTE-FB.CATALOG-U @ RTE-REGION-CATALOG-SIZE <> IF DROP 0 EXIT THEN
    DUP _RTE-FB.CATALOG-A @ _RTE-RC-FIXED? 0= IF DROP 0 EXIT THEN
    DUP _RTE-FB.FAMILIES-A @ OVER _RTE-FB.FAMILIES-U @
        _RTE-RC-POS-SPAN? 0= IF DROP 0 EXIT THEN
    DUP _RTE-FB.FAMILIES-U @ RTE-FAMILY-ENTRY-SIZE MOD IF DROP 0 EXIT THEN
    DUP _RTE-FB.FAMILIES-U @ RTE-FAMILY-ENTRY-SIZE / 0 ?DO
        DUP _RTE-FB.FAMILIES-A @ I RTE-FAMILY-ENTRY-SIZE * +
            _RTE-RC-FAMILY-FIXED? 0= IF DROP 0 UNLOOP EXIT THEN
    LOOP DROP -1 ;

