    DUP _RTE-PANE.CONTENT-HEIGHT @ DUP 0= SWAP _RTE-U32? 0= OR IF DROP 0 EXIT THEN
    DUP _RTE-PANE.CONTENT-WIDTH @ DUP 0= SWAP _RTE-U32? 0= OR IF DROP 0 EXIT THEN
    DUP _RTE-PANE.CONTENT-ROW @ OVER _RTE-PANE.CONTENT-HEIGHT @ _RTE-SADD? 0= IF 2DROP 0 EXIT THEN DROP
    DUP _RTE-PANE.CONTENT-COL @ OVER _RTE-PANE.CONTENT-WIDTH @ _RTE-SADD? 0= IF 2DROP 0 EXIT THEN DROP
