\ Enumerate exact source extents; unused span positions are canonical (0,0).
\ Separate families can use adjacent slices of one allocation, not overlapping
\ containing capacities. No caller work bank or hidden count cap is needed.
: RTE-FAMILY-BATCH-FIXED? ( batch -- flag ) _RTE-RC-BATCH-FIXED? ;
: RTE-FAMILY-BATCH-SPAN-COUNT ( fixed-batch -- count )
    _RTE-FB.FAMILIES-U @ RTE-FAMILY-ENTRY-SIZE / 5 * 4 + ;
: RTE-FAMILY-BATCH-SPAN@ ( index fixed-batch -- a u )
    2DUP RTE-FAMILY-BATCH-SPAN-COUNT U< 0= IF 2DROP 0 0 EXIT THEN
    OVER 0= IF NIP RTE-FAMILY-BATCH-SIZE EXIT THEN
    OVER 1 = IF NIP _RTE-FB.CATALOG-A @ RTE-REGION-CATALOG-SIZE EXIT THEN
    OVER 2 = IF NIP _RTE-FB.CATALOG-A @
        DUP _RTE-RC.REGIONS-A @ SWAP _RTE-RC.REGIONS-U @ EXIT THEN
    OVER 3 = IF NIP DUP _RTE-FB.FAMILIES-A @ SWAP _RTE-FB.FAMILIES-U @ EXIT THEN
    SWAP 4 - 5 /MOD RTE-FAMILY-ENTRY-SIZE * ROT _RTE-FB.FAMILIES-A @ +
    OVER 0= IF NIP DUP _RTE-FE.PLAN-A @ SWAP _RTE-FE.PLAN-U @ EXIT THEN
    OVER 1 = IF NIP RTE-FAMILY-ITEMS@ EXIT THEN
    OVER 2 = IF NIP DUP _RTE-FE.BYTES-A @ SWAP _RTE-FE.BYTES-U @ EXIT THEN
    OVER 3 = IF NIP DUP _RTE-FE.REFS-A @ SWAP _RTE-FE.REFS-U @ EXIT THEN
    NIP RTE-FAMILY-REGIONS@ ;
: _RTE-RC-SPAN-AT ( index -- a u ) _RTE-RC-BATCH @ RTE-FAMILY-BATCH-SPAN@ ;
: _RTE-RC-PAIRWISE? ( -- flag )
    _RTE-RC-COUNT @ 5 * 4 + _RTE-RC-SPAN-COUNT !
    _RTE-RC-SPAN-COUNT @ 0 ?DO
        I _RTE-RC-SPAN-AT _RTE-RC-SU ! _RTE-RC-SA !
        I 0 ?DO
            I _RTE-RC-SPAN-AT _RTE-RC-SA @ _RTE-RC-SU @ MSPAN-OVERLAP? IF
                0 UNLOOP UNLOOP EXIT
            THEN
        LOOP
    LOOP -1 ;
: _RTE-RC-MATCH-REGION? ( region-copy -- flag )
    DUP _RTE-IR.ID @ _RTE-RC-CATALOG @ RTE-REGION-CATALOG-FIND DUP 0= IF
        2DROP 0 EXIT
    THEN 96 ROT 96 COMPARE 0= ;
: _RTE-RC-PLAN-HEADER? ( -- flag )
    _RTE-RC-PLAN @ 32 _RTE-RC-CATALOG @ 32 COMPARE IF 0 EXIT THEN
    _RTE-RC-KIND @ RTE-FAMILY-SERIES = IF -1 EXIT THEN
    _RTE-RC-KIND @ RTE-FAMILY-INSTRUMENT = IF
        _RTE-RC-PLAN @ _RTE-IP.RESERVED @ IF 0 EXIT THEN
        _RTE-RC-FAMILY @ RTE-FAMILY-REGIONS@ 96 / 0 ?DO
            DUP I 96 * + _RTE-RC-MATCH-REGION? 0= IF DROP 0 UNLOOP EXIT THEN
        LOOP DROP -1 EXIT
    THEN
    _RTE-RC-PLAN @ _RTE-CP.RESERVED @ IF 0 EXIT THEN
    _RTE-RC-PLAN @ _RTE-CP.REGION-ID @
        _RTE-RC-CATALOG @ RTE-REGION-CATALOG-FIND DUP 0= IF DROP 0 EXIT THEN
    88 _RTE-RC-PLAN @ 32 + 88 COMPARE 0= ;
: _RTE-RC-DENSE? ( a u -- flag )
    DUP 0= IF DROP 0= EXIT THEN
    OVER _RTE-RC-FAMILY @ _RTE-FE.BYTES-A @ _RTE-RC-TEXT-O @ + <> IF 2DROP 0 EXIT THEN
    _RTE-RC-TEXT-O @ OVER _RTE-UADD? 0= IF DROP 2DROP 0 EXIT THEN
    DUP _RTE-RC-FAMILY @ _RTE-FE.BYTES-U @ U> IF DROP 2DROP 0 EXIT THEN
    _RTE-RC-TEXT-O ! 2DROP -1 ;
: _RTE-RC-PAYLOAD? ( -- flag )
    _RTE-RC-KIND @ RTE-FAMILY-CONTROL = IF
        _RTE-RC-ITEM @ _RTE-CONTROL.LABEL-A @ _RTE-RC-ITEM @ _RTE-CONTROL.LABEL-U @
            _RTE-RC-DENSE? 0= IF 0 EXIT THEN
        _RTE-RC-ITEM @ _RTE-CONTROL.SHORTCUT-A @ _RTE-RC-ITEM @ _RTE-CONTROL.SHORTCUT-U @
            _RTE-RC-DENSE? 0= IF 0 EXIT THEN
        _RTE-RC-ITEM @ _RTE-CONTROL.CONTENT-A @ _RTE-RC-ITEM @ _RTE-CONTROL.CONTENT-U @
            _RTE-RC-DENSE? EXIT
    THEN
    _RTE-RC-KIND @ RTE-FAMILY-GLYPH = IF
        _RTE-RC-REF @ @ _RTE-RC-TEXT-O @ <> IF 0 EXIT THEN
        _RTE-RC-REF @ 8 + @ DUP _RTE-RC-ITEM @ _RTE-LPI.TEXT-CAPACITY @ <> IF DROP 0 EXIT THEN
        DUP IF _RTE-RC-FAMILY @ _RTE-FE.BYTES-A @ _RTE-RC-TEXT-O @ + SWAP
        ELSE 0 SWAP THEN _RTE-RC-DENSE? EXIT
    THEN
    _RTE-RC-KIND @ RTE-FAMILY-INSTRUMENT = IF
        _RTE-RC-ITEM @ _RTE-INSTRUMENT.UNIT-A @ _RTE-RC-ITEM @ _RTE-INSTRUMENT.UNIT-U @
            _RTE-RC-DENSE? EXIT
    THEN
    _RTE-RC-KIND @ RTE-FAMILY-STATIC = IF
        _RTE-RC-ITEM @ _RTE-STATIC.LABEL-A @ _RTE-RC-ITEM @ _RTE-STATIC.LABEL-U @
            _RTE-RC-DENSE? 0= IF 0 EXIT THEN
        _RTE-RC-ITEM @ _RTE-STATIC.VALUE-A @ _RTE-RC-ITEM @ _RTE-STATIC.VALUE-U @
            _RTE-RC-DENSE? EXIT
    THEN
    _RTE-RC-KIND @ RTE-FAMILY-SERIES = IF
        _RTE-RC-ITEM @ _RTE-SERIES.MODE @ DUP 1 U> IF DROP 0 EXIT THEN
        IF 8 ELSE 16 THEN
        _RTE-RC-ITEM @ _RTE-SERIES.SAMPLES-U @ OVER MOD IF DROP 0 EXIT THEN DROP
        _RTE-RC-ITEM @ _RTE-SERIES.SAMPLES-A @
        _RTE-RC-ITEM @ _RTE-SERIES.SAMPLES-U @ _RTE-RC-DENSE? EXIT
    THEN
    _RTE-RC-ITEM @ _RTE-PANE.TITLE-A @ _RTE-RC-ITEM @ _RTE-PANE.TITLE-U @ _RTE-RC-DENSE? ;
VARIABLE _RTE-RC-MATCHES
: _RTE-RC-PANE-UNIQUE? ( -- flag )
    0 _RTE-RC-MATCHES !
    _RTE-RC-COUNT @ 0 ?DO
        _RTE-RC-FAMILIES @ I RTE-FAMILY-ENTRY-SIZE * +
        DUP _RTE-FE.KIND @ RTE-FAMILY-PANE = IF
            RTE-FAMILY-ITEMS@ RTE-PANE-SIZE / 0 ?DO
                DUP I RTE-PANE-SIZE * + _RTE-PANE.CONTENT-REGION @
                _RTE-RC-PANE @ _RTE-PANE.CONTENT-REGION @ = IF 1 _RTE-RC-MATCHES +! THEN
            LOOP DROP
        ELSE DROP THEN
    LOOP _RTE-RC-MATCHES @ 1 = ;
: _RTE-RC-PANE-GRAPH? ( -- flag )
    _RTE-RC-ITEM @ _RTE-RC-PANE !
    _RTE-RC-PANE @ RTE-PANE-VALID? 0= IF 0 EXIT THEN
    _RTE-RC-PANE-UNIQUE? 0= IF 0 EXIT THEN
    _RTE-RC-PANE @ _RTE-PANE.CONTENT-REGION @ _RTE-RC-CATALOG @
        RTE-REGION-CATALOG-FIND DUP 0= IF DROP 0 EXIT THEN _RTE-RC-CONTENT !
    _RTE-RC-CONTENT @ _RTE-IR.Z @ _RTE-RC-MEMBER @ _RTE-IR.Z @ < IF 0 EXIT THEN
    _RTE-RC-CONTENT @ _RTE-IR.Z @ _RTE-RC-MEMBER @ _RTE-IR.Z @ = IF
        _RTE-RC-CONTENT @ _RTE-IR.ID @ _RTE-RC-MEMBER @ _RTE-IR.ID @ U> 0= IF 0 EXIT THEN
    THEN
    _RTE-RC-CONTENT @ _RTE-IR.FLAGS @ RTE-REGION-CLIPPED AND 0= IF 0 EXIT THEN
    _RTE-RC-CONTENT @ _RTE-IR.CLIP-COLS @ 0= IF -1 EXIT THEN
    _RTE-RC-MEMBER @ _RTE-IR.X @ _RTE-RC-PANE @ _RTE-PANE.COL @ +
