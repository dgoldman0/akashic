0 CONSTANT RSHMM-S-OK
1 CONSTANT RSHMM-S-CAPACITY
2 CONSTANT RSHMM-S-UNAVAILABLE
3 CONSTANT RSHMM-S-INVALID
112 CONSTANT RSHMM-ENTRY-SIZE
: RSHMM.TOKEN ( entry -- a ) ;
: RSHMM.SLOT-ID ( entry -- a ) 8 + ;
: RSHMM.OWNER ( entry -- a ) 16 + ;
: RSHMM.GENERATION ( entry -- a ) 24 + ;
: RSHMM.CONTENT-REGION ( entry -- a ) 32 + ;
: RSHMM.SOURCE-INDEX ( entry -- a ) 40 + ;
: RSHMM.DIRECTORY-INDEX ( entry -- a ) 48 + ;
: RSHMM.ROW ( entry -- a ) 56 + ;
: RSHMM.COL ( entry -- a ) 64 + ;
: RSHMM.HEIGHT ( entry -- a ) 72 + ;
: RSHMM.WIDTH ( entry -- a ) 80 + ;
: RSHMM.CHROME-REGION ( entry -- a ) 88 + ;
: RSHMM.PANE-ID ( entry -- a ) 96 + ;
: RSHMM.RESERVED ( entry -- a ) 104 + ;
: RSHMM-TOKEN@ ( entry -- token ) RSHMM.TOKEN @ ;
: RSHMM-CONTENT-REGION@ ( entry -- region ) RSHMM.CONTENT-REGION @ ;

CREATE _RSHMM-OWNED-START
VARIABLE _RSHMM-OWNED-LIMIT
: RSHMM-STORAGE-DISJOINT? ( a u -- flag )
    DUP 0= IF DROP 0= EXIT THEN
    OVER 0= OVER 0< OR IF 2DROP 0 EXIT THEN
    2DUP MSPAN-NONWRAPPING? 0= IF 2DROP 0 EXIT THEN
    2DUP RSHPL-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    _RSHMM-OWNED-START _RSHMM-OWNED-LIMIT @ _RSHMM-OWNED-START - MSPAN-OVERLAP? 0= ;
: _RSHMM-SPAN? ( a u -- flag )
    OVER 7 AND IF 2DROP 0 EXIT THEN RSHMM-STORAGE-DISJOINT? ;
: _RSHMM-8DROP ( x x x x x x x x -- ) 2DROP 2DROP 2DROP 2DROP ;
VARIABLE _RSHMM-M VARIABLE _RSHMM-MU
VARIABLE _RSHMM-D VARIABLE _RSHMM-DU
VARIABLE _RSHMM-C VARIABLE _RSHMM-CU
VARIABLE _RSHMM-O VARIABLE _RSHMM-OU
CREATE _RSHMM-SPANS 64 ALLOT
VARIABLE _RSHMM-N VARIABLE _RSHMM-USED
VARIABLE _RSHMM-ENTRY VARIABLE _RSHMM-CORR VARIABLE _RSHMM-DIR
VARIABLE _RSHMM-PANE-INDEX VARIABLE _RSHMM-DIR-INDEX
VARIABLE _RSHMM-I VARIABLE _RSHMM-J VARIABLE _RSHMM-OTHER
VARIABLE _RSHMM-DRAW VARIABLE _RSHMM-ATTACHMENT
VARIABLE _RSHMM-SA VARIABLE _RSHMM-SU VARIABLE _RSHMM-OUT
: _RSHMM-S@ ( index -- a u ) 16 * _RSHMM-SPANS + DUP @ SWAP 8 + @ ;
: _RSHMM-S! ( a u index -- ) 16 * _RSHMM-SPANS + >R R@ 8 + ! R> ! ;
: _RSHMM-SPANS? ( model/u directory/u correlations/u dst/cap -- flag )
    7 PICK 7 PICK _RSHMM-SPAN? 0= IF _RSHMM-8DROP 0 EXIT THEN
    5 PICK 5 PICK _RSHMM-SPAN? 0= IF _RSHMM-8DROP 0 EXIT THEN
    3 PICK 3 PICK _RSHMM-SPAN? 0= IF _RSHMM-8DROP 0 EXIT THEN
    1 PICK 1 PICK _RSHMM-SPAN? 0= IF _RSHMM-8DROP 0 EXIT THEN
    _RSHMM-OU ! _RSHMM-O ! _RSHMM-CU ! _RSHMM-C !
    _RSHMM-DU ! _RSHMM-D ! _RSHMM-MU ! _RSHMM-M !
    _RSHMM-M @ _RSHMM-MU @ 0 _RSHMM-S!
    _RSHMM-D @ _RSHMM-DU @ 1 _RSHMM-S!
    _RSHMM-C @ _RSHMM-CU @ 2 _RSHMM-S!
    _RSHMM-O @ _RSHMM-OU @ 3 _RSHMM-S!
    4 0 DO I _RSHMM-S@ _RSHMM-SU ! _RSHMM-SA !
        I 0 ?DO I _RSHMM-S@ _RSHMM-SA @ _RSHMM-SU @ MSPAN-OVERLAP? IF
            0 UNLOOP UNLOOP EXIT
        THEN LOOP
    LOOP -1 ;
: _RSHMM-DIRECTORY? ( -- flag )
    _RSHMM-DU @ RUHA-DOCUMENT-SIZE MOD IF 0 EXIT THEN
    _RSHMM-DU @ RUHA-DOCUMENT-SIZE / 0 ?DO
        _RSHMM-D @ I RUHA-DOCUMENT-SIZE * + _RSHMM-DIR !
        _RSHMM-DIR @ RUHA-DOCUMENT-TOKEN@ 0= IF 0 UNLOOP EXIT THEN
        _RSHMM-DIR @ RUHA-DOCUMENT-SLOT-ID@ DUP 0= SWAP -1 = OR IF 0 UNLOOP EXIT THEN
        _RSHMM-DIR @ RUHA-DOCUMENT-OWNER-ID@ 0=
        _RSHMM-DIR @ RUHA-DOCUMENT-OWNER-GENERATION@ 0= OR IF 0 UNLOOP EXIT THEN
        _RSHMM-DIR @ RUHA-DOCUMENT-ROW@ _RTE-I32? 0=
        _RSHMM-DIR @ RUHA-DOCUMENT-COL@ _RTE-I32? 0= OR IF 0 UNLOOP EXIT THEN
        _RSHMM-DIR @ RUHA-DOCUMENT-HEIGHT@ DUP 0= SWAP _RTE-U32? 0= OR IF 0 UNLOOP EXIT THEN
        _RSHMM-DIR @ RUHA-DOCUMENT-WIDTH@ DUP 0= SWAP _RTE-U32? 0= OR IF 0 UNLOOP EXIT THEN
        I 0 ?DO
            _RSHMM-D @ I RUHA-DOCUMENT-SIZE * +
            DUP RUHA-DOCUMENT-TOKEN@ _RSHMM-DIR @ RUHA-DOCUMENT-TOKEN@ =
            SWAP RUHA-DOCUMENT-SLOT-ID@ _RSHMM-DIR @ RUHA-DOCUMENT-SLOT-ID@ = OR IF
                0 UNLOOP UNLOOP EXIT
            THEN
        LOOP
    LOOP -1 ;
: _RSHMM-CORRELATION-BASE? ( -- flag )
    _RSHMM-CORR @ RSHPL-CORRELATION.KIND @ DUP 1 < SWAP 5 > OR IF 0 EXIT THEN
    _RSHMM-CORR @ RSHPL-CORRELATION.SOURCE-OWNER @ _RSHMM-M @ SHM.OWNER-ID @ <>
    _RSHMM-CORR @ RSHPL-CORRELATION.SOURCE-GENERATION @ _RSHMM-M @ SHM.OWNER-GEN @ <> OR
    _RSHMM-CORR @ RSHPL-CORRELATION.EPOCH @ _RSHMM-M @ SHM.EPOCH @ <> OR IF 0 EXIT THEN
    _RSHMM-CORR @ RSHPL-CORRELATION.DRAW @ DUP 0= IF DROP 0 EXIT THEN
    _RSHMM-DRAW @ IF _RSHMM-DRAW @ <> IF 0 EXIT THEN ELSE _RSHMM-DRAW ! THEN
    _RSHMM-CORR @ RSHPL-CORRELATION.ATTACHMENT @ DUP 0= IF DROP 0 EXIT THEN
    _RSHMM-ATTACHMENT @ IF _RSHMM-ATTACHMENT @ <> IF 0 EXIT THEN
    ELSE _RSHMM-ATTACHMENT ! THEN -1 ;
: _RSHMM-PANE-CORRELATION? ( -- flag )
    _RSHMM-CORR @ RSHPL-CORRELATION.INDEX @ DUP _RSHMM-M @ SHM.COUNT @ U< 0= IF
        DROP 0 EXIT
    THEN DUP _RSHMM-PANE-INDEX ! _RSHMM-M @ SHM-ENTRY _RSHMM-ENTRY !
    _RSHMM-ENTRY @ SHME.KIND @ SHM-K-PANE <> IF 0 EXIT THEN
    _RSHMM-CORR @ RSHPL-CORRELATION.KEY @ _RSHMM-ENTRY @ SHME.KEY @ <>
    _RSHMM-CORR @ RSHPL-CORRELATION.IDENTITY @ _RSHMM-ENTRY @ SHME.IDENTITY @ <> OR
    _RSHMM-CORR @ RSHPL-CORRELATION.OWNER @ _RSHMM-ENTRY @ SHME.OWNER-ID @ <> OR
    _RSHMM-CORR @ RSHPL-CORRELATION.GENERATION @ _RSHMM-ENTRY @ SHME.OWNER-GEN @ <> OR IF 0 EXIT THEN
    _RSHMM-CORR @ RSHPL-CORRELATION.ACTION @ _RSHMM-ENTRY @ SHME.ACTION @ <>
    _RSHMM-CORR @ RSHPL-CORRELATION.FLAGS @ _RSHMM-ENTRY @ SHME.FLAGS @ <> OR IF 0 EXIT THEN
    _RSHMM-CORR @ RSHPL-CORRELATION.ROW @ _RSHMM-ENTRY @ SHME.ROW @ <>
    _RSHMM-CORR @ RSHPL-CORRELATION.COL @ _RSHMM-ENTRY @ SHME.COL @ <> OR
    _RSHMM-CORR @ RSHPL-CORRELATION.HEIGHT @ _RSHMM-ENTRY @ SHME.HEIGHT @ <> OR
    _RSHMM-CORR @ RSHPL-CORRELATION.WIDTH @ _RSHMM-ENTRY @ SHME.WIDTH @ <> OR IF 0 EXIT THEN
    _RSHMM-CORR @ RSHPL-CORRELATION.ID @ 0=
    _RSHMM-CORR @ RSHPL-CORRELATION.REGION @ 0= OR
    _RSHMM-CORR @ RSHPL-CORRELATION.CONTENT-REGION @ 0= OR IF 0 EXIT THEN
    _RSHMM-CORR @ RSHPL-CORRELATION.REGION @
    _RSHMM-CORR @ RSHPL-CORRELATION.CONTENT-REGION @ = IF 0 EXIT THEN
    _RSHMM-CORR @ RSHPL-CORRELATION.ACTION-OFFSET @
    _RSHMM-CORR @ RSHPL-CORRELATION.ACTION-BYTES @ OR IF 0 EXIT THEN
    _RSHMM-CORR @ RSHPL-CORRELATION.TEXT-BYTES @ _RSHMM-ENTRY @ SHME.TITLE-U @ <> IF 0 EXIT THEN
    _RSHMM-CORR @ RSHPL-CORRELATION.TEXT-OFFSET @ _RTE-U32? 0= IF 0 EXIT THEN
    _RSHMM-I @ 0 ?DO
        _RSHMM-C @ I RSHPL-CORRELATION-SIZE * + _RSHMM-OTHER !
        _RSHMM-OTHER @ RSHPL-CORRELATION.KIND @ SHM-K-PANE = IF
            _RSHMM-OTHER @ RSHPL-CORRELATION.INDEX @ _RSHMM-PANE-INDEX @ =
            _RSHMM-OTHER @ RSHPL-CORRELATION.IDENTITY @ _RSHMM-ENTRY @ SHME.IDENTITY @ = OR
            _RSHMM-OTHER @ RSHPL-CORRELATION.CONTENT-REGION @
                _RSHMM-CORR @ RSHPL-CORRELATION.CONTENT-REGION @ = OR
            _RSHMM-OTHER @ RSHPL-CORRELATION.ID @ _RSHMM-CORR @ RSHPL-CORRELATION.ID @ = OR IF
                0 UNLOOP EXIT
            THEN
        THEN
    LOOP -1 ;
: _RSHMM-JOIN? ( -- flag )
    -1 _RSHMM-DIR-INDEX ! 0 _RSHMM-DIR !
    _RSHMM-DU @ RUHA-DOCUMENT-SIZE / 0 ?DO
        _RSHMM-D @ I RUHA-DOCUMENT-SIZE * + DUP RUHA-DOCUMENT-SLOT-ID@
        _RSHMM-ENTRY @ SHME.IDENTITY @ = IF
            DUP _RSHMM-DIR ! I _RSHMM-DIR-INDEX !
        THEN DROP
    LOOP
    _RSHMM-DIR @ 0= IF -1 EXIT THEN
    _RSHMM-DIR @ RUHA-DOCUMENT-OWNER-ID@ _RSHMM-ENTRY @ SHME.OWNER-ID @ <>
    _RSHMM-DIR @ RUHA-DOCUMENT-OWNER-GENERATION@ _RSHMM-ENTRY @ SHME.OWNER-GEN @ <> OR IF 0 EXIT THEN
    _RSHMM-DIR @ RUHA-DOCUMENT-ROW@ _RSHMM-ENTRY @ SHME.CONTENT-ROW @ <>
    _RSHMM-DIR @ RUHA-DOCUMENT-COL@ _RSHMM-ENTRY @ SHME.CONTENT-COL @ <> OR
    _RSHMM-DIR @ RUHA-DOCUMENT-HEIGHT@ _RSHMM-ENTRY @ SHME.CONTENT-H @ <> OR
    _RSHMM-DIR @ RUHA-DOCUMENT-WIDTH@ _RSHMM-ENTRY @ SHME.CONTENT-W @ <> OR 0= ;
: _RSHMM-MEASURE? ( -- flag )
    _RSHMM-M @ _RSHMM-MU @ SHSN-FROZEN-VALIDATE SHSN-S-OK <> IF 0 EXIT THEN
    _RSHMM-DIRECTORY? 0= IF 0 EXIT THEN
    _RSHMM-CU @ RSHPL-CORRELATION-SIZE MOD IF 0 EXIT THEN
    0 _RSHMM-N ! 0 _RSHMM-DRAW ! 0 _RSHMM-ATTACHMENT !
    _RSHMM-CU @ RSHPL-CORRELATION-SIZE / 0 ?DO
        I _RSHMM-I ! _RSHMM-C @ I RSHPL-CORRELATION-SIZE * + _RSHMM-CORR !
        _RSHMM-CORRELATION-BASE? 0= IF 0 UNLOOP EXIT THEN
        _RSHMM-CORR @ RSHPL-CORRELATION.KIND @ SHM-K-PANE = IF
            _RSHMM-PANE-CORRELATION? 0= IF 0 UNLOOP EXIT THEN
            _RSHMM-JOIN? 0= IF 0 UNLOOP EXIT THEN
            1 _RSHMM-N +!
        THEN
    LOOP _RSHMM-N @ RSHMM-ENTRY-SIZE * _RSHMM-USED ! -1 ;
: _RSHMM-EMIT ( -- )
    _RSHMM-OUT @ RSHMM-ENTRY-SIZE 0 FILL
    _RSHMM-DIR @ IF _RSHMM-DIR @ RUHA-DOCUMENT-TOKEN@ ELSE 0 THEN _RSHMM-OUT @ RSHMM.TOKEN !
    _RSHMM-ENTRY @ SHME.IDENTITY @ _RSHMM-OUT @ RSHMM.SLOT-ID !
    _RSHMM-ENTRY @ SHME.OWNER-ID @ _RSHMM-OUT @ RSHMM.OWNER !
    _RSHMM-ENTRY @ SHME.OWNER-GEN @ _RSHMM-OUT @ RSHMM.GENERATION !
    _RSHMM-CORR @ RSHPL-CORRELATION.CONTENT-REGION @ _RSHMM-OUT @ RSHMM.CONTENT-REGION !
    _RSHMM-PANE-INDEX @ _RSHMM-OUT @ RSHMM.SOURCE-INDEX !
    _RSHMM-DIR-INDEX @ _RSHMM-OUT @ RSHMM.DIRECTORY-INDEX !
    _RSHMM-ENTRY @ SHME.CONTENT-ROW @ _RSHMM-OUT @ RSHMM.ROW !
    _RSHMM-ENTRY @ SHME.CONTENT-COL @ _RSHMM-OUT @ RSHMM.COL !
    _RSHMM-ENTRY @ SHME.CONTENT-H @ _RSHMM-OUT @ RSHMM.HEIGHT !
    _RSHMM-ENTRY @ SHME.CONTENT-W @ _RSHMM-OUT @ RSHMM.WIDTH !
    _RSHMM-CORR @ RSHPL-CORRELATION.REGION @ _RSHMM-OUT @ RSHMM.CHROME-REGION !
    _RSHMM-CORR @ RSHPL-CORRELATION.ID @ _RSHMM-OUT @ RSHMM.PANE-ID !
    RSHMM-ENTRY-SIZE _RSHMM-OUT +! ;
: RSHMM-BUILD ( model/u directory/u correlations/u dst/cap -- count used status )
    _RSHMM-SPANS? 0= IF 0 0 RSHMM-S-INVALID EXIT THEN
    _RSHMM-MEASURE? 0= IF 0 0 RSHMM-S-INVALID EXIT THEN
    _RSHMM-USED @ _RSHMM-OU @ U> IF 0 0 RSHMM-S-CAPACITY EXIT THEN
    _RSHMM-O @ _RSHMM-OUT !
    _RSHMM-CU @ RSHPL-CORRELATION-SIZE / 0 ?DO
        _RSHMM-C @ I RSHPL-CORRELATION-SIZE * + _RSHMM-CORR !
        _RSHMM-CORR @ RSHPL-CORRELATION.KIND @ SHM-K-PANE = IF
            _RSHMM-CORR @ RSHPL-CORRELATION.INDEX @ DUP _RSHMM-PANE-INDEX !
            _RSHMM-M @ SHM-ENTRY _RSHMM-ENTRY !
            _RSHMM-JOIN? DROP _RSHMM-EMIT
        THEN
    LOOP _RSHMM-N @ _RSHMM-USED @ RSHMM-S-OK ;

\ Lookup is read-only and requires the exact immutable successful output span.
: RSHMM-FIND ( token validated-map-a map-u -- entry|0 )
    2 PICK 0= IF DROP 2DROP 0 EXIT THEN
    OVER + >R BEGIN DUP R@ U< WHILE
        2DUP RSHMM.TOKEN @ = IF NIP R> DROP EXIT THEN
        RSHMM-ENTRY-SIZE +
    REPEAT 2DROP R> DROP 0 ;

VARIABLE _RSHMM-R VARIABLE _RSHMM-L VARIABLE _RSHMM-H VARIABLE _RSHMM-W
VARIABLE _RSHMM-MAP VARIABLE _RSHMM-MAP-U VARIABLE _RSHMM-MATCHES VARIABLE _RSHMM-REGION
: RSHMM-RECT-MEMBER ( row col height width validated-map-a map-u -- region status )
    2DUP _RSHMM-SPAN? 0= IF 2DROP 2DROP 2DROP 0 RSHMM-S-INVALID EXIT THEN
    DUP RSHMM-ENTRY-SIZE MOD IF 2DROP 2DROP 2DROP 0 RSHMM-S-INVALID EXIT THEN
    _RSHMM-MAP-U ! _RSHMM-MAP ! _RSHMM-W ! _RSHMM-H ! _RSHMM-L ! _RSHMM-R !
    _RSHMM-R @ _RTE-I32? 0= _RSHMM-L @ _RTE-I32? 0= OR IF 0 RSHMM-S-INVALID EXIT THEN
    _RSHMM-H @ DUP 0= SWAP _RTE-U32? 0= OR
    _RSHMM-W @ DUP 0= SWAP _RTE-U32? 0= OR OR IF 0 RSHMM-S-INVALID EXIT THEN
    0 _RSHMM-MATCHES ! 0 _RSHMM-REGION !
    _RSHMM-MAP-U @ RSHMM-ENTRY-SIZE / 0 ?DO
        _RSHMM-MAP @ I RSHMM-ENTRY-SIZE * + _RSHMM-ENTRY !
        _RSHMM-R @ _RSHMM-ENTRY @ RSHMM.ROW @ >=
        _RSHMM-L @ _RSHMM-ENTRY @ RSHMM.COL @ >= AND
        _RSHMM-R @ _RSHMM-H @ +
            _RSHMM-ENTRY @ RSHMM.ROW @ _RSHMM-ENTRY @ RSHMM.HEIGHT @ + <= AND
        _RSHMM-L @ _RSHMM-W @ +
            _RSHMM-ENTRY @ RSHMM.COL @ _RSHMM-ENTRY @ RSHMM.WIDTH @ + <= AND IF
                1 _RSHMM-MATCHES +!
                _RSHMM-ENTRY @ RSHMM.CONTENT-REGION @ _RSHMM-REGION !
        THEN
    LOOP
    _RSHMM-MATCHES @ 1 <> IF 0 RSHMM-S-UNAVAILABLE EXIT THEN
    _RSHMM-REGION @ RSHMM-S-OK ;
CREATE _RSHMM-OWNED-END
_RSHMM-OWNED-END _RSHMM-OWNED-LIMIT !
