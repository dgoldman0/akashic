        RTAPT-OWNER-ST-FREE <> IF
            DUP _RTAPT-O.OWNER @ _RTAPT-OF-OWNER @ =
            OVER _RTAPT-O.GENERATION @ _RTAPT-OF-GEN @ = AND IF
                _RTAPT-OF-RESULT !
            ELSE DROP THEN
        ELSE DROP THEN
    LOOP
    _RTAPT-OF-RESULT @ ;

