    R@ _RTAPT-E.COMPLETION PT-COMPLETION-OWNER@ =
    R@ _RTAPT-E.COMPLETION PT-COMPLETION-REQUEST@ ROT = AND
    R@ _RTAPT-E.COMPLETION PT-COMPLETION-KIND@ ROT = AND
    R> DROP ;

