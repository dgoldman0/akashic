        _RTAPTSCBOP-PUBLISHER @ _RTAPTSCB.PRODUCER-BUDGET @
            _RTAPTSCBOP-BUDGET @ = AND
        _RTAPTSCBOP-PUBLISHER @ _RTAPTSCB.PRODUCER-STEP-XT @
