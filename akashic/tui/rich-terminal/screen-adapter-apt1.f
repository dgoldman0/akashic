\ =====================================================================
\  screen-adapter-apt1.f — RTAPT publisher for the neutral APT screen ABI
\ =====================================================================
\
\  This is the only bridge between the generic APTSCBP callback descriptor
\  and the generic RTAPT engine.  It owns no session, engine, or capacity;
\  every range is caller-provided and borrowed for the binding lifetime.
\
\  Prefix: RTAPTSCB- (public), _RTAPTSCB- (internal)

PROVIDED akashic-tui-rtaptscb1

REQUIRE ../screen-backend-apt1.f
REQUIRE apt1-engine.f

APTSCB-PUBLISHER-SIZE CONSTANT _RTAPTSCB-O-ENGINE
APTSCB-PUBLISHER-SIZE 8 + CONSTANT _RTAPTSCB-O-MAGIC
APTSCB-PUBLISHER-SIZE 16 + CONSTANT RTAPTSCB-SIZE

HEX 5254415054534342 CONSTANT _RTAPTSCB-MAGIC DECIMAL

: RTAPTSCB.ENGINE  ( publisher -- field ) _RTAPTSCB-O-ENGINE + ;
: _RTAPTSCB.MAGIC  ( publisher -- field ) _RTAPTSCB-O-MAGIC + ;

VARIABLE _RTAPTSCB-R
VARIABLE _RTAPTSCB-E
VARIABLE _RTAPTSCB-STATUS
VARIABLE _RTAPTSCB-PENDING
VARIABLE _RTAPTSCB-V0
VARIABLE _RTAPTSCB-V1
VARIABLE _RTAPTSCB-V2
VARIABLE _RTAPTSCB-V3
VARIABLE _RTAPTSCB-V4

: RTAPTSCB-VALID?  ( publisher -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP RTAPTSCB-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    _RTAPTSCB-R !
    _RTAPTSCB-R @ APTSCB-PUBLISHER-VALID? 0= IF 0 EXIT THEN
    _RTAPTSCB-R @ APTSCBP.CONTEXT @ _RTAPTSCB-R @ <> IF 0 EXIT THEN
    _RTAPTSCB-R @ _RTAPTSCB.MAGIC @ _RTAPTSCB-MAGIC <> IF 0 EXIT THEN
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ DUP _RTAPTSCB-E !
        RTAPT-VALID? 0= IF 0 EXIT THEN
    _RTAPTSCB-R @ APTSCBP.SESSION @ _RTAPTSCB-E @
        RTAPT-USES-SESSION? 0= IF 0 EXIT THEN
    _RTAPTSCB-R @ RTAPTSCB-SIZE _RTAPTSCB-E @
        RTAPT-STORAGE-DISJOINT? ;

: _RTAPTSCB-MAP-STATUS  ( rtapt-status -- scb-status )
    DUP RTAPT-S-OK = IF DROP SCB-S-OK EXIT THEN
    DUP RTAPT-S-WOULD-BLOCK = IF DROP SCB-S-WOULD-BLOCK EXIT THEN
    DUP RTAPT-S-BUSY = IF DROP SCB-S-WOULD-BLOCK EXIT THEN
    DUP RTAPT-S-SESSION-LOST = IF DROP SCB-S-SESSION-LOST EXIT THEN
    DROP SCB-S-INVALID ;

: _RTAPTSCB-BEGIN  ( cols rows spans cells cell-mode context -- status )
    _RTAPTSCB-R ! _RTAPTSCB-V4 ! _RTAPTSCB-V3 !
    _RTAPTSCB-V2 ! _RTAPTSCB-V1 ! _RTAPTSCB-V0 !
    _RTAPTSCB-R @ RTAPTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCB-V0 @ _RTAPTSCB-V1 @ _RTAPTSCB-V2 @
    _RTAPTSCB-V3 @ _RTAPTSCB-V4 @
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-CELL-BEGIN
    _RTAPTSCB-MAP-STATUS ;

: _RTAPTSCB-SPAN  ( row col count context -- status )
    _RTAPTSCB-R ! _RTAPTSCB-V2 ! _RTAPTSCB-V1 ! _RTAPTSCB-V0 !
    _RTAPTSCB-R @ RTAPTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCB-V0 @ _RTAPTSCB-V1 @ _RTAPTSCB-V2 @
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-CELL-SPAN-BEGIN
    _RTAPTSCB-MAP-STATUS ;

: _RTAPTSCB-CELL  ( codepoint fg bg attrs context -- status )
    _RTAPTSCB-R ! _RTAPTSCB-V3 ! _RTAPTSCB-V2 !
    _RTAPTSCB-V1 ! _RTAPTSCB-V0 !
    _RTAPTSCB-R @ RTAPTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCB-V0 @ _RTAPTSCB-V1 @ _RTAPTSCB-V2 @ _RTAPTSCB-V3 @
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-CELL-WRITE
    _RTAPTSCB-MAP-STATUS ;

: _RTAPTSCB-CURSOR  ( row col visible context -- status )
    _RTAPTSCB-R ! _RTAPTSCB-V2 ! _RTAPTSCB-V1 ! _RTAPTSCB-V0 !
    _RTAPTSCB-R @ RTAPTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCB-V0 @ _RTAPTSCB-V1 @ _RTAPTSCB-V2 @
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-CELL-CURSOR
    _RTAPTSCB-MAP-STATUS ;

: _RTAPTSCB-COMMIT  ( context -- status )
    DUP RTAPTSCB-VALID? 0= IF DROP SCB-S-INVALID EXIT THEN
    RTAPTSCB.ENGINE @ RTAPT-CELL-COMMIT _RTAPTSCB-MAP-STATUS ;

: _RTAPTSCB-ABORT  ( reason context -- status )
    DUP RTAPTSCB-VALID? 0= IF 2DROP SCB-S-INVALID EXIT THEN
    RTAPTSCB.ENGINE @ RTAPT-CELL-ABORT _RTAPTSCB-MAP-STATUS ;

\ Normal scheduling is deliberately distinct from close settlement.  During
\ discovery or a reset boundary there is no available publisher route, but an
\ already-active completion is still polled by RTAPT-STEP on every service.
: _RTAPTSCB-STEP  ( context -- status )
    DUP _RTAPTSCB-R ! RTAPTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-STEP _RTAPTSCB-STATUS !
    _RTAPTSCB-STATUS @ DUP RTAPT-S-WOULD-BLOCK =
    SWAP RTAPT-S-UNSUPPORTED = OR
    _RTAPTSCB-R @ APTSCBP.SESSION @ PT-RETAINED-AVAILABLE? 0= AND IF
        SCB-S-OK EXIT
    THEN
    _RTAPTSCB-STATUS @ _RTAPTSCB-MAP-STATUS ;

\ RTAPT-SETTLE never schedules queued lifecycle work.  Once no completion is
\ pending, every engine outcome is diagnostic state rather than PT wire
\ authority: preserve it in the engine, but never let it prevent PT-CLOSE.
: _RTAPTSCB-SETTLE  ( context -- status pending? )
    DUP _RTAPTSCB-R ! RTAPTSCB-VALID? 0= IF SCB-S-INVALID 0 EXIT THEN
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-SETTLE
    _RTAPTSCB-PENDING ! _RTAPTSCB-STATUS !
    _RTAPTSCB-PENDING @ IF SCB-S-WOULD-BLOCK -1 EXIT THEN
    SCB-S-OK 0 ;

VARIABLE _RTAPTSCBI-SESSION
VARIABLE _RTAPTSCBI-ENGINE
VARIABLE _RTAPTSCBI-PUBLISHER

\ RTAPTSCB-INIT ( session engine publisher -- status )
: RTAPTSCB-INIT  ( session engine publisher -- status )
    _RTAPTSCBI-PUBLISHER ! _RTAPTSCBI-ENGINE ! _RTAPTSCBI-SESSION !
    _RTAPTSCBI-ENGINE @ RTAPT-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCBI-SESSION @ _RTAPTSCBI-ENGINE @
        RTAPT-USES-SESSION? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCBI-PUBLISHER @ 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCBI-PUBLISHER @ 7 AND IF SCB-S-INVALID EXIT THEN
    _RTAPTSCBI-PUBLISHER @ RTAPTSCB-SIZE
        MSPAN-NONWRAPPING? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCBI-PUBLISHER @ RTAPTSCB-SIZE _RTAPTSCBI-ENGINE @
        RTAPT-STORAGE-DISJOINT? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCBI-PUBLISHER @ RTAPTSCB-SIZE 0 FILL
    _RTAPTSCBI-ENGINE @ _RTAPTSCBI-PUBLISHER @ RTAPTSCB.ENGINE !
    _RTAPTSCB-MAGIC _RTAPTSCBI-PUBLISHER @ _RTAPTSCB.MAGIC !
    _RTAPTSCBI-SESSION @ _RTAPTSCBI-PUBLISHER @
    ['] _RTAPTSCB-BEGIN ['] _RTAPTSCB-SPAN ['] _RTAPTSCB-CELL
    ['] _RTAPTSCB-CURSOR ['] _RTAPTSCB-COMMIT ['] _RTAPTSCB-ABORT
    ['] _RTAPTSCB-STEP ['] _RTAPTSCB-SETTLE
    _RTAPTSCBI-PUBLISHER @ APTSCB-PUBLISHER-INIT
    DUP SCB-S-OK <> IF EXIT THEN DROP
    _RTAPTSCBI-PUBLISHER @ RTAPTSCB-VALID? IF
        SCB-S-OK
    ELSE SCB-S-INVALID THEN ;

VARIABLE _RTAPTSCBA-PUBLISHER
VARIABLE _RTAPTSCBA-ADAPTER

\ Attach only after proving that the neutral adapter itself is disjoint from
\ every range borrowed by the concrete engine and exact PT session.
: RTAPTSCB-ATTACH  ( publisher adapter -- status )
    _RTAPTSCBA-ADAPTER ! _RTAPTSCBA-PUBLISHER !
    _RTAPTSCBA-PUBLISHER @ RTAPTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCBA-ADAPTER @ APTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCBA-PUBLISHER @ APTSCBP.SESSION @
    _RTAPTSCBA-ADAPTER @ APTSCB-SESSION@ <> IF SCB-S-INVALID EXIT THEN
    _RTAPTSCBA-PUBLISHER @ RTAPTSCB-SIZE
    _RTAPTSCBA-ADAPTER @ APTSCB-SIZE MSPAN-OVERLAP? IF
        SCB-S-INVALID EXIT
    THEN
    _RTAPTSCBA-ADAPTER @ APTSCB-SIZE
    _RTAPTSCBA-PUBLISHER @ RTAPTSCB.ENGINE @
        RTAPT-STORAGE-DISJOINT? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCBA-PUBLISHER @ _RTAPTSCBA-ADAPTER @ APTSCB-PUBLISHER! ;
