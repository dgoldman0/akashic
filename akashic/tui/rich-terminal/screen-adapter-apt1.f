    _RTAPTSCB-PHASE-REVEAL-AWAITING U> 0= ;

: _RTAPTSCB-SPAN?  ( a u -- flag )
    OVER 0<> OVER 0> AND 0= IF 2DROP 0 EXIT THEN
    OVER 7 AND IF 2DROP 0 EXIT THEN
    MSPAN-NONWRAPPING? ;

: _RTAPTSCB-DIMENSION?  ( value -- flag )
    DUP 0> SWAP 0xFFFFFFFF U> 0= AND ;

: _RTAPTSCB-SURFACE-VALID?  ( publisher -- flag )
    DUP _RTAPTSCB.SURFACE-GENERATION @ 0= IF
        DUP _RTAPTSCB.SURFACE-COLS @ 0=
        OVER _RTAPTSCB.SURFACE-ROWS @ 0= AND
        SWAP DROP EXIT
    THEN
    DUP _RTAPTSCB.SURFACE-COLS @ _RTAPTSCB-DIMENSION?
    OVER _RTAPTSCB.SURFACE-ROWS @ _RTAPTSCB-DIMENSION? AND
    SWAP DROP ;

\ A latched fault is diagnostic scheduler state, not structural corruption.
\ It revokes both scheduling hints while leaving the publisher valid for
\ close settlement.  Only whole-record reconstruction or retirement clears it.
: _RTAPTSCB-FAULT-VALID?  ( publisher -- flag )
    DUP _RTAPTSCB.FAULT-STATUS @ DUP _RTAPTSCB-FAULT-STATUS? 0= IF
        2DROP 0 EXIT
    THEN
    0= IF DROP -1 EXIT THEN
    DUP _RTAPTSCB.MORE-WORK @ 0=
    SWAP _RTAPTSCB.OUTPUT-NEEDED @ 0= AND ;

: _RTAPTSCB-ADAPTER-VALID?  ( publisher -- flag )
    DUP _RTAPTSCB-VALID-PUBLISHER !
    _RTAPTSCB.ADAPTER @ DUP _RTAPTSCB-VALID-ADAPTER !
    0= IF -1 EXIT THEN
    _RTAPTSCB-VALID-ADAPTER @ APTSCB-VALID? 0= IF 0 EXIT THEN
    _RTAPTSCB-VALID-ADAPTER @ APTSCB-SESSION@
        _RTAPTSCB-VALID-PUBLISHER @ APTSCBP.SESSION @ <> IF 0 EXIT THEN
    _RTAPTSCB-VALID-ADAPTER @ APTSCB.PUBLISHER @
        _RTAPTSCB-VALID-PUBLISHER @ <> IF 0 EXIT THEN
    _RTAPTSCB-VALID-PUBLISHER @ RTAPTSCB-SIZE
        _RTAPTSCB-VALID-ADAPTER @ APTSCB-SIZE MSPAN-OVERLAP? IF
        0 EXIT
    THEN
    _RTAPTSCB-VALID-ADAPTER @ APTSCB-SIZE
        _RTAPTSCB-VALID-PUBLISHER @ RTAPTSCB.ENGINE @
        RTAPT-STORAGE-DISJOINT? ;

: _RTAPTSCB-PRODUCER-VALID?  ( publisher -- flag )
    DUP _RTAPTSCB-VALID-PUBLISHER !
    DUP _RTAPTSCB.PRODUCER-CONTEXT @ _RTAPTSCB-VALID-CONTEXT !
    _RTAPTSCB.PRODUCER-U @ _RTAPTSCB-VALID-CONTEXT-U !
    _RTAPTSCB-VALID-CONTEXT @ 0= IF
        _RTAPTSCB-VALID-CONTEXT-U @ 0=
        _RTAPTSCB-VALID-PUBLISHER @ _RTAPTSCB.PRODUCER-BUDGET @ 0= AND
        _RTAPTSCB-VALID-PUBLISHER @ _RTAPTSCB.PRODUCER-STEP-XT @ 0= AND
        _RTAPTSCB-VALID-PUBLISHER @
            _RTAPTSCB.PRODUCER-PREPARE-XT @ 0= AND
        _RTAPTSCB-VALID-PUBLISHER @ _RTAPTSCB.MORE-WORK @ 0= AND
        _RTAPTSCB-VALID-PUBLISHER @ _RTAPTSCB.OUTPUT-NEEDED @ 0= AND
        _RTAPTSCB-VALID-PUBLISHER @ _RTAPTSCB.PHASE @
            _RTAPTSCB-PHASE-CELL = AND
        EXIT
    THEN
    _RTAPTSCB-VALID-CONTEXT @ _RTAPTSCB-VALID-CONTEXT-U @
        _RTAPTSCB-SPAN? 0= IF 0 EXIT THEN
    _RTAPTSCB-VALID-PUBLISHER @ _RTAPTSCB.PRODUCER-BUDGET @
        0> 0= IF 0 EXIT THEN
    _RTAPTSCB-VALID-PUBLISHER @ _RTAPTSCB.PRODUCER-STEP-XT @ 0=
    _RTAPTSCB-VALID-PUBLISHER @
        _RTAPTSCB.PRODUCER-PREPARE-XT @ 0= OR IF 0 EXIT THEN
    _RTAPTSCB-VALID-PUBLISHER @ _RTAPTSCB.MORE-WORK @
        _RTAPTSCB-BOOL? 0=
    _RTAPTSCB-VALID-PUBLISHER @ _RTAPTSCB.OUTPUT-NEEDED @
        _RTAPTSCB-BOOL? 0= OR IF 0 EXIT THEN
    _RTAPTSCB-VALID-CONTEXT @ _RTAPTSCB-VALID-CONTEXT-U @
        _RTAPTSCB-VALID-PUBLISHER @ RTAPTSCB-SIZE
        MSPAN-OVERLAP? IF 0 EXIT THEN
    _RTAPTSCB-VALID-CONTEXT @ _RTAPTSCB-VALID-CONTEXT-U @
        _RTAPTSCB-VALID-PUBLISHER @ RTAPTSCB.ENGINE @
        RTAPT-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    _RTAPTSCB-VALID-PUBLISHER @ _RTAPTSCB.ADAPTER @ ?DUP IF
        _RTAPTSCB-VALID-CONTEXT @ _RTAPTSCB-VALID-CONTEXT-U @ ROT
        APTSCB-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    THEN
    -1 ;

: RTAPTSCB-VALID?  ( publisher -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP RTAPTSCB-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    _RTAPTSCB-R !
    _RTAPTSCB-R @ APTSCB-PUBLISHER-VALID? 0= IF 0 EXIT THEN
    _RTAPTSCB-R @ APTSCBP.CONTEXT @ _RTAPTSCB-R @ <> IF 0 EXIT THEN
    _RTAPTSCB-R @ _RTAPTSCB.MAGIC @ _RTAPTSCB-MAGIC <> IF 0 EXIT THEN
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ DUP _RTAPTSCB-E !
        RTAPT-VALID? 0= IF 0 EXIT THEN
    _RTAPTSCB-R @ APTSCBP.SESSION @ _RTAPTSCB-E @
        RTAPT-USES-SESSION? 0= IF 0 EXIT THEN
    _RTAPTSCB-R @ RTAPTSCB-SIZE _RTAPTSCB-E @
        RTAPT-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    _RTAPTSCB-R @ _RTAPTSCB-SURFACE-VALID? 0= IF 0 EXIT THEN
    _RTAPTSCB-R @ _RTAPTSCB.PHASE @ _RTAPTSCB-PHASE? 0= IF 0 EXIT THEN
    _RTAPTSCB-R @ _RTAPTSCB-FAULT-VALID? 0= IF 0 EXIT THEN
    _RTAPTSCB-R @ _RTAPTSCB-ADAPTER-VALID? 0= IF 0 EXIT THEN
    _RTAPTSCB-R @ _RTAPTSCB-PRODUCER-VALID? ;

: _RTAPTSCB-MAP-STATUS  ( rtapt-status -- scb-status )
    DUP RTAPT-S-OK = IF DROP SCB-S-OK EXIT THEN
    DUP RTAPT-S-WOULD-BLOCK = IF DROP SCB-S-WOULD-BLOCK EXIT THEN
    DUP RTAPT-S-BUSY = IF DROP SCB-S-WOULD-BLOCK EXIT THEN
    DUP RTAPT-S-SESSION-LOST = IF DROP SCB-S-SESSION-LOST EXIT THEN
    DROP SCB-S-INVALID ;

: _RTAPTSCB-PRODUCER-BOUND?  ( publisher -- flag )
    _RTAPTSCB.PRODUCER-CONTEXT @ 0<> ;

\ Preserve the first fatal producer/engine scheduler outcome until the
\ publisher record is reconstructed or retired.  Keeping the record valid is
\ essential: close settlement must still be able to poll admitted engine work.
: _RTAPTSCB-FAULT-LATCH  ( status publisher -- status )
    _RTAPTSCB-R ! _RTAPTSCB-STATUS !
    _RTAPTSCB-STATUS @ _RTAPTSCB-FATAL-STATUS? 0= IF
        SCB-S-INVALID _RTAPTSCB-STATUS !
    THEN
    0 _RTAPTSCB-R @ _RTAPTSCB.MORE-WORK !
    0 _RTAPTSCB-R @ _RTAPTSCB.OUTPUT-NEEDED !
    _RTAPTSCB-R @ _RTAPTSCB.FAULT-STATUS @ ?DUP IF EXIT THEN
    _RTAPTSCB-STATUS @ DUP
        _RTAPTSCB-R @ _RTAPTSCB.FAULT-STATUS ! ;

: _RTAPTSCB-EXACT-SCREEN?  ( publisher -- flag )
    DUP _RTAPTSCB-VALID-PUBLISHER !
    _RTAPTSCB.ADAPTER @ DUP _RTAPTSCB-VALID-ADAPTER !
    0= IF 0 EXIT THEN
    _RTAPTSCB-VALID-ADAPTER @ APTSCB-VALID? 0= IF 0 EXIT THEN
    _RTAPTSCB-VALID-ADAPTER @ APTSCB.PUBLISHER @
        _RTAPTSCB-VALID-PUBLISHER @ =
    SCR-BACKEND@ _RTAPTSCB-VALID-ADAPTER @ = AND ;

VARIABLE _RTAPTSCB-SURFACE-PUBLISHER
