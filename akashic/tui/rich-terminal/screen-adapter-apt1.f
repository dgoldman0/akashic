VARIABLE _RTAPTSCB-PRODUCER-STATUS
VARIABLE _RTAPTSCB-PRODUCER-MORE
VARIABLE _RTAPTSCB-PRODUCER-OUTPUT

: _RTAPTSCB-ENGINE-STEP  ( publisher -- status )
    _RTAPTSCB-R !
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-STEP _RTAPTSCB-STATUS !
    \ A rejected owner/output completion has already been reconciled and
    \ released the engine slot.  Let the producer observe that neutral state
    \ and decide whether to retire, coalesce, or retry it.
    _RTAPTSCB-STATUS @ RTAPT-S-REJECTED = IF SCB-S-OK EXIT THEN
    _RTAPTSCB-STATUS @ DUP RTAPT-S-WOULD-BLOCK =
    SWAP RTAPT-S-UNSUPPORTED = OR
    _RTAPTSCB-R @ APTSCBP.SESSION @ PT-RETAINED-AVAILABLE? 0= AND IF
        SCB-S-OK EXIT
    THEN
    _RTAPTSCB-STATUS @ _RTAPTSCB-MAP-STATUS ;

: _RTAPTSCB-PRODUCER-STEP  ( publisher -- status )
    DUP _RTAPTSCB-R !
    _RTAPTSCB-PRODUCER-BOUND? 0= IF SCB-S-OK EXIT THEN
    _RTAPTSCB-R @ _RTAPTSCB.SURFACE-GENERATION @ 0= IF
        SCB-S-OK EXIT
    THEN
    _RTAPTSCB-R @ _RTAPTSCB-EXACT-SCREEN? 0= IF
        SCB-S-INVALID EXIT
    THEN
    _RTAPTSCB-R @ _RTAPTSCB.SURFACE-COLS @
    _RTAPTSCB-R @ _RTAPTSCB.SURFACE-ROWS @
    _RTAPTSCB-R @ _RTAPTSCB.SURFACE-GENERATION @
    _RTAPTSCB-R @ _RTAPTSCB.PRODUCER-BUDGET @
    _RTAPTSCB-R @ _RTAPTSCB.PRODUCER-CONTEXT @
    _RTAPTSCB-R @ >R
    _RTAPTSCB-R @ _RTAPTSCB.PRODUCER-STEP-XT @ EXECUTE
    R> _RTAPTSCB-R !
    _RTAPTSCB-PRODUCER-OUTPUT !
    _RTAPTSCB-PRODUCER-MORE !
    _RTAPTSCB-PRODUCER-STATUS !
    _RTAPTSCB-PRODUCER-STATUS @ _RTAPTSCB-SCB-STATUS? 0= IF
        SCB-S-INVALID EXIT
    THEN
    _RTAPTSCB-PRODUCER-MORE @ _RTAPTSCB-BOOL? 0=
    _RTAPTSCB-PRODUCER-OUTPUT @ _RTAPTSCB-BOOL? 0= OR IF
        SCB-S-INVALID EXIT
    THEN
    \ A well-formed fatal result revokes all producer scheduling authority.
    \ OK and WOULD-BLOCK may both carry truthful level-triggered observations.
    _RTAPTSCB-PRODUCER-STATUS @ DUP SCB-S-SESSION-LOST =
    SWAP SCB-S-INVALID = OR IF
        0 _RTAPTSCB-R @ _RTAPTSCB.MORE-WORK !
        0 _RTAPTSCB-R @ _RTAPTSCB.OUTPUT-NEEDED !
        _RTAPTSCB-PRODUCER-STATUS @ EXIT
    THEN
    _RTAPTSCB-PRODUCER-MORE @
        _RTAPTSCB-R @ _RTAPTSCB.MORE-WORK !
    \ These are latest level-triggered observations, not sticky ownership.
    \ Once OUTPUT-NEEDED is scheduled, SCR-REQUEST-FLUSH persists through
    \ later false observations and every refusal until an accepted COMMIT.
    _RTAPTSCB-PRODUCER-OUTPUT @
        _RTAPTSCB-R @ _RTAPTSCB.OUTPUT-NEEDED !
    _RTAPTSCB-PRODUCER-STATUS @ ;

\ RTAPTSCB owns the producer-to-screen scheduling edge because only this
\ layer can re-prove that its attached adapter is the exact current backend.
\ MORE-WORK never enters this path and remains an outer scheduler hint.
: _RTAPTSCB-SCHEDULE-OUTPUT  ( publisher -- )
    DUP _RTAPTSCB-EXACT-SCREEN? 0= IF DROP EXIT THEN
    _RTAPTSCB.OUTPUT-NEEDED @ IF SCR-REQUEST-FLUSH THEN ;

\ Normal scheduling is deliberately distinct from close settlement.  During
\ discovery or a reset boundary there is no available publisher route, but an
\ already-active completion is still polled by RTAPT-STEP on every service.
\ A bound output producer receives one bounded call only after that engine
\ step.  A valid nonfatal OUTPUT-NEEDED observation schedules one neutral,
\ persistent screen request after exact-backend proof.  This bridge neither
\ starts another service loop nor forces or retransmits a CELL snapshot.
: _RTAPTSCB-STEP  ( context -- status )
    DUP _RTAPTSCB-R ! RTAPTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCB-R @ _RTAPTSCB-ENGINE-STEP
    DUP SCB-S-OK <> IF EXIT THEN DROP
    _RTAPTSCB-R @ _RTAPTSCB-PRODUCER-STEP DUP _RTAPTSCB-STATUS !
    DUP SCB-S-OK = SWAP SCB-S-WOULD-BLOCK = OR IF
        _RTAPTSCB-R @ _RTAPTSCB-SCHEDULE-OUTPUT
    THEN
    _RTAPTSCB-STATUS @ ;

\ RTAPT-SETTLE never schedules queued lifecycle work.  Once no completion is
\ pending, every engine outcome is diagnostic state rather than PT wire
\ authority: preserve it in the engine, but never let it prevent PT-CLOSE.
: _RTAPTSCB-SETTLE  ( context -- status pending? )
    DUP _RTAPTSCB-R ! RTAPTSCB-VALID? 0= IF SCB-S-INVALID 0 EXIT THEN
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-SETTLE
    _RTAPTSCB-PENDING ! _RTAPTSCB-STATUS !
    _RTAPTSCB-PENDING @ IF SCB-S-WOULD-BLOCK -1 EXIT THEN
    SCB-S-OK 0 ;

\ These queries expose only validated scheduler observations.  In particular,
\ OUTPUT-NEEDED? is false unless this publisher's immutable attached APTSCB is
\ also the exact current screen backend.  Normal STEP consumes that observation
\ into SCR-REQUEST-FLUSH; it never turns the flag into a CELL snapshot.
: RTAPTSCB-MORE-WORK?  ( publisher -- flag )
    DUP RTAPTSCB-VALID? 0= IF DROP 0 EXIT THEN
    _RTAPTSCB.MORE-WORK @ ;

: RTAPTSCB-OUTPUT-NEEDED?  ( publisher -- flag )
    DUP RTAPTSCB-VALID? 0= IF DROP 0 EXIT THEN
    DUP _RTAPTSCB-EXACT-SCREEN? 0= IF DROP 0 EXIT THEN
    _RTAPTSCB.OUTPUT-NEEDED @ ;

