\ RTAPTSCB-OUTPUT-PRODUCER!
\   ( context-a context-u budget step-xt prepare-xt publisher -- status )
\ Install one optional, engine-neutral source of bounded output work while the
\ surface is still unobserved.  The producer span is borrowed until publisher
\ retirement.  Exact repetition is idempotent; replacement or unbinding is
\ forbidden because callbacks may retain source-free lifecycle authority.
