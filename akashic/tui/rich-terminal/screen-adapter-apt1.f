VARIABLE _RTAPTSCB-SURFACE-ROWS
VARIABLE _RTAPTSCB-SURFACE-NEXT

\ Publish a surface generation from the exact dimensions offered by one CELL
\ BEGIN.  A refused later PREPARE or engine BEGIN does not make those observed
\ dimensions stale.  Generation exhaustion refuses before changing the tuple.
: _RTAPTSCB-SURFACE-OBSERVE  ( cols rows publisher -- status )
    _RTAPTSCB-SURFACE-PUBLISHER !
    _RTAPTSCB-SURFACE-ROWS ! _RTAPTSCB-SURFACE-COLS !
    _RTAPTSCB-SURFACE-COLS @ _RTAPTSCB-DIMENSION? 0= IF
        SCB-S-INVALID EXIT
    THEN
    _RTAPTSCB-SURFACE-ROWS @ _RTAPTSCB-DIMENSION? 0= IF
        SCB-S-INVALID EXIT
    THEN
    _RTAPTSCB-SURFACE-PUBLISHER @
        _RTAPTSCB.SURFACE-GENERATION @ 0= IF
        _RTAPTSCB-SURFACE-COLS @ _RTAPTSCB-SURFACE-PUBLISHER @
            _RTAPTSCB.SURFACE-COLS !
        _RTAPTSCB-SURFACE-ROWS @ _RTAPTSCB-SURFACE-PUBLISHER @
            _RTAPTSCB.SURFACE-ROWS !
        1 _RTAPTSCB-SURFACE-PUBLISHER @
            _RTAPTSCB.SURFACE-GENERATION !
        SCB-S-OK EXIT
    THEN
    _RTAPTSCB-SURFACE-COLS @ _RTAPTSCB-SURFACE-PUBLISHER @
        _RTAPTSCB.SURFACE-COLS @ =
    _RTAPTSCB-SURFACE-ROWS @ _RTAPTSCB-SURFACE-PUBLISHER @
        _RTAPTSCB.SURFACE-ROWS @ = AND IF SCB-S-OK EXIT THEN
    _RTAPTSCB-SURFACE-PUBLISHER @ _RTAPTSCB.SURFACE-GENERATION @
        1+ DUP 0= IF DROP SCB-S-INVALID EXIT THEN
    _RTAPTSCB-SURFACE-NEXT !
    _RTAPTSCB-SURFACE-COLS @ _RTAPTSCB-SURFACE-PUBLISHER @
        _RTAPTSCB.SURFACE-COLS !
    _RTAPTSCB-SURFACE-ROWS @ _RTAPTSCB-SURFACE-PUBLISHER @
        _RTAPTSCB.SURFACE-ROWS !
    _RTAPTSCB-SURFACE-NEXT @ _RTAPTSCB-SURFACE-PUBLISHER @
        _RTAPTSCB.SURFACE-GENERATION !
    SCB-S-OK ;

: _RTAPTSCB-PRODUCER-PREPARE  ( publisher -- status )
    DUP _RTAPTSCB-R !
    _RTAPTSCB-PRODUCER-BOUND? 0= IF SCB-S-OK EXIT THEN
    _RTAPTSCB-R @ _RTAPTSCB-EXACT-SCREEN? 0= IF
        SCB-S-INVALID EXIT
    THEN
    _RTAPTSCB-R @ _RTAPTSCB.SURFACE-COLS @
    _RTAPTSCB-R @ _RTAPTSCB.SURFACE-ROWS @
    _RTAPTSCB-R @ _RTAPTSCB.SURFACE-GENERATION @
    _RTAPTSCB-R @ _RTAPTSCB.PRODUCER-CONTEXT @
    _RTAPTSCB-R @ >R
    _RTAPTSCB-R @ _RTAPTSCB.PRODUCER-PREPARE-XT @ EXECUTE
    R> _RTAPTSCB-R !
    DUP _RTAPTSCB-SCB-STATUS? 0= IF DROP SCB-S-INVALID THEN
    DUP _RTAPTSCB-FATAL-STATUS? IF
        _RTAPTSCB-R @ _RTAPTSCB-FAULT-LATCH
    THEN ;

: _RTAPTSCB-SEALED-READ  ( -- rtapt-status )
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-SEALED-PRESENTATION@
    _RTAPTSCB-SEALED-STATUS !
    _RTAPTSCB-SEALED-DISPOSITION ! _RTAPTSCB-SEALED-MODE !
    _RTAPTSCB-SEALED-STATUS @ ;

: _RTAPTSCB-HIDDEN-PRESENTATION?  ( -- flag )
    _RTAPTSCB-SEALED-MODE @ DUP RTAPT-RICH-REPLACE-START =
    SWAP RTAPT-RICH-REPLACE-CONTINUE = OR
    _RTAPTSCB-SEALED-DISPOSITION @ RTAPT-COMMIT = AND ;

: _RTAPTSCB-REVEAL-PRESENTATION?  ( -- flag )
    _RTAPTSCB-SEALED-MODE @ RTAPT-RICH-REPLACE-CONTINUE =
    _RTAPTSCB-SEALED-DISPOSITION @
        RTAPT-COMMIT-AND-REVEAL = AND ;

: _RTAPTSCB-DELTA-PRESENTATION?  ( -- flag )
    _RTAPTSCB-SEALED-MODE @ RTAPT-RICH-DELTA =
    _RTAPTSCB-SEALED-DISPOSITION @ RTAPT-COMMIT = AND ;

: _RTAPTSCB-INVALID-FAULT  ( -- status )
    SCB-S-INVALID _RTAPTSCB-R @ _RTAPTSCB-FAULT-LATCH ;

\ Admit a sealed hidden replacement as a retained-only transaction.  The
\ surrounding authoritative screen BEGIN is deliberately refused, so SCR
\ keeps the exact CELL plane dirty until a later reveal can carry it.
: _RTAPTSCB-PUBLISH-HIDDEN  ( -- status )
    _RTAPTSCB-BEGIN-COLS @ _RTAPTSCB-BEGIN-ROWS @
    0 0 PT-CELL-NONE
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-CELL-BEGIN
    _RTAPTSCB-MAP-STATUS DUP SCB-S-OK <> IF EXIT THEN DROP
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-CELL-COMMIT
    _RTAPTSCB-MAP-STATUS DUP SCB-S-OK = IF
        _RTAPTSCB-PHASE-HIDDEN _RTAPTSCB-R @ _RTAPTSCB.PHASE !
        0 _RTAPTSCB-R @ _RTAPTSCB.OUTPUT-NEEDED !
        DROP SCB-S-WOULD-BLOCK
    THEN ;

\ A neutral retained request does not itself authorize CELL reuse.  Promote
\ the same persistent request to a complete snapshot, then let the next
\ authoritative BEGIN run PREPARE against those exact dimensions.
: _RTAPTSCB-PROMOTE-NONE  ( -- status )
    _RTAPTSCB-R @ _RTAPTSCB-PRODUCER-BOUND? 0= IF
        SCB-S-WOULD-BLOCK EXIT
    THEN
    _RTAPTSCB-R @ _RTAPTSCB-EXACT-SCREEN? 0= IF
        _RTAPTSCB-INVALID-FAULT EXIT
    THEN
    SCR-FORCE
    SCB-S-WOULD-BLOCK ;

\ PREPARE runs on every authoritative CELL offer.  A hidden COMMIT is sent
\ without CELL and refuses the outer offer; only a matching CONTINUE+REVEAL
\ may proceed into the ordinary CELL callbacks.
: _RTAPTSCB-AUTHORITATIVE-PREPARE  ( -- status )
    _RTAPTSCB-R @ _RTAPTSCB-PRODUCER-PREPARE
    DUP SCB-S-OK <> IF EXIT THEN DROP
    _RTAPTSCB-SEALED-READ DUP RTAPT-S-OK = IF
        DROP
        _RTAPTSCB-R @ _RTAPTSCB.PHASE @
            _RTAPTSCB-PHASE-CELL = IF
            _RTAPTSCB-DELTA-PRESENTATION? IF SCB-S-OK EXIT THEN
            _RTAPTSCB-HIDDEN-PRESENTATION? 0= IF
                _RTAPTSCB-INVALID-FAULT EXIT
            THEN
            _RTAPTSCB-PUBLISH-HIDDEN EXIT
        THEN
        _RTAPTSCB-R @ _RTAPTSCB.PHASE @
            _RTAPTSCB-PHASE-HIDDEN = IF
            _RTAPTSCB-REVEAL-PRESENTATION? IF SCB-S-OK EXIT THEN
            _RTAPTSCB-HIDDEN-PRESENTATION? IF
                _RTAPTSCB-PUBLISH-HIDDEN EXIT
            THEN
            _RTAPTSCB-INVALID-FAULT EXIT
        THEN
        _RTAPTSCB-INVALID-FAULT EXIT
    THEN
    RTAPT-S-BUSY = IF
        _RTAPTSCB-R @ _RTAPTSCB.PHASE @
            _RTAPTSCB-PHASE-CELL = IF SCB-S-OK
        ELSE SCB-S-WOULD-BLOCK THEN
        EXIT
    THEN
    _RTAPTSCB-INVALID-FAULT ;

: _RTAPTSCB-BEGIN  ( cols rows spans cells cell-mode context -- status )
    _RTAPTSCB-R ! _RTAPTSCB-BEGIN-CELL-MODE !
    _RTAPTSCB-BEGIN-CELLS ! _RTAPTSCB-BEGIN-SPANS !
    _RTAPTSCB-BEGIN-ROWS ! _RTAPTSCB-BEGIN-COLS !
    _RTAPTSCB-R @ RTAPTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    \ Every CELL BEGIN is authoritative surface evidence, independent of
    \ whether an optional neutral output producer is installed.
    _RTAPTSCB-BEGIN-COLS @ _RTAPTSCB-BEGIN-ROWS @ _RTAPTSCB-R @
        _RTAPTSCB-SURFACE-OBSERVE DUP SCB-S-OK <> IF
        EXIT
    THEN DROP
    _RTAPTSCB-R @ _RTAPTSCB.FAULT-STATUS @ ?DUP IF EXIT THEN
    _RTAPTSCB-BEGIN-CELL-MODE @ PT-CELL-NONE = IF
        _RTAPTSCB-PROMOTE-NONE EXIT
    THEN
    _RTAPTSCB-R @ _RTAPTSCB-PRODUCER-BOUND? IF
        _RTAPTSCB-AUTHORITATIVE-PREPARE
        DUP SCB-S-OK <> IF EXIT THEN DROP
    THEN
    _RTAPTSCB-BEGIN-COLS @ _RTAPTSCB-BEGIN-ROWS @
    _RTAPTSCB-BEGIN-SPANS @ _RTAPTSCB-BEGIN-CELLS @
    _RTAPTSCB-BEGIN-CELL-MODE @
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-CELL-BEGIN
    _RTAPTSCB-MAP-STATUS DUP SCB-S-OK = IF
        \ BEGIN transfers retry authority to the persistent screen request.
        \ It remains set until SCR-FLUSH? accepts COMMIT, while an abort
        \ rewinds a sealed retained candidate.  The producer latch is no
        \ longer an additional owner of this admitted observation.
        0 _RTAPTSCB-R @ _RTAPTSCB.OUTPUT-NEEDED !
    THEN ;

: _RTAPTSCB-SPAN  ( row col count context -- status )
    _RTAPTSCB-R ! _RTAPTSCB-SPAN-COUNT !
    _RTAPTSCB-SPAN-COL ! _RTAPTSCB-SPAN-ROW !
    _RTAPTSCB-R @ RTAPTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCB-SPAN-ROW @ _RTAPTSCB-SPAN-COL @ _RTAPTSCB-SPAN-COUNT @
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-CELL-SPAN-BEGIN
    _RTAPTSCB-MAP-STATUS ;

: _RTAPTSCB-CELL  ( codepoint fg bg attrs context -- status )
    _RTAPTSCB-R ! _RTAPTSCB-CELL-ATTRS ! _RTAPTSCB-CELL-BG !
    _RTAPTSCB-CELL-FG ! _RTAPTSCB-CELL-CODEPOINT !
    _RTAPTSCB-R @ RTAPTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCB-CELL-CODEPOINT @ _RTAPTSCB-CELL-FG @
    _RTAPTSCB-CELL-BG @ _RTAPTSCB-CELL-ATTRS @
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-CELL-WRITE
    _RTAPTSCB-MAP-STATUS ;

: _RTAPTSCB-CURSOR  ( row col visible context -- status )
    _RTAPTSCB-R ! _RTAPTSCB-CURSOR-VISIBLE !
    _RTAPTSCB-CURSOR-COL ! _RTAPTSCB-CURSOR-ROW !
    _RTAPTSCB-R @ RTAPTSCB-VALID? 0= IF SCB-S-INVALID EXIT THEN
    _RTAPTSCB-CURSOR-ROW @ _RTAPTSCB-CURSOR-COL @
    _RTAPTSCB-CURSOR-VISIBLE @
    _RTAPTSCB-R @ RTAPTSCB.ENGINE @ RTAPT-CELL-CURSOR
    _RTAPTSCB-MAP-STATUS ;

: _RTAPTSCB-COMMIT  ( context -- status )
