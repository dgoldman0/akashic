        _RTAPTSCBOP-PUBLISHER @ _RTAPTSCB.PRODUCER-CONTEXT @
            _RTAPTSCBOP-CONTEXT @ =
        _RTAPTSCBOP-PUBLISHER @ _RTAPTSCB.PRODUCER-U @
