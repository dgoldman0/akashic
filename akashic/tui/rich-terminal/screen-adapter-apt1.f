: _RTAPTSCB-BOOL?  ( value -- flag )
    DUP 0= SWAP -1 = OR ;

: _RTAPTSCB-SCB-STATUS?  ( status -- flag )
    SCB-S-INVALID U> 0= ;

: _RTAPTSCB-FATAL-STATUS?  ( status -- flag )
    DUP SCB-S-SESSION-LOST = SWAP SCB-S-INVALID = OR ;

: _RTAPTSCB-FAULT-STATUS?  ( status -- flag )
    DUP 0= SWAP _RTAPTSCB-FATAL-STATUS? OR ;

