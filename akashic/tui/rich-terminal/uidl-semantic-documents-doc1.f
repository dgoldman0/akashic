\ =====================================================================
\  uidl-semantic-documents-doc1.f -- frozen native document to DOC1
\ =====================================================================
\
\  Translates one already-deep-validated, immutable USCOL document entry
\  and its correlated summary into canonical little-endian DOC1
\  (SEMANTIC-CONTENT-1).  Like the ITM1 packer, this module is not another
\  validation authority: it performs only constant-time correlation, span,
\  capacity, and revision checks before one bounded walk over the blocks,
\  containers, text, and runs.  It does not decode UTF-8, sort keys, or
\  repeat the structure proofs.
\
\  The destination tag remains zero until the complete cursor accounting
\  succeeds, so an impossible post-freeze mismatch cannot leave a
\  valid-looking partial value.
\
\  Public API:
\    USDOC-PACK
\      ( entry entry-bytes summary source-revision destination capacity
\        -- bytes status )
\
\  Prefix: USDOC- (public), _USDOC- (private)

PROVIDED akashic-tui-rterm-usdoc

REQUIRE ../semantic-collections.f

0x31434F44 CONSTANT USDOC-TAG
1 CONSTANT USDOC-VERSION
32 CONSTANT USDOC-HEADER-SIZE
32 CONSTANT USDOC-BLOCK-HEADER-SIZE
8 CONSTANT USDOC-CONTAINER-SIZE
12 CONSTANT USDOC-RUN-SIZE

VARIABLE _USDOC-ENTRY
VARIABLE _USDOC-ENTRY-U
VARIABLE _USDOC-SUMMARY
VARIABLE _USDOC-REVISION
VARIABLE _USDOC-DST
VARIABLE _USDOC-CAP

VARIABLE _USDOC-BLOCKS
VARIABLE _USDOC-UTF8-U
VARIABLE _USDOC-RUN-COUNT
VARIABLE _USDOC-CONTAINER-COUNT
VARIABLE _USDOC-OUT-U

VARIABLE _USDOC-NATIVE
VARIABLE _USDOC-NATIVE-U
VARIABLE _USDOC-WIRE
VARIABLE _USDOC-WIRE-U
VARIABLE _USDOC-TEXT-U
VARIABLE _USDOC-RUNS
VARIABLE _USDOC-CONTAINERS
VARIABLE _USDOC-NATIVE-STEP
VARIABLE _USDOC-WIRE-STEP
VARIABLE _USDOC-COPIED-UTF8
VARIABLE _USDOC-COPIED-RUNS
VARIABLE _USDOC-COPIED-CONTAINERS
VARIABLE _USDOC-A
VARIABLE _USDOC-W

: _USDOC-ALIGNED-SPAN?  ( address bytes -- flag )
    OVER 0<> OVER 0> AND 0= IF 2DROP 0 EXIT THEN
    OVER 7 AND IF 2DROP 0 EXIT THEN
    MSPAN-NONWRAPPING? ;

: _USDOC-DISJOINT?  ( a u b v -- flag )  MSPAN-OVERLAP? 0= ;

: _USDOC-U32?  ( value -- flag )
    DUP 0< IF DROP 0 EXIT THEN 0x100000000 U< ;

: _USDOC-UADD?  ( a b -- sum flag )  OVER + DUP ROT U< 0= ;

: _USDOC-LE16!  ( value address -- )  2DUP C! SWAP 8 RSHIFT SWAP 1+ C! ;
: _USDOC-LE32!  ( value address -- )
    2DUP _USDOC-LE16! SWAP 16 RSHIFT SWAP 2 + _USDOC-LE16! ;
: _USDOC-LE64!  ( value address -- )
    2DUP _USDOC-LE32! SWAP 32 RSHIFT SWAP 4 + _USDOC-LE32! ;

: _USDOC-ARGS!  ( entry entry-u summary revision destination capacity -- )
    _USDOC-CAP ! _USDOC-DST ! _USDOC-REVISION !
    _USDOC-SUMMARY ! _USDOC-ENTRY-U ! _USDOC-ENTRY ! ;

\ Deliberately O(1): FAMILY, KEY, and ENTRY-BYTES bind the summary to the
\ exact frozen native slice whose deep validation produced it.
: _USDOC-CORRELATE  ( -- status )
    _USDOC-ENTRY @ _USDOC-ENTRY-U @ _USDOC-ALIGNED-SPAN? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USDOC-SUMMARY @ USCOL-SUMMARY-SIZE _USDOC-ALIGNED-SPAN? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USDOC-ENTRY @ _USDOC-ENTRY-U @
        _USDOC-SUMMARY @ USCOL-SUMMARY-SIZE _USDOC-DISJOINT? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USDOC-REVISION @ 0= IF USCOL-S-INVALID EXIT THEN
    _USDOC-ENTRY-U @ USCOL-ENTRY-HEADER-SIZE U< IF USCOL-S-INVALID EXIT THEN
    _USDOC-ENTRY-U @ 7 AND IF USCOL-S-INVALID EXIT THEN
    _USDOC-ENTRY @ USCOL-ENTRY-BYTES@ _USDOC-ENTRY-U @ <> IF
        USCOL-S-INVALID EXIT
    THEN
    _USDOC-ENTRY @ USCOL-ENTRY-FAMILY-ABI@ USCOL-FAMILY-ABI <> IF
        USCOL-S-INVALID EXIT
    THEN
    _USDOC-SUMMARY @ USCOL-SUMMARY-ENTRY-BYTES@ _USDOC-ENTRY-U @ <> IF
        USCOL-S-INVALID EXIT
    THEN
    _USDOC-ENTRY @ USCOL-ENTRY-FAMILY@
        _USDOC-SUMMARY @ USCOL-SUMMARY-FAMILY@ <> IF USCOL-S-INVALID EXIT THEN
    _USDOC-ENTRY @ USCOL-ENTRY-KEY@ DUP 0= IF DROP USCOL-S-INVALID EXIT THEN
    _USDOC-SUMMARY @ USCOL-SUMMARY-ROOT-KEY@ <> IF USCOL-S-INVALID EXIT THEN
    _USDOC-ENTRY @ USCOL-ENTRY-FAMILY@ USCOL-F-DOCUMENT <> IF
        USCOL-S-UNSUPPORTED EXIT
    THEN
    _USDOC-ENTRY-U @ USCOL-DOC-FIXED-SIZE U< IF USCOL-S-INVALID EXIT THEN
    _USDOC-ENTRY @ USCOL-DOC-BLOCK-COUNT@
    _USDOC-SUMMARY @ USCOL-SUMMARY-ITEM-COUNT@ DUP _USDOC-BLOCKS !
        <> IF USCOL-S-INVALID EXIT THEN
    _USDOC-SUMMARY @ USCOL-SUMMARY-UTF8-BYTES@ DUP _USDOC-UTF8-U !
        _USDOC-U32? 0= IF USCOL-S-INVALID EXIT THEN
    _USDOC-SUMMARY @ USCOL-SUMMARY-RUN-COUNT@ DUP _USDOC-RUN-COUNT !
        _USDOC-U32? 0= IF USCOL-S-INVALID EXIT THEN
    _USDOC-SUMMARY @ USCOL-SUMMARY-FIELD-COUNT@ DUP _USDOC-CONTAINER-COUNT !
        _USDOC-U32? 0= IF USCOL-S-INVALID EXIT THEN

    _USDOC-SUMMARY @ USCOL-SUMMARY-DOC1-BYTES
    DUP USCOL-S-OK <> IF NIP EXIT THEN
    DROP _USDOC-OUT-U !

    _USDOC-CAP @ 0< IF USCOL-S-INVALID EXIT THEN
    _USDOC-CAP @ _USDOC-OUT-U @ U< IF USCOL-S-CAPACITY EXIT THEN
    _USDOC-DST @ _USDOC-CAP @ OVER 0<> OVER 0> AND 0= IF
        2DROP USCOL-S-INVALID EXIT
    THEN
    MSPAN-NONWRAPPING? 0= IF USCOL-S-INVALID EXIT THEN
    _USDOC-ENTRY @ _USDOC-ENTRY-U @
        _USDOC-DST @ _USDOC-CAP @ _USDOC-DISJOINT? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USDOC-SUMMARY @ USCOL-SUMMARY-SIZE
        _USDOC-DST @ _USDOC-CAP @ _USDOC-DISJOINT? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    USCOL-S-OK ;

: _USDOC-HEADER!  ( -- )
    \ Zero is the invalid publication tag until the complete walk succeeds.
    0 _USDOC-DST @ _USDOC-LE32!
    USDOC-VERSION _USDOC-DST @ 4 + _USDOC-LE16!
    0 _USDOC-DST @ 6 + _USDOC-LE16!
    _USDOC-REVISION @ _USDOC-DST @ 8 + _USDOC-LE64!
    _USDOC-ENTRY @ USCOL-DOC-FLAGS@ _USDOC-DST @ 16 + _USDOC-LE16!
    0 _USDOC-DST @ 18 + _USDOC-LE16!
    _USDOC-BLOCKS @ _USDOC-DST @ 20 + _USDOC-LE32!
    _USDOC-ENTRY @ USCOL-DOC-VIEWPORT-ROW@ _USDOC-DST @ 24 + _USDOC-LE32!
    0 _USDOC-DST @ 28 + _USDOC-LE32! ;

: _USDOC-CURSORS!  ( -- )
    _USDOC-ENTRY @ USCOL-DOC-FIRST-BLOCK _USDOC-NATIVE !
    _USDOC-ENTRY-U @ USCOL-DOC-FIXED-SIZE - _USDOC-NATIVE-U !
    _USDOC-DST @ USDOC-HEADER-SIZE + _USDOC-WIRE !
    _USDOC-OUT-U @ USDOC-HEADER-SIZE - _USDOC-WIRE-U !
    0 _USDOC-COPIED-UTF8 ! 0 _USDOC-COPIED-RUNS !
    0 _USDOC-COPIED-CONTAINERS ! ;

\ _USDOC-STEP? ( native-step wire-step -- flag )
\   Both records fit what remains; they become the cursors' next steps.
: _USDOC-STEP?  ( native-step wire-step -- flag )
    DUP _USDOC-WIRE-STEP ! _USDOC-WIRE-U @ U> IF DROP 0 EXIT THEN
    DUP _USDOC-NATIVE-STEP ! _USDOC-NATIVE-U @ U> 0= ;

: _USDOC-ADVANCE  ( -- )
    _USDOC-NATIVE-STEP @ _USDOC-NATIVE +!
    _USDOC-NATIVE-STEP @ NEGATE _USDOC-NATIVE-U +!
    _USDOC-WIRE-STEP @ _USDOC-WIRE +!
    _USDOC-WIRE-STEP @ NEGATE _USDOC-WIRE-U +! ;

\ _USDOC-COUNT+? ( n variable total -- flag )
\   Add N to the copied count in VARIABLE, which may not pass TOTAL.
: _USDOC-COUNT+?  ( n variable total -- flag )
    >R DUP >R @ _USDOC-UADD? 0= IF DROP R> R> 2DROP 0 EXIT THEN
    DUP R> SWAP R> U> IF 2DROP 0 EXIT THEN
    ! -1 ;

\ The block's records on the wire, after its 32-byte header: u8 kind, u8
\ flags, u16 width and u32 number for each container, the raw text, and
\ u32 start, u32 length, u16 meaning and a zero u16 for each style run.
: _USDOC-BODY!  ( -- )
    _USDOC-NATIVE @ USCOL-BLOCK-FIRST-CONTAINER _USDOC-A !
    _USDOC-WIRE @ USDOC-BLOCK-HEADER-SIZE + _USDOC-W !
    _USDOC-CONTAINERS @ 0 ?DO
        _USDOC-A @ USCOL-CONTAINER-KIND@ _USDOC-W @ C!
        _USDOC-A @ USCOL-CONTAINER-FLAGS@ _USDOC-W @ 1+ C!
        _USDOC-A @ USCOL-CONTAINER-WIDTH@ _USDOC-W @ 2 + _USDOC-LE16!
        _USDOC-A @ USCOL-CONTAINER-NUMBER@ _USDOC-W @ 4 + _USDOC-LE32!
        USCOL-CONTAINER-SIZE _USDOC-A +!
        USDOC-CONTAINER-SIZE _USDOC-W +!
    LOOP
    _USDOC-A @ _USDOC-W @ _USDOC-TEXT-U @ MOVE
    _USDOC-TEXT-U @ _USDOC-W +!
    _USDOC-TEXT-U @ 7 + -8 AND _USDOC-A +!
    _USDOC-RUNS @ 0 ?DO
        _USDOC-A @ USCOL-RUN-START@ _USDOC-W @ _USDOC-LE32!
        _USDOC-A @ USCOL-RUN-LENGTH@ _USDOC-W @ 4 + _USDOC-LE32!
        _USDOC-A @ USCOL-RUN-MEANING@ _USDOC-W @ 8 + _USDOC-LE16!
        0 _USDOC-W @ 10 + _USDOC-LE16!
        USCOL-RUN-SIZE _USDOC-A +!
        USDOC-RUN-SIZE _USDOC-W +!
    LOOP ;

\ Cursor checks are memory-safety accounting, not a second semantic proof.
: _USDOC-BLOCK?  ( -- flag )
    _USDOC-NATIVE-U @ USCOL-BLOCK-HEADER-SIZE U< IF 0 EXIT THEN
    _USDOC-NATIVE @ USCOL-BLOCK-CONTAINER-COUNT@ DUP _USDOC-CONTAINERS !
        0x10000 U< 0= IF 0 EXIT THEN
    _USDOC-NATIVE @ USCOL-BLOCK-TEXT-BYTES@ DUP _USDOC-TEXT-U !
        _USDOC-U32? 0= IF 0 EXIT THEN
    _USDOC-NATIVE @ USCOL-BLOCK-RUN-COUNT@ DUP _USDOC-RUNS !
        _USDOC-U32? 0= IF 0 EXIT THEN
    \ The native record: header, containers, padded text, runs.
    _USDOC-CONTAINERS @ USCOL-CONTAINER-SIZE * USCOL-BLOCK-HEADER-SIZE +
    _USDOC-TEXT-U @ 7 + -8 AND _USDOC-UADD? 0= IF DROP 0 EXIT THEN
    _USDOC-RUNS @ USCOL-RUN-SIZE * _USDOC-UADD? 0= IF DROP 0 EXIT THEN
    \ The wire record: header, containers, raw text, runs.
    _USDOC-CONTAINERS @ USDOC-CONTAINER-SIZE * USDOC-BLOCK-HEADER-SIZE +
    _USDOC-TEXT-U @ _USDOC-UADD? 0= IF 2DROP 0 EXIT THEN
    _USDOC-RUNS @ USDOC-RUN-SIZE * _USDOC-UADD? 0= IF 2DROP 0 EXIT THEN
    _USDOC-STEP? 0= IF 0 EXIT THEN
    _USDOC-TEXT-U @ _USDOC-COPIED-UTF8 _USDOC-UTF8-U @ _USDOC-COUNT+?
        0= IF 0 EXIT THEN
    _USDOC-RUNS @ _USDOC-COPIED-RUNS _USDOC-RUN-COUNT @ _USDOC-COUNT+?
        0= IF 0 EXIT THEN
    _USDOC-CONTAINERS @ _USDOC-COPIED-CONTAINERS _USDOC-CONTAINER-COUNT @
        _USDOC-COUNT+? 0= IF 0 EXIT THEN
    _USDOC-NATIVE @ USCOL-BLOCK-KEY@ _USDOC-WIRE @ _USDOC-LE64!
    _USDOC-NATIVE @ USCOL-BLOCK-KIND@ _USDOC-WIRE @ 8 + _USDOC-LE16!
    _USDOC-NATIVE @ USCOL-BLOCK-LEVEL@ _USDOC-WIRE @ 10 + _USDOC-LE16!
    _USDOC-NATIVE @ USCOL-BLOCK-ROWS-BEFORE@ _USDOC-WIRE @ 12 + _USDOC-LE16!
    _USDOC-NATIVE @ USCOL-BLOCK-INSIDE@ _USDOC-WIRE @ 14 + _USDOC-LE16!
    _USDOC-NATIVE @ USCOL-BLOCK-PICTURE-ROWS@ _USDOC-WIRE @ 16 + _USDOC-LE32!
    _USDOC-CONTAINERS @ _USDOC-WIRE @ 20 + _USDOC-LE16!
    0 _USDOC-WIRE @ 22 + _USDOC-LE16!
    _USDOC-TEXT-U @ _USDOC-WIRE @ 24 + _USDOC-LE32!
    _USDOC-RUNS @ _USDOC-WIRE @ 28 + _USDOC-LE32!
    _USDOC-BODY!
    _USDOC-ADVANCE
    -1 ;

: _USDOC-WALK?  ( -- flag )
    _USDOC-BLOCKS @ 0 ?DO
        _USDOC-BLOCK? 0= IF 0 UNLOOP EXIT THEN
    LOOP
    _USDOC-NATIVE-U @ 0=
    _USDOC-WIRE-U @ 0= AND
    _USDOC-COPIED-UTF8 @ _USDOC-UTF8-U @ = AND
    _USDOC-COPIED-RUNS @ _USDOC-RUN-COUNT @ = AND
    _USDOC-COPIED-CONTAINERS @ _USDOC-CONTAINER-COUNT @ = AND ;

: _USDOC-PACK-BODY  ( -- bytes status )
    _USDOC-CORRELATE DUP USCOL-S-OK <> IF 0 SWAP EXIT THEN DROP
    _USDOC-HEADER!
    _USDOC-CURSORS!
    _USDOC-WALK? 0= IF 0 USCOL-S-INVALID EXIT THEN
    \ The tag is the final write; no fallible operation follows it.
    USDOC-TAG _USDOC-DST @ _USDOC-LE32!
    _USDOC-OUT-U @ USCOL-S-OK ;

: _USDOC-SCRUB  ( -- )
    0 _USDOC-ENTRY ! 0 _USDOC-ENTRY-U ! 0 _USDOC-SUMMARY !
    0 _USDOC-REVISION ! 0 _USDOC-DST ! 0 _USDOC-CAP !
    0 _USDOC-BLOCKS ! 0 _USDOC-UTF8-U ! 0 _USDOC-RUN-COUNT !
    0 _USDOC-CONTAINER-COUNT ! 0 _USDOC-OUT-U !
    0 _USDOC-NATIVE ! 0 _USDOC-NATIVE-U ! 0 _USDOC-WIRE ! 0 _USDOC-WIRE-U !
    0 _USDOC-TEXT-U ! 0 _USDOC-RUNS ! 0 _USDOC-CONTAINERS !
    0 _USDOC-NATIVE-STEP ! 0 _USDOC-WIRE-STEP !
    0 _USDOC-COPIED-UTF8 ! 0 _USDOC-COPIED-RUNS ! 0 _USDOC-COPIED-CONTAINERS !
    0 _USDOC-A ! 0 _USDOC-W ! ;

: USDOC-PACK
    ( entry entry-u summary revision destination capacity -- bytes status )
    _USDOC-ARGS!
    ['] _USDOC-PACK-BODY CATCH ?DUP IF DROP 0 USCOL-S-INVALID THEN
    >R >R _USDOC-SCRUB R> R> ;
