    _RSHPL-CONTROL
    _RSHPL-PARENT @ _RSHPL-C @ _RTE-CONTROL.PARENT !
    _RSHPL-I @ _RSHPL-C @ _RTE-CONTROL.ORDER !
    _RSHPL-E @ SHME.COL @ _RSHPL-BAND-C @ - _RSHPL-C @ _RTE-CONTROL.COL !
    _RSHPL-E @ SHME.WIDTH @ _RSHPL-C @ _RTE-CONTROL.WIDTH !
