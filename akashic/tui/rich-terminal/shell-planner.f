: _RSHPL-U32? ( n -- flag ) 0xFFFFFFFF U> 0= ;
: _RSHPL-I32? ( n -- flag ) DUP -2147483648 >= SWAP 2147483647 <= AND ;
: RSHPL-STORAGE-DISJOINT? ( a u -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN DUP 0= IF 2DROP -1 EXIT THEN
    OVER 0= IF 2DROP 0 EXIT THEN
    2DUP MSPAN-NONWRAPPING? 0= IF 2DROP 0 EXIT THEN
    2DUP _RSHPL-OWNED-START _RSHPL-OWNED-LIMIT @ _RSHPL-OWNED-START -
        MSPAN-OVERLAP? IF 2DROP 0 EXIT THEN
    2DUP RTE-ADMISSION-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    SHSN-STORAGE-DISJOINT? ;
: _RSHPL-SPAN? ( a u -- flag )
    DUP _RSHPL-U32? 0= IF 2DROP 0 EXIT THEN
    DUP 0= IF DROP 0= EXIT THEN RSHPL-STORAGE-DISJOINT? ;
: _RSHPL-ALIGNED? ( a u -- flag )
    2DUP _RSHPL-SPAN? 0= IF 2DROP 0 EXIT THEN DROP 7 AND 0= ;
: _RSHPL-S@ ( index -- a u ) 16 * _RSHPL-SPANS + DUP @ SWAP 8 + @ ;
: _RSHPL-S! ( a u index -- ) 16 * _RSHPL-SPANS + >R R@ 8 + ! R> ! ;
: _RSHPL-SPANS? ( q -- flag )
