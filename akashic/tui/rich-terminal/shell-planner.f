        RTE-CONTROL-TASK _RSHPL-C @ _RTE-CONTROL.KIND !
        3 _RSHPL-E @ SHME.FLAGS @ SHM-F-SELECTED AND IF 8 OR THEN
        _RSHPL-E @ SHME.FLAGS @ SHM-F-MINIMIZED AND IF 32 OR THEN
    ELSE
        RTE-CONTROL-LAUNCHER _RSHPL-C @ _RTE-CONTROL.KIND !
        1 _RSHPL-E @ SHME.FLAGS @ SHM-F-DISABLED AND
        _RSHPL-E @ SHME.ACTION @ 0= OR 0= IF 2 OR THEN
    THEN _RSHPL-C @ _RTE-CONTROL.STATE !
