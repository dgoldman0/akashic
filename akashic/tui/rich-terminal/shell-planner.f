    _RSHPL-REGIONS @ RTE-INSTRUMENT-REGION-SIZE * _RSHPL-Q @ _RSHPL-Q.REGIONS-A @ +
        DUP _RSHPL-R ! RTE-INSTRUMENT-REGION-SIZE 0 FILL
    _RSHPL-NEXT-R @ _RSHPL-R @ _RTE-IR.ID !
    _RSHPL-M @ SHM.WIDTH @ _RSHPL-R @ _RTE-IR.COLS !
    _RSHPL-M @ SHM.HEIGHT @ _RSHPL-R @ _RTE-IR.ROWS !
    _RSHPL-CCOL @ _RSHPL-R @ _RTE-IR.CLIP-X !
    _RSHPL-CROW @ _RSHPL-R @ _RTE-IR.CLIP-Y !
    _RSHPL-CW @ _RSHPL-R @ _RTE-IR.CLIP-COLS !
    _RSHPL-CH @ _RSHPL-R @ _RTE-IR.CLIP-ROWS !
    _RSHPL-Z @ _RSHPL-R @ _RTE-IR.Z !
    RTE-REGION-VISIBLE RTE-REGION-CLIPPED OR _RSHPL-R @ _RTE-IR.FLAGS !
    1 _RSHPL-REGIONS +! _RSHPL-NEXT-R @ 1 _RSHPL-NEXT-R +! ;
: _RSHPL-COPY$ ( a u -- offset )
    _RSHPL-TEXT @ >R
    DUP IF
        DUP >R _RSHPL-Q @ _RSHPL-Q.TEXT-A @ _RSHPL-TEXT @ + SWAP CMOVE
        R> _RSHPL-TEXT +!
    ELSE 2DROP THEN R> ;
: _RSHPL-COPY-ACTION$ ( a u -- offset )
    _RSHPL-ACTIONS @ >R
    DUP IF
        DUP >R _RSHPL-Q @ _RSHPL-Q.ACTIONS-A @ _RSHPL-ACTIONS @ + SWAP CMOVE
        R> _RSHPL-ACTIONS +!
    ELSE 2DROP THEN R> ;
: _RSHPL-TEXT$ ( offset bytes -- a u )
    DUP 0= IF 2DROP 0 0 ELSE SWAP _RSHPL-Q @ _RSHPL-Q.TEXT-A @ + SWAP THEN ;
