            I _RSHPL-PANE? IF
                I _RSHPL-I ! I _RSHPL-ENTRY _RSHPL-E ! _RSHPL-PANE
            THEN
        LOOP
    THEN
    _RSHPL-TASK-N @ _RSHPL-LAUNCH-N @ OR IF
        _RSHPL-Q @ _RSHPL-Q.TASKBAR-Z @
        _RSHPL-M @ SHM.HEIGHT @ 1- 0 1 _RSHPL-M @ SHM.END-COL @
        _RSHPL-REGION _RSHPL-TBREG !
        _RSHPL-TASK-N @ IF SHM-K-TASK _RSHPL-BAND-EMIT THEN
        _RSHPL-LAUNCH-N @ IF SHM-K-LAUNCHER _RSHPL-BAND-EMIT THEN
    THEN ;
