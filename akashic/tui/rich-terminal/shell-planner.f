    _RSHPL-I @ _RSHPL-X @ RSHPL-CORRELATION.INDEX !
    _RSHPL-ID @ _RSHPL-X @ RSHPL-CORRELATION.ID !
    _RSHPL-RID @ _RSHPL-X @ RSHPL-CORRELATION.REGION !
    _RSHPL-CONTENT @ _RSHPL-X @ RSHPL-CORRELATION.CONTENT-REGION !
    _RSHPL-M @ SHM.OWNER-ID @ _RSHPL-X @ RSHPL-CORRELATION.SOURCE-OWNER !
    _RSHPL-M @ SHM.OWNER-GEN @ _RSHPL-X @ RSHPL-CORRELATION.SOURCE-GENERATION !
    _RSHPL-M @ SHM.EPOCH @ _RSHPL-X @ RSHPL-CORRELATION.EPOCH !
