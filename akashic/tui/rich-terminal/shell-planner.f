    RTE-CONTROL-TASKBAR _RSHPL-C @ _RTE-CONTROL.KIND !
    1 _RSHPL-M @ SHM.FLAGS @ SHM-F-INPUT-BLOCKED AND 0= IF 2 OR THEN
        _RSHPL-C @ _RTE-CONTROL.STATE !
    _RSHPL-M @ SHM.HEIGHT @ 1- _RSHPL-C @ _RTE-CONTROL.ROW !
    _RSHPL-BAND-C @ _RSHPL-C @ _RTE-CONTROL.COL !
    _RSHPL-BAND-W @ _RSHPL-C @ _RTE-CONTROL.WIDTH !
    0 _RSHPL-TEXT-O ! 0 _RSHPL-TEXT-N ! 0 _RSHPL-ACTION-O ! 0 _RSHPL-ACTION-N !
    _RSHPL-BAND @ SHM-K-TASK = IF
        -1 _RSHPL-I ! RSHPL-K-TASKBAR-TASKS
    ELSE -2 _RSHPL-I ! RSHPL-K-TASKBAR-LAUNCHERS THEN _RSHPL-CORRELATE
    RSHPL-CLAIM-TASKBAR _RSHPL-K !
    _RSHPL-M @ SHM.HEIGHT @ 1- _RSHPL-BAND-C @ 1 _RSHPL-BAND-W @ _RSHPL-CLAIM
    1 _RSHPL-ROOTS +! ;
