\ Exact two source-authored bands. A band with no entries is not emitted.
\ TASKS occupy [0, divider), LAUNCHERS [divider+2, end), or [0,end)
\ when the source has no divider. Every selected entry must fit its band.
: _RSHPL-BAND-BOUNDS ( kind -- col width )
    SHM-K-TASK = IF
        0 _RSHPL-M @ SHM.DIVIDER-COL @ DUP 0< IF
            DROP _RSHPL-M @ SHM.END-COL @
        THEN
    ELSE
        _RSHPL-M @ SHM.DIVIDER-COL @ DUP 0< IF DROP 0 ELSE 2 + THEN
        DUP _RSHPL-M @ SHM.END-COL @ SWAP -
    THEN ;
: _RSHPL-BAND-FITS? ( e -- flag )
    DUP SHME.KIND @ _RSHPL-BAND-BOUNDS _RSHPL-BAND-W ! _RSHPL-BAND-C !
    _RSHPL-BAND-W @ 0> 0= IF DROP 0 EXIT THEN
    _RSHPL-BAND-C @ _RSHPL-BAND-W @ + _RSHPL-M @ SHM.END-COL @ > IF DROP 0 EXIT THEN
    _RSHPL-BAND-C @ _RSHPL-I32? 0= IF DROP 0 EXIT THEN
    _RSHPL-M @ SHM.HEIGHT @ 1- _RSHPL-I32? 0= IF DROP 0 EXIT THEN
    DUP SHME.COL @ _RSHPL-BAND-C @ < IF DROP 0 EXIT THEN
    DUP SHME.COL @ SWAP SHME.WIDTH @ + _RSHPL-BAND-C @ _RSHPL-BAND-W @ + <= ;

\ The public bound helpers validate the frozen model on every call. Their
\ internal -PROVED peers skip only SHSN-FROZEN-VALIDATE, for a caller that
\ validated the model and has not written it since.
VARIABLE _RSHPL-PROVED
: _RSHPL-MODEL-OK? ( model bytes -- flag )
    2DUP RSHPL-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    _RSHPL-PROVED @ IF 2DROP -1 EXIT THEN
    SHSN-FROZEN-VALIDATE SHSN-S-OK = ;

\ Geometry-only helper; validates frozen bytes and returns the canonical
\ band, without asserting any final-writer or blank-cell proof.
: _RSHPL-BAND-BOUNDS-OF ( kind model bytes -- row col height width status )
    2DUP _RSHPL-MODEL-OK? 0= IF
        2DROP DROP 0 0 0 0 RSHPL-S-INVALID EXIT
    THEN DROP _RSHPL-M !
    DUP SHM-K-TASK = OVER SHM-K-LAUNCHER = OR 0= IF
        DROP 0 0 0 0 RSHPL-S-INVALID EXIT
    THEN
    _RSHPL-BAND-BOUNDS _RSHPL-BAND-W ! _RSHPL-BAND-C !
    _RSHPL-BAND-W @ 0< _RSHPL-BAND-C @ _RSHPL-I32? 0= OR
    _RSHPL-BAND-C @ _RSHPL-BAND-W @ + _RSHPL-M @ SHM.END-COL @ > OR
    _RSHPL-M @ SHM.HEIGHT @ 1- _RSHPL-I32? 0= OR IF
        0 0 0 0 RSHPL-S-INVALID EXIT
    THEN
    _RSHPL-M @ SHM.HEIGHT @ 1- _RSHPL-BAND-C @ 1 _RSHPL-BAND-W @ RSHPL-S-OK ;
: RSHPL-BAND-BOUNDS ( kind model bytes -- row col height width status )
    0 _RSHPL-PROVED ! _RSHPL-BAND-BOUNDS-OF ;
: _RSHPL-BAND-BOUNDS-PROVED ( kind model bytes -- row col height width status )
    -1 _RSHPL-PROVED ! _RSHPL-BAND-BOUNDS-OF 0 _RSHPL-PROVED ! ;

\ Deep source validation precedes every count or record dereference.
: _RSHPL-SOURCE? ( -- flag )
    _RSHPL-Q @ _RSHPL-Q.MODEL-A @ _RSHPL-Q @ _RSHPL-Q.MODEL-U @
        SHSN-FROZEN-VALIDATE SHSN-S-OK <> IF 0 EXIT THEN
    _RSHPL-Q @ _RSHPL-Q.MODEL-A @ _RSHPL-M !
    _RSHPL-Q @ _RSHPL-Q.RESERVED @ IF 0 EXIT THEN
    _RSHPL-Q @ _RSHPL-Q.OWNER @ 0= _RSHPL-Q @ _RSHPL-Q.GENERATION @ 0= OR
    _RSHPL-Q @ _RSHPL-Q.ATTACHMENT @ 0= OR _RSHPL-Q @ _RSHPL-Q.DRAW @ 0= OR
        IF 0 EXIT THEN
    _RSHPL-Q @ _RSHPL-Q.BANDS @ 3 INVERT AND IF 0 EXIT THEN
    _RSHPL-Q @ _RSHPL-Q.CHROME-Z @ _RSHPL-I32? 0=
    _RSHPL-Q @ _RSHPL-Q.CONTENT-Z @ _RSHPL-I32? 0= OR
    _RSHPL-Q @ _RSHPL-Q.TASKBAR-Z @ _RSHPL-I32? 0= OR IF 0 EXIT THEN
    _RSHPL-Q @ _RSHPL-Q.CONTENT-Z @ _RSHPL-Q @ _RSHPL-Q.CHROME-Z @ < IF 0 EXIT THEN
    _RSHPL-Q @ _RSHPL-Q.RESULT-U @ RSHPL-RESULT-SIZE < IF 0 EXIT THEN
    _RSHPL-Q @ _RSHPL-Q.ELIGIBLE-U @ ?DUP IF
        _RSHPL-M @ SHM.COUNT @ 8 * <> IF 0 EXIT THEN
        _RSHPL-M @ SHM.COUNT @ 0 ?DO
            I _RSHPL-PANE? DUP 1 U> IF DROP 0 UNLOOP EXIT THEN
            I _RSHPL-ENTRY SHME.KIND @ SHM-K-PANE <> AND IF 0 UNLOOP EXIT THEN
        LOOP
    THEN -1 ;

: _RSHPL-CHROME-COUNT ( e -- count )
    DUP SHME.CONTENT-ROW @ OVER SHME.ROW @ > IF 1 ELSE 0 THEN
    OVER DUP SHME.CONTENT-ROW @ SWAP SHME.CONTENT-H @ +
    2 PICK DUP SHME.ROW @ SWAP SHME.HEIGHT @ + < IF 1+ THEN
    OVER SHME.CONTENT-COL @ 2 PICK SHME.COL @ > IF 1+ THEN
    OVER DUP SHME.CONTENT-COL @ SWAP SHME.CONTENT-W @ +
    2 PICK DUP SHME.COL @ SWAP SHME.WIDTH @ + < IF 1+ THEN NIP ;
: _RSHPL-BAND-EXCLUSIVE? ( kind -- flag )
    DUP _RSHPL-K ! _RSHPL-BAND-BOUNDS _RSHPL-BAND-W ! _RSHPL-BAND-C !
    _RSHPL-M @ SHM.COUNT @ 0 ?DO
        I _RSHPL-ENTRY DUP SHME.KIND @ DUP SHM-K-PANE <>
        SWAP _RSHPL-K @ <> AND IF
            DUP SHME.COL @ _RSHPL-BAND-C @ _RSHPL-BAND-W @ + <
            OVER SHME.COL @ ROT SHME.WIDTH @ + _RSHPL-BAND-C @ > AND IF
                0 UNLOOP EXIT
            THEN
        ELSE DROP THEN
    LOOP -1 ;
: _RSHPL-CHROME-UNOBSCURED? ( -- flag )
    _RSHPL-M @ SHM.COUNT @ 0 ?DO
        I _RSHPL-PANE? IF
            I _RSHPL-ENTRY _RSHPL-OTHER !
            _RSHPL-E @ SHME.COL @ _RSHPL-OTHER @ SHME.CONTENT-COL @ MAX _RSHPL-LEFT !
            _RSHPL-E @ SHME.COL @ _RSHPL-E @ SHME.WIDTH @ +
            _RSHPL-OTHER @ SHME.CONTENT-COL @ _RSHPL-OTHER @ SHME.CONTENT-W @ +
                MIN _RSHPL-RIGHT !
            _RSHPL-E @ SHME.ROW @ _RSHPL-OTHER @ SHME.CONTENT-ROW @ MAX _RSHPL-TOP !
            _RSHPL-E @ SHME.ROW @ _RSHPL-E @ SHME.HEIGHT @ +
            _RSHPL-OTHER @ SHME.CONTENT-ROW @ _RSHPL-OTHER @ SHME.CONTENT-H @ +
                MIN _RSHPL-BOTTOM !
            _RSHPL-RIGHT @ _RSHPL-LEFT @ > _RSHPL-BOTTOM @ _RSHPL-TOP @ > AND IF
                _RSHPL-LEFT @ _RSHPL-E @ SHME.CONTENT-COL @ <
                _RSHPL-RIGHT @ _RSHPL-E @ SHME.CONTENT-COL @ _RSHPL-E @ SHME.CONTENT-W @ + > OR
                _RSHPL-TOP @ _RSHPL-E @ SHME.CONTENT-ROW @ < OR
                _RSHPL-BOTTOM @ _RSHPL-E @ SHME.CONTENT-ROW @ _RSHPL-E @ SHME.CONTENT-H @ + > OR
                    IF 0 UNLOOP EXIT THEN
            THEN
        THEN
    LOOP -1 ;
: _RSHPL-COUNT? ( -- flag )
    _RSHPL-RESET
    _RSHPL-M @ SHM.COUNT @ 0 ?DO
        I _RSHPL-ENTRY _RSHPL-E !
        _RSHPL-E @ SHME.KIND @ SHM-K-PANE = IF
            I _RSHPL-PANE? IF
                _RSHPL-CHROME-UNOBSCURED? 0= IF 0 UNLOOP EXIT THEN
                _RSHPL-E @ SHME.ROW @ _RSHPL-I32? 0=
                _RSHPL-E @ SHME.COL @ _RSHPL-I32? 0= OR
                _RSHPL-E @ SHME.CONTENT-ROW @ _RSHPL-I32? 0= OR
                _RSHPL-E @ SHME.CONTENT-COL @ _RSHPL-I32? 0= OR
                    IF 0 UNLOOP EXIT THEN
                1 _RSHPL-PANES +!
                _RSHPL-E @ SHME.TITLE-U @ DUP _RSHPL-TEXT +! _RSHPL-PANE-UTF8 +!
                _RSHPL-E @ _RSHPL-CHROME-COUNT _RSHPL-CLAIMS +!
                _RSHPL-E @ SHME.FLAGS @ SHM-F-OVERLAY AND IF
                    _RSHPL-Q @ _RSHPL-Q.CONTENT-Z @ 2147483647 = IF 0 UNLOOP EXIT THEN
                THEN
            THEN
        ELSE
            _RSHPL-E @ SHME.KIND @ _RSHPL-BAND? IF
                _RSHPL-M @ SHM.FLAGS @ SHM-F-TASKBAR-HIDDEN AND 0= IF
                    _RSHPL-E @ _RSHPL-BAND-FITS? 0= IF 0 UNLOOP EXIT THEN
                    _RSHPL-E @ SHME.KIND @ SHM-K-TASK = IF
                        1 _RSHPL-TASK-N +!
                    ELSE 1 _RSHPL-LAUNCH-N +! THEN
                    1 _RSHPL-CONTROLS +!
                    _RSHPL-E @ SHME.LABEL-U @ DUP _RSHPL-TEXT +! _RSHPL-CONTROL-UTF8 +!
                    _RSHPL-E @ SHME.ACTION-U @ _RSHPL-ACTIONS +!
                THEN
            THEN
        THEN
    LOOP
    _RSHPL-TASK-N @ IF SHM-K-TASK _RSHPL-BAND-EXCLUSIVE? 0= IF 0 EXIT THEN THEN
    _RSHPL-LAUNCH-N @ IF SHM-K-LAUNCHER _RSHPL-BAND-EXCLUSIVE? 0= IF 0 EXIT THEN THEN
    _RSHPL-TASK-N @ 0<> IF 1 _RSHPL-ROOTS +! THEN
    _RSHPL-LAUNCH-N @ 0<> IF 1 _RSHPL-ROOTS +! THEN
    _RSHPL-ROOTS @ _RSHPL-CONTROLS +!
    _RSHPL-ROOTS @ _RSHPL-CLAIMS +!
    _RSHPL-PANES @ DUP IF 1+ THEN
    _RSHPL-ROOTS @ IF 1+ THEN _RSHPL-REGIONS !
    _RSHPL-PANES @ _RSHPL-CONTROLS @ + _RSHPL-CORRS ! -1 ;
: _RSHPL-IDS? ( first count -- flag )
    DUP 0= IF 2DROP -1 EXIT THEN OVER 0= IF 2DROP 0 EXIT THEN
    1- OVER + SWAP U< 0= ;
: _RSHPL-CAPACITY? ( -- flag )
    _RSHPL-REGIONS @ RTE-INSTRUMENT-REGION-SIZE * _RSHPL-Q @ _RSHPL-Q.REGIONS-U @ U>
    _RSHPL-PANES @ RTE-PANE-SIZE * _RSHPL-Q @ _RSHPL-Q.PANES-U @ U> OR
    _RSHPL-CONTROLS @ RTE-CONTROL-SIZE * _RSHPL-Q @ _RSHPL-Q.CONTROLS-U @ U> OR
    _RSHPL-TEXT @ _RSHPL-Q @ _RSHPL-Q.TEXT-U @ U> OR
    _RSHPL-ACTIONS @ _RSHPL-Q @ _RSHPL-Q.ACTIONS-U @ U> OR
    _RSHPL-CORRS @ RSHPL-CORRELATION-SIZE * _RSHPL-Q @ _RSHPL-Q.CORRELATIONS-U @ U> OR
    _RSHPL-CLAIMS @ RSHPL-CLAIM-SIZE * _RSHPL-Q @ _RSHPL-Q.CLAIMS-U @ U> OR IF 0 EXIT THEN
    _RSHPL-Q @ _RSHPL-Q.FIRST-REGION @ _RSHPL-REGIONS @ _RSHPL-IDS?
    _RSHPL-Q @ _RSHPL-Q.FIRST-OBJECT @ _RSHPL-PANES @ _RSHPL-IDS? AND
    _RSHPL-Q @ _RSHPL-Q.FIRST-CONTROL @ _RSHPL-CONTROLS @ _RSHPL-IDS? AND ;

VARIABLE _RSHPL-TEXT-N VARIABLE _RSHPL-ACTION-N VARIABLE _RSHPL-RID
VARIABLE _RSHPL-Z VARIABLE _RSHPL-GAP-N VARIABLE _RSHPL-GAP-I
VARIABLE _RSHPL-GAP-C VARIABLE _RSHPL-GAP-END
3 CONSTANT RSHPL-S-END

\ Enumerate only the source's blank-spacing rectangles. The publisher must
\ check these exact cells are ordinary spaces and that the entire selected
\ band is clear under SHSN-RECT-CLEAR? for the completed draw. END returns
\ canonical zero geometry. No source text is interpreted.
: _RSHPL-GAP-TAKE? ( end-col -- found? )
    _RSHPL-GAP-C @ > IF
        _RSHPL-GAP-I @ _RSHPL-GAP-N @ = IF -1 EXIT THEN
        1 _RSHPL-GAP-I +!
    THEN 0 ;
: _RSHPL-GAP-RETURN ( end-col -- row col height width status )
    _RSHPL-GAP-C @ - >R
    _RSHPL-M @ SHM.HEIGHT @ 1- _RSHPL-GAP-C @ 1 R> RSHPL-S-OK ;
: _RSHPL-GAP-BOUNDS-OF ( ordinal kind model bytes -- row col height width status )
    2DUP _RSHPL-MODEL-OK? 0= IF
        2DROP 2DROP 0 0 0 0 RSHPL-S-INVALID EXIT
    THEN DROP _RSHPL-M ! _RSHPL-K ! _RSHPL-GAP-N !
    _RSHPL-K @ DUP SHM-K-TASK = SWAP SHM-K-LAUNCHER = OR 0=
    _RSHPL-GAP-N @ 0< OR IF 0 0 0 0 RSHPL-S-INVALID EXIT THEN
    _RSHPL-K @ _RSHPL-BAND-BOUNDS OVER + _RSHPL-GAP-END ! _RSHPL-GAP-C !
    0 _RSHPL-GAP-I !
    _RSHPL-M @ SHM.COUNT @ 0 ?DO
        I _RSHPL-ENTRY _RSHPL-E !
        _RSHPL-E @ SHME.KIND @ _RSHPL-K @ = IF
            _RSHPL-E @ _RSHPL-BAND-FITS? 0= IF
                0 0 0 0 RSHPL-S-INVALID UNLOOP EXIT
            THEN
            _RSHPL-E @ SHME.COL @ DUP _RSHPL-GAP-TAKE? IF
                _RSHPL-GAP-RETURN UNLOOP EXIT
            THEN DROP
            _RSHPL-E @ SHME.COL @ _RSHPL-E @ SHME.WIDTH @ + _RSHPL-GAP-C !
        THEN
    LOOP
    _RSHPL-GAP-END @ DUP _RSHPL-GAP-TAKE? IF _RSHPL-GAP-RETURN EXIT THEN
    DROP 0 0 0 0 RSHPL-S-END ;
: RSHPL-GAP-BOUNDS ( ordinal kind model bytes -- row col height width status )
    0 _RSHPL-PROVED ! _RSHPL-GAP-BOUNDS-OF ;
: _RSHPL-GAP-BOUNDS-PROVED ( ordinal kind model bytes -- row col height width status )
    -1 _RSHPL-PROVED ! _RSHPL-GAP-BOUNDS-OF 0 _RSHPL-PROVED ! ;

: _RSHPL-REGION ( z row col height width -- id )
