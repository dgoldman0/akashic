    _RSHPL-Q !
    _RSHPL-Q @ _RSHPL-Q.MODEL-A @ _RSHPL-Q @ _RSHPL-Q.MODEL-U @
        _RSHPL-ALIGNED? 0= IF 0 EXIT THEN
    _RSHPL-Q @ _RSHPL-Q.ELIGIBLE-A @ _RSHPL-Q @ _RSHPL-Q.ELIGIBLE-U @
        _RSHPL-ALIGNED? 0= IF 0 EXIT THEN
    7 0 DO
        _RSHPL-Q @ 120 I 16 * + + DUP @ SWAP 8 + @
        I 3 = IF _RSHPL-SPAN? ELSE _RSHPL-ALIGNED? THEN
        0= IF 0 UNLOOP EXIT THEN
    LOOP
    _RSHPL-Q @ _RSHPL-Q.ACTIONS-A @ _RSHPL-Q @ _RSHPL-Q.ACTIONS-U @
        _RSHPL-SPAN? 0= IF 0 EXIT THEN
    _RSHPL-Q @ RSHPL-REQUEST-SIZE 0 _RSHPL-S!
    _RSHPL-Q @ _RSHPL-Q.MODEL-A @ _RSHPL-Q @ _RSHPL-Q.MODEL-U @ 1 _RSHPL-S!
