        _RSHPL-E @ SHME.KEY @ _RSHPL-X @ RSHPL-CORRELATION.KEY !
        _RSHPL-E @ SHME.IDENTITY @ _RSHPL-X @ RSHPL-CORRELATION.IDENTITY !
        _RSHPL-E @ SHME.OWNER-ID @ _RSHPL-X @ RSHPL-CORRELATION.OWNER !
        _RSHPL-E @ SHME.OWNER-GEN @ _RSHPL-X @ RSHPL-CORRELATION.GENERATION !
        _RSHPL-E @ SHME.ACTION @ _RSHPL-X @ RSHPL-CORRELATION.ACTION !
        _RSHPL-E @ SHME.FLAGS @ _RSHPL-X @ RSHPL-CORRELATION.FLAGS !
        _RSHPL-E @ SHME.ROW @ _RSHPL-X @ RSHPL-CORRELATION.ROW !
        _RSHPL-E @ SHME.COL @ _RSHPL-X @ RSHPL-CORRELATION.COL !
        _RSHPL-E @ SHME.HEIGHT @ _RSHPL-X @ RSHPL-CORRELATION.HEIGHT !
        _RSHPL-E @ SHME.WIDTH @ _RSHPL-X @ RSHPL-CORRELATION.WIDTH !
    ELSE
        _RSHPL-M @ SHM.OWNER-ID @ _RSHPL-X @ RSHPL-CORRELATION.OWNER !
        _RSHPL-M @ SHM.OWNER-GEN @ _RSHPL-X @ RSHPL-CORRELATION.GENERATION !
        _RSHPL-M @ SHM.FLAGS @ _RSHPL-X @ RSHPL-CORRELATION.FLAGS !
        _RSHPL-M @ SHM.HEIGHT @ 1- _RSHPL-X @ RSHPL-CORRELATION.ROW !
        _RSHPL-BAND-C @ _RSHPL-X @ RSHPL-CORRELATION.COL !
        1 _RSHPL-X @ RSHPL-CORRELATION.HEIGHT !
        _RSHPL-BAND-W @ _RSHPL-X @ RSHPL-CORRELATION.WIDTH !
    THEN
    _RSHPL-TEXT-O @ _RSHPL-X @ RSHPL-CORRELATION.TEXT-OFFSET !
    _RSHPL-TEXT-N @ _RSHPL-X @ RSHPL-CORRELATION.TEXT-BYTES !
    _RSHPL-ACTION-O @ _RSHPL-X @ RSHPL-CORRELATION.ACTION-OFFSET !
    _RSHPL-ACTION-N @ _RSHPL-X @ RSHPL-CORRELATION.ACTION-BYTES !
    1 _RSHPL-CORRS +! ;
