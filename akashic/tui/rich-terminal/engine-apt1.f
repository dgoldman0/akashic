\ =====================================================================
\  engine-apt1.f -- RTAPT provider bridge for the neutral RTE facade
\ =====================================================================
\
\  This is the sole mapping between the generic retained-engine ABI and the
\  concrete APT-1 engine.  It is loaded only by an outer product composition;
\  UIDL lifecycle code depends on engine.f and never names RTAPT or PT.
\
\  Prefix:   RTAPTE- (public), _RTAPTE- (private)
\  Provider: akashic-tui-rtapte1

PROVIDED akashic-tui-rtapte1

REQUIRE engine.f
REQUIRE apt1-engine.f

: _RTAPTE-STATUS>RTE  ( rtapt-status -- rte-status )
    DUP RTAPT-S-OK = IF DROP RTE-S-OK EXIT THEN
    DUP RTAPT-S-WOULD-BLOCK = IF DROP RTE-S-WOULD-BLOCK EXIT THEN
    DUP RTAPT-S-BUSY = IF DROP RTE-S-WOULD-BLOCK EXIT THEN
    DUP RTAPT-S-SESSION-LOST = IF DROP RTE-S-SESSION-LOST EXIT THEN
    DUP RTAPT-S-INVALID = IF DROP RTE-S-INVALID EXIT THEN
    DUP RTAPT-S-UNSUPPORTED = IF DROP RTE-S-UNAVAILABLE EXIT THEN
    DUP RTAPT-S-CAPACITY = IF DROP RTE-S-CAPACITY EXIT THEN
    DUP RTAPT-S-REJECTED = IF DROP RTE-S-STALE EXIT THEN
    DROP RTE-S-INVALID ;

: _RTAPTE-OWNER-ST>RTE  ( rtapt-owner-state -- rte-owner-state )
    DUP RTAPT-OWNER-ST-FREE = IF DROP RTE-OWNER-ST-FREE EXIT THEN
    DUP RTAPT-OWNER-ST-OPEN-QUEUED =
    OVER RTAPT-OWNER-ST-OPENING = OR
    OVER RTAPT-OWNER-ST-TOMBSTONE-OPEN-QUEUED = OR
    OVER RTAPT-OWNER-ST-TOMBSTONE-OPENING = OR IF
        DROP RTE-OWNER-ST-OPENING EXIT
    THEN
    DUP RTAPT-OWNER-ST-OPEN = IF DROP RTE-OWNER-ST-OPEN EXIT THEN
    DUP RTAPT-OWNER-ST-DROP-QUEUED =
    OVER RTAPT-OWNER-ST-DROPPING = OR
    OVER RTAPT-OWNER-ST-TOMBSTONE-DROP-QUEUED = OR
    OVER RTAPT-OWNER-ST-TOMBSTONE-DROPPING = OR
    OVER RTAPT-OWNER-ST-DROP-RETRY-QUEUED = OR
    OVER RTAPT-OWNER-ST-DROP-RETRY-DROPPING = OR IF
        DROP RTE-OWNER-ST-DROPPING EXIT
    THEN
    DUP RTAPT-OWNER-ST-TOMBSTONE = IF
        DROP RTE-OWNER-ST-TOMBSTONE EXIT
    THEN
    RTAPT-OWNER-ST-QUARANTINED = IF
        RTE-OWNER-ST-QUARANTINED EXIT
    THEN
    RTE-OWNER-ST-FREE ;

: _RTAPTE-MODE>RTAPT  ( rte-mode -- rtapt-mode flag )
    DUP RTE-RICH-DELTA = IF DROP RTAPT-RICH-DELTA -1 EXIT THEN
    DUP RTE-RICH-REPLACE-START = IF
        DROP RTAPT-RICH-REPLACE-START -1 EXIT
    THEN
    DUP RTE-RICH-REPLACE-CONTINUE = IF
        DROP RTAPT-RICH-REPLACE-CONTINUE -1 EXIT
    THEN
    DUP RTE-RICH-LAYOUT-START = IF
        DROP RTAPT-RICH-LAYOUT-START -1 EXIT
    THEN
    RTE-RICH-LAYOUT-CONTINUE = IF
        RTAPT-RICH-LAYOUT-CONTINUE -1 EXIT
    THEN
    0 0 ;

: _RTAPTE-DISPOSITION>RTAPT  ( rte-disposition -- rtapt-disposition flag )
    DUP RTE-COMMIT = IF DROP RTAPT-COMMIT -1 EXIT THEN
    RTE-COMMIT-AND-REVEAL = IF
        RTAPT-COMMIT-AND-REVEAL -1 EXIT
    THEN
    0 0 ;

\ Facade callbacks receive their explicit RTAPT engine as the final context.
: _RTAPTE-DISJOINT?  ( a u engine -- flag )
    RTAPT-STORAGE-DISJOINT? ;

: _RTAPTE-STATUS@  ( engine -- status )
    RTAPT-STATUS _RTAPTE-STATUS>RTE ;

: _RTAPTE-OWNER-OPEN
    ( owner generation region-q resource-q object-q series-q
      resource-bytes utf8-bytes sample-slots engine -- status )
    RTAPT-OWNER-OPEN _RTAPTE-STATUS>RTE ;

: _RTAPTE-OWNER-STATE@  ( owner generation engine -- owner-state status )
    RTAPT-OWNER-STATE@
    _RTAPTE-STATUS>RTE >R _RTAPTE-OWNER-ST>RTE R> ;

: _RTAPTE-RICH-BEGIN  ( rte-mode engine -- status )
    SWAP _RTAPTE-MODE>RTAPT 0= IF 2DROP RTE-S-INVALID EXIT THEN
    SWAP RTAPT-RICH-BEGIN _RTAPTE-STATUS>RTE ;

: _RTAPTE-REGION-DEFINE
    ( owner generation region x y cols rows z flags engine -- status )
    RTAPT-REGION-DEFINE _RTAPTE-STATUS>RTE ;

: _RTAPTE-RICH-SEAL  ( rte-disposition engine -- status )
    SWAP _RTAPTE-DISPOSITION>RTAPT 0= IF
        2DROP RTE-S-INVALID EXIT
    THEN
    SWAP RTAPT-RICH-SEAL _RTAPTE-STATUS>RTE ;

: _RTAPTE-RICH-CANCEL  ( engine -- status )
    RTAPT-RICH-CANCEL _RTAPTE-STATUS>RTE ;

: _RTAPTE-OWNER-DROP  ( owner generation engine -- status )
    RTAPT-OWNER-DROP _RTAPTE-STATUS>RTE ;

: _RTAPTE-ZERO?  ( a u -- flag )
    0 ?DO
        DUP I + C@ IF DROP 0 UNLOOP EXIT THEN
    LOOP
    DROP -1 ;

: _RTAPTE-FACADE?  ( facade -- flag )
    DUP RTE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _RTE-F.CONTEXT @ RTAPT-VALID? 0= IF DROP 0 EXIT THEN
    DUP _RTE-F.DISJOINT-XT @ ['] _RTAPTE-DISJOINT? =
    OVER _RTE-F.STATUS-XT @ ['] _RTAPTE-STATUS@ = AND
    OVER _RTE-F.OWNER-OPEN-XT @ ['] _RTAPTE-OWNER-OPEN = AND
    OVER _RTE-F.OWNER-STATE-XT @ ['] _RTAPTE-OWNER-STATE@ = AND
    OVER _RTE-F.RICH-BEGIN-XT @ ['] _RTAPTE-RICH-BEGIN = AND
    OVER _RTE-F.REGION-DEF-XT @ ['] _RTAPTE-REGION-DEFINE = AND
    OVER _RTE-F.RICH-SEAL-XT @ ['] _RTAPTE-RICH-SEAL = AND
    OVER _RTE-F.RICH-CANCEL-XT @ ['] _RTAPTE-RICH-CANCEL = AND
    OVER _RTE-F.OWNER-DROP-XT @ ['] _RTAPTE-OWNER-DROP = AND
    NIP ;

VARIABLE _RTAPTE-I-ENGINE
VARIABLE _RTAPTE-I-FACADE

: _RTAPTE-SCRUB-BORROWED  ( -- )
    0 _RTAPTE-I-ENGINE !
    0 _RTAPTE-I-FACADE ! ;

: _RTAPTE-INIT-BODY  ( engine facade -- status )
    _RTAPTE-I-FACADE ! _RTAPTE-I-ENGINE !
    _RTAPTE-I-FACADE @ RTE-FACADE-SIZE _RTE-SPAN? 0= IF
        RTE-S-INVALID EXIT
    THEN
    _RTAPTE-I-ENGINE @ RTAPT-VALID? 0= IF RTE-S-INVALID EXIT THEN
    _RTAPTE-I-FACADE @ RTE-FACADE-SIZE _RTAPTE-I-ENGINE @
        RTAPT-STORAGE-DISJOINT? 0= IF RTE-S-INVALID EXIT THEN
    _RTAPTE-I-FACADE @ _RTE-F.MAGIC @ _RTE-MAGIC = IF
        RTE-S-WOULD-BLOCK EXIT
    THEN

    _RTAPTE-I-FACADE @ RTE-FACADE-SIZE 0 FILL
    _RTE-ABI _RTAPTE-I-FACADE @ _RTE-F.ABI !
    RTE-FACADE-SIZE _RTAPTE-I-FACADE @ _RTE-F.SIZE !
    _RTAPTE-I-FACADE @ DUP _RTE-F.SELF !
    _RTAPTE-I-ENGINE @ _RTAPTE-I-FACADE @ _RTE-F.CONTEXT !
    ['] _RTAPTE-DISJOINT? _RTAPTE-I-FACADE @ _RTE-F.DISJOINT-XT !
    ['] _RTAPTE-STATUS@ _RTAPTE-I-FACADE @ _RTE-F.STATUS-XT !
    ['] _RTAPTE-OWNER-OPEN _RTAPTE-I-FACADE @ _RTE-F.OWNER-OPEN-XT !
    ['] _RTAPTE-OWNER-STATE@ _RTAPTE-I-FACADE @ _RTE-F.OWNER-STATE-XT !
    ['] _RTAPTE-RICH-BEGIN _RTAPTE-I-FACADE @ _RTE-F.RICH-BEGIN-XT !
    ['] _RTAPTE-REGION-DEFINE _RTAPTE-I-FACADE @ _RTE-F.REGION-DEF-XT !
    ['] _RTAPTE-RICH-SEAL _RTAPTE-I-FACADE @ _RTE-F.RICH-SEAL-XT !
    ['] _RTAPTE-RICH-CANCEL _RTAPTE-I-FACADE @ _RTE-F.RICH-CANCEL-XT !
    ['] _RTAPTE-OWNER-DROP _RTAPTE-I-FACADE @ _RTE-F.OWNER-DROP-XT !
    _RTE-MAGIC _RTAPTE-I-FACADE @ _RTE-F.MAGIC !
    RTE-S-OK ;

: _RTAPTE-FINI-BODY  ( facade -- status )
    DUP RTE-FACADE-SIZE _RTE-SPAN? 0= IF DROP RTE-S-INVALID EXIT THEN
    DUP RTE-FACADE-SIZE _RTAPTE-ZERO? IF DROP RTE-S-OK EXIT THEN
    DUP _RTAPTE-FACADE? 0= IF DROP RTE-S-INVALID EXIT THEN
    DUP RTE-FACADE-SIZE OVER _RTE-F.CONTEXT @
        RTAPT-STORAGE-DISJOINT? 0= IF DROP RTE-S-INVALID EXIT THEN
    RTE-FACADE-SIZE 0 FILL
    RTE-S-OK ;

: _RTAPTE-P-DO-INIT  ( -- status )
    _RTAPTE-I-ENGINE @ _RTAPTE-I-FACADE @ _RTAPTE-INIT-BODY ;

: RTAPTE-INIT  ( engine facade -- status )
    _RTAPTE-I-FACADE ! _RTAPTE-I-ENGINE !
    ['] _RTAPTE-P-DO-INIT CATCH ?DUP IF DROP RTE-S-INVALID THEN
    _RTAPTE-SCRUB-BORROWED ;

: _RTAPTE-P-DO-FINI  ( -- status )
    _RTAPTE-I-FACADE @ _RTAPTE-FINI-BODY ;

: RTAPTE-FINI  ( facade -- status )
    _RTAPTE-I-FACADE !
    ['] _RTAPTE-P-DO-FINI CATCH ?DUP IF DROP RTE-S-INVALID THEN
    _RTAPTE-SCRUB-BORROWED ;
