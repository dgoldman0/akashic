\ =====================================================================
\  engine-apt1.f -- RTAPT provider bridge for the neutral RTE facade
\ =====================================================================
\
\  This is the sole mapping between the generic retained-engine ABI and the
\  concrete APT-1 engine.  It is loaded only by an outer product composition;
\  UIDL lifecycle code depends on engine.f and never names RTAPT or PT.
\
\  Prefix:   RTAPTE- (public), _RTAPTE- (private)
\  Provider: akashic-tui-rtapte1

PROVIDED akashic-tui-rtapte1

REQUIRE engine.f
REQUIRE apt1-engine.f

: _RTAPTE-STATUS>RTE  ( rtapt-status -- rte-status )
    DUP RTAPT-S-OK = IF DROP RTE-S-OK EXIT THEN
    DUP RTAPT-S-WOULD-BLOCK = IF DROP RTE-S-WOULD-BLOCK EXIT THEN
    DUP RTAPT-S-BUSY = IF DROP RTE-S-WOULD-BLOCK EXIT THEN
    DUP RTAPT-S-SESSION-LOST = IF DROP RTE-S-SESSION-LOST EXIT THEN
    DUP RTAPT-S-INVALID = IF DROP RTE-S-INVALID EXIT THEN
    DUP RTAPT-S-UNSUPPORTED = IF DROP RTE-S-UNAVAILABLE EXIT THEN
    DUP RTAPT-S-CAPACITY = IF DROP RTE-S-CAPACITY EXIT THEN
    DUP RTAPT-S-REJECTED = IF DROP RTE-S-STALE EXIT THEN
    DROP RTE-S-INVALID ;

: _RTAPTE-OWNER-ST>RTE  ( rtapt-owner-state -- rte-owner-state )
    DUP RTAPT-OWNER-ST-FREE = IF DROP RTE-OWNER-ST-FREE EXIT THEN
    DUP RTAPT-OWNER-ST-OPEN-QUEUED =
    OVER RTAPT-OWNER-ST-OPENING = OR
    OVER RTAPT-OWNER-ST-TOMBSTONE-OPEN-QUEUED = OR
    OVER RTAPT-OWNER-ST-TOMBSTONE-OPENING = OR IF
        DROP RTE-OWNER-ST-OPENING EXIT
    THEN
    DUP RTAPT-OWNER-ST-OPEN = IF DROP RTE-OWNER-ST-OPEN EXIT THEN
    DUP RTAPT-OWNER-ST-DROP-QUEUED =
    OVER RTAPT-OWNER-ST-DROPPING = OR
    OVER RTAPT-OWNER-ST-TOMBSTONE-DROP-QUEUED = OR
    OVER RTAPT-OWNER-ST-TOMBSTONE-DROPPING = OR
    OVER RTAPT-OWNER-ST-DROP-RETRY-QUEUED = OR
    OVER RTAPT-OWNER-ST-DROP-RETRY-DROPPING = OR IF
        DROP RTE-OWNER-ST-DROPPING EXIT
    THEN
    DUP RTAPT-OWNER-ST-TOMBSTONE = IF
        DROP RTE-OWNER-ST-TOMBSTONE EXIT
    THEN
    RTAPT-OWNER-ST-QUARANTINED = IF
        RTE-OWNER-ST-QUARANTINED EXIT
    THEN
    RTE-OWNER-ST-FREE ;

: _RTAPTE-MODE>RTAPT  ( rte-mode -- rtapt-mode flag )
    DUP RTE-RETAINED-DELTA = IF DROP RTAPT-RICH-DELTA -1 EXIT THEN
    DUP RTE-RETAINED-REPLACE-START = IF
        DROP RTAPT-RICH-REPLACE-START -1 EXIT
    THEN
    DUP RTE-RETAINED-REPLACE-CONTINUE = IF
        DROP RTAPT-RICH-REPLACE-CONTINUE -1 EXIT
    THEN
    DUP RTE-RETAINED-LAYOUT-START = IF
        DROP RTAPT-RICH-LAYOUT-START -1 EXIT
    THEN
    RTE-RETAINED-LAYOUT-CONTINUE = IF
        RTAPT-RICH-LAYOUT-CONTINUE -1 EXIT
    THEN
    0 0 ;

: _RTAPTE-DISPOSITION>RTAPT  ( rte-disposition -- rtapt-disposition flag )
    DUP RTE-COMMIT = IF DROP RTAPT-COMMIT -1 EXIT THEN
    RTE-COMMIT-AND-REVEAL = IF
        RTAPT-COMMIT-AND-REVEAL -1 EXIT
    THEN
    0 0 ;

\ Facade callbacks receive their explicit RTAPT engine as the final context.
: _RTAPTE-DISJOINT?  ( a u engine -- flag )
    RTAPT-STORAGE-DISJOINT? ;

: _RTAPTE-STATUS@  ( engine -- status )
    RTAPT-STATUS _RTAPTE-STATUS>RTE ;

: _RTAPTE-FEATURES>RTE  ( rtapt-features -- rte-features )
    0 SWAP
    DUP RTAPT-F-CORE AND IF SWAP RTE-F-CORE OR SWAP THEN
    DUP RTAPT-F-VECTOR AND IF SWAP RTE-F-VECTOR OR SWAP THEN
    DUP RTAPT-F-IMAGE AND IF SWAP RTE-F-IMAGE OR SWAP THEN
    DUP RTAPT-F-INSTRUMENT AND IF SWAP RTE-F-INSTRUMENT OR SWAP THEN
    DUP RTAPT-F-SERIES AND IF SWAP RTE-F-SERIES OR SWAP THEN
    DUP RTAPT-F-CADENCE AND IF SWAP RTE-F-CADENCE OR SWAP THEN
    DROP ;

