    _USFSN-DIRTY-DESCRIPTOR-U @ ?DUP IF
        _USFSN-DESCRIPTORS-A @ SWAP 0 FILL
    THEN
    _USFSN-DIRTY-NATIVE-U @ ?DUP IF
        _USFSN-NATIVE-A @ SWAP 0 FILL
    THEN ;


