\ =====================================================================
\  uidl-status-field-snapshot.f -- direct and mounted status-field snapshot
\ =====================================================================
\
\  One coherent UIDL-TUI observation captures ordinary direct status labels
\  and mounted SFIELD widgets into a separate caller-owned native USF bank and
\  pointer-free descriptors. Records are canonical by unsigned source index
\  and relation root key. Native field keys remain application-owned.
\
\  Only complete one-row fields whose exact clip equals their full geometry
\  are admitted. Unsupported or partially clipped roots remain CELL-owned;
\  a capacity failure clears every dirtied descriptor/native output byte.
\  Caller banks must be pairwise disjoint and disjoint from module scratch,
\  UIDL authority, and every live semantic widget and backing model.
\
\  USFSN-CAPTURE ( descriptors-a descriptors-u native-a native-u
\                  -- descriptor-count native-used status )
\  USFSN-FROZEN-WORK-BYTES ( descriptor-count -- bytes|0 )
\  USFSN-FROZEN-VALIDATE ( work-a work-u descriptors-a descriptors-u
\                          native-a native-u -- status )
\
\  Frozen validation never consults the live tree. It validates every USF,
\  checks complete descriptor geometry and counts, and sorts caller-owned
\  offsets to prove exact native-bank coverage without overlap or gaps.
\  Prefix: USFSN- (public), _USFSN- (private).

