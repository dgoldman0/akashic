    R> + -1 ;


: _USFSN-V-ROOT-FIT?  ( -- flag )
    _USFSN-V-ENTRY @ USF-WIDTH@ DUP _USFSN-V-WIDTH !
        _USFSN-V-EXTENT-WIDTH @ <> IF 0 EXIT THEN
    1 _USFSN-V-HEIGHT !
    _USFSN-V-ORIGIN-ROW @ DUP _USFSN-V-ROW !
        1 _USFSN-IADD-NONNEG? 0= IF DROP 0 EXIT THEN DROP
    _USFSN-V-ORIGIN-COLUMN @ DUP _USFSN-V-COLUMN !
        _USFSN-V-WIDTH @ _USFSN-IADD-NONNEG? 0= IF DROP 0 EXIT THEN DROP
    _USFSN-V-RESOLVED-A @ 64 + @ DUP _USFSN-V-Z !
        255 U> IF 0 EXIT THEN
    -1 ;
