: _USFSN-F-UADD?  ( a b -- sum flag )
    OVER + DUP ROT U< 0= ;

: _USFSN-F-WORK-AT  ( ordinal -- address )
    USFSN-FROZEN-WORK-ENTRY-SIZE * _USFSN-F-WORK-A @ + ;

: _USFSN-F-DESCRIPTOR-AT  ( ordinal -- descriptor )
    USFSN-DESCRIPTOR-SIZE * _USFSN-F-DESCRIPTORS-A @ + ;

: _USFSN-F-CLEAR-SCRATCH  ( -- )
    _USFSN-F-RANGES-VALID @ IF
        _USFSN-F-WORK-NEED @ ?DUP IF
            _USFSN-F-WORK-A @ SWAP 0 FILL
        THEN
    THEN ;

: _USFSN-F-SCRUB  ( -- )
    0 _USFSN-F-WORK-A ! 0 _USFSN-F-WORK-U !
    0 _USFSN-F-WORK-NEED !
    0 _USFSN-F-DESCRIPTORS-A ! 0 _USFSN-F-DESCRIPTORS-U !
    0 _USFSN-F-NATIVE-A ! 0 _USFSN-F-NATIVE-U !
    0 _USFSN-F-COUNT ! 0 _USFSN-F-I ! 0 _USFSN-F-J !
    0 _USFSN-F-VALUE ! 0 _USFSN-F-DESCRIPTOR !
    0 _USFSN-F-HEAP-ROOT ! 0 _USFSN-F-HEAP-END !
    0 _USFSN-F-HEAP-CHILD ! 0 _USFSN-F-HEAP-LARGEST !
    0 _USFSN-F-HEAP-A ! 0 _USFSN-F-HEAP-B !
    0 _USFSN-F-FIELD ! 0 _USFSN-F-FIELD-U !
    0 _USFSN-F-OFFSET ! 0 _USFSN-F-CURSOR !
    0 _USFSN-F-INDEX ! 0 _USFSN-F-GENERATION !
    0 _USFSN-F-RELATION ! 0 _USFSN-F-PRIOR-INDEX !
    0 _USFSN-F-PRIOR-GENERATION ! 0 _USFSN-F-PRIOR-RELATION !
    0 _USFSN-F-HAVE-PRIOR !
    0 _USFSN-F-RANGES-VALID ! ;

: _USFSN-F-AUTHORITY-DISJOINT?  ( address bytes -- flag )
    DUP 0= IF 2DROP -1 EXIT THEN
    2DUP _USFSN-OWNED-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP USCOL-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP UDG-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP DGF-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP SFIELD-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    USF-STORAGE-DISJOINT? ;

: _USFSN-F-RANGES  ( -- status )
    _USFSN-F-DESCRIPTORS-A @ _USFSN-F-DESCRIPTORS-U @
        _USFSN-OPTIONAL-SPAN? 0= IF USFSN-S-INVALID EXIT THEN
    _USFSN-F-DESCRIPTORS-U @ USFSN-DESCRIPTOR-SIZE MOD IF
        USFSN-S-INVALID EXIT
    THEN
    _USFSN-F-NATIVE-A @ _USFSN-F-NATIVE-U @
        _USFSN-OPTIONAL-SPAN? 0= IF USFSN-S-INVALID EXIT THEN
    _USFSN-F-DESCRIPTORS-U @ 0=
        _USFSN-F-NATIVE-U @ 0= <> IF USFSN-S-INVALID EXIT THEN
    _USFSN-F-DESCRIPTORS-U @ IF
        _USFSN-F-DESCRIPTORS-A @ _USFSN-ALIGNED? 0= IF
            USFSN-S-INVALID EXIT
        THEN
        _USFSN-F-NATIVE-A @ _USFSN-ALIGNED? 0= IF
            USFSN-S-INVALID EXIT
        THEN
        _USFSN-F-NATIVE-U @ 7 AND IF USFSN-S-INVALID EXIT THEN
    THEN

    _USFSN-F-DESCRIPTORS-U @ USFSN-DESCRIPTOR-SIZE /
        DUP _USFSN-F-COUNT !
    USFSN-FROZEN-WORK-BYTES DUP _USFSN-F-WORK-NEED !
    _USFSN-F-COUNT @ IF
        DUP 0= IF DROP USFSN-S-INVALID EXIT THEN
    THEN DROP
    _USFSN-F-WORK-A @ _USFSN-F-WORK-U @
        _USFSN-OPTIONAL-SPAN? 0= IF USFSN-S-INVALID EXIT THEN
    _USFSN-F-WORK-U @ IF
        _USFSN-F-WORK-A @ _USFSN-ALIGNED? 0= IF
            USFSN-S-INVALID EXIT
        THEN
    THEN
    _USFSN-F-WORK-U @ _USFSN-F-WORK-NEED @ U< IF
        USFSN-S-CAPACITY EXIT
    THEN

    _USFSN-F-WORK-A @ _USFSN-F-WORK-U @
        _USFSN-F-AUTHORITY-DISJOINT? 0= IF USFSN-S-INVALID EXIT THEN
    _USFSN-F-DESCRIPTORS-A @ _USFSN-F-DESCRIPTORS-U @
        _USFSN-F-AUTHORITY-DISJOINT? 0= IF USFSN-S-INVALID EXIT THEN
    _USFSN-F-NATIVE-A @ _USFSN-F-NATIVE-U @
        _USFSN-F-AUTHORITY-DISJOINT? 0= IF USFSN-S-INVALID EXIT THEN

    _USFSN-F-WORK-A @ _USFSN-F-WORK-U @
        _USFSN-F-DESCRIPTORS-A @ _USFSN-F-DESCRIPTORS-U @
        _USFSN-DISJOINT? 0= IF USFSN-S-INVALID EXIT THEN
    _USFSN-F-WORK-A @ _USFSN-F-WORK-U @
        _USFSN-F-NATIVE-A @ _USFSN-F-NATIVE-U @
        _USFSN-DISJOINT? 0= IF USFSN-S-INVALID EXIT THEN
    _USFSN-F-DESCRIPTORS-A @ _USFSN-F-DESCRIPTORS-U @
        _USFSN-F-NATIVE-A @ _USFSN-F-NATIVE-U @
        _USFSN-DISJOINT? 0= IF USFSN-S-INVALID EXIT THEN

    -1 _USFSN-F-RANGES-VALID !
    _USFSN-F-CLEAR-SCRATCH
    USFSN-S-OK ;

: _USFSN-F-ORDER?  ( -- flag )
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-SOURCE@
        USFSN-SOURCE-UIDL <> IF 0 EXIT THEN
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-SOURCE-INDEX@
        DUP 0< IF DROP 0 EXIT THEN _USFSN-F-INDEX !
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-SOURCE-GENERATION@
        DUP _USFSN-GENERATION? 0= IF DROP 0 EXIT THEN
        _USFSN-F-GENERATION !
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-ROOT-KEY@
        DUP 0= IF DROP 0 EXIT THEN _USFSN-F-RELATION !
    _USFSN-F-GENERATION @ 0= IF
        _USFSN-F-RELATION @ 1 <> IF 0 EXIT THEN
    THEN
    _USFSN-F-HAVE-PRIOR @ IF
        _USFSN-F-INDEX @ _USFSN-F-PRIOR-INDEX @ U< IF 0 EXIT THEN
        _USFSN-F-INDEX @ _USFSN-F-PRIOR-INDEX @ = IF
            _USFSN-F-PRIOR-RELATION @ _USFSN-F-RELATION @
                U< 0= IF 0 EXIT THEN
            _USFSN-F-GENERATION @ _USFSN-F-PRIOR-GENERATION @
                <> IF 0 EXIT THEN
        THEN
    THEN
    _USFSN-F-INDEX @ _USFSN-F-PRIOR-INDEX !
    _USFSN-F-GENERATION @ _USFSN-F-PRIOR-GENERATION !
    _USFSN-F-RELATION @ _USFSN-F-PRIOR-RELATION !
    -1 _USFSN-F-HAVE-PRIOR !
    -1 ;

: _USFSN-F-GEOMETRY?  ( -- flag )
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-HEIGHT@ 1 <> IF 0 EXIT THEN
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-WIDTH@
        _USFSN-F-FIELD @ USF-WIDTH@ <> IF 0 EXIT THEN
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-ROW@ DUP 0< IF
        DROP 0 EXIT
    THEN
    1 _USFSN-IADD-NONNEG? 0= IF DROP 0 EXIT THEN DROP
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-COLUMN@ DUP 0< IF
        DROP 0 EXIT
    THEN
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-WIDTH@
        _USFSN-IADD-NONNEG? 0= IF DROP 0 EXIT THEN DROP
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-CLIP-ROW@
        _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-ROW@ <> IF 0 EXIT THEN
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-CLIP-COLUMN@
        _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-COLUMN@ <> IF 0 EXIT THEN
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-CLIP-HEIGHT@ 1 <> IF 0 EXIT THEN
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-CLIP-WIDTH@
        _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-WIDTH@ <> IF 0 EXIT THEN
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-Z@ 255 U> IF 0 EXIT THEN
    -1 ;
: _USFSN-F-ENTRY?  ( -- flag )
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-NATIVE-OFFSET@
        DUP 0< IF DROP 0 EXIT THEN
        DUP 7 AND IF DROP 0 EXIT THEN
        DUP _USFSN-F-OFFSET !
    _USFSN-F-NATIVE-U @ U> IF 0 EXIT THEN
    _USFSN-F-NATIVE-U @ _USFSN-F-OFFSET @ -
        USF-HEADER-SIZE U< IF 0 EXIT THEN
    _USFSN-F-NATIVE-A @ _USFSN-F-OFFSET @ +
        DUP _USFSN-F-FIELD !
    USF-BYTES@ DUP _USFSN-F-FIELD-U !
    DUP USF-HEADER-SIZE U< OVER 7 AND OR IF DROP 0 EXIT THEN
    _USFSN-F-NATIVE-U @ _USFSN-F-OFFSET @ - U> IF 0 EXIT THEN
    _USFSN-F-FIELD @ _USFSN-F-FIELD-U @ USF-VALIDATE
        USF-S-OK <> IF 0 EXIT THEN
    _USFSN-F-FIELD @ USF-FLAGS@ USF-F-VISIBLE AND 0= IF 0 EXIT THEN
    _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-ENTRY-BYTES@
        _USFSN-F-FIELD-U @ <> IF 0 EXIT THEN
    _USFSN-F-FIELD @ USF-LABEL-BYTES@
    _USFSN-F-FIELD @ USF-VALUE-BYTES@ +
        _USFSN-F-DESCRIPTOR @ USFSN-DESCRIPTOR-UTF8-BYTES@ <> IF 0 EXIT THEN
    _USFSN-F-GEOMETRY? 0= IF 0 EXIT THEN
    _USFSN-F-OFFSET @ _USFSN-F-I @ _USFSN-F-WORK-AT !
    -1 ;
: _USFSN-F-SWAP-OFFSETS  ( ordinal-a ordinal-b -- )
    _USFSN-F-HEAP-B ! _USFSN-F-HEAP-A !
    _USFSN-F-HEAP-A @ _USFSN-F-WORK-AT @ _USFSN-F-VALUE !
    _USFSN-F-HEAP-B @ _USFSN-F-WORK-AT @
        _USFSN-F-HEAP-A @ _USFSN-F-WORK-AT !
    _USFSN-F-VALUE @ _USFSN-F-HEAP-B @ _USFSN-F-WORK-AT ! ;

\ Restore one unsigned max-heap below the exclusive END ordinal.  The
\ caller-bounded ledger makes this O(n log n) at the configured ceiling.
: _USFSN-F-SIFT-DOWN  ( root end -- )
    _USFSN-F-HEAP-END ! _USFSN-F-HEAP-ROOT !
    BEGIN
        _USFSN-F-HEAP-ROOT @ 2 * 1+ DUP _USFSN-F-HEAP-CHILD !
        _USFSN-F-HEAP-END @ U<
    WHILE
        _USFSN-F-HEAP-ROOT @ _USFSN-F-HEAP-LARGEST !
        _USFSN-F-HEAP-LARGEST @ _USFSN-F-WORK-AT @
        _USFSN-F-HEAP-CHILD @ _USFSN-F-WORK-AT @ U< IF
            _USFSN-F-HEAP-CHILD @ _USFSN-F-HEAP-LARGEST !
        THEN
        _USFSN-F-HEAP-CHILD @ 1+ DUP _USFSN-F-HEAP-CHILD !
        _USFSN-F-HEAP-END @ U< IF
            _USFSN-F-HEAP-LARGEST @ _USFSN-F-WORK-AT @
            _USFSN-F-HEAP-CHILD @ _USFSN-F-WORK-AT @ U< IF
                _USFSN-F-HEAP-CHILD @ _USFSN-F-HEAP-LARGEST !
            THEN
        THEN
        _USFSN-F-HEAP-LARGEST @ _USFSN-F-HEAP-ROOT @ = IF EXIT THEN
        _USFSN-F-HEAP-ROOT @ _USFSN-F-HEAP-LARGEST @
            _USFSN-F-SWAP-OFFSETS
        _USFSN-F-HEAP-LARGEST @ _USFSN-F-HEAP-ROOT !
    REPEAT ;

: _USFSN-F-SORT-OFFSETS  ( -- )
    _USFSN-F-COUNT @ 2 / _USFSN-F-I !
    BEGIN _USFSN-F-I @ 0> WHILE
        -1 _USFSN-F-I +!
        _USFSN-F-I @ _USFSN-F-COUNT @ _USFSN-F-SIFT-DOWN
    REPEAT
    _USFSN-F-COUNT @ _USFSN-F-J !
    BEGIN _USFSN-F-J @ 1 > WHILE
        -1 _USFSN-F-J +!
        0 _USFSN-F-J @ _USFSN-F-SWAP-OFFSETS
        0 _USFSN-F-J @ _USFSN-F-SIFT-DOWN
    REPEAT ;

: _USFSN-F-COVERAGE?  ( -- flag )
    0 _USFSN-F-CURSOR ! 0 _USFSN-F-I !
    BEGIN _USFSN-F-I @ _USFSN-F-COUNT @ U< WHILE
        _USFSN-F-I @ _USFSN-F-WORK-AT @ DUP _USFSN-F-OFFSET !
        _USFSN-F-CURSOR @ <> IF 0 EXIT THEN
        _USFSN-F-OFFSET @ _USFSN-F-NATIVE-U @ U> IF 0 EXIT THEN
        _USFSN-F-NATIVE-U @ _USFSN-F-OFFSET @ -
            USF-HEADER-SIZE U< IF 0 EXIT THEN
        _USFSN-F-NATIVE-A @ _USFSN-F-OFFSET @ + USF-BYTES@
            DUP USF-HEADER-SIZE U< OVER 7 AND OR IF DROP 0 EXIT THEN
        _USFSN-F-CURSOR @ SWAP _USFSN-F-UADD?
            0= IF DROP 0 EXIT THEN
        DUP _USFSN-F-NATIVE-U @ U> IF DROP 0 EXIT THEN
            _USFSN-F-CURSOR !
        1 _USFSN-F-I +!
    REPEAT
    _USFSN-F-CURSOR @ _USFSN-F-NATIVE-U @ = ;

: _USFSN-F-VALIDATE-BODY  ( -- status )
    _USFSN-F-RANGES DUP USFSN-S-OK <> IF EXIT THEN DROP
    _USFSN-F-COUNT @ 0= IF USFSN-S-OK EXIT THEN
    0 _USFSN-F-PRIOR-INDEX ! 0 _USFSN-F-PRIOR-GENERATION !
    0 _USFSN-F-PRIOR-RELATION ! 0 _USFSN-F-HAVE-PRIOR !
    0 _USFSN-F-I !
    BEGIN _USFSN-F-I @ _USFSN-F-COUNT @ U< WHILE
        _USFSN-F-I @ _USFSN-F-DESCRIPTOR-AT
            _USFSN-F-DESCRIPTOR !
        _USFSN-F-ORDER? 0= IF USFSN-S-INVALID EXIT THEN
        _USFSN-F-ENTRY? 0= IF USFSN-S-INVALID EXIT THEN
        1 _USFSN-F-I +!
    REPEAT
    _USFSN-F-SORT-OFFSETS
    _USFSN-F-COVERAGE? 0= IF USFSN-S-INVALID EXIT THEN
    USFSN-S-OK ;

: _USFSN-F-VALIDATE-CALL  ( -- status )
    ['] _USFSN-F-VALIDATE-BODY CATCH ?DUP IF
        DROP USFSN-S-INVALID
    THEN
    _USFSN-F-CLEAR-SCRATCH
    _USFSN-F-SCRUB ;

: USFSN-FROZEN-VALIDATE
    ( offset-work-a offset-work-u descriptors-a descriptors-u native-a native-u -- status )
    5 PICK 5 PICK USFSN-STORAGE-DISJOINT? 0= IF
        2DROP 2DROP 2DROP USFSN-S-INVALID EXIT
    THEN
    3 PICK 3 PICK USFSN-STORAGE-DISJOINT? 0= IF
        2DROP 2DROP 2DROP USFSN-S-INVALID EXIT
    THEN
    2DUP USFSN-STORAGE-DISJOINT? 0= IF
        2DROP 2DROP 2DROP USFSN-S-INVALID EXIT
    THEN
    _USFSN-F-NATIVE-U ! _USFSN-F-NATIVE-A !
    _USFSN-F-DESCRIPTORS-U ! _USFSN-F-DESCRIPTORS-A !
    _USFSN-F-WORK-U ! _USFSN-F-WORK-A !
    0 _USFSN-F-WORK-NEED ! 0 _USFSN-F-RANGES-VALID !
    ['] _USFSN-F-VALIDATE-CALL CATCH ?DUP IF
        DROP
        _USFSN-F-CLEAR-SCRATCH
        _USFSN-F-SCRUB
        USFSN-S-INVALID
    THEN ;

