        _USFSN-SET-UNAVAILABLE 0 EXIT
    THEN
    _USFSN-V-ENTRY @ USF-BYTES@ _USFSN-V-ENTRY-U @ <> IF
        _USFSN-SET-INVALID 0 EXIT
    THEN
    _USFSN-V-ROOT-FIT? 0= IF _USFSN-SET-INVALID 0 EXIT THEN
    -1 ;
