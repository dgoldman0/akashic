\ _USFSN-V-REFUSED ( -- )
\   A root's own widget could not publish it.  Leave that root out, so CELL
\   draws its area and the snapshot keeps its other roots, and keep nothing
\   of it: its entry bytes and descriptor are cleared as a fully clipped
\   root's are.  A capacity refusal stays the snapshot's.
: _USFSN-V-REFUSED  ( -- )
    _USFSN-STATUS @ DUP USFSN-S-UNAVAILABLE = SWAP USFSN-S-INVALID = OR
        0= IF EXIT THEN
    _USFSN-V-DESCRIPTOR @ IF _USFSN-V-ROLLBACK-CLIPPED THEN
    USFSN-S-OK _USFSN-STATUS ! ;

: _USFSN-V-CAPTURE  ( -- )
    _USFSN-V-CLIP-HEIGHT @ 0= _USFSN-V-CLIP-WIDTH @ 0= OR IF
        EXIT
    THEN
    _USFSN-V-CAPACITY? 0= IF EXIT THEN
    _USFSN-NATIVE-USED @ _USFSN-NATIVE-U @ U> IF
        _USFSN-SET-INVALID EXIT
    THEN
    _USFSN-NATIVE-U @ _USFSN-NATIVE-USED @ - DUP 0= IF
        DROP _USFSN-SET-CAPACITY EXIT
    THEN
    _USFSN-V-REMAINING !
    0 _USFSN-V-ENTRY-U !

    \ Measure through the exact same current widget before touching
    \ the native bank.  The captured byte count must remain identical.
    0 0 _USFSN-V-PRODUCE
    DUP USF-S-OK <> IF
        >R DROP R> _USFSN-MAP-USF _USFSN-V-REFUSED EXIT
    THEN
    DROP
    DUP 0> 0= OVER 7 AND OR IF
        DROP _USFSN-SET-INVALID _USFSN-V-REFUSED EXIT
    THEN
    DUP _USFSN-V-REMAINING @ U> IF
        DROP _USFSN-SET-CAPACITY EXIT
    THEN
    _USFSN-V-ENTRY-U !

    _USFSN-NATIVE-A @ _USFSN-NATIVE-USED @ + _USFSN-V-ENTRY !
    _USFSN-NATIVE-USED @ _USFSN-V-ENTRY-U @ + DUP
        _USFSN-V-NEXT-NATIVE ! _USFSN-DIRTY-NATIVE-U !
    _USFSN-V-ENTRY @ _USFSN-V-ENTRY-U @ _USFSN-V-PRODUCE
    DUP USF-S-OK <> IF
        >R DROP R> _USFSN-MAP-USF _USFSN-V-REFUSED EXIT
    THEN
    DROP _USFSN-V-ENTRY-U @ <> IF
        _USFSN-SET-INVALID _USFSN-V-REFUSED EXIT
    THEN

    _USFSN-V-VALIDATE? 0= IF _USFSN-V-REFUSED EXIT THEN
    _USFSN-V-CLIP-HEIGHT @ 0= _USFSN-V-CLIP-WIDTH @ 0= OR IF
        _USFSN-V-ROLLBACK-CLIPPED EXIT
    THEN
    _USFSN-V-WRITE-METADATA
    _USFSN-V-NEXT-NATIVE @ _USFSN-NATIVE-USED !
    1 _USFSN-COUNT +! ;

: _USFSN-VISITOR
    ( source-index source-generation root-key resolved-a resolved-u -- )
    _USFSN-V-RESOLVED-U ! _USFSN-V-RESOLVED-A !
    _USFSN-V-ROOT-KEY ! _USFSN-V-GENERATION ! _USFSN-V-INDEX !
    _USFSN-STATUS @ USFSN-S-OK <> IF EXIT THEN
    _USFSN-V-ARGS? 0= IF _USFSN-SET-INVALID EXIT THEN
    _USFSN-V-ORDER? 0= IF _USFSN-SET-INVALID EXIT THEN
    0 _USFSN-V-DESCRIPTOR ! 0 _USFSN-V-ENTRY-U !
    _USFSN-V-GEOMETRY? 0= IF _USFSN-V-REFUSED EXIT THEN
    _USFSN-V-CAPTURE ;

