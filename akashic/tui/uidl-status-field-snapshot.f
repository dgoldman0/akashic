: _USFSN-ALIGNED?  ( address -- flag )  7 AND 0= ;

: _USFSN-OPTIONAL-SPAN?  ( address bytes -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    DUP 0= IF DROP 0= EXIT THEN
    OVER 0< IF 2DROP 0 EXIT THEN
    OVER 0= IF 2DROP 0 EXIT THEN
    MSPAN-NONWRAPPING? ;

: _USFSN-DISJOINT?  ( a1 u1 a2 u2 -- flag )
    2 PICK 0= OVER 0= OR IF 2DROP 2DROP -1 EXIT THEN
    MSPAN-OVERLAP? 0= ;

: _USFSN-OWNED-DISJOINT?  ( address bytes -- flag )
    DUP 0= IF 2DROP -1 EXIT THEN
    _USFSN-OWNED-LIMIT @ DUP _USFSN-OWNED-START U< IF
        DROP 2DROP 0 EXIT
    THEN
    _USFSN-OWNED-START - >R
    2DUP _USFSN-OWNED-START R> MSPAN-OVERLAP? 0= NIP NIP ;

\ Pure preflight for owners that reserve snapshot banks inside larger arenas.
: USFSN-STORAGE-DISJOINT?  ( address bytes -- flag )
    2DUP _USFSN-OPTIONAL-SPAN? 0= IF 2DROP 0 EXIT THEN
    _USFSN-OWNED-DISJOINT? ;

\ Runs inside the outer resolved observation before the unified iterator.
\ The final seam includes hidden/direct/nested live widget authority.
: _USFSN-AUTHORITY-DISJOINT?  ( address bytes -- flag )
    DUP 0= IF 2DROP -1 EXIT THEN
    2DUP _USFSN-OWNED-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP USF-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP SFIELD-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP USCOL-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP UDG-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP DGF-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP _UTUI-STORAGE-DISJOINT-BODY? 0= IF 2DROP 0 EXIT THEN
    _UTUI-STATUS-FIELD-STORAGE-DISJOINT-OBSERVED?
    DUP USF-S-OK <> IF 2DROP 0 EXIT THEN
    DROP ;
CREATE _USFSN-PROOF-SPANS 2 MSPAN-SET-BYTES ALLOT

\ Collect the two caller spans for one enclosed authority proof.  Their
\ shapes are admitted first, and the prover skips empty optional spans.
: _USFSN-PROOF-SPANS?  ( -- flag )
    2 _USFSN-PROOF-SPANS MSPAN-SET-INIT MSPAN-SET-S-OK <> IF 0 EXIT THEN
    _USFSN-DESCRIPTORS-A @ _USFSN-DESCRIPTORS-U @
        _USFSN-PROOF-SPANS MSPAN-SET-PUSH MSPAN-SET-S-OK <> IF 0 EXIT THEN
    _USFSN-NATIVE-A @ _USFSN-NATIVE-U @ _USFSN-PROOF-SPANS MSPAN-SET-PUSH
        MSPAN-SET-S-OK = ;
\ Caller span shapes and mutual disjointness.  Authority is proved
\ separately, before the first live status-field visit.
: _USFSN-SHAPES?  ( -- flag )
    _USFSN-DESCRIPTORS-A @ _USFSN-DESCRIPTORS-U @
        _USFSN-OPTIONAL-SPAN? 0= IF 0 EXIT THEN
    _USFSN-DESCRIPTORS-U @ USFSN-DESCRIPTOR-SIZE MOD IF 0 EXIT THEN
    _USFSN-DESCRIPTORS-U @ IF
        _USFSN-DESCRIPTORS-A @ _USFSN-ALIGNED? 0= IF 0 EXIT THEN
    THEN
    _USFSN-NATIVE-A @ _USFSN-NATIVE-U @
        _USFSN-OPTIONAL-SPAN? 0= IF 0 EXIT THEN
    _USFSN-NATIVE-U @ IF
        _USFSN-NATIVE-A @ _USFSN-ALIGNED? 0= IF 0 EXIT THEN
    THEN
    _USFSN-DESCRIPTORS-A @ _USFSN-DESCRIPTORS-U @
        _USFSN-NATIVE-A @ _USFSN-NATIVE-U @ _USFSN-DISJOINT? ;
\ Each authority query walks the document's storage.  Clustered caller spans
\ need one enclosed query instead of one per span.
: _USFSN-AUTHORITY?  ( -- flag )
    _USFSN-PROOF-SPANS? 0= IF 0 EXIT THEN
    _USFSN-PROOF-SPANS ['] _USFSN-AUTHORITY-DISJOINT?
        MSPAN-SET-PROVE-DISJOINT? ;

: _USFSN-DESCRIPTOR-AT  ( ordinal -- descriptor )
    USFSN-DESCRIPTOR-SIZE * _USFSN-DESCRIPTORS-A @ + ;

: _USFSN-SET-CAPACITY  ( -- )
    _USFSN-STATUS @ USFSN-S-OK = IF
        USFSN-S-CAPACITY _USFSN-STATUS !
    THEN ;

: _USFSN-SET-UNAVAILABLE  ( -- )
    _USFSN-STATUS @ USFSN-S-OK = IF
        USFSN-S-UNAVAILABLE _USFSN-STATUS !
    THEN ;

: _USFSN-SET-INVALID  ( -- )
    USFSN-S-INVALID _USFSN-STATUS ! ;

: _USFSN-MAP-USF  ( status -- )
    DUP USF-S-OK = IF DROP EXIT THEN
    DUP USF-S-CAPACITY = IF DROP _USFSN-SET-CAPACITY EXIT THEN
    DUP USF-S-UNSUPPORTED = IF DROP _USFSN-SET-UNAVAILABLE EXIT THEN
    DROP _USFSN-SET-INVALID ;
: _USFSN-MAP-MOUNTED  ( status -- )
    DUP _UTUI-MC-S-OK = IF DROP EXIT THEN
    DUP _UTUI-MC-S-UNAVAILABLE = IF
        DROP _USFSN-SET-UNAVAILABLE
    ELSE
        DROP _USFSN-SET-INVALID
    THEN ;

