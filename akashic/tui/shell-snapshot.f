\ Deep pointer-free validation of exact frozen bytes. Text spans appear in
\ entry order, label/title/action order; empty fields are zero or the current
\ cursor. This proves complete nonoverlapping text coverage without scratch.
VARIABLE _SHSN-V-M VARIABLE _SHSN-V-U VARIABLE _SHSN-V-E
VARIABLE _SHSN-V-CURSOR VARIABLE _SHSN-V-I VARIABLE _SHSN-V-KIND
VARIABLE _SHSN-V-LAST-KIND VARIABLE _SHSN-V-END VARIABLE _SHSN-V-SELECTED
