: _SHSN-V-TEXT? ( offset bytes -- flag )
    _SHSN-V-N ! _SHSN-V-O !
    _SHSN-V-N @ 0< IF 0 EXIT THEN
    _SHSN-V-N @ 0= IF
        _SHSN-V-O @ 0= _SHSN-V-O @ _SHSN-V-CURSOR @ = OR EXIT
    THEN
    _SHSN-V-O @ _SHSN-V-CURSOR @ <> IF 0 EXIT THEN
    _SHSN-V-N @ _SHSN-V-U @ _SHSN-V-CURSOR @ - U> IF 0 EXIT THEN
    _SHSN-V-M @ _SHSN-V-CURSOR @ + _SHSN-V-N @ USF-TEXT? 0= IF 0 EXIT THEN
    _SHSN-V-N @ _SHSN-V-CURSOR +! -1 ;
: _SHSN-V-AXIS? ( start length limit -- flag )
    >R DUP _SHSN-POS? 0= IF 2DROP R> DROP 0 EXIT THEN
    OVER _SHSN-U32? 0= IF 2DROP R> DROP 0 EXIT THEN
    + R> U> 0= ;
: _SHSN-V-RECT? ( -- flag )
    _SHSN-V-E @ SHME.ROW @ _SHSN-V-E @ SHME.HEIGHT @
        _SHSN-V-M @ SHM.HEIGHT @ _SHSN-V-AXIS? 0= IF 0 EXIT THEN
    _SHSN-V-E @ SHME.COL @ _SHSN-V-E @ SHME.WIDTH @
        _SHSN-V-M @ SHM.WIDTH @ _SHSN-V-AXIS? ;
: _SHSN-V-PANE? ( -- flag )
    _SHSN-V-E @ SHME.FLAGS @ SHM-F-SELECTED SHM-F-OVERLAY OR INVERT AND IF 0 EXIT THEN
    _SHSN-V-E @ SHME.IDENTITY @ DUP 0= OVER -1 = OR IF DROP 0 EXIT THEN
    _SHSN-V-E @ SHME.ACTION @ <> IF 0 EXIT THEN
    _SHSN-V-E @ SHME.FLAGS @ SHM-F-OVERLAY AND IF
        _SHSN-V-E @ SHME.IDENTITY @ DUP -1 < 0= IF DROP 0 EXIT THEN NEGATE
    ELSE
        _SHSN-V-E @ SHME.IDENTITY @ DUP 0> 0= IF DROP 0 EXIT THEN
    THEN _SHSN-V-E @ SHME.KEY @ <> IF 0 EXIT THEN
    _SHSN-V-E @ SHME.CONTENT-ROW @ _SHSN-V-E @ SHME.ROW @ -
        _SHSN-V-E @ SHME.CONTENT-H @ _SHSN-V-E @ SHME.HEIGHT @
        _SHSN-V-AXIS? 0= IF 0 EXIT THEN
    _SHSN-V-E @ SHME.CONTENT-COL @ _SHSN-V-E @ SHME.COL @ -
        _SHSN-V-E @ SHME.CONTENT-W @ _SHSN-V-E @ SHME.WIDTH @
        _SHSN-V-AXIS? 0= IF 0 EXIT THEN
    _SHSN-V-E @ SHME.LABEL-U @ _SHSN-V-E @ SHME.ACTION-U @ OR 0= ;
: _SHSN-V-TASK? ( -- flag )
    _SHSN-V-E @ SHME.FLAGS @ DUP SHM-F-SELECTED SHM-F-MINIMIZED OR INVERT AND IF DROP 0 EXIT THEN
    DUP SHM-F-SELECTED SHM-F-MINIMIZED OR = IF DROP 0 EXIT THEN
    SHM-F-SELECTED AND IF 1 _SHSN-V-SELECTED +! THEN
    _SHSN-V-SELECTED @ 1 > IF 0 EXIT THEN
    _SHSN-V-E @ SHME.IDENTITY @ DUP 0> 0= IF DROP 0 EXIT THEN
    DUP _SHSN-V-E @ SHME.KEY @ <>
    SWAP _SHSN-V-E @ SHME.ACTION @ <> OR IF 0 EXIT THEN
    _SHSN-V-E @ SHME.ACTION-U @ 0= ;
: _SHSN-V-LAUNCHER? ( -- flag )
    _SHSN-V-E @ SHME.FLAGS @ SHM-F-DISABLED SHM-F-ERROR OR SHM-F-RUNNING OR INVERT AND IF 0 EXIT THEN
    _SHSN-V-E @ SHME.OWNER-ID @ _SHSN-V-M @ SHM.OWNER-ID @ <>
    _SHSN-V-E @ SHME.OWNER-GEN @ _SHSN-V-M @ SHM.OWNER-GEN @ <> OR IF 0 EXIT THEN
    _SHSN-V-E @ SHME.ACTION @ 0= IF
        _SHSN-V-E @ SHME.FLAGS @ SHM-F-DISABLED AND 0<>
        _SHSN-V-E @ SHME.IDENTITY @ 0= AND
        _SHSN-V-E @ SHME.ACTION-U @ 0= AND EXIT
    THEN
    _SHSN-V-E @ SHME.ACTION @ _SHSN-V-E @ SHME.KEY @ =
    _SHSN-V-E @ SHME.IDENTITY @ 0<> AND
    _SHSN-V-E @ SHME.ACTION-U @ 0> AND ;
: _SHSN-V-ENTRY? ( -- flag )
    _SHSN-V-E @ SHME.KEY @ 0> 0= IF 0 EXIT THEN
    _SHSN-V-E @ SHME.OWNER-ID @ 0= _SHSN-V-E @ SHME.OWNER-GEN @ 0= OR IF 0 EXIT THEN
    _SHSN-V-E @ SHME.KIND @ DUP _SHSN-V-KIND !
        DUP 1 < SWAP 3 > OR IF 0 EXIT THEN
    _SHSN-V-KIND @ _SHSN-V-LAST-KIND @ < IF 0 EXIT THEN
    _SHSN-V-KIND @ _SHSN-V-LAST-KIND !
    _SHSN-V-I @ 0 ?DO
        I _SHSN-V-M @ SHM-ENTRY
        DUP SHME.KIND @ _SHSN-V-KIND @ =
        OVER SHME.KEY @ _SHSN-V-E @ SHME.KEY @ = AND
        OVER SHME.IDENTITY @ _SHSN-V-E @ SHME.IDENTITY @ = AND
        OVER SHME.OWNER-ID @ _SHSN-V-E @ SHME.OWNER-ID @ = AND
        SWAP SHME.OWNER-GEN @ _SHSN-V-E @ SHME.OWNER-GEN @ = AND
            IF 0 UNLOOP EXIT THEN
    LOOP
    _SHSN-V-RECT? 0= IF 0 EXIT THEN
    _SHSN-V-KIND @ SHM-K-PANE = IF _SHSN-V-PANE? 0= IF 0 EXIT THEN ELSE
        _SHSN-V-M @ SHM.FLAGS @ SHM-F-TASKBAR-HIDDEN AND IF 0 EXIT THEN
        _SHSN-V-E @ SHME.CONTENT-ROW 32 _SHSN-ZERO? 0= IF 0 EXIT THEN
        _SHSN-V-E @ SHME.HEIGHT @ 1 <>
        _SHSN-V-E @ SHME.ROW @ _SHSN-V-M @ SHM.HEIGHT @ 1- <> OR IF 0 EXIT THEN
        _SHSN-V-E @ SHME.COL @ _SHSN-V-END @ < IF 0 EXIT THEN
        _SHSN-V-E @ SHME.COL @ _SHSN-V-E @ SHME.WIDTH @ + _SHSN-V-END !
        _SHSN-V-KIND @ SHM-K-TASK = IF _SHSN-V-TASK? ELSE _SHSN-V-LAUNCHER? THEN
            0= IF 0 EXIT THEN
    THEN
    _SHSN-V-E @ SHME.LABEL-OFF @ _SHSN-V-E @ SHME.LABEL-U @ _SHSN-V-TEXT? 0= IF 0 EXIT THEN
    _SHSN-V-E @ SHME.TITLE-OFF @ _SHSN-V-E @ SHME.TITLE-U @ _SHSN-V-TEXT? 0= IF 0 EXIT THEN
    _SHSN-V-E @ SHME.ACTION-OFF @ _SHSN-V-E @ SHME.ACTION-U @ _SHSN-V-TEXT? 0= IF 0 EXIT THEN
    _SHSN-V-KIND @ SHM-K-PANE <> IF
        _SHSN-V-E @ _SHSN-V-M @ SHME-LABEL$ _SHSN-V-GR GR-SWIDTH-WITH
        _SHSN-V-E @ SHME.WIDTH @ <> IF 0 EXIT THEN
    THEN -1 ;
: _SHSN-FROZEN? ( -- flag )
    _SHSN-V-M @ SHM.ABI @ SHM-ABI <>
    _SHSN-V-M @ SHM.CAPACITY @ _SHSN-V-U @ <> OR
    _SHSN-V-M @ SHM.USED @ _SHSN-V-U @ <> OR
    _SHSN-V-M @ SHM.READY @ -1 <> OR IF 0 EXIT THEN
    _SHSN-V-M @ 112 + 16 _SHSN-ZERO? 0= IF 0 EXIT THEN
    _SHSN-V-M @ SHM.OWNER-ID @ 0= _SHSN-V-M @ SHM.OWNER-GEN @ 0= OR
    _SHSN-V-M @ SHM.EPOCH @ 0= OR IF 0 EXIT THEN
    _SHSN-V-M @ SHM.WIDTH @ _SHSN-POS? 0=
    _SHSN-V-M @ SHM.HEIGHT @ _SHSN-POS? 0= OR IF 0 EXIT THEN
    _SHSN-V-M @ SHM.FLAGS @ DUP 3 INVERT AND IF DROP 0 EXIT THEN
    DUP SHM-F-TASKBAR-HIDDEN AND IF 3 <> IF 0 EXIT THEN ELSE DROP THEN
    _SHSN-V-M @ SHM.FLAGS @ SHM-F-TASKBAR-HIDDEN AND IF
        _SHSN-V-M @ SHM.DIVIDER-COL @ -1 <>
        _SHSN-V-M @ SHM.END-COL @ 0<> OR IF 0 EXIT THEN
    THEN
    _SHSN-V-M @ SHM.DIVIDER-COL @ DUP -1 <> IF
        _SHSN-V-M @ SHM.WIDTH @ U< 0= IF 0 EXIT THEN ELSE DROP THEN
    _SHSN-V-M @ SHM.END-COL @ _SHSN-V-M @ SHM.WIDTH @ U> IF 0 EXIT THEN
    _SHSN-V-M @ SHM.ENTRY-LIMIT @
        _SHSN-V-U @ SHM-HEADER-SIZE - SHM-ENTRY-SIZE / U> IF 0 EXIT THEN
    _SHSN-V-M @ SHM.COUNT @ _SHSN-V-M @ SHM.ENTRY-LIMIT @ U> IF 0 EXIT THEN
    _SHSN-V-M @ SHM.ENTRY-LIMIT @ SHM-ENTRY-SIZE * SHM-HEADER-SIZE + _SHSN-V-CURSOR !
    _SHSN-V-M @ SHM.COUNT @ _SHSN-V-M @ SHM-ENTRY
    _SHSN-V-M @ SHM.ENTRY-LIMIT @ _SHSN-V-M @ SHM.COUNT @ - SHM-ENTRY-SIZE *
        _SHSN-ZERO? 0= IF 0 EXIT THEN
    0 _SHSN-V-LAST-KIND ! 0 _SHSN-V-END ! 0 _SHSN-V-SELECTED !
    _SHSN-V-M @ SHM.COUNT @ 0 ?DO
        I _SHSN-V-I ! I _SHSN-V-M @ SHM-ENTRY _SHSN-V-E !
        _SHSN-V-ENTRY? 0= IF 0 UNLOOP EXIT THEN
    LOOP
    _SHSN-V-END @ _SHSN-V-M @ SHM.END-COL @ U> IF 0 EXIT THEN
    _SHSN-V-CURSOR @ _SHSN-V-U @ = ;
: SHSN-FROZEN-VALIDATE ( model bytes -- status )
    DUP SHM-HEADER-SIZE U< IF 2DROP SHSN-S-INVALID EXIT THEN
    2DUP _SHSN-SPAN? 0= IF 2DROP SHSN-S-INVALID EXIT THEN
    _SHSN-V-U ! _SHSN-V-M !
    _SHSN-FROZEN? IF SHSN-S-OK ELSE SHSN-S-INVALID THEN ;

VARIABLE _SHSN-I-S VARIABLE _SHSN-I-A VARIABLE _SHSN-I-AU
