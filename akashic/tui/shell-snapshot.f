VARIABLE _SHSN-I-QA VARIABLE _SHSN-I-QU VARIABLE _SHSN-I-INST VARIABLE _SHSN-I-DESC
: _SHSN-I-DISJOINT? ( a u -- flag )
    2DUP MSPAN-NONWRAPPING? 0= IF 2DROP 0 EXIT THEN
    _SHSN-I-QA @ _SHSN-I-QU @ MSPAN-OVERLAP? 0= ;
: _SHSN-I-AUTHORITY? ( a u -- flag )
    _SHSN-I-QU ! _SHSN-I-QA !
    _SCR-CUR @ IF
        _SHSN-I-QA @ _SHSN-I-QU @ SCR-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    THEN
    _SHSN-I-QA @ _SHSN-I-QU @ UTUI-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    _SHSN-I-QA @ _SHSN-I-QU @ UTUI-COLLECTION-STORAGE-DISJOINT?
    USCOL-S-OK <> IF DROP 0 EXIT THEN 0= IF 0 EXIT THEN
    _ASHELL-INST @ DUP 0= IF DROP -1 EXIT THEN _SHSN-I-INST !
    _SHSN-I-INST @ COMP-INST _SHSN-I-DISJOINT? 0= IF 0 EXIT THEN
    _SHSN-I-INST @ CINST.DESC @ DUP 0= IF DROP 0 EXIT THEN _SHSN-I-DESC !
    _SHSN-I-DESC @ COMP-DESC _SHSN-I-DISJOINT? 0= IF 0 EXIT THEN
    _SHSN-I-DESC @ COMP-DESC-VALID? 0= IF 0 EXIT THEN
    _SHSN-I-DESC @ DUP COMP.SIZE @ _SHSN-I-DISJOINT? 0= IF 0 EXIT THEN
    _SHSN-I-DESC @ COMP.STATE-SIZE @ DUP 0< IF DROP 0 EXIT THEN
    DUP IF _SHSN-I-INST @ CINST.STATE @ DUP 0= IF 2DROP 0 EXIT THEN
        SWAP _SHSN-I-DISJOINT? 0= IF 0 EXIT THEN ELSE DROP THEN
    _ASHELL-DESC @ ?DUP IF APP-DESC _SHSN-I-DISJOINT? 0= IF 0 EXIT THEN THEN
    ASHELL-REGION ?DUP IF RGN-SIZE _SHSN-I-DISJOINT? 0= IF 0 EXIT THEN THEN -1 ;
: _SHSN-I-SPANS? ( -- flag )
    _SHSN-I-S @ SHSN-SIZE _SHSN-I-A @ _SHSN-I-AU @ MSPAN-OVERLAP? IF 0 EXIT THEN
    _SHSN-I-S @ SHSN-SIZE _SHSN-I-B @ _SHSN-I-BU @ MSPAN-OVERLAP? IF 0 EXIT THEN
    _SHSN-I-A @ _SHSN-I-AU @ _SHSN-I-B @ _SHSN-I-BU @ MSPAN-OVERLAP? 0= ;
: SHSN-INIT ( bank-a bytes-a bank-b bytes-b source -- status )
    _SHSN-INSTALLED @ IF DROP 2DROP 2DROP SHSN-S-UNAVAILABLE EXIT THEN
    DUP SHSN-SIZE _SHSN-SPAN? 0= IF DROP 2DROP 2DROP SHSN-S-INVALID EXIT THEN
    4 PICK 4 PICK _SHSN-SPAN? 0= IF DROP 2DROP 2DROP SHSN-S-INVALID EXIT THEN
    2 PICK 2 PICK _SHSN-SPAN? 0= IF DROP 2DROP 2DROP SHSN-S-INVALID EXIT THEN
    _SHSN-I-S ! _SHSN-I-BU ! _SHSN-I-B ! _SHSN-I-AU ! _SHSN-I-A !
    _SHSN-I-AU @ SHM-HEADER-SIZE < _SHSN-I-BU @ SHM-HEADER-SIZE < OR IF SHSN-S-INVALID EXIT THEN
    _SHSN-I-SPANS? 0= IF SHSN-S-INVALID EXIT THEN
    _SHSN-I-S @ SHSN-SIZE _SHSN-I-AUTHORITY? 0= IF SHSN-S-INVALID EXIT THEN
    _SHSN-I-A @ _SHSN-I-AU @ _SHSN-I-AUTHORITY? 0= IF SHSN-S-INVALID EXIT THEN
    _SHSN-I-B @ _SHSN-I-BU @ _SHSN-I-AUTHORITY? 0= IF SHSN-S-INVALID EXIT THEN
    _SHSN-I-S @ SHSN-SIZE 0 FILL
    _SHSN-MAGIC _SHSN-I-S @ _SHSN.MAGIC !
    SHSN-SIZE _SHSN-I-S @ _SHSN.SIZE !
    _SHSN-I-S @ DUP _SHSN.SELF !
    _SHSN-I-A @ _SHSN-I-S @ _SHSN.A ! _SHSN-I-AU @ _SHSN-I-S @ _SHSN.A-U !
    _SHSN-I-B @ _SHSN-I-S @ _SHSN.B ! _SHSN-I-BU @ _SHSN-I-S @ _SHSN.B-U ! SHSN-S-OK ;

: _SHSN-BANK-CAPACITY ( bank source -- bytes|0 )
    >R DUP R@ _SHSN.A @ = IF DROP R> _SHSN.A-U @ EXIT THEN
    R@ _SHSN.B @ = IF R> _SHSN.B-U @ ELSE R> DROP 0 THEN ;
VARIABLE _SHSN-VS-S VARIABLE _SHSN-VS-CAP
: _SHSN-VS-METADATA? ( -- flag )
    _SHSN-VS-S @ _SHSN.SCREEN @ 0= _SHSN-VS-S @ _SHSN.HOST @ 0= OR
    _SHSN-VS-S @ _SHSN.BORROWED @ 0= OR _SHSN-VS-S @ _SHSN.INSTANCE @ 0= OR IF 0 EXIT THEN
    _SHSN-VS-S @ _SHSN.WIDTH @ _SHSN-POS?
    _SHSN-VS-S @ _SHSN.HEIGHT @ _SHSN-POS? AND ;
: _SHSN-SLOTS? ( source -- flag )
    _SHSN-VS-S !
    _SHSN-VS-S @ _SHSN.ACTIVE @ ?DUP IF
        _SHSN-VS-S @ _SHSN-BANK-CAPACITY DUP 0= IF DROP 0 EXIT THEN _SHSN-VS-CAP !
        _SHSN-VS-S @ _SHSN.USED @ _SHSN-VS-CAP @ U> IF 0 EXIT THEN
    ELSE
        _SHSN-VS-S @ _SHSN.USED @ IF 0 EXIT THEN
    THEN
    _SHSN-VS-S @ _SHSN.STAGED @ ?DUP IF
        DUP _SHSN-VS-S @ _SHSN.ACTIVE @ = IF DROP 0 EXIT THEN
        _SHSN-VS-S @ _SHSN-BANK-CAPACITY DUP 0= IF DROP 0 EXIT THEN _SHSN-VS-CAP !
        _SHSN-VS-S @ _SHSN.STAGED-U @ DUP SHM-HEADER-SIZE U<
        SWAP _SHSN-VS-CAP @ U> OR IF 0 EXIT THEN
        _SHSN-VS-S @ _SHSN.OPEN @ -1 <>
        _SHSN-VS-S @ _SHSN.USED @ 0<> OR IF 0 EXIT THEN
        _SHSN-VS-METADATA? 0= IF 0 EXIT THEN
    ELSE
        _SHSN-VS-S @ _SHSN.STAGED-U @ _SHSN-VS-S @ _SHSN.OPEN @ OR IF 0 EXIT THEN
    THEN
    _SHSN-VS-S @ _SHSN.USED @ ?DUP IF
        SHM-HEADER-SIZE U< IF 0 EXIT THEN
        _SHSN-VS-S @ _SHSN.DRAW @ 0= IF 0 EXIT THEN
        _SHSN-VS-METADATA? EXIT
    THEN _SHSN-VS-S @ _SHSN.DRAW @ 0= ;
: SHSN-VALID? ( source -- flag )
    DUP SHSN-SIZE _SHSN-SPAN? 0= IF DROP 0 EXIT THEN
    DUP _SHSN.MAGIC @ _SHSN-MAGIC <>
    OVER _SHSN.SIZE @ SHSN-SIZE <> OR
    OVER _SHSN.SELF @ 2 PICK <> OR IF DROP 0 EXIT THEN
    DUP _SHSN.A @ OVER _SHSN.A-U @ 2DUP _SHSN-SPAN? 0= IF 2DROP DROP 0 EXIT THEN
    DUP SHM-HEADER-SIZE < IF 2DROP DROP 0 EXIT THEN 2DROP
    DUP _SHSN.B @ OVER _SHSN.B-U @ 2DUP _SHSN-SPAN? 0= IF 2DROP DROP 0 EXIT THEN
    DUP SHM-HEADER-SIZE < IF 2DROP DROP 0 EXIT THEN 2DROP
    DUP SHSN-SIZE 2 PICK _SHSN.A @ 3 PICK _SHSN.A-U @ MSPAN-OVERLAP? IF DROP 0 EXIT THEN
    DUP SHSN-SIZE 2 PICK _SHSN.B @ 3 PICK _SHSN.B-U @ MSPAN-OVERLAP? IF DROP 0 EXIT THEN
    DUP _SHSN.A @ OVER _SHSN.A-U @ 2 PICK _SHSN.B @ 3 PICK _SHSN.B-U @
        MSPAN-OVERLAP? IF DROP 0 EXIT THEN _SHSN-SLOTS? ;
: _SHSN-INVALIDATE ( source -- )
    _SHSN.USED 96 0 FILL ;

\ One predicate protects every byte of caller source/banks against each
\ borrowed span before capture writes. Root instance state includes both
\ ordinary SHM banks; child slot, descriptor, instance, state, region and
\ saved UCTX ranges are independently checked. No opaque app pointer is read.
VARIABLE _SHSN-C-S VARIABLE _SHSN-C-M VARIABLE _SHSN-C-H
VARIABLE _SHSN-C-I VARIABLE _SHSN-C-D VARIABLE _SHSN-C-SLOT
VARIABLE _SHSN-C-LEFT VARIABLE _SHSN-C-DST VARIABLE _SHSN-C-CAP
VARIABLE _SHSN-C-R VARIABLE _SHSN-C-RLEFT
: _SHSN-OUTPUTS-DISJOINT? ( a u -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    2DUP MSPAN-NONWRAPPING? 0= IF 2DROP 0 EXIT THEN
    2DUP _SHSN-C-S @ SHSN-SIZE MSPAN-OVERLAP? IF 2DROP 0 EXIT THEN
    2DUP _SHSN-C-S @ _SHSN.A @ _SHSN-C-S @ _SHSN.A-U @ MSPAN-OVERLAP? IF 2DROP 0 EXIT THEN
    _SHSN-C-S @ _SHSN.B @ _SHSN-C-S @ _SHSN.B-U @ MSPAN-OVERLAP? 0= ;
: _SHSN-C-INSTANCE? ( instance -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP COMP-INST _SHSN-OUTPUTS-DISJOINT? 0= IF DROP 0 EXIT THEN _SHSN-C-I !
    _SHSN-C-I @ CINST.DESC @ DUP 0= IF DROP 0 EXIT THEN
    DUP COMP-DESC _SHSN-OUTPUTS-DISJOINT? 0= IF DROP 0 EXIT THEN
    DUP COMP-DESC-VALID? 0= IF DROP 0 EXIT THEN _SHSN-C-D !
    _SHSN-C-D @ DUP COMP.SIZE @ _SHSN-OUTPUTS-DISJOINT? 0= IF 0 EXIT THEN
    _SHSN-C-I @ CINST.ID @ 0= _SHSN-C-I @ CINST.GENERATION @ 0= OR IF 0 EXIT THEN
    _SHSN-C-D @ COMP.STATE-SIZE @ DUP 0< IF DROP 0 EXIT THEN
    DUP IF _SHSN-C-I @ CINST.STATE @ DUP 0= IF 2DROP 0 EXIT THEN SWAP
        _SHSN-OUTPUTS-DISJOINT? ELSE DROP -1 THEN ;
: _SHSN-C-APP? ( app-desc -- flag )
    DUP 0= IF DROP -1 EXIT THEN
    DUP APP-DESC _SHSN-OUTPUTS-DISJOINT? 0= IF DROP 0 EXIT THEN
    DUP APP-DESC-VALID? 0= IF DROP 0 EXIT THEN
    DUP APP.SIZE @ _SHSN-OUTPUTS-DISJOINT? ;
: _SHSN-C-REGION? ( region -- flag )
    _SHSN-C-R !
    _SHSN-C-S @ _SHSN.A-U @ _SHSN-C-S @ _SHSN.B-U @ MAX RGN-SIZE / _SHSN-C-RLEFT !
    BEGIN _SHSN-C-R @ WHILE
        _SHSN-C-RLEFT @ 0= IF 0 EXIT THEN -1 _SHSN-C-RLEFT +!
        _SHSN-C-R @ RGN-SIZE _SHSN-OUTPUTS-DISJOINT? 0= IF 0 EXIT THEN
        _SHSN-C-R @ _RGN-O-PARENT + @ _SHSN-C-R !
    REPEAT -1 ;
: _SHSN-C-SCREEN? ( -- flag )
    _SHSN-C-S @ SHSN-SIZE SCR-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    _SHSN-C-S @ _SHSN.A @ _SHSN-C-S @ _SHSN.A-U @ SCR-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    _SHSN-C-S @ _SHSN.B @ _SHSN-C-S @ _SHSN.B-U @ SCR-STORAGE-DISJOINT? ;
: _SHSN-C-CURRENT-SPAN? ( a u -- flag )
    2DUP UTUI-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    UTUI-COLLECTION-STORAGE-DISJOINT?
    USCOL-S-OK <> IF DROP 0 EXIT THEN ;
: _SHSN-C-CURRENT? ( -- flag )
    _SHSN-C-S @ SHSN-SIZE _SHSN-C-CURRENT-SPAN? 0= IF 0 EXIT THEN
    _SHSN-C-S @ _SHSN.A @ _SHSN-C-S @ _SHSN.A-U @ _SHSN-C-CURRENT-SPAN? 0= IF 0 EXIT THEN
    _SHSN-C-S @ _SHSN.B @ _SHSN-C-S @ _SHSN.B-U @ _SHSN-C-CURRENT-SPAN? ;
: _SHSN-C-AUTHORITY? ( -- flag )
    _SHSN-C-M @ SHM-HEADER-SIZE _SHSN-OUTPUTS-DISJOINT? 0= IF 0 EXIT THEN
    _SHSN-C-M @ SHM-VALID? 0= IF 0 EXIT THEN
    _SHSN-C-M @ DUP SHM.CAPACITY @ _SHSN-OUTPUTS-DISJOINT? 0= IF 0 EXIT THEN
    _SHSN-C-H @ AHOST-SIZE _SHSN-OUTPUTS-DISJOINT? 0= IF 0 EXIT THEN
    _SHSN-C-H @ AHOST.CONTEXT @ DUP _SHSN-PENDING-I @ <> IF DROP 0 EXIT THEN
    DUP _SHSN-C-INSTANCE? 0= IF DROP 0 EXIT THEN
    DUP CINST.ID @ _SHSN-C-M @ SHM.OWNER-ID @ <>
    SWAP CINST.GENERATION @ _SHSN-C-M @ SHM.OWNER-GEN @ <> OR IF 0 EXIT THEN
    _SHSN-C-H @ AHOST-SHELL-MODEL@ _SHSN-C-M @ <> IF 0 EXIT THEN
    _SHSN-C-S @ _SHSN.A-U @ _SHSN-C-S @ _SHSN.B-U @ MAX SHM-ENTRY-SIZE / _SHSN-C-LEFT !
    _SHSN-C-H @ AHOST.HEAD @ _SHSN-C-SLOT !
    BEGIN _SHSN-C-SLOT @ WHILE
        _SHSN-C-LEFT @ 0= IF 0 EXIT THEN -1 _SHSN-C-LEFT +!
        _SHSN-C-SLOT @ AHS-SIZE _SHSN-OUTPUTS-DISJOINT? 0= IF 0 EXIT THEN
        _SHSN-C-SLOT @ AHS.INST @ _SHSN-C-INSTANCE? 0= IF 0 EXIT THEN
        _SHSN-C-SLOT @ AHS.DESC @ _SHSN-C-APP? 0= IF 0 EXIT THEN
        _SHSN-C-SLOT @ AHS.RGN @ _SHSN-C-REGION? 0= IF 0 EXIT THEN
        _SHSN-C-SLOT @ AHS.UCTX @ ?DUP IF UCTX-TOTAL _SHSN-OUTPUTS-DISJOINT? 0= IF 0 EXIT THEN THEN
        _SHSN-C-SLOT @ AHS.UIDL-BUF @ ?DUP IF _ASHELL-UIDL-FILE-MAX _SHSN-OUTPUTS-DISJOINT? 0= IF 0 EXIT THEN THEN
        _SHSN-C-SLOT @ AHS.NEXT @ _SHSN-C-SLOT !
    REPEAT _SHSN-C-SCREEN? 0= IF 0 EXIT THEN _SHSN-C-CURRENT? ;

VARIABLE _SHSN-C-E VARIABLE _SHSN-C-FOUND VARIABLE _SHSN-C-FLAGS
: _SHSN-C-PANE? ( -- flag )
    _SHSN-C-SLOT @ AHS-VISIBLE? 0= IF 0 EXIT THEN
    _SHSN-C-SLOT @ AHS.RGN @ DUP 0= IF DROP 0 EXIT THEN _SHSN-C-R !
    _SHSN-C-E @ SHME.CONTENT-ROW @ _SHSN-C-R @ RGN-ROW <>
    _SHSN-C-E @ SHME.CONTENT-COL @ _SHSN-C-R @ RGN-COL <> OR
    _SHSN-C-E @ SHME.CONTENT-H @ _SHSN-C-R @ RGN-H <> OR
    _SHSN-C-E @ SHME.CONTENT-W @ _SHSN-C-R @ RGN-W <> OR IF 0 EXIT THEN
    _SHSN-C-E @ SHME.ROW @ _SHSN-C-E @ SHME.CONTENT-ROW @ <>
    _SHSN-C-E @ SHME.COL @ _SHSN-C-E @ SHME.CONTENT-COL @ <> OR IF 0 EXIT THEN
    _SHSN-C-E @ SHME.HEIGHT @ _SHSN-C-E @ SHME.CONTENT-H @ -
    _SHSN-C-E @ SHME.WIDTH @ _SHSN-C-E @ SHME.CONTENT-W @ -
    _SHSN-C-SLOT @ AHS-OVERLAY? IF OR 0<> ELSE 1 U> SWAP 1 U> OR THEN IF 0 EXIT THEN
    \ Every parent must contain the complete ordinary pane content.
    BEGIN _SHSN-C-R @ WHILE
        _SHSN-C-E @ SHME.CONTENT-ROW @ _SHSN-C-R @ RGN-ROW -
        _SHSN-C-E @ SHME.CONTENT-H @ _SHSN-C-R @ RGN-H _SHSN-V-AXIS? 0= IF 0 EXIT THEN
        _SHSN-C-E @ SHME.CONTENT-COL @ _SHSN-C-R @ RGN-COL -
        _SHSN-C-E @ SHME.CONTENT-W @ _SHSN-C-R @ RGN-W _SHSN-V-AXIS? 0= IF 0 EXIT THEN
        _SHSN-C-R @ _RGN-O-PARENT + @ _SHSN-C-R !
    REPEAT -1 ;
: _SHSN-C-ENTRY-LIVE? ( -- flag )
    _SHSN-C-SLOT @ AHS-CALLABLE? 0= IF 0 EXIT THEN
    _SHSN-C-SLOT @ AHS.STATE @ AHS-S-FOCUSED =
    _SHSN-C-SLOT @ _SHSN-C-H @ AHOST.FOCUS @ = <> IF 0 EXIT THEN
    _SHSN-C-SLOT @ AHS.STATE @ DUP 1 < OVER 3 > OR IF DROP 0 EXIT THEN
    DUP AHS-S-FOCUSED = IF SHM-F-SELECTED ELSE 0 THEN _SHSN-C-FLAGS !
    AHS-S-MINIMIZED = IF SHM-F-MINIMIZED _SHSN-C-FLAGS +! THEN
    _SHSN-C-E @ SHME.KIND @ SHM-K-PANE = IF
        _SHSN-C-SLOT @ AHS-OVERLAY? IF SHM-F-OVERLAY _SHSN-C-FLAGS +! THEN
        _SHSN-C-PANE? 0= IF 0 EXIT THEN
    ELSE
        _SHSN-C-SLOT @ AHS-OVERLAY? IF 0 EXIT THEN
    THEN
    _SHSN-C-FLAGS @ _SHSN-C-E @ SHME.FLAGS @ = ;
: _SHSN-C-ENTRIES? ( -- flag )
    _SHSN-C-DST @ SHM.COUNT @ 0 ?DO
        I _SHSN-C-DST @ SHM-ENTRY _SHSN-C-E !
        _SHSN-C-E @ SHME.KIND @ SHM-K-LAUNCHER <> IF
            0 _SHSN-C-FOUND ! _SHSN-C-H @ AHOST.HEAD @ _SHSN-C-SLOT !
            BEGIN _SHSN-C-SLOT @ WHILE
                _SHSN-C-SLOT @ AHS.ID @ _SHSN-C-E @ SHME.IDENTITY @ = IF
                    _SHSN-C-SLOT @ AHS.INST @ CINST.ID @ _SHSN-C-E @ SHME.OWNER-ID @ =
                    _SHSN-C-SLOT @ AHS.INST @ CINST.GENERATION @ _SHSN-C-E @ SHME.OWNER-GEN @ = AND IF
                        _SHSN-C-FOUND @ IF 0 UNLOOP EXIT THEN
                        _SHSN-C-ENTRY-LIVE? 0= IF 0 UNLOOP EXIT THEN -1 _SHSN-C-FOUND !
                    THEN
                THEN
                _SHSN-C-SLOT @ AHS.NEXT @ _SHSN-C-SLOT !
            REPEAT
            _SHSN-C-FOUND @ 0= IF 0 UNLOOP EXIT THEN
        THEN
    LOOP -1 ;

\ Only this installed source owns both callbacks. Private borrowed pointers
\ survive until the owner's mandatory null notification or uninstall; they
\ never appear inside a returned snapshot or a packed publisher candidate.
VARIABLE _SHSN-H-S VARIABLE _SHSN-H-M VARIABLE _SHSN-H-H
: _SHSN-HOST-CALL ( model host source -- )
    DUP _SHSN-INSTALLED @ <> IF DROP 2DROP EXIT THEN
    DUP SHSN-VALID? 0= IF DROP 2DROP EXIT THEN
    _SHSN-H-S ! _SHSN-H-H ! _SHSN-H-M !
    _SHSN-H-M @ 0= IF -1 _SHSN-REFUSED ! 0 _SHSN-PENDING ! EXIT THEN
    _SHSN-PENDING @ 0= IF EXIT THEN
    \ Exactly one host publication may contribute to a root transaction.
    _SHSN-PENDING @ 1 <> IF -1 _SHSN-REFUSED ! 0 _SHSN-PENDING ! EXIT THEN
    0 _SHSN-PENDING !
    _SHSN-H-S @ _SHSN-C-S ! _SHSN-H-M @ _SHSN-C-M ! _SHSN-H-H @ _SHSN-C-H !
    _SHSN-C-AUTHORITY? 0= IF EXIT THEN
    _SHSN-H-S @ _SHSN.ACTIVE @ _SHSN-H-S @ _SHSN.A @ = IF
        _SHSN-H-S @ _SHSN.B @ _SHSN-C-DST ! _SHSN-H-S @ _SHSN.B-U @
    ELSE
        _SHSN-H-S @ _SHSN.A @ _SHSN-C-DST ! _SHSN-H-S @ _SHSN.A-U @
    THEN _SHSN-C-CAP !
    _SHSN-H-M @ SHM.USED @ _SHSN-C-CAP @ U> IF EXIT THEN
    _SHSN-H-M @ _SHSN-C-DST @ _SHSN-H-M @ SHM.USED @ MOVE
    _SHSN-H-M @ SHM.USED @ _SHSN-C-DST @ SHM.CAPACITY !
    _SHSN-C-DST @ _SHSN-H-M @ SHM.USED @ SHSN-FROZEN-VALIDATE SHSN-S-OK <> IF
        _SHSN-C-DST @ _SHSN-H-M @ SHM.USED @ 0 FILL EXIT
    THEN
    _SHSN-C-DST @ SHM.WIDTH @ _SHSN-PENDING-W @ <>
    _SHSN-C-DST @ SHM.HEIGHT @ _SHSN-PENDING-H @ <> OR IF EXIT THEN
    _SHSN-C-ENTRIES? 0= IF EXIT THEN
    \ All live authority is now proved disjoint. This is the first source write.
    _SHSN-H-S @ _SHSN-INVALIDATE
    _SHSN-PENDING-SCREEN @ _SHSN-H-S @ _SHSN.SCREEN !
    _SHSN-PENDING-DRAW @ _SHSN-H-S @ _SHSN.BEFORE !
    _SHSN-PENDING-I @ _SHSN-H-S @ _SHSN.INSTANCE !
    _SHSN-PENDING-W @ _SHSN-H-S @ _SHSN.WIDTH !
    _SHSN-PENDING-H @ _SHSN-H-S @ _SHSN.HEIGHT !
    _SHSN-H-H @ _SHSN-H-S @ _SHSN.HOST !
    _SHSN-H-M @ _SHSN-H-S @ _SHSN.BORROWED !
    _SHSN-C-DST @ _SHSN-H-S @ _SHSN.STAGED !
    _SHSN-H-M @ SHM.USED @ _SHSN-H-S @ _SHSN.STAGED-U !
    -1 _SHSN-H-S @ _SHSN.OPEN ! 2 _SHSN-PENDING ! ;
VARIABLE _SHSN-D-S VARIABLE _SHSN-D-I VARIABLE _SHSN-D-P
: _SHSN-DRAW-CALL ( phase instance source -- )
    DUP _SHSN-INSTALLED @ <> IF DROP 2DROP EXIT THEN
    DUP SHSN-VALID? 0= IF DROP 2DROP EXIT THEN
    _SHSN-D-S ! _SHSN-D-I ! _SHSN-D-P !
    _SHSN-D-P @ ASHELL-DRAW-BEGIN = IF
        \ BEGIN cannot yet know the host graph. Keep all pending authority
        \ private, so an eventual alias refusal leaves caller bytes untouched.
        -1 _SHSN-REFUSED ! 0 _SHSN-PENDING !
        _SHSN-D-S @ _SHSN-C-S !
        _SCR-CUR @ 0= _SHSN-D-I @ 0= OR IF EXIT THEN
        _SHSN-D-I @ _SHSN-C-INSTANCE? 0= IF EXIT THEN
        _ASHELL-DESC @ _SHSN-C-APP? 0= IF EXIT THEN
        ASHELL-REGION _SHSN-C-REGION? 0= IF EXIT THEN
        _SHSN-C-SCREEN? 0= IF EXIT THEN
        _SHSN-C-CURRENT? 0= IF EXIT THEN
        _SCR-CUR @ _SHSN-PENDING-SCREEN !
        SCR-DRAW-GENERATION@ _SHSN-PENDING-DRAW !
        _SHSN-D-I @ _SHSN-PENDING-I !
        SCR-W _SHSN-PENDING-W ! SCR-H _SHSN-PENDING-H !
        1 _SHSN-PENDING ! EXIT
    THEN
    _SHSN-D-P @ ASHELL-DRAW-COMPLETE <> IF
        -1 _SHSN-REFUSED ! 0 _SHSN-PENDING ! EXIT
    THEN
    _SHSN-PENDING @ 2 <> IF -1 _SHSN-REFUSED ! 0 _SHSN-PENDING ! EXIT THEN
    0 _SHSN-PENDING !
    _SHSN-D-I @ _SHSN-PENDING-I @ <>
    _SCR-CUR @ _SHSN-PENDING-SCREEN @ <> OR IF EXIT THEN
    SCR-W _SHSN-PENDING-W @ <> SCR-H _SHSN-PENDING-H @ <> OR IF EXIT THEN
    _SHSN-PENDING-DRAW @ 1+ DUP 0= IF DROP 1 THEN
    SCR-DRAW-GENERATION@ <> IF EXIT THEN
    _SHSN-D-S @ _SHSN.HOST @ _SHSN-H-H @ <>
    _SHSN-D-S @ _SHSN.BORROWED @ _SHSN-H-M @ <> OR IF EXIT THEN
    _SHSN-D-S @ _SHSN.HOST @ AHOST-SHELL-MODEL@
    _SHSN-D-S @ _SHSN.BORROWED @ <> IF EXIT THEN
    _SHSN-D-S @ _SHSN.STAGED @ _SHSN-D-S @ _SHSN.ACTIVE !
    _SHSN-D-S @ _SHSN.STAGED-U @ _SHSN-D-S @ _SHSN.USED !
    SCR-DRAW-GENERATION@ _SHSN-D-S @ _SHSN.DRAW !
    0 _SHSN-D-S @ _SHSN.OPEN !
    0 _SHSN-D-S @ _SHSN.STAGED ! 0 _SHSN-D-S @ _SHSN.STAGED-U !
    0 _SHSN-REFUSED ! ;
: _SHSN-OWNS-HOOKS? ( source -- flag )
    DUP _SHSN-INSTALLED @ <> IF DROP 0 EXIT THEN
    DUP AHOST-SHELL-OBSERVER@ ROT = SWAP ['] _SHSN-HOST-CALL = AND 0= IF DROP 0 EXIT THEN
    ASHELL-DRAW-OBSERVER@ ROT = SWAP ['] _SHSN-DRAW-CALL = AND ;
: SHSN-INSTALL ( source -- status )
    DUP SHSN-VALID? 0= IF DROP SHSN-S-INVALID EXIT THEN
    DUP _SHSN-OWNS-HOOKS? IF DROP SHSN-S-OK EXIT THEN
    _SHSN-INSTALLED @ IF DROP SHSN-S-UNAVAILABLE EXIT THEN
    AHOST-SHELL-OBSERVER@ OR ASHELL-DRAW-OBSERVER@ OR OR IF DROP SHSN-S-UNAVAILABLE EXIT THEN
    DUP _SHSN-INVALIDATE DUP _SHSN-INSTALLED !
    0 _SHSN-REFUSED ! 0 _SHSN-PENDING !
    DUP ['] _SHSN-HOST-CALL SWAP AHOST-SHELL-OBSERVE!
    ['] _SHSN-DRAW-CALL SWAP ASHELL-DRAW-OBSERVE! SHSN-S-OK ;
: SHSN-UNINSTALL ( source -- status )
    DUP SHSN-VALID? 0= IF DROP SHSN-S-INVALID EXIT THEN
    DUP _SHSN-INSTALLED @ <> IF DROP SHSN-S-UNAVAILABLE EXIT THEN
    DUP AHOST-SHELL-OBSERVER@ ROT = SWAP ['] _SHSN-HOST-CALL = AND IF 0 0 AHOST-SHELL-OBSERVE! THEN
    DUP ASHELL-DRAW-OBSERVER@ ROT = SWAP ['] _SHSN-DRAW-CALL = AND IF 0 0 ASHELL-DRAW-OBSERVE! THEN
    _SHSN-REFUSED @ IF DROP ELSE _SHSN-INVALIDATE THEN
    0 _SHSN-INSTALLED ! 0 _SHSN-REFUSED ! 0 _SHSN-PENDING ! SHSN-S-OK ;
: SHSN-SNAPSHOT-FOR@ ( draw source -- model bytes status )
    DUP SHSN-VALID? 0= IF 2DROP 0 0 SHSN-S-INVALID EXIT THEN
    DUP _SHSN-OWNS-HOOKS? 0= IF 2DROP 0 0 SHSN-S-UNAVAILABLE EXIT THEN
    _SHSN-REFUSED @ IF 2DROP 0 0 SHSN-S-UNAVAILABLE EXIT THEN
    OVER 0= OVER _SHSN.DRAW @ 3 PICK <> OR
    OVER _SHSN.SCREEN @ _SCR-CUR @ <> OR
    OVER _SHSN.OPEN @ OR IF 2DROP 0 0 SHSN-S-UNAVAILABLE EXIT THEN
    OVER SCR-DRAW-GENERATION@ <> IF 2DROP 0 0 SHSN-S-UNAVAILABLE EXIT THEN
    DUP _SHSN.WIDTH @ SCR-W <> OVER _SHSN.HEIGHT @ SCR-H <> OR IF
        2DROP 0 0 SHSN-S-UNAVAILABLE EXIT
    THEN
    DUP _SHSN.HOST @ _SHSN-H-H @ <>
    OVER _SHSN.BORROWED @ _SHSN-H-M @ <> OR IF
        2DROP 0 0 SHSN-S-UNAVAILABLE EXIT
    THEN
    DUP _SHSN.HOST @ DUP 0= IF DROP 2DROP 0 0 SHSN-S-UNAVAILABLE EXIT THEN
    AHOST-SHELL-MODEL@ OVER _SHSN.BORROWED @ <> IF 2DROP 0 0 SHSN-S-UNAVAILABLE EXIT THEN
    DUP _SHSN.ACTIVE @ OVER _SHSN.USED @ SHSN-FROZEN-VALIDATE SHSN-S-OK <> IF
        2DROP 0 0 SHSN-S-INVALID EXIT
    THEN
    NIP DUP _SHSN.ACTIVE @ SWAP _SHSN.USED @ SHSN-S-OK ;

\ A publisher protects its own candidate storage against the source's full
\ A/B capacities, including the currently inactive bank. No live root or
\ child pointer needs to escape to perform this proof.
VARIABLE _SHSN-SD-S
: SHSN-SOURCE-STORAGE-DISJOINT? ( a u source -- flag )
    2 PICK 2 PICK SHSN-STORAGE-DISJOINT? 0= IF DROP 2DROP 0 EXIT THEN
    DUP SHSN-VALID? 0= IF DROP 2DROP 0 EXIT THEN _SHSN-SD-S !
    2DUP _SHSN-SD-S @ SHSN-SIZE MSPAN-OVERLAP? IF 2DROP 0 EXIT THEN
    2DUP _SHSN-SD-S @ _SHSN.A @ _SHSN-SD-S @ _SHSN.A-U @ MSPAN-OVERLAP? IF 2DROP 0 EXIT THEN
    _SHSN-SD-S @ _SHSN.B @ _SHSN-SD-S @ _SHSN.B-U @ MSPAN-OVERLAP? 0= ;

\ Final-writer fallback is deliberately separate from model validation:
\ toast/cursor/modal foreground may cover a truthful ordinary shell slot.
\ Call on the UI owner core while preparing this exact completed draw.
VARIABLE _SHSN-OR-S VARIABLE _SHSN-OR-D
VARIABLE _SHSN-OR-R VARIABLE _SHSN-OR-C VARIABLE _SHSN-OR-H VARIABLE _SHSN-OR-W
: SHSN-RECT-CLEAR? ( row col height width draw source -- clear? status )
    DUP SHSN-VALID? 0= IF 2DROP 2DROP 2DROP 0 SHSN-S-INVALID EXIT THEN
    _SHSN-OR-S ! _SHSN-OR-D !
    _SHSN-OR-W ! _SHSN-OR-H ! _SHSN-OR-C ! _SHSN-OR-R !
    _SHSN-OR-D @ _SHSN-OR-S @ SHSN-SNAPSHOT-FOR@ DUP SHSN-S-OK <> IF
        >R 2DROP 0 R> EXIT
    THEN DROP 2DROP
    _SHSN-OR-R @ _SHSN-OR-H @ SCR-H _SHSN-V-AXIS? 0=
    _SHSN-OR-C @ _SHSN-OR-W @ SCR-W _SHSN-V-AXIS? 0= OR IF
        0 SHSN-S-INVALID EXIT
    THEN
    _SHSN-OR-R @ _SHSN-OR-C @ _SHSN-OR-H @ _SHSN-OR-W @
    SCR-OCCLUSION-RECT? 0= IF DROP 0 SHSN-S-INVALID EXIT THEN
    0= SHSN-S-OK ;

\ A later publisher must also exclude the ordinary graph retained by this
\ source. Frozen A/B banks alone do not protect the host or ordinary SHM.
\ This predicate writes only module scratch, never the queried span/source.
\ Call on the UI owner core, before each new publisher construction/capture.
VARIABLE _SHSN-LD-S VARIABLE _SHSN-LD-A VARIABLE _SHSN-LD-U
VARIABLE _SHSN-LD-H VARIABLE _SHSN-LD-M VARIABLE _SHSN-LD-I
VARIABLE _SHSN-LD-D VARIABLE _SHSN-LD-APP VARIABLE _SHSN-LD-SLOT
VARIABLE _SHSN-LD-LEFT VARIABLE _SHSN-LD-R VARIABLE _SHSN-LD-RLEFT
: _SHSN-LD-DISJOINT? ( a u -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    DUP 0= IF 2DROP -1 EXIT THEN
    OVER 0= IF 2DROP 0 EXIT THEN
    2DUP MSPAN-NONWRAPPING? 0= IF 2DROP 0 EXIT THEN
    _SHSN-LD-A @ _SHSN-LD-U @ MSPAN-OVERLAP? 0= ;
: _SHSN-LD-COMP? ( descriptor -- flag )
    DUP COMP-DESC _SHSN-LD-DISJOINT? 0= IF DROP 0 EXIT THEN
    DUP COMP-DESC-VALID? 0= IF DROP 0 EXIT THEN
    DUP COMP.SIZE @ _SHSN-LD-DISJOINT? ;
: _SHSN-LD-INSTANCE? ( instance -- flag )
    DUP COMP-INST _SHSN-LD-DISJOINT? 0= IF DROP 0 EXIT THEN _SHSN-LD-I !
    _SHSN-LD-I @ CINST.DESC @ DUP _SHSN-LD-COMP? 0= IF DROP 0 EXIT THEN _SHSN-LD-D !
    _SHSN-LD-D @ COMP.STATE-SIZE @ DUP 0< IF DROP 0 EXIT THEN
    DUP IF _SHSN-LD-I @ CINST.STATE @ SWAP _SHSN-LD-DISJOINT?
    ELSE DROP -1 THEN ;
: _SHSN-LD-APP? ( descriptor|0 -- flag )
    DUP 0= IF DROP -1 EXIT THEN
    DUP APP-DESC _SHSN-LD-DISJOINT? 0= IF DROP 0 EXIT THEN _SHSN-LD-APP !
    \ APP-DESC-VALID? follows COMP-DESC; prove that header before its read.
    _SHSN-LD-APP @ APP.COMP-DESC @ _SHSN-LD-COMP? 0= IF 0 EXIT THEN
    _SHSN-LD-APP @ APP-DESC-VALID? 0= IF 0 EXIT THEN
    _SHSN-LD-APP @ DUP APP.SIZE @ _SHSN-LD-DISJOINT? ;
: _SHSN-LD-REGION? ( region|0 -- flag )
    _SHSN-LD-R !
    _SHSN-LD-S @ _SHSN.A-U @ _SHSN-LD-S @ _SHSN.B-U @ MAX RGN-SIZE / _SHSN-LD-RLEFT !
    BEGIN _SHSN-LD-R @ WHILE
        _SHSN-LD-RLEFT @ 0= IF 0 EXIT THEN -1 _SHSN-LD-RLEFT +!
        _SHSN-LD-R @ RGN-SIZE _SHSN-LD-DISJOINT? 0= IF 0 EXIT THEN
        _SHSN-LD-R @ _RGN-O-PARENT + @ _SHSN-LD-R !
    REPEAT -1 ;
: _SHSN-LD-CURRENT? ( -- flag )
    _SCR-CUR @ IF
        _SHSN-LD-A @ _SHSN-LD-U @ SCR-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    THEN
    _SHSN-LD-A @ _SHSN-LD-U @ UTUI-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    _SHSN-LD-A @ _SHSN-LD-U @ UTUI-COLLECTION-STORAGE-DISJOINT?
        USCOL-S-OK <> IF DROP 0 EXIT THEN 0= IF 0 EXIT THEN
    _ASHELL-INST @ ?DUP IF _SHSN-LD-INSTANCE? 0= IF 0 EXIT THEN THEN
    _ASHELL-DESC @ _SHSN-LD-APP? 0= IF 0 EXIT THEN
    ASHELL-REGION _SHSN-LD-REGION? ;
: _SHSN-LD-BODY? ( -- flag )
    _SHSN-LD-A @ _SHSN-LD-U @ _SHSN-LD-S @ SHSN-SOURCE-STORAGE-DISJOINT? 0= IF 0 EXIT THEN
    _SHSN-LD-CURRENT? 0= IF 0 EXIT THEN
    _SHSN-LD-S @ _SHSN.HOST @ DUP 0= IF DROP -1 EXIT THEN _SHSN-LD-H !
    \ Public source metadata cannot invent a different live pointer graph.
    _SHSN-LD-S @ _SHSN-H-S @ <>
    _SHSN-LD-H @ _SHSN-H-H @ <> OR
    _SHSN-LD-S @ _SHSN.BORROWED @ _SHSN-H-M @ <> OR IF 0 EXIT THEN
