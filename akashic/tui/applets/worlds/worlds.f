CREATE _WORLD-SNAP-DIGEST SHA3-256-LEN ALLOT

: WORLD-TELEMETRY-SNAPSHOT-SIZE  ( run -- bytes status )
    DUP WRUN-VALID? 0= IF DROP 0 WRUN-S-INVALID EXIT THEN
    WRUN.TELEMETRY-N @ DUP 0> 0= IF DROP 0 WRUN-S-INVALID EXIT THEN
    DUP 65536 _WORLD-TS-HEADER-SIZE - _WORLD-TS-SAMPLE-SIZE / > IF
        DROP 0 WRUN-S-CAPACITY EXIT
    THEN
    _WORLD-TS-SAMPLE-SIZE * _WORLD-TS-HEADER-SIZE + WRUN-S-OK ;

: _WORLD-SNAPSHOT-CONTENT-DIGEST  ( snapshot count destination -- )
    >R _WORLD-SNAP-N ! _WORLD-SNAP-A !
    SHA3-256-BEGIN
    S" org.akashic.worlds.telemetry.upper.v1" SHA3-256-ADD
    _WORLD-SNAP-A @ _WTS.CONTENT-DIGEST SHA3-256-ADD
    _WORLD-SNAP-A @ _WTS.STATE-DIGEST + SHA3-256-LEN SHA3-256-ADD
    _WORLD-SNAP-A @ _WTS.SAMPLES +
        _WORLD-SNAP-N @ _WORLD-TS-SAMPLE-SIZE * SHA3-256-ADD
    R> SHA3-256-END ;

: WORLD-TELEMETRY-SNAPSHOT  ( run destination capacity -- bytes status )
    _WORLD-SNAP-CAP ! _WORLD-SNAP-A ! _WORLD-SNAP-RUN !
    _WORLD-SNAP-RUN @ WORLD-TELEMETRY-SNAPSHOT-SIZE
    DUP IF NIP 0 SWAP EXIT THEN DROP _WORLD-SNAP-U !
    _WORLD-SNAP-A @ 0=
    _WORLD-SNAP-U @ _WORLD-SNAP-CAP @ > OR IF
        0 WRUN-S-CAPACITY EXIT
    THEN
    _WORLD-SNAP-A @ _WORLD-SNAP-U @ 0 FILL
    _WORLD-TS-MAGIC _WORLD-SNAP-A @ _WTS.MAGIC + WRUN-BE64!
    _WORLD-TS-VERSION _WORLD-SNAP-A @ _WTS.VERSION + WRUN-BE64!
    _WORLD-TS-OWNER-WORLDS _WORLD-SNAP-A @ _WTS.OWNER-KIND + WRUN-BE64!
    _WORLD-SNAP-RUN @ WRUN.RUN-ID @
        _WORLD-SNAP-A @ _WTS.RUN-ID + WRUN-BE64!
    _WORLD-SNAP-RUN @ WRUN.BRANCH-ID @
        _WORLD-SNAP-A @ _WTS.BRANCH-ID + WRUN-BE64!
    _WORLD-SNAP-RUN @ WRUN.REVISION @
        _WORLD-SNAP-A @ _WTS.REVISION + WRUN-BE64!
    _WORLD-TS-X-TICK _WORLD-SNAP-A @ _WTS.X-KIND + WRUN-BE64!
    _WORLD-TS-Y-UPPER-AMOUNT _WORLD-SNAP-A @ _WTS.Y-KIND + WRUN-BE64!
    _WORLD-TS-Y-SCALE _WORLD-SNAP-A @ _WTS.Y-SCALE + WRUN-BE64!
    _WORLD-SNAP-RUN @ WRUN.TELEMETRY-N @ DUP _WORLD-SNAP-N !
        _WORLD-SNAP-A @ _WTS.COUNT + WRUN-BE64!
    _WORLD-SNAP-RUN @ WRUN.STATE-DIGEST
        _WORLD-SNAP-A @ _WTS.STATE-DIGEST + SHA3-256-LEN CMOVE
    _WORLD-SNAP-N @ 0 DO
        I _WORLD-SNAP-RUN @ WRUN-SAMPLE@
        _WORLD-SNAP-OK ! _WORLD-SNAP-Y ! _WORLD-SNAP-X !
        _WORLD-SNAP-OK @ 0= IF 0 WRUN-S-CORRUPT UNLOOP EXIT THEN
        _WORLD-SNAP-X @ _WORLD-SNAP-A @ _WTS.SAMPLES +
            I _WORLD-TS-SAMPLE-SIZE * + WRUN-BE64!
        _WORLD-SNAP-Y @ _WORLD-SNAP-A @ _WTS.SAMPLES +
            I _WORLD-TS-SAMPLE-SIZE * + 8 + WRUN-BE64!
    LOOP
    _WORLD-SNAP-A @ _WORLD-SNAP-N @ _WORLD-SNAP-DIGEST
        _WORLD-SNAPSHOT-CONTENT-DIGEST
    _WORLD-SNAP-DIGEST _WORLD-SNAP-A @ _WTS.CONTENT-DIGEST +
        SHA3-256-LEN CMOVE
    _WORLD-SNAP-U @ WRUN-S-OK ;

