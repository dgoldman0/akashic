: WORLDS-INIT-CB  ( instance -- )
    _WORLD-ACTIVATE
    0 _WORLD-PANEL-RGN ! 0 _WORLD-JOURNAL ! 0 _WORLD-TELEMETRY !
    0 _WORLD-RUNNING ! 0 _WORLD-REPLAY-STATUS !
    WRUN-S-OK _WORLD-LAST-STATUS ! 2 _WORLD-NEXT-BRANCH !
    WRUN-RECORD-SIZE _WORLD-DEMO-HORIZON * ALLOCATE
        0<> ABORT" worlds: journal allocation failed" _WORLD-JOURNAL !
    _WORLD-DEMO-HORIZON 1+ 8 * ALLOCATE
        0<> ABORT" worlds: telemetry allocation failed" _WORLD-TELEMETRY !
    _WORLD-JOURNAL @ _WORLD-DEMO-HORIZON
        _WORLD-TELEMETRY @ _WORLD-DEMO-HORIZON 1+
        _WORLD-CHECKPOINT _WORLD-CURRENT-INSTANCE @ CINST.ID @ _WORLD-RUN
        WRUN-INIT 0<> ABORT" worlds: run initialization failed"
    S" worlds-body" UTUI-BY-ID _WORLD-E-BODY !
    _WORLD-E-BODY @ ?DUP IF
        UTUI-ELEM-RGN RGN-NEW _WORLD-PANEL-INIT
        _WORLD-PANEL _WORLD-E-BODY @ UTUI-WIDGET-SET
        _WORLD-E-BODY @ UTUI-FOCUS!
    THEN
    S" step" ['] _WORLD-DO-STEP UTUI-DO!
    S" run" ['] _WORLD-DO-RUN UTUI-DO!
    S" valve" ['] _WORLD-DO-VALVE UTUI-DO!
    S" checkpoint" ['] _WORLD-DO-CHECKPOINT UTUI-DO!
    S" branch" ['] _WORLD-DO-BRANCH UTUI-DO!
    S" replay" ['] _WORLD-DO-REPLAY UTUI-DO!
    S" analyze" ['] _WORLD-DO-ANALYZE UTUI-DO!
    S" quit" ['] _WORLD-DO-QUIT UTUI-DO! ;

