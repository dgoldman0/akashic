VARIABLE _WORLD-H-WIDGET

: _WORLD-PANEL-HANDLE  ( event widget -- consumed? )
    _WORLD-H-WIDGET !
    DUP @ KEY-T-SPECIAL = IF
        8 + @ CASE
            KEY-LEFT OF _WORLD-SET-NEXT-VALVE -1 EXIT ENDOF
            KEY-RIGHT OF _WORLD-SET-NEXT-VALVE -1 EXIT ENDOF
        ENDCASE
        0 EXIT
    THEN
    DUP @ KEY-T-CHAR = IF
        DUP 16 + @ 0= IF
            8 + @ CASE
                [CHAR] s OF _WORLD-STEP -1 EXIT ENDOF
                BL OF _WORLD-TOGGLE-RUN -1 EXIT ENDOF
                [CHAR] v OF _WORLD-SET-NEXT-VALVE -1 EXIT ENDOF
                [CHAR] c OF _WORLD-CHECKPOINT-ACTION -1 EXIT ENDOF
                [CHAR] b OF _WORLD-BRANCH-ACTION -1 EXIT ENDOF
                [CHAR] r OF _WORLD-REPLAY-ACTION -1 EXIT ENDOF
                [CHAR] a OF _WORLD-ANALYZE-ACTION -1 EXIT ENDOF
            ENDCASE
            0 EXIT
        THEN
    THEN
    DROP 0 ;

