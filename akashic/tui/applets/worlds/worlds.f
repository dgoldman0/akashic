: _WORLD-ACTIVATE  ( instance -- )
    DUP _WORLD-CURRENT-INSTANCE !
    CINST-STATE _WORLD-CURRENT-STATE ! ;

: _WORLD-STATE-FINI  ( state -- )
    _WORLD-CURRENT-STATE !
    _WORLD-JOURNAL @ ?DUP IF FREE THEN
    _WORLD-TELEMETRY @ ?DUP IF FREE THEN
    0 _WORLD-JOURNAL ! 0 _WORLD-TELEMETRY ! ;

: _WORLD-INVALIDATE  ( -- )
    _WORLD-PANEL WDG-DIRTY
    _WORLD-E-BODY @ ?DUP IF UIDL-DIRTY! THEN
    ASHELL-DIRTY! ;

: _WORLD-TOUCHED  ( -- )
    _WORLD-CURRENT-INSTANCE @ ?DUP IF CINST-TOUCH THEN
    _WORLD-INVALIDATE ;

: _WORLD-STATUS$  ( status -- address length )
    CASE
        WRUN-S-OK OF S" ready" ENDOF
        WRUN-S-INVALID OF S" invalid action refused" ENDOF
        WRUN-S-STALE OF S" stale revision refused" ENDOF
        WRUN-S-CAPACITY OF S" configured horizon full" ENDOF
        WRUN-S-NO-CHECKPOINT OF S" create a checkpoint first" ENDOF
        WRUN-S-CORRUPT OF S" replay mismatch / corrupt evidence" ENDOF
        WRUN-S-OVERFLOW OF S" revision or tick exhausted" ENDOF
        DROP S" unavailable"
    ENDCASE ;

: _WORLD-APPLY-STATUS  ( status -- )
    DUP _WORLD-LAST-STATUS !
    DUP WRUN-S-OK = IF
        DROP _WORLD-TOUCHED
    ELSE
        DUP WRUN-S-CAPACITY = IF 0 _WORLD-RUNNING ! THEN
        _WORLD-INVALIDATE DROP
    THEN ;

: _WORLD-STEP  ( -- )
    _WORLD-RUN WRUN.REVISION @ _WORLD-RUN WRUN-STEP
        _WORLD-APPLY-STATUS ;

VARIABLE _WORLD-NEXT-VALVE

: _WORLD-SET-NEXT-VALVE  ( -- )
    _WORLD-RUN WRUN.VALVE @ 250 + DUP 1000 > IF DROP 0 THEN
        _WORLD-NEXT-VALVE !
    _WORLD-NEXT-VALVE @ _WORLD-RUN WRUN.REVISION @
        _WORLD-RUN WRUN-VALVE-SET _WORLD-APPLY-STATUS ;

: _WORLD-CHECKPOINT-ACTION  ( -- )
    _WORLD-RUN WRUN.REVISION @ _WORLD-RUN WRUN-CHECKPOINT
        _WORLD-APPLY-STATUS ;

: _WORLD-BRANCH-ACTION  ( -- )
    _WORLD-NEXT-BRANCH @ _WORLD-RUN WRUN.REVISION @
        _WORLD-RUN WRUN-BRANCH
    DUP WRUN-S-OK = IF 1 _WORLD-NEXT-BRANCH +! THEN
    _WORLD-APPLY-STATUS ;

: _WORLD-REPLAY-ACTION  ( -- )
    _WORLD-REPLAY _WORLD-RUN WRUN-REPLAY
    DUP _WORLD-REPLAY-STATUS ! _WORLD-APPLY-STATUS ;

: _WORLD-TOGGLE-RUN  ( -- )
    _WORLD-RUNNING @ 0= _WORLD-RUNNING !
    MS@ _WORLD-LAST-AUTO-MS !
    WRUN-S-OK _WORLD-LAST-STATUS ! _WORLD-TOUCHED ;

