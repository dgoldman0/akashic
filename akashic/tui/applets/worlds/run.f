    _WR-CP-CHECK @ _WCP.VERSION + WRUN-BE64@
        WRUN-FORMAT-VERSION = AND
    _WR-CP-CHECK @ 192 _WR-CHECK-DIGEST SHA3-256-HASH
    _WR-CHECK-DIGEST _WR-CP-CHECK @ _WCP.DIGEST +
        SHA3-256-COMPARE AND ;

