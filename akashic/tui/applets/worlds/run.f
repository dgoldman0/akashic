    DUP WRUN-VALID? 0= IF DROP WRUN-S-INVALID EXIT THEN
    DUP _WR-PREP-RUN !
    WRUN.REVISION @ _WRUN-CELL-MAX >= IF WRUN-S-OVERFLOW EXIT THEN
    _WR-PREP-RUN @ WRUN.TICK @ _WRUN-CELL-MAX >= IF
        WRUN-S-OVERFLOW EXIT
    THEN
    _WR-PREP-RUN @ WRUN.LOWER-CAP @
        _WR-PREP-RUN @ WRUN.LOWER @ - _WR-PREP-FREE !
    _WR-PREP-RUN @ WRUN.VALVE @
