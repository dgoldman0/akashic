    _WR-EXPECTED @ _WR-ACTION-RUN @ WRUN.REVISION @ <> IF
        WRUN-S-STALE EXIT
    THEN
    _WR-ACTION-RUN @
        _WR-ACTION-RUN @ WRUN.CHECKPOINT-A @ _WR-CHECKPOINT-WRITE
    -1 _WR-ACTION-RUN @ WRUN.HAS-CHECKPOINT !
    WRUN-S-OK ;

