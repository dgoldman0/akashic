: WRUN-BE64!  ( u address -- )
    _WR-BE-A ! _WR-BE-V !
    8 0 DO
        _WR-BE-V @ 56 I 8 * - RSHIFT 0xFF AND
        _WR-BE-A @ I + C!
    LOOP ;

: WRUN-BE64@  ( address -- u )
    _WR-BE-A ! 0 _WR-BE-N !
    8 0 DO
        _WR-BE-N @ 8 LSHIFT _WR-BE-A @ I + C@ OR _WR-BE-N !
    LOOP
    _WR-BE-N @ ;

