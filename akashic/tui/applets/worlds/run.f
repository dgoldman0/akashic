        _WR-CAND-UPPER !
    _WR-PREP-RUN @ WRUN.LOWER @ _WR-CAND-ACTUAL @ +
        _WR-CAND-LOWER !
    _WR-PREP-RUN @ WRUN.VALVE @ _WR-CAND-VALVE !
    _WR-PREP-RUN @ WRUN.TICK @ 1+ _WR-CAND-TICK !
    _WR-PREP-RUN @ WRUN.REVISION @ 1+ _WR-CAND-REVISION !
