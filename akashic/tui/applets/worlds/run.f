VARIABLE _WR-REPLAY-STATUS

: _WR-REPLAY-COMMIT  ( scratch -- )
    _WR-CAND-UPPER @ OVER WRUN.UPPER !
    _WR-CAND-LOWER @ OVER WRUN.LOWER !
    _WR-CAND-VALVE @ OVER WRUN.VALVE !
    _WR-CAND-TICK @ OVER WRUN.TICK !
    _WR-CAND-REVISION @ OVER WRUN.REVISION !
    _WR-CAND-STATE-DIGEST OVER WRUN.STATE-DIGEST SHA3-256-LEN CMOVE
    _WR-CAND-JOURNAL-DIGEST SWAP WRUN.JOURNAL-DIGEST
        SHA3-256-LEN CMOVE ;

: _WR-REPLAY-ONE  ( record scratch -- flag )
    _WR-REPLAY-SCRATCH ! _WR-REPLAY-RECORD !
    _WR-REPLAY-RECORD @ _WRE.VERSION + WRUN-BE64@
        WRUN-FORMAT-VERSION <> IF 0 EXIT THEN
    _WR-REPLAY-RECORD @ WRUN-RECORD-KIND@ CASE
        WRUN-EVENT-STEP OF
            _WR-REPLAY-SCRATCH @ _WR-PREP-STEP
        ENDOF
        WRUN-EVENT-VALVE-SET OF
            _WR-REPLAY-RECORD @ WRUN-RECORD-ARGUMENT@
                _WR-REPLAY-SCRATCH @ _WR-PREP-VALVE-SET
        ENDOF
        WRUN-S-CORRUPT SWAP
    ENDCASE
    WRUN-S-OK <> IF 0 EXIT THEN
    _WR-CAND-RECORD WRUN-RECORD-SIZE
        _WR-REPLAY-RECORD @ WRUN-RECORD-SIZE
        COMPARE 0<> IF 0 EXIT THEN
    _WR-REPLAY-SCRATCH @ _WR-REPLAY-COMMIT -1 ;

: WRUN-REPLAY  ( scratch live -- status )
    _WR-REPLAY-LIVE ! _WR-REPLAY-SCRATCH !
    _WR-REPLAY-LIVE @ WRUN-VALID? 0= IF WRUN-S-INVALID EXIT THEN
    _WR-REPLAY-SCRATCH @ 0= IF WRUN-S-INVALID EXIT THEN
    _WR-REPLAY-LIVE @ WRUN.HAS-CHECKPOINT @ 0= IF
        WRUN-S-NO-CHECKPOINT EXIT
    THEN
    _WR-REPLAY-LIVE @ WRUN.CHECKPOINT-A @ DUP
        WRUN-CHECKPOINT-VALID? 0= IF DROP WRUN-S-CORRUPT EXIT THEN
    _WR-CP-A !
    _WR-REPLAY-SCRATCH @ WRUN-SIZE 0 FILL
    \ Replay uses the same candidate-transition path as live commits.  Give
    \ its session header valid borrowed bounds; replay never writes them.
    _WR-REPLAY-LIVE @ WRUN.JOURNAL-A @
        _WR-REPLAY-SCRATCH @ WRUN.JOURNAL-A !
    _WR-REPLAY-LIVE @ WRUN.JOURNAL-CAP @
        _WR-REPLAY-SCRATCH @ WRUN.JOURNAL-CAP !
    _WR-REPLAY-LIVE @ WRUN.TELEMETRY-A @
        _WR-REPLAY-SCRATCH @ WRUN.TELEMETRY-A !
    _WR-REPLAY-LIVE @ WRUN.TELEMETRY-CAP @
        _WR-REPLAY-SCRATCH @ WRUN.TELEMETRY-CAP !
    1 _WR-REPLAY-SCRATCH @ WRUN.TELEMETRY-N !
    _WR-REPLAY-LIVE @ WRUN.CHECKPOINT-A @
        _WR-REPLAY-SCRATCH @ WRUN.CHECKPOINT-A !
    _WR-CP-A @ _WCP.UPPER + WRUN-BE64@
        _WR-REPLAY-SCRATCH @ WRUN.UPPER !
    _WR-CP-A @ _WCP.UPPER-CAP + WRUN-BE64@
        _WR-REPLAY-SCRATCH @ WRUN.UPPER-CAP !
    _WR-CP-A @ _WCP.LOWER + WRUN-BE64@
        _WR-REPLAY-SCRATCH @ WRUN.LOWER !
    _WR-CP-A @ _WCP.LOWER-CAP + WRUN-BE64@
        _WR-REPLAY-SCRATCH @ WRUN.LOWER-CAP !
    _WR-CP-A @ _WCP.VALVE + WRUN-BE64@
        _WR-REPLAY-SCRATCH @ WRUN.VALVE !
    _WR-CP-A @ _WCP.TICK + WRUN-BE64@
        _WR-REPLAY-SCRATCH @ WRUN.TICK !
    1 _WR-REPLAY-SCRATCH @ WRUN.REVISION !
    _WR-REPLAY-LIVE @ WRUN.RUN-ID @
        _WR-REPLAY-SCRATCH @ WRUN.RUN-ID !
    _WR-REPLAY-LIVE @ WRUN.BRANCH-ID @
        _WR-REPLAY-SCRATCH @ WRUN.BRANCH-ID !
    _WR-CP-A @ _WCP.BRANCH-ID + WRUN-BE64@
        _WR-REPLAY-SCRATCH @ WRUN.PARENT-BRANCH-ID !
    _WR-CP-A @ _WCP.REVISION + WRUN-BE64@
        _WR-REPLAY-SCRATCH @ WRUN.PARENT-REVISION !
    _WR-REPLAY-SCRATCH @ WRUN.JOURNAL-DIGEST _WR-JOURNAL-GENESIS
    _WR-REPLAY-SCRATCH @ WRUN.UPPER @ _WR-CAND-UPPER !
    _WR-REPLAY-SCRATCH @ WRUN.LOWER @ _WR-CAND-LOWER !
    _WR-REPLAY-SCRATCH @ WRUN.VALVE @ _WR-CAND-VALVE !
    _WR-REPLAY-SCRATCH @ WRUN.TICK @ _WR-CAND-TICK !
    1 _WR-CAND-REVISION !
    _WR-REPLAY-SCRATCH @ _WR-BUILD-CANDIDATE-STATE
    _WR-CAND-STATE-DIGEST _WR-REPLAY-SCRATCH @ WRUN.STATE-DIGEST
        SHA3-256-LEN CMOVE
    WRUN-S-OK _WR-REPLAY-STATUS !
    _WR-REPLAY-LIVE @ WRUN.JOURNAL-N @ 0 ?DO
        I _WR-REPLAY-LIVE @ WRUN-RECORD@
            _WR-REPLAY-SCRATCH @ _WR-REPLAY-ONE 0= IF
            WRUN-S-CORRUPT _WR-REPLAY-STATUS ! LEAVE
        THEN
    LOOP
    _WR-REPLAY-STATUS @ IF _WR-REPLAY-STATUS @ EXIT THEN
    _WR-REPLAY-SCRATCH @ WRUN.STATE-DIGEST
        _WR-REPLAY-LIVE @ WRUN.STATE-DIGEST SHA3-256-COMPARE 0= IF
        WRUN-S-CORRUPT EXIT
    THEN
    _WR-REPLAY-SCRATCH @ WRUN.JOURNAL-DIGEST
        _WR-REPLAY-LIVE @ WRUN.JOURNAL-DIGEST SHA3-256-COMPARE 0= IF
        WRUN-S-CORRUPT EXIT
    THEN
    WRUN-S-OK ;

