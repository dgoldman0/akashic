: _SRRO-SUCCESS  ( owner -- status )
    >R
    R@ _SRRO-CLEAR-FACTS
    R@ _SRRO-CAPTURE-PROVIDER
    R@ SRRO.PROVIDER-OUTCOME @ SCONF-O-OK <>
    R@ SRRO.PROVIDER @ SCONF-RESULT-VALID? 0= OR IF
        R> _SRRO-TERMINATE-PROVIDER EXIT
    THEN
    R@ SRRO.PROVIDER @ SCONF-EFFECTIVE$
    DUP R@ SRRO.EFFECTIVE-U !
    DUP 1 < OVER OCHK-URI-MAX > OR IF
        2DROP SYNDEC-S-CAPACITY R>
        _SRRO-TERMINATE-DECODE EXIT
    THEN
    OVER 0= IF
        2DROP SYNDEC-S-INVALID R>
        _SRRO-TERMINATE-DECODE EXIT
    THEN
    2DUP MSPAN-NONWRAPPING? 0= IF
        2DROP SYNDEC-S-INVALID R>
        _SRRO-TERMINATE-DECODE EXIT
    THEN
    2DUP UTF8-VALID? 0= IF
        2DROP SYNDEC-S-INVALID R>
        _SRRO-TERMINATE-DECODE EXIT
    THEN
    R@ SRRO.EFFECTIVE SWAP MOVE
    R@ SRRO.SOURCE SSOURCE.FORMAT @
    R@ SRRO.PROVIDER @
    R@ SRRO.DECODER @
        STREAMS-SYNDICATION-DECODE
    DUP R@ SRRO.DECODE-STATUS !
    DUP SYNDEC-S-OK <> IF
        R> _SRRO-TERMINATE-DECODE EXIT
    THEN DROP
    R@ SRRO.DECODER @ STREAMS-SYNDICATION-CANDIDATES
    DUP R@ SRRO.SCRATCH-COUNT !
    SWAP R@ SRRO.SCRATCH-CANDIDATES !
    DROP
    R@ SRRO.SCRATCH-COUNT @ DUP 0<
    SWAP OCHK-BATCH-MAX > OR IF
        SYNDEC-S-CAPACITY R> _SRRO-TERMINATE-DECODE EXIT
    THEN
    R@ SRRO.SCRATCH-COUNT @ 0= IF
        0 R@ SRRO.SCRATCH-CANDIDATES !
    ELSE
        R@ SRRO.SCRATCH-CANDIDATES @ 0= IF
            SYNDEC-S-INVALID R> _SRRO-TERMINATE-DECODE EXIT
        THEN
    THEN
    R@ _SRRO-APPLY-REQUEST!
    DUP R@ SRRO.LAST-APPLY-STATUS !
    DUP STREAMS-APPLY-S-OK <> IF
        DROP
        SYNDEC-S-INVALID R> _SRRO-TERMINATE-DECODE EXIT
    THEN DROP
    -1 R@ SRRO.REVALIDATE-ARMED !
    R@ SRRO.APPLY-REQUEST
    R@ SRRO.ATTEMPT
    R@ SRRO.REPOSITORY @
    R@ SRRO.REPO-WORK @
    R@ SRRO.APPLY-WORK
        STREAMS-APPLY
    DUP R@ SRRO.LAST-APPLY-STATUS !
    DUP R@ SRRO.LAST-AUTHORITY-STATUS !
    DROP
    0 R@ SRRO.REVALIDATE-ARMED !
    R> _SRRO-APPLY-RESULT ;

