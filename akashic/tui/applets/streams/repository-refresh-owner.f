        STREAMS-APPLY-S-NOT-FOUND OF SRRO-S-STALE ENDOF
        STREAMS-APPLY-S-GONE OF SRRO-S-STALE ENDOF
        STREAMS-APPLY-S-STALE OF SRRO-S-STALE ENDOF
        STREAMS-APPLY-S-DUPLICATE OF SRRO-S-DECODE ENDOF
        STREAMS-APPLY-S-BUSY OF SRRO-S-BUSY ENDOF
        STREAMS-APPLY-S-MISMATCH OF SRRO-S-STALE ENDOF
        STREAMS-APPLY-S-STATE OF SRRO-S-BLOCKED ENDOF
        STREAMS-APPLY-S-CAPACITY OF SRRO-S-CAPACITY ENDOF
        STREAMS-APPLY-S-CLEANUP OF SRRO-S-CLEANUP ENDOF
