    R@ SRRO.SOURCE _SRRO-SOURCE-SUPPORTED? 0= IF
        R@ SRRO.SOURCE STREAMS-SOURCE-SIZE 0 FILL
        R> DROP SRRO-S-INVALID EXIT
    THEN
    R@ _SRRO-NAMESPACE!

