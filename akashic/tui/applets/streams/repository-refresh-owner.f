: _SRRO-XIO-TOPOLOGY?  ( owner -- flag )
    >R
    R@ SRRO.XIO-OP XIOO.STATE @
    CASE
        XIO-STATE-ACTIVE OF
            R@ SRRO.XIO-SERVICE @ XIOS.ACTIVE @
                R@ SRRO.XIO-OP =
            R@ SRRO.XIO-SERVICE @ XIOS.RETAINED @ 0= AND
        ENDOF
        XIO-STATE-SUCCEEDED OF
            R@ SRRO.XIO-SERVICE @ XIOS.ACTIVE @ 0=
            R@ SRRO.XIO-SERVICE @ XIOS.RETAINED @
                R@ SRRO.XIO-OP = AND
            R@ SRRO.XIO-OP XIOO.RESULT @
                R@ SRRO.PROVIDER @ = AND
        ENDOF
        XIO-STATE-FAILED OF
            R@ SRRO.XIO-SERVICE @ XIOS.ACTIVE @ 0=
            R@ SRRO.XIO-SERVICE @ XIOS.RETAINED @ 0= AND
        ENDOF
        XIO-STATE-CANCELLED OF
            R@ SRRO.XIO-SERVICE @ XIOS.ACTIVE @ 0=
            R@ SRRO.XIO-SERVICE @ XIOS.RETAINED @ 0= AND
        ENDOF
        XIO-STATE-TIMED-OUT OF
            R@ SRRO.XIO-SERVICE @ XIOS.ACTIVE @ 0=
            R@ SRRO.XIO-SERVICE @ XIOS.RETAINED @ 0= AND
        ENDOF
        XIO-STATE-RESET OF
            R@ SRRO.XIO-SERVICE @ XIOS.ACTIVE @ 0=
            R@ SRRO.XIO-SERVICE @ XIOS.RETAINED @ 0= AND
        ENDOF
        0 SWAP
    ENDCASE
    R> DROP ;

: _SRRO-BLOCK-INDETERMINATE  ( owner -- status )
    >R
    SRRO-PHASE-BLOCKED
    SRRO-S-INDETERMINATE
    SRRO-S-INDETERMINATE
    R> _SRRO-MARK ;

