  ( owner-id owner-generation owner -- changed? status )
    >R
    R@ STREAMS-REPOSITORY-REFRESH-OWNER-VALID? 0= IF
        2DROP R> DROP 0 SRRO-S-INVALID EXIT
    THEN
    DUP R@ SRRO.CURRENT-OWNER-GENERATION !
    OVER R@ SRRO.CURRENT-OWNER-ID !
    2DROP
    R@ SRRO.PHASE @ SRRO-PHASE-ACTIVE <>
    R@ SRRO.ACCEPTED @ 0= OR IF
        R> DROP 0 SRRO-S-INVALID EXIT
    THEN
    R@ _SRRO-SERVICE-OWNED? 0= IF
        R> DROP 0 SRRO-S-UNAVAILABLE EXIT
    THEN
    R@ SRRO.CURRENT-OWNER-ID @ R@ SRRO.OWNER-ID @ <>
    R@ SRRO.CURRENT-OWNER-GENERATION @
        R@ SRRO.OWNER-GENERATION @ <> OR IF
        R> DROP 0 SRRO-S-INVALID EXIT
    THEN
    R@ _SRRO-XIO-EXACT? 0= IF
        R> _SRRO-TERMINATE-STALE -1 SWAP EXIT
    THEN
    R@ _SRRO-XIO-TOPOLOGY? 0= IF
        R> _SRRO-TERMINATE-STALE -1 SWAP EXIT
    THEN
    R@ SRRO.XIO-OP XIOO.STATE @
    DUP XIO-STATE-RESET = IF
        DROP R> _SRRO-BLOCK-INDETERMINATE 0 SWAP EXIT
    THEN
    DUP XIO-STATE-FAILED =
    OVER XIO-STATE-CANCELLED = OR
    SWAP XIO-STATE-TIMED-OUT = OR IF
        R> _SRRO-TERMINATE-XIO -1 SWAP EXIT
    THEN
    R> _SRRO-TERMINATE-CANCEL -1 SWAP ;

