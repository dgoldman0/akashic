    R> DROP ;

: _SRRO-MARK-APPLY-FAILURE  ( owner -- status )
    >R
    0 R@ SRRO.ACCEPTED !
    R@ SRRO.ATTEMPT OCS.OUTCOME @ DUP OCHK-O-CLEANUP = IF
        DROP
        SRRO-PHASE-CLEANUP SRRO-S-CLEANUP
        R@ SRRO.CLEANUP-ERROR @ ?DUP
        0= IF R@ SRRO.LAST-APPLY-STATUS @ THEN
        R> _SRRO-MARK EXIT
    THEN
    DUP OCHK-O-STALE = IF
        DROP
        SRRO-PHASE-STALE SRRO-S-STALE
        R@ SRRO.LAST-APPLY-STATUS @
        R> _SRRO-MARK EXIT
    THEN
    DUP OCHK-O-CAPACITY = IF
        DROP
        SRRO-PHASE-FAILED SRRO-S-CAPACITY
        R@ SRRO.LAST-APPLY-STATUS @
        R> _SRRO-MARK EXIT
    THEN
    OCHK-O-DECODE = IF
        SRRO-PHASE-FAILED SRRO-S-DECODE
        R@ SRRO.LAST-APPLY-STATUS @
        R> _SRRO-MARK EXIT
    THEN
    SRRO-PHASE-FAILED
    R@ SRRO.LAST-APPLY-STATUS @ _SRRO-APPLY>STATUS
    R@ SRRO.LAST-APPLY-STATUS @
    R> _SRRO-MARK ;

: _SRRO-APPLY-RESULT  ( owner -- status )
    >R
    R@ SRRO.DECODER @ STREAMS-SYNDICATION-DECODER-RESET
        R@ SRRO.SCRATCH-TEMP !
    R@ SRRO.ATTEMPT OCS.STATE @
    DUP OCHK-ATTEMPT-SUCCEEDED = IF
        DROP
        0 R@ SRRO.ACCEPTED !
        R@ SRRO.SCRATCH-TEMP @ SYNDEC-S-OK <> IF
            SRRO-PHASE-CLEANUP SRRO-S-CLEANUP
            R@ SRRO.SCRATCH-TEMP @
            R> _SRRO-MARK EXIT
        THEN
        SRRO-PHASE-SUCCEEDED SRRO-S-OK 0
        R> _SRRO-MARK EXIT
    THEN
    DUP OCHK-ATTEMPT-FAILED = IF
        DROP R> _SRRO-MARK-APPLY-FAILURE EXIT
    THEN
    DROP
    R@ SRRO.CLEANUP-DONE @ 0= IF
        R@ _SRRO-RESET DROP
    THEN
    SRRO-PHASE-BLOCKED SRRO-S-BLOCKED
    R@ SRRO.CLEANUP-ERROR @ ?DUP
    0= IF R@ SRRO.LAST-APPLY-STATUS @ THEN
    R> _SRRO-MARK ;

