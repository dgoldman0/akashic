: _SRRO-FIRST-CLEANUP!  ( error owner -- )
    >R
    ?DUP IF
        R@ SRRO.CLEANUP-ERROR @ 0=
        IF R@ SRRO.CLEANUP-ERROR ! ELSE DROP THEN
    THEN
    R> DROP ;

\ RESET is also APPLY's cleanup callback.  It makes one retry after a thrown
\ wipe callback so XIO's wipe-once flag can release the retained operation.
\ The provider is poisoned on any lower cleanup error.
: _SRRO-RESET  ( owner -- cleanup-error )
    >R
    0 R@ SRRO.CLEANUP-DONE !
    0 R@ SRRO.CLEANUP-ERROR !
    R@ SRRO.XIO-OP XIOO.CLEANUP-ERROR @
        R@ _SRRO-FIRST-CLEANUP!
    R@ SRRO.PROVIDER @ SCONF-CLEANUP-ERROR@
        R@ _SRRO-FIRST-CLEANUP!
    R@ SRRO.XIO-SERVICE @ R@ SRRO.XIO-OP XIO-RESET
    DUP R@ SRRO.SCRATCH-STATUS !
    DUP XIO-S-CALLBACK = IF
        DROP
        R@ SRRO.XIO-OP XIOO.CLEANUP-ERROR @
            R@ _SRRO-FIRST-CLEANUP!
        R@ SRRO.PROVIDER @ SCONF-CLEANUP-ERROR@
            R@ _SRRO-FIRST-CLEANUP!
        R@ SRRO.XIO-SERVICE @ R@ SRRO.XIO-OP XIO-RESET
        DUP R@ SRRO.SCRATCH-STATUS !
    THEN
    DUP XIO-S-OK <> IF
        DUP R@ _SRRO-FIRST-CLEANUP!
    THEN
    DROP
    R@ SRRO.XIO-OP XIOO.CLEANUP-ERROR @
        R@ _SRRO-FIRST-CLEANUP!
    R@ SRRO.PROVIDER @ SCONF-CLEANUP-ERROR@
        R@ _SRRO-FIRST-CLEANUP!
    R@ SRRO.SCRATCH-STATUS @ XIO-S-OK =
    R@ SRRO.XIO-OP XIOO.STATE @ XIO-STATE-RESET = AND
    R@ SRRO.XIO-SERVICE @ XIO-ACTIVE? 0= AND
    R@ SRRO.XIO-SERVICE @ XIOS.RETAINED @ 0= AND IF
        R@ SRRO.XIO-OP XIO-OP-INIT
        -1 R@ SRRO.CLEANUP-DONE !
    THEN
    R@ SRRO.CLEANUP-ERROR @ DUP IF
        DUP R@ SRRO.PROVIDER @ SCONF-POISON
    THEN
    R> DROP ;

