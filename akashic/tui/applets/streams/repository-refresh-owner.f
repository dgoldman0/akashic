: _SRRO-SOURCE-SUPPORTED?  ( source -- flag )
    DUP STREAMS-SOURCE-VALID? 0= IF DROP 0 EXIT THEN
    DUP SSOURCE.KIND @ SSOURCE-KIND-SYNDICATION <> IF
        DROP 0 EXIT
    THEN
    DUP SSOURCE.FLAGS @ SSOURCE-F-ENABLED AND 0= IF
        DROP 0 EXIT
    THEN
    DUP SSOURCE.FORMAT @ DUP SSOURCE-FORMAT-AUTO =
        OVER SSOURCE-FORMAT-RSS = OR
        OVER SSOURCE-FORMAT-ATOM = OR
        SWAP SSOURCE-FORMAT-JSON-FEED = OR 0= IF
        DROP 0 EXIT
    THEN
    SSOURCE.PAGE-MAX @ 1 = ;

: STREAMS-REPOSITORY-REFRESH-SOURCE-SUPPORTED?
  ( source -- flag )
    _SRRO-SOURCE-SUPPORTED? ;

: _SRRO-SOURCE-SPAN-SAFE?  ( source owner -- flag )
    >R
    DUP 0= IF DROP R> DROP 0 EXIT THEN
    DUP STREAMS-SOURCE-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP STREAMS-SOURCE-SIZE
    R@ STREAMS-REPOSITORY-REFRESH-OWNER-SIZE
        MSPAN-OVERLAP? IF
        DROP R> DROP 0 EXIT
    THEN
    DUP STREAMS-SOURCE-SIZE
    R@ SRRO.REPOSITORY @
    R@ SRRO.REPO-WORK @
        STREAMS-REPOSITORY-SPAN-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    STREAMS-SOURCE-SIZE
    R@ SRRO.XIO-SERVICE @ XIO-SERVICE-SIZE
        MSPAN-OVERLAP? 0=
    R> DROP ;

\ Hashing a number stores the native 8-byte cell in caller-owned scratch.
\ This intentionally preserves the legacy `_SREF-HASH-N,` byte domain.
: _SRRO-HASH-N,  ( n owner -- )
    >R
    R@ SRRO.SCRATCH-TEMP !
    R@ SRRO.SCRATCH-TEMP 8 SHA3-256-ADD
    R> DROP ;

: _SRRO-HASH-$,  ( a u owner -- )
    >R
    DUP R@ _SRRO-HASH-N,
    SHA3-256-ADD
    R> DROP ;

: _SRRO-NAMESPACE!  ( owner -- )
    >R
    SHA3-256-BEGIN
    S" akashic.streams.syndication-source.v1"
        R@ _SRRO-HASH-$,
    R@ SRRO.SOURCE SSOURCE.ID SHA3-256-LEN SHA3-256-ADD
    R@ SRRO.SOURCE SSOURCE.KIND @ R@ _SRRO-HASH-N,
    R@ SRRO.SOURCE SSOURCE.FORMAT @ R@ _SRRO-HASH-N,
    R@ SRRO.SOURCE STREAMS-SOURCE-ENDPOINT$ R@ _SRRO-HASH-$,
    R@ SRRO.SOURCE STREAMS-SOURCE-CONFIG$ R@ _SRRO-HASH-$,
    R@ SRRO.SOURCE SSOURCE.REDIRECT-MAX @ R@ _SRRO-HASH-N,
    R@ SRRO.SOURCE SSOURCE.RESPONSE-MAX @ R@ _SRRO-HASH-N,
    R@ SRRO.SOURCE SSOURCE.PAGE-MAX @ R@ _SRRO-HASH-N,
    R@ SRRO.SOURCE SSOURCE.OBSERVATION-MAX @ R@ _SRRO-HASH-N,
    R@ SRRO.SOURCE SSOURCE.REVISION-MAX @ R@ _SRRO-HASH-N,
    R@ SRRO.NAMESPACE SHA3-256-END
    R> DROP ;

