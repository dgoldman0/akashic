    DUP R@ SRRO.LAST-AUTHORITY-STATUS !
    DUP SCONF-S-OK <> IF
        DUP _SRRO-SCONF>STATUS
        SWAP
        SRRO-PHASE-FAILED -ROT
        R> _SRRO-MARK EXIT
    THEN DROP
    R@ _SRRO-CURRENT-SOURCE-EXACT? 0= IF
        SRRO-PHASE-FAILED SRRO-S-STALE SCONF-S-INVALID
        R> _SRRO-MARK EXIT
    THEN
    R@ _SRRO-NAMESPACE!
    R@ SRRO.PROVIDER @ SCONF-REQUESTED$
    DUP R@ SRRO.REQUESTED-U !
    DUP 1 < OVER OCHK-URI-MAX > OR IF
        2DROP
        SRRO-PHASE-FAILED SRRO-S-CAPACITY SCONF-S-CAPACITY
        R> _SRRO-MARK EXIT
    THEN
    OVER 0= IF
        2DROP
        SRRO-PHASE-FAILED SRRO-S-INVALID SCONF-S-INVALID
        R> _SRRO-MARK EXIT
    THEN
    2DUP MSPAN-NONWRAPPING? 0= IF
        2DROP
        SRRO-PHASE-FAILED SRRO-S-INVALID SCONF-S-INVALID
        R> _SRRO-MARK EXIT
    THEN
    2DUP UTF8-VALID? 0= IF
        2DROP
        SRRO-PHASE-FAILED SRRO-S-INVALID SCONF-S-INVALID
        R> _SRRO-MARK EXIT
    THEN
    R@ SRRO.REQUESTED SWAP MOVE

    R@ _SRRO-BEGIN-REQUEST!
    DUP R@ SRRO.LAST-ACQUISITION-STATUS !
    DUP R@ SRRO.LAST-AUTHORITY-STATUS !
    DUP IF
        DUP _SRRO-ACQUISITION>STATUS
        SWAP
        SRRO-PHASE-FAILED -ROT
        R> _SRRO-MARK EXIT
    THEN DROP
    R@ SRRO.BEGIN-REQUEST
    R@ SRRO.ATTEMPT
    R@ SRRO.REPOSITORY @
    R@ SRRO.REPO-WORK @
    R@ SRRO.ACQUISITION-WORK
        STREAMS-ACQUISITION-BEGIN
    DUP R@ SRRO.LAST-ACQUISITION-STATUS !
    DUP R@ SRRO.LAST-AUTHORITY-STATUS !
    DUP IF
        DUP _SRRO-ACQUISITION>STATUS
        SWAP
        SRRO-PHASE-FAILED -ROT
        R> _SRRO-MARK EXIT
    THEN DROP

    -1 R@ SRRO.ACCEPTED !
    -1 R@ SRRO.ATTEMPT-PRESENT !
    R@ SRRO.CURRENT-OWNER-ID @ R@ SRRO.OWNER-ID !
    R@ SRRO.CURRENT-OWNER-GENERATION @
        R@ SRRO.OWNER-GENERATION !
    R@ SRRO.REQUEST-GENERATION @ 1+
        R@ SRRO.REQUEST-GENERATION !
    R@ _SRRO-ACCEPTED-EXACT? 0= IF
        R@ _SRRO-CLEAR-FACTS
        OCHK-ATTEMPT-INDETERMINATE OCHK-O-INDETERMINATE
        SRRO-PHASE-BLOCKED SRRO-S-INDETERMINATE
        R@ _SRRO-TERMINAL-SPEC!
        R> _SRRO-TERMINALIZE EXIT
    THEN

    R@ SRRO.XIO-SERVICE @
    R@ SRRO.OWNER-ID @
    R@ SRRO.OWNER-GENERATION @
    R@ SRRO.REQUEST-GENERATION @
    MS@ STREAMS-REPOSITORY-REFRESH-TIMEOUT-MS +
    R@ SRRO.PROVIDER @
    ['] SCONF-XIO-START
    ['] SCONF-XIO-POLL
    ['] SCONF-XIO-CANCEL
    ['] SCONF-XIO-WIPE
    R@ SRRO.XIO-OP XIO-OP-CONFIGURE
    DUP R@ SRRO.SCRATCH-STATUS !
    DUP XIO-S-OK <> IF
        R> _SRRO-START-TERMINAL EXIT
    THEN DROP
    R@ SRRO.XIO-SERVICE @ R@ SRRO.XIO-OP XIO-SUBMIT
    DUP R@ SRRO.SCRATCH-STATUS !
    DUP XIO-S-OK <> IF
        R> _SRRO-START-TERMINAL EXIT
