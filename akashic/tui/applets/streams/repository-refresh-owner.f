: STREAMS-REPOSITORY-REFRESH-OWNER-RELEASE  ( owner -- status )
    DUP STREAMS-REPOSITORY-REFRESH-OWNER-VALID? 0= IF
        DROP SRRO-S-INVALID EXIT
    THEN
    >R
    SRRO-S-OK R@ SRRO.SCRATCH-STATUS !
    R@ SRRO.ACCEPTED @ IF
        R@ SRRO.PHASE @ SRRO-PHASE-BLOCKED = IF
            R@ SRRO.LAST-STATUS @ SRRO-S-INDETERMINATE = IF
                R> _SRRO-BLOCK-INDETERMINATE EXIT
            THEN
            R@ _SRRO-TERMINALIZE
        ELSE
            R@ _SRRO-SERVICE-OWNED? 0= IF
                R> DROP SRRO-S-UNAVAILABLE EXIT
            THEN
            R@ _SRRO-XIO-TOPOLOGY? 0= IF
                R> _SRRO-BLOCK-INDETERMINATE EXIT
            THEN
            R@ SRRO.XIO-OP XIOO.STATE @
            DUP XIO-STATE-RESET = IF
                DROP R> _SRRO-BLOCK-INDETERMINATE EXIT
            THEN
            DUP XIO-STATE-FAILED =
            OVER XIO-STATE-CANCELLED = OR
            SWAP XIO-STATE-TIMED-OUT = OR IF
                R@ _SRRO-TERMINATE-XIO
            ELSE
                R@ _SRRO-TERMINATE-CANCEL
            THEN
        THEN
        DUP SRRO-S-CLEANUP =
        OVER SRRO-S-BLOCKED = OR
        OVER SRRO-S-REPOSITORY = OR IF
            R@ SRRO.SCRATCH-STATUS !
        ELSE
            DROP
        THEN
    ELSE
        R@ SRRO.XIO-OP XIOO.STATE @ XIO-STATE-RESET <> IF
            R@ _SRRO-CLEAR-FACTS
            R@ _SRRO-CANCEL-ACTIVE
            R@ _SRRO-RESET ?DUP IF
                DROP SRRO-S-CLEANUP R@ SRRO.SCRATCH-STATUS !
            THEN
        THEN
    THEN
    R@ SRRO.PROVIDER @ ?DUP IF
        DUP SCONF-RELEASABLE? 0= IF
            DROP
            SRRO-PHASE-CLEANUP SRRO-S-CLEANUP
            R@ SRRO.CLEANUP-ERROR @
            R> _SRRO-MARK EXIT
        THEN
        SCONF-RELEASE
        DUP SCONF-S-OK <> IF
            SRRO-PHASE-CLEANUP SRRO-S-CLEANUP ROT
            R> _SRRO-MARK EXIT
        THEN
        DROP
    THEN
    0 R@ SRRO.PROVIDER !
    R@ SRRO.DECODER @ STREAMS-SYNDICATION-DECODER-FREE
    DUP SYNDEC-S-OK <> IF
        R@ STREAMS-REPOSITORY-REFRESH-OWNER-SIZE 0 FILL
        R> DROP
        DROP SRRO-S-CLEANUP EXIT
    THEN
    DROP
    0 R@ SRRO.DECODER !
    R@ SRRO.SCRATCH-STATUS @
    R@ STREAMS-REPOSITORY-REFRESH-OWNER-SIZE 0 FILL
    R> DROP ;
