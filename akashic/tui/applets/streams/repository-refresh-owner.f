: STREAMS-REPOSITORY-REFRESH-OWNER-TICK
  ( current-source|0 owner-id owner-generation owner -- changed? status )
    >R
    R@ STREAMS-REPOSITORY-REFRESH-OWNER-VALID? 0= IF
        _SRRO-DROP3 R> DROP 0 SRRO-S-INVALID EXIT
    THEN
    DUP R@ SRRO.CURRENT-OWNER-GENERATION !
    OVER R@ SRRO.CURRENT-OWNER-ID !
    2 PICK R@ SRRO.CURRENT-SOURCE !
    _SRRO-DROP3
    R@ SRRO.PHASE @ SRRO-PHASE-ACTIVE <> IF
        R> DROP 0 SRRO-S-OK EXIT
    THEN
    R@ SRRO.ACCEPTED @ 0= IF
        R> DROP 0 SRRO-S-BLOCKED EXIT
    THEN
    R@ _SRRO-SERVICE-OWNED? 0= IF
        R> DROP 0 SRRO-S-UNAVAILABLE EXIT
    THEN
    R@ SRRO.CURRENT-OWNER-ID @ R@ SRRO.OWNER-ID @ <> IF
        R> DROP 0 SRRO-S-INVALID EXIT
    THEN
    R@ SRRO.CURRENT-OWNER-GENERATION @
    R@ SRRO.OWNER-GENERATION @ <> IF
        R> _SRRO-TERMINATE-STALE -1 SWAP EXIT
    THEN
    R@ _SRRO-CURRENT-SOURCE-EXACT? 0=
    R@ _SRRO-XIO-EXACT? 0= OR IF
        R> _SRRO-TERMINATE-STALE -1 SWAP EXIT
    THEN
    R@ _SRRO-XIO-TOPOLOGY? 0= IF
        R> _SRRO-TERMINATE-STALE -1 SWAP EXIT
    THEN
    R@ SRRO.XIO-OP XIOO.STATE @
    DUP XIO-STATE-ACTIVE = IF
        DROP
        R> DROP 0 SRRO-S-OK EXIT
    THEN
    DUP XIO-STATE-SUCCEEDED = IF
        DROP
        R> _SRRO-SUCCESS -1 SWAP EXIT
    THEN
    DUP XIO-STATE-RESET = IF
        DROP
        R> _SRRO-BLOCK-INDETERMINATE 0 SWAP EXIT
    THEN
    DROP
    R> _SRRO-TERMINATE-XIO -1 SWAP ;

