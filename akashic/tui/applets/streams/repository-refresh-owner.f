\ Publish the terminal specification already stored in SCRATCH fields.
\ ACCEPTED remains set on a lower failure so boot recovery retains authority.
: _SRRO-TERMINALIZE  ( owner -- status )
    >R
    R@ SRRO.TERMINAL-REQUEST
        STREAMS-ACQUISITION-TERMINAL-REQUEST-INIT
    DUP IF
        DUP R@ SRRO.LAST-ACQUISITION-STATUS !
        DUP R@ SRRO.LAST-AUTHORITY-STATUS !
        DROP
        SRRO-PHASE-BLOCKED SRRO-S-BLOCKED SRRO-S-INVALID
        R> _SRRO-MARK EXIT
    THEN DROP
    R@ SRRO.ATTEMPT OCS.SOURCE-ID
        R@ SRRO.TERMINAL-REQUEST SATR.SOURCE-ID RID-COPY
    R@ SRRO.ATTEMPT OCS.SOURCE-REVISION @
        R@ SRRO.TERMINAL-REQUEST SATR.SOURCE-REVISION !
    R@ SRRO.ATTEMPT OCS.ATTEMPT-ID
        R@ SRRO.TERMINAL-REQUEST SATR.ATTEMPT-ID RID-COPY
    R@ SRRO.ATTEMPT OCS.REQUEST-SEAL
        R@ SRRO.TERMINAL-REQUEST SATR.REQUEST-SEAL RID-COPY
    R@ SRRO.SCRATCH-STATE @
        R@ SRRO.TERMINAL-REQUEST SATR.FACTS SACQF.STATE !
    R@ SRRO.SCRATCH-OUTCOME @
        R@ SRRO.TERMINAL-REQUEST SATR.FACTS SACQF.OUTCOME !
    R@ _SRRO-FINISHED-MS
        R@ SRRO.TERMINAL-REQUEST SATR.FACTS SACQF.FINISHED-MS !
    R@ SRRO.DETAIL @
        R@ SRRO.TERMINAL-REQUEST SATR.FACTS SACQF.DETAIL !
    R@ SRRO.HTTP-STATUS @
        R@ SRRO.TERMINAL-REQUEST SATR.FACTS SACQF.HTTP-STATUS !
    R@ SRRO.DECODE-STATUS @
        R@ SRRO.TERMINAL-REQUEST SATR.FACTS SACQF.DECODE-STATUS !
    R@ SRRO.XIO-ERROR @
        R@ SRRO.TERMINAL-REQUEST SATR.FACTS SACQF.XIO-ERROR !
    R@ SRRO.CLEANUP-ERROR @
        R@ SRRO.TERMINAL-REQUEST SATR.FACTS SACQF.CLEANUP-ERROR !
    R@ SRRO.TERMINAL-REQUEST
    R@ SRRO.ATTEMPT
    R@ SRRO.REPOSITORY @
    R@ SRRO.REPO-WORK @
    R@ SRRO.ACQUISITION-WORK
        STREAMS-ACQUISITION-TERMINAL
    DUP R@ SRRO.LAST-ACQUISITION-STATUS !
    DUP R@ SRRO.LAST-AUTHORITY-STATUS !
    DUP IF
        DROP
        SRRO-PHASE-BLOCKED SRRO-S-BLOCKED
        R@ SRRO.LAST-ACQUISITION-STATUS @
        R> _SRRO-MARK EXIT
    THEN DROP
    0 R@ SRRO.ACCEPTED !
    R@ SRRO.SCRATCH-PHASE @
    R@ SRRO.SCRATCH-OWNER-STATUS @
    R@ _SRRO-TERMINAL-ERROR
    R> _SRRO-MARK ;

