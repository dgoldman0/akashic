: _SRRO-REPOSITORY-USABLE?  ( owner -- flag )
    >R
    R@ SRRO.REPOSITORY @ DUP STREAMS-REPOSITORY-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP STREAMS-REPOSITORY-LOADED? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP STREAMS-REPOSITORY-PROVISIONED? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    STREAMS-REPOSITORY-BLOCKED? IF
        R> DROP 0 EXIT
    THEN
    R@ SRRO.REPO-WORK @ DUP STREAMS-REPOSITORY-WORK-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R@ SRRO.REPOSITORY @ OVER
        STREAMS-REPOSITORY-WORK-BOUND? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP STREAMS-REPOSITORY-WORK-BUSY? IF
        DROP R> DROP 0 EXIT
    THEN
    DUP STREAMS-REPOSITORY-ACTIVE? IF
        DROP R> DROP 0 EXIT
    THEN
    DUP STREAMS-REPOSITORY-REOPEN-REQUIRED? IF
        DROP R> DROP 0 EXIT
    THEN
    STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF DROP R> DROP 0 EXIT THEN
    STREAMS-AUTHORITY-ROOT-HEADER-VALID?
    R> DROP ;

: _SRRO-BOOT-RECOVERED?  ( owner -- flag )
    DUP _SRRO-REPOSITORY-USABLE? 0= IF DROP 0 EXIT THEN
    SRRO.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF DROP 0 EXIT THEN
    SAR.ACTIVE-COUNT @ 0= ;

: STREAMS-REPOSITORY-REFRESH-OWNER-VALID?  ( owner -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-REPOSITORY-REFRESH-OWNER-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP SRRO.MAGIC @ _SRRO-MAGIC <> IF DROP 0 EXIT THEN
    DUP SRRO.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP SRRO.PHASE @ DUP SRRO-PHASE-OFFLINE <
        SWAP SRRO-PHASE-CLEANUP > OR IF DROP 0 EXIT THEN
    DUP SRRO.XIO-OP XIO-OP-VALID? 0= IF DROP 0 EXIT THEN
    DUP SRRO.ACQUISITION-WORK
        STREAMS-ACQUISITION-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP SRRO.APPLY-WORK
        STREAMS-APPLY-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP SRRO.PROVIDER @ DUP 0<> IF
        SCONF-VALID?
    ELSE
        DROP 0
    THEN 0= IF DROP 0 EXIT THEN
    DUP SRRO.DECODER @ DUP 0<> IF
        STREAMS-SYNDICATION-DECODER-VALID?
    ELSE
        DROP 0
    THEN 0= IF DROP 0 EXIT THEN
    DUP SRRO.REPOSITORY @ OVER SRRO.REPO-WORK @
        STREAMS-REPOSITORY-WORK-BOUND? 0= IF DROP 0 EXIT THEN
    DUP STREAMS-REPOSITORY-REFRESH-OWNER-SIZE
    2 PICK SRRO.REPOSITORY @
    3 PICK SRRO.REPO-WORK @
        STREAMS-REPOSITORY-SPAN-DISJOINT?
    NIP ;

: STREAMS-REPOSITORY-REFRESH-OWNER-AVAILABLE?  ( owner -- flag )
    DUP STREAMS-REPOSITORY-REFRESH-OWNER-VALID? 0= IF
        DROP 0 EXIT
    THEN
    DUP SRRO.PHASE @ DUP SRRO-PHASE-BLOCKED <>
        SWAP SRRO-PHASE-CLEANUP <> AND 0= IF
        DROP 0 EXIT
    THEN
    DUP _SRRO-REPOSITORY-USABLE? 0= IF DROP 0 EXIT THEN
    DUP SRRO.XIO-SERVICE @ DUP XIO-SERVICE-BOUND? 0= IF
        DROP DROP 0 EXIT
    THEN
    XIO-SERVICE-OWNER? 0= IF DROP 0 EXIT THEN
    SRRO.PROVIDER @ SCONF-CLEANUP-ERROR@ 0= ;

