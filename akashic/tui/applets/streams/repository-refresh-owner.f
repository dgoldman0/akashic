        R> DROP SRRO-S-BLOCKED EXIT
    THEN
    R@ SRRO.PHASE @ SRRO-PHASE-CLEANUP = IF
        R> DROP SRRO-S-CLEANUP EXIT
    THEN
    R@ SRRO.PHASE @ SRRO-PHASE-ACTIVE =
    R@ SRRO.ACCEPTED @ 0<> OR IF
        R> DROP SRRO-S-BUSY EXIT
    THEN
    R@ STREAMS-REPOSITORY-REFRESH-OWNER-AVAILABLE? 0= IF
        R> DROP SRRO-S-UNAVAILABLE EXIT
    THEN
    R@ SRRO.CURRENT-OWNER-ID @ 0=
    R@ SRRO.CURRENT-OWNER-GENERATION @ 0> 0= OR IF
        R> DROP SRRO-S-INVALID EXIT
    THEN
    R@ SRRO.CURRENT-SOURCE @ DUP 0= IF
        DROP R> DROP SRRO-S-INVALID EXIT
    THEN
    DUP R@ _SRRO-SOURCE-SPAN-SAFE? 0= IF
        DROP R> DROP SRRO-S-INVALID EXIT
    THEN
    DUP _SRRO-SOURCE-SUPPORTED? 0= IF
        DROP R> DROP SRRO-S-INVALID EXIT
    THEN
    DROP
    R@ SRRO.XIO-OP XIOO.STATE @ XIO-STATE-RESET <> IF
        R> DROP SRRO-S-BUSY EXIT
    THEN
    R@ SRRO.XIO-SERVICE @ XIO-ACTIVE?
    R@ SRRO.XIO-SERVICE @ XIOS.RETAINED @ 0<> OR IF
        R> DROP SRRO-S-BUSY EXIT
    THEN
