    R@ 0= IF DROP R> DROP 0 EXIT THEN
    R@ SRRO.MAGIC @ _SRRO-MAGIC <> IF DROP R> DROP 0 EXIT THEN
    R@ SRRO.SELF @ R@ <> IF DROP R> DROP 0 EXIT THEN
    R@ SRRO.REVALIDATE-ARMED @ 0= IF DROP R> DROP 0 EXIT THEN
    R@ SRRO.CLEANUP-DONE @ 0= IF DROP R> DROP 0 EXIT THEN
    R@ SRRO.PHASE @ SRRO-PHASE-ACTIVE <> IF
        DROP R> DROP 0 EXIT
    THEN
    R@ SRRO.ACCEPTED @ 0= IF DROP R> DROP 0 EXIT THEN
    R@ SRRO.CURRENT-OWNER-ID @ R@ SRRO.OWNER-ID @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    R@ SRRO.CURRENT-OWNER-GENERATION @
    R@ SRRO.OWNER-GENERATION @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _SRRO-CURRENT-SOURCE-EXACT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _SRRO-NAMESPACE!
    R@ SRRO.NAMESPACE
    R@ SRRO.ATTEMPT OCS.NAMESPACE RID= 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SAPAR.COMPONENT-INSTANCE @ R@ SRRO.OWNER-ID @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SAPAR.COMPONENT-GENERATION @
    R@ SRRO.OWNER-GENERATION @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SAPAR.REQUEST-GENERATION @
    R@ SRRO.REQUEST-GENERATION @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SAPAR.SOURCE-ID
    R@ SRRO.ATTEMPT OCS.SOURCE-ID RID= 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SAPAR.SOURCE-REVISION @
    R@ SRRO.ATTEMPT OCS.SOURCE-REVISION @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SAPAR.ATTEMPT-ID
    R@ SRRO.ATTEMPT OCS.ATTEMPT-ID RID= 0= IF
        DROP R> DROP 0 EXIT
    THEN
    SAPAR.REQUEST-SEAL
    R@ SRRO.ATTEMPT OCS.REQUEST-SEAL RID= 0= IF
        R> DROP 0 EXIT
    THEN
    R@ SRRO.XIO-OP XIOO.STATE @ XIO-STATE-RESET <> IF
        R> DROP 0 EXIT
    THEN
    R@ SRRO.XIO-SERVICE @ DUP XIO-SERVICE-BOUND? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    XIO-SERVICE-OWNER? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ SRRO.XIO-SERVICE @ XIO-ACTIVE? IF
        R> DROP 0 EXIT
    THEN
    R@ SRRO.XIO-SERVICE @ XIOS.RETAINED @ 0=
    R> DROP ;

: _SRRO-APPLY-REQUEST!  ( owner -- status )
    >R
    R@ SRRO.APPLY-REQUEST STREAMS-APPLY-REQUEST-INIT
    DUP IF R> DROP EXIT THEN DROP
    R@ SRRO.ATTEMPT OCS.SOURCE-ID
        R@ SRRO.APPLY-REQUEST SAPAR.SOURCE-ID RID-COPY
    R@ SRRO.ATTEMPT OCS.SOURCE-REVISION @
        R@ SRRO.APPLY-REQUEST SAPAR.SOURCE-REVISION !
    R@ SRRO.ATTEMPT OCS.ATTEMPT-ID
        R@ SRRO.APPLY-REQUEST SAPAR.ATTEMPT-ID RID-COPY
    R@ SRRO.ATTEMPT OCS.REQUEST-SEAL
        R@ SRRO.APPLY-REQUEST SAPAR.REQUEST-SEAL RID-COPY
    R@ SRRO.OWNER-ID @
        R@ SRRO.APPLY-REQUEST SAPAR.COMPONENT-INSTANCE !
    R@ SRRO.OWNER-GENERATION @
        R@ SRRO.APPLY-REQUEST SAPAR.COMPONENT-GENERATION !
    R@ SRRO.REQUEST-GENERATION @
        R@ SRRO.APPLY-REQUEST SAPAR.REQUEST-GENERATION !
    R@ SRRO.EFFECTIVE
        R@ SRRO.APPLY-REQUEST SAPAR.EFFECTIVE-A !
    R@ SRRO.EFFECTIVE-U @
        R@ SRRO.APPLY-REQUEST SAPAR.EFFECTIVE-U !
    R@ SRRO.SCRATCH-CANDIDATES @
        R@ SRRO.APPLY-REQUEST SAPAR.CANDIDATES-A !
    R@ SRRO.SCRATCH-COUNT @
        R@ SRRO.APPLY-REQUEST SAPAR.CANDIDATE-COUNT !
    R@ _SRRO-FINISHED-MS
        R@ SRRO.APPLY-REQUEST SAPAR.FINISHED-MS !
    R@ SRRO.DETAIL @
        R@ SRRO.APPLY-REQUEST SAPAR.DETAIL !
    R@ SRRO.HTTP-STATUS @
        R@ SRRO.APPLY-REQUEST SAPAR.HTTP-STATUS !
    SYNDEC-S-OK
        R@ SRRO.APPLY-REQUEST SAPAR.DECODE-STATUS !
    ['] _SRRO-APPLY-CLEANUP
        R@ SRRO.APPLY-REQUEST SAPAR.CLEANUP-XT !
