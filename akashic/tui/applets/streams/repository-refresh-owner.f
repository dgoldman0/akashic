\ =====================================================================
\ repository-refresh-owner.f - repository-backed configured refresh
\ =====================================================================
\ This owner is the L13 runtime composition for one explicit configured
\ syndication refresh.  It coordinates one exact source snapshot, one
\ configured provider, Desk's serialized XIO service, bounded syndication
\ decode, durable acquisition acceptance/non-success, and atomic repository
\ application.  It owns no repository lifecycle, scheduler, Library document,
\ draft, output, search, or public-Bluesky policy.
\
\ The caller owns one fixed descriptor.  The descriptor embeds the XIO
\ operation, all exact request/evidence buffers, and both authority work
\ areas.  Only the configured-provider factory and syndication-decoder
\ factory allocate, under their existing bounded ownership contracts.
\
\ INIT is deliberately post-boot: the external repository owner must have
\ opened/provisioned the repository and completed acquisition recovery first.
\ INIT proves that no accepted attempt remains before it allocates a decoder
\ or provider.  RELEASE never closes, aborts, or releases the repository.
\
\ Public lifecycle:
\   STREAMS-REPOSITORY-REFRESH-OWNER-INIT
\     ( xio-service configured-factory-xt repository repo-work owner
\       -- status )
\   STREAMS-REPOSITORY-REFRESH-OWNER-START
\     ( exact-source owner-id owner-generation owner -- status )
\   STREAMS-REPOSITORY-REFRESH-OWNER-TICK
\     ( current-source|0 owner-id owner-generation owner
\       -- changed? status )
\   STREAMS-REPOSITORY-REFRESH-OWNER-CANCEL
\     ( owner-id owner-generation owner -- changed? status )
\   STREAMS-REPOSITORY-REFRESH-OWNER-RELEASE
\     ( owner -- status )
\
\ START performs provider CONFIGURE and canonical requested-URI freezing
\ before durable BEGIN.  No XIO operation is configured or submitted until
\ BEGIN has published ACCEPTED.  On successful XIO, APPLY stages decoded
\ candidates, calls this owner's cleanup/reset callback, revalidates the
\ exact runtime evidence, and publishes success atomically.
\ =====================================================================

\ Keep the module identity within KDOS's 23-byte bound.
