: _SRRO-PARTIAL-RELEASE  ( owner -- )
    >R
    R@ SRRO.PROVIDER @ ?DUP IF
        DUP SCONF-VALID? IF
            DUP SCONF-RELEASABLE?
            IF SCONF-RELEASE DROP ELSE DROP THEN
        ELSE
            DROP
        THEN
    THEN
    R@ SRRO.DECODER @ ?DUP IF
        STREAMS-SYNDICATION-DECODER-FREE DROP
    THEN
    R@ STREAMS-REPOSITORY-REFRESH-OWNER-SIZE 0 FILL
    R> DROP ;

: STREAMS-REPOSITORY-REFRESH-OWNER-INIT
  ( xio-service configured-factory-xt repository repo-work owner -- status )
    >R
    R@ 0= IF
        _SRRO-DROP4 R> DROP SRRO-S-INVALID EXIT
    THEN
    R@ STREAMS-REPOSITORY-REFRESH-OWNER-SIZE
        MSPAN-NONWRAPPING? 0= IF
        _SRRO-DROP4 R> DROP SRRO-S-INVALID EXIT
    THEN
    R@ SRRO.MAGIC @ _SRRO-MAGIC = IF
        _SRRO-DROP4 R> DROP SRRO-S-BUSY EXIT
    THEN
    3 PICK DUP 0= IF
        DROP _SRRO-DROP4 R> DROP SRRO-S-INVALID EXIT
    THEN
    DUP XIO-SERVICE-BOUND? 0= IF
        DROP _SRRO-DROP4 R> DROP SRRO-S-UNAVAILABLE EXIT
    THEN
    XIO-SERVICE-OWNER? 0= IF
        _SRRO-DROP4 R> DROP SRRO-S-UNAVAILABLE EXIT
    THEN
    2 PICK 0= IF
        _SRRO-DROP4 R> DROP SRRO-S-INVALID EXIT
    THEN
    2DUP STREAMS-REPOSITORY-WORK-BOUND? 0= IF
        _SRRO-DROP4 R> DROP SRRO-S-INVALID EXIT
    THEN
    R@ STREAMS-REPOSITORY-REFRESH-OWNER-SIZE
    3 PICK 3 PICK STREAMS-REPOSITORY-SPAN-DISJOINT? 0= IF
        _SRRO-DROP4 R> DROP SRRO-S-INVALID EXIT
    THEN
    R@ STREAMS-REPOSITORY-REFRESH-OWNER-SIZE
    5 PICK XIO-SERVICE-SIZE MSPAN-OVERLAP? IF
        _SRRO-DROP4 R> DROP SRRO-S-INVALID EXIT
    THEN

    R@ STREAMS-REPOSITORY-REFRESH-OWNER-SIZE 0 FILL
    3 PICK R@ SRRO.XIO-SERVICE !
    2 PICK R@ SRRO.FACTORY-XT !
    OVER R@ SRRO.REPOSITORY !
    DUP R@ SRRO.REPO-WORK !
    _SRRO-DROP4
    R@ SRRO.XIO-OP XIO-OP-INIT
    R@ SRRO.ACQUISITION-WORK STREAMS-ACQUISITION-WORK-INIT
    DUP IF
        DROP R@ _SRRO-PARTIAL-RELEASE
        R> DROP SRRO-S-INVALID EXIT
    THEN DROP
    R@ SRRO.APPLY-WORK STREAMS-APPLY-WORK-INIT
    DUP IF
        DROP R@ _SRRO-PARTIAL-RELEASE
        R> DROP SRRO-S-INVALID EXIT
    THEN DROP
    R@ _SRRO-BOOT-RECOVERED? 0= IF
        R@ _SRRO-PARTIAL-RELEASE
        R> DROP SRRO-S-BLOCKED EXIT
    THEN

    STREAMS-SYNDICATION-DECODER-NEW
    DUP R@ SRRO.LAST-AUTHORITY-STATUS !
    DUP SYNDEC-S-OK <> IF
        DROP DROP
        R@ _SRRO-PARTIAL-RELEASE
        R> DROP SRRO-S-CAPACITY EXIT
    THEN
    DROP
    R@ SRRO.DECODER !

    R@ SRRO.FACTORY-XT @ EXECUTE
    DUP R@ SRRO.LAST-AUTHORITY-STATUS !
    DUP SCONF-S-OK <> IF
        DUP _SRRO-SCONF>STATUS R@ SRRO.SCRATCH-STATUS !
        DROP
        ?DUP IF
            DUP SCONF-VALID? IF
                DUP SCONF-RELEASABLE?
                IF SCONF-RELEASE DROP ELSE DROP THEN
            ELSE
                DROP
            THEN
        THEN
        R@ SRRO.SCRATCH-STATUS @
        R@ _SRRO-PARTIAL-RELEASE
        R> DROP EXIT
    THEN
    DROP
    DUP SCONF-VALID? 0= IF
        DROP
        R@ _SRRO-PARTIAL-RELEASE
        R> DROP SRRO-S-UNAVAILABLE EXIT
    THEN
    R@ SRRO.PROVIDER !

    _SRRO-MAGIC R@ SRRO.MAGIC !
    R@ R@ SRRO.SELF !
    SRRO-PHASE-IDLE R@ SRRO.PHASE !
    SRRO-S-OK R@ SRRO.LAST-STATUS !
    0 R@ SRRO.LAST-ERROR !
    0 R@ SRRO.LAST-AUTHORITY-STATUS !
    R> DROP SRRO-S-OK ;

