1 CONSTANT STREAMS-PAYLOAD-S-INVALID
2 CONSTANT STREAMS-PAYLOAD-S-BUSY
3 CONSTANT STREAMS-PAYLOAD-S-CAPACITY
4 CONSTANT STREAMS-PAYLOAD-S-STALE
5 CONSTANT STREAMS-PAYLOAD-S-CLEANUP
6 CONSTANT STREAMS-PAYLOAD-S-INTEGRITY

1 CONSTANT STREAMS-PAYLOAD-STATE-READY
2 CONSTANT STREAMS-PAYLOAD-STATE-BUILDING
3 CONSTANT STREAMS-PAYLOAD-STATE-SEALED
4 CONSTANT STREAMS-PAYLOAD-STATE-CLOSING
5 CONSTANT STREAMS-PAYLOAD-STATE-CLOSED
6 CONSTANT STREAMS-PAYLOAD-STATE-CLEANUP-FAILED

1 CONSTANT STREAMS-PAYLOAD-F-WIPE

0x7FFFFFFFFFFFFFFF CONSTANT _SPAY-CELL-MAX

: _SPAY-ZERO?  ( address length -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    0 ?DO
        DUP I + C@ IF DROP 0 UNLOOP EXIT THEN
    LOOP
    DROP -1 ;

\ =====================================================================
\ Caller-owned segment table
\ =====================================================================

 0 CONSTANT _SPSEG-DATA
 8 CONSTANT _SPSEG-CAPACITY
16 CONSTANT _SPSEG-USED
24 CONSTANT STREAMS-PAYLOAD-SEGMENT-SIZE

: SPSEG.DATA      ( segment -- a ) _SPSEG-DATA + ;
: SPSEG.CAPACITY  ( segment -- a ) _SPSEG-CAPACITY + ;
: SPSEG.USED      ( segment -- a ) _SPSEG-USED + ;

-1 1 RSHIFT STREAMS-PAYLOAD-SEGMENT-SIZE /
    CONSTANT _SPAY-SEGMENT-COUNT-MAX

: STREAMS-PAYLOAD-SEGMENT-BYTES  ( count -- bytes|0 )
    DUP 1 < IF DROP 0 EXIT THEN
    DUP _SPAY-SEGMENT-COUNT-MAX U> IF DROP 0 EXIT THEN
    STREAMS-PAYLOAD-SEGMENT-SIZE * ;

: _SPAY-SEGMENT-AT  ( index segments -- segment )
    SWAP STREAMS-PAYLOAD-SEGMENT-SIZE * + ;

: STREAMS-PAYLOAD-SEGMENT-INIT  ( data-a capacity segment -- status )
    >R
    R@ 0= IF 2DROP R> DROP STREAMS-PAYLOAD-S-INVALID EXIT THEN
    R@ STREAMS-PAYLOAD-SEGMENT-SIZE MSPAN-NONWRAPPING? 0= IF
        2DROP R> DROP STREAMS-PAYLOAD-S-INVALID EXIT
    THEN
    DUP 1 < IF 2DROP R> DROP STREAMS-PAYLOAD-S-INVALID EXIT THEN
    OVER 0= IF 2DROP R> DROP STREAMS-PAYLOAD-S-INVALID EXIT THEN
    2DUP MSPAN-NONWRAPPING? 0= IF
        2DROP R> DROP STREAMS-PAYLOAD-S-INVALID EXIT
    THEN
    2DUP R@ STREAMS-PAYLOAD-SEGMENT-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP STREAMS-PAYLOAD-S-INVALID EXIT
    THEN
    R@ STREAMS-PAYLOAD-SEGMENT-SIZE 0 FILL
    DUP R@ SPSEG.CAPACITY !
    OVER R@ SPSEG.DATA !
    2DROP R> DROP STREAMS-PAYLOAD-S-OK ;

: _SPSEG-LIVE?  ( segment -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-PAYLOAD-SEGMENT-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP 0 EXIT
    THEN
    DUP SPSEG.DATA @ 0= IF DROP 0 EXIT THEN
    DUP SPSEG.CAPACITY @ 1 < IF DROP 0 EXIT THEN
    DUP SPSEG.DATA @ OVER SPSEG.CAPACITY @
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP SPSEG.USED @ DUP 0<
        SWAP 2 PICK SPSEG.CAPACITY @ > OR IF DROP 0 EXIT THEN
    DUP SPSEG.DATA @ OVER SPSEG.CAPACITY @
        2 PICK STREAMS-PAYLOAD-SEGMENT-SIZE
        MSPAN-OVERLAP? 0= SWAP DROP ;

