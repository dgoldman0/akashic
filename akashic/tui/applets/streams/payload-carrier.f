\ =====================================================================
\ payload-carrier.f - caller-owned segmented Streams payload carrier
\ =====================================================================
\ A carrier owns no allocation, I/O, persistence, or process-global
\ workspace.  The caller supplies the descriptor, a fixed segment table,
\ and every writable byte span named by that table.
\
\ Segments form one logical byte string in table order.  APPEND packs each
\ segment before advancing to the next.  SEAL hashes the used prefixes in
\ that same order and freezes the logical length.  Exact reads never expose
\ mutable segment-table entries and revalidate the whole-payload digest
\ before copying bytes.
\
\ Release callback:
\   RELEASE  ( segments-a segment-count release-context -- error )
\
\ A zero release XT means the segment geometry remains caller-owned and may
\ be RESET after CLOSE.  A nonzero release XT makes the binding one-shot:
\ CLOSE wipes when requested, calls RELEASE exactly once, and then clears
\ every live geometry and callback pointer even when RELEASE fails or throws.
\ =====================================================================

PROVIDED akashic-streams-payload-carrier

REQUIRE ../../../utils/memory-span.f
REQUIRE ../../../math/sha3.f

