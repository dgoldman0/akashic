  8 CONSTANT _SPAY-SIZE
 16 CONSTANT _SPAY-STATE
 24 CONSTANT _SPAY-BUSY
 32 CONSTANT _SPAY-GENERATION
 40 CONSTANT _SPAY-PROFILE
 48 CONSTANT _SPAY-FLAGS
 56 CONSTANT _SPAY-SEGMENTS
 64 CONSTANT _SPAY-SEGMENT-N
 72 CONSTANT _SPAY-BYTE-CAP
 80 CONSTANT _SPAY-BYTE-U
 88 CONSTANT _SPAY-RELEASE-XT
 96 CONSTANT _SPAY-RELEASE-CONTEXT
