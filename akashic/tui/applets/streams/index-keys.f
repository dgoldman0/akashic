\ ---------------------------------------------------------------------
\ Pure structural helpers
\ ---------------------------------------------------------------------

: _SPI-DROP3  ( x1 x2 x3 -- ) 2DROP DROP ;
: _SPI-DROP4  ( x1 x2 x3 x4 -- ) 2DROP 2DROP ;
: _SPI-DROP5  ( x1 x2 x3 x4 x5 -- ) 2DROP 2DROP DROP ;
: _SPI-DROP6  ( x1 x2 x3 x4 x5 x6 -- ) 2DROP 2DROP 2DROP ;

: _SPI-SPAN?  ( address length -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    OVER 0= IF 2DROP 0 EXIT THEN
    MSPAN-NONWRAPPING? ;

: _SPI-DEST?  ( destination bytes -- flag )
    DUP 0> OVER STREAMS-PI-KEY-MAX <= AND 0= IF
        2DROP 0 EXIT
    THEN
    _SPI-SPAN? ;

: _SPI-NONZERO?  ( address bytes -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    0 ?DO
        DUP I + C@ IF DROP -1 UNLOOP EXIT THEN
    LOOP
    DROP 0 ;

: _SPI-FF?  ( address bytes -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    0 ?DO
        DUP I + C@ 255 <> IF DROP 0 UNLOOP EXIT THEN
    LOOP
    DROP -1 ;

: _SPI-RID?  ( rid -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP RID-SIZE _SPI-SPAN? 0= IF DROP 0 EXIT THEN
    RID-SIZE _SPI-NONZERO? ;

: _SPI-DIGEST?  ( digest -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-PI-DIGEST-SIZE _SPI-SPAN? 0= IF DROP 0 EXIT THEN
    STREAMS-PI-DIGEST-SIZE _SPI-NONZERO? ;

: _SPI-POSITIVE?  ( value -- flag ) 0> ;

: _SPI-COLLISION-ORDINAL?  ( value -- flag )
    DUP 0> SWAP STREAMS-PI-NATIVE-COLLISION-MAX <= AND ;

: _SPI-FAMILY?  ( family -- flag )
    DUP STREAMS-PI-F-SOURCE-RID =
    OVER STREAMS-PI-F-SOURCE-ORDER = OR
    OVER STREAMS-PI-F-ACTIVE-ATTEMPT = OR
    OVER STREAMS-PI-F-ATTEMPT-BY-SOURCE = OR
    OVER STREAMS-PI-F-NATIVE-HEAD = OR
    OVER STREAMS-PI-F-OBSERVATION-REVISION = OR
    OVER STREAMS-PI-F-GLOBAL-TIME = OR
    OVER STREAMS-PI-F-SOURCE-TIME = OR
    SWAP STREAMS-PI-F-THREAD-TIME = OR ;

: STREAMS-PI-FAMILY-TREE  ( family -- tree-index|-1 )
    DUP STREAMS-PI-F-SOURCE-RID =
    OVER STREAMS-PI-F-SOURCE-ORDER = OR
    OVER STREAMS-PI-F-ACTIVE-ATTEMPT = OR IF
        DROP STREAMS-PI-TREE-DIRECTORY EXIT
    THEN
    DUP STREAMS-PI-F-ATTEMPT-BY-SOURCE = IF
        DROP STREAMS-PI-TREE-ATTEMPTS EXIT
    THEN
    DUP STREAMS-PI-F-NATIVE-HEAD =
    OVER STREAMS-PI-F-OBSERVATION-REVISION = OR IF
        DROP STREAMS-PI-TREE-IDENTITIES EXIT
    THEN
    DUP STREAMS-PI-F-GLOBAL-TIME =
    OVER STREAMS-PI-F-SOURCE-TIME = OR
    SWAP STREAMS-PI-F-THREAD-TIME = OR IF
        STREAMS-PI-TREE-ORDERINGS
    ELSE
        -1
    THEN ;

: _SPI-KEY-FAMILY@  ( key-a key-u -- family|0 )
    2DUP _SPI-SPAN? 0= IF 2DROP 0 EXIT THEN
    DUP 0= IF 2DROP 0 EXIT THEN
    DROP C@ DUP _SPI-FAMILY? 0= IF DROP 0 THEN ;

: _SPI-U64-BE!  ( positive-value destination -- )
    >R
    DUP 56 RSHIFT 255 AND R@     C!
    DUP 48 RSHIFT 255 AND R@ 1 + C!
    DUP 40 RSHIFT 255 AND R@ 2 + C!
    DUP 32 RSHIFT 255 AND R@ 3 + C!
    DUP 24 RSHIFT 255 AND R@ 4 + C!
    DUP 16 RSHIFT 255 AND R@ 5 + C!
    DUP  8 RSHIFT 255 AND R@ 6 + C!
        255 AND R@ 7 + C!
    R> DROP ;

: _SPI-U64-BE-POSITIVE?  ( source -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-PI-U64-SIZE _SPI-SPAN? 0= IF DROP 0 EXIT THEN
    DUP C@ 128 AND IF DROP 0 EXIT THEN
    STREAMS-PI-U64-SIZE _SPI-NONZERO? ;

: _SPI-U64-BE@  ( source -- positive-value )
    0 SWAP
    STREAMS-PI-U64-SIZE 0 ?DO
        DUP I + C@ ROT 8 LSHIFT OR SWAP
    LOOP
    DROP ;

: STREAMS-PI-POSITIVE-U64-BE!
  ( positive-value destination -- status )
    OVER _SPI-POSITIVE? 0= IF 2DROP STREAMS-PI-S-INVALID EXIT THEN
    DUP STREAMS-PI-U64-SIZE _SPI-DEST? 0= IF
        2DROP STREAMS-PI-S-INVALID EXIT
    THEN
    _SPI-U64-BE! STREAMS-PI-S-OK ;

: STREAMS-PI-POSITIVE-U64-BE@
  ( source -- positive-value flag )
    DUP _SPI-U64-BE-POSITIVE? 0= IF DROP 0 0 EXIT THEN
    _SPI-U64-BE@ -1 ;

: _SPI-EXACT-TAG?  ( key-a key-u exact-u family -- flag )
    >R
    2 PICK 2 PICK _SPI-SPAN? 0= IF
        _SPI-DROP3 R> DROP 0 EXIT
    THEN
    OVER <> IF 2DROP R> DROP 0 EXIT THEN
    DROP C@ R> = ;

: _SPI-TAIL-FF?  ( boundary-a boundary-u prefix-u -- flag )
    >R
    DUP R@ < IF 2DROP R> DROP 0 EXIT THEN
    OVER R@ + SWAP R@ - ROT DROP _SPI-FF?
    R> DROP ;

\ ---------------------------------------------------------------------
\ Generic family, RID-scope, and boundary construction
\ ---------------------------------------------------------------------

: _SPI-FAMILY-PREFIX  ( family destination -- status )
    >R
    DUP _SPI-FAMILY? 0= IF DROP R> DROP STREAMS-PI-S-INVALID EXIT THEN
    R@ STREAMS-PI-FAMILY-PREFIX-SIZE _SPI-DEST? 0= IF
        DROP R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    R@ STREAMS-PI-FAMILY-PREFIX-SIZE 0 FILL
    R@ C!
    R> DROP STREAMS-PI-S-OK ;

: _SPI-FAMILY-PREFIX?  ( prefix-a prefix-u family -- flag )
    >R
    STREAMS-PI-FAMILY-PREFIX-SIZE R> _SPI-EXACT-TAG? ;

: STREAMS-PI-FAMILY-PREFIX  ( family destination -- status )
    _SPI-FAMILY-PREFIX ;

: STREAMS-PI-FAMILY-PREFIX-VALID?
  ( prefix-a prefix-u family -- flag )
    _SPI-FAMILY-PREFIX? ;

: _SPI-FAMILY-LAST-BOUNDARY
  ( family complete-key-u destination -- status )
    >R
    OVER _SPI-FAMILY? 0= IF
        2DROP R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    DUP STREAMS-PI-FAMILY-PREFIX-SIZE >
    OVER STREAMS-PI-KEY-MAX <= AND 0= IF
        2DROP R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    R@ OVER _SPI-DEST? 0= IF
        2DROP R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    R@ OVER 0 FILL
    OVER R@ C!
    R@ 1+ OVER 1- 255 FILL
    2DROP R> DROP STREAMS-PI-S-OK ;

: _SPI-RID-KEY  ( rid family destination -- status )
    >R
    OVER _SPI-RID? 0= IF 2DROP R> DROP STREAMS-PI-S-INVALID EXIT THEN
    DUP _SPI-FAMILY? 0= IF 2DROP R> DROP STREAMS-PI-S-INVALID EXIT THEN
    R@ STREAMS-PI-SOURCE-RID-KEY-SIZE _SPI-DEST? 0= IF
        2DROP R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    OVER RID-SIZE R@ STREAMS-PI-SOURCE-RID-KEY-SIZE
        MSPAN-OVERLAP? IF
        2DROP R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    R@ STREAMS-PI-SOURCE-RID-KEY-SIZE 0 FILL
    DUP R@ C!
    OVER R@ 1+ RID-COPY
    2DROP R> DROP STREAMS-PI-S-OK ;

: _SPI-RID-KEY?  ( key-a key-u family -- flag )
    >R
    2DUP STREAMS-PI-SOURCE-RID-KEY-SIZE R@ _SPI-EXACT-TAG? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    OVER 1+ _SPI-RID? NIP NIP
    R> DROP ;

: _SPI-RID-LAST-BOUNDARY
  ( rid family complete-key-u destination -- status )
    >R
    2 PICK _SPI-RID? 0= IF
        _SPI-DROP3 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    OVER _SPI-FAMILY? 0= IF
        _SPI-DROP3 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    DUP STREAMS-PI-SOURCE-RID-KEY-SIZE >
    OVER STREAMS-PI-KEY-MAX <= AND 0= IF
        _SPI-DROP3 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    R@ OVER _SPI-DEST? 0= IF
        _SPI-DROP3 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    2 PICK RID-SIZE R@ 3 PICK MSPAN-OVERLAP? IF
        _SPI-DROP3 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    R@ OVER 0 FILL
    OVER R@ C!
    2 PICK R@ 1+ RID-COPY
    R@ STREAMS-PI-SOURCE-RID-KEY-SIZE +
    OVER STREAMS-PI-SOURCE-RID-KEY-SIZE - 255 FILL
    _SPI-DROP3 R> DROP STREAMS-PI-S-OK ;

