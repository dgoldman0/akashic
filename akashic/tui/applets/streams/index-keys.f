: STREAMS-PI-ATTEMPT-BY-SOURCE-KEY
  ( source-rid attempt-sequence attempt-rid destination -- status )
    >R
    2 PICK _SPI-RID? 0= IF
        _SPI-DROP3 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    OVER _SPI-POSITIVE? 0= IF
        _SPI-DROP3 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    DUP _SPI-RID? 0= IF
        _SPI-DROP3 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    R@ STREAMS-PI-ATTEMPT-BY-SOURCE-KEY-SIZE _SPI-DEST? 0= IF
        _SPI-DROP3 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    2 PICK RID-SIZE R@ STREAMS-PI-ATTEMPT-BY-SOURCE-KEY-SIZE
        MSPAN-OVERLAP? IF
        _SPI-DROP3 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    DUP RID-SIZE R@ STREAMS-PI-ATTEMPT-BY-SOURCE-KEY-SIZE
        MSPAN-OVERLAP? IF
        _SPI-DROP3 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    R@ STREAMS-PI-ATTEMPT-BY-SOURCE-KEY-SIZE 0 FILL
    STREAMS-PI-F-ATTEMPT-BY-SOURCE R@ C!
    2 PICK R@ 1+ RID-COPY
    OVER R@ 1 RID-SIZE + + _SPI-U64-BE!
    DUP R@ 1 RID-SIZE + STREAMS-PI-U64-SIZE + + RID-COPY
    _SPI-DROP3 R> DROP STREAMS-PI-S-OK ;

