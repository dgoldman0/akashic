    DUP STREAMS-PI-DIGEST-SIZE R@ STREAMS-PI-THREAD-TIME-KEY-SIZE
        MSPAN-OVERLAP? IF
        _SPI-DROP3 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    R@ STREAMS-PI-THREAD-TIME-KEY-SIZE 0 FILL
    STREAMS-PI-F-THREAD-TIME R@ C!
    2 PICK R@ 1+ RID-COPY
    OVER R@ 1 RID-SIZE + + STREAMS-PI-DIGEST-SIZE MOVE
    DUP R@ 1 RID-SIZE + STREAMS-PI-DIGEST-SIZE + +
        STREAMS-PI-DIGEST-SIZE MOVE
    R@ STREAMS-PI-THREAD-TIME-PREFIX-SIZE +
        STREAMS-PI-THREAD-TIME-KEY-SIZE
        STREAMS-PI-THREAD-TIME-PREFIX-SIZE - 255 FILL
    _SPI-DROP3 R> DROP STREAMS-PI-S-OK ;

: STREAMS-PI-THREAD-TIME-LATEST-BOUNDARY
  ( source-rid namespace thread-root-digest destination -- status )
    STREAMS-PI-THREAD-TIME-LAST-BOUNDARY ;

: STREAMS-PI-THREAD-TIME-LAST-BOUNDARY-VALID?
  ( boundary-a boundary-u -- flag )
    2DUP STREAMS-PI-THREAD-TIME-KEY-SIZE
        STREAMS-PI-F-THREAD-TIME _SPI-EXACT-TAG? 0= IF
        2DROP 0 EXIT
    THEN
    OVER STREAMS-PI-THREAD-TIME-PREFIX-SIZE
        STREAMS-PI-THREAD-TIME-PREFIX-VALID? 0= IF
        2DROP 0 EXIT
    THEN
    STREAMS-PI-THREAD-TIME-PREFIX-SIZE _SPI-TAIL-FF? ;

