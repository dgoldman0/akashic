    THEN
    OVER 1+ _SPI-RID? 0= IF 2DROP 0 EXIT THEN
    OVER 1 RID-SIZE + + _SPI-U64-BE-POSITIVE? 0= IF
        2DROP 0 EXIT
    THEN
    OVER 1 RID-SIZE + STREAMS-PI-U64-SIZE + + _SPI-RID?
    NIP NIP ;

