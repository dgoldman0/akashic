    STREAMS-PI-F-ATTEMPT-BY-SOURCE _SPI-FAMILY-PREFIX? ;

: STREAMS-PI-ATTEMPT-BY-SOURCE-PREFIX
  ( source-rid destination -- status )
    STREAMS-PI-F-ATTEMPT-BY-SOURCE SWAP _SPI-RID-KEY ;

