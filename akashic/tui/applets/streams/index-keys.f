: STREAMS-PI-KEY-VALID?  ( key-a key-u -- flag )
    2DUP _SPI-KEY-FAMILY@ DUP 0= IF
        DROP 2DROP 0 EXIT
    THEN
    DUP STREAMS-PI-F-SOURCE-RID = IF
        DROP STREAMS-PI-SOURCE-RID-KEY-VALID? EXIT
    THEN
    DUP STREAMS-PI-F-SOURCE-ORDER = IF
        DROP STREAMS-PI-SOURCE-ORDER-KEY-VALID? EXIT
    THEN
    DUP STREAMS-PI-F-ACTIVE-ATTEMPT = IF
        DROP STREAMS-PI-ACTIVE-ATTEMPT-KEY-VALID? EXIT
    THEN
    DUP STREAMS-PI-F-ATTEMPT-BY-SOURCE = IF
        DROP STREAMS-PI-ATTEMPT-BY-SOURCE-KEY-VALID? EXIT
    THEN
    DUP STREAMS-PI-F-NATIVE-HEAD = IF
        DROP STREAMS-PI-NATIVE-HEAD-KEY-VALID? EXIT
    THEN
    DUP STREAMS-PI-F-OBSERVATION-REVISION = IF
        DROP STREAMS-PI-OBSERVATION-REVISION-KEY-VALID? EXIT
    THEN
    DUP STREAMS-PI-F-GLOBAL-TIME = IF
        DROP STREAMS-PI-GLOBAL-TIME-KEY-VALID? EXIT
    THEN
    DUP STREAMS-PI-F-SOURCE-TIME = IF
        DROP STREAMS-PI-SOURCE-TIME-KEY-VALID? EXIT
