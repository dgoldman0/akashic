: STREAMS-PI-NATIVE-HEAD-FAMILY-PREFIX  ( destination -- status )
    STREAMS-PI-F-NATIVE-HEAD SWAP _SPI-FAMILY-PREFIX ;

: STREAMS-PI-NATIVE-HEAD-FAMILY-PREFIX-VALID?
  ( prefix-a prefix-u -- flag )
    STREAMS-PI-F-NATIVE-HEAD _SPI-FAMILY-PREFIX? ;

: STREAMS-PI-NATIVE-HEAD-PREFIX
  ( source-rid namespace format kind digest destination -- status )
    >R
    4 PICK _SPI-RID? 0= IF
        _SPI-DROP5 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    3 PICK _SPI-DIGEST? 0= IF
        _SPI-DROP5 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    2 PICK _SPI-POSITIVE? 0= IF
        _SPI-DROP5 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    OVER _SPI-POSITIVE? 0= IF
        _SPI-DROP5 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    DUP _SPI-DIGEST? 0= IF
        _SPI-DROP5 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    R@ STREAMS-PI-NATIVE-HEAD-PREFIX-SIZE _SPI-DEST? 0= IF
        _SPI-DROP5 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    4 PICK RID-SIZE R@ STREAMS-PI-NATIVE-HEAD-PREFIX-SIZE
        MSPAN-OVERLAP? IF
        _SPI-DROP5 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    3 PICK STREAMS-PI-DIGEST-SIZE
        R@ STREAMS-PI-NATIVE-HEAD-PREFIX-SIZE MSPAN-OVERLAP? IF
        _SPI-DROP5 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    DUP STREAMS-PI-DIGEST-SIZE
        R@ STREAMS-PI-NATIVE-HEAD-PREFIX-SIZE MSPAN-OVERLAP? IF
        _SPI-DROP5 R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    R@ STREAMS-PI-NATIVE-HEAD-PREFIX-SIZE 0 FILL
    STREAMS-PI-F-NATIVE-HEAD R@ C!
    4 PICK R@ 1+ RID-COPY
    3 PICK R@ 1 RID-SIZE + + STREAMS-PI-DIGEST-SIZE MOVE
    2 PICK R@ 1 RID-SIZE + STREAMS-PI-DIGEST-SIZE + + _SPI-U64-BE!
    OVER R@ 1 RID-SIZE + STREAMS-PI-DIGEST-SIZE +
        STREAMS-PI-U64-SIZE + + _SPI-U64-BE!
    DUP R@ 1 RID-SIZE + STREAMS-PI-DIGEST-SIZE +
        STREAMS-PI-U64-SIZE 2 * + +
        STREAMS-PI-DIGEST-SIZE MOVE
    _SPI-DROP5 R> DROP STREAMS-PI-S-OK ;

: STREAMS-PI-NATIVE-HEAD-PREFIX-VALID?
