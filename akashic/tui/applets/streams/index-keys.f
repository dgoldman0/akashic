    STREAMS-PI-F-SOURCE-ORDER _SPI-FAMILY-PREFIX? ;

: STREAMS-PI-SOURCE-ORDER-KEY
  ( creation-sequence source-rid destination -- status )
    >R
    OVER _SPI-POSITIVE? 0= IF
        2DROP R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    DUP _SPI-RID? 0= IF 2DROP R> DROP STREAMS-PI-S-INVALID EXIT THEN
    R@ STREAMS-PI-SOURCE-ORDER-KEY-SIZE _SPI-DEST? 0= IF
        2DROP R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    DUP RID-SIZE R@ STREAMS-PI-SOURCE-ORDER-KEY-SIZE
        MSPAN-OVERLAP? IF
        2DROP R> DROP STREAMS-PI-S-INVALID EXIT
    THEN
    R@ STREAMS-PI-SOURCE-ORDER-KEY-SIZE 0 FILL
    STREAMS-PI-F-SOURCE-ORDER R@ C!
    OVER R@ 1+ _SPI-U64-BE!
    DUP R@ 1 STREAMS-PI-U64-SIZE + + RID-COPY
    2DROP R> DROP STREAMS-PI-S-OK ;

: STREAMS-PI-SOURCE-ORDER-KEY-VALID?  ( key-a key-u -- flag )
    2DUP STREAMS-PI-SOURCE-ORDER-KEY-SIZE
        STREAMS-PI-F-SOURCE-ORDER _SPI-EXACT-TAG? 0= IF
        2DROP 0 EXIT
    THEN
    OVER 1+ _SPI-U64-BE-POSITIVE? 0= IF 2DROP 0 EXIT THEN
    OVER 1 STREAMS-PI-U64-SIZE + + _SPI-RID? NIP NIP ;

: STREAMS-PI-SOURCE-ORDER-LAST-BOUNDARY  ( destination -- status )
    STREAMS-PI-F-SOURCE-ORDER STREAMS-PI-SOURCE-ORDER-KEY-SIZE ROT
    _SPI-FAMILY-LAST-BOUNDARY ;

: STREAMS-PI-SOURCE-ORDER-LAST-BOUNDARY-VALID?
  ( boundary-a boundary-u -- flag )
    2DUP STREAMS-PI-SOURCE-ORDER-KEY-SIZE
        STREAMS-PI-F-SOURCE-ORDER _SPI-EXACT-TAG? 0= IF
        2DROP 0 EXIT
    THEN
    STREAMS-PI-SOURCE-ORDER-PREFIX-SIZE _SPI-TAIL-FF? ;

: STREAMS-PI-ACTIVE-ATTEMPT-PREFIX  ( destination -- status )
