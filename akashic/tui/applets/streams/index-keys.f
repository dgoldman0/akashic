\ =====================================================================
\  index-keys.f - Streams-owned ordered persistence keys
\ =====================================================================
\  These byte layouts are the four-tree L13 authority topology described
\  in docs/tui/applets/streams/l13-authority-topology-retention.md.
\  Neutral persistence sees only unsigned lexicographic byte keys.
\
\  Every key begins with one globally unique nonzero family byte.  Positive
\  numeric fields in the current ABI are bounded to 1..PERSIST-MAX-SIGNED and
\  use fixed eight-byte big-endian encodings, so byte order agrees with
\  semantic order.  RIDs and SHA3-256 digests remain exact 32-byte values.
\  Variable provider identities never enter a key; their digest selects
\  bounded candidates and the semantic record supplies the required
\  exact-byte comparison.
\
\  Constructors validate every input and every complete destination span,
\  reject destination aliasing with borrowed RID/digest inputs, and leave
\  the destination unchanged on rejection.  There is no mutable module
\  state.  LAST-BOUNDARY constructors create seek-only values whose suffix
\  is all 0xFF; they are deliberately not valid semantic keys.
\ =====================================================================

PROVIDED akashic-tui-streams-index-keys

REQUIRE ../../../runtime/identity.f
REQUIRE ../../../utils/memory-span.f
REQUIRE ../../../persistence/btree.f

