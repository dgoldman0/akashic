: STREAMS-ACQUISITION-BEGIN
  ( request output-attempt repository repo-work work -- status )
    >R
    2DUP R@ _SAA-PREPARE
    DUP IF
        R@ STREAMS-ACQUISITION-WORK-VALID? IF
            DUP R@ _SAAW.STATUS !
        THEN
        >R _SAA-DROP4 R> R> DROP EXIT
    THEN DROP
    3 PICK R@ _SAAW.REQUEST-A !
    2 PICK R@ _SAAW.OUTPUT-A !
    R@ _SAA-BEGIN-ARGS-SAFE? 0= IF
        STREAMS-ACQUISITION-S-INVALID
        R@ _SAA-WORK-STATUS! >R _SAA-DROP4 R> R> DROP EXIT
    THEN
    ['] _SAA-BEGIN-RUN R@ _SAA-INVOKE
    >R _SAA-DROP4 R> R> DROP ;

