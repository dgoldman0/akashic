    DUP R@ _SAA-SOURCE-KEY
    DUP IF NIP R> DROP EXIT THEN DROP
    DROP
    R@ _SAAW.SOURCE-KEY STREAMS-PI-SOURCE-RID-KEY-SIZE
    R@ _SAAW.SOURCE-RECORD STREAMS-PERSISTENCE-RECORD-MAX
