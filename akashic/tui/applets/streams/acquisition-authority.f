: _SAA-BEGIN-ARGS-SAFE?  ( work -- flag )
    >R
    R@ _SAAW.REQUEST-A @ STREAMS-ACQUISITION-BEGIN-REQUEST-SIZE
        R@ _SAA-EXTERNAL-SPAN? 0= IF R> DROP 0 EXIT THEN
    R@ _SAAW.OUTPUT-A @ OCHK-SOURCE-SIZE
        R@ _SAA-EXTERNAL-SPAN? 0= IF R> DROP 0 EXIT THEN
    R@ _SAAW.REQUEST-A @
        STREAMS-ACQUISITION-BEGIN-REQUEST-VALID? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _SAAW.REQUEST-A @ SABR.REQUESTED-A @
    R@ _SAAW.REQUEST-A @ SABR.REQUESTED-U @
        R@ _SAA-EXTERNAL-SPAN? 0= IF R> DROP 0 EXIT THEN
    R@ _SAAW.OUTPUT-A @ OCHK-SOURCE-SIZE
    R@ _SAAW.REQUEST-A @ STREAMS-ACQUISITION-BEGIN-REQUEST-SIZE
        MSPAN-OVERLAP? IF R> DROP 0 EXIT THEN
    R@ _SAAW.OUTPUT-A @ OCHK-SOURCE-SIZE
    R@ _SAAW.REQUEST-A @ SABR.REQUESTED-A @
    R@ _SAAW.REQUEST-A @ SABR.REQUESTED-U @
        MSPAN-OVERLAP? 0=
    R> DROP ;

