        R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    SPREC-SOURCE-TOMBSTONE-SIZE = IF
        R@ _SAAW.SOURCE-RECORD SPREC.KIND @
            SPREC-KIND-SOURCE-TOMBSTONE = IF
            R> DROP STREAMS-ACQUISITION-S-GONE EXIT
        THEN
        R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-ACQUISITION-S-CORRUPT ;

