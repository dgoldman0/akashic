: _SAA-RECOVER  ( primary-status work -- final-status )
    >R
    DUP R@ _SAAW.TEMP-STATUS !
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-ACTIVE?
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-REOPEN-REQUIRED? OR
    OVER STREAMS-ACQUISITION-S-OK = AND IF
        STREAMS-ACQUISITION-S-FAULT R@ _SAAW.TEMP-STATUS !
    THEN
    DROP
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-ACTIVE? IF
        R@ _SAAW.ADAPTER @ R@ _SAAW.ADAPTER-WORK @
            STREAMS-PA-ABORT _SAA-ADAPTER>STATUS
            R@ _SAA-CONSIDER-RECOVERY
    THEN
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-REOPEN-REQUIRED? IF
        R@ _SAAW.ADAPTER @ R@ _SAAW.ADAPTER-WORK @
            STREAMS-PA-REBIND _SAA-ADAPTER>STATUS
            R@ _SAA-CONSIDER-RECOVERY
    THEN
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-ACTIVE? IF
        STREAMS-ACQUISITION-S-FAULT R@ _SAAW.TEMP-STATUS !
    THEN
    R@ _SAAW.TEMP-STATUS @ R> DROP ;

: _SAA-OWNER-DISPATCH  ( work repository repo-work -- repo-status )
    2DROP >R
    R@ R@ _SAAW.OP-XT @ CATCH
    DUP IF
        DROP DROP STREAMS-ACQUISITION-S-FAULT
    ELSE
        DROP
    THEN
    R@ _SAA-RECOVER
    DUP R@ _SAAW.RESULT ! DROP
    R> DROP STREAMS-REPOSITORY-S-OK ;

: _SAA-INVOKE  ( operation-xt work -- status )
    >R
    DUP 0= IF
        DROP STREAMS-ACQUISITION-S-INVALID
        R@ _SAA-WORK-STATUS! R> DROP EXIT
    THEN
    R@ _SAAW.BUSY @ IF
        DROP STREAMS-ACQUISITION-S-BUSY
        R@ _SAA-WORK-STATUS! R> DROP EXIT
    THEN
    R@ _SAAW.OP-XT !
    STREAMS-ACQUISITION-S-INVALID R@ _SAAW.RESULT !
    0 R@ _SAAW.RESULT-COUNT !
    -1 R@ _SAAW.BUSY !
    R@ ['] _SAA-OWNER-DISPATCH
    R@ _SAAW.REPOSITORY @ R@ _SAAW.REPO-WORK @
        STREAMS-REPOSITORY-WITH-OWNER
    DUP STREAMS-REPOSITORY-S-OK = IF
        DROP R@ _SAAW.RESULT @
    ELSE
        _SAA-REPOSITORY>STATUS
    THEN
    DUP R@ _SAAW.STATUS !
    0 R@ _SAAW.BUSY !
    0 R@ _SAAW.OP-XT !
    R> DROP ;

: _SAA-READY  ( work -- status )
    >R
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-ACTIVE? IF
        R> DROP STREAMS-ACQUISITION-S-BUSY EXIT
    THEN
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-REOPEN-REQUIRED? IF
        R@ _SAAW.ADAPTER @ R@ _SAAW.ADAPTER-WORK @
            STREAMS-PA-REBIND _SAA-ADAPTER>STATUS
        DUP IF R> DROP EXIT THEN DROP
    THEN
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF
        DROP R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    STREAMS-AUTHORITY-ROOT-HEADER-VALID? 0= IF
        R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-ACQUISITION-S-OK ;

