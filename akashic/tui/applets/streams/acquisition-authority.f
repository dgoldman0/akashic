    DROP
    DUP SPREC-SOURCE-SIZE = IF
        DROP
        R@ _SAAW.SOURCE-RECORD SPREC.KIND @
            SPREC-KIND-SOURCE = IF
            R> DROP STREAMS-ACQUISITION-S-OK EXIT
