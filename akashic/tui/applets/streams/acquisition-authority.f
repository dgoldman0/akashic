    STREAMS-PA-COMMIT _SAA-ADAPTER>STATUS NIP ;

: _SAA-MUTATION-CAPACITY  ( work -- status )
    >R
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF
        DROP R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    DUP SAR.LOGICAL-GENERATION @ PERSIST-MAX-SIGNED >= IF
        DROP R> DROP STREAMS-ACQUISITION-S-CAPACITY EXIT
    THEN
    SAR.MUTATION-SEQUENCE @ PERSIST-MAX-SIGNED >= IF
        R> DROP STREAMS-ACQUISITION-S-CAPACITY EXIT
    THEN
    R> DROP STREAMS-ACQUISITION-S-OK ;

: _SAA-BEGIN-COUNTERS  ( work -- status )
    >R
    R@ _SAA-MUTATION-CAPACITY DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP SAR.ACQUISITION-SEQUENCE @ PERSIST-MAX-SIGNED >= IF
        DROP R> DROP STREAMS-ACQUISITION-S-CAPACITY EXIT
    THEN
    DUP SAR.ATTEMPT-COUNT @ PERSIST-MAX-SIGNED >= IF
        DROP R> DROP STREAMS-ACQUISITION-S-CAPACITY EXIT
    THEN
    DUP SAR.ACTIVE-COUNT @ STREAMS-AUTHORITY-ACTIVE-MAX >= IF
        DROP R> DROP STREAMS-ACQUISITION-S-CAPACITY EXIT
    THEN
    SAR.ACQUISITION-SEQUENCE @ 1+
        R@ _SAAW.NEXT-SEQUENCE !
    R> DROP STREAMS-ACQUISITION-S-OK ;

: _SAA-PUBLISH-BEGIN  ( work -- status )
    >R
    R@ _SAA-BEGIN-TX DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-APPEND-CANDIDATE DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-PUT-HISTORY DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-PUT-ACTIVE DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF
        DROP R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    R@ _SAAW.NEXT-SEQUENCE @ OVER SAR.ACQUISITION-SEQUENCE !
    1 OVER SAR.ATTEMPT-COUNT +!
    1 SWAP SAR.ACTIVE-COUNT +!
    R@ _SAA-COMMIT R> DROP ;

: _SAA-PUBLISH-TERMINAL  ( work -- status )
    >R
    R@ _SAA-BEGIN-TX DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-APPEND-CANDIDATE DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-PUT-HISTORY DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-DELETE-ACTIVE DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF
        DROP R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    DUP SAR.ACTIVE-COUNT @ 0> 0= IF
        DROP R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    -1 SWAP SAR.ACTIVE-COUNT +!
    R@ _SAA-COMMIT R> DROP ;

