\ =====================================================================
\  acquisition-authority.f - durable configured acquisition truth
\ =====================================================================
\  This is the repository-backed ACCEPTED/non-success attempt authority for
\  configured Streams.  It owns durable acquisition facts only.  Provider
\  execution, XIO, decoding, observation application, success, Library
\  documents, legacy checkpoints, output, and public-Bluesky policy remain
\  outside this module.
\
\  All mutable state is caller-owned.  Every operation crosses
\  STREAMS-REPOSITORY-WITH-OWNER.  BEGIN publishes one canonical ACCEPTED
\  attempt before external work may start.  Exact source RID, revision, and
\  enabled state are the repository-backed authorization proof.  The
\  provider-derived namespace, provider kind, and canonical requested URI are
\  retained as sealed attempt evidence; this provider-agnostic layer does not
\  recreate provider canonicalization.  TERMINAL replaces that exact attempt
\  with FAILED, CANCELLED, or INDETERMINATE facts.  Boot recovery scans only
\  ACTIVE-ATTEMPT rows in bounded adapter pages, reconciles no more than
\  STREAMS-AUTHORITY-ACTIVE-MAX accepted attempts, and terminalizes NEXT or
\  ALL without touching a legacy file.
\
\  Public operations:
\    STREAMS-ACQUISITION-BEGIN
\      request output-attempt repository repo-work work -> status
\    STREAMS-ACQUISITION-TERMINAL
\      request output-attempt repository repo-work work -> status
\    STREAMS-ACQUISITION-RECOVER-NEXT
\      output-attempt repository repo-work work -> status
\    STREAMS-ACQUISITION-RECOVER-ALL
\      outputs capacity repository repo-work work -> count status
\
\  Output attempts are exact OCHK-SOURCE-SIZE values and change only after
\  an OK publication.  RECOVER-ALL capacity is measured in attempts and is
\  bounded by STREAMS-AUTHORITY-ACTIVE-MAX.  Every post-BEGIN return path
\  attempts ABORT and required REBIND before releasing the repository owner.
\ =====================================================================

