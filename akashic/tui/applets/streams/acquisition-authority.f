    R@ _SAAW.HASH-U 8 SHA3-256-ADD
    R> DROP ;

: _SAA-DERIVE-ATTEMPT-ID  ( attempt work -- )
    >R
    SHA3-256-BEGIN
    26 R@ _SAA-SHA-U
    S" akashic.streams.attempt.v1" SHA3-256-ADD
    DUP OCS.SOURCE-ID RID-SIZE SHA3-256-ADD
    DUP OCS.NAMESPACE SHA3-256-LEN SHA3-256-ADD
    DUP OCS.SOURCE-REVISION @ R@ _SAA-SHA-U
    DUP OCS.ATTEMPT-SEQUENCE @ R@ _SAA-SHA-U
    DUP OCS.REQUESTED$
    DUP R@ _SAA-SHA-U
    SHA3-256-ADD
    DUP OCS.ATTEMPT-ID SHA3-256-END
    DROP R> DROP ;

: _SAA-DERIVE-REQUEST-SEAL  ( attempt work -- )
    >R
    SHA3-256-BEGIN
    26 R@ _SAA-SHA-U
    S" akashic.streams.request.v1" SHA3-256-ADD
    DUP OCS.SOURCE-ID RID-SIZE SHA3-256-ADD
    DUP OCS.NAMESPACE SHA3-256-LEN SHA3-256-ADD
    DUP OCS.SOURCE-REVISION @ R@ _SAA-SHA-U
    DUP OCS.PROVIDER-KIND @ R@ _SAA-SHA-U
    DUP OCS.REQUESTED$
    DUP R@ _SAA-SHA-U
    SHA3-256-ADD
    DUP OCS.REQUEST-SEAL SHA3-256-END
    DROP R> DROP ;

: _SAA-CONSTRUCT-ACCEPTED  ( work -- status )
    >R
    R@ _SAAW.REQUEST-A @
    STREAMS-ACQUISITION-BEGIN-REQUEST-VALID? 0= IF
        R> DROP STREAMS-ACQUISITION-S-INVALID EXIT
    THEN
    R@ _SAAW.CANDIDATE-RECORD SPREC-ATTEMPT-INIT
        _SAA-SPREC>STATUS
    DUP IF R> DROP EXIT THEN DROP
    OCHK-ATTEMPT-ACCEPTED
        R@ _SAAW.CANDIDATE-RECORD SPRA.STATE !
    R@ _SAAW.NEXT-SEQUENCE @
        R@ _SAAW.CANDIDATE-RECORD SPRA.ATTEMPT-SEQUENCE !
    R@ _SAAW.REQUEST-A @ SABR.SOURCE-REVISION @
        R@ _SAAW.CANDIDATE-RECORD SPRA.SOURCE-REVISION !
    R@ _SAAW.REQUEST-A @ SABR.PROVIDER-KIND @
        R@ _SAAW.CANDIDATE-RECORD SPRA.PROVIDER-KIND !
    R@ _SAAW.REQUEST-A @ SABR.SOURCE-ID
        R@ _SAAW.CANDIDATE-RECORD SPRA.SOURCE-ID RID-COPY
    R@ _SAAW.REQUEST-A @ SABR.NAMESPACE
        R@ _SAAW.CANDIDATE-RECORD SPRA.NAMESPACE RID-COPY
    R@ _SAAW.REQUEST-A @ SABR.REQUESTED-A @
    R@ _SAAW.CANDIDATE-RECORD SPRA.REQUESTED
    R@ _SAAW.REQUEST-A @ SABR.REQUESTED-U @ MOVE
    R@ _SAAW.REQUEST-A @ SABR.REQUESTED-U @
        R@ _SAAW.CANDIDATE-RECORD SPRA.REQUESTED-U !
    MS@ R@ _SAAW.CANDIDATE-RECORD SPRA.STARTED-MS !
    R@ _SAAW.CANDIDATE-RECORD SPRA.ATTEMPT
        R@ _SAA-DERIVE-ATTEMPT-ID
    R@ _SAAW.CANDIDATE-RECORD SPRA.ATTEMPT
        R@ _SAA-DERIVE-REQUEST-SEAL
    R@ _SAAW.CANDIDATE-RECORD SPREC-ATTEMPT-SEAL!
        _SAA-SPREC>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.CANDIDATE-RECORD SPRA.ATTEMPT
    R@ _SAAW.ATTEMPT OCHK-SOURCE-SIZE MOVE
    R> DROP STREAMS-ACQUISITION-S-OK ;

: _SAA-TERMINAL-FACTS!  ( facts work -- status )
    >R
    DUP STREAMS-ACQUISITION-TERMINAL-FACTS-VALID? 0= IF
        DROP R> DROP STREAMS-ACQUISITION-S-INVALID EXIT
    THEN
    DUP SACQF.FINISHED-MS @
    R@ _SAAW.ATTEMPT OCS.STARTED-MS @ < IF
        DROP R> DROP STREAMS-ACQUISITION-S-INVALID EXIT
    THEN
    DUP SACQF.STATE @ R@ _SAAW.ATTEMPT OCS.STATE !
    DUP SACQF.OUTCOME @ R@ _SAAW.ATTEMPT OCS.OUTCOME !
    DUP SACQF.FINISHED-MS @ R@ _SAAW.ATTEMPT OCS.FINISHED-MS !
    DUP SACQF.DETAIL @ R@ _SAAW.ATTEMPT OCS.DETAIL !
    DUP SACQF.HTTP-STATUS @ R@ _SAAW.ATTEMPT OCS.HTTP-STATUS !
    DUP SACQF.DECODE-STATUS @ R@ _SAAW.ATTEMPT OCS.DECODE-STATUS !
    DUP SACQF.XIO-ERROR @ R@ _SAAW.ATTEMPT OCS.XIO-ERROR !
    SACQF.CLEANUP-ERROR @ R@ _SAAW.ATTEMPT OCS.CLEANUP-ERROR !
    R@ _SAAW.ATTEMPT R@ _SAAW.CANDIDATE-RECORD
        SPREC-ATTEMPT-CONSTRUCT _SAA-SPREC>STATUS
    R> DROP ;

