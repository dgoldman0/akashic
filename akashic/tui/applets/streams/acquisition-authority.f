: _SAA-BEGIN-RUN  ( work -- status )
    >R
    R@ _SAA-READY DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.REQUEST-A @
        STREAMS-ACQUISITION-BEGIN-REQUEST-VALID? 0= IF
        R> DROP STREAMS-ACQUISITION-S-INVALID EXIT
    THEN
    R@ _SAAW.REQUEST-A @ SABR.SOURCE-ID
    R@ _SAA-GET-SOURCE
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.SOURCE-RECORD SPRS.REVISION @
    R@ _SAAW.REQUEST-A @ SABR.SOURCE-REVISION @ <> IF
        R> DROP STREAMS-ACQUISITION-S-STALE EXIT
    THEN
    R@ _SAAW.SOURCE-RECORD SPRS.FLAGS @
        SSOURCE-F-ENABLED AND 0= IF
        R> DROP STREAMS-ACQUISITION-S-DISABLED EXIT
    THEN
    R@ _SAAW.REQUEST-A @ SABR.SOURCE-ID
    R@ _SAA-ACTIVE-ABSENT
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-BEGIN-COUNTERS DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-CONSTRUCT-ACCEPTED DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.ATTEMPT R@ _SAA-HISTORY-ABSENT
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-PUBLISH-BEGIN
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.ATTEMPT R@ _SAAW.OUTPUT-A @
        OCHK-SOURCE-SIZE MOVE
    R> DROP STREAMS-ACQUISITION-S-OK ;

: _SAA-TERMINAL-EXACT?  ( request work -- status )
    >R
    DUP SATR.SOURCE-REVISION @
    R@ _SAAW.ACTIVE-RECORD SPRA.SOURCE-REVISION @ <> IF
        DROP R> DROP STREAMS-ACQUISITION-S-STALE EXIT
    THEN
    DUP SATR.ATTEMPT-ID
    R@ _SAAW.ACTIVE-RECORD SPRA.ATTEMPT-ID RID= 0= IF
        DROP R> DROP STREAMS-ACQUISITION-S-MISMATCH EXIT
    THEN
    SATR.REQUEST-SEAL
    R@ _SAAW.ACTIVE-RECORD SPRA.REQUEST-SEAL RID= 0= IF
        R> DROP STREAMS-ACQUISITION-S-MISMATCH EXIT
    THEN
    R> DROP STREAMS-ACQUISITION-S-OK ;

: _SAA-TERMINAL-RUN  ( work -- status )
    >R
    R@ _SAA-READY DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.REQUEST-A @
        STREAMS-ACQUISITION-TERMINAL-REQUEST-VALID? 0= IF
        R> DROP STREAMS-ACQUISITION-S-INVALID EXIT
    THEN
    R@ _SAAW.REQUEST-A @ SATR.SOURCE-ID
    R@ _SAA-GET-SOURCE
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.REQUEST-A @ SATR.SOURCE-ID
    R@ _SAA-GET-ACTIVE
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.REQUEST-A @ R@ _SAA-TERMINAL-EXACT?
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.SOURCE-RECORD SPRS.REVISION @
    R@ _SAAW.REQUEST-A @ SATR.SOURCE-REVISION @ < IF
        R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    R@ _SAA-ACTIVE-HISTORY-AGREES
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.ACTIVE-RECORD SPRA.ATTEMPT
    R@ _SAAW.ATTEMPT OCHK-SOURCE-SIZE MOVE
    R@ _SAAW.REQUEST-A @ SATR.FACTS
    R@ _SAA-TERMINAL-FACTS!
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-MUTATION-CAPACITY DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
        SAR.ACTIVE-COUNT @ 0> 0= IF
        R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    R@ _SAA-PUBLISH-TERMINAL
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.ATTEMPT R@ _SAAW.OUTPUT-A @
        OCHK-SOURCE-SIZE MOVE
    R> DROP STREAMS-ACQUISITION-S-OK ;

\ ---------------------------------------------------------------------
\ Bounded accepted-at-boot discovery
\ ---------------------------------------------------------------------
\ ACTIVE-ATTEMPT keys are tag || source RID, so adapter range order also
\ defines deterministic ascending-source-RID recovery output order.

: _SAA-COLLECT-ACTIVE  ( active-record work -- status )
    >R
    DUP SPRA.STATE @ OCHK-ATTEMPT-ACCEPTED <> IF
        DROP R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    DUP R@ _SAAW.ACTIVE-RECORD SPREC-ATTEMPT-SIZE MOVE
    R@ _SAA-ACTIVE-HISTORY-AGREES
    DUP IF NIP R> DROP EXIT THEN DROP
    DROP
    R@ _SAAW.RECOVERY-COUNT @
    DUP R@ _SAAW.EXPECTED-ACTIVE @ >=
    OVER STREAMS-AUTHORITY-ACTIVE-MAX >= OR IF
        DROP R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    DUP R@ _SAAW-RECOVERY-HEAD
    R@ _SAAW.ACTIVE-RECORD SPRA.ATTEMPT
    SWAP OCHK-SOURCE-SIZE MOVE
    1 R@ _SAAW.RECOVERY-COUNT +!
    DROP
    R> DROP STREAMS-ACQUISITION-S-OK ;

: _SAA-RANGE-FIRST  ( work -- status )
    >R
    R@ _SAAW.PREFIX STREAMS-PI-ACTIVE-ATTEMPT-PREFIX-SIZE
    R@ _SAAW.RANGE-ROWS STREAMS-PA-RANGE-MAX
    R@ _SAAW.ADAPTER @ R@ _SAAW.ADAPTER-WORK @
        STREAMS-PA-RANGE-FIRST
    DUP IF
        SWAP DROP _SAA-ADAPTER>STATUS R> DROP EXIT
    THEN
    DROP R@ _SAAW.PAGE-COUNT !
    R> DROP STREAMS-ACQUISITION-S-OK ;

: _SAA-RANGE-AFTER  ( work -- status )
    >R
    R@ _SAAW.PREFIX STREAMS-PI-ACTIVE-ATTEMPT-PREFIX-SIZE
    R@ _SAAW.RESUME-KEY R@ _SAAW.RESUME-U @
    R@ _SAAW.RANGE-ROWS STREAMS-PA-RANGE-MAX
    R@ _SAAW.ADAPTER @ R@ _SAAW.ADAPTER-WORK @
        STREAMS-PA-RANGE-AFTER
    DUP IF
        SWAP DROP _SAA-ADAPTER>STATUS R> DROP EXIT
    THEN
    DROP R@ _SAAW.PAGE-COUNT !
    R> DROP STREAMS-ACQUISITION-S-OK ;

: _SAA-PROCESS-RANGE-PAGE  ( work -- status )
    DUP _SAAW.PAGE-COUNT @ DUP 0<
    OVER STREAMS-PA-RANGE-MAX > OR IF
        2DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    0 ?DO
        I OVER _SAAW-RANGE-ROW
            STREAMS-PA-RANGE-ROW-KEY$
        2DUP STREAMS-PI-ACTIVE-ATTEMPT-KEY-VALID? 0= IF
            2DROP DROP
            STREAMS-ACQUISITION-S-CORRUPT UNLOOP EXIT
        THEN
        2DROP
        I OVER _SAAW-RANGE-ROW
            STREAMS-PA-RANGE-ROW-RECORD$
        DUP SPREC-ATTEMPT-SIZE <> IF
            2DROP DROP
            STREAMS-ACQUISITION-S-CORRUPT UNLOOP EXIT
        THEN
        DROP
        DUP SPREC.KIND @ SPREC-KIND-ATTEMPT <> IF
            DROP DROP
            STREAMS-ACQUISITION-S-CORRUPT UNLOOP EXIT
        THEN
        OVER _SAA-COLLECT-ACTIVE
        DUP IF NIP UNLOOP EXIT THEN DROP
    LOOP
    DUP _SAAW.PAGE-COUNT @ 0= IF
        DROP STREAMS-ACQUISITION-S-OK EXIT
    THEN
    DUP _SAAW.PAGE-COUNT @ 1-
    OVER _SAAW-RANGE-ROW STREAMS-PA-RANGE-ROW-KEY$
    DUP STREAMS-PI-ACTIVE-ATTEMPT-KEY-SIZE <> IF
        2DROP DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    DUP 3 PICK _SAAW.RESUME-U !
    2 PICK _SAAW.RESUME-KEY SWAP MOVE
    DROP STREAMS-ACQUISITION-S-OK ;

: _SAA-COLLECT-RECOVERY  ( work -- status )
    >R
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF
        DROP R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    SAR.ACTIVE-COUNT @ DUP 0<
    OVER STREAMS-AUTHORITY-ACTIVE-MAX > OR IF
        DROP R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    R@ _SAAW.EXPECTED-ACTIVE !
    0 R@ _SAAW.RECOVERY-COUNT !
    0 R@ _SAAW.RESUME-U !
    R@ _SAAW.RECOVERY-HEADS
    STREAMS-AUTHORITY-ACTIVE-MAX OCHK-SOURCE-SIZE * 0 FILL
    R@ _SAAW.PREFIX STREAMS-PI-ACTIVE-ATTEMPT-PREFIX
        _SAA-PI>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-RANGE-FIRST DUP IF R> DROP EXIT THEN DROP
    BEGIN
        R@ _SAAW.PAGE-COUNT @ 0>
    WHILE
        R@ _SAA-PROCESS-RANGE-PAGE
        DUP IF R> DROP EXIT THEN DROP
        R@ _SAA-RANGE-AFTER
        DUP IF R> DROP EXIT THEN DROP
    REPEAT
    R@ _SAAW.RECOVERY-COUNT @
    R@ _SAAW.EXPECTED-ACTIVE @ <> IF
        R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-ACQUISITION-S-OK ;

\ ---------------------------------------------------------------------
\ Bounded INDETERMINATE recovery publication
\ ---------------------------------------------------------------------

: _SAA-MAKE-INDETERMINATE  ( attempt work -- status )
    >R
    DUP OCS.STATE @ OCHK-ATTEMPT-ACCEPTED <> IF
        DROP R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    MS@ OVER OCS.STARTED-MS @ MAX
        OVER OCS.FINISHED-MS !
    OCHK-O-INDETERMINATE OVER OCS.OUTCOME !
    OCHK-ATTEMPT-INDETERMINATE OVER OCS.STATE !
    DUP R@ _SAAW.CANDIDATE-RECORD
        SPREC-ATTEMPT-CONSTRUCT _SAA-SPREC>STATUS
    NIP R> DROP ;

: _SAA-PREPARE-RECOVERY  ( work -- status )
    >R
    R@ _SAAW.RECOVERY-N @ DUP 1 <
    OVER R@ _SAAW.RECOVERY-COUNT @ > OR IF
        DROP R> DROP STREAMS-ACQUISITION-S-INVALID EXIT
    THEN
    DROP
    R@ _SAA-MUTATION-CAPACITY DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    SAR.ACTIVE-COUNT @ R@ _SAAW.RECOVERY-N @ < IF
        R> DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    R>
    DUP _SAAW.RECOVERY-N @ 0 ?DO
        I OVER _SAAW-RECOVERY-HEAD
        OVER _SAA-MAKE-INDETERMINATE
        DUP IF NIP UNLOOP EXIT THEN DROP
    LOOP
    DROP STREAMS-ACQUISITION-S-OK ;

: _SAA-WRITE-RECOVERY-HEAD  ( attempt work -- status )
    >R
    DUP R@ _SAAW.CANDIDATE-RECORD
        SPREC-ATTEMPT-CONSTRUCT _SAA-SPREC>STATUS
    DUP IF NIP R> DROP EXIT THEN DROP
    DUP R@ _SAA-HISTORY-KEY
    DUP IF NIP R> DROP EXIT THEN DROP
    DUP OCS.SOURCE-ID R@ _SAA-ACTIVE-KEY
    DUP IF NIP R> DROP EXIT THEN DROP
    DROP
    R@ _SAA-APPEND-CANDIDATE
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-PUT-HISTORY
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-DELETE-ACTIVE
    R> DROP ;

: _SAA-PUBLISH-RECOVERY  ( work -- status )
    DUP _SAA-BEGIN-TX DUP IF NIP EXIT THEN DROP
    DUP _SAAW.RECOVERY-N @ 0 ?DO
        I OVER _SAAW-RECOVERY-HEAD
        OVER _SAA-WRITE-RECOVERY-HEAD
        DUP IF NIP UNLOOP EXIT THEN DROP
    LOOP
    DUP _SAAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF
        2DROP STREAMS-ACQUISITION-S-CORRUPT EXIT
    THEN
    OVER _SAAW.RECOVERY-N @ NEGATE
        SWAP SAR.ACTIVE-COUNT +!
    _SAA-COMMIT ;

: _SAA-RECOVER-NEXT-RUN  ( work -- status )
    >R
    R@ _SAA-READY DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-COLLECT-RECOVERY DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.RECOVERY-COUNT @ 0= IF
        R> DROP STREAMS-ACQUISITION-S-NOT-FOUND EXIT
    THEN
    1 R@ _SAAW.RECOVERY-N !
    R@ _SAA-PREPARE-RECOVERY DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-PUBLISH-RECOVERY DUP IF R> DROP EXIT THEN DROP
    0 R@ _SAAW-RECOVERY-HEAD R@ _SAAW.OUTPUT-A @
        OCHK-SOURCE-SIZE MOVE
    R> DROP STREAMS-ACQUISITION-S-OK ;

: _SAA-RECOVER-ALL-RUN  ( work -- status )
    >R
    R@ _SAA-READY DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-COLLECT-RECOVERY DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.RECOVERY-COUNT @
    R@ _SAAW.OUTPUT-CAPACITY @ > IF
        R> DROP STREAMS-ACQUISITION-S-CAPACITY EXIT
    THEN
    R@ _SAAW.RECOVERY-COUNT @ DUP R@ _SAAW.RESULT-COUNT !
    DUP 0= IF
        DROP R> DROP STREAMS-ACQUISITION-S-OK EXIT
    THEN
    R@ _SAAW.RECOVERY-N !
    R@ _SAA-PREPARE-RECOVERY DUP IF R> DROP EXIT THEN DROP
    R@ _SAA-PUBLISH-RECOVERY DUP IF R> DROP EXIT THEN DROP
    R@ _SAAW.RECOVERY-HEADS R@ _SAAW.OUTPUTS-A @
    R@ _SAAW.RECOVERY-N @ OCHK-SOURCE-SIZE * MOVE
    R> DROP STREAMS-ACQUISITION-S-OK ;

