: STREAMS-EXECUTION-PROFILE-RUNTIME-BYTES  ( profile -- bytes )
    DUP STREAMS-RUNTIME-PROFILE-VALID? 0= IF DROP 0 EXIT THEN
    DUP STREAMS-RUNTIME-PAYLOAD-CAPACITY
    OVER STREAMS-RUNTIME-OPERATION-CAPACITY +
    SWAP STREAMS-PAYLOAD-SEGMENT-SIZE
        STREAMS-RUNTIME-SEGMENT-TABLE-BYTES +
    STREAMS-FLOW-SIZE +
    STREAMS-PAYLOAD-SIZE 2 * + ;

: STREAMS-EXECUTION-FLOW-RUNTIME-BYTES  ( flow -- bytes )
    DUP STREAMS-FLOW-VALID? 0= IF DROP 0 EXIT THEN
    SFLOW.PROFILE @ STREAMS-EXECUTION-PROFILE-RUNTIME-BYTES ;

: _SPOOL-ENTRY-SNAPSHOT-CURRENT?  ( entry -- flag )
    >R
    R@ _SPE.FLOW @ DUP _SFLOW-HEADER? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.BINDING-EPOCH @ R@ _SPE.BINDING-EPOCH @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.PROFILE @ DUP STREAMS-RUNTIME-PROFILE-VALID? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    R@ _SPE.PROFILE @ <> IF DROP R> DROP 0 EXIT THEN
    DUP SFLOW.INGRESS-CARRIER R@ _SPE.INGRESS-CARRIER @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.EGRESS-CARRIER R@ _SPE.EGRESS-CARRIER @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.OPERATION R@ _SPE.OPERATION @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.OPERATION-CAPACITY
        R@ _SPE.OPERATION-CAPACITY @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.INPUT-CONNECTOR @ R@ _SPE.INPUT-CONNECTOR @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.OUTPUT-CONNECTOR @ R@ _SPE.OUTPUT-CONNECTOR @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.STATE @ DUP STREAMS-FLOW-STATE-IDLE <
        SWAP STREAMS-FLOW-STATE-TERMINAL > OR IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.BUSY @ DUP 0<> SWAP -1 <> AND IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _SPE.PROFILE @ STREAMS-EXECUTION-PROFILE-RUNTIME-BYTES
        R@ _SPE.RUNTIME-BYTES @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _SPE.OCCUPIED @ DUP 0= SWAP -1 = OR 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _SPE.OCCUPIED @ IF
        DROP R@ _SPE.LEASE @ 0> R> DROP EXIT
    THEN
    R@ _SPE.LEASE @ 0<> IF DROP R> DROP 0 EXIT THEN
    DUP SFLOW.BUSY @ 0=
    SWAP SFLOW.STATE @ STREAMS-FLOW-STATE-IDLE = AND
    R> DROP ;

: _SPOOL-ENTRY-CURRENT?  ( entry -- flag )
    DUP _SPOOL-ENTRY-SNAPSHOT-CURRENT? 0= IF DROP 0 EXIT THEN
    _SPE.FLOW @ STREAMS-FLOW-VALID? ;

