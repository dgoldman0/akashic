: STREAMS-EXECUTION-POOL-INIT  ( entries capacity pool -- status )
    DUP 0= IF 2DROP DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP STREAMS-EXECUTION-POOL-SIZE MSPAN-NONWRAPPING? 0= IF
        2DROP DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SPOOL-HEADER? IF
        DUP _SPOOL.STATE @ _SPOOL-STATE-SEALED =
        OVER _SPOOL.BUSY @ 0<> OR
        OVER _SPOOL.ACTIVE @ 0<> OR
        OVER _SPOOL.BOUND @ 0<> OR IF
            2DROP DROP STREAMS-FLOW-S-BUSY EXIT
        THEN
    THEN
    OVER DUP 1 <
    SWAP _SPOOL-CELL-MAX STREAMS-EXECUTION-POOL-SIZE -
        STREAMS-EXECUTION-ENTRY-SIZE / > OR IF
        2DROP DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    2 PICK 0= IF
        2DROP DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    2 PICK 2 PICK STREAMS-EXECUTION-ENTRY-SIZE *
        MSPAN-NONWRAPPING? 0= IF
        2DROP DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    2 PICK 2 PICK STREAMS-EXECUTION-ENTRY-SIZE *
        2 PICK STREAMS-EXECUTION-POOL-SIZE MSPAN-OVERLAP? IF
        2DROP DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    >R
    2DUP STREAMS-EXECUTION-ENTRY-SIZE * 0 FILL
    R@ STREAMS-EXECUTION-POOL-SIZE 0 FILL
    _SPOOL-MAGIC R@ _SPOOL.MAGIC !
    STREAMS-EXECUTION-POOL-SIZE R@ _SPOOL.SIZE !
    _SPOOL-STATE-BUILDING R@ _SPOOL.STATE !
    DUP R@ _SPOOL.CAPACITY !
    OVER R@ _SPOOL.ENTRIES !
    DUP STREAMS-EXECUTION-ENTRY-SIZE *
        STREAMS-EXECUTION-POOL-SIZE + R@ _SPOOL.RUNTIME-BYTES !
    2DROP
    R> DROP STREAMS-FLOW-S-OK ;

: _SPOOL-FLOW-AVAILABLE?  ( flow -- flag )
    DUP STREAMS-FLOW-VALID? 0= IF DROP 0 EXIT THEN
    DUP SFLOW.BUSY @ IF DROP 0 EXIT THEN
    SFLOW.STATE @ STREAMS-FLOW-STATE-IDLE = ;

\ Does an arbitrary span avoid every mutable byte owned by one valid flow cell?
: _SPOOL-SPAN-FLOW-DISJOINT-VALID?  ( address length flow -- flag )
    >R
    2DUP R@ STREAMS-FLOW-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP 0 EXIT
    THEN
    2DUP R@ SFLOW.INGRESS-CARRIER
        _SPAY-SPAN-DISJOINT-VALID? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    2DUP R@ SFLOW.EGRESS-CARRIER
        _SPAY-SPAN-DISJOINT-VALID? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    R@ SFLOW.OPERATION R@ SFLOW.OPERATION-CAPACITY
        MSPAN-OVERLAP? 0=
    R> DROP ;

: _SPOOL-SPAN-FLOW-DISJOINT?  ( address length flow -- flag )
    >R
    R@ STREAMS-FLOW-VALID? 0= IF 2DROP R> DROP 0 EXIT THEN
    R> _SPOOL-SPAN-FLOW-DISJOINT-VALID? ;

: _SPOOL-SPAN-METADATA-DISJOINT?  ( address length pool -- flag )
    >R
    2DUP R@ STREAMS-EXECUTION-POOL-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP 0 EXIT
    THEN
    R@ _SPOOL.ENTRIES @
    R@ _SPOOL.CAPACITY @ STREAMS-EXECUTION-ENTRY-SIZE *
    MSPAN-OVERLAP? 0=
    R> DROP ;

: _SPOOL-FLOW-CONNECTORS-METADATA-DISJOINT?  ( flow pool -- flag )
    >R
    DUP SFLOW.INPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
        R@ _SPOOL-SPAN-METADATA-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    SFLOW.OUTPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
    R> _SPOOL-SPAN-METADATA-DISJOINT? ;

: _SPOOL-FLOW-METADATA-DISJOINT-VALID?  ( flow pool -- flag )
    >R
    R@ STREAMS-EXECUTION-POOL-SIZE 2 PICK
        _SPOOL-SPAN-FLOW-DISJOINT-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _SPOOL.ENTRIES @
    R@ _SPOOL.CAPACITY @ STREAMS-EXECUTION-ENTRY-SIZE *
    2 PICK _SPOOL-SPAN-FLOW-DISJOINT-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R> _SPOOL-FLOW-CONNECTORS-METADATA-DISJOINT? ;

: _SPOOL-FLOW-METADATA-DISJOINT?  ( flow pool -- flag )
    >R
    DUP STREAMS-FLOW-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    R> _SPOOL-FLOW-METADATA-DISJOINT-VALID? ;

: _SPOOL-FLOW-CONNECTORS-DISJOINT-VALID?
  ( connector-owner-flow other-flow -- flag )
    >R
    DUP SFLOW.INPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
        R@ _SPOOL-SPAN-FLOW-DISJOINT-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    SFLOW.OUTPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
    R> _SPOOL-SPAN-FLOW-DISJOINT-VALID? ;

: _SPOOL-CONNECTORS-SAME-OR-DISJOINT?  ( connector-a connector-b -- flag )
    2DUP = IF 2DROP -1 EXIT THEN
    SWAP STREAMS-CONNECTOR-SIZE
    ROT STREAMS-CONNECTOR-SIZE MSPAN-OVERLAP? 0= ;

: _SPOOL-FLOW-OWN-CONNECTORS-SAME-OR-DISJOINT?  ( flow -- flag )
    DUP SFLOW.INPUT-CONNECTOR @
    SWAP SFLOW.OUTPUT-CONNECTOR @
    _SPOOL-CONNECTORS-SAME-OR-DISJOINT? ;

\ A sealed flow can outlive the configuration call which originally proved
\ these relationships.  Recheck its complete intra-cell isolation instead of
\ treating individually valid carrier and connector descriptors as sufficient.
: _SPOOL-FLOW-SELF-DISJOINT-VALID?  ( flow -- flag )
    DUP _SFLOW-WORKSPACE-DISJOINT? 0= IF DROP 0 EXIT THEN
    DUP SFLOW.INPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
        2 PICK STREAMS-FLOW-SIZE MSPAN-OVERLAP? IF DROP 0 EXIT THEN
    DUP SFLOW.OUTPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
        2 PICK STREAMS-FLOW-SIZE MSPAN-OVERLAP? IF DROP 0 EXIT THEN
    DUP SFLOW.INPUT-CONNECTOR @ OVER
        _SFLOW-CONNECTOR-WORKSPACE-DISJOINT? 0= IF DROP 0 EXIT THEN
    DUP SFLOW.OUTPUT-CONNECTOR @ OVER
        _SFLOW-CONNECTOR-WORKSPACE-DISJOINT? 0= IF DROP 0 EXIT THEN
    _SPOOL-FLOW-OWN-CONNECTORS-SAME-OR-DISJOINT? ;

: _SPOOL-FLOW-CONNECTORS-SAME-OR-DISJOINT?  ( flow-a flow-b -- flag )
    >R
    DUP _SPOOL-FLOW-OWN-CONNECTORS-SAME-OR-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _SPOOL-FLOW-OWN-CONNECTORS-SAME-OR-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.INPUT-CONNECTOR @
        R@ SFLOW.INPUT-CONNECTOR @
        _SPOOL-CONNECTORS-SAME-OR-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.INPUT-CONNECTOR @
        R@ SFLOW.OUTPUT-CONNECTOR @
        _SPOOL-CONNECTORS-SAME-OR-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.OUTPUT-CONNECTOR @
        R@ SFLOW.INPUT-CONNECTOR @
        _SPOOL-CONNECTORS-SAME-OR-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    SFLOW.OUTPUT-CONNECTOR @
    R> SFLOW.OUTPUT-CONNECTOR @
    _SPOOL-CONNECTORS-SAME-OR-DISJOINT? ;

\ Two valid cells are distinct only when their complete mutable footprints are.
: _SPOOL-FLOWS-DISJOINT-VALID?  ( flow-a flow-b -- flag )
    >R
    DUP R@ _SPOOL-FLOW-CONNECTORS-DISJOINT-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R@ OVER _SPOOL-FLOW-CONNECTORS-DISJOINT-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP R@ _SPOOL-FLOW-CONNECTORS-SAME-OR-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP STREAMS-FLOW-SIZE R@
        _SPOOL-SPAN-FLOW-DISJOINT-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R@ STREAMS-FLOW-SIZE 2 PICK
        _SPOOL-SPAN-FLOW-DISJOINT-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.INGRESS-CARRIER R@ SFLOW.INGRESS-CARRIER
        _SPAY-DISJOINT-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.INGRESS-CARRIER R@ SFLOW.EGRESS-CARRIER
        _SPAY-DISJOINT-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.EGRESS-CARRIER R@ SFLOW.INGRESS-CARRIER
        _SPAY-DISJOINT-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.EGRESS-CARRIER R@ SFLOW.EGRESS-CARRIER
        _SPAY-DISJOINT-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.OPERATION OVER SFLOW.OPERATION-CAPACITY R@
        _SPOOL-SPAN-FLOW-DISJOINT-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R@ SFLOW.OPERATION R@ SFLOW.OPERATION-CAPACITY 2 PICK
        _SPOOL-SPAN-FLOW-DISJOINT-VALID?
    NIP R> DROP ;

: _SPOOL-FLOWS-DISJOINT?  ( flow-a flow-b -- flag )
    2DUP STREAMS-FLOW-VALID? SWAP STREAMS-FLOW-VALID? AND 0= IF
        2DROP 0 EXIT
    THEN
    _SPOOL-FLOWS-DISJOINT-VALID? ;

: _SPOOL-FLOW-ISOLATED-CURRENT?  ( flow pool -- flag )
    OVER STREAMS-FLOW-VALID? 0= IF 2DROP 0 EXIT THEN
    OVER _SPOOL-FLOW-SELF-DISJOINT-VALID? 0= IF
        2DROP 0 EXIT
    THEN
    2DUP _SPOOL-FLOW-METADATA-DISJOINT-VALID? 0= IF
        2DROP 0 EXIT
    THEN
    DUP _SPOOL.BOUND @ 0 ?DO
        OVER I 2 PICK _SPOOL-ENTRY _SPE.FLOW @
        2DUP = IF
            2DROP
        ELSE
            _SPOOL-FLOWS-DISJOINT? 0= IF
                2DROP 0 UNLOOP EXIT
            THEN
        THEN
    LOOP
    2DROP -1 ;

: _SPOOL-BOUND-FLOW-UNIQUE?  ( flow pool -- flag )
    DUP _SPOOL.BOUND @ 0 ?DO
        I OVER _SPOOL-ENTRY
        DUP _SPOOL-ENTRY-CURRENT? 0= IF
            DROP 2DROP 0 UNLOOP EXIT
        THEN
        DUP _SPE.FLOW @
            _SPOOL-FLOW-SELF-DISJOINT-VALID? 0= IF
            DROP 2DROP 0 UNLOOP EXIT
        THEN
        DUP _SPE.FLOW @ 2 PICK
            _SPOOL-FLOW-METADATA-DISJOINT-VALID? 0= IF
            DROP 2DROP 0 UNLOOP EXIT
        THEN
        2 PICK OVER _SPE.FLOW @
            _SPOOL-FLOWS-DISJOINT? 0= IF
            DROP 2DROP 0 UNLOOP EXIT
        THEN
        DROP
    LOOP
    2DROP -1 ;

: _SPOOL-ENTRIES-DISTINCT?  ( entry-a entry-b -- flag )
    2DUP _SPE.FLOW @ SWAP _SPE.FLOW @
        _SPOOL-FLOWS-DISJOINT-VALID? 0= IF 2DROP 0 EXIT THEN
    OVER _SPE.OCCUPIED @ OVER _SPE.OCCUPIED @ AND IF
        OVER _SPE.LEASE @ OVER _SPE.LEASE @ <>
        NIP NIP EXIT
    THEN
    2DROP -1 ;

: _SPOOL-ALL-FLOWS-UNIQUE?  ( pool -- flag )
    DUP _SPOOL.BOUND @ 0 ?DO
        DUP _SPOOL.BOUND @ I 1+ ?DO
            J OVER _SPOOL-ENTRY
            I 2 PICK _SPOOL-ENTRY
            _SPOOL-ENTRIES-DISTINCT? 0= IF
                DROP 0 UNLOOP UNLOOP EXIT
            THEN
        LOOP
    LOOP
    DROP -1 ;

: _SPOOL-ALL-FLOW-POINTERS-UNIQUE?  ( pool -- flag )
    DUP _SPOOL.BOUND @ 0 ?DO
        DUP _SPOOL.BOUND @ I 1+ ?DO
            J OVER _SPOOL-ENTRY _SPE.FLOW @
            I 2 PICK _SPOOL-ENTRY _SPE.FLOW @ = IF
                DROP 0 UNLOOP UNLOOP EXIT
            THEN
        LOOP
    LOOP
    DROP -1 ;

: _SPOOL-ALL-ENTRY-SNAPSHOTS-CURRENT?  ( pool -- flag )
    DUP _SPOOL.BOUND @ 0 ?DO
        I OVER _SPOOL-ENTRY
        DUP _SPOOL-ENTRY-SNAPSHOT-CURRENT? 0= IF
            2DROP 0 UNLOOP EXIT
        THEN
        DUP _SPE.OCCUPIED @ IF
            DUP _SPE.LEASE @ 2 PICK _SPOOL.GENERATION @ > IF
                2DROP 0 UNLOOP EXIT
            THEN
        THEN
        DROP
    LOOP
    DROP -1 ;

: _SPOOL-ALL-ENTRIES-CURRENT?  ( pool -- flag )
    DUP _SPOOL.BOUND @ 0 ?DO
        I OVER _SPOOL-ENTRY DUP _SPOOL-ENTRY-CURRENT? 0= IF
            2DROP 0 UNLOOP EXIT
        THEN
        DUP _SPE.FLOW @
            _SPOOL-FLOW-SELF-DISJOINT-VALID? 0= IF
            2DROP 0 UNLOOP EXIT
        THEN
        DUP _SPE.FLOW @ 2 PICK
            _SPOOL-FLOW-METADATA-DISJOINT-VALID? 0= IF
            2DROP 0 UNLOOP EXIT
        THEN
        DUP _SPE.OCCUPIED @ IF
            DUP _SPE.LEASE @ 2 PICK _SPOOL.GENERATION @ > IF
                2DROP 0 UNLOOP EXIT
            THEN
        THEN
        DROP
    LOOP
    DROP -1 ;

: _SPOOL-OCCUPIED-COUNT  ( pool -- count )
    0 SWAP
    DUP _SPOOL.BOUND @ 0 ?DO
        I OVER _SPOOL-ENTRY _SPE.OCCUPIED @ IF
            SWAP 1+ SWAP
        THEN
    LOOP
    DROP ;

: _SPOOL-CURRENT-RUNTIME-SUM  ( pool -- bytes flag )
    DUP _SPOOL.CAPACITY @ STREAMS-EXECUTION-ENTRY-SIZE *
        STREAMS-EXECUTION-POOL-SIZE + SWAP
    DUP _SPOOL.BOUND @ 0 ?DO
        I OVER _SPOOL-ENTRY _SPE.RUNTIME-BYTES @
        DUP _SPOOL-CELL-MAX SWAP - 3 PICK SWAP > IF
            2DROP DROP 0 0 UNLOOP EXIT
        THEN
        ROT + SWAP
    LOOP
    DROP -1 ;

: _SPOOL-SEALED-OPERATIONAL?  ( pool -- flag )
    DUP _SPOOL-HEADER? 0= IF DROP 0 EXIT THEN
    DUP _SPOOL-SHAPE? 0= IF DROP 0 EXIT THEN
    DUP _SPOOL.STATE @ _SPOOL-STATE-SEALED <> IF DROP 0 EXIT THEN
    DUP _SPOOL.BOUND @ OVER _SPOOL.CAPACITY @ <> IF DROP 0 EXIT THEN
    DUP _SPOOL-ALL-ENTRY-SNAPSHOTS-CURRENT? 0= IF DROP 0 EXIT THEN
    DUP _SPOOL-OCCUPIED-COUNT OVER _SPOOL.ACTIVE @ <> IF
        DROP 0 EXIT
    THEN
    DUP _SPOOL-CURRENT-RUNTIME-SUM
    0= IF 2DROP 0 EXIT THEN
    OVER _SPOOL.RUNTIME-BYTES @ <> IF DROP 0 EXIT THEN
    DUP _SPOOL-ALL-FLOW-POINTERS-UNIQUE? 0= IF DROP 0 EXIT THEN
    DROP -1 ;

: _SPOOL-SEALED-DEEP?  ( pool -- flag )
    DUP _SPOOL-SEALED-OPERATIONAL? 0= IF DROP 0 EXIT THEN
    DUP _SPOOL-ALL-ENTRIES-CURRENT? 0= IF DROP 0 EXIT THEN
    DUP _SPOOL-ALL-FLOWS-UNIQUE? 0= IF DROP 0 EXIT THEN
    DROP -1 ;

: STREAMS-EXECUTION-POOL-VALID?  ( pool -- flag )
    DUP _SPOOL-HEADER? 0= IF DROP 0 EXIT THEN
    DUP _SPOOL-SHAPE? 0= IF DROP 0 EXIT THEN
    DUP _SPOOL.STATE @ _SPOOL-STATE-SEALED = IF
        DUP _SPOOL.BOUND @ OVER _SPOOL.CAPACITY @ = 0= IF
            DROP 0 EXIT
        THEN
        DUP _SPOOL-SEALED-DEEP? 0= IF DROP 0 EXIT THEN
    THEN
    DROP -1 ;

: STREAMS-EXECUTION-POOL-CAPACITY@  ( pool -- count )
    DUP STREAMS-EXECUTION-POOL-VALID? 0= IF DROP 0 EXIT THEN
    _SPOOL.CAPACITY @ ;

: STREAMS-EXECUTION-POOL-ACTIVE@  ( pool -- count )
    DUP STREAMS-EXECUTION-POOL-VALID? 0= IF DROP 0 EXIT THEN
    _SPOOL.ACTIVE @ ;

: STREAMS-EXECUTION-POOL-LEASE-AVAILABLE?  ( pool -- flag )
    DUP STREAMS-EXECUTION-POOL-VALID? 0= IF DROP 0 EXIT THEN
    _SPOOL.GENERATION @ _SPOOL-CELL-MAX < ;

: STREAMS-EXECUTION-POOL-RUNTIME-BYTES@  ( pool -- bytes )
    DUP STREAMS-EXECUTION-POOL-VALID? 0= IF DROP 0 EXIT THEN
    _SPOOL.RUNTIME-BYTES @ ;

: STREAMS-EXECUTION-POOL-ENTRY-RUNTIME-BYTES@
  ( index pool -- bytes )
    DUP STREAMS-EXECUTION-POOL-VALID? 0= IF 2DROP 0 EXIT THEN
    OVER 0< IF 2DROP 0 EXIT THEN
    2DUP _SPOOL.BOUND @ >= IF 2DROP 0 EXIT THEN
    _SPOOL-ENTRY _SPE.RUNTIME-BYTES @ ;

: STREAMS-EXECUTION-POOL-BIND  ( flow pool -- status )
    DUP _SPOOL-HEADER? 0= IF 2DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP _SPOOL-SHAPE? 0= IF 2DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP _SPOOL.BUSY @ IF 2DROP STREAMS-FLOW-S-BUSY EXIT THEN
    DUP _SPOOL.STATE @ _SPOOL-STATE-BUILDING <> IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SPOOL.BOUND @ OVER _SPOOL.CAPACITY @ >= IF
        2DROP STREAMS-FLOW-S-FULL EXIT
    THEN
    OVER _SPOOL-FLOW-AVAILABLE? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    OVER _SPOOL-FLOW-SELF-DISJOINT-VALID? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    2DUP _SPOOL-FLOW-METADATA-DISJOINT? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    2DUP _SPOOL-BOUND-FLOW-UNIQUE? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    OVER STREAMS-EXECUTION-FLOW-RUNTIME-BYTES
    DUP 0= IF
        DROP 2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SPOOL-CELL-MAX SWAP - 2 PICK _SPOOL.RUNTIME-BYTES @
        SWAP > IF
        DROP 2DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    -1 2 PICK _SPOOL.BUSY !
    DUP 2 PICK _SPOOL.ARG-INGRESS !
    DROP
    DUP _SPOOL.BOUND @ OVER _SPOOL-ENTRY
    2 PICK OVER _SPE.FLOW !
    OVER _SPOOL.ARG-INGRESS @ OVER _SPE.RUNTIME-BYTES !
    2 PICK SFLOW.BINDING-EPOCH @ OVER _SPE.BINDING-EPOCH !
    2 PICK SFLOW.PROFILE @ OVER _SPE.PROFILE !
    2 PICK SFLOW.INGRESS-CARRIER OVER _SPE.INGRESS-CARRIER !
    2 PICK SFLOW.EGRESS-CARRIER OVER _SPE.EGRESS-CARRIER !
    2 PICK SFLOW.OPERATION OVER _SPE.OPERATION !
    2 PICK SFLOW.OPERATION-CAPACITY OVER _SPE.OPERATION-CAPACITY !
    2 PICK SFLOW.INPUT-CONNECTOR @ OVER _SPE.INPUT-CONNECTOR !
    2 PICK SFLOW.OUTPUT-CONNECTOR @ OVER _SPE.OUTPUT-CONNECTOR !
    DROP
    DUP _SPOOL.ARG-INGRESS @ OVER _SPOOL.RUNTIME-BYTES +!
    1 OVER _SPOOL.BOUND +!
    NIP
    STREAMS-FLOW-S-OK SWAP _SPOOL-LEAVE ;

: STREAMS-EXECUTION-POOL-SEAL  ( pool -- status )
    DUP _SPOOL-HEADER? 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP _SPOOL-SHAPE? 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP _SPOOL.BUSY @ IF DROP STREAMS-FLOW-S-BUSY EXIT THEN
    DUP _SPOOL.STATE @ _SPOOL-STATE-BUILDING <> IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SPOOL.BOUND @ OVER _SPOOL.CAPACITY @ <> IF
        DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    DUP _SPOOL.ACTIVE @ IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP _SPOOL.GENERATION @ IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP _SPOOL.CURSOR @ IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    -1 OVER _SPOOL.BUSY !
    _SPOOL-STATE-SEALED OVER _SPOOL.STATE !
    DUP _SPOOL-SEALED-DEEP? 0= IF
        _SPOOL-STATE-BUILDING OVER _SPOOL.STATE !
        STREAMS-FLOW-S-INVALID SWAP _SPOOL-LEAVE EXIT
    THEN
    STREAMS-FLOW-S-OK SWAP _SPOOL-LEAVE ;

