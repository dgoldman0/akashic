: _SPOOL-ENTRY  ( index pool -- entry )
    _SPOOL.ENTRIES @ SWAP STREAMS-EXECUTION-ENTRY-SIZE * + ;

: _SPOOL-CLEAR-ARGS  ( pool -- )
    0 OVER _SPOOL.ARG-INGRESS !
    0 OVER _SPOOL.ARG-EGRESS !
    0 OVER _SPOOL.ARG-FLOW !
    0 OVER _SPOOL.ARG-LEASE !
    0 OVER _SPOOL.ARG-ENTRY !
    0 SWAP _SPOOL.ARG-FREE ! ;

: _SPOOL-LEAVE  ( status pool -- status )
    DUP _SPOOL-CLEAR-ARGS
    0 SWAP _SPOOL.BUSY ! ;

: _SPOOL-ACQUIRE-FAIL  ( status pool -- flow lease status )
    _SPOOL-LEAVE >R 0 0 R> ;

: _SPOOL-HEADER?  ( pool -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-EXECUTION-POOL-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP 0 EXIT
    THEN
    DUP _SPOOL.MAGIC @ _SPOOL-MAGIC =
    OVER _SPOOL.SIZE @ STREAMS-EXECUTION-POOL-SIZE = AND
    OVER _SPOOL.STATE @ DUP _SPOOL-STATE-BUILDING =
        SWAP _SPOOL-STATE-SEALED = OR AND
    SWAP _SPOOL.BUSY @ DUP 0= SWAP -1 = OR AND ;

: _SPOOL-STORAGE?  ( pool -- flag )
    DUP _SPOOL.CAPACITY @ DUP 1 <
    SWAP _SPOOL-CELL-MAX STREAMS-EXECUTION-POOL-SIZE -
        STREAMS-EXECUTION-ENTRY-SIZE / > OR IF
        DROP 0 EXIT
    THEN
    DUP _SPOOL.ENTRIES @ DUP 0= IF 2DROP 0 EXIT THEN
    OVER _SPOOL.CAPACITY @ STREAMS-EXECUTION-ENTRY-SIZE *
    2DUP MSPAN-NONWRAPPING? 0= IF 2DROP DROP 0 EXIT THEN
    2 PICK STREAMS-EXECUTION-POOL-SIZE MSPAN-OVERLAP? 0= NIP ;

: _SPOOL-SHAPE?  ( pool -- flag )
    DUP _SPOOL-STORAGE? 0= IF DROP 0 EXIT THEN
    DUP _SPOOL.BOUND @ DUP 0<
        SWAP 2 PICK _SPOOL.CAPACITY @ > OR IF DROP 0 EXIT THEN
    DUP _SPOOL.ACTIVE @ DUP 0<
        SWAP 2 PICK _SPOOL.BOUND @ > OR IF DROP 0 EXIT THEN
    DUP _SPOOL.CURSOR @ DUP 0<
        SWAP 2 PICK _SPOOL.CAPACITY @ >= OR IF DROP 0 EXIT THEN
    DUP _SPOOL.GENERATION @ 0< IF DROP 0 EXIT THEN
    DUP _SPOOL.RUNTIME-BYTES @
    OVER _SPOOL.CAPACITY @ STREAMS-EXECUTION-ENTRY-SIZE *
        STREAMS-EXECUTION-POOL-SIZE + < IF DROP 0 EXIT THEN
    DROP -1 ;

