\ =====================================================================
\ execution-pool.f - bounded caller-owned Streams execution-cell pool
\ =====================================================================
\ The pool owns no storage.  Its caller supplies one pool descriptor, one
\ fixed entry array, and each already configured flow plus its profile
\ workspaces.  Binding never retargets a flow.  Acquisition selects the
\ first fitting free cell from a rotating cursor and gives it a pool-wide,
\ strictly increasing lease.  Release requires that exact flow/lease pair
\ and an already-idle flow.
\
\ Runtime byte measurements include the pool descriptor and entry array.
\ Each bound entry adds its flow descriptor, two payload descriptors, both
\ payload byte regions, both segment tables, and its connector-operation
\ workspace.  These are live-memory measurements, never persistent formats.
\ =====================================================================

PROVIDED akashic-streams-execution-pool

REQUIRE flow-core.f
REQUIRE runtime-profile.f

