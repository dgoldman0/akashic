: _SPOOL-NEXT-INDEX  ( pool -- )
    DUP _SPOOL.ARG-ENTRY @ 1+
    2DUP SWAP _SPOOL.CAPACITY @ >= IF
        DROP 0
    THEN
    SWAP _SPOOL.ARG-ENTRY ! ;

: _SPOOL-ENTRY-FITS?  ( entry pool -- flag )
    >R _SPE.FLOW @ SFLOW.PROFILE @
    DUP STREAMS-RUNTIME-INGRESS-CAPACITY R@ _SPOOL.ARG-INGRESS @ >=
    SWAP STREAMS-RUNTIME-EGRESS-CAPACITY R> _SPOOL.ARG-EGRESS @ >=
    AND ;

: _SPOOL-ACQUIRE-SELECTED  ( pool -- flow lease status )
    DUP _SPOOL.GENERATION @ 1+ OVER _SPOOL.ARG-LEASE !
    DUP _SPOOL.ARG-LEASE @ OVER _SPOOL.GENERATION !
    DUP _SPOOL.ARG-ENTRY @ OVER _SPOOL-ENTRY
        OVER _SPOOL.ARG-FREE !
    DUP _SPOOL.ARG-FREE @ _SPE.FLOW @ OVER _SPOOL.ARG-FLOW !
    DUP _SPOOL.ARG-LEASE @
        OVER _SPOOL.ARG-FREE @ _SPE.LEASE !
    -1 OVER _SPOOL.ARG-FREE @ _SPE.OCCUPIED !
    1 OVER _SPOOL.ACTIVE +!
    DUP _SPOOL-NEXT-INDEX
    DUP _SPOOL.ARG-ENTRY @ OVER _SPOOL.CURSOR !
    DUP _SPOOL.ARG-LEASE @ >R
    DUP _SPOOL.ARG-FLOW @ >R
    STREAMS-FLOW-S-OK SWAP _SPOOL-LEAVE
    R> R> ROT ;

: STREAMS-EXECUTION-POOL-ACQUIRE
  ( required-ingress required-egress pool -- flow lease status )
    >R
    R@ _SPOOL-SEALED-OPERATIONAL? 0= IF
        2DROP R> DROP 0 0 STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ _SPOOL.STATE @ _SPOOL-STATE-SEALED <> IF
        2DROP R> DROP 0 0 STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ _SPOOL.BUSY @ IF
        2DROP R> DROP 0 0 STREAMS-FLOW-S-BUSY EXIT
    THEN
    R@ _SPOOL.ACTIVE @ R@ _SPOOL.CAPACITY @ = IF
        2DROP R> DROP 0 0 STREAMS-FLOW-S-FULL EXIT
    THEN
    DUP 0< 2 PICK 0< OR IF
        2DROP R> DROP 0 0 STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ _SPOOL.GENERATION @ _SPOOL-CELL-MAX >= IF
        2DROP R> DROP 0 0 STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    -1 R@ _SPOOL.BUSY !
    DUP R@ _SPOOL.ARG-EGRESS !
    SWAP R@ _SPOOL.ARG-INGRESS !
    DROP
    R> DUP _SPOOL.CURSOR @ OVER _SPOOL.ARG-ENTRY !
    0 OVER _SPOOL.ARG-FREE !
    DUP _SPOOL.CAPACITY @ 0 ?DO
        DUP _SPOOL.ARG-ENTRY @ OVER _SPOOL-ENTRY
        DUP _SPOOL-ENTRY-SNAPSHOT-CURRENT? 0= IF
            DROP STREAMS-FLOW-S-INVALID SWAP _SPOOL-ACQUIRE-FAIL
            UNLOOP EXIT
        THEN
        DUP _SPE.OCCUPIED @ 0= IF
            -1 2 PICK _SPOOL.ARG-FREE !
            2DUP SWAP _SPOOL-ENTRY-FITS? IF
                DUP _SPE.FLOW @ 2 PICK
                    _SPOOL-FLOW-ISOLATED-CURRENT? 0= IF
                    DROP STREAMS-FLOW-S-INVALID
                    SWAP _SPOOL-ACQUIRE-FAIL UNLOOP EXIT
                THEN
                DROP _SPOOL-ACQUIRE-SELECTED UNLOOP EXIT
            THEN
        THEN
        DROP
        DUP _SPOOL-NEXT-INDEX
    LOOP
    DUP _SPOOL.ARG-FREE @ IF
        STREAMS-FLOW-S-CAPACITY
    ELSE
        STREAMS-FLOW-S-FULL
    THEN
    SWAP _SPOOL-ACQUIRE-FAIL ;

: STREAMS-EXECUTION-POOL-RELEASE  ( flow lease pool -- status )
    >R
    R@ _SPOOL-SEALED-OPERATIONAL? 0= IF
        2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ _SPOOL.STATE @ _SPOOL-STATE-SEALED <> IF
        2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ _SPOOL.BUSY @ IF
        2DROP R> DROP STREAMS-FLOW-S-BUSY EXIT
    THEN
    DUP 0> 0= IF 2DROP R> DROP STREAMS-FLOW-S-STALE EXIT THEN
    -1 R@ _SPOOL.BUSY !
    R@ _SPOOL.ARG-LEASE !
    R@ _SPOOL.ARG-FLOW !
    R> 0 OVER _SPOOL.ARG-ENTRY !
    DUP _SPOOL.BOUND @ 0 ?DO
        I OVER _SPOOL-ENTRY DUP _SPE.FLOW @
        2 PICK _SPOOL.ARG-FLOW @ = IF
            OVER _SPOOL.ARG-ENTRY !
            DUP _SPOOL.ARG-ENTRY @ _SPE.OCCUPIED @ 0= IF
                STREAMS-FLOW-S-STALE SWAP _SPOOL-LEAVE
                UNLOOP EXIT
            THEN
            DUP _SPOOL.ARG-ENTRY @ _SPE.LEASE @
            OVER _SPOOL.ARG-LEASE @ <> IF
                STREAMS-FLOW-S-STALE SWAP _SPOOL-LEAVE
                UNLOOP EXIT
            THEN
            DUP _SPOOL.ARG-FLOW @ DUP 2 PICK
                _SPOOL-FLOW-ISOLATED-CURRENT? 0= IF
                DROP STREAMS-FLOW-S-INVALID SWAP _SPOOL-LEAVE
                UNLOOP EXIT
            THEN
            DUP SFLOW.BUSY @ IF
                DROP STREAMS-FLOW-S-BUSY SWAP _SPOOL-LEAVE
                UNLOOP EXIT
            THEN
            SFLOW.STATE @ STREAMS-FLOW-STATE-IDLE <> IF
                STREAMS-FLOW-S-BUSY SWAP _SPOOL-LEAVE
                UNLOOP EXIT
            THEN
            DUP _SPOOL.ACTIVE @ 0= IF
                STREAMS-FLOW-S-INVALID SWAP _SPOOL-LEAVE
                UNLOOP EXIT
            THEN
            0 OVER _SPOOL.ARG-ENTRY @ _SPE.OCCUPIED !
            0 OVER _SPOOL.ARG-ENTRY @ _SPE.LEASE !
            -1 OVER _SPOOL.ACTIVE +!
            STREAMS-FLOW-S-OK SWAP _SPOOL-LEAVE
            UNLOOP EXIT
        THEN
        DROP
    LOOP
    STREAMS-FLOW-S-STALE SWAP _SPOOL-LEAVE ;
