            SRBMGR-RESULT.LAST-STATUS !
        SRBPROV-D-BURROW-FINALIZE _SRBMPM-PLAN @ SRBMGR-PLAN.RESULT
            SRBMGR-RESULT.LAST-DETAIL !
    THEN
    _SRBMPM-PLAN @ SRBMGR-PLAN-VALID? IF
