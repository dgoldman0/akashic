    _SRBMGR-COMMIT-RECEIPT? 0= IF 0 EXIT THEN
    _SRBMC-PLAN @ SRBMGR-PLAN.RECEIPT
    _SRBMC-REPLAY @ SRBMGR-REPLAY.RECEIPT
        SHA3-256-COMPARE 0= IF 0 EXIT THEN
    _SRBMC-PLAN @ SRBMGR-PLAN.RESULT SRBMGR-RESULT.BURROW
    _SRBMC-REPLAY @ SRBMGR-REPLAY.TARGET RID= 0= IF 0 EXIT THEN
    _SRBMC-REPLAY @ SRBMGR-REPLAY.TARGET
    _SRBMC-MANAGER @ _SRBMGR-FIND-DECL DUP _SRBMC-DECL ! 0= IF
        0 EXIT
    THEN
    _SRBMC-PLAN @ SRBMGR-PLAN.DECL-INDEX @ _SRBMFD-INDEX @ <> IF
        0 EXIT
    THEN
    _SRBMC-PLAN @ SRBMGR-PLAN.OP @ SRBMGR-OP-CREATE = IF
        _SRBMC-PLAN @ SRBMGR-PLAN.INVOCATION
        _SRBMC-DECL @ SRBMGR-DECL.BURROW
            _SRBMGR-CREATE-RESOURCE? 0= IF 0 EXIT THEN
    THEN
    _SRBMGR-COMMIT-REPLAY-RESULT? ;

: _SRBMGR-COMMIT-FRESH-VALID?  ( -- flag )
    _SRBMC-PLAN @ SRBMGR-PLAN.RESULT _SRBMC-RESULT !
    _SRBMC-MANAGER @ SRBMGR.SERIAL @ _SRBMGR-CELL-MAX = IF 0 EXIT THEN
    _SRBMGR-COMMIT-RECEIPT? 0= IF 0 EXIT THEN
    _SRBMC-PLAN @ SRBMGR-PLAN.REPLAY-INDEX @
        _SRBMC-MANAGER @ SRBMGR.REPLAY-COUNT @ <> IF 0 EXIT THEN
    _SRBMC-MANAGER @ SRBMGR.REPLAY-COUNT @
        _SRBMC-MANAGER @ SRBMGR.REPLAY-CAPACITY @ >= IF 0 EXIT THEN
    _SRBMC-PLAN @ SRBMGR-PLAN.INVOCATION
        _SRBMC-MANAGER @ _SRBMGR-FIND-REPLAY IF 0 EXIT THEN
    _SRBMC-PLAN @ SRBMGR-PLAN.OP @ SRBMGR-OP-CREATE = IF
        _SRBMC-PLAN @ SRBMGR-PLAN.DECL-INDEX @
            _SRBMC-MANAGER @ SRBMGR.ROW-COUNT @ <> IF 0 EXIT THEN
        _SRBMC-MANAGER @ SRBMGR.ROW-COUNT @
            _SRBMC-MANAGER @ SRBMGR.ROW-CAPACITY @ >= IF 0 EXIT THEN
        _SRBMC-PLAN @ SRBMGR-PLAN.RESULT SRBMGR-RESULT.BURROW
            _SRBMC-MANAGER @ _SRBMGR-FIND-DECL IF 0 EXIT THEN
        _SRBMGR-COMMIT-CREATE-RESULT? EXIT
    THEN
    _SRBMC-PLAN @ SRBMGR-PLAN.DECL-INDEX @
        _SRBMC-MANAGER @ SRBMGR.ROW-COUNT @ U< 0= IF 0 EXIT THEN
    _SRBMC-PLAN @ SRBMGR-PLAN.DECL-INDEX @
        _SRBMC-MANAGER @ _SRBMGR-DECL@ _SRBMC-DECL !
    _SRBMC-DECL @ SRBMGR-DECL.BURROW
    _SRBMC-PLAN @ SRBMGR-PLAN.RESULT SRBMGR-RESULT.BURROW RID= 0= IF
        0 EXIT
    THEN
    _SRBMC-DECL @ SRBMGR-DECL.DOMAIN-REVISION @ _SRBMGR-CELL-MAX = IF
        0 EXIT
    THEN
    _SRBMC-DECL @ SRBMGR-DECL.DOMAIN-REVISION @ 1+
    _SRBMC-PLAN @ SRBMGR-PLAN.RESULT
        SRBMGR-RESULT.DOMAIN-REVISION @ = 0= IF 0 EXIT THEN
    _SRBMC-DECL @ SRBMGR-DECL.STATE @
    _SRBMC-PLAN @ SRBMGR-PLAN.OP @ _SRBMGR-MUTATE-STATE-OK? 0= IF
        0 EXIT
    THEN
    _SRBMGR-COMMIT-MUTATION-RESULT? ;

: _SRBMGR-COMMIT-REPLAY!  ( -- )
    _SRBMC-MANAGER @ SRBMGR.REPLAY-COUNT @
        _SRBMC-MANAGER @ _SRBMGR-REPLAY@ _SRBMC-REPLAY !
    _SRBMC-REPLAY @ SRBMGR-REPLAY-SIZE 0 FILL
    -1 _SRBMC-REPLAY @ SRBMGR-REPLAY.OCCUPIED !
    _SRBMC-PLAN @ SRBMGR-PLAN.OP @
        _SRBMC-REPLAY @ SRBMGR-REPLAY.OP !
    _SRBMC-PLAN @ SRBMGR-PLAN.INVOCATION
        _SRBMC-REPLAY @ SRBMGR-REPLAY.INVOCATION RID-COPY
    _SRBMC-PLAN @ SRBMGR-PLAN.ARGS-LEN @
        _SRBMC-REPLAY @ SRBMGR-REPLAY.ARGS-LEN !
    _SRBMC-PLAN @ SRBMGR-PLAN.ARGS-DIGEST
        _SRBMC-REPLAY @ SRBMGR-REPLAY.ARGS-DIGEST RID-COPY
    _SRBMC-PLAN @ SRBMGR-PLAN.RESULT SRBMGR-RESULT.BURROW
        _SRBMC-REPLAY @ SRBMGR-REPLAY.TARGET RID-COPY
    _SRBMC-PLAN @ SRBMGR-PLAN.RECEIPT
        _SRBMC-REPLAY @ SRBMGR-REPLAY.RECEIPT RID-COPY
    1 _SRBMC-MANAGER @ SRBMGR.REPLAY-COUNT +! ;

: _SRBMGR-COMMIT-CREATE!  ( -- )
    _SRBMC-MANAGER @ SRBMGR.ROW-COUNT @
        _SRBMC-MANAGER @ _SRBMGR-DECL@ _SRBMC-DECL !
    _SRBMC-DECL @ SRBMGR-DECLARATION-SIZE 0 FILL
    -1 _SRBMC-DECL @ SRBMGR-DECL.OCCUPIED !
    _SRBMC-RESULT @ SRBMGR-RESULT.BURROW
        _SRBMC-DECL @ SRBMGR-DECL.BURROW RID-COPY
    _SRBMC-RESULT @ SRBMGR-RESULT.DOMAIN-REVISION @
        _SRBMC-DECL @ SRBMGR-DECL.DOMAIN-REVISION !
    _SRBMC-RESULT @ SRBMGR-RESULT.STATE @
        _SRBMC-DECL @ SRBMGR-DECL.STATE !
    _SRBMC-RESULT @ SRBMGR-RESULT.PEER-COUNT @
        _SRBMC-DECL @ SRBMGR-DECL.PEER-COUNT !
    _SRBMC-RESULT @ SRBMGR-RESULT.SERVICE-COUNT @
        _SRBMC-DECL @ SRBMGR-DECL.SERVICE-COUNT !
    _SRBMC-RESULT @ SRBMGR-RESULT.CLEANUP-PENDING @
        _SRBMC-DECL @ SRBMGR-DECL.CLEANUP-PENDING !
    _SRBMC-RESULT @ SRBMGR-RESULT.LAST-STATUS @
        _SRBMC-DECL @ SRBMGR-DECL.LAST-STATUS !
    _SRBMC-RESULT @ SRBMGR-RESULT.LAST-DETAIL @
        _SRBMC-DECL @ SRBMGR-DECL.LAST-DETAIL !
    SRBPROV-S-NONE _SRBMC-DECL @ SRBMGR-DECL.CAUSE-STATUS !
    SRBPROV-D-NONE _SRBMC-DECL @ SRBMGR-DECL.CAUSE-DETAIL !
    _SRBMC-DECL @ SRBMGR-DECL.SPEC SRBPROV-GRAPH-SPEC-INIT
    _SRBMC-RESULT @ SRBMGR-RESULT.COLLECTION
        _SRBMC-DECL @ SRBMGR-DECL.SPEC SRBPROV-SPEC.COLLECTION RID-COPY
    _SRBMC-RESULT @ SRBMGR-RESULT.COLLECTION-REVISION @
        _SRBMC-DECL @ SRBMGR-DECL.SPEC
        SRBPROV-SPEC.COLLECTION-REVISION !
    _SRBMC-RESULT @ SRBMGR-RESULT.REQUEST-DIGEST
        _SRBMC-DECL @ SRBMGR-DECL.SPEC
        SRBPROV-SPEC.REQUEST-DIGEST RID-COPY
    _SRBMC-RESULT @ SRBMGR-RESULT.PEER-CAPACITY @
        _SRBMC-DECL @ SRBMGR-DECL.SPEC SRBPROV-SPEC.PEER-CAPACITY !
    1 _SRBMC-MANAGER @ SRBMGR.ROW-COUNT +! ;

: _SRBMGR-COMMIT-MUTATION!  ( -- )
    _SRBMC-PLAN @ SRBMGR-PLAN.DECL-INDEX @
        _SRBMC-MANAGER @ _SRBMGR-DECL@ _SRBMC-DECL !
    _SRBMC-RESULT @ SRBMGR-RESULT.DOMAIN-REVISION @
        _SRBMC-DECL @ SRBMGR-DECL.DOMAIN-REVISION !
    _SRBMC-RESULT @ SRBMGR-RESULT.STATE @
        _SRBMC-DECL @ SRBMGR-DECL.STATE !
    _SRBMC-RESULT @ SRBMGR-RESULT.PEER-COUNT @
        _SRBMC-DECL @ SRBMGR-DECL.PEER-COUNT !
    _SRBMC-RESULT @ SRBMGR-RESULT.CLEANUP-PENDING @
        _SRBMC-DECL @ SRBMGR-DECL.CLEANUP-PENDING !
    _SRBMC-RESULT @ SRBMGR-RESULT.LAST-STATUS @
        _SRBMC-DECL @ SRBMGR-DECL.LAST-STATUS !
    _SRBMC-RESULT @ SRBMGR-RESULT.LAST-DETAIL @
        _SRBMC-DECL @ SRBMGR-DECL.LAST-DETAIL !
    SRBPROV-S-NONE _SRBMC-DECL @ SRBMGR-DECL.CAUSE-STATUS !
    SRBPROV-D-NONE _SRBMC-DECL @ SRBMGR-DECL.CAUSE-DETAIL !
    _SRBMC-PLAN @ SRBMGR-PLAN.OP @ SRBMGR-OP-START = IF
        _SRBMGR-PHASE-ACQUIRE _SRBMC-DECL @ SRBMGR-DECL.PHASE !
        0 _SRBMC-DECL @ SRBMGR-DECL.LEASE-SERVICE-SEEN !
    ELSE
        \ BLOCKED retry resumes the exact retained cleanup phase.  Other
        \ admitted stop states have not yet entered the cleanup ratchet.
        _SRBMC-DECL @ SRBMGR-DECL.PHASE @ _SRBMGR-PHASE-CANCEL < IF
            _SRBMGR-PHASE-CANCEL _SRBMC-DECL @ SRBMGR-DECL.PHASE !
        THEN
    THEN ;

: SRBMGR-COMMIT  ( plan manager -- changed? status )
    _SRBMC-MANAGER ! _SRBMC-PLAN !
    _SRBMC-MANAGER @ SRBMGR-VALID? 0= IF
        0 SRBPROV-S-INVALID EXIT
    THEN
    _SRBMC-PLAN @ SRBMGR-PLAN-VALID? 0= IF
        0 SRBPROV-S-INVALID EXIT
    THEN
    _SRBMC-PLAN @ SRBMGR-PLAN.MANAGER @ _SRBMC-MANAGER @ <> IF
        0 SRBPROV-S-INVALID EXIT
    THEN
    _SRBMC-PLAN @ SRBMGR-PLAN.SERIAL @
        _SRBMC-MANAGER @ SRBMGR.SERIAL @ <> IF
        0 SRBPROV-S-CONFLICT EXIT
    THEN
    _SRBMC-PLAN @ SRBMGR-PLAN.FRESH @ 0= IF
        _SRBMGR-COMMIT-REPLAY-VALID? IF
            0 SRBPROV-S-NONE
        ELSE
            0 SRBPROV-S-CONFLICT
        THEN EXIT
    THEN
    _SRBMGR-COMMIT-FRESH-VALID? 0= IF 0 SRBPROV-S-CONFLICT EXIT THEN
    _SRBMC-PLAN @ SRBMGR-PLAN.RESULT _SRBMC-RESULT !
    _SRBMC-PLAN @ SRBMGR-PLAN.OP @ SRBMGR-OP-CREATE = IF
        _SRBMGR-COMMIT-CREATE!
    ELSE
        _SRBMGR-COMMIT-MUTATION!
    THEN
    _SRBMGR-COMMIT-REPLAY!
    1 _SRBMC-MANAGER @ SRBMGR.SERIAL +!
    -1 SRBPROV-S-NONE ;

