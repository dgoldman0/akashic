        DROP
        _SRBMDV-D @ SRBMGR-DECL.LEASE @ 0=
        _SRBMDV-D @ SRBMGR-DECL.PHASE @ _SRBMGR-PHASE-NONE = AND
        _SRBMDV-D @ SRBMGR-DECL.PEER-COUNT @ 0= AND
        _SRBMDV-D @ SRBMGR-DECL.LEASE-SERVICE-SEEN @ 0= AND
        _SRBMDV-D @ SRBMGR-DECL.CLEANUP-PENDING @ 0= AND
        _SRBMDV-D @ SRBMGR-DECL.LAST-STATUS @ SRBPROV-S-PENDING <> AND
        _SRBMDV-D @ SRBMGR-DECL.LAST-STATUS @
            _SRBMDV-D @ SRBMGR-DECL.CAUSE-STATUS @ = AND
        _SRBMDV-D @ SRBMGR-DECL.LAST-DETAIL @
            _SRBMDV-D @ SRBMGR-DECL.CAUSE-DETAIL @ = AND EXIT
    THEN
    DROP
    _SRBMDV-D @ SRBMGR-DECL.LEASE @ 0<>
    _SRBMDV-D @ SRBMGR-DECL.CLEANUP-PENDING @ -1 = AND
    _SRBMDV-D @ SRBMGR-DECL.PHASE @ DUP _SRBMGR-PHASE-CANCEL >=
    SWAP _SRBMGR-PHASE-RELEASE <= AND AND
