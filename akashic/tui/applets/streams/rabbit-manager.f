        SWAP _SRBMGR-PHASE-OPEN <= AND AND
        _SRBMDV-D @ SRBMGR-DECL.PHASE @ _SRBMGR-PHASE-ACQUIRE = IF
            _SRBMDV-D @ SRBMGR-DECL.LEASE @ 0= AND
        ELSE
            _SRBMDV-D @ SRBMGR-DECL.LEASE @ 0<> AND
        THEN EXIT
    THEN
    DUP SRBMGR-STATE-RUNNING = IF
        DROP
        _SRBMDV-D @ SRBMGR-DECL.LEASE @ 0<>
        _SRBMDV-D @ SRBMGR-DECL.PHASE @ _SRBMGR-PHASE-NONE = AND
