: _SRBMGR-TICK-PHASE!  ( phase -- )
    _SRBMT-DECL @ SRBMGR-DECL.PHASE @ OVER <> IF
        _SRBMT-DECL @ SRBMGR-DECL.PHASE ! -1 _SRBMT-INTERNAL !
    ELSE
        DROP
    THEN ;

: _SRBMGR-TICK-LEASE!  ( lease -- )
    _SRBMT-DECL @ SRBMGR-DECL.LEASE @ OVER <> IF
        _SRBMT-DECL @ SRBMGR-DECL.LEASE ! -1 _SRBMT-INTERNAL !
    ELSE
        DROP
    THEN ;

: _SRBMGR-TICK-CAUSE!  ( status detail -- )
    _SRBMT-DECL @ SRBMGR-DECL.CAUSE-DETAIL !
    _SRBMT-DECL @ SRBMGR-DECL.CAUSE-STATUS !
    -1 _SRBMT-INTERNAL ! ;

: _SRBMGR-TICK-DESIRED
  ( state peer-count cleanup? status detail -- )
    _SRBMT-NEXT-DETAIL ! _SRBMT-NEXT-STATUS ! _SRBMT-NEXT-CLEANUP !
    _SRBMT-NEXT-PEERS ! _SRBMT-NEXT-STATE ! ;

: _SRBMGR-TICK-PUBLISH  ( -- status )
    _SRBMT-NEXT-STATE @ SRBMGR-STATE-VALID? 0= IF
        SRBPROV-S-FAULT EXIT
    THEN
    _SRBMT-NEXT-PEERS @ DUP 0< IF DROP SRBPROV-S-FAULT EXIT THEN
    _SRBMT-DECL @ SRBMGR-DECL.SPEC SRBPROV-SPEC.PEER-CAPACITY @ U> IF
        SRBPROV-S-FAULT EXIT
    THEN
    _SRBMT-NEXT-CLEANUP @ _SRBMGR-BOOL? 0= IF SRBPROV-S-FAULT EXIT THEN
    _SRBMT-NEXT-STATUS @ _SRBMT-NEXT-DETAIL @
        SRBPROV-RESULT-VALID? 0= IF SRBPROV-S-FAULT EXIT THEN
    _SRBMT-DECL @ SRBMGR-DECL.STATE @ _SRBMT-NEXT-STATE @ =
    _SRBMT-DECL @ SRBMGR-DECL.PEER-COUNT @ _SRBMT-NEXT-PEERS @ = AND
    _SRBMT-DECL @ SRBMGR-DECL.CLEANUP-PENDING @
        _SRBMT-NEXT-CLEANUP @ = AND
    _SRBMT-DECL @ SRBMGR-DECL.LAST-STATUS @ _SRBMT-NEXT-STATUS @ = AND
    _SRBMT-DECL @ SRBMGR-DECL.LAST-DETAIL @ _SRBMT-NEXT-DETAIL @ = AND IF
        SRBPROV-S-NONE EXIT
    THEN
    _SRBMT-DECL @ SRBMGR-DECL.DOMAIN-REVISION @
        _SRBMGR-CELL-MAX = IF SRBPROV-S-CAPACITY EXIT THEN
    _SRBMT-NEXT-STATE @ _SRBMT-DECL @ SRBMGR-DECL.STATE !
    _SRBMT-NEXT-PEERS @ _SRBMT-DECL @ SRBMGR-DECL.PEER-COUNT !
    _SRBMT-NEXT-CLEANUP @
        _SRBMT-DECL @ SRBMGR-DECL.CLEANUP-PENDING !
    _SRBMT-NEXT-STATUS @ _SRBMT-DECL @ SRBMGR-DECL.LAST-STATUS !
    _SRBMT-NEXT-DETAIL @ _SRBMT-DECL @ SRBMGR-DECL.LAST-DETAIL !
    1 _SRBMT-DECL @ SRBMGR-DECL.DOMAIN-REVISION +!
    -1 _SRBMT-PUBLIC ! -1 _SRBMT-INTERNAL !
    SRBPROV-S-NONE ;

: _SRBMGR-TICK-COUNTS  ( -- status )
    _SRBMT-DECL @ SRBMGR-DECL.LEASE @
    _SRBMT-MANAGER @ SRBMGR.PROVIDER @ SRBPROV-COUNTS
    _SRBMT-DETAIL ! _SRBMT-STATUS !
    _SRBMT-SERVICE-COUNT ! _SRBMT-PEER-COUNT !
    _SRBMT-STATUS @ SRBPROV-S-NONE <> IF _SRBMT-STATUS @ EXIT THEN
    _SRBMT-PEER-COUNT @
    _SRBMT-DECL @ SRBMGR-DECL.SPEC SRBPROV-SPEC.PEER-CAPACITY @ U> IF
        SRBPROV-D-INVARIANT _SRBMT-DETAIL !
        SRBPROV-S-FAULT _SRBMT-STATUS ! SRBPROV-S-FAULT EXIT
    THEN
    _SRBMT-SERVICE-COUNT @
    _SRBMT-DECL @ SRBMGR-DECL.LEASE-SERVICE-SEEN @ U< IF
        SRBPROV-D-INVARIANT _SRBMT-DETAIL !
        SRBPROV-S-CORRUPT _SRBMT-STATUS ! SRBPROV-S-CORRUPT EXIT
    THEN
    _SRBMT-SERVICE-COUNT @
    _SRBMT-DECL @ SRBMGR-DECL.LEASE-SERVICE-SEEN @ <> IF
        _SRBMT-SERVICE-COUNT @
        _SRBMT-DECL @ SRBMGR-DECL.LEASE-SERVICE-SEEN @ -
        _SRBMT-DECL @ SRBMGR-DECL.SERVICE-COUNT @
        _SRBMGR-CELL-MAX OVER - 2 PICK U< IF
            2DROP _SRBMGR-CELL-MAX
        ELSE
            +
        THEN
        _SRBMT-DECL @ SRBMGR-DECL.SERVICE-COUNT !
        _SRBMT-SERVICE-COUNT @
            _SRBMT-DECL @ SRBMGR-DECL.LEASE-SERVICE-SEEN !
        -1 _SRBMT-INTERNAL !
    THEN
    SRBPROV-S-NONE ;

: _SRBMGR-TICK-ROLLBACK  ( status detail -- )
    2DUP _SRBMGR-TICK-CAUSE!
    _SRBMT-DETAIL ! _SRBMT-STATUS !
    _SRBMT-DECL @ SRBMGR-DECL.LEASE @ IF
        _SRBMGR-PHASE-CANCEL _SRBMGR-TICK-PHASE!
        SRBMGR-STATE-STOPPING
        _SRBMT-DECL @ SRBMGR-DECL.PEER-COUNT @ -1
        _SRBMT-STATUS @ _SRBMT-DETAIL @ _SRBMGR-TICK-DESIRED
    ELSE
        _SRBMGR-PHASE-NONE _SRBMGR-TICK-PHASE!
        SRBMGR-STATE-STOPPED 0 0
        _SRBMT-STATUS @ _SRBMT-DETAIL @ _SRBMGR-TICK-DESIRED
    THEN
    _SRBMGR-TICK-PUBLISH DUP SRBPROV-S-NONE <> IF
        _SRBMT-STATUS !
    ELSE
        DROP
    THEN ;

: _SRBMGR-TICK-BLOCK  ( status detail -- )
    _SRBMT-DETAIL ! _SRBMT-STATUS !
    SRBMGR-STATE-BLOCKED
    _SRBMT-DECL @ SRBMGR-DECL.PEER-COUNT @ -1
    _SRBMT-STATUS @ _SRBMT-DETAIL @ _SRBMGR-TICK-DESIRED
    _SRBMGR-TICK-PUBLISH DUP SRBPROV-S-NONE <> IF
        _SRBMT-STATUS !
    ELSE
        DROP
    THEN ;

: _SRBMGR-TICK-START-ACQUIRE  ( -- )
    _SRBMT-MANAGER @ SRBMGR.PROVIDER @ DUP 0= IF
        DROP SRBPROV-S-UNAVAILABLE SRBPROV-D-PROVIDER-ACQUIRE
            _SRBMGR-TICK-ROLLBACK EXIT
    THEN
    _SRBMT-DECL @ SRBMGR-DECL.SPEC SWAP SRBPROV-ACQUIRE
    _SRBMT-DETAIL ! _SRBMT-STATUS ! _SRBMT-LEASE !
    _SRBMT-LEASE @ ?DUP IF _SRBMGR-TICK-LEASE! THEN
    _SRBMT-STATUS @ SRBPROV-S-NONE = IF
        _SRBMGR-PHASE-OPEN _SRBMGR-TICK-PHASE!
        EXIT
    THEN
    _SRBMT-STATUS @ SRBPROV-S-PENDING = IF
        _SRBMGR-PHASE-ACQUIRE-TICK _SRBMGR-TICK-PHASE!
        EXIT
    THEN
    _SRBMT-STATUS @ _SRBMT-DETAIL @ _SRBMGR-TICK-ROLLBACK ;

: _SRBMGR-TICK-START-ACQUIRE-TICK  ( -- )
    _SRBMT-DECL @ SRBMGR-DECL.LEASE @
    _SRBMT-MANAGER @ SRBMGR.PROVIDER @ SRBPROV-ACQUIRE-TICK
    _SRBMT-DETAIL ! _SRBMT-STATUS !
    _SRBMT-STATUS @ SRBPROV-S-NONE = IF
        _SRBMGR-PHASE-OPEN _SRBMGR-TICK-PHASE! EXIT
    THEN
    _SRBMT-STATUS @ SRBPROV-S-PENDING = IF EXIT THEN
    _SRBMT-STATUS @ _SRBMT-DETAIL @ _SRBMGR-TICK-ROLLBACK ;

: _SRBMGR-TICK-START-OPEN  ( -- )
    _SRBMT-DECL @ SRBMGR-DECL.LEASE @
    _SRBMT-MANAGER @ SRBMGR.PROVIDER @ SRBPROV-OPEN
    _SRBMT-DETAIL ! _SRBMT-STATUS !
    \ OPEN is deliberately one-shot.  PENDING here is a provider state
    \ contract violation, not an asynchronous state the manager can retain.
    _SRBMT-STATUS @ SRBPROV-S-PENDING = IF
        SRBPROV-S-STATE _SRBMT-STATUS !
        SRBPROV-D-BURROW-OPEN _SRBMT-DETAIL !
    THEN
    _SRBMT-STATUS @ SRBPROV-S-NONE <> IF
        _SRBMT-STATUS @ _SRBMT-DETAIL @ _SRBMGR-TICK-ROLLBACK EXIT
    THEN
    _SRBMGR-TICK-COUNTS DUP SRBPROV-S-NONE <> IF
        DROP _SRBMT-STATUS @ _SRBMT-DETAIL @ _SRBMGR-TICK-ROLLBACK EXIT
    THEN DROP
    _SRBMGR-PHASE-NONE _SRBMGR-TICK-PHASE!
    SRBMGR-STATE-RUNNING _SRBMT-PEER-COUNT @ 0
    SRBPROV-S-NONE SRBPROV-D-NONE _SRBMGR-TICK-DESIRED
    _SRBMGR-TICK-PUBLISH DUP SRBPROV-S-NONE <> IF
        _SRBMT-STATUS !
    ELSE
        DROP SRBPROV-S-NONE _SRBMT-STATUS !
    THEN ;

: _SRBMGR-TICK-STARTING  ( -- )
    _SRBMT-DECL @ SRBMGR-DECL.PHASE @
    DUP _SRBMGR-PHASE-ACQUIRE = IF DROP _SRBMGR-TICK-START-ACQUIRE EXIT THEN
    DUP _SRBMGR-PHASE-ACQUIRE-TICK = IF
        DROP _SRBMGR-TICK-START-ACQUIRE-TICK EXIT
    THEN
    _SRBMGR-PHASE-OPEN = IF _SRBMGR-TICK-START-OPEN EXIT THEN
    SRBPROV-S-FAULT SRBPROV-D-INVARIANT _SRBMGR-TICK-ROLLBACK ;

: _SRBMGR-TICK-RUNNING  ( -- )
    _SRBMT-DECL @ SRBMGR-DECL.LEASE @
    _SRBMT-MANAGER @ SRBMGR.PROVIDER @ SRBPROV-SERVICE
    _SRBMT-DETAIL ! _SRBMT-STATUS !
    _SRBMT-STATUS @ DUP SRBPROV-S-NONE =
    SWAP SRBPROV-S-PENDING = OR 0= IF
        _SRBMT-STATUS @ _SRBMT-DETAIL @ _SRBMGR-TICK-ROLLBACK EXIT
    THEN
    _SRBMGR-TICK-COUNTS DUP SRBPROV-S-NONE <> IF
        DROP _SRBMT-STATUS @ _SRBMT-DETAIL @ _SRBMGR-TICK-ROLLBACK EXIT
    THEN DROP
    SRBMGR-STATE-RUNNING _SRBMT-PEER-COUNT @ 0
    SRBPROV-S-NONE SRBPROV-D-NONE _SRBMGR-TICK-DESIRED
    _SRBMGR-TICK-PUBLISH DUP SRBPROV-S-NONE <> IF
        _SRBMT-STATUS !
    ELSE
        DROP SRBPROV-S-NONE _SRBMT-STATUS !
    THEN ;

: _SRBMGR-TICK-STOPPED!  ( -- )
    0 _SRBMGR-TICK-LEASE!
    _SRBMGR-PHASE-NONE _SRBMGR-TICK-PHASE!
    _SRBMT-DECL @ SRBMGR-DECL.LEASE-SERVICE-SEEN @ IF
        0 _SRBMT-DECL @ SRBMGR-DECL.LEASE-SERVICE-SEEN !
        -1 _SRBMT-INTERNAL !
    THEN
    SRBMGR-STATE-STOPPED 0 0
    _SRBMT-DECL @ SRBMGR-DECL.CAUSE-STATUS @
    _SRBMT-DECL @ SRBMGR-DECL.CAUSE-DETAIL @ _SRBMGR-TICK-DESIRED
    _SRBMGR-TICK-PUBLISH DUP SRBPROV-S-NONE <> IF
        _SRBMT-STATUS !
    ELSE
        DROP SRBPROV-S-NONE _SRBMT-STATUS !
    THEN ;

: _SRBMGR-TICK-STOP-CANCEL  ( -- )
    _SRBMT-DECL @ SRBMGR-DECL.LEASE @ 0= IF
        _SRBMGR-TICK-STOPPED! EXIT
    THEN
    _SRBMT-DECL @ SRBMGR-DECL.LEASE @
    _SRBMT-MANAGER @ SRBMGR.PROVIDER @ SRBPROV-CANCEL
    _SRBMT-DETAIL ! _SRBMT-STATUS !
    _SRBMT-STATUS @ SRBPROV-S-NONE = IF
        _SRBMGR-PHASE-FINALIZE _SRBMGR-TICK-PHASE! EXIT
    THEN
    _SRBMT-STATUS @ SRBPROV-S-PENDING = IF EXIT THEN
    _SRBMT-STATUS @ _SRBMT-DETAIL @ _SRBMGR-TICK-BLOCK ;

: _SRBMGR-TICK-STOP-FINALIZE  ( -- )
    _SRBMT-DECL @ SRBMGR-DECL.LEASE @
    _SRBMT-MANAGER @ SRBMGR.PROVIDER @ SRBPROV-FINALIZE
    _SRBMT-DETAIL ! _SRBMT-STATUS !
    _SRBMT-STATUS @ SRBPROV-S-NONE = IF
        _SRBMGR-PHASE-RELEASE _SRBMGR-TICK-PHASE! EXIT
    THEN
    _SRBMT-STATUS @ SRBPROV-S-PENDING = IF EXIT THEN
    _SRBMT-STATUS @ _SRBMT-DETAIL @ _SRBMGR-TICK-BLOCK ;

: _SRBMGR-TICK-STOP-RELEASE  ( -- )
    _SRBMT-DECL @ SRBMGR-DECL.LEASE @
    _SRBMT-MANAGER @ SRBMGR.PROVIDER @ SRBPROV-RELEASE
    _SRBMT-DETAIL ! _SRBMT-STATUS !
    _SRBMT-STATUS @ SRBPROV-S-NONE = IF
        _SRBMGR-TICK-STOPPED! EXIT
    THEN
    _SRBMT-STATUS @ SRBPROV-S-PENDING = IF EXIT THEN
    _SRBMT-STATUS @ _SRBMT-DETAIL @ _SRBMGR-TICK-BLOCK ;

: _SRBMGR-TICK-STOPPING  ( -- )
    _SRBMT-DECL @ SRBMGR-DECL.PHASE @
    DUP _SRBMGR-PHASE-CANCEL = IF DROP _SRBMGR-TICK-STOP-CANCEL EXIT THEN
    DUP _SRBMGR-PHASE-FINALIZE = IF
        DROP _SRBMGR-TICK-STOP-FINALIZE EXIT
    THEN
    _SRBMGR-PHASE-RELEASE = IF _SRBMGR-TICK-STOP-RELEASE EXIT THEN
    SRBPROV-S-FAULT SRBPROV-D-INVARIANT _SRBMGR-TICK-BLOCK ;

: _SRBMGR-TICK-ACTIVE?  ( declaration -- flag )
    SRBMGR-DECL.STATE @ DUP SRBMGR-STATE-STARTING =
    OVER SRBMGR-STATE-RUNNING = OR
    SWAP SRBMGR-STATE-STOPPING = OR ;

: _SRBMGR-TICK-SELECT  ( -- flag )
    0 _SRBMT-FOUND !
    _SRBMT-MANAGER @ SRBMGR.ROW-COUNT @ DUP 0= IF DROP 0 EXIT THEN
    0 ?DO
        _SRBMT-MANAGER @ SRBMGR.NEXT-INDEX @ I +
        _SRBMT-MANAGER @ SRBMGR.ROW-COUNT @ MOD DUP _SRBMT-INDEX !
        _SRBMT-MANAGER @ _SRBMGR-DECL@ DUP _SRBMT-DECL !
        _SRBMGR-TICK-ACTIVE? IF -1 _SRBMT-FOUND ! LEAVE THEN
    LOOP
    _SRBMT-FOUND @ IF
        _SRBMT-INDEX @ 1+ _SRBMT-MANAGER @ SRBMGR.ROW-COUNT @ MOD
            _SRBMT-MANAGER @ SRBMGR.NEXT-INDEX !
    THEN
    _SRBMT-FOUND @ ;

: _SRBMGR-TICK-PROCESS  ( -- )
    _SRBMT-DECL @ SRBMGR-DECL.STATE @
    DUP SRBMGR-STATE-STARTING = IF DROP _SRBMGR-TICK-STARTING EXIT THEN
    DUP SRBMGR-STATE-RUNNING = IF DROP _SRBMGR-TICK-RUNNING EXIT THEN
    DROP _SRBMGR-TICK-STOPPING ;

: SRBMGR-TICK  ( manager -- changed? status )
    DUP _SRBMT-MANAGER ! SRBMGR-VALID? 0= IF
        0 SRBPROV-S-INVALID EXIT
    THEN
    _SRBMT-MANAGER @ SRBMGR.SERIAL @ _SRBMGR-CELL-MAX = IF
        0 SRBPROV-S-CAPACITY EXIT
    THEN
    _SRBMGR-TICK-SELECT 0= IF 0 SRBPROV-S-NONE EXIT THEN
    _SRBMT-DECL @ SRBMGR-DECL.DOMAIN-REVISION @ _SRBMGR-CELL-MAX = IF
        0 SRBPROV-S-CAPACITY EXIT
    THEN
    0 _SRBMT-INTERNAL ! 0 _SRBMT-PUBLIC !
    SRBPROV-S-NONE _SRBMT-STATUS ! SRBPROV-D-NONE _SRBMT-DETAIL !
    _SRBMGR-TICK-PROCESS
    _SRBMT-INTERNAL @ IF 1 _SRBMT-MANAGER @ SRBMGR.SERIAL +! THEN
    _SRBMT-PUBLIC @ _SRBMT-STATUS @ ;

