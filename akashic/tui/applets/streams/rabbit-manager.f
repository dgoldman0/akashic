\ Close negotiation and final release
\ =====================================================================

VARIABLE _SRBMQ-MANAGER
VARIABLE _SRBMQ-DECL
VARIABLE _SRBMQ-INDEX
VARIABLE _SRBMQ-CHANGED
VARIABLE _SRBMQ-STATUS

: SRBMGR-RELEASABLE?  ( manager -- flag )
    DUP _SRBMQ-MANAGER ! SRBMGR-VALID? 0= IF 0 EXIT THEN
    _SRBMQ-MANAGER @ SRBMGR.ROW-COUNT @ 0 ?DO
        I _SRBMQ-MANAGER @ _SRBMGR-DECL@ _SRBMQ-DECL !
        _SRBMQ-DECL @ SRBMGR-DECL.LEASE @ IF 0 UNLOOP EXIT THEN
        _SRBMQ-DECL @ SRBMGR-DECL.CLEANUP-PENDING @ IF
            0 UNLOOP EXIT
        THEN
        _SRBMQ-DECL @ SRBMGR-DECL.STATE @ DUP
            SRBMGR-STATE-CONFIGURED =
        SWAP SRBMGR-STATE-STOPPED = OR 0= IF 0 UNLOOP EXIT THEN
    LOOP
    -1 ;

: _SRBMGR-QUIESCE-STAGE  ( -- changed? status )
    _SRBMQ-MANAGER @ SRBMGR.SERIAL @ _SRBMGR-CELL-MAX = IF
        0 SRBPROV-S-CAPACITY EXIT
    THEN
    _SRBMQ-DECL @ SRBMGR-DECL.DOMAIN-REVISION @ _SRBMGR-CELL-MAX = IF
        0 SRBPROV-S-CAPACITY EXIT
    THEN
    _SRBMQ-MANAGER @ _SRBMT-MANAGER !
    _SRBMQ-DECL @ _SRBMT-DECL !
    0 _SRBMT-INTERNAL ! 0 _SRBMT-PUBLIC !
    SRBPROV-S-NONE SRBPROV-D-NONE _SRBMGR-TICK-CAUSE!
    _SRBMQ-DECL @ SRBMGR-DECL.PHASE @ _SRBMGR-PHASE-CANCEL < IF
        _SRBMGR-PHASE-CANCEL _SRBMGR-TICK-PHASE!
    THEN
    SRBMGR-STATE-STOPPING
    _SRBMQ-DECL @ SRBMGR-DECL.PEER-COUNT @ -1
    SRBPROV-S-PENDING SRBPROV-D-BURROW-FINALIZE
        _SRBMGR-TICK-DESIRED
    _SRBMGR-TICK-PUBLISH DUP SRBPROV-S-NONE <> IF
        _SRBMT-INTERNAL @ IF
            1 _SRBMQ-MANAGER @ SRBMGR.SERIAL +!
        THEN
        0 SWAP EXIT
    THEN DROP
    _SRBMT-INTERNAL @ IF 1 _SRBMQ-MANAGER @ SRBMGR.SERIAL +! THEN
    _SRBMT-PUBLIC @ SRBPROV-S-PENDING ;

: SRBMGR-QUIESCE  ( manager -- clean? changed? status )
    DUP _SRBMQ-MANAGER ! SRBMGR-VALID? 0= IF
        0 0 SRBPROV-S-INVALID EXIT
    THEN
    _SRBMQ-MANAGER @ SRBMGR-RELEASABLE? IF
        -1 0 SRBPROV-S-NONE EXIT
    THEN
    -1 _SRBMQ-INDEX !
    _SRBMQ-MANAGER @ SRBMGR.ROW-COUNT @ 0 ?DO
        I _SRBMQ-MANAGER @ _SRBMGR-DECL@ _SRBMQ-DECL !
        _SRBMQ-DECL @ SRBMGR-DECL.STATE @ DUP
            SRBMGR-STATE-CONFIGURED =
        SWAP SRBMGR-STATE-STOPPED = OR 0= IF
            I _SRBMQ-INDEX ! LEAVE
        THEN
    LOOP
    _SRBMQ-INDEX @ 0< IF 0 0 SRBPROV-S-FAULT EXIT THEN
    _SRBMQ-DECL @ SRBMGR-DECL.STATE @ SRBMGR-STATE-STOPPING = IF
        _SRBMQ-INDEX @ _SRBMQ-MANAGER @ SRBMGR.NEXT-INDEX !
        _SRBMQ-MANAGER @ SRBMGR-TICK
        _SRBMQ-STATUS ! _SRBMQ-CHANGED !
        _SRBMQ-MANAGER @ SRBMGR-RELEASABLE?
        _SRBMQ-CHANGED @ _SRBMQ-STATUS @ EXIT
    THEN
    _SRBMGR-QUIESCE-STAGE
    _SRBMQ-STATUS ! _SRBMQ-CHANGED !
    0 _SRBMQ-CHANGED @ _SRBMQ-STATUS @ ;

: SRBMGR-CANCEL  ( manager -- clean? changed? status )
    SRBMGR-QUIESCE ;

VARIABLE _SRBMF-MANAGER
VARIABLE _SRBMF-ROWS
VARIABLE _SRBMF-ROW-BYTES
VARIABLE _SRBMF-REPLAYS
VARIABLE _SRBMF-REPLAY-BYTES

: SRBMGR-FINI  ( manager -- status )
    DUP _SRBMF-MANAGER ! SRBMGR-VALID? 0= IF SRBPROV-S-INVALID EXIT THEN
    _SRBMF-MANAGER @ SRBMGR-RELEASABLE? 0= IF SRBPROV-S-STATE EXIT THEN
    _SRBMF-MANAGER @ SRBMGR.ROWS @ _SRBMF-ROWS !
    _SRBMF-MANAGER @ SRBMGR.ROW-CAPACITY @
        SRBMGR-DECLARATION-BYTES _SRBMF-ROW-BYTES !
    _SRBMF-MANAGER @ SRBMGR.REPLAYS @ _SRBMF-REPLAYS !
    _SRBMF-MANAGER @ SRBMGR.REPLAY-CAPACITY @
        SRBMGR-REPLAY-BYTES _SRBMF-REPLAY-BYTES !
    _SRBMF-ROW-BYTES @ IF
        _SRBMF-ROWS @ _SRBMF-ROW-BYTES @ 0 FILL
    THEN
    _SRBMF-REPLAY-BYTES @ IF
        _SRBMF-REPLAYS @ _SRBMF-REPLAY-BYTES @ 0 FILL
    THEN
    _SRBMF-MANAGER @ SRBMGR-SIZE 0 FILL
    SRBPROV-S-NONE ;
