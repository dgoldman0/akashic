\ =====================================================================
\ rabbit-manager.f - activation-local Streams Rabbit lifecycle owner
\ =====================================================================
\ This module owns product lifecycle and replay, but no concrete Rabbit,
\ Library, CINST, or capability-bus object.  All storage is caller-owned.
\ Public declaration rows are append-only for one Streams activation.  A
\ STOPPED row is deliberately retained as a pointer-free terminal record;
\ only its provider lease is returned and cleared.  Provider graph storage
\ may consequently be reused without ever reusing a public Burrow RID.
\
\ Planning is transactional.  A plan captures the manager serial and predicts
\ the exact public result.  COMMIT refuses a stale serial before writing any
\ row.  Replay rows are append-only and never evicted: an exact invocation,
\ operation, canonical length, and digest returns the current truthful public
\ snapshot with its historical receipt, while any alteration conflicts.
\
\ Lifecycle pumping is cooperative.  TICK visits at most one declaration.
\ Provider acquire/open/service/cancel/finalize/release calls are individually
\ bounded by the provider ABI.  Hidden phase progress and service counters do
\ not advance the public domain revision; one atomic public snapshot change
\ advances it exactly once.
\ =====================================================================

\ Keep the module identity within KDOS's 23-byte bound.
PROVIDED akashic-streams-rmgr

