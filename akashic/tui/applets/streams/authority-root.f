: _SAR-ZERO?  ( a u -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    0 ?DO DUP I + C@ IF DROP 0 UNLOOP EXIT THEN LOOP
    DROP -1 ;

: _SAR-BOOL?  ( value -- flag )
    DUP 0= SWAP -1 = OR ;

: _SAR-PROVENANCE?  ( value -- flag )
    DUP STREAMS-AUTHORITY-PROVENANCE-NATIVE >=
    SWAP STREAMS-AUTHORITY-PROVENANCE-COMPLETE-EMPTY <= AND ;

: _SAR-COMPLETENESS?  ( value -- flag )
    DUP STREAMS-AUTHORITY-COMPLETE >=
    SWAP STREAMS-AUTHORITY-UNKNOWN-LEGACY-ABSENT <= AND ;

: _SAR-NONNEG-CELL?  ( value -- flag )
