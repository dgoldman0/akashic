: STREAMS-AUTHORITY-ROOT-SEAL  ( root -- status )
    DUP 0= IF DROP STREAMS-AUTHORITY-ROOT-S-INVALID EXIT THEN
    DUP STREAMS-AUTHORITY-ROOT-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-INVALID EXIT
    THEN
    DUP SAR.SEAL SHA3-256-LEN 0 FILL
    DUP _SAR-SEAL-OFF OVER SAR.SEAL SHA3-256-HASH
    DROP STREAMS-AUTHORITY-ROOT-S-OK ;

\ This is deliberately the self-contained header classifier, not the complete
\ cold-open predicate.  A bound persistence adapter must call it before it
\ validates all four PBTREE roots against their descriptors and current PSTORE
\ generation, reconciles their cardinalities, and opens reclaim state.
: STREAMS-AUTHORITY-ROOT-HEADER-CLASSIFY  ( root -- status )
    DUP 0= IF DROP STREAMS-AUTHORITY-ROOT-S-INVALID EXIT THEN
    DUP STREAMS-AUTHORITY-ROOT-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-INVALID EXIT
    THEN
    DUP SAR.MAGIC @ _SAR-MAGIC <> IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.ABI @ STREAMS-AUTHORITY-ROOT-ABI > IF
        DROP STREAMS-AUTHORITY-ROOT-S-UNSUPPORTED EXIT
    THEN
    DUP SAR.ABI @ STREAMS-AUTHORITY-ROOT-ABI <> IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.SIZE @ STREAMS-AUTHORITY-ROOT-SIZE <> IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.FLAGS @ IF DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT THEN
    DUP _SAR-SEAL-VALID? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.RESERVED
        STREAMS-AUTHORITY-ROOT-SIZE _SAR-RESERVED-OFF -
        _SAR-ZERO? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.LOGICAL-GENERATION @ _SAR-NONNEG-CELL? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.MUTATION-SEQUENCE @ _SAR-NONNEG-CELL? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.ACQUISITION-SEQUENCE @ _SAR-NONNEG-CELL? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.SOURCE-COUNT @ _SAR-NONNEG-CELL? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.ATTEMPT-COUNT @ _SAR-NONNEG-CELL? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.OBSERVATION-COUNT @ _SAR-NONNEG-CELL? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.NATIVE-COUNT @ _SAR-NONNEG-CELL? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.ACTIVE-COUNT @ DUP 0<
    SWAP STREAMS-AUTHORITY-ACTIVE-MAX > OR IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.REMOVED-SOURCE-COUNT @ _SAR-NONNEG-CELL? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.ACTIVE-COUNT @ OVER SAR.ATTEMPT-COUNT @ > IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.ACTIVE-COUNT @ OVER SAR.SOURCE-COUNT @ > IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.ATTEMPT-COUNT @
        OVER SAR.ACQUISITION-SEQUENCE @ > IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.NATIVE-COUNT @ OVER SAR.OBSERVATION-COUNT @ > IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.PROVENANCE @ _SAR-PROVENANCE? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.SOURCE-COMPLETENESS @ _SAR-COMPLETENESS? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.OBSERVATION-COMPLETENESS @ _SAR-COMPLETENESS? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.AUTHORITY-ID RID-PRESENT? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.LEGACY-SOURCE-PRESENT OVER SAR.LEGACY-SOURCE-BYTES
        2 PICK SAR.LEGACY-SOURCE-DIGEST _SAR-LEGACY-EVIDENCE? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.LEGACY-OBSERVATION-PRESENT
        OVER SAR.LEGACY-OBSERVATION-BYTES
        2 PICK SAR.LEGACY-OBSERVATION-DIGEST
        _SAR-LEGACY-EVIDENCE? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP _SAR-PROVENANCE-EVIDENCE? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP _SAR-PROVENANCE-COMPLETENESS? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DUP SAR.RECLAIM-STATE RECLAIM-STATE-SIZE
        RECLAIM-STATE-VALID? 0= IF
        DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN
    DROP STREAMS-AUTHORITY-ROOT-S-OK ;

: STREAMS-AUTHORITY-ROOT-HEADER-VALID?  ( root -- flag )
    STREAMS-AUTHORITY-ROOT-HEADER-CLASSIFY
        STREAMS-AUTHORITY-ROOT-S-OK = ;

\ Prepare the native empty header and reclaim state.  The four tree spans stay
\ deliberately uninitialized and this template is therefore not yet a valid
\ sealed authority.  The bound adapter must initialize every PBTREE root and
\ call STREAMS-AUTHORITY-ROOT-SEAL only after all fields are final.
: STREAMS-AUTHORITY-ROOT-TEMPLATE-INIT
  ( authority-id root -- status )
    >R
    R@ 0= IF DROP R> DROP STREAMS-AUTHORITY-ROOT-S-INVALID EXIT THEN
    R@ STREAMS-AUTHORITY-ROOT-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP R> DROP STREAMS-AUTHORITY-ROOT-S-INVALID EXIT
    THEN
    DUP RID-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP R> DROP STREAMS-AUTHORITY-ROOT-S-INVALID EXIT
    THEN
    DUP RID-PRESENT? 0= IF
        DROP R> DROP STREAMS-AUTHORITY-ROOT-S-INVALID EXIT
    THEN
    DUP RID-SIZE R@ STREAMS-AUTHORITY-ROOT-SIZE MSPAN-OVERLAP? IF
        DROP R> DROP STREAMS-AUTHORITY-ROOT-S-INVALID EXIT
    THEN
    R@ STREAMS-AUTHORITY-ROOT-SIZE 0 FILL
    _SAR-MAGIC R@ SAR.MAGIC !
    STREAMS-AUTHORITY-ROOT-ABI R@ SAR.ABI !
    STREAMS-AUTHORITY-ROOT-SIZE R@ SAR.SIZE !
    STREAMS-AUTHORITY-PROVENANCE-NATIVE R@ SAR.PROVENANCE !
    STREAMS-AUTHORITY-COMPLETE R@ SAR.SOURCE-COMPLETENESS !
    STREAMS-AUTHORITY-COMPLETE R@ SAR.OBSERVATION-COMPLETENESS !
    DUP R@ SAR.AUTHORITY-ID RID-COPY
    DROP
    R@ SAR.RECLAIM-STATE RECLAIM-STATE-SIZE RECLAIM-STATE-INIT
    DUP IF
        DROP R> DROP STREAMS-AUTHORITY-ROOT-S-CORRUPT EXIT
    THEN DROP
    R> DROP STREAMS-AUTHORITY-ROOT-S-OK ;
