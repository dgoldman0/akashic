: _SAR-LEGACY-EVIDENCE?
  ( present-a bytes-a digest-a -- flag )
    >R >R
    DUP @ _SAR-BOOL? 0= IF DROP R> DROP R> DROP 0 EXIT THEN
    @ IF
        R> @ 0> R> SHA3-256-LEN _SAR-ZERO? 0= AND
    ELSE
        R> @ 0= R> SHA3-256-LEN _SAR-ZERO? AND
    THEN ;

: _SAR-SEAL-VALID?  ( root -- flag )
