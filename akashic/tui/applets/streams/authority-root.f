: _SAR-PROVENANCE-EVIDENCE?  ( root -- flag )
    DUP SAR.PROVENANCE @ CASE
        STREAMS-AUTHORITY-PROVENANCE-NATIVE OF
            DUP SAR.LEGACY-SOURCE-PRESENT @ 0=
            OVER SAR.LEGACY-OBSERVATION-PRESENT @ 0= AND
        ENDOF
        STREAMS-AUTHORITY-PROVENANCE-LEGACY-BOTH OF
            DUP SAR.LEGACY-SOURCE-PRESENT @ -1 =
            OVER SAR.LEGACY-OBSERVATION-PRESENT @ -1 = AND
        ENDOF
        STREAMS-AUTHORITY-PROVENANCE-LEGACY-SOURCES OF
            DUP SAR.LEGACY-SOURCE-PRESENT @ -1 =
            OVER SAR.LEGACY-OBSERVATION-PRESENT @ 0= AND
        ENDOF
        STREAMS-AUTHORITY-PROVENANCE-LEGACY-OBSERVATIONS OF
            DUP SAR.LEGACY-SOURCE-PRESENT @ 0=
            OVER SAR.LEGACY-OBSERVATION-PRESENT @ -1 = AND
        ENDOF
        STREAMS-AUTHORITY-PROVENANCE-LEGACY-EMPTY-SOURCES OF
            DUP SAR.LEGACY-SOURCE-PRESENT @ -1 =
            OVER SAR.LEGACY-OBSERVATION-PRESENT @ -1 = AND
