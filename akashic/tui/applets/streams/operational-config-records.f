: _SOPCONN-CREDENTIAL?  ( connector -- flag )
    DUP SOPCONN.CREDENTIAL-POLICY @
    DUP STREAMS-OPCONN-CREDENTIAL-NONE = IF
        DROP SOPCONN.CREDENTIAL-ID RID-ZERO? EXIT
    THEN
    STREAMS-OPCONN-CREDENTIAL-OPAQUE <> IF
        DROP 0 EXIT
    THEN
    SOPCONN.CREDENTIAL-ID RID-PRESENT? ;

: _SOPCONN-RECEIPT?  ( connector -- flag )
    DUP SOPCONN.RECEIPT-POLICY @
    DUP STREAMS-OPCONN-RECEIPT-NONE = IF
        DROP SOPCONN.RECEIPT-BYTE-LIMIT @ 0= EXIT
    THEN
    STREAMS-OPCONN-RECEIPT-BOUNDED <> IF
        DROP 0 EXIT
    THEN
    SOPCONN.RECEIPT-BYTE-LIMIT @ _SOPCFG-POSITIVE? ;

: _SOPCONN-LIFECYCLE?  ( connector -- flag )
    DUP SOPCONN.LIFECYCLE @
    STREAMS-OPCONN-LIFECYCLE-CONFIGURED
    STREAMS-OPCONN-LIFECYCLE-RETIRED _SOPCFG-CLOSED? 0= IF
        DROP 0 EXIT
    THEN
    DUP SOPCONN.ENABLED @ _SOPCFG-BOOLEAN? 0= IF
        DROP 0 EXIT
    THEN
    DUP SOPCONN.LIFECYCLE @ STREAMS-OPCONN-LIFECYCLE-ACTIVE =
    SWAP SOPCONN.ENABLED @ 1 = = ;

