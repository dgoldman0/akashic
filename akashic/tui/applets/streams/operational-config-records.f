\ =====================================================================
\ operational-config-records.f - Current Streams operational config
\ =====================================================================
\ These sealed, pointer-free values describe the connector, flow, and
\ checkpoint facts needed by the first SR3 egress outbox.  They perform no
\ I/O, own no mutable state, and retain no runtime address.  Connector
\ credentials are represented only by an optional opaque RID; secret,
\ session, trust, and endpoint-runtime bytes do not belong in these records.
\
\ There is one current prerelease shape, inherited from
\ operational-records.f.  A shape change replaces this module and its
\ fixtures directly; this module exposes only that single encoding.
\ =====================================================================

PROVIDED akashic-streams-opconfig-records

