        STREAMS-OPREC-S-OK <> IF DROP 0 EXIT THEN
    DUP SOPCONN.CONNECTOR-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPCONN.ENDPOINT-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPCONN.ENDPOINT-SEAL RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPCONN.REVISION @ _SOPCFG-POSITIVE? 0= IF DROP 0 EXIT THEN
    DUP SOPCONN.DIRECTION @ STREAMS-OPCONN-DIRECTION-EGRESS <>
        IF DROP 0 EXIT THEN
    DUP SOPCONN.PROTOCOL @ _SOPCFG-POSITIVE? 0= IF DROP 0 EXIT THEN
    DUP SOPCONN.PROFILE @ _SOPCFG-POSITIVE? 0= IF DROP 0 EXIT THEN
    DUP SOPCONN.ENDPOINT-POLICY @
        STREAMS-OPCONN-ENDPOINT-PINNED
        STREAMS-OPCONN-ENDPOINT-ALLOWLISTED _SOPCFG-CLOSED? 0=
        IF DROP 0 EXIT THEN
    DUP _SOPCONN-CREDENTIAL? 0= IF DROP 0 EXIT THEN
    DUP SOPCONN.REQUEST-BYTE-LIMIT @ _SOPCFG-POSITIVE? 0=
        IF DROP 0 EXIT THEN
    DUP SOPCONN.RESPONSE-BYTE-LIMIT @ _SOPCFG-POSITIVE? 0=
        IF DROP 0 EXIT THEN
