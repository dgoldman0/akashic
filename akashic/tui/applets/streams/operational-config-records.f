: _SOPCFG-BOOLEAN?  ( value -- flag )
    DUP 0= SWAP 1 = OR ;

: _SOPCFG-POSITIVE?  ( value -- flag )
    DUP 0> SWAP _SOPREC-MAX-SIGNED <= AND ;

: _SOPCFG-CLOSED?  ( value low high -- flag )
    >R OVER <= SWAP R> <= AND ;

: _SOPCFG-SEAL-MATCHES?  ( record exact-u -- flag )
    >R
    DUP SOPREC.SEAL RID-PRESENT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP R@ _SOPREC-HASH-FEED
    SOPREC.SEAL SHA3-256-END-COMPARE
    R> DROP ;

: _SOPCFG-COPY-VALID  ( source destination exact-u -- status )
    >R
    DUP 0= IF
        2DROP R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    DUP R@ MSPAN-NONWRAPPING? 0= IF
        2DROP R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    2DUP R@ SWAP R@ MSPAN-OVERLAP? IF
        2DROP R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    R> MOVE STREAMS-OPREC-S-OK ;

