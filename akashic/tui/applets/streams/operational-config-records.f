: _SOPCHECKPOINT-PRIOR?  ( checkpoint -- flag )
    DUP SOPCHECKPOINT.FLAGS @
    DUP 0= SWAP STREAMS-OPCHECKPOINT-F-HAS-PRIOR = OR 0= IF
        DROP 0 EXIT
    THEN
    DUP SOPCHECKPOINT.FLAGS @ STREAMS-OPCHECKPOINT-F-HAS-PRIOR
        AND IF
        DUP SOPCHECKPOINT.PRIOR-CHECKPOINT-ID RID-PRESENT? 0= IF
            DROP 0 EXIT
        THEN
        DUP SOPCHECKPOINT.PRIOR-CHECKPOINT-ID
            OVER SOPCHECKPOINT.CHECKPOINT-ID RID= IF
            DROP 0 EXIT
        THEN
        SOPCHECKPOINT.ORDER @ 1 >
        EXIT
    THEN
    DUP SOPCHECKPOINT.PRIOR-CHECKPOINT-ID RID-ZERO? 0= IF
        DROP 0 EXIT
    THEN
    SOPCHECKPOINT.ORDER @ 1 = ;

: _SOPCHECKPOINT-SHAPE?  ( checkpoint -- flag )
    DUP STREAMS-OPCHECKPOINT-SIZE
        STREAMS-OPCHECKPOINT-HEADER-CLASSIFY
        STREAMS-OPREC-S-OK <> IF DROP 0 EXIT THEN
    DUP SOPCHECKPOINT.CHECKPOINT-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPCHECKPOINT.CONNECTOR-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPCHECKPOINT.FLOW-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPCHECKPOINT.CURSOR-DIGEST RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPCHECKPOINT.CONNECTOR-REVISION @ _SOPCFG-POSITIVE? 0=
        IF DROP 0 EXIT THEN
    DUP SOPCHECKPOINT.FLOW-REVISION @ _SOPCFG-POSITIVE? 0=
        IF DROP 0 EXIT THEN
    DUP SOPCHECKPOINT.RECORD-REVISION @ _SOPCFG-POSITIVE? 0=
        IF DROP 0 EXIT THEN
    DUP SOPCHECKPOINT.ORDER @ _SOPCFG-POSITIVE? 0= IF DROP 0 EXIT THEN
    DUP SOPCHECKPOINT.COMMITTED-MS @ _SOPREC-NONNEG? 0=
        IF DROP 0 EXIT THEN
    DUP SOPCHECKPOINT.CURSOR-U @ _SOPREC-NONNEG? 0=
        IF DROP 0 EXIT THEN
    DUP SOPCHECKPOINT.CURSOR-BLOB PBLOB-VALID? 0= IF DROP 0 EXIT THEN
    DUP SOPCHECKPOINT.CURSOR-BLOB PBLOB-TOTAL@
        OVER SOPCHECKPOINT.CURSOR-U @ <> IF DROP 0 EXIT THEN
    DUP _SOPCHECKPOINT-PRIOR? 0= IF DROP 0 EXIT THEN
    SOPCHECKPOINT.RESERVED
        STREAMS-OPCHECKPOINT-SIZE _SOPK-RESERVED -
        _SOPREC-ZERO? ;

: STREAMS-OPCHECKPOINT-VALID?  ( checkpoint-a checkpoint-u -- flag )
    DUP STREAMS-OPCHECKPOINT-SIZE <> IF 2DROP 0 EXIT THEN
    DROP
    DUP _SOPCHECKPOINT-SHAPE? 0= IF DROP 0 EXIT THEN
    STREAMS-OPCHECKPOINT-SIZE _SOPCFG-SEAL-MATCHES? ;

: STREAMS-OPCHECKPOINT-INIT  ( checkpoint -- status )
    STREAMS-OPREC-KIND-CHECKPOINT STREAMS-OPCHECKPOINT-SIZE ROT
        _SOPREC-INIT ;

: STREAMS-OPCHECKPOINT-SEAL  ( checkpoint -- status )
    DUP 0= IF DROP STREAMS-OPREC-S-INVALID EXIT THEN
    DUP STREAMS-OPCHECKPOINT-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    DUP SOPREC.SEAL SHA3-256-LEN 0 FILL
    DUP _SOPCHECKPOINT-SHAPE? 0= IF
        DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    DUP STREAMS-OPCHECKPOINT-SIZE _SOPREC-HASH-FEED
    DUP SOPREC.SEAL SHA3-256-END
    DUP STREAMS-OPCHECKPOINT-SIZE STREAMS-OPCHECKPOINT-VALID? IF
        DROP STREAMS-OPREC-S-OK
    ELSE
        DUP SOPREC.SEAL SHA3-256-LEN 0 FILL
        DROP STREAMS-OPREC-S-CORRUPT
    THEN ;

: STREAMS-OPCHECKPOINT-COPY  ( source destination -- status )
    OVER STREAMS-OPCHECKPOINT-SIZE STREAMS-OPCHECKPOINT-VALID? 0= IF
        2DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    STREAMS-OPCHECKPOINT-SIZE _SOPCFG-COPY-VALID ;

