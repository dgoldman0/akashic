    STREAMS-OPCONN-SIZE _SOPCFG-SEAL-MATCHES? ;

: STREAMS-OPCONN-INIT  ( connector -- status )
    >R
    STREAMS-OPREC-KIND-CONNECTOR STREAMS-OPCONN-SIZE R@
        _SOPREC-INIT DUP IF R> DROP EXIT THEN DROP
    STREAMS-OPCONN-DIRECTION-EGRESS R@ SOPCONN.DIRECTION !
    STREAMS-OPCONN-ENDPOINT-PINNED R@ SOPCONN.ENDPOINT-POLICY !
    STREAMS-OPCONN-CREDENTIAL-NONE R@ SOPCONN.CREDENTIAL-POLICY !
    STREAMS-OPCONN-RECEIPT-NONE R@ SOPCONN.RECEIPT-POLICY !
    STREAMS-OPCONN-IDEMPOTENCY-NONE R@ SOPCONN.IDEMPOTENCY-POLICY !
    STREAMS-OPCONN-LIFECYCLE-CONFIGURED R@ SOPCONN.LIFECYCLE !
    STREAMS-OPCONN-HEALTH-UNKNOWN R@ SOPCONN.HEALTH !
    R> DROP STREAMS-OPREC-S-OK ;

: STREAMS-OPCONN-SEAL  ( connector -- status )
    DUP 0= IF DROP STREAMS-OPREC-S-INVALID EXIT THEN
    DUP STREAMS-OPCONN-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    DUP SOPREC.SEAL SHA3-256-LEN 0 FILL
    DUP _SOPCONN-SHAPE? 0= IF
        DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    DUP STREAMS-OPCONN-SIZE _SOPREC-HASH-FEED
    DUP SOPREC.SEAL SHA3-256-END
    DUP STREAMS-OPCONN-SIZE STREAMS-OPCONN-VALID? IF
        DROP STREAMS-OPREC-S-OK
    ELSE
        DUP SOPREC.SEAL SHA3-256-LEN 0 FILL
        DROP STREAMS-OPREC-S-CORRUPT
    THEN ;

: STREAMS-OPCONN-COPY  ( source destination -- status )
    OVER STREAMS-OPCONN-SIZE STREAMS-OPCONN-VALID? 0= IF
        2DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    STREAMS-OPCONN-SIZE _SOPCFG-COPY-VALID ;

