        DROP STREAMS-OPREC-S-OK
    ELSE
        DUP SOPREC.SEAL SHA3-256-LEN 0 FILL
        DROP STREAMS-OPREC-S-CORRUPT
    THEN ;

: STREAMS-OPFLOW-COPY  ( source destination -- status )
    OVER STREAMS-OPFLOW-SIZE STREAMS-OPFLOW-VALID? 0= IF
        2DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    STREAMS-OPFLOW-SIZE _SOPCFG-COPY-VALID ;

