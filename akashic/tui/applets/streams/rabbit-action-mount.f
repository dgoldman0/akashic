  ( mapper-xt mapper-context json-a json-cap building-router mount -- status )
    ['] _SRAM-INIT _SRAM-GUARD WITH-GUARD ;

\ Router storage owns the borrowed handler pointer.  Servers and the Burrow
\ must be finalized first, then the router must be RESET or FINI before this
\ record and its JSON arena can be wiped.
: _SRAM-FINI  ( mount -- status )
    DUP STREAMS-RABBIT-ACTION-MOUNT-BINDING-VALID? 0= IF
        DROP STREAMS-RABBIT-ACTION-MOUNT-S-INVALID EXIT
    THEN
    DUP SRAM.BUSY @ IF DROP STREAMS-RABBIT-ACTION-MOUNT-S-BUSY EXIT THEN
    DUP _SRAMV-M ! SRAM.ROUTER @ DUP RROUTER-BINDING-VALID? IF
        DUP RROUTER-VALID? 0= IF
            DROP STREAMS-RABBIT-ACTION-MOUNT-S-STATE EXIT
        THEN
        _SRAMV-M @ SRAM.ROUTE-INDEX @ SWAP RROUTER-HANDLER@ IF
            SWAP ['] STREAMS-RABBIT-ACTION-MOUNT-HANDLE =
            SWAP _SRAMV-M @ = AND IF
                STREAMS-RABBIT-ACTION-MOUNT-S-STATE EXIT
            THEN
        ELSE 2DROP THEN
    ELSE
        DUP RROUTER-SIZE _SRAM-ZERO-SPAN? 0= IF
            DROP STREAMS-RABBIT-ACTION-MOUNT-S-STATE EXIT
        THEN DROP
    THEN
    _SRAMV-M @ DUP _SRAM-REQUEST-CLEAR
    DUP _SRAM-JSON-CLEAR
    STREAMS-RABBIT-ACTION-MOUNT-SIZE 0 FILL
    STREAMS-RABBIT-ACTION-MOUNT-S-OK ;

: STREAMS-RABBIT-ACTION-MOUNT-FINI  ( mount -- status )
    ['] _SRAM-FINI _SRAM-GUARD WITH-GUARD ;
