\ =====================================================================
\ rabbit-action-mount.f - exact effectful Rabbit actions onto Practice
\ =====================================================================
\ This mount is deliberately separate from rabbit-facet-mount.f.  It binds
\ one exact PUBLISH selector to one exact local COMMAND capability whose
\ declared effect is MUTATE and whose descriptor promises idempotency.
\ Observe routes therefore never acquire effectful behavior by implication.
\
\ The active Burrow binding supplies the admitted peer's Practice facet and
\ context.  A facet is selection metadata, not authority: the selected entry
\ must explicitly allow INVOKE, REVIEW-COMMIT, and result disclosure, and an
\ injected authorizer must still return ALLOW.  Actor identity is derived by
\ the application owner from the stamped Practice/context fields.  No body
\ field is copied into identity or authority fields by this adapter.
\
\ Every admitted request has a nonempty Txn and Idem, an exact canonical
\ application/akashic-value+json body, and an input-schema-valid owned graph.
\ The graph is sealed with CBR-ARGS-SEAL!.  A domain-separated SHA3-256 of the
\ exact Idem bytes becomes CBR.INVOCATION-ID; the raw borrowed header is never
\ retained past the callback.  CBR.EXPECT-REV remains zero intentionally.
\ The application handler must scope its idempotency lookup by the authorized
\ actor/context, look up INVOCATION-ID first, compare CBR.ARGS-DIGEST on a
\ hit, and only then apply expected-world-revision semantics on a miss.
\
\ CBUS-S-OK and CBUS-S-NO-EFFECT both carry typed application receipts.  An
\ injected mapper validates the receipt and returns one closed response class.
\ ACCEPTED and PRECONDITION emit exact typed bodies; CONFLICT and CAPACITY are
\ bodyless.  A response encoding/build failure after CBUS-S-OK cannot undo or
\ erase the authoritative owner's receipt.  Retrying the same Idem therefore
\ reaches the owner's prior-result path instead of repeating the mutation.
\
\ The mount owns one inline reusable CBR and exclusively borrows one caller-
\ provided JSON arena.  All callback scratch is serialized and wiped.  No
\ selector, receipt, application-owner, or idempotency-ledger capacity is
\ fixed here.
\ =====================================================================

