: _SRAMH-INNER  ( -- )
    _SRAMH-ROUTE? 0= IF
        STREAMS-RABBIT-ACTION-MOUNT-S-ROUTER
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-ROUTER RROUTER-S-INVALID
        _SRAMH-FAIL EXIT
    THEN
    _SRAMH-CORRELATION? 0= IF
        STREAMS-RABBIT-ACTION-MOUNT-S-MESSAGE
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-MESSAGE RMSG-S-REQUIRED
        _SRAMH-MOUNT @ _SRAM-STATUS! DROP
        400 S" BAD REQUEST" _SRAMH-BODYLESS EXIT
    THEN
    _SRAMH-TOKEN @ _SRAMH-MOUNT @ SRAM.BURROW @
    STREAMS-RABBIT-BURROW-ACTIVE-BINDING@
    _SRAMH-STATUS ! _SRAMH-FACET ! _SRAMH-EVIDENCE ! _SRAMH-OWNER !
    _SRAMH-STATUS @ STREAMS-RABBIT-BURROW-S-OK <> IF
        STREAMS-RABBIT-ACTION-MOUNT-S-PEER
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-BURROW _SRAMH-STATUS @
        _SRAMH-FAIL EXIT
    THEN
    _SRAMH-ACTIVE-GEOMETRY? 0= IF
        STREAMS-RABBIT-ACTION-MOUNT-S-ALIAS
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-BURROW
        STREAMS-RABBIT-BURROW-S-ALIAS _SRAMH-FAIL EXIT
    THEN
    _SRAMH-OWNER @ RSERVSUB.SERVER @ DUP RSERVER.BUILDER @
        _SRAMH-BUILDER @ <> IF
        DROP STREAMS-RABBIT-ACTION-MOUNT-S-PEER
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-SERVER RSERVER-S-INVALID
        _SRAMH-FAIL EXIT
    THEN
    RABBIT-SERVER-HELD-APP-LANE-ENSURE DUP RSERVER-S-OK <> IF
        STREAMS-RABBIT-ACTION-MOUNT-S-PEER
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-SERVER ROT
        _SRAMH-FAIL EXIT
    THEN DROP
    _SRAMH-CALLER? 0= IF
        STREAMS-RABBIT-ACTION-MOUNT-S-BUS
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-CBUS CBUS-S-STALE-INSTANCE
        _SRAMH-MOUNT @ _SRAM-STATUS! DROP
        404 S" NOT FOUND" _SRAMH-BODYLESS EXIT
    THEN
    _SRAMH-TARGET-CAP? 0= IF
        STREAMS-RABBIT-ACTION-MOUNT-S-BUS
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-CBUS CBUS-S-STALE-INSTANCE
        _SRAMH-MOUNT @ _SRAM-STATUS! DROP
        404 S" NOT FOUND" _SRAMH-BODYLESS EXIT
    THEN
    _SRAMH-FACET? 0= IF
        STREAMS-RABBIT-ACTION-MOUNT-S-FACET
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-AUTHORIZER 0
        _SRAMH-DENY EXIT
    THEN
    _SRAMH-AUTHORIZED? 0= IF
        STREAMS-RABBIT-ACTION-MOUNT-S-DENIED
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-AUTHORIZER
        _SRAMH-AUTH-DECISION @ _SRAMH-DENY EXIT
    THEN
    _SRAMH-VIEW? 0= IF
        STREAMS-RABBIT-ACTION-MOUNT-S-MESSAGE
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-MESSAGE RMSG-S-VALUE
        _SRAMH-MOUNT @ _SRAM-STATUS! DROP
        400 S" BAD REQUEST" _SRAMH-BODYLESS EXIT
    THEN
    _SRAMH-MOUNT @ _SRAM-REQUEST-CLEAR
    _SRAMH-DECODE DUP _SRAMH-STATUS ! IF
        STREAMS-RABBIT-ACTION-MOUNT-S-CODEC
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-IVJSON _SRAMH-STATUS @
        _SRAMH-MOUNT @ _SRAM-STATUS! DROP
        _SRAMH-STATUS @ IVJSON-E-CAPACITY = IF
            413 S" PAYLOAD TOO LARGE"
        ELSE
            _SRAMH-STATUS @ IVJSON-E-NOMEM = IF
                503 S" UNAVAILABLE"
            ELSE
                400 S" BAD REQUEST"
            THEN
        THEN
        _SRAMH-BODYLESS EXIT
    THEN
    _SRAMH-CANONICAL? DUP _SRAMH-STATUS ! IF
        STREAMS-RABBIT-ACTION-MOUNT-S-CODEC
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-IVJSON _SRAMH-STATUS @
        _SRAMH-MOUNT @ _SRAM-STATUS! DROP
        _SRAMH-STATUS @ IVJSON-E-CAPACITY = IF
            413 S" PAYLOAD TOO LARGE"
        ELSE
            400 S" BAD REQUEST"
        THEN
        _SRAMH-BODYLESS EXIT
    THEN
    _SRAMH-STAMP-REQUEST DUP IF
        STREAMS-RABBIT-ACTION-MOUNT-S-CODEC
        STREAMS-RABBIT-ACTION-MOUNT-DETAIL-SEAL ROT
        _SRAMH-MOUNT @ _SRAM-STATUS! DROP
        503 S" UNAVAILABLE" _SRAMH-BODYLESS EXIT
    THEN DROP
    _SRAMH-DISPATCH DUP CBUS-RESULT-BEARING? IF
        _SRAMH-MAPPED-RESPONSE EXIT
    THEN
    _SRAMH-BUS-RESPONSE ;

