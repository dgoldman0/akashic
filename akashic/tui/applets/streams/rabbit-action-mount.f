    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    _SRAMI-STATE-U @ MSPAN-NONWRAPPING? ;

: _SRAMI-ALIASES?  ( source-a source-u -- flag )
    2DUP _SRAMI-MOUNT @ STREAMS-RABBIT-ACTION-MOUNT-SIZE
        MSPAN-OVERLAP? IF 2DROP -1 EXIT THEN
    _SRAMI-JSON-A @ _SRAMI-JSON-CAP @ MSPAN-OVERLAP? ;

: _SRAMI-LONG-LIVED-ALIASES?  ( source-a source-u -- flag )
    2DUP _SRAMI-ALIASES? >R
    _SRAMI-BURROW @ STREAMS-RABBIT-BURROW-SIZE MSPAN-OVERLAP?
    R> OR ;

: _SRAMI-INSTANCE-LONG-LIVED-ALIASES?  ( instance -- flag )
    DUP _SRAMI-LIVE !
    DUP COMP-INST _SRAMI-LONG-LIVED-ALIASES? IF DROP -1 EXIT THEN
    CINST-DESC DUP _SRAMI-DESC !
    DUP COMP-DESC _SRAMI-LONG-LIVED-ALIASES? IF DROP -1 EXIT THEN
    DUP COMP.CAPS-N @ CAP-DESC * _SRAMI-CAPS-U !
    COMP.CAPS-A @ _SRAMI-CAPS-A !
    _SRAMI-CAPS-U @ IF
        _SRAMI-CAPS-A @ _SRAMI-CAPS-U @
            _SRAMI-LONG-LIVED-ALIASES? IF -1 EXIT THEN
    THEN
    _SRAMI-MOUNT @ STREAMS-RABBIT-ACTION-MOUNT-SIZE _SRAMI-DESC @
        COMP-CAPS-GRAPH-SPAN-OVERLAP? IF -1 EXIT THEN
    _SRAMI-JSON-A @ _SRAMI-JSON-CAP @ _SRAMI-DESC @
        COMP-CAPS-GRAPH-SPAN-OVERLAP? IF -1 EXIT THEN
    _SRAMI-BURROW @ STREAMS-RABBIT-BURROW-SIZE _SRAMI-DESC @
        COMP-CAPS-GRAPH-SPAN-OVERLAP? IF -1 EXIT THEN
    _SRAMI-DESC @ COMP.STATE-SIZE @ _SRAMI-STATE-U !
    _SRAMI-STATE-U @ IF
        _SRAMI-LIVE @ CINST-STATE _SRAMI-STATE-U @
            _SRAMI-LONG-LIVED-ALIASES? IF -1 EXIT THEN
    THEN
    0 ;

: _SRAMI-ROUTER-ALIASES?  ( address bytes -- flag )
    _SRAMI-ROUTER @ RROUTER-OWNED-SPAN-OVERLAP? ;

: _SRAMI-DESC-ROUTER-GRAPH-ALIASES?  ( comp-desc -- flag )
    _SRAMI-DESC !
    RROUTER-OWNED-SPAN-COUNT 0 ?DO
        I _SRAMI-ROUTER @ RROUTER-OWNED-SPAN@
        _SRAMI-OWN-STATUS ! _SRAMI-OWN-U ! _SRAMI-OWN-A !
        _SRAMI-OWN-STATUS @ RROUTER-S-OK <> IF -1 UNLOOP EXIT THEN
        _SRAMI-OWN-A @ _SRAMI-OWN-U @ _SRAMI-DESC @
            COMP-CAPS-GRAPH-SPAN-OVERLAP? IF -1 UNLOOP EXIT THEN
    LOOP
    0 ;

: _SRAMI-INSTANCE-ROUTER-ALIASES?  ( instance -- flag )
    DUP _SRAMI-LIVE !
    DUP COMP-INST _SRAMI-ROUTER-ALIASES? IF DROP -1 EXIT THEN
    CINST-DESC DUP _SRAMI-DESC !
    DUP COMP-DESC _SRAMI-ROUTER-ALIASES? IF DROP -1 EXIT THEN
    DUP COMP.CAPS-N @ CAP-DESC * _SRAMI-CAPS-U !
    COMP.CAPS-A @ _SRAMI-CAPS-A !
    _SRAMI-CAPS-U @ IF
        _SRAMI-CAPS-A @ _SRAMI-CAPS-U @ _SRAMI-ROUTER-ALIASES? IF
            -1 EXIT
        THEN
    THEN
    _SRAMI-DESC @ _SRAMI-DESC-ROUTER-GRAPH-ALIASES? IF -1 EXIT THEN
    _SRAMI-DESC @ COMP.STATE-SIZE @ _SRAMI-STATE-U !
    _SRAMI-STATE-U @ IF
        _SRAMI-LIVE @ CINST-STATE _SRAMI-STATE-U @
            _SRAMI-ROUTER-ALIASES? IF -1 EXIT THEN
    THEN
    0 ;

: _SRAM-ZERO-SPAN?  ( address bytes -- flag )
    0 ?DO
        DUP I + C@ IF DROP 0 UNLOOP EXIT THEN
    LOOP
    DROP -1 ;

: _SRAMI-PREFLIGHT?  ( -- flag )
    _SRAMI-MOUNT @ DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP STREAMS-RABBIT-ACTION-MOUNT-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP 0 EXIT
    THEN
    SRAM.MAGIC @ _SRAM-MAGIC-VALUE = IF 0 EXIT THEN
    _SRAMI-SELECTOR-U @ 0> 0= IF 0 EXIT THEN
    _SRAMI-SELECTOR-A @ _SRAMI-SELECTOR-U @
        MSPAN-NONWRAPPING? 0= IF 0 EXIT THEN
    _SRAMI-AUTH-XT @ 0= IF 0 EXIT THEN
    _SRAMI-MAPPER-XT @ 0= IF 0 EXIT THEN
    _SRAMI-JSON-CAP @ 0> 0= IF 0 EXIT THEN
    _SRAMI-JSON-A @ DUP 0= IF DROP 0 EXIT THEN
    _SRAMI-JSON-CAP @ MSPAN-NONWRAPPING? 0= IF 0 EXIT THEN
    _SRAMI-MOUNT @ STREAMS-RABBIT-ACTION-MOUNT-SIZE
    _SRAMI-JSON-A @ _SRAMI-JSON-CAP @ MSPAN-OVERLAP? IF 0 EXIT THEN
    _SRAMI-SELECTOR-A @ _SRAMI-SELECTOR-U @ _SRAMI-ALIASES? IF 0 EXIT THEN
    _SRAMI-BURROW @ DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    STREAMS-RABBIT-BURROW-SIZE MSPAN-NONWRAPPING? 0= IF 0 EXIT THEN
    _SRAMI-BURROW @ STREAMS-RABBIT-BURROW-SIZE _SRAMI-ALIASES? IF
        0 EXIT
    THEN
    _SRAMI-BURROW @ STREAMS-RABBIT-BURROW-SIZE _SRAM-ZERO-SPAN? 0= IF
        0 EXIT
    THEN
    _SRAMI-BUS @ _SRAM-BUS-GEOMETRY? 0= IF 0 EXIT THEN
    _SRAMI-BUS @ CBUS.REGISTRY @ _SRAMI-REGISTRY !
    _SRAMI-BUS @ CBUS-SIZE _SRAMI-LONG-LIVED-ALIASES? IF 0 EXIT THEN
    _SRAMI-REGISTRY @ CREG-SIZE _SRAMI-LONG-LIVED-ALIASES? IF
        0 EXIT
    THEN
    _SRAMI-CALLER @ _SRAMI-LIVE-INSTANCE? 0= IF 0 EXIT THEN
    _SRAMI-TARGET @ _SRAMI-LIVE-INSTANCE? 0= IF 0 EXIT THEN
    _SRAMI-CALLER @ _SRAMI-INSTANCE-LONG-LIVED-ALIASES? IF 0 EXIT THEN
    _SRAMI-TARGET @ _SRAMI-INSTANCE-LONG-LIVED-ALIASES? IF 0 EXIT THEN
    _SRAMI-CAP @ _SRAM-ACTION-CAP? 0= IF 0 EXIT THEN
    _SRAMI-CAP @ CAP-DESC _SRAMI-LONG-LIVED-ALIASES? IF 0 EXIT THEN
    _SRAMI-CAP @ DUP CAP-ID
        _SRAMI-TARGET @ CINST-DESC COMP-CAP-FIND <> IF 0 EXIT THEN
    _SRAMI-RESOURCE @ ?DUP IF
        DUP RID-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
        DUP RID-SIZE _SRAMI-ALIASES? IF DROP 0 EXIT THEN DROP
    THEN
    _SRAMI-ROUTER @ DUP RROUTER-VALID? 0= IF DROP 0 EXIT THEN
    DUP RROUTER-STATE@ RROUTER-STATE-BUILDING <> IF DROP 0 EXIT THEN
    _SRAMI-MOUNT @ STREAMS-RABBIT-ACTION-MOUNT-SIZE _SRAMI-ROUTER @
        RROUTER-OWNED-SPAN-OVERLAP? IF DROP 0 EXIT THEN
    _SRAMI-BURROW @ STREAMS-RABBIT-BURROW-SIZE _SRAMI-ROUTER @
        RROUTER-OWNED-SPAN-OVERLAP? IF DROP 0 EXIT THEN
    _SRAMI-BUS @ CBUS-SIZE _SRAMI-ROUTER @
        RROUTER-OWNED-SPAN-OVERLAP? IF DROP 0 EXIT THEN
    _SRAMI-REGISTRY @ CREG-SIZE _SRAMI-ROUTER @
        RROUTER-OWNED-SPAN-OVERLAP? IF DROP 0 EXIT THEN
    _SRAMI-CALLER @ _SRAMI-INSTANCE-ROUTER-ALIASES? IF DROP 0 EXIT THEN
    _SRAMI-TARGET @ _SRAMI-INSTANCE-ROUTER-ALIASES? IF DROP 0 EXIT THEN
    _SRAMI-CAP @ CAP-DESC _SRAMI-ROUTER @
        RROUTER-OWNED-SPAN-OVERLAP? IF DROP 0 EXIT THEN
    _SRAMI-JSON-A @ _SRAMI-JSON-CAP @ ROT
        RROUTER-OWNED-SPAN-OVERLAP? 0= ;

: _SRAMI-WIPE  ( -- )
    _SRAMI-JSON-A @ _SRAMI-JSON-CAP @ 0 FILL
    _SRAMI-MOUNT @ STREAMS-RABBIT-ACTION-MOUNT-SIZE 0 FILL ;

: _SRAM-INIT
  ( selector-a selector-u caller target cap resource-rid|0 )
  ( bus future-burrow authorizer-xt authorizer-context )
  ( mapper-xt mapper-context json-a json-cap building-router mount -- status )
    _SRAMI-MOUNT ! _SRAMI-ROUTER ! _SRAMI-JSON-CAP ! _SRAMI-JSON-A !
    _SRAMI-MAPPER-CONTEXT ! _SRAMI-MAPPER-XT !
    _SRAMI-AUTH-CONTEXT ! _SRAMI-AUTH-XT ! _SRAMI-BURROW !
    _SRAMI-BUS ! _SRAMI-RESOURCE ! _SRAMI-CAP ! _SRAMI-TARGET !
    _SRAMI-CALLER ! _SRAMI-SELECTOR-U ! _SRAMI-SELECTOR-A !
    _SRAMI-PREFLIGHT? 0= IF
        STREAMS-RABBIT-ACTION-MOUNT-S-INVALID EXIT
    THEN
    _SRAMI-ROUTER @ RROUTER-COUNT@ _SRAMI-ROUTE-INDEX !
    _SRAMI-WIPE
    _SRAMI-ROUTE-INDEX @ _SRAMI-MOUNT @ SRAM.ROUTE-INDEX !
    _SRAMI-ROUTER @ _SRAMI-MOUNT @ SRAM.ROUTER !
    _SRAMI-BUS @ _SRAMI-MOUNT @ SRAM.BUS !
    _SRAMI-BURROW @ _SRAMI-MOUNT @ SRAM.BURROW !
    _SRAMI-CALLER @ CINST.ID @ _SRAMI-MOUNT @ SRAM.CALLER-ID !
    _SRAMI-CALLER @ CINST.GENERATION @ _SRAMI-MOUNT @ SRAM.CALLER-GEN !
    _SRAMI-TARGET @ CINST.ID @ _SRAMI-MOUNT @ SRAM.TARGET-ID !
    _SRAMI-TARGET @ CINST.GENERATION @ _SRAMI-MOUNT @ SRAM.TARGET-GEN !
    _SRAMI-CAP @ _SRAMI-MOUNT @ SRAM.CAP !
    _SRAMI-AUTH-XT @ _SRAMI-MOUNT @ SRAM.AUTH-XT !
    _SRAMI-AUTH-CONTEXT @ _SRAMI-MOUNT @ SRAM.AUTH-CONTEXT !
    _SRAMI-MAPPER-XT @ _SRAMI-MOUNT @ SRAM.MAPPER-XT !
    _SRAMI-MAPPER-CONTEXT @ _SRAMI-MOUNT @ SRAM.MAPPER-CONTEXT !
    _SRAMI-JSON-A @ _SRAMI-MOUNT @ SRAM.JSON-A !
    _SRAMI-JSON-CAP @ _SRAMI-MOUNT @ SRAM.JSON-CAP !
    _SRAMI-RESOURCE @ ?DUP IF
        _SRAMI-MOUNT @ SRAM.RESOURCE-ID RID-COPY
    THEN
    S" PUBLISH" _SRAMI-SELECTOR-A @ _SRAMI-SELECTOR-U @
    ['] STREAMS-RABBIT-ACTION-MOUNT-HANDLE _SRAMI-MOUNT @
    _SRAMI-ROUTER @ RROUTER-ADD DUP _SRAMI-STATUS !
    RROUTER-S-OK <> IF
        _SRAMI-WIPE STREAMS-RABBIT-ACTION-MOUNT-S-ROUTER EXIT
    THEN
    _SRAM-MAGIC-VALUE _SRAMI-MOUNT @ SRAM.MAGIC !
    _SRAM-ABI-VERSION _SRAMI-MOUNT @ SRAM.ABI !
    STREAMS-RABBIT-ACTION-MOUNT-SIZE _SRAMI-MOUNT @ SRAM.BYTES !
    STREAMS-RABBIT-ACTION-MOUNT-ST-BOUND _SRAMI-MOUNT @ SRAM.STATE !
    STREAMS-RABBIT-ACTION-MOUNT-S-OK _SRAMI-MOUNT @ SRAM.LAST-STATUS !
    STREAMS-RABBIT-ACTION-MOUNT-S-OK ;

: STREAMS-RABBIT-ACTION-MOUNT-INIT
  ( selector-a selector-u caller target cap resource-rid|0 )
