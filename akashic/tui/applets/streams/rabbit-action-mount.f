            _SRAMH-MOUNT @ _SRAM-STATUS! DROP
            0 _SRAMH-MOUNT-CLAIMED !
        THEN
    THEN
    _SRAM-GUARD GUARD-RELEASE
    DUP IF
        DROP _SRAMH-DROP-CALL RSERVER-HANDLER-FAILED EXIT
    THEN
    DROP ;

