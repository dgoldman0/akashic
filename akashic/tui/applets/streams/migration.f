: _SMIG-RUN-ARGS?
  ( authority-id source-store observation-store repository repository-work migration-work -- flag )
    >R
    R@ STREAMS-MIGRATION-WORK-VALID? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN
    R@ _SMW.BUSY @ IF _SMIG-DROP5 R> DROP 0 EXIT THEN
    2DUP STREAMS-REPOSITORY-WORK-BOUND? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN
    3 PICK STREAMS-SOURCE-STORE-VALID? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN
    2 PICK STREAMS-OBSERVATION-STORE-VALID? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN
    4 PICK RID-PRESENT? 0= IF _SMIG-DROP5 R> DROP 0 EXIT THEN

    R@ STREAMS-MIGRATION-WORK-SIZE
        3 PICK 3 PICK STREAMS-REPOSITORY-SPAN-DISJOINT? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN
    3 PICK STREAMS-SOURCE-STORE-SIZE
        3 PICK 3 PICK STREAMS-REPOSITORY-SPAN-DISJOINT? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN
    2 PICK STREAMS-OBSERVATION-STORE-SIZE
        3 PICK 3 PICK STREAMS-REPOSITORY-SPAN-DISJOINT? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN
    4 PICK RID-SIZE
        3 PICK 3 PICK STREAMS-REPOSITORY-SPAN-DISJOINT? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN

    R@ STREAMS-MIGRATION-WORK-SIZE
        5 PICK STREAMS-SOURCE-STORE-SIZE
        _SMIG-SPANS-DISJOINT? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN
    R@ STREAMS-MIGRATION-WORK-SIZE
        4 PICK STREAMS-OBSERVATION-STORE-SIZE
        _SMIG-SPANS-DISJOINT? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN
    3 PICK STREAMS-SOURCE-STORE-SIZE
        4 PICK STREAMS-OBSERVATION-STORE-SIZE
        _SMIG-SPANS-DISJOINT? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN
    4 PICK RID-SIZE R@ STREAMS-MIGRATION-WORK-SIZE
        _SMIG-SPANS-DISJOINT? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN
    4 PICK RID-SIZE 5 PICK STREAMS-SOURCE-STORE-SIZE
        _SMIG-SPANS-DISJOINT? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN
    4 PICK RID-SIZE 4 PICK STREAMS-OBSERVATION-STORE-SIZE
        _SMIG-SPANS-DISJOINT? 0= IF
        _SMIG-DROP5 R> DROP 0 EXIT
    THEN
    _SMIG-DROP5 R> DROP -1 ;

