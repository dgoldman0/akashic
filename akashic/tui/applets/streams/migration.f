    R@ _SMW.SOURCE-COUNT @ OVER SAR.MUTATION-SEQUENCE !
    R@ _SMIG-ACQUISITION-SEQUENCE@
        OVER SAR.ACQUISITION-SEQUENCE !
    R@ _SMW.SOURCE-COUNT @ OVER SAR.SOURCE-COUNT !
    R@ _SMW.ATTEMPT-COUNT @ OVER SAR.ATTEMPT-COUNT !
    R@ _SMW.OBSERVATION-COUNT @ OVER SAR.OBSERVATION-COUNT !
    R@ _SMW.NATIVE-COUNT @ OVER SAR.NATIVE-COUNT !
    0 OVER SAR.ACTIVE-COUNT !
    R@ _SMW.PROVENANCE @ OVER SAR.PROVENANCE !
    R@ _SMW.SOURCE-COMPLETENESS @
        OVER SAR.SOURCE-COMPLETENESS !
    R@ _SMW.OBSERVATION-COMPLETENESS @
        OVER SAR.OBSERVATION-COMPLETENESS !
    R@ _SMW.SOURCE-PRESENT @ OVER SAR.LEGACY-SOURCE-PRESENT !
    R@ _SMW.SOURCE-RECORD-U @ OVER SAR.LEGACY-SOURCE-BYTES !
    R@ _SMW.SOURCE-DIGEST OVER SAR.LEGACY-SOURCE-DIGEST
        SHA3-256-LEN MOVE
    R@ _SMW.OBSERVATION-PRESENT @
        OVER SAR.LEGACY-OBSERVATION-PRESENT !
    R@ _SMW.OBSERVATION-RECORD-U @
        OVER SAR.LEGACY-OBSERVATION-BYTES !
    R@ _SMW.OBSERVATION-DIGEST
        OVER SAR.LEGACY-OBSERVATION-DIGEST SHA3-256-LEN MOVE
    0 OVER SAR.REMOVED-SOURCE-COUNT !

    DUP R@ _SMIG-ROOT-METADATA? 0= IF
        DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    DROP
    R@ _SMW.ADAPTER @ R@ _SMW.ADAPTER-WORK @
        STREAMS-PA-MARK-MUTATED
    R> DROP ;

: _SMIG-STAGE-CORE  ( work -- status )
    >R
    R@ _SMW.AUTHORITY-ID
    R@ _SMW.ADAPTER @ R@ _SMW.ADAPTER-WORK @
        STREAMS-PA-FIRST-STAGE-BEGIN
    DUP IF R> DROP EXIT THEN DROP
    R@ _SMIG-IMPORT-ALL
    DUP IF R> DROP EXIT THEN DROP
    R@ _SMIG-VERIFY-ALL
    DUP IF R> DROP EXIT THEN DROP
    R@ _SMIG-EDIT-STAGED-ROOT
    DUP IF R> DROP EXIT THEN DROP
    -1 R@ _SMW.COMMIT-ATTEMPTED !
    R@ _SMW.ADAPTER @ R@ _SMW.ADAPTER-WORK @
        STREAMS-PA-FIRST-STAGE-COMMIT
    R> DROP ;

: _SMIG-STAGE-DISPATCH  ( work -- )
    DUP _SMIG-STAGE-CORE SWAP _SMW.STAGE-STATUS ! ;

\ The repository owner callback may return only the repository status domain.
\ A clean pre-commit discard therefore returns repository OK and leaves the
\ semantic failure in STAGE-STATUS for the outer migration call.
: _SMIG-STAGING-BODY
  ( migration-work repository repository-work -- repository-status )
    2 PICK _SMW.REPOSITORY @ 2 PICK <> IF
        _SMIG-DROP3 STREAMS-REPOSITORY-S-INVALID EXIT
    THEN
    2 PICK _SMW.REPOSITORY-WORK @ OVER <> IF
        _SMIG-DROP3 STREAMS-REPOSITORY-S-INVALID EXIT
    THEN
    OVER STREAMS-REPOSITORY-ADAPTER@
        3 PICK _SMW.ADAPTER !
    DUP STREAMS-REPOSITORY-ADAPTER-WORK@
        3 PICK _SMW.ADAPTER-WORK !
    2DROP
    >R
    R@ _SMW.ADAPTER @ 0=
    R@ _SMW.ADAPTER-WORK @ 0= OR IF
        R> DROP STREAMS-REPOSITORY-S-INVALID EXIT
    THEN
    STREAMS-MIGRATION-S-FAULT R@ _SMW.STAGE-STATUS !
    R@ ['] _SMIG-STAGE-DISPATCH CATCH
    DUP IF
        2DROP
    ELSE
        DROP
    THEN
    R@ _SMW.STAGE-STATUS @ DUP 0= IF
        DROP R> DROP STREAMS-REPOSITORY-S-OK EXIT
    THEN
    R@ _SMW.COMMIT-ATTEMPTED @ IF
        R> DROP EXIT
    THEN
    DROP
    R@ _SMW.ADAPTER @ R@ _SMW.ADAPTER-WORK @
        STREAMS-PA-FIRST-STAGE-DISCARD
    DUP STREAMS-PA-S-OK = IF
        DROP R> DROP STREAMS-REPOSITORY-S-OK EXIT
    THEN
    DUP R@ _SMW.STAGE-STATUS !
    R> DROP ;

: _SMIG-REPOSITORY-LOAD  ( work -- status )
    >R
    R@ _SMW.REPOSITORY @ R@ _SMW.REPOSITORY-WORK @
        STREAMS-REPOSITORY-LOAD
    R> DROP ;

: _SMIG-PUBLISHED-ROOT?  ( work -- flag )
    >R
    R@ _SMW.REPOSITORY-WORK @
        STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF DROP R> DROP 0 EXIT THEN
    DUP STREAMS-AUTHORITY-ROOT-HEADER-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _SMIG-ROOT-METADATA?
    R> DROP ;

: _SMIG-RESOLVE-AFTER-COMMIT  ( work -- status )
    >R
    R@ _SMIG-REPOSITORY-LOAD
    DUP STREAMS-REPOSITORY-S-OK = IF
        DROP
        R@ _SMIG-PUBLISHED-ROOT? 0= IF
            R> DROP STREAMS-MIGRATION-S-VERIFY EXIT
        THEN
        -1 R@ _SMW.FLIP-CONFIRMED !
        R> DROP STREAMS-MIGRATION-S-OK EXIT
    THEN
    DUP STREAMS-REPOSITORY-S-ABSENT = IF
        DROP
        R@ _SMW.STAGE-STATUS @ DUP IF
            R> DROP EXIT
        THEN
        DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    R> DROP ;

: _SMIG-RESOLVE-PREPARE-CONFLICT  ( work -- status )
    >R
    R@ _SMIG-REPOSITORY-LOAD
    DUP STREAMS-REPOSITORY-S-OK = IF
        DROP -1 R@ _SMW.FLIP-CONFIRMED !
        R> DROP STREAMS-MIGRATION-S-ALREADY EXIT
    THEN
    DUP STREAMS-REPOSITORY-S-ABSENT = IF
        DROP R> DROP STREAMS-MIGRATION-S-CONFLICT EXIT
    THEN
    R> DROP ;

: _SMIG-WITH-STAGING-OWNER  ( work -- status )
    >R
    R@ ['] _SMIG-STAGING-BODY
    R@ _SMW.REPOSITORY @ R@ _SMW.REPOSITORY-WORK @
        STREAMS-REPOSITORY-WITH-STAGING-OWNER
    R> DROP ;

\ ---------------------------------------------------------------------
\ Idempotent cold orchestration
\ ---------------------------------------------------------------------

: _SMIG-RUN-INNER  ( work -- status )
    DUP _SMIG-REPOSITORY-LOAD
    DUP STREAMS-REPOSITORY-S-OK = IF
        DROP
        -1 OVER _SMW.FLIP-CONFIRMED !
        DROP STREAMS-MIGRATION-S-ALREADY EXIT
    THEN
    DUP STREAMS-REPOSITORY-S-ABSENT <> IF NIP EXIT THEN
    DROP

    DUP _SMIG-LOAD-LEGACY
    DUP IF NIP EXIT THEN DROP
    DUP _SMIG-PREPARE-LEGACY
    DUP IF NIP EXIT THEN DROP

    DUP _SMW.REPOSITORY @
    OVER _SMW.REPOSITORY-WORK @
        STREAMS-REPOSITORY-STAGING-PREPARE
    DUP IF
        DUP STREAMS-REPOSITORY-S-CONFLICT = IF
            DROP _SMIG-RESOLVE-PREPARE-CONFLICT EXIT
        THEN
        NIP EXIT
    THEN
    DROP

    STREAMS-MIGRATION-S-OK OVER _SMW.STAGE-STATUS !
    0 OVER _SMW.COMMIT-ATTEMPTED !
    DUP _SMIG-WITH-STAGING-OWNER
    DUP 2 PICK _SMW.OWNER-STATUS !
    OVER _SMW.COMMIT-ATTEMPTED @ IF
        DROP _SMIG-RESOLVE-AFTER-COMMIT EXIT
    THEN
    DUP IF NIP EXIT THEN
    DROP
    DUP _SMW.STAGE-STATUS @ SWAP DROP ;

: _SMIG-RUN-DISPATCH  ( work -- )
    DUP _SMIG-RUN-INNER SWAP _SMW.STATUS ! ;

: STREAMS-MIGRATION-RUN
  ( authority-id source-store observation-store repository repository-work migration-work -- status )
    DUP STREAMS-MIGRATION-WORK-VALID? 0= IF
        _SMIG-DROP6 STREAMS-MIGRATION-S-INVALID EXIT
    THEN
    DUP _SMW.BUSY @ IF
        _SMIG-DROP6 STREAMS-MIGRATION-S-BUSY EXIT
    THEN
    5 PICK 5 PICK 5 PICK 5 PICK 5 PICK 5 PICK
        _SMIG-RUN-ARGS? 0= IF
        _SMIG-DROP6 STREAMS-MIGRATION-S-INVALID EXIT
    THEN
    >R
    -1 R@ _SMW.BUSY !
    R@ _SMIG-RUN-RESET
    4 PICK R@ _SMW.AUTHORITY-ID RID-COPY
    3 PICK R@ _SMW.SOURCE-STORE !
    2 PICK R@ _SMW.OBSERVATION-STORE !
    1 PICK R@ _SMW.REPOSITORY !
    DUP R@ _SMW.REPOSITORY-WORK !
    _SMIG-DROP5

    R@ ['] _SMIG-RUN-DISPATCH CATCH
    DUP IF
        2DROP
        STREAMS-MIGRATION-S-FAULT R@ _SMW.STATUS !
    ELSE
        DROP
    THEN
    0 R@ _SMW.BUSY !
    R@ _SMW.STATUS @ R> DROP ;
