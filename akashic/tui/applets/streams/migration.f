: _SMIG-LOAD-SOURCE-EVIDENCE  ( work -- status )
    >R
    R@ _SMW.SOURCE-EVIDENCE STREAMS-SOURCE-REGISTRY-SIZE
    R@ _SMW.SOURCE-DIGEST R@ _SMW.SOURCE-STORE @
        STREAMS-SOURCE-STORE-LOAD-EVIDENCE
    DUP SSSTORE-S-OK = IF
        DROP
        DUP 0< IF 2DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT THEN
        DUP R@ _SMW.SOURCE-GENERATION !
        DROP
        DUP R@ _SMW.SOURCE-RECORD-U !
        STREAMS-SOURCE-STORE-RECORD-MAX <> IF
            R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
        THEN
        R@ _SMW.SOURCE-DIGEST RID-PRESENT? 0= IF
            R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
        THEN
        R@ _SMW-REGISTRY STREAMS-SOURCE-REGISTRY-VALID? 0= IF
            R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
        THEN
        R@ _SMW-REGISTRY SSREG.GENERATION @
            R@ _SMW.SOURCE-GENERATION @ <> IF
            R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
        THEN
        -1 R@ _SMW.SOURCE-PRESENT !
        R> DROP STREAMS-MIGRATION-S-OK EXIT
    THEN
    DUP SSSTORE-S-ABSENT = IF
        DROP
        OR IF R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT THEN
        R@ _SMW.SOURCE-DIGEST SHA3-256-LEN _SMIG-ZERO? 0= IF
            R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
        THEN
        R> DROP STREAMS-MIGRATION-S-OK EXIT
    THEN
    NIP NIP _SMIG-SOURCE>STATUS R> DROP ;

: _SMIG-LOAD-OBSERVATION-EVIDENCE  ( work -- status )
    >R
    R@ _SMW.OBSERVATION-EVIDENCE
        STREAMS-OBSERVATION-CHECKPOINT-SIZE
    R@ _SMW.OBSERVATION-DIGEST R@ _SMW.OBSERVATION-STORE @
        STREAMS-OBSERVATION-STORE-LOAD-EVIDENCE
    DUP OSTORE-S-OK = IF
        DROP
        DUP 0< IF 2DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT THEN
        DUP R@ _SMW.OBSERVATION-GENERATION !
        DROP
        DUP R@ _SMW.OBSERVATION-RECORD-U !
        STREAMS-OBSERVATION-STORE-RECORD-MAX <> IF
            R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
        THEN
        R@ _SMW.OBSERVATION-DIGEST RID-PRESENT? 0= IF
            R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
        THEN
        R@ _SMW-EVIDENCE-CHECKPOINT OCHK-VALID? 0= IF
            R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
        THEN
        R@ _SMW-EVIDENCE-CHECKPOINT R@ _SMW.CHECKPOINT
            STREAMS-OBSERVATION-CHECKPOINT-SIZE MOVE
        R@ _SMW.CHECKPOINT OCHK.GENERATION @
            R@ _SMW.OBSERVATION-GENERATION @ <> IF
            R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
        THEN
        -1 R@ _SMW.OBSERVATION-PRESENT !
        R> DROP STREAMS-MIGRATION-S-OK EXIT
    THEN
    DUP OSTORE-S-ABSENT = IF
        DROP
        OR IF R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT THEN
        R@ _SMW.OBSERVATION-DIGEST SHA3-256-LEN _SMIG-ZERO? 0= IF
            R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
        THEN
        R> DROP STREAMS-MIGRATION-S-OK EXIT
    THEN
    NIP NIP _SMIG-OBSERVATION>STATUS R> DROP ;

: _SMIG-LOAD-LEGACY  ( work -- status )
    DUP _SMIG-LOAD-SOURCE-EVIDENCE
    DUP IF NIP EXIT THEN DROP
    _SMIG-LOAD-OBSERVATION-EVIDENCE ;

