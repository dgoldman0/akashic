\ =====================================================================
\  migration.f - cold legacy-to-repository Streams authority migration
\ =====================================================================
\  This module performs the one supported L13 authority transition:
\
\      legacy snapshots -> hidden repository staging -> verified first root
\
\  It never dual-writes, saves, clears, or falls back to either legacy
\  snapshot.  A pre-existing valid repository root wins before legacy is
\  inspected.  Legacy ACCEPTED attempts are terminalized as INDETERMINATE
\  only in this caller-owned work copy; the exact checked-record fingerprint
\  and the checked semantic payload remain unchanged in the evidence area.
\
\  The caller supplies initialized source/observation stores, an initialized
\  repository and bound repository work, a nonzero authority RID, and one
\  migration work span.  All migration scratch and callback state is inside
\  that work span.  Work is fixed by the legacy maxima: sixteen sources,
\  sixteen retained attempt heads, forty-eight observation revisions, and
\  sixty-four native heads.
\
\  Public API:
\    STREAMS-MIGRATION-WORK-INIT
\      ( work -- status )
\    STREAMS-MIGRATION-WORK-VALID?
\      ( work -- flag )
\    STREAMS-MIGRATION-RUN
\      ( authority-id source-store observation-store repository
\        repository-work migration-work -- status )
\
\  OK means this call published and reopened the verified first root.
\  ALREADY means LOAD found an existing valid repository authority before
\  any legacy read.  Every other status leaves authority selection to a
\  subsequent repository LOAD; callers must never infer a legacy fallback
\  from a failed or uncertain commit attempt.
\ =====================================================================

PROVIDED akashic-tui-streams-migration

