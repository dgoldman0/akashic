: _SMIG-CANDIDATE-FROM-KEY  ( key work -- status )
    >R
    R@ _SMW.CANDIDATE OCHK-CANDIDATE-INIT
    DUP OCK.FORMAT @ R@ _SMW.CANDIDATE OCC.FORMAT !
    DUP OCK.NATIVE-KIND @ R@ _SMW.CANDIDATE OCC.NATIVE-KIND !
    DUP R@ _SMW.CHECKPOINT OCHK-KEY-NATIVE$
        R@ _SMW.CANDIDATE OCC.NATIVE-A
        R@ _SMW.CANDIDATE OCC.NATIVE-U _SMIG-VIEW!
    DROP
    R@ _SMW.CANDIDATE SPREC-CANDIDATE-VALID?
    IF STREAMS-MIGRATION-S-OK
    ELSE STREAMS-MIGRATION-S-CORRUPT THEN
    R> DROP ;

: _SMIG-CANDIDATE-FROM-OBSERVATION  ( observation work -- status )
    >R
    DUP OCO.KEY-INDEX @ R@ _SMW.CHECKPOINT OCHK-KEY-NTH
    DUP 0= IF
        2DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    R@ _SMW.CANDIDATE OCHK-CANDIDATE-INIT
    OVER OCO.FORMAT @ R@ _SMW.CANDIDATE OCC.FORMAT !
    DUP OCK.NATIVE-KIND @ R@ _SMW.CANDIDATE OCC.NATIVE-KIND !
    DUP R@ _SMW.CHECKPOINT OCHK-KEY-NATIVE$
        R@ _SMW.CANDIDATE OCC.NATIVE-A
        R@ _SMW.CANDIDATE OCC.NATIVE-U _SMIG-VIEW!
    OVER R@ _SMW.CHECKPOINT OCHK-OBSERVATION-TITLE$
        R@ _SMW.CANDIDATE OCC.TITLE-A
        R@ _SMW.CANDIDATE OCC.TITLE-U _SMIG-VIEW!
    OVER R@ _SMW.CHECKPOINT OCHK-OBSERVATION-URL$
        R@ _SMW.CANDIDATE OCC.URL-A
        R@ _SMW.CANDIDATE OCC.URL-U _SMIG-VIEW!
    OVER R@ _SMW.CHECKPOINT OCHK-OBSERVATION-SUMMARY$
        R@ _SMW.CANDIDATE OCC.SUMMARY-A
        R@ _SMW.CANDIDATE OCC.SUMMARY-U _SMIG-VIEW!
    OVER R@ _SMW.CHECKPOINT OCHK-OBSERVATION-CONTENT$
        R@ _SMW.CANDIDATE OCC.CONTENT-A
        R@ _SMW.CANDIDATE OCC.CONTENT-U _SMIG-VIEW!
    OVER R@ _SMW.CHECKPOINT OCHK-OBSERVATION-PUBLISHED$
        R@ _SMW.CANDIDATE OCC.PUBLISHED-A
        R@ _SMW.CANDIDATE OCC.PUBLISHED-U _SMIG-VIEW!
    OVER R@ _SMW.CHECKPOINT OCHK-OBSERVATION-MODIFIED$
        R@ _SMW.CANDIDATE OCC.MODIFIED-A
        R@ _SMW.CANDIDATE OCC.MODIFIED-U _SMIG-VIEW!
    2DROP
    R@ _SMW.CANDIDATE SPREC-CANDIDATE-VALID?
    IF STREAMS-MIGRATION-S-OK
    ELSE STREAMS-MIGRATION-S-CORRUPT THEN
    R> DROP ;

: _SMIG-NATIVE-BUCKET-KEYS?  ( key1 key2 -- flag )
    >R
    DUP OCK.SOURCE-ID R@ OCK.SOURCE-ID RID= 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP OCK.NAMESPACE R@ OCK.NAMESPACE SHA3-256-LEN
        _SMIG-BYTES= 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP OCK.FORMAT @ R@ OCK.FORMAT @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP OCK.NATIVE-KIND @ R@ OCK.NATIVE-KIND @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    OCK.NATIVE-DIGEST R> OCK.NATIVE-DIGEST SHA3-256-LEN
        _SMIG-BYTES= ;

: _SMIG-NATIVE-BUCKET-PAIR?  ( index1 index2 work -- flag )
    >R
    OVER R@ _SMW.CHECKPOINT OCHK-KEY-NTH
    SWAP R@ _SMW.CHECKPOINT OCHK-KEY-NTH
    ROT DROP
    _SMIG-NATIVE-BUCKET-KEYS?
    R> DROP ;

: _SMIG-NATIVE-EXACT-KEYS?  ( key1 key2 work -- flag )
    >R
    2DUP _SMIG-NATIVE-BUCKET-KEYS? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    OVER R@ _SMW.CHECKPOINT OCHK-KEY-NATIVE$
    2 PICK R@ _SMW.CHECKPOINT OCHK-KEY-NATIVE$
    _SMIG-$=
    NIP NIP R> DROP ;

: _SMIG-NATIVE-ORDINAL  ( index work -- ordinal )
    0 OVER _SMW.TEMP !
    OVER 1+ 0 ?DO
        I 2 PICK 2 PICK _SMIG-NATIVE-BUCKET-PAIR? IF
            1 OVER _SMW.TEMP +!
        THEN
    LOOP
    NIP _SMW.TEMP @ ;

: _SMIG-CONSTRUCT-NATIVE  ( key-index work -- status )
    >R
    DUP R@ _SMIG-NATIVE-ORDINAL
    DUP 1 < OVER STREAMS-PI-NATIVE-COLLISION-MAX > OR IF
        2DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    DUP R@ _SMW.TEMP2 !
    DROP
    R@ _SMW.CHECKPOINT OCHK-KEY-NTH
    DUP 0= IF DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT THEN

    R@ _SMW.RECORD SPREC-NATIVE-INIT _SMIG-SPREC>STATUS
    DUP IF NIP R> DROP EXIT THEN DROP
    DUP OCK.SOURCE-ID R@ _SMW.RECORD SPRH.SOURCE-ID RID-COPY
    DUP OCK.NAMESPACE R@ _SMW.RECORD SPRH.NAMESPACE
        SHA3-256-LEN MOVE
    DUP OCK.LATEST-REVISION @
        R@ _SMW.RECORD SPRH.LATEST-REVISION !
    DUP OCK.LAST-SEEN-SEQUENCE @
        R@ _SMW.RECORD SPRH.LAST-SEEN-SEQUENCE !
    R@ _SMW.TEMP2 @ R@ _SMW.RECORD SPRH.COLLISION-ORDINAL !

    DUP R@ _SMIG-CANDIDATE-FROM-KEY
    DUP IF NIP R> DROP EXIT THEN DROP
    R@ _SMW.CANDIDATE R@ _SMW.RECORD
        SPREC-NATIVE-CANDIDATE! _SMIG-SPREC>STATUS
    DUP IF NIP R> DROP EXIT THEN DROP
    DUP OCK.OBSERVATION-ID
        R@ _SMW.RECORD SPRH.OBSERVATION-ID RID= 0= IF
        DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    OCK.NATIVE-DIGEST R@ _SMW.RECORD SPRH.NATIVE-DIGEST
        SHA3-256-LEN _SMIG-BYTES= 0= IF
        R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-MIGRATION-S-OK ;

: _SMIG-ATTEMPT-PAIR-VALID?  ( index1 index2 work -- flag )
    >R
    OVER R@ _SMW.CHECKPOINT OCHK-SOURCE-NTH
    SWAP R@ _SMW.CHECKPOINT OCHK-SOURCE-NTH
    ROT DROP
    >R
    DUP OCS.SOURCE-ID R@ OCS.SOURCE-ID RID= IF
        DROP R> DROP R> DROP 0 EXIT
    THEN
    DUP OCS.ATTEMPT-ID R@ OCS.ATTEMPT-ID RID= IF
        DROP R> DROP R> DROP 0 EXIT
    THEN
    OCS.ATTEMPT-SEQUENCE @ R> OCS.ATTEMPT-SEQUENCE @ <>
    R> DROP ;

: _SMIG-OBSERVATION-PAIR-VALID?  ( index1 index2 work -- flag )
    >R
    OVER R@ _SMW.CHECKPOINT OCHK-OBSERVATION-NTH
    SWAP R@ _SMW.CHECKPOINT OCHK-OBSERVATION-NTH
    ROT DROP
    >R
    DUP OCO.ID R@ OCO.ID RID= IF
        DUP OCO.REVISION @ R@ OCO.REVISION @ = IF
            DROP R> DROP R> DROP 0 EXIT
        THEN
    THEN
    DROP R> DROP R> DROP -1 ;

: _SMIG-KEY-PAIR-VALID?  ( index1 index2 work -- flag )
    >R
    OVER R@ _SMW.CHECKPOINT OCHK-KEY-NTH
    SWAP R@ _SMW.CHECKPOINT OCHK-KEY-NTH
    ROT DROP
    OVER OCK.OBSERVATION-ID OVER OCK.OBSERVATION-ID RID= IF
        2DROP R> DROP 0 EXIT
    THEN
    R@ _SMIG-NATIVE-EXACT-KEYS? 0=
    R> DROP ;

: _SMIG-OBSERVATION-KEY-AGREES?  ( observation key -- flag )
    >R
    DUP OCO.SOURCE-ID R@ OCK.SOURCE-ID RID= 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP OCO.NAMESPACE R@ OCK.NAMESPACE SHA3-256-LEN
        _SMIG-BYTES= 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP OCO.ID R@ OCK.OBSERVATION-ID RID= 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP OCO.FORMAT @ R@ OCK.FORMAT @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    OCO.REVISION @ R> OCK.LATEST-REVISION @ <= ;

: _SMIG-LATEST-OBSERVATION-AGREES?
  ( key-index key observation -- flag )
    >R
    R@ OCO.KEY-INDEX @ 2 PICK <> IF
        2DROP R> DROP 0 EXIT
    THEN
    R@ OVER _SMIG-OBSERVATION-KEY-AGREES? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    R@ OCO.REVISION @ OVER OCK.LATEST-REVISION @ <> IF
        2DROP R> DROP 0 EXIT
    THEN
    R@ OCO.SEQUENCE @ OVER OCK.LAST-SEEN-SEQUENCE @ <=
    NIP NIP R> DROP ;

\ Legacy stores only one current attempt head per source.  When an older
\ observation's original successful attempt is still that head, require exact
\ lineage agreement.  When a later head replaced it, admit the missing attempt
\ without inventing request evidence; sealed migration provenance records that
\ incompleteness for compaction.
: _SMIG-OBSERVATION-ATTEMPT-IF-PRESENT?  ( observation work -- flag )
    DUP _SMW.CHECKPOINT OCHK.SOURCE-COUNT @ 0 ?DO
        I OVER _SMW.CHECKPOINT OCHK-SOURCE-NTH
        2 PICK OCO.ATTEMPT-ID OVER OCS.ATTEMPT-ID RID= IF
            DUP OCS.STATE @ OCHK-ATTEMPT-SUCCEEDED <> IF
                DROP 2DROP 0 UNLOOP EXIT
            THEN
            DUP OCS.SOURCE-ID 3 PICK OCO.SOURCE-ID RID= 0= IF
                DROP 2DROP 0 UNLOOP EXIT
            THEN
            DUP OCS.NAMESPACE 3 PICK OCO.NAMESPACE SHA3-256-LEN
                _SMIG-BYTES= 0= IF
                DROP 2DROP 0 UNLOOP EXIT
            THEN
            OCS.ATTEMPT-SEQUENCE @
                2 PICK OCO.SEQUENCE @ <> IF
                2DROP 0 UNLOOP EXIT
            THEN
        ELSE
            DROP
        THEN
    LOOP
    2DROP -1 ;

\ Count every retained immutable observation version belonging to one current
\ legacy source.  The checkpoint is already fully checked and the scan is
\ bounded by the legacy maximum of forty-eight observations.  Missing
\ observation evidence means an exact current count of zero with separately
\ recorded UNKNOWN_LEGACY_ABSENT completeness; it never authorizes inventing
\ observation rows.
: _SMIG-SOURCE-OBSERVATION-COUNT
  ( source work -- count status )
    DUP _SMW.OBSERVATION-PRESENT @ 0= IF
        2DROP 0 STREAMS-MIGRATION-S-OK EXIT
    THEN
    0 SWAP
    DUP _SMW.CHECKPOINT OCHK.OBSERVATION-COUNT @
    DUP 0< OVER OCHK-OBSERVATION-MAX > OR IF
        2DROP 2DROP
        0 STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    0 ?DO
        I OVER _SMW.CHECKPOINT OCHK-OBSERVATION-NTH
        DUP 0= IF
            DROP _SMIG-DROP3
            0 STREAMS-MIGRATION-S-CORRUPT UNLOOP EXIT
        THEN
        OCO.SOURCE-ID 3 PICK SSOURCE.ID RID= IF
            SWAP 1+ SWAP
        THEN
    LOOP
    DROP NIP STREAMS-MIGRATION-S-OK ;

: _SMIG-VALIDATE-SOURCE-ONE  ( index work -- status )
    >R
    DUP 1+ DUP 0> 0= IF
        2DROP R> DROP STREAMS-MIGRATION-S-CAPACITY EXIT
    THEN
    SWAP R@ _SMW-REGISTRY STREAMS-SOURCE-NTH
    DUP R@ _SMIG-SOURCE-OBSERVATION-COUNT
    DUP IF
        >R DROP 2DROP R> R> DROP EXIT
    THEN DROP
    R@ _SMW.TEMP !
    SWAP R@ _SMW.RECORD SPREC-SOURCE-CONSTRUCT
        _SMIG-SPREC>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SMW.TEMP @ R@ _SMW.RECORD SPRS.OBSERVATION-COUNT !
    R@ _SMW.RECORD SPREC-SOURCE-SEAL!
        _SMIG-SPREC>STATUS
    R> DROP ;

: _SMIG-VALIDATE-ATTEMPT-ONE  ( attempt work -- status )
    >R
    DUP OCS.ATTEMPT-SEQUENCE @
        R@ _SMW.CHECKPOINT OCHK.SEQUENCE @ > IF
        DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    DUP OCS.STATE @ OCHK-ATTEMPT-ACCEPTED = IF
        DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    R@ _SMW.RECORD SPREC-ATTEMPT-CONSTRUCT
        _SMIG-SPREC>STATUS
    R> DROP ;

: _SMIG-VALIDATE-KEY-ONE  ( key-index work -- status )
    >R
    DUP R@ _SMW.EXPECTED-U !
    DUP R@ _SMW.CHECKPOINT OCHK-KEY-NTH
    DUP 0= IF
        2DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    DUP OCK.LAST-SEEN-SEQUENCE @
        R@ _SMW.CHECKPOINT OCHK.SEQUENCE @ > IF
        2DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    DUP OCK.LATEST-OBSERVATION @
        R@ _SMW.CHECKPOINT OCHK-OBSERVATION-NTH
    DUP 0= IF
        _SMIG-DROP3 R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    _SMIG-LATEST-OBSERVATION-AGREES? 0= IF
        R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    R@ _SMW.EXPECTED-U @ R@ _SMIG-CONSTRUCT-NATIVE
    R> DROP ;

: _SMIG-VALIDATE-OBSERVATION-ONE  ( observation work -- status )
    >R
    DUP OCO.SEQUENCE @ R@ _SMW.CHECKPOINT OCHK.SEQUENCE @ > IF
        DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    DUP OCO.REVISION @ OVER OCO.SEQUENCE @ > IF
        DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    DUP OCO.KEY-INDEX @ R@ _SMW.CHECKPOINT OCHK-KEY-NTH
    DUP 0= IF
        2DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    2DUP _SMIG-OBSERVATION-KEY-AGREES? 0= IF
        2DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    DROP
    DUP R@ _SMIG-OBSERVATION-ATTEMPT-IF-PRESENT? 0= IF
        DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    DUP R@ _SMIG-CANDIDATE-FROM-OBSERVATION
    DUP IF NIP R> DROP EXIT THEN DROP
    R@ _SMW.CANDIDATE R@ _SMW.TEMP-DIGEST
        SPREC-CANDIDATE-SEMANTIC-DIGEST! _SMIG-SPREC>STATUS
    DUP IF NIP R> DROP EXIT THEN DROP
    DUP OCO.SEMANTIC-DIGEST R@ _SMW.TEMP-DIGEST SHA3-256-LEN
        _SMIG-BYTES= 0= IF
        DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    DUP OCO.KEY-INDEX @ R@ _SMIG-CONSTRUCT-NATIVE
    DUP IF NIP R> DROP EXIT THEN DROP
    OCO.ID R@ _SMW.RECORD SPRH.OBSERVATION-ID RID= 0= IF
        R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-MIGRATION-S-OK ;

: _SMIG-VALIDATE-SOURCES  ( work -- status )
    DUP _SMW.SOURCE-COUNT @ 0 ?DO
        I OVER _SMIG-VALIDATE-SOURCE-ONE
        DUP IF NIP UNLOOP EXIT THEN DROP
    LOOP
    DROP STREAMS-MIGRATION-S-OK ;

: _SMIG-VALIDATE-ATTEMPTS  ( work -- status )
    DUP _SMW.ATTEMPT-COUNT @ 0 ?DO
        I OVER _SMW.CHECKPOINT OCHK-SOURCE-NTH
        OVER _SMIG-VALIDATE-ATTEMPT-ONE
        DUP IF NIP UNLOOP EXIT THEN DROP
    LOOP
    DUP _SMW.ATTEMPT-COUNT @ 0 ?DO
        I 0 ?DO
            J I 2 PICK _SMIG-ATTEMPT-PAIR-VALID? 0= IF
                DROP STREAMS-MIGRATION-S-CORRUPT
                UNLOOP UNLOOP EXIT
            THEN
        LOOP
    LOOP
    DUP _SMW.ATTEMPT-COUNT @
        OVER _SMW.OBSERVATION-PRESENT @ IF
            OVER _SMW.CHECKPOINT OCHK.SEQUENCE @
        ELSE
            0
        THEN
        > IF
        DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    DROP STREAMS-MIGRATION-S-OK ;

: _SMIG-VALIDATE-KEYS  ( work -- status )
    DUP _SMW.NATIVE-COUNT @ 0 ?DO
        I OVER _SMIG-VALIDATE-KEY-ONE
        DUP IF NIP UNLOOP EXIT THEN DROP
    LOOP
    DUP _SMW.NATIVE-COUNT @ 0 ?DO
        I 0 ?DO
            J I 2 PICK _SMIG-KEY-PAIR-VALID? 0= IF
                DROP STREAMS-MIGRATION-S-CORRUPT
                UNLOOP UNLOOP EXIT
            THEN
        LOOP
    LOOP
    DUP _SMW.NATIVE-COUNT @ OVER _SMW.OBSERVATION-COUNT @ > IF
        DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    DROP STREAMS-MIGRATION-S-OK ;

: _SMIG-VALIDATE-OBSERVATIONS  ( work -- status )
    DUP _SMW.OBSERVATION-COUNT @ 0 ?DO
        I OVER _SMW.CHECKPOINT OCHK-OBSERVATION-NTH
        OVER _SMIG-VALIDATE-OBSERVATION-ONE
        DUP IF NIP UNLOOP EXIT THEN DROP
    LOOP
    DUP _SMW.OBSERVATION-COUNT @ 0 ?DO
        I 0 ?DO
            J I 2 PICK _SMIG-OBSERVATION-PAIR-VALID? 0= IF
                DROP STREAMS-MIGRATION-S-CORRUPT
                UNLOOP UNLOOP EXIT
            THEN
        LOOP
    LOOP
    DROP STREAMS-MIGRATION-S-OK ;

: _SMIG-VALIDATE-LEGACY-GRAPH  ( work -- status )
    DUP _SMIG-VALIDATE-SOURCES
    DUP IF NIP EXIT THEN DROP
    DUP _SMIG-VALIDATE-ATTEMPTS
    DUP IF NIP EXIT THEN DROP
    DUP _SMIG-VALIDATE-KEYS
    DUP IF NIP EXIT THEN DROP
    _SMIG-VALIDATE-OBSERVATIONS ;

: _SMIG-PREPARE-LEGACY  ( work -- status )
    DUP _SMIG-RECOVER-CALLER-CHECKPOINT
    DUP IF NIP EXIT THEN DROP
    DUP _SMIG-SET-MATRIX
    _SMIG-VALIDATE-LEGACY-GRAPH ;

