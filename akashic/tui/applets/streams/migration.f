: STREAMS-MIGRATION-WORK-VALID?  ( work -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-MIGRATION-WORK-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SMW.MAGIC @ _SMIG-WORK-MAGIC <> IF DROP 0 EXIT THEN
    DUP _SMW.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _SMW.BUSY @ _SMIG-BOOL? 0= IF DROP 0 EXIT THEN
    _SMW.STATUS @ _SMIG-STATUS? ;

: STREAMS-MIGRATION-WORK-INIT  ( work -- status )
    DUP 0= IF DROP STREAMS-MIGRATION-S-INVALID EXIT THEN
    DUP STREAMS-MIGRATION-WORK-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP STREAMS-MIGRATION-S-INVALID EXIT THEN
    DUP STREAMS-MIGRATION-WORK-SIZE 0 FILL
    _SMIG-WORK-MAGIC OVER _SMW.MAGIC !
    DUP OVER _SMW.SELF !
    STREAMS-MIGRATION-S-OK OVER _SMW.STATUS !
    DUP STREAMS-MIGRATION-WORK-VALID? 0= IF
        STREAMS-MIGRATION-WORK-SIZE 0 FILL
        STREAMS-MIGRATION-S-CORRUPT
    ELSE
        DROP STREAMS-MIGRATION-S-OK
    THEN ;

