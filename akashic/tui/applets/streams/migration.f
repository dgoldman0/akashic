: _SMIG-BLOB-SOURCE
  ( logical-offset destination-a requested-u work -- actual-u status )
    >R
    2 PICK 0< OVER 0< OR IF
        _SMIG-DROP3 R> DROP 0 PERSIST-S-INVALID EXIT
    THEN
    2 PICK R@ _SMW.CALLBACK-U @ > IF
        _SMIG-DROP3 R> DROP 0 PERSIST-S-INVALID EXIT
    THEN
    R@ _SMW.CALLBACK-U @ 3 PICK - OVER < IF
        _SMIG-DROP3 R> DROP 0 PERSIST-S-INVALID EXIT
    THEN
    DUP IF
        OVER 0= IF
            _SMIG-DROP3 R> DROP 0 PERSIST-S-INVALID EXIT
        THEN
        OVER OVER MSPAN-NONWRAPPING? 0= IF
            _SMIG-DROP3 R> DROP 0 PERSIST-S-INVALID EXIT
        THEN
    THEN
    2 PICK R@ _SMW.CALLBACK-A @ +
    2 PICK 2 PICK MOVE
    NIP NIP PERSIST-S-OK
    R> DROP ;

: _SMIG-BLOB-SINK
  ( logical-offset source-a offered-u work -- status )
    >R
    2 PICK 0< OVER 0< OR IF
        _SMIG-DROP3 R> DROP PERSIST-S-INVALID EXIT
    THEN
    2 PICK R@ _SMW.CALLBACK-OFFSET @ <> IF
        _SMIG-DROP3 R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    2 PICK R@ _SMW.CALLBACK-U @ > IF
        _SMIG-DROP3 R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    R@ _SMW.CALLBACK-U @ 3 PICK - OVER < IF
        _SMIG-DROP3 R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    DUP IF
        OVER 0= IF
            _SMIG-DROP3 R> DROP PERSIST-S-INVALID EXIT
        THEN
        OVER OVER MSPAN-NONWRAPPING? 0= IF
            _SMIG-DROP3 R> DROP PERSIST-S-INVALID EXIT
        THEN
    THEN
    2 PICK R@ _SMW.CALLBACK-A @ +
    2 PICK 2 PICK _SMIG-BYTES= 0= IF
        _SMIG-DROP3 R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    DUP R@ _SMW.CALLBACK-OFFSET +!
    _SMIG-DROP3 R> DROP PERSIST-S-OK ;

: _SMIG-APPEND-CURRENT  ( record-u work -- status )
    >R
    R@ _SMW.RECORD SWAP R@ _SMW.REF
    R@ _SMW.ADAPTER @ R@ _SMW.ADAPTER-WORK @
        STREAMS-PA-APPEND-RECORD
    R> DROP ;

: _SMIG-PUT-CURRENT  ( key-u work -- status )
    >R
    R@ _SMW.KEY SWAP R@ _SMW.REF
    R@ _SMW.ADAPTER @ R@ _SMW.ADAPTER-WORK @
