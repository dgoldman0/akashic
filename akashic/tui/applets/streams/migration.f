    DUP OCHK-S-OK <> IF
        2DROP R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    DROP
    DUP R@ _SMW.RECOVERED-COUNT !
    DROP
    R@ _SMW.CHECKPOINT OCHK-VALID? 0= IF
        R> DROP STREAMS-MIGRATION-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-MIGRATION-S-OK ;

: _SMIG-SET-MATRIX  ( work -- )
    >R
    R@ _SMW.SOURCE-PRESENT @ IF
        R@ _SMW-REGISTRY STREAMS-SOURCE-COUNT
    ELSE
        0
    THEN
    DUP R@ _SMW.SOURCE-COUNT !
    DROP
    R@ _SMW.OBSERVATION-PRESENT @ IF
        R@ _SMW.CHECKPOINT OCHK.SOURCE-COUNT @
        R@ _SMW.CHECKPOINT OCHK.OBSERVATION-COUNT @
        R@ _SMW.CHECKPOINT OCHK.KEY-COUNT @
    ELSE
        0 0 0
    THEN
    R@ _SMW.NATIVE-COUNT !
    R@ _SMW.OBSERVATION-COUNT !
    R@ _SMW.ATTEMPT-COUNT !

    R@ _SMW.SOURCE-PRESENT @ IF
        STREAMS-AUTHORITY-COMPLETE
            R@ _SMW.SOURCE-COMPLETENESS !
    ELSE
        R@ _SMW.OBSERVATION-PRESENT @ IF
            STREAMS-AUTHORITY-UNKNOWN-LEGACY-ABSENT
                R@ _SMW.SOURCE-COMPLETENESS !
        ELSE
            STREAMS-AUTHORITY-COMPLETE
                R@ _SMW.SOURCE-COMPLETENESS !
        THEN
    THEN
    R@ _SMW.OBSERVATION-PRESENT @ IF
        STREAMS-AUTHORITY-COMPLETE
            R@ _SMW.OBSERVATION-COMPLETENESS !
    ELSE
        R@ _SMW.SOURCE-PRESENT @ IF
            STREAMS-AUTHORITY-UNKNOWN-LEGACY-ABSENT
                R@ _SMW.OBSERVATION-COMPLETENESS !
        ELSE
            STREAMS-AUTHORITY-COMPLETE
                R@ _SMW.OBSERVATION-COMPLETENESS !
        THEN
    THEN

    R@ _SMW.SOURCE-PRESENT @ IF
        R@ _SMW.OBSERVATION-PRESENT @ IF
            R@ _SMW.SOURCE-COUNT @ 0= IF
                STREAMS-AUTHORITY-PROVENANCE-LEGACY-EMPTY-SOURCES
            ELSE
                STREAMS-AUTHORITY-PROVENANCE-LEGACY-BOTH
            THEN
        ELSE
            STREAMS-AUTHORITY-PROVENANCE-LEGACY-SOURCES
        THEN
    ELSE
        R@ _SMW.OBSERVATION-PRESENT @ IF
            STREAMS-AUTHORITY-PROVENANCE-LEGACY-OBSERVATIONS
        ELSE
            STREAMS-AUTHORITY-PROVENANCE-COMPLETE-EMPTY
        THEN
    THEN
    R@ _SMW.PROVENANCE !
    R> DROP ;

