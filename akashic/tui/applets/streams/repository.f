: STREAMS-REPOSITORY-FINI  ( repository work -- status )
    2DUP _SREPO-PAIR? 0= IF
        2DROP STREAMS-REPOSITORY-S-INVALID EXIT
    THEN
    DUP _SRW.BUSY @ IF
        2DROP STREAMS-REPOSITORY-S-BUSY EXIT
    THEN
    OVER _SR.FLAGS @ _SR-F-COMPACTION-BOUND AND IF
        DUP _SRW.COMPACT PCOMPACT-STATE@ DUP
        PCOMPACT-STATE-IDLE <>
        SWAP PCOMPACT-STATE-CLEANED <> AND IF
            2DROP STREAMS-REPOSITORY-S-BUSY EXIT
        THEN
    THEN
    OVER _SR.GUARD @ GUARD-HELD? IF
        2DROP STREAMS-REPOSITORY-S-BUSY EXIT
    THEN
    OVER _SR.FLAGS @ _SR-F-COMPACTION-CONFIGURED AND IF
        OVER _SR.BUILDER-GUARD @ GUARD-HELD? IF
            2DROP STREAMS-REPOSITORY-S-BUSY EXIT
        THEN
    THEN
    OVER _SR.GUARD @ GUARD-TRY-ACQUIRE 0= IF
        2DROP STREAMS-REPOSITORY-S-BUSY EXIT
    THEN
    OVER _SR.GUARD @ >R
    OVER _SR.FLAGS @ _SR-F-COMPACTION-CONFIGURED AND IF
        OVER _SR.BUILDER-GUARD @ GUARD-TRY-ACQUIRE 0= IF
            R> GUARD-RELEASE
            2DROP STREAMS-REPOSITORY-S-BUSY EXIT
        THEN
        OVER _SR.BUILDER-GUARD @ >R
    ELSE
        0 >R
    THEN
    OVER _SREPO-RELEASE-CACHES
    DUP STREAMS-REPOSITORY-WORK-SIZE 0 FILL
    DROP
    STREAMS-REPOSITORY-SIZE 0 FILL
    R> ?DUP IF GUARD-RELEASE THEN
    R> GUARD-RELEASE
    STREAMS-REPOSITORY-S-OK ;
