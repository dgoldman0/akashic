    OVER _SR.GUARD @ GUARD-TRY-ACQUIRE 0= IF
        2DROP STREAMS-REPOSITORY-S-BUSY EXIT
    THEN
    -1 SWAP _SRW.BUSY !
    DROP STREAMS-REPOSITORY-S-OK ;

