    DUP _SRW.REPOSITORY @ _SR.FLAGS @
        _SR-F-COMPACTION-CONFIGURED AND
    IF _SRW.COMPACT PCOMPACT-BYTES-USED@ ELSE DROP -1 THEN ;

: STREAMS-REPOSITORY-COMPACTION-WORK@  ( work -- count|-1 )
    DUP STREAMS-REPOSITORY-WORK-VALID? 0= IF DROP -1 EXIT THEN
    DUP _SRW.REPOSITORY @ _SR.FLAGS @
        _SR-F-COMPACTION-CONFIGURED AND
    IF _SRW.COMPACT PCOMPACT-WORK-USED@ ELSE DROP -1 THEN ;

: _SREPO-COMPACTION-READY?  ( work -- flag )
    _SRW.REPOSITORY @ _SR.FLAGS @
        _SR-F-COMPACTION-CONFIGURED
        _SR-F-COMPACTION-BOUND OR AND
        _SR-F-COMPACTION-CONFIGURED
        _SR-F-COMPACTION-BOUND OR = ;

: _SREPO-COMPACTION-BLOCK?  ( repository-status work -- flag )
    OVER STREAMS-REPOSITORY-S-OK <> IF 2DROP -1 EXIT THEN
    _SRW.COMPACT PCOMPACT-STATE@ DUP PCOMPACT-STATE-IDLE =
    SWAP PCOMPACT-STATE-CLEANED = OR 0=
    NIP ;

: _SREPO-SET-COMPACTION-FENCE  ( flag repository -- )
    _SR.FLAGS
    SWAP IF
        DUP @ _SR-F-COMPACTION-FENCE OR SWAP !
    ELSE
        DUP @ _SR-F-COMPACTION-FENCE INVERT AND SWAP !
    THEN ;

: _SREPO-COMPACTION-BLOCK-UPDATE  ( repository-status work -- )
    2DUP _SREPO-COMPACTION-BLOCK?
    1 PICK _SRW.REPOSITORY @ _SREPO-SET-COMPACTION-FENCE
    2DROP ;

\ Neutral PCOMPACT has no UNSUPPORTED spelling.  The semantic context retains
\ that exact Streams result before PCOMPACT defensively reports FAULT.
: _SREPO-COMPACTION-PERSIST>STATUS  ( persist-status work -- status )
    >R
    DUP PERSIST-S-FAULT = IF
        R@ _SRW.COMPACTION-CONTEXT
            STREAMS-PA-COMPACTION-STATUS@
            STREAMS-PA-S-UNSUPPORTED = IF
            DROP STREAMS-REPOSITORY-S-UNSUPPORTED
            R> DROP EXIT
        THEN
    THEN
    _SREPO-PERSIST>STATUS
    R> DROP ;

: _SREPO-COMPACT-BEGIN-RUN  ( work -- status )
    >R
    R@ _SRW.REPOSITORY @ _SR.FLAGS @ DUP
        _SR-F-BLOCKED AND IF
        DROP R> DROP STREAMS-REPOSITORY-S-CONFLICT EXIT
    THEN
    DUP _SR-F-STAGING-PREPARED AND IF
        DROP R> DROP STREAMS-REPOSITORY-S-CONFLICT EXIT
    THEN
    _SR-F-LOADED _SR-F-PROVISIONED OR AND
        _SR-F-LOADED _SR-F-PROVISIONED OR <> IF
        R> DROP STREAMS-REPOSITORY-S-CONFLICT EXIT
    THEN
    R@ _SRW.REPOSITORY @ _SR.COMPACT
    R> _SRW.COMPACT PCOMPACT-BEGIN
    _SREPO-PERSIST>STATUS ;

