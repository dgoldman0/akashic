\ Resolve each reserved terminal without following its final component.
\ Absent active/inactive roles are interpreted later by the atomic-root
\ authority; every present reserved role must be a regular file.
: _SREPO-NOFOLLOW-TYPE
  ( path-a path-u expected-type repository -- status )
    SWAP >R >R
    VFS-RP-NOFOLLOW-FINAL R@ _SR.VFS @ VFS-RESOLVE-POLICY?
    DUP IF
        NIP _SREPO-IOR>STATUS
        R> DROP R> DROP EXIT
    THEN
    DROP
    DUP 0= IF
        DROP R> DROP R> DROP STREAMS-REPOSITORY-S-CORRUPT EXIT
    THEN
    IN.TYPE @
    R> DROP R> =
    IF STREAMS-REPOSITORY-S-OK
    ELSE STREAMS-REPOSITORY-S-CORRUPT THEN ;

: _SREPO-DIRECTORY-TYPE  ( repository -- status )
    >R
    _SREPO-DIRECTORY$ VFS-T-DIR R>
    _SREPO-NOFOLLOW-TYPE ;

