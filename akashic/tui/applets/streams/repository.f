: _SREPO-BASE-VALID?  ( repository -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-REPOSITORY-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SR.MAGIC @ _SREPO-MAGIC <> IF DROP 0 EXIT THEN
    DUP _SR.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _SR.VFS @ DUP 0= IF 2DROP 0 EXIT THEN
    VFS-DESC-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SR.FLAGS @ _SR-F-KNOWN INVERT AND IF DROP 0 EXIT THEN
    DUP _SR.FLAGS @ _SR-F-INITIALIZED AND 0= IF DROP 0 EXIT THEN
    DUP _SR.FLAGS @ _SR-F-COMPACTION-BOUND AND
    OVER _SR.FLAGS @ _SR-F-COMPACTION-CONFIGURED AND 0= AND IF
        DROP 0 EXIT
    THEN
    DUP _SR.STATUS @ _SREPO-STATUS? 0= IF DROP 0 EXIT THEN
    DUP _SR.GUARD @ DUP GUARD-SPIN? 0= IF 2DROP 0 EXIT THEN DROP
    DUP _SR.CACHE-0 @ PPAGE-CACHE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SR.CACHE-1 @ PPAGE-CACHE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SR.CACHE-0 @ OVER _SR.CACHE-1 @ = IF DROP 0 EXIT THEN
    DUP _SR.FAULT-XT @ 0= IF
        DUP _SR.FAULT-CONTEXT @ IF DROP 0 EXIT THEN
    THEN
    DUP _SR.STORE PSTORE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SR.BANK1-PAGE PPAGE-FILE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SR.BANK1-SEGMENT PSEG-FILE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SR.ADAPTER STREAMS-PA-VALID? 0= IF DROP 0 EXIT THEN
    >R
    PERSIST-DATA-BANK-1 R@ _SR.STORE
        PSTORE-PAGE-FILE-FOR-BANK@ R@ _SR.BANK1-PAGE <> IF
        R> DROP 0 EXIT
