: _SREPO-COMPACTION-BUDGETS?
  ( byte-budget work-budget step-byte-budget -- flag )
    >R
    OVER 0> OVER 0> AND R@ 0> AND
    R> 3 PICK <= AND
    NIP NIP ;

: _SREPO-COMPACTION-REBINDABLE?  ( work -- flag )
    DUP _SRW.REPOSITORY @ _SR.FLAGS @
        _SR-F-COMPACTION-BOUND AND 0= IF DROP -1 EXIT THEN
    _SRW.COMPACT PCOMPACT-STATE@ DUP PCOMPACT-STATE-IDLE =
    SWAP PCOMPACT-STATE-CLEANED = OR ;

: STREAMS-REPOSITORY-COMPACTION-BIND
  ( byte-budget work-budget step-byte-budget repository work -- status )
    2DUP _SREPO-ENTER-MAINTENANCE DUP IF
        >R _SREPO-DROP5 R> EXIT
    THEN DROP
    >R
    DUP _SR.FLAGS @ _SR-F-COMPACTION-CONFIGURED AND 0= IF
        _SREPO-DROP4
        STREAMS-REPOSITORY-S-CONFLICT
        R@ _SRW.REPOSITORY @ R> _SREPO-LEAVE EXIT
    THEN
    3 PICK 3 PICK 3 PICK _SREPO-COMPACTION-BUDGETS? 0= IF
        _SREPO-DROP4
        STREAMS-REPOSITORY-S-INVALID
        R@ _SRW.REPOSITORY @ R> _SREPO-LEAVE EXIT
    THEN
    R@ _SREPO-COMPACTION-REBINDABLE? 0= IF
        _SREPO-DROP4
        STREAMS-REPOSITORY-S-BUSY
        R@ _SRW.REPOSITORY @ R> _SREPO-LEAVE EXIT
    THEN
    R@ _SRW.REPOSITORY @ _SR.FLAGS DUP @
        _SR-F-COMPACTION-BOUND INVERT AND SWAP !
    R@ _SRW.COMPACT-BUFFER-A @ R@ _SRW.COMPACT-BUFFER-U @
        R@ _SRW.COMPACT PCOMPACT-WORK-INIT
    _SREPO-PERSIST>STATUS
    DUP IF
        >R _SREPO-DROP4 R>
        R@ _SRW.REPOSITORY @ R> _SREPO-LEAVE EXIT
    THEN DROP
    R@ _SRW.REPOSITORY @ _SR.ADAPTER
    R@ _SRW.ADAPTER
    R@ _SRW.REPOSITORY @ _SR.BUILDER-ADAPTER
    R@ _SRW.BUILDER-ADAPTER
    R@ _SRW.COMPACTION-CONTEXT
        STREAMS-PA-COMPACTION-CONTEXT-INIT
    _SREPO-ADAPTER>STATUS
    DUP IF
        >R _SREPO-DROP4 R>
        R@ _SRW.REPOSITORY @ R> _SREPO-LEAVE EXIT
    THEN DROP
    R@ _SRW.REPOSITORY @ _SR.STORE PSTORE-ROOT-FILE@
    R@ _SRW.REPOSITORY @ _SR.BUILDER-STORE
    R@ _SRW.BUILDER-PSTORE
    STREAMS-PA-COMPACTION-STEP-XT
    STREAMS-PA-COMPACTION-FINALIZE-XT
    R@ _SRW.COMPACTION-CONTEXT
    9 PICK 9 PICK 9 PICK
    R@ _SRW.REPOSITORY @ _SR.COMPACT PCOMPACT-INIT
    _SREPO-PERSIST>STATUS
    >R _SREPO-DROP4 R>
    DUP 0= IF
        R@ _SRW.REPOSITORY @ _SR.FLAGS DUP @
            _SR-F-COMPACTION-BOUND OR SWAP !
    THEN
    R@ _SRW.REPOSITORY @ R> _SREPO-LEAVE ;

: STREAMS-REPOSITORY-COMPACTION-STATE@  ( work -- state|-1 )
    DUP STREAMS-REPOSITORY-WORK-VALID? 0= IF DROP -1 EXIT THEN
    DUP _SRW.REPOSITORY @ _SR.FLAGS @
        _SR-F-COMPACTION-CONFIGURED AND
    IF _SRW.COMPACT PCOMPACT-STATE@ ELSE DROP -1 THEN ;

: STREAMS-REPOSITORY-COMPACTION-BYTES@  ( work -- bytes|-1 )
