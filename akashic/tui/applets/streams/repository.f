        2DROP STREAMS-REPOSITORY-S-FAULT
    ELSE
        DROP
        DUP _SREPO-STATUS? 0= IF
            DROP STREAMS-REPOSITORY-S-FAULT
        THEN
    THEN
    ['] _SREPO-VFS-RESTORE _SREPO-VFS-CLEANUP-CALL
