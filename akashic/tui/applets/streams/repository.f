        2DROP STREAMS-REPOSITORY-S-INVALID EXIT
    THEN
    OVER _SR.FLAGS @ _SR-F-COMPACTION-FENCE AND IF
        2DROP STREAMS-REPOSITORY-S-CONFLICT EXIT
    THEN
    _SREPO-ENTER-MAINTENANCE ;

