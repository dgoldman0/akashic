    THEN DROP
    R@ _SRW.REPOSITORY @ _SR.FLAGS DUP @
        _SR-F-STAGING-PREPARED _SR-F-LOADED OR OR
        _SR-F-PROVISIONED INVERT AND SWAP !
    0 R@ _SRW.REPOSITORY @ _SREPO-SET-BLOCKED
    R@ _SRW.REPOSITORY @ _SR.VFS @ VFS-SYNC
        _SREPO-IOR>STATUS
    R> DROP ;

: STREAMS-REPOSITORY-STAGING-PREPARE  ( repository work -- status )
    2DUP _SREPO-ENTER DUP IF >R 2DROP R> EXIT THEN DROP
    DUP ['] _SREPO-STAGING-PREPARE-RUN _SREPO-VFS-OP-CALL
    ROT ROT _SREPO-LEAVE ;

\ Provision creates the physical two-bank roles, opens the empty/current
\ store, and idempotently publishes the adapter's checked empty authority
\ for the caller-supplied nonzero authority RID.
: _SREPO-PROVISION-RUN  ( work -- status )
    >R
    R@ _SRW.OP-ARG0 @ RID-SIZE
    R@ _SRW.REPOSITORY @ R@
        STREAMS-REPOSITORY-SPAN-DISJOINT? 0= IF
        R> DROP STREAMS-REPOSITORY-S-INVALID EXIT
    THEN
    R@ _SRW.OP-ARG0 @ RID-PRESENT? 0= IF
        R> DROP STREAMS-REPOSITORY-S-INVALID EXIT
    THEN
    R@ _SRW.REPOSITORY @ _SREPO-ENSURE-DIRECTORY
    DUP IF
        R@ _SRW.REPOSITORY @ _SREPO-MARK-BLOCKING
        R> DROP EXIT
    THEN DROP
    R@ _SRW.REPOSITORY @ _SREPO-TOPOLOGY-ALLOW-ABSENT
    DUP IF
        R@ _SRW.REPOSITORY @ _SREPO-MARK-BLOCKING
        R> DROP EXIT
    THEN DROP
    R@ _SRW.REPOSITORY @ _SR.STORE
    R@ _SRW.PSTORE PSTORE-PROVISION
    _SREPO-PERSIST>STATUS
    DUP IF
        R@ _SRW.REPOSITORY @ _SREPO-MARK-BLOCKING
        R> DROP EXIT
    THEN DROP
    _SREPO-PAGES-1$
    R@ _SRW.REPOSITORY @ _SREPO-ENSURE-FILE
    DUP IF
        R@ _SRW.REPOSITORY @ _SREPO-MARK-BLOCKING
        R> DROP EXIT
    THEN DROP
    _SREPO-SEGMENTS-1$
    R@ _SRW.REPOSITORY @ _SREPO-ENSURE-FILE
    DUP IF
        R@ _SRW.REPOSITORY @ _SREPO-MARK-BLOCKING
        R> DROP EXIT
    THEN DROP
    R@ _SREPO-LOAD-RUN
    DUP STREAMS-REPOSITORY-S-ABSENT = IF
        DROP
    ELSE
        DUP IF R> DROP EXIT THEN DROP
    THEN
    R@ _SRW.OP-ARG0 @
    R@ _SRW.REPOSITORY @ _SR.ADAPTER
    R@ _SRW.ADAPTER STREAMS-PA-PROVISION
    _SREPO-ADAPTER>STATUS
    DUP IF
        R@ _SRW.REPOSITORY @ _SREPO-MARK-BLOCKING
        R> DROP EXIT
    THEN DROP
    R@ _SRW.REPOSITORY @ _SR.FLAGS DUP @
        _SR-F-PROVISIONED _SR-F-LOADED OR OR SWAP !
    0 R@ _SRW.REPOSITORY @ _SREPO-SET-BLOCKED
    R@ _SRW.REPOSITORY @ _SR.VFS @ VFS-SYNC
        _SREPO-IOR>STATUS
    R> DROP ;

: STREAMS-REPOSITORY-PROVISION
  ( authority-id repository work -- status )
    2DUP _SREPO-ENTER DUP IF
        >R _SREPO-DROP3 R> EXIT
    THEN DROP
    >R
    OVER R@ _SRW.OP-ARG0 !
    R@ ['] _SREPO-PROVISION-RUN _SREPO-VFS-OP-CALL
    SWAP R> _SREPO-LEAVE
    NIP ;

