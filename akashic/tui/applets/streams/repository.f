: _SREPO-WORK-SHAPE?  ( work -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-REPOSITORY-WORK-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SRW.MAGIC @ _SREPO-WORK-MAGIC <> IF DROP 0 EXIT THEN
    DUP _SRW.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _SRW.BUSY @ DUP 0= SWAP -1 = OR 0= IF DROP 0 EXIT THEN
    DUP _SRW.STATUS @ _SREPO-STATUS? 0= IF DROP 0 EXIT THEN
    DUP _SRW.PSTORE PSTORE-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SRW.ADAPTER STREAMS-PA-WORK-VALID? 0= IF DROP 0 EXIT THEN
    >R
    R@ _SRW.PSTORE PSTORE-WORK-RECORD-BUFFER$
    R@ _SRW.RECORD-U @ <> IF DROP R> DROP 0 EXIT THEN
    R@ _SRW.RECORD-A @ =
    R> DROP ;

: _SREPO-COMPACTION-WORK-SHAPE?  ( repository work -- flag )
    >R
    DUP _SR.FLAGS @ _SR-F-COMPACTION-CONFIGURED AND 0= IF
        DROP R> DROP -1 EXIT
    THEN
    R@ _SRW.BUILDER-PSTORE PSTORE-WORK-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _SRW.BUILDER-ADAPTER STREAMS-PA-WORK-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _SRW.COMPACTION-CONTEXT
        STREAMS-PA-COMPACTION-CONTEXT-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _SRW.COMPACT PCOMPACT-WORK-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    R@ _SRW.BUILDER-PSTORE PSTORE-WORK-RECORD-BUFFER$
    R@ _SRW.BUILDER-RECORD-U @ <> IF
        DROP DROP R> DROP 0 EXIT
    THEN
    R@ _SRW.BUILDER-RECORD-A @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DROP R> DROP -1 ;

: STREAMS-REPOSITORY-WORK-VALID?  ( work -- flag )
    DUP _SREPO-WORK-SHAPE? 0= IF DROP 0 EXIT THEN
    >R
    R@ _SRW.REPOSITORY @ DUP _SREPO-BASE-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP _SR.WORK @ R@ <> IF DROP R> DROP 0 EXIT THEN
    R@ _SREPO-COMPACTION-WORK-SHAPE?
    R> DROP ;

: STREAMS-REPOSITORY-VALID?  ( repository -- flag )
    DUP _SREPO-BASE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SR.WORK @ ?DUP IF
        DUP _SREPO-WORK-SHAPE? 0= IF 2DROP 0 EXIT THEN
        _SRW.REPOSITORY @ OVER <> IF DROP 0 EXIT THEN
        DUP DUP _SR.WORK @ _SREPO-COMPACTION-WORK-SHAPE? 0= IF
            DROP 0 EXIT
        THEN
    THEN
    DROP -1 ;

