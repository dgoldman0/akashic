    _SREPO-EVIDENCE-PATH$ 0= IF
        2DROP R> DROP STREAMS-REPOSITORY-S-INVALID EXIT
    THEN
    VFS-T-FILE R> _SREPO-NOFOLLOW-TYPE ;

