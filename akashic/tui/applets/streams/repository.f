\ Existing source initialization stays ABI-compatible.  This one-shot
\ extension binds the separate builder descriptors and work graph without
\ creating any compact roots or touching either data bank.
: STREAMS-REPOSITORY-COMPACTION-INIT
  ( bc0 bc1 guard builder-a builder-u compact-a compact-u repo work -- status )
    >R
    DUP STREAMS-REPOSITORY-VALID? 0= IF
        _SREPO-DROP8 R> DROP STREAMS-REPOSITORY-S-INVALID EXIT
