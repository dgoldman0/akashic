: _SREPO-COMPACTION-VFS-RUN  ( work -- status )
    DUP _SRW.REPOSITORY @ _SREPO-TOPOLOGY-ALLOW-ABSENT
    DUP IF NIP EXIT THEN DROP
    DUP _SRW.OP-ARG0 @ EXECUTE ;

: _SREPO-COMPACTION-CALL  ( repository work operation-xt -- status )
    >R
    2DUP _SREPO-ENTER-MAINTENANCE DUP IF
        >R 2DROP R> R> DROP EXIT
    THEN DROP
    DUP _SREPO-COMPACTION-READY? 0= IF
        R> DROP
        STREAMS-REPOSITORY-S-CONFLICT
    ELSE
        R> OVER _SRW.OP-ARG0 !
        DUP ['] _SREPO-COMPACTION-VFS-RUN
            _SREPO-VFS-OP-CALL >R
        R@ OVER _SREPO-COMPACTION-BLOCK-UPDATE
        R>
    THEN
    ROT ROT _SREPO-LEAVE ;

