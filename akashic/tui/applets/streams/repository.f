\ =====================================================================
\  repository.f - Desk/Streams physical persistence owner
\ =====================================================================
\  This file alone chooses the sealed /streams paths and composes the
\  Streams persistence adapter with one shared two-bank PSTORE plus one
\  private builder view used by neutral PCOMPACT.  It owns no provider,
\  refresh, query, projection, controller, Library-document, or
\  public-Bluesky policy.
\
\  All mutable descriptors, workspaces, caches, buffers, and guards are
\  supplied by the caller.  Existing source-side INIT and WORK-INIT call
\  shapes remain valid.  COMPACTION-INIT adds the distinct builder caches,
\  guard, record buffer, and coordinator segment buffer; COMPACTION-BIND
\  then fixes bounded maintenance budgets before any lifecycle operation.
\ =====================================================================

PROVIDED akashic-tui-streams-repository

