    THEN
    2 PICK 0= IF
        _SREPO-DROP3 R> DROP STREAMS-REPOSITORY-S-INVALID EXIT
    THEN
    2 PICK 2 PICK MSPAN-NONWRAPPING? 0= IF
        _SREPO-DROP3 R> DROP STREAMS-REPOSITORY-S-INVALID EXIT
    THEN
    2 PICK 2 PICK R@ STREAMS-REPOSITORY-WORK-SIZE
        MSPAN-OVERLAP? IF
        _SREPO-DROP3 R> DROP STREAMS-REPOSITORY-S-INVALID EXIT
    THEN
    R@ STREAMS-REPOSITORY-WORK-SIZE 0 FILL
    _SREPO-WORK-MAGIC R@ _SRW.MAGIC !
    R@ R@ _SRW.SELF !
    DUP R@ _SRW.REPOSITORY !
    STREAMS-REPOSITORY-S-OK R@ _SRW.STATUS !
    2 PICK R@ _SRW.RECORD-A !
    1 PICK R@ _SRW.RECORD-U !
    _SREPO-DROP3
    R@ _SRW.RECORD-A @ R@ _SRW.RECORD-U @
        R@ _SREPO-WORK-BUFFER-SAFE? 0= IF
        STREAMS-REPOSITORY-S-INVALID R> _SREPO-WORK-INIT-FAIL EXIT
    THEN
    R@ _SREPO-WORK-COMPONENTS-INIT DUP IF
        R> _SREPO-WORK-INIT-FAIL EXIT
    THEN DROP
    R@ R@ _SRW.REPOSITORY @ _SR.WORK !
    R@ STREAMS-REPOSITORY-WORK-VALID? 0= IF
        STREAMS-REPOSITORY-S-CONFLICT
        R> _SREPO-WORK-INIT-FAIL EXIT
    THEN
    R> DROP STREAMS-REPOSITORY-S-OK ;

