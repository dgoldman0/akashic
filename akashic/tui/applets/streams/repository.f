: STREAMS-REPOSITORY-SPAN-DISJOINT?
  ( address length repository work -- flag )
    2DUP _SREPO-PAIR? 0= IF _SREPO-DROP4 0 EXIT THEN
    3 PICK 3 PICK MSPAN-NONWRAPPING? 0= IF
        _SREPO-DROP4 0 EXIT
    THEN
    >R >R
    2DUP R@ STREAMS-REPOSITORY-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP R> DROP 0 EXIT
    THEN
    2DUP R@ _SR.STORE PSTORE-SPAN-DISJOINT? 0= IF
        2DROP R> DROP R> DROP 0 EXIT
    THEN
    R@ _SR.FLAGS @ _SR-F-COMPACTION-CONFIGURED AND IF
        2DUP R@ _SR.BUILDER-STORE
            PSTORE-SPAN-DISJOINT? 0= IF
            2DROP R> DROP R> DROP 0 EXIT
        THEN
    THEN
    R> DROP
    2DUP R@ STREAMS-REPOSITORY-WORK-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP 0 EXIT
    THEN
    2DUP R@ _SRW.PSTORE PSTORE-WORK-SPAN-DISJOINT? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    2DROP R> DROP -1 ;

