    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-CONNECTOR-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP SCON.MAGIC @ _SCON-MAGIC =
    OVER SCON.ABI @ STREAMS-CONNECTOR-ABI = AND
    OVER SCON.SIZE @ STREAMS-CONNECTOR-SIZE = AND
    OVER SCON.STATE @ _SCON-STATE-SEALED = AND
    SWAP _SCON-CONFIG-VALID? AND ;

: STREAMS-CONNECTOR-SEAL  ( connector -- status )
