    R@ SFLOW.EGRESS-EVENT
    R@ SFLOW.OPERATION
    R@ _SFLOW.OUTPUT-CONTEXT @
    R@ _SFLOW.OUTPUT-CLEANUP-XT @ EXECUTE
    R> SFLOW.EGRESS-ATTEMPT SATT.CLEANUP-ERROR ! ;

: _SFLOW-EGRESS-EXACT?  ( flow -- flag )
    _SFLOW-EGRESS-RETAINED-EXACT? ;

: _SFLOW-CONNECTOR-CALL  ( callback-body-xt flow -- throw )
    DUP _SFLOW-CONNECTOR-ENTER 0= IF
        2DROP STREAMS-FLOW-E-CONNECTOR-BUSY EXIT
    THEN
    DUP >R SWAP CATCH
    R@ _SFLOW-CONNECTOR-LEAVE
    R> DROP
    DUP IF NIP THEN ;

: _SFLOW-OUTPUT-CLEANUP-CALL  ( flow -- throw )
    ['] _SFLOW-OUTPUT-CLEANUP-BODY SWAP _SFLOW-CONNECTOR-CALL ;

: _SFLOW-OUTPUT-CLEANUP  ( flow -- )
    DUP _SFLOW.OUTPUT-STARTED @ 0=
    OVER _SFLOW.CLEANUP-DONE @ 0<> OR IF DROP EXIT THEN
    -1 OVER _SFLOW.CLEANUP-DONE !
    DUP _SFLOW-OUTPUT-CLEANUP-CALL
    DUP IF OVER SFLOW.EGRESS-ATTEMPT SATT.CLEANUP-ERROR !
        ELSE DROP THEN
    DUP SFLOW.OPERATION OVER SFLOW.OPERATION-CAPACITY 0 FILL
    DROP ;

: _SFLOW-OUTPUT-RESULT>STATE  ( result -- state effect status )
    DUP SCRR.EFFECT @ >R
    DUP SCRR.COMPLETION @ STREAMS-CONNECTOR-COMPLETION-DELIVERED = IF
        DROP STREAMS-ATTEMPT-STATE-DELIVERED
        R> STREAMS-FLOW-S-DELIVERED EXIT
    THEN
    DUP SCRR.COMPLETION @ STREAMS-CONNECTOR-COMPLETION-INDETERMINATE = IF
        DROP STREAMS-ATTEMPT-STATE-INDETERMINATE
        R> STREAMS-FLOW-S-INDETERMINATE EXIT
    THEN
    DUP SCRR.COMPLETION @ STREAMS-CONNECTOR-COMPLETION-CANCELLED = IF
        DROP
        R@ STREAMS-EFFECT-NOT-APPLIED = IF
            STREAMS-ATTEMPT-STATE-CANCELLED R>
            STREAMS-FLOW-S-CANCELLED EXIT
        THEN
        R@ STREAMS-EFFECT-APPLIED = IF
            STREAMS-ATTEMPT-STATE-FAILED-AFTER R>
            STREAMS-FLOW-S-FAILED EXIT
        THEN
        STREAMS-ATTEMPT-STATE-INDETERMINATE R>
        STREAMS-FLOW-S-INDETERMINATE EXIT
    THEN
    DUP SCRR.COMPLETION @ STREAMS-CONNECTOR-COMPLETION-STALE = IF
        DROP
        R@ STREAMS-EFFECT-NOT-APPLIED = IF
            STREAMS-ATTEMPT-STATE-STALE R>
            STREAMS-FLOW-S-STALE EXIT
        THEN
        R@ STREAMS-EFFECT-APPLIED = IF
            STREAMS-ATTEMPT-STATE-FAILED-AFTER R>
            STREAMS-FLOW-S-FAILED EXIT
        THEN
        STREAMS-ATTEMPT-STATE-INDETERMINATE R>
        STREAMS-FLOW-S-INDETERMINATE EXIT
    THEN
    DROP
    R@ STREAMS-EFFECT-NOT-APPLIED = IF
        STREAMS-ATTEMPT-STATE-FAILED-BEFORE R>
        STREAMS-FLOW-S-FAILED EXIT
    THEN
    R@ STREAMS-EFFECT-APPLIED = IF
        STREAMS-ATTEMPT-STATE-FAILED-AFTER R>
        STREAMS-FLOW-S-FAILED EXIT
    THEN
    STREAMS-ATTEMPT-STATE-INDETERMINATE R>
    STREAMS-FLOW-S-INDETERMINATE ;

: _SFLOW-OUTPUT-TERMINAL  ( reason flow -- status )
    >R
    R@ SFLOW.CONNECTOR-RESULT _SFLOW-OUTPUT-RESULT>STATE
    DUP R@ SFLOW.LAST-STATUS !
    DROP
    ROT
    R@ SFLOW.CONNECTOR-RESULT SCRR.DETAIL @
    R@ SFLOW.CONNECTOR-RESULT SCRR.ERROR @
    R@ _SFLOW.ARG-NOW @
    R@ SFLOW.EGRESS-ATTEMPT _SATT-TERMINAL!
    R@ _SFLOW-OUTPUT-CLEANUP
    R@ SFLOW.EGRESS-ATTEMPT SATT.CLEANUP-ERROR @ IF
        STREAMS-FLOW-S-CLEANUP
    ELSE
        R@ SFLOW.LAST-STATUS @
    THEN
    R> _SFLOW-MARK-TERMINAL ;

: _SFLOW-OUTPUT-CALL  ( callback-body-xt flow -- throw )
    DUP SFLOW.CONNECTOR-RESULT STREAMS-CONNECTOR-RESULT-INIT
    _SFLOW-CONNECTOR-CALL ;

: _SFLOW-OUTPUT-INDETERMINATE  ( error reason flow -- status )
    >R
    R@ SFLOW.EGRESS-ATTEMPT SATT.EFFECT @ STREAMS-EFFECT-APPLIED =
    IF
        STREAMS-CONNECTOR-COMPLETION-FAILED
            R@ SFLOW.CONNECTOR-RESULT SCRR.COMPLETION !
        STREAMS-EFFECT-APPLIED
            R@ SFLOW.CONNECTOR-RESULT SCRR.EFFECT !
    ELSE
        STREAMS-CONNECTOR-COMPLETION-INDETERMINATE
            R@ SFLOW.CONNECTOR-RESULT SCRR.COMPLETION !
        STREAMS-EFFECT-UNCERTAIN
            R@ SFLOW.CONNECTOR-RESULT SCRR.EFFECT !
    THEN
    OVER R@ SFLOW.CONNECTOR-RESULT SCRR.ERROR !
    NIP R> _SFLOW-OUTPUT-TERMINAL ;

: _SFLOW-OUTPUT-TAMPER-BEFORE-START  ( flow -- status )
    >R
    R@ SFLOW.CONNECTOR-RESULT STREAMS-CONNECTOR-RESULT-INIT
    STREAMS-CONNECTOR-COMPLETION-FAILED
        R@ SFLOW.CONNECTOR-RESULT SCRR.COMPLETION !
    STREAMS-EFFECT-NOT-APPLIED
        R@ SFLOW.CONNECTOR-RESULT SCRR.EFFECT !
    STREAMS-FLOW-E-PAYLOAD-CHANGED
        R@ SFLOW.CONNECTOR-RESULT SCRR.ERROR !
    STREAMS-ATTEMPT-REASON-CALLBACK
    R> _SFLOW-OUTPUT-TERMINAL ;

: _SFLOW-EGRESS-TAMPER  ( flow -- status )
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-DELIVERING = IF
        STREAMS-FLOW-E-PAYLOAD-CHANGED
        STREAMS-ATTEMPT-REASON-CALLBACK ROT
        _SFLOW-OUTPUT-INDETERMINATE EXIT
    THEN
    _SFLOW-OUTPUT-TAMPER-BEFORE-START ;

: _SFLOW-PAYLOAD-PREFLIGHT  ( flow -- status )
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-ACCEPTED = IF
        DUP _SFLOW-INGRESS-EXACT? 0= IF
            _SFLOW-INGRESS-TAMPER EXIT
        THEN
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-OUTPUT-READY >= IF
        DUP _SFLOW-EGRESS-EXACT? 0= IF
            _SFLOW-EGRESS-TAMPER EXIT
        THEN
    THEN
    DROP STREAMS-FLOW-S-OK ;

: _SFLOW-PRESERVE-KNOWN-EFFECT  ( flow -- )
    DUP SFLOW.EGRESS-ATTEMPT SATT.EFFECT @
        STREAMS-EFFECT-APPLIED <> IF DROP EXIT THEN
    DUP SFLOW.CONNECTOR-RESULT SCRR.COMPLETION @
        STREAMS-CONNECTOR-COMPLETION-PENDING = IF
        STREAMS-EFFECT-APPLIED
            SWAP SFLOW.CONNECTOR-RESULT SCRR.EFFECT !
        EXIT
    THEN
    DUP SFLOW.CONNECTOR-RESULT SCRR.COMPLETION @
        STREAMS-CONNECTOR-COMPLETION-DELIVERED <> IF
        STREAMS-CONNECTOR-COMPLETION-FAILED
            OVER SFLOW.CONNECTOR-RESULT SCRR.COMPLETION !
    THEN
    STREAMS-EFFECT-APPLIED
        SWAP SFLOW.CONNECTOR-RESULT SCRR.EFFECT ! ;

: _SFLOW-OUTPUT-HANDLE  ( reason flow -- status )
    >R
    R@ SFLOW.CONNECTOR-RESULT STREAMS-CONNECTOR-RESULT-VALID? 0= IF
        STREAMS-FLOW-E-INVALID-RESULT SWAP
        R> _SFLOW-OUTPUT-INDETERMINATE EXIT
    THEN
    R@ _SFLOW-PRESERVE-KNOWN-EFFECT
    R@ _SFLOW-EGRESS-EXACT? 0= IF
        STREAMS-FLOW-E-PAYLOAD-CHANGED SWAP
        R> _SFLOW-OUTPUT-INDETERMINATE EXIT
    THEN
    R@ SFLOW.CONNECTOR-RESULT SCRR.COMPLETION @
        STREAMS-CONNECTOR-COMPLETION-PENDING = IF
        R@ SFLOW.CONNECTOR-RESULT SCRR.EFFECT @
            R@ SFLOW.EGRESS-ATTEMPT SATT.EFFECT !
        STREAMS-FLOW-STATE-DELIVERING R@ SFLOW.STATE !
        STREAMS-FLOW-S-PENDING R@ SFLOW.LAST-STATUS !
        DROP R> DROP STREAMS-FLOW-S-PENDING EXIT
    THEN
    R> _SFLOW-OUTPUT-TERMINAL ;

: _SFLOW-STEP-OUTPUT-START  ( flow -- status )
    DUP SFLOW.OPERATION OVER SFLOW.OPERATION-CAPACITY 0 FILL
    -1 OVER _SFLOW.OUTPUT-STARTED !
    0 OVER _SFLOW.CLEANUP-DONE !
    DUP _SFLOW.ARG-NOW @ OVER SFLOW.EGRESS-ATTEMPT _SATT-ACTIVE!
    ['] _SFLOW-OUTPUT-START-BODY OVER _SFLOW-OUTPUT-CALL
    ?DUP IF
        STREAMS-ATTEMPT-REASON-CALLBACK ROT
        _SFLOW-OUTPUT-INDETERMINATE EXIT
    THEN
    STREAMS-ATTEMPT-REASON-OUTPUT SWAP _SFLOW-OUTPUT-HANDLE ;

: _SFLOW-STEP-OUTPUT-POLL  ( flow -- status )
    ['] _SFLOW-OUTPUT-POLL-BODY OVER _SFLOW-OUTPUT-CALL
    ?DUP IF
        STREAMS-ATTEMPT-REASON-CALLBACK ROT
        _SFLOW-OUTPUT-INDETERMINATE EXIT
    THEN
    STREAMS-ATTEMPT-REASON-OUTPUT SWAP _SFLOW-OUTPUT-HANDLE ;

: _SFLOW-BEFORE-OUTPUT
  ( status attempt-state reason flow -- status )
    >R
    STREAMS-EFFECT-NOT-APPLIED SWAP
    0 0 R@ _SFLOW.ARG-NOW @
    R@ SFLOW.STATE @ STREAMS-FLOW-STATE-ACCEPTED = IF
        R@ SFLOW.INGRESS-ATTEMPT
    ELSE
        R@ SFLOW.EGRESS-ATTEMPT
    THEN
    _SATT-TERMINAL!
    R> _SFLOW-MARK-TERMINAL ;

: _SFLOW-CANCEL-BEFORE-OUTPUT  ( reason flow -- status )
    >R
    STREAMS-FLOW-S-CANCELLED
    STREAMS-ATTEMPT-STATE-CANCELLED
    ROT
    R> _SFLOW-BEFORE-OUTPUT ;

: _SFLOW-CANCEL-ACTIVE  ( reason flow -- status )
    >R
    ['] _SFLOW-OUTPUT-CANCEL-BODY R@ _SFLOW-OUTPUT-CALL
    ?DUP IF
        NIP
        STREAMS-ATTEMPT-REASON-CALLBACK
        R> _SFLOW-OUTPUT-INDETERMINATE EXIT
    THEN
    R@ SFLOW.CONNECTOR-RESULT SCRR.COMPLETION @
        STREAMS-CONNECTOR-COMPLETION-PENDING = IF
        STREAMS-CONNECTOR-COMPLETION-INDETERMINATE
            R@ SFLOW.CONNECTOR-RESULT SCRR.COMPLETION !
        STREAMS-EFFECT-UNCERTAIN
            R@ SFLOW.CONNECTOR-RESULT SCRR.EFFECT !
    THEN
    R> _SFLOW-OUTPUT-HANDLE ;

: _SFLOW-TIMEOUT  ( flow -- status )
    DUP >R
    STREAMS-ATTEMPT-REASON-TIMEOUT OVER SFLOW.STATE @
    STREAMS-FLOW-STATE-DELIVERING =
    IF SWAP _SFLOW-CANCEL-ACTIVE ELSE SWAP _SFLOW-CANCEL-BEFORE-OUTPUT THEN
    DUP STREAMS-FLOW-S-CANCELLED = IF
        DROP STREAMS-FLOW-S-TIMED-OUT DUP R@ SFLOW.LAST-STATUS !
    THEN
    R> DROP ;

: _SFLOW-STALE-BEFORE-OUTPUT  ( flow -- status )
    >R
    STREAMS-FLOW-S-STALE
    STREAMS-ATTEMPT-STATE-STALE
    STREAMS-ATTEMPT-REASON-STALE
    R> _SFLOW-BEFORE-OUTPUT ;

: _SFLOW-STALE-ACTIVE  ( flow -- status )
    DUP SFLOW.CONNECTOR-RESULT STREAMS-CONNECTOR-RESULT-INIT
    STREAMS-CONNECTOR-COMPLETION-INDETERMINATE
        OVER SFLOW.CONNECTOR-RESULT SCRR.COMPLETION !
    STREAMS-EFFECT-UNCERTAIN
        OVER SFLOW.CONNECTOR-RESULT SCRR.EFFECT !
    STREAMS-FLOW-E-INVALID-RESULT
        OVER SFLOW.CONNECTOR-RESULT SCRR.ERROR !
    DUP _SFLOW-PRESERVE-KNOWN-EFFECT
    STREAMS-ATTEMPT-REASON-STALE SWAP _SFLOW-OUTPUT-TERMINAL ;

: _SFLOW-STEP-STAGING  ( flow -- status )
    DUP _SFLOW.ARG-NOW @ OVER SFLOW.DEADLINE @ >= IF
        STREAMS-FLOW-S-TIMED-OUT SWAP
        _SFLOW-ROLLBACK-RESERVATION EXIT
    THEN
    DUP _SFLOW-INPUT-CURRENT? 0=
    OVER _SFLOW-OUTPUT-CURRENT? 0= OR IF
        STREAMS-FLOW-S-STALE SWAP
        _SFLOW-ROLLBACK-RESERVATION EXIT
    THEN
    STREAMS-FLOW-S-PENDING OVER SFLOW.LAST-STATUS !
    DROP STREAMS-FLOW-S-PENDING ;

: _SFLOW-STEP-BODY  ( flow -- status )
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-TERMINAL = IF
        SFLOW.LAST-STATUS @ EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-IDLE = IF
        DROP STREAMS-FLOW-S-NO-WORK EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-RECEIVING = IF
        _SFLOW-STEP-STAGING EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-EGRESS-STAGING = IF
        _SFLOW-STEP-STAGING EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-OUTPUT-READY >=
    OVER _SFLOW-CONNECTOR-BUSY? AND IF
        DROP STREAMS-FLOW-S-BUSY EXIT
    THEN
    DUP _SFLOW-PAYLOAD-PREFLIGHT
    DUP STREAMS-FLOW-S-OK <> IF NIP EXIT THEN DROP
    DUP _SFLOW.ARG-NOW @ OVER SFLOW.DEADLINE @ >= IF
        _SFLOW-TIMEOUT EXIT
    THEN
    DUP _SFLOW-INPUT-CURRENT? 0= IF
        DUP SFLOW.STATE @ STREAMS-FLOW-STATE-DELIVERING = IF
            _SFLOW-STALE-ACTIVE EXIT
        THEN
        _SFLOW-STALE-BEFORE-OUTPUT EXIT
    THEN
    DUP _SFLOW-OUTPUT-CURRENT? 0= IF
        DUP SFLOW.STATE @ STREAMS-FLOW-STATE-DELIVERING = IF
            _SFLOW-STALE-ACTIVE EXIT
        THEN
        _SFLOW-STALE-BEFORE-OUTPUT EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-ACCEPTED = IF
        _SFLOW-STEP-TRANSFORM EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-OUTPUT-READY = IF
        _SFLOW-STEP-OUTPUT-START EXIT
    THEN
    _SFLOW-STEP-OUTPUT-POLL ;

: STREAMS-FLOW-STEP  ( now-ms flow -- status )
    >R
    R@ _SFLOW-HEADER? 0= IF DROP R> DROP STREAMS-FLOW-S-INVALID EXIT THEN
    R@ SFLOW.BUSY @ IF DROP R> DROP STREAMS-FLOW-S-BUSY EXIT THEN
    R@ STREAMS-FLOW-VALID? 0= IF
        DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP 0< IF DROP R> DROP STREAMS-FLOW-S-INVALID EXIT THEN
    R@ SFLOW.LAST-NOW @ DUP 0>= IF
        OVER SWAP < IF DROP R> DROP STREAMS-FLOW-S-STALE EXIT THEN
    ELSE DROP THEN
    R@ _SFLOW.ARG-NOW !
    -1 R@ SFLOW.BUSY !
    R@ _SFLOW.ARG-NOW @ R@ SFLOW.LAST-NOW !
    R@ _SFLOW-STEP-BODY
    R> _SFLOW-LEAVE ;

: _SFLOW-CANCEL-BODY  ( flow -- status )
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-IDLE = IF
        DROP STREAMS-FLOW-S-NO-WORK EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-RECEIVING = IF
        _SFLOW-ABORT-BODY EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-EGRESS-STAGING = IF
        _SFLOW-EGRESS-ABORT-BODY EXIT
    THEN
    DUP _SFLOW.ARG-GENERATION @ OVER SFLOW.GENERATION @ <> IF
        DROP STREAMS-FLOW-S-STALE EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-TERMINAL = IF
        SFLOW.LAST-STATUS @ EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-OUTPUT-READY >=
    OVER _SFLOW-CONNECTOR-BUSY? AND IF
        DROP STREAMS-FLOW-S-BUSY EXIT
    THEN
    DUP _SFLOW-PAYLOAD-PREFLIGHT
    DUP STREAMS-FLOW-S-OK <> IF NIP EXIT THEN DROP
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-DELIVERING = IF
        STREAMS-ATTEMPT-REASON-CANCEL SWAP _SFLOW-CANCEL-ACTIVE EXIT
    THEN
    STREAMS-ATTEMPT-REASON-CANCEL SWAP _SFLOW-CANCEL-BEFORE-OUTPUT ;

: STREAMS-FLOW-CANCEL  ( generation now-ms flow -- status )
    >R
    R@ _SFLOW-HEADER? 0= IF 2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT THEN
    R@ SFLOW.BUSY @ IF 2DROP R> DROP STREAMS-FLOW-S-BUSY EXIT THEN
    R@ STREAMS-FLOW-VALID? 0= IF
        2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP 0< IF 2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT THEN
    R@ SFLOW.LAST-NOW @ DUP 0>= IF
        OVER SWAP < IF 2DROP R> DROP STREAMS-FLOW-S-STALE EXIT THEN
    ELSE DROP THEN
    R@ _SFLOW.ARG-NOW !
    R@ _SFLOW.ARG-GENERATION !
    -1 R@ SFLOW.BUSY !
    R@ _SFLOW.ARG-NOW @ R@ SFLOW.LAST-NOW !
    R@ _SFLOW-CANCEL-BODY
    R> _SFLOW-LEAVE ;

\ ---------------------------------------------------------------------
\ Exact retirement
\ ---------------------------------------------------------------------

: STREAMS-FLOW-RETIRE  ( generation flow -- status )
    >R
    R@ _SFLOW-HEADER? 0= IF DROP R> DROP STREAMS-FLOW-S-INVALID EXIT THEN
    R@ SFLOW.BUSY @ IF DROP R> DROP STREAMS-FLOW-S-BUSY EXIT THEN
    R@ STREAMS-FLOW-VALID? 0= IF
        DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ SFLOW.STATE @ STREAMS-FLOW-STATE-TERMINAL <> IF
        DROP R> DROP STREAMS-FLOW-S-BUSY EXIT
    THEN
    R@ SFLOW.GENERATION @ <> IF R> DROP STREAMS-FLOW-S-STALE EXIT THEN
    -1 R@ SFLOW.BUSY !
    R@ _SFLOW-PAYLOAD-FAILURE-KNOWN? 0=
    R@ _SFLOW-CLOSE-PAYLOADS STREAMS-FLOW-S-OK <> AND
    R@ _SFLOW-EXPIRE-EVENTS
    R@ _SFLOW-CLEAR-SLOT
    DUP STREAMS-FLOW-S-OK <> IF
        NIP R> _SFLOW-LEAVE EXIT
    THEN
    DROP
    -1 R@ SFLOW.DEADLINE !
    STREAMS-FLOW-STATE-IDLE R@ SFLOW.STATE !
    IF
        STREAMS-FLOW-S-CLEANUP DUP R@ SFLOW.LAST-STATUS !
    ELSE
        STREAMS-FLOW-S-OK DUP R@ SFLOW.LAST-STATUS !
    THEN
    R> _SFLOW-LEAVE ;
