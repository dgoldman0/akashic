: _SFLOW-CONNECTOR-DIRECTION?  ( direction -- flag )
    DUP STREAMS-CONNECTOR-DIRECTION-INPUT =
    OVER STREAMS-CONNECTOR-DIRECTION-OUTPUT = OR
    SWAP STREAMS-CONNECTOR-DIRECTION-BIDIRECTIONAL = OR ;

: _SFLOW-EVENT-DIRECTION?  ( direction -- flag )
    DUP STREAMS-EVENT-DIRECTION-INGRESS =
    OVER STREAMS-EVENT-DIRECTION-EGRESS = OR
    SWAP STREAMS-EVENT-DIRECTION-INTERNAL = OR ;

: _SFLOW-EFFECT?  ( effect -- flag )
    DUP STREAMS-EFFECT-NOT-APPLIED >=
    SWAP STREAMS-EFFECT-UNCERTAIN <= AND ;

: _SFLOW-ZERO?  ( address length -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    0 ?DO
        DUP I + C@ IF DROP 0 UNLOOP EXIT THEN
    LOOP
    DROP -1 ;

