    DUP _SFLOW.INPUT-REVISION @
        OVER _SFLOW.ARG-EVENT @ SEVT.CONNECTOR-REVISION !
    STREAMS-EVENT-DIRECTION-INGRESS
        OVER _SFLOW.ARG-EVENT @ SEVT.DIRECTION !
    DUP _SFLOW.INPUT-PROTOCOL @
        OVER _SFLOW.ARG-EVENT @ SEVT.PROTOCOL !
    _SFLOW.ARG-EVENT @ STREAMS-EVENT-SEAL ;

: STREAMS-FLOW-SEAL-INGRESS
  ( input-connector event flow -- status )
    >R
    R@ _SFLOW-HEADER? 0= IF 2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT THEN
    R@ SFLOW.BUSY @ IF 2DROP R> DROP STREAMS-FLOW-S-BUSY EXIT THEN
    R@ STREAMS-FLOW-VALID? 0= IF
        2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ _SFLOW.ARG-EVENT !
    R@ _SFLOW.ARG-CONNECTOR !
    -1 R@ SFLOW.BUSY !
    R@ _SFLOW-SEAL-INGRESS-BODY
    R> _SFLOW-LEAVE ;

: _SATT-ACCEPT  ( event generation now direction attempt -- )
    >R
    R@ _SATT-INIT
    STREAMS-ATTEMPT-STATE-ACCEPTED R@ SATT.STATE !
    STREAMS-EFFECT-NOT-APPLIED R@ SATT.EFFECT !
    DUP R@ SATT.ACCEPTED-MS !
    OVER R@ SATT.GENERATION !
    2 PICK SEVT.PAYLOAD-U @ R@ SATT.PAYLOAD-U !
    2 PICK SEVT.EVENT-ID R@ SATT.EVENT-ID RID-COPY
    2 PICK SEVT.CONNECTOR-ID R@ SATT.CONNECTOR-ID RID-COPY
    2 PICK SEVT.FLOW-ID R@ SATT.FLOW-ID RID-COPY
    2 PICK SEVT.CORRELATION-ID R@ SATT.CORRELATION-ID RID-COPY
    2 PICK SEVT.IDEMPOTENCY-ID R@ SATT.IDEMPOTENCY-ID RID-COPY
    2 PICK SEVT.PAYLOAD-DIGEST R@ SATT.PAYLOAD-DIGEST RID-COPY
    2DROP DROP R> DROP ;

: _SFLOW-EVENT-MATCH?  ( event flow -- flag )
    >R
    DUP SEVT.DIRECTION @ STREAMS-EVENT-DIRECTION-INGRESS =
    OVER SEVT.CONNECTOR-ID R@ _SFLOW.INPUT-ID RID= AND
    OVER SEVT.CONNECTOR-REVISION @ R@ _SFLOW.INPUT-REVISION @ = AND
    OVER SEVT.FLOW-ID R@ SFLOW.ID RID= AND
    OVER SEVT.ORIGIN-ID R@ _SFLOW.INPUT-ENDPOINT-ID RID= AND
    SWAP SEVT.DESTINATION-ID R@ SFLOW.ID RID= AND
    R> DROP ;

: _SFLOW-ADMIT-PRECHECK  ( flow -- status )
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-IDLE <> IF
        DROP STREAMS-FLOW-S-FULL EXIT
    THEN
    DUP _SFLOW.ARG-EXPECTED @ OVER SFLOW.REVISION @ <> IF
        DROP STREAMS-FLOW-S-STALE EXIT
    THEN
    DUP _SFLOW-INPUT-CURRENT? 0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DUP _SFLOW-OUTPUT-CURRENT? 0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DUP _SFLOW.ARG-NOW @ 0< IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP SFLOW.LAST-NOW @ 0>= IF
        DUP _SFLOW.ARG-NOW @ OVER SFLOW.LAST-NOW @ < IF
            DROP STREAMS-FLOW-S-STALE EXIT
        THEN
    THEN
    DUP _SFLOW.ARG-EVENT @ DUP STREAMS-EVENT-VALID? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    OVER _SFLOW-EVENT-MATCH? 0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DUP _SFLOW.ARG-EVENT @ STREAMS-EVENT-SIZE
        2 PICK STREAMS-FLOW-SIZE
        MSPAN-OVERLAP? IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP _SFLOW.ARG-EVENT @
    DUP SEVT.PAYLOAD-A @ SWAP SEVT.PAYLOAD-U @
        2 PICK STREAMS-FLOW-SIZE MSPAN-OVERLAP? IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.GENERATION @ _SFLOW-CELL-MAX >= IF
        DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    DUP SFLOW.TIMEOUT-MS @ _SFLOW-CELL-MAX SWAP -
    OVER _SFLOW.ARG-NOW @ < IF
        DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    DROP STREAMS-FLOW-S-OK ;

: _SFLOW-COPY-INGRESS  ( flow -- )
    >R
    R@ _SFLOW.ARG-EVENT @
        R@ SFLOW.INGRESS-EVENT STREAMS-EVENT-SIZE MOVE
    R@ SFLOW.INGRESS-PAYLOAD STREAMS-FLOW-PAYLOAD-MAX 0 FILL
    R@ _SFLOW.ARG-EVENT @ SEVT.PAYLOAD-U @ ?DUP IF
        R@ _SFLOW.ARG-EVENT @ SEVT.PAYLOAD-A @
        R@ SFLOW.INGRESS-PAYLOAD ROT MOVE
    THEN
    R@ SFLOW.INGRESS-PAYLOAD
        R@ SFLOW.INGRESS-EVENT SEVT.PAYLOAD-A !
    STREAMS-EVENT-OWNERSHIP-INLINE
        R@ SFLOW.INGRESS-EVENT SEVT.OWNERSHIP !
    0 R@ SFLOW.INGRESS-EVENT SEVT.RELEASE-XT !
    0 R@ SFLOW.INGRESS-EVENT SEVT.RELEASE-CONTEXT !
    _SEVT-STATE-INLINE R@ SFLOW.INGRESS-EVENT SEVT.STATE !
    R@ SFLOW.INGRESS-EVENT STREAMS-EVENT-SIZE
        R@ SFLOW.CONNECTOR-RESULT SHA3-256-HASH
    R> DROP ;

: _SFLOW-COMMIT-ADMISSION  ( flow -- status )
    >R
    R@ SFLOW.GENERATION @ 1+ R@ SFLOW.GENERATION !
    R@ _SFLOW.ARG-NOW @ R@ SFLOW.TIMEOUT-MS @ +
        R@ SFLOW.DEADLINE !
    R@ _SFLOW.ARG-NOW @ R@ SFLOW.LAST-NOW !
    R@ SFLOW.INGRESS-EVENT
    R@ SFLOW.GENERATION @
    R@ _SFLOW.ARG-NOW @
    STREAMS-EVENT-DIRECTION-INGRESS
    R@ SFLOW.INGRESS-ATTEMPT _SATT-ACCEPT
    STREAMS-FLOW-STATE-ACCEPTED R@ SFLOW.STATE !
    STREAMS-FLOW-S-OK R@ SFLOW.LAST-STATUS !
    R> DROP STREAMS-FLOW-S-OK ;

: _SFLOW-ADMIT-BODY  ( flow -- status )
    DUP _SFLOW-ADMIT-PRECHECK
    DUP STREAMS-FLOW-S-OK <> IF NIP EXIT THEN
    DROP
    DUP _SFLOW-COPY-INGRESS
    DUP _SFLOW.ARG-EVENT @ STREAMS-EVENT-CLOSE
    DUP STREAMS-FLOW-S-OK <> IF
        >R DUP _SFLOW-CLEAR-SLOT DROP R> EXIT
    THEN
    DROP _SFLOW-COMMIT-ADMISSION ;

: STREAMS-FLOW-ADMIT
  ( event expected-flow-revision now-ms flow -- status )
    >R
    R@ _SFLOW-HEADER? 0= IF
        2DROP DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ SFLOW.BUSY @ IF
        2DROP DROP R> DROP STREAMS-FLOW-S-BUSY EXIT
    THEN
    R@ STREAMS-FLOW-VALID? 0= IF
        2DROP DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ _SFLOW.ARG-NOW !
    R@ _SFLOW.ARG-EXPECTED !
    R@ _SFLOW.ARG-EVENT !
    -1 R@ SFLOW.BUSY !
    R@ _SFLOW-ADMIT-BODY
    R> _SFLOW-LEAVE ;

