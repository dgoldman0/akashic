: _SEVT-HEADER?  ( event -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-EVENT-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP SEVT.MAGIC @ _SEVT-MAGIC =
    SWAP SEVT.SIZE @ STREAMS-EVENT-SIZE = AND ;

: _SEVT-PAYLOAD-SPAN?  ( address length -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    DUP 0> 2 PICK 0= AND IF 2DROP 0 EXIT THEN
    MSPAN-NONWRAPPING? ;

