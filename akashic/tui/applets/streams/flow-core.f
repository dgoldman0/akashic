: STREAMS-CONNECTOR-INIT  ( connector -- status )
    DUP 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP STREAMS-CONNECTOR-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP STREAMS-CONNECTOR-SIZE 0 FILL
    _SCON-MAGIC OVER SCON.MAGIC !
    STREAMS-CONNECTOR-SIZE OVER SCON.SIZE !
    _SCON-STATE-BUILDING SWAP SCON.STATE !
    STREAMS-FLOW-S-OK ;

: _SCON-OUTPUT-SURFACE?  ( connector -- flag )
    DUP SCON.OP-SIZE @ 0> 0= IF DROP 0 EXIT THEN
    DUP SCON.START-XT @ 0<>
    OVER SCON.POLL-XT @ 0<> AND
    OVER SCON.CANCEL-XT @ 0<> AND
    SWAP SCON.CLEANUP-XT @ 0<> AND ;

: _SCON-INPUT-SURFACE?  ( connector -- flag )
    DUP SCON.OP-SIZE @ 0=
    OVER SCON.START-XT @ 0= AND
    OVER SCON.POLL-XT @ 0= AND
    OVER SCON.CANCEL-XT @ 0= AND
    SWAP SCON.CLEANUP-XT @ 0= AND ;

: _SCON-CONFIG-VALID?  ( connector -- flag )
    DUP SCON.ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SCON.ENDPOINT-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SCON.REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP SCON.DIRECTION @ _SFLOW-CONNECTOR-DIRECTION? 0= IF
        DROP 0 EXIT
    THEN
    DUP SCON.PROTOCOL @ 0> 0= IF DROP 0 EXIT THEN
    DUP SCON.CALLBACK-BUSY @ DUP 0<> SWAP -1 <> AND IF
        DROP 0 EXIT
    THEN
    DUP SCON.DIRECTION @ STREAMS-CONNECTOR-DIRECTION-INPUT = IF
        _SCON-INPUT-SURFACE? EXIT
    THEN
    _SCON-OUTPUT-SURFACE? ;

: STREAMS-CONNECTOR-VALID?  ( connector -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-CONNECTOR-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP SCON.MAGIC @ _SCON-MAGIC =
    OVER SCON.SIZE @ STREAMS-CONNECTOR-SIZE = AND
    OVER SCON.STATE @ _SCON-STATE-SEALED = AND
    SWAP _SCON-CONFIG-VALID? AND ;

: STREAMS-CONNECTOR-SEAL  ( connector -- status )
    DUP 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP STREAMS-CONNECTOR-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SCON.MAGIC @ _SCON-MAGIC <>
    OVER SCON.SIZE @ STREAMS-CONNECTOR-SIZE <> OR
    OVER SCON.STATE @ _SCON-STATE-BUILDING <> OR IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SCON-CONFIG-VALID? 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    _SCON-STATE-SEALED SWAP SCON.STATE !
    STREAMS-FLOW-S-OK ;

