    DUP SCON.MAGIC @ _SCON-MAGIC <>
    OVER SCON.ABI @ STREAMS-CONNECTOR-ABI <> OR
    OVER SCON.SIZE @ STREAMS-CONNECTOR-SIZE <> OR
    OVER SCON.STATE @ _SCON-STATE-BUILDING <> OR IF
        DROP STREAMS-FLOW-S-INVALID EXIT
