    DUP SEVT.EVENT-ID RID-PRESENT?
    OVER SEVT.CORRELATION-ID RID-PRESENT? AND
    OVER SEVT.IDEMPOTENCY-ID RID-PRESENT? AND
    OVER SEVT.MEDIA @ 0> AND
    OVER SEVT.SEQUENCE @ 0>= AND
    SWAP SEVT.RECEIVED-MS @ 0>= AND ;

: _SEVT-UNBOUND-METADATA?  ( event -- flag )
    DUP _SEVT-HEADER? 0= IF DROP 0 EXIT THEN
    DUP SEVT.STATE @ _SEVT-STATE-BUILDING <> IF DROP 0 EXIT THEN
    DUP _SEVT-METADATA-CONTENT? 0= IF DROP 0 EXIT THEN
    DUP SEVT.PAYLOAD-A @ 0=
    OVER SEVT.PAYLOAD-U @ 0= AND
    OVER SEVT.OWNERSHIP @ 0= AND
    OVER SEVT.RELEASE-XT @ 0= AND
    OVER SEVT.RELEASE-CONTEXT @ 0= AND
    OVER SEVT.CLEANUP-ERROR @ 0= AND
    SWAP SEVT.PAYLOAD-DIGEST SHA3-256-LEN _SFLOW-ZERO? AND ;

: STREAMS-EVENT-BORROW  ( payload-a payload-u event -- status )
    >R
    R@ _SEVT-HEADER? 0= IF
        2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ SEVT.STATE @ _SEVT-STATE-BUILDING <> IF
        2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ SEVT.OWNERSHIP @ 0<> IF
        2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    2DUP _SEVT-PAYLOAD-SPAN? 0= IF
        2DROP R> DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    DUP R@ SEVT.PAYLOAD-U !
    OVER R@ SEVT.PAYLOAD-A !
    2DROP
    STREAMS-EVENT-OWNERSHIP-BORROWED R@ SEVT.OWNERSHIP !
    R> DROP STREAMS-FLOW-S-OK ;

: STREAMS-EVENT-OWN
  ( payload-a payload-u release-xt release-context event -- status )
    >R
    R@ _SEVT-HEADER? 0= IF
        2DROP 2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ SEVT.STATE @ _SEVT-STATE-BUILDING <> IF
        2DROP 2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ SEVT.OWNERSHIP @ 0<> IF
        2DROP 2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    1 PICK 0= IF
        2DROP 2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    3 PICK 3 PICK _SEVT-PAYLOAD-SPAN? 0= IF
        2DROP 2DROP R> DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    R@ SEVT.RELEASE-CONTEXT !
    R@ SEVT.RELEASE-XT !
    R@ SEVT.PAYLOAD-U !
    R@ SEVT.PAYLOAD-A !
    STREAMS-EVENT-OWNERSHIP-OWNED R@ SEVT.OWNERSHIP !
    R> DROP STREAMS-FLOW-S-OK ;

: _SEVT-CARRIER-BOUND?  ( event -- flag )
    >R
    R@ SEVT.PAYLOAD-A @ DUP 0= IF DROP R> DROP 0 EXIT THEN
    STREAMS-PAYLOAD-BOUND? 0= IF R> DROP 0 EXIT THEN
    R@ SEVT.PAYLOAD-A @ SPAY.STATE @
        STREAMS-PAYLOAD-STATE-SEALED <> IF R> DROP 0 EXIT THEN
    R@ SEVT.PAYLOAD-A @ SPAY.BINDING-EPOCH @
        R@ SEVT.RELEASE-CONTEXT @ <> IF R> DROP 0 EXIT THEN
    R@ SEVT.PAYLOAD-A @ SPAY.BYTE-U @
        R@ SEVT.PAYLOAD-U @ <> IF R> DROP 0 EXIT THEN
    R> DROP -1 ;

: _SEVT-CARRIER-EXACT?  ( event -- flag )
    >R
    R@ _SEVT-CARRIER-BOUND? 0= IF R> DROP 0 EXIT THEN
    R@ SEVT.PAYLOAD-A @ SPAY.GENERATION @
        R@ SEVT.PAYLOAD-A @
        STREAMS-PAYLOAD-EXACT? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ SEVT.PAYLOAD-A @ SPAY.BYTE-U @
        R@ SEVT.PAYLOAD-U @ <> IF R> DROP 0 EXIT THEN
    R@ SEVT.PAYLOAD-A @ SPAY.DIGEST
        R@ SEVT.PAYLOAD-DIGEST SHA3-256-COMPARE
    R> DROP ;

: STREAMS-EVENT-CARRIER  ( payload-carrier event -- status )
    >R
    R@ _SEVT-HEADER? 0= IF
        DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ SEVT.STATE @ _SEVT-STATE-BUILDING <>
    R@ SEVT.OWNERSHIP @ 0<> OR IF
        DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SPAY.GENERATION @ OVER STREAMS-PAYLOAD-EXACT? 0= IF
        DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ STREAMS-EVENT-SIZE 2 PICK
        STREAMS-PAYLOAD-SPAN-DISJOINT? 0= IF
        DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP R@ SEVT.PAYLOAD-A !
    DUP SPAY.BYTE-U @ R@ SEVT.PAYLOAD-U !
    DUP SPAY.BINDING-EPOCH @ R@ SEVT.RELEASE-CONTEXT !
    DROP
    STREAMS-EVENT-OWNERSHIP-CARRIER R@ SEVT.OWNERSHIP !
    0 R@ SEVT.RELEASE-XT !
    R> DROP STREAMS-FLOW-S-OK ;

: _SEVT-IDENTITY?  ( event -- flag )
    DUP SEVT.EVENT-ID RID-PRESENT?
    OVER SEVT.CONNECTOR-ID RID-PRESENT? AND
    OVER SEVT.FLOW-ID RID-PRESENT? AND
    OVER SEVT.CORRELATION-ID RID-PRESENT? AND
    OVER SEVT.IDEMPOTENCY-ID RID-PRESENT? AND
    OVER SEVT.ORIGIN-ID RID-PRESENT? AND
    SWAP SEVT.DESTINATION-ID RID-PRESENT? AND ;

: _SEVT-CONFIG?  ( event -- flag )
    DUP _SEVT-IDENTITY? 0= IF DROP 0 EXIT THEN
    DUP SEVT.CONNECTOR-REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP SEVT.DIRECTION @ _SFLOW-EVENT-DIRECTION? 0= IF DROP 0 EXIT THEN
    DUP SEVT.PROTOCOL @ 0> 0= IF DROP 0 EXIT THEN
    DUP SEVT.MEDIA @ 0> 0= IF DROP 0 EXIT THEN
    DUP SEVT.SEQUENCE @ 0< IF DROP 0 EXIT THEN
    DUP SEVT.RECEIVED-MS @ 0< IF DROP 0 EXIT THEN
    DUP SEVT.OWNERSHIP @ STREAMS-EVENT-OWNERSHIP-CARRIER = IF
        DUP SEVT.RELEASE-XT @ 0=
        OVER SEVT.RELEASE-CONTEXT @ 0> AND
        SWAP _SEVT-CARRIER-BOUND? AND EXIT
    THEN
    DUP SEVT.PAYLOAD-A @ OVER SEVT.PAYLOAD-U @
        _SEVT-PAYLOAD-SPAN? 0= IF DROP 0 EXIT THEN
    DUP SEVT.OWNERSHIP @ STREAMS-EVENT-OWNERSHIP-BORROWED = IF
        DUP SEVT.RELEASE-XT @ 0=
        SWAP SEVT.RELEASE-CONTEXT @ 0= AND EXIT
    THEN
    DUP SEVT.OWNERSHIP @ STREAMS-EVENT-OWNERSHIP-OWNED = IF
        SEVT.RELEASE-XT @ 0<> EXIT
    THEN
    DROP 0 ;

: _SEVT-PAYLOAD-EXACT?  ( event -- flag )
    DUP SEVT.OWNERSHIP @ STREAMS-EVENT-OWNERSHIP-CARRIER = IF
        _SEVT-CARRIER-EXACT? EXIT
    THEN
    DUP SEVT.PAYLOAD-A @ OVER SEVT.PAYLOAD-U @
    ROT SEVT.PAYLOAD-DIGEST SHA3-256-HASH-COMPARE ;

: STREAMS-EVENT-VALID?  ( event -- flag )
    DUP _SEVT-HEADER? 0= IF DROP 0 EXIT THEN
    DUP SEVT.STATE @ DUP _SEVT-STATE-OPEN =
        OVER _SEVT-STATE-CARRIER = OR IF
        DROP DUP _SEVT-CONFIG? IF _SEVT-PAYLOAD-EXACT? ELSE DROP 0 THEN
        EXIT
    THEN
    DUP _SEVT-STATE-CLOSED =
    OVER _SEVT-STATE-CLEANUP-FAILED = OR
    SWAP _SEVT-STATE-EXPIRED = OR IF
        DUP _SEVT-IDENTITY? 0= IF DROP 0 EXIT THEN
        DUP SEVT.PAYLOAD-A @ 0=
        OVER SEVT.PAYLOAD-U @ 0>= AND
        OVER SEVT.RELEASE-XT @ 0= AND
        OVER SEVT.RELEASE-CONTEXT @ 0= AND
        OVER SEVT.STATE @ _SEVT-STATE-CLEANUP-FAILED =
        IF OVER SEVT.CLEANUP-ERROR @ 0<> AND ELSE
            OVER SEVT.CLEANUP-ERROR @ 0= AND
        THEN
        NIP EXIT
    THEN
    DROP 0 ;

: STREAMS-EVENT-SEAL  ( event -- status )
    DUP _SEVT-HEADER? 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP SEVT.STATE @ _SEVT-STATE-BUILDING <> IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SEVT-CONFIG? 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP SEVT.OWNERSHIP @ STREAMS-EVENT-OWNERSHIP-CARRIER = IF
        DUP SEVT.PAYLOAD-A @ SPAY.GENERATION @
            OVER SEVT.PAYLOAD-A @
            STREAMS-PAYLOAD-EXACT? 0= IF
            DROP STREAMS-FLOW-S-INVALID EXIT
        THEN
        DUP SEVT.PAYLOAD-A @ SPAY.DIGEST
            OVER SEVT.PAYLOAD-DIGEST SHA3-256-LEN MOVE
    ELSE
        DUP SEVT.PAYLOAD-A @ OVER SEVT.PAYLOAD-U @
            2 PICK SEVT.PAYLOAD-DIGEST SHA3-256-HASH
    THEN
    _SEVT-STATE-OPEN SWAP SEVT.STATE !
    STREAMS-FLOW-S-OK ;

: STREAMS-EVENT-APPEND-TO-CARRIER
  ( destination-generation destination-carrier event -- status )
    >R
    R@ STREAMS-EVENT-VALID? 0= IF
        2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ SEVT.OWNERSHIP @ STREAMS-EVENT-OWNERSHIP-CARRIER = IF
        R@ SEVT.PAYLOAD-A @ SPAY.GENERATION @
        R@ SEVT.PAYLOAD-A @
        2SWAP STREAMS-PAYLOAD-APPEND-PAYLOAD
    ELSE
        R@ SEVT.PAYLOAD-A @ R@ SEVT.PAYLOAD-U @
        2SWAP STREAMS-PAYLOAD-APPEND
    THEN
    R> DROP
    DUP STREAMS-PAYLOAD-S-OK = IF
        DROP STREAMS-FLOW-S-OK EXIT
    THEN
