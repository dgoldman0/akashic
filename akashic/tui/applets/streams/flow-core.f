: _SFLOW-BIND-EGRESS-METADATA  ( flow -- )
    DUP _SFLOW.ARG-EVENT @ SEVT.PAYLOAD-DIGEST
        OVER SFLOW.TRANSFORM-RESULT SHA3-256-LEN MOVE
    DUP _SFLOW.ARG-EVENT @
        OVER SFLOW.EGRESS-EVENT STREAMS-EVENT-SIZE MOVE
    _SEVT-STATE-BUILDING OVER SFLOW.EGRESS-EVENT SEVT.STATE !
    DUP _SFLOW.OUTPUT-ID
        OVER SFLOW.EGRESS-EVENT SEVT.CONNECTOR-ID RID-COPY
    DUP SFLOW.ID OVER SFLOW.EGRESS-EVENT SEVT.FLOW-ID RID-COPY
    DUP _SFLOW.OUTPUT-ENDPOINT-ID
        OVER SFLOW.EGRESS-EVENT SEVT.DESTINATION-ID RID-COPY
    DUP _SFLOW.OUTPUT-REVISION @
        OVER SFLOW.EGRESS-EVENT SEVT.CONNECTOR-REVISION !
    STREAMS-EVENT-DIRECTION-EGRESS
        OVER SFLOW.EGRESS-EVENT SEVT.DIRECTION !
    DUP _SFLOW.OUTPUT-PROTOCOL @
        OVER SFLOW.EGRESS-EVENT SEVT.PROTOCOL !
    DUP SFLOW.OUTPUT-MEDIA @
        OVER SFLOW.EGRESS-EVENT SEVT.MEDIA !
    DUP SFLOW.EGRESS-CARRIER
        OVER SFLOW.EGRESS-EVENT SEVT.PAYLOAD-A !
    DUP _SFLOW.ARG-GENERATION @
        OVER SFLOW.EGRESS-EVENT SEVT.PAYLOAD-U !
    STREAMS-EVENT-OWNERSHIP-CARRIER
        OVER SFLOW.EGRESS-EVENT SEVT.OWNERSHIP !
    0 OVER SFLOW.EGRESS-EVENT SEVT.RELEASE-XT !
    DUP SFLOW.EGRESS-CARRIER-EPOCH @
        OVER SFLOW.EGRESS-EVENT SEVT.RELEASE-CONTEXT !
    0 OVER SFLOW.EGRESS-EVENT SEVT.CLEANUP-ERROR !
    DUP SFLOW.EGRESS-EVENT SEVT.PAYLOAD-DIGEST
        SHA3-256-LEN 0 FILL
    _SFLOW-EGRESS-STAGING-SEAL! ;

: _SFLOW-BEGIN-EGRESS-RESERVATION  ( flow -- generation status )
    DUP _SFLOW-BIND-EGRESS-METADATA
    DUP SFLOW.GENERATION @ 1+ DUP 2 PICK SFLOW.GENERATION !
    DUP 2 PICK _SFLOW.ARG-GENERATION !
    OVER _SFLOW.ARG-NOW @ 2 PICK SFLOW.TIMEOUT-MS @ +
        2 PICK SFLOW.DEADLINE !
    OVER _SFLOW.ARG-NOW @ 2 PICK SFLOW.LAST-NOW !
    STREAMS-FLOW-STATE-EGRESS-STAGING 2 PICK SFLOW.STATE !
    STREAMS-FLOW-S-PENDING 2 PICK SFLOW.LAST-STATUS !
    NIP STREAMS-FLOW-S-OK ;

: _SFLOW-EGRESS-STAGE-PRECHECK  ( flow -- status )
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-EGRESS-STAGING <> IF
        DROP STREAMS-FLOW-S-NO-WORK EXIT
    THEN
    DUP _SFLOW.ARG-NOW @ OVER SFLOW.DEADLINE @ >= IF
        DROP STREAMS-FLOW-S-TIMED-OUT EXIT
    THEN
    DUP _SFLOW.ARG-GENERATION @ OVER SFLOW.GENERATION @ <> IF
        DROP STREAMS-FLOW-S-STALE EXIT
    THEN
    DUP _SFLOW-INPUT-CURRENT? 0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DUP _SFLOW-OUTPUT-CURRENT? 0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DUP _SFLOW-EGRESS-STAGING-SEAL? 0= IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DROP STREAMS-FLOW-S-OK ;

: _SFLOW-EGRESS-APPEND-BODY  ( flow -- status )
    DUP _SFLOW-EGRESS-STAGE-PRECHECK
    DUP STREAMS-FLOW-S-TIMED-OUT = IF
        DROP STREAMS-FLOW-S-TIMED-OUT SWAP
        _SFLOW-ROLLBACK-RESERVATION EXIT
    THEN
    DUP STREAMS-FLOW-S-OK <> IF NIP EXIT THEN
    DROP
    DUP SFLOW.EGRESS-EVENT SEVT.PAYLOAD-U @
        OVER SFLOW.EGRESS-CARRIER SPAY.BYTE-U @ -
        OVER _SFLOW.ARG-CONNECTOR @ < IF
        DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    >R
    R@ _SFLOW.ARG-EVENT @
    R@ _SFLOW.ARG-CONNECTOR @
    R@ SFLOW.EGRESS-CARRIER SPAY.GENERATION @
    R@ SFLOW.EGRESS-CARRIER STREAMS-PAYLOAD-APPEND
    R> DROP
    DUP STREAMS-PAYLOAD-S-OK = IF DROP STREAMS-FLOW-S-OK EXIT THEN
    DUP STREAMS-PAYLOAD-S-CAPACITY = IF DROP STREAMS-FLOW-S-CAPACITY EXIT THEN
    DUP STREAMS-PAYLOAD-S-STALE = IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    STREAMS-PAYLOAD-S-BUSY = IF
        STREAMS-FLOW-S-BUSY
    ELSE
        STREAMS-FLOW-S-INVALID
    THEN ;

: _SFLOW-SEAL-EGRESS-RESERVATION  ( flow -- status )
    >R
    R@ SFLOW.EGRESS-CARRIER SPAY.BYTE-U @
        R@ SFLOW.EGRESS-EVENT SEVT.PAYLOAD-U @ <> IF
        R> DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    R@ SFLOW.EGRESS-CARRIER SPAY.GENERATION @
        R@ SFLOW.EGRESS-CARRIER STREAMS-PAYLOAD-SEAL
    DUP STREAMS-PAYLOAD-S-OK <> IF
        DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DROP
    R@ SFLOW.EGRESS-CARRIER SPAY.DIGEST
        R@ SFLOW.TRANSFORM-RESULT SHA3-256-COMPARE 0= IF
        R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ SFLOW.EGRESS-EVENT STREAMS-EVENT-SEAL
        STREAMS-FLOW-S-OK <> IF
        R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    _SEVT-STATE-CARRIER R@ SFLOW.EGRESS-EVENT SEVT.STATE !
    R@ SFLOW.EGRESS-EVENT STREAMS-EVENT-SIZE
        R@ SFLOW.TRANSFORM-RESULT SHA3-256-HASH
    R> DROP STREAMS-FLOW-S-OK ;

: _SFLOW-PUBLISH-EGRESS  ( flow -- status )
    >R
    R@ SFLOW.EGRESS-EVENT
    R@ SFLOW.GENERATION @
    R@ _SFLOW.ARG-NOW @
    STREAMS-EVENT-DIRECTION-EGRESS
    R@ SFLOW.EGRESS-ATTEMPT _SATT-ACCEPT
    STREAMS-FLOW-STATE-OUTPUT-READY R@ SFLOW.STATE !
    STREAMS-FLOW-S-OK R@ SFLOW.LAST-STATUS !
    R> DROP STREAMS-FLOW-S-OK ;

: _SFLOW-EGRESS-COMMIT-BODY  ( flow -- status )
    DUP _SFLOW-EGRESS-STAGE-PRECHECK
    DUP STREAMS-FLOW-S-TIMED-OUT = IF
        DROP STREAMS-FLOW-S-TIMED-OUT SWAP
        _SFLOW-ROLLBACK-RESERVATION EXIT
    THEN
    DUP STREAMS-FLOW-S-OK <> IF NIP EXIT THEN
    DROP
    DUP _SFLOW-SEAL-EGRESS-RESERVATION
    DUP STREAMS-FLOW-S-CAPACITY = IF NIP EXIT THEN
    DUP STREAMS-FLOW-S-OK <> IF
        DROP STREAMS-FLOW-S-INVALID SWAP
        _SFLOW-ROLLBACK-RESERVATION EXIT
    THEN
    DROP _SFLOW-PUBLISH-EGRESS ;

: _SFLOW-EGRESS-ABORT-BODY  ( flow -- status )
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-EGRESS-STAGING <> IF
        DROP STREAMS-FLOW-S-NO-WORK EXIT
    THEN
    DUP _SFLOW.ARG-NOW @ OVER SFLOW.DEADLINE @ >= IF
        STREAMS-FLOW-S-TIMED-OUT SWAP
        _SFLOW-ROLLBACK-RESERVATION EXIT
    THEN
    DUP _SFLOW.ARG-GENERATION @ OVER SFLOW.GENERATION @ <> IF
        DROP STREAMS-FLOW-S-STALE EXIT
    THEN
    STREAMS-FLOW-S-CANCELLED SWAP _SFLOW-ROLLBACK-RESERVATION ;

