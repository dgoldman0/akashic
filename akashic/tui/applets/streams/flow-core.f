: _SFLOW-DERIVE-EGRESS-ID  ( flow -- )
    SHA3-256-BEGIN
    S" akashic.streams.egress.v1" SHA3-256-ADD
    DUP SFLOW.INGRESS-EVENT SEVT.EVENT-ID RID-SIZE SHA3-256-ADD
    DUP SFLOW.ID RID-SIZE SHA3-256-ADD
    DUP _SFLOW.OUTPUT-ID RID-SIZE SHA3-256-ADD
    SFLOW.EGRESS-EVENT SEVT.EVENT-ID SHA3-256-END ;

: _SFLOW-BUILD-EGRESS  ( flow -- status )
    DUP SFLOW.EGRESS-EVENT STREAMS-EVENT-INIT
        STREAMS-FLOW-S-OK <> IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP _SFLOW-DERIVE-EGRESS-ID
    DUP _SFLOW.OUTPUT-ID OVER SFLOW.EGRESS-EVENT SEVT.CONNECTOR-ID RID-COPY
    DUP SFLOW.ID OVER SFLOW.EGRESS-EVENT SEVT.FLOW-ID RID-COPY
    DUP SFLOW.INGRESS-EVENT SEVT.CORRELATION-ID
        OVER SFLOW.EGRESS-EVENT SEVT.CORRELATION-ID RID-COPY
    DUP SFLOW.INGRESS-EVENT SEVT.IDEMPOTENCY-ID
        OVER SFLOW.EGRESS-EVENT SEVT.IDEMPOTENCY-ID RID-COPY
    DUP SFLOW.ID OVER SFLOW.EGRESS-EVENT SEVT.ORIGIN-ID RID-COPY
    DUP _SFLOW.OUTPUT-ENDPOINT-ID
        OVER SFLOW.EGRESS-EVENT SEVT.DESTINATION-ID RID-COPY
    DUP _SFLOW.OUTPUT-REVISION @
        OVER SFLOW.EGRESS-EVENT SEVT.CONNECTOR-REVISION !
    STREAMS-EVENT-DIRECTION-EGRESS
        OVER SFLOW.EGRESS-EVENT SEVT.DIRECTION !
    DUP _SFLOW.OUTPUT-PROTOCOL @
        OVER SFLOW.EGRESS-EVENT SEVT.PROTOCOL !
    DUP SFLOW.OUTPUT-MEDIA @
        OVER SFLOW.EGRESS-EVENT SEVT.MEDIA !
    DUP SFLOW.INGRESS-EVENT SEVT.SEQUENCE @
        OVER SFLOW.EGRESS-EVENT SEVT.SEQUENCE !
    DUP _SFLOW.ARG-NOW @
        OVER SFLOW.EGRESS-EVENT SEVT.RECEIVED-MS !
    DUP SFLOW.EGRESS-PAYLOAD
    OVER SFLOW.TRANSFORM-RESULT STRR.OUTPUT-U @
    2 PICK SFLOW.EGRESS-EVENT STREAMS-EVENT-BORROW
        STREAMS-FLOW-S-OK <> IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    STREAMS-EVENT-OWNERSHIP-INLINE OVER SFLOW.EGRESS-EVENT SEVT.OWNERSHIP !
    DUP SFLOW.EGRESS-EVENT STREAMS-EVENT-SEAL
        STREAMS-FLOW-S-OK <> IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    _SEVT-STATE-INLINE OVER SFLOW.EGRESS-EVENT SEVT.STATE !
    DUP SFLOW.EGRESS-EVENT STREAMS-EVENT-SIZE
        2 PICK SFLOW.TRANSFORM-RESULT SHA3-256-HASH
    DROP STREAMS-FLOW-S-OK ;

: _SFLOW-TRANSFORM-FAIL
  ( status state effect reason detail error flow -- status )
    >R
    R@ _SFLOW.ARG-NOW @
    R@ SFLOW.INGRESS-ATTEMPT _SATT-TERMINAL!
    R> _SFLOW-MARK-TERMINAL ;

: _SFLOW-TRANSFORM-RESULT-FAIL
  ( status state effect reason flow -- status )
    >R
    R@ SFLOW.TRANSFORM-RESULT STRR.DETAIL @
    R@ SFLOW.TRANSFORM-RESULT STRR.ERROR @
    R> _SFLOW-TRANSFORM-FAIL ;

: _SFLOW-TRANSFORM-CALL  ( flow -- throw )
    ['] _SFLOW-TRANSFORM-BODY CATCH
    DUP IF NIP THEN ;

: _SFLOW-INGRESS-EXACT?  ( flow -- flag )
    DUP SFLOW.INGRESS-EVENT SEVT.PAYLOAD-A @
        OVER SFLOW.INGRESS-PAYLOAD <> IF DROP 0 EXIT THEN
    DUP SFLOW.INGRESS-EVENT SEVT.PAYLOAD-U @
        OVER SFLOW.INGRESS-ATTEMPT SATT.PAYLOAD-U @ <> IF
        DROP 0 EXIT
    THEN
    DUP SFLOW.INGRESS-EVENT _SEVT-PAYLOAD-EXACT?
    SWAP >R
    R@ SFLOW.INGRESS-EVENT STREAMS-EVENT-SIZE
        R@ SFLOW.CONNECTOR-RESULT SHA3-256-HASH-COMPARE
    R> DROP AND ;

: _SFLOW-STEP-TRANSFORM  ( flow -- status )
    DUP _SFLOW.ARG-NOW @ OVER SFLOW.INGRESS-ATTEMPT _SATT-ACTIVE!
    DUP SFLOW.TRANSFORM-RESULT STREAMS-TRANSFORM-RESULT-INIT
    DUP _SFLOW-TRANSFORM-CALL
    DUP IF
        OVER SFLOW.TRANSFORM-RESULT STRR.ERROR !
        >R
        STREAMS-FLOW-S-FAILED
        STREAMS-ATTEMPT-STATE-FAILED-BEFORE
        STREAMS-EFFECT-NOT-APPLIED
        STREAMS-ATTEMPT-REASON-CALLBACK
        R> _SFLOW-TRANSFORM-RESULT-FAIL EXIT
    THEN
    DROP
    DUP _SFLOW-INGRESS-EXACT? 0= IF
        STREAMS-FLOW-E-PAYLOAD-CHANGED
            OVER SFLOW.TRANSFORM-RESULT STRR.ERROR !
        >R
        STREAMS-FLOW-S-FAILED
        STREAMS-ATTEMPT-STATE-FAILED-BEFORE
        STREAMS-EFFECT-NOT-APPLIED
        STREAMS-ATTEMPT-REASON-CALLBACK
        R> _SFLOW-TRANSFORM-RESULT-FAIL EXIT
    THEN
    DUP SFLOW.TRANSFORM-RESULT STREAMS-TRANSFORM-RESULT-VALID? 0= IF
        STREAMS-FLOW-E-INVALID-RESULT
            OVER SFLOW.TRANSFORM-RESULT STRR.ERROR !
        >R
        STREAMS-FLOW-S-FAILED
        STREAMS-ATTEMPT-STATE-FAILED-BEFORE
        STREAMS-EFFECT-NOT-APPLIED
        STREAMS-ATTEMPT-REASON-CAPACITY
        R> _SFLOW-TRANSFORM-RESULT-FAIL EXIT
    THEN
    DUP SFLOW.TRANSFORM-RESULT STRR.COMPLETION @
    DUP STREAMS-TRANSFORM-COMPLETION-OK = IF
        DROP
        DUP _SFLOW-BUILD-EGRESS STREAMS-FLOW-S-OK <> IF
            STREAMS-FLOW-E-INVALID-RESULT
                OVER SFLOW.TRANSFORM-RESULT STRR.ERROR !
            >R
            STREAMS-FLOW-S-FAILED
            STREAMS-ATTEMPT-STATE-FAILED-BEFORE
            STREAMS-EFFECT-NOT-APPLIED
            STREAMS-ATTEMPT-REASON-CAPACITY
            R> _SFLOW-TRANSFORM-RESULT-FAIL EXIT
        THEN
        DUP >R
        STREAMS-ATTEMPT-STATE-ACKNOWLEDGED
        STREAMS-EFFECT-APPLIED
        STREAMS-ATTEMPT-REASON-NONE 0 0
        R@ _SFLOW.ARG-NOW @
        R@ SFLOW.INGRESS-ATTEMPT _SATT-TERMINAL!
        R@ SFLOW.EGRESS-EVENT
        R@ SFLOW.GENERATION @
        R@ _SFLOW.ARG-NOW @
        STREAMS-EVENT-DIRECTION-EGRESS
        R@ SFLOW.EGRESS-ATTEMPT _SATT-ACCEPT
        R> DROP
        STREAMS-FLOW-STATE-OUTPUT-READY OVER SFLOW.STATE !
        STREAMS-FLOW-S-ACKNOWLEDGED OVER SFLOW.LAST-STATUS !
        DROP STREAMS-FLOW-S-ACKNOWLEDGED EXIT
    THEN
    DUP STREAMS-TRANSFORM-COMPLETION-CANCELLED = IF
        DROP
        >R
        STREAMS-FLOW-S-CANCELLED
        STREAMS-ATTEMPT-STATE-CANCELLED
        STREAMS-EFFECT-NOT-APPLIED
        STREAMS-ATTEMPT-REASON-TRANSFORM
        R> _SFLOW-TRANSFORM-RESULT-FAIL EXIT
    THEN
    STREAMS-TRANSFORM-COMPLETION-STALE = IF
        >R
        STREAMS-FLOW-S-STALE
        STREAMS-ATTEMPT-STATE-STALE
        STREAMS-EFFECT-NOT-APPLIED
        STREAMS-ATTEMPT-REASON-STALE
        R> _SFLOW-TRANSFORM-RESULT-FAIL EXIT
    THEN
    >R
    STREAMS-FLOW-S-FAILED
    STREAMS-ATTEMPT-STATE-FAILED-BEFORE
    STREAMS-EFFECT-NOT-APPLIED
    STREAMS-ATTEMPT-REASON-TRANSFORM
    R> _SFLOW-TRANSFORM-RESULT-FAIL ;

