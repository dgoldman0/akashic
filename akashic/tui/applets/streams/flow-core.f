        2DROP 0 EXIT
    THEN
    >R
    DUP SFLOW.INGRESS-CARRIER DUP STREAMS-PAYLOAD-BOUND? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    DUP SPAY.PROFILE @ R@ <>
    OVER SPAY.BYTE-CAP @ R@ STREAMS-RUNTIME-INGRESS-CAPACITY <> OR IF
        2DROP R> DROP 0 EXIT
    THEN
    R@ STREAMS-RUNTIME-INGRESS-SEGMENTS
        STREAMS-RUNTIME-SEGMENT-BYTES
        2 PICK STREAMS-PAYLOAD-UNIFORM-GEOMETRY? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    DROP
    DUP SFLOW.EGRESS-CARRIER DUP STREAMS-PAYLOAD-BOUND? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    DUP SPAY.PROFILE @ R@ <>
    OVER SPAY.BYTE-CAP @ R@ STREAMS-RUNTIME-EGRESS-CAPACITY <> OR IF
        2DROP R> DROP 0 EXIT
    THEN
    R@ STREAMS-RUNTIME-EGRESS-SEGMENTS
        STREAMS-RUNTIME-SEGMENT-BYTES
        2 PICK STREAMS-PAYLOAD-UNIFORM-GEOMETRY? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    DROP
    DUP SFLOW.INGRESS-CARRIER OVER SFLOW.EGRESS-CARRIER = IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.OPERATION-CAPACITY
        R@ STREAMS-RUNTIME-OPERATION-CAPACITY <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.OPERATION 0= IF DROP R> DROP 0 EXIT THEN
    DUP SFLOW.OPERATION OVER SFLOW.OPERATION-CAPACITY
        MSPAN-NONWRAPPING? 0= IF DROP R> DROP 0 EXIT THEN
    DUP SFLOW.BINDING-EPOCH @ 1 < IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-CONFIGURING <> IF
        DUP SFLOW.INGRESS-CARRIER SPAY.BINDING-EPOCH @
            OVER SFLOW.INGRESS-CARRIER-EPOCH @ <> IF
            DROP R> DROP 0 EXIT
        THEN
        DUP SFLOW.EGRESS-CARRIER SPAY.BINDING-EPOCH @
            OVER SFLOW.EGRESS-CARRIER-EPOCH @ <> IF
            DROP R> DROP 0 EXIT
        THEN
    THEN
    DROP R> DROP -1 ;

: _SFLOW-CONFIG?  ( flow -- flag )
    DUP SFLOW.ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SFLOW.REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP SFLOW.TIMEOUT-MS @ DUP 1 <
        SWAP STREAMS-FLOW-TIMEOUT-MAX-MS > OR IF DROP 0 EXIT THEN
    DUP SFLOW.OUTPUT-MEDIA @ 0> 0= IF DROP 0 EXIT THEN
    DUP SFLOW.TRANSFORM-XT @ 0= IF DROP 0 EXIT THEN
    DUP _SFLOW-WORKSPACE-CONFIG? 0= IF DROP 0 EXIT THEN
    DUP SFLOW.INPUT-CONNECTOR @ DUP STREAMS-CONNECTOR-VALID? 0= IF
        2DROP 0 EXIT
    THEN
    _SFLOW-INPUT-DIRECTION? 0= IF DROP 0 EXIT THEN
    DUP SFLOW.OUTPUT-CONNECTOR @ DUP STREAMS-CONNECTOR-VALID? 0= IF
        2DROP 0 EXIT
    THEN
    DUP _SFLOW-OUTPUT-DIRECTION? 0= IF 2DROP 0 EXIT THEN
    SCON.OP-SIZE @ OVER SFLOW.OPERATION-CAPACITY <=
    NIP ;

: _SFLOW-SNAPSHOT  ( flow -- )
    DUP SFLOW.INPUT-CONNECTOR @ >R
    R@ SCON.ID OVER _SFLOW.INPUT-ID RID-COPY
    R@ SCON.ENDPOINT-ID OVER _SFLOW.INPUT-ENDPOINT-ID RID-COPY
    R@ SCON.REVISION @ OVER _SFLOW.INPUT-REVISION !
    R> SCON.PROTOCOL @ OVER _SFLOW.INPUT-PROTOCOL !
    DUP SFLOW.OUTPUT-CONNECTOR @ >R
    R@ SCON.ID OVER _SFLOW.OUTPUT-ID RID-COPY
    R@ SCON.ENDPOINT-ID OVER _SFLOW.OUTPUT-ENDPOINT-ID RID-COPY
    R@ SCON.REVISION @ OVER _SFLOW.OUTPUT-REVISION !
    R@ SCON.PROTOCOL @ OVER _SFLOW.OUTPUT-PROTOCOL !
    R@ SCON.CONTEXT @ OVER _SFLOW.OUTPUT-CONTEXT !
    R@ SCON.OP-SIZE @ OVER _SFLOW.OUTPUT-OP-SIZE !
    R@ SCON.START-XT @ OVER _SFLOW.OUTPUT-START-XT !
    R@ SCON.POLL-XT @ OVER _SFLOW.OUTPUT-POLL-XT !
    R@ SCON.CANCEL-XT @ OVER _SFLOW.OUTPUT-CANCEL-XT !
    R> SCON.CLEANUP-XT @ OVER _SFLOW.OUTPUT-CLEANUP-XT !
    DUP SFLOW.INGRESS-CARRIER SPAY.BINDING-EPOCH @
        OVER SFLOW.INGRESS-CARRIER-EPOCH !
    DUP SFLOW.EGRESS-CARRIER SPAY.BINDING-EPOCH @
        SWAP SFLOW.EGRESS-CARRIER-EPOCH ! ;

: _SFLOW-INPUT-CURRENT?  ( flow -- flag )
    DUP SFLOW.INPUT-CONNECTOR @ DUP STREAMS-CONNECTOR-VALID? 0= IF
        2DROP 0 EXIT
    THEN
    DUP SCON.ID 2 PICK _SFLOW.INPUT-ID RID=
    OVER SCON.ENDPOINT-ID 3 PICK _SFLOW.INPUT-ENDPOINT-ID RID= AND
    OVER SCON.REVISION @ 3 PICK _SFLOW.INPUT-REVISION @ = AND
    OVER SCON.PROTOCOL @ 3 PICK _SFLOW.INPUT-PROTOCOL @ = AND
    NIP NIP ;

: _SFLOW-OUTPUT-CURRENT?  ( flow -- flag )
    DUP SFLOW.OUTPUT-CONNECTOR @ DUP STREAMS-CONNECTOR-VALID? 0= IF
        2DROP 0 EXIT
    THEN
    DUP SCON.ID 2 PICK _SFLOW.OUTPUT-ID RID=
    OVER SCON.ENDPOINT-ID 3 PICK _SFLOW.OUTPUT-ENDPOINT-ID RID= AND
    OVER SCON.REVISION @ 3 PICK _SFLOW.OUTPUT-REVISION @ = AND
    OVER SCON.PROTOCOL @ 3 PICK _SFLOW.OUTPUT-PROTOCOL @ = AND
    OVER SCON.CONTEXT @ 3 PICK _SFLOW.OUTPUT-CONTEXT @ = AND
    OVER SCON.OP-SIZE @ 3 PICK _SFLOW.OUTPUT-OP-SIZE @ = AND
    OVER SCON.START-XT @ 3 PICK _SFLOW.OUTPUT-START-XT @ = AND
    OVER SCON.POLL-XT @ 3 PICK _SFLOW.OUTPUT-POLL-XT @ = AND
    OVER SCON.CANCEL-XT @ 3 PICK _SFLOW.OUTPUT-CANCEL-XT @ = AND
    OVER SCON.CLEANUP-XT @ 3 PICK _SFLOW.OUTPUT-CLEANUP-XT @ = AND
    NIP NIP ;

: _SFLOW-CARRIER-RESETTABLE?  ( carrier -- flag )
    DUP STREAMS-PAYLOAD-BOUND? 0= IF DROP 0 EXIT THEN
    DUP SPAY.RELEASE-XT @ IF DROP 0 EXIT THEN
    DUP SPAY.STATE @ DUP STREAMS-PAYLOAD-STATE-READY =
    OVER STREAMS-PAYLOAD-STATE-CLOSED = OR IF
        2DROP -1 EXIT
    THEN
    STREAMS-PAYLOAD-STATE-BUILDING = IF
        SPAY.BYTE-U @ 0= EXIT
    THEN
    DROP 0 ;

: _SFLOW-RESET-CARRIER  ( carrier -- status )
    DUP SPAY.GENERATION @ SWAP STREAMS-PAYLOAD-RESET
    NIP
    DUP STREAMS-PAYLOAD-S-OK = IF DROP STREAMS-FLOW-S-OK EXIT THEN
    STREAMS-PAYLOAD-S-CAPACITY = IF
        STREAMS-FLOW-S-CAPACITY
    ELSE
        STREAMS-FLOW-S-INVALID
    THEN ;

: _SFLOW-CLOSE-CARRIER  ( carrier -- status )
    DUP SPAY.GENERATION @ SWAP STREAMS-PAYLOAD-CLOSE
    DUP STREAMS-PAYLOAD-S-OK = IF DROP STREAMS-FLOW-S-OK EXIT THEN
    DROP STREAMS-FLOW-S-CLEANUP ;

: _SFLOW-CLEAR-SLOT  ( flow -- status )
    DUP SFLOW.INGRESS-CARRIER _SFLOW-CARRIER-RESETTABLE? 0= IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.EGRESS-CARRIER _SFLOW-CARRIER-RESETTABLE? 0= IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.INGRESS-CARRIER _SFLOW-RESET-CARRIER
    DUP STREAMS-FLOW-S-OK <> IF NIP EXIT THEN DROP
    DUP SFLOW.EGRESS-CARRIER _SFLOW-RESET-CARRIER
    DUP STREAMS-FLOW-S-OK <> IF NIP EXIT THEN DROP
    DUP SFLOW.INGRESS-EVENT STREAMS-EVENT-SIZE 0 FILL
    DUP SFLOW.EGRESS-EVENT STREAMS-EVENT-SIZE 0 FILL
    STREAMS-EVENT-DIRECTION-INGRESS OVER SFLOW.INGRESS-ATTEMPT _SATT-INIT
    STREAMS-EVENT-DIRECTION-EGRESS OVER SFLOW.EGRESS-ATTEMPT _SATT-INIT
    DUP SFLOW.OPERATION OVER SFLOW.OPERATION-CAPACITY 0 FILL
    DUP SFLOW.TRANSFORM-RESULT STREAMS-TRANSFORM-RESULT-INIT
    DUP SFLOW.CONNECTOR-RESULT STREAMS-CONNECTOR-RESULT-INIT
    0 OVER _SFLOW.OUTPUT-STARTED !
    0 SWAP _SFLOW.CLEANUP-DONE !
    STREAMS-FLOW-S-OK ;

: _SFLOW-CONNECTOR-WORKSPACE-DISJOINT?  ( connector flow -- flag )
    >R
    DUP STREAMS-CONNECTOR-SIZE R@ SFLOW.INGRESS-CARRIER
        STREAMS-PAYLOAD-SPAN-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP STREAMS-CONNECTOR-SIZE R@ SFLOW.EGRESS-CARRIER
        STREAMS-PAYLOAD-SPAN-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP STREAMS-CONNECTOR-SIZE
        R@ SFLOW.OPERATION R@ SFLOW.OPERATION-CAPACITY
        MSPAN-OVERLAP? IF DROP R> DROP 0 EXIT THEN
    DROP R> DROP -1 ;

: _SFLOW-ROLLBACK-SLOT  ( flow -- status )
    DUP SFLOW.INGRESS-CARRIER _SFLOW-CLOSE-CARRIER
    OVER SFLOW.EGRESS-CARRIER _SFLOW-CLOSE-CARRIER
    OR IF DROP STREAMS-FLOW-S-CLEANUP EXIT THEN
    _SFLOW-CLEAR-SLOT ;

: STREAMS-FLOW-SEAL  ( flow -- status )
    DUP _SFLOW-HEADER? 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-CONFIGURING <> IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SFLOW-CONFIG? 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP SFLOW.INPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
        2 PICK STREAMS-FLOW-SIZE MSPAN-OVERLAP? IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.OUTPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
        2 PICK STREAMS-FLOW-SIZE MSPAN-OVERLAP? IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.INPUT-CONNECTOR @ OVER
        _SFLOW-CONNECTOR-WORKSPACE-DISJOINT? 0= IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.OUTPUT-CONNECTOR @ OVER
        _SFLOW-CONNECTOR-WORKSPACE-DISJOINT? 0= IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SFLOW-SNAPSHOT
    DUP _SFLOW-CLEAR-SLOT DUP STREAMS-FLOW-S-OK <> IF
        NIP EXIT
    THEN
    DROP
    STREAMS-FLOW-STATE-IDLE OVER SFLOW.STATE !
    STREAMS-FLOW-S-OK OVER SFLOW.LAST-STATUS !
    DROP STREAMS-FLOW-S-OK ;

: _SFLOW-EGRESS-STAGING-SEAL!  ( flow -- )
    SHA3-256-BEGIN
    DUP SFLOW.EGRESS-EVENT STREAMS-EVENT-SIZE SHA3-256-ADD
    DUP SFLOW.TRANSFORM-RESULT SHA3-256-LEN SHA3-256-ADD
    SFLOW.CONNECTOR-RESULT SHA3-256-END ;

: _SFLOW-EGRESS-STAGING-SEAL?  ( flow -- flag )
    SHA3-256-BEGIN
    DUP SFLOW.EGRESS-EVENT STREAMS-EVENT-SIZE SHA3-256-ADD
    DUP SFLOW.TRANSFORM-RESULT SHA3-256-LEN SHA3-256-ADD
    SFLOW.CONNECTOR-RESULT SHA3-256-END-COMPARE ;

: _SFLOW-RECEIVING?  ( flow -- flag )
    DUP SFLOW.GENERATION @ 0> 0= IF DROP 0 EXIT THEN
    DUP SFLOW.LAST-NOW @ 0< IF DROP 0 EXIT THEN
    DUP SFLOW.DEADLINE @ OVER SFLOW.LAST-NOW @ < IF DROP 0 EXIT THEN
    DUP SFLOW.INGRESS-CARRIER SPAY.STATE @
        STREAMS-PAYLOAD-STATE-BUILDING <> IF DROP 0 EXIT THEN
    DUP SFLOW.INGRESS-EVENT DUP _SEVT-HEADER? 0= IF
        2DROP 0 EXIT
    THEN
    DUP SEVT.STATE @ _SEVT-STATE-BUILDING <> IF
        2DROP 0 EXIT
    THEN
    DUP _SEVT-METADATA-CONTENT? 0= IF 2DROP 0 EXIT THEN
    DUP SEVT.CONNECTOR-ID 2 PICK _SFLOW.INPUT-ID RID=
    OVER SEVT.FLOW-ID 3 PICK SFLOW.ID RID= AND
    OVER SEVT.ORIGIN-ID 3 PICK _SFLOW.INPUT-ENDPOINT-ID RID= AND
    OVER SEVT.DESTINATION-ID 3 PICK SFLOW.ID RID= AND
    OVER SEVT.CONNECTOR-REVISION @
        3 PICK _SFLOW.INPUT-REVISION @ = AND
    OVER SEVT.DIRECTION @ STREAMS-EVENT-DIRECTION-INGRESS = AND
    OVER SEVT.PROTOCOL @ 3 PICK _SFLOW.INPUT-PROTOCOL @ = AND
    OVER SEVT.PAYLOAD-A @ 3 PICK SFLOW.INGRESS-CARRIER = AND
    OVER SEVT.OWNERSHIP @ STREAMS-EVENT-OWNERSHIP-CARRIER = AND
    OVER SEVT.RELEASE-XT @ 0= AND
    OVER SEVT.RELEASE-CONTEXT @
        3 PICK SFLOW.INGRESS-CARRIER-EPOCH @ = AND
    OVER SEVT.CLEANUP-ERROR @ 0= AND
    OVER SEVT.PAYLOAD-DIGEST SHA3-256-LEN _SFLOW-ZERO? AND
    0= IF 2DROP 0 EXIT THEN
    DUP SEVT.PAYLOAD-U @ 0< IF 2DROP 0 EXIT THEN
    DUP SEVT.PAYLOAD-U @ 2 PICK SFLOW.INGRESS-CARRIER SPAY.BYTE-CAP @ >
        IF 2DROP 0 EXIT THEN
    SEVT.PAYLOAD-U @ OVER SFLOW.INGRESS-CARRIER SPAY.BYTE-U @ <
        IF DROP 0 EXIT THEN
    DUP SFLOW.INGRESS-ATTEMPT DUP STREAMS-ATTEMPT-VALID?
        SWAP SATT.STATE @ STREAMS-ATTEMPT-STATE-EMPTY = AND
    OVER SFLOW.EGRESS-ATTEMPT DUP STREAMS-ATTEMPT-VALID?
        SWAP SATT.STATE @ STREAMS-ATTEMPT-STATE-EMPTY = AND
    ROT DROP AND ;

: _SFLOW-EGRESS-STAGING?  ( flow -- flag )
    DUP SFLOW.GENERATION @ 0> 0= IF DROP 0 EXIT THEN
    DUP SFLOW.LAST-NOW @ 0< IF DROP 0 EXIT THEN
    DUP SFLOW.DEADLINE @ OVER SFLOW.LAST-NOW @ < IF DROP 0 EXIT THEN
    DUP SFLOW.INGRESS-CARRIER SPAY.STATE @
        STREAMS-PAYLOAD-STATE-BUILDING <> IF DROP 0 EXIT THEN
    DUP SFLOW.INGRESS-CARRIER SPAY.BYTE-U @ IF DROP 0 EXIT THEN
    DUP SFLOW.EGRESS-CARRIER SPAY.STATE @
        STREAMS-PAYLOAD-STATE-BUILDING <> IF DROP 0 EXIT THEN
    DUP SFLOW.EGRESS-EVENT DUP _SEVT-HEADER? 0= IF
        2DROP 0 EXIT
    THEN
    DUP SEVT.STATE @ _SEVT-STATE-BUILDING <> IF
        2DROP 0 EXIT
    THEN
    DUP _SEVT-METADATA-CONTENT? 0= IF 2DROP 0 EXIT THEN
    DUP SEVT.CONNECTOR-ID 2 PICK _SFLOW.OUTPUT-ID RID=
    OVER SEVT.FLOW-ID 3 PICK SFLOW.ID RID= AND
    OVER SEVT.ORIGIN-ID RID-PRESENT? AND
    OVER SEVT.DESTINATION-ID 3 PICK _SFLOW.OUTPUT-ENDPOINT-ID RID= AND
    OVER SEVT.CONNECTOR-REVISION @
        3 PICK _SFLOW.OUTPUT-REVISION @ = AND
    OVER SEVT.DIRECTION @ STREAMS-EVENT-DIRECTION-EGRESS = AND
    OVER SEVT.PROTOCOL @ 3 PICK _SFLOW.OUTPUT-PROTOCOL @ = AND
    OVER SEVT.MEDIA @ 3 PICK SFLOW.OUTPUT-MEDIA @ = AND
    OVER SEVT.PAYLOAD-A @ 3 PICK SFLOW.EGRESS-CARRIER = AND
    OVER SEVT.OWNERSHIP @ STREAMS-EVENT-OWNERSHIP-CARRIER = AND
    OVER SEVT.RELEASE-XT @ 0= AND
    OVER SEVT.RELEASE-CONTEXT @
        3 PICK SFLOW.EGRESS-CARRIER-EPOCH @ = AND
    OVER SEVT.CLEANUP-ERROR @ 0= AND
    OVER SEVT.PAYLOAD-DIGEST SHA3-256-LEN _SFLOW-ZERO? AND
    0= IF 2DROP 0 EXIT THEN
    DUP SEVT.PAYLOAD-U @ 0< IF 2DROP 0 EXIT THEN
    DUP SEVT.PAYLOAD-U @ 2 PICK SFLOW.EGRESS-CARRIER SPAY.BYTE-CAP @ >
        IF 2DROP 0 EXIT THEN
    SEVT.PAYLOAD-U @ OVER SFLOW.EGRESS-CARRIER SPAY.BYTE-U @ <
        IF DROP 0 EXIT THEN
    DUP SFLOW.INGRESS-EVENT STREAMS-EVENT-SIZE _SFLOW-ZERO? 0= IF
        DROP 0 EXIT
    THEN
    DUP SFLOW.TRANSFORM-RESULT RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP _SFLOW-EGRESS-STAGING-SEAL? 0= IF DROP 0 EXIT THEN
    DUP SFLOW.INGRESS-ATTEMPT DUP STREAMS-ATTEMPT-VALID?
        SWAP SATT.STATE @ STREAMS-ATTEMPT-STATE-EMPTY = AND
    OVER SFLOW.EGRESS-ATTEMPT DUP STREAMS-ATTEMPT-VALID?
        SWAP SATT.STATE @ STREAMS-ATTEMPT-STATE-EMPTY = AND
    ROT DROP AND ;

: STREAMS-FLOW-VALID?  ( flow -- flag )
    DUP _SFLOW-HEADER? 0= IF DROP 0 EXIT THEN
    DUP SFLOW.STATE @ DUP STREAMS-FLOW-STATE-IDLE <
        SWAP STREAMS-FLOW-STATE-TERMINAL > OR IF DROP 0 EXIT THEN
    DUP SFLOW.BUSY @ DUP 0<> SWAP -1 <> AND IF DROP 0 EXIT THEN
    DUP _SFLOW-CONFIG? 0= IF DROP 0 EXIT THEN
    DUP SFLOW.GENERATION @ 0< IF DROP 0 EXIT THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-IDLE = IF
        DUP SFLOW.INGRESS-ATTEMPT STREAMS-ATTEMPT-VALID?
        SWAP SFLOW.EGRESS-ATTEMPT STREAMS-ATTEMPT-VALID? AND EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-RECEIVING = IF
        _SFLOW-RECEIVING? EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-EGRESS-STAGING = IF
        _SFLOW-EGRESS-STAGING? EXIT
    THEN
    DUP SFLOW.INGRESS-ATTEMPT STREAMS-ATTEMPT-VALID?
    SWAP SFLOW.EGRESS-ATTEMPT STREAMS-ATTEMPT-VALID? AND ;

: _SFLOW-CLEAR-ARGS  ( flow -- )
    0 OVER _SFLOW.ARG-EVENT !
    0 OVER _SFLOW.ARG-CONNECTOR !
    0 OVER _SFLOW.ARG-EXPECTED !
    0 OVER _SFLOW.ARG-NOW !
    0 SWAP _SFLOW.ARG-GENERATION ! ;

: _SFLOW-CLEAR-WORKSPACE  ( flow -- )
    0 OVER SFLOW.PROFILE !
    0 OVER _SFLOW.INGRESS-CARRIER-A !
    0 OVER _SFLOW.EGRESS-CARRIER-A !
    0 OVER _SFLOW.OPERATION-A !
    0 OVER _SFLOW.OPERATION-CAPACITY-A !
    0 OVER SFLOW.INGRESS-CARRIER-EPOCH !
    0 SWAP SFLOW.EGRESS-CARRIER-EPOCH ! ;

: _SFLOW-WORKSPACE-DISJOINT?  ( flow -- flag )
    DUP STREAMS-FLOW-SIZE 2 PICK SFLOW.INGRESS-CARRIER
        STREAMS-PAYLOAD-SPAN-DISJOINT? 0= IF DROP 0 EXIT THEN
    DUP STREAMS-FLOW-SIZE 2 PICK SFLOW.EGRESS-CARRIER
        STREAMS-PAYLOAD-SPAN-DISJOINT? 0= IF DROP 0 EXIT THEN
    DUP SFLOW.OPERATION OVER SFLOW.OPERATION-CAPACITY
        2 PICK STREAMS-FLOW-SIZE MSPAN-OVERLAP? IF DROP 0 EXIT THEN
    DUP SFLOW.OPERATION OVER SFLOW.OPERATION-CAPACITY
        2 PICK SFLOW.INGRESS-CARRIER
        STREAMS-PAYLOAD-SPAN-DISJOINT? 0= IF DROP 0 EXIT THEN
    DUP SFLOW.OPERATION OVER SFLOW.OPERATION-CAPACITY
        2 PICK SFLOW.EGRESS-CARRIER
        STREAMS-PAYLOAD-SPAN-DISJOINT? 0= IF DROP 0 EXIT THEN
    DUP SFLOW.INGRESS-CARRIER OVER SFLOW.EGRESS-CARRIER
        STREAMS-PAYLOAD-DISJOINT? 0= IF DROP 0 EXIT THEN
    DROP -1 ;

: STREAMS-FLOW-WORKSPACE!
  ( profile ingress-carrier egress-carrier operation-a operation-cap flow -- status )
    >R
    R@ _SFLOW-HEADER? 0= IF
        2DROP 2DROP DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ SFLOW.STATE @ STREAMS-FLOW-STATE-CONFIGURING <>
    R@ SFLOW.BUSY @ 0<> OR IF
        2DROP 2DROP DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ _SFLOW.ARG-GENERATION !
    R@ _SFLOW.ARG-NOW !
    R@ _SFLOW.ARG-CONNECTOR !
    R@ _SFLOW.ARG-EVENT !
    R@ _SFLOW.ARG-EXPECTED !
    R@ SFLOW.PROFILE @
    R@ _SFLOW.INGRESS-CARRIER-A @ OR
    R@ _SFLOW.EGRESS-CARRIER-A @ OR
    R@ _SFLOW.OPERATION-A @ OR
    R@ _SFLOW.OPERATION-CAPACITY-A @ OR IF
        R@ _SFLOW-CLEAR-ARGS
        R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ _SFLOW.ARG-EXPECTED @ R@ SFLOW.PROFILE !
    R@ _SFLOW.ARG-EVENT @ R@ _SFLOW.INGRESS-CARRIER-A !
    R@ _SFLOW.ARG-CONNECTOR @ R@ _SFLOW.EGRESS-CARRIER-A !
    R@ _SFLOW.ARG-NOW @ R@ _SFLOW.OPERATION-A !
    R@ _SFLOW.ARG-GENERATION @ R@ _SFLOW.OPERATION-CAPACITY-A !
    R@ _SFLOW-WORKSPACE-CONFIG?
    R@ _SFLOW-WORKSPACE-DISJOINT? AND 0= IF
        R@ _SFLOW-CLEAR-WORKSPACE
        R@ _SFLOW-CLEAR-ARGS
        R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ SFLOW.OPERATION R@ SFLOW.OPERATION-CAPACITY 0 FILL
    R@ _SFLOW-CLEAR-ARGS
    R> DROP STREAMS-FLOW-S-OK ;

: _SFLOW-LEAVE  ( status flow -- status )
    DUP _SFLOW-CLEAR-ARGS
    0 SWAP SFLOW.BUSY ! ;

