        OVER SATT.FINISHED-MS @ -1 = AND
        OVER SATT.EVENT-ID RID-ZERO? AND
        SWAP SATT.CONNECTOR-ID RID-ZERO? AND EXIT
    THEN
    DUP SATT.GENERATION @ 0> 0= IF DROP 0 EXIT THEN
    DUP SATT.ACCEPTED-MS @ 0< IF DROP 0 EXIT THEN
