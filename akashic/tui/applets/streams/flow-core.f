    >R
    R@ SFLOW.EGRESS-EVENT
    R@ SFLOW.OPERATION
    R@ _SFLOW.OUTPUT-CONTEXT @
    R@ SFLOW.CONNECTOR-RESULT
    R> _SFLOW.OUTPUT-CANCEL-XT @ EXECUTE ;

: _SFLOW-OUTPUT-CLEANUP-BODY  ( flow -- )
