\ =====================================================================
\ flow-core.f - bounded storage-free Streams connector/event/flow core
\ =====================================================================
\ SR1 deliberately has no VFS, persistence, network, web, applet, source,
\ observation, or repository dependency.  Every mutable byte belongs to a
\ caller-supplied connector, event, or flow descriptor.  One flow owns one
\ admission slot: an occupied or terminal slot refuses another event until
\ its exact generation is retired.
\
\ Connector callback stack effects:
\   TRANSFORM  ( ingress-event output-a output-cap context result -- )
\   START      ( egress-event operation context result -- )
\   POLL       ( egress-event operation context result -- )
\   CANCEL     ( egress-event operation context result -- )
\   CLEANUP    ( egress-event operation context -- error )
\
\ Callbacks borrow their event and payload for the duration of the call.
\ They must not retain or mutate them.  START/POLL/CANCEL report completion
\ separately from effect truth.  A throw or malformed result after START may
\ have begun is therefore INDETERMINATE, never silently "not sent".
\ =====================================================================

