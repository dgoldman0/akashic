: STREAMS-EVENT-VALID?  ( event -- flag )
    DUP _SEVT-HEADER? 0= IF DROP 0 EXIT THEN
    DUP SEVT.STATE @ DUP _SEVT-STATE-OPEN =
        OVER _SEVT-STATE-INLINE = OR IF
        DROP DUP _SEVT-CONFIG? IF _SEVT-PAYLOAD-EXACT? ELSE DROP 0 THEN
        EXIT
    THEN
    DUP _SEVT-STATE-CLOSED =
    OVER _SEVT-STATE-CLEANUP-FAILED = OR
    SWAP _SEVT-STATE-EXPIRED = OR IF
        DUP _SEVT-IDENTITY? 0= IF DROP 0 EXIT THEN
        DUP SEVT.PAYLOAD-A @ 0=
        OVER SEVT.PAYLOAD-U @ DUP 0<
            SWAP STREAMS-FLOW-PAYLOAD-MAX <= AND AND
        OVER SEVT.RELEASE-XT @ 0= AND
        OVER SEVT.RELEASE-CONTEXT @ 0= AND
        OVER SEVT.RESERVED 8 _SFLOW-ZERO? AND
        OVER SEVT.STATE @ _SEVT-STATE-CLEANUP-FAILED =
        IF OVER SEVT.CLEANUP-ERROR @ 0<> AND ELSE
            OVER SEVT.CLEANUP-ERROR @ 0= AND
        THEN
        NIP EXIT
    THEN
    DROP 0 ;

: STREAMS-EVENT-SEAL  ( event -- status )
    DUP _SEVT-HEADER? 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP SEVT.STATE @ _SEVT-STATE-BUILDING <> IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SEVT-CONFIG? 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP SEVT.PAYLOAD-A @ OVER SEVT.PAYLOAD-U @
        2 PICK SEVT.PAYLOAD-DIGEST SHA3-256-HASH
    _SEVT-STATE-OPEN SWAP SEVT.STATE !
    STREAMS-FLOW-S-OK ;

: _SEVT-CLOSE-BODY  ( event -- )
    >R
    R@ SEVT.PAYLOAD-A @
    R@ SEVT.PAYLOAD-U @
    R@ SEVT.RELEASE-CONTEXT @
    R@ SEVT.RELEASE-XT @ EXECUTE
    R> SEVT.CLEANUP-ERROR ! ;

: _SEVT-CLOSE-CALL  ( event -- throw )
    ['] _SEVT-CLOSE-BODY CATCH
    DUP IF NIP THEN ;

: _SEVT-CLEAR-LIVE-POINTERS  ( event -- )
    0 OVER SEVT.PAYLOAD-A !
    0 OVER SEVT.RELEASE-XT !
    0 SWAP SEVT.RELEASE-CONTEXT ! ;

: STREAMS-EVENT-CLOSE  ( event -- status )
    DUP _SEVT-HEADER? 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP SEVT.STATE @ _SEVT-STATE-CLOSED = IF
        DROP STREAMS-FLOW-S-OK EXIT
    THEN
    DUP SEVT.STATE @ _SEVT-STATE-CLEANUP-FAILED = IF
        DROP STREAMS-FLOW-S-CLEANUP EXIT
    THEN
    DUP SEVT.STATE @ _SEVT-STATE-OPEN <> IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SEVT-CONFIG? 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    _SEVT-STATE-CLOSING OVER SEVT.STATE !
    0 OVER SEVT.CLEANUP-ERROR !
    DUP SEVT.OWNERSHIP @ STREAMS-EVENT-OWNERSHIP-OWNED = IF
        DUP _SEVT-CLOSE-CALL
        DUP IF OVER SEVT.CLEANUP-ERROR ! ELSE DROP THEN
    THEN
    DUP _SEVT-CLEAR-LIVE-POINTERS
    DUP SEVT.CLEANUP-ERROR @ IF
        _SEVT-STATE-CLEANUP-FAILED SWAP SEVT.STATE !
        STREAMS-FLOW-S-CLEANUP
    ELSE
        _SEVT-STATE-CLOSED SWAP SEVT.STATE !
        STREAMS-FLOW-S-OK
    THEN ;

