: _SATT-ACTIVE!  ( now attempt -- )
    STREAMS-ATTEMPT-STATE-ACTIVE OVER SATT.STATE !
    SWAP OVER SATT.STARTED-MS !
    DROP ;

: _SATT-TERMINAL!
  ( state effect reason detail error now attempt -- )
    >R
    R@ SATT.FINISHED-MS !
    R@ SATT.ERROR !
    R@ SATT.DETAIL !
    R@ SATT.REASON !
    R@ SATT.EFFECT !
    R> SATT.STATE ! ;

: _SEVT-EXPIRE  ( event -- )
    DUP _SEVT-CLEAR-LIVE-POINTERS
    _SEVT-STATE-EXPIRED SWAP SEVT.STATE ! ;

: _SFLOW-CLOSE-PAYLOADS  ( flow -- status )
    DUP SFLOW.INGRESS-CARRIER _SFLOW-CLOSE-CARRIER
    OVER SFLOW.EGRESS-CARRIER _SFLOW-CLOSE-CARRIER
    OR IF DROP STREAMS-FLOW-S-CLEANUP
        ELSE DROP STREAMS-FLOW-S-OK THEN ;

: _SFLOW-INGRESS-RETAINED-EXACT?  ( flow -- flag )
    DUP SFLOW.INGRESS-EVENT SEVT.PAYLOAD-A @
        OVER SFLOW.INGRESS-CARRIER <> IF DROP 0 EXIT THEN
    DUP SFLOW.INGRESS-EVENT SEVT.PAYLOAD-U @
        OVER SFLOW.INGRESS-ATTEMPT SATT.PAYLOAD-U @ <> IF
        DROP 0 EXIT
    THEN
    DUP SFLOW.INGRESS-EVENT _SEVT-PAYLOAD-EXACT?
    SWAP >R
    R@ SFLOW.INGRESS-EVENT STREAMS-EVENT-SIZE
        R@ SFLOW.CONNECTOR-RESULT SHA3-256-HASH-COMPARE
    R> DROP AND ;

: _SFLOW-EGRESS-RETAINED-EXACT?  ( flow -- flag )
    DUP SFLOW.EGRESS-EVENT SEVT.PAYLOAD-A @
        OVER SFLOW.EGRESS-CARRIER <> IF DROP 0 EXIT THEN
    DUP SFLOW.EGRESS-EVENT SEVT.PAYLOAD-U @
        OVER SFLOW.EGRESS-ATTEMPT SATT.PAYLOAD-U @ <> IF
        DROP 0 EXIT
    THEN
    DUP SFLOW.EGRESS-EVENT _SEVT-PAYLOAD-EXACT?
    SWAP >R
    R@ SFLOW.EGRESS-EVENT STREAMS-EVENT-SIZE
        R@ SFLOW.TRANSFORM-RESULT SHA3-256-HASH-COMPARE
    R> DROP AND ;

: _SFLOW-TERMINAL-ATTEMPT  ( flow -- attempt )
    DUP SFLOW.EGRESS-ATTEMPT SATT.STATE @
        STREAMS-ATTEMPT-STATE-EMPTY = IF
        SFLOW.INGRESS-ATTEMPT
    ELSE
        SFLOW.EGRESS-ATTEMPT
    THEN ;

: _SFLOW-TERMINAL-PAYLOAD-EXACT?  ( flow -- flag )
    DUP SFLOW.EGRESS-ATTEMPT SATT.STATE @
        STREAMS-ATTEMPT-STATE-EMPTY = IF
        DUP _SFLOW-INGRESS-RETAINED-EXACT?
        SWAP SFLOW.EGRESS-CARRIER STREAMS-PAYLOAD-VALID? AND
    ELSE
        DUP SFLOW.INGRESS-CARRIER STREAMS-PAYLOAD-VALID?
        SWAP _SFLOW-EGRESS-RETAINED-EXACT? AND
    THEN ;

: _SFLOW-NOTE-TERMINAL-PAYLOAD-CHANGE  ( flow -- )
    DUP _SFLOW-TERMINAL-PAYLOAD-EXACT? IF DROP EXIT THEN
    DUP _SFLOW-TERMINAL-ATTEMPT
    DUP SATT.CLEANUP-ERROR @ 0= IF
        STREAMS-FLOW-E-PAYLOAD-CHANGED OVER SATT.CLEANUP-ERROR !
    THEN
    SATT.ERROR @ STREAMS-FLOW-E-PAYLOAD-CHANGED <> IF
        STREAMS-FLOW-S-CLEANUP OVER SFLOW.LAST-STATUS !
    THEN
    DROP ;

: _SFLOW-PAYLOAD-FAILURE-KNOWN?  ( flow -- flag )
    DUP SFLOW.INGRESS-ATTEMPT DUP SATT.ERROR @
        STREAMS-FLOW-E-PAYLOAD-CHANGED =
    SWAP SATT.CLEANUP-ERROR @
        STREAMS-FLOW-E-PAYLOAD-CHANGED = OR
    SWAP SFLOW.EGRESS-ATTEMPT DUP SATT.ERROR @
        STREAMS-FLOW-E-PAYLOAD-CHANGED =
    SWAP SATT.CLEANUP-ERROR @
        STREAMS-FLOW-E-PAYLOAD-CHANGED = OR
    OR ;

: _SFLOW-EXPIRE-EVENTS  ( flow -- )
    DUP SFLOW.INGRESS-EVENT _SEVT-HEADER? IF
        DUP SFLOW.INGRESS-EVENT _SEVT-EXPIRE
    THEN
    DUP SFLOW.EGRESS-EVENT _SEVT-HEADER? IF
        DUP SFLOW.EGRESS-EVENT _SEVT-EXPIRE
    THEN
    DROP ;

: _SFLOW-MARK-TERMINAL  ( status flow -- status )
    >R
    DUP R@ SFLOW.LAST-STATUS !
    DROP
    R@ _SFLOW-NOTE-TERMINAL-PAYLOAD-CHANGE
    STREAMS-FLOW-STATE-TERMINAL R@ SFLOW.STATE !
    R> SFLOW.LAST-STATUS @ ;

