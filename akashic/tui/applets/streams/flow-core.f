: _SFLOW-SEAL-INGRESS-BODY  ( flow -- status )
    DUP _SFLOW.ARG-CONNECTOR @ DUP STREAMS-CONNECTOR-VALID? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SFLOW-INPUT-DIRECTION? 0= IF 2DROP STREAMS-FLOW-S-INVALID EXIT THEN
    SCON.ID OVER _SFLOW.INPUT-ID RID= 0= IF
        DROP STREAMS-FLOW-S-STALE EXIT
    THEN
    DUP _SFLOW.ARG-EVENT @ DUP _SEVT-HEADER? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    SEVT.STATE @ _SEVT-STATE-BUILDING <> IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SFLOW.INPUT-ID OVER _SFLOW.ARG-EVENT @ SEVT.CONNECTOR-ID RID-COPY
    DUP SFLOW.ID OVER _SFLOW.ARG-EVENT @ SEVT.FLOW-ID RID-COPY
    DUP _SFLOW.INPUT-ENDPOINT-ID
        OVER _SFLOW.ARG-EVENT @ SEVT.ORIGIN-ID RID-COPY
    DUP SFLOW.ID OVER _SFLOW.ARG-EVENT @ SEVT.DESTINATION-ID RID-COPY
    DUP _SFLOW.INPUT-REVISION @
        OVER _SFLOW.ARG-EVENT @ SEVT.CONNECTOR-REVISION !
    STREAMS-EVENT-DIRECTION-INGRESS
        OVER _SFLOW.ARG-EVENT @ SEVT.DIRECTION !
    DUP _SFLOW.INPUT-PROTOCOL @
        OVER _SFLOW.ARG-EVENT @ SEVT.PROTOCOL !
    _SFLOW.ARG-EVENT @ STREAMS-EVENT-SEAL ;

: STREAMS-FLOW-SEAL-INGRESS
  ( input-connector event flow -- status )
    >R
    R@ _SFLOW-HEADER? 0= IF 2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT THEN
    R@ SFLOW.BUSY @ IF 2DROP R> DROP STREAMS-FLOW-S-BUSY EXIT THEN
