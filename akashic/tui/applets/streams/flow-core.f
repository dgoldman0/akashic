: _SFLOW-EVENT-WORKSPACE-DISJOINT?  ( event flow -- flag )
    >R
    DUP STREAMS-EVENT-SIZE R@ SFLOW.INGRESS-CARRIER
        STREAMS-PAYLOAD-SPAN-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP STREAMS-EVENT-SIZE R@ SFLOW.EGRESS-CARRIER
        STREAMS-PAYLOAD-SPAN-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP STREAMS-EVENT-SIZE
        R@ SFLOW.OPERATION R@ SFLOW.OPERATION-CAPACITY
        MSPAN-OVERLAP? IF DROP R> DROP 0 EXIT THEN
    DUP SEVT.OWNERSHIP @ STREAMS-EVENT-OWNERSHIP-CARRIER = IF
        DUP SEVT.PAYLOAD-A @ R@ SFLOW.INGRESS-CARRIER
            STREAMS-PAYLOAD-DISJOINT? 0= IF DROP R> DROP 0 EXIT THEN
        DUP SEVT.PAYLOAD-A @ R@ SFLOW.EGRESS-CARRIER
            STREAMS-PAYLOAD-DISJOINT? 0= IF DROP R> DROP 0 EXIT THEN
        R@ STREAMS-FLOW-SIZE 2 PICK SEVT.PAYLOAD-A @
            STREAMS-PAYLOAD-SPAN-DISJOINT? 0= IF
            DROP R> DROP 0 EXIT
        THEN
        R@ SFLOW.OPERATION R@ SFLOW.OPERATION-CAPACITY
            2 PICK SEVT.PAYLOAD-A @
            STREAMS-PAYLOAD-SPAN-DISJOINT? 0= IF
            DROP R> DROP 0 EXIT
        THEN
    ELSE
        DUP SEVT.PAYLOAD-A @ OVER SEVT.PAYLOAD-U @
            R@ STREAMS-FLOW-SIZE MSPAN-OVERLAP? IF
            DROP R> DROP 0 EXIT
        THEN
        DUP SEVT.PAYLOAD-A @ OVER SEVT.PAYLOAD-U @
            R@ SFLOW.INGRESS-CARRIER
            STREAMS-PAYLOAD-SPAN-DISJOINT? 0= IF
            DROP R> DROP 0 EXIT
        THEN
        DUP SEVT.PAYLOAD-A @ OVER SEVT.PAYLOAD-U @
            R@ SFLOW.EGRESS-CARRIER
            STREAMS-PAYLOAD-SPAN-DISJOINT? 0= IF
            DROP R> DROP 0 EXIT
        THEN
        DUP SEVT.PAYLOAD-A @ OVER SEVT.PAYLOAD-U @
            R@ SFLOW.OPERATION R@ SFLOW.OPERATION-CAPACITY
            MSPAN-OVERLAP? IF DROP R> DROP 0 EXIT THEN
    THEN
    DROP R> DROP -1 ;

