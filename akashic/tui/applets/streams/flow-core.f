: _SFLOW-RESERVATION-PRECHECK  ( flow -- status )
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-IDLE <> IF
        DROP STREAMS-FLOW-S-FULL EXIT
    THEN
    DUP _SFLOW.ARG-EXPECTED @ OVER SFLOW.REVISION @ <> IF
        DROP STREAMS-FLOW-S-STALE EXIT
    THEN
    DUP _SFLOW-INPUT-CURRENT? 0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DUP _SFLOW-OUTPUT-CURRENT? 0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DUP _SFLOW.ARG-CONNECTOR @ DUP STREAMS-CONNECTOR-VALID? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SFLOW-INPUT-DIRECTION? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SCON.ID 2 PICK _SFLOW.INPUT-ID RID=
    OVER SCON.ENDPOINT-ID 3 PICK _SFLOW.INPUT-ENDPOINT-ID RID= AND
    OVER SCON.REVISION @ 3 PICK _SFLOW.INPUT-REVISION @ = AND
    SWAP SCON.PROTOCOL @ 2 PICK _SFLOW.INPUT-PROTOCOL @ = AND
    0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DUP _SFLOW.ARG-NOW @ 0< IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP SFLOW.LAST-NOW @ 0>= IF
        DUP _SFLOW.ARG-NOW @ OVER SFLOW.LAST-NOW @ < IF
            DROP STREAMS-FLOW-S-STALE EXIT
        THEN
    THEN
    DUP _SFLOW.ARG-GENERATION @ DUP 0<
        SWAP 2 PICK SFLOW.INGRESS-CARRIER SPAY.BYTE-CAP @ > OR IF
        DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    DUP SFLOW.INGRESS-CARRIER SPAY.STATE @
        STREAMS-PAYLOAD-STATE-BUILDING <> IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.INGRESS-CARRIER SPAY.BYTE-U @ IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.EGRESS-CARRIER SPAY.STATE @
        STREAMS-PAYLOAD-STATE-BUILDING <> IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.EGRESS-CARRIER SPAY.BYTE-U @ IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.GENERATION @ _SFLOW-CELL-MAX >= IF
        DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    DUP SFLOW.TIMEOUT-MS @ _SFLOW-CELL-MAX SWAP -
    OVER _SFLOW.ARG-NOW @ < IF
        DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    DROP STREAMS-FLOW-S-OK ;

: _SFLOW-EGRESS-RESERVATION-PRECHECK  ( flow -- status )
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-IDLE <> IF
        DROP STREAMS-FLOW-S-FULL EXIT
    THEN
    DUP _SFLOW.ARG-EXPECTED @ OVER SFLOW.REVISION @ <> IF
        DROP STREAMS-FLOW-S-STALE EXIT
    THEN
    DUP _SFLOW-INPUT-CURRENT? 0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DUP _SFLOW-OUTPUT-CURRENT? 0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DUP _SFLOW.ARG-CONNECTOR @ DUP STREAMS-CONNECTOR-VALID? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP _SFLOW-OUTPUT-DIRECTION? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SCON.ID 2 PICK _SFLOW.OUTPUT-ID RID=
    OVER SCON.ENDPOINT-ID 3 PICK _SFLOW.OUTPUT-ENDPOINT-ID RID= AND
    OVER SCON.REVISION @ 3 PICK _SFLOW.OUTPUT-REVISION @ = AND
    OVER SCON.PROTOCOL @ 3 PICK _SFLOW.OUTPUT-PROTOCOL @ = AND
    OVER SCON.CONTEXT @ 3 PICK _SFLOW.OUTPUT-CONTEXT @ = AND
    OVER SCON.OP-SIZE @ 3 PICK _SFLOW.OUTPUT-OP-SIZE @ = AND
    OVER SCON.START-XT @ 3 PICK _SFLOW.OUTPUT-START-XT @ = AND
    OVER SCON.POLL-XT @ 3 PICK _SFLOW.OUTPUT-POLL-XT @ = AND
    OVER SCON.CANCEL-XT @ 3 PICK _SFLOW.OUTPUT-CANCEL-XT @ = AND
    SWAP SCON.CLEANUP-XT @ 2 PICK _SFLOW.OUTPUT-CLEANUP-XT @ = AND
    0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DUP _SFLOW.ARG-NOW @ 0< IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP SFLOW.LAST-NOW @ 0>= IF
        DUP _SFLOW.ARG-NOW @ OVER SFLOW.LAST-NOW @ < IF
            DROP STREAMS-FLOW-S-STALE EXIT
        THEN
    THEN
    DUP _SFLOW.ARG-GENERATION @ DUP 0<
        SWAP 2 PICK SFLOW.EGRESS-CARRIER SPAY.BYTE-CAP @ > OR IF
        DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    DUP SFLOW.INGRESS-CARRIER SPAY.STATE @
        STREAMS-PAYLOAD-STATE-BUILDING <> IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.INGRESS-CARRIER SPAY.BYTE-U @ IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.EGRESS-CARRIER SPAY.STATE @
        STREAMS-PAYLOAD-STATE-BUILDING <> IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.EGRESS-CARRIER SPAY.BYTE-U @ IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP SFLOW.GENERATION @ _SFLOW-CELL-MAX >= IF
        DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    DUP SFLOW.TIMEOUT-MS @ _SFLOW-CELL-MAX SWAP -
    OVER _SFLOW.ARG-NOW @ < IF
        DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    DROP STREAMS-FLOW-S-OK ;

: _SFLOW-EGRESS-BEGIN-PRECHECK  ( flow -- status )
    DUP _SFLOW-EGRESS-RESERVATION-PRECHECK
    DUP STREAMS-FLOW-S-OK <> IF NIP EXIT THEN
    DROP
    DUP _SFLOW.ARG-EVENT @ DUP
        _SEVT-DIGESTED-EGRESS-METADATA? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DUP 2 PICK _SFLOW-EGRESS-METADATA-MATCH? 0= IF
        2DROP STREAMS-FLOW-S-STALE EXIT
    THEN
    OVER _SFLOW-METADATA-WORKSPACE-DISJOINT? 0= IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DROP STREAMS-FLOW-S-OK ;

: _SFLOW-BEGIN-PRECHECK  ( flow -- status )
    DUP _SFLOW-RESERVATION-PRECHECK
    DUP STREAMS-FLOW-S-OK <> IF NIP EXIT THEN
    DROP
    DUP _SFLOW.ARG-EVENT @ DUP _SEVT-UNBOUND-METADATA? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    OVER _SFLOW-METADATA-WORKSPACE-DISJOINT? 0= IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DROP STREAMS-FLOW-S-OK ;

: _SFLOW-ADMIT-PRECHECK  ( flow -- status )
    DUP _SFLOW-RESERVATION-PRECHECK
    DUP STREAMS-FLOW-S-OK <> IF NIP EXIT THEN
    DROP
    DUP _SFLOW.ARG-EVENT @ DUP STREAMS-EVENT-VALID? 0= IF
        2DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    OVER _SFLOW-EVENT-MATCH? 0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DUP _SFLOW.ARG-EVENT @ STREAMS-EVENT-SIZE
        2 PICK STREAMS-FLOW-SIZE
        MSPAN-OVERLAP? IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP _SFLOW.ARG-EVENT @ OVER
        _SFLOW-EVENT-WORKSPACE-DISJOINT? 0= IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DROP STREAMS-FLOW-S-OK ;

: _SFLOW-BIND-INGRESS-METADATA  ( flow -- )
    DUP _SFLOW.ARG-EVENT @
        OVER SFLOW.INGRESS-EVENT STREAMS-EVENT-SIZE MOVE
    _SEVT-STATE-BUILDING OVER SFLOW.INGRESS-EVENT SEVT.STATE !
    DUP _SFLOW.INPUT-ID
        OVER SFLOW.INGRESS-EVENT SEVT.CONNECTOR-ID RID-COPY
    DUP SFLOW.ID OVER SFLOW.INGRESS-EVENT SEVT.FLOW-ID RID-COPY
    DUP _SFLOW.INPUT-ENDPOINT-ID
        OVER SFLOW.INGRESS-EVENT SEVT.ORIGIN-ID RID-COPY
    DUP SFLOW.ID OVER SFLOW.INGRESS-EVENT SEVT.DESTINATION-ID RID-COPY
    DUP _SFLOW.INPUT-REVISION @
        OVER SFLOW.INGRESS-EVENT SEVT.CONNECTOR-REVISION !
    STREAMS-EVENT-DIRECTION-INGRESS
        OVER SFLOW.INGRESS-EVENT SEVT.DIRECTION !
    DUP _SFLOW.INPUT-PROTOCOL @
        OVER SFLOW.INGRESS-EVENT SEVT.PROTOCOL !
    DUP SFLOW.INGRESS-CARRIER
        OVER SFLOW.INGRESS-EVENT SEVT.PAYLOAD-A !
    DUP _SFLOW.ARG-GENERATION @
        OVER SFLOW.INGRESS-EVENT SEVT.PAYLOAD-U !
    STREAMS-EVENT-OWNERSHIP-CARRIER
        OVER SFLOW.INGRESS-EVENT SEVT.OWNERSHIP !
    0 OVER SFLOW.INGRESS-EVENT SEVT.RELEASE-XT !
    DUP SFLOW.INGRESS-CARRIER-EPOCH @
        OVER SFLOW.INGRESS-EVENT SEVT.RELEASE-CONTEXT !
    0 OVER SFLOW.INGRESS-EVENT SEVT.CLEANUP-ERROR !
    SFLOW.INGRESS-EVENT SEVT.PAYLOAD-DIGEST
        SHA3-256-LEN 0 FILL ;

: _SFLOW-BEGIN-RESERVATION  ( flow -- generation status )
    DUP _SFLOW-BIND-INGRESS-METADATA
    DUP SFLOW.GENERATION @ 1+ DUP 2 PICK SFLOW.GENERATION !
    DUP 2 PICK _SFLOW.ARG-GENERATION !
    OVER _SFLOW.ARG-NOW @ 2 PICK SFLOW.TIMEOUT-MS @ +
        2 PICK SFLOW.DEADLINE !
    OVER _SFLOW.ARG-NOW @ 2 PICK SFLOW.LAST-NOW !
    STREAMS-FLOW-STATE-RECEIVING 2 PICK SFLOW.STATE !
    STREAMS-FLOW-S-PENDING 2 PICK SFLOW.LAST-STATUS !
    NIP STREAMS-FLOW-S-OK ;

: _SFLOW-RECEIVE-PRECHECK  ( flow -- status )
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-RECEIVING <> IF
        DROP STREAMS-FLOW-S-NO-WORK EXIT
    THEN
    DUP _SFLOW.ARG-NOW @ OVER SFLOW.DEADLINE @ >= IF
        DROP STREAMS-FLOW-S-TIMED-OUT EXIT
    THEN
    DUP _SFLOW.ARG-GENERATION @ OVER SFLOW.GENERATION @ <> IF
        DROP STREAMS-FLOW-S-STALE EXIT
    THEN
    DUP _SFLOW-INPUT-CURRENT? 0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DUP _SFLOW-OUTPUT-CURRENT? 0= IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    DROP STREAMS-FLOW-S-OK ;

: _SFLOW-APPEND-EVENT  ( flow -- status )
    >R
    R@ SFLOW.INGRESS-CARRIER SPAY.GENERATION @
    R@ SFLOW.INGRESS-CARRIER
    R@ _SFLOW.ARG-EVENT @ STREAMS-EVENT-APPEND-TO-CARRIER
    R> DROP ;

: _SFLOW-SEAL-RESERVATION  ( flow -- status )
    >R
    R@ SFLOW.INGRESS-CARRIER SPAY.BYTE-U @
        R@ SFLOW.INGRESS-EVENT SEVT.PAYLOAD-U @ <> IF
        R> DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    R@ SFLOW.INGRESS-CARRIER SPAY.GENERATION @
        R@ SFLOW.INGRESS-CARRIER STREAMS-PAYLOAD-SEAL
    DUP STREAMS-PAYLOAD-S-OK <> IF
        DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    DROP
    R@ SFLOW.INGRESS-EVENT STREAMS-EVENT-SEAL
        STREAMS-FLOW-S-OK <> IF
        R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    _SEVT-STATE-CARRIER R@ SFLOW.INGRESS-EVENT SEVT.STATE !
    R@ SFLOW.INGRESS-EVENT STREAMS-EVENT-SIZE
        R@ SFLOW.CONNECTOR-RESULT SHA3-256-HASH
    R> DROP STREAMS-FLOW-S-OK ;

: _SFLOW-PUBLISH-ADMISSION  ( flow -- status )
    >R
    R@ SFLOW.INGRESS-EVENT
    R@ SFLOW.GENERATION @
    R@ _SFLOW.ARG-NOW @
    STREAMS-EVENT-DIRECTION-INGRESS
    R@ SFLOW.INGRESS-ATTEMPT _SATT-ACCEPT
    STREAMS-FLOW-STATE-ACCEPTED R@ SFLOW.STATE !
    STREAMS-FLOW-S-OK R@ SFLOW.LAST-STATUS !
    R> DROP STREAMS-FLOW-S-OK ;

: _SFLOW-ROLLBACK-RESERVATION  ( completion-status flow -- status )
    >R
    R@ _SFLOW-ROLLBACK-SLOT
    DUP STREAMS-FLOW-S-OK <> IF
        NIP DUP R@ SFLOW.LAST-STATUS !
        R> DROP EXIT
    THEN
    DROP
    DUP R@ SFLOW.LAST-STATUS !
    -1 R@ SFLOW.DEADLINE !
    STREAMS-FLOW-STATE-IDLE R@ SFLOW.STATE !
    R> DROP ;

: _SFLOW-APPEND-BODY  ( flow -- status )
    DUP _SFLOW-RECEIVE-PRECHECK
    DUP STREAMS-FLOW-S-TIMED-OUT = IF
        DROP STREAMS-FLOW-S-TIMED-OUT SWAP
        _SFLOW-ROLLBACK-RESERVATION EXIT
    THEN
    DUP STREAMS-FLOW-S-OK <> IF NIP EXIT THEN
    DROP
    DUP SFLOW.INGRESS-EVENT SEVT.PAYLOAD-U @
        OVER SFLOW.INGRESS-CARRIER SPAY.BYTE-U @ -
        OVER _SFLOW.ARG-CONNECTOR @ < IF
        DROP STREAMS-FLOW-S-CAPACITY EXIT
    THEN
    >R
    R@ _SFLOW.ARG-EVENT @
    R@ _SFLOW.ARG-CONNECTOR @
    R@ SFLOW.INGRESS-CARRIER SPAY.GENERATION @
    R@ SFLOW.INGRESS-CARRIER STREAMS-PAYLOAD-APPEND
    R> DROP
    DUP STREAMS-PAYLOAD-S-OK = IF DROP STREAMS-FLOW-S-OK EXIT THEN
    DUP STREAMS-PAYLOAD-S-CAPACITY = IF DROP STREAMS-FLOW-S-CAPACITY EXIT THEN
    DUP STREAMS-PAYLOAD-S-STALE = IF DROP STREAMS-FLOW-S-STALE EXIT THEN
    STREAMS-PAYLOAD-S-BUSY = IF
        STREAMS-FLOW-S-BUSY
    ELSE
        STREAMS-FLOW-S-INVALID
    THEN ;

: _SFLOW-COMMIT-BODY  ( flow -- status )
    DUP _SFLOW-RECEIVE-PRECHECK
    DUP STREAMS-FLOW-S-TIMED-OUT = IF
        DROP STREAMS-FLOW-S-TIMED-OUT SWAP
        _SFLOW-ROLLBACK-RESERVATION EXIT
    THEN
    DUP STREAMS-FLOW-S-OK <> IF NIP EXIT THEN
    DROP
    DUP _SFLOW-SEAL-RESERVATION
    DUP STREAMS-FLOW-S-CAPACITY = IF NIP EXIT THEN
    DUP STREAMS-FLOW-S-OK <> IF
        DROP STREAMS-FLOW-S-INVALID SWAP
        _SFLOW-ROLLBACK-RESERVATION EXIT
    THEN
    DROP _SFLOW-PUBLISH-ADMISSION ;

: _SFLOW-ABORT-BODY  ( flow -- status )
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-RECEIVING <> IF
        DROP STREAMS-FLOW-S-NO-WORK EXIT
    THEN
    DUP _SFLOW.ARG-NOW @ OVER SFLOW.DEADLINE @ >= IF
        STREAMS-FLOW-S-TIMED-OUT SWAP
        _SFLOW-ROLLBACK-RESERVATION EXIT
    THEN
    DUP _SFLOW.ARG-GENERATION @ OVER SFLOW.GENERATION @ <> IF
        DROP STREAMS-FLOW-S-STALE EXIT
    THEN
    STREAMS-FLOW-S-CANCELLED SWAP _SFLOW-ROLLBACK-RESERVATION ;

: _SFLOW-LEAVE-GENERATION  ( generation status flow -- generation status )
    DUP _SFLOW-CLEAR-ARGS
    0 SWAP SFLOW.BUSY ! ;

: STREAMS-FLOW-INGRESS-BEGIN
  ( connector metadata declared-u expected-revision now-ms flow -- generation status )
    >R
    R@ _SFLOW-HEADER? 0= IF
        2DROP 2DROP DROP R> DROP 0 STREAMS-FLOW-S-INVALID EXIT
    THEN
    4 PICK STREAMS-CONNECTOR-SIZE MSPAN-NONWRAPPING? 0= IF
        2DROP 2DROP DROP R> DROP 0 STREAMS-FLOW-S-INVALID EXIT
    THEN
    3 PICK STREAMS-EVENT-SIZE MSPAN-NONWRAPPING? 0= IF
        2DROP 2DROP DROP R> DROP 0 STREAMS-FLOW-S-INVALID EXIT
    THEN
    4 PICK STREAMS-CONNECTOR-SIZE
        R@ STREAMS-FLOW-SIZE MSPAN-OVERLAP? IF
        2DROP 2DROP DROP R> DROP 0 STREAMS-FLOW-S-INVALID EXIT
    THEN
    3 PICK STREAMS-EVENT-SIZE
        R@ STREAMS-FLOW-SIZE MSPAN-OVERLAP? IF
        2DROP 2DROP DROP R> DROP 0 STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ SFLOW.BUSY @ IF
        2DROP 2DROP DROP R> DROP 0 STREAMS-FLOW-S-BUSY EXIT
    THEN
    R@ STREAMS-FLOW-VALID? 0= IF
