        2DROP R> DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
    R@ _SFLOW.ARG-EVENT !
    R@ _SFLOW.ARG-CONNECTOR !
    -1 R@ SFLOW.BUSY !
