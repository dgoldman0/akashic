: STREAMS-CONNECTOR-INIT  ( connector -- status )
    DUP 0= IF DROP STREAMS-FLOW-S-INVALID EXIT THEN
    DUP STREAMS-CONNECTOR-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP STREAMS-FLOW-S-INVALID EXIT
    THEN
