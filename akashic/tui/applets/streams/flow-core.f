: _SFLOW-ADMIT-BODY  ( flow -- status )
    DUP _SFLOW.ARG-EVENT @ SEVT.PAYLOAD-U @
        OVER _SFLOW.ARG-GENERATION !
    DUP SFLOW.INPUT-CONNECTOR @ OVER _SFLOW.ARG-CONNECTOR !
    DUP _SFLOW-ADMIT-PRECHECK
    DUP STREAMS-FLOW-S-OK <> IF NIP EXIT THEN
    DROP
    DUP _SFLOW-BEGIN-RESERVATION
    DUP STREAMS-FLOW-S-OK <> IF
        NIP NIP EXIT
    THEN
    DROP DROP
    DUP _SFLOW-APPEND-EVENT
    DUP STREAMS-FLOW-S-OK <> IF
        SWAP _SFLOW-ROLLBACK-RESERVATION EXIT
    THEN
    DROP
    DUP _SFLOW-SEAL-RESERVATION
    DUP STREAMS-FLOW-S-OK <> IF
        SWAP _SFLOW-ROLLBACK-RESERVATION EXIT
    THEN
    DROP
    DUP _SFLOW.ARG-EVENT @ STREAMS-EVENT-CLOSE
    DUP STREAMS-FLOW-S-OK <> IF
        SWAP _SFLOW-ROLLBACK-RESERVATION EXIT
    THEN
    DROP _SFLOW-PUBLISH-ADMISSION ;

