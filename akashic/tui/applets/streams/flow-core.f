: _SCON-OUTPUT-SURFACE?  ( connector -- flag )
    DUP SCON.OP-SIZE @ DUP 1 <
        SWAP STREAMS-FLOW-OP-MAX > OR IF DROP 0 EXIT THEN
    DUP SCON.START-XT @ 0<>
    OVER SCON.POLL-XT @ 0<> AND
    OVER SCON.CANCEL-XT @ 0<> AND
    SWAP SCON.CLEANUP-XT @ 0<> AND ;

