\ =====================================================================
\ rabbit-library-profile.f - fixed read-only Library Rabbit projection
\ =====================================================================
\ One profile binds LIST and FETCH on the exact Library-read-v1 selector to
\ two explicit, live Library capability descriptors.  The peer controls only
\ the closed reduced maps {after,limit} and {resource,domain_revision}; the
\ profile injects its copied collection, collection revision, and request
\ digest before the ordinary capability schema is validated and dispatched.
\
\ The profile owns its graph-spec copy, immutable scope values, dedicated
\ two-entry facet, reduced schemas, and two temporary decoded CV graphs.  It
\ borrows the component instances, capabilities, bus, future Burrow root,
\ JSON arenas, router, and mounts supplied by its composition.  In
\ particular this neutral module never imports Library service, controller,
\ persistence, VFS, or product composition code.
\
\ INIT is transactional.  It registers both mount handlers while the router
\ is BUILDING; the graph provider seals it immediately before constructing
\ the Burrow.  Failure resets the router before finalizing any successful
\ mount, so no borrowed handler context can survive rollback.  Runtime
\ teardown is the inverse: the server and Burrow must be finalized first and
\ the router reset or finalized before FINI.
\ =====================================================================

