: _SRLP-FINI  ( profile -- status )
    DUP _SRLP-BINDING-VALID? 0= IF
        DROP STREAMS-RABBIT-LIBRARY-PROFILE-S-INVALID EXIT
    THEN
    DUP _SRLPFIN-P ! SRLP.BUSY @ IF
        STREAMS-RABBIT-LIBRARY-PROFILE-S-BUSY EXIT
    THEN
    _SRLPFIN-P @ SRLP.BURROW @ STREAMS-RABBIT-BURROW-SIZE
        _SRLP-ZERO-SPAN? 0= IF STREAMS-RABBIT-LIBRARY-PROFILE-S-STATE EXIT THEN
    _SRLPFIN-P @ SRLP.ROUTER @ DUP RROUTER-VALID? IF
        DUP RROUTER-STATE@ RROUTER-STATE-BUILDING <>
        OVER RROUTER-COUNT@ 0<> OR IF
            DROP STREAMS-RABBIT-LIBRARY-PROFILE-S-STATE EXIT
        THEN DROP
    ELSE
        RROUTER-SIZE _SRLP-ZERO-SPAN? 0= IF
            STREAMS-RABBIT-LIBRARY-PROFILE-S-STATE EXIT
        THEN
    THEN
    _SRLPFIN-P @ SRLP.QUERY-MOUNT @ SRFM.BUSY @
    _SRLPFIN-P @ SRLP.READ-MOUNT @ SRFM.BUSY @ OR IF
        STREAMS-RABBIT-LIBRARY-PROFILE-S-BUSY EXIT
    THEN
    _SRLPFIN-P @ SRLP.READ-MOUNT @ STREAMS-RABBIT-FACET-MOUNT-FINI
        STREAMS-RABBIT-FACET-MOUNT-S-OK <> IF
        STREAMS-RABBIT-LIBRARY-PROFILE-S-MOUNT EXIT
    THEN
    _SRLPFIN-P @ SRLP.QUERY-MOUNT @ STREAMS-RABBIT-FACET-MOUNT-FINI
        STREAMS-RABBIT-FACET-MOUNT-S-OK <> IF
        STREAMS-RABBIT-LIBRARY-PROFILE-S-MOUNT EXIT
    THEN
    _SRLPFIN-P @ SRLP.QUERY-STAGE CV-FREE
    _SRLPFIN-P @ SRLP.READ-STAGE CV-FREE
    _SRLPFIN-P @ STREAMS-RABBIT-LIBRARY-PROFILE-SIZE 0 FILL
    STREAMS-RABBIT-LIBRARY-PROFILE-S-OK ;

