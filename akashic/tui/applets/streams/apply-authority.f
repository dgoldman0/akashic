: _SAPA-CANDIDATE-VIEWS-SAFE?  ( candidate work -- flag )
    >R
    DUP SPREC-CANDIDATE-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    DUP OCC.NATIVE-A @ OVER OCC.NATIVE-U @
        R@ _SAPA-EXTERNAL-SPAN? 0= IF DROP R> DROP 0 EXIT THEN
    DUP OCC.TITLE-U @ IF
        DUP OCC.TITLE-A @ OVER OCC.TITLE-U @
            R@ _SAPA-EXTERNAL-SPAN? 0= IF
            DROP R> DROP 0 EXIT
        THEN
    THEN
    DUP OCC.URL-U @ IF
        DUP OCC.URL-A @ OVER OCC.URL-U @
            R@ _SAPA-EXTERNAL-SPAN? 0= IF
            DROP R> DROP 0 EXIT
        THEN
    THEN
    DUP OCC.SUMMARY-U @ IF
        DUP OCC.SUMMARY-A @ OVER OCC.SUMMARY-U @
            R@ _SAPA-EXTERNAL-SPAN? 0= IF
            DROP R> DROP 0 EXIT
        THEN
    THEN
    DUP OCC.CONTENT-U @ IF
        DUP OCC.CONTENT-A @ OVER OCC.CONTENT-U @
            R@ _SAPA-EXTERNAL-SPAN? 0= IF
            DROP R> DROP 0 EXIT
        THEN
    THEN
    DUP OCC.PUBLISHED-U @ IF
        DUP OCC.PUBLISHED-A @ OVER OCC.PUBLISHED-U @
            R@ _SAPA-EXTERNAL-SPAN? 0= IF
            DROP R> DROP 0 EXIT
        THEN
    THEN
    DUP OCC.MODIFIED-U @ IF
        DUP OCC.MODIFIED-A @ OVER OCC.MODIFIED-U @
            R@ _SAPA-EXTERNAL-SPAN? 0= IF
            DROP R> DROP 0 EXIT
        THEN
    THEN
    DROP R> DROP -1 ;

: _SAPA-CANDIDATE-OUTPUT-SAFE?  ( candidate work -- flag )
    >R
    DUP R@ _SAPA-CANDIDATE-VIEWS-SAFE? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP OCC.NATIVE-A @ OVER OCC.NATIVE-U @
        R@ _SAPA-OUTPUT-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP OCC.TITLE-A @ OVER OCC.TITLE-U @
        R@ _SAPA-OUTPUT-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP OCC.URL-A @ OVER OCC.URL-U @
        R@ _SAPA-OUTPUT-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP OCC.SUMMARY-A @ OVER OCC.SUMMARY-U @
        R@ _SAPA-OUTPUT-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP OCC.CONTENT-A @ OVER OCC.CONTENT-U @
        R@ _SAPA-OUTPUT-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP OCC.PUBLISHED-A @ OVER OCC.PUBLISHED-U @
        R@ _SAPA-OUTPUT-DISJOINT? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP OCC.MODIFIED-A @ SWAP OCC.MODIFIED-U @
        R@ _SAPA-OUTPUT-DISJOINT?
    R> DROP ;

: _SAPA-ARGS-SAFE?  ( work -- flag )
    >R
    R@ _SAPAW.REQUEST-A @ STREAMS-APPLY-REQUEST-SIZE
        R@ _SAPA-EXTERNAL-SPAN? 0= IF R> DROP 0 EXIT THEN
    R@ _SAPAW.OUTPUT-A @ OCHK-SOURCE-SIZE
        R@ _SAPA-EXTERNAL-SPAN? 0= IF R> DROP 0 EXIT THEN
    R@ _SAPAW.REQUEST-A @ STREAMS-APPLY-REQUEST-VALID? 0= IF
        R> DROP 0 EXIT
    THEN
    R@ _SAPAW.REQUEST-A @ SAPAR.EFFECTIVE-A @
    R@ _SAPAW.REQUEST-A @ SAPAR.EFFECTIVE-U @
        R@ _SAPA-EXTERNAL-SPAN? 0= IF R> DROP 0 EXIT THEN
    R@ _SAPAW.REQUEST-A @ SAPAR.CANDIDATE-COUNT @ IF
        R@ _SAPAW.REQUEST-A @ SAPAR.CANDIDATES-A @
        R@ _SAPAW.REQUEST-A @ SAPAR.CANDIDATE-COUNT @
            OCHK-CANDIDATE-SIZE *
            R@ _SAPA-EXTERNAL-SPAN? 0= IF R> DROP 0 EXIT THEN
    THEN
    R@ _SAPAW.REQUEST-A @ STREAMS-APPLY-REQUEST-SIZE
        R@ _SAPA-OUTPUT-DISJOINT? 0= IF R> DROP 0 EXIT THEN
    R@ _SAPAW.REQUEST-A @ SAPAR.EFFECTIVE-A @
    R@ _SAPAW.REQUEST-A @ SAPAR.EFFECTIVE-U @
        R@ _SAPA-OUTPUT-DISJOINT? 0= IF R> DROP 0 EXIT THEN
    R@ _SAPAW.REQUEST-A @ SAPAR.CANDIDATE-COUNT @ IF
        R@ _SAPAW.REQUEST-A @ SAPAR.CANDIDATES-A @
        R@ _SAPAW.REQUEST-A @ SAPAR.CANDIDATE-COUNT @
            OCHK-CANDIDATE-SIZE *
            R@ _SAPA-OUTPUT-DISJOINT? 0= IF R> DROP 0 EXIT THEN
    THEN
    R@ _SAPAW.REQUEST-A @ SAPAR.CANDIDATE-COUNT @
    R> SWAP 0 ?DO
        DUP _SAPAW.REQUEST-A @ SAPAR.CANDIDATES-A @
        I OCHK-CANDIDATE-SIZE * +
        OVER _SAPA-CANDIDATE-OUTPUT-SAFE? 0= IF
            DROP 0 UNLOOP EXIT
        THEN
    LOOP
    DROP -1 ;

