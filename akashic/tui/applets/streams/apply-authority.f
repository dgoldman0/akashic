: _SAPA-PRIOR-NEW-PREFIX?  ( prior-entry work -- flag )
    >R
    DUP _SAPAE.ACTION @ _SAPAE-ACTION-NEW <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP _SAPAE.ORDINAL @
    R@ _SAPAW.PROBE-ORDINAL @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP _SAPAE.HEAD SPRH.OBSERVATION-FORMAT @
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-CANDIDATE
        OCC.FORMAT @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP _SAPAE.HEAD SPRH.NATIVE-KIND @
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-CANDIDATE
        OCC.NATIVE-KIND @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    _SAPAE.HEAD SPRH.NATIVE-DIGEST
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY
        _SAPAE.NATIVE-DIGEST
    SHA3-256-LEN _SAPA-BYTES=
    R> DROP ;

: _SAPA-ORDINAL-RESERVED?  ( ordinal work -- flag )
    SWAP OVER _SAPAW.PROBE-ORDINAL !
    DUP _SAPAW.CURRENT-INDEX @ 0 ?DO
        I OVER _SAPAW-ENTRY
        OVER _SAPA-PRIOR-NEW-PREFIX? IF
            DROP -1 UNLOOP EXIT
        THEN
    LOOP
    DROP 0 ;

