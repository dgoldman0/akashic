: _SAPA-WORK-PLACEMENT?  ( repository repo-work work -- flag )
    >R
    2DUP STREAMS-REPOSITORY-WORK-BOUND? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    R@ STREAMS-APPLY-WORK-SIZE
    2OVER STREAMS-REPOSITORY-SPAN-DISJOINT?
    NIP NIP R> DROP ;

: _SAPA-EXTERNAL-SPAN?  ( address length work -- flag )
    >R
    DUP 0> 0= IF 2DROP R> DROP 0 EXIT THEN
    OVER 0= IF 2DROP R> DROP 0 EXIT THEN
    2DUP MSPAN-NONWRAPPING? 0= IF 2DROP R> DROP 0 EXIT THEN
    2DUP R@ STREAMS-APPLY-WORK-SIZE
        MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    R@ _SAPAW.REPOSITORY @ R@ _SAPAW.REPO-WORK @
        STREAMS-REPOSITORY-SPAN-DISJOINT?
    R> DROP ;

: _SAPA-PREPARE  ( repository repo-work work -- status )
    >R
    R@ STREAMS-APPLY-WORK-VALID? 0= IF
        2DROP R> DROP STREAMS-APPLY-S-INVALID EXIT
    THEN
    R@ _SAPAW.BUSY @ IF
        2DROP STREAMS-APPLY-S-BUSY
        DUP R@ _SAPAW.STATUS ! R> DROP EXIT
    THEN
    2DUP R@ _SAPA-WORK-PLACEMENT? 0= IF
        2DROP STREAMS-APPLY-S-INVALID
        DUP R@ _SAPAW.STATUS ! R> DROP EXIT
    THEN
    OVER R@ _SAPAW.REPOSITORY !
    DUP R@ _SAPAW.REPO-WORK !
    OVER STREAMS-REPOSITORY-ADAPTER@ DUP 0= IF
        DROP 2DROP STREAMS-APPLY-S-INVALID
        DUP R@ _SAPAW.STATUS ! R> DROP EXIT
    THEN
    R@ _SAPAW.ADAPTER !
    DUP STREAMS-REPOSITORY-ADAPTER-WORK@ DUP 0= IF
        DROP 2DROP STREAMS-APPLY-S-INVALID
        DUP R@ _SAPAW.STATUS ! R> DROP EXIT
    THEN
    R@ _SAPAW.ADAPTER-WORK !
    2DROP
    STREAMS-APPLY-S-OK
    DUP R@ _SAPAW.STATUS ! R> DROP ;

: _SAPA-CONSIDER-RECOVERY  ( recovery-status work -- )
    >R
    DUP _SAPA-BLOCKING? IF
        R@ _SAPAW.TEMP-STATUS @ _SAPA-BLOCKING? IF
            DROP
        ELSE
            R@ _SAPAW.TEMP-STATUS !
        THEN
    ELSE
        DROP
    THEN
    R> DROP ;

: _SAPA-RECOVER  ( primary-status work -- final-status )
    >R
    DUP R@ _SAPAW.TEMP-STATUS !
    DROP
    R@ _SAPAW.STAGING @ IF
        R@ _SAPAW.ADAPTER @ R@ _SAPAW.ADAPTER-WORK @
            STREAMS-PA-STAGE-DISCARD _SAPA-ADAPTER>STATUS
        DUP STREAMS-APPLY-S-OK = IF
            0 R@ _SAPAW.STAGING !
        THEN
        R@ _SAPA-CONSIDER-RECOVERY
    THEN
    R@ _SAPAW.REPO-WORK @ STREAMS-REPOSITORY-ACTIVE?
    R@ _SAPAW.REPO-WORK @ STREAMS-REPOSITORY-REOPEN-REQUIRED? OR
    R@ _SAPAW.TEMP-STATUS @ STREAMS-APPLY-S-OK = AND IF
        STREAMS-APPLY-S-FAULT R@ _SAPAW.TEMP-STATUS !
    THEN
    R@ _SAPAW.REPO-WORK @ STREAMS-REPOSITORY-ACTIVE? IF
        R@ _SAPAW.ADAPTER @ R@ _SAPAW.ADAPTER-WORK @
            STREAMS-PA-ABORT _SAPA-ADAPTER>STATUS
            R@ _SAPA-CONSIDER-RECOVERY
    THEN
    R@ _SAPAW.REPO-WORK @ STREAMS-REPOSITORY-REOPEN-REQUIRED? IF
        R@ _SAPAW.ADAPTER @ R@ _SAPAW.ADAPTER-WORK @
            STREAMS-PA-REBIND _SAPA-ADAPTER>STATUS
            R@ _SAPA-CONSIDER-RECOVERY
    THEN
    R@ _SAPAW.REPO-WORK @ STREAMS-REPOSITORY-ACTIVE? IF
        STREAMS-APPLY-S-FAULT R@ _SAPAW.TEMP-STATUS !
    THEN
    R@ _SAPAW.TEMP-STATUS @ R> DROP ;

: _SAPA-OWNER-DISPATCH  ( work repository repo-work -- repo-status )
    2DROP >R
    R@ R@ _SAPAW.OP-XT @ CATCH
    DUP IF
        DROP DROP STREAMS-APPLY-S-FAULT
    ELSE
        DROP
    THEN
    R@ _SAPA-RECOVER
    DUP R@ _SAPAW.RESULT ! DROP
    R> DROP STREAMS-REPOSITORY-S-OK ;

: _SAPA-INVOKE  ( operation-xt work -- status )
    >R
    DUP 0= IF
        DROP STREAMS-APPLY-S-INVALID
        R@ _SAPA-WORK-STATUS! R> DROP EXIT
    THEN
    R@ _SAPAW.BUSY @ IF
        DROP STREAMS-APPLY-S-BUSY
        R@ _SAPA-WORK-STATUS! R> DROP EXIT
    THEN
    R@ _SAPAW.OP-XT !
    STREAMS-APPLY-S-INVALID R@ _SAPAW.RESULT !
    -1 R@ _SAPAW.BUSY !
    R@ ['] _SAPA-OWNER-DISPATCH
    R@ _SAPAW.REPOSITORY @ R@ _SAPAW.REPO-WORK @
        STREAMS-REPOSITORY-WITH-OWNER
    DUP STREAMS-REPOSITORY-S-OK = IF
        DROP R@ _SAPAW.RESULT @
    ELSE
        _SAPA-REPOSITORY>STATUS
    THEN
    DUP R@ _SAPAW.STATUS !
    0 R@ _SAPAW.BUSY !
    0 R@ _SAPAW.OP-XT !
    R> DROP ;

: _SAPA-READY  ( work -- status )
    >R
    R@ _SAPAW.REPO-WORK @ STREAMS-REPOSITORY-ACTIVE? IF
        R> DROP STREAMS-APPLY-S-BUSY EXIT
    THEN
    R@ _SAPAW.REPO-WORK @ STREAMS-REPOSITORY-REOPEN-REQUIRED? IF
        R@ _SAPAW.ADAPTER @ R@ _SAPAW.ADAPTER-WORK @
            STREAMS-PA-REBIND _SAPA-ADAPTER>STATUS
        DUP IF R> DROP EXIT THEN DROP
    THEN
    R@ _SAPAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF DROP R> DROP STREAMS-APPLY-S-CORRUPT EXIT THEN
    STREAMS-AUTHORITY-ROOT-HEADER-VALID? 0= IF
        R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-APPLY-S-OK ;

