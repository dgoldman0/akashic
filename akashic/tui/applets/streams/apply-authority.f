    >R
    R@ _SAPAW.KEY-0 STREAMS-PI-NATIVE-HEAD-KEY-SIZE
    R@ _SAPAW.STAGED-RECORD STREAMS-PERSISTENCE-RECORD-MAX
    R@ _SAPA-GET
    R> DROP ;

: _SAPA-PROBE-NATIVE-BUCKET  ( work -- existing? status )
    DUP 0 SWAP _SAPAW.FIRST-ABSENT !
    DUP 0 SWAP _SAPAW.MATCH-COUNT !
    SPREC-NATIVE-COLLISION-MAX 1+ 1 ?DO
        I OVER _SAPA-NATIVE-KEY
        DUP IF
            NIP 0 SWAP UNLOOP EXIT
        THEN DROP
        DUP _SAPA-GET-PROBED-NATIVE
        DUP STREAMS-APPLY-S-NOT-FOUND = IF
            2DROP
            DUP _SAPAW.FIRST-ABSENT @ 0= IF
                I OVER _SAPA-ORDINAL-RESERVED? 0= IF
                    I OVER _SAPAW.FIRST-ABSENT !
                THEN
            THEN
        ELSE
            DUP IF
                SWAP DROP NIP 0 SWAP UNLOOP EXIT
            THEN
            DROP
            SPREC-NATIVE-HEAD-SIZE <> IF
                DROP
                0 STREAMS-APPLY-S-CORRUPT
                UNLOOP EXIT
            THEN
            DUP _SAPAW.CURRENT-INDEX @ OVER _SAPAW-CANDIDATE
            OVER _SAPAW.STAGED-RECORD _SAPA-NATIVE-EXACT? IF
                1 OVER _SAPAW.MATCH-COUNT +!
                DUP _SAPAW.MATCH-COUNT @ 1 > IF
                    DROP
                    0 STREAMS-APPLY-S-CORRUPT
                    UNLOOP EXIT
                THEN
                DUP _SAPAW.STAGED-RECORD
                OVER _SAPAW.CURRENT-INDEX @ 2 PICK _SAPAW-ENTRY
                    _SAPAE.HEAD
                SPREC-NATIVE-HEAD-SIZE MOVE
                I OVER _SAPAW.CURRENT-INDEX @ 2 PICK _SAPAW-ENTRY
                    _SAPAE.ORDINAL !
            THEN
        THEN
    LOOP
    DUP _SAPAW.MATCH-COUNT @ IF
        DROP -1 STREAMS-APPLY-S-OK
    ELSE
        DUP _SAPAW.FIRST-ABSENT @ DUP 0= IF
            2DROP 0 STREAMS-APPLY-S-CAPACITY
        ELSE
            OVER _SAPAW.CURRENT-INDEX @ 2 PICK _SAPAW-ENTRY
                _SAPAE.ORDINAL !
            DROP 0 STREAMS-APPLY-S-OK
        THEN
    THEN ;

