    DUP STREAMS-APPLY-REQUEST-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP SAPAR.SOURCE-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SAPAR.SOURCE-REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP SAPAR.ATTEMPT-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SAPAR.REQUEST-SEAL RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SAPAR.COMPONENT-INSTANCE @ 0= IF DROP 0 EXIT THEN
    DUP SAPAR.COMPONENT-GENERATION @ 0> 0= IF DROP 0 EXIT THEN
    DUP SAPAR.REQUEST-GENERATION @ 0> 0= IF DROP 0 EXIT THEN
    DUP SAPAR.EFFECTIVE-U @ DUP 1 <
        SWAP OCHK-URI-MAX > OR IF DROP 0 EXIT THEN
    DUP SAPAR.EFFECTIVE-A @ DUP 0= IF 2DROP 0 EXIT THEN
    OVER SAPAR.EFFECTIVE-U @ MSPAN-NONWRAPPING? 0= IF
        DROP 0 EXIT
    THEN
    DUP SAPAR.EFFECTIVE-A @ OVER SAPAR.EFFECTIVE-U @
        UTF8-VALID? 0= IF DROP 0 EXIT THEN
    DUP SAPAR.CANDIDATE-COUNT @ DUP 0<
        SWAP OCHK-BATCH-MAX > OR IF DROP 0 EXIT THEN
    DUP SAPAR.CANDIDATE-COUNT @ IF
        DUP SAPAR.CANDIDATES-A @ DUP 0= IF 2DROP 0 EXIT THEN
        OVER SAPAR.CANDIDATE-COUNT @ OCHK-CANDIDATE-SIZE *
            MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    ELSE
        DUP SAPAR.CANDIDATES-A @ IF DROP 0 EXIT THEN
    THEN
    DUP SAPAR.FINISHED-MS @ 0< IF DROP 0 EXIT THEN
    DUP SAPAR.CLEANUP-XT @ 0= IF DROP 0 EXIT THEN
    DUP SAPAR.REVALIDATE-XT @ 0= IF DROP 0 EXIT THEN
