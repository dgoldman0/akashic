        R@ _SAPAW.ATTEMPT OCS.REVISED-COUNT !
    R@ _SAPAW.UNCHANGED-COUNT @
        R@ _SAPAW.ATTEMPT OCS.UNCHANGED-COUNT !
    0 R@ _SAPAW.ATTEMPT OCS.REJECTED-COUNT !
    0 R@ _SAPAW.ATTEMPT OCS.XIO-ERROR !
    0 R@ _SAPAW.ATTEMPT OCS.CLEANUP-ERROR !
    R@ _SAPAW.ATTEMPT _OCS-EFFECTIVE +
        OCHK-URI-MAX 0 FILL
    R@ _SAPAW.EFFECTIVE
    R@ _SAPAW.ATTEMPT _OCS-EFFECTIVE +
