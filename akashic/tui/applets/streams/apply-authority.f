: _SAPA-UPDATE-EXISTING-HEAD  ( action work -- status )
    >R
    DUP _SAPAE-ACTION-REVISED = IF
        R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY
            _SAPAE.HEAD SPRH.LATEST-REVISION @
        R@ _SAPAW.SOURCE-RECORD SPRS.REVISION-MAX @ >= IF
            DROP R> DROP STREAMS-APPLY-S-CAPACITY EXIT
        THEN
        R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY
            _SAPAE.HEAD SPRH.LATEST-REVISION @
            PERSIST-MAX-SIGNED >= IF
            DROP R> DROP STREAMS-APPLY-S-CAPACITY EXIT
        THEN
        1 R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY
            _SAPAE.HEAD SPRH.LATEST-REVISION +!
    THEN
    DROP
    R@ _SAPAW.ACTIVE-RECORD SPRA.ATTEMPT-SEQUENCE @
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY
        _SAPAE.HEAD SPRH.LAST-SEEN-SEQUENCE !
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY _SAPAE.HEAD
        SPREC-NATIVE-SEAL! _SAPA-SPREC>STATUS
    R> DROP ;

: _SAPA-PREFLIGHT-CANDIDATE  ( index work -- status )
    >R
    DUP R@ _SAPAW.CURRENT-INDEX !
    DUP R@ _SAPAW-CANDIDATE SPREC-CANDIDATE-VALID? 0= IF
        DROP R> DROP STREAMS-APPLY-S-INVALID EXIT
    THEN
    DUP R@ _SAPA-DUPLICATE-IN-BATCH? IF
        DROP R> DROP STREAMS-APPLY-S-DUPLICATE EXIT
    THEN
    DROP
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-CANDIDATE
    DUP OCC.NATIVE-A @ SWAP OCC.NATIVE-U @
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY
        _SAPAE.NATIVE-DIGEST SHA3-256-HASH
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-CANDIDATE
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY
        _SAPAE.SEMANTIC-DIGEST
        SPREC-CANDIDATE-SEMANTIC-DIGEST! _SAPA-SPREC>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-PROBE-NATIVE-BUCKET
    DUP IF
        >R DROP R> R> DROP EXIT
    THEN
    DROP
    IF
        R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY _SAPAE.HEAD
        DUP SPRH.LAST-SEEN-SEQUENCE @
        R@ _SAPAW.ACTIVE-RECORD SPRA.ATTEMPT-SEQUENCE @ >= IF
            DROP R> DROP STREAMS-APPLY-S-CORRUPT EXIT
        THEN
        R@ _SAPA-GET-LATEST-OBSERVATION
        DUP IF R> DROP EXIT THEN DROP
        R@ _SAPAW.STAGED-RECORD SPRO.SEMANTIC-DIGEST
        R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY
            _SAPAE.SEMANTIC-DIGEST
        SHA3-256-LEN _SAPA-BYTES= IF
            _SAPAE-ACTION-UNCHANGED
        ELSE
            _SAPAE-ACTION-REVISED
        THEN
        DUP
        R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY _SAPAE.ACTION !
        DUP R@ _SAPA-UPDATE-EXISTING-HEAD
        DUP IF NIP R> DROP EXIT THEN DROP
        _SAPAE-ACTION-UNCHANGED = IF
            1 R@ _SAPAW.UNCHANGED-COUNT +!
        ELSE
            R@ _SAPA-TARGET-REVISION-ABSENT
            DUP IF R> DROP EXIT THEN DROP
            1 R@ _SAPAW.REVISED-COUNT +!
        THEN
    ELSE
        _SAPAE-ACTION-NEW
        R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY _SAPAE.ACTION !
        R@ _SAPA-CONSTRUCT-NEW-HEAD
        DUP IF R> DROP EXIT THEN DROP
        R@ _SAPA-TARGET-REVISION-ABSENT
        DUP IF R> DROP EXIT THEN DROP
        1 R@ _SAPAW.NEW-COUNT +!
    THEN
    R> DROP STREAMS-APPLY-S-OK ;

\ The sealed source wrapper owns the exact per-source retained-version
\ aggregate.  This keeps configured observation-max admission O(batch);
\ the aggregate authority-root count is used only for repository-wide
\ arithmetic and never substituted for the per-source policy.
: _SAPA-COUNTER-CAPACITY  ( work -- status )
    >R
    R@ _SAPAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF DROP R> DROP STREAMS-APPLY-S-CORRUPT EXIT THEN
    DUP SAR.LOGICAL-GENERATION @ PERSIST-MAX-SIGNED >= IF
        DROP R> DROP STREAMS-APPLY-S-CAPACITY EXIT
    THEN
    DUP SAR.MUTATION-SEQUENCE @ PERSIST-MAX-SIGNED >= IF
        DROP R> DROP STREAMS-APPLY-S-CAPACITY EXIT
    THEN
    DUP SAR.ACTIVE-COUNT @ 0> 0= IF
        DROP R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    DUP SAR.OBSERVATION-COUNT @
    R@ _SAPAW.SOURCE-RECORD SPRS.OBSERVATION-COUNT @ < IF
        DROP R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    R@ _SAPAW.NEW-COUNT @ R@ _SAPAW.REVISED-COUNT @ +
    DUP R@ _SAPAW.SOURCE-RECORD SPRS.OBSERVATION-COUNT @ +
    DUP 0< IF
        2DROP DROP R> DROP STREAMS-APPLY-S-CAPACITY EXIT
    THEN
    R@ _SAPAW.SOURCE-RECORD SPRS.OBSERVATION-MAX @ > IF
        DROP DROP R> DROP STREAMS-APPLY-S-CAPACITY EXIT
    THEN
    OVER SAR.OBSERVATION-COUNT @ OVER +
    DUP 0< OVER PERSIST-MAX-SIGNED > OR IF
        DROP 2DROP R> DROP STREAMS-APPLY-S-CAPACITY EXIT
    THEN
    DROP
    DROP
    DUP SAR.NATIVE-COUNT @ R@ _SAPAW.NEW-COUNT @ +
    DUP 0< OVER PERSIST-MAX-SIGNED > OR IF
        DROP DROP R> DROP STREAMS-APPLY-S-CAPACITY EXIT
    THEN
    DROP DROP
    R> DROP STREAMS-APPLY-S-OK ;

: _SAPA-PREFLIGHT  ( work -- status )
    DUP 0 SWAP _SAPAW.NEW-COUNT !
    DUP 0 SWAP _SAPAW.REVISED-COUNT !
    DUP 0 SWAP _SAPAW.UNCHANGED-COUNT !
    DUP _SAPAW.ENTRIES OCHK-BATCH-MAX _SAPAE-SIZE * 0 FILL
    DUP _SAPAW.CANDIDATE-COUNT @ 0 ?DO
        I OVER _SAPA-PREFLIGHT-CANDIDATE
        DUP IF NIP UNLOOP EXIT THEN DROP
    LOOP
    _SAPA-COUNTER-CAPACITY ;

