    >R
    DUP OCC.FORMAT @ R@ SPRH.OBSERVATION-FORMAT @ =
    OVER OCC.NATIVE-KIND @ R@ SPRH.NATIVE-KIND @ = AND
    OVER OCC.NATIVE-U @ R@ SPRH.NATIVE-U @ = AND
    SWAP OCC.NATIVE-A @
    R@ SPRH.NATIVE
    R@ SPRH.NATIVE-U @ _SAPA-BYTES= AND
    R> DROP ;

