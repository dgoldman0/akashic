    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.REQUEST SAPAR.SOURCE-ID R@ _SAPA-ACTIVE-KEY
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.ACTIVE-RECORD R@ _SAPA-HISTORY-KEY
    DUP IF R> DROP EXIT THEN DROP

    R@ _SAPAW.KEY-0 STREAMS-PI-SOURCE-RID-KEY-SIZE
    R@ _SAPAW.STAGED-RECORD STREAMS-PERSISTENCE-RECORD-MAX
    R@ _SAPA-STAGED-GET
    DUP IF SWAP DROP R> DROP EXIT THEN
    DROP SPREC-SOURCE-SIZE <> IF
        R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    R@ _SAPAW.STAGED-RECORD
    R@ _SAPAW.SOURCE-RECORD
    SPREC-SOURCE-SIZE _SAPA-BYTES= 0= IF
        R> DROP STREAMS-APPLY-S-STALE EXIT
    THEN

    R@ _SAPAW.KEY-1 STREAMS-PI-ACTIVE-ATTEMPT-KEY-SIZE
    R@ _SAPAW.STAGED-RECORD STREAMS-PERSISTENCE-RECORD-MAX
    R@ _SAPA-STAGED-GET
    DUP IF SWAP DROP R> DROP EXIT THEN
    DROP SPREC-ATTEMPT-SIZE <> IF
        R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    R@ _SAPAW.STAGED-RECORD
    R@ _SAPAW.ACTIVE-RECORD
    SPREC-ATTEMPT-SIZE _SAPA-BYTES= 0= IF
        R> DROP STREAMS-APPLY-S-MISMATCH EXIT
    THEN

    R@ _SAPAW.KEY-2 STREAMS-PI-ATTEMPT-BY-SOURCE-KEY-SIZE
    R@ _SAPAW.STAGED-RECORD STREAMS-PERSISTENCE-RECORD-MAX
    R@ _SAPA-STAGED-GET
    DUP IF SWAP DROP R> DROP EXIT THEN
    DROP SPREC-ATTEMPT-SIZE <> IF
        R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    R@ _SAPAW.STAGED-RECORD
    R@ _SAPAW.HISTORY-RECORD
    SPREC-ATTEMPT-SIZE _SAPA-BYTES= 0= IF
        R> DROP STREAMS-APPLY-S-MISMATCH EXIT
    THEN
    R> _SAPA-REQUEST-ATTEMPT-EXACT? ;

