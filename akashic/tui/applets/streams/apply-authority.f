    R@ _SAPAW.KEY-1 STREAMS-PI-OBSERVATION-REVISION-KEY
        _SAPA-PI>STATUS
    DUP IF NIP R> DROP EXIT THEN DROP
    DUP SPRO.ACQUISITION-SEQUENCE @
    OVER SPRO.OBSERVATION-ID
    2 PICK SPRO.REVISION @
    R@ _SAPAW.KEY-2 STREAMS-PI-GLOBAL-TIME-KEY
        _SAPA-PI>STATUS
    DUP IF NIP R> DROP EXIT THEN DROP
    DUP SPRO.SOURCE-ID
    OVER SPRO.ACQUISITION-SEQUENCE @
    2 PICK SPRO.OBSERVATION-ID
    3 PICK SPRO.REVISION @
    R@ _SAPAW.KEY-3 STREAMS-PI-SOURCE-TIME-KEY
        _SAPA-PI>STATUS
    NIP R> DROP ;

: _SAPA-PREPARE-SOURCE-COUNT  ( work -- status )
    >R
    R@ _SAPAW.NEW-COUNT @ R@ _SAPAW.REVISED-COUNT @ +
    DUP 0= IF DROP R> DROP STREAMS-APPLY-S-OK EXIT THEN
    R@ _SAPAW.SOURCE-RECORD SPRS.OBSERVATION-COUNT +!
    R@ _SAPAW.SOURCE-RECORD SPREC-SOURCE-SEAL!
        _SAPA-SPREC>STATUS
    R> DROP ;

: _SAPA-STAGE-SOURCE  ( work -- status )
    >R
    R@ _SAPAW.NEW-COUNT @ R@ _SAPAW.REVISED-COUNT @ +
    0= IF R> DROP STREAMS-APPLY-S-OK EXIT THEN
    R@ _SAPAW.SOURCE-RECORD SPRS.ID R@ _SAPA-SOURCE-KEY
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.SOURCE-RECORD R@ _SAPA-SOURCE-ORDER-KEY
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.SOURCE-RECORD SPREC-SOURCE-SIZE
    R@ _SAPA-APPEND
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.KEY-0 STREAMS-PI-SOURCE-RID-KEY-SIZE
    R@ _SAPA-STAGED-PUT
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.KEY-1 STREAMS-PI-SOURCE-ORDER-KEY-SIZE
    R@ _SAPA-STAGED-PUT
    R> DROP ;

: _SAPA-STAGE-HEAD  ( index work -- status )
    >R
    DUP R@ _SAPAW.CURRENT-INDEX !
    DUP R@ _SAPAW-ENTRY R@ _SAPA-NATIVE-ENTRY-KEY
    DUP IF NIP R> DROP EXIT THEN DROP
    R@ _SAPAW-ENTRY _SAPAE.HEAD SPREC-NATIVE-HEAD-SIZE
    R@ _SAPA-APPEND
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.KEY-0 STREAMS-PI-NATIVE-HEAD-KEY-SIZE
    R@ _SAPA-STAGED-PUT
    R> DROP ;

: _SAPA-CONSTRUCT-OBSERVATION  ( index work -- status )
    >R
    DUP R@ _SAPAW.CURRENT-INDEX !
    R@ _SAPAW.OC-WORK STREAMS-OC-WORK-INIT _SAPA-OC>STATUS
    DUP IF NIP R> DROP EXIT THEN DROP
    R@ _SAPAW-CANDIDATE
    R@ _SAPAW.TERMINAL-RECORD
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY _SAPAE.HEAD
    R@ _SAPAW.OBSERVATION
    R@ _SAPAW.ADAPTER @ R@ _SAPAW.ADAPTER-WORK @
    R@ _SAPAW.OC-WORK STREAMS-OC-CONSTRUCT _SAPA-OC>STATUS
    R> DROP ;

: _SAPA-STAGE-OBSERVATION  ( work -- status )
    >R
    R@ _SAPAW.OBSERVATION R@ _SAPA-OBS-KEYS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.OBSERVATION SPREC-OBSERVATION-SIZE
    R@ _SAPA-APPEND
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.KEY-1 STREAMS-PI-OBSERVATION-REVISION-KEY-SIZE
    R@ _SAPA-STAGED-PUT
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.KEY-2 STREAMS-PI-GLOBAL-TIME-KEY-SIZE
    R@ _SAPA-STAGED-PUT
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.KEY-3 STREAMS-PI-SOURCE-TIME-KEY-SIZE
    R@ _SAPA-STAGED-PUT
    R> DROP ;

: _SAPA-STAGE-CANDIDATE  ( index work -- status )
    >R
    DUP R@ _SAPAW.CURRENT-INDEX !
    DUP R@ _SAPAW-ENTRY _SAPAE.ACTION @
        _SAPAE-ACTION-UNCHANGED <> IF
        DUP R@ _SAPA-CONSTRUCT-OBSERVATION
        DUP IF NIP R> DROP EXIT THEN DROP
        R@ _SAPA-STAGE-OBSERVATION
        DUP IF NIP R> DROP EXIT THEN DROP
    THEN
    R@ _SAPA-STAGE-HEAD
    R> DROP ;

: _SAPA-STAGE-BATCH  ( work -- status )
    DUP _SAPA-STAGE-BEGIN DUP IF NIP EXIT THEN DROP
    DUP _SAPA-STAGE-SOURCE DUP IF NIP EXIT THEN DROP
    DUP _SAPAW.CANDIDATE-COUNT @ 0 ?DO
        I OVER _SAPA-STAGE-CANDIDATE
        DUP IF NIP UNLOOP EXIT THEN DROP
    LOOP
    DROP STREAMS-APPLY-S-OK ;

