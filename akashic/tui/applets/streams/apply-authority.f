\ =====================================================================
\  apply-authority.f - atomic repository-backed refresh application
\ =====================================================================
\  This module is the successful configured-refresh commit authority.  It
\  owns no provider, XIO, decoder, component, Desk, Library-document,
\  output, draft, legacy-checkpoint, or public-Bluesky policy.
\
\  APPLY admits one exact durable ACCEPTED attempt and a bounded decoded
\  candidate batch.  Before it opens a hidden-root transaction it resolves
\  every exact native identity, digest collision, immutable revision,
\  unchanged value, source retention bound, and authority counter.  Duplicate
\  native identities in one batch are rejected as one complete batch.
\
\  Changed PBLOBs, immutable revisions, native heads, both time orderings,
\  the terminal SUCCEEDED attempt, and active-row removal are staged behind
\  caller-owned hidden roots.  The cleanup callback runs before success can
\  become visible.  After cleanup, the module revalidates the exact staged
\  source, active attempt, history record, request seal, and caller-supplied
\  component/request-generation verifier.  One STAGE-COMMIT then exposes all
\  four roots and advances the logical generation once.
\
\  Candidate-preflight, retention, cleanup, and stale-owner failures replace
\  the accepted attempt with a checked FAILED record when durable publication
\  remains possible.  Physical staging or publication failures never expose
\  a partial batch; the accepted attempt remains recovery evidence when the
\  failure cannot itself be terminalized.  A physically uncertain publication
\  leaves the bound PSTORE descriptor sticky-uncertain; the repository lifecycle
\  owner must recreate its repository/work descriptors before selecting the
\  authoritative old-or-new root and resuming mutation.
\
\  Callback contracts:
\    cleanup-xt    ( cleanup-context -- cleanup-error )
\    revalidate-xt ( frozen-request revalidate-context -- exact? )
\
\  The revalidator owns the runtime-only component-instance,
\  component-generation, and request-generation comparison.  This module
\  independently revalidates source revision, attempt ID, and request seal.
\  Both callbacks execute while the serialized Streams repository owner is
\  held and therefore must not re-enter repository mutation.
\
\  Public API:
\    STREAMS-APPLY-REQUEST-INIT       ( request -- status )
\    STREAMS-APPLY-REQUEST-VALID?     ( request -- flag )
\    STREAMS-APPLY-WORK-INIT          ( work -- status )
\    STREAMS-APPLY-WORK-VALID?        ( work -- flag )
\    STREAMS-APPLY-WORK-STATUS@       ( work -- status )
\    STREAMS-APPLY
\      ( request output-attempt repository repo-work work -- status )
\
\  output-attempt is an OCHK-SOURCE-SIZE value.  It changes only after a
\  durable terminal publication.  Consequently a successful apply returns a
\  SUCCEEDED value, while a durably terminalized semantic failure returns its
\  non-OK status with the corresponding FAILED value.
\ =====================================================================

