: STREAMS-APPLY
  ( request output-attempt repository repo-work work -- status )
    >R
    2DUP R@ _SAPA-PREPARE
    DUP IF
        R@ STREAMS-APPLY-WORK-VALID? IF
            DUP R@ _SAPAW.STATUS !
        THEN
        >R _SAPA-DROP4 R> R> DROP EXIT
    THEN DROP
    3 PICK R@ _SAPAW.REQUEST-A !
    2 PICK R@ _SAPAW.OUTPUT-A !
    R@ _SAPA-ARGS-SAFE? 0= IF
        STREAMS-APPLY-S-INVALID
        R@ _SAPA-WORK-STATUS! >R
        _SAPA-DROP4 R> R> DROP EXIT
    THEN
    R@ _SAPA-FREEZE-REQUEST
    ['] _SAPA-RUN R@ _SAPA-INVOKE
    >R _SAPA-DROP4 R> R> DROP ;
