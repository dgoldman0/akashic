        _SAPAE.HEAD SPRH.LAST-SEEN-SEQUENCE !
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY _SAPAE.ORDINAL @
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY
        _SAPAE.HEAD SPRH.COLLISION-ORDINAL !
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-CANDIDATE
    R@ _SAPAW.CURRENT-INDEX @ R@ _SAPAW-ENTRY _SAPAE.HEAD
