    >R
    R@ _SAPAW.ACTIVE-RECORD R@ _SAPA-HISTORY-KEY
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.KEY-2 STREAMS-PI-ATTEMPT-BY-SOURCE-KEY-SIZE
    R@ _SAPAW.HISTORY-RECORD STREAMS-PERSISTENCE-RECORD-MAX
    R@ _SAPA-GET
    DUP IF SWAP DROP R> DROP EXIT THEN
    DROP
    SPREC-ATTEMPT-SIZE =
    IF STREAMS-APPLY-S-OK ELSE STREAMS-APPLY-S-CORRUPT THEN
    R> DROP ;

: _SAPA-REQUEST-ATTEMPT-EXACT?  ( work -- status )
    >R
    R@ _SAPAW.ACTIVE-RECORD SPRA.SOURCE-ID
    R@ _SAPAW.REQUEST SAPAR.SOURCE-ID RID= 0= IF
        R> DROP STREAMS-APPLY-S-MISMATCH EXIT
    THEN
    R@ _SAPAW.ACTIVE-RECORD SPRA.SOURCE-REVISION @
    R@ _SAPAW.REQUEST SAPAR.SOURCE-REVISION @ <> IF
        R> DROP STREAMS-APPLY-S-STALE EXIT
    THEN
    R@ _SAPAW.ACTIVE-RECORD SPRA.ATTEMPT-ID
    R@ _SAPAW.REQUEST SAPAR.ATTEMPT-ID RID= 0= IF
        R> DROP STREAMS-APPLY-S-MISMATCH EXIT
    THEN
    R@ _SAPAW.ACTIVE-RECORD SPRA.REQUEST-SEAL
    R@ _SAPAW.REQUEST SAPAR.REQUEST-SEAL RID= 0= IF
        R> DROP STREAMS-APPLY-S-MISMATCH EXIT
    THEN
    R@ _SAPAW.ACTIVE-RECORD
    R@ _SAPAW.HISTORY-RECORD
    SPREC-ATTEMPT-SIZE _SAPA-BYTES= 0= IF
        R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    R@ _SAPAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF DROP R> DROP STREAMS-APPLY-S-CORRUPT EXIT THEN
    DUP SAR.ACTIVE-COUNT @ 0> 0= IF
        DROP R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    SAR.ACQUISITION-SEQUENCE @
    R@ _SAPAW.ACTIVE-RECORD SPRA.ATTEMPT-SEQUENCE @ < IF
        R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-APPLY-S-OK ;

: _SAPA-LOAD-ATTEMPT-EXACT  ( work -- status )
    >R
    R@ _SAPA-GET-ACTIVE DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-GET-HISTORY DUP IF
        DUP STREAMS-APPLY-S-NOT-FOUND = IF
            DROP STREAMS-APPLY-S-CORRUPT
        THEN
        R> DROP EXIT
    THEN DROP
    R> _SAPA-REQUEST-ATTEMPT-EXACT? ;

: _SAPA-LOAD-EXACT  ( work -- status )
    >R
    R@ _SAPA-GET-SOURCE DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-LOAD-ATTEMPT-EXACT DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.SOURCE-RECORD SPRS.REVISION @
    R@ _SAPAW.REQUEST SAPAR.SOURCE-REVISION @ <> IF
        R> DROP STREAMS-APPLY-S-STALE EXIT
    THEN
    R@ _SAPAW.SOURCE-RECORD SPRS.FLAGS @
        SSOURCE-F-ENABLED AND 0= IF
        R> DROP STREAMS-APPLY-S-STALE EXIT
    THEN
    R> DROP STREAMS-APPLY-S-OK ;

\ Staged revalidation runs only after cleanup and before the terminal attempt
\ or active-row deletion has been added to the hidden roots.
