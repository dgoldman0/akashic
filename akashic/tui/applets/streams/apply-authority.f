: _SAPA-MUTATION-CAPACITY  ( work -- status )
    >R
    R@ _SAPAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF DROP R> DROP STREAMS-APPLY-S-CORRUPT EXIT THEN
    DUP SAR.LOGICAL-GENERATION @ PERSIST-MAX-SIGNED >= IF
        DROP R> DROP STREAMS-APPLY-S-CAPACITY EXIT
    THEN
    DUP SAR.MUTATION-SEQUENCE @ PERSIST-MAX-SIGNED >= IF
        DROP R> DROP STREAMS-APPLY-S-CAPACITY EXIT
    THEN
    SAR.ACTIVE-COUNT @ 0> 0= IF
        R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-APPLY-S-OK ;

: _SAPA-APPEND-TERMINAL  ( work -- status )
    >R
    R@ _SAPAW.TERMINAL-RECORD SPREC-ATTEMPT-SIZE
    R@ _SAPA-APPEND
    R> DROP ;

: _SAPA-PUT-HISTORY  ( staged? work -- status )
    >R
    DUP IF
        DROP
        R@ _SAPAW.KEY-2 STREAMS-PI-ATTEMPT-BY-SOURCE-KEY-SIZE
        R@ _SAPA-STAGED-PUT
    ELSE
        DROP
        R@ _SAPAW.KEY-2 STREAMS-PI-ATTEMPT-BY-SOURCE-KEY-SIZE
        R@ _SAPA-PUT
    THEN
    R> DROP ;

: _SAPA-DELETE-ACTIVE  ( staged? work -- status )
    >R
    DUP IF
        DROP
        R@ _SAPAW.KEY-1 STREAMS-PI-ACTIVE-ATTEMPT-KEY-SIZE
        R@ _SAPA-STAGED-DELETE
    ELSE
        DROP
        R@ _SAPAW.KEY-1 STREAMS-PI-ACTIVE-ATTEMPT-KEY-SIZE
        R@ _SAPA-DELETE
    THEN
    DUP STREAMS-APPLY-S-NOT-FOUND = IF
        DROP STREAMS-APPLY-S-CORRUPT
    THEN
    R> DROP ;

: _SAPA-TERMINAL-KEYS  ( work -- status )
    >R
    R@ _SAPAW.REQUEST SAPAR.SOURCE-ID R@ _SAPA-ACTIVE-KEY
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.ACTIVE-RECORD R@ _SAPA-HISTORY-KEY
    R> DROP ;

: _SAPA-DECREMENT-ACTIVE  ( work -- status )
    >R
    R@ _SAPAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF DROP R> DROP STREAMS-APPLY-S-CORRUPT EXIT THEN
    DUP SAR.ACTIVE-COUNT @ 0> 0= IF
        DROP R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    -1 SWAP SAR.ACTIVE-COUNT +!
    R> DROP STREAMS-APPLY-S-OK ;

: _SAPA-PUBLISH-FAILURE  ( work -- status )
    >R
    \ A source may have been replaced or disabled after this accepted
    \ attempt.  Failure publication therefore revalidates the exact attempt
    \ authority without requiring the old source revision to remain current.
    R@ _SAPA-LOAD-ATTEMPT-EXACT DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-MUTATION-CAPACITY DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-BUILD-FAILURE-ATTEMPT DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-TERMINAL-KEYS DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-BEGIN-TX DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-APPEND-TERMINAL DUP IF R> DROP EXIT THEN DROP
    0 R@ _SAPA-PUT-HISTORY DUP IF R> DROP EXIT THEN DROP
    0 R@ _SAPA-DELETE-ACTIVE DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-DECREMENT-ACTIVE DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-COMMIT
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.TERMINAL-RECORD SPRA.ATTEMPT
    R@ _SAPAW.OUTPUT-A @ OCHK-SOURCE-SIZE MOVE
    R@ _SAPAW.RETURN-STATUS @ R> DROP ;

: _SAPA-STAGE-TERMINAL  ( work -- status )
    >R
    R@ _SAPA-TERMINAL-KEYS DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-APPEND-TERMINAL DUP IF R> DROP EXIT THEN DROP
    -1 R@ _SAPA-PUT-HISTORY DUP IF R> DROP EXIT THEN DROP
    -1 R@ _SAPA-DELETE-ACTIVE DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-DECREMENT-ACTIVE DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF DROP R> DROP STREAMS-APPLY-S-CORRUPT EXIT THEN
    R@ _SAPAW.NEW-COUNT @ R@ _SAPAW.REVISED-COUNT @ +
        OVER SAR.OBSERVATION-COUNT +!
    R@ _SAPAW.NEW-COUNT @ SWAP SAR.NATIVE-COUNT +!
    R> DROP STREAMS-APPLY-S-OK ;

\ ---------------------------------------------------------------------
\ Semantic failure terminalization and complete apply operation
\ ---------------------------------------------------------------------

: _SAPA-SET-FAILURE  ( return-status outcome work -- )
    >R
    R@ _SAPAW.FAIL-OUTCOME !
    R@ _SAPAW.RETURN-STATUS !
    R> DROP ;

: _SAPA-SEMANTIC-FAILURE  ( return-status outcome work -- status )
    >R
    R@ _SAPA-SET-FAILURE
    R@ _SAPA-CALL-CLEANUP
    R@ _SAPAW.CLEANUP-ERROR @ IF
        STREAMS-APPLY-S-CLEANUP OCHK-O-CLEANUP
        R@ _SAPA-SET-FAILURE
    THEN
    R@ _SAPA-CALL-REVALIDATE
    STREAMS-APPLY-S-OK <> IF
        R@ _SAPAW.CLEANUP-ERROR @ 0= IF
            STREAMS-APPLY-S-STALE OCHK-O-STALE
            R@ _SAPA-SET-FAILURE
        THEN
    THEN
    R> _SAPA-PUBLISH-FAILURE ;

: _SAPA-DISCARD-AND-FAIL
  ( return-status outcome work -- status )
    >R
    R@ _SAPA-STAGE-DISCARD
    DUP IF
        >R 2DROP R> R> DROP EXIT
    THEN DROP
    R> _SAPA-SEMANTIC-FAILURE ;

: _SAPA-PREFLIGHT-OUTCOME  ( status -- outcome|0 )
    DUP STREAMS-APPLY-S-INVALID =
    OVER STREAMS-APPLY-S-DUPLICATE = OR IF
        DROP OCHK-O-DECODE EXIT
    THEN
    STREAMS-APPLY-S-CAPACITY =
    IF OCHK-O-CAPACITY ELSE 0 THEN ;

: _SAPA-RUN  ( work -- status )
    >R
    R@ _SAPA-READY DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-LOAD-EXACT
    DUP IF
        DUP STREAMS-APPLY-S-STALE = IF
            OCHK-O-STALE R@ _SAPA-SEMANTIC-FAILURE
            R> DROP EXIT
        THEN
        R> DROP EXIT
    THEN DROP
    R@ _SAPA-PREFLIGHT
    DUP IF
        DUP _SAPA-PREFLIGHT-OUTCOME DUP IF
            R@ _SAPA-SEMANTIC-FAILURE R> DROP EXIT
        THEN
        DROP R> DROP EXIT
    THEN DROP
    R@ _SAPA-BUILD-SUCCESS-ATTEMPT
    DUP IF
        DUP STREAMS-APPLY-S-INVALID = IF
            OCHK-O-DECODE R@ _SAPA-SEMANTIC-FAILURE
            R> DROP EXIT
        THEN
        R> DROP EXIT
    THEN DROP
    R@ _SAPA-PREPARE-SOURCE-COUNT
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-STAGE-BATCH
    DUP IF R> DROP EXIT THEN DROP

    R@ _SAPA-CALL-CLEANUP
    R@ _SAPAW.CLEANUP-ERROR @ IF
        STREAMS-APPLY-S-CLEANUP OCHK-O-CLEANUP
        R@ _SAPA-DISCARD-AND-FAIL R> DROP EXIT
    THEN
    R@ _SAPA-CALL-REVALIDATE
    DUP IF
        DUP STREAMS-APPLY-S-STALE = IF
            OCHK-O-STALE R@ _SAPA-DISCARD-AND-FAIL
            R> DROP EXIT
        THEN
        R> DROP EXIT
    THEN DROP
    R@ _SAPA-STAGED-REVALIDATE
    DUP IF
        DUP STREAMS-APPLY-S-STALE =
        OVER STREAMS-APPLY-S-MISMATCH = OR IF
            DROP STREAMS-APPLY-S-STALE OCHK-O-STALE
            R@ _SAPA-DISCARD-AND-FAIL R> DROP EXIT
        THEN
        R> DROP EXIT
    THEN DROP
    R@ _SAPA-STAGE-TERMINAL
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPA-STAGE-COMMIT
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.TERMINAL-RECORD SPRA.ATTEMPT
    R@ _SAPAW.OUTPUT-A @ OCHK-SOURCE-SIZE MOVE
    R> DROP STREAMS-APPLY-S-OK ;

