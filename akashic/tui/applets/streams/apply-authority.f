: _SAPA-GET-SOURCE  ( work -- status )
    >R
    R@ _SAPAW.REQUEST SAPAR.SOURCE-ID R@ _SAPA-SOURCE-KEY
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.KEY-0 STREAMS-PI-SOURCE-RID-KEY-SIZE
    R@ _SAPAW.SOURCE-RECORD STREAMS-PERSISTENCE-RECORD-MAX
    R@ _SAPA-GET
    DUP IF SWAP DROP R> DROP EXIT THEN
    DROP
    DUP SPREC-SOURCE-SIZE = IF
        DROP
        R@ _SAPAW.SOURCE-RECORD SPREC.KIND @
            SPREC-KIND-SOURCE = IF
            R> DROP STREAMS-APPLY-S-OK EXIT
        THEN
        R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    SPREC-SOURCE-TOMBSTONE-SIZE = IF
        R@ _SAPAW.SOURCE-RECORD SPREC.KIND @
            SPREC-KIND-SOURCE-TOMBSTONE = IF
            R> DROP STREAMS-APPLY-S-GONE EXIT
        THEN
        R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-APPLY-S-CORRUPT ;

: _SAPA-GET-ACTIVE  ( work -- status )
    >R
    R@ _SAPAW.REQUEST SAPAR.SOURCE-ID R@ _SAPA-ACTIVE-KEY
    DUP IF R> DROP EXIT THEN DROP
    R@ _SAPAW.KEY-1 STREAMS-PI-ACTIVE-ATTEMPT-KEY-SIZE
    R@ _SAPAW.ACTIVE-RECORD STREAMS-PERSISTENCE-RECORD-MAX
    R@ _SAPA-GET
    DUP IF SWAP DROP R> DROP EXIT THEN
    DROP
    SPREC-ATTEMPT-SIZE <> IF
        R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    R@ _SAPAW.ACTIVE-RECORD SPRA.STATE @
        OCHK-ATTEMPT-ACCEPTED <> IF
        R> DROP STREAMS-APPLY-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-APPLY-S-OK ;

