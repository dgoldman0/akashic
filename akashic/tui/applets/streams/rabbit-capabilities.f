: _SRBCAP-HEX-NIBBLE  ( c -- nibble flag )
    DUP [CHAR] 0 >= OVER [CHAR] 9 <= AND IF
        [CHAR] 0 - -1 EXIT
    THEN
    DUP [CHAR] a >= OVER [CHAR] f <= AND IF
        [CHAR] a - 10 + -1 EXIT
    THEN
    DROP 0 0 ;

: _SRBCAP-H64@  ( value destination -- flag )
    _SRBCAPH-DESTINATION !
    DUP 0= IF DROP 0 EXIT THEN
    DUP CV-TYPE@ CV-T-STRING <> IF DROP 0 EXIT THEN
    DUP CV-LEN@ SHA3-256-HEX-LEN <> IF DROP 0 EXIT THEN
    CV-DATA@ DUP 0= IF DROP 0 EXIT THEN _SRBCAPH-SOURCE !
    SHA3-256-LEN 0 ?DO
        _SRBCAPH-SOURCE @ I 2 * + C@ _SRBCAP-HEX-NIBBLE 0= IF
            DROP 0 UNLOOP EXIT
        THEN
        _SRBCAPH-HI !
        _SRBCAPH-SOURCE @ I 2 * 1+ + C@ _SRBCAP-HEX-NIBBLE 0= IF
            DROP 0 UNLOOP EXIT
        THEN
        _SRBCAPH-HI @ 4 LSHIFT OR
            _SRBCAPH-DESTINATION @ I + C!
    LOOP
    -1 ;

