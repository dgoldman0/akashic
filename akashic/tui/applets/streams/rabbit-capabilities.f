: _SRBCAP-HANDLER-RUN  ( request instance body-xt -- bus-status )
    >R
    _SRBCAP-BUSY @ IF
        R> DROP DROP _SRBCAP-BUSY-ERROR EXIT
    THEN
    -1 _SRBCAP-BUSY !
    _SRBCAP-INSTANCE ! _SRBCAP-REQUEST !
    _SRBCAP-REQUEST @ CBR-ERROR-CLEAR
    _SRBCAP-SCRATCH-WIPE
    _SRBCAP-BUILDER-READY DUP IF
        _SRBCAP-CONSTRUCTION-ERROR _SRBCAP-BUS-STATUS !
        R> DROP
    ELSE
        DROP
        R> CATCH
        ?DUP IF
            DROP SRBPROV-S-FAULT _SRBCAP-MANAGER>CBUS
        THEN
        _SRBCAP-BUS-STATUS !
    THEN
    _SRBCAP-BUILDER CVB-ABORT ?DUP IF
        _SRBCAP-CONSTRUCTION-ERROR _SRBCAP-BUS-STATUS !
    THEN
    _SRBCAP-SCRATCH-WIPE
    0 _SRBCAP-INSTANCE ! 0 _SRBCAP-REQUEST !
    0 _SRBCAP-BUSY !
    _SRBCAP-BUS-STATUS @ ;

