\ =====================================================================
\ rabbit-capabilities.f - exact Streams Burrow capability surface
\ =====================================================================
\ Four static descriptors adapt the activation-local Rabbit manager to the
\ capability bus.  The adapter owns no manager, provider, CINST, or durable
\ state.  A Streams-owned resolver supplies the manager for the live instance
\ and an invalidator dirties the visible applet only after a fresh commit.
\
\ Mutation results are constructed and deeply schema-validated in an owned
\ CVB candidate before SRBMGR-COMMIT.  A construction failure therefore cannot
\ mutate manager state.  Exact manager replay publishes the same typed result
\ with CBUS-S-NO-EFFECT; only a fresh commit returns CBUS-S-OK.
\ =====================================================================

