\ =====================================================================
\ rabbit-remote-sub.f - persistent typed Rabbit subscription ownership
\ =====================================================================
\ One caller-owned descriptor registers exactly one neutral Rabbit
\ subscription entry and publishes accepted EVENT bodies through one
\ STREAMS-RABBIT-REMOTE-RESOURCE cache.  The connector remains owned by the
\ surrounding mux: this module never polls it and CONSUME claims only the
\ exact entry/generation item returned by that mux.
\
\ The neutral callback copies no borrowed frame address.  It validates the
\ exact target and View, decodes once into resource-owned staging, and carries
\ only the scalar stage generation across the poll boundary.  The immutable
\ event validator supplied at INIT binds that decoded value and the exact raw
\ bytes to Lane/Event-Seq/delivery evidence before the callback may COMMIT.
\ A new EVENT is published only after CONSUME proves that the enclosing client
\ commit also succeeded.  Duplicate and rejected stages are discarded by the
\ same exact token.  Cleanup failures retain that action for EVENT-RETRY.
\ The surrounding mux must not poll again while PENDING@ reports a non-NONE
\ action; the retained stage is the only authoritative transaction in that
\ interval.
\
\ Registration survives connector replacement.  RECONCILE mirrors the
\ neutral entry after coordinated connector detach; REBIND then emits the
\ cursor retained by the neutral owner.  FINI deliberately refuses a bound,
\ binding, result-bearing, or staged entry.  The caller must finish staging,
\ resolve any bind result, coordinate connector detach when bound, reconcile,
\ and only then release this entry.
\
\ Target and result slices returned by accessors are borrowed with the
\ lifetimes documented by rabbit-remote.f and rabbit-connector.f.  The
\ connector and remote resource must outlive this owner.
\ =====================================================================

\ Keep the KDOS module identity within 23 bytes.
