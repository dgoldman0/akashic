            STREAMS-RABBIT-REMOTE-SUB-DETAIL-BIND
            STREAMS-RABBIT-REMOTE-SUB-E-STATE-MISMATCH
                _SRRSQ-O @ _SRRS-STATUS! EXIT
        THEN
    ELSE _SRRSQ-ENTRY-STATE @ RSUB-ENTRY-BIND-RESULT = IF
        _SRRSQ-O @ SRRS.STATE @ DUP
            STREAMS-RABBIT-REMOTE-SUB-ST-BINDING =
        SWAP STREAMS-RABBIT-REMOTE-SUB-ST-BIND-RESULT = OR 0= IF
            STREAMS-RABBIT-REMOTE-SUB-S-STATE
            STREAMS-RABBIT-REMOTE-SUB-DETAIL-BIND
            STREAMS-RABBIT-REMOTE-SUB-E-STATE-MISMATCH
