        STREAMS-RABBIT-REMOTE-SUB-ST-BIND-RESULT _SRRSQ-O @ SRRS.STATE !
    ELSE
        STREAMS-RABBIT-REMOTE-SUB-S-STATE
        STREAMS-RABBIT-REMOTE-SUB-DETAIL-CONNECTOR
        _SRRSQ-ENTRY-STATE @ _SRRSQ-O @ _SRRS-STATUS! EXIT
    THEN THEN THEN THEN THEN
    STREAMS-RABBIT-REMOTE-SUB-S-OK
    STREAMS-RABBIT-REMOTE-SUB-DETAIL-NONE 0
