    _SRRSQ-CS @ STREAMS-RABBIT-CONNECTOR-S-OK <> IF
        _SRRSQ-CS @ _SRRS-CONNECTOR>STATUS
        STREAMS-RABBIT-REMOTE-SUB-DETAIL-CONNECTOR _SRRSQ-CS @
