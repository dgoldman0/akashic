    DUP _SRRSQ-O ! _SRRS-VALID? 0= IF
        STREAMS-RABBIT-REMOTE-SUB-S-INVALID EXIT
    THEN
    _SRRSQ-O @ SRRS.EVENT-ACTION @
        STREAMS-RABBIT-REMOTE-SUB-ACTION-NONE <>
    _SRRSQ-O @ SRRS.CALLBACK-SEEN @ 0<> OR
    _SRRSQ-O @ SRRS.CALLBACK-CONFLICT @ 0<> OR IF
        STREAMS-RABBIT-REMOTE-SUB-S-BUSY EXIT
    THEN
