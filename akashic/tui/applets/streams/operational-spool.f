\ The caller source contract is
\   ( logical-offset destination requested-u context -- actual-u status ).
\ PBLOB contains this callback, verifies exact production, and poisons a
\ proposal if any emitted chunk is followed by failure.  The tee absorbs only
\ an exact produced chunk into caller-owned SHA3 state.
: _SSPW-TEE-SOURCE
  ( logical-offset destination requested-u work -- actual-u persist-status )
    >R
    OVER R@ _SSPW.CHUNK-A !
    DUP R@ _SSPW.CHUNK-U !
    R@ _SSPW.SOURCE-CONTEXT @
    R@ _SSPW.SOURCE-XT @ EXECUTE
    DUP IF R> DROP EXIT THEN
    DROP
    DUP R@ _SSPW.CHUNK-U @ <> IF
        PERSIST-S-CORRUPT R> DROP EXIT
    THEN
    DROP
    R@ _SSPW.CHUNK-A @ R@ _SSPW.CHUNK-U @
        R@ _SSPW.HASH SHA3-256-CONTEXT-UPDATE
    _SSP-S3CTX>PERSIST
    DUP IF
        0 SWAP
    ELSE
        DROP R@ _SSPW.CHUNK-U @ PERSIST-S-OK
    THEN
    R> DROP ;

: _SSPW-HASH-SINK
  ( logical-offset payload-a payload-u work -- persist-status )
    >R ROT DROP
    R@ _SSPW.HASH SHA3-256-CONTEXT-UPDATE
    _SSP-S3CTX>PERSIST
    R> DROP ;

: _SSPW-HASH-INIT  ( work -- status )
    _SSPW.HASH SHA3-256-CONTEXT-INIT
    _SSP-S3CTX>STATUS ;

: _SSPW-HASH-VERIFY  ( expected-digest work -- status )
    >R
    R@ _SSPW.HASH SHA3-256-CONTEXT-FINAL-COMPARE
    DUP IF
        >R DROP R> _SSP-S3CTX>STATUS R> DROP EXIT
    THEN
    DROP
    IF STREAMS-SPOOL-S-OK ELSE STREAMS-SPOOL-S-CORRUPT THEN
    R> DROP ;

