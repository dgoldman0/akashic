    >R
    DUP STREAMS-SPOOL-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    R@ STREAMS-SPOOL-WORK-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    R@ _SSPW.SPOOL @ OVER <> IF DROP R> DROP 0 EXIT THEN
    DUP STREAMS-SPOOL-SIZE R@ STREAMS-SPOOL-WORK-SIZE
        MSPAN-OVERLAP? IF DROP R> DROP 0 EXIT THEN
    DUP STREAMS-SPOOL-SIZE R@ _SSPW.PSTORE-WORK @
        PSTORE-WORK-SPAN-DISJOINT? 0= IF DROP R> DROP 0 EXIT THEN
    DUP _SSP-D.STORE @
    R@ STREAMS-SPOOL-WORK-SIZE 2 PICK PSTORE-SPAN-DISJOINT?
    NIP NIP R> DROP ;

