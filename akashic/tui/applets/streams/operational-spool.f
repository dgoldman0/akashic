: _SSPW-RECONCILE-CURRENT  ( work -- status )
    >R
    R@ _SSPW-CARDINALITIES? 0= IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    R@ _SSPW-SCAN-CONNECTORS-CURRENT _SSP-COLD>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW-SCAN-FLOWS-CURRENT _SSP-COLD>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW-SCAN-CHECKPOINTS-CURRENT _SSP-COLD>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW-SCAN-USAGE-CURRENT _SSP-COLD>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW-SCAN-ATTEMPTS-CURRENT _SSP-COLD>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW-SCAN-DISPATCH-CURRENT _SSP-COLD>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW-SCAN-TERMINAL-CURRENT _SSP-COLD>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW-SCAN-IDEMPOTENCY-CURRENT _SSP-COLD>STATUS
    DUP IF R> DROP EXIT THEN DROP
    _SSPW-STATE-READY R@ _SSPW.STATE !
    R> DROP STREAMS-SPOOL-S-OK ;

: _SSPW-OPEN-FULL-RUN  ( work -- status )
    >R
    R@ _SSPW-OPEN-RUN
    DUP STREAMS-SPOOL-S-ABSENT = IF R> DROP EXIT THEN
    _SSP-COLD>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW-COLD-PHYSICAL-AUDIT
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW-RECONCILE-CURRENT
    DUP IF
        _SSPW-STATE-REOPEN R@ _SSPW.STATE !
    THEN
    R> DROP ;

: STREAMS-SPOOL-OPEN  ( spool work -- status )
    2DUP _SSPW-ENTER DUP IF >R 2DROP R> EXIT THEN DROP
    DUP ['] _SSPW-OPEN-FULL-RUN _SSPW-WORK-CATCH
    ROT ROT _SSPW-LEAVE ;

: STREAMS-SPOOL-REBIND  ( spool work -- status )
    STREAMS-SPOOL-OPEN ;

