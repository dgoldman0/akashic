\ ADMIT snapshots the request descriptor before invoking its source.  The
\ result destination is written only for a fully verified replay or after the
\ new root is independently known durable.
: STREAMS-SPOOL-ADMIT  ( request result spool work -- status )
    3 PICK STREAMS-SPOOL-REQUEST-VALID? 0= IF
        _SSP-DROP4 STREAMS-SPOOL-S-INVALID EXIT
    THEN
    2 PICK 0= IF _SSP-DROP4 STREAMS-SPOOL-S-INVALID EXIT THEN
    2 PICK STREAMS-SPOOL-RESULT-SIZE
        MSPAN-NONWRAPPING? 0= IF
        _SSP-DROP4 STREAMS-SPOOL-S-INVALID EXIT
    THEN
    2DUP _SSP-BOUND? 0= IF
        _SSP-DROP4 STREAMS-SPOOL-S-INVALID EXIT
    THEN
    3 PICK STREAMS-SPOOL-REQUEST-SIZE
    4 PICK STREAMS-SPOOL-RESULT-SIZE MSPAN-OVERLAP? IF
        _SSP-DROP4 STREAMS-SPOOL-S-INVALID EXIT
    THEN
    3 PICK STREAMS-SPOOL-REQUEST-SIZE
        2 PICK _SSPW-SPAN-SAFE? 0= IF
        _SSP-DROP4 STREAMS-SPOOL-S-INVALID EXIT
    THEN
    2 PICK STREAMS-SPOOL-RESULT-SIZE
        2 PICK _SSPW-SPAN-SAFE? 0= IF
        _SSP-DROP4 STREAMS-SPOOL-S-INVALID EXIT
    THEN
    2DUP _SSPW-ENTER DUP IF
        >R _SSP-DROP4 R> EXIT
    THEN DROP
    >R DROP
    OVER R@ _SSPW.ATTEMPT STREAMS-SPOOL-REQUEST-SIZE MOVE
    R@ _SSPW.ATTEMPT DUP SPOOLREQ.SELF !
    R@ _SSPW.ATTEMPT R@ _SSPW.REQUEST !
    R@ _SSPW.ATTEMPT SPOOLREQ.SOURCE-XT @
        R@ _SSPW.SOURCE-XT !
    R@ _SSPW.ATTEMPT SPOOLREQ.SOURCE-CONTEXT @
        R@ _SSPW.SOURCE-CONTEXT !
    DUP R@ _SSPW.RESULT !
    2DROP
    R@ ['] _SSPW-ADMIT-RUN _SSPW-WORK-CATCH
    0 R@ _SSPW.REQUEST !
    0 R@ _SSPW.RESULT !
    0 R@ _SSPW.SOURCE-XT !
    0 R@ _SSPW.SOURCE-CONTEXT !
    0 R@ _SSPW.CHUNK-A !
    0 R@ _SSPW.CHUNK-U !
    R@ _SSPW.SPOOL @ R@ _SSPW-LEAVE
    R> DROP ;

