: _SSPW-PUBLISH  ( work -- status )
    >R
    R@ _SSPW.STATE @ _SSPW-STATE-ACTIVE <> IF
        R> DROP STREAMS-SPOOL-S-BUSY EXIT
    THEN
    R@ _SSPW.TX-PHASE @ _SSPW-TX-STORE-RECLAIM <> IF
        R> DROP STREAMS-SPOOL-S-BUSY EXIT
    THEN
    R@ _SSPW.FUTURE-RETIREMENT @
        RECLAIM-FINALIZE-RETIREMENT-MAX <> IF
        STREAMS-SPOOL-S-CORRUPT R@ _SSPW-ABORT-ACTIVE
        R> DROP EXIT
    THEN
    R@ _SSPW-ROOTS-ADVANCE
    DUP IF R@ _SSPW-ABORT-ACTIVE R> DROP EXIT THEN DROP
    R@
    R@ _SSPW.SPOOL @ _SSP-D.STORE @
    R@ _SSPW.PSTORE-WORK @ _SSPW-ALLOCATE
    DUP IF
        _SSP-PERSIST>STATUS >R DROP R>
        R@ _SSPW-ABORT-ACTIVE R> DROP EXIT
    THEN DROP
    R@ _SSPW.APP-ROOT-PAGE !
    R@ _SSPW.PAGE PERSIST-PAGE-PAYLOAD-SIZE 0 FILL
    R@ _SSPW.PAGE PERSIST-PAGE-PAYLOAD-SIZE
    R@ _SSPW.APP-ROOT-PAGE @
    R@ _SSPW.SPOOL @ _SSP-D.STORE @
    R@ _SSPW.PSTORE-WORK @ PSTORE-WRITE-PAGE-TX
    DUP IF
        _SSP-PERSIST>STATUS R@ _SSPW-ABORT-ACTIVE
        R> DROP EXIT
    THEN DROP
    R@ _SSPW.RECLAIM-WORK RECLAIM-FINALIZE
    DUP IF
        _SSP-PERSIST>STATUS R@ _SSPW-ABORT-ACTIVE
        R> DROP EXIT
    THEN DROP
    R@ _SSPW-WORK>ROOT
    DUP IF R@ _SSPW-ABORT-ACTIVE R> DROP EXIT THEN DROP
    R@ _SSPW.CURRENT-ROOT R@ _SSPW.PAGE STREAMS-OPROOT-SIZE MOVE
    R@ _SSPW.PAGE PERSIST-PAGE-PAYLOAD-SIZE
    R@ _SSPW.APP-ROOT-PAGE @
    R@ _SSPW.SPOOL @ _SSP-D.STORE @
    R@ _SSPW.PSTORE-WORK @ PSTORE-WRITE-PAGE-TX
    DUP IF
        _SSP-PERSIST>STATUS R@ _SSPW-ABORT-ACTIVE
        R> DROP EXIT
    THEN DROP
    R@ _SSPW.APP-ROOT-PAGE @
    R@ _SSPW.SPOOL @ _SSP-D.STORE @
    R@ _SSPW.PSTORE-WORK @ PSTORE-APPLICATION-ROOT!
    DUP IF
        _SSP-PERSIST>STATUS R@ _SSPW-ABORT-ACTIVE
        R> DROP EXIT
    THEN DROP
    R@ _SSPW.SPOOL @ _SSP-D.STORE @
    R@ _SSPW.PSTORE-WORK @ PSTORE-COMMIT
    _SSPW-TX-RECLAIM R@ _SSPW.TX-PHASE !
    _SSP-PERSIST>STATUS R@ _SSPW.TEMP-STATUS !
    0 R@ _SSPW.FUTURE-RETIREMENT !
    R@ _SSPW-COMMIT-DURABLE? IF
        -1 R@ _SSPW.DURABLE !
        R@ _SSPW.SPOOL @ _SSP-D.STORE @ PSTORE-GENERATION@
            R@ _SSPW.BASE-GENERATION !
        STREAMS-SPOOL-S-OK R@ _SSPW.TEMP-STATUS !
        R@ _SSPW.RECLAIM-WORK R@ _SSPW.RECLAIM RECLAIM-ADOPT
        DUP IF
            DROP
            R@ _SSPW.RECLAIM-WORK RECLAIM-ABORT
            DUP PERSIST-S-OK = IF
                DROP _SSPW-TX-NONE R@ _SSPW.TX-PHASE !
            ELSE
                DROP
            THEN
            _SSPW-STATE-REOPEN R@ _SSPW.STATE !
        ELSE
            DROP
            _SSPW-TX-NONE R@ _SSPW.TX-PHASE !
            _SSPW-STATE-READY R@ _SSPW.STATE !
        THEN
    ELSE
        R@ _SSPW.TEMP-STATUS @ STREAMS-SPOOL-S-OK = IF
            STREAMS-SPOOL-S-UNCERTAIN R@ _SSPW.TEMP-STATUS !
        THEN
        R@ _SSPW.TEMP-STATUS @ R@ _SSPW-ABORT-ACTIVE
            R@ _SSPW.TEMP-STATUS !
    THEN
    R@ _SSPW.TEMP-STATUS @ R> DROP ;

