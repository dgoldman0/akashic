    R@ _SSPW-LOOKUP-ATTEMPT-CURRENT
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW.RECORD SOPATT.CONNECTOR-ID
        R@ _SSPW.CONNECTOR RID= 0= IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
