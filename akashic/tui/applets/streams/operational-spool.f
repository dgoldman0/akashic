: _SSPW-ABORT-TRANSACTION  ( work -- cleanup-status )
    >R
    STREAMS-SPOOL-S-OK R@ _SSPW.PAGE-ID !
    R@ _SSPW.TX-PHASE @ _SSPW-TX-HAS-STORE? IF
        R@ _SSPW.SPOOL @ _SSP-D.STORE @
        R@ _SSPW.PSTORE-WORK @ PSTORE-ABORT
        DUP PERSIST-S-OK <> IF
            _SSP-PERSIST>STATUS R@ _SSPW.PAGE-ID !
        ELSE
            DROP
        THEN
    THEN
    R@ _SSPW.PAGE-ID @ STREAMS-SPOOL-S-OK =
    R@ _SSPW.TX-PHASE @ _SSPW-TX-HAS-RECLAIM? AND IF
        R@ _SSPW.RECLAIM-WORK RECLAIM-ABORT
        DUP PERSIST-S-OK <> IF
            _SSP-PERSIST>STATUS R@ _SSPW.PAGE-ID !
        ELSE
            DROP
        THEN
    THEN
    R@ _SSPW.PAGE-ID @ STREAMS-SPOOL-S-OK = IF
        _SSPW-TX-NONE R@ _SSPW.TX-PHASE !
    THEN
    0 R@ _SSPW.FUTURE-RETIREMENT !
    R@ _SSPW.PAGE-ID @ R> DROP ;

: _SSPW-ABORT-ACTIVE  ( primary-status work -- final-status )
    >R
    R@ _SSPW-ABORT-TRANSACTION
    _SSPW-STATE-REOPEN R@ _SSPW.STATE !
    DUP IF
        NIP R> DROP EXIT
    THEN
    DROP
    R@ _SSPW-OLD-AUTHORITY-SELECTED? 0= IF
        DROP R> DROP STREAMS-SPOOL-S-UNCERTAIN EXIT
    THEN
    R@ _SSPW-RESTORE-CURRENT
    DUP STREAMS-SPOOL-S-ABSENT = IF
        DROP _SSPW-STATE-READY R@ _SSPW.STATE !
        R> DROP EXIT
    THEN
    DUP IF
        NIP R> DROP EXIT
    THEN
    DROP _SSPW-STATE-READY R@ _SSPW.STATE !
    R> DROP ;

\ A throw during cold proof has no prior active authority to restore.  Abort
\ the borrowed read-only store proposal and leave publication closed.
: _SSPW-ABORT-REOPEN  ( primary-status work -- final-status )
    >R
    R@ _SSPW-ABORT-TRANSACTION
    _SSPW-STATE-REOPEN R@ _SSPW.STATE !
    DUP IF
        NIP R> DROP EXIT
    THEN
    DROP R> DROP ;

: _SSPW-WORK-CATCH  ( work body-xt -- status )
    >R DUP R> CATCH
    DUP IF
        DROP DROP
        DUP _SSPW.TX-PHASE @ _SSPW-TX-NONE <> IF
            DUP _SSPW.STATE @ _SSPW-STATE-ACTIVE = IF
                STREAMS-SPOOL-S-FAULT OVER _SSPW-ABORT-ACTIVE NIP
            ELSE
                STREAMS-SPOOL-S-FAULT OVER _SSPW-ABORT-REOPEN NIP
            THEN
        ELSE
