    R@ _SSPW-READY? 0= IF R> DROP STREAMS-SPOOL-S-BUSY EXIT THEN
    0 R@ _SSPW.FUTURE-RETIREMENT !
    R@ _SSPW.SPOOL @ _SSP-D.STORE @ PSTORE-GENERATION@
        R@ _SSPW.BASE-GENERATION !
    R@ _SSPW-ROOTS-CURRENT? 0= IF
        R> DROP STREAMS-SPOOL-S-CONFLICT EXIT
    THEN
    R@ _SSPW.SPOOL @ _SSP-D.STORE @ PSTORE-CURRENT-ROOT@
    DUP 0= IF R> DROP STREAMS-SPOOL-S-CORRUPT EXIT THEN
    DUP R@ _SSPW.BASE-ROOT PERSIST-ROOT-VALUE-COPY
    PROOTV.APPLICATION-ROOT @
    R@ _SSPW.OLD-ROOT-PAGE !
    R@ _SSPW.SPOOL @ _SSP-D.STORE @
