            R@ _SSPW.SCAN-INDETERMINATE @
                R@ _SSPW.CURRENT-ROOT SOPROOT.INDETERMINATE-COUNT @
                <> IF R> DROP STREAMS-SPOOL-S-CORRUPT EXIT THEN
            R@ _SSPW-COLD-USAGE-MATCH? 0= IF
                R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
            THEN
            R@ _SSPW-COLD-SEQUENCES-UNIQUE? 0= IF
                R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
            THEN
            R> DROP STREAMS-SPOOL-S-OK EXIT
        THEN
        DUP IF >R _SSP-DROP4 R> R> DROP EXIT THEN DROP
        3 PICK 3 PICK STREAMS-OI-ATTEMPT-KEY-VALID? 0= IF
            _SSP-DROP4 R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
        THEN
        1 PICK 1 PICK R@ _SSPW-ROW-REF!
        DUP IF >R _SSP-DROP4 R> R> DROP EXIT THEN DROP
        3 PICK 3 PICK STREAMS-OI-ATTEMPT-KEY-ID@
            R@ _SSPW.ATTEMPT-ID RID-COPY
        _SSP-DROP4
        R@ _SSPW.RECORD-REF R@ _SSPW-READ-ATTEMPT-CURRENT
        DUP IF R> DROP EXIT THEN DROP
        R@ _SSPW.RECORD SOPATT.ATTEMPT-ID
            R@ _SSPW.ATTEMPT-ID RID= 0= IF
            R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
        THEN
        R@ _SSPW-VERIFY-ATTEMPT-CANONICAL-CURRENT
        DUP IF R> DROP EXIT THEN DROP
        R@ _SSPW.RECORD SOPATT.ACCEPTED-SEQUENCE @
            R@ _SSPW.CURRENT-ROOT SOPROOT.NEXT-ACCEPTED-SEQUENCE @
            >= IF
            R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
        THEN
        R@ _SSPW.RECORD SOPATT.READY-SEQUENCE @
            R@ _SSPW.CURRENT-ROOT SOPROOT.NEXT-READY-SEQUENCE @
            >= IF
            R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
        THEN
        R@ _SSPW.RECORD R@ _SSPW-VERIFY-ATTEMPT-BLOB-CURRENT
        DUP IF R> DROP EXIT THEN DROP
        R@ _SSPW.RECORD R@ _SSPW-VERIFY-ATTEMPT-RECEIPT-CURRENT
        DUP IF R> DROP EXIT THEN DROP
        R@ _SSPW.RECORD SOPATT.FLAGS @
            STREAMS-OPATT-F-RECEIPT-PRESENT AND IF
            R@ _SSPW.SCAN-RECEIPTS @ 1 _SSP-ADD?
            0= IF DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT THEN
            R@ _SSPW.SCAN-RECEIPTS !
            R@ _SSPW.RECEIPT SOPRECEIPT.REMOTE-RECEIPT-U @
            R@ _SSPW.RECEIPT SOPRECEIPT.REMOTE-CORRELATION-U @
                _SSP-ADD?
            0= IF DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT THEN
            R@ _SSPW.SCAN-REMOTE-BYTES @ SWAP _SSP-ADD?
            0= IF DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT THEN
            R@ _SSPW.SCAN-REMOTE-BYTES !
        THEN
        R@ _SSPW-COLD-ACCUMULATE-ATTEMPT
        DUP IF R> DROP EXIT THEN DROP
        R@ _SSPW.SCAN-ITEMS @ 1 _SSP-ADD?
        0= IF DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT THEN
        R@ _SSPW.SCAN-ITEMS !
        R@ _SSPW.SCAN-BYTES @
            R@ _SSPW.RECORD SOPATT.PAYLOAD-U @ _SSP-ADD?
        0= IF DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT THEN
        R@ _SSPW.SCAN-BYTES !
        R@ _SSPW-ATTEMPT-STATE-ROW-CURRENT
        DUP IF R> DROP EXIT THEN DROP
        R@ _SSPW.RECORD R@ _SSPW-EXPECT-IDEMPOTENCY-CURRENT
        DUP IF R> DROP EXIT THEN DROP
        R@ _SSPW-VERIFY-ATTEMPT-AUTHORITY-CURRENT
        DUP IF R> DROP EXIT THEN DROP
    AGAIN ;

