    R@ _SSPW.RECORD SOPATT.STATE @
        STREAMS-OPATT-STATE-ACCEPTED <> IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    R@ _SSPW.RECORD SOPATT.READY-SEQUENCE @
        R@ _SSPW.PAGE-ID @ <> IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
