: _SSP-BYTES=  ( a b u -- flag )
    DUP 0< IF DROP 2DROP 0 EXIT THEN
    DUP 0= IF DROP 2DROP -1 EXIT THEN
    2 PICK 0= 2 PICK 0= OR IF DROP 2DROP 0 EXIT THEN
    2 PICK OVER MSPAN-NONWRAPPING? 0= IF DROP 2DROP 0 EXIT THEN
    OVER OVER MSPAN-NONWRAPPING? 0= IF DROP 2DROP 0 EXIT THEN
    0 ?DO
        2DUP I + C@ SWAP I + C@ <> IF
            2DROP 0 UNLOOP EXIT
        THEN
    LOOP
    2DROP -1 ;

-1 1 RSHIFT CONSTANT _SSP-MAX-SIGNED

: _SSP-ZERO?  ( a u -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    0 ?DO DUP I + C@ IF DROP 0 UNLOOP EXIT THEN LOOP
    DROP -1 ;

: _SSP-NONNEG?  ( n -- flag )
    DUP 0>= SWAP _SSP-MAX-SIGNED <= AND ;

: _SSP-ADD?  ( nonnegative-a nonnegative-b -- sum flag )
    OVER 0< OVER 0< OR IF 2DROP 0 0 EXIT THEN
    2DUP + DUP 0< IF DROP 2DROP 0 0 EXIT THEN
    DUP _SSP-MAX-SIGNED > IF DROP 2DROP 0 0 EXIT THEN
    DUP 3 PICK U< IF DROP 2DROP 0 0 EXIT THEN
    >R 2DROP R> -1 ;

: _SSP-STATUS?  ( status -- flag )
    DUP STREAMS-SPOOL-S-OK >=
    SWAP STREAMS-SPOOL-S-REPLAY <= AND ;

