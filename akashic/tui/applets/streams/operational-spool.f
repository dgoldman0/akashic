\ =====================================================================
\ operational-spool.f - Current bounded Streams operational outbox
\ =====================================================================
\ This is the sole persistence owner for the prerelease SR3 egress outbox.
\ It composes the current pointer-free operational records and index with
\ neutral PSTORE, PBTREE, PBLOB, and RECLAIM.  It does not import the
\ displaced Streams repository, its persistence adapter, or any migration
\ or compatibility surface.
\
\ Every mutable byte is caller-owned.  One admission publishes its exact
\ payload blob, attempt record, four required index rows, capacity counters,
\ and one checked application root in one PSTORE transaction.
\ =====================================================================

