: _SSPW-AUDIT-GEOMETRY?
  ( audit-a audit-u pstore-work spool work -- flag )
    >R
    2 PICK _SSP-NONNEG? 0= IF _SSP-DROP4 R> DROP 0 EXIT THEN
    2 PICK 0= IF
        3 PICK 0=
        >R _SSP-DROP4 R> R> DROP EXIT
    THEN
    3 PICK 0= IF _SSP-DROP4 R> DROP 0 EXIT THEN
    3 PICK 7 AND IF _SSP-DROP4 R> DROP 0 EXIT THEN
    3 PICK 3 PICK MSPAN-NONWRAPPING? 0= IF
        _SSP-DROP4 R> DROP 0 EXIT
    THEN
    3 PICK 3 PICK R@ STREAMS-SPOOL-WORK-SIZE
        MSPAN-OVERLAP? IF _SSP-DROP4 R> DROP 0 EXIT THEN
    3 PICK 3 PICK 3 PICK PSTORE-WORK-SIZE
        MSPAN-OVERLAP? IF _SSP-DROP4 R> DROP 0 EXIT THEN
    3 PICK 3 PICK 3 PICK
        PSTORE-WORK-SPAN-DISJOINT? 0= IF
        _SSP-DROP4 R> DROP 0 EXIT
    THEN
    1 PICK PSTORE-WORK-RECORD-BUFFER$
    5 PICK 5 PICK 2SWAP MSPAN-OVERLAP? IF
        _SSP-DROP4 R> DROP 0 EXIT
    THEN
    3 PICK 3 PICK 2 PICK STREAMS-SPOOL-SIZE
        MSPAN-OVERLAP? IF _SSP-DROP4 R> DROP 0 EXIT THEN
    3 PICK 3 PICK 2 PICK _SSP-D.STORE @
        PSTORE-SPAN-DISJOINT? 0= IF
        _SSP-DROP4 R> DROP 0 EXIT
    THEN
    _SSP-DROP4 R> DROP -1 ;

: STREAMS-SPOOL-WORK-VALID?  ( work -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-SPOOL-WORK-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SSPW.MAGIC @ _SSPW-MAGIC <> IF DROP 0 EXIT THEN
    DUP _SSPW.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _SSPW.BUSY @ DUP 0= SWAP -1 = OR 0= IF DROP 0 EXIT THEN
    DUP _SSPW.STATE @ DUP _SSPW-STATE-READY >=
        SWAP _SSPW-STATE-REOPEN <= AND 0= IF DROP 0 EXIT THEN
    DUP _SSPW.TX-PHASE @ DUP _SSPW-TX-NONE >=
        SWAP _SSPW-TX-RECLAIM <= AND 0= IF DROP 0 EXIT THEN
    DUP _SSPW.STATE @ _SSPW-STATE-ACTIVE <> IF
        DUP _SSPW.FUTURE-RETIREMENT @ IF DROP 0 EXIT THEN
    THEN
    DUP _SSPW.FUTURE-RETIREMENT @
        DUP 0>= SWAP RECLAIM-RETIRED-MAX <= AND 0= IF DROP 0 EXIT THEN
    DUP _SSPW.STATUS @ _SSP-STATUS? 0= IF DROP 0 EXIT THEN
    DUP _SSPW.SPOOL @ STREAMS-SPOOL-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SSPW.PSTORE-WORK @ PSTORE-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SSPW.RECLAIM RECLAIM-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SSPW.RECLAIM RECLAIM-STORE@
    DUP 0=
    SWAP 2 PICK _SSPW.SPOOL @ _SSP-D.STORE @ = OR 0= IF
        DROP 0 EXIT
    THEN
    DUP _SSPW.RECLAIM-WORK RECLAIM-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SSPW.BTREE-WORK PBTREE-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SSPW.BLOB-WORK PBLOB-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SSPW.PBTREE-AUDIT-WORK
        PBTREE-AUDIT-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SSPW.RECLAIM-AUDIT-WORK
        RECLAIM-AUDIT-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SSPW.HASH SHA3-256-CONTEXT-VALID? 0= IF DROP 0 EXIT THEN
    DUP >R
    R@ _SSPW.AUDIT-A @
    R@ _SSPW.AUDIT-U @
    R@ _SSPW.PSTORE-WORK @
    R@ _SSPW.SPOOL @
    R@ _SSPW-AUDIT-GEOMETRY? 0= IF R> DROP DROP 0 EXIT THEN
    R> DROP
    DUP _SSPW-TREES-BOUND? NIP ;

\ The audit span is borrowed for the complete initialized-work lifetime.  A
\ zero span is representable for an empty store, but any nonempty cold root
\ reports CAPACITY until the caller supplies its checked bound and reinitializes.
: STREAMS-SPOOL-WORK-INIT
  ( audit-a audit-u pstore-work spool work -- status )
    2 PICK 2 PICK 2 PICK _SSPW-INIT-GEOMETRY? 0= IF
        _SSP-DROP5 STREAMS-SPOOL-S-INVALID EXIT
    THEN
    4 PICK 4 PICK 4 PICK 4 PICK 4 PICK
        _SSPW-AUDIT-GEOMETRY? 0= IF
        _SSP-DROP5 STREAMS-SPOOL-S-INVALID EXIT
    THEN
    >R
    R@ STREAMS-SPOOL-WORK-SIZE 0 FILL
    _SSPW-MAGIC R@ _SSPW.MAGIC !
    R@ R@ _SSPW.SELF !
    STREAMS-SPOOL-S-OK R@ _SSPW.STATUS !
    OVER R@ _SSPW.PSTORE-WORK !
    DUP R@ _SSPW.SPOOL !
    3 PICK R@ _SSPW.AUDIT-A !
    2 PICK R@ _SSPW.AUDIT-U !
    OVER R@ _SSPW.BTREE-WORK PBTREE-WORK-INIT
    DUP IF
        _SSP-PERSIST>STATUS >R _SSP-DROP4 R> R> DROP EXIT
    THEN DROP
    R@ _SSPW.BLOB-WORK PBLOB-WORK-INIT
    DUP IF
        _SSP-PERSIST>STATUS >R _SSP-DROP4 R> R> DROP EXIT
    THEN DROP
    R@ _SSPW.RECLAIM RECLAIM-INIT
    DUP IF
        _SSP-PERSIST>STATUS >R _SSP-DROP4 R> R> DROP EXIT
    THEN DROP
    R@ _SSPW.RECLAIM-WORK RECLAIM-WORK-INIT
    DUP IF
        _SSP-PERSIST>STATUS >R _SSP-DROP4 R> R> DROP EXIT
    THEN DROP
    R@ _SSPW.PSTORE-WORK @
    R@ _SSPW.PBTREE-AUDIT-WORK PBTREE-AUDIT-WORK-INIT
    DUP IF
        _SSP-PERSIST>STATUS >R _SSP-DROP4 R> R> DROP EXIT
    THEN DROP
    R@ _SSPW.RECLAIM-AUDIT-WORK RECLAIM-AUDIT-WORK-INIT
    DUP IF
        _SSP-PERSIST>STATUS >R _SSP-DROP4 R> R> DROP EXIT
    THEN DROP
    R@ _SSPW.HASH SHA3-256-CONTEXT-INIT
    DUP IF
        _SSP-S3CTX>STATUS >R _SSP-DROP4 R> R> DROP EXIT
    THEN DROP
    0
    BEGIN DUP _SSP-TREE-COUNT < WHILE
        DUP R@ _SSPW-INIT-TREE
        DUP IF >R _SSP-DROP5 R> R> DROP EXIT THEN DROP
        1+
    REPEAT
    DROP
    _SSPW-STATE-REOPEN R@ _SSPW.STATE !
    -1 R@ _SSPW.APP-ROOT-PAGE !
    _SSP-DROP4 R> DROP STREAMS-SPOOL-S-OK ;

