    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-SPOOL-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SSP-D.MAGIC @ _SSP-MAGIC <> IF DROP 0 EXIT THEN
    DUP _SSP-D.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _SSP-D.STATUS @ _SSP-STATUS? 0= IF DROP 0 EXIT THEN
