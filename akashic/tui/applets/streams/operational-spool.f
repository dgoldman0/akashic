\ Validate and load the checked semantic root and its eight embedded tree
\ roots.  Reclaim binding is deliberately separate so rollback can preserve
\ the already-audited descriptor instead of clearing its proof latch.
: _SSPW-ROOT>WORK-CORE  ( payload-a payload-u work -- status )
    >R
    DUP STREAMS-OPROOT-SIZE <> IF
        2DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    OVER OVER STREAMS-OPROOT-HEADER-CLASSIFY _SSP-OPREC>STATUS
    DUP IF >R 2DROP R> R> DROP EXIT THEN DROP
    OVER STREAMS-OPROOT-STRUCTURE-VALID? 0= IF
        2DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    OVER R@ _SSPW.CURRENT-ROOT STREAMS-OPROOT-SIZE MOVE
    2DROP
    R@ _SSPW-AUTHORITY-MATCHES-STORE? 0= IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    0
    BEGIN DUP _SSP-TREE-COUNT < WHILE
        DUP R@ _SSPW.PAGE-ID !
        R@ _SSPW.PAGE-ID @ R@ _SSPW.CURRENT-ROOT
            STREAMS-OPROOT-TREE
        R@ _SSPW.PAGE-ID @ R@ _SSPW-ROOT
        PBTREE-ROOT-COPY
        DUP IF
            _SSP-PERSIST>STATUS >R DROP R> R> DROP EXIT
        THEN DROP
        R@ _SSPW.PAGE-ID @ R@ _SSPW-ROOT
        R@ _SSPW.PAGE-ID @ R@ _SSPW-TREE
            PBTREE-ROOT-VALID? 0= IF
            DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
        THEN
        R@ _SSPW.PAGE-ID @ R@ _SSPW-ROOT
            PBTREE-ROOT-GENERATION@
        R@ _SSPW.SPOOL @ _SSP-D.STORE @
            PSTORE-GENERATION@ <> IF
            DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
        THEN
        1+
    REPEAT
    DROP
    R@ _SSPW-CARDINALITIES? 0= IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-SPOOL-S-OK ;

: _SSPW-ROOT>WORK  ( payload-a payload-u work -- status )
    >R
    R@ _SSPW-ROOT>WORK-CORE
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW.CURRENT-ROOT SOPROOT.RECLAIM-STATE
        RECLAIM-STATE-SIZE
    R@ _SSPW.SPOOL @ _SSP-D.STORE @
    R@ _SSPW.RECLAIM RECLAIM-OPEN
    _SSP-PERSIST>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW.SPOOL @ _SSP-D.STORE @ PSTORE-GENERATION@
        R@ _SSPW.BASE-GENERATION !
    -1 R@ _SSPW.AUTHORITY-PRESENT !
    _SSPW-STATE-REOPEN R@ _SSPW.STATE !
    R> DROP STREAMS-SPOOL-S-OK ;

\ Restore a transaction's exact prior authority without reopening reclaim.
\ RECLAIM-ABORT leaves the descriptor and audited-generation latch untouched;
\ the selected immutable root must name those same state bytes and generation.
: _SSPW-ROOT>WORK-RESTORE  ( payload-a payload-u work -- status )
    >R
    R@ _SSPW-ROOT>WORK-CORE
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW.RECLAIM RECLAIM-STORE@
    R@ _SSPW.SPOOL @ _SSP-D.STORE @ <> IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    R@ _SSPW.RECLAIM RECLAIM-GENERATION@
    R@ _SSPW.SPOOL @ _SSP-D.STORE @ PSTORE-GENERATION@ <> IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    R@ _SSPW.RECLAIM RECLAIM-AUDITED-GENERATION@
    R@ _SSPW.SPOOL @ _SSP-D.STORE @ PSTORE-GENERATION@ <> IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    R@ _SSPW.CURRENT-ROOT SOPROOT.RECLAIM-STATE
    R@ _SSPW.RECLAIM RECLAIM-STATE$
    DUP RECLAIM-STATE-SIZE <> IF
        2DROP DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    _SSP-BYTES= 0= IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    R@ _SSPW.SPOOL @ _SSP-D.STORE @ PSTORE-GENERATION@
        R@ _SSPW.BASE-GENERATION !
    -1 R@ _SSPW.AUTHORITY-PRESENT !
    _SSPW-STATE-REOPEN R@ _SSPW.STATE !
    R> DROP STREAMS-SPOOL-S-OK ;

: _SSPW-WORK>ROOT  ( work -- status )
    >R
    R@ _SSPW.AUTHORITY-PRESENT @ 0= IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    R@ _SSPW-ROOTS-PROPOSED? 0= IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    0
    BEGIN DUP _SSP-TREE-COUNT < WHILE
        DUP R@ _SSPW-ROOT
        OVER R@ _SSPW.CURRENT-ROOT STREAMS-OPROOT-TREE
        PBTREE-ROOT-COPY
        DUP IF
            _SSP-PERSIST>STATUS >R DROP R> R> DROP EXIT
        THEN DROP
        1+
    REPEAT
    DROP
    R@ _SSPW.CURRENT-ROOT SOPROOT.RECLAIM-STATE
        RECLAIM-STATE-SIZE
    R@ _SSPW.RECLAIM-WORK RECLAIM-STATE!
    DUP IF _SSP-PERSIST>STATUS R> DROP EXIT THEN DROP
    R@ _SSPW.CURRENT-ROOT STREAMS-OPROOT-SEAL _SSP-OPREC>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPW-CARDINALITIES? 0= IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
