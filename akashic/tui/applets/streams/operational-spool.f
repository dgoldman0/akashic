    PSTORE-SIZE ROT STREAMS-SPOOL-SIZE MSPAN-OVERLAP? 0= ;

: STREAMS-SPOOL-INIT  ( store spool -- status )
    >R
    DUP PSTORE-VALID? 0= IF DROP R> DROP STREAMS-SPOOL-S-INVALID EXIT THEN
    R@ 0= IF DROP R> DROP STREAMS-SPOOL-S-INVALID EXIT THEN
    R@ STREAMS-SPOOL-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP R> DROP STREAMS-SPOOL-S-INVALID EXIT
    THEN
    R@ STREAMS-SPOOL-SIZE 2 PICK PSTORE-SPAN-DISJOINT? 0= IF
        DROP R> DROP STREAMS-SPOOL-S-INVALID EXIT
    THEN
    DUP PSTORE-SIZE R@ STREAMS-SPOOL-SIZE MSPAN-OVERLAP? IF
        DROP R> DROP STREAMS-SPOOL-S-INVALID EXIT
    THEN
    R@ STREAMS-SPOOL-SIZE 0 FILL
    _SSP-MAGIC R@ _SSP-D.MAGIC !
    R@ R@ _SSP-D.SELF !
    DUP R@ _SSP-D.STORE !
    STREAMS-SPOOL-S-OK R@ _SSP-D.STATUS !
    DROP R> DROP STREAMS-SPOOL-S-OK ;

: STREAMS-SPOOL-STATUS@  ( spool -- status )
    DUP STREAMS-SPOOL-VALID? IF
        _SSP-D.STATUS @
    ELSE
        DROP STREAMS-SPOOL-S-INVALID
    THEN ;

