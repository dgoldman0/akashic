    _SSPW-TX-STORE-RECLAIM R@ _SSPW.TX-PHASE !
    _SSPW-STATE-ACTIVE R@ _SSPW.STATE !
    R@ _SSPW.OLD-ROOT-PAGE @ 0>= IF
        R@ _SSPW.OLD-ROOT-PAGE 1
        R@ _SSPW.RECLAIM-WORK RECLAIM-RETIRE-BATCH
        DUP IF
            _SSP-PERSIST>STATUS R@ _SSPW-ABORT-ACTIVE
            R> DROP EXIT
        THEN DROP
    THEN
    R@ _SSPW.BASE-GENERATION @ 0= IF
        R@ _SSPW-ROOTS-INIT
        DUP IF R@ _SSPW-ABORT-ACTIVE R> DROP EXIT THEN DROP
    THEN
    -1 R@ _SSPW.APP-ROOT-PAGE !
    0 R@ _SSPW.DURABLE !
    0 R@ _SSPW.DISPOSITION !
    R@ _SSPW.BLOB PBLOB-SIZE 0 FILL
    R> DROP STREAMS-SPOOL-S-OK ;

