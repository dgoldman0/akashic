\ PBTREE and RECLAIM visitor work is already part of STREAMS-SPOOL-WORK-SIZE.
\ The sequence component contains two independent cell arrays so accepted
\ and ready ordinals can each be sorted and checked.
: STREAMS-SPOOL-COLD-AUDIT-BYTES?
  ( page-count connector-count flow-count item-count -- bytes status )
    3 PICK _SSP-NONNEG? 0= IF
        _SSP-DROP4 0 STREAMS-SPOOL-S-INVALID EXIT
    THEN
    2 PICK _SSP-NONNEG? 0= IF
        _SSP-DROP4 0 STREAMS-SPOOL-S-INVALID EXIT
    THEN
    1 PICK _SSP-NONNEG? 0= IF
        _SSP-DROP4 0 STREAMS-SPOOL-S-INVALID EXIT
    THEN
    DUP _SSP-NONNEG? 0= IF
        _SSP-DROP4 0 STREAMS-SPOOL-S-INVALID EXIT
    THEN
    2 PICK _SSP-MAX-SIGNED _SSP-COLD-CONNECTOR-ENTRY-SIZE / > IF
        _SSP-DROP4 0 STREAMS-SPOOL-S-CAPACITY EXIT
    THEN
    1 PICK _SSP-MAX-SIGNED _SSP-COLD-FLOW-ENTRY-SIZE / > IF
        _SSP-DROP4 0 STREAMS-SPOOL-S-CAPACITY EXIT
    THEN
    DUP _SSP-MAX-SIGNED 16 / > IF
        _SSP-DROP4 0 STREAMS-SPOOL-S-CAPACITY EXIT
    THEN
    16 * >R
    _SSP-COLD-FLOW-ENTRY-SIZE * >R
    _SSP-COLD-CONNECTOR-ENTRY-SIZE * >R
    RECLAIM-AUDIT-MAP-BYTES?
    DUP IF
        NIP _SSP-PERSIST>STATUS
        R> DROP R> DROP R> DROP
        0 SWAP EXIT
    THEN
    DROP
    7 _SSP-ADD? 0= IF
        DROP R> DROP R> DROP R> DROP
        0 STREAMS-SPOOL-S-CAPACITY EXIT
    THEN
    7 INVERT AND
    R> _SSP-ADD? 0= IF
        DROP R> DROP R> DROP 0 STREAMS-SPOOL-S-CAPACITY EXIT
    THEN
    R> _SSP-ADD? 0= IF
        DROP R> DROP 0 STREAMS-SPOOL-S-CAPACITY EXIT
    THEN
    R> _SSP-ADD? 0= IF
        DROP 0 STREAMS-SPOOL-S-CAPACITY EXIT
    THEN
    STREAMS-SPOOL-S-OK ;

