    R@ _SSPW.AUTHORITY-PRESENT @ IF
        R@ _SSPW.CURRENT-ROOT STREAMS-OPROOT-STRUCTURE-VALID? 0= IF
            DROP R> DROP 0 EXIT
        THEN
        PROOTV.IDENTITY
        R@ _SSPW.CURRENT-ROOT SOPROOT.AUTHORITY-ID RID= 0= IF
            R> DROP 0 EXIT
        THEN
    ELSE
        DROP
        R@ _SSPW.APP-ROOT-PAGE @ -1 <> IF R> DROP 0 EXIT THEN
    THEN
    0
    BEGIN DUP _SSP-TREE-COUNT < WHILE
