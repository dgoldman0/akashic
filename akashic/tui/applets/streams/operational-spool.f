: _SSPW-SCAN-DISPATCH-CURRENT  ( work -- status )
    >R
    0 R@ _SSPW.SCAN-ITEMS !
    STREAMS-OPROOT-TREE-DISPATCH R@ _SSPW-CURSOR-BEGIN
    DUP IF R> DROP EXIT THEN DROP
    BEGIN
        STREAMS-OPROOT-TREE-DISPATCH R@ _SSPW-CURSOR-NEXT
        DUP STREAMS-SPOOL-S-NOT-FOUND = IF
            DROP _SSP-DROP4
            R@ _SSPW.CURRENT-ROOT SOPROOT.READY-COUNT @
            R@ _SSPW.CURRENT-ROOT SOPROOT.ACTIVE-COUNT @ _SSP-ADD?
            0= IF DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT THEN
            R@ _SSPW.SCAN-ITEMS @ =
            IF STREAMS-SPOOL-S-OK ELSE STREAMS-SPOOL-S-CORRUPT THEN
            R> DROP EXIT
        THEN
        DUP IF >R _SSP-DROP4 R> R> DROP EXIT THEN DROP
        3 PICK 3 PICK STREAMS-OI-DISPATCH-READY-KEY-VALID? IF
            R@ _SSPW-DISPATCH-READY-ENTRY
        ELSE
            R@ _SSPW-DISPATCH-ACTIVE-ENTRY
        THEN
        DUP IF R> DROP EXIT THEN DROP
        R@ _SSPW.SCAN-ITEMS @ 1 _SSP-ADD?
        0= IF DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT THEN
        R@ _SSPW.SCAN-ITEMS !
    AGAIN ;

