: _SSPW-CONFIG-ROOM?  ( tree-index work -- flag )
    >R
    DUP 0< OVER _SSP-TREE-COUNT >= OR IF
        DROP R> DROP 0 EXIT
    THEN
    _SSP-CONFIG-ALLOCATION-RESERVE
    SWAP R@ _SSPW-ROOT PBTREE-ROOT-HEIGHT@
        STREAMS-OPROOT-TREE-USAGE R@ _SSPW-ROOT
        PBTREE-ROOT-HEIGHT@ +
        RECLAIM-STEP-RETIREMENT-MAX +
        RECLAIM-ALLOCATION-RETIREMENT-MAX +
        RECLAIM-FINALIZE-RETIREMENT-MAX +
    0 R@ _SSPW.RECLAIM-WORK RECLAIM-TX-ROOM?
    R> DROP ;

: _SSPW-CONFIG-COUNTER-ROOM?  ( tree-index work -- flag )
    >R
    R@ _SSPW.CURRENT-ROOT SOPROOT.LOGICAL-GENERATION @
        _SSP-MAX-SIGNED >= IF DROP R> DROP 0 EXIT THEN
    R@ _SSPW.CURRENT-ROOT SOPROOT.MUTATION-SEQUENCE @
        _SSP-MAX-SIGNED >= IF DROP R> DROP 0 EXIT THEN
    R@ _SSPW.DISPOSITION @ 0= IF
        DROP R> DROP -1 EXIT
    THEN
    DUP STREAMS-OPROOT-TREE-CONNECTORS = IF
        DROP R@ _SSPW.CURRENT-ROOT SOPROOT.CONNECTOR-COUNT @
            _SSP-MAX-SIGNED <
        R> DROP EXIT
    THEN
    STREAMS-OPROOT-TREE-FLOWS = IF
        R@ _SSPW.CURRENT-ROOT SOPROOT.FLOW-COUNT @
            _SSP-MAX-SIGNED <
        R> DROP EXIT
    THEN
    R> DROP 0 ;

