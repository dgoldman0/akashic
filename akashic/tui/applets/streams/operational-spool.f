    DUP _SSPW.STATE @ _SSPW-STATE-READY <> IF DROP 0 EXIT THEN
    DUP _SSPW.TX-PHASE @ _SSPW-TX-NONE <> IF
        _SSPW-STATE-REOPEN OVER _SSPW.STATE !
        DROP 0 EXIT
    THEN
    DUP _SSPW.RECLAIM RECLAIM-STORE@ 0= IF
        _SSPW-STATE-REOPEN OVER _SSPW.STATE !
        DROP 0 EXIT
    THEN
    DUP _SSPW.AUTHORITY-PRESENT @ IF
        DUP _SSPW.RECLAIM RECLAIM-AUDITED-GENERATION@
        OVER _SSPW.SPOOL @ _SSP-D.STORE @ PSTORE-GENERATION@ <> IF
            _SSPW-STATE-REOPEN OVER _SSPW.STATE !
            DROP 0 EXIT
        THEN
    THEN
    DUP _SSPW-AUTHORITY-CURRENT? 0= IF
        _SSPW-STATE-REOPEN OVER _SSPW.STATE !
        DROP 0 EXIT
    THEN
    DROP -1 ;

