: _SATP-CLEANUP-DETACH  ( context -- status )
    DUP _SATP-C !
    DUP SATP.XIO-OP XIOO.STATE @ XIO-STATE-ACTIVE = IF
        DUP SATP.XIO-SERVICE @ OVER SATP.XIO-OP XIO-CANCEL DROP
    THEN
    DUP _SATP-XIO-RESET DUP IF NIP EXIT THEN DROP
    DUP _SATP-XIO-REFERS? IF DROP SAUTH-S-BUSY EXIT THEN
    DUP _SATP-FEED-FLOW-DISCARD DUP IF NIP EXIT THEN DROP
    DUP _SATP-POST-FLOW-DISCARD DUP IF NIP EXIT THEN DROP
    DUP _SATP-FEED-UNBIND DUP IF NIP EXIT THEN DROP
    DUP SATP.POST-BOUND @ IF
        DUP SATP.POST-EXCHANGE-P @ AT-XRPC-EXCHANGE-UNBIND
        AT-XRPC-EXCHANGE-S-OK <> IF DROP SAUTH-S-CLEANUP EXIT THEN
        0 OVER SATP.POST-BOUND !
    THEN
    DROP SAUTH-S-OK ;

: _SATP-FREE-GRAPHS  ( context -- status )
    _SATP-C ! SAUTH-S-OK _SATP-STATUS !
    AT-TEXT-POST-CONNECTOR-SIZE _SATP-C @ SATP.POST-OWNER-P
        _SATP-FREE-FIELD DUP IF _SATP-STATUS ! ELSE DROP THEN
    _SATP-C @ _SATP-ACCOUNT@ SATACC.RESULT-BYTES-CAP @
        _SATP-C @ SATP.RESULT-BYTES-P _SATP-FREE-FIELD
        DUP IF _SATP-STATUS ! ELSE DROP THEN
    AT-CREATE-RECORD-RESULT-SIZE _SATP-C @ SATP.CREATE-RESULT-P
        _SATP-FREE-FIELD DUP IF _SATP-STATUS ! ELSE DROP THEN
    AT-CREATE-RECORD-CODEC-WORKSPACE-SIZE _SATP-C @ SATP.CREATE-WORK-P
        _SATP-FREE-FIELD DUP IF _SATP-STATUS ! ELSE DROP THEN
    _SATP-C @ _SATP-ACCOUNT@ SATACC.CREATE-BODY-CAP @
        _SATP-C @ SATP.CREATE-BODY-P _SATP-FREE-FIELD
        DUP IF _SATP-STATUS ! ELSE DROP THEN
    AT-CREATE-RECORD-SIZE _SATP-C @ SATP.CREATE-OWNER-P
        _SATP-FREE-FIELD DUP IF _SATP-STATUS ! ELSE DROP THEN
    _SATP-C @ _SATP-ACCOUNT@ SATACC.POST-BODY-CAP @
        _SATP-C @ SATP.POST-BODY-P _SATP-FREE-FIELD
        DUP IF _SATP-STATUS ! ELSE DROP THEN
    _SATP-C @ _SATP-ACCOUNT@ SATACC.POST-REQUEST-CAP @
        _SATP-C @ SATP.POST-REQUEST-P _SATP-FREE-FIELD
        DUP IF _SATP-STATUS ! ELSE DROP THEN
    AT-XRPC-EXCHANGE-SIZE _SATP-C @ SATP.POST-EXCHANGE-P
        _SATP-FREE-FIELD DUP IF _SATP-STATUS ! ELSE DROP THEN
    _SATP-C @ _SATP-ACCOUNT@ SATACC.FEED-BODY-CAP @
        _SATP-C @ SATP.FEED-BODY-P _SATP-FREE-FIELD
        DUP IF _SATP-STATUS ! ELSE DROP THEN
    _SATP-C @ _SATP-ACCOUNT@ SATACC.FEED-REQUEST-CAP @
        _SATP-C @ SATP.FEED-REQUEST-P _SATP-FREE-FIELD
        DUP IF _SATP-STATUS ! ELSE DROP THEN
    AT-AUTHOR-FEED-CONNECTOR-SIZE _SATP-C @ SATP.FEED-OWNER-P
        _SATP-FREE-FIELD DUP IF _SATP-STATUS ! ELSE DROP THEN
    _SATP-STATUS @ ;

: _SATP-CONTEXT-DISPOSE  ( context -- status )
    DUP 0= IF DROP SAUTH-S-OK EXIT THEN
    DUP _SATP-C !
    DUP SATP.MAGIC @ _SATP-MAGIC-VALUE = IF
        DUP _SATP-CLEANUP-DETACH DUP IF NIP EXIT THEN DROP
    THEN
    DUP _SATP-FREE-GRAPHS DUP IF NIP EXIT THEN DROP
    DUP STREAMS-AT-AUTH-CONTEXT-SIZE 0 FILL FREE
    SAUTH-S-OK ;

: _SATP-RELEASE  ( context -- status )
    DUP _SATP-CONTEXT-VALID? 0= IF DROP SAUTH-S-INVALID EXIT THEN
    _SATP-CONTEXT-DISPOSE ;

