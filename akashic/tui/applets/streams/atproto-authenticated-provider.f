    STREAMS-FLOW-S-ACKNOWLEDGED <> IF SAUTH-S-FEED EXIT THEN
    _SATP-NOW @ _SATP-C @ SATP.FEED-FLOW STREAMS-FLOW-STEP
    STREAMS-FLOW-S-DELIVERED <> IF SAUTH-S-FEED EXIT THEN
    _SATP-C @ _SATP-FEED-FLOW-RETIRE ;

: _SATP-FEED-SUCCESS  ( instance context -- status )
    _SATP-C ! _SATP-INSTANCE !
