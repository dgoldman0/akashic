: _SATP-TICK  ( instance context -- changed? status )
    _SATP-C ! _SATP-INSTANCE !
    _SATP-C @ _SATP-CONTEXT-VALID? 0= IF 0 SAUTH-S-INVALID EXIT THEN
    _SATP-INSTANCE @ _SATP-C @ _SATP-INSTANCE-EXACT-OR-UNBOUND? 0= IF
        0 SAUTH-S-STATE EXIT
    THEN
    _SATP-C @ SATP.STATE @ DUP SAUTH-STATE-FEED-ACTIVE <>
        SWAP SAUTH-STATE-POST-ACTIVE <> AND IF 0 SAUTH-S-OK EXIT THEN
    _SATP-C @ SATP.OP-KIND @ _SATP-OP-FEED = IF
        \ Feed bytes have no externally visible effect until presentation,
        \ so a source mutation rejects the whole operation.
        _SATP-INSTANCE @ _SATP-C @ _SATP-SOURCE-EXACT? 0= IF
            _SATP-C @ _SATP-FEED-ABANDON DUP IF
                SAUTH-STATE-CLEANUP SAUTH-S-CLEANUP ROT
                    _SATP-C @ _SATP-MARK DROP
                -1 SAUTH-S-CLEANUP EXIT
            THEN DROP
            SAUTH-STATE-FAILED SAUTH-S-STATE SAUTH-S-STATE
                _SATP-C @ _SATP-MARK DROP
            -1 SAUTH-S-STATE EXIT
        THEN
        _SATP-C @ SATP.XIO-OP XIOO.STATE @ XIO-STATE-ACTIVE = IF
            0 SAUTH-S-OK EXIT
        THEN
        _SATP-C @ SATP.XIO-OP XIOO.STATE @ XIO-STATE-RESET = IF
            SAUTH-STATE-FAILED SAUTH-S-STATE SAUTH-S-STATE
                _SATP-C @ _SATP-MARK DROP
            -1 SAUTH-S-STATE EXIT
        THEN
        _SATP-INSTANCE @ _SATP-C @ _SATP-FEED-TERMINAL EXIT
    THEN
    _SATP-C @ SATP.OP-KIND @ _SATP-OP-POST = IF
        _SATP-C @ SATP.XIO-OP XIOO.STATE @ XIO-STATE-ACTIVE = IF
            _SATP-INSTANCE @ _SATP-C @ _SATP-SOURCE-EXACT? IF
                0 SAUTH-S-OK EXIT
            THEN
            \ Cancellation is meaningful only while the post is active.
            \ Its lower connector records whether cancellation caused no
            \ effect or left an uncertain outcome; consume that truth below.
            _SATP-C @ SATP.XIO-SERVICE @ _SATP-C @ SATP.XIO-OP
                XIO-CANCEL DROP
            _SATP-C @ SATP.XIO-OP XIOO.STATE @ XIO-STATE-ACTIVE = IF
                0 SAUTH-S-BUSY EXIT
            THEN
        THEN
        _SATP-C @ SATP.XIO-OP XIOO.STATE @ XIO-STATE-RESET = IF
            SAUTH-STATE-FAILED SAUTH-S-STATE SAUTH-S-STATE
                _SATP-C @ _SATP-MARK DROP
            -1 SAUTH-S-STATE EXIT
        THEN
        \ A terminal post is an external fact.  Do not reject or relabel it
        \ merely because its source changed while completion awaited TICK.
        _SATP-C @ _SATP-POST-TERMINAL EXIT
    THEN
    SAUTH-STATE-FAILED SAUTH-S-STATE SAUTH-S-STATE
        _SATP-C @ _SATP-MARK DROP
    -1 SAUTH-S-STATE ;

: _SATP-RESIDUE?  ( context -- flag )
    DUP SATP.XIO-OP XIOO.STATE @ XIO-STATE-RESET <>
    OVER SATP.FEED-FLOW-READY @ 0<> OR
    OVER SATP.POST-FLOW-READY @ 0<> OR
    SWAP _SATP-XIO-REFERS? OR ;

: _SATP-QUIESCE-RESIDUE  ( context -- changed? status )
    DUP _SATP-RESIDUE? 0= IF DROP 0 SAUTH-S-OK EXIT THEN
    _SATP-C !
    _SATP-C @ SATP.XIO-OP XIOO.STATE @ XIO-STATE-ACTIVE = IF
        0 SAUTH-S-BUSY EXIT
    THEN
    _SATP-C @ _SATP-XIO-RESET DUP IF 0 SWAP EXIT THEN DROP
    _SATP-C @ _SATP-FEED-FLOW-DISCARD DUP IF 0 SWAP EXIT THEN DROP
    _SATP-C @ _SATP-POST-FLOW-DISCARD DUP IF 0 SWAP EXIT THEN DROP
    _SATP-C @ _SATP-XIO-REFERS? IF 0 SAUTH-S-CLEANUP EXIT THEN
    _SATP-OP-NONE _SATP-C @ SATP.OP-KIND !
    -1 SAUTH-S-OK ;

: _SATP-CANCEL  ( instance context -- changed? status )
    _SATP-C ! _SATP-INSTANCE !
    _SATP-C @ _SATP-CONTEXT-VALID? 0= IF 0 SAUTH-S-INVALID EXIT THEN
    _SATP-INSTANCE @ _SATP-C @ _SATP-INSTANCE-EXACT-OR-UNBOUND? 0= IF
        0 SAUTH-S-STATE EXIT
    THEN
    _SATP-C @ SATP.STATE @ DUP SAUTH-STATE-FEED-ACTIVE <>
        SWAP SAUTH-STATE-POST-ACTIVE <> AND IF
        _SATP-C @ _SATP-QUIESCE-RESIDUE EXIT
    THEN
    _SATP-C @ SATP.OP-KIND @ _SATP-OP-POST = IF
        _SATP-C @ SATP.XIO-OP XIOO.STATE @ XIO-STATE-ACTIVE = IF
            _SATP-C @ SATP.XIO-SERVICE @ _SATP-C @ SATP.XIO-OP
                XIO-CANCEL _SATP-XIO>SAUTH _SATP-STATUS !
            _SATP-C @ SATP.XIO-OP XIOO.STATE @ XIO-STATE-ACTIVE = IF
                0 _SATP-STATUS @ EXIT
            THEN
        THEN
        _SATP-C @ SATP.XIO-OP XIOO.STATE @ XIO-STATE-RESET = IF
            SAUTH-STATE-FAILED SAUTH-S-STATE SAUTH-S-STATE
                _SATP-C @ _SATP-MARK DROP
            -1 SAUTH-S-STATE EXIT
        THEN
        \ If completion beat CANCEL, preserve it.  If cancellation won, the
        \ connector reports the resulting no-effect/uncertain truth here.
        _SATP-C @ _SATP-POST-TERMINAL EXIT
    THEN
    _SATP-C @ SATP.OP-KIND @ _SATP-OP-FEED = IF
        _SATP-C @ _SATP-FEED-ABANDON DUP IF
            SAUTH-STATE-CLEANUP SAUTH-S-CLEANUP ROT
                _SATP-C @ _SATP-MARK DROP
            -1 SAUTH-S-CLEANUP EXIT
        THEN DROP
        SAUTH-STATE-CANCELLED SAUTH-S-CANCELLED 0
            _SATP-C @ _SATP-MARK DROP
        -1 SAUTH-S-CANCELLED EXIT
    THEN
    SAUTH-STATE-FAILED SAUTH-S-STATE SAUTH-S-STATE
        _SATP-C @ _SATP-MARK DROP
    -1 SAUTH-S-STATE ;

: _SATP-STATE@  ( context -- state ) SATP.STATE @ ;
: _SATP-LAST-STATUS@  ( context -- status ) SATP.LAST-STATUS @ ;
: _SATP-ERROR@  ( context -- error ) SATP.ERROR @ ;
: _SATP-URI$  ( context -- uri-a uri-u ) DUP SATP.URI SWAP SATP.URI-U @ ;
: _SATP-CID$  ( context -- cid-a cid-u ) DUP SATP.CID SWAP SATP.CID-U @ ;

: _SATP-RELEASABLE?  ( context -- flag )
    DUP _SATP-CONTEXT-VALID? 0= IF DROP 0 EXIT THEN
    DUP SATP.STATE @ DUP SAUTH-STATE-FEED-ACTIVE <>
        SWAP SAUTH-STATE-POST-ACTIVE <> AND
    OVER _SATP-XIO-REFERS? 0= AND
    OVER SATP.XIO-OP XIOO.STATE @ XIO-STATE-RESET = AND
    OVER SATP.FEED-FLOW-READY @ 0= AND
    SWAP SATP.POST-FLOW-READY @ 0= AND ;

