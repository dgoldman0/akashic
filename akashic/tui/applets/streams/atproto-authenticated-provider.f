        SAUTH-S-STATE EXIT
    THEN
    \ Flow deadlines use the same monotonic domain as FLOW-STEP/CANCEL.
    \ The injected epoch clock remains reserved for AT request timestamps.
    MS@ _SATP-NOW !
    _SATP-FLOW-REVISION _SATP-NOW @
    _SATP-C @ SATP.FEED-FLOW
    _SATP-C @ SATP.FEED-OWNER-P @ AT-AUTHOR-FEED-CONNECTOR-PUBLISH
    _SATP-FEED>SAUTH DUP IF EXIT THEN DROP
    _SATP-C @ SATP.FEED-OWNER-P @ ATAFC.SEQUENCE @
        _SATP-C @ SATP.FEED-SEQUENCE !
    \ This is the terminal app boundary.  The earlier whole-record comparison
    \ protects the concrete provider; this public check also proves that the
    \ exact enabled RID/revision is still admitted by the live Streams app.
    _SATP-C @ SATP.SOURCE _SATP-INSTANCE @
        STREAMS-AUTH-SOURCE-ADMISSIBLE? 0= IF SAUTH-S-STATE EXIT THEN
    _SATP-C @ SATP.FEED-OWNER-P @ _SATP-INSTANCE @
        STREAMS-AT-AUTHOR-FEED-PRESENT
    STREAMS-AT-VIEW-S-OK <> IF SAUTH-S-FEED EXIT THEN
    \ Presentation has copied the exact authenticated page into Streams.
    \ Only now may reset invoke the connector wipe and release response bytes.
    _SATP-C @ _SATP-XIO-RESET DUP IF EXIT THEN DROP
    _SATP-NOW @ _SATP-C @ _SATP-FEED-FLOW-ACK ;

