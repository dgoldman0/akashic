: _SATP-RECEIPT-COPY  ( context -- status )
    DUP _SATP-C ! _SATP-RECEIPT-CLEAR
    _SATP-C @ SATP.POST-OWNER-P @ AT-TEXT-POST-CONNECTOR-URI@
    DUP AT-TEXT-POST-CONNECTOR-S-OK <> IF
        >R 2DROP R> DROP SAUTH-S-POST EXIT
    THEN
    DROP DUP ATURI-LENGTH-MAX U> IF 2DROP SAUTH-S-CAPACITY EXIT THEN
    DUP _SATP-C @ SATP.URI-U !
    _SATP-C @ SATP.URI SWAP MOVE
    _SATP-C @ SATP.POST-OWNER-P @ AT-TEXT-POST-CONNECTOR-CID@
    DUP AT-TEXT-POST-CONNECTOR-S-OK <> IF
        >R 2DROP R> DROP _SATP-C @ _SATP-RECEIPT-CLEAR
        SAUTH-S-POST EXIT
    THEN
    DROP DUP AT-CID-TEXT-LENGTH U> IF
        2DROP _SATP-C @ _SATP-RECEIPT-CLEAR SAUTH-S-CAPACITY EXIT
    THEN
    DUP _SATP-C @ SATP.CID-U !
    _SATP-C @ SATP.CID SWAP MOVE
    SAUTH-S-OK ;

: _SATP-POST-CAPTURE  ( context -- state status error )
    DUP _SATP-C !
    SATP.POST-OWNER-P @ AT-TEXT-POST-CONNECTOR-CREATE-OUTCOME@
    DUP AT-TEXT-POST-CONNECTOR-S-OK <> IF
        >R DROP R>
        SAUTH-STATE-POST-UNCERTAIN SAUTH-S-INDETERMINATE ROT EXIT
    THEN DROP
    CASE
        AT-CREATE-RECORD-OUTCOME-CREATED OF
            _SATP-C @ _SATP-RECEIPT-COPY DUP SAUTH-S-OK = IF
                DROP SAUTH-STATE-POST-DELIVERED SAUTH-S-OK 0
            ELSE
                SAUTH-STATE-POST-UNCERTAIN SWAP SAUTH-S-POST
            THEN
        ENDOF
        AT-CREATE-RECORD-OUTCOME-NO-EFFECT OF
            _SATP-C @ _SATP-RECEIPT-CLEAR
            SAUTH-STATE-POST-NO-EFFECT SAUTH-S-POST
            _SATP-C @ SATP.POST-OWNER-P @
                AT-TEXT-POST-CONNECTOR-LAST-STATUS@
        ENDOF
        AT-CREATE-RECORD-OUTCOME-UNCERTAIN OF
            _SATP-C @ _SATP-RECEIPT-CLEAR
            SAUTH-STATE-POST-UNCERTAIN SAUTH-S-INDETERMINATE
            _SATP-C @ SATP.POST-OWNER-P @
                AT-TEXT-POST-CONNECTOR-LAST-STATUS@
        ENDOF
        DROP
        _SATP-C @ _SATP-RECEIPT-CLEAR
        SAUTH-STATE-POST-UNCERTAIN SAUTH-S-INDETERMINATE SAUTH-S-POST
    ENDCASE ;

