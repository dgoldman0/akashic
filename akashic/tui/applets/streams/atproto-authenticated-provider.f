\ =====================================================================
\ atproto-authenticated-provider.f - authenticated Streams account owner
\ =====================================================================
\ This is the concrete account composition behind authenticated-provider.f.
\ It owns one author-feed connector, one text-post connector graph, their
\ bounded arenas, two real Streams flows, and one operation on the Desk XIO
\ service.  It deliberately does not own credentials or account discovery.
\
\ The caller keeps one sealed STREAMS-AT-ACCOUNT descriptor unchanged, and
\ every object named by it alive, until the provider is released.  In
\ particular the credential vault, client configuration, OAuth
\ profile/session, trusted
\ clock, TID clock, and createRecord target remain in the outer account
\ owner.  No token, credential pointer, PDS URL, or mutable account object is
\ copied into a persisted source.  A source stores only its actor in ENDPOINT
\ and the descriptor's opaque account binding in CONFIG.
\
\ A composition-specific factory can close over a statically named account:
\
\   : MY-STREAMS-AT-FACTORY  ( vfs xio-service -- provider status )
\       MY-ACCOUNT STREAMS-AT-AUTH-PROVIDER-NEW ;
\
\ and pass that XT to STREAMS-ONLINE-ENTRY-WITH-PROVIDERS.  The VFS argument
\ is intentionally not retained: source durability stays with Streams.  The
\ shared XIO service is retained only while the provider exists and is
\ detached from the provider operation before release succeeds.
\ =====================================================================

\ Keep the module identity within KDOS's 23-byte bound.
PROVIDED akashic-streams-atowner

REQUIRE atproto-author-feed-present.f
REQUIRE atproto-text-post-connector.f

