    _SATP-STATUS2 @ _SATP-STATUS @ _SATP-NOW @
        _SATP-C @ _SATP-MARK DROP
    -1 _SATP-STATUS @ ;

: _SATP-POST-TERMINAL  ( context -- changed? status )
    _SATP-C !
    _SATP-C @ _SATP-POST-CAPTURE
    _SATP-C @ _SATP-XIO-RESET DUP IF
        >R 2DROP DROP R>
        SAUTH-STATE-CLEANUP SAUTH-S-CLEANUP ROT
            _SATP-C @ _SATP-MARK DROP
        -1 SAUTH-S-CLEANUP EXIT
    THEN DROP
    \ A successful outer reset normally retired the flow through its wipe
    \ callback.  Retry the explicit discard path as well so a callback that
    \ reported cleanup failure cannot be forgotten behind a cleared XIO op.
    _SATP-C @ _SATP-POST-FLOW-DISCARD DUP IF
        >R 2DROP DROP R>
        SAUTH-STATE-CLEANUP SAUTH-S-CLEANUP ROT
            _SATP-C @ _SATP-MARK DROP
        -1 SAUTH-S-CLEANUP EXIT
    THEN DROP
    _SATP-OP-NONE _SATP-C @ SATP.OP-KIND !
    _SATP-C @ _SATP-MARK
    -1 SWAP ;

