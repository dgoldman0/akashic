    _SATP-C @ SATP.XIO-SERVICE @ XIOS.RETAINED @
        _SATP-C @ SATP.XIO-OP = AND
    _SATP-C @ SATP.XIO-OP XIOO.RESULT @
        _SATP-C @ SATP.FEED-OWNER-P @ = AND IF
        _SATP-INSTANCE @ _SATP-C @ _SATP-FEED-SUCCESS DUP IF
            _SATP-STATUS !
            _SATP-C @ _SATP-FEED-ABANDON DUP IF
                SAUTH-STATE-CLEANUP SAUTH-S-CLEANUP ROT
                    _SATP-C @ _SATP-MARK DROP
                -1 SAUTH-S-CLEANUP EXIT
            THEN DROP
            SAUTH-STATE-FAILED _SATP-STATUS @ _SATP-STATUS @
                _SATP-C @ _SATP-MARK DROP
