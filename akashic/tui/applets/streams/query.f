: _SQ-RANGE-CALL  ( work -- count status )
    >R
    R@ _SQW.MODE @ CASE
        _SQ-MODE-FIRST OF
            R@ _SQW.PREFIX R@ _SQW.PREFIX-U @
            R@ _SQW.PAGE @ SQP.ROWS @
            R@ _SQW.PAGE @ SQP.CAPACITY @
            R@ _SQW.ADAPTER @ R@ _SQW.ADAPTER-WORK @
            STREAMS-PA-RANGE-FIRST
        ENDOF
        _SQ-MODE-LAST OF
            R@ _SQW.PREFIX R@ _SQW.PREFIX-U @
            R@ _SQW.PAGE @ SQP.ROWS @
            R@ _SQW.PAGE @ SQP.CAPACITY @
            R@ _SQW.ADAPTER @ R@ _SQW.ADAPTER-WORK @
            STREAMS-PA-RANGE-LAST
        ENDOF
        _SQ-MODE-AFTER OF
            R@ _SQW.PREFIX R@ _SQW.PREFIX-U @
            R@ _SQW.KEY R@ _SQW.KEY-U @
            R@ _SQW.PAGE @ SQP.ROWS @
            R@ _SQW.PAGE @ SQP.CAPACITY @
            R@ _SQW.ADAPTER @ R@ _SQW.ADAPTER-WORK @
            STREAMS-PA-RANGE-AFTER
        ENDOF
        _SQ-MODE-BEFORE OF
            R@ _SQW.PREFIX R@ _SQW.PREFIX-U @
            R@ _SQW.KEY R@ _SQW.KEY-U @
            R@ _SQW.PAGE @ SQP.ROWS @
            R@ _SQW.PAGE @ SQP.CAPACITY @
            R@ _SQW.ADAPTER @ R@ _SQW.ADAPTER-WORK @
            STREAMS-PA-RANGE-BEFORE
        ENDOF
        0 STREAMS-QUERY-S-INVALID ROT
    ENDCASE
    R> DROP ;

: _SQ-RESULT-ROW  ( index work -- row )
    _SQW.PAGE @ _SQP-ROW ;

: _SQ-RESULT-ROWS-VALID?  ( work -- flag )
    >R
    R@ _SQW.RESULT-U @ DUP 0<
    OVER R@ _SQW.PAGE @ SQP.CAPACITY @ > OR IF
        DROP R> DROP 0 EXIT
    THEN
    DROP 0
    BEGIN
        DUP R@ _SQW.RESULT-U @ <
    WHILE
        DUP R@ _SQ-RESULT-ROW
        DUP R@ _SQW.FAMILY @ _SQP-ROW-FAMILY-VALID? 0= IF
            2DROP R> DROP 0 EXIT
        THEN
        STREAMS-PA-RANGE-ROW-KEY$
        DUP R@ _SQW.PREFIX-U @ < IF
            2DROP DROP R> DROP 0 EXIT
        THEN
        R@ _SQW.PREFIX R@ _SQW.PREFIX-U @
        >R SWAP DROP R> _SQ-BYTES= 0= IF
            DROP R> DROP 0 EXIT
        THEN
        DUP IF
            DUP 1- R@ _SQ-RESULT-ROW
                STREAMS-PA-RANGE-ROW-KEY$
            2 PICK R@ _SQ-RESULT-ROW
                STREAMS-PA-RANGE-ROW-KEY$
            COMPARE 0>= IF DROP R> DROP 0 EXIT THEN
        THEN
        1+
    REPEAT
    DROP
    R@ _SQW.PAGE @ SQP.ROWS @
    R@ _SQW.RESULT-U @ STREAMS-PA-RANGE-ROW-SIZE * +
    R@ _SQW.PAGE @ SQP.CAPACITY @
    R@ _SQW.RESULT-U @ -
        STREAMS-PA-RANGE-ROW-SIZE * _SQ-ZERO?
    R> DROP ;

: _SQ-BUILD-PAGE-TOKEN  ( row direction work -- status )
    >R
    DUP _SQ-DIRECTION? 0= IF
        2DROP R> DROP STREAMS-QUERY-S-CORRUPT EXIT
    THEN
    DUP STREAMS-QUERY-DIRECTION-AFTER = IF
        R@ _SQW.PAGE @ SQP.AFTER-CONTINUATION
    ELSE
        R@ _SQW.PAGE @ SQP.BEFORE-CONTINUATION
    THEN
    R@ _SQW.TOKEN-DEST !
    R@ _SQW.TOKEN-DEST @
        STREAMS-QUERY-CONTINUATION-INIT
    DUP IF
        >R 2DROP R> R> DROP EXIT
    THEN
    DROP
    DUP R@ _SQW.TOKEN-DEST @ SQC.DIRECTION !
    R@ _SQW.FAMILY @ R@ _SQW.TOKEN-DEST @ SQC.FAMILY !
    R@ _SQW.AUTHORITY-ID
    R@ _SQW.TOKEN-DEST @ SQC.AUTHORITY-ID RID-COPY
    R@ _SQW.SCOPE-FINGERPRINT
    R@ _SQW.TOKEN-DEST @ SQC.SCOPE-FINGERPRINT
        SHA3-256-LEN MOVE
    DROP
    DUP IF
        STREAMS-PA-RANGE-ROW-KEY$
        2DUP R@ _SQW.FAMILY @ _SQ-FAMILY-KEY-VALID? 0= IF
            2DROP R> DROP STREAMS-QUERY-S-CORRUPT EXIT
        THEN
        DUP R@ _SQW.TOKEN-DEST @ SQC.KEY-U !
        2DUP R@ _SQW.TOKEN-DEST @ SQC.KEY SWAP MOVE
        2DROP
    ELSE
        DROP
    THEN
    R@ _SQW.TOKEN-DEST @ _SQC-SEAL
    R@ _SQW.TOKEN-DEST @
        STREAMS-QUERY-CONTINUATION-VALID? 0= IF
        R> DROP STREAMS-QUERY-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-QUERY-S-OK ;

: _SQ-PUBLISH-PAGE  ( work -- status )
    >R
    R@ _SQW.FAMILY @ R@ _SQW.PAGE @ SQP.FAMILY !
    R@ _SQW.RESULT-U @ R@ _SQW.PAGE @ SQP.COUNT !
    R@ _SQW.PROVENANCE @ R@ _SQW.PAGE @ SQP.PROVENANCE !
    R@ _SQW.SOURCE-COMPLETENESS @
        R@ _SQW.PAGE @ SQP.SOURCE-COMPLETENESS !
    R@ _SQW.OBSERVATION-COMPLETENESS @
        R@ _SQW.PAGE @ SQP.OBSERVATION-COMPLETENESS !
    R@ _SQW.AUTHORITY-ID R@ _SQW.PAGE @ SQP.AUTHORITY-ID RID-COPY
    R@ _SQW.RESULT-U @ IF
        R@ _SQW.RESULT-U @ 1- R@ _SQ-RESULT-ROW
    ELSE
        0
    THEN
    STREAMS-QUERY-DIRECTION-AFTER R@ _SQ-BUILD-PAGE-TOKEN
    DUP IF R> DROP EXIT THEN DROP
    R@ _SQW.RESULT-U @ IF
        0 R@ _SQ-RESULT-ROW
    ELSE
        0
    THEN
    STREAMS-QUERY-DIRECTION-BEFORE R@ _SQ-BUILD-PAGE-TOKEN
    DUP IF R> DROP EXIT THEN DROP
    R@ _SQW.PAGE @ STREAMS-QUERY-PAGE-VALID? 0= IF
        R> DROP STREAMS-QUERY-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-QUERY-S-OK ;

: _SQ-RANGE-RUN  ( work -- status )
    >R
    R@ _SQ-BUILD-PREFIX
    DUP IF R> DROP EXIT THEN DROP
    R@ _SQ-CAPTURE-AUTHORITY
    DUP IF R> DROP EXIT THEN DROP
    R@ _SQ-PREPARE-CONTINUATION
    DUP IF R> DROP EXIT THEN DROP
    R@ _SQW.PAGE @ _SQ-CLEAR-PAGE
    R@ _SQ-RANGE-CALL
    DUP IF
        >R DROP R> R> DROP EXIT
    THEN
    DROP
    DUP R@ _SQW.RESULT-U !
    DROP
    R@ _SQ-RESULT-ROWS-VALID? 0= IF
        R> DROP STREAMS-QUERY-S-CORRUPT EXIT
    THEN
    R@ _SQ-PUBLISH-PAGE
    R> DROP ;

