: _SQ-BEGIN-RANGE  ( scope-a scope-u continuation mode family page adapter adapter-work work -- status )
    >R
    R@ STREAMS-QUERY-WORK-VALID? 0= IF
        _SQ-DROP8 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    R@ _SQW.BUSY @ IF
        _SQ-DROP8 R> DROP STREAMS-QUERY-S-BUSY EXIT
    THEN
    DUP STREAMS-PA-WORK-VALID? 0= IF
        _SQ-DROP8 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    OVER STREAMS-PA-VALID? 0= IF
        _SQ-DROP8 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    R@ STREAMS-QUERY-WORK-SIZE 2 PICK
        STREAMS-PA-SPAN-DISJOINT? 0= IF
        _SQ-DROP8 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    2 PICK STREAMS-QUERY-PAGE-VALID? 0= IF
        _SQ-DROP8 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    7 PICK R@ _SQW.SCOPE-A !
    6 PICK R@ _SQW.SCOPE-U !
    5 PICK R@ _SQW.CONTINUATION !
    4 PICK R@ _SQW.MODE !
    3 PICK R@ _SQW.FAMILY !
    2 PICK R@ _SQW.PAGE !
    OVER R@ _SQW.ADAPTER !
    DUP R@ _SQW.ADAPTER-WORK !
    _SQ-DROP8
    R@ _SQ-RANGE-SHAPE? 0= IF
        R@ _SQW-CLEAR-TRANSIENT
        R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    R@ _SQ-RANGE-GEOMETRY? 0= IF
        R@ _SQW-CLEAR-TRANSIENT
        R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    -1 R@ _SQW.BUSY !
    STREAMS-QUERY-S-INVALID R@ _SQW.STATUS !
    R> DROP STREAMS-QUERY-S-OK ;

