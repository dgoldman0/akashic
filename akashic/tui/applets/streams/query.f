    R@ STREAMS-QUERY-WORK-SIZE R@
        _SQ-SPAN-PA-SAFE? 0= IF R> DROP 0 EXIT THEN
    R@ STREAMS-QUERY-WORK-SIZE R@
        _SQ-SPAN-OUTSIDE-ADAPTER? 0= IF R> DROP 0 EXIT THEN
    R@ _SQW.SCOPE-A @ RID-SIZE R@
        _SQ-SPAN-OUTSIDE-WORK? 0= IF R> DROP 0 EXIT THEN
    R@ _SQW.SCOPE-A @ RID-SIZE R@
        _SQ-SPAN-PA-SAFE? 0= IF R> DROP 0 EXIT THEN
    R@ _SQW.SCOPE-A @ RID-SIZE R@
        _SQ-SPAN-OUTSIDE-ADAPTER? 0= IF R> DROP 0 EXIT THEN
    R@ _SQW.DEST-A @ R@ _SQW.DEST-U @ R@
        _SQ-SPAN-OUTSIDE-WORK? 0= IF R> DROP 0 EXIT THEN
    R@ _SQW.DEST-A @ R@ _SQW.DEST-U @ R@
        _SQ-SPAN-PA-SAFE? 0= IF R> DROP 0 EXIT THEN
    R@ _SQW.DEST-A @ R@ _SQW.DEST-U @ R@
        _SQ-SPAN-OUTSIDE-ADAPTER? 0= IF R> DROP 0 EXIT THEN
    R@ _SQW.SCOPE-A @ RID-SIZE
    R@ _SQW.DEST-A @ R@ _SQW.DEST-U @
        _SQ-SPANS-DISJOINT?
    R> DROP ;

: _SQ-BEGIN-EXACT  ( observation-rid revision destination destination-u adapter adapter-work work -- status )
    >R
    R@ STREAMS-QUERY-WORK-VALID? 0= IF
        _SQ-DROP6 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    R@ _SQW.BUSY @ IF
        _SQ-DROP6 R> DROP STREAMS-QUERY-S-BUSY EXIT
    THEN
    DUP STREAMS-PA-WORK-VALID? 0= IF
        _SQ-DROP6 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    OVER STREAMS-PA-VALID? 0= IF
        _SQ-DROP6 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    R@ STREAMS-QUERY-WORK-SIZE 2 PICK
        STREAMS-PA-SPAN-DISJOINT? 0= IF
        _SQ-DROP6 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    5 PICK DUP 0= IF
        DROP _SQ-DROP6 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    DUP RID-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP _SQ-DROP6 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    RID-PRESENT? 0= IF
        _SQ-DROP6 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    4 PICK DUP 0> 0= SWAP PERSIST-MAX-SIGNED > OR IF
        _SQ-DROP6 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    2 PICK SPREC-OBSERVATION-SIZE <> IF
        _SQ-DROP6 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    3 PICK DUP 0= IF
        DROP _SQ-DROP6 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    3 PICK MSPAN-NONWRAPPING? 0= IF
        _SQ-DROP6 R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    5 PICK R@ _SQW.SCOPE-A !
    RID-SIZE R@ _SQW.SCOPE-U !
    4 PICK R@ _SQW.REVISION !
    3 PICK R@ _SQW.DEST-A !
    2 PICK R@ _SQW.DEST-U !
    OVER R@ _SQW.ADAPTER !
    DUP R@ _SQW.ADAPTER-WORK !
    _SQ-DROP6
    R@ _SQ-EXACT-GEOMETRY? 0= IF
        R@ _SQW-CLEAR-TRANSIENT
        R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    -1 R@ _SQW.BUSY !
    STREAMS-QUERY-S-INVALID R@ _SQW.STATUS !
    R> DROP STREAMS-QUERY-S-OK ;

: _SQ-EXACT-FAIL  ( status work -- status )
    >R
    R@ _SQW.DEST-A @ R@ _SQW.DEST-U @ 0 FILL
    0 R@ _SQW.RESULT-U !
    R> DROP ;

: _SQ-EXACT-RUN  ( work -- status )
    >R
    R@ _SQW.DEST-A @ R@ _SQW.DEST-U @ 0 FILL
    R@ _SQW.KEY PBTREE-KEY-MAX 0 FILL
    R@ _SQW.SCOPE-A @ R@ _SQW.REVISION @ R@ _SQW.KEY
        STREAMS-PI-OBSERVATION-REVISION-KEY
    DUP IF
        DROP STREAMS-QUERY-S-INVALID R@ _SQ-EXACT-FAIL
        R> DROP EXIT
    THEN
    DROP
    R@ _SQW.KEY STREAMS-PI-OBSERVATION-REVISION-KEY-SIZE
    R@ _SQW.DEST-A @ R@ _SQW.DEST-U @
    R@ _SQW.ADAPTER @ R@ _SQW.ADAPTER-WORK @
        STREAMS-PA-GET
    DUP IF
        >R DROP R> R@ _SQ-EXACT-FAIL R> DROP EXIT
    THEN
    DROP
    DUP SPREC-OBSERVATION-SIZE <> IF
        DROP STREAMS-QUERY-S-CORRUPT R@ _SQ-EXACT-FAIL
        R> DROP EXIT
    THEN
    R@ _SQW.DEST-A @ OVER SPREC-OBSERVATION-VALID? 0= IF
        DROP STREAMS-QUERY-S-CORRUPT R@ _SQ-EXACT-FAIL
        R> DROP EXIT
    THEN
    R@ _SQW.RESULT-U !
    R> DROP STREAMS-QUERY-S-OK ;

: STREAMS-QUERY-OBSERVATION-REVISION@  ( observation-rid revision destination destination-u adapter adapter-work work -- record-u status )
    DUP >R _SQ-BEGIN-EXACT
    DUP IF R> DROP 0 SWAP EXIT THEN DROP
    R@ ['] _SQ-EXACT-RUN _SQ-WORK-CATCH
    DUP IF R@ _SQ-EXACT-FAIL THEN
    R@ _SQW.RESULT-U @ SWAP
    R> _SQ-LEAVE ;

\ ---------------------------------------------------------------------
\ Bounded immutable observation content
\ ---------------------------------------------------------------------
\ The sink callback is exactly
\   ( logical-offset source-a offered-u sink-context -- status )
\ and must consume the complete offered span before returning OK.  These
\ wrappers admit only a fully valid SPREC observation, then pass its checked
\ PBLOB descriptor to the READY-only, read-only adapter operations.  Neither
\ call materializes the complete body in query or adapter memory.  The record
\ remains borrowed for the whole call and the callback must not mutate it.

: _SQ-OBSERVATION-CONTENT-ARGS?  ( observation-record adapter adapter-work -- flag )
    DUP STREAMS-PA-WORK-VALID? 0= IF _SQ-DROP3 0 EXIT THEN
    OVER STREAMS-PA-VALID? 0= IF _SQ-DROP3 0 EXIT THEN
    2 PICK 0= IF _SQ-DROP3 0 EXIT THEN
    2 PICK SPREC-OBSERVATION-SIZE
        MSPAN-NONWRAPPING? 0= IF _SQ-DROP3 0 EXIT THEN
    2 PICK SPREC-OBSERVATION-SIZE
        SPREC-OBSERVATION-VALID? 0= IF _SQ-DROP3 0 EXIT THEN
    2 PICK SPREC-OBSERVATION-SIZE 2 PICK
        STREAMS-PA-SPAN-DISJOINT? 0= IF _SQ-DROP3 0 EXIT THEN
    2 PICK SPREC-OBSERVATION-SIZE
    3 PICK STREAMS-PA-SIZE MSPAN-OVERLAP? IF
        _SQ-DROP3 0 EXIT
    THEN
    _SQ-DROP3 -1 ;

: STREAMS-QUERY-OBSERVATION-CONTENT-SIZE@  ( observation-record -- bytes|-1 )
    DUP 0= IF DROP -1 EXIT THEN
    DUP SPREC-OBSERVATION-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP -1 EXIT THEN
    DUP SPREC-OBSERVATION-SIZE
        SPREC-OBSERVATION-VALID? 0= IF DROP -1 EXIT THEN
    SPRO.CONTENT-U @ ;

: STREAMS-QUERY-OBSERVATION-CONTENT-READ-RANGE  ( observation-record offset requested-u sink-xt sink-context adapter adapter-work -- status )
    6 PICK 2 PICK 2 PICK
        _SQ-OBSERVATION-CONTENT-ARGS? 0= IF
        _SQ-DROP7 STREAMS-QUERY-S-INVALID EXIT
    THEN
    5 PICK 0< IF _SQ-DROP7 STREAMS-QUERY-S-INVALID EXIT THEN
    4 PICK 0< IF _SQ-DROP7 STREAMS-QUERY-S-INVALID EXIT THEN
    3 PICK 0= IF _SQ-DROP7 STREAMS-QUERY-S-INVALID EXIT THEN
    >R >R >R >R >R >R >R
    R> SPRO.CONTENT
    R> R> R> R> R> R>
    STREAMS-PA-BLOB-READ-RANGE ;

: STREAMS-QUERY-OBSERVATION-CONTENT-STREAM  ( observation-record offset sink-xt sink-context adapter adapter-work -- status )
    5 PICK 2 PICK 2 PICK
        _SQ-OBSERVATION-CONTENT-ARGS? 0= IF
        _SQ-DROP6 STREAMS-QUERY-S-INVALID EXIT
    THEN
    4 PICK 0< IF _SQ-DROP6 STREAMS-QUERY-S-INVALID EXIT THEN
    3 PICK 0= IF _SQ-DROP6 STREAMS-QUERY-S-INVALID EXIT THEN
    >R >R >R >R >R >R
    R> SPRO.CONTENT
    R> R> R> R> R>
    STREAMS-PA-BLOB-STREAM ;
