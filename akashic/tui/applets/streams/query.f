: _SQ-BUILD-PREFIX  ( work -- status )
    >R
    R@ _SQW.PREFIX PBTREE-KEY-MAX 0 FILL
    R@ _SQW.FAMILY @ CASE
        STREAMS-QUERY-FAMILY-SOURCES OF
            R@ _SQW.PREFIX STREAMS-PI-SOURCE-ORDER-PREFIX
        ENDOF
        STREAMS-QUERY-FAMILY-ATTEMPTS OF
            R@ _SQW.SCOPE-A @ R@ _SQW.PREFIX
            STREAMS-PI-ATTEMPT-BY-SOURCE-PREFIX
        ENDOF
        STREAMS-QUERY-FAMILY-OBSERVATION-REVISIONS OF
            R@ _SQW.SCOPE-A @ R@ _SQW.PREFIX
            STREAMS-PI-OBSERVATION-REVISION-PREFIX
        ENDOF
        STREAMS-QUERY-FAMILY-GLOBAL-TIME OF
            R@ _SQW.PREFIX STREAMS-PI-GLOBAL-TIME-PREFIX
        ENDOF
        STREAMS-QUERY-FAMILY-SOURCE-TIME OF
            R@ _SQW.SCOPE-A @ R@ _SQW.PREFIX
            STREAMS-PI-SOURCE-TIME-PREFIX
        ENDOF
        STREAMS-QUERY-S-INVALID SWAP
    ENDCASE
    DUP IF DROP R> DROP STREAMS-QUERY-S-INVALID EXIT THEN DROP
    R@ _SQW.FAMILY @ _SQ-FAMILY-PREFIX-SIZE
    DUP 0= IF DROP R> DROP STREAMS-QUERY-S-CORRUPT EXIT THEN
    DUP R@ _SQW.PREFIX-U !
    R@ _SQW.PREFIX SWAP R@ _SQW.FAMILY @
        _SQ-FAMILY-PREFIX-VALID? 0= IF
        R> DROP STREAMS-QUERY-S-CORRUPT EXIT
    THEN
    R@ _SQW.PREFIX R@ _SQW.PREFIX-U @
    R@ _SQW.SCOPE-FINGERPRINT SHA3-256-HASH
    R> DROP STREAMS-QUERY-S-OK ;

: _SQ-CAPTURE-AUTHORITY  ( work -- status )
    >R
    R@ _SQW.ADAPTER-WORK @ STREAMS-PA-ACTIVE? IF
        R> DROP STREAMS-QUERY-S-BUSY EXIT
    THEN
    R@ _SQW.ADAPTER-WORK @ STREAMS-PA-REOPEN-REQUIRED? IF
        R> DROP STREAMS-QUERY-S-CONFLICT EXIT
    THEN
    R@ _SQW.ADAPTER-WORK @ _SQ-AUTHORITY-ROOT DUP 0= IF
        DROP R> DROP STREAMS-QUERY-S-ABSENT EXIT
    THEN
    DUP R@ _SQW.ROOT !
    DUP SAR.AUTHORITY-ID R@ _SQW.AUTHORITY-ID RID-COPY
    DUP SAR.PROVENANCE @ R@ _SQW.PROVENANCE !
    DUP SAR.SOURCE-COMPLETENESS @
        R@ _SQW.SOURCE-COMPLETENESS !
    SAR.OBSERVATION-COMPLETENESS @
        R@ _SQW.OBSERVATION-COMPLETENESS !
    R@ _SQW.AUTHORITY-ID RID-PRESENT? 0= IF
        R> DROP STREAMS-QUERY-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-QUERY-S-OK ;

: _SQ-CONTINUATION-MATCH?  ( work -- flag )
    >R
    R@ _SQW.CONTINUATION @ DUP
        STREAMS-QUERY-CONTINUATION-READY? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SQC.FAMILY @ R@ _SQW.FAMILY @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SQC.DIRECTION @
    R@ _SQW.MODE @ _SQ-MODE-DIRECTION <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SQC.AUTHORITY-ID R@ _SQW.AUTHORITY-ID RID= 0= IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SQC.SCOPE-FINGERPRINT
    R@ _SQW.SCOPE-FINGERPRINT SHA3-256-LEN
        _SQ-BYTES= 0= IF DROP R> DROP 0 EXIT THEN
    DUP STREAMS-QUERY-CONTINUATION-KEY$
    R@ _SQW.FAMILY @ _SQ-FAMILY-KEY-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    STREAMS-QUERY-CONTINUATION-KEY$
    R@ _SQW.PREFIX R@ _SQW.PREFIX-U @
    2 PICK OVER < IF _SQ-DROP4 R> DROP 0 EXIT THEN
    >R SWAP DROP R> _SQ-BYTES=
    R> DROP ;

: _SQ-PREPARE-CONTINUATION  ( work -- status )
    >R
    R@ _SQW.KEY PBTREE-KEY-MAX 0 FILL
    0 R@ _SQW.KEY-U !
    R@ _SQW.MODE @ DUP _SQ-MODE-FIRST =
    SWAP _SQ-MODE-LAST = OR IF
        R> DROP STREAMS-QUERY-S-OK EXIT
    THEN
    R@ _SQ-CONTINUATION-MATCH? 0= IF
        R> DROP STREAMS-QUERY-S-INVALID EXIT
    THEN
    R@ _SQW.CONTINUATION @
        STREAMS-QUERY-CONTINUATION-KEY$
    DUP R@ _SQW.KEY-U !
    2DUP R@ _SQW.KEY SWAP MOVE
    2DROP
    R> DROP STREAMS-QUERY-S-OK ;

