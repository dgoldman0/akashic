\ =====================================================================
\  query.f - bounded, stable Streams query surfaces
\ =====================================================================
\  This layer exposes only the durable streaming topology needed by Streams:
\  configured sources in creation order, retained attempts by source,
\  immutable revisions by observation identity, observations in global
\  acquisition order, observations in one source's acquisition order, and
\  exact immutable observation revisions.  It deliberately owns no text
\  search, thread, Library-document, projection, or output/publication policy.
\
\  Every page retains the adapter's exact semantic key and complete SPREC
\  snapshot in caller-owned rows.  Continuations are sealed, pointer-free
\  semantic keyset tokens.  They bind the query family, direction, hash of
\  the exact canonical prefix, and authority ID; no physical cursor, page,
\  slot, or logical generation crosses this boundary.
\
\  FIRST and LAST are the two initial traversals.  A successful page publishes
\  both directions: AFTER resumes from its last row and BEFORE resumes from
\  its first row.  The authority's provenance and both completeness
\  classifications are copied even for a zero-row page, so absence is never
\  promoted silently to complete history.
\ =====================================================================

