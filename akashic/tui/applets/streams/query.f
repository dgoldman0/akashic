        _SQ-SPAN-OUTSIDE-ADAPTER? 0= IF R> DROP 0 EXIT THEN
    R@ _SQW.PAGE @ STREAMS-QUERY-PAGE-SIZE
    R@ _SQW.CONTINUATION @
    R@ _SQW.MODE @ DUP _SQ-MODE-FIRST =
    SWAP _SQ-MODE-LAST = OR IF
        0
    ELSE
        STREAMS-QUERY-CONTINUATION-SIZE
    THEN
        _SQ-SPANS-DISJOINT? 0= IF R> DROP 0 EXIT THEN
    R@ _SQW.PAGE @ SQP.ROWS @
    R@ _SQW.PAGE @ SQP.CAPACITY @
        STREAMS-PA-RANGE-ROW-SIZE *
    R@ _SQW.CONTINUATION @
    R@ _SQW.MODE @ DUP _SQ-MODE-FIRST =
    SWAP _SQ-MODE-LAST = OR IF
        0
    ELSE
        STREAMS-QUERY-CONTINUATION-SIZE
    THEN
        _SQ-SPANS-DISJOINT? 0= IF R> DROP 0 EXIT THEN
    R@ _SQW.PAGE @ STREAMS-QUERY-PAGE-SIZE
    R@ _SQW.SCOPE-A @ R@ _SQW.SCOPE-U @
        _SQ-SPANS-DISJOINT? 0= IF R> DROP 0 EXIT THEN
    R@ _SQW.PAGE @ SQP.ROWS @
    R@ _SQW.PAGE @ SQP.CAPACITY @
        STREAMS-PA-RANGE-ROW-SIZE *
    R@ _SQW.SCOPE-A @ R@ _SQW.SCOPE-U @
        _SQ-SPANS-DISJOINT? 0= IF R> DROP 0 EXIT THEN
    R@ _SQW.CONTINUATION @
    R@ _SQW.MODE @ DUP _SQ-MODE-FIRST =
    SWAP _SQ-MODE-LAST = OR IF
        0
    ELSE
        STREAMS-QUERY-CONTINUATION-SIZE
