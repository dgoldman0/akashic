\ =====================================================================
\ rabbit-connector.f - long-lived Streams Rabbit client connector
\ =====================================================================
\ One caller-owned connector adopts an already configured neutral Rabbit
\ client plus its RABBIT-SUBSCRIPTIONS owner.  The connector is a persistent
\ product lifetime, not one terminal STREAMS-FLOW cell.  Individual Rabbit
\ operations may later publish Streams flow/attempt evidence, but closing one
\ operation never closes this tunnel.
\
\ INIT does not assemble transport memory.  The caller supplies a valid,
\ attached subscription graph whose current client owns the connection,
\ session, parser, and client operation storage.  This keeps all variable
\ capacities in the neutral caller-provided graph.  After INIT succeeds the
\ caller drives that graph only through this owner until DETACH or FINI.
\
\ DETACH preserves configured subscription targets, callbacks, generations,
\ and application Event-Seq cursors while cancelling and finalizing the old
\ client.  ATTACH adopts a fresh READY or ACTIVE neutral client; Streams may
\ then HELLO and rebind without changing application state.  Queue and
\ physical transport storage remain outside the client graph and are released
\ by their own neutral/transport owners after DETACH.
\
\ The neutral Rabbit implementation currently uses serialized synchronous
\ scratch.  All public operations here therefore refuse connector reentry and
\ are intended to run on one Streams/Desk scheduling owner.  No word blocks,
\ allocates, or retains a borrowed inbound frame.  Correlated operation
\ results remain owned by the adopted client, but callers inspect and release
\ them through generation-checked connector words rather than escaping through
\ the nested client pointer.
\ The RESULT@ body slice is borrowed only until operation release, detach,
\ replacement, or finalization; a retaining owner must copy it first.
\ =====================================================================

\ Keep the KDOS module identity within 23 bytes.
PROVIDED akashic-streams-rconn

