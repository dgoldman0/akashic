    CASE
        RSUB-ITEM-NONE OF
            STREAMS-RABBIT-CONNECTOR-ACTIVITY-NONE ENDOF
        RSUB-ITEM-BIND OF
            STREAMS-RABBIT-CONNECTOR-ACTIVITY-BIND ENDOF
        RSUB-ITEM-EVENT OF
            STREAMS-RABBIT-CONNECTOR-ACTIVITY-EVENT ENDOF
        RSUB-ITEM-CLIENT-OP OF
            STREAMS-RABBIT-CONNECTOR-ACTIVITY-OPERATION ENDOF
        STREAMS-RABBIT-CONNECTOR-ACTIVITY-OTHER SWAP
    ENDCASE ;

