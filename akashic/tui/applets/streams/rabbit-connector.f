: _SRCONN-SPAN-HITS-SUB-GRAPH?
  ( address bytes subscriptions -- flag )
    _SRCONNG-S ! _SRCONNG-U ! _SRCONNG-A !
    _SRCONNG-A @ _SRCONNG-U @
        _SRCONNG-S @ RABBIT-SUBSCRIPTIONS-SIZE
        MSPAN-OVERLAP? IF -1 EXIT THEN
    _SRCONNG-S @ RSUB.CAPACITY @ IF
        _SRCONNG-A @ _SRCONNG-U @
            _SRCONNG-S @ RSUB.ENTRIES @
            _SRCONNG-S @ RSUB.CAPACITY @
                RABBIT-SUBSCRIPTION-ENTRY-BYTES
            MSPAN-OVERLAP? IF -1 EXIT THEN
        _SRCONNG-A @ _SRCONNG-U @
            _SRCONNG-S @ RSUB.TARGET-A @
            _SRCONNG-S @ RSUB.CAPACITY @
            _SRCONNG-S @ RSUB.TARGET-SLOT-BYTES @ *
            MSPAN-OVERLAP? IF -1 EXIT THEN
        _SRCONNG-A @ _SRCONNG-U @
            _SRCONNG-S @ RSUB.EVENT-A @
            _SRCONNG-S @ RSUB.CAPACITY @
            _SRCONNG-S @ RSUB.EVENT-SLOT-BYTES @ *
            MSPAN-OVERLAP? IF -1 EXIT THEN
    THEN
    _SRCONNG-A @ _SRCONNG-U @ _SRCONNG-S @ RSUB.CLIENT @ ?DUP IF
        RABBIT-CLIENT-OWNED-SPAN-OVERLAP?
    ELSE
        2DROP 0
    THEN ;

: STREAMS-RABBIT-CONNECTOR-VALID?  ( connector -- flag )
    \ Neutral client/subscription validation uses module scratch too.  A
    \ callback may not even inspect this owner until its outer poll returns.
    _SRCONN-BUSY @ IF DROP 0 EXIT THEN
    DUP _SRCONN-HEADER? 0= IF DROP 0 EXIT THEN
    DUP SRCONN.STATE @ STREAMS-RABBIT-CONNECTOR-STATE-VALID? 0= IF
        DROP 0 EXIT
    THEN
    DUP SRCONN.LAST-STATUS @
        STREAMS-RABBIT-CONNECTOR-STATUS-VALID? 0= IF DROP 0 EXIT THEN
    DUP SRCONN.LAST-ACTIVITY @
        STREAMS-RABBIT-CONNECTOR-ACTIVITY-VALID? 0= IF DROP 0 EXIT THEN
    DUP SRCONN.POLL-COUNT @ 0< IF DROP 0 EXIT THEN
    DUP SRCONN.RECONNECT-COUNT @ 0< IF DROP 0 EXIT THEN
    DUP SRCONN.ATTACHMENT-GENERATION @ 0= IF DROP 0 EXIT THEN
    DUP SRCONN.FLAGS @ IF DROP 0 EXIT THEN
    DUP SRCONN.SUBSCRIPTIONS @ DUP 0= IF 2DROP 0 EXIT THEN
    RABBIT-SUBSCRIPTIONS-VALID? 0= IF DROP 0 EXIT THEN
    DUP SRCONN.STATE @ STREAMS-RABBIT-CONNECTOR-ST-ATTACHED = IF
        DUP SRCONN.CLIENT @ DUP 0= IF 2DROP 0 EXIT THEN
        RABBIT-CLIENT-VALID? 0= IF DROP 0 EXIT THEN
        DUP SRCONN.SUBSCRIPTIONS @ RSUB.STATE @ RSUB-ST-ATTACHED <>
            IF DROP 0 EXIT THEN
        DUP SRCONN.SUBSCRIPTIONS @ RSUB.CLIENT @
            OVER SRCONN.CLIENT @ = 0= IF DROP 0 EXIT THEN
    ELSE DUP SRCONN.STATE @
        STREAMS-RABBIT-CONNECTOR-ST-DETACHED = IF
        DUP SRCONN.CLIENT @ IF DROP 0 EXIT THEN
        DUP SRCONN.SUBSCRIPTIONS @ RSUB.STATE @ RSUB-ST-DETACHED <>
            IF DROP 0 EXIT THEN
        DUP SRCONN.SUBSCRIPTIONS @ RSUB.CLIENT @ IF DROP 0 EXIT THEN
    ELSE
        DUP SRCONN.CLIENT @ DUP 0= IF 2DROP 0 EXIT THEN
        RABBIT-CLIENT-VALID? 0= IF DROP 0 EXIT THEN
        DUP SRCONN.SUBSCRIPTIONS @ RSUB.STATE @
        DUP RSUB-ST-ATTACHED = IF
            DROP
            DUP SRCONN.SUBSCRIPTIONS @ RSUB.CLIENT @
                OVER SRCONN.CLIENT @ = 0= IF DROP 0 EXIT THEN
        ELSE
            RSUB-ST-DETACHED <> IF DROP 0 EXIT THEN
            DUP SRCONN.SUBSCRIPTIONS @ RSUB.CLIENT @ IF DROP 0 EXIT THEN
        THEN
    THEN
    THEN
    DROP -1 ;

VARIABLE _SRCONNG-O

\ Fail-closed evidence for a higher Streams owner which borrows this complete
\ connector graph.  The sealed application configuration above the connector
\ can stay opaque without learning subscription or neutral-client layout.
: STREAMS-RABBIT-CONNECTOR-OWNED-SPAN-OVERLAP?
  ( address bytes connector -- flag )
    _SRCONNG-O ! _SRCONNG-U ! _SRCONNG-A !
    _SRCONNG-U @ 0< IF -1 EXIT THEN
    _SRCONNG-U @ IF _SRCONNG-A @ 0= IF -1 EXIT THEN THEN
    _SRCONNG-A @ _SRCONNG-U @ MSPAN-NONWRAPPING? 0= IF -1 EXIT THEN
    _SRCONN-BUSY @ IF -1 EXIT THEN
    _SRCONNG-O @ STREAMS-RABBIT-CONNECTOR-VALID? 0= IF -1 EXIT THEN
    _SRCONNG-A @ _SRCONNG-U @
        _SRCONNG-O @ STREAMS-RABBIT-CONNECTOR-SIZE
        MSPAN-OVERLAP? IF -1 EXIT THEN
    _SRCONNG-A @ _SRCONNG-U @
        _SRCONNG-O @ SRCONN.SUBSCRIPTIONS @
        _SRCONN-SPAN-HITS-SUB-GRAPH? ;

