: _SRCONN-STATUS!  ( status detail connector -- status )
    _SRCONNS-O ! _SRCONNS-DETAIL !
    DUP _SRCONNS-O @ SRCONN.LAST-STATUS !
    _SRCONNS-DETAIL @ _SRCONNS-O @ SRCONN.DETAIL ! ;

: _SRCONN-RSUB>STATUS  ( rsub-status -- connector-status )
    DUP RSUB-S-OK = IF DROP STREAMS-RABBIT-CONNECTOR-S-OK EXIT THEN
    \ These are successful poll outcomes, not connector failures.  Their
    \ exact delivery/result domain remains available through DETAIL@ while
    \ the returned item selects the application path which owns that detail.
    DUP RSUB-S-BIND-RESULT = IF
        DROP STREAMS-RABBIT-CONNECTOR-S-OK EXIT
    THEN
    DUP RSUB-S-EVENT = IF DROP STREAMS-RABBIT-CONNECTOR-S-OK EXIT THEN
    DUP RSUB-S-EVENT-DUPLICATE = IF
        DROP STREAMS-RABBIT-CONNECTOR-S-OK EXIT
    THEN
    DUP RSUB-S-GAP = IF DROP STREAMS-RABBIT-CONNECTOR-S-OK EXIT THEN
    DUP RSUB-S-OVERFLOW = IF
        DROP STREAMS-RABBIT-CONNECTOR-S-OK EXIT
    THEN
    DUP RSUB-S-DROPPED = IF DROP STREAMS-RABBIT-CONNECTOR-S-OK EXIT THEN
    DUP RSUB-S-OTHER = IF DROP STREAMS-RABBIT-CONNECTOR-S-OK EXIT THEN
    DUP RSUB-S-PENDING = IF
        DROP STREAMS-RABBIT-CONNECTOR-S-PENDING EXIT
    THEN
    DUP RSUB-S-DISCONNECTED = IF
        DROP STREAMS-RABBIT-CONNECTOR-S-DISCONNECTED EXIT
    THEN
    DUP RSUB-S-STATE = IF DROP STREAMS-RABBIT-CONNECTOR-S-STATE EXIT THEN
    DUP RSUB-S-CLIENT = IF DROP STREAMS-RABBIT-CONNECTOR-S-CLIENT EXIT THEN
    DROP STREAMS-RABBIT-CONNECTOR-S-SUBSCRIPTIONS ;

: _SRCONN-RCLIENT>STATUS  ( client-status -- connector-status )
    DUP RCLIENT-S-OK = IF DROP STREAMS-RABBIT-CONNECTOR-S-OK EXIT THEN
    DUP RCLIENT-S-PENDING = IF
        DROP STREAMS-RABBIT-CONNECTOR-S-PENDING EXIT
    THEN
    DUP RCLIENT-S-CANCELLED = IF
        DROP STREAMS-RABBIT-CONNECTOR-S-DISCONNECTED EXIT
    THEN
    DUP RCLIENT-S-CAPACITY = IF
        DROP STREAMS-RABBIT-CONNECTOR-S-CAPACITY EXIT
    THEN
    DUP RCLIENT-S-STATE = IF DROP STREAMS-RABBIT-CONNECTOR-S-STATE EXIT THEN
    DROP STREAMS-RABBIT-CONNECTOR-S-CLIENT ;

