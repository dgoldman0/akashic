: STREAMS-RABBIT-CONNECTOR-INIT
  ( subscriptions client connector -- status )
    _SRCONN-BUSY @ IF
        2DROP DROP STREAMS-RABBIT-CONNECTOR-S-BUSY EXIT
    THEN
    _SRCONNI-O ! _SRCONNI-CLIENT ! _SRCONNI-SUBS !
    _SRCONNI-O @ 0= IF STREAMS-RABBIT-CONNECTOR-S-INVALID EXIT THEN
    _SRCONNI-O @ 7 AND IF STREAMS-RABBIT-CONNECTOR-S-INVALID EXIT THEN
    _SRCONNI-O @ STREAMS-RABBIT-CONNECTOR-SIZE
        MSPAN-NONWRAPPING? 0= IF
        STREAMS-RABBIT-CONNECTOR-S-INVALID EXIT
    THEN
    _SRCONNI-O @ SRCONN.MAGIC @ _SRCONN-MAGIC-VALUE = IF
        STREAMS-RABBIT-CONNECTOR-S-STATE EXIT
    THEN
    _SRCONNI-SUBS @ RABBIT-SUBSCRIPTIONS-VALID? 0= IF
        STREAMS-RABBIT-CONNECTOR-S-SUBSCRIPTIONS EXIT
    THEN
    _SRCONNI-SUBS @ RSUB.STATE @ RSUB-ST-ATTACHED <> IF
        STREAMS-RABBIT-CONNECTOR-S-STATE EXIT
    THEN
    _SRCONNI-CLIENT @ RABBIT-CLIENT-VALID? 0= IF
        STREAMS-RABBIT-CONNECTOR-S-CLIENT EXIT
    THEN
    _SRCONNI-SUBS @ RSUB.CLIENT @ _SRCONNI-CLIENT @ <> IF
        STREAMS-RABBIT-CONNECTOR-S-INVALID EXIT
    THEN
    _SRCONNI-O @ STREAMS-RABBIT-CONNECTOR-SIZE _SRCONNI-SUBS @
        _SRCONN-SPAN-HITS-SUB-GRAPH? IF
        STREAMS-RABBIT-CONNECTOR-S-INVALID EXIT
    THEN
    _SRCONNI-O @ STREAMS-RABBIT-CONNECTOR-SIZE 0 FILL
    _SRCONN-MAGIC-VALUE _SRCONNI-O @ SRCONN.MAGIC !
    _SRCONN-ABI-VERSION _SRCONNI-O @ SRCONN.ABI !
    STREAMS-RABBIT-CONNECTOR-SIZE _SRCONNI-O @ SRCONN.BYTES !
    STREAMS-RABBIT-CONNECTOR-ST-ATTACHED _SRCONNI-O @ SRCONN.STATE !
    STREAMS-RABBIT-CONNECTOR-S-OK _SRCONNI-O @ SRCONN.LAST-STATUS !
    _SRCONNI-CLIENT @ _SRCONNI-O @ SRCONN.CLIENT !
    _SRCONNI-SUBS @ _SRCONNI-O @ SRCONN.SUBSCRIPTIONS !
    1 _SRCONNI-O @ SRCONN.ATTACHMENT-GENERATION !
    STREAMS-RABBIT-CONNECTOR-S-OK ;

