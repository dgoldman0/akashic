VARIABLE _SRCONN-BUSY

: _SRCONN-COUNT+  ( count-field -- )
    \ Diagnostic evidence saturates; it must never wrap and invalidate the
    \ lifecycle owner it is meant to describe.
    DUP @ -1 1 RSHIFT U< IF 1 SWAP +! ELSE DROP THEN ;

: _SRCONN-HEADER?  ( connector -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP 7 AND IF DROP 0 EXIT THEN
    DUP STREAMS-RABBIT-CONNECTOR-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP SRCONN.MAGIC @ _SRCONN-MAGIC-VALUE =
    OVER SRCONN.ABI @ _SRCONN-ABI-VERSION = AND
    SWAP SRCONN.BYTES @ STREAMS-RABBIT-CONNECTOR-SIZE = AND ;

