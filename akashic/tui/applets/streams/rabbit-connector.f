: _SRCONNP-CLEAR  ( -- )
    0 _SRCONNP-O ! 0 _SRCONNP-FALLBACK-XT !
    0 _SRCONNP-FALLBACK-CONTEXT ! 0 _SRCONNP-ITEM !
    0 _SRCONNP-SUBJECT ! 0 _SRCONNP-GENERATION ! 0 _SRCONNP-RS !
    0 _SRCONNP-CS ! ;

: STREAMS-RABBIT-CONNECTOR-POLL
  ( fallback-xt fallback-context connector -- )
  ( item subject generation connector-status )
    _SRCONN-BUSY @ IF
        2DROP DROP
        RSUB-ITEM-NONE 0 0 STREAMS-RABBIT-CONNECTOR-S-BUSY EXIT
    THEN
    _SRCONNP-O ! _SRCONNP-FALLBACK-CONTEXT ! _SRCONNP-FALLBACK-XT !
    _SRCONNP-O @ STREAMS-RABBIT-CONNECTOR-VALID? 0= IF
        _SRCONNP-CLEAR
        RSUB-ITEM-NONE 0 0 STREAMS-RABBIT-CONNECTOR-S-INVALID EXIT
    THEN
    _SRCONNP-O @ SRCONN.STATE @
        STREAMS-RABBIT-CONNECTOR-ST-ATTACHED <> IF
        STREAMS-RABBIT-CONNECTOR-S-DISCONNECTED 0 _SRCONNP-O @
            _SRCONN-STATUS! DROP
        _SRCONNP-CLEAR
        RSUB-ITEM-NONE 0 0
            STREAMS-RABBIT-CONNECTOR-S-DISCONNECTED EXIT
    THEN
    -1 _SRCONN-BUSY !
    _SRCONNP-FALLBACK-XT @ _SRCONNP-FALLBACK-CONTEXT @
        _SRCONNP-O @ SRCONN.SUBSCRIPTIONS @
        RABBIT-SUBSCRIPTIONS-POLL
    _SRCONNP-RS ! _SRCONNP-GENERATION !
    _SRCONNP-SUBJECT ! _SRCONNP-ITEM !
    \ A terminal neutral poll detaches its subscription owner so it cannot
    \ retain a dead client.  Keep the still-owned client reachable for the
    \ retryable DETACH/FINI cleanup path instead of leaving a split owner.
    _SRCONNP-O @ SRCONN.SUBSCRIPTIONS @ RSUB.STATE @
        RSUB-ST-DETACHED = IF
        STREAMS-RABBIT-CONNECTOR-ST-CLEANUP
            _SRCONNP-O @ SRCONN.STATE !
    THEN
    0 _SRCONN-BUSY !
    _SRCONNP-O @ SRCONN.POLL-COUNT _SRCONN-COUNT+
    _SRCONNP-ITEM @ _SRCONN-ITEM>ACTIVITY
        _SRCONNP-O @ SRCONN.LAST-ACTIVITY !
    _SRCONNP-SUBJECT @ _SRCONNP-O @ SRCONN.LAST-SUBJECT !
    _SRCONNP-GENERATION @ _SRCONNP-O @ SRCONN.LAST-GENERATION !
    _SRCONNP-RS @ _SRCONN-RSUB>STATUS DUP _SRCONNP-CS !
        _SRCONNP-RS @ _SRCONNP-O @ _SRCONN-STATUS! DROP
    _SRCONNP-ITEM @ _SRCONNP-SUBJECT @ _SRCONNP-GENERATION @
    _SRCONNP-CS @ >R _SRCONNP-CLEAR R> ;

