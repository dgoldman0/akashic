    R@ SRT.BOOT @ IF
        2DROP R> DROP SRT-S-BUSY EXIT
    THEN
    OVER R@ SRT.BOOT-SIZE !
    DUP R@ SRT.BOOT-KIND !
    DROP
    XMEM-ALLOT? IF
        DROP
        0 R@ SRT.BOOT-SIZE !
        _SRT-BOOT-KIND-NONE R@ SRT.BOOT-KIND !
        R> DROP SRT-S-CAPACITY EXIT
    THEN
    DUP R@ SRT.BOOT !
    R@ SRT.BOOT-SIZE @ 0 FILL
    R> DROP SRT-S-OK ;

: _SRT-BOOT-DISCARD  ( owner -- )
    DUP SRT.BOOT @ ?DUP IF
        OVER SRT.BOOT-SIZE @ 2DUP 0 FILL
        XMEM-FREE-BLOCK
    THEN
    DUP 0 SWAP SRT.BOOT !
    DUP 0 SWAP SRT.BOOT-SIZE !
    _SRT-BOOT-KIND-NONE SWAP SRT.BOOT-KIND ! ;

: _SRT-CLOSE-LEGACY  ( owner -- status )
    >R
    0 R@ SRT.CLEANUP-STATUS !
    R@ SRT.OBSERVATION-OPEN @ IF
        R@ _SRT-MIGRATION-OBSERVATION-STORE
            STREAMS-OBSERVATION-STORE-FINI
        DUP IF
            R@ _SRT-FIRST-CLEANUP!
        ELSE
            DROP 0 R@ SRT.OBSERVATION-OPEN !
        THEN
    THEN
    R@ SRT.SOURCE-OPEN @ IF
        R@ _SRT-MIGRATION-SOURCE-STORE
            STREAMS-SOURCE-STORE-FINI
        DUP IF
            R@ _SRT-FIRST-CLEANUP!
        ELSE
            DROP 0 R@ SRT.SOURCE-OPEN !
        THEN
    THEN
    R@ SRT.SOURCE-OPEN @
    R@ SRT.OBSERVATION-OPEN @ OR IF
        R> DROP SRT-S-CLEANUP EXIT
    THEN
    R@ _SRT-BOOT-DISCARD
    R> DROP SRT-S-OK ;

