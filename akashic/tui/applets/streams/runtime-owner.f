        R> DROP SRT-S-OK EXIT
    THEN
    R@ SRT.WORK-OPEN @ IF
        R> DROP SRT-S-OK EXIT
    THEN
    R@ _SRT-RECORD-BUFFER
    STREAMS-REPOSITORY-RECORD-BUFFER-MIN
    R@ _SRT-REPOSITORY
    R@ _SRT-REPOSITORY-WORK
        STREAMS-REPOSITORY-WORK-INIT
