: STREAMS-RUNTIME-OWNER-RELEASE  ( owner -- status )
    DUP 0= IF DROP SRT-S-INVALID EXIT THEN
    DUP STREAMS-RUNTIME-OWNER-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP SRT-S-INVALID EXIT THEN
    DUP _SRT-RELEASE-ENTER
    DUP SRT-S-OK <> IF NIP EXIT THEN DROP
    >R
    0 R@ SRT.CLEANUP-STATUS !

    R@ SRT.BOOT @ IF
        R@ _SRT-CLOSE-LEGACY DUP IF
            DROP
            SRT-S-CLEANUP R@ SRT.STATUS !
            R@ _SRT-RELEASE-RETRY
            R> DROP SRT-S-CLEANUP EXIT
        THEN DROP
    THEN

    R@ SRT.REFRESH-OPEN @
    R@ _SRT-REFRESH
        STREAMS-REPOSITORY-REFRESH-OWNER-VALID? OR IF
        R@ _SRT-REFRESH
            _SRT-REFRESH-RELEASE-CATCH
        DUP R@ SRT.REFRESH-STATUS !
        DUP SRRO-S-OK <> IF
            DUP R@ _SRT-FIRST-CLEANUP!
            R@ _SRT-REFRESH
                STREAMS-REPOSITORY-REFRESH-OWNER-VALID? IF
                DROP
                -1 R@ SRT.REFRESH-OPEN !
                SRT-S-CLEANUP R@ SRT.STATUS !
                R@ _SRT-RELEASE-RETRY
                R> DROP SRT-S-CLEANUP EXIT
            THEN
            DROP 0 R@ SRT.REFRESH-OPEN !
        ELSE
            DROP 0 R@ SRT.REFRESH-OPEN !
        THEN
    THEN

    R@ _SRT-ENSURE-WORK-FOR-CLOSE DUP IF
        R@ _SRT-FIRST-CLEANUP!
        SRT-S-CLEANUP R@ SRT.STATUS !
        R@ _SRT-RELEASE-RETRY
        R> DROP SRT-S-CLEANUP EXIT
    THEN DROP

    R@ SRT.REPOSITORY-OPEN @ IF
        R@ _SRT-REPOSITORY
        R@ _SRT-REPOSITORY-WORK
            STREAMS-REPOSITORY-FINI
        DUP R@ SRT.REPOSITORY-STATUS !
        DUP STREAMS-REPOSITORY-S-OK <> IF
            R@ _SRT-FIRST-CLEANUP!
            SRT-S-CLEANUP R@ SRT.STATUS !
            R@ _SRT-RELEASE-RETRY
            R> DROP SRT-S-CLEANUP EXIT
        THEN
        DROP
        0 R@ SRT.WORK-OPEN !
        0 R@ SRT.REPOSITORY-OPEN !
    THEN

    R@ SRT.CLEANUP-STATUS @ 0<>
    R@ SRT.RUNTIME @ ?DUP IF
        DUP STREAMS-RUNTIME-BLOCK-SIZE 0 FILL
        STREAMS-RUNTIME-BLOCK-SIZE XMEM-FREE-BLOCK
        0 R@ SRT.RUNTIME !
    THEN
    R@ _SRT-LIVE-UNCLAIM
    R@ STREAMS-RUNTIME-OWNER-SIZE 0 FILL
    R> DROP
    IF SRT-S-CLEANUP ELSE SRT-S-OK THEN ;
