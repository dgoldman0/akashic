\ =====================================================================
\ runtime-owner.f - cold repository lifecycle for Streams
\ =====================================================================
\ This is the activation-local L13 persistence composition.  It owns one
\ bounded XMEM working set containing the repository, ordinary page caches,
\ source/query work, and repository-backed configured-refresh owner.
\
\ Cold INIT always asks migration.f to select authority.  A valid repository
\ root wins before legacy evidence is read; an absent repository is imported
\ and atomically flipped by the migration owner.  No failure authorizes a
\ writable legacy fallback.  Accepted repository attempts are recovered as
\ indeterminate before source/query work or external refresh is enabled.
\
\ Legacy evidence descriptors and acquisition-recovery buffers are allocated
\ only as temporary boot scratch and are wiped/freed before INIT returns.
\ RELEASE orders refresh teardown before repository finalization and never
\ frees a block still referenced by a lower owner.
\
\ This module owns streaming persistence and acquisition composition only.
\ It owns no draft, Library document, public-Bluesky, UI, output, scheduling,
\ search, or inter-applet policy.
\ =====================================================================

\ Keep the module identity within KDOS's 23-byte bound.
PROVIDED akashic-streams-runtime

