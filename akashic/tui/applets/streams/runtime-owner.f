: _SRT-OPEN  ( owner -- status )
    >R
    R@ _SRT-CACHE-MEMORY-0 R@ _SRT-CACHE-0 _SRT-CACHE-INIT
    DUP R@ SRT.REPOSITORY-STATUS !
    DUP IF DROP R> DROP SRT-S-REPOSITORY EXIT THEN DROP
    R@ _SRT-CACHE-MEMORY-1 R@ _SRT-CACHE-1 _SRT-CACHE-INIT
    DUP R@ SRT.REPOSITORY-STATUS !
    DUP IF DROP R> DROP SRT-S-REPOSITORY EXIT THEN DROP

    R@ SRT.VFS @
    R@ _SRT-CACHE-0
    R@ _SRT-CACHE-1
    R@ _SRT-GUARD
    0 0
    R@ _SRT-REPOSITORY
        STREAMS-REPOSITORY-INIT
    DUP R@ SRT.REPOSITORY-STATUS !
    DUP STREAMS-REPOSITORY-S-OK <> IF
        DROP R> DROP SRT-S-REPOSITORY EXIT
    THEN
    DROP -1 R@ SRT.REPOSITORY-OPEN !

    R@ _SRT-RECORD-BUFFER
    STREAMS-REPOSITORY-RECORD-BUFFER-MIN
    R@ _SRT-REPOSITORY
    R@ _SRT-REPOSITORY-WORK
        STREAMS-REPOSITORY-WORK-INIT
    DUP R@ SRT.REPOSITORY-STATUS !
    DUP STREAMS-REPOSITORY-S-OK <> IF
        DROP R> DROP SRT-S-REPOSITORY EXIT
    THEN
    DROP -1 R@ SRT.WORK-OPEN !

    R@ _SRT-MIGRATE DUP IF R> DROP EXIT THEN DROP
    R@ _SRT-REPOSITORY STREAMS-REPOSITORY-LOADED? 0= IF
        R> DROP SRT-S-REPOSITORY EXIT
    THEN
    R@ _SRT-REPOSITORY STREAMS-REPOSITORY-PROVISIONED? 0= IF
        R> DROP SRT-S-REPOSITORY EXIT
    THEN
    R@ _SRT-RECOVER DUP IF R> DROP EXIT THEN DROP
    R@ _SRT-SEMANTIC-INIT DUP IF R> DROP EXIT THEN DROP
    R@ _SRT-REFRESH-INIT DUP IF R> DROP EXIT THEN DROP
    R> DROP SRT-S-OK ;

