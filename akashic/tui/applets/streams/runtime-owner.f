    DUP SRT.REPOSITORY-OPEN @ IF
        DUP _SRT-REPOSITORY STREAMS-REPOSITORY-VALID? 0= IF
            DROP 0 EXIT
        THEN
    THEN
    DUP SRT.WORK-OPEN @ IF
        DUP SRT.REPOSITORY-OPEN @ 0= IF DROP 0 EXIT THEN
        DUP _SRT-REPOSITORY-WORK
            STREAMS-REPOSITORY-WORK-VALID? 0= IF
            DROP 0 EXIT
        THEN
        DUP _SRT-REPOSITORY OVER _SRT-REPOSITORY-WORK
            STREAMS-REPOSITORY-WORK-BOUND? 0= IF
            DROP 0 EXIT
        THEN
    THEN
    DUP SRT.SOURCE-OPEN @ IF
        DUP SRT.BOOT-KIND @
            _SRT-BOOT-KIND-MIGRATION <> IF DROP 0 EXIT THEN
        DUP _SRT-MIGRATION-SOURCE-STORE
            STREAMS-SOURCE-STORE-VALID? 0= IF DROP 0 EXIT THEN
