: _SRT-MIGRATE  ( owner -- status )
    >R
    SRT-S-MIGRATION R@ SRT.TEMP-STATUS !
    \ A published repository is authoritative without any dependency on
    \ legacy descriptors or the much larger import scratch allocation.
    R@ _SRT-REPOSITORY
    R@ _SRT-REPOSITORY-WORK
        STREAMS-REPOSITORY-LOAD
    DUP R@ SRT.REPOSITORY-STATUS !
    DUP R@ SRT.MIGRATION-STATUS !
    DUP STREAMS-REPOSITORY-S-OK = IF
        DROP
        R@ _SRT-ROOT-AUTHORITY? 0= IF
            STREAMS-MIGRATION-S-CONFLICT
                R@ SRT.MIGRATION-STATUS !
            R> DROP SRT-S-MIGRATION EXIT
        THEN
        STREAMS-MIGRATION-S-ALREADY
            R@ SRT.MIGRATION-STATUS !
        0 R@ SRT.MIGRATED-RECOVERED !
        R> DROP SRT-S-OK EXIT
    THEN
    DUP STREAMS-REPOSITORY-S-ABSENT <> IF
        DROP R> DROP SRT-S-MIGRATION EXIT
    THEN
    DROP

    STREAMS-RUNTIME-MIGRATION-SCRATCH-SIZE
    _SRT-BOOT-KIND-MIGRATION
        R@ _SRT-BOOT-ALLOC
    DUP IF
        SRT-S-CAPACITY R@ SRT.TEMP-STATUS !
        STREAMS-MIGRATION-S-CAPACITY
            R@ SRT.MIGRATION-STATUS !
        R> DROP EXIT
    THEN DROP

    R@ SRT.VFS @ R@ _SRT-MIGRATION-SOURCE-STORE
        STREAMS-SOURCE-STORE-INIT
    DUP R@ SRT.LEGACY-STATUS !
    DUP SSSTORE-S-OK <> IF
        DUP _SRT-LEGACY>MIGRATION
            R@ SRT.MIGRATION-STATUS !
        DROP
        R@ _SRT-CLOSE-LEGACY DUP IF
            R> DROP EXIT
        THEN DROP
        R@ SRT.TEMP-STATUS @ R> DROP EXIT
    THEN
    DROP -1 R@ SRT.SOURCE-OPEN !

    R@ SRT.VFS @ R@ _SRT-MIGRATION-OBSERVATION-STORE
        STREAMS-OBSERVATION-STORE-INIT
    DUP R@ SRT.LEGACY-STATUS !
    DUP OSTORE-S-OK <> IF
        DUP _SRT-LEGACY>MIGRATION
            R@ SRT.MIGRATION-STATUS !
        DROP
        R@ _SRT-CLOSE-LEGACY DUP IF
            R> DROP EXIT
        THEN DROP
        R@ SRT.TEMP-STATUS @ R> DROP EXIT
    THEN
    DROP -1 R@ SRT.OBSERVATION-OPEN !

    R@ _SRT-MIGRATION-WORK STREAMS-MIGRATION-WORK-INIT
    DUP R@ SRT.MIGRATION-STATUS !
    DUP STREAMS-MIGRATION-S-OK <> IF
        DROP
        R@ _SRT-CLOSE-LEGACY DUP IF
            R> DROP EXIT
        THEN DROP
        R@ SRT.TEMP-STATUS @ R> DROP EXIT
    THEN DROP

    R@ SRT.AUTHORITY-ID
    R@ _SRT-MIGRATION-SOURCE-STORE
    R@ _SRT-MIGRATION-OBSERVATION-STORE
    R@ _SRT-REPOSITORY
    R@ _SRT-REPOSITORY-WORK
    R@ _SRT-MIGRATION-WORK
        STREAMS-MIGRATION-RUN
    DUP R@ SRT.MIGRATION-STATUS !
    DUP STREAMS-MIGRATION-S-OK =
    OVER STREAMS-MIGRATION-S-ALREADY = OR IF
        DROP
        R@ _SRT-ROOT-AUTHORITY? IF
            STREAMS-REPOSITORY-S-OK
                R@ SRT.REPOSITORY-STATUS !
            R@ _SRT-MIGRATION-WORK
                STREAMS-MIGRATION-RECOVERED-ATTEMPT-COUNT@
            DUP 0<
            OVER STREAMS-AUTHORITY-ACTIVE-MAX > OR IF
                DROP
                STREAMS-MIGRATION-S-RECOVERY
                    R@ SRT.MIGRATION-STATUS !
            ELSE
                R@ SRT.MIGRATED-RECOVERED !
                SRT-S-OK R@ SRT.TEMP-STATUS !
            THEN
        ELSE
            STREAMS-MIGRATION-S-CONFLICT
                R@ SRT.MIGRATION-STATUS !
        THEN
    ELSE
        DROP
    THEN

    R@ _SRT-CLOSE-LEGACY DUP IF
        R> DROP EXIT
    THEN DROP
    R@ SRT.TEMP-STATUS @ R> DROP ;

: _SRT-RECOVER  ( owner -- status )
    >R
    SRT-S-RECOVERY R@ SRT.TEMP-STATUS !
    STREAMS-RUNTIME-RECOVERY-SCRATCH-SIZE
    _SRT-BOOT-KIND-RECOVERY
        R@ _SRT-BOOT-ALLOC
    DUP IF
        SRT-S-CAPACITY R@ SRT.TEMP-STATUS !
        STREAMS-ACQUISITION-S-CAPACITY
            R@ SRT.RECOVERY-STATUS !
        R> DROP EXIT
    THEN DROP
    R@ _SRT-RECOVERY-WORK STREAMS-ACQUISITION-WORK-INIT
    DUP R@ SRT.RECOVERY-STATUS !
    DUP STREAMS-ACQUISITION-S-OK <> IF
        DROP R@ _SRT-BOOT-DISCARD
        R@ SRT.TEMP-STATUS @ R> DROP EXIT
    THEN DROP

    R@ _SRT-RECOVERY-OUTPUTS
    STREAMS-AUTHORITY-ACTIVE-MAX
    R@ _SRT-REPOSITORY
    R@ _SRT-REPOSITORY-WORK
    R@ _SRT-RECOVERY-WORK
        STREAMS-ACQUISITION-RECOVER-ALL
    DUP R@ SRT.RECOVERY-STATUS !
    DUP IF
        2DROP
    ELSE
        DROP
        DUP R@ SRT.NATIVE-RECOVERED !
        DROP
        R@ _SRT-REPOSITORY-WORK
            STREAMS-REPOSITORY-AUTHORITY-ROOT@
        DUP 0= IF
            DROP
            STREAMS-ACQUISITION-S-CORRUPT
                R@ SRT.RECOVERY-STATUS !
        ELSE
            DUP STREAMS-AUTHORITY-ROOT-HEADER-VALID? 0= IF
                DROP
                STREAMS-ACQUISITION-S-CORRUPT
                    R@ SRT.RECOVERY-STATUS !
            ELSE
                SAR.ACTIVE-COUNT @ 0= IF
                    SRT-S-OK R@ SRT.TEMP-STATUS !
                ELSE
                    STREAMS-ACQUISITION-S-CORRUPT
                        R@ SRT.RECOVERY-STATUS !
                THEN
            THEN
        THEN
    THEN
    R@ _SRT-BOOT-DISCARD
    R@ SRT.TEMP-STATUS @ R> DROP ;

