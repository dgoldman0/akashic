: _SRT-BOOT-VALID?  ( owner -- flag )
    >R
    R@ SRT.BOOT @
    R@ SRT.BOOT-SIZE @
    R@ SRT.BOOT-KIND @
    DUP _SRT-BOOT-KIND-NONE = IF
        DROP OR 0= R> DROP EXIT
    THEN
    DUP _SRT-BOOT-KIND-MIGRATION = IF
        DROP
        DUP STREAMS-RUNTIME-MIGRATION-SCRATCH-SIZE <> IF
            2DROP R> DROP 0 EXIT
        THEN
    ELSE
        _SRT-BOOT-KIND-RECOVERY <> IF
            2DROP R> DROP 0 EXIT
        THEN
        DUP STREAMS-RUNTIME-RECOVERY-SCRATCH-SIZE <> IF
            2DROP R> DROP 0 EXIT
        THEN
    THEN
    OVER 0= IF 2DROP R> DROP 0 EXIT THEN
    2DUP MSPAN-NONWRAPPING? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    2DUP R@ STREAMS-RUNTIME-OWNER-SIZE
        MSPAN-OVERLAP? IF
        2DROP R> DROP 0 EXIT
    THEN
    2DUP R@ SRT.RUNTIME @ STREAMS-RUNTIME-BLOCK-SIZE
        MSPAN-OVERLAP? IF
        2DROP R> DROP 0 EXIT
    THEN
    2DROP R> DROP -1 ;

: _SRT-BASE-VALID?  ( owner -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-RUNTIME-OWNER-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP SRT.MAGIC @ _SRT-MAGIC <> IF DROP 0 EXIT THEN
    DUP SRT.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP SRT.PHASE @ _SRT-PHASE? 0= IF DROP 0 EXIT THEN
    DUP SRT.STATUS @ _SRT-STATUS? 0= IF DROP 0 EXIT THEN
    DUP SRT.SOURCE-OPEN @ _SRT-BOOL? 0= IF DROP 0 EXIT THEN
    DUP SRT.OBSERVATION-OPEN @ _SRT-BOOL? 0= IF DROP 0 EXIT THEN
    DUP SRT.REPOSITORY-OPEN @ _SRT-BOOL? 0= IF DROP 0 EXIT THEN
    DUP SRT.WORK-OPEN @ _SRT-BOOL? 0= IF DROP 0 EXIT THEN
    DUP SRT.REFRESH-OPEN @ _SRT-BOOL? 0= IF DROP 0 EXIT THEN
    DUP SRT.RUNTIME @ DUP 0= IF
        DROP DROP 0 EXIT
    THEN
    STREAMS-RUNTIME-BLOCK-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP 0 EXIT
    THEN
    DUP SRT.RUNTIME @ STREAMS-RUNTIME-BLOCK-SIZE
    2 PICK STREAMS-RUNTIME-OWNER-SIZE
        MSPAN-OVERLAP? IF DROP 0 EXIT THEN
    DUP SRT.VFS @ DUP 0= IF
        DROP DROP 0 EXIT
    THEN
    VFS-DESC-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP 0 EXIT
    THEN
    DUP SRT.XIO-SERVICE @ 0=
    OVER SRT.FACTORY-XT @ 0= <> IF
        DROP 0 EXIT
    THEN
    DUP SRT.XIO-SERVICE @ ?DUP IF
        XIO-SERVICE-SIZE MSPAN-NONWRAPPING? 0= IF
            DROP 0 EXIT
        THEN
    THEN
    DUP _SRT-BOOT-VALID? 0= IF DROP 0 EXIT THEN
    DROP -1 ;

: _SRT-LOWER-VALID?  ( owner -- flag )
