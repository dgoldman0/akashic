    DUP STREAMS-REPOSITORY-S-OK = IF
        DROP -1 R@ SRT.WORK-OPEN !
        R> DROP SRT-S-OK EXIT
    THEN
    DROP R> DROP SRT-S-CLEANUP ;

: _SRT-RELEASE-ENTER-LOCKED  ( owner -- status )
    _SRT-LIVE-OWNER @ OVER <> IF
        DROP SRT-S-INVALID EXIT
    THEN
    DUP SRT.MAGIC @ _SRT-MAGIC <> IF
        DROP SRT-S-INVALID EXIT
    THEN
    DUP SRT.SELF @ OVER <> IF
        DROP SRT-S-INVALID EXIT
    THEN
    DUP SRT.PHASE @ DUP SRT-PHASE-READY =
    SWAP SRT-PHASE-BLOCKED = OR 0= IF
        DROP SRT-S-BUSY EXIT
    THEN
    DUP _SRT-LOWER-VALID? 0= IF
        DROP SRT-S-INVALID EXIT
    THEN
    SRT-PHASE-CLEANUP SWAP SRT.PHASE !
    SRT-S-OK ;

