    >R
    DUP R@ ATTPC.ARG-OP @ XIOO.ERROR !
    STREAMS-CONNECTOR-COMPLETION-INDETERMINATE
    STREAMS-EFFECT-UNCERTAIN
    AT-TEXT-POST-CONNECTOR-S-CREATE 3 ROLL
    _ATTPC-STATE-TERMINAL R@ _ATTPC-REPORT
    R> DROP ;

: _ATTPC-START  ( event operation owner result -- )
    OVER _ATTPC-OWNER-SHAPE? 0= IF _ATTPC-INVALID-CALL EXIT THEN
    3 PICK 2 PICK _ATTPC-EVENT-PRESAVE-STATUS ?DUP IF
        >R 2DROP 2DROP R> DROP EXIT
    THEN
    1 PICK 3 PICK _ATTPC-OP-PRESAVE-STATUS ?DUP IF
        >R 2DROP 2DROP R> DROP EXIT
    THEN
    2DUP _ATTPC-RESULT-PRESAVE-STATUS ?DUP IF
        >R 2DROP 2DROP R> DROP EXIT
    THEN
    _ATTPC-SAVE-CALL >R
    R@ _ATTPC-RESULT-GEOMETRY ?DUP IF
        DUP R@ ATTPC.LAST-STATUS ! DROP
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN
    R@ ATTPC.STATE @ _ATTPC-STATE-IDLE <> IF
        AT-TEXT-POST-CONNECTOR-S-BUSY
        AT-TEXT-POST-CONNECTOR-XERR-STATE
        R@ _ATTPC-UNCLAIMED-FAIL
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN
    R@ _ATTPC-CALL-GEOMETRY ?DUP IF
        AT-TEXT-POST-CONNECTOR-XERR-INVALID R@ _ATTPC-UNCLAIMED-FAIL
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN

    R@ ATTPC.ARG-OP @ XIO-OP-INIT
    R@ ATTPC.ARG-OP @ R@ ATTPC.ACTIVE-OP !
    _ATTPC-STATE-ACTIVE R@ ATTPC.STATE !
    R@ _ATTPC-SCRATCH-WIPE
    R@ ATTPC.TEXT BSKY-TEXT-RECORD-TEXT-MAX
    R@ ATTPC.ARG-EVENT @ STREAMS-EVENT-PAYLOAD-COPY
    DUP STREAMS-FLOW-S-OK <> IF
        >R DROP R> _ATTPC-FLOW>STATUS
        AT-TEXT-POST-CONNECTOR-XERR-RECORD R@ _ATTPC-LOCAL-FAIL
        R@ _ATTPC-SCRATCH-WIPE
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN
    DROP R@ ATTPC.TEXT-U !

    R@ _ATTPC-NOW ?DUP IF
        AT-TEXT-POST-CONNECTOR-XERR-CLOCK R@ _ATTPC-LOCAL-FAIL
        R@ _ATTPC-SCRATCH-WIPE
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN
    R@ _ATTPC-ENCODE-RECORD ?DUP IF
        AT-TEXT-POST-CONNECTOR-XERR-RECORD R@ _ATTPC-LOCAL-FAIL
        R@ _ATTPC-SCRATCH-WIPE
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN
    R@ _ATTPC-NEXT-TID ?DUP IF
        AT-TEXT-POST-CONNECTOR-XERR-TID R@ _ATTPC-LOCAL-FAIL
        R@ _ATTPC-SCRATCH-WIPE
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN
    R@ _ATTPC-PREPARE ?DUP IF
        AT-TEXT-POST-CONNECTOR-XERR-CREATE R@ _ATTPC-LOCAL-FAIL
        R@ _ATTPC-SCRATCH-WIPE
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN
    R@ _ATTPC-SCRATCH-WIPE

    R@ ['] _ATTPC-CREATE-START-INNER CATCH
    DUP IF
        NIP R@ _ATTPC-THROW-FAIL
    ELSE
        DROP DROP R@ _ATTPC-MAP-CREATE
    THEN
    R@ _ATTPC-CLEAR-CALL
    R> DROP ;

: _ATTPC-ACTIVE-CALL?  ( owner -- flag )
    DUP ATTPC.STATE @ _ATTPC-STATE-ACTIVE =
    SWAP DUP ATTPC.ARG-OP @ SWAP ATTPC.ACTIVE-OP @ = AND ;

