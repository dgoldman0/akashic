    DUP ATTPC.CREATE @ >R
    ATTPC.CREATE @ AT-CREATE-RECORD-RESULT@
    DUP AT-CREATE-RECORD-S-OK <> IF
        NIP _ATTPC-CREATE>STATUS 0 SWAP DUP R> DROP EXIT
    THEN
    DROP
    DUP AT-CREATE-RECORD-RESULT-OUTCOME@
    DUP AT-CREATE-RECORD-S-OK <> IF
        NIP NIP _ATTPC-CREATE>STATUS 0 SWAP DUP R> DROP EXIT
    THEN
    DROP
    NIP
    R@ AT-CREATE-RECORD-LAST-STATUS@ _ATTPC-CREATE>STATUS
    R> DROP
    AT-TEXT-POST-CONNECTOR-S-OK ;

: _ATTPC-OP-ERROR  ( owner -- error )
    ATTPC.ACTIVE-OP @ DUP 0= IF
        DROP AT-TEXT-POST-CONNECTOR-XERR-CREATE EXIT
    THEN
    XIOO.ERROR @ ?DUP IF EXIT THEN
    AT-TEXT-POST-CONNECTOR-XERR-CREATE ;

: _ATTPC-MAP-CREATE  ( owner -- )
    >R
    R@ _ATTPC-CREATE-SNAPSHOT
    DUP AT-TEXT-POST-CONNECTOR-S-OK <> IF
        NIP NIP
        STREAMS-CONNECTOR-COMPLETION-INDETERMINATE
        STREAMS-EFFECT-UNCERTAIN ROT
        AT-TEXT-POST-CONNECTOR-XERR-CREATE
        _ATTPC-STATE-TERMINAL R@ _ATTPC-REPORT
        R> DROP EXIT
    THEN
    DROP SWAP
    CASE
        AT-CREATE-RECORD-OUTCOME-PENDING OF
            STREAMS-CONNECTOR-COMPLETION-PENDING
            STREAMS-EFFECT-UNCERTAIN ROT
            0 _ATTPC-STATE-ACTIVE R@ _ATTPC-REPORT
        ENDOF
        AT-CREATE-RECORD-OUTCOME-CREATED OF
            STREAMS-CONNECTOR-COMPLETION-DELIVERED
            STREAMS-EFFECT-APPLIED ROT
            0 _ATTPC-STATE-TERMINAL R@ _ATTPC-REPORT
        ENDOF
        AT-CREATE-RECORD-OUTCOME-NO-EFFECT OF
            R@ ATTPC.TMP-CANCEL @ IF
                STREAMS-CONNECTOR-COMPLETION-CANCELLED
            ELSE
                STREAMS-CONNECTOR-COMPLETION-FAILED
            THEN
            STREAMS-EFFECT-NOT-APPLIED ROT
            R@ _ATTPC-OP-ERROR
            _ATTPC-STATE-TERMINAL R@ _ATTPC-REPORT
        ENDOF
        AT-CREATE-RECORD-OUTCOME-UNCERTAIN OF
            STREAMS-CONNECTOR-COMPLETION-INDETERMINATE
            STREAMS-EFFECT-UNCERTAIN ROT
            R@ _ATTPC-OP-ERROR
            _ATTPC-STATE-TERMINAL R@ _ATTPC-REPORT
        ENDOF
        DROP
        STREAMS-CONNECTOR-COMPLETION-INDETERMINATE
        STREAMS-EFFECT-UNCERTAIN
        AT-TEXT-POST-CONNECTOR-S-CREATE
        AT-TEXT-POST-CONNECTOR-XERR-CREATE
        _ATTPC-STATE-TERMINAL R@ _ATTPC-REPORT
    ENDCASE
    R> DROP ;

