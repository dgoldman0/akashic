: _ATTPC-LIFECYCLE-SHAPE?  ( owner -- flag )
    DUP ATTPC.STATE @
    CASE
        _ATTPC-STATE-IDLE OF
            DUP ATTPC.ACTIVE-OP @ 0=
            SWAP ATTPC.CLEANUP-ERROR @ 0= AND
        ENDOF
        _ATTPC-STATE-ACTIVE OF
            DUP ATTPC.ACTIVE-OP @ 0<>
            SWAP ATTPC.CLEANUP-ERROR @ 0= AND
        ENDOF
        _ATTPC-STATE-TERMINAL OF
            DUP ATTPC.ACTIVE-OP @ 0<>
            SWAP ATTPC.CLEANUP-ERROR @ 0= AND
        ENDOF
        _ATTPC-STATE-FAILED OF
            DUP ATTPC.ACTIVE-OP @ 0=
            SWAP ATTPC.CLEANUP-ERROR @ 0<> AND
        ENDOF
        DROP 0 SWAP
    ENDCASE ;

: _ATTPC-OWNER-SHAPE?  ( owner -- flag )
    DUP AT-TEXT-POST-CONNECTOR-SIZE _ATTPC-FIXED-STATUS
    AT-TEXT-POST-CONNECTOR-S-OK <> IF DROP 0 EXIT THEN
    DUP ATTPC.MAGIC @ _ATTPC-MAGIC-VALUE <> IF DROP 0 EXIT THEN
    DUP ATTPC.STATE @ _ATTPC-STATE? 0= IF DROP 0 EXIT THEN
    DUP ATTPC.LAST-STATUS @
        AT-TEXT-POST-CONNECTOR-STATUS-VALID? 0= IF DROP 0 EXIT THEN
    DUP ATTPC.CREATE @ AT-CREATE-RECORD-VALID? 0= IF DROP 0 EXIT THEN
    DUP ATTPC.TARGET AT-CREATE-RECORD-TARGET? 0= IF DROP 0 EXIT THEN
    DUP ATTPC.TID-CLOCK @ TID-CLOCK-VALID? 0= IF DROP 0 EXIT THEN
    DUP ATTPC.CLOCK-XT @ 0= IF DROP 0 EXIT THEN
    DUP ATTPC.LAST-EPOCH-MS @ -1 < IF DROP 0 EXIT THEN
    DUP ATTPC.TEXT-U @ DUP 0<
        SWAP BSKY-TEXT-RECORD-TEXT-MAX > OR IF DROP 0 EXIT THEN
    DUP ATTPC.RECORD-U @ DUP 0<
        SWAP BSKY-TEXT-RECORD-BODY-MAX > OR IF DROP 0 EXIT THEN
    DUP ATTPC.CONNECTOR STREAMS-CONNECTOR-VALID? 0= IF DROP 0 EXIT THEN
    DUP ATTPC.CONNECTOR SCON.CONTEXT @ OVER <> IF DROP 0 EXIT THEN
    DUP ATTPC.CONNECTOR SCON.DIRECTION @
        STREAMS-CONNECTOR-DIRECTION-OUTPUT <> IF DROP 0 EXIT THEN
    DUP ATTPC.CONNECTOR SCON.PROTOCOL @
        STREAMS-PROTOCOL-ATPROTO <> IF DROP 0 EXIT THEN
    DUP ATTPC.CONNECTOR SCON.OP-SIZE @ XIO-OP-SIZE <> IF DROP 0 EXIT THEN
    DUP _ATTPC-LIFECYCLE-SHAPE? 0= IF DROP 0 EXIT THEN
    DUP AT-TEXT-POST-CONNECTOR-SIZE
        2 PICK ATTPC.CREATE @ AT-CREATE-RECORD-EXTERNAL-SPAN-STATUS
        AT-CREATE-RECORD-S-OK <> IF DROP 0 EXIT THEN
    DUP ATTPC.TARGET HTARGET-SIZE
        2 PICK ATTPC.CREATE @ AT-CREATE-RECORD-EXTERNAL-SPAN-STATUS
        AT-CREATE-RECORD-S-OK <> IF DROP 0 EXIT THEN
    DUP ATTPC.TID-CLOCK @ TID-CLOCK-SIZE
        2 PICK ATTPC.CREATE @ AT-CREATE-RECORD-EXTERNAL-SPAN-STATUS
        AT-CREATE-RECORD-S-OK <> IF DROP 0 EXIT THEN
    DUP AT-TEXT-POST-CONNECTOR-SIZE
        2 PICK ATTPC.TID-CLOCK @ TID-CLOCK-SIZE MSPAN-OVERLAP? IF
        DROP 0 EXIT
    THEN
    DUP ATTPC.TARGET HTARGET-SIZE
        2 PICK ATTPC.TID-CLOCK @ TID-CLOCK-SIZE MSPAN-OVERLAP? IF
        DROP 0 EXIT
    THEN
    DROP -1 ;

