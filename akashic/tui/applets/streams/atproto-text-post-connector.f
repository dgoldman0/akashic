    OVER _ATTPC-OWNER-SHAPE? 0= IF _ATTPC-INVALID-CALL EXIT THEN
    3 PICK 2 PICK _ATTPC-EVENT-PRESAVE-STATUS ?DUP IF
        >R 2DROP 2DROP R> DROP EXIT
    THEN
    1 PICK 3 PICK _ATTPC-OP-PRESAVE-STATUS ?DUP IF
        >R 2DROP 2DROP R> DROP EXIT
    THEN
    2DUP _ATTPC-RESULT-PRESAVE-STATUS ?DUP IF
        >R 2DROP 2DROP R> DROP EXIT
    THEN
    _ATTPC-SAVE-CALL >R
    R@ _ATTPC-RESULT-GEOMETRY ?DUP IF
        DUP R@ ATTPC.LAST-STATUS ! DROP
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN
    R@ _ATTPC-CALL-GEOMETRY ?DUP IF
        AT-TEXT-POST-CONNECTOR-XERR-INVALID R@ _ATTPC-UNCLAIMED-FAIL
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN
    R@ _ATTPC-ACTIVE-CALL? 0= IF
        AT-TEXT-POST-CONNECTOR-S-STATE
        AT-TEXT-POST-CONNECTOR-XERR-STATE
        R@ _ATTPC-UNCLAIMED-FAIL
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN
    R@ ['] _ATTPC-CREATE-POLL-INNER CATCH
    DUP IF
        NIP R@ _ATTPC-THROW-FAIL
    ELSE
        DROP DROP R@ _ATTPC-MAP-CREATE
    THEN
    R@ _ATTPC-CLEAR-CALL
    R> DROP ;

: _ATTPC-CANCEL  ( event operation owner result -- )
    OVER _ATTPC-OWNER-SHAPE? 0= IF _ATTPC-INVALID-CALL EXIT THEN
    3 PICK 2 PICK _ATTPC-EVENT-PRESAVE-STATUS ?DUP IF
        >R 2DROP 2DROP R> DROP EXIT
    THEN
    1 PICK 3 PICK _ATTPC-OP-PRESAVE-STATUS ?DUP IF
        >R 2DROP 2DROP R> DROP EXIT
    THEN
    2DUP _ATTPC-RESULT-PRESAVE-STATUS ?DUP IF
        >R 2DROP 2DROP R> DROP EXIT
    THEN
    _ATTPC-SAVE-CALL >R
    R@ _ATTPC-RESULT-GEOMETRY ?DUP IF
        DUP R@ ATTPC.LAST-STATUS ! DROP
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN
    R@ _ATTPC-CALL-GEOMETRY ?DUP IF
        AT-TEXT-POST-CONNECTOR-XERR-INVALID R@ _ATTPC-UNCLAIMED-FAIL
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN
    R@ _ATTPC-ACTIVE-CALL? 0= IF
        AT-TEXT-POST-CONNECTOR-S-STATE R@ ATTPC.LAST-STATUS !
        STREAMS-CONNECTOR-COMPLETION-INDETERMINATE
        STREAMS-EFFECT-UNCERTAIN
        AT-TEXT-POST-CONNECTOR-S-STATE
        AT-TEXT-POST-CONNECTOR-XERR-STATE
        R@ _ATTPC-RESULT!
        R@ _ATTPC-CLEAR-CALL R> DROP EXIT
    THEN
    -1 R@ ATTPC.TMP-CANCEL !
    R@ ['] _ATTPC-CREATE-CANCEL-INNER CATCH
    DUP IF
        NIP DUP R@ ATTPC.ARG-OP @ XIOO.ERROR ! DROP
    ELSE
        DROP
    THEN
    R@ _ATTPC-MAP-CREATE
    R@ _ATTPC-CLEAR-CALL
    R> DROP ;

: _ATTPC-FIRST-CLEANUP!  ( error owner -- )
    DUP ATTPC.CLEANUP-ERROR @ IF 2DROP EXIT THEN
    ATTPC.CLEANUP-ERROR ! ;

: _ATTPC-CLEANUP  ( event operation owner -- error )
    DUP _ATTPC-OWNER-SHAPE? 0= IF
        DROP 2DROP AT-TEXT-POST-CONNECTOR-XERR-INVALID EXIT
    THEN
    >R NIP
    DUP R@ ATTPC.ACTIVE-OP @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP R@ ATTPC.ARG-OP !
    R@ ATTPC.STATE @ _ATTPC-STATE-ACTIVE = IF
        R@ ['] _ATTPC-CREATE-CANCEL-INNER CATCH
        DUP IF
            NIP DUP R@ _ATTPC-FIRST-CLEANUP! DROP
        ELSE
            DROP
        THEN
    THEN
    R@ ['] _ATTPC-CREATE-WIPE-INNER CATCH
    DUP IF
        NIP DUP R@ _ATTPC-FIRST-CLEANUP! DROP
    ELSE
        DROP
    THEN
    DROP
    R@ _ATTPC-SCRATCH-WIPE
    0 R@ ATTPC.ARG-OP !
    0 R@ ATTPC.ACTIVE-OP !
    R@ ATTPC.CLEANUP-ERROR @ ?DUP IF
        AT-TEXT-POST-CONNECTOR-S-CLEANUP R@ ATTPC.LAST-STATUS !
        _ATTPC-STATE-FAILED R@ ATTPC.STATE !
        R> DROP EXIT
    THEN
    _ATTPC-STATE-IDLE R@ ATTPC.STATE !
    R> DROP 0 ;

: _ATTPC-INIT-GEOMETRY
  \ ( id endpoint revision clock-context clock-xt tid-clock target
  \   create-owner owner -- status )
    DUP AT-TEXT-POST-CONNECTOR-SIZE _ATTPC-FIXED-STATUS
    ?DUP IF _ATTPC-RETURN9 EXIT THEN
    8 PICK RID-SIZE _ATTPC-REQUIRED-SPAN-STATUS
    ?DUP IF _ATTPC-RETURN9 EXIT THEN
    7 PICK RID-SIZE _ATTPC-REQUIRED-SPAN-STATUS
    ?DUP IF _ATTPC-RETURN9 EXIT THEN
    8 PICK RID-PRESENT? 0= IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-INVALID EXIT
    THEN
    7 PICK RID-PRESENT? 0= IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-INVALID EXIT
    THEN
    6 PICK 0> 0= IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-INVALID EXIT
    THEN
    4 PICK 0= IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-INVALID EXIT
    THEN
    2 PICK HTARGET-SIZE _ATTPC-FIXED-STATUS
    ?DUP IF _ATTPC-RETURN9 EXIT THEN
    3 PICK TID-CLOCK-VALID? 0= IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-TID EXIT
    THEN
    2 PICK AT-CREATE-RECORD-TARGET? 0= IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-TARGET EXIT
    THEN
    1 PICK AT-CREATE-RECORD-VALID? 0= IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-INVALID EXIT
    THEN
    1 PICK AT-CREATE-RECORD-STATE@
    DUP AT-CREATE-RECORD-S-OK <> IF
        2DROP _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-INVALID EXIT
    THEN
    DROP AT-CREATE-RECORD-STATE-IDLE <> IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-STATE EXIT
    THEN
    1 PICK AT-CREATE-RECORD-CLEANUP-ERROR@ IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-CLEANUP EXIT
    THEN

    DUP AT-TEXT-POST-CONNECTOR-SIZE 3 PICK
        AT-CREATE-RECORD-EXTERNAL-SPAN-STATUS _ATTPC-CREATE>STATUS
    ?DUP IF _ATTPC-RETURN9 EXIT THEN
    2 PICK HTARGET-SIZE 3 PICK
        AT-CREATE-RECORD-EXTERNAL-SPAN-STATUS _ATTPC-CREATE>STATUS
    ?DUP IF _ATTPC-RETURN9 EXIT THEN
    3 PICK TID-CLOCK-SIZE 3 PICK
        AT-CREATE-RECORD-EXTERNAL-SPAN-STATUS _ATTPC-CREATE>STATUS
    ?DUP IF _ATTPC-RETURN9 EXIT THEN

    DUP AT-TEXT-POST-CONNECTOR-SIZE 4 PICK HTARGET-SIZE
        MSPAN-OVERLAP? IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-ALIAS EXIT
    THEN
    DUP AT-TEXT-POST-CONNECTOR-SIZE 5 PICK TID-CLOCK-SIZE
        MSPAN-OVERLAP? IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-ALIAS EXIT
    THEN
    2 PICK HTARGET-SIZE 5 PICK TID-CLOCK-SIZE MSPAN-OVERLAP? IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-ALIAS EXIT
    THEN
    8 PICK RID-SIZE 2 PICK AT-TEXT-POST-CONNECTOR-SIZE
        MSPAN-OVERLAP? IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-ALIAS EXIT
    THEN
    7 PICK RID-SIZE 2 PICK AT-TEXT-POST-CONNECTOR-SIZE
        MSPAN-OVERLAP? IF
        _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-ALIAS EXIT
    THEN
    _ATTPC-DROP9 AT-TEXT-POST-CONNECTOR-S-OK ;

: AT-TEXT-POST-CONNECTOR-VALID?  ( owner -- flag )
    DUP _ATTPC-OWNER-SHAPE? 0= IF DROP 0 EXIT THEN
    DUP ATTPC.CONNECTOR SCON.START-XT @ ['] _ATTPC-START =
    OVER ATTPC.CONNECTOR SCON.POLL-XT @ ['] _ATTPC-POLL = AND
    OVER ATTPC.CONNECTOR SCON.CANCEL-XT @ ['] _ATTPC-CANCEL = AND
    OVER ATTPC.CONNECTOR SCON.CLEANUP-XT @ ['] _ATTPC-CLEANUP = AND
    NIP ;

: AT-TEXT-POST-CONNECTOR-INIT
  \ ( id endpoint revision clock-context clock-xt tid-clock target
  \   create-owner owner -- status )
    8 PICK 8 PICK 8 PICK 8 PICK 8 PICK
    8 PICK 8 PICK 8 PICK 8 PICK _ATTPC-INIT-GEOMETRY
    ?DUP IF >R _ATTPC-DROP9 R> EXIT THEN
    >R
    R@ AT-TEXT-POST-CONNECTOR-SIZE 0 FILL
    R@ ATTPC.CREATE !
    DUP R@ ATTPC.TARGET HTARGET-SIZE MOVE DROP
    R@ ATTPC.TID-CLOCK !
    R@ ATTPC.CLOCK-XT !
    R@ ATTPC.CLOCK-CONTEXT !

    R@ ATTPC.CONNECTOR STREAMS-CONNECTOR-INIT
    STREAMS-FLOW-S-OK <> IF
        2DROP DROP
        R@ AT-TEXT-POST-CONNECTOR-SIZE 0 FILL
        R> DROP AT-TEXT-POST-CONNECTOR-S-INTERNAL EXIT
    THEN
    2 PICK R@ ATTPC.CONNECTOR SCON.ID RID-COPY
    1 PICK R@ ATTPC.CONNECTOR SCON.ENDPOINT-ID RID-COPY
    DUP R@ ATTPC.CONNECTOR SCON.REVISION !
    2DROP DROP
    STREAMS-CONNECTOR-DIRECTION-OUTPUT
        R@ ATTPC.CONNECTOR SCON.DIRECTION !
    STREAMS-PROTOCOL-ATPROTO R@ ATTPC.CONNECTOR SCON.PROTOCOL !
    R@ R@ ATTPC.CONNECTOR SCON.CONTEXT !
    XIO-OP-SIZE R@ ATTPC.CONNECTOR SCON.OP-SIZE !
    ['] _ATTPC-START R@ ATTPC.CONNECTOR SCON.START-XT !
    ['] _ATTPC-POLL R@ ATTPC.CONNECTOR SCON.POLL-XT !
    ['] _ATTPC-CANCEL R@ ATTPC.CONNECTOR SCON.CANCEL-XT !
    ['] _ATTPC-CLEANUP R@ ATTPC.CONNECTOR SCON.CLEANUP-XT !
    R@ ATTPC.CONNECTOR STREAMS-CONNECTOR-SEAL
    STREAMS-FLOW-S-OK <> IF
        R@ AT-TEXT-POST-CONNECTOR-SIZE 0 FILL
        R> DROP AT-TEXT-POST-CONNECTOR-S-INTERNAL EXIT
    THEN
    -1 R@ ATTPC.LAST-EPOCH-MS !
    _ATTPC-STATE-IDLE R@ ATTPC.STATE !
    AT-TEXT-POST-CONNECTOR-S-OK R@ ATTPC.LAST-STATUS !
    _ATTPC-MAGIC-VALUE R@ ATTPC.MAGIC !
    R> DROP AT-TEXT-POST-CONNECTOR-S-OK ;

