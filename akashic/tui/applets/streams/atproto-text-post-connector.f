: _ATTPC-CARRIER-CREATE-DISJOINT?
  ( payload create-owner -- flag )
    OVER STREAMS-PAYLOAD-BOUND? 0= IF 2DROP 0 EXIT THEN
    OVER STREAMS-PAYLOAD-SIZE 2 PICK
        _ATTPC-CREATE-EXTERNAL? 0= IF 2DROP 0 EXIT THEN
    OVER SPAY.SEGMENTS @
    2 PICK SPAY.SEGMENT-N @ STREAMS-PAYLOAD-SEGMENT-BYTES
    2 PICK _ATTPC-CREATE-EXTERNAL? 0= IF 2DROP 0 EXIT THEN
    OVER SPAY.SEGMENT-N @ 0 ?DO
        I 2 PICK SPAY.SEGMENTS @
        SWAP STREAMS-PAYLOAD-SEGMENT-SIZE * +
        DUP SPSEG.DATA @ SWAP SPSEG.CAPACITY @
        2 PICK _ATTPC-CREATE-EXTERNAL? 0= IF
            2DROP 0 UNLOOP EXIT
        THEN
    LOOP
    2DROP -1 ;

