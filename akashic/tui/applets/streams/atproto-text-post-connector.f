    R@ ATTPC.ARG-EVENT @ STREAMS-EVENT-SIZE R@ ATTPC.CREATE @
        AT-CREATE-RECORD-EXTERNAL-SPAN-STATUS _ATTPC-CREATE>STATUS
    ?DUP IF R> DROP EXIT THEN
    R@ ATTPC.ARG-OP @ XIO-OP-SIZE R@ ATTPC.CREATE @
        AT-CREATE-RECORD-EXTERNAL-SPAN-STATUS _ATTPC-CREATE>STATUS
    R> DROP ;

DT-EPOCH-S-MAX 1000 * 999 + CONSTANT _ATTPC-EPOCH-MS-MAX

