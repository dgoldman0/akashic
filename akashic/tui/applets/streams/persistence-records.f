    DROP
    R@ _SPREC-NATIVE-OBSERVATION-ID-FEED
    R@ SPRH.OBSERVATION-ID SHA3-256-END
    R@ SPREC-NATIVE-SEAL!
    DUP IF R@ _SPREC-NATIVE-CANDIDATE-RESET! THEN
    R> DROP ;

