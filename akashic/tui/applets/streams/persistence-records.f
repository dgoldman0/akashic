    R@ _SPREC-OBSERVATION-HEADER? 0= IF
        2DROP R> DROP SPREC-S-INVALID EXIT
    THEN
    2DUP R@ SPRO.URL OCHK-URL-MAX _SPREC-TEXT!
    DUP IF >R 2DROP R> R> DROP EXIT THEN DROP
    DUP R@ SPRO.URL-U !
    2DROP R> DROP SPREC-S-OK ;

