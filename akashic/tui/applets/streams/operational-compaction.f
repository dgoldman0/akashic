: _SSPCOM-BLOB-SINK
  ( logical-offset payload-a payload-u context -- persist-status )
    >R
    DUP 0< IF _SSP-DROP3 R> DROP PERSIST-S-INVALID EXIT THEN
    2 PICK
    R@ _SSPCOM.READ-BASE @ R@ _SSPCOM.READ-USED @ + <> IF
        _SSP-DROP3 R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    R@ _SSPCOM.READ-USED @ OVER _SSP-ADD?
    0= IF DROP _SSP-DROP3 R> DROP PERSIST-S-CAPACITY EXIT THEN
    R@ _SSPCOM.READ-LIMIT @ > IF
        _SSP-DROP3 R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    1 PICK
    R@ _SSPCOM.READ-DEST @ R@ _SSPCOM.READ-USED @ +
    2 PICK MOVE
    DUP R@ _SSPCOM.READ-USED +!
    _SSP-DROP3 R> DROP PERSIST-S-OK ;

