\ =====================================================================
\ operational-compaction.f - Current Streams live-set compaction
\ =====================================================================
\ PCOMPACT owns offline bank selection, the immutable source-root fence,
\ exact shared publication, mirroring, recovery, and old-bank cleanup.
\ This friend of operational-spool.f owns only the current Streams meaning:
\ it traverses the four primary trees, copies their checked semantic records
\ and PBLOB bytes, derives all secondary rows and usage, and writes one final
\ root whose eight physical roots are rebased to the shared generation.
\
\ Every mutable byte is caller-owned.  There is one prerelease record shape
\ and one rebuild path; no old-shape reader or compatibility state is kept.
\ =====================================================================

