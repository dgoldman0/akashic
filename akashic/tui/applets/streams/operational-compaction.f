: _SSPCOM-ATTEMPT-COUNTERS!  ( context -- )
    >R
    1 R@ _SSPCOM.BUILDER-WORK @
        _SSPW.CURRENT-ROOT SOPROOT.ITEM-COUNT +!
    R@ _SSPCOM.RECORD SOPATT.PAYLOAD-U @
    R@ _SSPCOM.BUILDER-WORK @
        _SSPW.CURRENT-ROOT SOPROOT.PAYLOAD-BYTES +!
    R@ _SSPCOM.RECORD SOPATT.STATE @
    DUP STREAMS-OPATT-STATE-ACCEPTED = IF
        DROP
        1 R@ _SSPCOM.BUILDER-WORK @
            _SSPW.CURRENT-ROOT SOPROOT.READY-COUNT +!
    ELSE
        DUP STREAMS-OPATT-STATE-ACTIVE = IF
            DROP
            1 R@ _SSPCOM.BUILDER-WORK @
                _SSPW.CURRENT-ROOT SOPROOT.ACTIVE-COUNT +!
        ELSE
            STREAMS-OPATT-STATE-INDETERMINATE = IF
                1 R@ _SSPCOM.BUILDER-WORK @
                    _SSPW.CURRENT-ROOT
                    SOPROOT.INDETERMINATE-COUNT +!
            THEN
            1 R@ _SSPCOM.BUILDER-WORK @
                _SSPW.CURRENT-ROOT SOPROOT.TERMINAL-COUNT +!
        THEN
    THEN
    R@ _SSPCOM.RECORD SOPATT.CLEANUP-ERROR @ IF
        1 R@ _SSPCOM.BUILDER-WORK @
            _SSPW.CURRENT-ROOT SOPROOT.CLEANUP-FAILED-COUNT +!
    THEN
    R@ _SSPCOM.RECORD SOPATT.FLAGS @
        STREAMS-OPATT-F-RECEIPT-PRESENT AND IF
        1 R@ _SSPCOM.BUILDER-WORK @
            _SSPW.CURRENT-ROOT SOPROOT.RECEIPT-COUNT +!
        R@ _SSPCOM.REMOTE-U @
        R@ _SSPCOM.BUILDER-WORK @
            _SSPW.CURRENT-ROOT SOPROOT.RECEIPT-BYTES +!
    THEN
    R> DROP ;

: _SSPCOM-ATTEMPT-FINISH  ( context -- status )
    >R
    R@ _SSPCOM.RECORD SOPATT.FLAGS @
        STREAMS-OPATT-F-RECEIPT-PRESENT AND IF
        R@ _SSPCOM-APPEND-RECEIPT
        DUP IF R> DROP EXIT THEN DROP
    THEN
    R@ _SSPCOM.RECORD
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.ATTEMPT
        STREAMS-OPATT-SIZE MOVE
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.ATTEMPT
        STREAMS-OPATT-SEAL _SSP-OPREC>STATUS
    DUP IF R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT THEN DROP
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.ATTEMPT SOPATT.ATTEMPT-ID
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.ATTEMPT-ID RID-COPY
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.ATTEMPT SOPATT.REQUEST-SEAL
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.REQUEST-SEAL RID-COPY
    R@ _SSPCOM.BUILDER-WORK @ _SSPW-APPEND-AND-VALIDATE-ATTEMPT
    DUP IF R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT THEN DROP
    R@ _SSPCOM.BUILDER-WORK @ _SSPW-INSERT-ATTEMPT-ROW
    DUP IF R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT THEN DROP
    R@ _SSPCOM-INSERT-STATE-ROW
    DUP IF R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT THEN DROP
    R@ _SSPCOM-INSERT-IDEMPOTENCY
    DUP IF R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT THEN DROP
    R@ _SSPCOM-INCREMENT-CONNECTOR-USAGE
    DUP IF R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT THEN DROP
    R@ _SSPCOM.RECORD _SSPCOM-ACTIVE? IF
        R@ _SSPCOM-ACTIVE-REMAINDER-ROOM? 0= IF
            STREAMS-SPOOL-S-CAPACITY R@ _SSPCOM-BUILDER-ABORT
            R> DROP EXIT
        THEN
        R@ _SSPCOM-ACTIVE-REMAINDER-FUTURE!
        DUP IF R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT THEN DROP
        R@ _SSPCOM-INCREMENT-FLOW-USAGE
        DUP IF R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT THEN DROP
    THEN
    R@ _SSPCOM-ATTEMPT-COUNTERS!
    R@ _SSPCOM-BUILDER-PUBLISH
    DUP IF R> DROP EXIT THEN DROP
    0 R@ _SSPCOM.ROW-STATE !
    1 R@ _SSPCOM.COPIED-ATTEMPT +!
    R> DROP STREAMS-SPOOL-S-OK ;

: _SSPCOM-ATTEMPT-PAYLOAD-DONE  ( context -- status )
    >R
    R@ _SSPCOM.RECORD SOPATT.PAYLOAD-U @
    R@ _SSPCOM.RECORD SOPATT.PAYLOAD-DIGEST
    R@ _SSPCOM-TARGET-DIGEST
    DUP IF R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT THEN DROP
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.BLOB
    R@ _SSPCOM.RECORD SOPATT.PAYLOAD-BLOB
        PBLOB-COPY _SSP-PERSIST>STATUS
    DUP IF R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT THEN DROP
    0 R@ _SSPCOM.REMOTE-U !
    R@ _SSPCOM.RECORD SOPATT.FLAGS @
        STREAMS-OPATT-F-RECEIPT-PRESENT AND IF
        R@ _SSPCOM.RECEIPT SOPRECEIPT.REMOTE-RECEIPT-U @
        R@ _SSPCOM.RECEIPT SOPRECEIPT.REMOTE-CORRELATION-U @
            _SSP-ADD? 0= IF
            DROP STREAMS-SPOOL-S-CORRUPT
            R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT
        THEN
        DUP R@ _SSPCOM.REMOTE-U !
        IF
            R@ _SSPCOM.REMOTE-U @ R@ _SSPCOM-PBLOB-BEGIN
            DUP IF R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT THEN DROP
            _SSPCOM-ROW-ATTEMPT-REMOTE R@ _SSPCOM.ROW-STATE !
            R> DROP STREAMS-SPOOL-S-OK EXIT
        THEN
    THEN
    R@ _SSPCOM-ATTEMPT-FINISH
    R> DROP ;

: _SSPCOM-ATTEMPT-REMOTE-DONE  ( context -- status )
    >R
    R@ _SSPCOM.REMOTE-U @
    R@ _SSPCOM.RECEIPT SOPRECEIPT.REMOTE-DIGEST
    R@ _SSPCOM-TARGET-DIGEST
    DUP IF R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT THEN DROP
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.BLOB
    R@ _SSPCOM.RECEIPT SOPRECEIPT.REMOTE-BLOB
        PBLOB-COPY _SSP-PERSIST>STATUS
    DUP IF R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT THEN DROP
    R@ _SSPCOM-ATTEMPT-FINISH
    R> DROP ;

: _SSPCOM-ATTEMPT-STEP  ( context -- status )
    >R
    R@ _SSPCOM.ROW-STATE @ _SSPCOM-ROW-NONE = IF
        R@ _SSPCOM-ATTEMPT-BEGIN
        DUP IF R> DROP EXIT THEN DROP
    THEN
    R@ _SSPCOM-PBLOB-STEP
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPCOM.BLOB-DONE @ 0= IF
        R> DROP STREAMS-SPOOL-S-OK EXIT
    THEN
    R@ _SSPCOM.ROW-STATE @
        _SSPCOM-ROW-ATTEMPT-PAYLOAD = IF
        R@ _SSPCOM-ATTEMPT-PAYLOAD-DONE
    ELSE
        R@ _SSPCOM.ROW-STATE @
            _SSPCOM-ROW-ATTEMPT-REMOTE = IF
            R@ _SSPCOM-ATTEMPT-REMOTE-DONE
        ELSE
            STREAMS-SPOOL-S-CORRUPT R@ _SSPCOM-BUILDER-ABORT
        THEN
    THEN
    R> DROP ;

