: _SSPCOM-BLOB-SOURCE
  ( logical-offset destination-a requested-u context -- actual-u persist-status )
    >R
    DUP 0> 0= IF _SSP-DROP3 R> DROP 0 PERSIST-S-INVALID EXIT THEN
    2 PICK R@ _SSPCOM.READ-BASE !
    DUP R@ _SSPCOM.READ-LIMIT !
    1 PICK R@ _SSPCOM.READ-DEST !
    0 R@ _SSPCOM.READ-USED !
    _SSP-DROP3
    R@ _SSPCOM-SOURCE-BLOB DUP 0= IF
        DROP R> DROP 0 PERSIST-S-CORRUPT EXIT
    THEN
    R@ _SSPCOM.READ-BASE @
    R@ _SSPCOM.READ-LIMIT @
    ['] _SSPCOM-BLOB-SINK R@
    R@ _SSPCOM.SOURCE-SPOOL @ _SSP-D.STORE @
    R@ _SSPCOM.SOURCE-WORK @ _SSPW.PSTORE-WORK @
    R@ _SSPCOM.SOURCE-WORK @ _SSPW.BLOB-WORK
    PBLOB-READ-RANGE
    DUP IF
        DUP PERSIST-S-NOT-FOUND = IF
            DROP PERSIST-S-CORRUPT
        THEN
        0 SWAP R> DROP EXIT
    THEN
    DROP
    R@ _SSPCOM.READ-USED @
    DUP R@ _SSPCOM.READ-LIMIT @ <> IF
        DROP R> DROP 0 PERSIST-S-CORRUPT EXIT
    THEN
    PERSIST-S-OK R> DROP ;

