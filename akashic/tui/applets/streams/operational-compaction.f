  ( logical-u expected-digest context -- status )
    >R
    R@ _SSPCOM.BUILDER-WORK @ _SSPW-HASH-INIT
    DUP IF
        >R 2DROP R> R> DROP EXIT
    THEN
    DROP
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.BLOB
    0
    3 PICK
    ['] _SSPW-HASH-SINK
    R@ _SSPCOM.BUILDER-WORK @
    R@ _SSPCOM.BUILDER-SPOOL @ _SSP-D.STORE @
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PSTORE-WORK @
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.BLOB-WORK
    PBLOB-READ-RANGE-TX
    DUP PERSIST-S-NOT-FOUND = IF
        DROP 2DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    DUP IF
        _SSP-PERSIST>STATUS >R 2DROP R> R> DROP EXIT
    THEN
    DROP NIP
    R@ _SSPCOM.BUILDER-WORK @ _SSPW-HASH-VERIFY
    R> DROP ;

