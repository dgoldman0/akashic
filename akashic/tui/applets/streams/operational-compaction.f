: _SSPCOM-SPOOL>PERSIST  ( spool-status -- persist-status )
    DUP STREAMS-SPOOL-S-OK >=
    OVER STREAMS-SPOOL-S-FAULT <= AND IF EXIT THEN
    CASE
        STREAMS-SPOOL-S-FULL-ITEMS OF PERSIST-S-CAPACITY ENDOF
        STREAMS-SPOOL-S-FULL-BYTES OF PERSIST-S-CAPACITY ENDOF
        STREAMS-SPOOL-S-REPLAY OF PERSIST-S-CONFLICT ENDOF
        STREAMS-SPOOL-S-STALE OF PERSIST-S-CONFLICT ENDOF
        STREAMS-SPOOL-S-UNKNOWN OF PERSIST-S-CORRUPT ENDOF
        PERSIST-S-FAULT SWAP
    ENDCASE ;

: _SSPCOM-DISPATCH-ROW  ( context -- status )
    DUP _SSPCOM.PHASE @ CASE
        _SSPCOM-PHASE-CONNECTOR OF _SSPCOM-CONNECTOR-ROW ENDOF
        _SSPCOM-PHASE-FLOW OF _SSPCOM-FLOW-ROW ENDOF
        _SSPCOM-PHASE-CHECKPOINT OF _SSPCOM-CHECKPOINT-STEP ENDOF
        _SSPCOM-PHASE-ATTEMPT OF _SSPCOM-ATTEMPT-STEP ENDOF
        2DROP STREAMS-SPOOL-S-CORRUPT
    ENDCASE ;

: _SSPCOM-STEP-ARGS?
  ( source-root builder-store builder-pstore-work allowance context -- flag )
    >R
    DUP 0> 0= IF _SSP-DROP4 R> DROP 0 EXIT THEN
    3 PICK R@ _SSPCOM-SOURCE-ROOT? 0= IF
        _SSP-DROP4 R> DROP 0 EXIT
    THEN
    2 PICK R@ _SSPCOM.BUILDER-SPOOL @ _SSP-D.STORE @ <> IF
        _SSP-DROP4 R> DROP 0 EXIT
    THEN
    1 PICK R@ _SSPCOM.BUILDER-WORK @
        _SSPW.PSTORE-WORK @ <> IF
        _SSP-DROP4 R> DROP 0 EXIT
    THEN
    _SSP-DROP4 R> DROP -1 ;

: _SSPCOM-STEP-RUN  ( context -- done? bytes-used spool-status )
    >R
    R@ _SSPCOM.STATE @ _SSPCOM-STATE-DONE >= IF
        R> DROP -1 0 STREAMS-SPOOL-S-OK EXIT
    THEN
    R@ _SSPCOM.STATE @ _SSPCOM-STATE-BOUND = IF
        R@ _SSPCOM-CAPTURE-SOURCE
        DUP IF R> DROP 0 0 ROT EXIT THEN DROP
    THEN
    BEGIN
        R@ _SSPCOM.STATE @ _SSPCOM-STATE-DONE <
    WHILE
        R@ _SSPCOM.ROW-STATE @ _SSPCOM-ROW-NONE = IF
            R@ _SSPCOM-NEXT-ROW
            DUP STREAMS-SPOOL-S-NOT-FOUND = IF
                DROP
                R@ _SSPCOM-NEXT-PHASE
                DUP IF R> DROP 0 0 ROT EXIT THEN DROP
                R@ _SSPCOM.STATE @ _SSPCOM-STATE-DONE = IF
                    R> DROP -1 0 STREAMS-SPOOL-S-OK EXIT
                THEN
                \ A family boundary is itself one bounded work call.
                R> DROP 0 0 STREAMS-SPOOL-S-OK EXIT
            THEN
            DUP IF R> DROP 0 0 ROT EXIT THEN DROP
        THEN
        R@ _SSPCOM-DISPATCH-ROW
        DUP IF R> DROP 0 0 ROT EXIT THEN DROP
        R@ _SSPCOM.USED @
        R> DROP 0 SWAP STREAMS-SPOOL-S-OK EXIT
    REPEAT
    R> DROP -1 0 STREAMS-SPOOL-S-OK ;

: _SSPCOM-STEP-CATCH  ( context -- done? bytes-used spool-status )
    DUP >R ['] _SSPCOM-STEP-RUN CATCH
    DUP IF
        2DROP
        STREAMS-SPOOL-S-FAULT R@ _SSPCOM-BUILDER-ABORT DROP
        STREAMS-SPOOL-S-FAULT R@ _SSPCOM.STATUS !
        0 0 STREAMS-SPOOL-S-FAULT
    ELSE
        DROP
    THEN
    R> DROP ;

: _SSPCOM-STEP
  ( source-root builder-store builder-pstore-work allowance context -- done? bytes-used persist-status )
    DUP STREAMS-SPOOL-COMPACTION-CONTEXT-VALID? 0= IF
        _SSP-DROP5 0 0 PERSIST-S-INVALID EXIT
    THEN
    >R
    3 PICK 3 PICK 3 PICK 3 PICK R@
        _SSPCOM-STEP-ARGS? 0= IF
        _SSP-DROP4 R> DROP 0 0 PERSIST-S-INVALID EXIT
    THEN
    DUP R@ _SSPCOM.ALLOWANCE !
    0 R@ _SSPCOM.USED !
    0 R@ _SSPCOM.BLOB-DONE !
    _SSP-DROP4
    R@ _SSPCOM-STEP-CATCH
    DUP R@ _SSPCOM.STATUS !
    _SSPCOM-SPOOL>PERSIST
    R> DROP ;

: _SSPCOM-RESET-BOUND  ( status context -- status )
    >R
    DUP R@ _SSPCOM.STATUS !
    _SSPCOM-STATE-BOUND R@ _SSPCOM.STATE !
    _SSPCOM-PHASE-CONNECTOR R@ _SSPCOM.PHASE !
    STREAMS-OPROOT-TREE-CONNECTORS R@ _SSPCOM.TREE !
    0 R@ _SSPCOM.CURSOR-READY !
    0 R@ _SSPCOM.ROW-STATE !
    0 R@ _SSPCOM.ALLOWANCE !
    0 R@ _SSPCOM.USED !
    0 R@ _SSPCOM.BLOB-DONE !
    0 R@ _SSPCOM.COPIED-CONNECTOR !
    0 R@ _SSPCOM.COPIED-FLOW !
    0 R@ _SSPCOM.COPIED-CHECKPOINT !
    0 R@ _SSPCOM.COPIED-ATTEMPT !
    0 R@ _SSPCOM.READ-BASE !
    0 R@ _SSPCOM.READ-LIMIT !
    0 R@ _SSPCOM.READ-DEST !
    0 R@ _SSPCOM.READ-USED !
    0 R@ _SSPCOM.REMOTE-U !
    R@ _SSPCOM.SNAPSHOT
    STREAMS-SPOOL-COMPACTION-CONTEXT-SIZE _SSPCOM-SNAPSHOT-OFF -
        0 FILL
    R> DROP ;

: STREAMS-SPOOL-COMPACTION-CANCEL  ( context -- status )
    DUP STREAMS-SPOOL-COMPACTION-CONTEXT-VALID? 0= IF
        DROP STREAMS-SPOOL-S-INVALID EXIT
    THEN
    >R
    STREAMS-SPOOL-S-OK
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.STATE @
        _SSPW-STATE-ACTIVE = IF
        R@ _SSPCOM.BUILDER-WORK @ _SSPW-ABORT-ACTIVE
    THEN
    DUP STREAMS-SPOOL-S-OK = IF
        R@ _SSPCOM-RESET-BOUND
    ELSE
        DUP R@ _SSPCOM.STATUS !
    THEN
    R> DROP ;

