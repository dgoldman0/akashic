: _SSPCOM-REBASE-ROOTS  ( exact-generation context -- status )
    >R
    0
    BEGIN DUP STREAMS-OPROOT-TREE-COUNT < WHILE
        DUP R@ _SSPCOM.BUILDER-WORK @ _SSPW-ROOT
        2 PICK
        R@ _SSPCOM.BUILDER-WORK @ _SSPW.STAGING-ROOT
        3 PICK R@ _SSPCOM.BUILDER-WORK @ _SSPW-TREE
        PBTREE-ROOT-REBASE
        DUP IF
            _SSP-PERSIST>STATUS >R 2DROP R> R> DROP EXIT
        THEN
        DROP
        R@ _SSPCOM.BUILDER-WORK @ _SSPW.STAGING-ROOT
        OVER
        R@ _SSPCOM.BUILDER-WORK @ _SSPW.PAGE
            STREAMS-OPROOT-TREE
        PBTREE-ROOT-COPY
        DUP IF
            _SSP-PERSIST>STATUS >R 2DROP R> R> DROP EXIT
        THEN
        DROP
        1+
    REPEAT
    DROP DROP R> DROP STREAMS-SPOOL-S-OK ;

: _SSPCOM-FINAL-SEMANTICS  ( exact-generation context -- status )
    >R
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.CURRENT-ROOT
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PAGE
        STREAMS-OPROOT-SIZE MOVE
    DUP R@ _SSPCOM-REBASE-ROOTS
    DUP IF NIP R> DROP EXIT THEN DROP
    DROP
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PAGE SOPROOT.RECLAIM-STATE
    RECLAIM-STATE-SIZE
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.RECLAIM-WORK RECLAIM-STATE!
    DUP IF
        _SSP-PERSIST>STATUS R> DROP EXIT
    THEN
    DROP
    0 R@ _SSPCOM.BUILDER-WORK @
        _SSPW.PAGE SOPROOT.UNCOMPACTED-CLEANUP-COUNT !
    R@ _SSPCOM.BUILDER-WORK @
        _SSPW.PAGE SOPROOT.LOGICAL-GENERATION @
        _SSP-MAX-SIGNED >= IF
        R> DROP STREAMS-SPOOL-S-CAPACITY EXIT
    THEN
    R@ _SSPCOM.BUILDER-WORK @
        _SSPW.PAGE SOPROOT.MUTATION-SEQUENCE @
        _SSP-MAX-SIGNED >= IF
        R> DROP STREAMS-SPOOL-S-CAPACITY EXIT
    THEN
    1 R@ _SSPCOM.BUILDER-WORK @
        _SSPW.PAGE SOPROOT.LOGICAL-GENERATION +!
    1 R@ _SSPCOM.BUILDER-WORK @
        _SSPW.PAGE SOPROOT.MUTATION-SEQUENCE +!
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PAGE
        STREAMS-OPROOT-SEAL _SSP-OPREC>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PAGE
        STREAMS-OPROOT-STRUCTURE-VALID? 0= IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PAGE
        _SSP-ROOT-CARDINALITIES? 0= IF
        R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PAGE
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.CURRENT-ROOT
        STREAMS-OPROOT-SIZE MOVE
    R> DROP STREAMS-SPOOL-S-OK ;

: _SSPCOM-FINAL-COMMIT-TAIL  ( commit-status context -- status )
    >R
    _SSPW-TX-RECLAIM R@ _SSPCOM.BUILDER-WORK @ _SSPW.TX-PHASE !
    _SSP-PERSIST>STATUS
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.TEMP-STATUS !
    0 R@ _SSPCOM.BUILDER-WORK @ _SSPW.FUTURE-RETIREMENT !
    R@ _SSPCOM.BUILDER-WORK @ _SSPW-COMMIT-DURABLE? IF
        -1 R@ _SSPCOM.BUILDER-WORK @ _SSPW.DURABLE !
        R@ _SSPCOM.BUILDER-SPOOL @ _SSP-D.STORE @
            PSTORE-GENERATION@
        R@ _SSPCOM.BUILDER-WORK @ _SSPW.BASE-GENERATION !
        STREAMS-SPOOL-S-OK
        R@ _SSPCOM.BUILDER-WORK @ _SSPW.TEMP-STATUS !
        R@ _SSPCOM.BUILDER-WORK @ _SSPW.RECLAIM-WORK
        R@ _SSPCOM.BUILDER-WORK @ _SSPW.RECLAIM RECLAIM-ADOPT
        DUP IF
            _SSP-PERSIST>STATUS
            R@ _SSPCOM.BUILDER-WORK @ _SSPW.TEMP-STATUS !
            R@ _SSPCOM.BUILDER-WORK @ _SSPW.RECLAIM-WORK
                RECLAIM-ABORT
            DUP PERSIST-S-OK = IF
                DROP _SSPW-TX-NONE
                R@ _SSPCOM.BUILDER-WORK @ _SSPW.TX-PHASE !
            ELSE
                DROP
            THEN
        ELSE
            DROP
            _SSPW-TX-NONE
            R@ _SSPCOM.BUILDER-WORK @ _SSPW.TX-PHASE !
        THEN
        \ Embedded roots now name the shared exact generation, which can
        \ intentionally differ from the staging store's private generation.
        _SSPW-STATE-REOPEN R@ _SSPCOM.BUILDER-WORK @ _SSPW.STATE !
    ELSE
        R@ _SSPCOM.BUILDER-WORK @ _SSPW.TEMP-STATUS @
            STREAMS-SPOOL-S-OK = IF
            STREAMS-SPOOL-S-UNCERTAIN
            R@ _SSPCOM.BUILDER-WORK @ _SSPW.TEMP-STATUS !
        THEN
        R@ _SSPCOM.BUILDER-WORK @ _SSPW.TEMP-STATUS @
        R@ _SSPCOM.BUILDER-WORK @ _SSPW-ABORT-ACTIVE
        R@ _SSPCOM.BUILDER-WORK @ _SSPW.TEMP-STATUS !
    THEN
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.TEMP-STATUS @
    R> DROP ;

: _SSPCOM-FINALIZE-ROOT  ( exact-generation context -- status )
    >R
    DUP 0> 0= IF DROP R> DROP STREAMS-SPOOL-S-INVALID EXIT THEN
    R@ _SSPCOM-FINAL-RECONCILE
    DUP IF NIP R> DROP EXIT THEN DROP
    R@ _SSPCOM.BUILDER-SPOOL @ _SSP-D.STORE @ PSTORE-GENERATION@
    DUP 0< OVER _SSP-MAX-SIGNED >= OR IF
        2DROP R> DROP STREAMS-SPOOL-S-CORRUPT EXIT
    THEN
    1+ OVER > IF
        DROP R> DROP STREAMS-SPOOL-S-CONFLICT EXIT
    THEN
    R@ _SSPCOM-BUILDER-BEGIN
    DUP IF NIP R> DROP EXIT THEN DROP
    R@ _SSPCOM.BUILDER-WORK @ _SSPCOM-FINAL-ROOM? 0= IF
        DROP STREAMS-SPOOL-S-CAPACITY
        R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT
    THEN
    RECLAIM-FINALIZE-RETIREMENT-MAX
    R@ _SSPCOM.BUILDER-WORK @ _SSPW-FUTURE-RETIREMENT!
    DUP IF
        NIP R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT
    THEN
    DROP
    R@ _SSPCOM.BUILDER-WORK @
    R@ _SSPCOM.BUILDER-SPOOL @ _SSP-D.STORE @
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PSTORE-WORK @
        _SSPW-ALLOCATE
    DUP IF
        _SSP-PERSIST>STATUS >R 2DROP R>
        R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT
    THEN
    DROP
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.APP-ROOT-PAGE !
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PAGE
        PERSIST-PAGE-PAYLOAD-SIZE 0 FILL
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PAGE
    PERSIST-PAGE-PAYLOAD-SIZE
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.APP-ROOT-PAGE @
    R@ _SSPCOM.BUILDER-SPOOL @ _SSP-D.STORE @
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PSTORE-WORK @
        PSTORE-WRITE-PAGE-TX
    DUP IF
        _SSP-PERSIST>STATUS NIP
        R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT
    THEN
    DROP
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.RECLAIM-WORK
        RECLAIM-FINALIZE
    DUP IF
        _SSP-PERSIST>STATUS NIP
        R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT
    THEN
    DROP
    DUP R@ _SSPCOM-FINAL-SEMANTICS
    DUP IF
        >R DROP R>
        R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT
    THEN
    DROP DROP
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PAGE
    PERSIST-PAGE-PAYLOAD-SIZE
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.APP-ROOT-PAGE @
    R@ _SSPCOM.BUILDER-SPOOL @ _SSP-D.STORE @
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PSTORE-WORK @
        PSTORE-WRITE-PAGE-TX
    DUP IF
        _SSP-PERSIST>STATUS
        R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT
    THEN
    DROP
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.APP-ROOT-PAGE @
    R@ _SSPCOM.BUILDER-SPOOL @ _SSP-D.STORE @
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PSTORE-WORK @
        PSTORE-APPLICATION-ROOT!
    DUP IF
        _SSP-PERSIST>STATUS
        R@ _SSPCOM-BUILDER-ABORT R> DROP EXIT
    THEN
    DROP
    R@ _SSPCOM.BUILDER-SPOOL @ _SSP-D.STORE @
    R@ _SSPCOM.BUILDER-WORK @ _SSPW.PSTORE-WORK @ PSTORE-COMMIT
    R@ _SSPCOM-FINAL-COMMIT-TAIL
    DUP STREAMS-SPOOL-S-OK = IF
        _SSPCOM-STATE-FINALIZED R@ _SSPCOM.STATE !
    THEN
    R> DROP ;

