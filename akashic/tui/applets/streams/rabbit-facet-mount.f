: _SRFM-HANDLE-CLAIMED
  ( frame kind peer-token builder mount -- outcome )
    DUP STREAMS-RABBIT-FACET-MOUNT-BINDING-VALID? 0= IF
        _SRFMH-DROP-CALL RSERVER-HANDLER-FAILED EXIT
    THEN
    DUP SRFM.BUSY @ IF
        _SRFMH-DROP-CALL RSERVER-HANDLER-FAILED EXIT
    THEN
    DUP SRFM.JSON-A @ _SRFMH-JSON-A !
    DUP SRFM.JSON-CAP @ _SRFMH-JSON-CAP !
    DUP -1 SWAP SRFM.BUSY !
    -1 _SRFMH-MOUNT-CLAIMED !
    _SRFMH-MOUNT ! _SRFMH-BUILDER ! _SRFMH-TOKEN !
    _SRFMH-KIND ! _SRFMH-FRAME !
    _SRFMH-AROUND ;

: _SRFM-HANDLE-IMPL
  ( frame kind peer-token builder mount -- outcome )
    _SRFM-GUARD GUARD-MINE? IF
        _SRFMH-DROP-CALL RSERVER-HANDLER-FAILED EXIT
    THEN
    _SRFM-GUARD GUARD-TRY-ACQUIRE 0= IF
        _SRFMH-DROP-CALL RSERVER-HANDLER-FAILED EXIT
    THEN
    0 _SRFMH-MOUNT-CLAIMED !
    ['] _SRFM-HANDLE-CLAIMED CATCH
    DUP IF
        _SRFMH-MOUNT-CLAIMED @ IF
            DUP _SRFMH-STATUS !
            _SRFMH-JSON-A @ _SRFMH-JSON-CAP @ 0 FILL
            0 _SRFMH-MOUNT @ SRFM.BUSY !
            STREAMS-RABBIT-FACET-MOUNT-S-CALLBACK
            STREAMS-RABBIT-FACET-MOUNT-DETAIL-NONE _SRFMH-STATUS @
            _SRFMH-MOUNT @ _SRFM-STATUS! DROP
            0 _SRFMH-MOUNT-CLAIMED !
        THEN
    THEN
    _SRFM-GUARD GUARD-RELEASE
    DUP IF
        DROP _SRFMH-DROP-CALL RSERVER-HANDLER-FAILED EXIT
    THEN
    DROP ;

