        CBUS-S-CONSUMED-AUTHORITY OF RSERVER-HANDLER-DENY _SRFMH-OUTCOME ! ENDOF
        CBUS-S-BUSY OF 503 S" BUSY" _SRFMH-BODYLESS ENDOF
        CBUS-S-TIMEOUT OF 504 S" TIMEOUT" _SRFMH-BODYLESS ENDOF
        CBUS-S-CANCELLED OF 409 S" CANCELLED" _SRFMH-BODYLESS ENDOF
        500 S" HANDLER FAILED" _SRFMH-BODYLESS
