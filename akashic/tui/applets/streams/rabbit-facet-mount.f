\ =====================================================================
\ rabbit-facet-mount.f - exact Rabbit routes onto Practice facets
\ =====================================================================
\ One caller-owned mount binds one exact read-only Rabbit request kind and
\ selector to one exact local observe capability.  INIT registers the mount
\ as a borrowed handler context in a BUILDING neutral router.  The router
\ copies the verb and selector and must be sealed before any server can use
\ the mount.  Mutating dispatch remains out of scope until Rabbit idempotency
\ and committed-result semantics can make post-commit response failure safe.
\
\ The Burrow host is intentionally only future storage at mount construction:
\ its INIT requires that same router to be sealed.  Request handling is the
\ publication gate.  It succeeds only inside the host's dynamic callback
\ scope, where ACTIVE-BINDING@ resolves the exact admitted peer token to the
\ currently driven neutral owner, peer evidence, and Practice facet.
\
\ A facet is selection metadata, never authority.  Every request revalidates
\ the exact target generation, capability pointer, effects, invocation and
\ disclosure flags, then calls an injected authorizer.  Missing, throwing, or
\ malformed authorizers deny.  Only an explicit allow stamps the request as a
\ component principal and approved before synchronous CBUS-DISPATCH.
\
\ Input and output are ordinary schema-constrained IVJSON.  The mount owns an
\ inline reusable CBR plus an exclusive caller-provided JSON scratch arena.
\ The response builder copies successful output before the complete scratch
\ arena is wiped.  No selector, response, or application capacity is fixed by
\ this module.
\
\ The neutral Rabbit and interoperability codecs still use serialized
\ synchronous scratch.  The hosted Burrow scheduler provides the normal
\ serialization boundary; a module guard also refuses handler reentry before
\ any callback scratch is replaced.
\ =====================================================================

