        CBUS-S-STALE-INSTANCE OF 404 S" NOT FOUND" _SRFMH-BODYLESS ENDOF
        CBUS-S-NO-HANDLER OF 404 S" NOT FOUND" _SRFMH-BODYLESS ENDOF
        CBUS-S-STALE-REVISION OF 409 S" CONFLICT" _SRFMH-BODYLESS ENDOF
