: _SRFMH-INNER  ( -- )
    _SRFMH-ROUTE? 0= IF
        STREAMS-RABBIT-FACET-MOUNT-S-ROUTER
        STREAMS-RABBIT-FACET-MOUNT-DETAIL-ROUTER RROUTER-S-INVALID
        _SRFMH-FAIL EXIT
    THEN
    _SRFMH-CORRELATION? 0= IF
        STREAMS-RABBIT-FACET-MOUNT-S-MESSAGE
        STREAMS-RABBIT-FACET-MOUNT-DETAIL-MESSAGE RMSG-S-REQUIRED
        _SRFMH-FAIL EXIT
    THEN
    _SRFMH-TOKEN @ _SRFMH-MOUNT @ SRFM.BURROW @
    STREAMS-RABBIT-BURROW-ACTIVE-BINDING@
    _SRFMH-STATUS ! _SRFMH-FACET ! _SRFMH-EVIDENCE ! _SRFMH-OWNER !
    _SRFMH-STATUS @ STREAMS-RABBIT-BURROW-S-OK <> IF
        STREAMS-RABBIT-FACET-MOUNT-S-PEER
        STREAMS-RABBIT-FACET-MOUNT-DETAIL-BURROW _SRFMH-STATUS @
        _SRFMH-FAIL EXIT
    THEN
    _SRFMH-ACTIVE-GEOMETRY? 0= IF
        STREAMS-RABBIT-FACET-MOUNT-S-ALIAS
        STREAMS-RABBIT-FACET-MOUNT-DETAIL-BURROW
        STREAMS-RABBIT-BURROW-S-ALIAS _SRFMH-FAIL EXIT
    THEN
    _SRFMH-OWNER @ RSERVSUB.SERVER @ DUP RSERVER.BUILDER @
        _SRFMH-BUILDER @ <> IF
        DROP STREAMS-RABBIT-FACET-MOUNT-S-PEER
        STREAMS-RABBIT-FACET-MOUNT-DETAIL-SERVER RSERVER-S-INVALID
        _SRFMH-FAIL EXIT
    THEN
    RABBIT-SERVER-HELD-APP-LANE-ENSURE DUP RSERVER-S-OK <> IF
        STREAMS-RABBIT-FACET-MOUNT-S-PEER
        STREAMS-RABBIT-FACET-MOUNT-DETAIL-SERVER ROT
        _SRFMH-FAIL EXIT
    THEN DROP
    _SRFMH-CALLER? 0= IF
        STREAMS-RABBIT-FACET-MOUNT-S-BUS
        STREAMS-RABBIT-FACET-MOUNT-DETAIL-CBUS CBUS-S-STALE-INSTANCE
        _SRFMH-MOUNT @ _SRFM-STATUS! DROP
        404 S" NOT FOUND" _SRFMH-BODYLESS EXIT
    THEN
    _SRFMH-TARGET-CAP? 0= IF
        STREAMS-RABBIT-FACET-MOUNT-S-BUS
        STREAMS-RABBIT-FACET-MOUNT-DETAIL-CBUS CBUS-S-STALE-INSTANCE
        _SRFMH-MOUNT @ _SRFM-STATUS! DROP
        404 S" NOT FOUND" _SRFMH-BODYLESS EXIT
    THEN
    _SRFMH-FACET? 0= IF
        STREAMS-RABBIT-FACET-MOUNT-S-FACET
        STREAMS-RABBIT-FACET-MOUNT-DETAIL-AUTHORIZER 0
        _SRFMH-DENY EXIT
    THEN
    _SRFMH-AUTHORIZED? 0= IF
        STREAMS-RABBIT-FACET-MOUNT-S-DENIED
        STREAMS-RABBIT-FACET-MOUNT-DETAIL-AUTHORIZER
        _SRFMH-AUTH-DECISION @ _SRFMH-DENY EXIT
    THEN
    _SRFMH-VIEW? 0= IF
        STREAMS-RABBIT-FACET-MOUNT-S-MESSAGE
        STREAMS-RABBIT-FACET-MOUNT-DETAIL-MESSAGE RMSG-S-VALUE
        _SRFMH-MOUNT @ _SRFM-STATUS! DROP
        400 S" BAD REQUEST" _SRFMH-BODYLESS EXIT
    THEN
    _SRFMH-MOUNT @ _SRFM-REQUEST-CLEAR
    _SRFMH-DECODE DUP _SRFMH-STATUS ! IF
        STREAMS-RABBIT-FACET-MOUNT-S-CODEC
        STREAMS-RABBIT-FACET-MOUNT-DETAIL-IVJSON _SRFMH-STATUS @
        _SRFMH-MOUNT @ _SRFM-STATUS! DROP
        _SRFMH-STATUS @ IVJSON-E-CAPACITY = IF
            413 S" PAYLOAD TOO LARGE"
        ELSE
            _SRFMH-STATUS @ IVJSON-E-NOMEM = IF
                503 S" UNAVAILABLE"
            ELSE
                400 S" BAD REQUEST"
            THEN
        THEN
        _SRFMH-BODYLESS EXIT
    THEN
    _SRFMH-STAMP-REQUEST
    _SRFMH-DISPATCH DUP CBUS-S-OK <> IF
        _SRFMH-BUS-RESPONSE EXIT
    THEN DROP
    _SRFMH-ENCODE-RESULT ;

: _SRFMH-CLEANUP  ( -- )
    _SRFMH-MOUNT @ _SRFM-REQUEST-CLEAR
    _SRFMH-JSON-A @ _SRFMH-JSON-CAP @ 0 FILL
    0 _SRFMH-MOUNT @ SRFM.BUSY !
    0 _SRFMH-MOUNT-CLAIMED ! ;

: _SRFMH-AROUND  ( -- outcome )
    RSERVER-HANDLER-FAILED _SRFMH-OUTCOME !
    ['] _SRFMH-INNER CATCH DUP IF
        STREAMS-RABBIT-FACET-MOUNT-S-CALLBACK
        STREAMS-RABBIT-FACET-MOUNT-DETAIL-NONE ROT
        _SRFMH-MOUNT @ _SRFM-STATUS! DROP
        RSERVER-HANDLER-FAILED _SRFMH-OUTCOME !
    ELSE
        DROP
    THEN
    _SRFMH-OUTCOME @ >R
    _SRFMH-CLEANUP
    R> ;

: _SRFMH-DROP-CALL  ( frame kind peer-token builder mount -- )
