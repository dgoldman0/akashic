\ =====================================================================
\ rabbit-remote-action.f - persistent typed Rabbit action attempts
\ =====================================================================
\ One caller-owned owner retains one semantic PUBLISH action across any
\ number of transport attempts.  Target, canonical body, Idem, current Txn,
\ and exact raw receipt bytes live in caller-sized buffers.  There is no
\ product message, token, or receipt capacity in this module.
\
\ INIT binds those buffers.  PROFILE! then seals two immutable borrowed media
\ types and the classifier/fallback callbacks.  PREPARE copies the semantic
\ target, body, and Idem exactly once.  Each SEND requires a fresh caller
\ supplied Txn, constructs and seals the exact PUBLISH in a disjoint empty
\ builder, and records the connector operation only after publication.  A
\ successful SEND is not application success: only an exactly matching
\ callback followed by an exactly matching CONSUME can publish a receipt.
\
\ The callback claims only the live Lane/Txn response.  Every other frame is
\ delegated to the immutable fallback with its original arguments, allowing
\ this word to sit in a connector-wide callback chain.  Likewise CONSUME
\ returns owned=false without mutation for another operation's poll item.
\
\ The generic receipt profile is deliberately narrow.  Codes 200 and 412
\ require a nonempty JSON body with View exactly equal to the configured
\ receipt Accept-View; the body is decoded once for the classifier.  Codes
\ 403, 409, 429, and 503 require no body and no View.  Only the immutable
\ classifier declares ACCEPTED, NO-EFFECT, FORBIDDEN, CONFLICT, or RETRYABLE.
\ It receives the exact raw bytes as well as the callback-temporary decoded
\ value.  The decoded value is read-only and expires before callback return.
\
\ A coordinated connector DETACH or replacement lets RECONCILE discard the
\ stale operation handle and return the same body/Idem to RETRYABLE.  The next
\ SEND still requires a different Txn.  Receipt and action accessors return
\ borrowed slices owned by this descriptor's caller buffers.  The connector,
\ both View slices, and callback contexts must outlive the owner.
\ =====================================================================

\ Keep the KDOS module identity within 23 bytes.
