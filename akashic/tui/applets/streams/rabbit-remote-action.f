    ELSE
        STREAMS-RABBIT-REMOTE-ACTION-ST-FAILED _SRRAN-O @ SRRA.STATE !
    THEN
    _SRRAN-O @ SRRA.CANDIDATE-STATUS @
    _SRRAN-O @ SRRA.CANDIDATE-DOMAIN @
    _SRRAN-O @ SRRA.CANDIDATE-DETAIL @
    _SRRAN-O @ _SRRA-STATUS! _SRRAN-RS !
    _SRRAN-O @ _SRRA-CLEAR-CANDIDATE
    _SRRAN-CHANGED @ _SRRAN-RS @ ;

