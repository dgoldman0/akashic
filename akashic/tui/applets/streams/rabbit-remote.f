        0 0 STREAMS-RABBIT-REMOTE-RESOURCE-S-OK EXIT
    THEN
    _SRRESC-O @ SRRES.EVENT-STAGE-STATE @
        _SRRES-EVENT-STAGE-EMPTY <> IF
        -1 0 STREAMS-RABBIT-REMOTE-RESOURCE-S-BUSY EXIT
    THEN
    -1 _SRRESC-BUSY !
    -1 _SRRESC-O @ SRRES.BUSY !
    0 _SRRESC-O @ SRRES.CANDIDATE-READY !
    _SRRESC-O @ SRRES.CACHE-GENERATION @
    _SRRESC-O @ SRRES.FETCH-CACHE-GENERATION @ <> IF
        _SRRESC-MARK-STALE
    ELSE
        _SRRESC-ACCESS
    THEN
    _SRRESC-RELEASE STREAMS-RABBIT-REMOTE-RESOURCE-S-CLEANUP = IF
        0 _SRRESC-O @ SRRES.BUSY !
        0 _SRRESC-BUSY !
        -1 0 STREAMS-RABBIT-REMOTE-RESOURCE-S-CLEANUP EXIT
    THEN
    _SRRESC-FINISH _SRRESC-RS !
    _SRRESC-O @ SRRES.CACHE-GENERATION @
    _SRRESC-O @ SRRES.CACHE-PRESENT @ AND 0<> _SRRESC-CHANGED !
    _SRRESC-RS @ STREAMS-RABBIT-REMOTE-RESOURCE-S-OK <> IF
        0 _SRRESC-CHANGED !
    THEN
    0 _SRRESC-O @ SRRES.BUSY !
    0 _SRRESC-BUSY !
