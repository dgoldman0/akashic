        0 STREAMS-RABBIT-REMOTE-RESOURCE-S-INVALID EXIT
    THEN
    _SRRESC-O @ SRRES.BUSY @ IF
        0 STREAMS-RABBIT-REMOTE-RESOURCE-S-BUSY EXIT
    THEN
    _SRRESC-O @ SRRES.EVENT-STAGE-STATE @
        _SRRES-EVENT-STAGE-EMPTY <> IF
        0 STREAMS-RABBIT-REMOTE-RESOURCE-S-STATE EXIT
    THEN
    _SRRESC-O @ SRRES.STATE @
        STREAMS-RABBIT-REMOTE-RESOURCE-ST-CLEANUP <> IF
        0 STREAMS-RABBIT-REMOTE-RESOURCE-S-STATE EXIT
    THEN
    -1 _SRRESC-O @ SRRES.BUSY !
    _SRRESC-O @ SRRES.OPERATION @ IF
        _SRRESC-RELEASE STREAMS-RABBIT-REMOTE-RESOURCE-S-CLEANUP = IF
            0 _SRRESC-O @ SRRES.BUSY !
            0 STREAMS-RABBIT-REMOTE-RESOURCE-S-CLEANUP EXIT
        THEN
    THEN
    _SRRESC-O @ SRRES.CANDIDATE-READY @ _SRRESC-CHANGED !
    _SRRESC-FINISH _SRRESC-RS !
    _SRRESC-RS @ STREAMS-RABBIT-REMOTE-RESOURCE-S-OK <> IF
        0 _SRRESC-CHANGED !
    THEN
    0 _SRRESC-O @ SRRES.BUSY !
    _SRRESC-CHANGED @ _SRRESC-RS @ ;

