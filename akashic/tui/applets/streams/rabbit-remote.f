\ =====================================================================
\ rabbit-remote.f - typed remote snapshot ownership for Streams
\ =====================================================================
\ One caller-owned resource binds to one persistent Streams Rabbit
\ connector and one immutable output schema.  The caller supplies the exact
\ selector and transaction arenas; this module fixes no product capacity.
\
\ FETCH accepts a caller-owned sealed Rabbit builder.  The builder remains a
\ profile concern, while this owner verifies the exact FETCH selector,
\ nonzero Lane, copied Txn, Akashic JSON View, and Accept-View before asking
\ the connector to publish it.  Only one operation is in flight per owner.
\
\ During connector POLL the public callback retains no frame pointer.  It
\ records scalar response evidence and always commits an exactly correlated
\ terminal response, including a response rejected by this application
\ profile.  Decoding and optional validation happen later from the neutral
\ client's durable result slot, after POLL has returned.
\
\ CONSUME reports whether a poll item belonged to this owner.  A false owned
\ flag means the caller still owns and must route the original item, subject,
\ and generation.  This makes the first dedicated-connector slice compatible
\ with a later Streams operation/subscription mux instead of swallowing its
\ traffic.
\
\ A successful refresh decodes into staging, validates it, releases the exact
\ generation- and attachment-fenced operation, and only then replaces the
\ cache root.  FETCH records the cache generation from which it started, so a
\ subscription event published while that response is pending makes the older
\ snapshot stale instead of allowing it to overwrite newer application state.
\
\ Registered neutral subscription callbacks decode once into resource-owned
\ staging through CACHE-STAGE-JSON-CALLBACK.  This is the connector's matching
\ entry-callback path, not this resource's already-busy response fallback.
\ Only the returned scalar stage generation crosses the callback boundary.
\ Post-poll publication moves that exact graph without decoding or invoking
\ the application validator again; publication and discard failures retain the
\ fenced stage for explicit retry.
\ Failed refreshes and staged publications preserve the old cache and its
\ generation.
\ CACHE@ returns a borrowed CV pointer valid until the next successful
\ publication or FINI.  CACHE-CALLBACK@ is the structural read-only form used
\ while the shared connector is synchronously dispatching a callback and its
\ ordinary complete-graph validation is therefore intentionally busy.
\ Configured validators receive borrowed read-only value and owner pointers;
\ they must not mutate or retain either graph and may only use callback-safe
\ accessors while the owner is busy.
\ The connector and schema must outlive this owner.
\ =====================================================================

