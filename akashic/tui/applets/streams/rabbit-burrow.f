\ =====================================================================
\ rabbit-burrow.f - Streams-owned hosted Rabbit peer composition
\ =====================================================================
\ A Burrow borrows one sealed neutral Rabbit router and owns a caller-sized
\ roster of configured per-peer RABBIT-SERVER-SUBSCRIPTIONS graphs.  Streams
\ chooses admission policy and schedules these graphs; framing, routing,
\ sessions, queues, subscriptions, and event delivery remain reusable neutral
\ Rabbit machinery under net/rabbit.
\
\ Rows retain stable evidence, peer token, and Practice facet while their
\ mutable server graph is detached.  REPLACE can therefore adopt a fresh graph
\ after reconnect without weakening identity or authority selection.  Facets
\ are selection metadata only: this owner never treats one as request authority.
\ A later facet mount must authorize every request independently.
\
\ SERVICE is cooperative and bounded.  One call selects at most one attached
\ peer, performs at most one server poll, and only when that poll is pending
\ performs at most one event-source service.  Round-robin selection prevents a
\ quiet, saturated, or disconnected peer from monopolizing the Desk scheduler.
\
\ Neutral Rabbit uses serialized synchronous operation scratch.  Ordinary
\ public words here refuse reentry before replacing any scratch.  Admission and
\ route handlers execute inside a lower poll, so ACTIVE-BINDING@ is a deliberately
\ narrow callback-only accessor guarded by exact dynamic host and peer-token
\ evidence; it does not recursively validate a busy lower owner.
\
\ All storage is caller-owned.  INIT builds no transport, router, server,
\ subscription table, queue, or journal.  CANCEL and FINI retain partially
\ cleaned graphs for retry.  The borrowed router and physical transports must
\ outlive this owner and are finalized by their own owners afterward.
\ =====================================================================

