\ =====================================================================
\  source-authority.f - repository-backed configured Streams sources
\ =====================================================================
\  This module owns only the configured-source directory in the sealed
\  Streams repository.  It is the small source-management surface required
\  by streaming infrastructure; it owns no fetched document, collection,
\  provider, refresh, projection, output, or public-Bluesky policy.
\
\  Every mutable byte is in one caller-owned work object.  Every authority
\  read and mutation crosses STREAMS-REPOSITORY-WITH-OWNER.  A successful
\  mutation has exactly one adapter transaction and one publication; a
\  successful ENABLE no-op has neither.  Every returned operation has
\  attempted to abort any live transaction and to rebind a reopen-required
\  adapter before it releases the repository owner.
\
\  Public status domain:
\    OK, INVALID, NOT-FOUND, GONE, DUPLICATE, STALE, CAPACITY, BUSY,
\    CORRUPT, CONFLICT, UNCERTAIN, IO, FAULT, and UNSUPPORTED.
\  GONE means that the stable source RID resolves to a checked tombstone.
\
\  Public API:
\    STREAMS-SOURCE-AUTHORITY-WORK-INIT
\      ( source-work -- status )
\    STREAMS-SOURCE-AUTHORITY-WORK-VALID?
\      ( source-work -- flag )
\    STREAMS-SOURCE-AUTHORITY-WORK-STATUS@
\      ( source-work -- status )
\    STREAMS-SOURCE-AUTHORITY-READ
\      ( rid destination repository repo-work source-work -- status )
\    STREAMS-SOURCE-AUTHORITY-CREATE
\      ( candidate repository repo-work source-work -- status )
\    STREAMS-SOURCE-AUTHORITY-REPLACE
\      candidate expected-revision repository repo-work source-work -> status
\    STREAMS-SOURCE-AUTHORITY-ENABLE
\      rid expected-revision enabled? repository repo-work source-work -> status
\    STREAMS-SOURCE-AUTHORITY-REMOVE
\      ( rid expected-revision repository repo-work source-work -- status )
\
\  Candidates, RIDs, and READ destinations must be complete nonwrapping
\  spans disjoint from the source work and from the complete bound
\  repository/work graph.  READ changes its destination only on OK.
\  Mutation candidates are copied before normalization and are never edited.
\ =====================================================================

