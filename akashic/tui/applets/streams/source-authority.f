: _SSA-MUTATION-CAPACITY  ( source-work -- status )
    >R
    R@ _SSAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP 0= IF
        DROP R> DROP STREAMS-SOURCE-AUTHORITY-S-CORRUPT EXIT
    THEN
    DUP SAR.LOGICAL-GENERATION @ PERSIST-MAX-SIGNED >= IF
        DROP R> DROP STREAMS-SOURCE-AUTHORITY-S-CAPACITY EXIT
    THEN
    SAR.MUTATION-SEQUENCE @ PERSIST-MAX-SIGNED >= IF
        R> DROP STREAMS-SOURCE-AUTHORITY-S-CAPACITY EXIT
    THEN
    R> DROP STREAMS-SOURCE-AUTHORITY-S-OK ;

: _SSA-CREATE-SEQUENCE  ( source-work -- status )
    >R
    R@ _SSA-MUTATION-CAPACITY DUP IF R> DROP EXIT THEN DROP
    R@ _SSAW.REPO-WORK @ STREAMS-REPOSITORY-AUTHORITY-ROOT@
    DUP SAR.SOURCE-COUNT @ PERSIST-MAX-SIGNED >= IF
        DROP R> DROP STREAMS-SOURCE-AUTHORITY-S-CAPACITY EXIT
    THEN
    SAR.MUTATION-SEQUENCE @ 1+
    DUP R@ _SSAW.SEQUENCE !
    R@ _SSAW.CREATION-SEQUENCE !
    R> DROP STREAMS-SOURCE-AUTHORITY-S-OK ;

