\ The repository callback must return the repository status domain.  Semantic
\ results travel through caller-owned RESULT so GONE/STALE/etc. can never be
\ mistaken for repository CAPACITY/IO values by WITH-OWNER.
: _SSA-OWNER-DISPATCH  ( source-work repository repo-work -- repo-status )
    2DROP >R
    R@ R@ _SSAW.OP-XT @ CATCH
    DUP IF
        DROP DROP STREAMS-SOURCE-AUTHORITY-S-FAULT
    ELSE
        DROP
    THEN
    R@ _SSA-RECOVER
    DUP R@ _SSAW.RESULT ! DROP
    R> DROP STREAMS-REPOSITORY-S-OK ;

: _SSA-INVOKE  ( operation-xt source-work -- status )
    >R
    DUP 0= IF
        DROP STREAMS-SOURCE-AUTHORITY-S-INVALID
        R@ _SSA-WORK-STATUS! R> DROP EXIT
    THEN
    R@ _SSAW.BUSY @ IF
        DROP STREAMS-SOURCE-AUTHORITY-S-BUSY
        R@ _SSA-WORK-STATUS! R> DROP EXIT
    THEN
    R@ _SSAW.OP-XT !
    STREAMS-SOURCE-AUTHORITY-S-INVALID R@ _SSAW.RESULT !
    -1 R@ _SSAW.BUSY !
    R@ ['] _SSA-OWNER-DISPATCH
    R@ _SSAW.REPOSITORY @ R@ _SSAW.REPO-WORK @
        STREAMS-REPOSITORY-WITH-OWNER
    DUP STREAMS-REPOSITORY-S-OK = IF
        DROP R@ _SSAW.RESULT @
    ELSE
        _SSA-REPOSITORY>STATUS
    THEN
    DUP R@ _SSAW.STATUS !
    0 R@ _SSAW.BUSY !
    0 R@ _SSAW.OP-XT !
    R> DROP ;

