: STREAMS-SOURCE-AUTHORITY-WORK-VALID?  ( work -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-SOURCE-AUTHORITY-WORK-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SSAW.MAGIC @ _SSA-WORK-MAGIC <> IF DROP 0 EXIT THEN
    DUP _SSAW.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _SSAW.STATUS @ _SSA-STATUS? 0= IF DROP 0 EXIT THEN
    _SSAW.BUSY @ DUP 0= SWAP -1 = OR ;

: STREAMS-SOURCE-AUTHORITY-WORK-INIT  ( work -- status )
    DUP 0= IF DROP STREAMS-SOURCE-AUTHORITY-S-INVALID EXIT THEN
    DUP STREAMS-SOURCE-AUTHORITY-WORK-SIZE
        MSPAN-NONWRAPPING? 0= IF
        DROP STREAMS-SOURCE-AUTHORITY-S-INVALID EXIT
    THEN
    DUP STREAMS-SOURCE-AUTHORITY-WORK-SIZE 0 FILL
    _SSA-WORK-MAGIC OVER _SSAW.MAGIC !
    DUP OVER _SSAW.SELF !
    STREAMS-SOURCE-AUTHORITY-S-OK OVER _SSAW.STATUS !
    DROP STREAMS-SOURCE-AUTHORITY-S-OK ;

