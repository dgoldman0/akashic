: _SOPREC-HEADER-CLASSIFY
  ( record-a record-u expected-kind expected-u -- status )
    >R
    1 PICK 0< IF
        _SOPREC-DROP3 R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    2 PICK 0= IF
        _SOPREC-DROP3 R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    2 PICK 2 PICK MSPAN-NONWRAPPING? 0= IF
        _SOPREC-DROP3 R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    1 PICK STREAMS-OPREC-HEADER-SIZE < IF
        _SOPREC-DROP3 R> DROP STREAMS-OPREC-S-CORRUPT EXIT
    THEN
    2 PICK SOPREC.MAGIC @ _SOPREC-MAGIC <> IF
        _SOPREC-DROP3 R> DROP STREAMS-OPREC-S-CORRUPT EXIT
    THEN
    2 PICK SOPREC.KIND @ OVER <> IF
        _SOPREC-DROP3 R> DROP STREAMS-OPREC-S-CORRUPT EXIT
    THEN
    2 PICK SOPREC.SIZE @ 2 PICK <> IF
        _SOPREC-DROP3 R> DROP STREAMS-OPREC-S-CORRUPT EXIT
    THEN
    2 PICK SOPREC.SHAPE @ DUP STREAMS-OPREC-SHAPE-CURRENT > IF
        DROP _SOPREC-DROP3 R> DROP STREAMS-OPREC-S-UNKNOWN EXIT
    THEN
    STREAMS-OPREC-SHAPE-CURRENT <> IF
        _SOPREC-DROP3 R> DROP STREAMS-OPREC-S-CORRUPT EXIT
    THEN
    1 PICK R@ <> IF
        _SOPREC-DROP3 R> DROP STREAMS-OPREC-S-CORRUPT EXIT
    THEN
    _SOPREC-DROP3 R> DROP STREAMS-OPREC-S-OK ;

: _SOPREC-INIT  ( kind exact-u record -- status )
    >R
    DUP STREAMS-OPREC-HEADER-SIZE < IF
        2DROP R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    R@ 0= IF 2DROP R> DROP STREAMS-OPREC-S-INVALID EXIT THEN
    R@ OVER MSPAN-NONWRAPPING? 0= IF
        2DROP R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    R@ OVER 0 FILL
    _SOPREC-MAGIC R@ SOPREC.MAGIC !
    STREAMS-OPREC-SHAPE-CURRENT R@ SOPREC.SHAPE !
    OVER R@ SOPREC.KIND !
    DUP R@ SOPREC.SIZE !
    2DROP R> DROP STREAMS-OPREC-S-OK ;

: _SOPREC-HASH-FEED  ( record exact-u -- )
    >R
    SHA3-256-BEGIN
    DUP _SOPR-SEAL SHA3-256-ADD
    DUP STREAMS-OPREC-HEADER-SIZE +
    R> STREAMS-OPREC-HEADER-SIZE -
    SHA3-256-ADD
    DROP ;

