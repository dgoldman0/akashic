        DUP SOPRECEIPT.DELIVERED-MS @ -1 <> IF DROP 0 EXIT THEN
    THEN
    DUP SOPRECEIPT.ACKNOWLEDGEMENT-ID RID-PRESENT?
    OVER SOPRECEIPT.DELIVERY-ID RID-PRESENT? OR 0= IF
        DROP 0 EXIT
    THEN
    DUP SOPRECEIPT.ACKNOWLEDGED-MS @ -1 <>
    OVER SOPRECEIPT.DELIVERED-MS @ -1 <> AND IF
        DUP SOPRECEIPT.DELIVERED-MS @
        OVER SOPRECEIPT.ACKNOWLEDGED-MS @ < IF DROP 0 EXIT THEN
    THEN
    DROP -1 ;

