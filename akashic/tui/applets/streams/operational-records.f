: STREAMS-OPROOT-TEMPLATE-INIT
  ( authority-rid item-limit byte-limit terminal-limit terminal-age root -- status )
    >R
    R@ 0= IF 2DROP 2DROP DROP R> DROP
        STREAMS-OPREC-S-INVALID EXIT THEN
    R@ STREAMS-OPROOT-SIZE MSPAN-NONWRAPPING? 0= IF
        2DROP 2DROP DROP R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    4 PICK RID-SIZE MSPAN-NONWRAPPING? 0= IF
        2DROP 2DROP DROP R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    4 PICK RID-PRESENT? 0= IF
        2DROP 2DROP DROP R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    4 PICK RID-SIZE R@ STREAMS-OPROOT-SIZE MSPAN-OVERLAP? IF
        2DROP 2DROP DROP R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    3 PICK 0> 0= 3 PICK 0> 0= OR IF
        2DROP 2DROP DROP R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    1 PICK 0> 0= IF
        2DROP 2DROP DROP R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    1 PICK 4 PICK > IF
        2DROP 2DROP DROP R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    DUP _SOPREC-NONNEG? 0= IF
        2DROP 2DROP DROP R> DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    R@ STREAMS-OPROOT-SIZE 0 FILL
    _SOPROOT-MAGIC R@ SOPROOT.MAGIC !
    STREAMS-OPREC-SHAPE-CURRENT R@ SOPROOT.SHAPE !
    STREAMS-OPROOT-SIZE R@ SOPROOT.SIZE !
    4 PICK R@ SOPROOT.AUTHORITY-ID RID-COPY
    3 PICK R@ SOPROOT.ITEM-LIMIT !
    2 PICK R@ SOPROOT.PAYLOAD-BYTE-LIMIT !
    1 PICK R@ SOPROOT.TERMINAL-LIMIT !
    DUP R@ SOPROOT.TERMINAL-AGE-MS !
    1 R@ SOPROOT.NEXT-ACCEPTED-SEQUENCE !
    1 R@ SOPROOT.NEXT-READY-SEQUENCE !
    R@ SOPROOT.RECLAIM-STATE RECLAIM-STATE-SIZE RECLAIM-STATE-INIT
    DUP IF
        DROP 2DROP 2DROP DROP R> DROP
        STREAMS-OPREC-S-CORRUPT EXIT
    THEN
    DROP
    2DROP 2DROP DROP R> DROP STREAMS-OPREC-S-OK ;

: STREAMS-OPROOT-SEAL  ( root -- status )
    DUP 0= IF DROP STREAMS-OPREC-S-INVALID EXIT THEN
    DUP STREAMS-OPROOT-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    DUP SOPROOT.SEAL SHA3-256-LEN 0 FILL
    DUP _SOPROOT-SHAPE? 0= IF
        DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    DUP _SOPROOT-HASH-FEED
    DUP SOPROOT.SEAL SHA3-256-END
    DUP STREAMS-OPROOT-STRUCTURE-VALID? IF
        DROP STREAMS-OPREC-S-OK
    ELSE
        DUP SOPROOT.SEAL SHA3-256-LEN 0 FILL
        DROP STREAMS-OPREC-S-CORRUPT
    THEN ;

: STREAMS-OPROOT-COPY  ( source destination -- status )
    OVER STREAMS-OPROOT-STRUCTURE-VALID? 0= IF
        2DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    DUP 0= IF 2DROP STREAMS-OPREC-S-INVALID EXIT THEN
    DUP STREAMS-OPROOT-SIZE MSPAN-NONWRAPPING? 0= IF
        2DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    2DUP STREAMS-OPROOT-SIZE SWAP STREAMS-OPROOT-SIZE
        MSPAN-OVERLAP? IF
        2DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    STREAMS-OPROOT-SIZE MOVE STREAMS-OPREC-S-OK ;

\ The template deliberately leaves logical generation and all eight physical
\ roots unset.  The operational adapter must bind those fields, reconcile
\ their complete authority, and only then seal the current root.
\
\ The complete root must fit one neutral application-root page.  The adapter
\ separately rejects a configured segment payload smaller than OPATT-SIZE;
\ PBLOB chunk geometry does not establish the segment-record ceiling.
: _SOPREC-GEOMETRY-ABORT  ( -- )
    ." Streams operational record geometry mismatch" CR ABORT ;

STREAMS-OPROOT-SIZE PERSIST-PAGE-PAYLOAD-SIZE <> [IF]
    _SOPREC-GEOMETRY-ABORT
[THEN]

1 CELLS 8 <> [IF]
    _SOPREC-GEOMETRY-ABORT
[THEN]

RID-SIZE 32 <> [IF]
    _SOPREC-GEOMETRY-ABORT
[THEN]

SHA3-256-LEN 32 <> [IF]
    _SOPREC-GEOMETRY-ABORT
[THEN]

PBLOB-SIZE 72 <> [IF]
    _SOPREC-GEOMETRY-ABORT
[THEN]

PERSIST-REF-SIZE 24 <> [IF]
    _SOPREC-GEOMETRY-ABORT
[THEN]

STREAMS-OPRECEIPT-SIZE 512 <> [IF]
    _SOPREC-GEOMETRY-ABORT
[THEN]
