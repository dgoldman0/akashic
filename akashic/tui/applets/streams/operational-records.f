        DUP SOPRECEIPT.ACKNOWLEDGED-MS @ _SOPREC-NONNEG? 0=
            IF DROP 0 EXIT THEN
    ELSE
        DUP SOPRECEIPT.ACKNOWLEDGEMENT-ID RID-ZERO? 0=
            IF DROP 0 EXIT THEN
        DUP SOPRECEIPT.ACKNOWLEDGED-MS @ -1 <> IF DROP 0 EXIT THEN
    THEN
    DUP SOPRECEIPT.DELIVERY-ID RID-PRESENT? IF
        DUP SOPRECEIPT.DELIVERED-MS @ _SOPREC-NONNEG? 0=
