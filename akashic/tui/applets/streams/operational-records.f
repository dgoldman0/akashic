\ =====================================================================
\ operational-records.f - Current pointer-free Streams outbox authority
\ =====================================================================
\ This module owns the semantic bytes for the first SR3 egress outbox.
\ It performs no I/O, selects no path, starts no transaction, and retains
\ no runtime address.  Exact payload and receipt bytes are named by neutral
\ PBLOB descriptors; the enclosing adapter publishes these values through
\ one PSTORE transaction and validates every embedded PBTREE root against
\ its bound tree descriptor before exposing authority.
\
\ There is one prerelease shape.  A greater, otherwise well-formed shape
\ is UNKNOWN; a lower or malformed shape is CORRUPT.  A shape change
\ replaces this module and its fixtures directly.  There are no alternate
\ readers, selectors, migrations, or raw runtime descriptor encodings.
\ =====================================================================

