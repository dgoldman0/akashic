    >R
    STREAMS-OPREC-KIND-ATTEMPT STREAMS-OPATT-SIZE R@
        _SOPREC-INIT DUP IF R> DROP EXIT THEN DROP
    STREAMS-OPATT-DIRECTION-EGRESS R@ SOPATT.DIRECTION !
    STREAMS-OPATT-STATE-ACCEPTED R@ SOPATT.STATE !
    STREAMS-OPATT-EFFECT-NOT-APPLIED R@ SOPATT.EFFECT !
    STREAMS-OPATT-IDEMPOTENCY-NONE R@ SOPATT.IDEMPOTENCY-POLICY !
    STREAMS-OPATT-RECEIPT-NONE R@ SOPATT.RECEIPT-POLICY !
    -1 R@ SOPATT.STARTED-MS !
    -1 R@ SOPATT.FINISHED-MS !
    R> DROP STREAMS-OPREC-S-OK ;

: STREAMS-OPATT-SEAL  ( attempt -- status )
    DUP 0= IF DROP STREAMS-OPREC-S-INVALID EXIT THEN
    DUP STREAMS-OPATT-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    DUP SOPREC.SEAL SHA3-256-LEN 0 FILL
    DUP _SOPATT-SHAPE? 0= IF
        DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    DUP STREAMS-OPATT-SIZE _SOPREC-HASH-FEED
    DUP SOPREC.SEAL SHA3-256-END
    DUP STREAMS-OPATT-SIZE STREAMS-OPATT-VALID? IF
        DROP STREAMS-OPREC-S-OK
    ELSE
        DUP SOPREC.SEAL SHA3-256-LEN 0 FILL
        DROP STREAMS-OPREC-S-CORRUPT
    THEN ;

: STREAMS-OPATT-COPY  ( source destination -- status )
    OVER STREAMS-OPATT-SIZE STREAMS-OPATT-VALID? 0= IF
        2DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    DUP 0= IF 2DROP STREAMS-OPREC-S-INVALID EXIT THEN
    DUP STREAMS-OPATT-SIZE MSPAN-NONWRAPPING? 0= IF
        2DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    2DUP STREAMS-OPATT-SIZE SWAP STREAMS-OPATT-SIZE
        MSPAN-OVERLAP? IF
        2DROP STREAMS-OPREC-S-INVALID EXIT
    THEN
    STREAMS-OPATT-SIZE MOVE STREAMS-OPREC-S-OK ;

