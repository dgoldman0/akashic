: _SOPATT-STATE?  ( state -- flag )
    DUP STREAMS-OPATT-STATE-ACCEPTED >=
    SWAP STREAMS-OPATT-STATE-INDETERMINATE <= AND ;

: _SOPATT-EFFECT?  ( effect -- flag )
    DUP STREAMS-OPATT-EFFECT-NOT-APPLIED >=
    SWAP STREAMS-OPATT-EFFECT-UNCERTAIN <= AND ;

: _SOPATT-IDEMPOTENCY?  ( policy -- flag )
    DUP STREAMS-OPATT-IDEMPOTENCY-NONE =
    SWAP STREAMS-OPATT-IDEMPOTENCY-EXACT = OR ;

: _SOPATT-RECEIPT-POLICY?  ( attempt -- flag )
    DUP SOPATT.RECEIPT-POLICY @
    DUP STREAMS-OPATT-RECEIPT-NONE = IF
        DROP SOPATT.RECEIPT-BYTE-LIMIT @ 0= EXIT
    THEN
    STREAMS-OPATT-RECEIPT-BOUNDED <> IF
        DROP 0 EXIT
    THEN
    SOPATT.RECEIPT-BYTE-LIMIT @ 0> ;

: _SOPATT-STATE-EFFECT?  ( state effect -- flag )
    >R
    DUP STREAMS-OPATT-STATE-ACCEPTED = IF
        DROP
        R> DUP STREAMS-OPATT-EFFECT-NOT-APPLIED =
        SWAP STREAMS-OPATT-EFFECT-UNCERTAIN = OR EXIT
    THEN
    DUP STREAMS-OPATT-STATE-ACTIVE = IF
        DROP R> STREAMS-OPATT-EFFECT-UNCERTAIN = EXIT
    THEN
    DUP STREAMS-OPATT-STATE-ACKNOWLEDGED =
    OVER STREAMS-OPATT-STATE-DELIVERED = OR
    OVER STREAMS-OPATT-STATE-FAILED-AFTER = OR IF
        DROP R> STREAMS-OPATT-EFFECT-APPLIED = EXIT
    THEN
    DUP STREAMS-OPATT-STATE-FAILED-BEFORE =
    OVER STREAMS-OPATT-STATE-STALE = OR IF
        DROP R> STREAMS-OPATT-EFFECT-NOT-APPLIED = EXIT
    THEN
    DUP STREAMS-OPATT-STATE-CANCELLED = IF
        DROP R> _SOPATT-EFFECT? EXIT
    THEN
    STREAMS-OPATT-STATE-INDETERMINATE =
    R> STREAMS-OPATT-EFFECT-UNCERTAIN = AND ;

: STREAMS-OPATT-TERMINAL-STATE-EFFECT?
  ( state effect -- flag )
    2DUP _SOPATT-STATE-EFFECT? 0= IF 2DROP 0 EXIT THEN
    DROP
    DUP STREAMS-OPATT-STATE-ACCEPTED =
    OVER STREAMS-OPATT-STATE-ACTIVE = OR
    SWAP STREAMS-OPATT-STATE-STALE = OR 0= ;

: _SOPATT-ACCEPTED-RETRY?  ( attempt -- flag )
    DUP SOPATT.STATE @ STREAMS-OPATT-STATE-ACCEPTED <> IF
        DROP -1 EXIT
    THEN
    DUP SOPATT.RETRY-COUNT @ 0= IF
        DUP SOPATT.DISPATCH-COUNT @ 0=
        SWAP SOPATT.EFFECT @
            STREAMS-OPATT-EFFECT-NOT-APPLIED = AND EXIT
    THEN
    DUP SOPATT.IDEMPOTENCY-POLICY @
        STREAMS-OPATT-IDEMPOTENCY-EXACT <> IF DROP 0 EXIT THEN
    DUP SOPATT.RETRY-COUNT @
        OVER SOPATT.DISPATCH-COUNT @ <> IF DROP 0 EXIT THEN
    SOPATT.EFFECT @
    DUP STREAMS-OPATT-EFFECT-NOT-APPLIED =
    SWAP STREAMS-OPATT-EFFECT-UNCERTAIN = OR ;

: _SOPATT-RECEIPT?  ( attempt -- flag )
    DUP SOPATT.FLAGS @ STREAMS-OPATT-F-RECEIPT-PRESENT AND 0= IF
        DUP SOPATT.RECEIPT-ID RID-ZERO?
        SWAP SOPATT.RECEIPT-REF PERSIST-REF-SIZE _SOPREC-ZERO? AND EXIT
    THEN
    DUP SOPATT.RECEIPT-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    SOPATT.RECEIPT-REF PERSIST-REF-VALID? ;

: _SOPATT-DISPATCH?  ( attempt -- flag )
    DUP SOPATT.READY-SEQUENCE @ 0> 0= IF DROP 0 EXIT THEN
    DUP SOPATT.DISPATCH-COUNT @ _SOPREC-NONNEG? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.RETRY-COUNT @ _SOPREC-NONNEG? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.RETRY-COUNT @ OVER SOPATT.DISPATCH-COUNT @ >
        IF DROP 0 EXIT THEN
    DUP SOPATT.STARTED-MS @ -1 <>
    OVER SOPATT.DISPATCH-COUNT @ 0= AND IF DROP 0 EXIT THEN
    DROP -1 ;

: _SOPATT-TIMES?  ( attempt -- flag )
    DUP SOPATT.RECEIVED-MS @ 0< IF DROP 0 EXIT THEN
    DUP SOPATT.ACCEPTED-MS @ DUP 0< IF 2DROP 0 EXIT THEN
    DUP 2 PICK SOPATT.RECEIVED-MS @ < IF 2DROP 0 EXIT THEN
    DROP
    DUP SOPATT.STARTED-MS @ DUP -1 < IF 2DROP 0 EXIT THEN
    DUP -1 <> IF
        DUP 2 PICK SOPATT.ACCEPTED-MS @ < IF 2DROP 0 EXIT THEN
    THEN
    DROP
    DUP SOPATT.FINISHED-MS @ DUP -1 < IF 2DROP 0 EXIT THEN
    DUP -1 <> IF
        DUP 2 PICK SOPATT.ACCEPTED-MS @ < IF 2DROP 0 EXIT THEN
    THEN
    DROP
    DUP SOPATT.STARTED-MS @ -1 <>
    OVER SOPATT.FINISHED-MS @ -1 <> AND IF
        DUP SOPATT.FINISHED-MS @
        OVER SOPATT.STARTED-MS @ < IF DROP 0 EXIT THEN
    THEN
    DUP SOPATT.STATE @ STREAMS-OPATT-STATE-ACCEPTED = IF
        DUP SOPATT.STARTED-MS @ -1 =
        SWAP SOPATT.FINISHED-MS @ -1 = AND EXIT
    THEN
    DUP SOPATT.STATE @ STREAMS-OPATT-STATE-ACTIVE = IF
        DUP SOPATT.STARTED-MS @ 0>=
        SWAP SOPATT.FINISHED-MS @ -1 = AND EXIT
    THEN
    DUP SOPATT.STATE @ STREAMS-OPATT-STATE-ACKNOWLEDGED =
    OVER SOPATT.STATE @ STREAMS-OPATT-STATE-DELIVERED = OR
    OVER SOPATT.STATE @ STREAMS-OPATT-STATE-FAILED-AFTER = OR
    OVER SOPATT.STATE @ STREAMS-OPATT-STATE-INDETERMINATE = OR IF
        DUP SOPATT.STARTED-MS @ 0>=
        SWAP SOPATT.FINISHED-MS @ 0>= AND EXIT
    THEN
    DUP SOPATT.STATE @ STREAMS-OPATT-STATE-CANCELLED =
    OVER SOPATT.EFFECT @ STREAMS-OPATT-EFFECT-NOT-APPLIED <> AND IF
        DUP SOPATT.STARTED-MS @ 0>=
        SWAP SOPATT.FINISHED-MS @ 0>= AND EXIT
    THEN
    SOPATT.FINISHED-MS @ 0>= ;

: _SOPATT-RECEIPT-STATE?  ( attempt -- flag )
    DUP SOPATT.FLAGS @ STREAMS-OPATT-F-RECEIPT-PRESENT AND IF
        DUP SOPATT.STATE @ STREAMS-OPATT-STATE-ACKNOWLEDGED =
            IF DROP -1 EXIT THEN
        DUP SOPATT.STATE @ STREAMS-OPATT-STATE-DELIVERED =
            IF DROP -1 EXIT THEN
        DUP SOPATT.STATE @ STREAMS-OPATT-STATE-FAILED-AFTER =
            IF DROP -1 EXIT THEN
        DUP SOPATT.STATE @ STREAMS-OPATT-STATE-CANCELLED <>
            IF DROP 0 EXIT THEN
        SOPATT.EFFECT @ STREAMS-OPATT-EFFECT-APPLIED = EXIT
    THEN
    DUP SOPATT.STATE @ STREAMS-OPATT-STATE-ACKNOWLEDGED <>
    OVER SOPATT.STATE @ STREAMS-OPATT-STATE-DELIVERED <> AND
    SWAP SOPATT.STATE @ STREAMS-OPATT-STATE-FAILED-AFTER <> AND ;

: _SOPATT-SHAPE?  ( attempt -- flag )
    DUP STREAMS-OPATT-SIZE STREAMS-OPATT-HEADER-CLASSIFY
        STREAMS-OPREC-S-OK <> IF DROP 0 EXIT THEN
    DUP SOPATT.ATTEMPT-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.EVENT-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.CONNECTOR-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.FLOW-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.CORRELATION-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.IDEMPOTENCY-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.ORIGIN-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.DESTINATION-ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.REQUEST-SEAL RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.ENDPOINT-SEAL RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.PAYLOAD-DIGEST RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.CONNECTOR-REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP SOPATT.FLOW-REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP SOPATT.RECORD-REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP SOPATT.ACCEPTED-SEQUENCE @ 0> 0= IF DROP 0 EXIT THEN
    DUP SOPATT.DIRECTION @ STREAMS-OPATT-DIRECTION-EGRESS <>
        IF DROP 0 EXIT THEN
    DUP SOPATT.PROTOCOL @ 0> 0= IF DROP 0 EXIT THEN
    DUP SOPATT.PROFILE @ 0> 0= IF DROP 0 EXIT THEN
    DUP SOPATT.MEDIA @ 0> 0= IF DROP 0 EXIT THEN
    DUP SOPATT.STATE @ _SOPATT-STATE? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.EFFECT @ _SOPATT-EFFECT? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.STATE @ OVER SOPATT.EFFECT @
        _SOPATT-STATE-EFFECT? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.IDEMPOTENCY-POLICY @ _SOPATT-IDEMPOTENCY?
        0= IF DROP 0 EXIT THEN
    DUP _SOPATT-ACCEPTED-RETRY? 0= IF DROP 0 EXIT THEN
    DUP _SOPATT-RECEIPT-POLICY? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.FLAGS @ DUP 0=
    SWAP STREAMS-OPATT-F-RECEIPT-PRESENT = OR 0= IF
        DROP 0 EXIT
    THEN
    DUP SOPATT.REASON @ _SOPREC-NONNEG? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.DETAIL @ _SOPREC-NONNEG? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.ERROR @ _SOPREC-NONNEG? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.CLEANUP-ERROR @ _SOPREC-NONNEG? 0=
        IF DROP 0 EXIT THEN
    DUP SOPATT.PAYLOAD-U @ DUP _SOPREC-NONNEG? 0= IF
        2DROP 0 EXIT
    THEN
    DROP
    DUP SOPATT.PAYLOAD-BLOB PBLOB-VALID? 0= IF DROP 0 EXIT THEN
    DUP SOPATT.PAYLOAD-BLOB PBLOB-TOTAL@
        OVER SOPATT.PAYLOAD-U @ <> IF DROP 0 EXIT THEN
    DUP _SOPATT-DISPATCH? 0= IF DROP 0 EXIT THEN
    DUP _SOPATT-RECEIPT? 0= IF DROP 0 EXIT THEN
    DUP _SOPATT-RECEIPT-STATE? 0= IF DROP 0 EXIT THEN
    DUP _SOPATT-TIMES? 0= IF DROP 0 EXIT THEN
    SOPATT.RESERVED STREAMS-OPATT-SIZE _SOPA-RESERVED -
        _SOPREC-ZERO? ;

: _SOPATT-SEAL-MATCHES?  ( attempt -- flag )
    DUP SOPREC.SEAL RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP STREAMS-OPATT-SIZE _SOPREC-HASH-FEED
    SOPREC.SEAL SHA3-256-END-COMPARE ;

: STREAMS-OPATT-VALID?  ( attempt-a attempt-u -- flag )
    DUP STREAMS-OPATT-SIZE <> IF 2DROP 0 EXIT THEN
    DROP
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-OPATT-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SOPATT-SHAPE? 0= IF DROP 0 EXIT THEN
    _SOPATT-SEAL-MATCHES? ;

