: _SOPREC-ZERO?  ( address length -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    0 ?DO
        DUP I + C@ IF DROP 0 UNLOOP EXIT THEN
    LOOP
    DROP -1 ;

: _SOPREC-NONZERO?  ( address length -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    0 ?DO
        DUP I + C@ IF DROP -1 UNLOOP EXIT THEN
    LOOP
    DROP 0 ;

: _SOPREC-NONNEG?  ( value -- flag )
    DUP 0>= SWAP _SOPREC-MAX-SIGNED <= AND ;

: _SOPREC-NONNEG-ADD?  ( left right -- sum flag )
    2DUP _SOPREC-NONNEG? SWAP _SOPREC-NONNEG? AND 0= IF
        2DROP 0 0 EXIT
    THEN
    + DUP _SOPREC-NONNEG? ;

: _SOPREC-DROP3  ( x1 x2 x3 -- ) 2DROP DROP ;

