: _SHTTP-SET-FAILURE  ( route-status flow-status operation -- )
    >R
    R@ _SHTTP-PRIMARY-FAILURE? IF
        2DROP
    ELSE
        DUP R@ _SHTO.FLOW-STATUS !
        SWAP R@ _SHTO.STATUS ! DROP
    THEN
    _SHTTP-OP-STATE-FAILED R@ _SHTO.STATE !
    R> DROP ;

: _SHTTP-MARK-CANCELLED  ( operation -- )
    DUP _SHTTP-PRIMARY-FAILURE? IF DROP EXIT THEN
    STREAMS-HTTP-ROUTE-S-CANCELLED SWAP _SHTO.STATUS ! ;

: _SHTTP-CANCEL-STATUS-ERROR?  ( status -- flag )
    DUP STREAMS-FLOW-S-OK =
    OVER STREAMS-FLOW-S-BUSY = OR
    OVER STREAMS-FLOW-S-NO-WORK = OR
    OVER STREAMS-FLOW-S-PENDING = OR
    OVER STREAMS-FLOW-S-ACKNOWLEDGED = OR
    OVER STREAMS-FLOW-S-DELIVERED = OR
    OVER STREAMS-FLOW-S-CANCELLED = OR
    SWAP DROP 0= ;

: _SHTTP-CANCEL-FLOW-STATUS!  ( flow-status operation -- flow-status )
    >R
    R@ _SHTO.STATUS @
    DUP STREAMS-HTTP-ROUTE-S-OK =
    OVER STREAMS-HTTP-ROUTE-S-PENDING = OR
    SWAP STREAMS-HTTP-ROUTE-S-CANCELLED = OR IF
        DUP R@ _SHTO.FLOW-STATUS !
    THEN
    DUP _SHTTP-CANCEL-STATUS-ERROR? IF
        DUP R@ _SHTTP-FIRST-CLEANUP!
    THEN
    R> DROP ;

: _SHTTP-RELEASE-IDLE  ( operation -- status )
    >R
    _SHTTP-OP-F-ACQUIRED R@ _SHTO-FLAG? 0= IF
        R> DROP STREAMS-FLOW-S-OK EXIT
    THEN
    _SHTTP-OP-F-RELEASED R@ _SHTO-FLAG? IF
        R> DROP STREAMS-FLOW-S-OK EXIT
    THEN
    R@ _SHTO.FLOW @ SFLOW.STATE @ STREAMS-FLOW-STATE-IDLE <> IF
        R> DROP STREAMS-FLOW-S-BUSY EXIT
    THEN
    R@ _SHTO.FLOW @ R@ _SHTO.LEASE @
    R@ _SHTO.CONFIG @ _SHTC.POOL @
        STREAMS-EXECUTION-POOL-RELEASE
    DUP STREAMS-FLOW-S-OK = IF
        _SHTTP-OP-F-RELEASED R@ _SHTO-FLAG+
    THEN
    R> DROP ;

: _SHTTP-ABORT-RECEIVING  ( operation -- status )
    >R
    R@ _SHTO.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-RECEIVING <> IF
        R> DROP STREAMS-FLOW-S-NO-WORK EXIT
    THEN
    R@ _SHTO.GENERATION @
    R@ _SHTO.NOW @ 0 MAX
    R@ _SHTO.FLOW @ STREAMS-FLOW-INGRESS-ABORT
    R@ _SHTTP-CANCEL-FLOW-STATUS!
    R@ _SHTO.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-RECEIVING <> IF
        _SHTTP-OP-F-INGRESS-OPEN R@ _SHTO-FLAG-
    THEN
    R> DROP ;

: _SHTTP-RESPONSE-FAIL!  ( detail operation -- )
    >R
    STREAMS-HTTP-ROUTE-S-RESPONSE SWAP
    R@ _SHTTP-PRIMARY-OR-CLEANUP!
    _SHTTP-OP-STATE-FAILED R@ _SHTO.STATE !
    R> DROP ;

: _SHTTP-SEAL-EMPTY-RESPONSE  ( http-status operation -- outcome )
    >R
    DUP R@ _SHTO.T0 !
    DROP
    R@ _SHTO.EXCHANGE @ HCONN-BODY-DISCARD
    DUP HCONN-S-PENDING <> IF
        R@ _SHTTP-RESPONSE-FAIL!
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    DROP
    R@ _SHTO.EXCHANGE @ HCONN-RESPONSE@ DUP 0= IF
        DROP
        HRESP-S-INVALID R@ _SHTTP-RESPONSE-FAIL!
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    R@ _SHTO.T2 !
    R@ _SHTO.T0 @ R@ _SHTO.T2 @ HRESP-BEGIN
    DUP HRESP-S-OK <> IF
        R@ _SHTTP-RESPONSE-FAIL!
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    DROP
    0 0 0 R@ _SHTO.T2 @ HRESP-BODY-SOURCE
    DUP HRESP-S-OK <> IF
        R@ _SHTTP-RESPONSE-FAIL!
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    DROP
    R@ _SHTO.T2 @ HRESP-SEAL
    DUP HRESP-S-OK <> IF
        R@ _SHTTP-RESPONSE-FAIL!
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    DROP
    0 R@ _SHTO.T0 !
    0 R@ _SHTO.T2 !
    _SHTTP-OP-F-RESPONSE-SEALED R@ _SHTO-FLAG+
    _SHTTP-OP-STATE-RESPONSE R@ _SHTO.STATE !
    R> DROP HROUTE-OUTCOME-RESPONSE ;

: _SHTTP-ACQUIRE-HTTP-STATUS  ( route-status -- http-status )
    DUP STREAMS-HTTP-ROUTE-S-REQUEST-CAPACITY = IF DROP 413 EXIT THEN
    DUP STREAMS-HTTP-ROUTE-S-POOL-FULL =
    OVER STREAMS-HTTP-ROUTE-S-NO-FIT = OR
    OVER STREAMS-HTTP-ROUTE-S-RESPONSE-CAPACITY = OR
    OVER STREAMS-HTTP-ROUTE-S-POOL-BUSY = OR
    SWAP STREAMS-HTTP-ROUTE-S-LEASE-CAPACITY = OR IF
        503
    ELSE
        500
    THEN ;

: _SHTTP-U-DIGITS  ( unsigned -- digits )
    1 SWAP
    BEGIN
        DUP 10 >=
    WHILE
        10 / SWAP 1+ SWAP
    REPEAT
    DROP ;

: _SHTTP-SUCCESS-RESPONSE-FITS?  ( operation -- flag )
    >R
    R@ _SHTO.EXCHANGE @ HCONN-RESPONSE@ DUP 0= IF
        DROP R> DROP 0 EXIT
    THEN
    HRESP-HEADER-CAPACITY@
    R@ _SHTO.CONFIG @ _SHTC.MAX-EGRESS @ _SHTTP-U-DIGITS
    _SHTTP-SUCCESS-HEADER-FIXED + >=
    R> DROP ;

: _SHTTP-ACQUIRE-FAIL  ( route-status flow-status operation -- outcome )
    >R
    OVER R@ _SHTO.STATUS !
    DUP R@ _SHTO.FLOW-STATUS !
    2DROP
    R@ _SHTO.STATUS @ _SHTTP-ACQUIRE-HTTP-STATUS
    R> _SHTTP-SEAL-EMPTY-RESPONSE ;

: _SHTTP-FAIL-EMPTY  ( route-status flow-status http-status operation -- outcome )
    >R
    DUP R@ _SHTO.T0 !
    DROP
    DUP R@ _SHTO.T1 !
    R@ _SHTTP-SET-FAILURE
    _SHTTP-OP-F-ACQUIRED R@ _SHTO-FLAG? IF
        R@ _SHTTP-ABORT-RECEIVING DROP
        R@ _SHTTP-RELEASE-IDLE
        DUP STREAMS-FLOW-S-OK <> IF
            DUP R@ _SHTTP-FIRST-CLEANUP!
        THEN
        DROP
    THEN
    R@ _SHTO.T1 @ R@ _SHTO.FLOW-STATUS !
    0 R@ _SHTO.T1 !
    R@ _SHTO.T0 @
    0 R@ _SHTO.T0 !
    R> _SHTTP-SEAL-EMPTY-RESPONSE ;

