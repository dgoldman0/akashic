: _SHTTP-BODY-INNER  ( request operation -- status )
    >R
    R@ _SHTO-HEADER? 0= IF DROP R> DROP -1 EXIT THEN
    R@ _SHTO.STATE @ _SHTTP-OP-STATE-RECEIVING <> IF
        DROP R> DROP -1 EXIT
    THEN
    _SHTTP-OP-F-INGRESS-OPEN R@ _SHTO-FLAG? 0= IF
        DROP R> DROP -1 EXIT
    THEN
    DUP R@ _SHTO.EXCHANGE @ HCONN-REQUEST@ <> IF
        DROP R> DROP -1 EXIT
    THEN
    WREQ-BODY-SLICE
    DUP R@ _SHTO.T0 !
    R@ _SHTTP-NOW STREAMS-HTTP-ROUTE-S-OK <> IF
        2DROP R> DROP -1 EXIT
    THEN
    2DUP MSPAN-NONWRAPPING? 0= IF
        2DROP
        STREAMS-HTTP-ROUTE-S-INGRESS
        STREAMS-FLOW-S-INVALID R@ _SHTTP-SET-FAILURE
        R> DROP -1 EXIT
    THEN
    R@ _SHTO.GENERATION @
    R@ _SHTO.NOW @
    R@ _SHTO.FLOW @ STREAMS-FLOW-INGRESS-APPEND
    DUP R@ _SHTO.FLOW-STATUS !
    STREAMS-FLOW-S-OK <> IF
        STREAMS-HTTP-ROUTE-S-INGRESS R@ _SHTO.STATUS !
        _SHTTP-OP-STATE-FAILED R@ _SHTO.STATE !
        R> DROP -1 EXIT
    THEN
    R@ _SHTO.T0 @ R@ _SHTO.RECEIVED-U +!
    R@ _SHTO.RECEIVED-U @ R@ _SHTO.DECLARED-U @ > IF
        STREAMS-HTTP-ROUTE-S-INGRESS R@ _SHTO.STATUS !
        STREAMS-FLOW-S-CAPACITY R@ _SHTO.FLOW-STATUS !
        _SHTTP-OP-STATE-FAILED R@ _SHTO.STATE !
        R> DROP -1 EXIT
    THEN
    0 R@ _SHTO.T0 !
    R> DROP 0 ;

: STREAMS-HTTP-ROUTE-BODY  ( request operation -- status )
    DUP _SHTO-HEADER? 0= IF 2DROP -1 EXIT THEN
    _SHTTP-OP-F-CALLBACK-ACTIVE OVER _SHTO-FLAG? IF
        2DROP -1 EXIT
    THEN
    DUP >R
    _SHTTP-OP-F-CALLBACK-ACTIVE R@ _SHTO-FLAG+
    ['] _SHTTP-BODY-INNER CATCH
    _SHTTP-OP-F-CALLBACK-ACTIVE R@ _SHTO-FLAG-
    ?DUP IF
        DUP STREAMS-HTTP-ROUTE-S-INGRESS SWAP
        R@ _SHTTP-PRIMARY-OR-CLEANUP!
        2DROP DROP
        _SHTTP-OP-STATE-FAILED R@ _SHTO.STATE !
        R> DROP -1 EXIT
    THEN
    R> DROP ;

: _SHTTP-RESPONSE-READ-INNER
  ( offset destination requested operation -- count source-status )
    >R
    DUP R@ _SHTO.T0 !
    2 PICK R@ _SHTO.T1 !
    OVER R@ _SHTO.T2 !
    2DROP DROP
    R@ _SHTO-HEADER? 0= IF
        R> DROP 0 HRESP-SOURCE-S-STALE EXIT
    THEN
    R@ _SHTO.STATE @ _SHTTP-OP-STATE-RESPONSE <>
    _SHTTP-OP-F-RESPONSE-SEALED R@ _SHTO-FLAG? 0= OR IF
        R> DROP 0 HRESP-SOURCE-S-STALE EXIT
    THEN
    R@ _SHTO.STATUS @ STREAMS-HTTP-ROUTE-S-OK <> IF
        R> DROP 0 HRESP-SOURCE-S-FAILED EXIT
    THEN
    R@ _SHTO.T0 @ 0<
    R@ _SHTO.T1 @ 0< OR IF
        R> DROP 0 HRESP-SOURCE-S-FAILED EXIT
    THEN
    R@ _SHTO.T0 @ 0>
    R@ _SHTO.T2 @ 0= AND IF
        R> DROP 0 HRESP-SOURCE-S-FAILED EXIT
    THEN
    R@ _SHTO.EXCHANGE @ HCONN-RESPONSE@
        HRESP-SEND-ARENA
    R@ _SHTO.T0 @ SWAP > IF
        DROP R> DROP 0 HRESP-SOURCE-S-FAILED EXIT
    THEN
    R@ _SHTO.T2 @ <> IF
        R> DROP 0 HRESP-SOURCE-S-FAILED EXIT
    THEN
    R@ _SHTO.T1 @ R@ _SHTO.RESPONSE-U @ > IF
        R> DROP 0 HRESP-SOURCE-S-FAILED EXIT
    THEN
    R@ _SHTO.RESPONSE-U @ R@ _SHTO.T1 @ -
    R@ _SHTO.T0 @ < IF
        R> DROP 0 HRESP-SOURCE-S-FAILED EXIT
    THEN
    R@ _SHTO.FLOW @ DUP STREAMS-FLOW-VALID? 0= IF
        DROP R> DROP 0 HRESP-SOURCE-S-STALE EXIT
    THEN
    DUP SFLOW.STATE @ STREAMS-FLOW-STATE-TERMINAL <> IF
        DROP R> DROP 0 HRESP-SOURCE-S-STALE EXIT
    THEN
    DUP SFLOW.GENERATION @ R@ _SHTO.GENERATION @ <> IF
        DROP R> DROP 0 HRESP-SOURCE-S-STALE EXIT
    THEN
    SFLOW.EGRESS-CARRIER
    R@ _SHTO.PAYLOAD-GENERATION @
        OVER STREAMS-PAYLOAD-EXACT? 0= IF
        DROP R> DROP 0 HRESP-SOURCE-S-STALE EXIT
    THEN
    DROP
    R@ _SHTO.T1 @
    R@ _SHTO.T2 @
    R@ _SHTO.T0 @
    R@ _SHTO.PAYLOAD-GENERATION @
    R@ _SHTO.FLOW @ SFLOW.EGRESS-CARRIER
        STREAMS-PAYLOAD-READ
    DUP STREAMS-PAYLOAD-S-OK = IF
        DROP
        R@ _SHTO.T0 @
        0 R@ _SHTO.T0 !
        0 R@ _SHTO.T1 !
        0 R@ _SHTO.T2 !
        R> DROP HRESP-SOURCE-S-OK EXIT
    THEN
    DUP R@ _SHTO.FLOW-STATUS !
    STREAMS-HTTP-ROUTE-S-SOURCE R@ _SHTO.STATUS !
    STREAMS-PAYLOAD-S-STALE = IF
        R> DROP 0 HRESP-SOURCE-S-STALE
    ELSE
        R> DROP 0 HRESP-SOURCE-S-FAILED
    THEN ;

: STREAMS-HTTP-ROUTE-RESPONSE-READ
  ( offset destination requested operation -- count source-status )
    DUP _SHTO-HEADER? 0= IF
        2DROP 2DROP 0 HRESP-SOURCE-S-STALE EXIT
    THEN
    _SHTTP-OP-F-CALLBACK-ACTIVE OVER _SHTO-FLAG? IF
        2DROP 2DROP 0 HRESP-SOURCE-S-STALE EXIT
    THEN
    DUP >R
    _SHTTP-OP-F-CALLBACK-ACTIVE R@ _SHTO-FLAG+
    ['] _SHTTP-RESPONSE-READ-INNER CATCH
    _SHTTP-OP-F-CALLBACK-ACTIVE R@ _SHTO-FLAG-
    ?DUP IF
        DUP STREAMS-HTTP-ROUTE-S-SOURCE SWAP
        R@ _SHTTP-PRIMARY-OR-CLEANUP!
        2DROP 2DROP DROP
        _SHTTP-OP-STATE-FAILED R@ _SHTO.STATE !
        R> DROP 0 HRESP-SOURCE-S-FAILED EXIT
    THEN
    R> DROP ;

\ ---------------------------------------------------------------------
\ Success response and cooperative flow driving
\ ---------------------------------------------------------------------

: _SHTTP-SEAL-SUCCESS-RESPONSE  ( operation -- outcome )
    >R
    R@ _SHTO.FLOW @ DUP SFLOW.GENERATION @
        R@ _SHTO.GENERATION @ <> IF
        DROP
        STREAMS-HTTP-ROUTE-S-FLOW
        STREAMS-FLOW-S-STALE R@ _SHTTP-SET-FAILURE
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    SFLOW.EGRESS-CARRIER
    DUP SPAY.BYTE-U @ R@ _SHTO.RESPONSE-U !
    DUP SPAY.GENERATION @ DUP R@ _SHTO.PAYLOAD-GENERATION !
    SWAP STREAMS-PAYLOAD-EXACT? 0= IF
        STREAMS-HTTP-ROUTE-S-FLOW
        STREAMS-FLOW-S-INVALID R@ _SHTTP-SET-FAILURE
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    R@ _SHTO.EXCHANGE @ HCONN-RESPONSE@ DUP 0= IF
        DROP
        STREAMS-HTTP-ROUTE-S-RESPONSE
        HRESP-S-INVALID R@ _SHTTP-SET-FAILURE
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    R@ _SHTO.T2 !
    200 R@ _SHTO.T2 @ HRESP-BEGIN HRESP-S-OK <> IF
        STREAMS-HTTP-ROUTE-S-RESPONSE
        HRESP-S-STATE R@ _SHTTP-SET-FAILURE
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    S" application/json" R@ _SHTO.T2 @ HRESP-CONTENT-TYPE
        HRESP-S-OK <> IF
        STREAMS-HTTP-ROUTE-S-RESPONSE
        HRESP-S-CAPACITY R@ _SHTTP-SET-FAILURE
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    R@ _SHTO.RESPONSE-U @
    R@
    ['] STREAMS-HTTP-ROUTE-RESPONSE-READ
    R@ _SHTO.T2 @ HRESP-BODY-SOURCE HRESP-S-OK <> IF
        STREAMS-HTTP-ROUTE-S-RESPONSE
        HRESP-S-STATE R@ _SHTTP-SET-FAILURE
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    R@ _SHTO.T2 @ HRESP-SEAL HRESP-S-OK <> IF
        STREAMS-HTTP-ROUTE-S-RESPONSE
        HRESP-S-CAPACITY R@ _SHTTP-SET-FAILURE
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    0 R@ _SHTO.T2 !
    STREAMS-HTTP-ROUTE-S-OK R@ _SHTO.STATUS !
    _SHTTP-OP-F-RESPONSE-SEALED R@ _SHTO-FLAG+
    _SHTTP-OP-STATE-RESPONSE R@ _SHTO.STATE !
    R> DROP HROUTE-OUTCOME-RESPONSE ;

: _SHTTP-COMMIT  ( operation -- outcome )
    >R
    R@ _SHTO.RECEIVED-U @ R@ _SHTO.DECLARED-U @ <> IF
        STREAMS-HTTP-ROUTE-S-INGRESS
        STREAMS-FLOW-S-CAPACITY R@ _SHTTP-SET-FAILURE
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    R@ _SHTTP-NOW STREAMS-HTTP-ROUTE-S-OK <> IF
        _SHTTP-OP-STATE-FAILED R@ _SHTO.STATE !
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    R@ _SHTO.GENERATION @
    R@ _SHTO.NOW @
    R@ _SHTO.FLOW @ STREAMS-FLOW-INGRESS-COMMIT
    DUP R@ _SHTO.FLOW-STATUS !
    STREAMS-FLOW-S-OK <> IF
        STREAMS-HTTP-ROUTE-S-INGRESS R@ _SHTO.STATUS !
        _SHTTP-OP-STATE-FAILED R@ _SHTO.STATE !
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    _SHTTP-OP-F-INGRESS-OPEN R@ _SHTO-FLAG-
    _SHTTP-OP-F-COMMITTED R@ _SHTO-FLAG+
    _SHTTP-OP-STATE-RUNNING R@ _SHTO.STATE !
    R> DROP HROUTE-OUTCOME-PENDING ;

: _SHTTP-DRIVE-FLOW  ( operation -- outcome )
    >R
    R@ _SHTTP-NOW STREAMS-HTTP-ROUTE-S-OK <> IF
        _SHTTP-OP-STATE-FAILED R@ _SHTO.STATE !
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    R@ _SHTO.NOW @ R@ _SHTO.FLOW @ STREAMS-FLOW-STEP
    DUP R@ _SHTO.FLOW-STATUS !
    R@ _SHTO.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-TERMINAL = IF
        DUP STREAMS-FLOW-S-DELIVERED = IF
            DROP R> _SHTTP-SEAL-SUCCESS-RESPONSE EXIT
        THEN
        STREAMS-HTTP-ROUTE-S-FLOW SWAP
        R@ _SHTTP-SET-FAILURE
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    DUP STREAMS-FLOW-S-PENDING =
    OVER STREAMS-FLOW-S-ACKNOWLEDGED = OR
    SWAP STREAMS-FLOW-S-BUSY = OR IF
        R> DROP HROUTE-OUTCOME-PENDING EXIT
    THEN
    STREAMS-HTTP-ROUTE-S-FLOW
    R@ _SHTO.FLOW-STATUS @ R@ _SHTTP-SET-FAILURE
    R> DROP HROUTE-OUTCOME-FAILED ;

