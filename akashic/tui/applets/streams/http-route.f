: _SHTO-HEADER?  ( operation -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-HTTP-ROUTE-OPERATION-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SHTO.STATE @ DUP _SHTTP-OP-STATE-STARTING >=
        SWAP _SHTTP-OP-STATE-CLEANED <= AND 0= IF DROP 0 EXIT THEN
    DUP _SHTO.STATUS @ _SHTTP-ROUTE-STATUS? 0= IF DROP 0 EXIT THEN
    DUP _SHTO.FLAGS @ _SHTTP-OP-FLAGS-MASK INVERT AND IF
        DROP 0 EXIT
    THEN
    DUP _SHTO.CONFIG @ STREAMS-HTTP-ROUTE-CONFIG-VALID? 0= IF
        DROP 0 EXIT
    THEN
    DUP _SHTO.EXCHANGE @ HCONN-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SHTO.DECLARED-U @ 0< IF DROP 0 EXIT THEN
    DUP _SHTO.RECEIVED-U @ DUP 0<
    SWAP 2 PICK _SHTO.DECLARED-U @ > OR IF DROP 0 EXIT THEN
    DUP _SHTO.NOW @ -1 < IF DROP 0 EXIT THEN
    _SHTTP-OP-F-ACQUIRED OVER _SHTO-FLAG? IF
        DUP _SHTO.FLOW @ 0<>
        OVER _SHTO.LEASE @ 0> AND
        OVER _SHTO.GENERATION @ 0>= AND
        OVER _SHTO.PAYLOAD-GENERATION @ 0>= AND
        SWAP DROP EXIT
    THEN
    DUP _SHTO.FLOW @
    OVER _SHTO.LEASE @ OR
    OVER _SHTO.GENERATION @ OR
    OVER _SHTO.PAYLOAD-GENERATION @ OR 0=
    SWAP DROP ;

