: _SHTTP-ACQUIRE-STATUS  ( flow-status -- route-status )
    DUP STREAMS-FLOW-S-FULL = IF
        DROP STREAMS-HTTP-ROUTE-S-POOL-FULL EXIT
    THEN
    DUP STREAMS-FLOW-S-CAPACITY = IF
        DROP STREAMS-HTTP-ROUTE-S-NO-FIT EXIT
    THEN
    STREAMS-FLOW-S-BUSY = IF
        STREAMS-HTTP-ROUTE-S-POOL-BUSY
    ELSE
        STREAMS-HTTP-ROUTE-S-INVALID
    THEN ;

: _SHTTP-START-INNER  ( exchange operation config -- outcome )
    DROP SWAP DROP >R
    R@ _SHTO.EXCHANGE @ HCONN-REQUEST@ DUP 0= IF
        DROP
        STREAMS-HTTP-ROUTE-S-INVALID
        STREAMS-FLOW-S-INVALID R@ _SHTTP-SET-FAILURE
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    WREQ-CONTENT-LENGTH@ DUP R@ _SHTO.DECLARED-U !
    DUP R@ _SHTO.CONFIG @ _SHTC.MAX-INGRESS @ > IF
        DROP
        STREAMS-HTTP-ROUTE-S-REQUEST-CAPACITY
        STREAMS-FLOW-S-CAPACITY R@ _SHTTP-ACQUIRE-FAIL
        R> DROP EXIT
    THEN
    DROP
    R@ _SHTTP-SUCCESS-RESPONSE-FITS? 0= IF
        STREAMS-HTTP-ROUTE-S-RESPONSE-CAPACITY
        HRESP-S-CAPACITY R@ _SHTTP-ACQUIRE-FAIL
        R> DROP EXIT
    THEN
    R@ _SHTO.CONFIG @ DUP _SHTC.REQUIRED-EGRESS @
    SWAP _SHTC.MAX-EGRESS @ > IF
        STREAMS-HTTP-ROUTE-S-RESPONSE-CAPACITY
        STREAMS-FLOW-S-CAPACITY R@ _SHTTP-ACQUIRE-FAIL
        R> DROP EXIT
    THEN
    R@ _SHTO.CONFIG @ _SHTC.POOL @
        STREAMS-EXECUTION-POOL-LEASE-AVAILABLE? 0= IF
        STREAMS-HTTP-ROUTE-S-LEASE-CAPACITY
        STREAMS-FLOW-S-CAPACITY R@ _SHTTP-ACQUIRE-FAIL
        R> DROP EXIT
    THEN
    R@ _SHTO.DECLARED-U @
    R@ _SHTO.CONFIG @ DUP _SHTC.REQUIRED-EGRESS @
    SWAP _SHTC.POOL @
        STREAMS-EXECUTION-POOL-ACQUIRE
    DUP R@ _SHTO.FLOW-STATUS !
    DUP STREAMS-FLOW-S-OK <> IF
        DUP _SHTTP-ACQUIRE-STATUS R@ _SHTO.STATUS !
        2DROP DROP
        R@ _SHTO.STATUS @
        R@ _SHTO.FLOW-STATUS @
        R@ _SHTTP-ACQUIRE-FAIL
        R> DROP EXIT
    THEN
    DROP
    DUP R@ _SHTO.LEASE !
    OVER R@ _SHTO.FLOW !
    2DROP
    _SHTTP-OP-F-ACQUIRED R@ _SHTO-FLAG+
    R@ _SHTO.FLOW @ SFLOW.INPUT-CONNECTOR @
        R@ _SHTO.CONFIG @ _SHTC.INPUT-CONNECTOR @ <> IF
        STREAMS-HTTP-ROUTE-S-INVALID
        STREAMS-FLOW-S-INVALID 500 R@ _SHTTP-FAIL-EMPTY
        R> DROP EXIT
    THEN
    R@ _SHTO.EVENT STREAMS-EVENT-INIT
        STREAMS-FLOW-S-OK <> IF
        STREAMS-HTTP-ROUTE-S-METADATA
        STREAMS-FLOW-S-INVALID 500 R@ _SHTTP-FAIL-EMPTY
        R> DROP EXIT
    THEN
    R@ _SHTTP-NOW STREAMS-HTTP-ROUTE-S-OK <> IF
        R@ _SHTO.STATUS @
        R@ _SHTO.FLOW-STATUS @
        500 R@ _SHTTP-FAIL-EMPTY
        R> DROP EXIT
    THEN
    R@ _SHTTP-METADATA STREAMS-HTTP-ROUTE-S-OK <> IF
        R@ _SHTO.STATUS @
        R@ _SHTO.FLOW-STATUS @
        500 R@ _SHTTP-FAIL-EMPTY
        R> DROP EXIT
    THEN
    R@ _SHTO.CONFIG @ _SHTC.INPUT-CONNECTOR @
    R@ _SHTO.EVENT
    R@ _SHTO.DECLARED-U @
    R@ _SHTO.FLOW @ SFLOW.REVISION @
    R@ _SHTO.NOW @
    R@ _SHTO.FLOW @ STREAMS-FLOW-INGRESS-BEGIN
    DUP R@ _SHTO.FLOW-STATUS !
    DUP STREAMS-FLOW-S-OK <> IF
        SWAP DROP
        STREAMS-HTTP-ROUTE-S-INGRESS SWAP 500
        R@ _SHTTP-FAIL-EMPTY
        R> DROP EXIT
    THEN
    DROP
    R@ _SHTO.GENERATION !
    _SHTTP-OP-F-INGRESS-OPEN R@ _SHTO-FLAG+
    _SHTTP-OP-STATE-RECEIVING R@ _SHTO.STATE !
    R@ _SHTO.DECLARED-U @ 0= IF
        R> _SHTTP-COMMIT EXIT
    THEN
    ['] STREAMS-HTTP-ROUTE-BODY
    R@
    R@ _SHTO.EXCHANGE @ HCONN-BODY-ACCEPT
    HCONN-S-PENDING <> IF
        STREAMS-HTTP-ROUTE-S-INGRESS
        STREAMS-FLOW-S-INVALID 500 R@ _SHTTP-FAIL-EMPTY
        R> DROP EXIT
    THEN
    R> DROP HROUTE-OUTCOME-PENDING ;

: _SHTTP-POLL-CANCELLING  ( operation -- outcome )
    >R
    R@ _SHTO.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-TERMINAL = IF
        _SHTTP-OP-STATE-CANCELLED R@ _SHTO.STATE !
        R@ _SHTTP-MARK-CANCELLED
        R> DROP HROUTE-OUTCOME-CANCELLED EXIT
    THEN
    R@ _SHTTP-NOW STREAMS-HTTP-ROUTE-S-OK <> IF
        R@ _SHTO.FLOW @ SFLOW.LAST-NOW @ 0 MAX R@ _SHTO.NOW !
        R@ _SHTTP-MARK-CANCELLED
    THEN
    R@ _SHTO.NOW @ R@ _SHTO.FLOW @ STREAMS-FLOW-STEP
    R@ _SHTTP-CANCEL-FLOW-STATUS!
    R@ _SHTO.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-TERMINAL = IF
        DROP
        _SHTTP-OP-STATE-CANCELLED R@ _SHTO.STATE !
        R@ _SHTTP-MARK-CANCELLED
        R> DROP HROUTE-OUTCOME-CANCELLED EXIT
    THEN
    DUP STREAMS-FLOW-S-PENDING =
    SWAP STREAMS-FLOW-S-BUSY = OR IF
        R> DROP HROUTE-OUTCOME-PENDING EXIT
    THEN
    R@ _SHTTP-MARK-CANCELLED
    R> DROP HROUTE-OUTCOME-PENDING ;

: _SHTTP-POLL-INNER  ( exchange operation config -- outcome )
    DROP NIP
    DUP _SHTO.STATE @ CASE
        _SHTTP-OP-STATE-RECEIVING OF
            DUP _SHTO.EXCHANGE @ HCONN-REQUEST@
                WREQ-DONE? 0= IF
                DROP HROUTE-OUTCOME-PENDING EXIT
            THEN
            _SHTTP-COMMIT
        ENDOF
        _SHTTP-OP-STATE-RUNNING OF
            _SHTTP-DRIVE-FLOW
        ENDOF
        _SHTTP-OP-STATE-RESPONSE OF
            DROP HROUTE-OUTCOME-RESPONSE
        ENDOF
        _SHTTP-OP-STATE-CANCELLING OF
            _SHTTP-POLL-CANCELLING
        ENDOF
        _SHTTP-OP-STATE-CANCELLED OF
            DROP HROUTE-OUTCOME-CANCELLED
        ENDOF
        SWAP DROP HROUTE-OUTCOME-FAILED SWAP
    ENDCASE ;

: _SHTTP-CANCEL-INNER  ( exchange operation config -- outcome )
    DROP NIP
    _SHTTP-OP-F-CANCEL-ENTERED OVER _SHTO-FLAG? IF
        DUP _SHTO.STATE @ _SHTTP-OP-STATE-CANCELLING = IF
            DROP HROUTE-OUTCOME-PENDING EXIT
        THEN
        DROP HROUTE-OUTCOME-CANCELLED EXIT
    THEN
    _SHTTP-OP-F-CANCEL-ENTERED OVER _SHTO-FLAG+
    _SHTTP-OP-F-ACQUIRED OVER _SHTO-FLAG? 0= IF
        _SHTTP-OP-STATE-CANCELLED OVER _SHTO.STATE !
        _SHTTP-MARK-CANCELLED
        HROUTE-OUTCOME-CANCELLED EXIT
    THEN
    DUP _SHTO.FLOW @ SFLOW.STATE @ CASE
        STREAMS-FLOW-STATE-IDLE OF
            _SHTTP-OP-STATE-CANCELLED OVER _SHTO.STATE !
            _SHTTP-MARK-CANCELLED
            HROUTE-OUTCOME-CANCELLED
        ENDOF
        STREAMS-FLOW-STATE-RECEIVING OF
            DUP _SHTTP-ABORT-RECEIVING
            DUP STREAMS-FLOW-S-CANCELLED =
            SWAP STREAMS-FLOW-S-OK = OR IF
                _SHTTP-OP-STATE-CANCELLED OVER _SHTO.STATE !
                _SHTTP-MARK-CANCELLED
                HROUTE-OUTCOME-CANCELLED
            ELSE
                DUP _SHTTP-MARK-CANCELLED
                _SHTTP-OP-STATE-CANCELLING SWAP _SHTO.STATE !
                HROUTE-OUTCOME-PENDING
            THEN
        ENDOF
        STREAMS-FLOW-STATE-TERMINAL OF
            _SHTTP-OP-STATE-CANCELLED OVER _SHTO.STATE !
            _SHTTP-MARK-CANCELLED
            HROUTE-OUTCOME-CANCELLED
        ENDOF
        >R
        DUP _SHTTP-NOW STREAMS-HTTP-ROUTE-S-OK <> IF
            DUP _SHTO.FLOW @ SFLOW.LAST-NOW @ 0 MAX
                OVER _SHTO.NOW !
        THEN
        DUP _SHTO.GENERATION @
        OVER _SHTO.NOW @
        2 PICK _SHTO.FLOW @ STREAMS-FLOW-CANCEL
        OVER _SHTTP-CANCEL-FLOW-STATUS!
        OVER _SHTO.FLOW @ SFLOW.STATE @
            STREAMS-FLOW-STATE-TERMINAL = IF
            DROP
            _SHTTP-OP-STATE-CANCELLED OVER _SHTO.STATE !
            _SHTTP-MARK-CANCELLED
            HROUTE-OUTCOME-CANCELLED
        ELSE
            DROP
            _SHTTP-OP-STATE-CANCELLING OVER _SHTO.STATE !
            _SHTTP-MARK-CANCELLED
            HROUTE-OUTCOME-PENDING
        THEN
        R>
    ENDCASE ;

: _SHTTP-CLEANUP-ACTIVE  ( operation -- status )
    >R
    R@ _SHTO.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-RECEIVING = IF
        R@ _SHTTP-ABORT-RECEIVING
        DUP STREAMS-FLOW-S-CANCELLED =
        OVER STREAMS-FLOW-S-OK = OR 0= IF
            R> DROP EXIT
        THEN
        DROP
    THEN
    R@ _SHTO.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-TERMINAL = IF
        R@ _SHTO.GENERATION @ R@ _SHTO.FLOW @
            STREAMS-FLOW-RETIRE
        DUP STREAMS-FLOW-S-OK <> IF R> DROP EXIT THEN
        DROP
    THEN
    R@ _SHTO.FLOW @ SFLOW.STATE @ STREAMS-FLOW-STATE-IDLE <> IF
        R> DROP STREAMS-FLOW-S-BUSY EXIT
    THEN
    R> _SHTTP-RELEASE-IDLE ;

: _SHTTP-CLEANUP-INNER  ( exchange operation config -- error )
    DROP NIP
    _SHTTP-OP-F-CLEANED OVER _SHTO-FLAG? IF
        _SHTO.CLEANUP-ERROR @ EXIT
    THEN
    _SHTTP-OP-F-ACQUIRED OVER _SHTO-FLAG? IF
        DUP _SHTTP-CLEANUP-ACTIVE
        DUP STREAMS-FLOW-S-OK <> IF
            DUP 2 PICK _SHTTP-FIRST-CLEANUP!
            STREAMS-HTTP-ROUTE-S-CLEANUP
            2 PICK _SHTTP-PRIMARY-STATUS!
            _SHTTP-OP-STATE-FAILED 2 PICK _SHTO.STATE !
            DROP _SHTO.CLEANUP-ERROR @ EXIT
        THEN
        DROP
    THEN
    _SHTTP-OP-F-CLEANED OVER _SHTO-FLAG+
    _SHTTP-OP-STATE-CLEANED OVER _SHTO.STATE !
    _SHTO.CLEANUP-ERROR @ ;

\ Lifecycle entry is serialized per operation.  The guards remain set while
\ CLOCK, METADATA, body, response-source, and flow callbacks execute, so a
\ callback cannot restart, cancel, or release the cell underneath its caller.
: STREAMS-HTTP-ROUTE-START  ( exchange operation config -- outcome )
    _SHTTP-3DUP _SHTTP-CALL-SHAPE? 0= IF
        2DROP DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    OVER _SHTTP-OPERATION-PRISTINE? 0= IF
        2DROP DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    _SHTTP-3DUP _SHTTP-OPERATION-INIT
    OVER >R
    _SHTTP-OP-F-CALLBACK-ACTIVE R@ _SHTO-FLAG+
    ['] _SHTTP-START-INNER CATCH
    _SHTTP-OP-F-CALLBACK-ACTIVE R@ _SHTO-FLAG-
    ?DUP IF
        DUP STREAMS-HTTP-ROUTE-S-FLOW SWAP
        R@ _SHTTP-PRIMARY-OR-CLEANUP!
        2DROP 2DROP
        _SHTTP-OP-STATE-FAILED R@ _SHTO.STATE !
        R> DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    R> DROP ;

: STREAMS-HTTP-ROUTE-POLL  ( exchange operation config -- outcome )
