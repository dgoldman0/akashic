    _SHTTP-OP-F-CALLBACK-ACTIVE 2 PICK _SHTO-FLAG? IF
        2DROP DROP HROUTE-OUTCOME-FAILED EXIT
    THEN
    OVER >R
    _SHTTP-OP-F-CALLBACK-ACTIVE R@ _SHTO-FLAG+
    ['] _SHTTP-POLL-INNER CATCH
    _SHTTP-OP-F-CALLBACK-ACTIVE R@ _SHTO-FLAG-
