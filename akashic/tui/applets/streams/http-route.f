: _SHTTP-SPAN-POOL-CONNECTORS-DISJOINT?
  ( address length pool -- flag )
    DUP _SPOOL.BOUND @ 0 ?DO
        2 PICK 2 PICK
        I 3 PICK _SPOOL-ENTRY _SPE.FLOW @
            SFLOW.INPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
        MSPAN-OVERLAP? IF
            2DROP DROP 0 UNLOOP EXIT
        THEN
        2 PICK 2 PICK
        I 3 PICK _SPOOL-ENTRY _SPE.FLOW @
            SFLOW.OUTPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
        MSPAN-OVERLAP? IF
            2DROP DROP 0 UNLOOP EXIT
        THEN
    LOOP
    2DROP DROP -1 ;

: _SHTTP-SPAN-POOL-DISJOINT?  ( address length pool -- flag )
    DUP STREAMS-EXECUTION-POOL-VALID? 0= IF
        2DROP DROP 0 EXIT
    THEN
    2 PICK 2 PICK 2 PICK
        _SPOOL-SPAN-METADATA-DISJOINT? 0= IF
        2DROP DROP 0 EXIT
    THEN
    DUP _SPOOL.BOUND @ 0 ?DO
        2 PICK 2 PICK
        I 3 PICK _SPOOL-ENTRY _SPE.FLOW @
        _SPOOL-SPAN-FLOW-DISJOINT? 0= IF
            2DROP DROP 0 UNLOOP EXIT
        THEN
    LOOP
    2 PICK 2 PICK 2 PICK
        _SHTTP-SPAN-POOL-CONNECTORS-DISJOINT? 0= IF
        2DROP DROP 0 EXIT
    THEN
    2DROP DROP -1 ;

: _SHTTP-POOL-HCONN-DISJOINT?  ( pool exchange -- flag )
    OVER STREAMS-EXECUTION-POOL-VALID? 0= IF 2DROP 0 EXIT THEN
    DUP HCONN-VALID? 0= IF 2DROP 0 EXIT THEN
    DUP _HCONN.GEOMETRY MSPAN-SET-COUNT@ 0 ?DO
        I OVER _HCONN-GEOMETRY-NTH
        DUP @ SWAP 8 + @
        3 PICK _SHTTP-SPAN-POOL-DISJOINT? 0= IF
            2DROP 0 UNLOOP EXIT
        THEN
    LOOP
    2DROP -1 ;

: _SHTTP-POOL-ROUTER-DISJOINT?  ( pool router -- flag )
    OVER STREAMS-EXECUTION-POOL-VALID? 0= IF 2DROP 0 EXIT THEN
    DUP HROUTER-VALID? 0= IF 2DROP 0 EXIT THEN
    DUP HROUTER-SIZE
        3 PICK _SHTTP-SPAN-POOL-DISJOINT? 0= IF
        2DROP 0 EXIT
    THEN
    DUP HROUTER.ENTRIES @
    OVER HROUTER.ENTRY-CAPACITY @ HROUTER-ENTRY-BYTES
        3 PICK _SHTTP-SPAN-POOL-DISJOINT? 0= IF
        2DROP 0 EXIT
    THEN
    DUP HROUTER.ARENA-A @
    OVER HROUTER.ARENA-CAPACITY @
        3 PICK _SHTTP-SPAN-POOL-DISJOINT? 0= IF
        2DROP 0 EXIT
    THEN
    2DROP -1 ;

