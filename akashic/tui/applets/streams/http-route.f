    _SHTTP-OP-F-ACQUIRED OVER _SHTO-FLAG?
    _SHTTP-OP-F-RELEASED ROT _SHTO-FLAG? 0= AND ;

\ ---------------------------------------------------------------------
\ Callback containment and exact operation admission
\ ---------------------------------------------------------------------

: _SHTTP-PRIMARY-FAILURE?  ( operation -- flag )
    _SHTO.STATUS @
    DUP STREAMS-HTTP-ROUTE-S-OK <>
    SWAP STREAMS-HTTP-ROUTE-S-PENDING <> AND ;

: _SHTTP-FIRST-CLEANUP!  ( error operation -- )
    >R
    ?DUP IF
        R@ _SHTO.CLEANUP-ERROR @ 0= IF
            R@ _SHTO.CLEANUP-ERROR !
        ELSE
            DROP
        THEN
    THEN
    R> DROP ;

: _SHTTP-PRIMARY-STATUS!  ( route-status operation -- )
    DUP _SHTTP-PRIMARY-FAILURE? IF 2DROP EXIT THEN
    _SHTO.STATUS ! ;

: _SHTTP-PRIMARY-OR-CLEANUP!
  ( route-status detail operation -- )
    >R
    R@ _SHTTP-PRIMARY-FAILURE? IF
        NIP R@ _SHTTP-FIRST-CLEANUP!
    ELSE
        DUP R@ _SHTO.FLOW-STATUS !
        SWAP R@ _SHTO.STATUS ! DROP
    THEN
    R> DROP ;

: _SHTTP-CLOCK-INNER  ( operation -- now-ms status )
    _SHTO.CONFIG @
    DUP _SHTC.CLOCK-CONTEXT @
    SWAP _SHTC.CLOCK-XT @ EXECUTE ;

: _SHTTP-NOW  ( operation -- status )
    DUP >R
    ['] _SHTTP-CLOCK-INNER CATCH ?DUP IF
        DUP STREAMS-HTTP-ROUTE-S-CLOCK SWAP
        R@ _SHTTP-PRIMARY-OR-CLEANUP!
        2DROP
        R> DROP STREAMS-HTTP-ROUTE-S-CLOCK EXIT
    THEN
    DUP IF
        DUP STREAMS-HTTP-ROUTE-S-CLOCK SWAP
        R@ _SHTTP-PRIMARY-OR-CLEANUP!
        2DROP
        R> DROP STREAMS-HTTP-ROUTE-S-CLOCK EXIT
    THEN
    DROP
    DUP 0< IF
        DROP
        STREAMS-HTTP-ROUTE-S-CLOCK STREAMS-FLOW-S-INVALID
        R@ _SHTTP-PRIMARY-OR-CLEANUP!
        R> DROP STREAMS-HTTP-ROUTE-S-CLOCK EXIT
    THEN
    R@ _SHTO.NOW @ DUP 0>= IF
        OVER SWAP < IF
            DROP
            STREAMS-HTTP-ROUTE-S-CLOCK STREAMS-FLOW-S-STALE
            R@ _SHTTP-PRIMARY-OR-CLEANUP!
            R> DROP STREAMS-HTTP-ROUTE-S-CLOCK EXIT
        THEN
    ELSE
        DROP
    THEN
    R@ _SHTO.NOW !
    R> DROP STREAMS-HTTP-ROUTE-S-OK ;

: _SHTTP-METADATA-INNER  ( operation -- status )
    >R
    R@ _SHTO.EXCHANGE @
    R@ _SHTO.EVENT
    R@ _SHTO.CONFIG @ DUP _SHTC.METADATA-CONTEXT @
    SWAP _SHTC.METADATA-XT @ EXECUTE
    R> DROP ;

: _SHTTP-METADATA  ( operation -- status )
    DUP >R
    ['] _SHTTP-METADATA-INNER CATCH ?DUP IF
        DUP STREAMS-HTTP-ROUTE-S-METADATA SWAP
        R@ _SHTTP-PRIMARY-OR-CLEANUP!
        2DROP
        R> DROP STREAMS-HTTP-ROUTE-S-METADATA EXIT
    THEN
    DUP IF
        DUP STREAMS-HTTP-ROUTE-S-METADATA SWAP
        R@ _SHTTP-PRIMARY-OR-CLEANUP!
        DROP
        R> DROP STREAMS-HTTP-ROUTE-S-METADATA EXIT
    THEN
    DROP
    R@ _SHTO.NOW @ R@ _SHTO.EVENT SEVT.RECEIVED-MS !
    R@ _SHTO.EVENT _SEVT-UNBOUND-METADATA? 0= IF
        STREAMS-HTTP-ROUTE-S-METADATA R@ _SHTO.STATUS !
        R> DROP STREAMS-HTTP-ROUTE-S-METADATA EXIT
    THEN
    R> DROP STREAMS-HTTP-ROUTE-S-OK ;

: _SHTTP-OPERATION-SPAN?  ( operation capacity config -- flag )
    >R
    DUP STREAMS-HTTP-ROUTE-OPERATION-SIZE < IF
        2DROP R> DROP 0 EXIT
    THEN
    OVER 0= IF 2DROP R> DROP 0 EXIT THEN
    2DUP MSPAN-NONWRAPPING? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    2DUP
        R@ STREAMS-HTTP-ROUTE-CONFIG-SIZE
        MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    2DUP
        R@ _SHTC.INPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
        MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    R@ _SHTC.POOL @ _SHTTP-SPAN-POOL-DISJOINT?
    R> DROP ;

: _SHTTP-CALL-SHAPE?  ( exchange operation config -- flag )
    DUP STREAMS-HTTP-ROUTE-CONFIG-VALID? 0= IF
        2DROP DROP 0 EXIT
    THEN
    2 PICK HCONN-VALID? 0= IF 2DROP DROP 0 EXIT THEN
    DUP STREAMS-HTTP-ROUTE-CONFIG-SIZE
        4 PICK HCONN-SPAN-DISJOINT? 0= IF
        2DROP DROP 0 EXIT
    THEN
    DUP _SHTC.POOL @
        3 PICK _SHTTP-POOL-HCONN-DISJOINT? 0= IF
        2DROP DROP 0 EXIT
    THEN
    2 PICK HCONN-ROUTE-OPERATION
    DUP STREAMS-HTTP-ROUTE-OPERATION-SIZE <> IF
        2DROP 2DROP DROP 0 EXIT
    THEN
    DROP
    2 PICK <> IF 2DROP DROP 0 EXIT THEN
    2 PICK HCONN-OPERATION-ARENA
    3 PICK 2 PICK <> IF
        2DROP 2DROP DROP 0 EXIT
    THEN
    2 PICK _SHTTP-OPERATION-SPAN? 0= IF
        2DROP DROP 0 EXIT
    THEN
    2DROP DROP -1 ;

: _SHTTP-OPERATION-INIT  ( exchange operation config -- )
    >R
    DUP STREAMS-HTTP-ROUTE-OPERATION-SIZE 0 FILL
    -1 OVER _SHTO.NOW !
    STREAMS-HTTP-ROUTE-S-PENDING OVER _SHTO.STATUS !
    STREAMS-FLOW-S-NO-WORK OVER _SHTO.FLOW-STATUS !
    _SHTTP-OP-STATE-STARTING OVER _SHTO.STATE !
    R@ OVER _SHTO.CONFIG !
    SWAP OVER _SHTO.EXCHANGE !
    DROP R> DROP ;

: _SHTTP-OPERATION-PRISTINE?  ( operation -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-HTTP-ROUTE-OPERATION-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    STREAMS-HTTP-ROUTE-OPERATION-SIZE 0 ?DO
        DUP I + C@ IF DROP 0 UNLOOP EXIT THEN
    LOOP
    DROP -1 ;

: _SHTTP-CALL-CURRENT?  ( exchange operation config -- flag )
    >R
    DUP _SHTO-HEADER? 0= IF 2DROP R> DROP 0 EXIT THEN
    DUP _SHTO.CONFIG @ R@ <> IF 2DROP R> DROP 0 EXIT THEN
    DUP _SHTO.EXCHANGE @ 2 PICK <> IF
        2DROP R> DROP 0 EXIT
    THEN
    2DROP R> DROP -1 ;

