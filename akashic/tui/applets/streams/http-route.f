\ =====================================================================
\ http-route.f - cooperative HTTP ingress route for Streams
\ =====================================================================
\ This module binds one admitted HTTP route to one caller-owned Streams
\ execution pool.  The route context is immutable after construction.
\ Every connection receives its own operation descriptor, including fresh
\ event-metadata storage, its exact pool lease, and response-source state.
\
\ Injected callback contracts:
\
\   CLOCK     ( clock-context -- now-ms status )
\   METADATA  ( exchange event metadata-context -- status )
\
\ Both callbacks return zero on success.  METADATA fills EVENT-ID,
\ CORRELATION-ID, IDEMPOTENCY-ID, MEDIA, and SEQUENCE in the freshly
\ initialized event.  The route owns RECEIVED-MS and all connector, flow,
\ direction, protocol, payload, and digest fields.
\
\ Every flow bound to one route pool has the same input connector, output
\ connector, transform word, timeout, and JSON output-media contract.  A
\ transform context may differ only to provide isolated per-cell workspace.
\ The transform emits complete syntactically valid JSON bytes; the route
\ transports those exact bytes and does not reinterpret trusted transform
\ output.
\
\ Route callbacks use the HTTP connection-owner contract:
\
\   START     ( exchange operation route-context -- outcome )
\   POLL      ( exchange operation route-context -- outcome )
\   CANCEL    ( exchange operation route-context -- outcome )
\   CLEANUP   ( exchange operation route-context -- error )
\
\ A positive body is accepted explicitly.  Each borrowed body slice is
\ appended before the callback returns and is never retained.  A zero-byte
\ body is committed during START.  Successful output is exposed as an
\ application/json pull source over the exact sealed egress carrier.
\ =====================================================================

