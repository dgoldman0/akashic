: _SHTTP-FLOW-SEMANTICS=  ( flow reference-flow -- flag )
    >R
    DUP SFLOW.INPUT-CONNECTOR @
        R@ SFLOW.INPUT-CONNECTOR @ =
    OVER SFLOW.OUTPUT-CONNECTOR @
        R@ SFLOW.OUTPUT-CONNECTOR @ = AND
    OVER SFLOW.TRANSFORM-XT @
        R@ SFLOW.TRANSFORM-XT @ = AND
    OVER SFLOW.TIMEOUT-MS @
        R@ SFLOW.TIMEOUT-MS @ = AND
    OVER SFLOW.OUTPUT-MEDIA @
        R@ SFLOW.OUTPUT-MEDIA @ = AND
    SWAP DROP
    R> DROP ;

: _SHTTP-POOL-SEMANTICS?  ( pool -- flag )
    DUP _SPOOL.BOUND @ 1 < IF DROP 0 EXIT THEN
    DUP 0 SWAP _SPOOL-ENTRY _SPE.FLOW @
    DUP SFLOW.OUTPUT-MEDIA @
        STREAMS-HTTP-ROUTE-MEDIA-JSON <> IF
        2DROP 0 EXIT
    THEN
    OVER _SPOOL.BOUND @ 0 ?DO
        I 2 PICK _SPOOL-ENTRY _SPE.FLOW @
        OVER _SHTTP-FLOW-SEMANTICS= 0= IF
            2DROP 0 UNLOOP EXIT
        THEN
    LOOP
    2DROP -1 ;

: _SHTTP-CONFIG-POOL-SHAPE?  ( config -- flag )
    DUP _SHTC.POOL @ DUP STREAMS-EXECUTION-POOL-VALID? 0= IF
        2DROP 0 EXIT
    THEN
    DUP _SPOOL.STATE @ _SPOOL-STATE-SEALED <> IF
        2DROP 0 EXIT
    THEN
    DUP _SHTTP-POOL-SEMANTICS? 0= IF
        2DROP 0 EXIT
    THEN
    OVER _SHTC.INPUT-CONNECTOR @ 1 PICK
        _SHTTP-POOL-CONNECTOR? 0= IF
        2DROP 0 EXIT
    THEN
    DUP _SHTTP-POOL-MAX-INGRESS
        2 PICK _SHTC.MAX-INGRESS @ =
    SWAP _SHTTP-POOL-MAX-EGRESS
        2 PICK _SHTC.MAX-EGRESS @ = AND
    NIP ;

: STREAMS-HTTP-ROUTE-CONFIG-VALID?  ( config -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-HTTP-ROUTE-CONFIG-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SHTC.STATE @ _SHTTP-CONFIG-STATE-READY <> IF
        DROP 0 EXIT
    THEN
    DUP _SHTC.INPUT-CONNECTOR @
        STREAMS-CONNECTOR-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SHTC.INPUT-CONNECTOR @ SCON.DIRECTION @
    DUP STREAMS-CONNECTOR-DIRECTION-INPUT =
    SWAP STREAMS-CONNECTOR-DIRECTION-BIDIRECTIONAL = OR 0= IF
        DROP 0 EXIT
    THEN
    DUP _SHTC.REQUIRED-EGRESS @ 0< IF DROP 0 EXIT THEN
    DUP _SHTC.CLOCK-XT @ 0= IF DROP 0 EXIT THEN
    DUP _SHTC.METADATA-XT @ 0= IF DROP 0 EXIT THEN
    DUP _SHTTP-CONFIG-POOL-SHAPE? 0= IF DROP 0 EXIT THEN
    DUP STREAMS-HTTP-ROUTE-CONFIG-SIZE
        OVER _SHTC.POOL @ _SHTTP-SPAN-POOL-DISJOINT? 0= IF
        DROP 0 EXIT
    THEN
    DUP STREAMS-HTTP-ROUTE-CONFIG-SIZE
        2 PICK _SHTC.INPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
        MSPAN-OVERLAP? 0= NIP ;

: STREAMS-HTTP-ROUTE-CONFIG-INIT
  ( pool connector required-egress clock-context clock-xt metadata-context metadata-xt config -- status )
    DUP 0= IF
        DROP _SHTTP-DROP7 STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    DUP STREAMS-HTTP-ROUTE-CONFIG-SIZE
        MSPAN-NONWRAPPING? 0= IF
        DROP _SHTTP-DROP7 STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    >R
    6 PICK STREAMS-EXECUTION-POOL-VALID? 0= IF
        _SHTTP-DROP7 R> DROP STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    6 PICK _SPOOL.STATE @ _SPOOL-STATE-SEALED <> IF
        _SHTTP-DROP7 R> DROP STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    6 PICK _SHTTP-POOL-SEMANTICS? 0= IF
        _SHTTP-DROP7 R> DROP STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    5 PICK STREAMS-CONNECTOR-VALID? 0= IF
        _SHTTP-DROP7 R> DROP STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    5 PICK SCON.DIRECTION @
    DUP STREAMS-CONNECTOR-DIRECTION-INPUT =
    SWAP STREAMS-CONNECTOR-DIRECTION-BIDIRECTIONAL = OR 0= IF
        _SHTTP-DROP7 R> DROP STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    4 PICK 0< IF
        _SHTTP-DROP7 R> DROP STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    2 PICK 0= DUP IF
        DROP _SHTTP-DROP7 R> DROP STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    DROP
    DUP 0= IF
        _SHTTP-DROP7 R> DROP STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    R@ STREAMS-HTTP-ROUTE-CONFIG-SIZE
        8 PICK _SHTTP-SPAN-POOL-DISJOINT? 0= IF
        _SHTTP-DROP7 R> DROP STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    R@ STREAMS-HTTP-ROUTE-CONFIG-SIZE
        7 PICK STREAMS-CONNECTOR-SIZE MSPAN-OVERLAP? IF
        _SHTTP-DROP7 R> DROP STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    R@ STREAMS-HTTP-ROUTE-CONFIG-SIZE 0 FILL
    R@ _SHTC.METADATA-XT !
    R@ _SHTC.METADATA-CONTEXT !
    R@ _SHTC.CLOCK-XT !
    R@ _SHTC.CLOCK-CONTEXT !
    R@ _SHTC.REQUIRED-EGRESS !
    R@ _SHTC.INPUT-CONNECTOR !
    R@ _SHTC.POOL !
    _SHTTP-CONFIG-STATE-READY R@ _SHTC.STATE !
    R@ _SHTC.INPUT-CONNECTOR @
    R@ _SHTC.POOL @ _SHTTP-POOL-CONNECTOR? 0= IF
        R@ STREAMS-HTTP-ROUTE-CONFIG-SIZE 0 FILL
        R> DROP STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    R@ _SHTC.POOL @ _SHTTP-POOL-MAX-INGRESS
        R@ _SHTC.MAX-INGRESS !
    R@ _SHTC.POOL @ _SHTTP-POOL-MAX-EGRESS
        R@ _SHTC.MAX-EGRESS !
    R@ STREAMS-HTTP-ROUTE-CONFIG-VALID? 0= IF
        R@ STREAMS-HTTP-ROUTE-CONFIG-SIZE 0 FILL
        R> DROP STREAMS-HTTP-ROUTE-S-INVALID EXIT
    THEN
    R> DROP STREAMS-HTTP-ROUTE-S-OK ;

