: _SPAW-ABORT-ACTIVE  ( primary-status work -- final-status )
    >R
    DUP R@ _SPAW.TEMP-STATUS !
    \ Keep the reclaim proposal fenced until PSTORE has abandoned its root.
    R@ _SPAW.PSTORE-WORK @ PSTORE-PROPOSED-ROOT@ IF
        R@ _SPAW.ADAPTER @ _SPA-D.STORE @
        R@ _SPAW.PSTORE-WORK @ PSTORE-ABORT
        DUP PERSIST-S-OK <> IF
            _SPA-PERSIST>STATUS R@ _SPAW.TEMP-STATUS !
        ELSE
            DROP
        THEN
    THEN
    R@ _SPAW.PSTORE-WORK @ PSTORE-PROPOSED-ROOT@ 0= IF
        R@ _SPAW.RECLAIM-WORK RECLAIM-ABORT
        DUP PERSIST-S-OK <> IF
            _SPA-PERSIST>STATUS R@ _SPAW.TEMP-STATUS !
        ELSE
            DROP
        THEN
    THEN
    _SPAW-STATE-REOPEN R@ _SPAW.STATE !
    DROP R@ _SPAW.TEMP-STATUS @ R> DROP ;

: _SPAW-FAIL-ACTIVE  ( status work -- status )
    >R
    DUP IF
        R@ _SPAW.STATE @ _SPAW-STATE-ACTIVE = IF
            R@ _SPAW-ABORT-ACTIVE
        THEN
    THEN
    R> DROP ;

: _SPAW-ABORT-STORE-PRIMARY  ( primary-status work -- final-status )
    >R
    DUP R@ _SPAW.TEMP-STATUS !
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @
    R@ _SPAW.PSTORE-WORK @ PSTORE-ABORT
    DUP PERSIST-S-OK <> IF
        _SPA-PERSIST>STATUS R@ _SPAW.TEMP-STATUS !
    ELSE
        DROP
    THEN
    DROP R@ _SPAW.TEMP-STATUS @ R> DROP ;

: _SPAW-BEGIN-RUN  ( work -- status )
    >R
    R@ _SPAW.STATE @ _SPAW-STATE-ACTIVE = IF
        R> DROP STREAMS-PA-S-BUSY EXIT
    THEN
    R@ _SPAW.STATE @ _SPAW-STATE-REOPEN = IF
        R> DROP STREAMS-PA-S-CONFLICT EXIT
    THEN
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @ PSTORE-GENERATION@
        R@ _SPAW.BASE-GENERATION !
    R@ _SPAW.RECLAIM RECLAIM-STORE@ 0= IF
        R@ _SPAW-BIND-EMPTY-RECLAIM
        DUP IF R> DROP EXIT THEN DROP
    THEN
    R@ _SPAW-ROOTS-CURRENT? 0= IF
        R> DROP STREAMS-PA-S-CONFLICT EXIT
    THEN
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @ PSTORE-CURRENT-ROOT@
    DUP IF
        PROOTV.APPLICATION-ROOT @
    ELSE
        DROP -1
    THEN
    R@ _SPAW.OLD-ROOT-PAGE !
    0 R@ _SPAW.RECLAIM-STEP-CALLS !
    0 R@ _SPAW.RECLAIM-MOVED !
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @
    R@ _SPAW.PSTORE-WORK @ PSTORE-BEGIN
    DUP IF _SPA-PERSIST>STATUS R> DROP EXIT THEN DROP
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @
    R@ _SPAW.PSTORE-WORK @ R@ _SPAW.RECLAIM
    R@ _SPAW.RECLAIM-WORK RECLAIM-TX-BEGIN
    DUP IF
        _SPA-PERSIST>STATUS R@ _SPAW-ABORT-STORE-PRIMARY
        R> DROP EXIT
    THEN DROP
    _SPAW-STATE-ACTIVE R@ _SPAW.STATE !
    R@ _SPAW.OLD-ROOT-PAGE @ 0>= IF
        R@ _SPAW.OLD-ROOT-PAGE 1
        R@ _SPAW.RECLAIM-WORK RECLAIM-RETIRE-BATCH
        DUP IF
            _SPA-PERSIST>STATUS R@ _SPAW-ABORT-ACTIVE
            R> DROP EXIT
        THEN DROP
    THEN
    R@ _SPAW.BASE-GENERATION @ 0= IF
        R@ _SPAW-ROOTS-INIT
        DUP IF R@ _SPAW-ABORT-ACTIVE R> DROP EXIT THEN DROP
    THEN
    0 R@ _SPAW.MUTATION-N !
    0 R@ _SPAW.PHYSICAL-ONLY-N !
    0 R@ _SPAW.RESULT-U !
    -1 R@ _SPAW.APP-ROOT-PAGE !
    R@ _SPAW.BLOB PBLOB-SIZE 0 FILL
    R> DROP STREAMS-PA-S-OK ;

: STREAMS-PA-BEGIN  ( adapter work -- status )
    2DUP _SPAW-ENTER DUP IF >R 2DROP R> EXIT THEN DROP
    DUP ['] _SPAW-BEGIN-RUN _SPAW-WORK-CATCH
    OVER _SPAW-FAIL-ACTIVE
    ROT ROT _SPAW-LEAVE ;

