\ =====================================================================
\  persistence-adapter.f - Streams authority over neutral persistence
\ =====================================================================
\  This adapter composes one caller-supplied PSTORE into the four-tree L13
\  configured-Streams authority.  It owns physical transaction mechanics,
\  checked application-root publication, bounded work, and semantic-record
\  dereference.  It owns no paths, provider policy, refresh policy, query
\  projection, migration choice, Library documents, or public-Bluesky state.
\
\  All mutable memory is caller-owned.  One work object permanently borrows
\  its PSTORE work and shares exactly one PBTREE work, one PBLOB work, and one
\  reclamation work across four workload-separated tree descriptors.  Its one
\  PBTREE cursor is call-local navigation state; only semantic keys resume.
\  A read-only span probe lets callers qualify buffers against that complete
\  borrowed-memory graph without entering or mutating the adapter.
\ =====================================================================

