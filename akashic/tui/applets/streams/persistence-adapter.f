        DROP STREAMS-PA-S-BUSY EXIT
    THEN
    DUP _SPAW.MUTATION-N @ PERSIST-MAX-SIGNED >= IF
        DROP STREAMS-PA-S-CAPACITY EXIT
    THEN
    1 SWAP _SPAW.MUTATION-N +!
    STREAMS-PA-S-OK ;

