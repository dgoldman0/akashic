: STREAMS-PA-VALID?  ( adapter -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-PA-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SPA-D.MAGIC @ _SPA-MAGIC <> IF DROP 0 EXIT THEN
    DUP _SPA-D.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _SPA-D.STATUS @ _SPA-STATUS? 0= IF DROP 0 EXIT THEN
    DUP _SPA-D.STORE @ DUP PSTORE-VALID? 0= IF 2DROP 0 EXIT THEN
    PSTORE-SIZE ROT STREAMS-PA-SIZE MSPAN-OVERLAP? 0= ;

: STREAMS-PA-INIT  ( store adapter -- status )
    >R
    DUP PSTORE-VALID? 0= IF DROP R> DROP STREAMS-PA-S-INVALID EXIT THEN
    R@ 0= IF DROP R> DROP STREAMS-PA-S-INVALID EXIT THEN
    R@ STREAMS-PA-SIZE MSPAN-NONWRAPPING? 0= IF
        DROP R> DROP STREAMS-PA-S-INVALID EXIT
    THEN
    R@ STREAMS-PA-SIZE 2 PICK PSTORE-SPAN-DISJOINT? 0= IF
        DROP R> DROP STREAMS-PA-S-INVALID EXIT
    THEN
    DUP PSTORE-SIZE R@ STREAMS-PA-SIZE MSPAN-OVERLAP? IF
        DROP R> DROP STREAMS-PA-S-INVALID EXIT
    THEN
    R@ STREAMS-PA-SIZE 0 FILL
    _SPA-MAGIC R@ _SPA-D.MAGIC !
    R@ R@ _SPA-D.SELF !
    DUP R@ _SPA-D.STORE !
    STREAMS-PA-S-OK R@ _SPA-D.STATUS !
    DROP R> DROP STREAMS-PA-S-OK ;

