: _SPA-RANGE-MODE?  ( mode -- flag )
    DUP _SPA-RANGE-FIRST >=
    SWAP _SPA-RANGE-LAST <= AND ;

: _SPAW-RANGE-PREFIX-CLASSIFY
  ( prefix-a prefix-u work -- status )
    >R
    2DUP STREAMS-PI-ACTIVE-ATTEMPT-PREFIX-VALID? IF
        2DROP
        STREAMS-PI-TREE-DIRECTORY R@ _SPAW.PAGE-ID !
        R> DROP STREAMS-PA-S-OK EXIT
    THEN
    2DUP STREAMS-PI-SOURCE-ORDER-PREFIX-VALID? IF
        2DROP
        STREAMS-PI-TREE-DIRECTORY R@ _SPAW.PAGE-ID !
        R> DROP STREAMS-PA-S-OK EXIT
    THEN
    2DUP STREAMS-PI-ATTEMPT-BY-SOURCE-PREFIX-VALID? IF
        2DROP
        STREAMS-PI-TREE-ATTEMPTS R@ _SPAW.PAGE-ID !
        R> DROP STREAMS-PA-S-OK EXIT
    THEN
    2DUP STREAMS-PI-OBSERVATION-REVISION-PREFIX-VALID? IF
        2DROP
        STREAMS-PI-TREE-IDENTITIES R@ _SPAW.PAGE-ID !
        R> DROP STREAMS-PA-S-OK EXIT
    THEN
    2DUP STREAMS-PI-GLOBAL-TIME-PREFIX-VALID? IF
        2DROP
        STREAMS-PI-TREE-ORDERINGS R@ _SPAW.PAGE-ID !
        R> DROP STREAMS-PA-S-OK EXIT
    THEN
    2DUP STREAMS-PI-SOURCE-TIME-PREFIX-VALID? IF
        2DROP
        STREAMS-PI-TREE-ORDERINGS R@ _SPAW.PAGE-ID !
        R> DROP STREAMS-PA-S-OK EXIT
    THEN
    2DUP STREAMS-PI-THREAD-TIME-FAMILY-PREFIX-VALID? IF
        2DROP R> DROP STREAMS-PA-S-UNSUPPORTED EXIT
    THEN
    2DUP STREAMS-PI-THREAD-TIME-PREFIX-VALID? IF
        2DROP R> DROP STREAMS-PA-S-UNSUPPORTED EXIT
    THEN
    2DROP R> DROP STREAMS-PA-S-INVALID ;

: _SPAW-RANGE-RESUME?  ( work -- flag )
    >R
    R@ _SPAW.VALUE-A @ R@ _SPAW.SOURCE-CONTEXT @
        R@ _SPAW-SPAN-SAFE? 0= IF R> DROP 0 EXIT THEN
    R@ _SPAW.VALUE-A @ R@ _SPAW.SOURCE-CONTEXT @
        STREAMS-PI-KEY-VALID? 0= IF R> DROP 0 EXIT THEN
    R@ _SPAW.VALUE-A @ R@ _SPAW.SOURCE-CONTEXT @
        _SPAW-KEY-INDEX
    R@ _SPAW.PAGE-ID @ <> IF R> DROP 0 EXIT THEN
    R@ _SPAW.SOURCE-CONTEXT @ R@ _SPAW.ARG-U @ < IF
        R> DROP 0 EXIT
    THEN
    R@ _SPAW.VALUE-A @ R@ _SPAW.ARG-A @ R@ _SPAW.ARG-U @
        _SPA-BYTES=
    R> DROP ;

: _SPAW-RANGE-LAST-BOUNDARY  ( work -- status )
    >R
    R@ _SPAW.ARG-A @ R@ _SPAW.ARG-U @
        STREAMS-PI-SOURCE-ORDER-PREFIX-VALID? IF
        R@ _SPAW.RANGE-KEY
            STREAMS-PI-SOURCE-ORDER-LAST-BOUNDARY
        DUP IF
            DROP R> DROP STREAMS-PA-S-INVALID EXIT
        THEN DROP
        STREAMS-PI-SOURCE-ORDER-KEY-SIZE
            R@ _SPAW.SOURCE-CONTEXT !
        R> DROP STREAMS-PA-S-OK EXIT
    THEN
    R@ _SPAW.ARG-A @ R@ _SPAW.ARG-U @
        STREAMS-PI-ATTEMPT-BY-SOURCE-PREFIX-VALID? IF
        R@ _SPAW.ARG-A @ 1+
        R@ _SPAW.RANGE-KEY
            STREAMS-PI-ATTEMPT-BY-SOURCE-LAST-BOUNDARY
        DUP IF
            DROP R> DROP STREAMS-PA-S-INVALID EXIT
        THEN DROP
        STREAMS-PI-ATTEMPT-BY-SOURCE-KEY-SIZE
            R@ _SPAW.SOURCE-CONTEXT !
        R> DROP STREAMS-PA-S-OK EXIT
    THEN
    R@ _SPAW.ARG-A @ R@ _SPAW.ARG-U @
        STREAMS-PI-OBSERVATION-REVISION-PREFIX-VALID? IF
        R@ _SPAW.ARG-A @ 1+
        R@ _SPAW.RANGE-KEY
            STREAMS-PI-OBSERVATION-REVISION-LAST-BOUNDARY
        DUP IF
            DROP R> DROP STREAMS-PA-S-INVALID EXIT
        THEN DROP
        STREAMS-PI-OBSERVATION-REVISION-KEY-SIZE
            R@ _SPAW.SOURCE-CONTEXT !
        R> DROP STREAMS-PA-S-OK EXIT
    THEN
    R@ _SPAW.ARG-A @ R@ _SPAW.ARG-U @
        STREAMS-PI-GLOBAL-TIME-PREFIX-VALID? IF
        R@ _SPAW.RANGE-KEY
            STREAMS-PI-GLOBAL-TIME-LAST-BOUNDARY
        DUP IF
            DROP R> DROP STREAMS-PA-S-INVALID EXIT
        THEN DROP
        STREAMS-PI-GLOBAL-TIME-KEY-SIZE
            R@ _SPAW.SOURCE-CONTEXT !
        R> DROP STREAMS-PA-S-OK EXIT
    THEN
    R@ _SPAW.ARG-A @ R@ _SPAW.ARG-U @
        STREAMS-PI-SOURCE-TIME-PREFIX-VALID? IF
        R@ _SPAW.ARG-A @ 1+
        R@ _SPAW.RANGE-KEY
            STREAMS-PI-SOURCE-TIME-LAST-BOUNDARY
        DUP IF
            DROP R> DROP STREAMS-PA-S-INVALID EXIT
        THEN DROP
        STREAMS-PI-SOURCE-TIME-KEY-SIZE
            R@ _SPAW.SOURCE-CONTEXT !
        R> DROP STREAMS-PA-S-OK EXIT
    THEN
    R> DROP STREAMS-PA-S-INVALID ;

: _SPAW-RANGE-ARGS  ( work -- status )
    >R
    0 R@ _SPAW.RESULT-U !
    R@ _SPAW-READY? 0= IF R> DROP STREAMS-PA-S-BUSY EXIT THEN
    R@ _SPAW.SOURCE-XT @ _SPA-RANGE-MODE? 0= IF
        R> DROP STREAMS-PA-S-INVALID EXIT
    THEN
    R@ _SPAW.ARG-A @ R@ _SPAW.ARG-U @
        R@ _SPAW-SPAN-SAFE? 0= IF
        R> DROP STREAMS-PA-S-INVALID EXIT
    THEN
    R@ _SPAW.ARG-A @ R@ _SPAW.ARG-U @
        R@ _SPAW-RANGE-PREFIX-CLASSIFY
    DUP IF R> DROP EXIT THEN DROP
    R@ _SPAW.SOURCE-XT @ DUP _SPA-RANGE-FIRST =
    SWAP _SPA-RANGE-LAST = OR IF
        R@ _SPAW.VALUE-A @
        R@ _SPAW.SOURCE-CONTEXT @ OR IF
            R> DROP STREAMS-PA-S-INVALID EXIT
        THEN
    ELSE
        R@ _SPAW-RANGE-RESUME? 0= IF
            R> DROP STREAMS-PA-S-INVALID EXIT
        THEN
    THEN
    R@ _SPAW.DEST-U @ DUP 1 <
    SWAP STREAMS-PA-RANGE-MAX > OR IF
        R> DROP STREAMS-PA-S-INVALID EXIT
    THEN
    R@ _SPAW.DEST-U @ STREAMS-PA-RANGE-ROW-SIZE _SPA-MUL?
    0= IF DROP R> DROP STREAMS-PA-S-CAPACITY EXIT THEN
    R@ _SPAW.TOTAL-U !
    R@ _SPAW.DEST-A @ R@ _SPAW.TOTAL-U @
        R@ _SPAW-SPAN-SAFE? 0= IF
        R> DROP STREAMS-PA-S-INVALID EXIT
    THEN
    R@ _SPAW.KEY PBTREE-KEY-MAX 0 FILL
    R@ _SPAW.ARG-A @ R@ _SPAW.KEY R@ _SPAW.ARG-U @ MOVE
    R@ _SPAW.RANGE-KEY PBTREE-KEY-MAX 0 FILL
    R@ _SPAW.SOURCE-XT @ _SPA-RANGE-LAST = IF
        R@ _SPAW-RANGE-LAST-BOUNDARY
        DUP IF R> DROP EXIT THEN DROP
    ELSE
        R@ _SPAW.SOURCE-XT @ _SPA-RANGE-FIRST <> IF
        R@ _SPAW.VALUE-A @ R@ _SPAW.RANGE-KEY
        R@ _SPAW.SOURCE-CONTEXT @ MOVE
        THEN
    THEN
    R@ _SPAW.KEY R@ _SPAW.ARG-A !
    R@ _SPAW.RANGE-KEY R@ _SPAW.VALUE-A !
    R@ _SPAW.DEST-A @ R@ _SPAW.TOTAL-U @ 0 FILL
    R> DROP STREAMS-PA-S-OK ;

: _SPAW-RANGE-ROW
  ( key-a key-u value-a value-u persist-status work -- status )
    >R
    DUP PERSIST-S-NOT-FOUND = IF
        DROP _SPA-DROP4 R> DROP STREAMS-PA-S-NOT-FOUND EXIT
    THEN
    DUP IF
        _SPA-PERSIST>STATUS >R
        _SPA-DROP4 R> R> DROP EXIT
    THEN
    DROP
    2 PICK R@ _SPAW.ARG-U @ < IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-NOT-FOUND EXIT
    THEN
    3 PICK R@ _SPAW.ARG-A @ R@ _SPAW.ARG-U @
        _SPA-BYTES= 0= IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-NOT-FOUND EXIT
    THEN
    3 PICK 3 PICK STREAMS-PI-KEY-VALID? 0= IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    DUP PERSIST-REF-SIZE <> IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    OVER PERSIST-REF-VALID? 0= IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    OVER R@ _SPAW.RECORD-REF PERSIST-REF-COPY
    2DROP
    R@ _SPAW.RECORD-REF
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @
    R@ _SPAW.PSTORE-WORK @ PSTORE-READ-RECORD
    DUP IF
        DUP PERSIST-S-NOT-FOUND = IF
            DROP 2DROP R> DROP STREAMS-PA-S-CORRUPT EXIT
        THEN
        _SPA-PERSIST>STATUS >R 2DROP R> R> DROP EXIT
    THEN
    DROP
    R@ _SPAW.PSTORE-WORK @ PSTORE-RECORD-PAYLOAD$
    2DUP SPREC-VALID? 0= IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    DUP STREAMS-PERSISTENCE-RECORD-MAX > IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    3 PICK 3 PICK 3 PICK 3 PICK
        STREAMS-PI-RECORD-AGREES? 0= IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    R@ _SPAW.RESULT-U @ R@ _SPAW.DEST-U @ >= IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    R@ _SPAW.RESULT-U @ STREAMS-PA-RANGE-ROW-SIZE *
    R@ _SPAW.DEST-A @ + R@ _SPAW.VALUE-A !
    R@ _SPAW.VALUE-A @ STREAMS-PA-RANGE-ROW-SIZE 0 FILL
    2 PICK R@ _SPAW.VALUE-A @ _SPAROW.KEY-U !
    DUP R@ _SPAW.VALUE-A @ _SPAROW.RECORD-U !
    3 PICK R@ _SPAW.VALUE-A @ _SPAROW.KEY
    4 PICK MOVE
    OVER R@ _SPAW.VALUE-A @ _SPAROW.RECORD
    2 PICK MOVE
    _SPA-DROP4
    R@ _SPAW.VALUE-A @ STREAMS-PA-RANGE-ROW-VALID? 0= IF
        R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    1 R@ _SPAW.RESULT-U +!
    R> DROP STREAMS-PA-S-OK ;

: _SPAW-RANGE-START  ( work -- status )
    >R
    R@ _SPAW.SOURCE-XT @ CASE
        _SPA-RANGE-FIRST OF
            R@ _SPAW.ARG-A @ R@ _SPAW.ARG-U @
            R@ _SPAW.PAGE-ID @ R@ _SPAW-ROOT
            R@ _SPAW.PAGE-ID @ R@ _SPAW-TREE
            R@ _SPAW.CURSOR R@ _SPAW.BTREE-WORK PBTREE-SEEK
        ENDOF
        _SPA-RANGE-AFTER OF
            R@ _SPAW.VALUE-A @ R@ _SPAW.SOURCE-CONTEXT @
            R@ _SPAW.PAGE-ID @ R@ _SPAW-ROOT
            R@ _SPAW.PAGE-ID @ R@ _SPAW-TREE
            R@ _SPAW.CURSOR R@ _SPAW.BTREE-WORK PBTREE-RESUME
        ENDOF
        _SPA-RANGE-BEFORE OF
            R@ _SPAW.VALUE-A @ R@ _SPAW.SOURCE-CONTEXT @
            R@ _SPAW.PAGE-ID @ R@ _SPAW-ROOT
            R@ _SPAW.PAGE-ID @ R@ _SPAW-TREE
            R@ _SPAW.CURSOR R@ _SPAW.BTREE-WORK
                PBTREE-SEEK-BEFORE
        ENDOF
        _SPA-RANGE-LAST OF
            R@ _SPAW.VALUE-A @ R@ _SPAW.SOURCE-CONTEXT @
            R@ _SPAW.PAGE-ID @ R@ _SPAW-ROOT
            R@ _SPAW.PAGE-ID @ R@ _SPAW-TREE
            R@ _SPAW.CURSOR R@ _SPAW.BTREE-WORK
                PBTREE-SEEK-BEFORE
        ENDOF
        DROP 0 0 0 0 PERSIST-S-INVALID 0
    ENDCASE
    R@ _SPAW-RANGE-ROW
    R> DROP ;

: _SPAW-RANGE-NEXT  ( work -- status )
    >R
    R@ _SPAW.PAGE-ID @ R@ _SPAW-ROOT
    R@ _SPAW.PAGE-ID @ R@ _SPAW-TREE
    R@ _SPAW.CURSOR R@ _SPAW.BTREE-WORK
    R@ _SPAW.SOURCE-XT @ DUP _SPA-RANGE-BEFORE =
    SWAP _SPA-RANGE-LAST = OR IF
        PBTREE-PREV
    ELSE
        PBTREE-NEXT
    THEN
    R@ _SPAW-RANGE-ROW
    R> DROP ;

: _SPAW-RANGE-REVERSE  ( work -- )
    >R 0
    BEGIN
        DUP R@ _SPAW.RESULT-U @ 2 / <
    WHILE
        R@ _SPAW.DEST-A @
        OVER STREAMS-PA-RANGE-ROW-SIZE * +
        R@ _SPAW.PAGE STREAMS-PA-RANGE-ROW-SIZE MOVE
        R@ _SPAW.DEST-A @
        R@ _SPAW.RESULT-U @ 1- 2 PICK -
        STREAMS-PA-RANGE-ROW-SIZE * +
        R@ _SPAW.DEST-A @
        2 PICK STREAMS-PA-RANGE-ROW-SIZE * +
        STREAMS-PA-RANGE-ROW-SIZE MOVE
        R@ _SPAW.PAGE
        R@ _SPAW.DEST-A @
        R@ _SPAW.RESULT-U @ 1- 3 PICK -
        STREAMS-PA-RANGE-ROW-SIZE * +
        STREAMS-PA-RANGE-ROW-SIZE MOVE
        1+
    REPEAT
    DROP R> DROP ;

: _SPAW-RANGE-SUCCESS  ( work -- status )
    DUP _SPAW.SOURCE-XT @ DUP _SPA-RANGE-BEFORE =
    SWAP _SPA-RANGE-LAST = OR IF
        DUP _SPAW-RANGE-REVERSE
    THEN
    DROP STREAMS-PA-S-OK ;

: _SPAW-RANGE-FAIL  ( status work -- status )
    >R
    R@ _SPAW.DEST-A @ R@ _SPAW.TOTAL-U @ 0 FILL
    0 R@ _SPAW.RESULT-U !
    R> DROP ;

: _SPAW-RANGE-RUN  ( work -- status )
    >R
    R@ _SPAW-RANGE-ARGS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SPAW.PAGE-ID @ R@ _SPAW-ROOT
    R@ _SPAW.PAGE-ID @ R@ _SPAW-TREE
    R@ _SPAW.CURSOR PBTREE-CURSOR-INIT
    DUP IF
        _SPA-PERSIST>STATUS R@ _SPAW-RANGE-FAIL
        R> DROP EXIT
    THEN
    DROP
    R@ _SPAW-RANGE-START
    DUP STREAMS-PA-S-NOT-FOUND = IF
        DROP R> _SPAW-RANGE-SUCCESS EXIT
    THEN
    DUP IF R@ _SPAW-RANGE-FAIL R> DROP EXIT THEN
    DROP
    BEGIN
        R@ _SPAW.RESULT-U @ R@ _SPAW.DEST-U @ <
    WHILE
        R@ _SPAW-RANGE-NEXT
        DUP STREAMS-PA-S-NOT-FOUND = IF
            DROP R> _SPAW-RANGE-SUCCESS EXIT
        THEN
        DUP IF R@ _SPAW-RANGE-FAIL R> DROP EXIT THEN
        DROP
    REPEAT
    R> _SPAW-RANGE-SUCCESS ;

