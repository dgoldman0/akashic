: _STREAMS-PA-RANGE-PUBLIC
    2DUP _SPAW-ENTER DUP IF
        >R _SPA-DROP9 0 R> EXIT
    THEN
    DROP
    >R
    1 PICK R@ _SPAW.SOURCE-XT !
    2 PICK R@ _SPAW.DEST-U !
    3 PICK R@ _SPAW.DEST-A !
    4 PICK R@ _SPAW.SOURCE-CONTEXT !
    5 PICK R@ _SPAW.VALUE-A !
    6 PICK R@ _SPAW.ARG-U !
    7 PICK R@ _SPAW.ARG-A !
    R@ ['] _SPAW-RANGE-RUN _SPAW-WORK-CATCH
    SWAP R@ _SPAW-LEAVE
    R@ _SPAW-COUNT-RESULT
    >R >R _SPA-DROP7 R> R> R> DROP ;

