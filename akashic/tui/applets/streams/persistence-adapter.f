    >R DROP R> R> DROP ;

\ ---------------------------------------------------------------------
\ Hidden staging roots for whole-batch logical publication
\ ---------------------------------------------------------------------

\ Staged COW paths retain the pages they replace because visible roots remain
\ authoritative until final publication.  Crashed shadow paths are ordinary
\ unreachable compaction input, never entries in the live reclaim ledger.
: _SPAW-PUT-STAGED-RAW
  ( key-a key-u value-a value-u tree-index work -- status )
    >R
    R@ _SPAW.STAGING-ACTIVE @ 0= IF
        _SPA-DROP5 R> DROP STREAMS-PA-S-CONFLICT EXIT
    THEN
    DUP 0< OVER _SPA-TREE-COUNT >= OR IF
        DROP _SPA-DROP4 R> DROP STREAMS-PA-S-INVALID EXIT
    THEN
    DUP R@ _SPAW.PAGE-ID ! DROP
    R@ _SPAW.PAGE-ID @ R@ _SPAW-STAGING-ROOT
    R@ _SPAW.TEMP-ROOT
    R@ _SPAW.PAGE-ID @ R@ _SPAW-TREE
    R@ _SPAW.BTREE-WORK PBTREE-PUT
    DUP IF _SPA-PERSIST>STATUS R> DROP EXIT THEN DROP
    R@ _SPAW.BTREE-WORK PBTREE-RETIRED-PAGES$ 2DROP
    R@ _SPAW.TEMP-ROOT
    R@ _SPAW.PAGE-ID @ R@ _SPAW-STAGING-ROOT PBTREE-ROOT-COPY
    _SPA-PERSIST>STATUS
    R> DROP ;

: _SPAW-DELETE-STAGED-RAW
  ( key-a key-u tree-index work -- status )
    >R
    R@ _SPAW.STAGING-ACTIVE @ 0= IF
        _SPA-DROP3 R> DROP STREAMS-PA-S-CONFLICT EXIT
    THEN
    DUP 0< OVER _SPA-TREE-COUNT >= OR IF
        _SPA-DROP3 R> DROP STREAMS-PA-S-INVALID EXIT
    THEN
    DUP R@ _SPAW.PAGE-ID ! DROP
    R@ _SPAW.PAGE-ID @ R@ _SPAW-STAGING-ROOT
    R@ _SPAW.TEMP-ROOT
    R@ _SPAW.PAGE-ID @ R@ _SPAW-TREE
    R@ _SPAW.BTREE-WORK PBTREE-DELETE
    DUP PERSIST-S-NOT-FOUND = IF
        DROP R> DROP STREAMS-PA-S-NOT-FOUND EXIT
    THEN
    DUP IF _SPA-PERSIST>STATUS R> DROP EXIT THEN DROP
    R@ _SPAW.BTREE-WORK PBTREE-RETIRED-PAGES$ 2DROP
    R@ _SPAW.TEMP-ROOT
    R@ _SPAW.PAGE-ID @ R@ _SPAW-STAGING-ROOT PBTREE-ROOT-COPY
    _SPA-PERSIST>STATUS
    R> DROP ;

RECLAIM-RETIRED-MAX RECLAIM-MAX-BATCH 1- +
