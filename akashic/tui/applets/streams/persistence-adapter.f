            DROP R> DROP 0 EXIT
        THEN
        1+
    REPEAT
    DROP R> DROP -1 ;

\ Seal validation is intentionally first on cold load.  Only a supported,
\ self-consistent header is copied into mutable work; bound tree scopes,
\ generations, cardinalities, and reclaim state follow in that order.
: _SPAW-ROOT>WORK  ( payload-a payload-u work -- status )
    >R
    DUP STREAMS-AUTHORITY-ROOT-SIZE <> IF
        2DROP R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    OVER STREAMS-AUTHORITY-ROOT-HEADER-CLASSIFY
        _SPA-ROOT>STATUS
    DUP IF >R 2DROP R> R> DROP EXIT THEN DROP
    OVER R@ _SPAW.AUTHORITY-ROOT STREAMS-AUTHORITY-ROOT-SIZE MOVE
    2DROP
    0
    BEGIN DUP _SPA-TREE-COUNT < WHILE
        DUP R@ _SPAW.PAGE-ID !
        R@ _SPAW.PAGE-ID @ R@ _SPAW.AUTHORITY-ROOT
            STREAMS-AUTHORITY-ROOT-TREE
        R@ _SPAW.PAGE-ID @ R@ _SPAW-ROOT
        PBTREE-ROOT-COPY
        DUP IF
            _SPA-PERSIST>STATUS >R DROP R> R> DROP EXIT
        THEN DROP
        R@ _SPAW.PAGE-ID @ R@ _SPAW-ROOT
        R@ _SPAW.PAGE-ID @ R@ _SPAW-TREE
            PBTREE-ROOT-VALID? 0= IF
            DROP R> DROP STREAMS-PA-S-CORRUPT EXIT
        THEN
        R@ _SPAW.PAGE-ID @ R@ _SPAW-ROOT
            PBTREE-ROOT-GENERATION@
        R@ _SPAW.ADAPTER @ _SPA-D.STORE @
            PSTORE-GENERATION@ <> IF
            DROP R> DROP STREAMS-PA-S-CORRUPT EXIT
        THEN
        1+
    REPEAT
    DROP
    R@ _SPAW-CARDINALITIES? 0= IF
        R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    R@ _SPAW.AUTHORITY-ROOT SAR.RECLAIM-STATE
        RECLAIM-STATE-SIZE
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @
    R@ _SPAW.RECLAIM RECLAIM-OPEN
    _SPA-PERSIST>STATUS
    DUP IF R> DROP EXIT THEN DROP
    -1 R@ _SPAW.AUTHORITY-PRESENT !
    _SPAW-STATE-READY R@ _SPAW.STATE !
    0 R@ _SPAW.STAGING-ACTIVE !
    R> DROP STREAMS-PA-S-OK ;

\ Serialization copies all physical roots and finalized reclaim state before
\ sealing.  Header validation and bound cardinality reconciliation are then
\ repeated before any page can become the PSTORE application root.
: _SPAW-WORK>ROOT  ( work -- status )
    >R
    R@ _SPAW.AUTHORITY-PRESENT @ 0= IF
        R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    R@ _SPAW-ROOTS-PROPOSED? 0= IF
        R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    0
    BEGIN DUP _SPA-TREE-COUNT < WHILE
        DUP R@ _SPAW-ROOT
        OVER R@ _SPAW.AUTHORITY-ROOT
            STREAMS-AUTHORITY-ROOT-TREE
        PBTREE-ROOT-COPY
        DUP IF
            _SPA-PERSIST>STATUS >R DROP R> R> DROP EXIT
        THEN DROP
        1+
    REPEAT
    DROP
    R@ _SPAW.AUTHORITY-ROOT SAR.RECLAIM-STATE
        RECLAIM-STATE-SIZE
    R@ _SPAW.RECLAIM-WORK RECLAIM-STATE!
    DUP IF _SPA-PERSIST>STATUS R> DROP EXIT THEN DROP
    R@ _SPAW.AUTHORITY-ROOT STREAMS-AUTHORITY-ROOT-SEAL
        _SPA-ROOT>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SPAW.AUTHORITY-ROOT
        STREAMS-AUTHORITY-ROOT-HEADER-CLASSIFY
        _SPA-ROOT>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SPAW-CARDINALITIES? 0= IF
        R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-PA-S-OK ;

: _SPAW-LOAD-CURRENT  ( work -- status )
    >R
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @ PSTORE-CURRENT-ROOT@
    DUP 0= IF DROP R> DROP STREAMS-PA-S-CORRUPT EXIT THEN
    PROOTV.APPLICATION-ROOT @ DUP 0< IF
        DROP R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    R@ _SPAW.PAGE-ID !
    R@ _SPAW.PAGE-ID @ R@ _SPAW.APP-ROOT-PAGE !
    R@ _SPAW.PAGE-ID @
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @
    R@ _SPAW.PSTORE-WORK @ PSTORE-READ-PAGE
    DUP IF _SPA-PERSIST>STATUS R> DROP EXIT THEN DROP
    R@ _SPAW.PSTORE-WORK @ PSTORE-PAGE-PAYLOAD$
    R> _SPAW-ROOT>WORK ;

: _SPAW-BIND-EMPTY-RECLAIM  ( work -- status )
