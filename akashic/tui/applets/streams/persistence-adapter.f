: _SPA-ADD?  ( nonnegative-a nonnegative-b -- sum flag )
    OVER 0< OVER 0< OR IF 2DROP 0 0 EXIT THEN
    2DUP + DUP 0< IF DROP 2DROP 0 0 EXIT THEN
    DUP PERSIST-MAX-SIGNED > IF DROP 2DROP 0 0 EXIT THEN
    DUP 3 PICK U< IF DROP 2DROP 0 0 EXIT THEN
    >R 2DROP R> -1 ;

: _SPA-MUL?  ( nonnegative-a positive-small-b -- product flag )
    OVER 0< OVER 0> 0= OR IF 2DROP 0 0 EXIT THEN
    PERSIST-MAX-SIGNED OVER / 2 PICK < IF
        2DROP 0 0 EXIT
    THEN
    * -1 ;

: _SPAW-DIRECTORY-CARDINALITY?  ( authority-root work -- flag )
