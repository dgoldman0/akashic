    OVER _SPAW-COMMIT-FINALIZE
    OVER _SPAW.STAGING-ACTIVE 0 SWAP !
    ROT ROT _SPAW-LEAVE ;

\ Atomically publish the first checked Streams application-root after cold
\ import and exact staged readback.  Unlike an ordinary logical mutation,
\ migration begins at semantic generation zero; the physical PSTORE
\ generation still advances normally at the authority flip.
: _SPAW-FIRST-STAGE-COMMIT-RUN  ( work -- status )
    >R
    R@ _SPAW.STATE @ _SPAW-STATE-ACTIVE <> IF
        R> DROP STREAMS-PA-S-BUSY EXIT
    THEN
    R@ _SPAW.STAGING-ACTIVE @ 0= IF
        R> DROP STREAMS-PA-S-CONFLICT EXIT
    THEN
    R@ _SPAW.OLD-ROOT-PAGE @ 0>= IF
        R> DROP STREAMS-PA-S-CONFLICT EXIT
    THEN
    R@ _SPAW.AUTHORITY-PRESENT @ 0= IF
        R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    R@ _SPAW-STAGING-ROOTS-ADVANCE
    DUP IF R@ _SPAW-ABORT-ACTIVE R> DROP EXIT THEN DROP
    R@ _SPAW-STAGING>ROOTS
    DUP IF R@ _SPAW-ABORT-ACTIVE R> DROP EXIT THEN DROP
    1 R@ _SPAW.MUTATION-N !
    1 R@ _SPAW.PHYSICAL-ONLY-N !
    R@ _SPAW-PUBLISH-RUN
    0 R@ _SPAW.STAGING-ACTIVE !
    R> DROP ;

: STREAMS-PA-FIRST-STAGE-COMMIT  ( adapter work -- status )
    2DUP _SPAW-ENTER DUP IF >R 2DROP R> EXIT THEN DROP
    DUP ['] _SPAW-FIRST-STAGE-COMMIT-RUN _SPAW-WORK-CATCH
    OVER _SPAW-COMMIT-FINALIZE
    OVER _SPAW.STAGING-ACTIVE 0 SWAP !
    ROT ROT _SPAW-LEAVE ;

: STREAMS-PA-STAGED-TREE-CARDINALITY@  ( tree-index work -- count|-1 )
    >R
    R@ STREAMS-PA-WORK-VALID? 0= IF DROP R> DROP -1 EXIT THEN
    DUP 0< OVER _SPA-TREE-COUNT >= OR IF
        DROP R> DROP -1 EXIT
    THEN
    R@ _SPAW.STATE @ _SPAW-STATE-ACTIVE <>
    R@ _SPAW.STAGING-ACTIVE @ 0= OR IF
        DROP R> DROP -1 EXIT
    THEN
    R> _SPAW-STAGING-ROOT PBTREE-ROOT-CARDINALITY@ ;

: _SPAW-STAGE-DISCARD-RUN  ( work -- status )
    >R
    STREAMS-PA-S-OK R@ _SPAW.TEMP-STATUS !
    R@ _SPAW.STATE @ _SPAW-STATE-ACTIVE = IF
        STREAMS-PA-S-OK R@ _SPAW-ABORT-ACTIVE
        R@ _SPAW.TEMP-STATUS !
    THEN
    0 R@ _SPAW.STAGING-ACTIVE !
    R@ _SPAW.STATE @ _SPAW-STATE-READY <> IF
        R@ _SPAW-OPEN-RUN
        DUP STREAMS-PA-S-OK =
        OVER STREAMS-PA-S-ABSENT = OR IF
            DROP
        ELSE
            R@ _SPAW.TEMP-STATUS !
        THEN
    THEN
    R@ _SPAW.TEMP-STATUS @ R> DROP ;

