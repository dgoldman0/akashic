: _SPAW-COMMIT-DURABLE?  ( work -- flag )
    >R
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @ PSTORE-GENERATION@
    R@ _SPAW.BASE-GENERATION @ 1+ =
    R@ _SPAW.PSTORE-WORK @ PSTORE-PROPOSED-ROOT@ 0= AND
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @ PSTORE-UNCERTAIN? 0= AND
    R> DROP ;

: _SPAW-PUBLISH-RUN  ( work -- status )
    >R
    R@ _SPAW.STATE @ _SPAW-STATE-ACTIVE <> IF
        R> DROP STREAMS-PA-S-BUSY EXIT
    THEN
    R@ _SPAW-ROOTS-ADVANCE
    DUP IF R@ _SPAW-ABORT-ACTIVE R> DROP EXIT THEN DROP
    R@
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @
    R@ _SPAW.PSTORE-WORK @ _SPAW-ALLOCATE
    DUP IF
        _SPA-PERSIST>STATUS >R DROP R>
        R@ _SPAW-ABORT-ACTIVE R> DROP EXIT
    THEN DROP
    R@ _SPAW.APP-ROOT-PAGE !
    \ Claim the application-root slot before reclaim finalization, including
    \ when a high-water staging transaction cannot consume ready pages.
    R@ _SPAW.PAGE PERSIST-PAGE-PAYLOAD-SIZE 0 FILL
    R@ _SPAW.PAGE PERSIST-PAGE-PAYLOAD-SIZE
    R@ _SPAW.APP-ROOT-PAGE @
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @
    R@ _SPAW.PSTORE-WORK @ PSTORE-WRITE-PAGE-TX
    DUP IF
        _SPA-PERSIST>STATUS R@ _SPAW-ABORT-ACTIVE
        R> DROP EXIT
    THEN DROP
    R@ _SPAW.RECLAIM-WORK RECLAIM-FINALIZE
    DUP IF
        _SPA-PERSIST>STATUS R@ _SPAW-ABORT-ACTIVE
        R> DROP EXIT
    THEN DROP
    R@ _SPAW-WORK>ROOT
    DUP IF R@ _SPAW-ABORT-ACTIVE R> DROP EXIT THEN DROP
    R@ _SPAW.AUTHORITY-ROOT STREAMS-AUTHORITY-ROOT-SIZE
    R@ _SPAW.APP-ROOT-PAGE @
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @
    R@ _SPAW.PSTORE-WORK @ PSTORE-WRITE-PAGE-TX
    DUP IF
        _SPA-PERSIST>STATUS R@ _SPAW-ABORT-ACTIVE
        R> DROP EXIT
    THEN DROP
    R@ _SPAW.APP-ROOT-PAGE @
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @
    R@ _SPAW.PSTORE-WORK @ PSTORE-APPLICATION-ROOT!
    DUP IF
        _SPA-PERSIST>STATUS R@ _SPAW-ABORT-ACTIVE
        R> DROP EXIT
    THEN DROP
    R@ _SPAW.ADAPTER @ _SPA-D.STORE @
    R@ _SPAW.PSTORE-WORK @ PSTORE-COMMIT
    _SPA-PERSIST>STATUS R@ _SPAW.TEMP-STATUS !
    R@ _SPAW-COMMIT-DURABLE? IF
        R@ _SPAW.RECLAIM-WORK R@ _SPAW.RECLAIM RECLAIM-ADOPT
        DUP IF
            _SPA-PERSIST>STATUS
            R@ _SPAW.TEMP-STATUS @ STREAMS-PA-S-OK = IF
                R@ _SPAW.TEMP-STATUS !
            ELSE
                DROP
            THEN
            _SPAW-STATE-REOPEN R@ _SPAW.STATE !
        ELSE
            DROP
            _SPAW-STATE-READY R@ _SPAW.STATE !
        THEN
    ELSE
        R@ _SPAW.TEMP-STATUS @ R@ _SPAW-ABORT-ACTIVE DROP
    THEN
    R@ _SPAW.TEMP-STATUS @ R> DROP ;

: _SPAW-INCREMENT-LOGICAL  ( work -- status )
    >R
    R@ _SPAW.AUTHORITY-ROOT SAR.LOGICAL-GENERATION @
        PERSIST-MAX-SIGNED >= IF
        R> DROP STREAMS-PA-S-CAPACITY EXIT
    THEN
    R@ _SPAW.AUTHORITY-ROOT SAR.MUTATION-SEQUENCE @
        PERSIST-MAX-SIGNED >= IF
        R> DROP STREAMS-PA-S-CAPACITY EXIT
    THEN
    1 R@ _SPAW.AUTHORITY-ROOT SAR.LOGICAL-GENERATION +!
    1 R@ _SPAW.AUTHORITY-ROOT SAR.MUTATION-SEQUENCE +!
    R> DROP STREAMS-PA-S-OK ;

: _SPAW-COMMIT-RUN  ( work -- status )
    >R
    R@ _SPAW.STATE @ _SPAW-STATE-ACTIVE <> IF
        R> DROP STREAMS-PA-S-BUSY EXIT
    THEN
    R@ _SPAW.STAGING-ACTIVE @ IF
        R> DROP STREAMS-PA-S-CONFLICT EXIT
    THEN
    R@ _SPAW.MUTATION-N @ 0= IF
        STREAMS-PA-S-INVALID R@ _SPAW-ABORT-ACTIVE
        R> DROP EXIT
    THEN
    R@ _SPAW.AUTHORITY-ROOT SAR.AUTHORITY-ID RID-PRESENT? 0= IF
        STREAMS-PA-S-CORRUPT R@ _SPAW-ABORT-ACTIVE
        R> DROP EXIT
    THEN
    R@ _SPAW-INCREMENT-LOGICAL
    DUP IF R@ _SPAW-ABORT-ACTIVE R> DROP EXIT THEN DROP
    0 R@ _SPAW.PHYSICAL-ONLY-N !
    R@ _SPAW-PUBLISH-RUN
    R> DROP ;

: _SPAW-COMMIT-FINALIZE  ( primary-status work -- final-status )
    >R
    DUP R@ _SPAW.TEMP-STATUS !
    R@ _SPAW.STATE @ _SPAW-STATE-ACTIVE <> IF
        R> DROP EXIT
    THEN
    R@ _SPAW-COMMIT-DURABLE? IF
        R@ _SPAW.RECLAIM-WORK R@ _SPAW.RECLAIM RECLAIM-ADOPT
        DUP IF
            _SPA-PERSIST>STATUS
            R@ _SPAW.TEMP-STATUS @ STREAMS-PA-S-OK = IF
                R@ _SPAW.TEMP-STATUS !
            ELSE
                DROP
            THEN
            _SPAW-STATE-REOPEN R@ _SPAW.STATE !
        ELSE
            DROP
            _SPAW-STATE-READY R@ _SPAW.STATE !
        THEN
    ELSE
        R@ _SPAW-ABORT-ACTIVE
    THEN
    DROP R@ _SPAW.TEMP-STATUS @ R> DROP ;

: STREAMS-PA-COMMIT  ( adapter work -- status )
    2DUP _SPAW-ENTER DUP IF >R 2DROP R> EXIT THEN DROP
    DUP ['] _SPAW-COMMIT-RUN _SPAW-WORK-CATCH
    OVER _SPAW-COMMIT-FINALIZE
    ROT ROT _SPAW-LEAVE ;

\ Provision is the sole native empty-template initializer.  It publishes
\ generation-zero semantic metadata without pretending that provisioning is
\ a configured-source mutation.
: _SPAW-PROVISION-RUN  ( work -- status )
    >R
    R@ _SPAW-READY? 0= IF R> DROP STREAMS-PA-S-BUSY EXIT THEN
    R@ _SPAW.ARG-A @ RID-SIZE R@ _SPAW-SPAN-SAFE? 0= IF
        R> DROP STREAMS-PA-S-INVALID EXIT
    THEN
    R@ _SPAW.ARG-A @ RID-PRESENT? 0= IF
        R> DROP STREAMS-PA-S-INVALID EXIT
    THEN
    R@ _SPAW.APP-ROOT-PAGE @ 0>= IF
        R@ _SPAW.ARG-A @
        R@ _SPAW.AUTHORITY-ROOT SAR.AUTHORITY-ID RID=
        IF STREAMS-PA-S-OK ELSE STREAMS-PA-S-CONFLICT THEN
        R> DROP EXIT
    THEN
    R@ _SPAW-BEGIN-RUN DUP IF R> DROP EXIT THEN DROP
    R@ _SPAW.ARG-A @ R@ _SPAW.AUTHORITY-ROOT
        STREAMS-AUTHORITY-ROOT-TEMPLATE-INIT
        _SPA-ROOT>STATUS
    DUP IF R@ _SPAW-ABORT-ACTIVE R> DROP EXIT THEN DROP
    -1 R@ _SPAW.AUTHORITY-PRESENT !
    1 R@ _SPAW.MUTATION-N !
    1 R@ _SPAW.PHYSICAL-ONLY-N !
    R@ _SPAW-PUBLISH-RUN
    R> DROP ;

