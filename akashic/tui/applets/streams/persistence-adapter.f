\ ---------------------------------------------------------------------
\ Bounded semantic ranges
\ ---------------------------------------------------------------------
\ Only the five query-bearing L13 families plus bounded ACTIVE-ATTEMPT
\ recovery are admitted here.  ACTIVE-ATTEMPT, SOURCE-ORDER, and GLOBAL-TIME
\ require their exact one-byte family prefix; ATTEMPT-BY-SOURCE,
\ OBSERVATION-REVISION, and SOURCE-TIME require their exact RID-scoped prefix.
\ THREAD-TIME is explicitly unsupported in ABI 1.
\
\ FIRST walks forward from the exact prefix.  LAST starts immediately before
\ the family's canonical seek-only upper boundary and walks backward.  AFTER
\ walks forward strictly after a complete semantic key.  BEFORE walks backward
\ strictly before a complete semantic key.  Backward results are reversed into
\ ascending key order before return.  Thus callers resume AFTER with the last
\ row's KEY$, and resume BEFORE with the first row's KEY$.  No physical cursor
\ or storage identity crosses the call boundary.

0 CONSTANT _SPA-RANGE-FIRST
1 CONSTANT _SPA-RANGE-AFTER
2 CONSTANT _SPA-RANGE-BEFORE
