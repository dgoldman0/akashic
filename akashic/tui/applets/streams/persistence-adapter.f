: _SPAW-INIT-GEOMETRY?  ( pstore-work adapter work -- flag )
    2 PICK PSTORE-WORK-VALID? 0= IF _SPA-DROP3 0 EXIT THEN
    1 PICK STREAMS-PA-VALID? 0= IF _SPA-DROP3 0 EXIT THEN
    DUP STREAMS-PA-WORK-SIZE MSPAN-NONWRAPPING? 0= IF
        _SPA-DROP3 0 EXIT
    THEN
    DUP STREAMS-PA-WORK-SIZE 4 PICK PSTORE-WORK-SIZE
        MSPAN-OVERLAP? IF _SPA-DROP3 0 EXIT THEN
    DUP STREAMS-PA-WORK-SIZE 4 PICK
        PSTORE-WORK-SPAN-DISJOINT? 0= IF _SPA-DROP3 0 EXIT THEN
    DUP STREAMS-PA-WORK-SIZE 3 PICK STREAMS-PA-SIZE
        MSPAN-OVERLAP? IF _SPA-DROP3 0 EXIT THEN
    1 PICK STREAMS-PA-SIZE 4 PICK
        PSTORE-WORK-SPAN-DISJOINT? 0= IF _SPA-DROP3 0 EXIT THEN
    DUP STREAMS-PA-WORK-SIZE 3 PICK _SPA-D.STORE @
        PSTORE-SPAN-DISJOINT? 0= IF _SPA-DROP3 0 EXIT THEN
    2 PICK PSTORE-WORK-RECORD-BUFFER$
    DUP STREAMS-PA-RECORD-BUFFER-MIN < IF
        2DROP _SPA-DROP3 0 EXIT
    THEN
    2DUP 4 PICK STREAMS-PA-WORK-SIZE MSPAN-OVERLAP? IF
        2DROP _SPA-DROP3 0 EXIT
    THEN
    2DROP _SPA-DROP3 -1 ;

: STREAMS-PA-WORK-VALID?  ( work -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-PA-WORK-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SPAW.MAGIC @ _SPAW-MAGIC <> IF DROP 0 EXIT THEN
    DUP _SPAW.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _SPAW.BUSY @ DUP 0= SWAP -1 = OR 0= IF DROP 0 EXIT THEN
    DUP _SPAW.STATE @ DUP _SPAW-STATE-READY >=
        SWAP _SPAW-STATE-REOPEN <= AND 0= IF DROP 0 EXIT THEN
    DUP _SPAW.STATUS @ _SPA-STATUS? 0= IF DROP 0 EXIT THEN
    DUP _SPAW.ADAPTER @ STREAMS-PA-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SPAW.PSTORE-WORK @ PSTORE-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SPAW.RECLAIM RECLAIM-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SPAW.RECLAIM-WORK RECLAIM-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SPAW.BTREE-WORK PBTREE-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _SPAW.BLOB-WORK PBLOB-WORK-VALID? 0= IF DROP 0 EXIT THEN
    0
    BEGIN DUP _SPA-TREE-COUNT < WHILE
        DUP 2 PICK _SPAW-TREE PBTREE-VALID? 0= IF
            2DROP 0 EXIT
        THEN
        1+
    REPEAT
    DROP DROP -1 ;

: STREAMS-PA-WORK-INIT  ( pstore-work adapter work -- status )
    2 PICK 2 PICK 2 PICK _SPAW-INIT-GEOMETRY? 0= IF
        _SPA-DROP3 STREAMS-PA-S-INVALID EXIT
    THEN
    >R
    R@ STREAMS-PA-WORK-SIZE 0 FILL
    _SPAW-MAGIC R@ _SPAW.MAGIC !
    R@ R@ _SPAW.SELF !
    STREAMS-PA-S-OK R@ _SPAW.STATUS !
    OVER R@ _SPAW.PSTORE-WORK !
    DUP R@ _SPAW.ADAPTER !
    OVER R@ _SPAW.BTREE-WORK PBTREE-WORK-INIT
    DUP IF
        _SPA-PERSIST>STATUS >R 2DROP R> R> DROP EXIT
    THEN DROP
    R@ _SPAW.BLOB-WORK PBLOB-WORK-INIT
    DUP IF
        _SPA-PERSIST>STATUS >R 2DROP R> R> DROP EXIT
    THEN DROP
    R@ _SPAW.RECLAIM RECLAIM-INIT
    DUP IF
        _SPA-PERSIST>STATUS >R 2DROP R> R> DROP EXIT
    THEN DROP
    R@ _SPAW.RECLAIM-WORK RECLAIM-WORK-INIT
    DUP IF
        _SPA-PERSIST>STATUS >R 2DROP R> R> DROP EXIT
    THEN DROP
    0
    BEGIN DUP _SPA-TREE-COUNT < WHILE
        DUP R@ _SPAW-INIT-TREE
        DUP IF >R _SPA-DROP3 R> R> DROP EXIT THEN DROP
        1+
    REPEAT
    DROP
    _SPAW-STATE-REOPEN R@ _SPAW.STATE !
    -1 R@ _SPAW.APP-ROOT-PAGE !
    2DROP R> DROP STREAMS-PA-S-OK ;

: _SPA-BOUND?  ( adapter work -- flag )
    >R
    DUP STREAMS-PA-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    R@ STREAMS-PA-WORK-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    R@ _SPAW.ADAPTER @ OVER <> IF DROP R> DROP 0 EXIT THEN
    DUP STREAMS-PA-SIZE R@ STREAMS-PA-WORK-SIZE
        MSPAN-OVERLAP? IF DROP R> DROP 0 EXIT THEN
    DUP STREAMS-PA-SIZE R@ _SPAW.PSTORE-WORK @
        PSTORE-WORK-SPAN-DISJOINT? 0= IF DROP R> DROP 0 EXIT THEN
    R@ STREAMS-PA-WORK-SIZE R@ _SPAW.PSTORE-WORK @
        PSTORE-WORK-SPAN-DISJOINT? 0= IF DROP R> DROP 0 EXIT THEN
    DUP _SPA-D.STORE @
    R@ STREAMS-PA-WORK-SIZE 2 PICK PSTORE-SPAN-DISJOINT?
    NIP NIP R> DROP ;

: _SPAW-ENTER  ( adapter work -- status )
    2DUP _SPA-BOUND? 0= IF
        2DROP STREAMS-PA-S-INVALID EXIT
    THEN
    DUP _SPAW.BUSY @ IF 2DROP STREAMS-PA-S-BUSY EXIT THEN
    -1 OVER _SPAW.BUSY !
    STREAMS-PA-S-INVALID OVER _SPAW.STATUS !
    2DROP STREAMS-PA-S-OK ;

: _SPAW-LEAVE  ( status adapter work -- status )
    >R
    OVER OVER _SPA-D.STATUS !
    OVER R@ _SPAW.STATUS !
    0 R@ _SPAW.BUSY !
    DROP R> DROP ;

