    DUP _SPAW.STATE @ _SPAW-STATE-ACTIVE <> IF
        DROP STREAMS-PA-S-BUSY EXIT
    THEN
    STREAMS-PA-S-OK SWAP _SPAW-ABORT-ACTIVE ;

: STREAMS-PA-ABORT  ( adapter work -- status )
    2DUP _SPAW-ENTER DUP IF >R 2DROP R> EXIT THEN DROP
    DUP ['] _SPAW-ABORT-RUN _SPAW-WORK-CATCH
    ROT ROT _SPAW-LEAVE ;

: _SPAW-MARK-MUTATED-RUN  ( work -- status )
