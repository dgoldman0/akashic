    \ retain only their source-rid tombstone; accepted attempts add active rows.
    DUP SAR.SOURCE-COUNT @ 2 _SPA-MUL?
    0= IF 2DROP R> DROP 0 EXIT THEN
    OVER SAR.REMOVED-SOURCE-COUNT @ _SPA-ADD?
    0= IF 2DROP R> DROP 0 EXIT THEN
    OVER SAR.ACTIVE-COUNT @ _SPA-ADD?
    0= IF 2DROP R> DROP 0 EXIT THEN
    STREAMS-PI-TREE-DIRECTORY R@ _SPAW-ROOT
        PBTREE-ROOT-CARDINALITY@ =
    NIP R> DROP ;

