: _SPA-BYTES=  ( a b u -- flag )
    DUP 0< IF DROP 2DROP 0 EXIT THEN
    DUP 0= IF DROP 2DROP -1 EXIT THEN
    2 PICK 0= 2 PICK 0= OR IF DROP 2DROP 0 EXIT THEN
    2 PICK OVER MSPAN-NONWRAPPING? 0= IF
        DROP 2DROP 0 EXIT
    THEN
