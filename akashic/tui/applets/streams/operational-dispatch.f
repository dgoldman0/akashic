\ PBLOB admission source:
\ ( logical-offset destination requested-u dispatch -- actual-u persist-status )
: _SOD-ENQUEUE-SOURCE
  ( offset destination requested-u dispatch -- actual-u persist-status )
    >R
    R@ _SOD.BUSY @ 0= IF
        _SOD-DROP3 R> DROP 0 PERSIST-S-CONFLICT EXIT
    THEN
    R@ _SOD.SOURCE-CARRIER @ DUP STREAMS-PAYLOAD-VALID? 0= IF
        DROP _SOD-DROP3 R> DROP 0 PERSIST-S-CORRUPT EXIT
    THEN
    DROP
    DUP R@ _SOD.SOURCE-U !
    2 PICK 2 PICK 2 PICK
    R@ _SOD.SOURCE-GENERATION @
    R@ _SOD.SOURCE-CARRIER @ STREAMS-PAYLOAD-READ
    >R _SOD-DROP3 R>
    CASE
        STREAMS-PAYLOAD-S-OK OF
            R@ _SOD.SOURCE-U @ PERSIST-S-OK
        ENDOF
        STREAMS-PAYLOAD-S-BUSY OF 0 PERSIST-S-BUSY ENDOF
        STREAMS-PAYLOAD-S-CAPACITY OF 0 PERSIST-S-CAPACITY ENDOF
        STREAMS-PAYLOAD-S-STALE OF 0 PERSIST-S-CONFLICT ENDOF
        0 PERSIST-S-CORRUPT ROT
    ENDCASE
    R> DROP ;

: _SOD-BUILD-REQUEST  ( accepted-ms flow dispatch -- status )
    >R
    DUP R@ _SOD-EGRESS-EVENT-MATCHES? 0= IF
        2DROP R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    DUP SFLOW.EGRESS-EVENT SEVT.RECEIVED-MS @ 2 PICK > IF
        2DROP R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    R@ _SOD.REQUEST STREAMS-SPOOL-REQUEST-INIT
    STREAMS-SPOOL-S-OK <> IF
        2DROP R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    ['] _SOD-ENQUEUE-SOURCE
        R@ _SOD.REQUEST SPOOLREQ.SOURCE-XT !
    R@ R@ _SOD.REQUEST SPOOLREQ.SOURCE-CONTEXT !
    DUP SFLOW.EGRESS-CARRIER DUP
        R@ _SOD.SOURCE-CARRIER !
    SPAY.GENERATION @ R@ _SOD.SOURCE-GENERATION !
    DUP SFLOW.EGRESS-EVENT SEVT.PAYLOAD-U @
        R@ _SOD.REQUEST SPOOLREQ.PAYLOAD-U !
    R@ _SOD.CONNECTOR SOPCONN.REVISION @
        R@ _SOD.REQUEST SPOOLREQ.CONNECTOR-REVISION !
    R@ _SOD.FLOW-CONFIG SOPFLOW.REVISION @
        R@ _SOD.REQUEST SPOOLREQ.FLOW-REVISION !
    R@ _SOD.CONNECTOR SOPCONN.PROTOCOL @
        R@ _SOD.REQUEST SPOOLREQ.PROTOCOL !
    R@ _SOD.CONNECTOR SOPCONN.PROFILE @
        R@ _SOD.REQUEST SPOOLREQ.PROFILE !
    R@ _SOD.MEDIA @ R@ _SOD.REQUEST SPOOLREQ.MEDIA !
    DUP SFLOW.EGRESS-EVENT SEVT.RECEIVED-MS @
        R@ _SOD.REQUEST SPOOLREQ.RECEIVED-MS !
    OVER R@ _SOD.REQUEST SPOOLREQ.ACCEPTED-MS !
    R@ _SOD-OPCONN-IDEMPOTENCY
        R@ _SOD.REQUEST SPOOLREQ.IDEMPOTENCY-POLICY !
    DUP SFLOW.EGRESS-EVENT SEVT.EVENT-ID
        R@ _SOD.REQUEST SPOOLREQ.EVENT-ID RID-COPY
    R@ _SOD.CONNECTOR SOPCONN.CONNECTOR-ID
        R@ _SOD.REQUEST SPOOLREQ.CONNECTOR-ID RID-COPY
    R@ _SOD.FLOW-CONFIG SOPFLOW.FLOW-ID
        R@ _SOD.REQUEST SPOOLREQ.FLOW-ID RID-COPY
    DUP SFLOW.EGRESS-EVENT SEVT.CORRELATION-ID
        R@ _SOD.REQUEST SPOOLREQ.CORRELATION-ID RID-COPY
    DUP SFLOW.EGRESS-EVENT SEVT.IDEMPOTENCY-ID
        R@ _SOD.REQUEST SPOOLREQ.IDEMPOTENCY-ID RID-COPY
    DUP SFLOW.EGRESS-EVENT SEVT.ORIGIN-ID
        R@ _SOD.REQUEST SPOOLREQ.ORIGIN-ID RID-COPY
    R@ _SOD.CONNECTOR SOPCONN.ENDPOINT-ID
        R@ _SOD.REQUEST SPOOLREQ.DESTINATION-ID RID-COPY
    R@ _SOD.CONNECTOR SOPCONN.ENDPOINT-SEAL
        R@ _SOD.REQUEST SPOOLREQ.ENDPOINT-SEAL RID-COPY
    DUP SFLOW.EGRESS-EVENT SEVT.PAYLOAD-DIGEST
        R@ _SOD.REQUEST SPOOLREQ.PAYLOAD-DIGEST RID-COPY
    2DROP
    R@ _SOD.REQUEST STREAMS-SPOOL-REQUEST-VALID? IF
        STREAMS-OPDISPATCH-S-OK
    ELSE
        STREAMS-OPDISPATCH-S-INVALID
    THEN
    R> DROP ;

: STREAMS-OPDISPATCH-ENQUEUE
  ( output-ready-flow accepted-ms result dispatch -- status )
    >R
    R@ _SOD-ENTER DUP IF
        >R _SOD-DROP3 R> R> DROP EXIT
    THEN DROP
    R@ _SOD.STATE @ STREAMS-OPDISPATCH-STATE-READY <> IF
        _SOD-DROP3
        STREAMS-OPDISPATCH-S-BUSY R> _SOD-LEAVE EXIT
    THEN
    1 PICK _SOD-NONNEG? 0= IF
        _SOD-DROP3
        STREAMS-OPDISPATCH-S-INVALID R> _SOD-LEAVE EXIT
    THEN
    DUP 0= IF
        _SOD-DROP3
        STREAMS-OPDISPATCH-S-INVALID R> _SOD-LEAVE EXIT
    THEN
    DUP STREAMS-SPOOL-RESULT-SIZE MSPAN-NONWRAPPING? 0= IF
        _SOD-DROP3
        STREAMS-OPDISPATCH-S-INVALID R> _SOD-LEAVE EXIT
    THEN
    1 PICK 3 PICK R@ _SOD-BUILD-REQUEST
    DUP IF
        >R _SOD-DROP3 R>
        R@ _SOD-CLEAR-SOURCE
        R> _SOD-LEAVE EXIT
    THEN DROP
    R@ _SOD.REQUEST
    1 PICK
    R@ _SOD.SPOOL @ R@ _SOD.SPOOL-WORK @
    STREAMS-SPOOL-ADMIT
    DUP R@ _SOD.SPOOL-STATUS !
    _SOD-SPOOL>STATUS
    R@ _SOD-CLEAR-SOURCE
    >R _SOD-DROP3
    R> R> _SOD-LEAVE ;

