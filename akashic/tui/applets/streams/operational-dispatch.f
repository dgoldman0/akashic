\ =====================================================================
\ operational-dispatch.f - SR2 runtime / SR3 durable outbox composition
\ =====================================================================
\ This is the sole composition edge between the storage-free execution pool
\ and the durable operational spool.  The caller owns every descriptor and
\ workspace.  Runtime addresses live only in this descriptor while a process
\ is running; durable records continue to contain semantic values only.
\
\ ENQUEUE snapshots one exact OUTPUT-READY SR2 egress event into the durable
\ outbox without starting its output connector.  The producer flow remains
\ caller-owned and must be cancelled/retired after ENQUEUE returns; the bridge
\ never guesses a producer lease it was not given.  DISPATCH selects one durable
\ READY attempt, acquires a fitting SR2 cell, reconstructs the exact egress
\ event, and durably activates the attempt before POLL may invoke START.
\ Terminal runtime evidence is durably committed before RELEASE retires and
\ returns that newly acquired delivery cell to its pool.
\ =====================================================================

