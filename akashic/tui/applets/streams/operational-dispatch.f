    -1 SWAP _SOD.BUSY !
    STREAMS-OPDISPATCH-S-OK ;

\ The two authorities validate their own internal geometry independently.
\ Their sole composition edge must additionally prove that every mutable pool
\ span avoids the dispatcher, spool workspace, and complete PSTORE authority.
: _SOD-POOL-SPAN-SAFE?  ( a u spool-work dispatch -- flag )
    >R
    2 PICK 2 PICK R@ STREAMS-OPDISPATCH-SIZE
        MSPAN-OVERLAP? IF
        _SOD-DROP3 R> DROP 0 EXIT
    THEN
    _SSPW-SPAN-SAFE?
    R> DROP ;

: _SOD-PAYLOAD-SPANS-SAFE?  ( payload spool-work dispatch -- flag )
    2 PICK STREAMS-PAYLOAD-BOUND? 0= IF _SOD-DROP3 0 EXIT THEN
    2 PICK STREAMS-PAYLOAD-SIZE
    3 PICK 3 PICK _SOD-POOL-SPAN-SAFE? 0= IF
        _SOD-DROP3 0 EXIT
    THEN
    2 PICK SPAY.SEGMENTS @
    3 PICK SPAY.SEGMENT-N @ STREAMS-PAYLOAD-SEGMENT-BYTES
    3 PICK 3 PICK _SOD-POOL-SPAN-SAFE? 0= IF
        _SOD-DROP3 0 EXIT
    THEN
    2 PICK SPAY.SEGMENT-N @ 0 ?DO
        I 3 PICK _SPAY-SEGMENT
        DUP SPSEG.DATA @ SWAP SPSEG.CAPACITY @
        3 PICK 3 PICK _SOD-POOL-SPAN-SAFE? 0= IF
            _SOD-DROP3 0 UNLOOP EXIT
        THEN
    LOOP
    _SOD-DROP3 -1 ;

: _SOD-POOL-ENTRY-SPANS-SAFE?  ( entry spool-work dispatch -- flag )
    2 PICK _SPE.FLOW @ STREAMS-FLOW-SIZE
    3 PICK 3 PICK _SOD-POOL-SPAN-SAFE? 0= IF
        _SOD-DROP3 0 EXIT
    THEN
    2 PICK _SPE.INGRESS-CARRIER @
    2 PICK 2 PICK _SOD-PAYLOAD-SPANS-SAFE? 0= IF
        _SOD-DROP3 0 EXIT
    THEN
    2 PICK _SPE.EGRESS-CARRIER @
    2 PICK 2 PICK _SOD-PAYLOAD-SPANS-SAFE? 0= IF
        _SOD-DROP3 0 EXIT
    THEN
    2 PICK _SPE.OPERATION @
    3 PICK _SPE.OPERATION-CAPACITY @
    3 PICK 3 PICK _SOD-POOL-SPAN-SAFE? 0= IF
        _SOD-DROP3 0 EXIT
    THEN
    2 PICK _SPE.INPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
    3 PICK 3 PICK _SOD-POOL-SPAN-SAFE? 0= IF
        _SOD-DROP3 0 EXIT
    THEN
    2 PICK _SPE.OUTPUT-CONNECTOR @ STREAMS-CONNECTOR-SIZE
    3 PICK 3 PICK _SOD-POOL-SPAN-SAFE? 0= IF
        _SOD-DROP3 0 EXIT
    THEN
    _SOD-DROP3 -1 ;

: _SOD-POOL-SPANS-SAFE?  ( pool spool-work dispatch -- flag )
    2 PICK STREAMS-EXECUTION-POOL-VALID? 0= IF
        _SOD-DROP3 0 EXIT
    THEN
    2 PICK STREAMS-EXECUTION-POOL-SIZE
    3 PICK 3 PICK _SOD-POOL-SPAN-SAFE? 0= IF
        _SOD-DROP3 0 EXIT
    THEN
    2 PICK _SPOOL.ENTRIES @
    3 PICK _SPOOL.CAPACITY @ STREAMS-EXECUTION-ENTRY-SIZE *
    3 PICK 3 PICK _SOD-POOL-SPAN-SAFE? 0= IF
        _SOD-DROP3 0 EXIT
    THEN
    2 PICK _SPOOL.CAPACITY @ 0 ?DO
        I 3 PICK _SPOOL-ENTRY
        2 PICK 2 PICK _SOD-POOL-ENTRY-SPANS-SAFE? 0= IF
            _SOD-DROP3 0 UNLOOP EXIT
        THEN
    LOOP
    _SOD-DROP3 -1 ;

: STREAMS-OPDISPATCH-BIND
  ( spool work pool opflow opconn media dispatch -- status )
    >R
    R@ _SOD-HEADER? 0= IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    R@ _SOD.STATE @ STREAMS-OPDISPATCH-STATE-BUILDING <> IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    R@ _SOD.BUSY @ IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-BUSY EXIT
    THEN
    5 PICK 5 PICK STREAMS-SPOOL-WORK-BOUND? 0= IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    3 PICK STREAMS-EXECUTION-POOL-VALID? 0= IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    2 PICK STREAMS-OPFLOW-SIZE STREAMS-OPFLOW-VALID? 0= IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    1 PICK STREAMS-OPCONN-SIZE STREAMS-OPCONN-VALID? 0= IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    DUP 0> 0= IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    5 PICK STREAMS-SPOOL-SIZE R@ STREAMS-OPDISPATCH-SIZE
        MSPAN-OVERLAP? IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    4 PICK STREAMS-SPOOL-WORK-SIZE R@ STREAMS-OPDISPATCH-SIZE
        MSPAN-OVERLAP? IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    3 PICK STREAMS-EXECUTION-POOL-SIZE R@ STREAMS-OPDISPATCH-SIZE
        MSPAN-OVERLAP? IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    2 PICK STREAMS-OPFLOW-SIZE R@ STREAMS-OPDISPATCH-SIZE
        MSPAN-OVERLAP? IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    1 PICK STREAMS-OPCONN-SIZE R@ STREAMS-OPDISPATCH-SIZE
        MSPAN-OVERLAP? IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    3 PICK 5 PICK R@ _SOD-POOL-SPANS-SAFE? 0= IF
        _SOD-DROP6 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    -1 R@ _SOD.BUSY !
    5 PICK R@ _SOD.SPOOL !
    4 PICK R@ _SOD.SPOOL-WORK !
    3 PICK R@ _SOD.POOL !
    2 PICK R@ _SOD.FLOW-CONFIG STREAMS-OPFLOW-SIZE MOVE
    1 PICK R@ _SOD.CONNECTOR STREAMS-OPCONN-SIZE MOVE
    DUP R@ _SOD.MEDIA !
    _SOD-DROP6
    R@ _SOD-CONFIG-BINDING? 0= IF
        STREAMS-OPDISPATCH-STATE-BUILDING R@ _SOD.STATE !
        STREAMS-OPDISPATCH-S-INVALID R> _SOD-LEAVE EXIT
    THEN
    STREAMS-OPDISPATCH-STATE-READY R@ _SOD.STATE !
    STREAMS-OPDISPATCH-S-OK R> _SOD-LEAVE ;

