: _SOD-DERIVE-EVIDENCE-ID
  ( tag-a tag-u destination dispatch -- status )
    >R
    1 PICK DUP 0< SWAP 32 > OR IF
        _SOD-DROP3 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    DUP 0= IF
        _SOD-DROP3 R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    R@ _SOD.ID-SCRATCH 128 0 FILL
    2 PICK 2 PICK R@ _SOD.ID-SCRATCH SWAP MOVE
    R@ _SOD.ATTEMPT SOPATT.ATTEMPT-ID
        R@ _SOD.ID-SCRATCH 32 + RID-COPY
    R@ _SOD.ATTEMPT SOPATT.EVENT-ID
        R@ _SOD.ID-SCRATCH 64 + RID-COPY
    R@ _SOD.COMPLETION SPOOLCOMP.FINISHED-MS @
        R@ _SOD.ID-SCRATCH 96 + _SOD-U64-BE!
    R@ _SOD.COMPLETION SPOOLCOMP.STATE @
        R@ _SOD.ID-SCRATCH 104 + _SOD-U64-BE!
    R@ _SOD.ID-SCRATCH 112 2 PICK SHA3-256-HASH
    DUP RID-PRESENT? IF
        _SOD-DROP3 R> DROP STREAMS-OPDISPATCH-S-OK
    ELSE
        _SOD-DROP3 R> DROP STREAMS-OPDISPATCH-S-INVALID
    THEN ;

: _SOD-COMPLETION-EVIDENCE!  ( dispatch -- status )
    >R
    R@ _SOD.COMPLETION SPOOLCOMP.STATE @
        STREAMS-OPATT-STATE-DELIVERED = IF
        S" streams-opdispatch-delivery-id"
        R@ _SOD.COMPLETION SPOOLCOMP.DELIVERY-ID R@
            _SOD-DERIVE-EVIDENCE-ID
        DUP IF R> DROP EXIT THEN DROP
        R@ _SOD.COMPLETION SPOOLCOMP.FINISHED-MS @
            R@ _SOD.COMPLETION SPOOLCOMP.DELIVERED-MS !
        R> DROP STREAMS-OPDISPATCH-S-OK EXIT
    THEN
    R@ _SOD.COMPLETION SPOOLCOMP.STATE @
        DUP STREAMS-OPATT-STATE-ACKNOWLEDGED =
        SWAP STREAMS-OPATT-STATE-FAILED-AFTER = OR
    R@ _SOD.COMPLETION SPOOLCOMP.STATE @
        STREAMS-OPATT-STATE-CANCELLED =
    R@ _SOD.COMPLETION SPOOLCOMP.EFFECT @
        STREAMS-OPATT-EFFECT-APPLIED = AND OR IF
        S" streams-opdispatch-ack-id"
        R@ _SOD.COMPLETION SPOOLCOMP.ACKNOWLEDGEMENT-ID R@
            _SOD-DERIVE-EVIDENCE-ID
        DUP IF R> DROP EXIT THEN DROP
        R@ _SOD.COMPLETION SPOOLCOMP.FINISHED-MS @
            R@ _SOD.COMPLETION SPOOLCOMP.ACKNOWLEDGED-MS !
    THEN
    R> DROP STREAMS-OPDISPATCH-S-OK ;

: _SOD-BUILD-COMPLETION  ( dispatch -- status )
    >R
    R@ _SOD.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-TERMINAL <> IF
        R> DROP STREAMS-OPDISPATCH-S-RUNTIME EXIT
    THEN
    R@ _SOD.FLOW @ SFLOW.EGRESS-ATTEMPT
    DUP STREAMS-ATTEMPT-VALID? 0= IF
        DROP R> DROP STREAMS-OPDISPATCH-S-RUNTIME EXIT
    THEN
    R@ _SOD.COMPLETION STREAMS-SPOOL-COMPLETION-INIT
        STREAMS-SPOOL-S-OK <> IF
        DROP R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    DUP SATT.STATE @ _SOD-RUNTIME-STATE>OP
    DUP -1 = IF
        2DROP R> DROP STREAMS-OPDISPATCH-S-RUNTIME EXIT
    THEN
    R@ _SOD.COMPLETION SPOOLCOMP.STATE !
    DUP SATT.EFFECT @ _SOD-RUNTIME-EFFECT>OP
    DUP -1 = IF
        2DROP R> DROP STREAMS-OPDISPATCH-S-RUNTIME EXIT
    THEN
    R@ _SOD.COMPLETION SPOOLCOMP.EFFECT !
    DUP SATT.REASON @ _SOD-RUNTIME-REASON>OP
    DUP -1 = IF
        2DROP R> DROP STREAMS-OPDISPATCH-S-RUNTIME EXIT
    THEN
    R@ _SOD.COMPLETION SPOOLCOMP.REASON !
    DUP SATT.DETAIL @ R@ _SOD.COMPLETION SPOOLCOMP.DETAIL !
    DUP SATT.ERROR @ R@ _SOD.COMPLETION SPOOLCOMP.ERROR !
    DUP SATT.CLEANUP-ERROR @
        R@ _SOD.COMPLETION SPOOLCOMP.CLEANUP-ERROR !
    SATT.FINISHED-MS @
        R@ _SOD.COMPLETION SPOOLCOMP.FINISHED-MS !
    R@ _SOD-COMPLETION-EVIDENCE!
    DUP IF R> DROP EXIT THEN DROP
    R@ _SOD.COMPLETION STREAMS-SPOOL-COMPLETION-VALID? IF
        STREAMS-OPDISPATCH-S-OK
    ELSE
        STREAMS-OPDISPATCH-S-RUNTIME
    THEN
    R> DROP ;

: _SOD-PERSIST-TERMINAL  ( dispatch -- status )
    >R
    R@ _SOD-BUILD-COMPLETION
    DUP IF R> DROP EXIT THEN DROP
    R@ _SOD.ATTEMPT SOPATT.RECORD-REVISION @ R@ _SOD.ARG-U !
    R@ _SOD.ATTEMPT SOPATT.ATTEMPT-ID
        R@ _SOD.ID-SCRATCH RID-COPY
    R@ _SOD.ID-SCRATCH
    R@ _SOD.ARG-U @
    R@ _SOD.COMPLETION
    R@ _SOD.ATTEMPT
    R@ _SOD.SPOOL @ R@ _SOD.SPOOL-WORK @
    STREAMS-SPOOL-TERMINALIZE
    DUP R@ _SOD.SPOOL-STATUS !
    DUP STREAMS-SPOOL-S-OK =
    OVER STREAMS-SPOOL-S-REPLAY = OR IF
        DROP
        STREAMS-OPDISPATCH-STATE-TERMINAL R@ _SOD.STATE !
        R@ _SOD.FLOW-STATUS @ STREAMS-FLOW-S-CLEANUP = IF
            R> DROP STREAMS-OPDISPATCH-S-CLEANUP EXIT
        THEN
        R> DROP STREAMS-OPDISPATCH-S-TERMINAL EXIT
    THEN
    _SOD-SPOOL>STATUS
    R> DROP ;

: STREAMS-OPDISPATCH-POLL  ( now-ms dispatch -- status )
    >R
    R@ _SOD-ENTER DUP IF
        >R DROP R> R> DROP EXIT
    THEN DROP
    R@ _SOD.STATE @ STREAMS-OPDISPATCH-STATE-ACTIVE <> IF
        DROP STREAMS-OPDISPATCH-S-BUSY R> _SOD-LEAVE EXIT
    THEN
    DUP _SOD-NONNEG? 0= IF
        DROP STREAMS-OPDISPATCH-S-INVALID R> _SOD-LEAVE EXIT
    THEN
    DUP R@ _SOD.NOW !
    DROP
    R@ _SOD.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-TERMINAL <> IF
        R@ _SOD.NOW @ R@ _SOD.FLOW @ STREAMS-FLOW-STEP
        DUP R@ _SOD.FLOW-STATUS !
        DROP
    THEN
    R@ _SOD.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-TERMINAL = IF
        R@ _SOD-PERSIST-TERMINAL
        R> _SOD-LEAVE EXIT
    THEN
    R@ _SOD.FLOW-STATUS @ _SOD-FLOW>STATUS
    R> _SOD-LEAVE ;

: STREAMS-OPDISPATCH-CANCEL  ( now-ms dispatch -- status )
    >R
    R@ _SOD-ENTER DUP IF
        >R DROP R> R> DROP EXIT
    THEN DROP
    R@ _SOD.STATE @ STREAMS-OPDISPATCH-STATE-ACTIVE <> IF
        DROP STREAMS-OPDISPATCH-S-BUSY R> _SOD-LEAVE EXIT
    THEN
    DUP _SOD-NONNEG? 0= IF
        DROP STREAMS-OPDISPATCH-S-INVALID R> _SOD-LEAVE EXIT
    THEN
    DUP R@ _SOD.NOW !
    DROP
    R@ _SOD.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-TERMINAL <> IF
        R@ _SOD.GENERATION @ R@ _SOD.NOW @ R@ _SOD.FLOW @
            STREAMS-FLOW-CANCEL
        DUP R@ _SOD.FLOW-STATUS !
        DROP
    THEN
    R@ _SOD.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-TERMINAL = IF
        R@ _SOD-PERSIST-TERMINAL
        R> _SOD-LEAVE EXIT
    THEN
    R@ _SOD.FLOW-STATUS @ _SOD-FLOW>STATUS
    R> _SOD-LEAVE ;

: STREAMS-OPDISPATCH-RELEASE  ( dispatch -- status )
    >R
    R@ _SOD-ENTER DUP IF R> DROP EXIT THEN DROP
    R@ _SOD.STATE @ DUP STREAMS-OPDISPATCH-STATE-TERMINAL =
    SWAP STREAMS-OPDISPATCH-STATE-CLEANUP = OR 0= IF
        STREAMS-OPDISPATCH-S-BUSY R> _SOD-LEAVE EXIT
    THEN
    R@ _SOD-RETIRE-AND-RELEASE
    DUP STREAMS-OPDISPATCH-S-OK =
    OVER STREAMS-OPDISPATCH-S-CLEANUP = OR
    R@ _SOD.FLOW @ 0= AND IF
        STREAMS-OPDISPATCH-STATE-READY R@ _SOD.STATE !
        R> _SOD-LEAVE EXIT
    THEN
    DROP
    STREAMS-OPDISPATCH-STATE-CLEANUP R@ _SOD.STATE !
    STREAMS-OPDISPATCH-S-CLEANUP R> _SOD-LEAVE ;

