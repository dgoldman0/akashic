: _SOD-RUNTIME-OUTPUT-MATCHES?  ( flow dispatch -- flag )
    >R
    DUP STREAMS-FLOW-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    DUP SFLOW.ID R@ _SOD.FLOW-CONFIG SOPFLOW.FLOW-ID RID= 0=
        IF DROP R> DROP 0 EXIT THEN
    DUP SFLOW.REVISION @
        R@ _SOD.FLOW-CONFIG SOPFLOW.REVISION @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.OUTPUT-MEDIA @ R@ _SOD.MEDIA @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP SFLOW.TIMEOUT-MS @
        R@ _SOD.FLOW-CONFIG SOPFLOW.TIMEOUT-MS @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    SFLOW.OUTPUT-CONNECTOR @
    DUP STREAMS-CONNECTOR-VALID? 0= IF DROP R> DROP 0 EXIT THEN
    DUP SCON.ID R@ _SOD.CONNECTOR SOPCONN.CONNECTOR-ID RID=
    OVER SCON.ENDPOINT-ID
