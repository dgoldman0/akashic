: STREAMS-OPDISPATCH-INIT  ( dispatch -- status )
    DUP 0= IF DROP STREAMS-OPDISPATCH-S-INVALID EXIT THEN
    DUP STREAMS-OPDISPATCH-SIZE
        MSPAN-NONWRAPPING? 0= IF
        DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    DUP STREAMS-OPDISPATCH-SIZE 0 FILL
    _SOD-MAGIC OVER _SOD.MAGIC !
    DUP DUP _SOD.SELF !
    STREAMS-OPDISPATCH-STATE-BUILDING OVER _SOD.STATE !
    STREAMS-OPDISPATCH-S-OK OVER _SOD.STATUS !
    STREAMS-SPOOL-S-OK OVER _SOD.SPOOL-STATUS !
    STREAMS-FLOW-S-OK SWAP _SOD.FLOW-STATUS !
    STREAMS-OPDISPATCH-S-OK ;

