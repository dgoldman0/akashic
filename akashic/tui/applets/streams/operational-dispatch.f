: _SOD-HEADER?  ( dispatch -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP STREAMS-OPDISPATCH-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _SOD.MAGIC @ _SOD-MAGIC =
    OVER _SOD.SELF @ 2 PICK = AND
    OVER _SOD.STATE @ _SOD-STATE? AND
    OVER _SOD.BUSY @ DUP 0= SWAP -1 = OR AND
    OVER _SOD.STATUS @ _SOD-STATUS? AND
    SWAP _SOD.RESERVED 24 _SFLOW-ZERO? AND ;

: _SOD-CONFIG-BINDING?  ( dispatch -- flag )
    >R
    R@ _SOD.CONNECTOR STREAMS-OPCONN-SIZE
        STREAMS-OPCONN-VALID? 0= IF R> DROP 0 EXIT THEN
    R@ _SOD.FLOW-CONFIG STREAMS-OPFLOW-SIZE
        STREAMS-OPFLOW-VALID? 0= IF R> DROP 0 EXIT THEN
    R@ _SOD.CONNECTOR SOPCONN.LIFECYCLE @
        STREAMS-OPCONN-LIFECYCLE-ACTIVE <> IF R> DROP 0 EXIT THEN
    R@ _SOD.CONNECTOR SOPCONN.ENABLED @ 1 <> IF R> DROP 0 EXIT THEN
    R@ _SOD.FLOW-CONFIG SOPFLOW.LIFECYCLE @
        STREAMS-OPFLOW-LIFECYCLE-ACTIVE <> IF R> DROP 0 EXIT THEN
    R@ _SOD.FLOW-CONFIG SOPFLOW.ENABLED @ 1 <> IF R> DROP 0 EXIT THEN
    R@ _SOD.FLOW-CONFIG SOPFLOW.OUTPUT-CONNECTOR-ID
        R@ _SOD.CONNECTOR SOPCONN.CONNECTOR-ID RID= 0=
        IF R> DROP 0 EXIT THEN
    R@ _SOD.FLOW-CONFIG SOPFLOW.OUTPUT-CONNECTOR-REVISION @
        R@ _SOD.CONNECTOR SOPCONN.REVISION @ <> IF
        R> DROP 0 EXIT
    THEN
    R@ _SOD.MEDIA @ 0>
    R> DROP ;

: _SOD-BOUND?  ( dispatch -- flag )
    >R
    R@ _SOD-HEADER? 0= IF R> DROP 0 EXIT THEN
    R@ _SOD.STATE @ STREAMS-OPDISPATCH-STATE-BUILDING = IF
        R> DROP -1 EXIT
    THEN
    R@ _SOD.SPOOL @ R@ _SOD.SPOOL-WORK @
        STREAMS-SPOOL-WORK-BOUND? 0= IF R> DROP 0 EXIT THEN
    R@ _SOD.POOL @ STREAMS-EXECUTION-POOL-VALID? 0=
        IF R> DROP 0 EXIT THEN
    R@ _SOD-CONFIG-BINDING? 0= IF R> DROP 0 EXIT THEN
    R@ _SOD.STATE @ STREAMS-OPDISPATCH-STATE-ACTIVE >= IF
        R@ _SOD.FLOW @ DUP STREAMS-FLOW-VALID? 0= IF
            DROP R> DROP 0 EXIT
        THEN
        DROP
        R@ _SOD.LEASE @ 0> R@ _SOD.GENERATION @ 0> AND
        R> DROP EXIT
    THEN
    R@ _SOD.FLOW @ 0=
    R@ _SOD.LEASE @ 0= AND
    R@ _SOD.GENERATION @ 0= AND
    R> DROP ;

