\ PBLOB dispatch sink:
\ ( logical-offset payload-a payload-u dispatch -- persist-status )
: _SOD-DISPATCH-SINK
  ( logical-offset payload-a payload-u dispatch -- persist-status )
    >R
    R@ _SOD.BUSY @ 0= IF
        _SOD-DROP3 R> DROP PERSIST-S-CONFLICT EXIT
    THEN
    2 PICK R@ _SOD.PAYLOAD-OFFSET @ <> IF
        _SOD-DROP3 R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    DUP R@ _SOD.ARG-U !
    OVER R@ _SOD.ARG-A !
    _SOD-DROP3
    R@ _SOD.ARG-A @ R@ _SOD.ARG-U @
    R@ _SOD.GENERATION @ R@ _SOD.NOW @ R@ _SOD.FLOW @
    STREAMS-FLOW-EGRESS-APPEND
    DUP R@ _SOD.FLOW-STATUS !
    CASE
        STREAMS-FLOW-S-OK OF
            R@ _SOD.ARG-U @ R@ _SOD.PAYLOAD-OFFSET +!
            PERSIST-S-OK
        ENDOF
        STREAMS-FLOW-S-BUSY OF PERSIST-S-BUSY ENDOF
        STREAMS-FLOW-S-CAPACITY OF PERSIST-S-CAPACITY ENDOF
        STREAMS-FLOW-S-STALE OF PERSIST-S-CONFLICT ENDOF
        PERSIST-S-CORRUPT SWAP
    ENDCASE
    R> DROP ;

: _SOD-RELEASE-IDLE  ( dispatch -- status )
    >R
    R@ _SOD.FLOW @ 0= IF
        R> DROP STREAMS-OPDISPATCH-S-OK EXIT
    THEN
    R@ _SOD.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-IDLE <> IF
        R> DROP STREAMS-OPDISPATCH-S-CLEANUP EXIT
    THEN
    R@ _SOD.FLOW @ R@ _SOD.LEASE @ R@ _SOD.POOL @
        STREAMS-EXECUTION-POOL-RELEASE
    DUP R@ _SOD.FLOW-STATUS !
    DUP STREAMS-FLOW-S-OK <> IF
        _SOD-FLOW>STATUS
        DUP STREAMS-OPDISPATCH-S-OK = IF
            DROP STREAMS-OPDISPATCH-S-CLEANUP
        THEN
        R> DROP EXIT
    THEN
    DROP
    R@ _SOD-CLEAR-RUNTIME
    R> DROP STREAMS-OPDISPATCH-S-OK ;

: _SOD-RETIRE-AND-RELEASE  ( dispatch -- status )
    >R
    0 R@ _SOD.SOURCE-U !
    R@ _SOD.FLOW @ 0= IF
        R> DROP STREAMS-OPDISPATCH-S-OK EXIT
    THEN
    R@ _SOD.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-EGRESS-STAGING = IF
        R@ _SOD.GENERATION @ R@ _SOD.NOW @ R@ _SOD.FLOW @
            STREAMS-FLOW-EGRESS-ABORT
        DUP R@ _SOD.FLOW-STATUS !
        DUP STREAMS-FLOW-S-CANCELLED =
        OVER STREAMS-FLOW-S-TIMED-OUT = OR
        OVER STREAMS-FLOW-S-OK = OR 0= IF
            DROP R> DROP STREAMS-OPDISPATCH-S-CLEANUP EXIT
        THEN
        DROP
    THEN
    R@ _SOD.FLOW @ SFLOW.STATE @
        DUP STREAMS-FLOW-STATE-OUTPUT-READY =
        OVER STREAMS-FLOW-STATE-DELIVERING = OR IF
        DROP
        R@ _SOD.GENERATION @ R@ _SOD.NOW @ R@ _SOD.FLOW @
            STREAMS-FLOW-CANCEL
        DUP R@ _SOD.FLOW-STATUS !
        DROP
    ELSE
        DROP
    THEN
    R@ _SOD.FLOW @ SFLOW.STATE @
        STREAMS-FLOW-STATE-TERMINAL = IF
        R@ _SOD.GENERATION @ R@ _SOD.FLOW @ STREAMS-FLOW-RETIRE
        DUP R@ _SOD.FLOW-STATUS !
        DUP STREAMS-FLOW-S-CLEANUP = IF
            -1 R@ _SOD.SOURCE-U !
        ELSE
            DUP STREAMS-FLOW-S-OK <> IF
                DROP R> DROP STREAMS-OPDISPATCH-S-CLEANUP EXIT
            THEN
        THEN
        DROP
    THEN
    R@ _SOD.FLOW @ SFLOW.STATE @ STREAMS-FLOW-STATE-IDLE <> IF
        R> DROP STREAMS-OPDISPATCH-S-CLEANUP EXIT
    THEN
    R@ _SOD-RELEASE-IDLE
    DUP STREAMS-OPDISPATCH-S-OK <> IF R> DROP EXIT THEN
    DROP
    R@ _SOD.SOURCE-U @ IF
        0 R@ _SOD.SOURCE-U !
        STREAMS-OPDISPATCH-S-CLEANUP
    ELSE
        STREAMS-OPDISPATCH-S-OK
    THEN
    R> DROP ;

: _SOD-DISPATCH-FAIL-CLEANUP  ( primary-status dispatch -- status )
    >R
    R@ _SOD-RETIRE-AND-RELEASE
    DUP STREAMS-OPDISPATCH-S-OK =
    OVER STREAMS-OPDISPATCH-S-CLEANUP =
        R@ _SOD.FLOW @ 0= AND OR 0= IF
        DROP DROP
        STREAMS-OPDISPATCH-STATE-CLEANUP R@ _SOD.STATE !
        R> DROP STREAMS-OPDISPATCH-S-CLEANUP EXIT
    THEN
    DROP
    STREAMS-OPDISPATCH-STATE-READY R@ _SOD.STATE !
    R> DROP ;

: _SOD-ACQUIRE-RUNTIME  ( dispatch -- status )
    >R
    0 R@ _SOD.ATTEMPT SOPATT.PAYLOAD-U @ R@ _SOD.POOL @
        STREAMS-EXECUTION-POOL-ACQUIRE
    DUP R@ _SOD.FLOW-STATUS !
    DUP STREAMS-FLOW-S-OK <> IF
        >R 2DROP R> _SOD-FLOW>STATUS R> DROP EXIT
    THEN
    DROP
    DUP R@ _SOD.LEASE !
    OVER R@ _SOD.FLOW !
    2DROP
    R@ _SOD.FLOW @ SFLOW.STATE @ STREAMS-FLOW-STATE-IDLE <>
    R@ _SOD.FLOW @ R@ _SOD-RUNTIME-OUTPUT-MATCHES? 0= OR IF
        R@ _SOD-RELEASE-IDLE
        DUP STREAMS-OPDISPATCH-S-OK <> IF
            DROP
            STREAMS-OPDISPATCH-STATE-CLEANUP R@ _SOD.STATE !
            R> DROP STREAMS-OPDISPATCH-S-CLEANUP EXIT
        THEN
        DROP
        R> DROP STREAMS-OPDISPATCH-S-INVALID EXIT
    THEN
    R> DROP STREAMS-OPDISPATCH-S-OK ;

: _SOD-STAGE-RUNTIME  ( dispatch -- status )
    >R
    R@ _SOD-BUILD-EVENT
    DUP IF R> DROP EXIT THEN DROP
    R@ _SOD.FLOW @ SFLOW.OUTPUT-CONNECTOR @
    R@ _SOD.EVENT
    R@ _SOD.ATTEMPT SOPATT.PAYLOAD-U @
    R@ _SOD.FLOW-CONFIG SOPFLOW.REVISION @
    R@ _SOD.NOW @
    R@ _SOD.FLOW @
    STREAMS-FLOW-EGRESS-BEGIN
    DUP R@ _SOD.FLOW-STATUS !
    DUP STREAMS-FLOW-S-OK <> IF
        NIP _SOD-FLOW>STATUS R> DROP EXIT
    THEN
    DROP R@ _SOD.GENERATION !
    0 R@ _SOD.PAYLOAD-OFFSET !
    R@ _SOD.ATTEMPT SOPATT.ATTEMPT-ID
    ['] _SOD-DISPATCH-SINK R@
    R@ _SOD.SPOOL @ R@ _SOD.SPOOL-WORK @
    STREAMS-SPOOL-PAYLOAD-STREAM
    DUP R@ _SOD.SPOOL-STATUS !
    DUP STREAMS-SPOOL-S-OK <> IF
        _SOD-SPOOL>STATUS R> DROP EXIT
    THEN
    DROP
    R@ _SOD.PAYLOAD-OFFSET @
        R@ _SOD.ATTEMPT SOPATT.PAYLOAD-U @ <> IF
        R> DROP STREAMS-OPDISPATCH-S-RUNTIME EXIT
    THEN
    R@ _SOD.GENERATION @ R@ _SOD.NOW @ R@ _SOD.FLOW @
        STREAMS-FLOW-EGRESS-COMMIT
    DUP R@ _SOD.FLOW-STATUS !
    DUP STREAMS-FLOW-S-OK <> IF
        _SOD-FLOW>STATUS R> DROP EXIT
    THEN
    DROP
    R> DROP STREAMS-OPDISPATCH-S-OK ;

: _SOD-CLASSIFY-STALE  ( dispatch -- status )
    >R
    R@ _SOD.ATTEMPT SOPATT.ATTEMPT-ID
        R@ _SOD.ID-SCRATCH RID-COPY
    R@ _SOD.ID-SCRATCH
    R@ _SOD.ATTEMPT SOPATT.RECORD-REVISION @
    R@ _SOD.NOW @
    R@ _SOD.ATTEMPT
    R@ _SOD.SPOOL @ R@ _SOD.SPOOL-WORK @
    STREAMS-SPOOL-CLASSIFY-STALE
    DUP R@ _SOD.SPOOL-STATUS !
    DUP STREAMS-SPOOL-S-STALE = IF
        DROP
        R> DROP STREAMS-OPDISPATCH-S-STALE EXIT
    THEN
    DUP STREAMS-SPOOL-S-CONFLICT = IF
        DROP
        R> DROP STREAMS-OPDISPATCH-S-NO-WORK EXIT
    THEN
    _SOD-SPOOL>STATUS
    R> DROP ;

: _SOD-ACTIVATE-DURABLE  ( dispatch -- status )
    >R
    R@ _SOD.ATTEMPT SOPATT.ATTEMPT-ID
        R@ _SOD.ID-SCRATCH RID-COPY
    R@ _SOD.ID-SCRATCH
    R@ _SOD.ATTEMPT SOPATT.RECORD-REVISION @
    R@ _SOD.NOW @
    R@ _SOD.ATTEMPT
    R@ _SOD.SPOOL @ R@ _SOD.SPOOL-WORK @
    STREAMS-SPOOL-ACTIVATE
    DUP R@ _SOD.SPOOL-STATUS !
    DUP STREAMS-SPOOL-S-OK = IF
        DROP
        STREAMS-OPDISPATCH-STATE-ACTIVE R@ _SOD.STATE !
        R> DROP STREAMS-OPDISPATCH-S-PENDING EXIT
    THEN
    DUP STREAMS-SPOOL-S-REPLAY = IF
        DROP
        \ A replay could belong to another descriptor that staged the same
        \ READY revision at the same millisecond.  This bridge never infers
        \ ownership from durable equality; UNCERTAIN requires cold recovery.
        R> DROP STREAMS-OPDISPATCH-S-BUSY EXIT
    THEN
    _SOD-SPOOL>STATUS
    R> DROP ;

: STREAMS-OPDISPATCH-DISPATCH  ( now-ms dispatch -- status )
    >R
    R@ _SOD-ENTER DUP IF
        >R DROP R> R> DROP EXIT
    THEN DROP
    R@ _SOD.STATE @ STREAMS-OPDISPATCH-STATE-READY <> IF
        DROP STREAMS-OPDISPATCH-S-BUSY R> _SOD-LEAVE EXIT
    THEN
    DUP _SOD-NONNEG? 0= IF
        DROP STREAMS-OPDISPATCH-S-INVALID R> _SOD-LEAVE EXIT
    THEN
    DUP R@ _SOD.NOW !
    DROP
    R@ _SOD.ATTEMPT
    R@ _SOD.SPOOL @ R@ _SOD.SPOOL-WORK @
    STREAMS-SPOOL-READY@
    DUP R@ _SOD.SPOOL-STATUS !
    DUP STREAMS-SPOOL-S-OK <> IF
        _SOD-SPOOL>STATUS R> _SOD-LEAVE EXIT
    THEN
    DROP
    R@ _SOD-CLASSIFY-STALE
    DUP STREAMS-OPDISPATCH-S-STALE = IF
        R> _SOD-LEAVE EXIT
    THEN
    DUP STREAMS-OPDISPATCH-S-NO-WORK <> IF
        R> _SOD-LEAVE EXIT
    THEN
    DROP
    R@ _SOD.ATTEMPT R@ _SOD-ATTEMPT-BINDING? 0= IF
        STREAMS-OPDISPATCH-S-NO-WORK R> _SOD-LEAVE EXIT
    THEN
    R@ _SOD-ACQUIRE-RUNTIME
    DUP IF R> _SOD-LEAVE EXIT THEN DROP
    R@ _SOD-STAGE-RUNTIME
    DUP IF
        R@ _SOD-DISPATCH-FAIL-CLEANUP
        R> _SOD-LEAVE EXIT
    THEN DROP
    R@ _SOD-ACTIVATE-DURABLE
    DUP STREAMS-OPDISPATCH-S-PENDING = IF
        R> _SOD-LEAVE EXIT
    THEN
    R@ _SOD-DISPATCH-FAIL-CLEANUP
    R> _SOD-LEAVE ;

