    R@ _SPACOM.BUILDER-WORK @ _SPAW.KEY
    STREAMS-PI-SOURCE-TIME-KEY-SIZE
    R@ _SPACOM.BUILDER-WORK @ _SPAW.RECORD-REF
    PERSIST-REF-SIZE STREAMS-PI-TREE-ORDERINGS
    R@ _SPACOM.BUILDER-WORK @ _SPAW-PUT
    DUP IF R@ _SPACOM-BUILDER-ABORT R> DROP EXIT THEN DROP
    1 R@ _SPACOM.COPIED-OBSERVATION +!
    1 R@ _SPACOM.BUILDER-WORK @
        _SPAW.AUTHORITY-ROOT SAR.OBSERVATION-COUNT +!
    R@ _SPACOM-BUILDER-PUBLISH
    DUP IF R> DROP EXIT THEN DROP
    0 R@ _SPACOM.ROW-ACTIVE !
    R> DROP STREAMS-PA-S-OK ;

: _SPACOM-OBSERVATION-STEP  ( context -- status )
    >R
    R@ _SPACOM.ROW-ACTIVE @ 0= IF
        R@ _SPACOM-OBSERVATION-BEGIN
        DUP IF R> DROP EXIT THEN DROP
    THEN
    ['] _SPACOM-BLOB-SOURCE R@
    R@ _SPACOM.ALLOWANCE @
    R@ _SPACOM.BUILDER-WORK @ _SPAW.BLOB-WORK
    PBLOB-WRITE-STEP
    DUP R@ _SPACOM.STATUS !
    DROP
    DUP R@ _SPACOM.USED !
    DROP
    DUP R@ _SPACOM.BLOB-DONE !
    DROP
    R@ _SPACOM.STATUS @
    DUP IF
        _SPA-PERSIST>STATUS
        R@ _SPACOM-BUILDER-ABORT R> DROP EXIT
    THEN
    DROP
    R@ _SPACOM.BLOB-DONE @ IF
        R@ _SPACOM-OBSERVATION-FINISH
    ELSE
        STREAMS-PA-S-OK
    THEN
    R> DROP ;

