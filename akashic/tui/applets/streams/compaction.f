\ =====================================================================
\  compaction.f - Streams semantic compaction over neutral PCOMPACT
\ =====================================================================
\  PCOMPACT owns two-bank selection, the immutable source snapshot, exact
\  shared-generation publication, mirroring, recovery, and cleanup.  This
\  adapter-friend owns the Streams meaning required to rebuild that snapshot:
\  it traverses only the four authoritative families, copies checked semantic
\  records, rewrites observation PBLOB descriptors, proves the target bytes'
\  digest, and derives every secondary index from the copied record.  A
\  migrated observation may predate the one legacy attempt head retained for
\  its source; only sealed legacy-observation provenance admits that missing
\  join.  Every present attempt and every native authority still agrees
\  exactly.
\
\  The source authority header is retained byte-for-byte.  Incremental builder
\  roots use the same logical, mutation, acquisition, provenance, completeness,
\  authority, and legacy-evidence metadata with partial semantic counts.  The
\  exact-generation finalizer starts from the captured header and changes only
\  the four physical roots, reclaim state, and the seal that covers them.
\
\  This is deliberately a friend of persistence-adapter.f.  Its primary-family
\  cursors and raw builder operations are private; it does not widen the five
\  query-bearing public range families or expose a generic maintenance range.
\ =====================================================================

