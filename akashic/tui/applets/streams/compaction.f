: _SPACOM-RAW-ROW
  ( key-a key-u value-a value-u persist-status context -- status )
    >R
    DUP PERSIST-S-NOT-FOUND = IF
        DROP _SPA-DROP4 R> DROP STREAMS-PA-S-NOT-FOUND EXIT
    THEN
    DUP IF
        _SPA-PERSIST>STATUS >R
        _SPA-DROP4 R> R> DROP EXIT
    THEN
    DROP
    2 PICK DUP 1 < SWAP PBTREE-KEY-MAX > OR IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    3 PICK C@ R@ _SPACOM.FAMILY @ <> IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-NOT-FOUND EXIT
    THEN
    3 PICK 3 PICK STREAMS-PI-KEY-VALID? 0= IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    DUP PERSIST-REF-SIZE <> IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    OVER PERSIST-REF-VALID? 0= IF
        _SPA-DROP4 R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    2 PICK R@ _SPACOM.KEY-U !
    3 PICK R@ _SPACOM.KEY R@ _SPACOM.KEY-U @ MOVE
    OVER R@ _SPACOM.SOURCE-WORK @ _SPAW.RECORD-REF
        PERSIST-REF-COPY
    _SPA-DROP4
    R@ _SPACOM.SOURCE-WORK @ _SPAW.RECORD-REF
    R@ _SPACOM.SOURCE-ADAPTER @ _SPA-D.STORE @
    R@ _SPACOM.SOURCE-WORK @ _SPAW.PSTORE-WORK @
    PSTORE-READ-RECORD
    DUP IF
        DUP PERSIST-S-NOT-FOUND = IF
            DROP R> DROP STREAMS-PA-S-CORRUPT EXIT
        THEN
        _SPA-PERSIST>STATUS R> DROP EXIT
    THEN
    DROP
    R@ _SPACOM.SOURCE-WORK @ _SPAW.PSTORE-WORK @
        PSTORE-RECORD-PAYLOAD$
    2DUP SPREC-VALID? 0= IF
