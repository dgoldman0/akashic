: _SPACOM-ROOT-PAGE  ( exact-generation context -- status )
    >R
    DUP 0> 0= IF DROP R> DROP STREAMS-PA-S-INVALID EXIT THEN
    R@ _SPACOM-FINAL-RECONCILE
    DUP IF NIP R> DROP EXIT THEN DROP
    R@ _SPACOM.SNAPSHOT
    R@ _SPACOM.BUILDER-WORK @ _SPAW.PAGE
        STREAMS-AUTHORITY-ROOT-SIZE MOVE
    0
    BEGIN DUP _SPA-TREE-COUNT < WHILE
        DUP R@ _SPACOM.BUILDER-WORK @ _SPAW-ROOT
        2 PICK
        R@ _SPACOM.BUILDER-WORK @ _SPAW.TEMP-ROOT
        3 PICK R@ _SPACOM.BUILDER-WORK @ _SPAW-TREE
        PBTREE-ROOT-REBASE
        DUP IF
            _SPA-PERSIST>STATUS >R 2DROP R> R> DROP EXIT
        THEN
        DROP
        R@ _SPACOM.BUILDER-WORK @ _SPAW.TEMP-ROOT
        OVER
        R@ _SPACOM.BUILDER-WORK @ _SPAW.PAGE
            STREAMS-AUTHORITY-ROOT-TREE
        PBTREE-ROOT-COPY
        DUP IF
            _SPA-PERSIST>STATUS >R 2DROP R> R> DROP EXIT
        THEN
        DROP
        1+
    REPEAT
    DROP
    R@ _SPACOM.BUILDER-WORK @ _SPAW.PAGE SAR.RECLAIM-STATE
    RECLAIM-STATE-SIZE
    RECLAIM-EMPTY-STATE-FOR-GENERATION _SPA-PERSIST>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SPACOM.BUILDER-WORK @ _SPAW.PAGE
        STREAMS-AUTHORITY-ROOT-SEAL _SPA-ROOT>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SPACOM.BUILDER-WORK @ _SPAW.PAGE
        STREAMS-AUTHORITY-ROOT-HEADER-CLASSIFY _SPA-ROOT>STATUS
    DUP IF R> DROP EXIT THEN DROP
    R@ _SPACOM.SNAPSHOT
    R@ _SPACOM.BUILDER-WORK @ _SPAW.PAGE
    _SAR-ROOTS-OFF _SPA-BYTES= 0= IF
        R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    R> DROP STREAMS-PA-S-OK ;

: _SPACOM-FINALIZE-ABORT
  ( primary-status builder-store builder-pstore-work -- final-status )
    >R
    R@ PSTORE-PROPOSED-ROOT@ IF
        DUP R@ PSTORE-ABORT
        DUP IF
            >R 2DROP R>
        ELSE
            DROP DROP
        THEN
    ELSE
        DROP
    THEN
    R> DROP ;

: _SPACOM-FINALIZE-RUN
  ( exact-generation builder-store builder-pstore-work context -- status )
    >R
    R@ _SPACOM.STATE @ _SPACOM-STATE-DONE <> IF
        _SPA-DROP3 R> DROP STREAMS-PA-S-CONFLICT EXIT
    THEN
    2 PICK R@ _SPACOM-ROOT-PAGE
    DUP IF >R _SPA-DROP3 R> R> DROP EXIT THEN DROP
    DUP R@ _SPACOM.BUILDER-WORK @
        _SPAW.PSTORE-WORK @ <> IF
        _SPA-DROP3 R> DROP STREAMS-PA-S-INVALID EXIT
    THEN
    1 PICK R@ _SPACOM.BUILDER-ADAPTER @
        _SPA-D.STORE @ <> IF
        _SPA-DROP3 R> DROP STREAMS-PA-S-INVALID EXIT
    THEN
    1 PICK 1 PICK PSTORE-BEGIN
    DUP IF >R _SPA-DROP3 R> R> DROP EXIT THEN DROP
    R@ _SPACOM.BUILDER-WORK @ _SPAW.PAGE
    PERSIST-PAGE-PAYLOAD-SIZE
    3 PICK 3 PICK PSTORE-APPEND-PAGE
    DUP IF
        _SPA-PERSIST>STATUS DUP R@ _SPACOM.STATUS ! DROP
        DROP
        R@ _SPACOM.STATUS @ 2 PICK 2 PICK
            _SPACOM-FINALIZE-ABORT
        >R _SPA-DROP3 R> R> DROP EXIT
    THEN
    DROP
    R@ _SPACOM.BUILDER-WORK @ _SPAW.APP-ROOT-PAGE !
    R@ _SPACOM.BUILDER-WORK @ _SPAW.APP-ROOT-PAGE @
    2 PICK 2 PICK PSTORE-APPLICATION-ROOT!
    DUP IF
        _SPA-PERSIST>STATUS DUP R@ _SPACOM.STATUS ! DROP
        R@ _SPACOM.STATUS @ 2 PICK 2 PICK
            _SPACOM-FINALIZE-ABORT
        >R _SPA-DROP3 R> R> DROP EXIT
    THEN
    DROP
    1 PICK 1 PICK PSTORE-COMMIT _SPA-PERSIST>STATUS
    >R _SPA-DROP3 R> R> DROP ;

: _SPACOM-FINALIZE
  ( exact-generation builder-store builder-pstore-work context -- persist-status )
    DUP STREAMS-PA-COMPACTION-CONTEXT-VALID? 0= IF
        _SPA-DROP4 PERSIST-S-INVALID EXIT
    THEN
    >R
    1 PICK R@ _SPACOM.BUILDER-ADAPTER @ _SPA-D.STORE @ <> IF
        _SPA-DROP3 R> DROP PERSIST-S-INVALID EXIT
    THEN
    DUP R@ _SPACOM.BUILDER-WORK @
        _SPAW.PSTORE-WORK @ <> IF
        _SPA-DROP3 R> DROP PERSIST-S-INVALID EXIT
    THEN
    R@ _SPACOM-FINALIZE-RUN
    DUP R@ _SPACOM.STATUS !
    R> DROP ;

