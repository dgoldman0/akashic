: _SPACOM-BLOB-SINK
  ( logical-offset payload-a payload-u context -- persist-status )
    >R
    DUP 0< IF _SPA-DROP3 R> DROP PERSIST-S-INVALID EXIT THEN
    2 PICK
    R@ _SPACOM.READ-BASE @ R@ _SPACOM.READ-USED @ + <> IF
        _SPA-DROP3 R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    R@ _SPACOM.READ-USED @ OVER + DUP
    R@ _SPACOM.READ-USED @ < IF
        DROP _SPA-DROP3 R> DROP PERSIST-S-CAPACITY EXIT
    THEN
    R@ _SPACOM.READ-LIMIT @ > IF
        _SPA-DROP3 R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    1 PICK
    R@ _SPACOM.READ-DEST @ R@ _SPACOM.READ-USED @ +
    2 PICK MOVE
    DUP R@ _SPACOM.READ-USED +!
    _SPA-DROP3 R> DROP PERSIST-S-OK ;

: _SPACOM-BLOB-SOURCE
  ( logical-offset destination-a requested-u context -- actual-u persist-status )
    >R
    DUP 0> 0= IF _SPA-DROP3 R> DROP 0 PERSIST-S-INVALID EXIT THEN
    2 PICK R@ _SPACOM.READ-BASE !
    DUP R@ _SPACOM.READ-LIMIT !
    1 PICK R@ _SPACOM.READ-DEST !
    0 R@ _SPACOM.READ-USED !
    _SPA-DROP3
    R@ _SPACOM.RECORD SPRO.CONTENT
    R@ _SPACOM.READ-BASE @
    R@ _SPACOM.READ-LIMIT @
    ['] _SPACOM-BLOB-SINK R@
    R@ _SPACOM.SOURCE-ADAPTER @ _SPA-D.STORE @
    R@ _SPACOM.SOURCE-WORK @ _SPAW.PSTORE-WORK @
    R@ _SPACOM.SOURCE-WORK @ _SPAW.BLOB-WORK
    PBLOB-READ-RANGE
    DUP IF
        DUP PERSIST-S-NOT-FOUND = IF
            DROP PERSIST-S-CORRUPT
        THEN
        0 SWAP R> DROP EXIT
    THEN
    DROP
    R@ _SPACOM.READ-USED @
    DUP R@ _SPACOM.READ-LIMIT @ <> IF
        DROP R> DROP 0 PERSIST-S-CORRUPT EXIT
    THEN
    PERSIST-S-OK R> DROP ;

: _SPACOM-HASH-SINK
  ( logical-offset payload-a payload-u context -- persist-status )
    >R
    DUP 0< IF _SPA-DROP3 R> DROP PERSIST-S-INVALID EXIT THEN
    2 PICK R@ _SPACOM.HASH-NEXT @ <> IF
        _SPA-DROP3 R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    R@ _SPACOM.HASH-USED @ OVER + DUP
    R@ _SPACOM.HASH-USED @ < IF
        DROP _SPA-DROP3 R> DROP PERSIST-S-CAPACITY EXIT
    THEN
    R@ _SPACOM.RECORD SPRO.CONTENT-U @ > IF
        _SPA-DROP3 R> DROP PERSIST-S-CORRUPT EXIT
    THEN
    1 PICK OVER SHA3-256-ADD
    DUP R@ _SPACOM.HASH-NEXT +!
    DUP R@ _SPACOM.HASH-USED +!
    _SPA-DROP3 R> DROP PERSIST-S-OK ;

