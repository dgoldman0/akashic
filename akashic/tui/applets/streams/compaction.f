    THEN
    DUP STREAMS-PERSISTENCE-RECORD-MAX > IF
        2DROP R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    R@ _SPACOM.KEY R@ _SPACOM.KEY-U @
    3 PICK 3 PICK STREAMS-PI-RECORD-AGREES? 0= IF
        2DROP R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    DUP R@ _SPACOM.RECORD-U !
    OVER R@ _SPACOM.RECORD 2 PICK MOVE
    2DROP R> DROP STREAMS-PA-S-OK ;

