    0 R@ _SPACOM.HASH-NEXT !
    0 R@ _SPACOM.HASH-USED !
    SHA3-256-BEGIN
    R@ _SPACOM.BUILDER-WORK @ _SPAW.BLOB
    0 R@ _SPACOM.RECORD SPRO.CONTENT-U @
    ['] _SPACOM-HASH-SINK R@
    R@ _SPACOM.BUILDER-ADAPTER @ _SPA-D.STORE @
    R@ _SPACOM.BUILDER-WORK @ _SPAW.PSTORE-WORK @
    R@ _SPACOM.BUILDER-WORK @ _SPAW.BLOB-WORK
