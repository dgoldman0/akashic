: _SPACOM-DISPATCH-ROW  ( context -- status )
    DUP _SPACOM.PHASE @ CASE
        _SPACOM-PHASE-SOURCE OF _SPACOM-SOURCE-ROW ENDOF
        _SPACOM-PHASE-ATTEMPT OF _SPACOM-ATTEMPT-ROW ENDOF
        _SPACOM-PHASE-OBSERVATION OF _SPACOM-OBSERVATION-STEP ENDOF
        _SPACOM-PHASE-NATIVE OF _SPACOM-NATIVE-ROW ENDOF
        2DROP STREAMS-PA-S-CORRUPT
    ENDCASE ;

: _SPACOM-STEP-ARGS?
  ( source-root builder-store builder-pstore-work allowance context -- flag )
    >R
    DUP 0> 0= IF _SPA-DROP4 R> DROP 0 EXIT THEN
    3 PICK R@ _SPACOM-SOURCE-ROOT? 0= IF
        _SPA-DROP4 R> DROP 0 EXIT
    THEN
    2 PICK R@ _SPACOM.BUILDER-ADAPTER @ _SPA-D.STORE @ <> IF
        _SPA-DROP4 R> DROP 0 EXIT
    THEN
    1 PICK R@ _SPACOM.BUILDER-WORK @
        _SPAW.PSTORE-WORK @ <> IF
        _SPA-DROP4 R> DROP 0 EXIT
    THEN
    _SPA-DROP4 R> DROP -1 ;

: _SPACOM-STEP-RUN  ( context -- done? bytes-used status )
    >R
    R@ _SPACOM.STATE @ _SPACOM-STATE-DONE = IF
        R> DROP -1 0 STREAMS-PA-S-OK EXIT
    THEN
    R@ _SPACOM.STATE @ _SPACOM-STATE-BOUND = IF
        R@ _SPACOM-CAPTURE-SOURCE
        DUP IF R> DROP 0 0 ROT EXIT THEN DROP
    THEN
    BEGIN
        R@ _SPACOM.STATE @ _SPACOM-STATE-DONE <>
    WHILE
        R@ _SPACOM.ROW-ACTIVE @ 0= IF
            R@ _SPACOM-NEXT-ROW
            DUP STREAMS-PA-S-NOT-FOUND = IF
                DROP
                R@ _SPACOM-NEXT-PHASE
                DUP IF R> DROP 0 0 ROT EXIT THEN DROP
                R@ _SPACOM.STATE @ _SPACOM-STATE-DONE = IF
                    R> DROP -1 0 STREAMS-PA-S-OK EXIT
                THEN
                \ A family boundary is one bounded unit of work.  The next
                \ callback initializes the new tree cursor; never dispatch
                \ the prior family's stale row under the advanced phase.
                R> DROP 0 0 STREAMS-PA-S-OK EXIT
            ELSE
                DUP IF R> DROP 0 0 ROT EXIT THEN DROP
            THEN
        THEN
        R@ _SPACOM.STATE @ _SPACOM-STATE-DONE = IF
            R> DROP -1 0 STREAMS-PA-S-OK EXIT
        THEN
        R@ _SPACOM-DISPATCH-ROW
        DUP IF R> DROP 0 0 ROT EXIT THEN DROP
        R@ _SPACOM.USED @
        R> DROP 0 SWAP STREAMS-PA-S-OK EXIT
    REPEAT
    R> DROP -1 0 STREAMS-PA-S-OK ;

: _SPACOM-STEP-CATCH  ( context -- done? bytes-used status )
    ['] _SPACOM-STEP-RUN CATCH
    DUP IF
        >R DROP R> DROP 0 0 STREAMS-PA-S-FAULT
    ELSE
        DROP
    THEN ;

: _SPACOM-STEP
  ( source-root builder-store builder-pstore-work allowance context -- done? bytes-used persist-status )
    DUP STREAMS-PA-COMPACTION-CONTEXT-VALID? 0= IF
        _SPA-DROP5 0 0 PERSIST-S-INVALID EXIT
    THEN
    >R
    3 PICK 3 PICK 3 PICK 3 PICK R@
        _SPACOM-STEP-ARGS? 0= IF
        _SPA-DROP4 R> DROP 0 0 PERSIST-S-INVALID EXIT
    THEN
    DUP R@ _SPACOM.ALLOWANCE !
    0 R@ _SPACOM.USED !
    0 R@ _SPACOM.BLOB-DONE !
    _SPA-DROP4
    R@ _SPACOM-STEP-CATCH
    DUP R@ _SPACOM.STATUS !
    R> DROP ;

