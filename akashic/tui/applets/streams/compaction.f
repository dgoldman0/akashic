    DUP IF
        DUP PERSIST-S-NOT-FOUND = IF
            DROP PERSIST-S-CORRUPT
        THEN
        _SPA-PERSIST>STATUS R> DROP EXIT
    THEN
    DROP
    R@ _SPACOM.HASH-USED @
    R@ _SPACOM.RECORD SPRO.CONTENT-U @ <> IF
        R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    R@ _SPACOM.HASH-NEXT @
    R@ _SPACOM.RECORD SPRO.CONTENT-U @ <> IF
        R> DROP STREAMS-PA-S-CORRUPT EXIT
    THEN
    R@ _SPACOM.RECORD SPRO.CONTENT-DIGEST
