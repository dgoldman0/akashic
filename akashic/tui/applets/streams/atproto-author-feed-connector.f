    _ATAFCX-OP @ ?DUP IF
        DUP XIO-OP-VALID? IF
            AT-AUTHOR-FEED-CONNECTOR-XERR-INVALID SWAP XIOO.ERROR !
        ELSE
            DROP
        THEN
    THEN
    _ATAFCX-CLEAR XIO-STEP-FAILED ;

: AT-AUTHOR-FEED-CONNECTOR-XIO-START
  ( operation owner -- step-status )
    _ATAFCX-OWNER ! _ATAFCX-OP !
    _ATAFCX-OWNER @ AT-AUTHOR-FEED-CONNECTOR-VALID? 0= IF
        _ATAFCX-FAIL-INVALID EXIT
    THEN
    _ATAFC-F-CURRENT _ATAFC-F-PUBLISHED OR
        _ATAFCX-OWNER @ _ATAFC-FLAG-
    _ATAFCX-OP @ _ATAFCX-OWNER @ ATAFC.EXCHANGE
    AT-XRPC-EXCHANGE-XIO-START DUP _ATAFCX-STEP !
