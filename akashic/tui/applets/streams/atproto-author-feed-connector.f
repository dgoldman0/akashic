\ =====================================================================
\  atproto-author-feed-connector.f - Authenticated AT feed input owner
\ =====================================================================
\  One caller-owned instance composes the general AT author-feed target,
\  authenticated XRPC exchange, bounded Bluesky feed projection, and one
\  sealed Streams input connector.  The concrete Bluesky AppView proxy is
\  trusted composition policy here; it is not embedded in generic XRPC or
\  HTTP code.
\
\  A successful poll first decodes the detached JSON response into the
\  instance-owned BFM projection.  PUBLISH then lends that same validated
\  raw JSON page to STREAMS-FLOW-ADMIT.  Admission copies it into the
\  flow-owned carrier and closes the source event before XIO cleanup can
\  wipe the response arena.  The owned BFM projection survives XIO wipe.
\
\  The instance owns no credentials, flow, carrier, clock, service, or
\  network singleton.  Credential/session objects and request/body arenas
\  remain caller-owned and must outlive a binding.  Calls are serialized on
\  the Streams/network owner context because BFM-DECODE-FEED uses the
\  existing owner-serialized JSON adapter.
\ =====================================================================

\ Keep the KDOS module identity within 23 bytes.
