        R@ ATAFC.EVENT SEVT.SEQUENCE !
    _ATAFCPB-NOW @ R@ ATAFC.EVENT SEVT.RECEIVED-MS !
    _ATAFCPB-BODY-A @ _ATAFCPB-BODY-U @
