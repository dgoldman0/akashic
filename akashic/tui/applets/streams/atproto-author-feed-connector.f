        AT-AUTHOR-FEED-CONNECTOR-S-OK
    ELSE
        AT-AUTHOR-FEED-CONNECTOR-S-XRPC
    THEN
    _ATAFCX-OWNER @ ATAFC.LAST-STATUS !
    _ATAFCX-STEP @
    _ATAFCX-CLEAR ;

: AT-AUTHOR-FEED-CONNECTOR-XIO-POLL
  ( operation owner -- step-status )
    _ATAFCX-OWNER ! _ATAFCX-OP !
    _ATAFCX-OWNER @ AT-AUTHOR-FEED-CONNECTOR-VALID? 0= IF
        _ATAFCX-FAIL-INVALID EXIT
    THEN
    _ATAFCX-OP @ _ATAFCX-OWNER @ ATAFC.EXCHANGE
    AT-XRPC-EXCHANGE-XIO-POLL DUP _ATAFCX-STEP !
    DUP XIO-STEP-PENDING = IF
        DROP XIO-STEP-PENDING _ATAFCX-CLEAR EXIT
    THEN
    XIO-STEP-SUCCEEDED <> IF
        AT-AUTHOR-FEED-CONNECTOR-S-XRPC
            _ATAFCX-OWNER @ ATAFC.LAST-STATUS !
        XIO-STEP-FAILED _ATAFCX-CLEAR EXIT
    THEN
    0 _ATAFCX-OP @ XIOO.RESULT !

    _ATAFCX-OWNER @ ATAFC.EXCHANGE AT-XRPC-EXCHANGE-BODY@
    DUP AT-XRPC-EXCHANGE-S-OK <> IF
        >R 2DROP R> DROP
        AT-AUTHOR-FEED-CONNECTOR-S-XRPC
            _ATAFCX-OWNER @ ATAFC.LAST-STATUS !
        AT-AUTHOR-FEED-CONNECTOR-XERR-INVALID
            _ATAFCX-OP @ XIOO.ERROR !
        XIO-STEP-FAILED _ATAFCX-CLEAR EXIT
    THEN
    DROP _ATAFCX-BODY-U ! _ATAFCX-BODY-A !
    _ATAFCX-BODY-A @ _ATAFCX-BODY-U @
    _ATAFCX-OWNER @ ATAFC.FEED BFM-DECODE-FEED
    BFM-S-OK <> IF
        _ATAFC-F-CURRENT _ATAFCX-OWNER @ _ATAFC-FLAG-
        AT-AUTHOR-FEED-CONNECTOR-S-DECODE
            _ATAFCX-OWNER @ ATAFC.LAST-STATUS !
        AT-AUTHOR-FEED-CONNECTOR-XERR-DECODE
            _ATAFCX-OP @ XIOO.ERROR !
        XIO-STEP-FAILED _ATAFCX-CLEAR EXIT
    THEN
    _ATAFC-F-FEED _ATAFC-F-CURRENT OR
        _ATAFCX-OWNER @ _ATAFC-FLAG+
    AT-AUTHOR-FEED-CONNECTOR-S-OK
        _ATAFCX-OWNER @ ATAFC.LAST-STATUS !
    _ATAFCX-OWNER @ _ATAFCX-OP @ XIOO.RESULT !
    XIO-STEP-SUCCEEDED _ATAFCX-CLEAR ;

