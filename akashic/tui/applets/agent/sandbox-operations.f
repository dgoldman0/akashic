: _ASBOX-OPS-INIT-DISJOINT?
  ( owner|0 parent ops -- flag )
    >R
    R@ AGENT-SBOX-OPS-SIZE
    2 PICK CTX-SIZE
        MSPAN-OVERLAP? IF
        2DROP R> DROP 0 EXIT
    THEN
    OVER IF
        R@ AGENT-SBOX-OPS-SIZE
        3 PICK SBOX-MODULE-OWNER-SPAN-DISJOINT? 0= IF
            2DROP R> DROP 0 EXIT
        THEN
        DUP CTX-SIZE
        3 PICK SBOX-MODULE-OWNER-SPAN-DISJOINT? 0= IF
            2DROP R> DROP 0 EXIT
        THEN
    THEN
    2DROP R> DROP -1 ;

