        R@ AGENT-SBOX-OPS-SIZE
        R@ _ASO.OWNER @
            SBOX-MODULE-OWNER-SPAN-DISJOINT? 0= IF
            R> DROP 0 EXIT
        THEN
        R@ _ASO.PARENT @ CTX-SIZE
