    _DSJV-SLOT @ _DSJS.CALLER-GENERATION @ 0> 0= IF 0 EXIT THEN
    _DSJV-SLOT @ _DSJS.INVOCATION-GENERATION @ DUP 0> 0= IF
        DROP 0 EXIT
    THEN
    _DSJV-ID !
    _DSJV-SLOT @ _DSJS.RUN-STATE @ DUP SBOX-VM-RUN-INVALID <
    SWAP SBOX-VM-RUN-CANCELLED > OR IF 0 EXIT THEN
    _DSJV-SLOT @ _DSJS.STATUS @ DUP
        DESK-SBOX-JOB-STATUS-VALID? 0= IF DROP 0 EXIT THEN
    _DSJV-STATUS !
    _DSJV-SLOT @ _DSJS.ADMISSION DUP _DSJV-ADMISSION !
    DESK-SBOX-ADMISSION-VALID? 0= IF 0 EXIT THEN

    \ VALID? has checked the entire embedded admission/component/host graph.
    \ Bind its borrowed authority graph and copied correlation fields to this
    \ service before private serialized TICK/TAKE paths reuse that proof.
    _DSJV-ADMISSION @ _DSA.OWNER @
    _DSJV-SERVICE @ _DSJ.MODULE-OWNER @ <> IF 0 EXIT THEN
    _DSJV-ADMISSION @ _DSA.HEAD @
    _DSJV-SERVICE @ _DSJ.HEAD @ <> IF 0 EXIT THEN
    _DSJV-ADMISSION @ _DSA.PARENT @
    _DSJV-SERVICE @ _DSJ.PARENT @ <> IF 0 EXIT THEN
    _DSJV-ADMISSION @ _DSA.ACTIVATION-GENERATION @
    _DSJV-GENERATION @ <> IF 0 EXIT THEN
    _DSJV-ADMISSION @ _DSA.ACTIVATION-ID @
    _DSJV-SERVICE @ _DSJ.ACTIVATION-ID @ <> IF 0 EXIT THEN
    _DSJV-ADMISSION @ _DSA.COMPONENT _DSC.LIVE-GENERATION @
    _DSJV-ID @ <> IF 0 EXIT THEN

    _DSJV-SLOT @ _DSJS.STATE @ DESK-SBOX-JOB-STATE-FAILED = IF
        _DSJV-STATUS @ DESK-SBOX-S-OK <> EXIT
    THEN
    _DSJV-ADMISSION @ _DSA.COMPONENT _DSC.HOST
    _SHOST-RUN-STATE-VALIDATED _DSJV-RUN !
    _DSJV-RUN @ _DSJV-SLOT @ _DSJS.RUN-STATE @ <> IF 0 EXIT THEN

    _DSJV-SLOT @ _DSJS.STATE @
    DUP DESK-SBOX-JOB-STATE-RUNNABLE = IF
        DROP
        _DSJV-STATUS @ DESK-SBOX-S-OK =
        _DSJV-RUN @ SBOX-VM-RUN-RUNNABLE = AND EXIT
    THEN
    DUP DESK-SBOX-JOB-STATE-READY = IF
        DROP
        _DSJV-STATUS @ DESK-SBOX-S-OK =
        _DSJV-RUN @ _DSJ-TERMINAL? AND EXIT
    THEN
    DROP
    _DSJV-STATUS @ DESK-SBOX-S-OK <> ;

