: _DSJ-LOOKUP  ( activation-id job-generation caller service -- slot status )
    _DSJL-SERVICE ! _DSJL-CALLER !
    _DSJL-GENERATION ! _DSJL-ACTIVATION !
    _DSJL-SERVICE @ DESK-SBOX-JOB-SERVICE-VALID? 0= IF
        0 DESK-SBOX-S-INVALID EXIT
    THEN
    _DSJL-SERVICE @ DESK-SBOX-JOB-SERVICE-OWNER? 0= IF
        0 DESK-SBOX-JOB-S-WRONG-CORE EXIT
    THEN
    _DSJL-ACTIVATION @ _DSJL-SERVICE @ _DSJ.ACTIVATION-ID @ <> IF
        0 DESK-SBOX-S-STALE-GENERATION EXIT
    THEN
    _DSJL-GENERATION @ 0> 0= IF
        0 DESK-SBOX-S-STALE-GENERATION EXIT
    THEN
    _DSJL-CALLER @ _DSJ-CALLER? 0= IF
        0 DESK-SBOX-JOB-S-NOT-CALLER EXIT
    THEN
    DESK-SBOX-JOB-CAPACITY 0 ?DO
        I _DSJL-SERVICE @ _DSJ-SLOT DUP _DSJL-SLOT !
        _DSJS.STATE @ DESK-SBOX-JOB-STATE-FREE <> IF
            _DSJL-SLOT @ _DSJS.JOB-GENERATION @
            _DSJL-GENERATION @ = IF
                _DSJL-SLOT @ _DSJS.CALLER-ID @
                    _DSJL-CALLER @ CINST.ID @ =
                _DSJL-SLOT @ _DSJS.CALLER-GENERATION @
                    _DSJL-CALLER @ CINST.GENERATION @ = AND IF
                    _DSJL-SLOT @ DESK-SBOX-S-OK UNLOOP EXIT
                THEN
                0 DESK-SBOX-JOB-S-NOT-CALLER UNLOOP EXIT
            THEN
        THEN
    LOOP
    0 DESK-SBOX-S-NOT-FOUND ;

