        SWAP DESK-SBOX-JOB-CAPACITY >= OR IF DROP 0 EXIT THEN
    DUP _DSJ.LIVE-N @ DUP 0<
        SWAP DESK-SBOX-JOB-CAPACITY > OR IF DROP 0 EXIT THEN
    DUP _DSJ.SLICE-STEPS @ 0> 0= IF DROP 0 EXIT THEN
    DUP _DSJ.INSTRUCTION-BUDGET @ 0> 0= IF DROP 0 EXIT THEN
    DUP _DSJ.VALUE-OP-BUDGET @ 0> 0= IF DROP 0 EXIT THEN
    DUP _DSJ.COPY-BUDGET @ 0> 0= IF DROP 0 EXIT THEN
