    _DSJV-SERVICE !
    0 _DSJV-LIVE-N !
    DESK-SBOX-JOB-CAPACITY 0 ?DO
        I _DSJV-SERVICE @ _DSJ-SLOT-VALID? 0= IF
            0 UNLOOP EXIT
        THEN
        I _DSJV-SERVICE @ _DSJ-SLOT _DSJS.STATE @
        DESK-SBOX-JOB-STATE-FREE <> IF
            1 _DSJV-LIVE-N +!
        THEN
    LOOP
