VARIABLE _DSJC-SLOT
VARIABLE _DSJC-STATUS
VARIABLE _DSJC-RUN

: DESK-SBOX-JOB-CANCEL
  ( activation-id job-generation caller-instance service -- status )
    _DSJ-LOOKUP
    DUP IF NIP EXIT THEN
    DROP _DSJC-SLOT !
    _DSJC-SLOT @ _DSJS.STATE @ DESK-SBOX-JOB-STATE-READY = IF
        DESK-SBOX-S-OK EXIT
    THEN
    _DSJC-SLOT @ _DSJS.STATE @ DESK-SBOX-JOB-STATE-FAILED = IF
        _DSJC-SLOT @ _DSJS.STATUS @ EXIT
    THEN
    _DSJC-SLOT @ _DSJS.INVOCATION-GENERATION @
    _DSJC-SLOT @ _DSJS.ADMISSION
    DESK-SBOX-ADMISSION-CANCEL DUP _DSJC-STATUS !
    DUP IF
        _DSJC-SLOT @ _DSJS.STATUS !
        DESK-SBOX-JOB-STATE-FAILED _DSJC-SLOT @ _DSJS.STATE !
        _DSJC-STATUS @ EXIT
    THEN
    DROP
    _DSJC-SLOT @ _DSJS.INVOCATION-GENERATION @
    _DSJC-SLOT @ _DSJS.ADMISSION
    DESK-SBOX-ADMISSION-RUN-STATE@
    _DSJC-STATUS ! _DSJC-RUN !
    _DSJC-RUN @ _DSJC-SLOT @ _DSJS.RUN-STATE !
    _DSJC-STATUS @ _DSJC-SLOT @ _DSJS.STATUS !
    _DSJC-STATUS @ IF
        DESK-SBOX-JOB-STATE-FAILED
    ELSE
        DESK-SBOX-JOB-STATE-READY
    THEN _DSJC-SLOT @ _DSJS.STATE !
    _DSJC-STATUS @ ;

: _DSJ-DISCARD-SLOT  ( slot service -- status )
    >R
    DUP _DSJS.STATE @ DESK-SBOX-JOB-STATE-FREE = IF
        DROP R> DROP DESK-SBOX-S-OK EXIT
    THEN
    DUP _DSJS.ADMISSION DESK-SBOX-ADMISSION-DRAIN
    OVER _DSJS.ADMISSION DESK-SBOX-ADMISSION-STATE@
    DESK-SBOX-ADMISSION-STATE-DRAINED <> IF
        NIP R> DROP EXIT
    THEN
    OVER _DSJS-SIZE 0 FILL
    -1 R> _DSJ.LIVE-N +!
    NIP ;

