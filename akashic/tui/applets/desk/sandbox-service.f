: _DSJSUB-FREE-SLOT  ( -- slot|0 )
    DESK-SBOX-JOB-CAPACITY 0 ?DO
        I _DSJSUB-SERVICE @ _DSJ-SLOT DUP _DSJSUB-SLOT !
        _DSJS.STATE @ DESK-SBOX-JOB-STATE-FREE = IF
            _DSJSUB-SLOT @ UNLOOP EXIT
        THEN
    LOOP
    0 ;

: _DSJSUB-BOUNDARY  ( -- status )
    _DSJSUB-SERVICE @ DESK-SBOX-JOB-SERVICE-VALID? 0= IF
        DESK-SBOX-S-INVALID EXIT
    THEN
    _DSJSUB-SERVICE @ DESK-SBOX-JOB-SERVICE-OWNER? 0= IF
        DESK-SBOX-JOB-S-WRONG-CORE EXIT
    THEN
    _DSJSUB-SERVICE @ _DSJ.STATE @
    DESK-SBOX-JOB-SERVICE-STATE-OPEN <> IF
        DESK-SBOX-S-STATE EXIT
    THEN
    _DSJSUB-SERVICE @ _DSJ.LIVE-N @
    DESK-SBOX-JOB-CAPACITY >= IF DESK-SBOX-JOB-S-FULL EXIT THEN
    _DSJSUB-CALLER @ _DSJ-CALLER? 0= IF
        DESK-SBOX-JOB-S-NOT-CALLER EXIT
    THEN
    _DSJSUB-REVISION @ 0> 0= IF DESK-SBOX-S-INVALID EXIT THEN
    _DSJSUB-INPUT-U @ 0> 0= IF DESK-SBOX-S-INVALID EXIT THEN
    _DSJSUB-RID @ RID-SIZE _DSJSUB-SERVICE @
        _DSJ-EXTERNAL-SPAN? 0= IF DESK-SBOX-S-ALIAS EXIT THEN
    _DSJSUB-ENTRY @ _DSJSUB-ENTRY-U @ _DSJSUB-SERVICE @
        _DSJ-EXTERNAL-SPAN? 0= IF DESK-SBOX-S-ALIAS EXIT THEN
    _DSJSUB-INPUT @ _DSJSUB-INPUT-U @ _DSJSUB-SERVICE @
        _DSJ-EXTERNAL-SPAN? 0= IF DESK-SBOX-S-ALIAS EXIT THEN
    _DSJSUB-RID @ RID-PRESENT? 0= IF DESK-SBOX-S-INVALID EXIT THEN
    _DSJSUB-SERVICE @ _DSJ.NEXT-GENERATION @
    _DSJ-GENERATION-MAX >= IF DESK-SBOX-S-STATE EXIT THEN
    _DSJSUB-FREE-SLOT 0= IF DESK-SBOX-JOB-S-FULL EXIT THEN
    DESK-SBOX-S-OK ;

: _DSJSUB-ROLLBACK  ( -- )
    _DSJSUB-SLOT @ ?DUP IF
        DUP _DSJS.ADMISSION DESK-SBOX-ADMISSION-RELEASE DROP
        _DSJS-SIZE 0 FILL
    THEN ;

: DESK-SBOX-JOB-SUBMIT
  ( rid revision entry entry-u input input-u caller-instance service -- activation-id|0 job-generation|0 status )
    _DSJSUB-SERVICE !
