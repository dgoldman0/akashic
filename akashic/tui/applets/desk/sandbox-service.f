    _DSJSUB-FREE-SLOT DUP _DSJSUB-SLOT !
    _DSJSUB-SERVICE @ _DSJ.NEXT-GENERATION DUP 1 SWAP +!
    @ _DSJSUB-JOB-GENERATION !

    _DSJSUB-SERVICE @ _DSJ.MODULE-OWNER @
    _DSJSUB-SERVICE @ _DSJ.HEAD @
    _DSJSUB-SERVICE @ _DSJ.PARENT @
    _DSJSUB-SERVICE @ _DSJ.LIMITS
    _DSJSUB-SERVICE @ _DSJ.INSTRUCTION-BUDGET @
    _DSJSUB-SERVICE @ _DSJ.VALUE-OP-BUDGET @
    _DSJSUB-SERVICE @ _DSJ.COPY-BUDGET @
    _DSJSUB-SERVICE @ _DSJ.ACTIVATION-ID @
    _DSJSUB-JOB-GENERATION @
    _DSJSUB-RID @
    _DSJSUB-REVISION @
    _DSJSUB-ENTRY @
    _DSJSUB-ENTRY-U @
    _DSJSUB-SLOT @ _DSJS.ADMISSION
    DESK-SBOX-ADMISSION-INIT
    DUP _DSJSUB-STATUS ! IF
        _DSJSUB-ROLLBACK
        0 0 _DSJSUB-STATUS @ EXIT
    THEN

    _DSJSUB-INPUT @
    _DSJSUB-INPUT-U @
    _DSJSUB-SLOT @ _DSJS.ADMISSION
    DESK-SBOX-ADMISSION-INVOKE
    _DSJSUB-STATUS ! _DSJSUB-INVOCATION !
    _DSJSUB-STATUS @ IF
        _DSJSUB-ROLLBACK
        0 0 _DSJSUB-STATUS @ EXIT
    THEN

    _DSJSUB-JOB-GENERATION @ _DSJSUB-SLOT @
        _DSJS.JOB-GENERATION !
    _DSJSUB-CALLER @ CINST.ID @ _DSJSUB-SLOT @ _DSJS.CALLER-ID !
    _DSJSUB-CALLER @ CINST.GENERATION @
        _DSJSUB-SLOT @ _DSJS.CALLER-GENERATION !
    _DSJSUB-INVOCATION @ _DSJSUB-SLOT @
        _DSJS.INVOCATION-GENERATION !
    SBOX-VM-RUN-RUNNABLE _DSJSUB-SLOT @ _DSJS.RUN-STATE !
    DESK-SBOX-S-OK _DSJSUB-SLOT @ _DSJS.STATUS !
    DESK-SBOX-JOB-STATE-RUNNABLE _DSJSUB-SLOT @ _DSJS.STATE !
    1 _DSJSUB-SERVICE @ _DSJ.LIVE-N +!

    _DSJSUB-SERVICE @ _DSJ.ACTIVATION-ID @
    _DSJSUB-JOB-GENERATION @
    DESK-SBOX-S-OK ;

