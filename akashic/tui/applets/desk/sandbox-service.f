VARIABLE _DSJT-STATUS

: _DSJT-ADVANCE-CURSOR  ( -- )
    _DSJT-INDEX @ 1+ DESK-SBOX-JOB-CAPACITY MOD
    _DSJT-SERVICE @ _DSJ.CURSOR ! ;

: DESK-SBOX-JOB-SERVICE-TICK  ( service -- status )
    DUP DESK-SBOX-JOB-SERVICE-VALID? 0= IF
        DROP DESK-SBOX-S-INVALID EXIT
    THEN
    DUP DESK-SBOX-JOB-SERVICE-OWNER? 0= IF
        DROP DESK-SBOX-JOB-S-WRONG-CORE EXIT
    THEN
    DUP _DSJ.STATE @ DESK-SBOX-JOB-SERVICE-STATE-OPEN <> IF
        DROP DESK-SBOX-S-STATE EXIT
    THEN
    _DSJT-SERVICE !
    0 _DSJT-ATTEMPT !
    BEGIN
        _DSJT-ATTEMPT @ DESK-SBOX-JOB-CAPACITY <
    WHILE
        _DSJT-SERVICE @ _DSJ.CURSOR @ _DSJT-ATTEMPT @ +
        DESK-SBOX-JOB-CAPACITY MOD DUP _DSJT-INDEX !
        _DSJT-SERVICE @ _DSJ-SLOT DUP _DSJT-SLOT !
        _DSJS.STATE @ DESK-SBOX-JOB-STATE-RUNNABLE = IF
            _DSJT-SERVICE @ _DSJ.SLICE-STEPS @
            _DSJT-SLOT @ _DSJS.INVOCATION-GENERATION @
            _DSJT-SLOT @ _DSJS.ADMISSION
            _DSA-RUN-SLICE-VALIDATED
            _DSJT-STATUS ! _DSJT-RUN !
            _DSJT-RUN @ _DSJT-SLOT @ _DSJS.RUN-STATE !
            _DSJT-STATUS @ DUP
                DESK-SBOX-JOB-STATUS-VALID? 0= IF
                DROP DESK-SBOX-S-HOST _DSJT-STATUS !
            THEN
            _DSJT-STATUS @ _DSJT-SLOT @ _DSJS.STATUS !
            _DSJT-STATUS @ IF
                DESK-SBOX-JOB-STATE-FAILED
                    _DSJT-SLOT @ _DSJS.STATE !
            ELSE
                _DSJT-RUN @ SBOX-VM-RUN-RUNNABLE = IF
                    DESK-SBOX-JOB-STATE-RUNNABLE
                ELSE
                    _DSJT-RUN @ _DSJ-TERMINAL? IF
                        DESK-SBOX-JOB-STATE-READY
                    ELSE
                        DESK-SBOX-S-HOST _DSJT-STATUS !
                        DESK-SBOX-S-HOST _DSJT-SLOT @ _DSJS.STATUS !
                        DESK-SBOX-JOB-STATE-FAILED
                    THEN
                THEN _DSJT-SLOT @ _DSJS.STATE !
            THEN
            _DSJT-ADVANCE-CURSOR
            _DSJT-STATUS @ EXIT
        THEN
        1 _DSJT-ATTEMPT +!
    REPEAT
    DESK-SBOX-S-OK ;

