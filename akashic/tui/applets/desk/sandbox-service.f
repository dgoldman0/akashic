: _DSJ-SLOT-VALID?  ( index service -- flag )
    _DSJV-SERVICE ! _DSJV-ID !
    _DSJV-ID @ _DSJV-SERVICE @ _DSJ-SLOT DUP _DSJV-SLOT !
    _DSJS.STATE @ DUP DESK-SBOX-JOB-STATE-FREE = IF
        DROP _DSJV-SLOT @ _DSJS-SIZE _DSJ-ZERO? EXIT
    THEN
    DUP DESK-SBOX-JOB-STATE-RUNNABLE <
    SWAP DESK-SBOX-JOB-STATE-FAILED > OR IF 0 EXIT THEN
    _DSJV-SLOT @ _DSJS.RESERVED @ IF 0 EXIT THEN
    _DSJV-SLOT @ _DSJS.JOB-GENERATION @ DUP 0> 0= IF DROP 0 EXIT THEN
    _DSJV-GENERATION !
