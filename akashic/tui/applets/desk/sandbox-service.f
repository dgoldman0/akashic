VARIABLE _DSJCL-SERVICE
VARIABLE _DSJCL-SLOT
VARIABLE _DSJCL-FIRST
VARIABLE _DSJCL-STATUS
VARIABLE _DSJCL-RUN

: _DSJCL-REMEMBER  ( status -- )
    ?DUP IF
        _DSJCL-FIRST @ DESK-SBOX-S-OK =
        IF _DSJCL-FIRST ! ELSE DROP THEN
    THEN ;

: DESK-SBOX-JOB-SERVICE-CLOSE  ( service -- status )
    DUP _DSJ-HEADER? 0= IF DROP DESK-SBOX-S-INVALID EXIT THEN
    DUP _DSJ.STATE @ DESK-SBOX-JOB-SERVICE-STATE-DRAINED = IF
        DROP DESK-SBOX-S-OK EXIT
    THEN
    DUP DESK-SBOX-JOB-SERVICE-OWNER? 0= IF
        DROP DESK-SBOX-JOB-S-WRONG-CORE EXIT
    THEN
    DUP _DSJCL-SERVICE !
    DESK-SBOX-JOB-SERVICE-STATE-CLOSING SWAP _DSJ.STATE !
    DESK-SBOX-S-OK _DSJCL-FIRST !
    DESK-SBOX-JOB-CAPACITY 0 ?DO
        I _DSJCL-SERVICE @ _DSJ-SLOT DUP _DSJCL-SLOT !
        _DSJS.STATE @ DESK-SBOX-JOB-STATE-FREE <> IF
            _DSJCL-SLOT @ _DSJS.ADMISSION
            DESK-SBOX-ADMISSION-CLOSE DUP _DSJCL-STATUS !
            _DSJCL-REMEMBER
            _DSJCL-STATUS @ DESK-SBOX-S-OK = IF
                _DSJCL-SLOT @ _DSJS.INVOCATION-GENERATION @
                _DSJCL-SLOT @ _DSJS.ADMISSION
                DESK-SBOX-ADMISSION-RUN-STATE@
                _DSJCL-STATUS ! _DSJCL-RUN !
                _DSJCL-STATUS @ _DSJCL-REMEMBER
                _DSJCL-STATUS @ IF
                    _DSJCL-STATUS @ _DSJCL-SLOT @ _DSJS.STATUS !
                    DESK-SBOX-JOB-STATE-FAILED
                        _DSJCL-SLOT @ _DSJS.STATE !
                ELSE
                    _DSJCL-RUN @ _DSJCL-SLOT @ _DSJS.RUN-STATE !
                    _DSJCL-RUN @ _DSJ-TERMINAL? IF
                        DESK-SBOX-S-OK
                            _DSJCL-SLOT @ _DSJS.STATUS !
                        DESK-SBOX-JOB-STATE-READY
                            _DSJCL-SLOT @ _DSJS.STATE !
                    ELSE
                        DESK-SBOX-S-HOST DUP _DSJCL-STATUS !
                        _DSJCL-SLOT @ _DSJS.STATUS !
                        DESK-SBOX-JOB-STATE-FAILED
                            _DSJCL-SLOT @ _DSJS.STATE !
                        _DSJCL-STATUS @ _DSJCL-REMEMBER
                    THEN
                THEN
            ELSE
                _DSJCL-STATUS @ _DSJCL-SLOT @ _DSJS.STATUS !
                DESK-SBOX-JOB-STATE-FAILED
                    _DSJCL-SLOT @ _DSJS.STATE !
            THEN
        THEN
    LOOP
    _DSJCL-FIRST @ ;

: _DSJ-DRAIN-CLEAR  ( service -- )
    DUP _DSJ.OWNER-CORE
    DESK-SBOX-JOB-SERVICE-SIZE _DSJ-OWNER-CORE -
    0 FILL
    DESK-SBOX-JOB-SERVICE-STATE-DRAINED SWAP _DSJ.STATE ! ;

: DESK-SBOX-JOB-SERVICE-DRAIN  ( service -- status )
    DUP _DSJ-HEADER? 0= IF DROP DESK-SBOX-S-INVALID EXIT THEN
    DUP _DSJ.STATE @ DESK-SBOX-JOB-SERVICE-STATE-DRAINED = IF
        DROP DESK-SBOX-S-OK EXIT
    THEN
    DUP _DSJ.OWNER-CORE @ COREID <> IF
        DROP DESK-SBOX-JOB-S-WRONG-CORE EXIT
    THEN
    _DSJCL-SERVICE !
    _DSJCL-SERVICE @ DESK-SBOX-JOB-SERVICE-CLOSE _DSJCL-FIRST !
    DESK-SBOX-JOB-CAPACITY 0 ?DO
        I _DSJCL-SERVICE @ _DSJ-SLOT DUP _DSJCL-SLOT !
        _DSJS.STATE @ DESK-SBOX-JOB-STATE-FREE <> IF
            _DSJCL-SLOT @ _DSJCL-SERVICE @
            _DSJ-DISCARD-SLOT _DSJCL-REMEMBER
        THEN
    LOOP
    _DSJCL-SERVICE @ _DSJ.LIVE-N @ 0= IF
        _DSJCL-SERVICE @ _DSJ-DRAIN-CLEAR
    THEN
    _DSJCL-FIRST @ ;

: DESK-SBOX-JOB-SERVICE-STATE@  ( service -- state|0 )
    DUP DESK-SBOX-JOB-SERVICE-VALID?
    IF _DSJ.STATE @ ELSE DROP 0 THEN ;

: DESK-SBOX-JOB-SERVICE-ACTIVATION@  ( service -- activation-id|0 )
    DUP DESK-SBOX-JOB-SERVICE-VALID?
    IF _DSJ.ACTIVATION-ID @ ELSE DROP 0 THEN ;

: DESK-SBOX-JOB-SERVICE-COUNT  ( service -- count|0 )
    DUP DESK-SBOX-JOB-SERVICE-VALID?
    IF _DSJ.LIVE-N @ ELSE DROP 0 THEN ;

: DESK-SBOX-JOB-SERVICE-RELEASE  ( service -- status )
    DUP _DSJ-FIXED? 0= IF DROP DESK-SBOX-S-INVALID EXIT THEN
    DUP DESK-SBOX-JOB-SERVICE-SIZE _DSJ-ZERO? IF
        DROP DESK-SBOX-S-OK EXIT
    THEN
    DUP _DSJ-HEADER? 0= IF DROP DESK-SBOX-S-INVALID EXIT THEN
    DUP DESK-SBOX-JOB-SERVICE-DRAIN
    OVER _DSJ.STATE @ DESK-SBOX-JOB-SERVICE-STATE-DRAINED = IF
        OVER DESK-SBOX-JOB-SERVICE-SIZE 0 FILL
    THEN
    NIP ;
