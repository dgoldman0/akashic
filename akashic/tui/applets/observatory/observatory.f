: OBS-TS-BE64!  ( u address -- )
    _OBS-BE-A ! _OBS-BE-V !
    8 0 DO
        _OBS-BE-V @ 56 I 8 * - RSHIFT 0xFF AND
            _OBS-BE-A @ I + C!
    LOOP ;

: OBS-TS-BE64@  ( address -- u )
    _OBS-BE-A ! 0 _OBS-BE-N !
    8 0 DO
        _OBS-BE-N @ 8 LSHIFT _OBS-BE-A @ I + C@ OR _OBS-BE-N !
    LOOP
    _OBS-BE-N @ ;

: OBS-TS-SIZE  ( count -- bytes flag )
    DUP 0> 0= IF DROP 0 0 EXIT THEN
    DUP 65536 OBS-TS-HEADER-SIZE - OBS-TS-SAMPLE-SIZE / > IF
        DROP 0 0 EXIT
    THEN
    OBS-TS-SAMPLE-SIZE * OBS-TS-HEADER-SIZE + -1 ;

