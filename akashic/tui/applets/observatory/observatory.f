        _OBS-CAP-HEX-A @ _OBS-CAP-I @ + C@
        DUP [CHAR] 0 >= OVER [CHAR] 9 <= AND
        OVER [CHAR] a >= ROT [CHAR] f <= AND OR 0= IF
            0 EXIT
        THEN
        1 _OBS-CAP-I +!
    REPEAT
    -1 ;

: _OBS-CAP-OPEN-HANDLER  ( request instance -- status )
    _OBS-ACTIVATE _OBS-CAP-REQ !
    _OBS-CAP-REQ @ CBR.ARGS DUP CV-TYPE@ CV-T-STRING <> IF
        DROP S" Expected the canonical Worlds telemetry envelope"
            CBUS-S-INVALID _OBS-CAP-REQ @ CBR-ERROR!
        CBUS-S-INVALID EXIT
    THEN
    DUP CV-DATA@ SWAP CV-LEN@
    2DUP _OBS-LOWER-HEX? 0= IF
        2DROP S" Worlds telemetry envelope is not canonical lowercase hex"
            CBUS-S-INVALID _OBS-CAP-REQ @ CBR-ERROR!
        CBUS-S-INVALID EXIT
    THEN
    DUP 2 / DUP _OBS-CAP-BINARY-U ! ALLOCATE DUP IF
        2DROP 2DROP S" Could not allocate telemetry validation buffer"
            CBUS-S-FAILED _OBS-CAP-REQ @ CBR-ERROR!
        CBUS-S-FAILED EXIT
    THEN
    DROP _OBS-CAP-BINARY !
    _OBS-CAP-BINARY @ FMT-HEX-DECODE _OBS-CAP-BINARY-U @ <> IF
        _OBS-CAP-BINARY @ FREE
        S" Worlds telemetry envelope decode failed"
            CBUS-S-INVALID _OBS-CAP-REQ @ CBR-ERROR!
        CBUS-S-INVALID EXIT
    THEN
    _OBS-CAP-BINARY @ _OBS-CAP-BINARY-U @ _OBS-ACCEPT-SNAPSHOT
    _OBS-CAP-BINARY @ FREE
    DUP _OBS-LAST-ATTEMPT ! OBS-S-OK <> IF
        S" Worlds telemetry snapshot validation failed"
            CBUS-S-INVALID _OBS-CAP-REQ @ CBR-ERROR!
        CBUS-S-INVALID EXIT
    THEN
    _OBS-RUN-SEQUENCE @ _OBS-CAP-REQ @ CBR.RESULT CV-INT!
    CBUS-S-OK ;

