: _LIBM-ZERO?  ( address length -- flag )
    0 ?DO DUP I + C@ IF DROP 0 UNLOOP EXIT THEN LOOP DROP -1 ;

: _LIBM-REQUEST-HASH-FEED  ( entry -- )
    SHA3-256-BEGIN
    S" akashic.library.initial-request.facts" SHA3-256-ADD
    DUP LIBE.RECEIPT LIBR.METHOD 8 SHA3-256-ADD
    DUP LIBE.KIND 8 SHA3-256-ADD
    DUP LIBE.RECEIPT LIBR.INITIAL-CONTENT-REVISION
        8 SHA3-256-ADD
    DUP LIBE.RECEIPT LIBR.INITIAL-CONTENT-U 8 SHA3-256-ADD
    DUP LIBE.RECEIPT LIBR.INITIAL-MEDIA 8 SHA3-256-ADD
    DUP LIBE.RECEIPT LIBR.INITIAL-CONTENT-DIGEST
        LIB-DIGEST-SIZE SHA3-256-ADD
    DUP LIBE.RECEIPT LIBR.IMPORT-CONTRACT-DIGEST
        LIB-DIGEST-SIZE SHA3-256-ADD
    DUP LIBE.RECEIPT LIBR.SOURCE-OWNER-U 8 SHA3-256-ADD
    DUP LIBE.RECEIPT LIBR.SOURCE-OWNER
        QLOC-OWNER-MAX SHA3-256-ADD
    DUP LIBE.TITLE-U 8 SHA3-256-ADD
    DUP LIBE.TITLE LIB-TITLE-MAX SHA3-256-ADD
    DUP LIBE.TAG-N 8 SHA3-256-ADD
    DUP LIBE.LINEAGE-N 8 SHA3-256-ADD
    DUP LIBE.ORIGIN-N 8 SHA3-256-ADD
    DUP LIBE.METADATA-U 8 SHA3-256-ADD
    LIBE.METADATA-DIGEST LIB-DIGEST-SIZE SHA3-256-ADD
;

: _LIBM-REQUEST-HASH  ( entry destination -- )
    >R _LIBM-REQUEST-HASH-FEED R> SHA3-256-END ;

: _LIBM-REQUEST-SEAL-MATCHES?  ( entry -- flag )
    DUP _LIBM-REQUEST-HASH-FEED
    LIBE.RECEIPT LIBR.REQUEST-SEAL SHA3-256-END-COMPARE ;

: _LIBM-TEXT-SLOT?  ( address capacity length allow-empty? -- flag )
    >R
    DUP 0< IF DROP 2DROP R> DROP 0 EXIT THEN
    DUP 2 PICK > IF DROP 2DROP R> DROP 0 EXIT THEN
    DUP 0= R@ 0= AND IF DROP 2DROP R> DROP 0 EXIT THEN
    DUP IF
        2 PICK OVER UTF8-VALID? 0= IF
            DROP 2DROP R> DROP 0 EXIT
        THEN
    THEN
    TUCK - >R + R> _LIBM-ZERO?
    R> DROP ;

: _LIBM-KIND?  ( kind -- flag )
    DUP LIB-KIND-MANAGED-DOCUMENT = SWAP LIB-KIND-CAPTURE = OR ;

: _LIBM-LIFECYCLE?  ( lifecycle -- flag )
    DUP LIB-LIFECYCLE-ACTIVE =
    OVER LIB-LIFECYCLE-ARCHIVED = OR
    SWAP LIB-LIFECYCLE-TOMBSTONED = OR ;

: _LIBM-MEDIA?  ( media -- flag )
    DUP LIB-MEDIA-TEXT-PLAIN =
    OVER LIB-MEDIA-TEXT-MARKDOWN = OR
    SWAP LIB-MEDIA-TEXT-CSV = OR ;

: _LIBM-KIND-MEDIA?  ( kind media -- flag )
    OVER LIB-KIND-MANAGED-DOCUMENT = IF
        NIP DUP LIB-MEDIA-TEXT-PLAIN =
        SWAP LIB-MEDIA-TEXT-MARKDOWN = OR EXIT
    THEN
    SWAP LIB-KIND-CAPTURE = IF _LIBM-MEDIA? ELSE DROP 0 THEN ;

: _LIBM-TIME-REQUIRED?  ( clock value -- flag )
    OVER LIB-CLOCK-UNIX-MS = IF NIP 0>= EXIT THEN
    OVER LIB-CLOCK-MUTATION-SEQUENCE = IF NIP 0> EXIT THEN
    2DROP 0 ;

: _LIBM-TIME-NONE?  ( clock value -- flag )
    SWAP LIB-CLOCK-NONE = SWAP 0= AND ;

: _LIBM-MSEQ-AT-MOST?  ( clock value mutation-sequence -- flag )
    >R OVER LIB-CLOCK-MUTATION-SEQUENCE = IF
        NIP DUP 0> SWAP R@ <= AND R> DROP EXIT
    THEN
    2DROP R> DROP -1 ;

: _LIBM-MSEQ-EXACT?  ( clock value mutation-sequence -- flag )
    >R OVER LIB-CLOCK-MUTATION-SEQUENCE = IF
        NIP R> = EXIT
    THEN
    2DROP R> DROP -1 ;

: _LIBM-VFS-VALID?  ( locator -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIB-VFS-LOCATOR-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LIBV.PATH LIB-VFS-PATH-MAX 1+
        2 PICK LIBV.PATH-U @ 0 _LIBM-TEXT-SLOT? 0= IF DROP 0 EXIT THEN
    DUP LIBV.PATH-U @ LIB-VFS-PATH-MAX > IF DROP 0 EXIT THEN
    DUP LIBV.PATH C@ [CHAR] / <> IF DROP 0 EXIT THEN
    DUP LIBV.CONTENT-U @
        DUP 0< SWAP LIB-CONTENT-LENGTH-MAX > OR IF
        DROP 0 EXIT
    THEN
    DUP LIBV.DIGEST-KIND @ QLOC-DK-PROJECTION-CONTENT <> IF
        DROP 0 EXIT
    THEN
    DUP LIBV.FLAGS @ 0<> IF DROP 0 EXIT THEN
    LIBV.CONTENT-DIGEST RID-PRESENT? ;

: _LIBM-SEMANTIC-EXACT?  ( qloc -- flag )
    DUP QLOC-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP QLOC-VALID? 0= IF DROP 0 EXIT THEN
    DUP QLOC.MODE @ QLOC-M-EXACT-DOMAIN =
    OVER QLOC.STATE-DIGEST RID-PRESENT? AND
    SWAP DROP ;

: _LIBM-ORIGIN-VALID?  ( origin -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIB-ORIGIN-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LIBO.KIND @
    DUP LIB-ORIGIN-NONE = IF
        DROP LIB-ORIGIN-SIZE _LIBM-ZERO? EXIT
    THEN
    DUP LIB-ORIGIN-SEMANTIC = IF
        DROP LIBO.SEMANTIC _LIBM-SEMANTIC-EXACT? EXIT
    THEN
    LIB-ORIGIN-VFS-SNAPSHOT = IF
        LIBO.VFS _LIBM-VFS-VALID? EXIT
    THEN
    DROP 0 ;

: _LIBM-RECEIPT-CREATED?  ( receipt -- flag )
    DUP LIBR.ORIGIN-REVISION @ 0= 0= IF DROP 0 EXIT THEN
    DUP LIBR.ORIGIN-DIGEST-KIND @ QLOC-DK-NONE <> IF DROP 0 EXIT THEN
    DUP LIBR.ORIGIN-STATE-DIGEST
        LIB-DIGEST-SIZE 2 * _LIBM-ZERO? 0= IF DROP 0 EXIT THEN
    DUP LIBR.SOURCE-OWNER-U @ 0<> IF DROP 0 EXIT THEN
    DUP LIBR.SOURCE-OWNER QLOC-OWNER-MAX _LIBM-ZERO? 0= IF DROP 0 EXIT THEN
    DUP LIBR.IMPORT-CONTRACT-DIGEST
        LIB-DIGEST-SIZE _LIBM-ZERO? 0= IF DROP 0 EXIT THEN
    DROP -1 ;

: _LIBM-RECEIPT-VFS?  ( receipt -- flag )
    DUP LIBR.ORIGIN-REVISION @ 0= 0= IF DROP 0 EXIT THEN
    DUP LIBR.ORIGIN-DIGEST-KIND @
        QLOC-DK-PROJECTION-CONTENT <> IF DROP 0 EXIT THEN
    DUP LIBR.ORIGIN-STATE-DIGEST RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBR.LOCATOR-DIGEST RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBR.SOURCE-OWNER QLOC-OWNER-MAX
        2 PICK LIBR.SOURCE-OWNER-U @ 0 _LIBM-TEXT-SLOT? 0= IF
        DROP 0 EXIT
    THEN
    DUP LIBR-SOURCE-OWNER$
        LIB-VFS-SOURCE-OWNER$ COMPARE IF DROP 0 EXIT THEN
    DUP LIBR.IMPORT-CONTRACT-DIGEST RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBR.INITIAL-CONTENT-DIGEST
        OVER LIBR.ORIGIN-STATE-DIGEST SHA3-256-COMPARE
    NIP ;

: _LIBM-RECEIPT-SEMANTIC?  ( receipt -- flag )
    DUP LIBR.ORIGIN-REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP LIBR.ORIGIN-DIGEST-KIND @ DUP
        QLOC-DK-SEMANTIC-STATE =
    SWAP QLOC-DK-PROJECTION-CONTENT = OR 0= IF DROP 0 EXIT THEN
    DUP LIBR.ORIGIN-STATE-DIGEST RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBR.LOCATOR-DIGEST RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBR.SOURCE-OWNER QLOC-OWNER-MAX
        2 PICK LIBR.SOURCE-OWNER-U @ 0 _LIBM-TEXT-SLOT? 0= IF
        DROP 0 EXIT
    THEN
    DUP LIBR.IMPORT-CONTRACT-DIGEST RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBR.ORIGIN-DIGEST-KIND @ QLOC-DK-PROJECTION-CONTENT = IF
        DUP LIBR.INITIAL-CONTENT-DIGEST
            OVER LIBR.ORIGIN-STATE-DIGEST SHA3-256-COMPARE 0= IF
            DROP 0 EXIT
        THEN
    THEN
    DROP -1 ;

: _LIBM-RECEIPT-VALID?  ( receipt -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIB-RECEIPT-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LIBR.OPERATION-KEY RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBR.INITIAL-CONTENT-REVISION @ 1 <> IF DROP 0 EXIT THEN
    DUP LIBR.INITIAL-CONTENT-U @ DUP 0<
        SWAP LIB-CONTENT-LENGTH-MAX > OR IF DROP 0 EXIT THEN
    DUP LIBR.INITIAL-MEDIA @ _LIBM-MEDIA? 0= IF DROP 0 EXIT THEN
    DUP LIBR.INITIAL-CONTENT-DIGEST RID-PRESENT? 0= IF
        DROP 0 EXIT
    THEN
    DUP LIBR.REQUEST-SEAL RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBR.FLAGS @ 0<> IF DROP 0 EXIT THEN
    DUP LIBR.METHOD @
    DUP LIB-IMPORT-CREATED = IF
        DROP _LIBM-RECEIPT-CREATED? EXIT
    THEN
    DUP LIB-IMPORT-VFS-SNAPSHOT = IF
        DROP _LIBM-RECEIPT-VFS? EXIT
    THEN
    LIB-IMPORT-SEMANTIC-SNAPSHOT = IF
        _LIBM-RECEIPT-SEMANTIC? EXIT
    THEN
    DROP 0 ;

: _LIBM-LINEAGE-VALUE?  ( lineage -- flag )
    DUP LIBLN.RELATION @ LIB-LINEAGE-RELATION-DERIVED-FROM =
    SWAP LIBLN.LOCATOR _LIBM-SEMANTIC-EXACT? AND ;

: _LIBM-FACT-PAYLOAD?  ( payload-a payload-u kind -- flag )
    CASE
        LIB-METADATA-FACT-TAG OF
            DUP 1 < OVER LIB-TAG-TEXT-MAX > OR IF
                2DROP 0
            ELSE
                2DUP MSPAN-NONWRAPPING?
                IF UTF8-VALID? ELSE 2DROP 0 THEN
            THEN
        ENDOF
        LIB-METADATA-FACT-ORIGIN OF
            DUP LIB-ORIGIN-SIZE <> IF
                2DROP 0
            ELSE
                DROP _LIBM-ORIGIN-VALID?
            THEN
        ENDOF
        LIB-METADATA-FACT-LINEAGE OF
            DUP LIB-LINEAGE-SIZE <> IF
                2DROP 0
            ELSE
                DROP _LIBM-LINEAGE-VALUE?
            THEN
        ENDOF
        DROP 2DROP 0
    ENDCASE ;

: _LIBM-SUMMARY-CANONICAL?
  ( payload-a payload-u kind summary -- flag )
    >R
    DUP R@ _LIBMS.LAST-KIND @ < IF
        DROP 2DROP R> DROP 0 EXIT
    THEN
    DUP R@ _LIBMS.LAST-KIND @ > IF
        DROP 2DROP R> DROP -1 EXIT
    THEN
    DROP
    R@ _LIBMS.LAST-A @ R@ _LIBMS.LAST-U @
    3 PICK 3 PICK COMPARE 0<
    NIP NIP R> DROP ;

: _LIBM-SUMMARY-COUNT+?  ( count-a -- flag )
    DUP @ LIB-METADATA-LENGTH-MAX >= IF DROP 0 EXIT THEN
    1 SWAP +! -1 ;

: _LIBM-SUMMARY-NOTE
  ( payload-a payload-u kind summary -- status )
    >R
    2 PICK 2 PICK 2 PICK R@ _LIBM-SUMMARY-CANONICAL? 0= IF
        2DROP DROP R> DROP LIB-S-INVALID EXIT
    THEN
    2 PICK 2 PICK 2 PICK _LIBM-FACT-PAYLOAD? 0= IF
        2DROP DROP R> DROP LIB-S-INVALID EXIT
    THEN
    DUP LIB-METADATA-FACT-TAG = IF
        R@ LIBMS.TAG-N _LIBM-SUMMARY-COUNT+?
    ELSE
        DUP LIB-METADATA-FACT-ORIGIN = IF
            R@ LIBMS.ORIGIN-N DUP @ 0<> IF
                DROP 0
            ELSE
                _LIBM-SUMMARY-COUNT+?
            THEN
        ELSE
            DUP LIB-METADATA-FACT-LINEAGE = IF
                R@ LIBMS.LINEAGE-N _LIBM-SUMMARY-COUNT+?
            ELSE
                0
            THEN
        THEN
    THEN
    0= IF 2DROP DROP R> DROP LIB-S-INVALID EXIT THEN
    DUP LIB-METADATA-FACT-ORIGIN = IF
        2 PICK R@ LIBMS.ORIGIN-A !
    THEN
    DUP R@ _LIBMS.LAST-KIND !
    2 PICK R@ _LIBMS.LAST-A !
    OVER R@ _LIBMS.LAST-U !
    2DROP DROP R> DROP LIB-S-OK ;

: _LIBM-FACT-STEP
  ( remaining-a remaining-u summary -- next-a next-u status )
    >R
    DUP LIB-METADATA-FACT-HEADER-SIZE < IF
        2DROP R> DROP 0 0 LIB-S-INVALID EXIT
    THEN
    OVER LIBMF.PAYLOAD-U @
    DUP 0< IF DROP 2DROP R> DROP 0 0 LIB-S-INVALID EXIT THEN
    DUP 2 PICK LIB-METADATA-FACT-HEADER-SIZE - > IF
        DROP 2DROP R> DROP 0 0 LIB-S-INVALID EXIT
    THEN
    2 PICK LIBMF.PAYLOAD
    OVER
    4 PICK LIBMF.KIND @
    R@ _LIBM-SUMMARY-NOTE
    DUP IF
        >R DROP 2DROP R> R> DROP 0 0 ROT EXIT
    THEN
    DROP
    LIB-METADATA-FACT-HEADER-SIZE + >R
    SWAP R@ + SWAP R> -
    R> DROP LIB-S-OK ;

: _LIBM-METADATA-SUMMARIZE
  ( facts-a facts-u summary -- status )
    >R
    R@ LIB-METADATA-SUMMARY-INIT
    DUP 0< OVER LIB-METADATA-LENGTH-MAX > OR IF
        2DROP R> DROP LIB-S-INVALID EXIT
    THEN
    OVER 0= OVER 0<> AND IF
        2DROP R> DROP LIB-S-INVALID EXIT
    THEN
    2DUP MSPAN-NONWRAPPING? 0= IF
        2DROP R> DROP LIB-S-INVALID EXIT
    THEN
    DUP R@ LIBMS.FACTS-U !
    2DUP R@ LIBMS.DIGEST SHA3-256-HASH
    BEGIN DUP WHILE
        R@ _LIBM-FACT-STEP
        DUP IF
            >R 2DROP R> R> DROP EXIT
        THEN
        DROP
    REPEAT
    2DROP R> DROP LIB-S-OK ;

: _LIBM-RECEIPT-MATCHES-VFS?  ( origin entry -- flag )
    >R
    R@ LIBE.RECEIPT LIBR.METHOD @
        LIB-IMPORT-VFS-SNAPSHOT <> IF DROP R> DROP 0 EXIT THEN
    R@ LIBE.RECEIPT LIBR.ORIGIN-REVISION @ IF
        DROP R> DROP 0 EXIT
    THEN
    DUP LIBO.VFS LIBV.DIGEST-KIND @
        R@ LIBE.RECEIPT LIBR.ORIGIN-DIGEST-KIND @
        <> IF DROP R> DROP 0 EXIT THEN
    DUP LIBO.VFS LIBV.CONTENT-U @
        R@ LIBE.RECEIPT LIBR.INITIAL-CONTENT-U @
        <> IF DROP R> DROP 0 EXIT THEN
    DUP LIBO.VFS LIBV.CONTENT-DIGEST
        R@ LIBE.RECEIPT LIBR.ORIGIN-STATE-DIGEST
        SHA3-256-COMPARE 0= IF DROP R> DROP 0 EXIT THEN
    R@ LIBE.RECEIPT LIBR-SOURCE-OWNER$
        LIB-VFS-SOURCE-OWNER$ COMPARE 0=
    NIP R> DROP ;

: _LIBM-RECEIPT-MATCHES-SEMANTIC?  ( origin entry -- flag )
    >R
    R@ LIBE.RECEIPT LIBR.METHOD @
        LIB-IMPORT-SEMANTIC-SNAPSHOT <> IF DROP R> DROP 0 EXIT THEN
    DUP LIBO.SEMANTIC QLOC.DOMAIN-REVISION @
        R@ LIBE.RECEIPT LIBR.ORIGIN-REVISION @
        <> IF DROP R> DROP 0 EXIT THEN
    DUP LIBO.SEMANTIC QLOC.DIGEST-KIND @
        R@ LIBE.RECEIPT LIBR.ORIGIN-DIGEST-KIND @
        <> IF DROP R> DROP 0 EXIT THEN
    DUP LIBO.SEMANTIC QLOC.STATE-DIGEST
        R@ LIBE.RECEIPT LIBR.ORIGIN-STATE-DIGEST
        SHA3-256-COMPARE 0= IF DROP R> DROP 0 EXIT THEN
    DUP LIBO.SEMANTIC QLOC-OWNER$
        R@ LIBE.RECEIPT LIBR-SOURCE-OWNER$ COMPARE IF
        DROP R> DROP 0 EXIT
    THEN
    DUP LIBO.SEMANTIC QLOC-PROJECTION$
        R@ LIBE.RECEIPT LIBR.IMPORT-CONTRACT-DIGEST
        SHA3-256-HASH-COMPARE
    NIP R> DROP ;

: _LIBM-RECEIPT-MATCHES-ORIGIN?  ( origin entry -- flag )
    >R
    DUP LIB-ORIGIN-SIZE
        R@ LIBE.RECEIPT LIBR.LOCATOR-DIGEST
        SHA3-256-HASH-COMPARE 0= IF DROP R> DROP 0 EXIT THEN
    DUP LIBO.KIND @
    DUP LIB-ORIGIN-VFS-SNAPSHOT = IF
        DROP R> _LIBM-RECEIPT-MATCHES-VFS? EXIT
    THEN
    LIB-ORIGIN-SEMANTIC = IF
        R> _LIBM-RECEIPT-MATCHES-SEMANTIC? EXIT
    THEN
    DROP R> DROP 0 ;

: _LIBM-METADATA-SUMMARY-SHAPE?  ( summary -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIB-METADATA-SUMMARY-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LIBMS.FACTS-U @ DUP 0<
        SWAP LIB-METADATA-LENGTH-MAX > OR IF DROP 0 EXIT THEN
    DUP LIBMS.TAG-N @ DUP 0<
        SWAP 2 PICK LIBMS.FACTS-U @
            LIB-METADATA-FACT-HEADER-SIZE / > OR IF DROP 0 EXIT THEN
    DUP LIBMS.LINEAGE-N @ DUP 0<
        SWAP 2 PICK LIBMS.FACTS-U @
            LIB-METADATA-FACT-HEADER-SIZE / > OR IF DROP 0 EXIT THEN
    DUP LIBMS.ORIGIN-N @ DUP 0< SWAP 1 > OR IF DROP 0 EXIT THEN
    LIBMS.DIGEST RID-PRESENT? ;

: _LIBM-METADATA-SUMMARY-MATCHES-ENTRY?  ( summary entry -- flag )
    >R
    DUP _LIBM-METADATA-SUMMARY-SHAPE? 0= IF DROP R> DROP 0 EXIT THEN
    DUP LIBMS.FACTS-U @ R@ LIBE.METADATA-U @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP LIBMS.TAG-N @ R@ LIBE.TAG-N @ <> IF DROP R> DROP 0 EXIT THEN
    DUP LIBMS.LINEAGE-N @ R@ LIBE.LINEAGE-N @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP LIBMS.ORIGIN-N @ R@ LIBE.ORIGIN-N @ <> IF
        DROP R> DROP 0 EXIT
    THEN
    DUP LIBMS.DIGEST R@ LIBE.METADATA-DIGEST
        SHA3-256-COMPARE 0= IF DROP R> DROP 0 EXIT THEN
    DUP LIBMS.ORIGIN-N @ 0= IF
        DROP
        R@ LIBE.RECEIPT LIBR.METHOD @ LIB-IMPORT-CREATED =
        R@ LIBE.KIND @ LIB-KIND-MANAGED-DOCUMENT = AND
        R> DROP EXIT
    THEN
    DUP LIBMS.ORIGIN-A @ DUP 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    SWAP DROP R> _LIBM-RECEIPT-MATCHES-ORIGIN? ;

: _LIBM-METADATA-SUMMARY-APPLY  ( summary entry -- status )
    >R
    DUP LIBMS.TAG-N @ R@ LIBE.TAG-N !
    DUP LIBMS.LINEAGE-N @ R@ LIBE.LINEAGE-N !
    DUP LIBMS.ORIGIN-N @ R@ LIBE.ORIGIN-N !
    DUP LIBMS.FACTS-U @ R@ LIBE.METADATA-U !
    DUP LIBMS.DIGEST R@ LIBE.METADATA-DIGEST
        LIB-DIGEST-SIZE MOVE
    DUP R@ _LIBM-METADATA-SUMMARY-MATCHES-ENTRY? IF
        DROP R> DROP LIB-S-OK EXIT
    THEN
    0 R@ LIBE.TAG-N !
    0 R@ LIBE.LINEAGE-N !
    0 R@ LIBE.ORIGIN-N !
    0 R@ LIBE.METADATA-U !
    R@ LIBE.METADATA-DIGEST LIB-DIGEST-SIZE 0 FILL
    DROP R> DROP LIB-S-INVALID ;

: _LIBM-ENTRY-TOMBSTONE?  ( entry -- flag )
    DUP LIBE.MEDIA @ LIB-MEDIA-NONE <> IF DROP 0 EXIT THEN
    DUP LIBE.CURRENT-CONTENT-REVISION @ 0<> IF DROP 0 EXIT THEN
    DUP LIBE.OLDEST-CONTENT-REVISION @ 0<> IF DROP 0 EXIT THEN
    DUP LIBE.CONTENT-U @ 0<> IF DROP 0 EXIT THEN
    DUP LIBE.CONTENT-DIGEST LIB-DIGEST-SIZE _LIBM-ZERO? 0= IF
        DROP 0 EXIT
    THEN
    DUP LIBE.CREATED-CLOCK @ OVER LIBE.CREATED-VALUE @
        _LIBM-TIME-NONE? 0= IF DROP 0 EXIT THEN
    DUP LIBE.IMPORTED-CLOCK @ OVER LIBE.IMPORTED-VALUE @
        _LIBM-TIME-NONE? 0= IF DROP 0 EXIT THEN
    DUP LIBE.MODIFIED-CLOCK @ OVER LIBE.MODIFIED-VALUE @
        _LIBM-TIME-NONE? 0= IF DROP 0 EXIT THEN
    DUP LIBE.DELETED-CLOCK @ OVER LIBE.DELETED-VALUE @
        _LIBM-TIME-REQUIRED? 0= IF DROP 0 EXIT THEN
    DUP LIBE.DELETED-CLOCK @ OVER LIBE.DELETED-VALUE @
        2 PICK LIBE.MUTATION-SEQUENCE @ _LIBM-MSEQ-EXACT? 0= IF
        DROP 0 EXIT
    THEN
    DUP LIBE.TITLE-U @ 0<> IF DROP 0 EXIT THEN
    DUP LIBE.TITLE LIB-TITLE-MAX _LIBM-ZERO? 0= IF DROP 0 EXIT THEN
    DUP LIBE.TAG-N @ 0<> IF DROP 0 EXIT THEN
    DUP LIBE.LINEAGE-N @ 0<> IF DROP 0 EXIT THEN
    DUP LIBE.ORIGIN-N @ 0<> IF DROP 0 EXIT THEN
    DUP LIBE.METADATA-U @ 0<> IF DROP 0 EXIT THEN
    LIBE.METADATA-DIGEST LIB-DIGEST-SIZE _LIBM-ZERO? ;

: _LIBM-ENTRY-METADATA-SHAPE?  ( entry -- flag )
    DUP LIBE.METADATA-U @ DUP 0<
        SWAP LIB-METADATA-LENGTH-MAX > OR IF DROP 0 EXIT THEN
    DUP LIBE.TAG-N @ DUP 0<
        SWAP 2 PICK LIBE.METADATA-U @
            LIB-METADATA-FACT-HEADER-SIZE / > OR IF DROP 0 EXIT THEN
    DUP LIBE.LINEAGE-N @ DUP 0<
        SWAP 2 PICK LIBE.METADATA-U @
            LIB-METADATA-FACT-HEADER-SIZE / > OR IF DROP 0 EXIT THEN
    DUP LIBE.ORIGIN-N @ DUP 0< SWAP 1 > OR IF DROP 0 EXIT THEN
    DUP LIBE.METADATA-U @ 0= IF
        DUP LIBE.TAG-N @
        OVER LIBE.LINEAGE-N @ OR
        OVER LIBE.ORIGIN-N @ OR IF DROP 0 EXIT THEN
    ELSE
        DUP LIBE.TAG-N @
        OVER LIBE.LINEAGE-N @ OR
        OVER LIBE.ORIGIN-N @ OR 0= IF DROP 0 EXIT THEN
    THEN
    DUP LIBE.METADATA-DIGEST RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBE.RECEIPT LIBR.METHOD @ LIB-IMPORT-CREATED = IF
        DUP LIBE.KIND @ LIB-KIND-MANAGED-DOCUMENT =
        SWAP LIBE.ORIGIN-N @ 0= AND EXIT
    THEN
    DUP LIBE.KIND @ LIB-KIND-CAPTURE =
    SWAP LIBE.ORIGIN-N @ 1 = AND ;

: _LIBM-ENTRY-REVISION-WINDOW?  ( entry -- flag )
    DUP LIBE.CURRENT-CONTENT-REVISION @ DUP 0> 0= IF
        2DROP 0 EXIT
    THEN
    OVER LIBE.DOMAIN-REVISION @ OVER < IF 2DROP 0 EXIT THEN
    OVER LIBE.KIND @ LIB-KIND-CAPTURE = IF
        DUP 1 <> IF 2DROP 0 EXIT THEN
        DROP LIBE.OLDEST-CONTENT-REVISION @ 1 = EXIT
    THEN
    DUP LIB-RETAINED-REVISION-MAX 1- > IF
        LIB-RETAINED-REVISION-MAX 1- -
    ELSE
        DROP 1
    THEN
    SWAP LIBE.OLDEST-CONTENT-REVISION @ = ;

: _LIBM-ENTRY-LIVE?  ( entry -- flag )
    DUP LIBE.KIND @ OVER LIBE.MEDIA @
        _LIBM-KIND-MEDIA? 0= IF DROP 0 EXIT THEN
    DUP LIBE.MEDIA @
        OVER LIBE.RECEIPT LIBR.INITIAL-MEDIA @ <> IF DROP 0 EXIT THEN
    DUP _LIBM-ENTRY-REVISION-WINDOW? 0= IF DROP 0 EXIT THEN
    DUP LIBE.CONTENT-U @
        DUP 0< SWAP LIB-CONTENT-LENGTH-MAX > OR IF
        DROP 0 EXIT
    THEN
    DUP LIBE.CONTENT-DIGEST RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBE.CREATED-CLOCK @
        OVER LIBE.CREATED-VALUE @ _LIBM-TIME-REQUIRED? 0= IF
        DROP 0 EXIT
    THEN
    DUP LIBE.MODIFIED-CLOCK @
        OVER LIBE.MODIFIED-VALUE @ _LIBM-TIME-REQUIRED? 0= IF
        DROP 0 EXIT
    THEN
    DUP LIBE.CREATED-CLOCK @
        OVER LIBE.CREATED-VALUE @
        2 PICK LIBE.MUTATION-SEQUENCE @ _LIBM-MSEQ-AT-MOST? 0= IF
        DROP 0 EXIT
    THEN
    DUP LIBE.IMPORTED-CLOCK @
        OVER LIBE.IMPORTED-VALUE @
        2 PICK LIBE.MUTATION-SEQUENCE @ _LIBM-MSEQ-AT-MOST? 0= IF
        DROP 0 EXIT
    THEN
    DUP LIBE.MODIFIED-CLOCK @
        OVER LIBE.MODIFIED-VALUE @
        2 PICK LIBE.MUTATION-SEQUENCE @ _LIBM-MSEQ-EXACT? 0= IF
        DROP 0 EXIT
    THEN
    DUP LIBE.DELETED-CLOCK @
        OVER LIBE.DELETED-VALUE @ _LIBM-TIME-NONE? 0= IF DROP 0 EXIT THEN
    DUP LIBE.TITLE LIB-TITLE-MAX
        2 PICK LIBE.TITLE-U @ 0 _LIBM-TEXT-SLOT? 0= IF DROP 0 EXIT THEN
    DUP _LIBM-ENTRY-METADATA-SHAPE? 0= IF DROP 0 EXIT THEN
    DUP LIBE.KIND @
        OVER LIBE.RECEIPT LIBR.INITIAL-MEDIA @
        _LIBM-KIND-MEDIA? 0= IF DROP 0 EXIT THEN
    DUP LIBE.CURRENT-CONTENT-REVISION @ 1 = IF
        DUP LIBE.CONTENT-U @
            OVER LIBE.RECEIPT LIBR.INITIAL-CONTENT-U @
            <> IF DROP 0 EXIT THEN
        DUP LIBE.MEDIA @
            OVER LIBE.RECEIPT LIBR.INITIAL-MEDIA @
            <> IF DROP 0 EXIT THEN
        DUP LIBE.CONTENT-DIGEST
            OVER LIBE.RECEIPT LIBR.INITIAL-CONTENT-DIGEST
            SHA3-256-COMPARE 0= IF DROP 0 EXIT THEN
    THEN
    DUP LIBE.DOMAIN-REVISION @ 1 = IF
        DUP _LIBM-REQUEST-SEAL-MATCHES? 0= IF DROP 0 EXIT THEN
    THEN
    DUP LIBE.RECEIPT LIBR.METHOD @ LIB-IMPORT-CREATED = IF
        DUP LIBE.KIND @ LIB-KIND-CAPTURE = IF DROP 0 EXIT THEN
        DUP LIBE.IMPORTED-CLOCK @
            OVER LIBE.IMPORTED-VALUE @ _LIBM-TIME-NONE?
        NIP EXIT
    THEN
    DUP LIBE.IMPORTED-CLOCK @
        OVER LIBE.IMPORTED-VALUE @ _LIBM-TIME-REQUIRED? 0= IF
        DROP 0 EXIT
    THEN
    LIBE.ORIGIN-N @ 1 = ;

: _LIBM-ENTRY-VALID?  ( entry -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIB-ENTRY-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LIBE.ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBE.DOMAIN-REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP LIBE.KIND @ _LIBM-KIND? 0= IF DROP 0 EXIT THEN
    DUP LIBE.LIFECYCLE @ _LIBM-LIFECYCLE? 0= IF DROP 0 EXIT THEN
    DUP LIBE.DOMAIN-REVISION @ 1 =
    OVER LIBE.LIFECYCLE @ LIB-LIFECYCLE-ACTIVE <> AND IF
        DROP 0 EXIT
    THEN
    DUP LIBE.MUTATION-SEQUENCE @ 0> 0= IF DROP 0 EXIT THEN
    DUP LIBE.FLAGS @ 0<> IF DROP 0 EXIT THEN
    DUP LIBE.RECEIPT _LIBM-RECEIPT-VALID? 0= IF DROP 0 EXIT THEN
    DUP LIBE.ID
        OVER LIBE.RECEIPT LIBR.OPERATION-KEY RID= IF DROP 0 EXIT THEN
    DUP LIBE.KIND @
        OVER LIBE.RECEIPT LIBR.INITIAL-MEDIA @
        _LIBM-KIND-MEDIA? 0= IF DROP 0 EXIT THEN
    DUP LIBE.LIFECYCLE @ LIB-LIFECYCLE-TOMBSTONED = IF
        _LIBM-ENTRY-TOMBSTONE?
    ELSE
        _LIBM-ENTRY-LIVE?
    THEN ;

: _LIBM-COLLECTION-VALID?  ( collection -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIB-COLLECTION-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LIBC.ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBC.OPERATION-KEY RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBC.ID OVER LIBC.OPERATION-KEY RID= IF DROP 0 EXIT THEN
    DUP LIBC.REQUEST-SEAL RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBC.REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP LIBC.MUTATION-SEQUENCE @ 0> 0= IF DROP 0 EXIT THEN
    DUP LIBC.CREATED-SEQUENCE @ 0> 0= IF DROP 0 EXIT THEN
    DUP LIBC.MEMBER-N @ 0< IF DROP 0 EXIT THEN
    DUP LIBC.FLAGS @ 0<> IF DROP 0 EXIT THEN
    DUP LIBC.TITLE LIB-COLLECTION-TITLE-MAX
        2 PICK LIBC.TITLE-U @ 0 _LIBM-TEXT-SLOT? 0= IF DROP 0 EXIT THEN
    LIBC.RESERVED 8 _LIBM-ZERO? ;

: _LIBM-CONTENT-SHAPE?  ( content -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIB-CONTENT-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LIBCT.ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBCT.DOMAIN-REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP LIBCT.CONTENT-REVISION @ DUP 0> 0= IF 2DROP 0 EXIT THEN
    OVER LIBCT.DOMAIN-REVISION @ OVER < IF 2DROP 0 EXIT THEN
    DROP
    DUP LIBCT.KIND @ OVER LIBCT.MEDIA @
        _LIBM-KIND-MEDIA? 0= IF DROP 0 EXIT THEN
    DUP LIBCT.KIND @ LIB-KIND-CAPTURE =
    OVER LIBCT.CONTENT-REVISION @ 1 <> AND IF DROP 0 EXIT THEN
    DUP LIBCT.DATA-U @
        DUP 0< SWAP LIB-CONTENT-LENGTH-MAX > OR IF
        DROP 0 EXIT
    THEN
    DUP LIBCT.DATA-U @ 0>
    OVER LIBCT.DATA-A @ 0= AND IF DROP 0 EXIT THEN
    DUP LIBCT-DATA$ MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LIBCT.FLAGS @ 0<> IF DROP 0 EXIT THEN
    LIBCT.RESERVED 8 _LIBM-ZERO? ;

: _LIBM-CONTENT-VALID?  ( content -- flag )
    DUP _LIBM-CONTENT-SHAPE? 0= IF DROP 0 EXIT THEN
    DUP LIBCT-DATA$ 2DUP UTF8-VALID? 0= IF
        2DROP DROP 0 EXIT
    THEN
    2 PICK LIBCT.DIGEST SHA3-256-HASH-COMPARE
    NIP ;

: _LIBM-CONTENT-DIGEST!  ( content -- status )
    DUP _LIBM-CONTENT-SHAPE? 0= IF DROP LIB-S-INVALID EXIT THEN
    DUP LIBCT-DATA$ 2DUP UTF8-VALID? 0= IF
        2DROP DROP LIB-S-INVALID EXIT
    THEN
    2 PICK LIBCT.DIGEST SHA3-256-HASH
    DROP LIB-S-OK ;

: _LIBM-ENTRY-REQUEST-SEAL!  ( entry -- status )
    DUP 0= IF DROP LIB-S-INVALID EXIT THEN
    DUP LIB-ENTRY-SIZE MSPAN-NONWRAPPING? 0= IF DROP LIB-S-INVALID EXIT THEN
    DUP LIBE.DOMAIN-REVISION @ 1 <> IF DROP LIB-S-INVALID EXIT THEN
    DUP LIBE.LIFECYCLE @ LIB-LIFECYCLE-ACTIVE <> IF
        DROP LIB-S-INVALID EXIT
    THEN
    DUP DUP LIBE.RECEIPT LIBR.REQUEST-SEAL _LIBM-REQUEST-HASH
    DUP _LIBM-ENTRY-VALID? IF DROP LIB-S-OK EXIT THEN
    LIBE.RECEIPT LIBR.REQUEST-SEAL LIB-DIGEST-SIZE 0 FILL
    LIB-S-INVALID ;

: LIB-VFS-LOCATOR-VALID?  ( locator -- flag )
