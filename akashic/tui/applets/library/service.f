    >R
    DUP R@ _LIBSVC-PAIR? 0= IF
        DROP R> DROP LIBRARY-SERVICE-S-INVALID EXIT
    THEN
    R@ _LSW.BUSY @ IF
        DROP R> DROP LIBRARY-SERVICE-S-BUSY EXIT
    THEN
    R@ ['] _LIBSVC-OWNER-NOOP
    2 PICK _LS.REPOSITORY @
    3 PICK _LS.REPOSITORY-WORK @
        LIBRARY-REPOSITORY-WITH-OWNER
    DUP IF NIP R> DROP EXIT THEN DROP
    R@ LIBRARY-SERVICE-WORK-FINI
    DUP IF NIP R> DROP EXIT THEN DROP
    LIBRARY-SERVICE-SIZE 0 FILL
    R> DROP
