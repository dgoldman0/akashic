    DUP 0= IF DROP 0 EXIT THEN
    DUP LIBRARY-SERVICE-WORK-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _LSW.MAGIC @ _LIBSVC-WORK-MAGIC <> IF DROP 0 EXIT THEN
