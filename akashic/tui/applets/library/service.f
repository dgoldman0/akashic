        DROP 2R> 2DROP 0 EXIT
    THEN
    DUP LSRXR.REQUIRED-OUT @ 8
    2R@ _LIBSVC-REQUEST-GRAPH-SAFE? 0= IF
        DROP 2R> 2DROP 0 EXIT
    THEN
