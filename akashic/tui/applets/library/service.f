: _LIBSVC-PAIR?  ( service work -- flag )
    DUP LIBRARY-SERVICE-WORK-VALID? 0= IF 2DROP 0 EXIT THEN
    _LSW.SERVICE @ = ;

\ A request descriptor is live for the complete synchronous operation.  Keep
\ it outside the service work and every span reachable from the checked
\ repository owner so guard/status/cache writes cannot rewrite request fields
\ while a callback is still reading them.
: _LIBSVC-REQUEST-GRAPH-SAFE?
  ( request request-u service service-work -- flag )
    2DUP _LIBSVC-PAIR? 0= IF _LIBSVC-DROP4 0 EXIT THEN
    >R >R
    2DUP MSPAN-NONWRAPPING? 0= IF
        2DROP R> DROP R> DROP 0 EXIT
    THEN
    2DUP R@ LIBRARY-SERVICE-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP R> DROP 0 EXIT
    THEN
    2DUP R@ _LS.REPOSITORY @ R@ _LS.REPOSITORY-WORK @
        LIBRARY-REPOSITORY-SPAN-DISJOINT? 0= IF
        2DROP R> DROP R> DROP 0 EXIT
    THEN
    R> DROP
    2DUP R@ LIBRARY-SERVICE-WORK-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP 0 EXIT
    THEN
    2DROP R> DROP -1 ;

: _LIBSVC-PAGE-GRAPH-SAFE?  ( page service service-work -- flag )
    2>R
    DUP LIBRARY-QUERY-PAGE-SIZE 2R@
        _LIBSVC-REQUEST-GRAPH-SAFE? 0= IF
        DROP 2R> 2DROP 0 EXIT
    THEN
    DUP LIBQP.ROWS @
    SWAP DUP LIBQP.CAPACITY @ SWAP LIBQP.ROW-SIZE @ *
    2R@ _LIBSVC-REQUEST-GRAPH-SAFE?
    2R> 2DROP ;

: _LIBSVC-ENTER  ( service work -- status )
    2DUP _LIBSVC-PAIR? 0= IF
        2DROP LIBRARY-SERVICE-S-INVALID EXIT
    THEN
    DUP _LSW.BUSY @ IF 2DROP LIBRARY-SERVICE-S-BUSY EXIT THEN
    -1 SWAP _LSW.BUSY !
    DROP LIBRARY-SERVICE-S-OK ;

: _LIBSVC-LEAVE  ( status service work -- status )
    >R
    OVER R@ _LSW.STATUS !
    OVER OVER _LS.STATUS !
    0 R@ _LSW.BUSY !
    DROP R> DROP ;

: _LIBSVC-WORK-STATUS!  ( status work -- )
    _LSW.STATUS ! ;

: _LIBSVC-OWNER-PREPARE
  ( service-work repository repository-work -- service-work )
    >R
    DUP LIBRARY-REPOSITORY-ADAPTER@
        2 PICK _LSW.ARG6 !
    R@ LIBRARY-REPOSITORY-INDEX-WORK@
        2 PICK _LSW.ARG7 !
    DROP R> DROP ;

: _LIBSVC-DISPATCH-ENTERED
  ( service work body-xt -- service-status )
    >R
    DUP R>
    3 PICK _LS.REPOSITORY @
    4 PICK _LS.REPOSITORY-WORK @
        LIBRARY-REPOSITORY-WITH-OWNER
    DUP IF DUP 2 PICK _LSW.STATUS ! THEN
    DROP
    DUP _LSW.STATUS @
    ROT ROT _LIBSVC-LEAVE ;

: _LIBSVC-REQUEST-RUN
  ( request service work request-u body-xt -- service-status )
    >R
    3 PICK 1 PICK 4 PICK 4 PICK
        _LIBSVC-REQUEST-GRAPH-SAFE? 0= IF
        _LIBSVC-DROP4 R> DROP LIBRARY-SERVICE-S-INVALID EXIT
    THEN
    DROP
    2DUP _LIBSVC-ENTER DUP IF
        >R _LIBSVC-DROP3 R> R> DROP EXIT
    THEN DROP
    2 PICK OVER _LSW.ARG0 !
    ROT DROP
    R> _LIBSVC-DISPATCH-ENTERED ;

: _LIBSVC-OWNER-END  ( repository-status service-work -- repository-status )
    >R DUP R@ _LSW.STATUS ! R> DROP ;

: _LIBSVC-OWNER-DOMAIN-END
  ( service-status service-work -- repository-status )
    _LSW.STATUS !
    LIBRARY-REPOSITORY-S-OK ;

