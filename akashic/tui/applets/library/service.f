\ =====================================================================
\  service.f - Caller-owned Desk/Library semantic service
\ =====================================================================
\  This service is the applet-owned command/read/query boundary over the
\  scalable Library repository.  It owns Library policy and fixed request
\  DTOs, but no VFS path, persistence page, process-global workspace, or
\  compatibility path.
\
\  A service descriptor borrows one checked repository/work pair.  A service
\  work object is supplied by the caller and embeds the reusable query work.
\  Semantic adapter and query operations execute only through
\  LIBRARY-REPOSITORY-WITH-OWNER.  Repository maintenance already owns that
\  scope and is therefore invoked directly after acquiring the service work.
\
\  Content descriptors are caller-owned immutable locators.  Their digest
\  pointer is borrowed from the descriptor, and their physical locator remains
\  usable only while the repository authority that issued it has not been
\  compacted or finalized.
\ =====================================================================

PROVIDED akashic-tui-library-service

REQUIRE repository.f
REQUIRE query.f
REQUIRE document-values.f

