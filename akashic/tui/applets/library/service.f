    R@ R@ _LS.SELF !
    OVER R@ _LS.REPOSITORY !
    DUP R@ _LS.REPOSITORY-WORK !
    LIBRARY-SERVICE-S-OK R@ _LS.STATUS !
    2DROP
    R@ _LIBSVC-BASE-VALID? 0= IF
        R@ LIBRARY-SERVICE-SIZE 0 FILL
        R> DROP LIBRARY-SERVICE-S-CONFLICT EXIT
    THEN
    R> DROP LIBRARY-SERVICE-S-OK ;

