: _LIBSVC-DIRECT-DISPATCH-ENTERED
  ( service work body-xt -- service-status )
    >R
    DUP R> EXECUTE
    DUP _LIBSVC-STATUS? 0= IF DROP LIBRARY-SERVICE-S-INVALID THEN
    DUP 2 PICK _LSW.STATUS !
    DROP
    DUP _LSW.STATUS @
    ROT ROT _LIBSVC-LEAVE ;

: _LIBSVC-DIRECT-REQUEST-RUN
  ( request service work request-u body-xt -- service-status )
    >R
    3 PICK 1 PICK 4 PICK 4 PICK
        _LIBSVC-REQUEST-GRAPH-SAFE? 0= IF
        _LIBSVC-DROP4 R> DROP LIBRARY-SERVICE-S-INVALID EXIT
    THEN
    DROP
    2DUP _LIBSVC-ENTER DUP IF
        >R _LIBSVC-DROP3 R> R> DROP EXIT
    THEN DROP
    2 PICK OVER _LSW.ARG0 !
    ROT DROP
    R> _LIBSVC-DIRECT-DISPATCH-ENTERED ;

