: LIBRARY-CAPABILITY-WORK-VALID?  ( work -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIBRARY-CAPABILITY-WORK-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _LCAPW-MAGIC + @ _LCAPW-MAGIC-VALUE <> IF DROP 0 EXIT THEN
    DUP _LCAPW-SELF + @ OVER <> IF DROP 0 EXIT THEN
    LCAPW.BUILDER CVB-VALID? ;

