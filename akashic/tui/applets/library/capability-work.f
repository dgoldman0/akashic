: LIBRARY-CAPABILITY-WORK-INIT  ( work -- status )
    DUP 0= IF DROP CBUILD-S-INVALID EXIT THEN
    DUP LIBRARY-CAPABILITY-WORK-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP CBUILD-S-INVALID EXIT THEN
    DUP LIBRARY-CAPABILITY-WORK-SIZE 0 FILL
    _LCAPW-MAGIC-VALUE OVER _LCAPW-MAGIC + !
    DUP OVER _LCAPW-SELF + !
    DUP LCAPW.BUILDER CVB-INIT DUP IF NIP EXIT THEN DROP
    DUP _LCAPW-VALUES-INIT
    DUP LIBRARY-CAPABILITY-WORK-VALID? 0= IF
        LIBRARY-CAPABILITY-WORK-SIZE 0 FILL
        CBUILD-S-INVALID EXIT
    THEN
    DROP CBUILD-S-OK ;

: LIBRARY-CAPABILITY-WORK-RESET  ( work -- status )
    DUP LIBRARY-CAPABILITY-WORK-VALID? 0= IF
        DROP CBUILD-S-INVALID EXIT
    THEN
    DUP LCAPW.BUILDER CVB-ABORT DUP IF NIP EXIT THEN DROP
    DUP _LCAPW-TRANSIENT +
    LIBRARY-CAPABILITY-WORK-SIZE _LCAPW-TRANSIENT - 0 FILL
    DUP _LCAPW-VALUES-INIT
    DROP CBUILD-S-OK ;

: LIBRARY-CAPABILITY-WORK-FINI  ( work -- status )
    DUP LIBRARY-CAPABILITY-WORK-VALID? 0= IF
        DROP CBUILD-S-INVALID EXIT
    THEN
    DUP LCAPW.BUILDER CVB-ABORT DUP IF NIP EXIT THEN DROP
    DUP LIBRARY-CAPABILITY-WORK-SIZE 0 FILL
    DROP CBUILD-S-OK ;
