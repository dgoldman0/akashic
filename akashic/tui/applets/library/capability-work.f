\ =====================================================================
\  capability-work.f - Activation-owned Library capability workspace
\ =====================================================================
\  This is a data-only, caller-owned working set for the public Library
\  capability handlers.  It owns no repository, service, VFS path, or UI
\  state.  In particular, the embedded service request objects all borrow
\  the controller's one activation-local service/work pair.
\
\  The result builder owns its candidate graph until publication.  RESET
\  releases that graph and wipes every borrowed request pointer, decoded
\  identifier, content byte, and query row.  FINI must run before the XMEM
\  block containing this workspace is returned.
\ =====================================================================

