        _LIBPI-DROP3 R> DROP LIB-S-INVALID EXIT
    THEN
    DUP _LIBPI-RID? 0= IF _LIBPI-DROP3 R> DROP LIB-S-INVALID EXIT THEN
    R@ LIBPI-TITLE-KEY-SIZE _LIBPI-DEST? 0= IF
        _LIBPI-DROP3 R> DROP LIB-S-INVALID EXIT
