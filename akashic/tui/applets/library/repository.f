: _LIBREPO-COMPACTION-BUDGETS?
  ( byte-budget work-budget step-byte-budget -- flag )
    >R
    OVER 0> OVER 0> AND R@ 0> AND
    R> 3 PICK <= AND
    NIP NIP ;

: _LIBREPO-COMPACTION-REBINDABLE?  ( work -- flag )
    DUP _LRW.REPOSITORY @ _LR.FLAGS @
        _LR-F-COMPACTION-BOUND AND 0= IF DROP -1 EXIT THEN
    _LRW.COMPACT PCOMPACT-STATE@ DUP PCOMPACT-STATE-IDLE =
    SWAP PCOMPACT-STATE-CLEANED = OR ;

: LIBRARY-REPOSITORY-COMPACTION-BIND
  ( byte-budget work-budget step-byte-budget repository work -- status )
    2DUP _LIBREPO-ENTER DUP IF
        >R _LIBREPO-DROP5 R> EXIT
    THEN DROP
    >R
    3 PICK 3 PICK 3 PICK _LIBREPO-COMPACTION-BUDGETS? 0= IF
        _LIBREPO-DROP4
        LIBRARY-REPOSITORY-S-INVALID
        R@ _LRW.REPOSITORY @ R> _LIBREPO-LEAVE EXIT
    THEN
    R@ _LIBREPO-COMPACTION-REBINDABLE? 0= IF
        _LIBREPO-DROP4
        LIBRARY-REPOSITORY-S-BUSY
        R@ _LRW.REPOSITORY @ R> _LIBREPO-LEAVE EXIT
    THEN
    R@ _LRW.REPOSITORY @ _LR.ADAPTER
    R@ _LRW.INDEX
    R@ _LRW.REPOSITORY @ _LR.BUILDER-ADAPTER
    R@ _LRW.BUILDER-INDEX
    R@ _LRW.COMPACTION-CONTEXT
        LIBPA-COMPACTION-CONTEXT-INIT
    DUP IF
        >R _LIBREPO-DROP4 R>
        R@ _LRW.REPOSITORY @ R> _LIBREPO-LEAVE EXIT
    THEN DROP
    R@ _LRW.REPOSITORY @ _LR.STORE PSTORE-ROOT-FILE@
    R@ _LRW.REPOSITORY @ _LR.BUILDER-STORE
    R@ _LRW.BUILDER-PSTORE
    LIBPA-COMPACTION-STEP-XT
    LIBPA-COMPACTION-FINALIZE-XT
    R@ _LRW.COMPACTION-CONTEXT
    9 PICK 9 PICK 9 PICK
    R@ _LRW.REPOSITORY @ _LR.COMPACT PCOMPACT-INIT
    >R _LIBREPO-DROP4 R>
    DUP 0= IF
        R@ _LRW.REPOSITORY @ _LR.FLAGS DUP @
            _LR-F-COMPACTION-BOUND OR SWAP !
    THEN
    R@ _LRW.REPOSITORY @ R> _LIBREPO-LEAVE ;

