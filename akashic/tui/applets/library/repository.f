        MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    2DUP R@ _LRW.BUILDER-AUDIT-MAP-A @
        R@ _LRW.BUILDER-AUDIT-MAP-U @
        MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    2DROP R> DROP -1 ;

: _LIBREPO-ENTER  ( repository work -- status )
    2DUP _LIBREPO-PAIR? 0= IF
        2DROP LIBRARY-REPOSITORY-S-INVALID EXIT
    THEN
    DUP _LRW.BUSY @ IF 2DROP LIBRARY-REPOSITORY-S-BUSY EXIT THEN
    OVER _LR.GUARD @ GUARD-TRY-ACQUIRE 0= IF
        2DROP LIBRARY-REPOSITORY-S-BUSY EXIT
    THEN
    -1 SWAP _LRW.BUSY !
    DROP LIBRARY-REPOSITORY-S-OK ;

: _LIBREPO-LEAVE  ( status repository work -- status )
    >R
    OVER R@ _LRW.STATUS !
    OVER OVER _LR.STATUS !
    0 R@ _LRW.BUSY !
    DUP _LR.GUARD @ GUARD-RELEASE
    DROP R> DROP ;

\ Execute one owner-scoped semantic operation without exposing the guard or
\ repository-private fields.  The callback receives the caller context and the
\ checked repository/work pair and must return one repository status.
\
\ This semantic boundary deliberately does not hold the global VFS transaction
\ for the callback's potentially large query or mutation.  Consequently, the
\ cold and physical-management topology checks below do not close replacement
\ of a reserved terminal after LOAD.  Closing that wider TOCTOU class requires
\ a narrower namespace lease or sealed-inode/open-handle capability; silently
\ serializing every service operation here would violate the scaling contract.
: LIBRARY-REPOSITORY-WITH-OWNER
  ( context body-xt repository work -- status )
    2 PICK 0= IF _LIBREPO-DROP4 LIBRARY-REPOSITORY-S-INVALID EXIT THEN
    2DUP _LIBREPO-PAIR? 0= IF
        _LIBREPO-DROP4 LIBRARY-REPOSITORY-S-INVALID EXIT
    THEN
    OVER _LR.FLAGS @ _LR-F-BLOCKED AND IF
        _LIBREPO-DROP4 LIBRARY-REPOSITORY-S-CONFLICT EXIT
    THEN
    2DUP _LIBREPO-ENTER DUP IF
        >R _LIBREPO-DROP4 R> EXIT
    THEN DROP
    >R
    SWAP R@ SWAP CATCH
    DUP IF
        _LIBREPO-DROP4
        LIBRARY-REPOSITORY-S-FAULT
    ELSE
        DROP
        DUP _LIBREPO-STATUS? 0= IF
            DROP LIBRARY-REPOSITORY-S-INVALID
        THEN
    THEN
    R@ _LRW.REPOSITORY @ R> _LIBREPO-LEAVE ;

