: _LIBREPO-BASE-VALID?  ( repository -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIBRARY-REPOSITORY-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _LR.MAGIC @ _LIBREPO-MAGIC <> IF DROP 0 EXIT THEN
    DUP _LR.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _LR.VFS @ DUP 0= IF 2DROP 0 EXIT THEN
    VFS-DESC-SIZE MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _LR.FLAGS @ _LR-F-KNOWN INVERT AND IF DROP 0 EXIT THEN
    DUP _LR.FLAGS @ _LR-F-INITIALIZED AND 0= IF DROP 0 EXIT THEN
    DUP _LR.STATUS @ _LIBREPO-STATUS? 0= IF DROP 0 EXIT THEN
    DUP _LR.GUARD @ DUP GUARD-SPIN? 0= IF 2DROP 0 EXIT THEN DROP
    DUP _LR.BUILDER-GUARD @ DUP GUARD-SPIN? 0= IF
        2DROP 0 EXIT
    THEN DROP
    DUP _LR.GUARD @ OVER _LR.BUILDER-GUARD @ = IF DROP 0 EXIT THEN
    DUP _LR.CACHE-0 @ PPAGE-CACHE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LR.CACHE-1 @ PPAGE-CACHE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LR.BUILDER-CACHE-0 @ PPAGE-CACHE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LR.BUILDER-CACHE-1 @ PPAGE-CACHE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LR.STORE PSTORE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LR.BANK1-PAGE PPAGE-FILE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LR.BANK1-SEGMENT PSEG-FILE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LR.ADAPTER LIBPA-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LR.BUILDER-STORE PSTORE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LR.BUILDER-BANK1-PAGE PPAGE-FILE-VALID? 0= IF
        DROP 0 EXIT
    THEN
    DUP _LR.BUILDER-BANK1-SEGMENT PSEG-FILE-VALID? 0= IF
        DROP 0 EXIT
    THEN
    DUP _LR.BUILDER-ADAPTER LIBPA-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LR.FLAGS @ _LR-F-COMPACTION-BOUND AND IF
        DUP _LR.COMPACT PCOMPACT-VALID? 0= IF DROP 0 EXIT THEN
    THEN
    _LIBREPO-PATHS? ;

: _LIBREPO-WORK-SHAPE?  ( work -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIBRARY-REPOSITORY-WORK-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP _LRW.MAGIC @ _LIBREPO-WORK-MAGIC <> IF DROP 0 EXIT THEN
    DUP _LRW.SELF @ OVER <> IF DROP 0 EXIT THEN
    DUP _LRW.BUSY @ DUP 0= SWAP -1 = OR 0= IF DROP 0 EXIT THEN
    DUP _LRW.STATUS @ _LIBREPO-STATUS? 0= IF DROP 0 EXIT THEN
    DUP _LRW.PSTORE PSTORE-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LRW.INDEX LIBPA-INDEX-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LRW.BUILDER-PSTORE PSTORE-WORK-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LRW.BUILDER-INDEX LIBPA-INDEX-WORK-VALID? 0= IF
        DROP 0 EXIT
    THEN
    DUP _LRW.COMPACTION-CONTEXT
        LIBPA-COMPACTION-CONTEXT-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LRW.COMPACT PCOMPACT-WORK-VALID? 0= IF DROP 0 EXIT THEN
    _LRW.ROOT PROOT-WORK-VALID? ;

: LIBRARY-REPOSITORY-WORK-VALID?  ( work -- flag )
    DUP _LIBREPO-WORK-SHAPE? 0= IF DROP 0 EXIT THEN
    >R
    R@ _LRW.REPOSITORY @ DUP _LIBREPO-BASE-VALID? 0= IF
        DROP R> DROP 0 EXIT
    THEN
    _LR.WORK @ R> = ;

: LIBRARY-REPOSITORY-VALID?  ( repository -- flag )
    DUP _LIBREPO-BASE-VALID? 0= IF DROP 0 EXIT THEN
    DUP _LR.WORK @ ?DUP IF
        DUP _LIBREPO-WORK-SHAPE? 0= IF 2DROP 0 EXIT THEN
        _LRW.REPOSITORY @ OVER <> IF DROP 0 EXIT THEN
    THEN
    DROP -1 ;

