    R@ _LRW.INSPECTION R@ _LIBREPO-INSPECT-RUN
    DUP IF >R 2DROP R> R> DROP EXIT THEN DROP
    DUP LRI.SEAL R@ _LRW.INSPECTION LRI.SEAL
        SHA3-256-COMPARE 0= IF
        2DROP R> DROP LIBRARY-REPOSITORY-S-CONFLICT EXIT
    THEN
    OVER R@ _LRW.ARG0 !
    R@ _LRW.INSPECTION R@ _LRW.ARG1 !
    R@ _LIBREPO-EXPORT-RUN
    DUP IF
        R@ _LRW.RESULT1 @ IF
            2 PICK R@ _LRW.INSPECTION LRI.RAW-REQUIRED @ 0 FILL
        THEN
    THEN
    >R 2DROP R> R> DROP ;

: _LIBREPO-RAW-VFS-RUN  ( work -- status )
    >R
    R@ _LRW.OP-ARG0 @ R@ _LRW.OP-ARG1 @
    R> _LIBREPO-RAW-LOCKED ;

\ The destination is caller-owned staging.  A short call reports the exact
\ required length without entering the repository or touching staging.  Once
\ streaming starts, success is the only commit point; any error scrubs the
\ complete negotiated span before returning.
: LIBRARY-REPOSITORY-RAW-EXPORT
  ( destination capacity sealed-inspection repository work -- required status )
    2 PICK LIBRARY-REPOSITORY-INSPECTION-SEALED? 0= IF
        _LIBREPO-DROP5 0 LIBRARY-REPOSITORY-S-INVALID EXIT
    THEN
    3 PICK 0< IF
        _LIBREPO-DROP5 0 LIBRARY-REPOSITORY-S-INVALID EXIT
    THEN
    2 PICK LRI.RAW-REQUIRED @ 4 PICK SWAP < IF
        2 PICK LRI.RAW-REQUIRED @ >R
        _LIBREPO-DROP5 R>
        LIBRARY-REPOSITORY-S-CAPACITY EXIT
    THEN
    4 PICK 4 PICK 4 PICK 4 PICK 4 PICK
        _LIBREPO-RAW-ARGS? 0= IF
        _LIBREPO-DROP5 0 LIBRARY-REPOSITORY-S-INVALID EXIT
    THEN
    2DUP _LIBREPO-ENTER DUP IF
        >R 2 PICK LRI.RAW-REQUIRED @ >R
        _LIBREPO-DROP5 R> R> EXIT
    THEN DROP
    >R
    3 PICK R@ _LRW.OP-ARG0 !
    1 PICK R@ _LRW.OP-ARG1 !
    R@ ['] _LIBREPO-RAW-VFS-RUN _LIBREPO-VFS-OP-CALL
    2 PICK LRI.RAW-REQUIRED @
    >R >R >R _LIBREPO-DROP3
    R> R> R>
    ROT ROT SWAP R> _LIBREPO-LEAVE ;

