\ The caller report is replaced only after every role and the decoded root
\ observation have completed under one repository guard.
: LIBRARY-REPOSITORY-INSPECT  ( inspection repository work -- status )
    2 PICK 2 PICK 2 PICK
        _LIBREPO-INSPECTION-DESTINATION? 0= IF
        _LIBREPO-DROP3 LIBRARY-REPOSITORY-S-INVALID EXIT
    THEN
    2DUP _LIBREPO-ENTER DUP IF
        >R _LIBREPO-DROP3 R> EXIT
    THEN DROP
    >R
    R@ ['] _LIBREPO-INSPECT-VFS-RUN _LIBREPO-VFS-OP-CALL
    DUP 0= IF
        R@ _LRW.INSPECTION 3 PICK
            LIBRARY-REPOSITORY-INSPECTION-SIZE MOVE
    THEN
    SWAP R> _LIBREPO-LEAVE
    NIP ;

: _LIBREPO-VERIFY-FINISH  ( primary object work -- final )
    >R >R
    R@ LRIO.DIGEST SHA3-256-END-COMPARE 0= IF
        DUP 0= IF DROP LIBRARY-REPOSITORY-S-CONFLICT THEN
    THEN
    R> DROP
    R@ _LIBREPO-CLOSE-EVIDENCE
    R> DROP _LIBREPO-PRIMARY-CLEANUP ;

: _LIBREPO-EXPORT-ROLE  ( role inspection work -- status )
    >R
    SWAP R@ _LRW.ARG2 !
    R@ _LRW.ARG2 @ OVER LRI.OBJECT R@ _LRW.ARG3 !
    DROP
    R@ _LRW.ARG2 @ R@ _LRW.REPOSITORY @ R@ _LIBREPO-OPEN-EVIDENCE
    R@ _LRW.ARG3 @ LRIO.PRESENT @ 0= IF
        DUP LIBRARY-REPOSITORY-S-ABSENT = IF
            DROP R> DROP LIBRARY-REPOSITORY-S-OK EXIT
        THEN
        DUP IF R> DROP EXIT THEN DROP
        LIBRARY-REPOSITORY-S-CONFLICT R@ _LIBREPO-CLOSE-PRIMARY
        R> DROP EXIT
    THEN
    DUP LIBRARY-REPOSITORY-S-ABSENT = IF
        DROP R> DROP LIBRARY-REPOSITORY-S-CONFLICT EXIT
    THEN
    DUP IF R> DROP EXIT THEN DROP
    R@ _LRW.RESULT0 @ R@ _LRW.ARG3 @ LRIO.BYTES @ <> IF
        LIBRARY-REPOSITORY-S-CONFLICT R@ _LIBREPO-CLOSE-PRIMARY
        R> DROP EXIT
    THEN
    R@ _LRW.RESULT0 @ R@ _LRW.ARG2 !
    SHA3-256-BEGIN
    BEGIN
        R@ _LRW.ARG2 @ 0>
    WHILE
        R@ _LRW.ARG2 @
        LIBRARY-REPOSITORY-RAW-CHUNK-MAX MIN
        R@ _LRW.STATUS !
        R@ _LRW.ARG0 @ R@ _LRW.RESULT1 @ +
        R@ _LRW.STATUS @ R@ _LRW.FD @ VFS-READ?
        DUP IF
            _LIBREPO-IOR>STATUS R@ _LRW.RESULT0 !
            DROP
            R@ _LRW.RESULT0 @ R@ _LRW.ARG3 @ R@
                _LIBREPO-VERIFY-FINISH
            R> DROP EXIT
        THEN
        DROP R@ _LRW.STATUS @ <> IF
            LIBRARY-REPOSITORY-S-IO
            R@ _LRW.ARG3 @ R@ _LIBREPO-VERIFY-FINISH
            R> DROP EXIT
        THEN
        R@ _LRW.ARG0 @ R@ _LRW.RESULT1 @ +
        R@ _LRW.STATUS @ SHA3-256-ADD
        R@ _LRW.STATUS @ NEGATE R@ _LRW.ARG2 +!
        R@ _LRW.STATUS @
        R@ _LRW.RESULT1 +!
    REPEAT
    LIBRARY-REPOSITORY-S-OK
    R@ _LRW.ARG3 @ R@ _LIBREPO-VERIFY-FINISH
    R> DROP ;

: _LIBREPO-EXPORT-RUN  ( work -- status )
    0 OVER _LRW.RESULT1 !
    LIBRARY-REPOSITORY-EVIDENCE-COUNT 0 ?DO
        I OVER _LRW.ARG1 @ 2 PICK _LIBREPO-EXPORT-ROLE
        DUP IF >R DROP R> UNLOOP EXIT THEN DROP
    LOOP
    DUP _LRW.RESULT1 @
    OVER _LRW.ARG1 @ LRI.RAW-REQUIRED @ <> IF
        DROP LIBRARY-REPOSITORY-S-CONFLICT EXIT
    THEN
    DROP LIBRARY-REPOSITORY-S-OK ;

: _LIBREPO-RAW-ARGS?  ( destination capacity inspection repository work -- flag )
    2DUP _LIBREPO-PAIR? 0= IF _LIBREPO-DROP5 0 EXIT THEN
    3 PICK 0< IF _LIBREPO-DROP5 0 EXIT THEN
    2 PICK LIBRARY-REPOSITORY-INSPECTION-SEALED? 0= IF
        _LIBREPO-DROP5 0 EXIT
    THEN
    2 PICK LRI.RAW-REQUIRED @ 0> 5 PICK 0= AND IF
        _LIBREPO-DROP5 0 EXIT
    THEN
    4 PICK 3 PICK LRI.RAW-REQUIRED @
        MSPAN-NONWRAPPING? 0= IF _LIBREPO-DROP5 0 EXIT THEN
    2 PICK LIBRARY-REPOSITORY-INSPECTION-SIZE
    3 PICK 3 PICK LIBRARY-REPOSITORY-SPAN-DISJOINT? 0= IF
        _LIBREPO-DROP5 0 EXIT
    THEN
    4 PICK 3 PICK LRI.RAW-REQUIRED @
    3 PICK 3 PICK LIBRARY-REPOSITORY-SPAN-DISJOINT? 0= IF
        _LIBREPO-DROP5 0 EXIT
    THEN
    4 PICK 3 PICK LRI.RAW-REQUIRED @
    4 PICK LIBRARY-REPOSITORY-INSPECTION-SIZE
        MSPAN-OVERLAP? IF _LIBREPO-DROP5 0 EXIT THEN
    _LIBREPO-DROP5 -1 ;

: _LIBREPO-RAW-LOCKED  ( destination inspection work -- status )
