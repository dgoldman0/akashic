    SHA3-256-BEGIN
    S" akashic.library.repository.inspection" SHA3-256-ADD
    R@ _LRI-SEAL SHA3-256-ADD
    R@ _LRI-OBJECTS +
        LIBRARY-REPOSITORY-EVIDENCE-COUNT _LRIO-SIZE *
        SHA3-256-ADD
    R> DROP ;

: _LIBREPO-INSPECTION-SEAL!  ( inspection -- )
    DUP _LIBREPO-INSPECTION-HASH-BEGIN LRI.SEAL SHA3-256-END ;

: LIBRARY-REPOSITORY-INSPECTION-SEALED?  ( inspection -- flag )
    DUP _LIBREPO-INSPECTION-SHAPE? 0= IF DROP 0 EXIT THEN
    DUP _LIBREPO-INSPECTION-HASH-BEGIN LRI.SEAL
        SHA3-256-END-COMPARE ;

: _LIBREPO-OPEN-EVIDENCE  ( role repository work -- status )
    >R >R
    DUP R@ _LIBREPO-EVIDENCE-TYPE
    DUP IF
        NIP R> DROP R> DROP EXIT
    THEN DROP
    _LIBREPO-EVIDENCE-PATH$ 0= IF
        2DROP R> DROP R> DROP LIBRARY-REPOSITORY-S-INVALID EXIT
    THEN
    VFS-FF-READ R@ _LR.VFS @ VFS-OPEN?
    DUP IF
        NIP DUP VFS-IOR-REASON VFS-R-NOENT = IF
            DROP LIBRARY-REPOSITORY-S-ABSENT
        ELSE
            _LIBREPO-IOR>STATUS
        THEN
        R> DROP R> DROP EXIT
    THEN
    DROP
    DUP R> DROP R@ _LRW.FD !
    VFS-SIZE R> _LRW.RESULT0 !
    LIBRARY-REPOSITORY-S-OK ;

: _LIBREPO-CLOSE-EVIDENCE  ( work -- status )
    DUP _LRW.FD @ DUP 0= IF
        2DROP LIBRARY-REPOSITORY-S-OK EXIT
    THEN
    VFS-CLOSE? _LIBREPO-IOR>STATUS
    SWAP 0 SWAP _LRW.FD ! ;

: _LIBREPO-PRIMARY-CLEANUP  ( primary cleanup -- final )
    OVER IF DROP ELSE NIP THEN ;

: _LIBREPO-CLOSE-PRIMARY  ( primary work -- final )
    >R R@ _LIBREPO-CLOSE-EVIDENCE R> DROP
    _LIBREPO-PRIMARY-CLEANUP ;

: _LIBREPO-HASH-FINISH  ( primary object work -- final )
    >R >R
    R@ LRIO.DIGEST SHA3-256-END
    R> DROP
    R@ _LIBREPO-CLOSE-EVIDENCE
    R> DROP _LIBREPO-PRIMARY-CLEANUP ;

: _LIBREPO-HASH-EVIDENCE  ( role inspection work -- status )
    >R
    SWAP R@ _LRW.ARG0 !
    R@ _LRW.ARG0 @ OVER LRI.OBJECT R@ _LRW.ARG1 !
    DROP
    R@ _LRW.ARG1 @ _LRIO-SIZE 0 FILL
    R@ _LRW.ARG0 @ R@ _LRW.REPOSITORY @ R@ _LIBREPO-OPEN-EVIDENCE
    DUP LIBRARY-REPOSITORY-S-ABSENT = IF
        DROP
        SHA3-256-BEGIN
        R@ _LRW.ARG1 @ LRIO.DIGEST SHA3-256-END
        R> DROP LIBRARY-REPOSITORY-S-OK EXIT
    THEN
    DUP IF R> DROP EXIT THEN DROP
    R@ _LRW.RESULT0 @ 0< IF
        LIBRARY-REPOSITORY-S-CORRUPT R@ _LIBREPO-CLOSE-PRIMARY
        R> DROP EXIT
    THEN
    -1 R@ _LRW.ARG1 @ LRIO.PRESENT !
    R@ _LRW.RESULT0 @ R@ _LRW.ARG1 @ LRIO.BYTES !
    0 R@ _LRW.RESULT1 !
    SHA3-256-BEGIN
    BEGIN
        R@ _LRW.RESULT1 @ R@ _LRW.RESULT0 @ <
    WHILE
        R@ _LRW.RESULT0 @ R@ _LRW.RESULT1 @ -
        R@ _LRW.STAGE-U @ MIN
        LIBRARY-REPOSITORY-RAW-CHUNK-MAX MIN
        R@ _LRW.ARG3 !
        R@ _LRW.STAGE-A @ R@ _LRW.ARG3 @
        R@ _LRW.FD @ VFS-READ?
        DUP IF
            _LIBREPO-IOR>STATUS R@ _LRW.STATUS !
            DROP
            R@ _LRW.STATUS @ R@ _LRW.ARG1 @ R@
                _LIBREPO-HASH-FINISH
            R> DROP EXIT
        THEN
        DROP R@ _LRW.ARG3 @ <> IF
            LIBRARY-REPOSITORY-S-IO
            R@ _LRW.ARG1 @ R@ _LIBREPO-HASH-FINISH
            R> DROP EXIT
        THEN
        R@ _LRW.STAGE-A @ R@ _LRW.ARG3 @ SHA3-256-ADD
        R@ _LRW.ARG3 @ R@ _LRW.RESULT1 +!
    REPEAT
    LIBRARY-REPOSITORY-S-OK
    R@ _LRW.ARG1 @ R@ _LIBREPO-HASH-FINISH
    R> DROP ;

: _LIBREPO-INSPECT-OBJECTS  ( inspection work -- status )
    LIBRARY-REPOSITORY-EVIDENCE-COUNT 0 ?DO
        I 2 PICK 2 PICK _LIBREPO-HASH-EVIDENCE
        DUP IF >R 2DROP R> UNLOOP EXIT THEN DROP
    LOOP
    0
    LIBRARY-REPOSITORY-EVIDENCE-COUNT 0 ?DO
        I 3 PICK LRI.OBJECT LRIO.BYTES @
        _LIBREPO-NONNEGATIVE+
        DUP IF
            >R DROP 2DROP R> UNLOOP EXIT
        THEN DROP
    LOOP
    DUP 3 PICK LRI.RAW-REQUIRED !
    _LIBREPO-DROP3 LIBRARY-REPOSITORY-S-OK ;

: _LIBREPO-FUTURE-ROOT-RECORD?  ( record-a record-u -- flag )
    DUP PROOT-RECORD-SIZE <> IF 2DROP 0 EXIT THEN DROP
    DUP CREC-H-MAGIC + 8 _PROOT-RECORD-MAGIC 8
        _LIBREPO-BYTES= 0= IF DROP 0 EXIT THEN
    DUP CREC-H-FORMAT + @ _PROOT-RECORD-FORMAT <= IF DROP 0 EXIT THEN
    DUP CREC-H-HEADER-U + @ CREC-HEADER-SIZE <> IF DROP 0 EXIT THEN
    DUP CREC-H-TAG + @ 0> 0= IF DROP 0 EXIT THEN
    DUP CREC-H-PAYLOAD-U + @ PERSIST-ROOT-VALUE-SIZE <>
        IF DROP 0 EXIT THEN
    DUP CREC-H-FLAGS + @ IF DROP 0 EXIT THEN
    DUP _CREC-HEADER-CRC
        OVER CREC-H-HEADER-CRC + @ <> IF DROP 0 EXIT THEN
    DUP CREC-HEADER-SIZE + PERSIST-ROOT-VALUE-SIZE CRC32
        OVER CREC-H-PAYLOAD-CRC + @ <> IF DROP 0 EXIT THEN
    DROP -1 ;

: _LIBREPO-ROOT-ROLE-FUTURE?  ( role work -- flag status )
    >R
    R@ _LRW.ARG0 !
    R@ _LRW.ARG0 @ R@ _LRW.REPOSITORY @ R@ _LIBREPO-OPEN-EVIDENCE
    DUP LIBRARY-REPOSITORY-S-ABSENT = IF
        DROP R> DROP 0 LIBRARY-REPOSITORY-S-OK EXIT
    THEN
    DUP IF R> DROP 0 SWAP EXIT THEN DROP
    R@ _LRW.RESULT0 @ PROOT-RECORD-SIZE <> IF
        LIBRARY-REPOSITORY-S-OK R@ _LIBREPO-CLOSE-PRIMARY
        R> DROP 0 SWAP EXIT
    THEN
    R@ _LRW.STAGE-A @ PROOT-RECORD-SIZE
    R@ _LRW.FD @ VFS-READ?
    DUP IF
        NIP _LIBREPO-IOR>STATUS
        R@ _LIBREPO-CLOSE-PRIMARY
        R> DROP 0 SWAP EXIT
    THEN
    DROP PROOT-RECORD-SIZE <> IF
        LIBRARY-REPOSITORY-S-IO R@ _LIBREPO-CLOSE-PRIMARY
        R> DROP 0 SWAP EXIT
    THEN
    LIBRARY-REPOSITORY-S-OK R@ _LIBREPO-CLOSE-PRIMARY
    DUP IF
        R> DROP 0 SWAP EXIT
    THEN
    DROP
    R@ _LRW.STAGE-A @ PROOT-RECORD-SIZE
        _LIBREPO-FUTURE-ROOT-RECORD?
    R> DROP LIBRARY-REPOSITORY-S-OK ;

: _LIBREPO-ANY-FUTURE-ROOT?  ( work -- flag status )
    >R
    LIBRARY-REPOSITORY-EVIDENCE-ROOT-0 R@
        _LIBREPO-ROOT-ROLE-FUTURE?
    DUP IF R> DROP EXIT THEN
    DROP IF R> DROP -1 LIBRARY-REPOSITORY-S-OK EXIT THEN
    LIBRARY-REPOSITORY-EVIDENCE-ROOT-1 R@
        _LIBREPO-ROOT-ROLE-FUTURE?
    R> DROP ;

: _LIBREPO-INSPECT-ROOT  ( inspection work -- status )
    >R
    R@ _LRW.ROOT-VALUE
    R@ _LRW.REPOSITORY @ _LR.STORE PSTORE-ROOT-FILE@
    R@ _LRW.ROOT PROOT-LOAD
    DUP PERSIST-S-ABSENT = IF
        2DROP
        LIBRARY-REPOSITORY-HEALTH-ABSENT OVER LRI.HEALTH !
        DROP R> DROP LIBRARY-REPOSITORY-S-OK EXIT
    THEN
    DUP IF
        NIP
        DUP PERSIST-S-UNCERTAIN = IF
            DROP LIBRARY-REPOSITORY-HEALTH-UNCERTAIN
        ELSE
            DROP
            R@ _LIBREPO-ANY-FUTURE-ROOT?
            DUP IF
                2DROP LIBRARY-REPOSITORY-HEALTH-UNCERTAIN
            ELSE
                DROP IF
                LIBRARY-REPOSITORY-HEALTH-FUTURE
                ELSE
                LIBRARY-REPOSITORY-HEALTH-CORRUPT
                THEN
            THEN
        THEN
        OVER LRI.HEALTH !
        DROP R> DROP LIBRARY-REPOSITORY-S-OK EXIT
    THEN
    DROP
    DUP 2 PICK LRI.GENERATION !
    DROP
    R@ _LRW.ROOT-VALUE PROOTV.DATA-BANK @ OVER LRI.ACTIVE-BANK !
    GPAIR-SLOT-A R@ _LRW.REPOSITORY @ _LR.STORE PSTORE-ROOT-FILE@
        PROOT-SLOT-GENERATION@ OVER LRI.SLOT-0-GENERATION !
    GPAIR-SLOT-A R@ _LRW.REPOSITORY @ _LR.STORE PSTORE-ROOT-FILE@
        PROOT-SLOT-DATA-BANK@ OVER LRI.SLOT-0-BANK !
    GPAIR-SLOT-B R@ _LRW.REPOSITORY @ _LR.STORE PSTORE-ROOT-FILE@
        PROOT-SLOT-GENERATION@ OVER LRI.SLOT-1-GENERATION !
    GPAIR-SLOT-B R@ _LRW.REPOSITORY @ _LR.STORE PSTORE-ROOT-FILE@
        PROOT-SLOT-DATA-BANK@ OVER LRI.SLOT-1-BANK !
    R@ _LRW.ROOT-VALUE PROOTV.PAGE-COUNT @
        OVER LRI.PAGE-COUNT !
    R@ _LRW.ROOT-VALUE PROOTV.SEGMENT-TAIL @
        OVER LRI.SEGMENT-TAIL !
    R@ _LRW.ROOT-VALUE PROOTV.RECORD-COUNT @
        OVER LRI.RECORD-COUNT !
    R@ _LRW.ROOT-VALUE PROOTV.APPLICATION-ROOT @
        OVER LRI.APPLICATION-ROOT !
    R@ _LRW.ROOT PROOT-FALLBACK? IF
        R@ _LIBREPO-ANY-FUTURE-ROOT?
        DUP IF
            2DROP
            LIBRARY-REPOSITORY-HEALTH-UNCERTAIN
                OVER LRI.HEALTH !
        ELSE
            DROP IF
                LIBRARY-REPOSITORY-HEALTH-FUTURE
                    OVER LRI.HEALTH !
            ELSE
                LIBRARY-REPOSITORY-HEALTH-FALLBACK
                    OVER LRI.HEALTH !
                LIBRARY-REPOSITORY-REPAIR-MIRROR
                    OVER LRI.REPAIR-MASK !
            THEN
        THEN
    ELSE
        LIBRARY-REPOSITORY-HEALTH-OK OVER LRI.HEALTH !
    THEN
    R@ _LRW.REPOSITORY @ LIBRARY-REPOSITORY-LOADED? IF
        R@ _LRW.INDEX LIBPA-INDEX-LOGICAL-GENERATION@
            OVER LRI.LOGICAL-GENERATION !
        R@ _LRW.INDEX LIBPA-INDEX-DOCUMENT-COUNT@
            OVER LRI.DOCUMENT-COUNT !
        R@ _LRW.INDEX LIBPA-INDEX-COLLECTION-COUNT@
            OVER LRI.COLLECTION-COUNT !
        R@ _LRW.INDEX LIBPA-INDEX-MEMBERSHIP-COUNT@
            OVER LRI.MEMBERSHIP-COUNT !
    THEN
    DROP R> DROP LIBRARY-REPOSITORY-S-OK ;

: _LIBREPO-INSPECT-RUN  ( inspection work -- status )
    >R
    DUP LIBRARY-REPOSITORY-INSPECTION-INIT
    R@ _LRW.REPOSITORY @ _LIBREPO-TOPOLOGY-ALLOW-ABSENT
    DUP IF NIP R> DROP EXIT THEN DROP
    DUP R@ _LIBREPO-INSPECT-OBJECTS
    DUP IF NIP R> DROP EXIT THEN DROP
    DUP R@ _LIBREPO-INSPECT-ROOT
    DUP IF NIP R> DROP EXIT THEN DROP
    DUP _LIBREPO-INSPECTION-SEAL!
    DROP R> DROP LIBRARY-REPOSITORY-S-OK ;

: _LIBREPO-INSPECT-VFS-RUN  ( work -- status )
    DUP _LRW.INSPECTION SWAP _LIBREPO-INSPECT-RUN ;

: _LIBREPO-INSPECTION-DESTINATION?  ( inspection repository work -- flag )
    2DUP _LIBREPO-PAIR? 0= IF _LIBREPO-DROP3 0 EXIT THEN
    2 PICK 0= IF _LIBREPO-DROP3 0 EXIT THEN
    2 PICK LIBRARY-REPOSITORY-INSPECTION-SIZE
        MSPAN-NONWRAPPING? 0= IF _LIBREPO-DROP3 0 EXIT THEN
    2 PICK LIBRARY-REPOSITORY-INSPECTION-SIZE
    3 PICK 3 PICK LIBRARY-REPOSITORY-SPAN-DISJOINT?
