\ Ordinary semantic callbacks stay excluded throughout every active
\ compaction state.  Only a successful return to IDLE (abort) or CLEANED
\ (cleanup/recovery plus repository reload) reopens the service boundary.
\ Any failed/uncertain phase remains blocked regardless of its status spelling.
: _LIBREPO-COMPACTION-BLOCK?  ( repository-status work -- flag )
    OVER LIBRARY-REPOSITORY-S-OK <> IF 2DROP -1 EXIT THEN
    _LRW.COMPACT PCOMPACT-STATE@ DUP PCOMPACT-STATE-IDLE =
    SWAP PCOMPACT-STATE-CLEANED = OR 0=
    NIP ;

: _LIBREPO-COMPACTION-BLOCK-UPDATE  ( repository-status work -- )
    2DUP _LIBREPO-COMPACTION-BLOCK?
    1 PICK _LRW.REPOSITORY @ _LIBREPO-SET-BLOCKED
    2DROP ;

: _LIBREPO-COMPACT-BEGIN-RUN  ( work -- status )
    DUP _LRW.REPOSITORY @ _LR.COMPACT
    SWAP _LRW.COMPACT PCOMPACT-BEGIN ;

: _LIBREPO-COMPACT-STEP-RUN  ( work -- status )
    _LRW.COMPACT PCOMPACT-STEP ;

: _LIBREPO-COMPACT-FINALIZE-RUN  ( work -- status )
    _LRW.COMPACT PCOMPACT-FINALIZE ;

: _LIBREPO-COMPACT-PUBLISH-RUN  ( work -- status )
    _LRW.COMPACT PCOMPACT-PUBLISH ;

: _LIBREPO-COMPACT-MIRROR-RUN  ( work -- status )
    _LRW.COMPACT PCOMPACT-MIRROR ;

: _LIBREPO-COMPACT-CLEANUP-RUN  ( work -- status )
    >R
    R@ _LRW.COMPACT PCOMPACT-CLEANUP
    DUP IF R> DROP EXIT THEN DROP
    R> _LIBREPO-LOAD-RUN ;

: _LIBREPO-COMPACT-ABORT-RUN  ( work -- status )
    _LRW.COMPACT PCOMPACT-ABORT ;

: _LIBREPO-COMPACT-RECOVER-RUN  ( work -- status )
    >R
    R@ _LRW.REPOSITORY @ _LR.COMPACT
    R@ _LRW.COMPACT PCOMPACT-RECOVER
    DUP IF R> DROP EXIT THEN DROP
    R> _LIBREPO-LOAD-RUN ;

: _LIBREPO-COMPACTION-VFS-RUN  ( work -- status )
    DUP _LRW.REPOSITORY @ _LIBREPO-TOPOLOGY-ALLOW-ABSENT
    DUP IF NIP EXIT THEN DROP
    DUP _LRW.OP-ARG0 @ EXECUTE ;

: _LIBREPO-COMPACTION-CALL  ( repository work operation-xt -- status )
    >R
    2DUP _LIBREPO-ENTER DUP IF
        >R 2DROP R> R> DROP EXIT
    THEN DROP
    DUP _LIBREPO-COMPACTION-READY? 0= IF
        R> DROP
        LIBRARY-REPOSITORY-S-CONFLICT
    ELSE
        R> OVER _LRW.OP-ARG0 !
        DUP ['] _LIBREPO-COMPACTION-VFS-RUN
            _LIBREPO-VFS-OP-CALL >R
        R@ OVER _LIBREPO-COMPACTION-BLOCK-UPDATE
        R>
    THEN
    ROT ROT _LIBREPO-LEAVE ;

: LIBRARY-REPOSITORY-COMPACTION-BEGIN  ( repository work -- status )
    ['] _LIBREPO-COMPACT-BEGIN-RUN _LIBREPO-COMPACTION-CALL ;

: LIBRARY-REPOSITORY-COMPACTION-STEP  ( repository work -- status )
    ['] _LIBREPO-COMPACT-STEP-RUN _LIBREPO-COMPACTION-CALL ;

: LIBRARY-REPOSITORY-COMPACTION-FINALIZE  ( repository work -- status )
    ['] _LIBREPO-COMPACT-FINALIZE-RUN _LIBREPO-COMPACTION-CALL ;

: LIBRARY-REPOSITORY-COMPACTION-PUBLISH  ( repository work -- status )
    ['] _LIBREPO-COMPACT-PUBLISH-RUN _LIBREPO-COMPACTION-CALL ;

: LIBRARY-REPOSITORY-COMPACTION-MIRROR  ( repository work -- status )
    ['] _LIBREPO-COMPACT-MIRROR-RUN _LIBREPO-COMPACTION-CALL ;

: LIBRARY-REPOSITORY-COMPACTION-CLEANUP  ( repository work -- status )
    ['] _LIBREPO-COMPACT-CLEANUP-RUN _LIBREPO-COMPACTION-CALL ;

: LIBRARY-REPOSITORY-COMPACTION-ABORT  ( repository work -- status )
    ['] _LIBREPO-COMPACT-ABORT-RUN _LIBREPO-COMPACTION-CALL ;

: LIBRARY-REPOSITORY-COMPACTION-RECOVER  ( repository work -- status )
    ['] _LIBREPO-COMPACT-RECOVER-RUN _LIBREPO-COMPACTION-CALL ;
