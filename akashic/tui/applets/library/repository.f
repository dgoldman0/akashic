    OVER LRI.SEAL R@ _LRW.INSPECTION LRI.SEAL
        SHA3-256-COMPARE 0= IF
        2DROP R> DROP LIBRARY-REPOSITORY-S-CONFLICT EXIT
    THEN
    R@ _LRW.INSPECTION LRI.HEALTH @
        LIBRARY-REPOSITORY-HEALTH-FALLBACK <>
    R@ _LRW.INSPECTION LRI.REPAIR-MASK @
