: _LIBREPO-IOR>STATUS  ( ior -- status )
    DUP 0= IF DROP LIBRARY-REPOSITORY-S-OK EXIT THEN
    DUP VFS-IOR-REASON
    CASE
        VFS-R-NOENT OF DROP LIBRARY-REPOSITORY-S-ABSENT ENDOF
        VFS-R-NOSPC OF DROP LIBRARY-REPOSITORY-S-CAPACITY ENDOF
        VFS-R-CORRUPT OF DROP LIBRARY-REPOSITORY-S-CORRUPT ENDOF
        VFS-R-INVALID OF DROP LIBRARY-REPOSITORY-S-INVALID ENDOF
        DROP LIBRARY-REPOSITORY-S-IO SWAP
    ENDCASE ;

\ Resolve one reserved namespace role without following its terminal name.
\ Absence is reported distinctly because an unpublished repository, an
\ inactive data bank, either compaction root, and one atomic-root mirror may
\ all be legitimately absent.  Any present role must have its sealed type;
\ a symlink is therefore corruption even when its target is a valid object.
: _LIBREPO-NOFOLLOW-TYPE
  ( path-a path-u expected-type repository -- status )
    SWAP >R >R
    VFS-RP-NOFOLLOW-FINAL R@ _LR.VFS @ VFS-RESOLVE-POLICY?
    DUP IF
        NIP _LIBREPO-IOR>STATUS
        R> DROP R> DROP EXIT
    THEN
    DROP
    DUP 0= IF
        DROP R> DROP R> DROP LIBRARY-REPOSITORY-S-CORRUPT EXIT
    THEN
    IN.TYPE @
    R> DROP R> =
    IF LIBRARY-REPOSITORY-S-OK
    ELSE LIBRARY-REPOSITORY-S-CORRUPT THEN ;

: _LIBREPO-DIRECTORY-TYPE  ( repository -- status )
    >R
    _LIBREPO-DIRECTORY$ VFS-T-DIR R>
    _LIBREPO-NOFOLLOW-TYPE ;

: _LIBREPO-EVIDENCE-TYPE  ( role repository -- status )
    >R
    _LIBREPO-EVIDENCE-PATH$ 0= IF
        2DROP R> DROP LIBRARY-REPOSITORY-S-INVALID EXIT
    THEN
    VFS-T-FILE R> _LIBREPO-NOFOLLOW-TYPE ;

\ Validate the complete current repository namespace before treating any
\ pathname as physical evidence.  Missing terminal roles remain admissible
\ here and are interpreted later by atomic-root and active-bank validation;
\ present symlinks or non-file roles never become authority by redirection.
: _LIBREPO-TOPOLOGY-ALLOW-ABSENT  ( repository -- status )
    DUP _LIBREPO-DIRECTORY-TYPE
    DUP LIBRARY-REPOSITORY-S-ABSENT = IF
        2DROP LIBRARY-REPOSITORY-S-OK EXIT
    THEN
    DUP IF NIP EXIT THEN DROP
    LIBRARY-REPOSITORY-EVIDENCE-COUNT 0 ?DO
        I OVER _LIBREPO-EVIDENCE-TYPE
        DUP LIBRARY-REPOSITORY-S-ABSENT = IF
            DROP
        ELSE
            DUP IF NIP UNLOOP EXIT THEN DROP
        THEN
    LOOP
    DROP LIBRARY-REPOSITORY-S-OK ;

\ One physical repository call holds the VFS exclusion region from sealed
\ namespace classification through its last open/create/publication.  Ambient
\ state capture, body containment, FD retirement, and restoration all occur
\ inside that same region, so cleanup cannot race another guarded VFS caller.

: _LIBREPO-VFS-USE-SAVED  ( work -- )
    _LRW.OP-OLD-VFS @ VFS-USE ;

: _LIBREPO-VFS-RESTORE  ( work -- status )
    DUP _LRW.OP-CWD @
    OVER _LRW.REPOSITORY @ _LR.VFS @ V.CWD !
    DUP ['] _LIBREPO-VFS-USE-SAVED CATCH
    DUP IF
        _LIBREPO-DROP3 LIBRARY-REPOSITORY-S-UNCERTAIN EXIT
    THEN
    DROP DROP LIBRARY-REPOSITORY-S-OK ;

: _LIBREPO-VFS-RETIRE-FD  ( work -- status )
    DUP _LRW.FD @ DUP 0= IF
        2DROP LIBRARY-REPOSITORY-S-OK EXIT
    THEN
    VFS-CLOSE? _LIBREPO-IOR>STATUS
    SWAP 0 SWAP _LRW.FD ! ;

: _LIBREPO-VFS-CLEANUP-CALL
  ( work primary cleanup-xt -- work final )
    2 PICK SWAP CATCH
    DUP IF
        2DROP DROP
        LIBRARY-REPOSITORY-S-UNCERTAIN EXIT
    THEN
    DROP
    DUP IF
        2DROP LIBRARY-REPOSITORY-S-UNCERTAIN
    ELSE
        DROP
    THEN ;

: _LIBREPO-VFS-TRANSACTION-DISPATCH  ( work -- status )
    VFS-CUR OVER _LRW.OP-OLD-VFS !
    DUP _LRW.REPOSITORY @ _LR.VFS @ V.CWD @
        OVER _LRW.OP-CWD !
    DUP DUP _LRW.OP-XT @ CATCH
    DUP IF
        2DROP LIBRARY-REPOSITORY-S-FAULT
    ELSE
        DROP
        DUP _LIBREPO-STATUS? 0= IF
            DROP LIBRARY-REPOSITORY-S-FAULT
        THEN
    THEN
    ['] _LIBREPO-VFS-RETIRE-FD _LIBREPO-VFS-CLEANUP-CALL
    ['] _LIBREPO-VFS-RESTORE _LIBREPO-VFS-CLEANUP-CALL
    NIP ;

: _LIBREPO-VFS-TRANSACTION-CALL  ( work -- status )
    ['] _LIBREPO-VFS-TRANSACTION-DISPATCH VFS-TRANSACTION ;

: _LIBREPO-VFS-OP-CALL  ( work operation-xt -- status )
    OVER _LRW.OP-XT !
    DUP ['] _LIBREPO-VFS-TRANSACTION-CALL CATCH
    DUP IF
        2DROP LIBRARY-REPOSITORY-S-FAULT
    ELSE
        DROP
        DUP _LIBREPO-STATUS? 0= IF
            DROP LIBRARY-REPOSITORY-S-FAULT
        THEN
    THEN
    NIP ;

: _LIBREPO-MKDIR-ROOT-RUN  ( repository -- ior )
    DUP _LR.VFS @ DUP >R
    V.ROOT @ R@ V.CWD !
    _LIBREPO-DIRECTORY-NAME$ R> VFS-MKDIR
    NIP ;

: _LIBREPO-ENSURE-DIRECTORY  ( repository -- status )
    _LIBREPO-DIRECTORY$ VFS-RP-NOFOLLOW-FINAL
        3 PICK _LR.VFS @ VFS-RESOLVE-POLICY?
    DUP 0= IF
        DROP
        DUP IN.TYPE @ VFS-T-DIR =
        IF 2DROP LIBRARY-REPOSITORY-S-OK
        ELSE 2DROP LIBRARY-REPOSITORY-S-CORRUPT THEN
        EXIT
    THEN
    DUP VFS-IOR-REASON VFS-R-NOENT <> IF
        >R 2DROP R> _LIBREPO-IOR>STATUS EXIT
    THEN
    2DROP
    DUP _LR.VFS @ V.CWD @ >R
    DUP ['] _LIBREPO-MKDIR-ROOT-RUN CATCH
    R> 3 PICK _LR.VFS @ V.CWD !
    DUP IF
        _LIBREPO-DROP3 LIBRARY-REPOSITORY-S-IO EXIT
    THEN
    DROP NIP _LIBREPO-IOR>STATUS
    ;

: _LIBREPO-ENSURE-FILE  ( path-a path-u repository -- status )
    >R
    2DUP VFS-RP-NOFOLLOW-FINAL
        R@ _LR.VFS @ VFS-RESOLVE-POLICY?
    DUP 0= IF
        DROP
        DUP IN.TYPE @ VFS-T-FILE =
        IF DROP 2DROP R> DROP LIBRARY-REPOSITORY-S-OK
        ELSE DROP 2DROP R> DROP LIBRARY-REPOSITORY-S-CORRUPT THEN
        EXIT
    THEN
    DUP VFS-IOR-REASON VFS-R-NOENT <> IF
        >R DROP 2DROP R> _LIBREPO-IOR>STATUS R> DROP EXIT
    THEN
    2DROP
    R@ _LR.VFS @ VFS-CREATE
    0= IF R> DROP LIBRARY-REPOSITORY-S-IO EXIT THEN
    R> DROP LIBRARY-REPOSITORY-S-OK ;

: _LIBREPO-SET-BLOCKED  ( flag repository -- )
    _LR.FLAGS
    SWAP IF
        DUP @ _LR-F-BLOCKED OR SWAP !
    ELSE
        DUP @ _LR-F-BLOCKED INVERT AND SWAP !
    THEN ;

: _LIBREPO-LOAD-RUN  ( work -- status )
    >R
    R@ _LRW.REPOSITORY @ _LIBREPO-TOPOLOGY-ALLOW-ABSENT
    DUP IF
        DUP LIBRARY-REPOSITORY-S-CORRUPT =
        OVER LIBRARY-REPOSITORY-S-UNCERTAIN = OR
        OVER LIBRARY-REPOSITORY-S-CONFLICT = OR
        R@ _LRW.REPOSITORY @ _LIBREPO-SET-BLOCKED
        R> DROP EXIT
    THEN DROP
    R@ _LRW.REPOSITORY @ _LR.STORE
    R@ _LRW.PSTORE PSTORE-OPEN-ACTIVE
    DUP PERSIST-S-ABSENT <> OVER PERSIST-S-OK <> AND IF
        DUP PERSIST-S-CORRUPT =
        OVER PERSIST-S-UNCERTAIN = OR
        OVER PERSIST-S-CONFLICT = OR
        R@ _LRW.REPOSITORY @ _LIBREPO-SET-BLOCKED
        R> DROP EXIT
    THEN
    DROP
    R@ _LRW.REPOSITORY @ _LR.ADAPTER
    R@ _LRW.INDEX LIBPA-INDEX-REBIND
    DUP LIBPA-S-ABSENT = IF
        DROP
        R@ _LRW.REPOSITORY @ _LR.FLAGS DUP @
            _LR-F-LOADED OR SWAP !
        0 R@ _LRW.REPOSITORY @ _LIBREPO-SET-BLOCKED
        R> DROP LIBRARY-REPOSITORY-S-ABSENT EXIT
    THEN
    DUP IF
        DUP LIBPA-S-CORRUPT =
        OVER LIBPA-S-UNCERTAIN = OR
        OVER LIBPA-S-CONFLICT = OR
        R@ _LRW.REPOSITORY @ _LIBREPO-SET-BLOCKED
        R> DROP EXIT
    THEN
    DROP
    R@ _LRW.REPOSITORY @ _LR.FLAGS DUP @
        _LR-F-LOADED _LR-F-PROVISIONED OR OR SWAP !
    0 R@ _LRW.REPOSITORY @ _LIBREPO-SET-BLOCKED
    R> DROP LIBRARY-REPOSITORY-S-OK ;

: LIBRARY-REPOSITORY-LOAD  ( repository work -- status )
    2DUP _LIBREPO-ENTER DUP IF >R 2DROP R> EXIT THEN DROP
    DUP ['] _LIBREPO-LOAD-RUN _LIBREPO-VFS-OP-CALL
    ROT ROT _LIBREPO-LEAVE ;

: _LIBREPO-PROVISION-RUN  ( work -- status )
    >R
    R@ _LRW.REPOSITORY @ _LIBREPO-ENSURE-DIRECTORY
    DUP IF R> DROP EXIT THEN DROP
    R@ _LRW.REPOSITORY @ _LIBREPO-TOPOLOGY-ALLOW-ABSENT
    DUP IF R> DROP EXIT THEN DROP
    R@ _LRW.REPOSITORY @ _LR.STORE
    R@ _LRW.PSTORE PSTORE-PROVISION
    DUP IF R> DROP EXIT THEN DROP
    _LIBREPO-PAGES-1$ R@ _LRW.REPOSITORY @ _LIBREPO-ENSURE-FILE
    DUP IF R> DROP EXIT THEN DROP
    _LIBREPO-SEGMENTS-1$ R@ _LRW.REPOSITORY @ _LIBREPO-ENSURE-FILE
    DUP IF R> DROP EXIT THEN DROP
    R@ _LIBREPO-LOAD-RUN
    DUP LIBRARY-REPOSITORY-S-ABSENT = IF DROP ELSE
        DUP IF R> DROP EXIT THEN DROP
    THEN
    R@ _LRW.REPOSITORY @ _LR.FLAGS DUP @
        _LR-F-PROVISIONED _LR-F-LOADED OR OR SWAP !
    R@ _LRW.REPOSITORY @ _LR.VFS @ VFS-SYNC _LIBREPO-IOR>STATUS
    R> DROP ;

: LIBRARY-REPOSITORY-PROVISION  ( repository work -- status )
    2DUP _LIBREPO-ENTER DUP IF >R 2DROP R> EXIT THEN DROP
    DUP ['] _LIBREPO-PROVISION-RUN _LIBREPO-VFS-OP-CALL
    ROT ROT _LIBREPO-LEAVE ;

: _LIBREPO-BOOTSTRAP-RUN  ( bootstrap-id work -- status )
    >R
    DUP RID-PRESENT? 0= IF DROP R> DROP LIBRARY-REPOSITORY-S-INVALID EXIT THEN
    R@ _LRW.REPOSITORY @ _LIBREPO-TOPOLOGY-ALLOW-ABSENT
    DUP IF NIP R> DROP EXIT THEN DROP
    DUP
    R@ _LRW.REPOSITORY @ _LR.ADAPTER
    R@ _LRW.INDEX LIBPA-INDEX-PROVISION
    >R DROP R> DUP IF R> DROP EXIT THEN
    DROP
    R@ _LRW.REPOSITORY @ _LR.FLAGS DUP @
        _LR-F-PROVISIONED _LR-F-LOADED OR OR SWAP !
    R> DROP LIBRARY-REPOSITORY-S-OK ;

: _LIBREPO-BOOTSTRAP-VFS-RUN  ( work -- status )
    DUP _LRW.OP-ARG0 @ SWAP _LIBREPO-BOOTSTRAP-RUN ;

: LIBRARY-REPOSITORY-BOOTSTRAP
  ( bootstrap-id repository work -- status )
    2DUP _LIBREPO-ENTER DUP IF
        >R _LIBREPO-DROP3 R> EXIT
    THEN DROP
    >R
    OVER R@ _LRW.OP-ARG0 !
    R@ ['] _LIBREPO-BOOTSTRAP-VFS-RUN _LIBREPO-VFS-OP-CALL
    SWAP R> _LIBREPO-LEAVE
    NIP ;

: LIBRARY-REPOSITORY-FINI  ( repository work -- status )
    2DUP _LIBREPO-PAIR? 0= IF
        2DROP LIBRARY-REPOSITORY-S-INVALID EXIT
    THEN
    DUP _LRW.BUSY @ IF 2DROP LIBRARY-REPOSITORY-S-BUSY EXIT THEN
    OVER _LR.FLAGS @ _LR-F-COMPACTION-BOUND AND IF
        DUP _LRW.COMPACT PCOMPACT-STATE@ DUP
        PCOMPACT-STATE-IDLE <>
        SWAP PCOMPACT-STATE-CLEANED <> AND IF
            2DROP LIBRARY-REPOSITORY-S-BUSY EXIT
        THEN
    THEN
    OVER _LR.GUARD @ GUARD-TRY-ACQUIRE 0= IF
        2DROP LIBRARY-REPOSITORY-S-BUSY EXIT
    THEN
    OVER _LR.GUARD @ >R
    DUP LIBRARY-REPOSITORY-WORK-SIZE 0 FILL
    DROP
    LIBRARY-REPOSITORY-SIZE 0 FILL
    R> GUARD-RELEASE
    LIBRARY-REPOSITORY-S-OK ;

