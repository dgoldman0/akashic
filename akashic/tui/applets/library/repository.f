    R@ _LIBREPO-MIRROR-RUN
    DUP IF >R 2DROP R> R> DROP EXIT THEN DROP
    R@ _LRW.INSPECTION R@ _LIBREPO-INSPECT-RUN
    DUP IF
        DROP 2DROP R> DROP LIBRARY-REPOSITORY-S-UNCERTAIN EXIT
    THEN DROP
    R@ _LRW.INSPECTION LRI.HEALTH @
        LIBRARY-REPOSITORY-HEALTH-OK <>
    R@ _LRW.INSPECTION LRI.REPAIR-MASK @ 0<> OR IF
        2DROP R> DROP LIBRARY-REPOSITORY-S-UNCERTAIN EXIT
