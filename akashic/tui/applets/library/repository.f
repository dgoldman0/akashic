\ =====================================================================
\  repository.f - Desk/Library physical persistence owner
\ =====================================================================
\  This file alone chooses the sealed /library paths and composes the
\  Library persistence adapter with neutral two-bank storage.  It owns no
\  command, query, projection, controller, or UI shapes.  All mutable
\  descriptors, workspaces, caches, buffers, and guards are supplied by
\  the caller; there is no process-global operation state.
\
\  Semantic compaction remains adapter policy.  The repository binds the
\  adapter-owned live-evidence step/finalizer privately and owns every
\  physical begin/step/finalize/publish/mirror/cleanup transition around it;
\  callers provide budgets, including independent source/builder cold-audit
\  maps, never executable policy.
\ =====================================================================

