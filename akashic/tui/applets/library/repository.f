    2DUP _LIBREPO-PAIR? 0= IF _LIBREPO-DROP4 0 EXIT THEN
    3 PICK LIBRARY-REPOSITORY-INSPECTION-SEALED? 0= IF
        _LIBREPO-DROP4 0 EXIT
