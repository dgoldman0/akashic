: _LIBREPO-NONNEGATIVE+  ( a b -- sum status )
    OVER 0< OVER 0< OR IF
        2DROP 0 LIBRARY-REPOSITORY-S-CAPACITY EXIT
    THEN
    2DUP PERSIST-MAX-SIGNED SWAP - > IF
        2DROP 0 LIBRARY-REPOSITORY-S-CAPACITY EXIT
    THEN
    + LIBRARY-REPOSITORY-S-OK ;

: _LIBREPO-OBJECT-SHAPE?  ( object -- flag )
    DUP LRIO.PRESENT @ DUP 0= SWAP -1 = OR 0= IF DROP 0 EXIT THEN
    DUP LRIO.BYTES @ 0< IF DROP 0 EXIT THEN
    DUP LRIO.PRESENT @ 0= IF LRIO.BYTES @ 0= ELSE DROP -1 THEN ;

: _LIBREPO-INSPECTION-SHAPE?  ( inspection -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIBRARY-REPOSITORY-INSPECTION-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LRI.HEALTH @ DUP LIBRARY-REPOSITORY-HEALTH-OK <
    SWAP LIBRARY-REPOSITORY-HEALTH-FUTURE > OR IF DROP 0 EXIT THEN
    DUP LRI.REPAIR-MASK @ DUP 0=
    SWAP LIBRARY-REPOSITORY-REPAIR-MIRROR = OR 0= IF DROP 0 EXIT THEN
    DUP LRI.HEALTH @ LIBRARY-REPOSITORY-HEALTH-FALLBACK = IF
        DUP LRI.REPAIR-MASK @
            LIBRARY-REPOSITORY-REPAIR-MIRROR <> IF DROP 0 EXIT THEN
    ELSE
        DUP LRI.REPAIR-MASK @ IF DROP 0 EXIT THEN
    THEN
    DUP LRI.RAW-REQUIRED @ 0< IF DROP 0 EXIT THEN
    0
    LIBRARY-REPOSITORY-EVIDENCE-COUNT 0 ?DO
        OVER I SWAP LRI.OBJECT
        DUP _LIBREPO-OBJECT-SHAPE? 0= IF
            DROP 2DROP 0 UNLOOP EXIT
        THEN
        LRIO.BYTES @ _LIBREPO-NONNEGATIVE+
        DUP IF
            >R 2DROP R> DROP 0 UNLOOP EXIT
        THEN DROP
    LOOP
    OVER LRI.RAW-REQUIRED @ = NIP ;

