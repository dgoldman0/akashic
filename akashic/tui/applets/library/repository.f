    THEN
    2 PICK SHA3-256-LEN
    3 PICK 3 PICK LIBRARY-REPOSITORY-SPAN-DISJOINT? 0= IF
        _LIBREPO-DROP4 0 EXIT
    THEN
    3 PICK LIBRARY-REPOSITORY-INSPECTION-SIZE
