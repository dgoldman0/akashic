: _LAPP-RUN-PAGE  ( -- status )
    _LAPP-READY? 0= IF
        0 _LAPP-ROW-COUNT ! _LAPP-CLEAR-PREVIEW
        _LAPP-LAST-STATUS @ EXIT
    THEN
    \ A FIRST refresh carries the semantic selection remembered before its
    \ page buffers were reinitialized.  Navigation deliberately starts at
    \ the first row of the adjacent keyset page.
    _LAPP-PAGE-MODE @ _LAPP-PAGE-FIRST <> IF
        _LAPP-CLEAR-SELECTION-ANCHOR
    THEN
    _LAPP-VIEW @ CASE
        _LAPP-V-HISTORY OF _LAPP-RUN-HISTORY ENDOF
        _LAPP-V-COLLECTIONS OF _LAPP-RUN-COLLECTION-PAGE ENDOF
        _LAPP-RUN-CORPUS-PAGE SWAP
    ENDCASE
    _LAPP-SET-STATUS
    DUP IF _LAPP-CLEAR-PREVIEW EXIT THEN DROP
    _LAPP-PAGE LIBQP.COUNT @ _LAPP-ROW-COUNT !
    _LAPP-RESTORE-SELECTION
    _LAPP-LOAD-SELECTION DROP
    _LAPP-LAST-STATUS @ ;

: _LAPP-RESET-PAGE  ( -- status )
    \ Page initialization clears the row storage, so retain the semantic
    \ selection before rebuilding those buffers.  Once the buffer is cleared,
    \ no failed refresh may leave the old visible row count behind.
    _LAPP-REMEMBER-SELECTION
    0 _LAPP-ROW-COUNT !
    0 _LAPP-PAGE-INDEX ! _LAPP-PAGE-FIRST _LAPP-PAGE-MODE !
    _LAPP-PAGE-INITIALIZE DUP IF _LAPP-SET-STATUS EXIT THEN DROP
    _LAPP-RUN-PAGE ;

: _LAPP-RELOAD  ( -- status )
    _LAPP-RUNTIME@ 0= IF
        LIBRARY-SERVICE-S-CAPACITY _LAPP-SET-STATUS EXIT
    THEN
    _LAPP-OWNER-INITIALIZED @ 0= IF
        _LAPP-OWNER-OPEN
        DUP LIBRARY-SERVICE-S-OK = IF
            DROP _LAPP-RESET-PAGE EXIT
        THEN
        _LAPP-CLEAR-PAGES _LAPP-CLEAR-PREVIEW EXIT
    THEN
    0 _LAPP-READY !
    _LAPP-REPOSITORY _LAPP-REPOSITORY-WORK
        LIBRARY-REPOSITORY-LOAD _LAPP-SET-STATUS
    DUP LIBRARY-SERVICE-S-OK = IF
        -1 _LAPP-READY ! DROP _LAPP-RESET-PAGE EXIT
    THEN
    _LAPP-CLEAR-PAGES _LAPP-CLEAR-PREVIEW ;

