: _LAPP-OWNER-OPEN  ( -- status )
    _LAPP-RUNTIME@ 0= IF
        LIBRARY-SERVICE-S-CAPACITY _LAPP-SET-STATUS EXIT
    THEN
    \ This also closes any partially initialized graph left by a failed open.
    _LAPP-OWNER-CLOSE
    _LAPP-RUNTIME@ _LAPP-RUNTIME-SIZE 0 FILL
    VFS-CUR DUP 0= IF
        DROP LIBRARY-SERVICE-S-IO _LAPP-SET-STATUS EXIT
    THEN
    _LAPP-VFS !
    _LAPP-CACHE-MEMORY-0 _LAPP-CACHE-0 _LAPP-CACHE-INIT
        _LAPP-SET-STATUS
    DUP IF EXIT THEN DROP
    _LAPP-CACHE-MEMORY-1 _LAPP-CACHE-1 _LAPP-CACHE-INIT
        _LAPP-SET-STATUS
    DUP IF EXIT THEN DROP
    _LAPP-BUILDER-CACHE-MEMORY-0 _LAPP-BUILDER-CACHE-0
        _LAPP-CACHE-INIT _LAPP-SET-STATUS
    DUP IF EXIT THEN DROP
    _LAPP-BUILDER-CACHE-MEMORY-1 _LAPP-BUILDER-CACHE-1
        _LAPP-CACHE-INIT _LAPP-SET-STATUS
    DUP IF EXIT THEN DROP
    _LAPP-VFS @
    _LAPP-CACHE-0 _LAPP-CACHE-1
    _LAPP-BUILDER-CACHE-0 _LAPP-BUILDER-CACHE-1
    _LAPP-GUARD _LAPP-BUILDER-GUARD
    0 0 _LAPP-REPOSITORY LIBRARY-REPOSITORY-INIT
        _LAPP-SET-STATUS
    DUP IF EXIT THEN DROP
    _LAPP-RECORD-BUFFER LIBRARY-REPOSITORY-RECORD-BUFFER-MIN
    _LAPP-STAGE-BUFFER LIBRARY-REPOSITORY-STAGE-BUFFER-MIN
    _LAPP-BUILDER-RECORD-BUFFER
        LIBRARY-REPOSITORY-RECORD-BUFFER-MIN
    _LAPP-COMPACTION-BUFFER _LAPP-COMPACTION-BUFFER-SIZE
    _LAPP-AUDIT-MAP _LAPP-AUDIT-MAP-CAPACITY
    _LAPP-BUILDER-AUDIT-MAP _LAPP-AUDIT-MAP-CAPACITY
    _LAPP-REPOSITORY _LAPP-REPOSITORY-WORK
        LIBRARY-REPOSITORY-WORK-INIT _LAPP-SET-STATUS
    DUP IF EXIT THEN DROP
    _LAPP-REPOSITORY _LAPP-REPOSITORY-WORK _LAPP-SERVICE
        LIBRARY-SERVICE-INIT _LAPP-SET-STATUS
    DUP IF EXIT THEN DROP
    _LAPP-SERVICE _LAPP-SERVICE-WORK
        LIBRARY-SERVICE-WORK-INIT _LAPP-SET-STATUS
    DUP IF EXIT THEN DROP
    -1 _LAPP-OWNER-INITIALIZED !
    _LAPP-REPOSITORY _LAPP-REPOSITORY-WORK
        LIBRARY-REPOSITORY-LOAD _LAPP-SET-STATUS
    DUP LIBRARY-SERVICE-S-OK = IF -1 _LAPP-READY ! THEN ;

: _LAPP-ENSURE-PROVISIONED  ( -- status )
    _LAPP-RUNTIME@ 0= IF
        LIBRARY-SERVICE-S-CAPACITY _LAPP-SET-STATUS EXIT
    THEN
    _LAPP-READY? IF
        LIBRARY-SERVICE-S-OK _LAPP-SET-STATUS EXIT
    THEN
    _LAPP-OWNER-INITIALIZED @ 0= IF
        _LAPP-OWNER-OPEN DROP
        _LAPP-READY? IF
            LIBRARY-SERVICE-S-OK _LAPP-SET-STATUS EXIT
        THEN
        _LAPP-OWNER-INITIALIZED @ 0= IF
            _LAPP-LAST-STATUS @ DUP LIBRARY-SERVICE-S-OK = IF
                DROP LIBRARY-SERVICE-S-IO _LAPP-SET-STATUS
            THEN
            EXIT
        THEN
    THEN
    \ Last-status is presentation state, not an authority certificate.  A
    \ prepared retry reclassifies the owner before deciding whether first-use
    \ provisioning is safe; only a fresh ABSENT result permits provisioning.
    0 _LAPP-READY !
    _LAPP-REPOSITORY _LAPP-REPOSITORY-WORK
        LIBRARY-REPOSITORY-LOAD _LAPP-SET-STATUS
    DUP LIBRARY-SERVICE-S-OK = IF
        -1 _LAPP-READY ! EXIT
    THEN
    DUP LIBRARY-SERVICE-S-ABSENT <> IF EXIT THEN DROP
    _LAPP-REPOSITORY _LAPP-REPOSITORY-WORK
        LIBRARY-REPOSITORY-PROVISION _LAPP-SET-STATUS
    DUP IF EXIT THEN DROP
    _LAPP-BOOTSTRAP-ID _LAPP-REPOSITORY _LAPP-REPOSITORY-WORK
        LIBRARY-REPOSITORY-BOOTSTRAP _LAPP-SET-STATUS
    DUP LIBRARY-SERVICE-S-OK = IF -1 _LAPP-READY ! THEN ;

