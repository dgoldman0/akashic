: _LIBQ-STABLE-KEY<=?
  ( first-sequence first-rid last-sequence last-rid -- flag )
    >R >R
    OVER R@ < IF
        2DROP R> DROP R> DROP -1 EXIT
    THEN
    OVER R@ > IF
        2DROP R> DROP R> DROP 0 EXIT
    THEN
    NIP R> DROP R>
    SWAP RID-SIZE ROT RID-SIZE COMPARE
    DUP 0< SWAP 0= OR ;

