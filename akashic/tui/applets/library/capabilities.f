    DUP 0= IF 2DROP CBUILD-S-INVALID _LCAP-BUILD-FAIL! EXIT THEN
    CV-INT! ;

: _LCAP-BOOL!  ( flag value -- )
    DUP 0= IF 2DROP CBUILD-S-INVALID _LCAP-BUILD-FAIL! EXIT THEN
    CV-BOOL! ;

: _LCAP-NULL!  ( value -- )
    DUP 0= IF DROP CBUILD-S-INVALID _LCAP-BUILD-FAIL! EXIT THEN
    CV-NULL! ;

: _LCAP-STRING!  ( a u value -- )
    DUP 0= IF 2DROP DROP CBUILD-S-INVALID _LCAP-BUILD-FAIL! EXIT THEN
    CV-STRING! ?DUP IF _LCAP-BUILD-FAIL! THEN ;

: _LCAP-RESOURCE!  ( ref value -- )
    DUP 0= IF 2DROP CBUILD-S-INVALID _LCAP-BUILD-FAIL! EXIT THEN
    IRES-RREF! DUP IRES-S-OK <> IF _LCAP-BUILD-FAIL! ELSE DROP THEN ;

: _LCAP-DIGEST-STRING!  ( digest value scratch -- )
    >R
    SWAP R@ SHA3-256->HEX DROP
    R@ SHA3-256-HEX-LEN ROT _LCAP-STRING!
    R> DROP ;

: _LCAP-RID-RESOURCE!  ( rid value -- )
    >R
    _LCAP-WORK LCAPW.REF2 RREF-INIT
    _LCAP-WORK LCAPW.REF2 RREF.ID RID-COPY
    _LCAP-WORK LCAPW.REF2 R> _LCAP-RESOURCE! ;

: _LCAP-RESULT-SEAL  ( schema -- bus-status )
    _LCAP-WORK LCAPW.BUILD-STATUS @ ?DUP IF
        NIP _LCAP-WORK LCAPW.BUILDER CVB-ABORT DROP
        _LCAP-CONSTRUCTION-FAIL EXIT
    THEN
    _LCAP-WORK LCAPW.BUILDER CVB-SEAL DUP IF
        _LCAP-WORK LCAPW.BUILDER CVB-ABORT DROP
        _LCAP-CONSTRUCTION-FAIL EXIT
    THEN DROP CBUS-S-OK ;

: _LCAP-RESULT-PREPARED  ( -- bus-status )
    _LCAP-WORK LCAPW.BUILD-STATUS @ ?DUP IF
        _LCAP-WORK LCAPW.BUILDER CVB-ABORT DROP
        _LCAP-CONSTRUCTION-FAIL EXIT
    THEN
    CBUS-S-OK ;

: _LCAP-RESULT-PUBLISH-SEALED  ( -- bus-status )
    _LCAP-REQUEST CBR.RESULT _LCAP-WORK LCAPW.BUILDER CVB-PUBLISH
    DUP IF _LCAP-CONSTRUCTION-FAIL ELSE DROP CBUS-S-OK THEN ;

: _LCAP-RESULT-PUBLISH  ( schema -- bus-status )
    _LCAP-RESULT-SEAL DUP CBUS-S-OK <> IF EXIT THEN DROP
    _LCAP-RESULT-PUBLISH-SEALED ;

: _LCAP-HANDLER-RUN  ( request instance body-xt -- status )
    >R
    _LAPP-CAPABILITY-ACTIVATE
    DUP IF SWAP _LCAP-SERVICE>CBUS R> DROP EXIT THEN DROP
    _LAPP-CAPABILITY-WORK DUP LIBRARY-CAPABILITY-WORK-VALID? 0= IF
        DROP
        >R S" Library capability workspace is unavailable" 0
        R@ CBR-ERROR! R> DROP
        R> DROP CBUS-S-FAILED EXIT
    THEN
    DUP LIBRARY-CAPABILITY-WORK-RESET ?DUP IF
        2DROP DROP R> DROP CBUS-S-FAILED EXIT
    THEN
    2DUP LCAPW.REQUEST !
    2DROP
    R> CATCH
    ?DUP IF
        S" Library capability handler threw" ROT
            _LCAP-REQUEST CBR-ERROR!
        CBUS-S-FAILED
    THEN
    >R
    _LCAP-WORK LIBRARY-CAPABILITY-WORK-RESET ?DUP IF
        S" Library capability workspace cleanup failed" ROT
            _LCAP-REQUEST CBR-ERROR!
        R> DROP CBUS-S-FAILED EXIT
    THEN
    R> ;

: _LCAP-ARG  ( key-a key-u -- value|0 )
    _LCAP-ARGS CV-MAP-FIND ;

: _LCAP-R0@  ( value ref -- flag )
    2DUP IRES-RREF@ IRES-S-OK <> IF 2DROP 0 EXIT THEN
    NIP RREF.REVISION @ 0= ;

: _LCAP-HEX-NIBBLE  ( c -- nibble flag )
    DUP [CHAR] 0 >= OVER [CHAR] 9 <= AND IF
        [CHAR] 0 - -1 EXIT
    THEN
    DUP [CHAR] a >= OVER [CHAR] f <= AND IF
        [CHAR] a - 10 + -1 EXIT
    THEN
    DROP 0 0 ;

: _LCAP-H64@  ( value digest -- flag )
    _LCAP-WORK LCAPW.DESTINATION !
    DUP 0= IF DROP 0 EXIT THEN
    DUP CV-TYPE@ CV-T-STRING <> IF DROP 0 EXIT THEN
    DUP CV-LEN@ SHA3-256-HEX-LEN <> IF DROP 0 EXIT THEN
    CV-DATA@ DUP 0= IF DROP 0 EXIT THEN
    _LCAP-WORK LCAPW.SOURCE !
    LIB-DIGEST-SIZE 0 DO
        _LCAP-WORK LCAPW.SOURCE @ I 2 * + C@
            _LCAP-HEX-NIBBLE 0= IF
            DROP 0 UNLOOP EXIT
        THEN
        _LCAP-WORK LCAPW.TEMP !
        _LCAP-WORK LCAPW.SOURCE @ I 2 * 1+ + C@
            _LCAP-HEX-NIBBLE 0= IF
            DROP 0 UNLOOP EXIT
        THEN
        _LCAP-WORK LCAPW.TEMP @ 4 LSHIFT OR
        _LCAP-WORK LCAPW.DESTINATION @ I + C!
    LOOP
    -1 ;

: _LCAP-MEDIA@  ( value -- media flag )
    DUP 0= IF DROP 0 0 EXIT THEN
    DUP CV-TYPE@ CV-T-STRING <> IF DROP 0 0 EXIT THEN
    DUP CV-DATA@ SWAP CV-LEN@
    2DUP S" text/plain" STR-STR= IF
        2DROP LIB-MEDIA-TEXT-PLAIN -1 EXIT
    THEN
    S" text/markdown" STR-STR= IF
        LIB-MEDIA-TEXT-MARKDOWN -1
    ELSE
        0 0
    THEN ;

: _LCAP-MANAGED-MEDIA$  ( media -- a u flag )
    DUP LIB-MEDIA-TEXT-PLAIN =
    OVER LIB-MEDIA-TEXT-MARKDOWN = OR 0= IF DROP 0 0 0 EXIT THEN
    LIB-MEDIA$ ;

: _LCAP-DERIVE-ID  ( domain-a domain-u invocation destination -- )
    >R >R
    SHA3-256-BEGIN
    SHA3-256-ADD
    _LCAP-NUL 1 SHA3-256-ADD
    R@ LIB-DIGEST-SIZE SHA3-256-ADD
    R> DROP R> SHA3-256-END ;

: _LCAP-PATCH-INT  ( n node -- flag )
    OVER 0< IF 2DROP 0 EXIT THEN
    DUP 0= IF 2DROP 0 EXIT THEN
    DUP CV-TYPE@ CV-T-INT <> IF 2DROP 0 EXIT THEN
    CV.DATA ! -1 ;

: _LCAP-PATCH-LOGICAL  ( generation -- flag )
    _LCAP-WORK LCAPW.LOGICAL-NODE @ _LCAP-PATCH-INT ;

: _LCAP-PATCH-DIGEST  ( digest node -- flag )
    _LCAP-WORK LCAPW.SOURCE !
    _LCAP-WORK LCAPW.SOURCE @ DUP 0= IF 2DROP 0 EXIT THEN
    DUP CV-TYPE@ CV-T-STRING <> IF 2DROP 0 EXIT THEN
    DUP CV-LEN@ SHA3-256-HEX-LEN <> IF 2DROP 0 EXIT THEN
    CV-DATA@ DUP 0= IF 2DROP 0 EXIT THEN
    SHA3-256->HEX SHA3-256-HEX-LEN = ;

