: _LCAP-SERVICE>CBUS  ( service-status request -- bus-status )
    >R
    DUP S" Library service operation failed" ROT R@ CBR-ERROR!
    CASE
        LIBRARY-SERVICE-S-INVALID OF CBUS-S-INVALID ENDOF
        LIBRARY-SERVICE-S-BUSY OF CBUS-S-BUSY ENDOF
        LIBRARY-SERVICE-S-ABSENT OF CBUS-S-NOT-FOUND ENDOF
        LIBRARY-SERVICE-S-NOT-FOUND OF CBUS-S-NOT-FOUND ENDOF
        LIBRARY-SERVICE-S-TOMBSTONED OF CBUS-S-NOT-FOUND ENDOF
        LIBRARY-SERVICE-S-GONE OF CBUS-S-NOT-FOUND ENDOF
        CBUS-S-FAILED SWAP
    ENDCASE
    R> DROP ;

