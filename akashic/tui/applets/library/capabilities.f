: _LCAP-COLLECTION-MEMBERS@  ( value -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP CV-TYPE@ CV-T-LIST <> IF DROP 0 EXIT THEN
    DUP CV-LEN@ DUP 0<
    OVER LIBRARY-CAPABILITY-MEMBER-MAX > OR IF
        2DROP 0 EXIT
    THEN
    DUP _LCAP-WORK LCAPW.LIMIT !
    DROP _LCAP-WORK LCAPW.DESTINATION !
    _LCAP-WORK LCAPW.LIMIT @ 0 ?DO
        I _LCAP-WORK LCAPW.DESTINATION @ CV-LIST-NTH
        _LCAP-WORK LCAPW.REF0 _LCAP-R0@ 0= IF
            0 UNLOOP EXIT
        THEN
        _LCAP-WORK LCAPW.REF0 RREF.ID
        _LCAP-WORK LCAPW.MEMBERS I RID-SIZE * + RID-COPY
        I IF
            _LCAP-WORK LCAPW.MEMBERS I 1- RID-SIZE * + RID-SIZE
            _LCAP-WORK LCAPW.MEMBERS I RID-SIZE * + RID-SIZE
                COMPARE 0< 0= IF
                0 UNLOOP EXIT
            THEN
        THEN
    LOOP
    -1 ;

