: _LCAP-QUERY-PREPARE  ( -- flag )
    _LCAP-WORK LCAPW.SCOPED-QUERY
        LIBRARY-SCOPED-QUERY-REQUEST-INIT
    _LCAP-WORK LCAPW.SCOPED-QUERY LSSQR.SCOPE
        _LCAP-SCOPE@ 0= IF 0 EXIT THEN

    S" limit" _LCAP-ARG DUP 0= IF DROP 0 EXIT THEN
    CV-DATA@ DUP 1 < OVER LIBRARY-CAPABILITY-QUERY-MAX > OR IF
        DROP 0 EXIT
    THEN
    _LCAP-WORK LCAPW.LIMIT !

    _LCAP-WORK LCAPW.CORPUS-QUERY
        LIBRARY-CORPUS-QUERY-REQUEST-INIT
    LIBRARY-CORPUS-LIFECYCLE-ACTIVE
        _LCAP-WORK LCAPW.CORPUS-QUERY LIBCQR.LIFECYCLE-MASK !
    LIBRARY-CORPUS-KIND-MANAGED
        _LCAP-WORK LCAPW.CORPUS-QUERY LIBCQR.KIND-MASK !
    LIBRARY-CORPUS-MEDIA-PLAIN LIBRARY-CORPUS-MEDIA-MARKDOWN OR
        _LCAP-WORK LCAPW.CORPUS-QUERY LIBCQR.MEDIA-MASK !
    _LCAP-WORK LCAPW.SCOPED-QUERY LSSQR.SCOPE LSECS.COLLECTION
        _LCAP-WORK LCAPW.CORPUS-QUERY LIBCQR.COLLECTION RID-COPY

    _LCAP-WORK LCAPW.QUERY-ROWS
    _LCAP-WORK LCAPW.LIMIT @
    _LCAP-WORK LCAPW.QUERY-PAGE LIBRARY-CORPUS-PAGE-INIT
    DUP IF DROP 0 EXIT THEN DROP

    S" after" _LCAP-ARG DUP 0= IF DROP 0 EXIT THEN
    DUP CV-TYPE@ CV-T-NULL = IF
        DROP 0 _LCAP-WORK LCAPW.HAS-AFTER !
    ELSE
        _LCAP-WORK LCAPW.QUERY-PAGE LIBQP.CONTINUATION
            _LCAP-CURSOR@ 0= IF 0 EXIT THEN
        \ A query page carrying a rows-bearing continuation must itself be
        \ structurally valid until the domain layer snapshots that cursor.
        1 _LCAP-WORK LCAPW.QUERY-PAGE LIBQP.COUNT !
        -1 _LCAP-WORK LCAPW.HAS-AFTER !
    THEN

    _LCAP-WORK LCAPW.CORPUS-QUERY
        _LCAP-WORK LCAPW.SCOPED-QUERY LSSQR.QUERY !
    _LCAP-WORK LCAPW.QUERY-PAGE
        _LCAP-WORK LCAPW.SCOPED-QUERY LSSQR.PAGE !
    _LCAP-WORK LCAPW.SCOPED-QUERY
        LIBRARY-SCOPED-QUERY-REQUEST-VALID? ;

: _LCAP-QUERY-RESULT  ( -- status )
    _LCAP-WORK LCAPW.QUERY-PAGE LIBRARY-CORPUS-PAGE-VALID? 0= IF
        CBUILD-S-VALUE _LCAP-CONSTRUCTION-FAIL EXIT
    THEN
    _LCAP-WORK LCAPW.QUERY-PAGE LIBQP.COUNT @ DUP 0<
    OVER _LCAP-WORK LCAPW.LIMIT @ > OR IF
        DROP CBUILD-S-VALUE _LCAP-CONSTRUCTION-FAIL EXIT
    THEN
    _LCAP-WORK LCAPW.COUNT !
    5 _LCAP-RESULT-BEGIN DUP 0= IF
        DROP CBUILD-S-NOMEM _LCAP-CONSTRUCTION-FAIL EXIT
    THEN DROP
    S" collection" 0 _LCAP-WORK LCAPW.ROOT @ _LCAP-SLOT
        _LCAP-WORK LCAPW.SCOPED-QUERY LSSQR.SCOPE LSECS.COLLECTION
        SWAP _LCAP-RID-RESOURCE!
    S" collection_domain_revision" 1
        _LCAP-WORK LCAPW.ROOT @ _LCAP-SLOT
        _LCAP-WORK LCAPW.SCOPED-QUERY LSSQR.SCOPE
            LSECS.DOMAIN-REVISION @ SWAP _LCAP-INT!
    S" request_digest" 2 _LCAP-WORK LCAPW.ROOT @ _LCAP-SLOT
        _LCAP-WORK LCAPW.SCOPED-QUERY LSSQR.SCOPE
            LSECS.REQUEST-SEAL
        SWAP _LCAP-WORK LCAPW.HEX0 _LCAP-DIGEST-STRING!
    S" documents" 3 _LCAP-WORK LCAPW.ROOT @ _LCAP-SLOT
        DUP _LCAP-WORK LCAPW.NESTED !
        _LCAP-WORK LCAPW.COUNT @ SWAP _LCAP-LIST-VALUE!
    _LCAP-WORK LCAPW.COUNT @ 0 ?DO
        I _LCAP-WORK LCAPW.QUERY-PAGE LIBRARY-CORPUS-PAGE-ROW
        I _LCAP-WORK LCAPW.NESTED @ CV-LIST-NTH
        OVER LIBRARY-QUERY-SUMMARY-VALID? 0= IF
            2DROP CBUILD-S-VALUE _LCAP-BUILD-FAIL!
        ELSE
            _LCAP-ROW-VALUE!
        THEN
    LOOP
    S" next" 4 _LCAP-WORK LCAPW.ROOT @ _LCAP-SLOT
    _LCAP-WORK LCAPW.QUERY-PAGE LIBQP.CONTINUATION
        LIBRARY-QUERY-CONTINUATION-HAS-AFTER? IF
        _LCAP-WORK LCAPW.QUERY-PAGE LIBQP.CONTINUATION
            SWAP _LCAP-CURSOR-VALUE!
    ELSE
        _LCAP-NULL!
    THEN
    _LCAP-QUERY-OUT-SCHEMA _LCAP-RESULT-PUBLISH ;

: _LCAP-DOCUMENT-QUERY-BODY  ( -- status )
    _LCAP-QUERY-PREPARE 0= IF _LCAP-INVALID-ARGS EXIT THEN
    _LCAP-REQUIRE-READY DUP IF
        _LCAP-REQUEST _LCAP-SERVICE>CBUS EXIT
    THEN DROP
    _LCAP-WORK LCAPW.HAS-AFTER @ IF
        _LCAP-WORK LCAPW.SCOPED-QUERY
            _LAPP-SERVICE _LAPP-SERVICE-WORK
            LIBRARY-SERVICE-COLLECTION-DOCUMENTS-AFTER
    ELSE
        _LCAP-WORK LCAPW.SCOPED-QUERY
            _LAPP-SERVICE _LAPP-SERVICE-WORK
            LIBRARY-SERVICE-COLLECTION-DOCUMENTS-FIRST
    THEN
    DUP IF _LCAP-REQUEST _LCAP-SERVICE>CBUS EXIT THEN DROP
    _LCAP-QUERY-RESULT ;

:NONAME  ( request instance -- status )
    ['] _LCAP-DOCUMENT-QUERY-BODY _LCAP-HANDLER-RUN ;
