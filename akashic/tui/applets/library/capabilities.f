    _LCAP-WORK LCAPW.READ-ENTRY LIBE.ID
    _LCAP-WORK LCAPW.SCOPED-READ LSSRR.RID RID= 0= IF 0 EXIT THEN
    _LCAP-WORK LCAPW.READ-ENTRY LIBE.DOMAIN-REVISION @
    _LCAP-WORK LCAPW.SCOPED-READ LSSRR.EXPECTED-DOMAIN @
        <> IF 0 EXIT THEN
    _LCAP-WORK LCAPW.READ-DESCRIPTOR
        LIBPA-CONTENT-DESCRIPTOR-VALID? 0= IF 0 EXIT THEN
    _LCAP-WORK LCAPW.SCOPED-READ LSSRR.CONTENT-U @ DUP 0<
    OVER LIBRARY-CAPABILITY-READ-CONTENT-MAX > OR IF
        DROP 0 EXIT
    THEN
    DUP _LCAP-WORK LCAPW.READ-ENTRY LIBE.CONTENT-U @ <> IF
        DROP 0 EXIT
    THEN
    DUP _LCAP-WORK LCAPW.READ-DESCRIPTOR
        LIBPA-CONTENT-SIZE@ <> IF DROP 0 EXIT THEN
    _LCAP-WORK LCAPW.CONTENT SWAP UTF8-VALID? 0= IF 0 EXIT THEN
    _LCAP-WORK LCAPW.READ-ENTRY LIBE.KIND @
        LIB-KIND-MANAGED-DOCUMENT <> IF 0 EXIT THEN
    _LCAP-WORK LCAPW.READ-ENTRY LIBE.LIFECYCLE @
        LIB-LIFECYCLE-ACTIVE <> IF 0 EXIT THEN
    _LCAP-WORK LCAPW.READ-ENTRY LIBE.MEDIA @ DUP
        LIB-MEDIA-TEXT-PLAIN =
    SWAP LIB-MEDIA-TEXT-MARKDOWN = OR 0= IF 0 EXIT THEN
    _LCAP-WORK LCAPW.READ-ENTRY LIBE.CONTENT-DIGEST
    _LCAP-WORK LCAPW.READ-DESCRIPTOR LIBPA-CONTENT-DIGEST@
        SHA3-256-COMPARE ;

