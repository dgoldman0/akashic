        DROP 0 EXIT
    THEN
    CV-DATA@ _LCAP-WORK LCAPW.NESTED @
        LIBQC.FIRST-ORDER-SEQUENCE !
    S" first_resource" _LCAP-MAP-ARG
        _LCAP-WORK LCAPW.REF0 _LCAP-R0@ 0= IF 0 EXIT THEN
    _LCAP-WORK LCAPW.REF0 RREF.ID
        _LCAP-WORK LCAPW.NESTED @ LIBQC.FIRST-RID RID-COPY
    S" last_order_sequence" _LCAP-MAP-ARG DUP 0= IF
