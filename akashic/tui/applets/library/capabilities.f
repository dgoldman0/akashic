    _LCAP-COLLECTION-ARGS 0= IF _LCAP-INVALID-ARGS EXIT THEN
    _LAPP-ENSURE-PROVISIONED DUP IF
        _LCAP-REQUEST _LCAP-SERVICE>CBUS EXIT
    THEN DROP
    _LCAP-COLLECTION-PREPARE DUP IF
        _LCAP-REQUEST _LCAP-SERVICE>CBUS EXIT
    THEN DROP
    _LCAP-COLLECTION-REQUEST!
    _LCAP-COLLECTION-RESULT DUP CBUS-S-OK <> IF EXIT THEN DROP
    _LCAP-WORK LCAPW.COLLECTION-WRITE-REQUEST
        _LAPP-SERVICE _LAPP-SERVICE-WORK
        LIBRARY-SERVICE-CREATE-COLLECTION
    DUP IF _LCAP-REQUEST _LCAP-SERVICE>CBUS EXIT THEN DROP
    _LCAP-WORK LCAPW.COLLECTION-RESULT LIBC.ID
    _LCAP-WORK LCAPW.COLLECTION LIBC.ID RID= 0= IF
        LIBRARY-SERVICE-S-CONFLICT
            _LCAP-REQUEST _LCAP-SERVICE>CBUS EXIT
    THEN
    \ The service operation lookup intentionally returns the current object.
    \ A create retry is exact only while that object is still the initial
    \ revision; after any collection replacement, the original create call is
    \ historical and must not be reported as a fresh no-effect success.
    _LCAP-WORK LCAPW.COLLECTION-RESULT LIBC.REVISION @
    _LCAP-WORK LCAPW.COLLECTION LIBC.REVISION @ <> IF
        LIBRARY-SERVICE-S-CONFLICT
            _LCAP-REQUEST _LCAP-SERVICE>CBUS EXIT
    THEN
    _LCAP-WORK LCAPW.COLLECTION-RESULT LIBC.REVISION @
        _LCAP-WORK LCAPW.CHILD @ _LCAP-PATCH-INT 0= IF
        CBUILD-S-VALUE _LCAP-CONSTRUCTION-FAIL EXIT
    THEN
    _LCAP-WORK LCAPW.COLLECTION-WRITE-REQUEST
        LSCWR.LOGICAL-GENERATION @ _LCAP-PATCH-LOGICAL 0= IF
        CBUILD-S-VALUE _LCAP-CONSTRUCTION-FAIL EXIT
    THEN
    _LCAP-WORK LCAPW.COLLECTION-WRITE-REQUEST LSCWR.CHANGED @
        _LCAP-WORK LCAPW.TEMP !
    _LCAP-COLLECTION-CREATE-OUT-SCHEMA _LCAP-RESULT-PUBLISH
    DUP CBUS-S-OK <> IF EXIT THEN DROP
    _LCAP-WORK LCAPW.TEMP @ IF
        CBUS-S-OK
    ELSE
        CBUS-S-NO-EFFECT
    THEN ;

