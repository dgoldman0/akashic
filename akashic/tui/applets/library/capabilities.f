    LIBRARY-QUERY-CONTINUATION-F-READY
    LIBRARY-QUERY-CONTINUATION-F-ROWS OR
    LIBRARY-QUERY-CONTINUATION-F-AFTER OR
        _LCAP-WORK LCAPW.NESTED @ LIBQC.FLAGS !
