: _LCAP-DOCUMENT-CREATE-BODY  ( -- status )
    _LCAP-DOCUMENT-ARGS 0= IF _LCAP-INVALID-ARGS EXIT THEN
    _LAPP-ENSURE-PROVISIONED DUP IF
        _LCAP-REQUEST _LCAP-SERVICE>CBUS EXIT
    THEN DROP
    _LCAP-DOCUMENT-PREPARE DUP IF
        _LCAP-REQUEST _LCAP-SERVICE>CBUS EXIT
    THEN DROP
    _LCAP-DOCUMENT-REQUEST!
    _LCAP-DOCUMENT-RESULT DUP CBUS-S-OK <> IF EXIT THEN DROP
    _LCAP-WORK LCAPW.DOCUMENT-CREATE-REQUEST
        _LAPP-SERVICE _LAPP-SERVICE-WORK
        LIBRARY-SERVICE-CREATE-MANAGED
    DUP IF _LCAP-REQUEST _LCAP-SERVICE>CBUS EXIT THEN DROP
    \ Generic Library replay follows the operation receipt and may return an
    \ authoritative object even when a caller proposed another RID.  This
    \ capability derives both identities from one invocation, so accepting
    \ such a collision would mix a proposed resource with authoritative
    \ revision/digest fields in the preflighted result graph.
    _LCAP-WORK LCAPW.DOCUMENT-RESULT LIBE.ID
    _LCAP-WORK LCAPW.DOCUMENT-ENTRY LIBE.ID RID= 0= IF
        LIBRARY-SERVICE-S-IDEMPOTENCY-MISMATCH
            _LCAP-REQUEST _LCAP-SERVICE>CBUS EXIT
    THEN
    _LCAP-WORK LCAPW.DOCUMENT-RESULT LIBE.DOMAIN-REVISION @
        _LCAP-WORK LCAPW.CHILD @ _LCAP-PATCH-INT 0= IF
        CBUILD-S-VALUE _LCAP-CONSTRUCTION-FAIL EXIT
    THEN
    _LCAP-WORK LCAPW.DOCUMENT-CREATE-REQUEST
        LSDCR.LOGICAL-GENERATION @ _LCAP-PATCH-LOGICAL 0= IF
        CBUILD-S-VALUE _LCAP-CONSTRUCTION-FAIL EXIT
    THEN
    _LCAP-WORK LCAPW.DOCUMENT-RESULT LIBE.CONTENT-DIGEST
        _LCAP-WORK LCAPW.NESTED @ _LCAP-PATCH-DIGEST 0= IF
        CBUILD-S-VALUE _LCAP-CONSTRUCTION-FAIL EXIT
    THEN
    _LCAP-WORK LCAPW.DOCUMENT-CREATE-REQUEST LSDCR.CHANGED @
        _LCAP-WORK LCAPW.TEMP !
    _LCAP-DOCUMENT-CREATE-OUT-SCHEMA _LCAP-RESULT-PUBLISH
    DUP CBUS-S-OK <> IF EXIT THEN DROP
    _LCAP-WORK LCAPW.TEMP @ IF
        CBUS-S-OK
    ELSE
        CBUS-S-NO-EFFECT
    THEN ;

