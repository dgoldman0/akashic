    S" fingerprint" _LCAP-MAP-ARG
        _LCAP-WORK LCAPW.NESTED @ LIBQC.FINGERPRINT
        _LCAP-H64@ 0= IF 0 EXIT THEN
    S" observed_logical_generation" _LCAP-MAP-ARG DUP 0= IF
        DROP 0 EXIT
    THEN
    CV-DATA@ _LCAP-WORK LCAPW.NESTED @
        LIBQC.OBSERVED-LOGICAL-GENERATION !
