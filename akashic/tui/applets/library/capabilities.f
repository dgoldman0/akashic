: _LCAP-BUILD-FAIL!  ( status -- )
    DUP 0= IF DROP EXIT THEN
    _LCAP-WORK LCAPW.BUILD-STATUS @ IF DROP EXIT THEN
    _LCAP-WORK LCAPW.BUILD-STATUS ! ;

: _LCAP-RESULT-BEGIN  ( field-count -- root|0 )
    _LCAP-WORK LCAPW.BUILDER CVB-BEGIN-MAP
    DUP IF _LCAP-BUILD-FAIL! 0 EXIT THEN DROP
    _LCAP-WORK LCAPW.BUILDER CVB-CANDIDATE
    DUP _LCAP-WORK LCAPW.ROOT ! ;

