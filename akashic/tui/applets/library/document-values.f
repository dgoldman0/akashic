\ Initial managed-document/capture draft
\ ---------------------------------------------------------------------

  0 CONSTANT _LSDID-ID
 32 CONSTANT _LSDID-OPERATION-KEY
 64 CONSTANT _LSDID-KIND
 72 CONSTANT _LSDID-MEDIA
 80 CONSTANT _LSDID-MUTATION-SEQUENCE
 88 CONSTANT _LSDID-CONTENT-A
 96 CONSTANT _LSDID-CONTENT-U
104 CONSTANT _LSDID-TITLE-U
112 CONSTANT _LSDID-FACTS-A
120 CONSTANT _LSDID-FACTS-U
128 CONSTANT _LSDID-TITLE
256 CONSTANT _LSDID-SUMMARY
_LSDID-SUMMARY LIB-METADATA-SUMMARY-SIZE +
    CONSTANT LIBRARY-DOCUMENT-INITIAL-DRAFT-SIZE

: LSDID.ID                 ( draft -- rid ) _LSDID-ID + ;
: LSDID.OPERATION-KEY      ( draft -- rid ) _LSDID-OPERATION-KEY + ;
: LSDID.KIND               ( draft -- a ) _LSDID-KIND + ;
: LSDID.MEDIA              ( draft -- a ) _LSDID-MEDIA + ;
: LSDID.MUTATION-SEQUENCE  ( draft -- a ) _LSDID-MUTATION-SEQUENCE + ;
: LSDID.CONTENT-A          ( draft -- a ) _LSDID-CONTENT-A + ;
: LSDID.CONTENT-U          ( draft -- a ) _LSDID-CONTENT-U + ;
: LSDID.TITLE-U            ( draft -- a ) _LSDID-TITLE-U + ;
: LSDID.FACTS-A            ( draft -- a ) _LSDID-FACTS-A + ;
: LSDID.FACTS-U            ( draft -- a ) _LSDID-FACTS-U + ;
: LSDID.TITLE              ( draft -- a ) _LSDID-TITLE + ;
: _LSDID.SUMMARY           ( draft -- summary ) _LSDID-SUMMARY + ;

: LSDID-TITLE$  ( draft -- a u )
    DUP LSDID.TITLE SWAP LSDID.TITLE-U @ ;

: LSDID-CONTENT$  ( draft -- a u )
    DUP LSDID.CONTENT-A @ SWAP LSDID.CONTENT-U @ ;

: LIBRARY-DOCUMENT-INITIAL-DRAFT-INIT  ( draft -- )
    DUP LIBRARY-DOCUMENT-INITIAL-DRAFT-SIZE 0 FILL
    DUP 0 SWAP LSDID.FACTS-U !
    DUP 0 SWAP LSDID.FACTS-A !
    _LSDID.SUMMARY LIB-METADATA-SUMMARY-INIT ;

: LSDID-FACTS$  ( draft -- a u )
    DUP LSDID.FACTS-A @ SWAP LSDID.FACTS-U @ ;

: _LSDID-ORIGIN@  ( draft -- origin|0 )
    _LSDID.SUMMARY LIBMS.ORIGIN-A @ ;

: _LIBDV-DRAFT-FACTS?  ( draft -- flag )
    DUP LSDID.KIND @ LIB-KIND-MANAGED-DOCUMENT = IF
        _LSDID.SUMMARY LIBMS.ORIGIN-N @ 0= EXIT
    THEN
    DUP _LSDID.SUMMARY LIBMS.ORIGIN-N @ 1 =
    SWAP _LSDID-ORIGIN@ 0<> AND ;

: LIBRARY-DOCUMENT-INITIAL-DRAFT-FACTS!
  ( facts-a facts-u draft -- service-status )
    >R
    2DUP R@ _LSDID.SUMMARY LIB-METADATA-SUMMARIZE
    DUP IF
        DROP 2DROP
        0 R@ LSDID.FACTS-A !
        0 R@ LSDID.FACTS-U !
        R@ _LSDID.SUMMARY LIB-METADATA-SUMMARY-INIT
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    DROP
    DUP R@ LSDID.FACTS-U !
    SWAP R@ LSDID.FACTS-A !
    DROP R> DROP _LIBDV-S-OK ;

: LIBRARY-DOCUMENT-INITIAL-DRAFT-VALID?  ( draft -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIBRARY-DOCUMENT-INITIAL-DRAFT-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LSDID.ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LSDID.OPERATION-KEY RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LSDID.ID OVER LSDID.OPERATION-KEY RID= IF DROP 0 EXIT THEN
    DUP LSDID.KIND @ OVER LSDID.MEDIA @
        _LIBDV-KIND-MEDIA? 0= IF DROP 0 EXIT THEN
    DUP LSDID.MUTATION-SEQUENCE @ DUP 0> SWAP
        _LIBDV-MAX-SIGNED <= AND 0= IF DROP 0 EXIT THEN
    DUP LSDID.TITLE-U @ DUP 1 <
        SWAP LIB-TITLE-MAX > OR IF DROP 0 EXIT THEN
    DUP LSDID.TITLE LIB-TITLE-MAX
        2 PICK LSDID.TITLE-U @ 0 _LIBDV-TEXT-SLOT? 0= IF
        DROP 0 EXIT
    THEN
    DUP LSDID.CONTENT-U @ DUP 0<
        SWAP LIB-CONTENT-LENGTH-MAX > OR IF DROP 0 EXIT THEN
    DUP LSDID.CONTENT-U @ 0>
    OVER LSDID.CONTENT-A @ 0= AND IF DROP 0 EXIT THEN
    DUP LSDID-CONTENT$ MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LSDID-CONTENT$ UTF8-VALID? 0= IF DROP 0 EXIT THEN
    DUP LSDID-CONTENT$
    2 PICK LIBRARY-DOCUMENT-INITIAL-DRAFT-SIZE
        MSPAN-OVERLAP? IF DROP 0 EXIT THEN
    DUP LSDID.FACTS-U @ DUP 0<
        SWAP LIB-METADATA-LENGTH-MAX > OR IF DROP 0 EXIT THEN
    DUP LSDID.FACTS-A @ 0=
    OVER LSDID.FACTS-U @ 0<> AND IF DROP 0 EXIT THEN
    DUP LSDID-FACTS$ MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LSDID-FACTS$
    2 PICK LIBRARY-DOCUMENT-INITIAL-DRAFT-SIZE
        MSPAN-OVERLAP? 0= NIP ;

: _LIBDV-PREPARE-INITIAL-ARGS?
  ( draft entry content expected-kind -- flag )
    >R
    2 PICK LIBRARY-DOCUMENT-INITIAL-DRAFT-VALID? 0= IF
        _LIBDV-DROP3 R> DROP 0 EXIT
    THEN
    2 PICK LSDID.KIND @ R@ <> IF
        _LIBDV-DROP3 R> DROP 0 EXIT
    THEN
    OVER LIB-ENTRY-SIZE _LIBDV-SPAN? 0= IF
        _LIBDV-DROP3 R> DROP 0 EXIT
    THEN
    DUP LIB-CONTENT-SIZE _LIBDV-SPAN? 0= IF
        _LIBDV-DROP3 R> DROP 0 EXIT
    THEN
    2 PICK LIBRARY-DOCUMENT-INITIAL-DRAFT-SIZE
    3 PICK LIB-ENTRY-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP3 R> DROP 0 EXIT
    THEN
    2 PICK LIBRARY-DOCUMENT-INITIAL-DRAFT-SIZE
    2 PICK LIB-CONTENT-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP3 R> DROP 0 EXIT
    THEN
    OVER LIB-ENTRY-SIZE
    2 PICK LIB-CONTENT-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP3 R> DROP 0 EXIT
    THEN
    2 PICK LSDID-CONTENT$
    3 PICK LIB-ENTRY-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP3 R> DROP 0 EXIT
    THEN
    2 PICK LSDID-CONTENT$
    2 PICK LIB-CONTENT-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP3 R> DROP 0 EXIT
    THEN
    2 PICK LSDID-FACTS$
    4 PICK LIB-ENTRY-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP3 R> DROP 0 EXIT
    THEN
    2 PICK LSDID-FACTS$
    3 PICK LIB-CONTENT-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP3 R> DROP 0 EXIT
    THEN
    _LIBDV-DROP3 R> DROP -1 ;

: _LIBDV-CAPTURE-RECEIPT!  ( draft entry -- status )
    >R
    DUP _LSDID-ORIGIN@ DUP LIBO.KIND @
    CASE
        LIB-ORIGIN-VFS-SNAPSHOT OF
            LIB-IMPORT-VFS-SNAPSHOT R@ LIBE.RECEIPT LIBR.METHOD !
            DUP LIBO.VFS LIBV.DIGEST-KIND @
                R@ LIBE.RECEIPT LIBR.ORIGIN-DIGEST-KIND !
            DUP LIBO.VFS LIBV.CONTENT-DIGEST
                R@ LIBE.RECEIPT LIBR.ORIGIN-STATE-DIGEST RID-COPY
            LIB-VFS-SOURCE-OWNER$
            DUP R@ LIBE.RECEIPT LIBR.SOURCE-OWNER-U !
            R@ LIBE.RECEIPT LIBR.SOURCE-OWNER SWAP MOVE
            LIB-VFS-IMPORT-CONTRACT$
                R@ LIBE.RECEIPT LIBR.IMPORT-CONTRACT-DIGEST
                SHA3-256-HASH
            DROP
        ENDOF
        LIB-ORIGIN-SEMANTIC OF
            LIB-IMPORT-SEMANTIC-SNAPSHOT
                R@ LIBE.RECEIPT LIBR.METHOD !
            DUP LIBO.SEMANTIC QLOC.DOMAIN-REVISION @
                R@ LIBE.RECEIPT LIBR.ORIGIN-REVISION !
            DUP LIBO.SEMANTIC QLOC.DIGEST-KIND @
                R@ LIBE.RECEIPT LIBR.ORIGIN-DIGEST-KIND !
            DUP LIBO.SEMANTIC QLOC.STATE-DIGEST
                R@ LIBE.RECEIPT LIBR.ORIGIN-STATE-DIGEST RID-COPY
            DUP LIBO.SEMANTIC QLOC-OWNER$
            DUP R@ LIBE.RECEIPT LIBR.SOURCE-OWNER-U !
            R@ LIBE.RECEIPT LIBR.SOURCE-OWNER SWAP MOVE
            DUP LIBO.SEMANTIC QLOC-PROJECTION$
                R@ LIBE.RECEIPT LIBR.IMPORT-CONTRACT-DIGEST
                SHA3-256-HASH
            DROP
        ENDOF
        DROP 2DROP R> DROP _LIBDV-S-INVALID EXIT
    ENDCASE
    DUP _LSDID-ORIGIN@ LIB-ORIGIN-SIZE
        R@ LIBE.RECEIPT LIBR.LOCATOR-DIGEST SHA3-256-HASH
    DROP R> DROP _LIBDV-S-OK ;

: _LIBDV-PREPARE-INITIAL-CONTENT  ( draft content -- status )
    >R
    R@ LIB-CONTENT-INIT
    DUP LSDID.ID R@ LIBCT.ID RID-COPY
    1 R@ LIBCT.DOMAIN-REVISION !
    1 R@ LIBCT.CONTENT-REVISION !
    DUP LSDID.KIND @ R@ LIBCT.KIND !
    DUP LSDID.MEDIA @ R@ LIBCT.MEDIA !
    DUP LSDID.CONTENT-A @ R@ LIBCT.DATA-A !
    DUP LSDID.CONTENT-U @ R@ LIBCT.DATA-U !
    R@ LIB-CONTENT-DIGEST!
    DUP IF
        DROP R@ LIB-CONTENT-INIT
        DROP R> DROP _LIBDV-S-INVALID EXIT
    THEN
    DROP DROP R> DROP _LIBDV-S-OK ;

: _LIBDV-PREPARE-INITIAL-ENTRY  ( draft content entry -- status )
    >R
    R@ LIB-ENTRY-INIT
    OVER LSDID.ID R@ LIBE.ID RID-COPY
    1 R@ LIBE.DOMAIN-REVISION !
    OVER LSDID.KIND @ R@ LIBE.KIND !
    LIB-LIFECYCLE-ACTIVE R@ LIBE.LIFECYCLE !
    OVER LSDID.MEDIA @ R@ LIBE.MEDIA !
    1 R@ LIBE.CURRENT-CONTENT-REVISION !
    1 R@ LIBE.OLDEST-CONTENT-REVISION !
    OVER LSDID.CONTENT-U @ R@ LIBE.CONTENT-U !
    DUP LIBCT.DIGEST R@ LIBE.CONTENT-DIGEST RID-COPY
    OVER LSDID.MUTATION-SEQUENCE @
        DUP R@ LIBE.MUTATION-SEQUENCE !
        DUP R@ LIBE.CREATED-VALUE !
        R@ LIBE.MODIFIED-VALUE !
    LIB-CLOCK-MUTATION-SEQUENCE R@ LIBE.CREATED-CLOCK !
    LIB-CLOCK-MUTATION-SEQUENCE R@ LIBE.MODIFIED-CLOCK !
    OVER LSDID.TITLE-U @ R@ LIBE.TITLE-U !
    OVER LSDID.TITLE R@ LIBE.TITLE
        3 PICK LSDID.TITLE-U @ MOVE
    OVER LSDID.KIND @ LIB-KIND-CAPTURE = IF
        LIB-CLOCK-MUTATION-SEQUENCE R@ LIBE.IMPORTED-CLOCK !
        OVER LSDID.MUTATION-SEQUENCE @ R@ LIBE.IMPORTED-VALUE !
    THEN
    OVER LSDID.OPERATION-KEY
        R@ LIBE.RECEIPT LIBR.OPERATION-KEY RID-COPY
    1 R@ LIBE.RECEIPT LIBR.INITIAL-CONTENT-REVISION !
    OVER LSDID.CONTENT-U @
        R@ LIBE.RECEIPT LIBR.INITIAL-CONTENT-U !
    OVER LSDID.MEDIA @ R@ LIBE.RECEIPT LIBR.INITIAL-MEDIA !
    DUP LIBCT.DIGEST
        R@ LIBE.RECEIPT LIBR.INITIAL-CONTENT-DIGEST RID-COPY
    OVER LSDID.KIND @ LIB-KIND-MANAGED-DOCUMENT = IF
        LIB-IMPORT-CREATED R@ LIBE.RECEIPT LIBR.METHOD !
    ELSE
        OVER R@ _LIBDV-CAPTURE-RECEIPT!
        DUP IF
            DROP 2DROP R@ LIB-ENTRY-INIT
            R> DROP _LIBDV-S-INVALID EXIT
        THEN DROP
    THEN
    OVER _LSDID.SUMMARY R@ LIB-METADATA-SUMMARY-APPLY
    DUP IF
        DROP 2DROP R@ LIB-ENTRY-INIT
        R> DROP _LIBDV-S-INVALID EXIT
    THEN DROP
    R@ LIB-ENTRY-REQUEST-SEAL!
    DUP IF
        DROP 2DROP R@ LIB-ENTRY-INIT
        R> DROP _LIBDV-S-INVALID EXIT
    THEN DROP
    R@ LIB-ENTRY-VALID?
    OVER LIB-CONTENT-VALID? AND 0= IF
        2DROP R@ LIB-ENTRY-INIT
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    2DROP R> DROP _LIBDV-S-OK ;

: _LIBDV-PREPARE-INITIAL  ( draft entry content -- status )
    >R
    OVER LSDID-FACTS$
    3 PICK _LSDID.SUMMARY LIB-METADATA-SUMMARIZE
    DUP IF
        DROP DUP LIB-ENTRY-INIT
        R@ LIB-CONTENT-INIT
        2DROP R> DROP _LIBDV-S-INVALID EXIT
    THEN DROP
    OVER _LIBDV-DRAFT-FACTS? 0= IF
        DUP LIB-ENTRY-INIT
        R@ LIB-CONTENT-INIT
        2DROP R> DROP _LIBDV-S-INVALID EXIT
    THEN
    OVER R@ _LIBDV-PREPARE-INITIAL-CONTENT
    DUP IF
        OVER LIB-ENTRY-INIT
        R@ LIB-CONTENT-INIT
        NIP NIP R> DROP EXIT
    THEN DROP
    R@ SWAP _LIBDV-PREPARE-INITIAL-ENTRY
    R> DROP ;
: LIBRARY-SERVICE-PREPARE-MANAGED-CREATE
  ( draft entry content -- service-status )
    2 PICK 2 PICK 2 PICK LIB-KIND-MANAGED-DOCUMENT
        _LIBDV-PREPARE-INITIAL-ARGS? 0= IF
        _LIBDV-DROP3 _LIBDV-S-INVALID EXIT
    THEN
    _LIBDV-PREPARE-INITIAL ;

: LIBRARY-SERVICE-PREPARE-CAPTURE-IMPORT
  ( draft entry content -- service-status )
    2 PICK 2 PICK 2 PICK LIB-KIND-CAPTURE
        _LIBDV-PREPARE-INITIAL-ARGS? 0= IF
        _LIBDV-DROP3 _LIBDV-S-INVALID EXIT
    THEN
    _LIBDV-PREPARE-INITIAL ;

\ ---------------------------------------------------------------------
\ Complete mutable metadata value
\ ---------------------------------------------------------------------
\ Identity, content, clocks, lifecycle, origin, and receipt are deliberately
\ absent.  INHERIT is the exact title-only path used by the applet; REPLACE
\ supplies a caller-owned canonical fact stream and replaces its PBLOB.

1 CONSTANT LIBRARY-METADATA-INHERIT
2 CONSTANT LIBRARY-METADATA-REPLACE

  0 CONSTANT _LIBDM-TITLE-U
  8 CONSTANT _LIBDM-MODE
 16 CONSTANT _LIBDM-FACTS-A
 24 CONSTANT _LIBDM-FACTS-U
 32 CONSTANT _LIBDM-TITLE
160 CONSTANT _LIBDM-SUMMARY
_LIBDM-SUMMARY LIB-METADATA-SUMMARY-SIZE +
    CONSTANT LIBRARY-DOCUMENT-METADATA-SIZE

: LIBDM.TITLE-U  ( metadata -- a ) _LIBDM-TITLE-U + ;
: LIBDM.MODE     ( metadata -- a ) _LIBDM-MODE + ;
: LIBDM.FACTS-A  ( metadata -- a ) _LIBDM-FACTS-A + ;
: LIBDM.FACTS-U  ( metadata -- a ) _LIBDM-FACTS-U + ;
: LIBDM.TITLE    ( metadata -- a ) _LIBDM-TITLE + ;
: _LIBDM.SUMMARY ( metadata -- summary ) _LIBDM-SUMMARY + ;

: LIBDM-FACTS$  ( metadata -- a u )
    DUP LIBDM.FACTS-A @ SWAP LIBDM.FACTS-U @ ;

: LIBRARY-DOCUMENT-METADATA-INIT  ( metadata -- )
    DUP LIBRARY-DOCUMENT-METADATA-SIZE 0 FILL
    LIBRARY-METADATA-INHERIT SWAP LIBDM.MODE ! ;

: LIBRARY-DOCUMENT-METADATA-FACTS!
  ( facts-a facts-u metadata -- service-status )
    >R
    2DUP R@ _LIBDM.SUMMARY LIB-METADATA-SUMMARIZE
    DUP IF
        DROP 2DROP
        0 R@ LIBDM.FACTS-A !
        0 R@ LIBDM.FACTS-U !
        LIBRARY-METADATA-INHERIT R@ LIBDM.MODE !
        R@ _LIBDM.SUMMARY LIB-METADATA-SUMMARY-INIT
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    DROP
    DUP R@ LIBDM.FACTS-U !
    SWAP R@ LIBDM.FACTS-A !
    DROP
    LIBRARY-METADATA-REPLACE R@ LIBDM.MODE !
    R> DROP _LIBDV-S-OK ;

: LIBRARY-DOCUMENT-METADATA-VALID?  ( metadata -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIBRARY-DOCUMENT-METADATA-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LIBDM.TITLE LIB-TITLE-MAX
        2 PICK LIBDM.TITLE-U @ 0 _LIBDV-TEXT-SLOT? 0= IF
        DROP 0 EXIT
    THEN
    DUP LIBDM.MODE @ LIBRARY-METADATA-INHERIT = IF
        DUP LIBDM.FACTS-A @ 0=
        OVER LIBDM.FACTS-U @ 0= AND
        SWAP _LIBDM.SUMMARY LIB-METADATA-SUMMARY-SIZE
            _LIBDV-ZERO? AND EXIT
    THEN
    DUP LIBDM.MODE @ LIBRARY-METADATA-REPLACE <> IF DROP 0 EXIT THEN
    DUP LIBDM.FACTS-U @ DUP 0<
        SWAP LIB-METADATA-LENGTH-MAX > OR IF DROP 0 EXIT THEN
    DUP LIBDM.FACTS-A @ 0=
        OVER LIBDM.FACTS-U @ 0<> AND IF DROP 0 EXIT THEN
    DUP LIBDM-FACTS$ MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LIBDM-FACTS$
    2 PICK LIBRARY-DOCUMENT-METADATA-SIZE
        MSPAN-OVERLAP? 0= NIP ;

: LIBRARY-DOCUMENT-METADATA-FROM-ENTRY
  ( entry metadata -- service-status )
    >R
    DUP LIB-ENTRY-VALID? 0= IF
        DROP R> DROP _LIBDV-S-INVALID EXIT
    THEN
    R@ 0= IF DROP R> DROP _LIBDV-S-INVALID EXIT THEN
    R@ LIBRARY-DOCUMENT-METADATA-SIZE
        MSPAN-NONWRAPPING? 0= IF
        DROP R> DROP _LIBDV-S-INVALID EXIT
    THEN
    DUP LIB-ENTRY-SIZE
    R@ LIBRARY-DOCUMENT-METADATA-SIZE MSPAN-OVERLAP? IF
        DROP R> DROP _LIBDV-S-INVALID EXIT
    THEN
    R@ LIBRARY-DOCUMENT-METADATA-INIT
    DUP LIBE.TITLE-U @ R@ LIBDM.TITLE-U !
    DUP LIBE.TITLE R@ LIBDM.TITLE LIB-TITLE-MAX MOVE
    DROP
    R@ LIBRARY-DOCUMENT-METADATA-VALID? 0= IF
        R@ LIBRARY-DOCUMENT-METADATA-INIT
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    R> DROP _LIBDV-S-OK ;

