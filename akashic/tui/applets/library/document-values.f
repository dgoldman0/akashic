\ =====================================================================
\  document-values.f - Canonical Desk/Library document value preparation
\ =====================================================================
\  These caller-owned values are Library-domain inputs, not persistence
\  records.  This module centralizes revision, clock, receipt, provenance,
\  digest, tombstone, and request-seal policy so controllers and projections
\  never manufacture sealed LIB-ENTRY or LIB-CONTENT records themselves.
\
\  The module is applet-local and stateless.  It performs no repository,
\  storage, VFS, query, controller, or UI operation.
\ =====================================================================

PROVIDED akashic-tui-library-document-values

REQUIRE model.f

\ These results intentionally match the service/repository OK and INVALID
\ values.  They remain private so this pure value module does not acquire a
\ dependency on the physical persistence owner.
0 CONSTANT _LIBDV-S-OK
2 CONSTANT _LIBDV-S-INVALID
-1 1 RSHIFT CONSTANT _LIBDV-MAX-SIGNED

: _LIBDV-DROP3  ( x1 x2 x3 -- ) 2DROP DROP ;
: _LIBDV-DROP4  ( x1 x2 x3 x4 -- ) 2DROP 2DROP ;
: _LIBDV-DROP6  ( x1 x2 x3 x4 x5 x6 -- ) 2DROP 2DROP 2DROP ;

: _LIBDV-SPAN?  ( address length -- flag )
    OVER 0= IF NIP 0= EXIT THEN
    MSPAN-NONWRAPPING? ;

: _LIBDV-ZERO?  ( address length -- flag )
    0 ?DO DUP I + C@ IF DROP 0 UNLOOP EXIT THEN LOOP DROP -1 ;

: _LIBDV-TEXT-SLOT?  ( address capacity length allow-empty? -- flag )
    >R
    DUP 0< IF DROP 2DROP R> DROP 0 EXIT THEN
    DUP 2 PICK > IF DROP 2DROP R> DROP 0 EXIT THEN
    DUP 0= R@ 0= AND IF DROP 2DROP R> DROP 0 EXIT THEN
    DUP IF
        2 PICK OVER UTF8-VALID? 0= IF
            DROP 2DROP R> DROP 0 EXIT
        THEN
    THEN
    TUCK - >R + R> _LIBDV-ZERO?
    R> DROP ;

: _LIBDV-KIND-MEDIA?  ( kind media -- flag )
    OVER LIB-KIND-MANAGED-DOCUMENT = IF
        NIP DUP LIB-MEDIA-TEXT-PLAIN =
        SWAP LIB-MEDIA-TEXT-MARKDOWN = OR EXIT
    THEN
    SWAP LIB-KIND-CAPTURE = IF
        DUP LIB-MEDIA-TEXT-PLAIN =
        OVER LIB-MEDIA-TEXT-MARKDOWN = OR
        SWAP LIB-MEDIA-TEXT-CSV = OR
    ELSE
        DROP 0
    THEN ;

: _LIBDV-NEXT-MUTATION?  ( current mutation -- flag )
    >R
    DUP LIBE.MUTATION-SEQUENCE @ R@ < SWAP DROP
    R@ DUP 0> SWAP _LIBDV-MAX-SIGNED <= AND AND
    R> DROP ;

