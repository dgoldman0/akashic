: _LIBDV-CONTENT-NEXT-BASIC?
  ( current data-a data-u next-mutation -- flag )
    3 PICK LIB-ENTRY-VALID? 0= IF _LIBDV-DROP4 0 EXIT THEN
    3 PICK LIBE.LIFECYCLE @ LIB-LIFECYCLE-TOMBSTONED = IF
        _LIBDV-DROP4 0 EXIT
    THEN
    3 PICK LIBE.KIND @ LIB-KIND-MANAGED-DOCUMENT <> IF
        _LIBDV-DROP4 0 EXIT
    THEN
    1 PICK DUP 0< SWAP LIB-CONTENT-LENGTH-MAX > OR IF
        _LIBDV-DROP4 0 EXIT
    THEN
    1 PICK 0> 2 PICK 0= AND IF _LIBDV-DROP4 0 EXIT THEN
    2 PICK 2 PICK MSPAN-NONWRAPPING? 0= IF
        _LIBDV-DROP4 0 EXIT
    THEN
    2 PICK 2 PICK UTF8-VALID? 0= IF _LIBDV-DROP4 0 EXIT THEN
    3 PICK OVER _LIBDV-NEXT-MUTATION? 0= IF
        _LIBDV-DROP4 0 EXIT
    THEN
    _LIBDV-DROP4 -1 ;

: _LIBDV-CONTENT-NEXT-SPANS?
  ( current data-a data-u next-mutation next-entry next-content -- flag )
    1 PICK LIB-ENTRY-SIZE _LIBDV-SPAN? 0= IF
        _LIBDV-DROP6 0 EXIT
    THEN
    DUP LIB-CONTENT-SIZE _LIBDV-SPAN? 0= IF
        _LIBDV-DROP6 0 EXIT
    THEN
    1 PICK LIB-ENTRY-SIZE
    2 PICK LIB-CONTENT-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP6 0 EXIT
    THEN
    5 PICK LIB-ENTRY-SIZE
    3 PICK LIB-ENTRY-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP6 0 EXIT
    THEN
    5 PICK LIB-ENTRY-SIZE
    2 PICK LIB-CONTENT-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP6 0 EXIT
    THEN
    4 PICK 4 PICK
    3 PICK LIB-ENTRY-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP6 0 EXIT
    THEN
    4 PICK 4 PICK
    2 PICK LIB-CONTENT-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP6 0 EXIT
    THEN
    4 PICK 4 PICK
    7 PICK LIB-ENTRY-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP6 0 EXIT
    THEN
    _LIBDV-DROP6 -1 ;

: _LIBDV-PREPARE-CONTENT-VALUE
  ( current data-a data-u next-content -- status )
    >R
    R@ LIB-CONTENT-INIT
    2 PICK LIBE.ID R@ LIBCT.ID RID-COPY
    2 PICK LIBE.DOMAIN-REVISION @ DUP _LIBDV-MAX-SIGNED >= IF
        DROP R@ LIB-CONTENT-INIT _LIBDV-DROP3
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    1+ R@ LIBCT.DOMAIN-REVISION !
    2 PICK LIBE.CURRENT-CONTENT-REVISION @
    DUP _LIBDV-MAX-SIGNED >= IF
        DROP R@ LIB-CONTENT-INIT _LIBDV-DROP3
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    1+ R@ LIBCT.CONTENT-REVISION !
    2 PICK LIBE.KIND @ R@ LIBCT.KIND !
    2 PICK LIBE.MEDIA @ R@ LIBCT.MEDIA !
    OVER R@ LIBCT.DATA-A !
    DUP R@ LIBCT.DATA-U !
    R@ LIB-CONTENT-DIGEST!
    DUP IF
        DROP R@ LIB-CONTENT-INIT _LIBDV-DROP3
        R> DROP _LIBDV-S-INVALID EXIT
    THEN DROP
    R@ LIB-CONTENT-VALID? 0= IF
        R@ LIB-CONTENT-INIT _LIBDV-DROP3
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    _LIBDV-DROP3 R> DROP _LIBDV-S-OK ;

: _LIBDV-PREPARE-CONTENT-ENTRY
  ( current next-content next-mutation next-entry -- status )
    >R
    2 PICK R@ LIB-ENTRY-SIZE MOVE
    OVER LIBCT.DOMAIN-REVISION @ R@ LIBE.DOMAIN-REVISION !
    OVER LIBCT.CONTENT-REVISION @ DUP
        R@ LIBE.CURRENT-CONTENT-REVISION !
    DUP LIB-RETAINED-REVISION-MAX 1- > IF
        LIB-RETAINED-REVISION-MAX 1- -
    ELSE
        DROP 1
    THEN
    R@ LIBE.OLDEST-CONTENT-REVISION !
    OVER LIBCT.DATA-U @ R@ LIBE.CONTENT-U !
    OVER LIBCT.DIGEST R@ LIBE.CONTENT-DIGEST RID-COPY
    DUP R@ LIBE.MUTATION-SEQUENCE !
    LIB-CLOCK-MUTATION-SEQUENCE R@ LIBE.MODIFIED-CLOCK !
    DUP R@ LIBE.MODIFIED-VALUE !
    R@ LIB-ENTRY-VALID? 0= IF
        R@ LIB-ENTRY-INIT _LIBDV-DROP3
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    _LIBDV-DROP3 R> DROP _LIBDV-S-OK ;

: LIBRARY-SERVICE-PREPARE-CONTENT-NEXT
  ( current data-a data-u next-mutation next-entry next-content -- status )
    5 PICK 5 PICK 5 PICK 5 PICK
        _LIBDV-CONTENT-NEXT-BASIC? 0= IF
        _LIBDV-DROP6 _LIBDV-S-INVALID EXIT
    THEN
    5 PICK 5 PICK 5 PICK 5 PICK 5 PICK 5 PICK
        _LIBDV-CONTENT-NEXT-SPANS? 0= IF
        _LIBDV-DROP6 _LIBDV-S-INVALID EXIT
    THEN
    5 PICK 5 PICK 5 PICK 3 PICK
        _LIBDV-PREPARE-CONTENT-VALUE
    DUP IF
        DROP 1 PICK LIB-ENTRY-INIT
        _LIBDV-DROP6 _LIBDV-S-INVALID EXIT
    THEN DROP
    5 PICK 1 PICK 4 PICK 4 PICK
        _LIBDV-PREPARE-CONTENT-ENTRY
    >R _LIBDV-DROP6 R> ;

: LIBRARY-SERVICE-PREPARE-METADATA-NEXT
  ( current metadata next-mutation next-entry -- status )
    >R
    2 PICK LIB-ENTRY-VALID? 0= IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    2 PICK LIBE.LIFECYCLE @ LIB-LIFECYCLE-TOMBSTONED = IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    OVER LIBRARY-DOCUMENT-METADATA-VALID? 0= IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    2 PICK OVER _LIBDV-NEXT-MUTATION? 0= IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    R@ LIB-ENTRY-SIZE _LIBDV-SPAN? 0= IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    2 PICK LIB-ENTRY-SIZE R@ LIB-ENTRY-SIZE
        MSPAN-OVERLAP? IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    OVER LIBRARY-DOCUMENT-METADATA-SIZE R@ LIB-ENTRY-SIZE
        MSPAN-OVERLAP? IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    2 PICK LIB-ENTRY-SIZE
    3 PICK LIBRARY-DOCUMENT-METADATA-SIZE MSPAN-OVERLAP? IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    OVER LIBDM.MODE @ LIBRARY-METADATA-REPLACE = IF
        OVER LIBDM-FACTS$
        R@ LIB-ENTRY-SIZE MSPAN-OVERLAP? IF
            _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
        THEN
        OVER LIBDM-FACTS$
        4 PICK LIB-ENTRY-SIZE MSPAN-OVERLAP? IF
            _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
        THEN
        OVER LIBDM-FACTS$
        3 PICK _LIBDM.SUMMARY LIB-METADATA-SUMMARIZE
        DUP IF
            DROP _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
        THEN DROP
    THEN

    2 PICK R@ LIB-ENTRY-SIZE MOVE
    2 PICK LIBE.DOMAIN-REVISION @ DUP _LIBDV-MAX-SIGNED >= IF
        DROP R@ LIB-ENTRY-INIT _LIBDV-DROP3
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    1+ R@ LIBE.DOMAIN-REVISION !
    DUP R@ LIBE.MUTATION-SEQUENCE !
    LIB-CLOCK-MUTATION-SEQUENCE R@ LIBE.MODIFIED-CLOCK !
    DUP R@ LIBE.MODIFIED-VALUE !
    OVER LIBDM.TITLE-U @ R@ LIBE.TITLE-U !
    OVER LIBDM.TITLE R@ LIBE.TITLE LIB-TITLE-MAX MOVE
    OVER LIBDM.MODE @ LIBRARY-METADATA-REPLACE = IF
        OVER _LIBDM.SUMMARY R@ LIB-METADATA-SUMMARY-APPLY
        DUP IF
            DROP R@ LIB-ENTRY-INIT _LIBDV-DROP3
            R> DROP _LIBDV-S-INVALID EXIT
        THEN DROP
    THEN
    R@ LIB-ENTRY-VALID? 0= IF
        R@ LIB-ENTRY-INIT _LIBDV-DROP3
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    _LIBDV-DROP3 R> DROP _LIBDV-S-OK ;

: LIBRARY-SERVICE-PREPARE-LIFECYCLE-NEXT
  ( current target-lifecycle next-mutation next-entry -- status )
    >R
    2 PICK LIB-ENTRY-VALID? 0= IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    2 PICK LIBE.LIFECYCLE @ LIB-LIFECYCLE-TOMBSTONED = IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    OVER DUP LIB-LIFECYCLE-ACTIVE =
    SWAP LIB-LIFECYCLE-ARCHIVED = OR 0= IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    2 PICK OVER _LIBDV-NEXT-MUTATION? 0= IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    R@ LIB-ENTRY-SIZE _LIBDV-SPAN? 0= IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    2 PICK LIB-ENTRY-SIZE R@ LIB-ENTRY-SIZE
        MSPAN-OVERLAP? IF
        _LIBDV-DROP3 R> DROP _LIBDV-S-INVALID EXIT
    THEN
    2 PICK R@ LIB-ENTRY-SIZE MOVE
    2 PICK LIBE.LIFECYCLE @ 2 PICK = IF
        R@ LIB-ENTRY-VALID? 0= IF
            R@ LIB-ENTRY-INIT _LIBDV-DROP3
            R> DROP _LIBDV-S-INVALID EXIT
        THEN
        _LIBDV-DROP3 R> DROP _LIBDV-S-OK EXIT
    THEN
    2 PICK LIBE.DOMAIN-REVISION @ DUP _LIBDV-MAX-SIGNED >= IF
        DROP R@ LIB-ENTRY-INIT _LIBDV-DROP3
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    1+ R@ LIBE.DOMAIN-REVISION !
    OVER R@ LIBE.LIFECYCLE !
    DUP R@ LIBE.MUTATION-SEQUENCE !
    LIB-CLOCK-MUTATION-SEQUENCE R@ LIBE.MODIFIED-CLOCK !
    DUP R@ LIBE.MODIFIED-VALUE !
    R@ LIB-ENTRY-VALID? 0= IF
        R@ LIB-ENTRY-INIT _LIBDV-DROP3
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    _LIBDV-DROP3 R> DROP _LIBDV-S-OK ;

\ ---------------------------------------------------------------------
\ Retained-content restore
\ ---------------------------------------------------------------------
\ A retained-content fact value is the applet-domain projection of a checked
\ persistence descriptor.  It deliberately contains no segment reference,
\ PBLOB locator, store type, or adapter status.  This keeps value preparation
\ independent of the physical Library owner while still making every field
\ used to derive the next catalog entry explicit and checkable.

  0 CONSTANT _LIBRCF-ID
 32 CONSTANT _LIBRCF-DOMAIN-REVISION
 40 CONSTANT _LIBRCF-CONTENT-REVISION
 48 CONSTANT _LIBRCF-KIND
 56 CONSTANT _LIBRCF-MEDIA
 64 CONSTANT _LIBRCF-DATA-U
 72 CONSTANT _LIBRCF-DIGEST
104 CONSTANT LIBRARY-RETAINED-CONTENT-FACTS-SIZE

: LIBRCF.ID                ( facts -- rid ) _LIBRCF-ID + ;
: LIBRCF.DOMAIN-REVISION   ( facts -- a ) _LIBRCF-DOMAIN-REVISION + ;
: LIBRCF.CONTENT-REVISION  ( facts -- a ) _LIBRCF-CONTENT-REVISION + ;
: LIBRCF.KIND              ( facts -- a ) _LIBRCF-KIND + ;
: LIBRCF.MEDIA             ( facts -- a ) _LIBRCF-MEDIA + ;
: LIBRCF.DATA-U            ( facts -- a ) _LIBRCF-DATA-U + ;
: LIBRCF.DIGEST            ( facts -- digest ) _LIBRCF-DIGEST + ;

: LIBRARY-RETAINED-CONTENT-FACTS-INIT  ( facts -- )
    LIBRARY-RETAINED-CONTENT-FACTS-SIZE 0 FILL ;

: LIBRARY-RETAINED-CONTENT-FACTS-VALID?  ( facts -- flag )
    DUP 0= IF DROP 0 EXIT THEN
    DUP LIBRARY-RETAINED-CONTENT-FACTS-SIZE
        MSPAN-NONWRAPPING? 0= IF DROP 0 EXIT THEN
    DUP LIBRCF.ID RID-PRESENT? 0= IF DROP 0 EXIT THEN
    DUP LIBRCF.DOMAIN-REVISION @ DUP 0> 0= IF
        2DROP 0 EXIT
    THEN
    OVER LIBRCF.CONTENT-REVISION @ < IF DROP 0 EXIT THEN
    DUP LIBRCF.CONTENT-REVISION @ 0> 0= IF DROP 0 EXIT THEN
    DUP LIBRCF.KIND @ OVER LIBRCF.MEDIA @
        _LIBDV-KIND-MEDIA? 0= IF DROP 0 EXIT THEN
    DUP LIBRCF.DATA-U @ DUP 0<
        SWAP LIB-CONTENT-LENGTH-MAX > OR IF DROP 0 EXIT THEN
    LIBRCF.DIGEST RID-PRESENT? ;

: _LIBDV-RESTORE-BASIC?
  ( current retained-facts next-mutation -- flag )
    >R
    OVER LIB-ENTRY-VALID? 0= IF 2DROP R> DROP 0 EXIT THEN
    OVER LIBE.LIFECYCLE @ LIB-LIFECYCLE-TOMBSTONED = IF
        2DROP R> DROP 0 EXIT
    THEN
    OVER LIBE.KIND @ LIB-KIND-MANAGED-DOCUMENT <> IF
        2DROP R> DROP 0 EXIT
    THEN
    DUP LIBRARY-RETAINED-CONTENT-FACTS-VALID? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    OVER LIBE.ID OVER LIBRCF.ID RID= 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    OVER LIBE.KIND @ OVER LIBRCF.KIND @ <> IF
        2DROP R> DROP 0 EXIT
    THEN
    OVER LIBE.MEDIA @ OVER LIBRCF.MEDIA @ <> IF
        2DROP R> DROP 0 EXIT
    THEN
    DUP LIBRCF.DOMAIN-REVISION @
    2 PICK LIBE.DOMAIN-REVISION @ > IF
        2DROP R> DROP 0 EXIT
    THEN
    DUP LIBRCF.CONTENT-REVISION @
    2 PICK LIBE.OLDEST-CONTENT-REVISION @ < IF
        2DROP R> DROP 0 EXIT
    THEN
    DUP LIBRCF.CONTENT-REVISION @
    2 PICK LIBE.CURRENT-CONTENT-REVISION @ >= IF
        2DROP R> DROP 0 EXIT
    THEN
    OVER LIBE.DOMAIN-REVISION @ _LIBDV-MAX-SIGNED >= IF
        2DROP R> DROP 0 EXIT
    THEN
    OVER LIBE.CURRENT-CONTENT-REVISION @
        _LIBDV-MAX-SIGNED >= IF
        2DROP R> DROP 0 EXIT
    THEN
    OVER R@ _LIBDV-NEXT-MUTATION? 0= IF
        2DROP R> DROP 0 EXIT
    THEN
    2DROP R> DROP -1 ;

: _LIBDV-RESTORE-SPANS?
  ( current retained-facts next-mutation next-entry -- flag )
    >R DROP
    OVER LIB-ENTRY-SIZE R@ LIB-ENTRY-SIZE
        MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    DUP LIBRARY-RETAINED-CONTENT-FACTS-SIZE
    R@ LIB-ENTRY-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP 0 EXIT
    THEN
    OVER LIB-ENTRY-SIZE
    2 PICK LIBRARY-RETAINED-CONTENT-FACTS-SIZE
        MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    2DROP R> DROP -1 ;

: LIBRARY-SERVICE-PREPARE-RETAINED-RESTORE
  ( current retained-facts next-mutation next-entry -- service-status )
    3 PICK 3 PICK 3 PICK _LIBDV-RESTORE-BASIC? 0= IF
        _LIBDV-DROP4 _LIBDV-S-INVALID EXIT
    THEN
    DUP LIB-ENTRY-SIZE _LIBDV-SPAN? 0= IF
        _LIBDV-DROP4 _LIBDV-S-INVALID EXIT
    THEN
    3 PICK 3 PICK 3 PICK 3 PICK
        _LIBDV-RESTORE-SPANS? 0= IF
        _LIBDV-DROP4 _LIBDV-S-INVALID EXIT
    THEN
    >R
    2 PICK R@ LIB-ENTRY-SIZE MOVE
    2 PICK LIBE.DOMAIN-REVISION @ 1+
        R@ LIBE.DOMAIN-REVISION !
    2 PICK LIBE.CURRENT-CONTENT-REVISION @ 1+ DUP
        R@ LIBE.CURRENT-CONTENT-REVISION !
    DUP LIB-RETAINED-REVISION-MAX 1- > IF
        LIB-RETAINED-REVISION-MAX 1- -
    ELSE
        DROP 1
    THEN
    R@ LIBE.OLDEST-CONTENT-REVISION !
    OVER LIBRCF.DATA-U @ R@ LIBE.CONTENT-U !
    OVER LIBRCF.DIGEST R@ LIBE.CONTENT-DIGEST RID-COPY
    DUP R@ LIBE.MUTATION-SEQUENCE !
    LIB-CLOCK-MUTATION-SEQUENCE R@ LIBE.MODIFIED-CLOCK !
    DUP R@ LIBE.MODIFIED-VALUE !
    R@ LIB-ENTRY-VALID? 0= IF
        R@ LIB-ENTRY-INIT _LIBDV-DROP3
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    _LIBDV-DROP3 R> DROP _LIBDV-S-OK ;

: LIBRARY-SERVICE-PREPARE-TOMBSTONE-NEXT
  ( current next-mutation next-entry -- status )
    >R
    OVER LIB-ENTRY-VALID? 0= IF
        2DROP R> DROP _LIBDV-S-INVALID EXIT
    THEN
    OVER LIBE.LIFECYCLE @ LIB-LIFECYCLE-TOMBSTONED = IF
        2DROP R> DROP _LIBDV-S-INVALID EXIT
    THEN
    OVER OVER _LIBDV-NEXT-MUTATION? 0= IF
        2DROP R> DROP _LIBDV-S-INVALID EXIT
    THEN
    R@ LIB-ENTRY-SIZE _LIBDV-SPAN? 0= IF
        2DROP R> DROP _LIBDV-S-INVALID EXIT
    THEN
    OVER LIB-ENTRY-SIZE R@ LIB-ENTRY-SIZE MSPAN-OVERLAP? IF
        2DROP R> DROP _LIBDV-S-INVALID EXIT
    THEN
    R@ LIB-ENTRY-INIT
    OVER LIBE.ID R@ LIBE.ID RID-COPY
    OVER LIBE.DOMAIN-REVISION @ DUP _LIBDV-MAX-SIGNED >= IF
        DROP R@ LIB-ENTRY-INIT 2DROP
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    1+ R@ LIBE.DOMAIN-REVISION !
    OVER LIBE.KIND @ R@ LIBE.KIND !
    LIB-LIFECYCLE-TOMBSTONED R@ LIBE.LIFECYCLE !
    LIB-MEDIA-NONE R@ LIBE.MEDIA !
    DUP R@ LIBE.MUTATION-SEQUENCE !
    LIB-CLOCK-MUTATION-SEQUENCE R@ LIBE.DELETED-CLOCK !
    DUP R@ LIBE.DELETED-VALUE !
    OVER LIBE.RECEIPT R@ LIBE.RECEIPT
        LIB-RECEIPT-SIZE MOVE
    R@ LIB-ENTRY-VALID? 0= IF
        R@ LIB-ENTRY-INIT 2DROP
        R> DROP _LIBDV-S-INVALID EXIT
    THEN
    2DROP R> DROP _LIBDV-S-OK ;
