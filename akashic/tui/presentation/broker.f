: _PBR-INIT-PREFLIGHT  ( config broker -- status )
    _PBRI-BROKER ! _PBRI-CONFIG !
    _PBRI-CONFIG @ PRES-BROKER-CONFIG-VALID? 0= IF
        PRES-S-INVALID EXIT
    THEN
    _PBRI-BROKER @ 0= IF PRES-S-INVALID EXIT THEN
    _PBRI-BROKER @ _PRES-CELL-ALIGNED? 0= IF PRES-S-INVALID EXIT THEN
    _PBRI-BROKER @ PRES-SCOPED-BROKER-SIZE
        MSPAN-NONWRAPPING? 0= IF PRES-S-INVALID EXIT THEN
    _PBRI-BROKER @ _PRES-BROKER-VALID? 0= IF PRES-S-INVALID EXIT THEN
    _PBRI-BROKER @ _PBR.MAGIC @ 0<> IF PRES-S-INVALID EXIT THEN
    _PBRI-BROKER @ _PBR.STATE @
        _PBR-STATE-UNINITIALIZED <> IF PRES-S-INVALID EXIT THEN
    _PBRI-BROKER @ _PRES-H.API @ _PBRI-API !
    _PBRI-CONFIG @ PRES-BROKER-C.SCOPE-RECORDS @ _PBRI-RECORDS !
    _PBRI-CONFIG @ PRES-BROKER-C.SCOPE-RECORD-BYTES @
        _PBRI-RECORD-BYTES !
    _PBRI-BROKER @ PRES-SCOPED-BROKER-SIZE
    _PBRI-CONFIG @ PRES-BROKER-CONFIG-SIZE
        MSPAN-OVERLAP? IF PRES-S-INVALID EXIT THEN
    _PBRI-API @ PRES-API-SIZE
    _PBRI-CONFIG @ PRES-BROKER-CONFIG-SIZE
        MSPAN-OVERLAP? IF PRES-S-INVALID EXIT THEN
    _PBRI-API @ PRES-API-SIZE
    _PBRI-BROKER @ PRES-SCOPED-BROKER-SIZE
        MSPAN-OVERLAP? IF PRES-S-INVALID EXIT THEN
    _PBRI-RECORD-BYTES @ IF
        _PBRI-RECORDS @ _PBRI-RECORD-BYTES @
        _PBRI-BROKER @ PRES-SCOPED-BROKER-SIZE
            MSPAN-OVERLAP? IF PRES-S-INVALID EXIT THEN
        _PBRI-RECORDS @ _PBRI-RECORD-BYTES @
        _PBRI-API @ PRES-API-SIZE
            MSPAN-OVERLAP? IF PRES-S-INVALID EXIT THEN
    THEN
    _PBRI-CONFIG @ PRES-BROKER-C.SUPPORTED @ IF
        _PBRI-CONFIG @ PRES-BROKER-C.SCOPE-RECORD-COUNT @
            0= IF PRES-S-CAPACITY EXIT THEN
    THEN
    PRES-S-OK ;

: _PBR-SERVICE-INIT  ( config broker -- status )
    2DUP _PBR-INIT-PREFLIGHT ?DUP IF NIP NIP EXIT THEN
    _PBRI-RECORD-BYTES @ IF
        _PBRI-RECORDS @ _PBRI-RECORD-BYTES @ 0 FILL
    THEN
    OVER PRES-BROKER-C.RESOLVER-XT @ OVER _PBR.RESOLVER-XT !
    OVER PRES-BROKER-C.RESOLVER-CONTEXT @ OVER _PBR.RESOLVER-CTX !
    OVER PRES-BROKER-C.SCOPE-RECORDS @ OVER _PBR.RECORDS !
    OVER PRES-BROKER-C.SCOPE-RECORD-BYTES @ OVER _PBR.RECORD-BYTES !
    OVER PRES-BROKER-C.SCOPE-RECORD-COUNT @ OVER _PBR.RECORD-COUNT !
    OVER PRES-BROKER-C.SUPPORTED @ OVER _PBR.SUPPORTED !
    0 OVER _PBR.LIVE-COUNT !
    0 OVER _PBR.PENDING-COUNT !
    _PBR-BROKER-MAGIC OVER _PBR.MAGIC !
    _PBR-STATE-READY SWAP _PBR.STATE !
    DROP PRES-S-OK ;

: _PBR-SERVICE-FINI  ( broker -- status )
    DUP _PBR-BROKER-VALID? 0= IF DROP PRES-S-INVALID EXIT THEN
    DUP _PBR.STATE @ _PBR-STATE-FINALIZED = IF
        DROP PRES-S-OK EXIT
    THEN
    DUP _PBR.LIVE-COUNT @ OVER _PBR.PENDING-COUNT @ OR IF
        DROP PRES-S-WOULD-BLOCK EXIT
    THEN
    _PBR-STATE-FINALIZED SWAP _PBR.STATE ! PRES-S-OK ;

: _PBR-SERVICE-STATUS  ( broker -- status )
    DUP _PBR-BROKER-VALID? 0= IF DROP PRES-S-INVALID EXIT THEN
    _PBR.STATE @ _PBR-STATE-READY = IF
        PRES-S-OK
    ELSE
        PRES-S-UNAVAILABLE
    THEN ;

: _PBR-SERVICE-STEP  ( work-budget broker -- status more-work? )
    DUP _PBR-BROKER-READY? 0= IF
        2DROP PRES-S-INVALID 0 EXIT
    THEN
    OVER 0> 0= IF 2DROP PRES-S-INVALID 0 EXIT THEN
    _PBR.PENDING-COUNT @ IF
        DROP PRES-S-WOULD-BLOCK -1
    ELSE
        DROP PRES-S-OK 0
    THEN ;

