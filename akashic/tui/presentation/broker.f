    _PBRRS-SCOPE @ _PBS.RESOURCE-CTX @ OR
    _PBRRS-SCOPE @ _PBS.SERIES-XT @ OR
    _PBRRS-SCOPE @ _PBS.SERIES-CTX @ OR IF
