: _PBR-RETIRE-LIVE  ( scope broker -- )
    _PBRT-BROKER ! _PBRT-SCOPE !
    0 _PBRT-SCOPE @ _PBS.RESOURCE-XT !
    0 _PBRT-SCOPE @ _PBS.RESOURCE-CTX !
    0 _PBRT-SCOPE @ _PBS.SERIES-XT !
    0 _PBRT-SCOPE @ _PBS.SERIES-CTX !
    0 _PBRT-SCOPE @ _PBS.ROW !
    0 _PBRT-SCOPE @ _PBS.COL !
    0 _PBRT-SCOPE @ _PBS.HEIGHT !
    0 _PBRT-SCOPE @ _PBS.WIDTH !
    0 _PBRT-SCOPE @ _PBS.VISIBLE !
    0 _PBRT-SCOPE @ _PBS.LIVE-CALLER !
    _PBR-SCOPE-RETIRE-PENDING _PBRT-SCOPE @ _PBS.STATE !
    _PBRT-BROKER @ _PBR.LIVE-COUNT @ 0> IF
        -1 _PBRT-BROKER @ _PBR.LIVE-COUNT +!
    THEN
    _PBRT-BROKER @ _PBR.PENDING-COUNT @
    _PBRT-BROKER @ _PBR.RECORD-COUNT @ U< IF
        1 _PBRT-BROKER @ _PBR.PENDING-COUNT +!
    THEN ;

: _PBR-HOST-RETIRE  ( caller-instance broker -- status )
    _PBRT-BROKER ! _PBRT-CALLER !
    _PBRT-CALLER @ 0= IF PRES-S-INVALID EXIT THEN
    _PBRT-BROKER @ _PBR-BROKER-READY? 0= IF PRES-S-INVALID EXIT THEN
    _PBRT-CALLER @ _PBRT-BROKER @ _PBR-FIND-LIVE-CALLER
        _PBRT-SCOPE !
    _PBRT-CALLER @ _PBRT-BROKER @ _PBR-RESOLVE ?DUP IF
        _PBRT-SCOPE @ IF
            _PBRT-SCOPE @ _PBRT-BROKER @ _PBR-RETIRE-LIVE
            DROP PRES-S-OK
        THEN
        EXIT
    THEN
    _PBRT-SCOPE @ IF
        _PBRT-SCOPE @ _PBRT-BROKER @ _PBR-RECORD-STATUS
            _PBRT-RECORD-STATUS !
        _PBRT-SCOPE @ _PBS.ID @ _PBRR-ID @ =
        _PBRT-SCOPE @ _PBS.GENERATION @ _PBRR-GENERATION @ = AND
        _PBRT-SCOPE @ _PBS.LIVE-CALLER @ _PBRT-CALLER @ = AND 0= IF
            _PBRT-SCOPE @ _PBRT-BROKER @ _PBR-RETIRE-LIVE
            PRES-S-STALE EXIT
        THEN
        _PBRT-SCOPE @ _PBRT-BROKER @ _PBR-RETIRE-LIVE
        _PBRT-RECORD-STATUS @ PRES-S-OK = IF
            PRES-S-OK
        ELSE
            PRES-S-INVALID
        THEN
        EXIT
    THEN
    _PBRR-ID @ _PBRR-GENERATION @ _PBRT-BROKER @
        _PBR-FIND-EXACT DUP 0= IF DROP PRES-S-OK EXIT THEN
    DUP _PBRT-SCOPE ! _PBRT-BROKER @ _PBR-RECORD-STATUS
    DUP PRES-S-OK = IF
        DROP _PBRT-SCOPE @ _PBS.LIVE-CALLER @
            _PBRT-CALLER @ <> IF PRES-S-STALE EXIT THEN
        _PBRT-SCOPE @ _PBRT-BROKER @ _PBR-RETIRE-LIVE
        PRES-S-OK EXIT
    THEN
    PRES-S-STALE =
    _PBRT-SCOPE @ _PBS.STATE @ _PBR-SCOPE-RETIRE-PENDING = AND IF
        PRES-S-OK
    ELSE
        PRES-S-INVALID
    THEN ;

