\ =====================================================================
\  broker.f - Caller-bounded scoped retained-presentation authority
\ =====================================================================
\  This backend supplies only the lifecycle and activation-authority core
\  behind presentation/api.f.  Desk injects an exact live-caller resolver;
\  the broker never accepts a child ID or generation from an application.
\
\  Scope records are a caller-owned fixed span.  There is no allocation and
\  no product capacity hidden in this module.  Scene operations deliberately
\  remain unavailable until a later backend slice supplies retained storage.
\ =====================================================================

PROVIDED akashic-tui-pres-broker

REQUIRE api.f

\ =====================================================================
\  Desk-owned exact activation descriptor
\ =====================================================================
\  The injected resolver has this exact callback contract:
\
\      ( caller-instance resolver-context -- activation-desc status )
\
\  On PRES-S-OK it returns a borrowed descriptor that remains Desk-owned.
\  The broker validates and copies every field before changing a scope.
\  Resolver callbacks must be non-yielding and non-reentrant: this backend is
\  single-owner code and uses bounded module scratch while a call is active.

