        _PBRX-DESC @ PRES-ACTIVATION-DESC-SIZE
        _PBRX-BROKER @ _PBR.RECORDS @
        _PBRX-BROKER @ _PBR.RECORD-BYTES @
            MSPAN-OVERLAP? 0=
    ELSE
        -1
    THEN ;

