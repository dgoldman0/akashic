    _PBRR-BROKER @ _PBR.RESOLVER-CTX @
    _PBRR-BROKER @ _PBR.RESOLVER-XT @ EXECUTE
    DUP PRES-STATUS-VALID? 0= IF
        2DROP PRES-S-INVALID EXIT
    THEN
    DUP PRES-S-OK <> IF SWAP DROP EXIT THEN
    DROP DUP _PBRR-DESC !
    DUP PRES-ACTIVATION-DESC-VALID? 0= IF
        DROP PRES-S-INVALID EXIT
    THEN
    DUP _PBRR-BROKER @ _PBR-ACTIVATION-EXTERNAL? 0= IF
        DROP PRES-S-INVALID EXIT
    THEN
    _PBR-CAPTURE-ACTIVATION PRES-S-OK ;

