: _PBR-SCOPE-ACQUIRE  ( caller-instance broker -- scope status )
    _PBRA-BROKER ! _PBRA-CALLER !
    _PBRA-CALLER @ 0= IF 0 PRES-S-INVALID EXIT THEN
    _PBRA-BROKER @ _PBR-BROKER-READY? 0= IF
        0 PRES-S-INVALID EXIT
    THEN
    _PBRA-CALLER @ _PBRA-BROKER @ _PBR-RESOLVE
    ?DUP IF 0 SWAP EXIT THEN
    _PBRA-BROKER @ _PBR.SUPPORTED @ 0= IF
        0 PRES-S-UNAVAILABLE EXIT
    THEN
    _PBRR-ID @ _PBRR-GENERATION @ _PBRA-BROKER @
        _PBR-FIND-EXACT DUP IF
        DUP _PBRA-SCOPE !
        _PBRA-BROKER @ _PBR-RECORD-STATUS
        DUP PRES-S-OK = IF
            DROP _PBRA-SCOPE @ _PBS.LIVE-CALLER @
                _PBRA-CALLER @ <> IF 0 PRES-S-STALE EXIT THEN
            _PBRA-SCOPE @ _PBR-STORE-RESOLVED-BOUNDS
            _PBRA-SCOPE @ PRES-S-OK EXIT
        THEN
        0 SWAP EXIT
    THEN
    DROP _PBRR-ID @ _PBRA-BROKER @ _PBR-FIND-ID IF
        0 PRES-S-STALE EXIT
    THEN
    _PBRA-CALLER @ _PBRA-BROKER @ _PBR-FIND-LIVE-CALLER IF
        0 PRES-S-STALE EXIT
    THEN
    _PBRA-BROKER @ _PBR-FIND-FREE DUP 0= IF
        DROP 0 PRES-S-CAPACITY EXIT
    THEN
    _PBRA-BROKER @ _PBR-NEW-LIVE ;

