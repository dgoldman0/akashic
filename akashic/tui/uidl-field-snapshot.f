CREATE _UFLSN-PROOF-SPANS 2 MSPAN-SET-BYTES ALLOT

\ Collect the two caller spans for one enclosed authority proof.  Their
\ shapes are admitted first, and the prover skips empty optional spans.
: _UFLSN-PROOF-SPANS?  ( -- flag )
    2 _UFLSN-PROOF-SPANS MSPAN-SET-INIT MSPAN-SET-S-OK <> IF 0 EXIT THEN
    _UFLSN-DESCRIPTORS-A @ _UFLSN-DESCRIPTORS-U @
        _UFLSN-PROOF-SPANS MSPAN-SET-PUSH MSPAN-SET-S-OK <> IF 0 EXIT THEN
    _UFLSN-NATIVE-A @ _UFLSN-NATIVE-U @ _UFLSN-PROOF-SPANS MSPAN-SET-PUSH
        MSPAN-SET-S-OK = ;
\ Caller span shapes and mutual disjointness.  Authority is proved
\ separately, before the first live FIELD visit.
: _UFLSN-SHAPES?  ( -- flag )
    _UFLSN-DESCRIPTORS-A @ _UFLSN-DESCRIPTORS-U @
        _UFLSN-OPTIONAL-SPAN? 0= IF 0 EXIT THEN
    _UFLSN-DESCRIPTORS-U @ UFLSN-DESCRIPTOR-SIZE MOD IF 0 EXIT THEN
    _UFLSN-DESCRIPTORS-U @ IF
        _UFLSN-DESCRIPTORS-A @ _UFLSN-ALIGNED? 0= IF 0 EXIT THEN
    THEN
    _UFLSN-NATIVE-A @ _UFLSN-NATIVE-U @
        _UFLSN-OPTIONAL-SPAN? 0= IF 0 EXIT THEN
    _UFLSN-NATIVE-U @ IF
        _UFLSN-NATIVE-A @ _UFLSN-ALIGNED? 0= IF 0 EXIT THEN
    THEN
    _UFLSN-DESCRIPTORS-A @ _UFLSN-DESCRIPTORS-U @
        _UFLSN-NATIVE-A @ _UFLSN-NATIVE-U @ _UFLSN-DISJOINT? ;
\ Each authority query walks the document's storage.  Clustered caller spans
\ need one enclosed query instead of one per span.
: _UFLSN-AUTHORITY?  ( -- flag )
    _UFLSN-PROOF-SPANS? 0= IF 0 EXIT THEN
    _UFLSN-PROOF-SPANS ['] _UFLSN-AUTHORITY-DISJOINT?
        MSPAN-SET-PROVE-DISJOINT? ;

