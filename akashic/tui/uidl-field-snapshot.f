\ _UFLSN-V-REFUSED ( -- )
\   A root's own widget could not publish it.  Leave that root out, so CELL
\   draws its area and the snapshot keeps its other roots, and keep nothing
\   of it: its entry bytes and descriptor are cleared as a fully clipped
\   root's are.  A capacity refusal stays the snapshot's.
: _UFLSN-V-REFUSED  ( -- )
    _UFLSN-STATUS @ DUP UFLSN-S-UNAVAILABLE = SWAP UFLSN-S-INVALID = OR
        0= IF EXIT THEN
    _UFLSN-V-DESCRIPTOR @ IF _UFLSN-V-ROLLBACK-CLIPPED THEN
    UFLSN-S-OK _UFLSN-STATUS ! ;

: _UFLSN-V-CAPTURE  ( -- )
    _UFLSN-V-CLIP-HEIGHT @ 0= _UFLSN-V-CLIP-WIDTH @ 0= OR IF
        EXIT
    THEN
    _UFLSN-V-CAPACITY? 0= IF EXIT THEN
    _UFLSN-NATIVE-USED @ _UFLSN-NATIVE-U @ U> IF
        _UFLSN-SET-INVALID EXIT
    THEN
    _UFLSN-NATIVE-U @ _UFLSN-NATIVE-USED @ - DUP 0= IF
        DROP _UFLSN-SET-CAPACITY EXIT
    THEN
    _UFLSN-V-REMAINING !
    0 _UFLSN-V-ENTRY-U !

    \ Measure through the exact same current widget before touching
    \ the native bank.  The captured byte count must remain identical.
    0 0 _UFLSN-V-PRODUCE
    DUP UFLD-S-OK <> IF
        >R DROP R> _UFLSN-MAP-UFLD _UFLSN-V-REFUSED EXIT
    THEN
    DROP
    DUP 0> 0= OVER 7 AND OR IF
        DROP _UFLSN-SET-INVALID _UFLSN-V-REFUSED EXIT
    THEN
    DUP _UFLSN-V-REMAINING @ U> IF
        DROP _UFLSN-SET-CAPACITY EXIT
    THEN
    _UFLSN-V-ENTRY-U !

    _UFLSN-NATIVE-A @ _UFLSN-NATIVE-USED @ + _UFLSN-V-ENTRY !
    _UFLSN-NATIVE-USED @ _UFLSN-V-ENTRY-U @ + DUP
        _UFLSN-V-NEXT-NATIVE ! _UFLSN-DIRTY-NATIVE-U !
    _UFLSN-V-ENTRY @ _UFLSN-V-ENTRY-U @ _UFLSN-V-PRODUCE
    DUP UFLD-S-OK <> IF
        >R DROP R> _UFLSN-MAP-UFLD _UFLSN-V-REFUSED EXIT
    THEN
    DROP _UFLSN-V-ENTRY-U @ <> IF
        _UFLSN-SET-INVALID _UFLSN-V-REFUSED EXIT
    THEN

    _UFLSN-V-VALIDATE? 0= IF _UFLSN-V-REFUSED EXIT THEN
    _UFLSN-V-CLIP-HEIGHT @ 0= _UFLSN-V-CLIP-WIDTH @ 0= OR IF
        _UFLSN-V-ROLLBACK-CLIPPED EXIT
    THEN
    _UFLSN-V-WRITE-METADATA
    _UFLSN-V-NEXT-NATIVE @ _UFLSN-NATIVE-USED !
    1 _UFLSN-COUNT +! ;

: _UFLSN-VISITOR
    ( source-index source-generation root-key resolved-a resolved-u -- )
    _UFLSN-V-RESOLVED-U ! _UFLSN-V-RESOLVED-A !
    _UFLSN-V-ROOT-KEY ! _UFLSN-V-GENERATION ! _UFLSN-V-INDEX !
    _UFLSN-STATUS @ UFLSN-S-OK <> IF EXIT THEN
    _UFLSN-V-ARGS? 0= IF _UFLSN-SET-INVALID EXIT THEN
    _UFLSN-V-ORDER? 0= IF _UFLSN-SET-INVALID EXIT THEN
    0 _UFLSN-V-DESCRIPTOR ! 0 _UFLSN-V-ENTRY-U !
    _UFLSN-V-GEOMETRY? 0= IF _UFLSN-V-REFUSED EXIT THEN
    _UFLSN-V-CAPTURE ;

