: _UFLSN-F-UADD?  ( a b -- sum flag )
    OVER + DUP ROT U< 0= ;

: _UFLSN-F-WORK-AT  ( ordinal -- address )
    UFLSN-FROZEN-WORK-ENTRY-SIZE * _UFLSN-F-WORK-A @ + ;

: _UFLSN-F-DESCRIPTOR-AT  ( ordinal -- descriptor )
    UFLSN-DESCRIPTOR-SIZE * _UFLSN-F-DESCRIPTORS-A @ + ;

: _UFLSN-F-CLEAR-SCRATCH  ( -- )
    _UFLSN-F-RANGES-VALID @ IF
        _UFLSN-F-WORK-NEED @ ?DUP IF
            _UFLSN-F-WORK-A @ SWAP 0 FILL
        THEN
    THEN ;

: _UFLSN-F-SCRUB  ( -- )
    0 _UFLSN-F-WORK-A ! 0 _UFLSN-F-WORK-U !
    0 _UFLSN-F-WORK-NEED !
    0 _UFLSN-F-DESCRIPTORS-A ! 0 _UFLSN-F-DESCRIPTORS-U !
    0 _UFLSN-F-NATIVE-A ! 0 _UFLSN-F-NATIVE-U !
    0 _UFLSN-F-COUNT ! 0 _UFLSN-F-I ! 0 _UFLSN-F-J !
    0 _UFLSN-F-VALUE ! 0 _UFLSN-F-DESCRIPTOR !
    0 _UFLSN-F-HEAP-ROOT ! 0 _UFLSN-F-HEAP-END !
    0 _UFLSN-F-HEAP-CHILD ! 0 _UFLSN-F-HEAP-LARGEST !
    0 _UFLSN-F-HEAP-A ! 0 _UFLSN-F-HEAP-B !
    0 _UFLSN-F-FIELD ! 0 _UFLSN-F-FIELD-U !
    0 _UFLSN-F-OFFSET ! 0 _UFLSN-F-CURSOR !
    0 _UFLSN-F-INDEX ! 0 _UFLSN-F-GENERATION !
    0 _UFLSN-F-RELATION ! 0 _UFLSN-F-PRIOR-INDEX !
    0 _UFLSN-F-PRIOR-GENERATION ! 0 _UFLSN-F-PRIOR-RELATION !
    0 _UFLSN-F-HAVE-PRIOR !
    0 _UFLSN-F-RANGES-VALID ! ;

: _UFLSN-F-AUTHORITY-DISJOINT?  ( address bytes -- flag )
    DUP 0= IF 2DROP -1 EXIT THEN
    2DUP _UFLSN-OWNED-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP USCOL-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP UDG-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP DGF-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP FLD-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    2DUP USF-STORAGE-DISJOINT? 0= IF 2DROP 0 EXIT THEN
    UFLD-STORAGE-DISJOINT? ;

: _UFLSN-F-RANGES  ( -- status )
    _UFLSN-F-DESCRIPTORS-A @ _UFLSN-F-DESCRIPTORS-U @
        _UFLSN-OPTIONAL-SPAN? 0= IF UFLSN-S-INVALID EXIT THEN
    _UFLSN-F-DESCRIPTORS-U @ UFLSN-DESCRIPTOR-SIZE MOD IF
        UFLSN-S-INVALID EXIT
    THEN
    _UFLSN-F-NATIVE-A @ _UFLSN-F-NATIVE-U @
        _UFLSN-OPTIONAL-SPAN? 0= IF UFLSN-S-INVALID EXIT THEN
    _UFLSN-F-DESCRIPTORS-U @ 0=
        _UFLSN-F-NATIVE-U @ 0= <> IF UFLSN-S-INVALID EXIT THEN
    _UFLSN-F-DESCRIPTORS-U @ IF
        _UFLSN-F-DESCRIPTORS-A @ _UFLSN-ALIGNED? 0= IF
            UFLSN-S-INVALID EXIT
        THEN
        _UFLSN-F-NATIVE-A @ _UFLSN-ALIGNED? 0= IF
            UFLSN-S-INVALID EXIT
        THEN
        _UFLSN-F-NATIVE-U @ 7 AND IF UFLSN-S-INVALID EXIT THEN
    THEN

    _UFLSN-F-DESCRIPTORS-U @ UFLSN-DESCRIPTOR-SIZE /
        DUP _UFLSN-F-COUNT !
    UFLSN-FROZEN-WORK-BYTES DUP _UFLSN-F-WORK-NEED !
    _UFLSN-F-COUNT @ IF
        DUP 0= IF DROP UFLSN-S-INVALID EXIT THEN
    THEN DROP
    _UFLSN-F-WORK-A @ _UFLSN-F-WORK-U @
        _UFLSN-OPTIONAL-SPAN? 0= IF UFLSN-S-INVALID EXIT THEN
    _UFLSN-F-WORK-U @ IF
        _UFLSN-F-WORK-A @ _UFLSN-ALIGNED? 0= IF
            UFLSN-S-INVALID EXIT
        THEN
    THEN
    _UFLSN-F-WORK-U @ _UFLSN-F-WORK-NEED @ U< IF
        UFLSN-S-CAPACITY EXIT
    THEN

    _UFLSN-F-WORK-A @ _UFLSN-F-WORK-U @
        _UFLSN-F-AUTHORITY-DISJOINT? 0= IF UFLSN-S-INVALID EXIT THEN
    _UFLSN-F-DESCRIPTORS-A @ _UFLSN-F-DESCRIPTORS-U @
        _UFLSN-F-AUTHORITY-DISJOINT? 0= IF UFLSN-S-INVALID EXIT THEN
    _UFLSN-F-NATIVE-A @ _UFLSN-F-NATIVE-U @
        _UFLSN-F-AUTHORITY-DISJOINT? 0= IF UFLSN-S-INVALID EXIT THEN

    _UFLSN-F-WORK-A @ _UFLSN-F-WORK-U @
        _UFLSN-F-DESCRIPTORS-A @ _UFLSN-F-DESCRIPTORS-U @
        _UFLSN-DISJOINT? 0= IF UFLSN-S-INVALID EXIT THEN
    _UFLSN-F-WORK-A @ _UFLSN-F-WORK-U @
        _UFLSN-F-NATIVE-A @ _UFLSN-F-NATIVE-U @
        _UFLSN-DISJOINT? 0= IF UFLSN-S-INVALID EXIT THEN
    _UFLSN-F-DESCRIPTORS-A @ _UFLSN-F-DESCRIPTORS-U @
        _UFLSN-F-NATIVE-A @ _UFLSN-F-NATIVE-U @
        _UFLSN-DISJOINT? 0= IF UFLSN-S-INVALID EXIT THEN

    -1 _UFLSN-F-RANGES-VALID !
    _UFLSN-F-CLEAR-SCRATCH
    UFLSN-S-OK ;

: _UFLSN-F-ORDER?  ( -- flag )
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-SOURCE@
        UFLSN-SOURCE-UIDL <> IF 0 EXIT THEN
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-SOURCE-INDEX@
        DUP 0< IF DROP 0 EXIT THEN _UFLSN-F-INDEX !
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-SOURCE-GENERATION@
        DUP _UFLSN-GENERATION? 0= IF DROP 0 EXIT THEN
        _UFLSN-F-GENERATION !
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-ROOT-KEY@
        DUP 0= IF DROP 0 EXIT THEN _UFLSN-F-RELATION !
    _UFLSN-F-HAVE-PRIOR @ IF
        _UFLSN-F-INDEX @ _UFLSN-F-PRIOR-INDEX @ U< IF 0 EXIT THEN
        _UFLSN-F-INDEX @ _UFLSN-F-PRIOR-INDEX @ = IF
            _UFLSN-F-PRIOR-RELATION @ _UFLSN-F-RELATION @
                U< 0= IF 0 EXIT THEN
            _UFLSN-F-GENERATION @ _UFLSN-F-PRIOR-GENERATION @
                <> IF 0 EXIT THEN
        THEN
    THEN
    _UFLSN-F-INDEX @ _UFLSN-F-PRIOR-INDEX !
    _UFLSN-F-GENERATION @ _UFLSN-F-PRIOR-GENERATION !
    _UFLSN-F-RELATION @ _UFLSN-F-PRIOR-RELATION !
    -1 _UFLSN-F-HAVE-PRIOR !
    -1 ;

: _UFLSN-F-GEOMETRY?  ( -- flag )
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-HEIGHT@
        _UFLSN-F-FIELD @ UFLD-HEIGHT@ <> IF 0 EXIT THEN
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-WIDTH@
        _UFLSN-F-FIELD @ UFLD-WIDTH@ <> IF 0 EXIT THEN
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-ROW@ DUP 0< IF
        DROP 0 EXIT
    THEN
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-HEIGHT@
        _UFLSN-IADD-NONNEG? 0= IF DROP 0 EXIT THEN DROP
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-COLUMN@ DUP 0< IF
        DROP 0 EXIT
    THEN
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-WIDTH@
        _UFLSN-IADD-NONNEG? 0= IF DROP 0 EXIT THEN DROP
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-CLIP-ROW@
        _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-ROW@ <> IF 0 EXIT THEN
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-CLIP-COLUMN@
        _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-COLUMN@ <> IF 0 EXIT THEN
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-CLIP-HEIGHT@
        _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-HEIGHT@ <> IF 0 EXIT THEN
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-CLIP-WIDTH@
        _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-WIDTH@ <> IF 0 EXIT THEN
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-Z@ 255 U> IF 0 EXIT THEN
    -1 ;
: _UFLSN-F-ENTRY?  ( -- flag )
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-NATIVE-OFFSET@
        DUP 0< IF DROP 0 EXIT THEN
        DUP 7 AND IF DROP 0 EXIT THEN
        DUP _UFLSN-F-OFFSET !
    _UFLSN-F-NATIVE-U @ U> IF 0 EXIT THEN
    _UFLSN-F-NATIVE-U @ _UFLSN-F-OFFSET @ -
        UFLD-HEADER-SIZE U< IF 0 EXIT THEN
    _UFLSN-F-NATIVE-A @ _UFLSN-F-OFFSET @ +
        DUP _UFLSN-F-FIELD !
    UFLD-BYTES@ DUP _UFLSN-F-FIELD-U !
    DUP UFLD-HEADER-SIZE U< OVER 7 AND OR IF DROP 0 EXIT THEN
    _UFLSN-F-NATIVE-U @ _UFLSN-F-OFFSET @ - U> IF 0 EXIT THEN
    _UFLSN-F-FIELD @ _UFLSN-F-FIELD-U @ UFLD-VALIDATE
        UFLD-S-OK <> IF 0 EXIT THEN
    _UFLSN-F-FIELD @ UFLD-STATE@ UFLD-STATE-VISIBLE AND 0= IF 0 EXIT THEN
    _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-ENTRY-BYTES@
        _UFLSN-F-FIELD-U @ <> IF 0 EXIT THEN
    _UFLSN-F-FIELD @ UFLD-UTF8-BYTES@
        _UFLSN-F-DESCRIPTOR @ UFLSN-DESCRIPTOR-UTF8-BYTES@ <> IF 0 EXIT THEN
    _UFLSN-F-GEOMETRY? 0= IF 0 EXIT THEN
    _UFLSN-F-OFFSET @ _UFLSN-F-I @ _UFLSN-F-WORK-AT !
    -1 ;
: _UFLSN-F-SWAP-OFFSETS  ( ordinal-a ordinal-b -- )
    _UFLSN-F-HEAP-B ! _UFLSN-F-HEAP-A !
    _UFLSN-F-HEAP-A @ _UFLSN-F-WORK-AT @ _UFLSN-F-VALUE !
    _UFLSN-F-HEAP-B @ _UFLSN-F-WORK-AT @
        _UFLSN-F-HEAP-A @ _UFLSN-F-WORK-AT !
    _UFLSN-F-VALUE @ _UFLSN-F-HEAP-B @ _UFLSN-F-WORK-AT ! ;

\ Restore one unsigned max-heap below the exclusive END ordinal.  The
\ caller-bounded ledger makes this O(n log n) at the configured ceiling.
: _UFLSN-F-SIFT-DOWN  ( root end -- )
    _UFLSN-F-HEAP-END ! _UFLSN-F-HEAP-ROOT !
    BEGIN
        _UFLSN-F-HEAP-ROOT @ 2 * 1+ DUP _UFLSN-F-HEAP-CHILD !
        _UFLSN-F-HEAP-END @ U<
    WHILE
        _UFLSN-F-HEAP-ROOT @ _UFLSN-F-HEAP-LARGEST !
        _UFLSN-F-HEAP-LARGEST @ _UFLSN-F-WORK-AT @
        _UFLSN-F-HEAP-CHILD @ _UFLSN-F-WORK-AT @ U< IF
            _UFLSN-F-HEAP-CHILD @ _UFLSN-F-HEAP-LARGEST !
        THEN
        _UFLSN-F-HEAP-CHILD @ 1+ DUP _UFLSN-F-HEAP-CHILD !
        _UFLSN-F-HEAP-END @ U< IF
            _UFLSN-F-HEAP-LARGEST @ _UFLSN-F-WORK-AT @
            _UFLSN-F-HEAP-CHILD @ _UFLSN-F-WORK-AT @ U< IF
                _UFLSN-F-HEAP-CHILD @ _UFLSN-F-HEAP-LARGEST !
            THEN
        THEN
        _UFLSN-F-HEAP-LARGEST @ _UFLSN-F-HEAP-ROOT @ = IF EXIT THEN
        _UFLSN-F-HEAP-ROOT @ _UFLSN-F-HEAP-LARGEST @
            _UFLSN-F-SWAP-OFFSETS
        _UFLSN-F-HEAP-LARGEST @ _UFLSN-F-HEAP-ROOT !
    REPEAT ;

: _UFLSN-F-SORT-OFFSETS  ( -- )
    _UFLSN-F-COUNT @ 2 / _UFLSN-F-I !
    BEGIN _UFLSN-F-I @ 0> WHILE
        -1 _UFLSN-F-I +!
        _UFLSN-F-I @ _UFLSN-F-COUNT @ _UFLSN-F-SIFT-DOWN
    REPEAT
    _UFLSN-F-COUNT @ _UFLSN-F-J !
    BEGIN _UFLSN-F-J @ 1 > WHILE
        -1 _UFLSN-F-J +!
        0 _UFLSN-F-J @ _UFLSN-F-SWAP-OFFSETS
        0 _UFLSN-F-J @ _UFLSN-F-SIFT-DOWN
    REPEAT ;

: _UFLSN-F-COVERAGE?  ( -- flag )
    0 _UFLSN-F-CURSOR ! 0 _UFLSN-F-I !
    BEGIN _UFLSN-F-I @ _UFLSN-F-COUNT @ U< WHILE
        _UFLSN-F-I @ _UFLSN-F-WORK-AT @ DUP _UFLSN-F-OFFSET !
        _UFLSN-F-CURSOR @ <> IF 0 EXIT THEN
        _UFLSN-F-OFFSET @ _UFLSN-F-NATIVE-U @ U> IF 0 EXIT THEN
        _UFLSN-F-NATIVE-U @ _UFLSN-F-OFFSET @ -
            UFLD-HEADER-SIZE U< IF 0 EXIT THEN
        _UFLSN-F-NATIVE-A @ _UFLSN-F-OFFSET @ + UFLD-BYTES@
            DUP UFLD-HEADER-SIZE U< OVER 7 AND OR IF DROP 0 EXIT THEN
        _UFLSN-F-CURSOR @ SWAP _UFLSN-F-UADD?
            0= IF DROP 0 EXIT THEN
        DUP _UFLSN-F-NATIVE-U @ U> IF DROP 0 EXIT THEN
            _UFLSN-F-CURSOR !
        1 _UFLSN-F-I +!
    REPEAT
    _UFLSN-F-CURSOR @ _UFLSN-F-NATIVE-U @ = ;

: _UFLSN-F-VALIDATE-BODY  ( -- status )
    _UFLSN-F-RANGES DUP UFLSN-S-OK <> IF EXIT THEN DROP
    _UFLSN-F-COUNT @ 0= IF UFLSN-S-OK EXIT THEN
    0 _UFLSN-F-PRIOR-INDEX ! 0 _UFLSN-F-PRIOR-GENERATION !
    0 _UFLSN-F-PRIOR-RELATION ! 0 _UFLSN-F-HAVE-PRIOR !
    0 _UFLSN-F-I !
    BEGIN _UFLSN-F-I @ _UFLSN-F-COUNT @ U< WHILE
        _UFLSN-F-I @ _UFLSN-F-DESCRIPTOR-AT
            _UFLSN-F-DESCRIPTOR !
        _UFLSN-F-ORDER? 0= IF UFLSN-S-INVALID EXIT THEN
        _UFLSN-F-ENTRY? 0= IF UFLSN-S-INVALID EXIT THEN
        1 _UFLSN-F-I +!
    REPEAT
    _UFLSN-F-SORT-OFFSETS
    _UFLSN-F-COVERAGE? 0= IF UFLSN-S-INVALID EXIT THEN
    UFLSN-S-OK ;

: _UFLSN-F-VALIDATE-CALL  ( -- status )
    ['] _UFLSN-F-VALIDATE-BODY CATCH ?DUP IF
        DROP UFLSN-S-INVALID
    THEN
    _UFLSN-F-CLEAR-SCRATCH
    _UFLSN-F-SCRUB ;

: UFLSN-FROZEN-VALIDATE
    ( offset-work-a offset-work-u descriptors-a descriptors-u native-a native-u -- status )
    5 PICK 5 PICK UFLSN-STORAGE-DISJOINT? 0= IF
        2DROP 2DROP 2DROP UFLSN-S-INVALID EXIT
    THEN
    3 PICK 3 PICK UFLSN-STORAGE-DISJOINT? 0= IF
        2DROP 2DROP 2DROP UFLSN-S-INVALID EXIT
    THEN
    2DUP UFLSN-STORAGE-DISJOINT? 0= IF
        2DROP 2DROP 2DROP UFLSN-S-INVALID EXIT
    THEN
    _UFLSN-F-NATIVE-U ! _UFLSN-F-NATIVE-A !
    _UFLSN-F-DESCRIPTORS-U ! _UFLSN-F-DESCRIPTORS-A !
    _UFLSN-F-WORK-U ! _UFLSN-F-WORK-A !
    0 _UFLSN-F-WORK-NEED ! 0 _UFLSN-F-RANGES-VALID !
    ['] _UFLSN-F-VALIDATE-CALL CATCH ?DUP IF
        DROP
        _UFLSN-F-CLEAR-SCRATCH
        _UFLSN-F-SCRUB
        UFLSN-S-INVALID
    THEN ;

