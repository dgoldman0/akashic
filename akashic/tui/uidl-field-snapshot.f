: _UFLSN-ALIGNED?  ( address -- flag )  7 AND 0= ;

: _UFLSN-OPTIONAL-SPAN?  ( address bytes -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    DUP 0= IF DROP 0= EXIT THEN
    OVER 0< IF 2DROP 0 EXIT THEN
    OVER 0= IF 2DROP 0 EXIT THEN
    MSPAN-NONWRAPPING? ;

: _UFLSN-DISJOINT?  ( a1 u1 a2 u2 -- flag )
    2 PICK 0= OVER 0= OR IF 2DROP 2DROP -1 EXIT THEN
    MSPAN-OVERLAP? 0= ;

: _UFLSN-OWNED-DISJOINT?  ( address bytes -- flag )
    DUP 0= IF 2DROP -1 EXIT THEN
    _UFLSN-OWNED-LIMIT @ DUP _UFLSN-OWNED-START U< IF
        DROP 2DROP 0 EXIT
    THEN
    _UFLSN-OWNED-START - >R
    2DUP _UFLSN-OWNED-START R> MSPAN-OVERLAP? 0= NIP NIP ;

\ Pure preflight for owners that reserve snapshot banks inside larger arenas.
: UFLSN-STORAGE-DISJOINT?  ( address bytes -- flag )
    2DUP _UFLSN-OPTIONAL-SPAN? 0= IF 2DROP 0 EXIT THEN
    _UFLSN-OWNED-DISJOINT? ;

