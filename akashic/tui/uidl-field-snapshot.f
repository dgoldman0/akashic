: _UFLSN-MAP-UFLD  ( status -- )
    DUP UFLD-S-OK = IF DROP EXIT THEN
    DUP UFLD-S-CAPACITY = IF DROP _UFLSN-SET-CAPACITY EXIT THEN
    DUP UFLD-S-UNSUPPORTED = IF DROP _UFLSN-SET-UNAVAILABLE EXIT THEN
    DROP _UFLSN-SET-INVALID ;
: _UFLSN-MAP-MOUNTED  ( status -- )
    DUP _UTUI-MC-S-OK = IF DROP EXIT THEN
    DUP _UTUI-MC-S-UNAVAILABLE = IF
        DROP _UFLSN-SET-UNAVAILABLE
    ELSE
        DROP _UFLSN-SET-INVALID
    THEN ;

