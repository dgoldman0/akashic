        UFLSN-S-CAPACITY _UFLSN-STATUS !
    THEN ;

: _UFLSN-SET-UNAVAILABLE  ( -- )
    _UFLSN-STATUS @ UFLSN-S-OK = IF
        UFLSN-S-UNAVAILABLE _UFLSN-STATUS !
    THEN ;

