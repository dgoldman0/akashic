: _UDGSN-F-RANGES  ( -- status )
    _UDGSN-F-DESCRIPTORS-A @ _UDGSN-F-DESCRIPTORS-U @
        _UDGSN-OPTIONAL-SPAN? 0= IF UDGSN-S-INVALID EXIT THEN
    _UDGSN-F-DESCRIPTORS-U @ UDGSN-DESCRIPTOR-SIZE MOD IF
        UDGSN-S-INVALID EXIT
    THEN
    _UDGSN-F-NATIVE-A @ _UDGSN-F-NATIVE-U @
        _UDGSN-OPTIONAL-SPAN? 0= IF UDGSN-S-INVALID EXIT THEN
    _UDGSN-F-DESCRIPTORS-U @ 0=
        _UDGSN-F-NATIVE-U @ 0= <> IF UDGSN-S-INVALID EXIT THEN
    _UDGSN-F-DESCRIPTORS-U @ IF
        _UDGSN-F-DESCRIPTORS-A @ _UDGSN-ALIGNED? 0= IF
            UDGSN-S-INVALID EXIT
        THEN
        _UDGSN-F-NATIVE-A @ _UDGSN-ALIGNED? 0= IF
            UDGSN-S-INVALID EXIT
        THEN
        _UDGSN-F-NATIVE-U @ 7 AND IF UDGSN-S-INVALID EXIT THEN
    THEN

    _UDGSN-F-DESCRIPTORS-U @ UDGSN-DESCRIPTOR-SIZE /
        DUP _UDGSN-F-COUNT !
    UDGSN-FROZEN-WORK-BYTES DUP _UDGSN-F-WORK-NEED !
    _UDGSN-F-COUNT @ IF
        DUP 0= IF DROP UDGSN-S-INVALID EXIT THEN
    THEN DROP
    _UDGSN-F-WORK-A @ _UDGSN-F-WORK-U @
        _UDGSN-OPTIONAL-SPAN? 0= IF UDGSN-S-INVALID EXIT THEN
    _UDGSN-F-WORK-U @ IF
        _UDGSN-F-WORK-A @ _UDGSN-ALIGNED? 0= IF
            UDGSN-S-INVALID EXIT
        THEN
    THEN
    _UDGSN-F-WORK-U @ _UDGSN-F-WORK-NEED @ U< IF
        UDGSN-S-CAPACITY EXIT
    THEN

    _UDGSN-F-WORK-A @ _UDGSN-F-WORK-U @
        _UDGSN-F-AUTHORITY-DISJOINT? 0= IF UDGSN-S-INVALID EXIT THEN
    _UDGSN-F-DESCRIPTORS-A @ _UDGSN-F-DESCRIPTORS-U @
        _UDGSN-F-AUTHORITY-DISJOINT? 0= IF UDGSN-S-INVALID EXIT THEN
    _UDGSN-F-NATIVE-A @ _UDGSN-F-NATIVE-U @
        _UDGSN-F-AUTHORITY-DISJOINT? 0= IF UDGSN-S-INVALID EXIT THEN

    _UDGSN-F-WORK-A @ _UDGSN-F-WORK-U @
        _UDGSN-F-DESCRIPTORS-A @ _UDGSN-F-DESCRIPTORS-U @
        _UDGSN-DISJOINT? 0= IF UDGSN-S-INVALID EXIT THEN
    _UDGSN-F-WORK-A @ _UDGSN-F-WORK-U @
        _UDGSN-F-NATIVE-A @ _UDGSN-F-NATIVE-U @
        _UDGSN-DISJOINT? 0= IF UDGSN-S-INVALID EXIT THEN
    _UDGSN-F-DESCRIPTORS-A @ _UDGSN-F-DESCRIPTORS-U @
        _UDGSN-F-NATIVE-A @ _UDGSN-F-NATIVE-U @
        _UDGSN-DISJOINT? 0= IF UDGSN-S-INVALID EXIT THEN

    -1 _UDGSN-F-RANGES-VALID !
    _UDGSN-F-CLEAR-SCRATCH
    UDGSN-S-OK ;

: _UDGSN-F-ORDER?  ( -- flag )
