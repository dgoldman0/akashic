        DROP 0 EXIT
    THEN
    DUP _UDGSN-F-GRAPH @ UDG-ROOT-COLUMN@ U< IF DROP 0 EXIT THEN
    _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-WIDTH@
