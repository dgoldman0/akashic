        UDGSN-SOURCE-UIDL <> IF 0 EXIT THEN
    _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-SOURCE-INDEX@
        DUP 0< IF DROP 0 EXIT THEN _UDGSN-F-INDEX !
    _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-SOURCE-GENERATION@
        DUP _UDGSN-GENERATION? 0= IF DROP 0 EXIT THEN
        _UDGSN-F-GENERATION !
    _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-ROOT-KEY@
        DUP 0= IF DROP 0 EXIT THEN _UDGSN-F-RELATION !
    _UDGSN-F-HAVE-PRIOR @ IF
        _UDGSN-F-INDEX @ _UDGSN-F-PRIOR-INDEX @ U< IF 0 EXIT THEN
        _UDGSN-F-INDEX @ _UDGSN-F-PRIOR-INDEX @ = IF
            _UDGSN-F-PRIOR-RELATION @ _UDGSN-F-RELATION @
                U< 0= IF 0 EXIT THEN
            _UDGSN-F-GENERATION @ _UDGSN-F-PRIOR-GENERATION @
                <> IF 0 EXIT THEN
        THEN
    THEN
    _UDGSN-F-INDEX @ _UDGSN-F-PRIOR-INDEX !
    _UDGSN-F-GENERATION @ _UDGSN-F-PRIOR-GENERATION !
    _UDGSN-F-RELATION @ _UDGSN-F-PRIOR-RELATION !
    -1 _UDGSN-F-HAVE-PRIOR !
    -1 ;

