        _UDGSN-F-ROOT-RIGHT !

    _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-CLIP-ROW@ DUP 0< IF
        DROP 0 EXIT
    THEN
    _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-CLIP-HEIGHT@
        DUP 0> 0= IF 2DROP 0 EXIT THEN
        _UDGSN-IADD-NONNEG? 0= IF DROP 0 EXIT THEN
        _UDGSN-F-CLIP-BOTTOM !
    _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-CLIP-COLUMN@ DUP 0< IF
        DROP 0 EXIT
    THEN
    _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-CLIP-WIDTH@
        DUP 0> 0= IF 2DROP 0 EXIT THEN
        _UDGSN-IADD-NONNEG? 0= IF DROP 0 EXIT THEN
        _UDGSN-F-CLIP-RIGHT !
    _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-CLIP-ROW@
        _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-ROW@ U< IF 0 EXIT THEN
    _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-CLIP-COLUMN@
        _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-COLUMN@ U< IF 0 EXIT THEN
    _UDGSN-F-CLIP-BOTTOM @ _UDGSN-F-ROOT-BOTTOM @ U> IF 0 EXIT THEN
    _UDGSN-F-CLIP-RIGHT @ _UDGSN-F-ROOT-RIGHT @ U> IF 0 EXIT THEN
    _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-Z@ 255 U> IF 0 EXIT THEN
    -1 ;

: _UDGSN-F-ENTRY?  ( -- flag )
    _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-NATIVE-OFFSET@
        DUP 0< IF DROP 0 EXIT THEN
        DUP 7 AND IF DROP 0 EXIT THEN
        DUP _UDGSN-F-OFFSET !
    _UDGSN-F-NATIVE-U @ U> IF 0 EXIT THEN
    _UDGSN-F-NATIVE-U @ _UDGSN-F-OFFSET @ -
        UDG-HEADER-SIZE U< IF 0 EXIT THEN
    _UDGSN-F-NATIVE-A @ _UDGSN-F-OFFSET @ +
        DUP _UDGSN-F-GRAPH !
    UDG-ENTRY-BYTES@ DUP _UDGSN-F-GRAPH-U !
    DUP UDG-HEADER-SIZE U< OVER 7 AND OR IF DROP 0 EXIT THEN
    _UDGSN-F-NATIVE-U @ _UDGSN-F-OFFSET @ - U> IF 0 EXIT THEN

    _UDGSN-F-GRAPH @ _UDGSN-F-GRAPH-U @ _UDGSN-F-SUMMARY
        UDG-ENTRY-VALIDATE UDG-S-OK <> IF 0 EXIT THEN
    _UDGSN-F-SUMMARY UDG-SUMMARY-SIZE
    _UDGSN-F-DESCRIPTOR @ UDGSN-DESCRIPTOR-SUMMARY UDG-SUMMARY-SIZE
        COMPARE 0= 0= IF 0 EXIT THEN
    _UDGSN-F-GEOMETRY? 0= IF 0 EXIT THEN
    _UDGSN-F-OFFSET @ _UDGSN-F-I @ _UDGSN-F-WORK-AT !
    -1 ;

: _UDGSN-F-SWAP-OFFSETS  ( ordinal-a ordinal-b -- )
    _UDGSN-F-HEAP-B ! _UDGSN-F-HEAP-A !
    _UDGSN-F-HEAP-A @ _UDGSN-F-WORK-AT @ _UDGSN-F-VALUE !
    _UDGSN-F-HEAP-B @ _UDGSN-F-WORK-AT @
        _UDGSN-F-HEAP-A @ _UDGSN-F-WORK-AT !
    _UDGSN-F-VALUE @ _UDGSN-F-HEAP-B @ _UDGSN-F-WORK-AT ! ;

\ Restore one unsigned max-heap below the exclusive END ordinal.  The
\ caller-bounded ledger makes this O(n log n) at the configured ceiling.
: _UDGSN-F-SIFT-DOWN  ( root end -- )
    _UDGSN-F-HEAP-END ! _UDGSN-F-HEAP-ROOT !
    BEGIN
        _UDGSN-F-HEAP-ROOT @ 2 * 1+ DUP _UDGSN-F-HEAP-CHILD !
        _UDGSN-F-HEAP-END @ U<
    WHILE
        _UDGSN-F-HEAP-ROOT @ _UDGSN-F-HEAP-LARGEST !
        _UDGSN-F-HEAP-LARGEST @ _UDGSN-F-WORK-AT @
        _UDGSN-F-HEAP-CHILD @ _UDGSN-F-WORK-AT @ U< IF
            _UDGSN-F-HEAP-CHILD @ _UDGSN-F-HEAP-LARGEST !
        THEN
        _UDGSN-F-HEAP-CHILD @ 1+ DUP _UDGSN-F-HEAP-CHILD !
        _UDGSN-F-HEAP-END @ U< IF
            _UDGSN-F-HEAP-LARGEST @ _UDGSN-F-WORK-AT @
            _UDGSN-F-HEAP-CHILD @ _UDGSN-F-WORK-AT @ U< IF
                _UDGSN-F-HEAP-CHILD @ _UDGSN-F-HEAP-LARGEST !
            THEN
        THEN
        _UDGSN-F-HEAP-LARGEST @ _UDGSN-F-HEAP-ROOT @ = IF EXIT THEN
        _UDGSN-F-HEAP-ROOT @ _UDGSN-F-HEAP-LARGEST @
            _UDGSN-F-SWAP-OFFSETS
        _UDGSN-F-HEAP-LARGEST @ _UDGSN-F-HEAP-ROOT !
    REPEAT ;

: _UDGSN-F-SORT-OFFSETS  ( -- )
    _UDGSN-F-COUNT @ 2 / _UDGSN-F-I !
    BEGIN _UDGSN-F-I @ 0> WHILE
        -1 _UDGSN-F-I +!
        _UDGSN-F-I @ _UDGSN-F-COUNT @ _UDGSN-F-SIFT-DOWN
    REPEAT
    _UDGSN-F-COUNT @ _UDGSN-F-J !
    BEGIN _UDGSN-F-J @ 1 > WHILE
        -1 _UDGSN-F-J +!
        0 _UDGSN-F-J @ _UDGSN-F-SWAP-OFFSETS
        0 _UDGSN-F-J @ _UDGSN-F-SIFT-DOWN
    REPEAT ;

: _UDGSN-F-COVERAGE?  ( -- flag )
    0 _UDGSN-F-CURSOR ! 0 _UDGSN-F-I !
    BEGIN _UDGSN-F-I @ _UDGSN-F-COUNT @ U< WHILE
        _UDGSN-F-I @ _UDGSN-F-WORK-AT @ DUP _UDGSN-F-OFFSET !
        _UDGSN-F-CURSOR @ <> IF 0 EXIT THEN
        _UDGSN-F-OFFSET @ _UDGSN-F-NATIVE-U @ U> IF 0 EXIT THEN
        _UDGSN-F-NATIVE-U @ _UDGSN-F-OFFSET @ -
            UDG-HEADER-SIZE U< IF 0 EXIT THEN
        _UDGSN-F-NATIVE-A @ _UDGSN-F-OFFSET @ + UDG-ENTRY-BYTES@
            DUP UDG-HEADER-SIZE U< OVER 7 AND OR IF DROP 0 EXIT THEN
        _UDGSN-F-CURSOR @ SWAP _UDGSN-F-UADD?
            0= IF DROP 0 EXIT THEN
        DUP _UDGSN-F-NATIVE-U @ U> IF DROP 0 EXIT THEN
            _UDGSN-F-CURSOR !
        1 _UDGSN-F-I +!
    REPEAT
    _UDGSN-F-CURSOR @ _UDGSN-F-NATIVE-U @ = ;

: _UDGSN-F-VALIDATE-BODY  ( -- status )
    _UDGSN-F-RANGES DUP UDGSN-S-OK <> IF EXIT THEN DROP
