: _USCOL-B-LATCH  ( status builder -- status )
    _USCOL-BL-B ! _USCOL-BL-STATUS !
    _USCOL-BL-B @ _USCOL-B.STATUS@ USCOL-S-OK = IF
        _USCOL-BL-STATUS @ _USCOL-BL-B @ _USCOL-B.STATUS!
    THEN
    _USCOL-BL-B @ _USCOL-B.STATUS@ ;

VARIABLE _USCOL-BR-B
VARIABLE _USCOL-BR-U
VARIABLE _USCOL-BR-OLD
VARIABLE _USCOL-BR-NEW

: _USCOL-B-RESERVE  ( bytes builder -- offset status )
    _USCOL-BR-B ! _USCOL-BR-U !
    _USCOL-BR-B @ _USCOL-B-HEADER? 0= IF
        0 USCOL-S-INVALID EXIT
    THEN
    _USCOL-BR-B @ _USCOL-B.STATUS@ DUP USCOL-S-OK <> IF
        0 SWAP EXIT
    THEN DROP
    _USCOL-BR-U @ 0< IF
        USCOL-S-INVALID _USCOL-BR-B @ _USCOL-B-LATCH
        0 SWAP EXIT
    THEN
    _USCOL-BR-B @ _USCOL-B.USED@ DUP _USCOL-BR-OLD !
    _USCOL-BR-U @ _USCOL-ADD? 0= IF
        DROP USCOL-S-INVALID _USCOL-BR-B @ _USCOL-B-LATCH
        0 SWAP EXIT
    THEN
    DUP _USCOL-BR-NEW !
    _USCOL-BR-B @ _USCOL-B.DST@ IF
        _USCOL-BR-B @ _USCOL-B.CAP@ U> IF
            USCOL-S-CAPACITY _USCOL-BR-B @ _USCOL-B-LATCH
            0 SWAP EXIT
        THEN
    ELSE
        DROP
    THEN
    _USCOL-BR-NEW @ _USCOL-BR-B @ _USCOL-B.USED!
    _USCOL-BR-OLD @ USCOL-S-OK ;

: _USCOL-B-ENTRY-A  ( builder -- address )
    DUP _USCOL-B.DST@ SWAP _USCOL-B.ENTRY@ + ;

: _USCOL-B-COPY?  ( builder -- flag )  _USCOL-B.DST@ 0<> ;

: _USCOL-B-SOURCE?  ( address length builder -- flag )
    >R
    2DUP _USCOL-BORROWED-SPAN? 0= IF 2DROP R> DROP 0 EXIT THEN
    DUP 0= IF 2DROP R> DROP -1 EXIT THEN
    R@ _USCOL-B-COPY? 0= IF 2DROP R> DROP -1 EXIT THEN
    2DUP R@ _USCOL-B.DST@ R@ _USCOL-B.CAP@
        MSPAN-OVERLAP? IF 2DROP R> DROP 0 EXIT THEN
    2DROP R> DROP -1 ;

