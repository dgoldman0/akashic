\ =====================================================================
\  Checked size and span helpers
\ =====================================================================

-1 1 RSHIFT CONSTANT _USCOL-SIGNED-MAX

: _USCOL-ADD?  ( a b -- sum flag )
    OVER + DUP ROT U< 0= ;

: _USCOL-MUL?  ( a b -- product flag )
    OVER 0< OVER 0< OR IF 2DROP 0 0 EXIT THEN
    DUP 0= IF 2DROP 0 -1 EXIT THEN
    _USCOL-SIGNED-MAX OVER / 2 PICK U< IF 2DROP 0 0 EXIT THEN
    * -1 ;

: _USCOL-ALIGN8?  ( bytes -- aligned flag )
    7 _USCOL-ADD? 0= IF DROP 0 0 EXIT THEN
    -8 AND -1 ;

: _USCOL-ALIGNED?  ( address -- flag )  7 AND 0= ;

: _USCOL-BORROWED-SPAN?  ( address length -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    DUP 0= IF 2DROP -1 EXIT THEN
    OVER 0= IF 2DROP 0 EXIT THEN
    MSPAN-NONWRAPPING? ;

: _USCOL-OPTIONAL-STORAGE?  ( address length -- flag )
    DUP 0< IF 2DROP 0 EXIT THEN
    DUP 0= IF DROP 0= EXIT THEN
    OVER 0= IF 2DROP 0 EXIT THEN
    OVER _USCOL-ALIGNED? 0= IF 2DROP 0 EXIT THEN
    MSPAN-NONWRAPPING? ;

: _USCOL-U32?  ( value -- flag )
    DUP 0< IF DROP 0 EXIT THEN 0x100000000 U< ;

: _USCOL-POSITIVE-U32?  ( value -- flag )
    DUP 0> SWAP _USCOL-U32? AND ;

: _USCOL-ZERO-PADDING?  ( address length -- flag )
    0 ?DO
        DUP I + C@ IF DROP 0 UNLOOP EXIT THEN
    LOOP
    DROP -1 ;

: USCOL-TEXT-ITEM-BYTES  ( text-bytes -- bytes|0 )
    DUP 0< IF DROP 0 EXIT THEN
    USCOL-ITEM-HEADER-SIZE _USCOL-ADD? 0= IF DROP 0 EXIT THEN
    _USCOL-ALIGN8? 0= IF DROP 0 THEN ;

: USCOL-TAB-BYTES  ( label-bytes shortcut-bytes -- bytes|0 )
    OVER 0< OVER 0< OR IF 2DROP 0 EXIT THEN
    _USCOL-ADD? 0= IF DROP 0 EXIT THEN
    USCOL-TAB-HEADER-SIZE _USCOL-ADD? 0= IF DROP 0 EXIT THEN
    _USCOL-ALIGN8? 0= IF DROP 0 THEN ;

