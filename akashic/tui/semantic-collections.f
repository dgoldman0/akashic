: _USCOL-VT-ORDER-STEP?  ( -- flag )
    _USCOL-VT-ORDER? @ IF
        _USCOL-VT-ROW @ _USCOL-VT-ORDER-ROW @ U< IF 0 EXIT THEN
        _USCOL-VT-ROW @ _USCOL-VT-ORDER-ROW @ = IF
            _USCOL-VT-COLUMN @ _USCOL-VT-ORDER-RIGHT @ U< IF 0 EXIT THEN
        THEN
    THEN
    -1 _USCOL-VT-ORDER? !
    _USCOL-VT-ROW @ _USCOL-VT-ORDER-ROW !
    _USCOL-VT-COLUMN @ _USCOL-VT-CSPAN @ + _USCOL-VT-ORDER-RIGHT !
    -1 ;

: _USCOL-VT-POSITIONS?  ( -- flag )
    _USCOL-VT-KEY @ _USCOL-VT-PRIMARY @ = IF
        -1 _USCOL-VT-PRIMARY-FOUND? !
        _USCOL-VT-PRIMARY-OFFSET @ _USCOL-VT-SCALARS @ U> IF 0 EXIT THEN
    THEN
    _USCOL-VT-KEY @ _USCOL-VT-ANCHOR @ = IF
        -1 _USCOL-VT-ANCHOR-FOUND? !
        _USCOL-VT-ANCHOR-OFFSET @ _USCOL-VT-SCALARS @ U> IF 0 EXIT THEN
    THEN
    -1 ;

: _USCOL-VT-FAMILY-SHAPE?  ( -- flag )
    _USCOL-V-FAMILY @ USCOL-F-TEXT-AREA = IF
        _USCOL-VT-ROLE @ USCOL-ROLE-CONTENT <> IF 0 EXIT THEN
        _USCOL-VT-ITEM-STATE @ IF 0 EXIT THEN
        _USCOL-VT-COLUMN @ IF 0 EXIT THEN
        _USCOL-VT-CSPAN @ _USCOL-V-ENTRY @ USCOL-TEXT-COLUMNS@ <>
            IF 0 EXIT THEN
        _USCOL-VT-SCALARS @ _USCOL-V-ENTRY @ USCOL-TEXT-COLUMNS@ U>
            IF 0 EXIT THEN
        -1 EXIT
    THEN
    _USCOL-VT-ITEM-STATE @ USCOL-ITEM-CURRENT AND IF
        1 _USCOL-VT-CURRENT-N +!
        _USCOL-VT-CURRENT-N @ 1 U> IF 0 EXIT THEN
    THEN
    -1 ;

: _USCOL-VT-ITEM-HEADER?  ( -- flag )
    _USCOL-VT-ITEM @ USCOL-ITEM-KEY@ DUP _USCOL-VT-KEY ! 0= IF 0 EXIT THEN
    _USCOL-VT-ITEM @ USCOL-ITEM-ROW@ DUP _USCOL-VT-ROW !
        _USCOL-U32? 0= IF 0 EXIT THEN
    _USCOL-VT-ITEM @ USCOL-ITEM-COLUMN@ DUP _USCOL-VT-COLUMN !
        _USCOL-U32? 0= IF 0 EXIT THEN
    _USCOL-VT-ITEM @ USCOL-ITEM-ROW-SPAN@ 1 <> IF 0 EXIT THEN
    _USCOL-VT-ITEM @ USCOL-ITEM-COLUMN-SPAN@ DUP _USCOL-VT-CSPAN !
        _USCOL-POSITIVE-U32? 0= IF 0 EXIT THEN
    _USCOL-VT-ROW @ _USCOL-V-ENTRY @ USCOL-TEXT-ROWS@ U< 0= IF
        0 EXIT
    THEN
    _USCOL-VT-COLUMN @ _USCOL-V-ENTRY @ USCOL-TEXT-COLUMNS@ U< 0= IF
        0 EXIT
    THEN
    _USCOL-VT-CSPAN @
        _USCOL-V-ENTRY @ USCOL-TEXT-COLUMNS@ _USCOL-VT-COLUMN @ - U>
        IF 0 EXIT THEN
    _USCOL-VT-ITEM @ USCOL-ITEM-ROLE@ DUP _USCOL-VT-ROLE !
    DUP USCOL-ROLE-CONTENT = OVER USCOL-ROLE-ROW-HEADER = OR
        SWAP USCOL-ROLE-COLUMN-HEADER = OR 0= IF 0 EXIT THEN
    _USCOL-VT-ITEM @ USCOL-ITEM-STATE@ DUP _USCOL-VT-ITEM-STATE !
    DUP _USCOL-ITEM-STATE-MASK INVERT AND IF DROP 0 EXIT THEN
    DUP USCOL-ITEM-CURRENT AND
    SWAP USCOL-ITEM-UNAVAILABLE AND AND IF 0 EXIT THEN
    -1 ;

: _USCOL-VALIDATE-TEXT  ( -- status )
    _USCOL-V-ENTRY @ USCOL-TEXT-FLAGS@
        _USCOL-CONTENT-FLAG-MASK INVERT AND IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ USCOL-TEXT-ROWS@ _USCOL-POSITIVE-U32? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ USCOL-TEXT-COLUMNS@ _USCOL-POSITIVE-U32? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ USCOL-TEXT-VIEWPORT-ROW@ DUP _USCOL-U32? 0= IF
        DROP USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ USCOL-TEXT-ROWS@ U< 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ USCOL-TEXT-VIEWPORT-COLUMN@ DUP _USCOL-U32? 0= IF
        DROP USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ USCOL-TEXT-COLUMNS@ U< 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ USCOL-TEXT-VIEWPORT-ROWS@ DUP
        _USCOL-POSITIVE-U32? 0= IF DROP USCOL-S-INVALID EXIT THEN
    _USCOL-V-ENTRY @ USCOL-TEXT-ROWS@
        _USCOL-V-ENTRY @ USCOL-TEXT-VIEWPORT-ROW@ - U> IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ USCOL-TEXT-VIEWPORT-COLUMNS@ DUP
        _USCOL-POSITIVE-U32? 0= IF DROP USCOL-S-INVALID EXIT THEN
    _USCOL-V-ENTRY @ USCOL-TEXT-COLUMNS@
        _USCOL-V-ENTRY @ USCOL-TEXT-VIEWPORT-COLUMN@ - U> IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ USCOL-TEXT-PRIMARY-KEY@ _USCOL-VT-PRIMARY !
    _USCOL-V-ENTRY @ USCOL-TEXT-ANCHOR-KEY@ _USCOL-VT-ANCHOR !
    _USCOL-V-ENTRY @ USCOL-TEXT-PRIMARY-OFFSET@
        DUP _USCOL-VT-PRIMARY-OFFSET ! _USCOL-U32? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ USCOL-TEXT-ANCHOR-OFFSET@
        DUP _USCOL-VT-ANCHOR-OFFSET ! _USCOL-U32? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-VT-PRIMARY @ 0= _USCOL-VT-PRIMARY-OFFSET @ 0<> AND IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-VT-ANCHOR @ 0= _USCOL-VT-ANCHOR-OFFSET @ 0<> AND IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-VT-ANCHOR @ 0<> _USCOL-VT-PRIMARY @ 0= AND IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-FAMILY @ USCOL-F-TEXT-GRID = IF
        _USCOL-VT-ANCHOR @ _USCOL-VT-PRIMARY-OFFSET @ OR
        _USCOL-VT-ANCHOR-OFFSET @ OR IF USCOL-S-INVALID EXIT THEN
    THEN
    _USCOL-V-ENTRY @ USCOL-TEXT-ITEM-COUNT@ _USCOL-V-COUNT !
    _USCOL-V-ENTRY @ USCOL-TEXT-FIRST _USCOL-VT-CURSOR !
    _USCOL-V-AVAILABLE @ USCOL-TEXT-FIXED-SIZE -
        _USCOL-VT-REMAINING !
    0 _USCOL-VT-I ! 0 _USCOL-V-UTF8 ! 0 _USCOL-VT-ORDER? !
    0 _USCOL-VT-PRIMARY-FOUND? ! 0 _USCOL-VT-ANCHOR-FOUND? !
    0 _USCOL-VT-CURRENT-N !
    BEGIN _USCOL-VT-I @ _USCOL-V-COUNT @ U< WHILE
        _USCOL-VT-REMAINING @ USCOL-ITEM-HEADER-SIZE U< IF
            USCOL-S-INVALID EXIT
        THEN
        _USCOL-VT-CURSOR @ DUP _USCOL-VT-ITEM !
            USCOL-ITEM-TEXT-BYTES@ DUP _USCOL-VT-TEXT-U !
            _USCOL-U32? 0= IF USCOL-S-INVALID EXIT THEN
        _USCOL-VT-TEXT-U @ USCOL-ITEM-HEADER-SIZE _USCOL-ADD? 0= IF
            DROP USCOL-S-INVALID EXIT
        THEN DUP _USCOL-VT-RAW !
        _USCOL-ALIGN8? 0= IF DROP USCOL-S-INVALID EXIT THEN
            DUP _USCOL-VT-STEP !
        _USCOL-VT-REMAINING @ U> IF USCOL-S-INVALID EXIT THEN
        _USCOL-VT-ITEM @ _USCOL-VT-RAW @ +
            _USCOL-VT-STEP @ _USCOL-VT-RAW @ - _USCOL-ZERO-PADDING? 0= IF
            USCOL-S-INVALID EXIT
        THEN
        _USCOL-VT-ITEM-HEADER? 0= IF USCOL-S-INVALID EXIT THEN
        _USCOL-VT-ORDER-STEP? 0= IF USCOL-S-INVALID EXIT THEN
        _USCOL-VT-ITEM @ USCOL-ITEM-TEXT-OFFSET + _USCOL-VT-TEXT-U @ -1
            _USCOL-TEXT-ANALYZE 0= IF DROP USCOL-S-INVALID EXIT THEN
            _USCOL-VT-SCALARS !
        _USCOL-V-UTF8 @ _USCOL-VT-TEXT-U @ _USCOL-ADD? 0= IF
            DROP USCOL-S-INVALID EXIT
        THEN _USCOL-V-UTF8 !
        _USCOL-VT-FAMILY-SHAPE? 0= IF USCOL-S-INVALID EXIT THEN
        _USCOL-VT-POSITIONS? 0= IF USCOL-S-INVALID EXIT THEN
        _USCOL-V-COUNT @ 2 U< 0= IF
            _USCOL-VT-KEY @ _USCOL-V-WORK @ _USCOL-VT-I @ 8 * + !
        THEN
        _USCOL-VT-STEP @ _USCOL-VT-CURSOR +!
        _USCOL-VT-STEP @ NEGATE _USCOL-VT-REMAINING +!
        1 _USCOL-VT-I +!
    REPEAT
    _USCOL-VT-REMAINING @ IF USCOL-S-INVALID EXIT THEN
    _USCOL-VT-PRIMARY @ IF
        _USCOL-VT-PRIMARY-FOUND? @ 0= IF USCOL-S-INVALID EXIT THEN
    THEN
    _USCOL-VT-ANCHOR @ IF
        _USCOL-VT-ANCHOR-FOUND? @ 0= IF USCOL-S-INVALID EXIT THEN
    THEN
    _USCOL-V-COUNT @ 2 U< 0= IF
        _USCOL-V-WORK @ _USCOL-V-COUNT @
            _USCOL-UNIQUE-CELLS? 0= IF USCOL-S-INVALID EXIT THEN
    THEN
    _USCOL-V-COUNT @ 32 _USCOL-MUL? 0= IF
        DROP USCOL-S-INVALID EXIT
    THEN
    72 _USCOL-ADD? 0= IF DROP USCOL-S-INVALID EXIT THEN
    _USCOL-V-UTF8 @ _USCOL-ADD? 0= IF
        DROP USCOL-S-INVALID EXIT
    THEN _USCOL-U32? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    0 _USCOL-V-CHILDREN ! _USCOL-V-COUNT @ _USCOL-V-ITEMS !
    USCOL-S-OK ;

