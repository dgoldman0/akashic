        _USCOL-V-SUMMARY @ USCOL-SUMMARY-FAMILY-OFFSET + !
    _USCOL-V-ENTRY @ USCOL-ENTRY-KEY@
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-ROOT-KEY-OFFSET + !
    _USCOL-V-AVAILABLE @
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-ENTRY-BYTES-OFFSET + !
    _USCOL-V-CHILDREN @
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-CHILD-COUNT-OFFSET + !
    _USCOL-V-ITEMS @
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-ITEM-COUNT-OFFSET + !
    _USCOL-V-UTF8 @
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-UTF8-BYTES-OFFSET + !
    _USCOL-V-RUNS @
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-RUN-COUNT-OFFSET + !
    _USCOL-V-FIELDS @
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-FIELD-COUNT-OFFSET + ! ;

: USCOL-ENTRY-VALIDATE
    ( entry available work-a work-u summary -- status )
    _USCOL-V-SUMMARY ! _USCOL-V-WORK-U ! _USCOL-V-WORK !
    _USCOL-V-AVAILABLE ! _USCOL-V-ENTRY !
    _USCOL-V-SUMMARY @ DUP 0= IF DROP USCOL-S-INVALID EXIT THEN
    DUP _USCOL-ALIGNED? 0= IF DROP USCOL-S-INVALID EXIT THEN
    USCOL-SUMMARY-SIZE MSPAN-NONWRAPPING? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ _USCOL-V-AVAILABLE @ _USCOL-BORROWED-SPAN? 0= IF
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-SIZE 0 FILL
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ _USCOL-V-AVAILABLE @
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-SIZE MSPAN-OVERLAP? IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-SUMMARY @ USCOL-SUMMARY-SIZE 0 FILL
    _USCOL-V-WORK @ _USCOL-V-WORK-U @ _USCOL-OPTIONAL-STORAGE? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-WORK-U @ IF
        _USCOL-V-WORK @ _USCOL-V-WORK-U @
            _USCOL-V-ENTRY @ _USCOL-V-AVAILABLE @ MSPAN-OVERLAP? IF
            USCOL-S-INVALID EXIT
        THEN
        _USCOL-V-WORK @ _USCOL-V-WORK-U @
            _USCOL-V-SUMMARY @ USCOL-SUMMARY-SIZE MSPAN-OVERLAP? IF
            USCOL-S-INVALID EXIT
        THEN
    THEN
    _USCOL-V-ENTRY @ _USCOL-V-AVAILABLE @ USCOL-VALIDATION-WORK-BYTES
    DUP USCOL-S-OK <> IF NIP EXIT THEN DROP _USCOL-V-NEED !
    _USCOL-V-WORK-U @ _USCOL-V-NEED @ U< IF
        USCOL-S-CAPACITY EXIT
    THEN
    _USCOL-V-AVAILABLE @ 7 AND IF USCOL-S-INVALID EXIT THEN
    _USCOL-V-ENTRY @ USCOL-ENTRY-KEY@ 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ USCOL-ENTRY-FAMILY@ _USCOL-V-FAMILY !
    _USCOL-V-ROOT? 0= IF USCOL-S-INVALID EXIT THEN
    0 _USCOL-V-UTF8 ! 0 _USCOL-V-CHILDREN ! 0 _USCOL-V-ITEMS !
    0 _USCOL-V-RUNS ! 0 _USCOL-V-FIELDS !
    _USCOL-V-FAMILY @ DUP USCOL-F-TEXT-AREA =
        SWAP USCOL-F-TEXT-GRID = OR IF
        _USCOL-VALIDATE-TEXT
    ELSE _USCOL-V-FAMILY @ USCOL-F-ITEM-VIEW = IF
        _USCOL-VALIDATE-ITEMS
    ELSE
        _USCOL-VALIDATE-TABSET
    THEN THEN
    DUP USCOL-S-OK <> IF EXIT THEN DROP
    _USCOL-V-SUMMARY!
    USCOL-S-OK ;

