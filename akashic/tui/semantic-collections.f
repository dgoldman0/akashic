: _USCOL-CS-AT  ( index -- address )  8 * _USCOL-CS-BASE @ + ;

: _USCOL-CS-SWAP  ( index-a index-b -- )
    _USCOL-CS-AT SWAP _USCOL-CS-AT
    OVER @ _USCOL-CS-TEMP !
    DUP @ ROT !
    _USCOL-CS-TEMP @ SWAP ! ;

: _USCOL-CS-SIFT  ( root count -- )
    _USCOL-CS-COUNT ! _USCOL-CS-ROOT !
    BEGIN
        _USCOL-CS-ROOT @ 2* 1+ DUP _USCOL-CS-CHILD !
        _USCOL-CS-COUNT @ U<
    WHILE
        _USCOL-CS-CHILD @ _USCOL-CS-LARGEST !
        _USCOL-CS-CHILD @ 1+ _USCOL-CS-COUNT @ U< IF
            _USCOL-CS-CHILD @ _USCOL-CS-AT @
            _USCOL-CS-CHILD @ 1+ _USCOL-CS-AT @ U< IF
                _USCOL-CS-CHILD @ 1+ _USCOL-CS-LARGEST !
            THEN
        THEN
        _USCOL-CS-ROOT @ _USCOL-CS-AT @
        _USCOL-CS-LARGEST @ _USCOL-CS-AT @ U< IF
            _USCOL-CS-ROOT @ _USCOL-CS-LARGEST @ _USCOL-CS-SWAP
            _USCOL-CS-LARGEST @ _USCOL-CS-ROOT !
        ELSE
            EXIT
        THEN
    REPEAT ;

: _USCOL-CELL-SORT  ( address count -- )
    _USCOL-CS-COUNT ! _USCOL-CS-BASE !
    _USCOL-CS-COUNT @ 2 U< IF EXIT THEN
    _USCOL-CS-COUNT @ 2 / 1- _USCOL-CS-START !
    BEGIN _USCOL-CS-START @ 0>= WHILE
        _USCOL-CS-START @ _USCOL-CS-COUNT @ _USCOL-CS-SIFT
        -1 _USCOL-CS-START +!
    REPEAT
    _USCOL-CS-COUNT @ 1- _USCOL-CS-END !
    BEGIN _USCOL-CS-END @ 0> WHILE
        0 _USCOL-CS-END @ _USCOL-CS-SWAP
        0 _USCOL-CS-END @ _USCOL-CS-SIFT
        -1 _USCOL-CS-END +!
    REPEAT ;

