        _USCOL-BB-WIDTH @ _USCOL-BB-ENTRY @ USCOL-ROOT-WIDTH-OFFSET + !
        _USCOL-BB-STATE @ _USCOL-BB-ENTRY @ USCOL-ROOT-STATE-OFFSET + !
    THEN
    0 _USCOL-BB-B @ _USCOL-B.COUNT!
    _USCOL-BB-KEY @ _USCOL-BB-B @ _USCOL-B.PRIOR!
    _USCOL-BB-PHASE @ _USCOL-BB-B @ _USCOL-B.PHASE!
    USCOL-S-OK ;

: USCOL-BUILDER-INIT  ( destination capacity builder -- status )
    >R
    R@ 0= IF 2DROP R> DROP USCOL-S-INVALID EXIT THEN
    R@ _USCOL-ALIGNED? 0= IF 2DROP R> DROP USCOL-S-INVALID EXIT THEN
    R@ USCOL-BUILDER-SIZE MSPAN-NONWRAPPING? 0= IF
        2DROP R> DROP USCOL-S-INVALID EXIT
    THEN
    DUP 0< IF 2DROP R> DROP USCOL-S-INVALID EXIT THEN
    OVER 0= IF
        DUP IF 2DROP R> DROP USCOL-S-INVALID EXIT THEN
    ELSE
        OVER _USCOL-ALIGNED? 0= IF
            2DROP R> DROP USCOL-S-INVALID EXIT
        THEN
        2DUP MSPAN-NONWRAPPING? 0= IF
            2DROP R> DROP USCOL-S-INVALID EXIT
        THEN
        2DUP R@ USCOL-BUILDER-SIZE MSPAN-OVERLAP? IF
            2DROP R> DROP USCOL-S-INVALID EXIT
        THEN
    THEN
    R@ USCOL-BUILDER-SIZE 0 FILL
    R@ R@ _USCOL-B.SELF + !
    DUP R@ _USCOL-B.CAP!
    SWAP R@ _USCOL-B.DST!
    DROP
    USCOL-S-OK R@ _USCOL-B.STATUS!
    R> DROP USCOL-S-OK ;

: USCOL-TEXT-BEGIN  ( family key row col h w state builder -- status )
    _USCOL-BB-B ! _USCOL-BB-STATE ! _USCOL-BB-WIDTH ! _USCOL-BB-HEIGHT !
    _USCOL-BB-COLUMN ! _USCOL-BB-ROW ! _USCOL-BB-KEY ! _USCOL-BB-FAMILY !
    _USCOL-BB-B @ _USCOL-B-HEADER? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-BB-FAMILY @ DUP USCOL-F-TEXT-AREA =
        SWAP USCOL-F-TEXT-GRID = OR 0= IF
        USCOL-S-INVALID _USCOL-BB-B @ _USCOL-B-LATCH EXIT
    THEN
    USCOL-TEXT-FIXED-SIZE _USCOL-BB-FIXED !
    _USCOL-B-PHASE-TEXT-SHAPE _USCOL-BB-PHASE !
    _USCOL-B-BEGIN ;

