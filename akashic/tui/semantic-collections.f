        _USCOL-BB-B @ _USCOL-B.DST@ _USCOL-BB-OFFSET @ +
            DUP _USCOL-BB-ENTRY !
        _USCOL-BB-FIXED @ 0 FILL
        _USCOL-BB-FAMILY @ _USCOL-BB-ENTRY @ 8 + !
        USCOL-FAMILY-ABI _USCOL-BB-ENTRY @ 16 + !
