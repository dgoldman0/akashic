\ =====================================================================
\  Conservative caller-work sizing
\ =====================================================================
\
\ ABI 1 admits unit-row items only.  Text and tab collections therefore need
\ one caller-owned key cell per member for the uniqueness sort, and item
\ views a key and an item address per item, which the parent lookups also
\ use.  Counts below two need no work.

VARIABLE _USCOL-WS-ENTRY
VARIABLE _USCOL-WS-AVAILABLE
VARIABLE _USCOL-WS-FAMILY
VARIABLE _USCOL-WS-COUNT
VARIABLE _USCOL-WS-MINIMUM

: _USCOL-WORK-FOR-KEYS  ( count -- bytes status )
    DUP 2 U< IF DROP 0 USCOL-S-OK EXIT THEN
    8 _USCOL-MUL? 0= IF DROP 0 USCOL-S-INVALID EXIT THEN
    USCOL-S-OK ;

: USCOL-VALIDATION-WORK-BYTES  ( entry available -- bytes status )
    _USCOL-WS-AVAILABLE ! _USCOL-WS-ENTRY !
    _USCOL-WS-AVAILABLE @ 0< IF 0 USCOL-S-INVALID EXIT THEN
    _USCOL-WS-AVAILABLE @ USCOL-ENTRY-HEADER-SIZE U< IF
        0 USCOL-S-INVALID EXIT
    THEN
    _USCOL-WS-ENTRY @ DUP 0= IF DROP 0 USCOL-S-INVALID EXIT THEN
    DUP _USCOL-ALIGNED? 0= IF DROP 0 USCOL-S-INVALID EXIT THEN
    _USCOL-WS-AVAILABLE @ MSPAN-NONWRAPPING? 0= IF
        0 USCOL-S-INVALID EXIT
    THEN
    _USCOL-WS-ENTRY @ USCOL-ENTRY-BYTES@
        _USCOL-WS-AVAILABLE @ <> IF 0 USCOL-S-INVALID EXIT THEN
    _USCOL-WS-ENTRY @ USCOL-ENTRY-FAMILY@
        DUP _USCOL-WS-FAMILY !
    USCOL-F-TEXT-AREA USCOL-F-ITEM-VIEW 1+ WITHIN 0= IF
        0 USCOL-S-UNSUPPORTED EXIT
    THEN
    _USCOL-WS-ENTRY @ USCOL-ENTRY-FAMILY-ABI@
        USCOL-FAMILY-ABI <> IF 0 USCOL-S-UNSUPPORTED EXIT THEN
    _USCOL-WS-FAMILY @ DUP USCOL-F-TEXT-AREA =
        SWAP USCOL-F-TEXT-GRID = OR IF
        _USCOL-WS-AVAILABLE @ USCOL-TEXT-FIXED-SIZE U< IF
            0 USCOL-S-INVALID EXIT
        THEN
        _USCOL-WS-ENTRY @ USCOL-TEXT-ITEM-COUNT@ DUP _USCOL-U32? 0= IF
            DROP 0 USCOL-S-INVALID EXIT
        THEN DUP _USCOL-WS-COUNT !
        USCOL-ITEM-HEADER-SIZE _USCOL-MUL? 0= IF
            DROP 0 USCOL-S-INVALID EXIT
        THEN
        USCOL-TEXT-FIXED-SIZE _USCOL-ADD? 0= IF
            DROP 0 USCOL-S-INVALID EXIT
        THEN _USCOL-WS-MINIMUM !
        _USCOL-WS-MINIMUM @ _USCOL-WS-AVAILABLE @ U> IF
            0 USCOL-S-INVALID EXIT
        THEN
        _USCOL-WS-COUNT @ _USCOL-WORK-FOR-KEYS EXIT
    THEN
    _USCOL-WS-FAMILY @ USCOL-F-ITEM-VIEW = IF
        _USCOL-WS-AVAILABLE @ USCOL-IV-FIXED-SIZE U< IF
            0 USCOL-S-INVALID EXIT
        THEN
        _USCOL-WS-ENTRY @ USCOL-IV-ITEM-COUNT@ DUP _USCOL-U32? 0= IF
            DROP 0 USCOL-S-INVALID EXIT
        THEN DUP _USCOL-WS-COUNT !
        USCOL-VI-HEADER-SIZE _USCOL-MUL? 0= IF
            DROP 0 USCOL-S-INVALID EXIT
        THEN
        USCOL-IV-FIXED-SIZE _USCOL-ADD? 0= IF
            DROP 0 USCOL-S-INVALID EXIT
        THEN _USCOL-WS-MINIMUM !
        _USCOL-WS-MINIMUM @ _USCOL-WS-AVAILABLE @ U> IF
            0 USCOL-S-INVALID EXIT
        THEN
        \ One key and item address per item, for the uniqueness sort and
        \ the parent lookups.
        _USCOL-WS-COUNT @ DUP 2 U< IF DROP 0 USCOL-S-OK EXIT THEN
        16 _USCOL-MUL? 0= IF DROP 0 USCOL-S-INVALID EXIT THEN
        USCOL-S-OK EXIT
    THEN
    _USCOL-WS-AVAILABLE @ USCOL-TABSET-FIXED-SIZE U< IF
        0 USCOL-S-INVALID EXIT
    THEN
    _USCOL-WS-ENTRY @ USCOL-TABSET-COUNT@ DUP _USCOL-U32? 0= IF
        DROP 0 USCOL-S-INVALID EXIT
    THEN DUP _USCOL-WS-COUNT !
    USCOL-TAB-HEADER-SIZE _USCOL-MUL? 0= IF
        DROP 0 USCOL-S-INVALID EXIT
    THEN
    USCOL-TABSET-FIXED-SIZE _USCOL-ADD? 0= IF
        DROP 0 USCOL-S-INVALID EXIT
    THEN _USCOL-WS-MINIMUM !
    _USCOL-WS-MINIMUM @ _USCOL-WS-AVAILABLE @ U> IF
        0 USCOL-S-INVALID EXIT
    THEN
    _USCOL-WS-COUNT @ _USCOL-WORK-FOR-KEYS ;

