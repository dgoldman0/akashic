\ =====================================================================
\
\ UTF8-VALID? is the sole scalar-codec proof.  Once it succeeds, a direct
\ byte pass derives the scalar count and control policy without decoding the
\ same text a second time: every byte outside 10xxxxxx begins one scalar, and
\ every prohibited C0/DEL value is necessarily its single-byte ASCII form.

