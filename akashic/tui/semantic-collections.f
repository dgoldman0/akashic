: _USCOL-VALIDATE-TABSET  ( -- status )
    _USCOL-V-ENTRY @ USCOL-TABSET-COUNT@ _USCOL-V-COUNT !
    _USCOL-V-ENTRY @ USCOL-TABSET-FIRST _USCOL-VB-CURSOR !
    _USCOL-V-AVAILABLE @ USCOL-TABSET-FIXED-SIZE -
        _USCOL-VB-REMAINING !
    0 _USCOL-VB-I ! 0 _USCOL-V-UTF8 ! 0 _USCOL-VB-PRIOR? !
    0 _USCOL-VB-SELECTED-N !
    BEGIN _USCOL-VB-I @ _USCOL-V-COUNT @ U< WHILE
        _USCOL-VB-REMAINING @ USCOL-TAB-HEADER-SIZE U< IF
            USCOL-S-INVALID EXIT
        THEN
        _USCOL-VB-CURSOR @ DUP _USCOL-VB-TAB !
            USCOL-TAB-LABEL-BYTES@ DUP _USCOL-VB-LABEL-U !
            DUP _USCOL-U32? 0= SWAP 0= OR IF
            USCOL-S-INVALID EXIT
        THEN
        _USCOL-VB-TAB @ USCOL-TAB-SHORTCUT-BYTES@
            DUP _USCOL-VB-SHORTCUT-U ! _USCOL-U32? 0= IF
            USCOL-S-INVALID EXIT
        THEN
        _USCOL-VB-LABEL-U @ _USCOL-VB-SHORTCUT-U @ _USCOL-ADD? 0= IF
            DROP USCOL-S-INVALID EXIT
        THEN
        USCOL-TAB-HEADER-SIZE _USCOL-ADD? 0= IF
            DROP USCOL-S-INVALID EXIT
        THEN DUP _USCOL-VB-RAW !
        _USCOL-ALIGN8? 0= IF DROP USCOL-S-INVALID EXIT THEN
            DUP _USCOL-VB-STEP !
        _USCOL-VB-REMAINING @ U> IF USCOL-S-INVALID EXIT THEN
        _USCOL-VB-TAB @ _USCOL-VB-RAW @ +
            _USCOL-VB-STEP @ _USCOL-VB-RAW @ - _USCOL-ZERO-PADDING? 0= IF
            USCOL-S-INVALID EXIT
        THEN
        _USCOL-VB-TAB @ USCOL-TAB-KEY@ DUP 0= IF
            DROP USCOL-S-INVALID EXIT
        THEN
        _USCOL-V-COUNT @ 2 U< 0= IF
            DUP _USCOL-V-WORK @ _USCOL-VB-I @ 8 * + !
        THEN DROP
        _USCOL-VB-TAB @ USCOL-TAB-ORDER@ DUP _USCOL-U32? 0= IF
            DROP USCOL-S-INVALID EXIT
        THEN
        _USCOL-VB-PRIOR? @ IF
            DUP _USCOL-VB-PRIOR-ORDER @ U> 0= IF
                DROP USCOL-S-INVALID EXIT
            THEN
        THEN
        _USCOL-VB-PRIOR-ORDER ! -1 _USCOL-VB-PRIOR? !
        _USCOL-VB-TAB @ USCOL-TAB-STATE@
        DUP _USCOL-STATE-MASK INVERT AND IF
            DROP USCOL-S-INVALID EXIT
        THEN
        DUP USCOL-STATE-SELECTED AND IF
            DUP USCOL-STATE-VISIBLE AND 0=
            OVER USCOL-STATE-ENABLED AND 0= OR IF
                DROP USCOL-S-INVALID EXIT
            THEN
            1 _USCOL-VB-SELECTED-N +!
            _USCOL-VB-SELECTED-N @ 1 U> IF
                DROP USCOL-S-INVALID EXIT
            THEN
        THEN DROP
        _USCOL-VB-TAB @ USCOL-TAB-LABEL@ 0 _USCOL-TEXT-ANALYZE
            0= IF DROP USCOL-S-INVALID EXIT THEN DROP
        _USCOL-VB-TAB @ USCOL-TAB-SHORTCUT@ 0 _USCOL-TEXT-ANALYZE
            0= IF DROP USCOL-S-INVALID EXIT THEN DROP
        _USCOL-V-UTF8 @ _USCOL-VB-LABEL-U @ _USCOL-ADD? 0= IF
            DROP USCOL-S-INVALID EXIT
        THEN
        _USCOL-VB-SHORTCUT-U @ _USCOL-ADD? 0= IF
            DROP USCOL-S-INVALID EXIT
        THEN _USCOL-V-UTF8 !
        _USCOL-VB-STEP @ _USCOL-VB-CURSOR +!
        _USCOL-VB-STEP @ NEGATE _USCOL-VB-REMAINING +!
        1 _USCOL-VB-I +!
    REPEAT
    _USCOL-VB-REMAINING @ IF USCOL-S-INVALID EXIT THEN
    _USCOL-V-COUNT @ 2 U< 0= IF
        _USCOL-V-WORK @ _USCOL-V-COUNT @ _USCOL-UNIQUE-CELLS? 0= IF
            USCOL-S-INVALID EXIT
        THEN
    THEN
    _USCOL-V-COUNT @ _USCOL-V-CHILDREN ! 0 _USCOL-V-ITEMS !
    USCOL-S-OK ;

: _USCOL-V-SUMMARY!  ( -- )
    _USCOL-V-FAMILY @
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-FAMILY-OFFSET + !
    _USCOL-V-ENTRY @ USCOL-ENTRY-KEY@
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-ROOT-KEY-OFFSET + !
    _USCOL-V-AVAILABLE @
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-ENTRY-BYTES-OFFSET + !
    _USCOL-V-CHILDREN @
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-CHILD-COUNT-OFFSET + !
    _USCOL-V-ITEMS @
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-ITEM-COUNT-OFFSET + !
    _USCOL-V-UTF8 @
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-UTF8-BYTES-OFFSET + ! ;

: USCOL-ENTRY-VALIDATE
    ( entry available work-a work-u summary -- status )
    _USCOL-V-SUMMARY ! _USCOL-V-WORK-U ! _USCOL-V-WORK !
    _USCOL-V-AVAILABLE ! _USCOL-V-ENTRY !
    _USCOL-V-SUMMARY @ DUP 0= IF DROP USCOL-S-INVALID EXIT THEN
    DUP _USCOL-ALIGNED? 0= IF DROP USCOL-S-INVALID EXIT THEN
    USCOL-SUMMARY-SIZE MSPAN-NONWRAPPING? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ _USCOL-V-AVAILABLE @ _USCOL-BORROWED-SPAN? 0= IF
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-SIZE 0 FILL
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ _USCOL-V-AVAILABLE @
        _USCOL-V-SUMMARY @ USCOL-SUMMARY-SIZE MSPAN-OVERLAP? IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-SUMMARY @ USCOL-SUMMARY-SIZE 0 FILL
    _USCOL-V-WORK @ _USCOL-V-WORK-U @ _USCOL-OPTIONAL-STORAGE? 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-WORK-U @ IF
        _USCOL-V-WORK @ _USCOL-V-WORK-U @
            _USCOL-V-ENTRY @ _USCOL-V-AVAILABLE @ MSPAN-OVERLAP? IF
            USCOL-S-INVALID EXIT
        THEN
        _USCOL-V-WORK @ _USCOL-V-WORK-U @
            _USCOL-V-SUMMARY @ USCOL-SUMMARY-SIZE MSPAN-OVERLAP? IF
            USCOL-S-INVALID EXIT
        THEN
    THEN
    _USCOL-V-ENTRY @ _USCOL-V-AVAILABLE @ USCOL-VALIDATION-WORK-BYTES
    DUP USCOL-S-OK <> IF NIP EXIT THEN DROP _USCOL-V-NEED !
    _USCOL-V-WORK-U @ _USCOL-V-NEED @ U< IF
        USCOL-S-CAPACITY EXIT
    THEN
    _USCOL-V-AVAILABLE @ 7 AND IF USCOL-S-INVALID EXIT THEN
    _USCOL-V-ENTRY @ USCOL-ENTRY-KEY@ 0= IF
        USCOL-S-INVALID EXIT
    THEN
    _USCOL-V-ENTRY @ USCOL-ENTRY-FAMILY@ _USCOL-V-FAMILY !
    _USCOL-V-ROOT? 0= IF USCOL-S-INVALID EXIT THEN
    0 _USCOL-V-UTF8 ! 0 _USCOL-V-CHILDREN ! 0 _USCOL-V-ITEMS !
    _USCOL-V-FAMILY @ DUP USCOL-F-TEXT-AREA =
        SWAP USCOL-F-TEXT-GRID = OR IF
        _USCOL-VALIDATE-TEXT
    ELSE
        _USCOL-VALIDATE-TABSET
    THEN
    DUP USCOL-S-OK <> IF EXIT THEN DROP
    _USCOL-V-SUMMARY!
    USCOL-S-OK ;

