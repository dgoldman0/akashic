        DROP USCOL-S-INVALID _USCOL-BB-B @ _USCOL-B-LATCH EXIT
    THEN DROP
    _USCOL-BB-B @ _USCOL-B.PRIOR@ ?DUP IF
        _USCOL-BB-KEY @ SWAP U> 0= IF
            USCOL-S-INVALID _USCOL-BB-B @ _USCOL-B-LATCH EXIT
        THEN
    THEN
    _USCOL-BB-FIXED @ _USCOL-BB-B @ _USCOL-B-RESERVE
