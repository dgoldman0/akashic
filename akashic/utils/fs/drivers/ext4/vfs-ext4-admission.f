\ =====================================================================
\  Checked hardware CRC32C adapter
\ =====================================================================

VARIABLE _EXT4-CRC-STATE

: _EXT4-CRC-START  ( seed -- )  0xFFFFFFFF AND _EXT4-CRC-STATE ! ;

: _EXT4-CRC-STATUS>IOR  ( status -- ior )
    DUP 1 = IF
        DROP 1 0 VFS-IOR-D-BINDING VFS-R-UNSUPPORTED VFS-IOR-MAKE EXIT
    THEN
    DUP 2 = IF
        DROP 2 VFS-IOR-F-RETRYABLE VFS-IOR-D-BINDING VFS-R-BUSY
        VFS-IOR-MAKE EXIT
    THEN
    DUP IF 0 VFS-IOR-D-BINDING VFS-R-IO VFS-IOR-MAKE THEN ;

: _EXT4-CRC-CAPABILITY  ( -- ior )
    CRYPTO-CAPS@ 1 AND IF 0 ELSE 1 _EXT4-CRC-STATUS>IOR THEN ;

: _EXT4-CRC-ADD  ( addr len -- ior )
    _EXT4-CRC-STATE @ -ROT CRC32C-RAW?
    DUP IF NIP _EXT4-CRC-STATUS>IOR EXIT THEN
    DROP 0xFFFFFFFF AND _EXT4-CRC-STATE ! 0 ;
: _EXT4-CRC@  ( -- crc )  _EXT4-CRC-STATE @ ;

