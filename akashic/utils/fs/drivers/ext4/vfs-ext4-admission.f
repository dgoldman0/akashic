    \ replay and strict checksum validation; immutable geometry is witnessed
    \ independently by sparse group 1 before any journal read.
    _EXT4-SV-CTX @ _EXT4-C.SUPER-TORN + @ 0= IF
        _EXT4-SV-SB @ _EXT4-SV-CTX @
        _EXT4-VALIDATE-SUPER-COUNTER-BOUNDS ?DUP IF EXIT THEN
    THEN
    _EXT4-SV-SB @ _EXT4-SB.CSUM-SEED + L@
    _EXT4-SV-CTX @ _EXT4-C.SEED + !
    _EXT4-SV-SB @ _EXT4-SB.UUID + @
    _EXT4-SV-CTX @ _EXT4-C.UUID-LO + !
    _EXT4-SV-SB @ _EXT4-SB.UUID 8 + + @
    _EXT4-SV-CTX @ _EXT4-C.UUID-HI + !
    0 ;
