: _EXT4-STAMP-SUPER-CHECKSUM  ( sb -- ior )
    DUP _EXT4-SB.CHECKSUM + 0 SWAP L!
    0xFFFFFFFF _EXT4-CRC-START
    DUP _EXT4-SB.CHECKSUM _EXT4-CRC-ADD ?DUP IF NIP EXIT THEN
    _EXT4-CRC@ SWAP _EXT4-SB.CHECKSUM + L! 0 ;

: _EXT4-PREPARE-CLEAN-SUPER  ( sb -- ior )
    DUP _EXT4-SB.INCOMPAT + DUP L@
    _EXT4-INCOMPAT-RECOVER INVERT AND SWAP L!
    1 OVER _EXT4-SB.STATE + W!
    _EXT4-STAMP-SUPER-CHECKSUM ;

\ The completed recovery endpoint additionally retires the modern-orphan
\ authority bit.  Keep this distinct from PREPARE-CLEAN-SUPER: AKW1 activation
\ must authenticate the exact old clean image, including ORPHAN_PRESENT.
: _EXT4-PREPARE-RECOVERED-SUPER  ( sb -- ior )
    DUP _EXT4-PREPARE-CLEAN-SUPER ?DUP IF NIP EXIT THEN
    DUP _EXT4-SB.RO-COMPAT + DUP L@
    _EXT4-RO-ORPHAN-PRESENT INVERT AND SWAP L!
    _EXT4-STAMP-SUPER-CHECKSUM ;

: _EXT4-PREPARE-DIRTY-SUPER  ( sb -- ior )
    DUP _EXT4-SB.INCOMPAT + DUP L@
    _EXT4-INCOMPAT-RECOVER OR SWAP L!
    1 OVER _EXT4-SB.STATE + W!
    _EXT4-STAMP-SUPER-CHECKSUM ;

: _EXT4-SUPER-CHECKSUM?  ( sb -- flag ior )
    DUP _EXT4-SB.CHECKSUM + L@ _EXT4-SV-STORED !
    0xFFFFFFFF _EXT4-CRC-START
    _EXT4-SB.CHECKSUM _EXT4-CRC-ADD ?DUP IF 0 SWAP EXIT THEN
    _EXT4-CRC@ _EXT4-SV-STORED @ = 0 ;

: _EXT4-SUPER-SEED?  ( sb -- flag ior )
    DUP _EXT4-SB.CSUM-SEED + L@ >R
    0xFFFFFFFF _EXT4-CRC-START
    _EXT4-SB.UUID + 16 _EXT4-CRC-ADD ?DUP IF
        R> DROP 0 SWAP EXIT
    THEN
    _EXT4-CRC@ R> = 0 ;

\ Return the checksum of the intended post-recovery primary superblock while
\ restoring every temporarily changed byte.  A durable journal anchor records
\ this value before RECOVER can be cleared across its two-sector write.
: _EXT4-INTENDED-SUPER-CHECKSUM  ( sb -- crc ior )
    DUP _EXT4-SI-SB !
    DUP _EXT4-SB.INCOMPAT + L@ _EXT4-SI-INCOMPAT !
    DUP _EXT4-SB.STATE + W@ _EXT4-SI-STATE !
    _EXT4-SB.CHECKSUM + L@ _EXT4-SI-STORED !
    _EXT4-SI-SB @ _EXT4-PREPARE-CLEAN-SUPER
    DUP IF
        _EXT4-SI-INCOMPAT @ _EXT4-SI-SB @ _EXT4-SB.INCOMPAT + L!
        _EXT4-SI-STATE @ _EXT4-SI-SB @ _EXT4-SB.STATE + W!
        _EXT4-SI-STORED @ _EXT4-SI-SB @ _EXT4-SB.CHECKSUM + L!
        0 SWAP EXIT
    THEN DROP
    _EXT4-SI-SB @ _EXT4-SB.CHECKSUM + L@ _EXT4-SI-CALC !
    _EXT4-SI-INCOMPAT @ _EXT4-SI-SB @ _EXT4-SB.INCOMPAT + L!
    _EXT4-SI-STATE @ _EXT4-SI-SB @ _EXT4-SB.STATE + W!
    _EXT4-SI-STORED @ _EXT4-SI-SB @ _EXT4-SB.CHECKSUM + L!
    _EXT4-SI-CALC @ 0 ;

: _EXT4-INTENDED-RECOVERED-SUPER-CHECKSUM  ( sb -- crc ior )
    DUP _EXT4-SI-SB !
    DUP _EXT4-SB.INCOMPAT + L@ _EXT4-SI-INCOMPAT !
    DUP _EXT4-SB.RO-COMPAT + L@ _EXT4-SI-RO !
    DUP _EXT4-SB.STATE + W@ _EXT4-SI-STATE !
    _EXT4-SB.CHECKSUM + L@ _EXT4-SI-STORED !
    _EXT4-SI-SB @ _EXT4-PREPARE-RECOVERED-SUPER
    DUP IF
        _EXT4-SI-INCOMPAT @ _EXT4-SI-SB @ _EXT4-SB.INCOMPAT + L!
        _EXT4-SI-RO @ _EXT4-SI-SB @ _EXT4-SB.RO-COMPAT + L!
        _EXT4-SI-STATE @ _EXT4-SI-SB @ _EXT4-SB.STATE + W!
        _EXT4-SI-STORED @ _EXT4-SI-SB @ _EXT4-SB.CHECKSUM + L!
        0 SWAP EXIT
    THEN DROP
    _EXT4-SI-SB @ _EXT4-SB.CHECKSUM + L@ _EXT4-SI-CALC !
    _EXT4-SI-INCOMPAT @ _EXT4-SI-SB @ _EXT4-SB.INCOMPAT + L!
    _EXT4-SI-RO @ _EXT4-SI-SB @ _EXT4-SB.RO-COMPAT + L!
    _EXT4-SI-STATE @ _EXT4-SI-SB @ _EXT4-SB.STATE + W!
    _EXT4-SI-STORED @ _EXT4-SI-SB @ _EXT4-SB.CHECKSUM + L!
    _EXT4-SI-CALC @ 0 ;

: _EXT4-INTENDED-DIRTY-SUPER-CHECKSUM  ( sb -- crc ior )
    DUP _EXT4-SI-SB !
    DUP _EXT4-SB.INCOMPAT + L@ _EXT4-SI-INCOMPAT !
    DUP _EXT4-SB.STATE + W@ _EXT4-SI-STATE !
    _EXT4-SB.CHECKSUM + L@ _EXT4-SI-STORED !
    _EXT4-SI-SB @ _EXT4-PREPARE-DIRTY-SUPER
    DUP IF
        _EXT4-SI-INCOMPAT @ _EXT4-SI-SB @ _EXT4-SB.INCOMPAT + L!
        _EXT4-SI-STATE @ _EXT4-SI-SB @ _EXT4-SB.STATE + W!
        _EXT4-SI-STORED @ _EXT4-SI-SB @ _EXT4-SB.CHECKSUM + L!
        0 SWAP EXIT
    THEN DROP
    _EXT4-SI-SB @ _EXT4-SB.CHECKSUM + L@ _EXT4-SI-CALC !
    _EXT4-SI-INCOMPAT @ _EXT4-SI-SB @ _EXT4-SB.INCOMPAT + L!
    _EXT4-SI-STATE @ _EXT4-SI-SB @ _EXT4-SB.STATE + W!
    _EXT4-SI-STORED @ _EXT4-SI-SB @ _EXT4-SB.CHECKSUM + L!
    _EXT4-SI-CALC @ 0 ;

VARIABLE _EXT4-SRP-SB
VARIABLE _EXT4-SRP-RECOVERY

\ These fields must let the next mount reach the redundant recovery witness.
\ Keep the ordinary mount and replay-candidate gates on one predicate path.
: _EXT4-VALIDATE-SUPER-RETRY-EARLY  ( sb recovery -- ior )
    _EXT4-SRP-RECOVERY ! _EXT4-SRP-SB !
    _EXT4-SRP-SB @ _EXT4-SB.STATE + W@ DUP 1 INVERT AND IF
        DROP EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT
    THEN
    1 <> _EXT4-SRP-RECOVERY @ 0= AND IF
        EXT4-D-RECOVERY _EXT4-UNSUPPORTED EXIT
    THEN
    _EXT4-SRP-SB @ _EXT4-SB.ERRORS + W@ 2 <> IF
        EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT
    THEN
    0 ;

: _EXT4-VALIDATE-SUPER-RETRY-LATE  ( sb -- ior )
    _EXT4-SRP-SB !
    _EXT4-SRP-SB @ _EXT4-SB.INODE-SIZE + W@ 256 = IF
        _EXT4-SRP-SB @ _EXT4-SB.MIN-EXTRA + W@ 32 <
        _EXT4-SRP-SB @ _EXT4-SB.WANT-EXTRA + W@ 32 < OR IF
            EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT
        THEN
    THEN
    _EXT4-SRP-SB @ _EXT4-SB.LOG-FLEX + C@ 4 <> IF
        EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT
    THEN
    _EXT4-SRP-SB @ _EXT4-SB.FIRST-INO + L@ 11 < IF
        EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT
    THEN
    0 ;

VARIABLE _EXT4-SCB-SB
VARIABLE _EXT4-SCB-CTX

\ A checksum-valid image cannot use the prefix-tear exception for counters.
: _EXT4-VALIDATE-SUPER-COUNTER-BOUNDS  ( sb ctx -- ior )
    _EXT4-SCB-CTX ! _EXT4-SCB-SB !
    _EXT4-SCB-SB @ _EXT4-SB.RBLOCKS-HI + L@
    _EXT4-SCB-SB @ _EXT4-SB.FREE-BLOCKS-HI + L@ OR IF
        EXT4-D-BOUNDS _EXT4-CORRUPT EXIT
    THEN
    _EXT4-SCB-SB @ _EXT4-SB.RBLOCKS-LO + L@
    _EXT4-SCB-CTX @ _EXT4-C.BLOCKS + @ U> IF
        EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT
    THEN
    _EXT4-SCB-SB @ _EXT4-SB.FREE-BLOCKS-LO + L@
    _EXT4-SCB-CTX @ _EXT4-C.BLOCKS + @ U> IF
        EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT
    THEN
    _EXT4-SCB-SB @ _EXT4-SB.FREE-INODES + L@
    _EXT4-SCB-CTX @ _EXT4-C.INODES + @ U> IF
        EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT
    THEN
    0 ;

: _EXT4-VALIDATE-SUPER  ( ctx vfs -- ior )
    DROP _EXT4-SV-CTX !
    _EXT4-SV-CTX @ _EXT4-C.SB + _EXT4-SV-SB !
    0 _EXT4-SV-CTX @ _EXT4-C.RECOVERY + !
    0 _EXT4-SV-CTX @ _EXT4-C.SUPER-TORN + !
    _EXT4-SV-SB @ _EXT4-SB.MAGIC + W@ _EXT4-MAGIC <> IF
        EXT4-D-MAGIC _EXT4-UNSUPPORTED EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SUPER-CHECKSUM? ?DUP IF NIP EXIT THEN 0= IF
        -1 _EXT4-SV-CTX @ _EXT4-C.SUPER-TORN + !
    THEN
    _EXT4-SV-SB @ _EXT4-SUPER-SEED? ?DUP IF NIP EXIT THEN 0= IF
        EXT4-D-SUPER-CHECKSUM _EXT4-CORRUPT EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SB.REVISION + L@ 1 <
    _EXT4-SV-SB @ _EXT4-SB.CREATOR + L@ 0<> OR IF
        EXT4-D-GEOMETRY _EXT4-UNSUPPORTED EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SB.COMPAT + L@ _EXT4-COMPAT-V1 <> IF
        EXT4-D-FEATURE _EXT4-UNSUPPORTED EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SB.INCOMPAT + L@ DUP _EXT4-SV-INCOMPAT !
    _EXT4-INCOMPAT-RECOVER AND IF
        -1 _EXT4-SV-CTX @ _EXT4-C.RECOVERY + !
    THEN
    _EXT4-SV-INCOMPAT @ _EXT4-INCOMPAT-RECOVER INVERT AND
    _EXT4-INCOMPAT-V1 <> IF
        EXT4-D-FEATURE _EXT4-UNSUPPORTED EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SB.RO-COMPAT + L@
    DUP _EXT4-RO-REFUSED AND IF
        DROP EXT4-D-FEATURE _EXT4-UNSUPPORTED EXIT
    THEN
    _EXT4-RO-READONLY _EXT4-RO-ORPHAN-PRESENT OR INVERT AND
    _EXT4-SV-RO !
    _EXT4-SV-SB @ _EXT4-SB.INODE-SIZE + W@ DUP
    128 = IF
        DROP _EXT4-SV-RO @ _EXT4-RO-I128-V1 AND
        _EXT4-RO-I128-V1 <>
    ELSE
        256 <> _EXT4-SV-RO @ _EXT4-RO-V1 AND
        _EXT4-RO-V1 <> OR
    THEN IF EXT4-D-FEATURE _EXT4-UNSUPPORTED EXIT THEN
    _EXT4-SV-SB @ _EXT4-SV-CTX @ _EXT4-C.RECOVERY + @
    _EXT4-VALIDATE-SUPER-RETRY-EARLY ?DUP IF EXIT THEN
    _EXT4-SV-SB @ _EXT4-SB.LOG-BLOCK + L@ DUP _EXT4-SV-LOG ! 2 > IF
        EXT4-D-GEOMETRY _EXT4-UNSUPPORTED EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SB.LOG-CLUSTER + L@ _EXT4-SV-LOG @ <> IF
        EXT4-D-GEOMETRY _EXT4-UNSUPPORTED EXIT
    THEN
    1024 _EXT4-SV-LOG @ LSHIFT DUP
    _EXT4-SV-CTX @ _EXT4-C.BSIZE + !
    512 / _EXT4-SV-CTX @ _EXT4-C.SPB + !
    _EXT4-SV-SB @ _EXT4-SB.BLOCKS-HI + L@ 0<> IF
        EXT4-D-BOUNDS _EXT4-CORRUPT EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SB.BLOCKS-LO + L@
    _EXT4-SV-CTX @ _EXT4-C.BLOCKS + !
    _EXT4-SV-SB @ _EXT4-SB.FIRST-DATA + L@ DUP
    _EXT4-SV-CTX @ _EXT4-C.FIRST + !
    _EXT4-SV-LOG @ 0= IF 1 <> ELSE 0<> THEN IF
        EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT
    THEN
    _EXT4-SV-CTX @ _EXT4-C.BLOCKS + @
    _EXT4-SV-CTX @ _EXT4-C.FIRST + @ <= IF
        EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT
    THEN
    _EXT4-SV-CTX @ _EXT4-C.BLOCKS + @
    _EXT4-SV-CTX @ _EXT4-C.SPB + @ *
    _EXT4-IO-VOL @ VOL.SECTORS U> IF
        EXT4-D-BOUNDS _EXT4-CORRUPT EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SB.BPG + L@ DUP
    _EXT4-SV-CTX @ _EXT4-C.BPG + !
    _EXT4-SV-CTX @ _EXT4-C.BSIZE + @ 8 * <> IF
        EXT4-D-GEOMETRY _EXT4-UNSUPPORTED EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SB.CPG + L@
    _EXT4-SV-CTX @ _EXT4-C.BPG + @ <> IF
        EXT4-D-GEOMETRY _EXT4-UNSUPPORTED EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SB.IPG + L@ DUP
    _EXT4-SV-CTX @ _EXT4-C.IPG + !
    _EXT4-SV-CTX @ _EXT4-C.BPG + @
    _EXT4-SV-CTX @ _EXT4-C.BSIZE + @ * 16384 / <> IF
        EXT4-D-GEOMETRY _EXT4-UNSUPPORTED EXIT
    THEN
    _EXT4-SV-CTX @ _EXT4-C.BLOCKS + @
    _EXT4-SV-CTX @ _EXT4-C.FIRST + @ -
    _EXT4-SV-CTX @ _EXT4-C.BPG + @ 1- +
    _EXT4-SV-CTX @ _EXT4-C.BPG + @ /
    DUP _EXT4-SV-GROUPS ! _EXT4-SV-CTX @ _EXT4-C.GROUPS + !
    _EXT4-SV-GROUPS @ 0= IF EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT THEN
    _EXT4-SV-SB @ _EXT4-SB.INODES + L@ DUP
    _EXT4-SV-CTX @ _EXT4-C.INODES + !
    _EXT4-SV-GROUPS @ _EXT4-SV-CTX @ _EXT4-C.IPG + @ * <> IF
        EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SB.INODE-SIZE + W@
    _EXT4-SV-CTX @ _EXT4-C.ISIZE + !
    _EXT4-SV-SB @ _EXT4-SB.DESC-SIZE + W@ DUP
    _EXT4-SV-CTX @ _EXT4-C.DSIZE + !
    _EXT4-DESC-SIZE <> IF EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT THEN
    _EXT4-SV-SB @ _EXT4-VALIDATE-SUPER-RETRY-LATE ?DUP IF EXIT THEN
    _EXT4-SV-SB @ _EXT4-SB.CSUM-TYPE + C@ 1 <> IF
        EXT4-D-GEOMETRY _EXT4-CORRUPT EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SB.JOURNAL-INO + L@ 8 <> IF
        EXT4-D-JOURNAL _EXT4-CORRUPT EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SB.ORPHAN-INO + L@ DUP
    _EXT4-SV-CTX @ _EXT4-C.ORPHAN-INO + !
    DUP 0= SWAP _EXT4-SV-CTX @ _EXT4-C.INODES + @ > OR IF
        EXT4-D-ORPHAN-FILE _EXT4-CORRUPT EXIT
    THEN
    _EXT4-SV-SB @ _EXT4-SB.RBLOCKS-LO + L@
    _EXT4-SV-CTX @ _EXT4-C.RESERVED-BLOCKS + !
    _EXT4-SV-SB @ _EXT4-SB.FREE-BLOCKS-LO + L@
    _EXT4-SV-CTX @ _EXT4-C.FREE-BLOCKS + !
    _EXT4-SV-SB @ _EXT4-SB.FREE-INODES + L@
    _EXT4-SV-CTX @ _EXT4-C.FREE-INODES + !
