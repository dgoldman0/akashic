    0 _EXT4-IO-VFS !
    _EXT4-PROBE-VOL @ _EXT4-IO-VOL !
    _EXT4-PROBE-BUF 2 2 _EXT4-READ-SECTORS
    DUP IF 0 SWAP EXIT THEN DROP
    _EXT4-PROBE-BUF _EXT4-SB.MAGIC + W@ _EXT4-MAGIC = IF
        EXT4-PROBE-SCORE
    ELSE
        0
    THEN 0 ;

