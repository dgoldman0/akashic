: _EXT4-PROBE  ( volume -- score ior )
    _EXT4-PROBE-VOL !
    _EXT4-CRC-CAPABILITY ?DUP IF 0 SWAP EXIT THEN
    _EXT4-PROBE-VOL @ VOL.SECTOR-SIZE _EXT4-SECTOR <> IF
