\ =====================================================================
\  Exact group geometry
\ =====================================================================

VARIABLE _EXT4-GBC-GROUP
VARIABLE _EXT4-GBC-CTX
VARIABLE _EXT4-GBC-START

: _EXT4-GROUP-BLOCK-COUNT  ( group ctx -- blocks ior )
    _EXT4-GBC-CTX ! DUP _EXT4-GBC-GROUP !
    _EXT4-GBC-CTX @ 0= IF DROP 0 VFS-E-INVALID EXIT THEN
    _EXT4-GBC-GROUP @
    _EXT4-GBC-CTX @ _EXT4-C.GROUPS + @ U< 0= IF
        DROP 0 EXT4-D-BOUNDS _EXT4-CORRUPT EXIT
    THEN
    DROP
    _EXT4-GBC-GROUP @ _EXT4-GBC-CTX @ _EXT4-C.BPG + @ _EXT4-UMUL?
    DUP IF NIP 0 SWAP EXIT THEN DROP
    _EXT4-GBC-CTX @ _EXT4-C.FIRST + @ _EXT4-UADD?
    DUP IF NIP 0 SWAP EXIT THEN DROP DUP _EXT4-GBC-START !
    _EXT4-GBC-CTX @ _EXT4-C.BLOCKS + @ U< 0= IF
        0 EXT4-D-BOUNDS _EXT4-CORRUPT EXIT
    THEN
    _EXT4-GBC-CTX @ _EXT4-C.BLOCKS + @ _EXT4-GBC-START @ -
    _EXT4-GBC-CTX @ _EXT4-C.BPG + @ MIN 0 ;

