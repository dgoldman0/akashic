VARIABLE _EXT4-GBR-GROUP
VARIABLE _EXT4-GBR-CTX
VARIABLE _EXT4-GBR-COUNT

\ Return the exact half-open physical interval owned by one block group.
\ Reuse the canonical short-last-group calculation and keep every address
\ operation checked so sizing cannot wrap malformed geometry into a match.
: _EXT4-GROUP-BLOCK-RANGE  ( group ctx -- first count ior )
    _EXT4-GBR-CTX ! _EXT4-GBR-GROUP !
    _EXT4-GBR-GROUP @ _EXT4-GBR-CTX @ _EXT4-GROUP-BLOCK-COUNT
    DUP IF NIP 0 0 ROT EXIT THEN DROP _EXT4-GBR-COUNT !
    _EXT4-GBR-GROUP @
    _EXT4-GBR-CTX @ _EXT4-C.BPG + @ _EXT4-UMUL?
    DUP IF NIP 0 0 ROT EXIT THEN DROP
    _EXT4-GBR-CTX @ _EXT4-C.FIRST + @ _EXT4-UADD?
    DUP IF NIP 0 0 ROT EXIT THEN DROP
    _EXT4-GBR-COUNT @ 0 ;

\ =====================================================================
\  Authenticated bitmap reads and raw allocation evidence
\ =====================================================================

: _EXT4-BLOCK-BITMAP-CRC  ( bitmap ctx -- crc ior )
    DUP _EXT4-C.SEED + @ _EXT4-CRC-START
    _EXT4-C.BPG + @ 8 / _EXT4-CRC-ADD ?DUP IF 0 SWAP EXIT THEN
    _EXT4-CRC@ 0 ;

: _EXT4-INODE-BITMAP-CRC  ( bitmap ctx -- crc ior )
    DUP _EXT4-C.SEED + @ _EXT4-CRC-START
    _EXT4-C.IPG + @ 8 / _EXT4-CRC-ADD ?DUP IF 0 SWAP EXIT THEN
    _EXT4-CRC@ 0 ;

VARIABLE _EXT4-LBB-GROUP
VARIABLE _EXT4-LBB-CTX
VARIABLE _EXT4-LBB-HOME
VARIABLE _EXT4-LBB-STORED

: _EXT4-LOAD-BLOCK-BITMAP  ( group ctx -- bitmap-home ior )
    _EXT4-LBB-CTX ! DUP _EXT4-LBB-GROUP !
    _EXT4-LBB-GROUP @ _EXT4-LBB-CTX @ _EXT4-LOAD-DESC
    ?DUP IF NIP 0 SWAP EXIT THEN
    _EXT4-GD-FLAGS @ _EXT4-BG-BLOCK-UNINIT AND IF
        DROP 0 EXT4-D-BITMAP-CHECKSUM _EXT4-CORRUPT EXIT
    THEN
    DROP
    _EXT4-LBB-CTX @ _EXT4-C.DESC + DUP
    _EXT4-GD.BLOCK-BITMAP-LO + L@ DUP _EXT4-LBB-HOME !
    SWAP _EXT4-GD.BLOCK-CSUM-LO + W@
    _EXT4-LBB-CTX @ _EXT4-C.DESC + _EXT4-GD.BLOCK-CSUM-HI + W@
    16 LSHIFT OR _EXT4-LBB-STORED ! DROP
    _EXT4-LBB-HOME @ _EXT4-LBB-CTX @ _EXT4-READ-BLOCK
    ?DUP IF 0 SWAP EXIT THEN
    _EXT4-LBB-CTX @ _EXT4-C.BLOCK + _EXT4-LBB-CTX @
    _EXT4-BLOCK-BITMAP-CRC ?DUP IF NIP 0 SWAP EXIT THEN
    _EXT4-LBB-STORED @ <> IF
        0 EXT4-D-BITMAP-CHECKSUM _EXT4-CORRUPT EXIT
    THEN
    _EXT4-LBB-HOME @ 0 ;

